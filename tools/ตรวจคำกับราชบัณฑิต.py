"""เทียบคำที่ดึงจาก PDF กับพจนานุกรมฉบับราชบัณฑิตยสถาน พ.ศ. 2554

    py -3.14 tools/ตรวจคำกับราชบัณฑิต.py <โฟลเดอร์ tsv> <ไฟล์ royin.db>

พจนานุกรมมีคำสะกดถูก 52,088 คำ ⇒ ใช้เป็น "คนตรวจ" ว่าเราดึงคำออกมาเพี้ยนไหม
⚠️ หาไม่เจอ ไม่ได้แปลว่าดึงเพี้ยนเสมอไป — พจนานุกรมไม่เก็บคำประสมและคำทับศัพท์ใหม่
⇒ ที่หาไม่เจอ จึงต้องแยกอีกชั้นว่า "ประกอบจากคำในพจนานุกรมได้ไหม"
"""

import re
import sqlite3
import sys
from collections import Counter
from pathlib import Path

# ตัวที่ต้องเกาะหลังพยัญชนะเสมอ ถ้าโผล่หน้าสุด = ดึงเพี้ยนแน่นอน
ตัวเกาะ = set("ัิีึืุู็่้๊๋์ํำาะๅๆๅ")
พยัญชนะ = set("กขฃคฅฆงจฉชซฌญฎฏฐฑฒณดตถทธนบปผฝพฟภมยรลวศษสหฬอฮ")
สระหน้า = set("เแโใไ")
วรรณยุกต์ = set("่้๊๋")


# คำที่ **ต้นฉบับพิมพ์ตกเอง** ⇒ ดึงมาถูกแล้ว แต่สะกดผิดตั้งแต่ในเล่ม
# เปิดภาพหน้ากระดาษยืนยันครบทั้ง 6 คำแล้ว 31 ส.ค. 2569
# ⚠️ อยู่ในกลุ่ม ② เพราะบังเอิญต่อจากคำในพจนานุกรมได้ ⇒ ต้องเตือนคนที่จะเอากลุ่มนี้ไปใช้
คำที่ต้นฉบับพิมพ์ตก = ["ครวจ", "ตนโต", "ท่าง", "นางสว", "มากกาย", "โน้ตดนรี"]


def คำย่อย(ข้อความ):
    """แตกช่องหนึ่งช่องเป็นคำที่ต้องตรวจ — ในวงเล็บคือคำพูดอีกแบบ ตรวจแยก

    ⭐ ขีดทับคือคำเดียวกันที่เขียนได้สองแบบ เช่น "เรา/พวกเรา" ⇒ ต้องตรวจแยกด้วย
    ไม่งั้นทั้งก้อนจะหาไม่เจอในพจนานุกรม แล้วตัวเลข "ไม่เจอ" จะพองขึ้นโดยไม่มีเหตุ
    """
    ข้อความ = ข้อความ.strip()
    if not ข้อความ:
        return []
    หลัก = re.sub(r"\s*\(.*?\)\s*", " ", ข้อความ).strip()
    ใน = re.findall(r"\((.*?)\)", ข้อความ)
    ผล = [x.strip() for x in หลัก.split("/") if x.strip().replace("…", "")]
    for ก in ใน:
        ผล.extend(x.strip() for x in ก.split(",") if x.strip())
    return [x.replace("…", "") for x in ผล if x.replace("…", "")]


def รูปเขียนพัง(คำ):
    """จับรูปที่เป็นไปไม่ได้ในภาษาไทย ⇒ ถ้าเจอ แปลว่าดึงเพี้ยนแน่ ๆ"""
    เหตุ = []
    if not คำ:
        return ["ว่าง"]
    if คำ[0] in ตัวเกาะ:
        เหตุ.append("ขึ้นต้นด้วยสระหรือวรรณยุกต์")
    for i, c in enumerate(คำ):
        if c in วรรณยุกต์ and (i == 0 or คำ[i - 1] in สระหน้า):
            เหตุ.append("วรรณยุกต์ไม่เกาะพยัญชนะ")
        if c in สระหน้า and (i + 1 >= len(คำ) or คำ[i + 1] not in พยัญชนะ):
            เหตุ.append("สระหน้าไม่มีพยัญชนะตาม")
    if re.search(r"[ก-ฮ]\s+[ัิีึืุู็่้๊๋์ำ]", คำ):
        เหตุ.append("ช่องว่างแทรกกลางคำ")
    return sorted(set(เหตุ))


def ประกอบได้(คำ, คลัง, ลึก=0):
    """คำนี้ต่อจากคำในพจนานุกรมได้ไหม เช่น ภาษา+ไทย ⇒ ภาษาไทย"""
    if not คำ:
        return True
    if ลึก > 4:
        return False
    for n in range(len(คำ), 0, -1):
        if คำ[:n] in คลัง and ประกอบได้(คำ[n:], คลัง, ลึก + 1):
            return True
    return False


def main():
    ที่เก็บ, ฐาน = Path(sys.argv[1]), sys.argv[2]
    c = sqlite3.connect(ฐาน)
    คลัง = {r[0] for r in c.execute("select headword_text from headword")}
    คลัง |= {r[0] for r in c.execute("select headword_search from headword")}
    print(f"พจนานุกรมราชบัณฑิต 2554 มีคำตั้ง {len(คลัง)} รูป")

    # ⛔ ไม่จดว่าไฟล์ไหนมีกี่ช่อง — บรรทัดหัวตารางในไฟล์ .tsv เป็นเจ้าของความจริงนั้น
    # (จดซ้ำแล้วไฟล์เปลี่ยนโครง ที่จดไว้จะค้างรุ่นเก่าโดยไม่มีใครรู้)
    ทั้งหมด = Counter()
    for f in sorted(ที่เก็บ.glob("คำพื้นฐาน-*.tsv")):
        บรรทัดทั้งหมด = f.read_text(encoding="utf-8").splitlines()
        หัว = บรรทัดทั้งหมด[0].split("\t")
        # ไฟล์ที่มีช่องชื่อ "คำ" ⇒ ตรวจเฉพาะช่องนั้น (ไฟล์ใหม่มีช่องตัวเลขกับช่องป้ายกำกับปนอยู่)
        # ไฟล์ที่ไม่มี ⇒ ทุกช่องหลังช่องแรกคือคำ (ตารางแยกชั้น ป.1 ป.2 ป.3)
        ช่องคำ = [หัว.index("คำ")] if "คำ" in หัว else range(1, len(หัว))
        for บรรทัด in บรรทัดทั้งหมด[1:]:
            ส่วน = บรรทัด.split("\t")
            for k in ช่องคำ:
                if k < len(ส่วน):
                    for w in คำย่อย(ส่วน[k]):
                        ทั้งหมด[w] += 1

    เจอ, พัง, ประสม, ไม่รู้ = [], [], [], []
    for คำ in sorted(ทั้งหมด):
        if คำ in คลัง or คำ.rstrip("ๆ") in คลัง:
            เจอ.append(คำ)
        elif (เหตุ := รูปเขียนพัง(คำ)):
            พัง.append((คำ, เหตุ))
        elif ประกอบได้(คำ, คลัง):
            ประสม.append(คำ)
        else:
            ไม่รู้.append(คำ)

    n = len(ทั้งหมด)
    print(f"\nคำไม่ซ้ำที่ดึงมาได้ {n} คำ")
    print(f"  ① เจอในพจนานุกรมตรง ๆ        {len(เจอ):5}  ({len(เจอ) / n:.1%})")
    print(f"  ② ไม่เจอ แต่ต่อจากคำในพจนานุกรมได้ {len(ประสม):5}  ({len(ประสม) / n:.1%})  ⇒ ⛔ ไม่ใช่ดึงเพี้ยน แต่ ⚠️ ไม่ได้แปลว่าสะกดถูกทุกคำ")
    print(f"  ③ ไม่เจอ และต่อไม่ได้           {len(ไม่รู้):5}  ({len(ไม่รู้) / n:.1%})  ⇒ ต้องเปิดดูทีละคำ")
    print(f"  ④ รูปเขียนเป็นไปไม่ได้         {len(พัง):5}  ({len(พัง) / n:.1%})  ⇒ ดึงเพี้ยนแน่นอน")
    if พัง:
        print("\nรายการที่รูปเขียนเป็นไปไม่ได้")
        for คำ, เหตุ in พัง:
            print("   ", repr(คำ), เหตุ)
    print(f"\n⚠️ กลุ่ม ② มีคำที่ **ต้นฉบับพิมพ์ตกเอง** ปนอยู่ด้วย เช่น {[w for w in คำที่ต้นฉบับพิมพ์ตก if w in ประสม]}")
    print("   เปิดภาพหน้ากระดาษยืนยันแล้วว่าดึงถูก ⇒ ⛔ อย่าเอากลุ่มนี้ไปใช้ทั้งก้อนโดยไม่ทาน")
    print(f"\nตัวอย่างกลุ่ม ② 15 คำแรก: {ประสม[:15]}")
    print(f"\nกลุ่ม ③ ทั้งหมด {len(ไม่รู้)} คำ:")
    for i in range(0, len(ไม่รู้), 8):
        print("   ", "  ".join(ไม่รู้[i : i + 8]))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
