# ============================================================ ที่อยู่ข้อในตัวหนังสือ
ที่อยู่เลข = re.compile(r"(\d+):(\d+)(?:[-–](\d+))?")
ต่อเล่มเดิม = re.compile(r"; ?(\d+:\d+(?:[-–]\d+)?)")


def ตารางชื่อเล่ม(กอง):
    """ชื่อเล่มที่ **เจ้าของฉบับเขียนเอง** ในไฟล์ USX (`toc1` `toc2` `toc3` `h`) ⇒ {ชื่อ: รหัส}
    ⇒ ⛔ ไม่พิมพ์ชื่อเล่มไว้ที่นี่ ⇒ ฉบับใช้ชื่อแบบไหน เราก็จับแบบนั้น"""
    ออก = {}
    for ไฟล์ in sorted(กอง.glob("*.usx")):
        t = ไฟล์.read_text("utf-8")
        m = re.search(r'<book code="([1-3A-Z]{3})"', t)
        if not m:
            continue
        for ชื่อ in re.findall(r'<para style="(?:toc[123]|h)">([^<]+)<', t):
            ชื่อ = ชื่อ.strip()
            if ชื่อ:
                ออก[ชื่อ] = m.group(1)
                if ชื่อ.startswith("The "):
                    ออก[ชื่อ[4:]] = m.group(1)
    return ออก


def หาที่อยู่(ข้อความ, ชื่อ_รหัส):
    """ที่อยู่ข้อที่เขียนเป็นตัวหนังสือ เช่น `Daniel 9:27; 11:31; 12:11` ⇒ [{ตัวหนังสือ, ที่อยู่}]
    ⇒ ต้องขึ้นต้นด้วยชื่อเล่มที่อยู่ในตารางของฉบับเท่านั้น ⇒ ⛔ เลขลอย ๆ ไม่นับ (เดาเล่มไม่ได้)
    ⇒ ตามด้วย `; 11:31` ⇒ เล่มเดิม"""
    if not ชื่อ_รหัส:
        return []
    ชื่อ = sorted(ชื่อ_รหัส, key=len, reverse=True)
    แบบ = re.compile(r"(?<!\w)(" + "|".join(re.escape(n) for n in ชื่อ) + r")\.? (\d+:\d+(?:[-–]\d+)?)")
    ออก = []
    for m in แบบ.finditer(ข้อความ):
        รหัส = ชื่อ_รหัส[m.group(1)]
        บ, ข = ที่อยู่เลข.match(m.group(2)).groups()[:2]
        ออก.append({"ตัวหนังสือ": m.group(0), "ที่อยู่": "%s %s:%s" % (รหัส, บ, ข)})
        ต่อ = m.end()
        while True:
            m2 = ต่อเล่มเดิม.match(ข้อความ, ต่อ)
            if not m2:
                break
            บ, ข = ที่อยู่เลข.match(m2.group(1)).groups()[:2]
            ออก.append({"ตัวหนังสือ": m2.group(1), "ที่อยู่": "%s %s:%s" % (รหัส, บ, ข)})
            ต่อ = m2.end()
    return ออก


