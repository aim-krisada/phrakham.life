ช่องว่าง = re.compile(r"\s")


def ตาย(ข้อความ):
    print("⛔ " + ข้อความ)
    raise SystemExit(1)


def แปลงตำแหน่ง(ต้นทาง, ของเว็บ, ที่):
    """คืน (ตำแหน่งบนตัวบทของเว็บ, ขั้นที่ใช้) ⇒ ขั้น ① ② ③ ตามหัวไฟล์"""
    if ต้นทาง == ของเว็บ:
        return ที่, 1
    if ช่องว่าง.sub("", ต้นทาง) == ช่องว่าง.sub("", ของเว็บ):
        นับ = len(ช่องว่าง.sub("", ต้นทาง[:ที่]))
        if นับ == 0:
            return 0, 2
        เจอ = 0
        for i, ต in enumerate(ของเว็บ):
            if not ช่องว่าง.match(ต):
                เจอ += 1
                if เจอ == นับ:
                    return i + 1, 2
    return len(ของเว็บ), 3


def พ่น():
    เนื้อบท = อ่านซอง(ซองเนื้อบท)
    ออก = {}
    for ฉบับ in เนื้อบท["ชั้น"]:
        ชั่วคราว = Path(tempfile.mkdtemp(prefix="pk-usx-"))
        try:
            if not แกะกองของฉบับ(ฉบับ, ชั่วคราว):
                print("%-6s ⛔ ไม่มีกอง USX" % ฉบับ)
                continue
            ข้อ, _, _, _, เชิงอรรถ, _ = อ่าน_usx(ชั่วคราว, ฉบับ, เอาคำพระเยซู=True)
            if not any(เชิงอรรถ.values()):
                print("%-6s ⛔ เจ้าของไม่ได้เขียนเชิงอรรถไว้ ⇒ ไม่ใส่ลงซอง" % ฉบับ)
                continue
            ของฉบับ, ขั้น = {}, {1: 0, 2: 0, 3: 0}
            ไม่มีข้อ = 0
            for (ล, บ), รายการ in sorted(เชิงอรรถ.items()):
                ก้อนบท = เนื้อบท["บท"].get("%s/%s" % (ล, บ), {}).get(ฉบับ, {})
                ของบท = []
                for ร in รายการ:
                    ของเว็บ = ก้อนบท.get(str(ร["ข้อ"]))
                    เกาะ, ข้อเดิม = ร["ข้อ"], None
                    if ของเว็บ is None:
                        # ⭐ ข้อที่มีเลขแต่ไม่มีเนื้อ เช่น MAT 17:21 ⇒ เจ้าของย้ายเนื้อไปไว้ในเชิงอรรถ
                        #   ⇒ เว็บไม่มีข้อนั้น ⇒ เกาะท้ายข้อก่อนหน้าที่มีจริง แล้วจำเลขข้อเดิมไว้
                        #   ⇒ ⛔ ไม่ทิ้ง ⇒ อันนี้คืออันที่คนอ่านต้องเห็นที่สุด
                        ก่อนหน้า = [int(k) for k in ก้อนบท if k.isdigit() and int(k) < ร["ข้อ"]]
                        if not ก่อนหน้า:
                            ไม่มีข้อ += 1
                            continue
                        เกาะ, ข้อเดิม = max(ก่อนหน้า), ร["ข้อ"]
                        ที่, ข = len(ก้อนบท[str(เกาะ)]), 3
                    else:
                        ต้นทาง = ข้อ.get((ล, str(บ), str(ร["ข้อ"])), "")
                        ที่, ข = แปลงตำแหน่ง(ต้นทาง, ของเว็บ, ร["หลังอักษร"])
                    ขั้น[ข] += 1
                    ก = {"ข้อ": เกาะ, "หลังอักษร": ที่, "ชนิด": ร["ชนิด"],
                         "ชิ้น": [{"ป้าย": c["ป้าย"], "ตัวหนังสือ": c["ตัวหนังสือ"]}
                                  for c in ร["ชิ้น"] if c["ตัวหนังสือ"].strip()]}
                    if ร.get("โยงไป"):
                        ก["โยงไป"] = ร["โยงไป"]
                    if ข้อเดิม:
                        ก["ข้อเดิม"] = ข้อเดิม
                    elif ข == 3:
                        ก["ท้ายข้อ"] = True
                    ของบท.append(ก)
                if ของบท:
                    ของบท.sort(key=lambda x: (x["ข้อ"], x["หลังอักษร"]))
                    ของฉบับ["%s/%d" % (ล, บ)] = ของบท
            ออก[ฉบับ] = ของฉบับ
            print("%-6s ✅ เชิงอรรถ %5d · บท %4d · ตรงทุกตัว %d · ต่างแค่ช่องว่าง %d · วางท้ายข้อหรือข้อว่าง %d · ทิ้ง %d"
                  % (ฉบับ, sum(len(v) for v in ของฉบับ.values()), len(ของฉบับ),
                     ขั้น[1], ขั้น[2], ขั้น[3], ไม่มีข้อ))
        finally:
            shutil.rmtree(ชั่วคราว, ignore_errors=True)
    if not ออก:
        ตาย("ไม่มีฉบับไหนมีเชิงอรรถเลย ⇒ ⛔ ไม่เขียนไฟล์")
    return ออก


