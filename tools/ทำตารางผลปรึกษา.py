def ล้าง(s):
    """ถอดสระฮีบรูกับเสียงหนักกรีกออก เหลือแต่ตัวพยัญชนะ ใช้เทียบว่าเป็นคำเดียวกันไหม"""
    s = unicodedata.normalize("NFD", s or "")
    s = "".join(c for c in s if not unicodedata.combining(c)
                and not (0x0591 <= ord(c) <= 0x05C7))
    return s.strip().lower()


สรรพนามฮีบรู = ("הוא", "היא", "אתה", "את", "אני", "אנחנו", "הם", "הן",
                "אתם", "אתן", "אנכי")


def เป็นหัวคำได้ไหม(คำ):
    """บอกว่าข้อความนี้เป็นหัวคำได้ไหม

    หัวคำต้องมีตัวพยัญชนะอย่างน้อยสองตัว
    ตัวเดียวไม่ใช่หัวคำ เป็นแค่ชิ้นส่วนที่เกาะท้ายคำ
    เช่นคำตอบที่เขียนมาว่า ה ตัวเดียว หรือ וֹ ตัวเดียว
    """
    return len(ล้าง(คำ)) >= 2


def เป็นสรรพนามไหม(คำ):
    """บอกว่าหัวคำนี้เป็นสรรพนามที่ยืนเองได้ไหม เช่น הוּא แปลว่า เขา"""
    return ล้าง(คำ) in สรรพนามฮีบรู


def บรรทัดแรกของคำตอบ(ทาง):
    """คืนค่า (สถานะ, บรรทัดแรก) จากไฟล์คำตอบหนึ่งใบ

    สถานะ ขาดไฟล์   คือยังไม่ได้ถาม
    สถานะ ไฟล์ว่าง  คือมีไฟล์แต่ไม่มีเนื้อ
    สถานะ หมดเวลา   คือถามแล้วแต่ปลายทางไม่ตอบจนหมดเวลา
    สถานะ ตอบไม่ได้  คือเขาตอบว่าแหล่งข้อมูลของเขาไม่ครอบคลุมเรื่องนี้
    สถานะ ตอบแล้ว   คือมีคำตอบจริง
    """
    if not ทาง.exists():
        return "ขาดไฟล์", ""
    เนื้อ = ทาง.read_text(encoding="utf-8").strip()
    if not เนื้อ:
        return "ไฟล์ว่าง", ""
    if "FAILED" in เนื้อ and "--- answer ---" not in เนื้อ:
        return "หมดเวลา", ""
    if "--- answer ---" not in เนื้อ:
        return "ไฟล์ว่าง", ""
    _, _, หลัง = เนื้อ.partition("--- answer ---")
    หลัง = หลัง.strip()
    if not หลัง:
        return "ไฟล์ว่าง", ""
    if "do not cover" in หลัง or "cannot provide" in หลัง:
        return "ตอบไม่ได้", ""
    for บรรทัด in หลัง.splitlines():
        t = re.sub(r"[*`#_]", "", บรรทัด).strip().strip(".").strip()
        if t:
            return "ตอบแล้ว", t
    return "ไฟล์ว่าง", ""


def คำตัดสินรอบแรก(บรรทัด):
    """รอบแรกบังคับให้บรรทัดแรกเป็น YES หรือ NO หรือ PARTLY"""
    หัว = บรรทัด.upper()
    for คำ in ("PARTLY", "YES", "NO"):
        if หัว.startswith(คำ):
            return คำ
    return ""


