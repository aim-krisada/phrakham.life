/** เลื่อนลงกลางบท ⇒ ขอบของแถบหนึบ ⇒ หัวคำเดิมยังเห็นและ ⛔ ไม่มีอะไรบัง */
async function สภาพหนึบ(แท็บ) {
  await แท็บ.evaluate(() => window.scrollTo(0, document.querySelector('.pk-ตัวบท').getBoundingClientRect().top + scrollY + 1200))
  await แท็บ.waitForTimeout(400)
  return แท็บ.evaluate(() => {
    const แถบ = document.querySelector('.pk-แถบบน').getBoundingClientRect().bottom
    const หนึบ = [...document.querySelectorAll('.pk-หัวคอลัมน์, .pk-ชื่อคำเดิม, .pk-หัวคำเดิม')].filter((e) => {
      const r = e.getBoundingClientRect()
      return r.height && Math.abs(r.top - แถบ) < 2 && ['sticky', 'fixed'].includes(getComputedStyle(e).position)
    })
    const หัวคำ = document.querySelector('.pk-ชื่อคำเดิม')
    const ร = หัวคำ?.getBoundingClientRect()
    const จุด = ร ? document.elementFromPoint(ร.left + 8, ร.top + ร.height / 2) : null
    const หัวฉบับ = document.querySelector('.pk-หัวคอลัมน์')?.getBoundingClientRect()
    const ล่างหนึบ = Math.max(แถบ, ...หนึบ.map((e) => e.getBoundingClientRect().bottom))
    // ⭐ ใบ #145 ข้อ 4 ⇒ คำเดิมเป็นช่องในตารางฉบับ (`pk-คำเดิมในช่อง`) ⇒ หัวของมันเป็นช่องในแถวหัว ⇒ ห่อลงแถวที่ 2 ได้เหมือนหัวฉบับแปล
    //   ⇒ เกณฑ์ *เห็น* ของแบบนี้ ⇒ ทั้งหัวอยู่ในแถบหนึบ และจุดกลางหัวเป็นของหัวเอง ⇒ แบบอื่นเกณฑ์เดิมทุกตัว (ขอบบนชิดแถบบน)
    const ในช่อง = !!document.querySelector('.pk-คอลัมน์.pk-คำเดิมในช่อง')
    return {
      แถบ: Math.round(แถบ * 10) / 10,
      สูงหนึบ: Math.round((ล่างหนึบ - แถบ) * 10) / 10,
      ชิ้นที่หนึบ: หนึบ.map((e) => e.className.split(' ')[0]),
      ในช่อง,
      หัวคำเห็น:
        !!ร &&
        ร.top >= แถบ - 1 &&
        (ในช่อง ? ร.bottom <= ล่างหนึบ + 1 : ร.top <= แถบ + 2) &&
        !!จุด &&
        หัวคำ.contains(จุด),
      หัวคำล่าง: ร ? Math.round(ร.bottom) : null,
      หัวฉบับล่าง: หัวฉบับ ? Math.round(หัวฉบับ.bottom) : null,
      ป้าย: หัวคำ?.querySelector('.pk-ที่ของช่อง')?.textContent.trim() || หัวคำ?.textContent.trim() || '',
    }
  })
}

