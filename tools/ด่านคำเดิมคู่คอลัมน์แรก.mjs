      const { ctx, แท็บ } = await เปิด('/read/2CO?c=6', { กว้าง, ฉบับ: ['TCV'], มุม: { ภาษาเดิม: true, จัดวาง: 'แยกตามย่อหน้า', ...(กว้าง < 768 ? { วางคอลัมน์: 'บนล่าง' } : {}) }, พัง })
