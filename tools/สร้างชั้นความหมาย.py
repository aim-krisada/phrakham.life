def ห่อ(ของ, ชื่อของ, บีบ=True):
    """ทำก้อนไบต์ ⇒ **ข้อมูลเท่าเดิมต้องได้ไบต์เท่าเดิม** (ท่าเดียวกับ `tools/สร้างเนื้อบท.py`)"""
    ข้อความ = json.dumps(ของ, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    if not บีบ:
        ข้อความ += "\n"
    กันของต้องห้ามหลุด(ข้อความ, ชื่อของ)      # ด่าน ④
    เนื้อ = ข้อความ.encode("utf-8")
    if not บีบ:
        return เนื้อ
    ถัง = io.BytesIO()
    # mtime=0 ⇒ ⛔ ไม่ประทับเวลาลงหัวซอง ⇒ ไม่งั้นไบต์เปลี่ยนทุกครั้งที่รัน
    with gzip.GzipFile(fileobj=ถัง, mode="wb", compresslevel=9, mtime=0) as ซ:
        ซ.write(เนื้อ)
    return ถัง.getvalue()


# ============================================== อ่านจำนวนคำของแต่ละข้อจากชั้นคำ
def คำของแต่ละบท(ฝั่ง):
    """คืน {(เล่ม, บท): {ข้อ: จำนวนคำ}} ของชั้นคำฝั่งนั้น จาก `_ข้อมูลเว็บ/`

    ⭐ **เจ้าของลำดับคำคือชั้นคำ** ⇒ ชั้นความหมายต้องเรียงตามเขา ⛔ ไม่นับเอง
    """
    ชื่อชั้นคำ = ชั้นคำของฝั่ง[ฝั่ง]
    ออก = {}
    for เล่ม in ตัวแปลง.สารบบ:
        โฟลเดอร์ = ต้นทางเว็บ / เล่ม
        if not โฟลเดอร์.is_dir():
            continue
        for ทาง in sorted(โฟลเดอร์.glob("*.json"), key=lambda p: int(p.stem)):
            d = json.loads(ทาง.read_text(encoding="utf-8"))
            ก้อน = d["ชั้น"].get(ชื่อชั้นคำ)
            if ก้อน:
                ออก[(เล่ม, int(ทาง.stem))] = {ข: len(ว) for ข, ว in ก้อน.items()}
    return ออก


