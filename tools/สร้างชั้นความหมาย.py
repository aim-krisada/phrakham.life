def ห่อกอง(รายบท, คลังรวม, สรุป):
    """คืน {ชื่อไฟล์ญาติ: ไบต์} ของทั้งกองชั้นความหมาย"""
    ไฟล์ = {}
    เล่มในบัญชี = {}
    for เล่ม, บท, ก้อน in รายบท:
        ไฟล์[f"{เล่ม}/{บท}.json.gz"] = ห่อ(ก้อน, f"ไฟล์ความหมาย {เล่ม}/{บท}")
        รายการ = เล่มในบัญชี.setdefault(เล่ม, {"รหัส": เล่ม, "ชั้น": [], "บทที่มี": []})
        รายการ["บทที่มี"].append(บท)
        for ช in ก้อน["ชั้น"]:
            if ช not in รายการ["ชั้น"]:
                รายการ["ชั้น"].append(ช)

    # ⛔ คลังแยกทีละฝั่ง ⇒ รหัสของสองฝั่งชนกันจริง (เหตุผลอยู่ที่หัวไฟล์)
    ชื่อคลัง = {}
    for ฝั่ง, ชื่อชั้น in ชั้นของฝั่ง.items():
        ของฝั่ง = คลังรวม[ชื่อชั้น]
        ชื่อคลัง[ชื่อชั้น] = f"คลัง-{ฝั่ง}.json.gz"
        ไฟล์[ชื่อคลัง[ชื่อชั้น]] = ห่อ({
            "ฝั่ง": ฝั่ง,
            "คำอธิบาย": "รหัสความหมาย ⇒ คำนิยามจากพจนานุกรมของ UBS ⇒ โหลดครั้งเดียวใช้ได้ทั้งฝั่ง",
            "นับ": {"ความหมายที่เนื้อจริงเรียกใช้": len(ของฝั่ง)},
            "ความหมาย": {k: ของฝั่ง[k] for k in sorted(ของฝั่ง)},
        }, f"คลังความหมายฝั่ง{ฝั่ง}")

    บัญชี = {
        "ชั้น": [ชั้นของฝั่ง[f] for f in ("ฮีบรู", "กรีก")],
        "แหล่งของชั้น": แหล่งของชั้น,
        "เครดิต": เครดิตของชั้น(),
        "คลังของชั้น": ชื่อคลัง,
        "เรียงตรงกับ": "_data/ภาษาเดิม/<เล่ม>/<บท>.json.gz ⇒ คำต่อคำ ⇒ ช่องว่างแปลว่าไม่มีความหมายให้",
        "เล่ม": list(เล่มในบัญชี.values()),
        "รวม": dict(สรุป, **{"ความหมายที่ใช้": {ช: len(ก) for ช, ก in คลังรวม.items()}}),
    }
    ไฟล์["บัญชี.json"] = ห่อ(บัญชี, "บัญชีของชั้นความหมาย", บีบ=False)
    return ไฟล์


def ที่มีอยู่จริง():
    if not ปลายทาง.exists():
        return {}
    return {p.relative_to(ปลายทาง).as_posix(): p.read_bytes()
            for p in ปลายทาง.rglob("*") if p.is_file()}


