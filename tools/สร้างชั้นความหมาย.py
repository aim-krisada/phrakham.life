def นับแล้วเทียบ(สรุป, ตรึงคำ=None, ตรึงต่อติด=None, พิมพ์=True):
    """เทียบ เล่ม · ข้อ · คำ · ต่อติด กับเลขที่ตรึงไว้ ⇒ คืน **รายการที่ผิด** ⛔ ไม่ตายเอง

    ⭐ เลข เล่ม · ข้อ · คำ ยืมมาจาก `ควรได้` ของ `tools/สร้างข้อมูลเว็บ.py`
      ⇒ ชั้นความหมายเรียงตรงกับชั้นคำ ⇒ **ต้องได้เลขชุดเดียวกันเป๊ะ** ⛔ ไม่ตรงคือของหาย
    """
    ตรึงคำ = ตรึงคำ or ตัวแปลง.ควรได้
    ตรึงต่อติด = ตรึงต่อติด or ต่อติดที่ตรึงไว้
    ผิด = []
    for ฝั่ง, ชื่อชั้น in ชั้นของฝั่ง.items():
        ได้ = สรุป.get(ชื่อชั้น)
        if ได้ is None:
            ผิด.append(f"{ชื่อชั้น}: ไม่มีชั้นนี้เลย")
            continue
        ค = ตรึงคำ[ชั้นคำของฝั่ง[ฝั่ง]]
        ของชั้นนี้ = [f"{ชื่อชั้น}: ได้ {ได้[เรื่อง]:,} {เรื่อง} ⇒ ควรได้ {ค[เรื่อง]:,} {เรื่อง}"
                     for เรื่อง in ("เล่ม", "ข้อ", "คำ") if ได้[เรื่อง] != ค[เรื่อง]]
        if ได้["ต่อติด"] != ตรึงต่อติด[ชื่อชั้น]:
            ของชั้นนี้.append(f"{ชื่อชั้น}: ต่อความหมายติด {ได้['ต่อติด']:,} คำ "
                             f"⇒ ที่ตรึงไว้คือ {ตรึงต่อติด[ชื่อชั้น]:,} คำ")
        ผิด += ของชั้นนี้
        if พิมพ์:
            print(f"   {'⛔' if ของชั้นนี้ else '✅'} {ชื่อชั้น:14} {ได้['เล่ม']:>2} เล่ม · "
                  f"{ได้['ข้อ']:>6,} ข้อ · {ได้['คำ']:>7,} คำ ⇒ ต่อติด {ได้['ต่อติด']:>7,} คำ "
                  f"({ได้['ต่อติด'] * 100 / ได้['คำ']:.2f} ใน 100)")
    return ผิด


