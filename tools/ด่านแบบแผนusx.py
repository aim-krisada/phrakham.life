ตัวอย่างเสีย = _หัวตัวอย่าง.format('<char style="qs"/>')


def ทดสอบตัวเอง() -> int:
    """พิสูจน์แดง-เขียวด้วยตัวอย่างที่ปั้นเอง ⛔ ไม่ต้องมีกอง"""
    ตก = 0
    เทส = [
        ("ของถูก ⇒ ด่านป้ายเปล่าต้องเขียว", lambda: not ป้ายเปล่า(ET.fromstring(ตัวอย่างดี))),
        ("แท็กเปล่า ⇒ ด่านป้ายเปล่าต้องแดง", lambda: bool(ป้ายเปล่า(ET.fromstring(ตัวอย่างเสีย)))),
    ]
    # ⭐ สองข้อนี้คือ **หลักฐานว่าทำไมต้องมีด่านป้ายเปล่า** ⇒ แบบแผนเขียวทั้งของถูกและแท็กเปล่า
    #   ⏸ ต้องมีทั้ง lxml และไฟล์แบบแผนในเครื่อง ⇒ ตัวรันที่ไม่มี ⇒ ข้ามพร้อมบอกเหตุ
    #   ⛔ ไม่ทำให้ด่านแดง ⇒ ของที่ขาดคือ *เครื่องมือ* ⛔ ไม่ใช่ *ตัวบท*
    มีแบบแผน = ที่อยู่แบบแผน.exists()
    try:
        import lxml  # noqa: F401

        มีlxml = True
    except ImportError:
        มีlxml = False
    if มีlxml and มีแบบแผน:
        ทาบ, etree = ตัวทาบแบบแผน()
        เทส += [
            ("ของถูก ⇒ แบบแผนต้องเขียว", lambda: ทาบ.validate(etree.fromstring(ตัวอย่างดี.encode()))),
            (
                "แท็กเปล่า ⇒ แบบแผนยังเขียว (เนื้อของ char เป็นตัวหนังสือได้ ⇒ ยาวศูนย์ตัวก็นับ)",
                lambda: ทาบ.validate(etree.fromstring(ตัวอย่างเสีย.encode())),
            ),
        ]
    else:
        ขาด = "lxml" if not มีlxml else f"ไฟล์แบบแผนที่ {ที่อยู่แบบแผน.name}"
        print(f"⏸ ข้ามสองข้อที่ทาบกับแบบแผน ⇒ เครื่องนี้ไม่มี {ขาด}")
    for ชื่อ, ทำ in เทส:
        ได้ = ทำ()
        if not ได้:
            ตก += 1
        print(f"{'✅' if ได้ else '⛔'} {ชื่อ}")
    print(f"⛔ เทสตก {ตก} ข้อ" if ตก else "✅ เทสผ่านครบ")
    return 1 if ตก else 0


def ตรวจที่ขึ้นเว็บ() -> int:
    """ตรวจป้ายเปล่าใน **ไฟล์จริงที่คอมมิตไว้** ⇒ ของที่จะออกไปถึงผู้อ่าน

    ⛔ ไม่ทาบแบบแผนที่นี่ ⇒ ท่อ CI ⛔ ไม่มีกอง `_แตก` ⇒ ไม่มีไฟล์แบบแผนให้ทาบ
    ⚠️ ต้องเป็นไบต์จริงของ LFS ⛔ ไม่ใช่ตัวชี้ ⇒ เจอตัวชี้ ด่านหยุดแล้วบอก
    """
    ตก = 0
    for โฟลเดอร์ in sorted(p for p in ปลายทาง.iterdir() if p.is_dir()):
        ไฟล์ = [โฟลเดอร์ / f"{เล่ม}.usx.gz" for เล่ม in สารบบ if (โฟลเดอร์ / f"{เล่ม}.usx.gz").exists()]
        if not ไฟล์:
            print(f"⛔ {โฟลเดอร์.name} ⇒ ไม่มีไฟล์ในสารบบสักเล่ม")
            ตก += 1
            continue
        แดง = 0
        for f in ไฟล์:
            ดิบ = f.read_bytes()
            if ดิบ[:2] != b"\x1f\x8b":
                print(f"⛔ {โฟลเดอร์.name}/{f.name} ⇒ ไม่ใช่ซองจริง (ตัวชี้ LFS?) ⇒ ด่านนี้ตรวจไม่ได้")
                return 2
            เจอ = ป้ายเปล่า(ET.fromstring(gzip.decompress(ดิบ)))
            if เจอ:
                แดง += 1
                ตก += 1
                print(f"⛔ {โฟลเดอร์.name}/{f.name} ⇒ ป้ายห่อถ้อยคำว่าง {len(เจอ)} จุด ⇒ {' · '.join(เจอ[:3])}")
        print(f"{'⛔' if แดง else '✅'} {โฟลเดอร์.name} ⇒ ตรวจ {len(ไฟล์)} เล่มที่ขึ้นเว็บ ⇒ ไม่ผ่าน {แดง}")
    return 1 if ตก else 0


def main() -> int:
    if "--ทดสอบตัวเอง" in sys.argv:
        return ทดสอบตัวเอง()
    if "--ที่ขึ้นเว็บ" in sys.argv:
        return ตรวจที่ขึ้นเว็บ()

    if not ที่พักแปลง.exists():
        print(f"⛔ ไม่เจอ {ที่พักแปลง.name} ⇒ สั่ง node tools/แปลงusfmเป็นusx.mjs ก่อน")
        return 2

    ทาบ, etree = ตัวทาบแบบแผน()
    ตก = 0
    for โฟลเดอร์ in sorted(p for p in ที่พักแปลง.iterdir() if p.is_dir()):
        # ⭐ ตรวจเฉพาะ 66 เล่มที่ขึ้นเว็บจริง ⇒ บัญชีเล่มขอจาก `สร้างข้อมูลเว็บ` ⛔ ไม่พิมพ์ซ้ำ
        #   ⇒ ไฟล์นอกบัญชี (หนังสือนอกสารบบ · หัวเล่ม · อภิธานศัพท์) ⛔ ไม่ขึ้นเว็บ ⇒ ไม่ตรวจ
        ไฟล์ = [โฟลเดอร์ / f"{เล่ม}.usx" for เล่ม in สารบบ if (โฟลเดอร์ / f"{เล่ม}.usx").exists()]
        นอกบัญชี = len(list(โฟลเดอร์.glob("*.usx"))) - len(ไฟล์)
        แดง = 0
        เปล่ารวม = 0
        for f in ไฟล์:
            ราก = etree.parse(str(f))
            if not ทาบ.validate(ราก):
                แดง += 1
                ตก += 1
                print(f"⛔ {โฟลเดอร์.name}/{f.name} ⇒ {ทาบ.error_log.last_error}")
            # ⭐ ด่านที่สอง ⇒ แบบแผนยอมให้ป้าย char ว่าง แต่เรา ⛔ ไม่ยอม (เหตุผลอยู่หัวไฟล์)
            เจอ = ป้ายเปล่า(ราก.getroot())
            if เจอ:
                เปล่ารวม += len(เจอ)
                ตก += 1
                print(f"⛔ {โฟลเดอร์.name}/{f.name} ⇒ ป้ายห่อถ้อยคำว่าง {len(เจอ)} จุด ⇒ {' · '.join(เจอ[:3])}")
        เครื่องหมาย = "⛔" if (แดง or เปล่ารวม) else "✅"
        print(
            f"{เครื่องหมาย} {โฟลเดอร์.name} ⇒ ตรวจ {len(ไฟล์)} เล่มในสารบบ ⇒ ผิดแบบแผน {แดง} · ป้ายเปล่า {เปล่ารวม}"
            + (f" (ข้ามไฟล์นอกสารบบ {นอกบัญชี})" if นอกบัญชี else "")
        )
    return 1 if ตก else 0


if __name__ == "__main__":
    sys.exit(main())
