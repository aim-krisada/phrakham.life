    //   ⇒ วัดที่ **ช่องของแต่ละฉบับ** ⛔ ไม่ใช่แถวทั้งแถว ⇒ ก้อนคำต้องอยู่ขวาของช่องคอลัมน์แรก และ ⛔ ทับช่องตัวบทของฉบับไหนเลย
    //   ⇒ ของเดิม (ใบ #112) วัดว่าอยู่ขวาของแถวทั้งแถว ⇒ พี่เอมอนุมัติให้เปลี่ยน ⇒ https://aimgit.aimagin.com/v3/phrakham/-/issues/125#note_30155
