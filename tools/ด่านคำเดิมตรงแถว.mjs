/** ไฟล์คำเดิมของบทที่เว็บส่งจริง ⇒ ⛔ ขอจาก Node ⛔ ไม่ผ่านแท็บ ⇒ ดักแก้ในแท็บแล้วด่านยังเห็นของจริง */
const คลังไฟล์ = new Map()
async function ไฟล์คำ(เล่ม, c) {
  const k = `${เล่ม}/${c}`
  if (!คลังไฟล์.has(k)) {
    const r = await fetch(`${ฐาน}/api/words/${k}.json`)
    คลังไฟล์.set(k, r.ok ? await r.json() : null)
  }
  return คลังไฟล์.get(k)
}

/** ข้อเดิมที่ควรอยู่ก้อนบท c ⇒ ข้อแปลข้อแรกที่อยู่บนหน้าอยู่บท c ⇒ คืน `[{ที่, ไป, คำ}]` */
async function ข้อเดิมของบท(เล่ม, c, บนหน้า) {
  const ออก = []
  for (const b of [c - 1, c, c + 1]) {
    const ไฟล์ = b >= 1 ? await ไฟล์คำ(เล่ม, b) : null
    if (!ไฟล์) continue
    for (const ข้อทั้งหมด of Object.values(ไฟล์.ชั้น))
      for (const [ข้อ, คำ] of Object.entries(ข้อทั้งหมด)) {
        const ไป = ไฟล์.ข้อแปล?.[ข้อ] ?? [[b, Number(ข้อ)]]
        if (ไป.find(([บ]) => บนหน้า.includes(บ))?.[0] === c) ออก.push({ ที่: `${b}:${ข้อ}`, ไป, คำ: คำ.length })
      }
  }
  return ออก
}

async function เปิด({ เล่ม, บท, กว้าง, จัดวาง, ขนาด, เลข = true, ฉบับ = ['TCV'] }, ตก) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: 950 } })
  await ctx.addInitScript(
    ([ฉ, จ, ข, ล]) => {
      localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
      localStorage.setItem('phrakham.view', JSON.stringify({ จัดวาง: จ, แสดงเลข: ล, ภาษาเดิม: true, ขนาดคำเดิม: ข }))
    },
    [ฉบับ, จัดวาง, ขนาด, เลข],
  )
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}/read/${เล่ม}?c=${บท}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: รอนานสุด })
  const พร้อม = await รอจัดเสร็จ(แท็บ, บท)
  if (!พร้อม) ตก.push(`${ป้าย({ เล่ม, บท, กว้าง, จัดวาง, ขนาด, เลข })} ⇒ หน้า ⛔ ไม่พร้อมภายใน ${รอนานสุด / 1000} วินาที`)
  return { ctx, แท็บ, พร้อม }
}

