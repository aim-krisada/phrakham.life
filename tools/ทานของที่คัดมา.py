"""ทานว่าไฟล์ต้นทางของรุ่น 2 ที่เราคัดของมา ยังเป็นไฟล์เดิมอยู่ไหม

รัน: py -3.14 tools/ทานของที่คัดมา.py
     py -3.14 tools/ทานของที่คัดมา.py --ราก <ที่อยู่รุ่น 2>

ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/24 เกณฑ์ผ่านข้อ 8

## ทำไมต้องมี

รุ่น 3 **คัดของรุ่น 2 มาเป็นฐาน** ⇒ เจ้าของเหตุผลคือ `docs/wpa-08-mission-statement.md`
หัวข้อ *หลัก 2 ข้อที่รุ่น 3 ยึด* ข้อ ② ⛔ ไม่จดซ้ำที่นี่

⇒ ⛔ **คัดมาแล้วเงียบ = วันที่เจ้าของต้นทางแก้ ไม่มีใครรู้เลย**
⇒ บัญชีที่ `docs/ของที่คัดจากรุ่น-2.tsv` ตรึงลายนิ้วมือไว้ ⇒ สคริปต์นี้ทาน

## ⛔ ด่านนี้รันบนอัมกิตไม่ได้

ตัวรันของอัมกิต ⛔ ไม่มีโฟลเดอร์ของรุ่น 2 ⇒ **นี่คือด่านของเครื่องเรา**
⇒ ไม่เจอโฟลเดอร์ต้นทาง ⇒ **ข้ามอย่างมีเสียง** ⛔ ไม่ใช่เขียวเงียบ ๆ เหมือนตรวจแล้ว

## ⛔ ห้ามแก้ห้ามแตะไฟล์ในรุ่น 2

สคริปต์นี้ **เปิดอ่านอย่างเดียว** ⛔ ไม่เขียนอะไรลงไปในโฟลเดอร์นั้นเลย
"""

import argparse
import csv
import hashlib
import io
import os
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ที่เก็บ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
บัญชี = os.path.join(ที่เก็บ, "docs", "ของที่คัดจากรุ่น-2.tsv")
รากปริยาย = r"C:\gl\krisada\phrakham.life2"
แท็บ = chr(9)


def อ่านบัญชี():
    with io.open(บัญชี, encoding="utf-8") as ฟ:
        แถว = [b for b in ฟ.read().split("\n") if b.strip() and not b.startswith("#")]
    หัว = แถว[0].split(แท็บ)
    if หัว[:3] != ["ไฟล์ต้นทาง", "ไบต์", "sha256"]:
        print(f"⛔ หัวตารางของ {บัญชี} ไม่ใช่รูปที่สคริปต์นี้อ่านได้ ⇒ ได้ {หัว[:3]}")
        sys.exit(2)
    return [dict(zip(หัว, b.split(แท็บ))) for b in แถว[1:]]


def ลายนิ้วมือ(ทาง):
    h = hashlib.sha256()
    with open(ทาง, "rb") as ฟ:
        for ก้อน in iter(lambda: ฟ.read(1 << 20), b""):
            h.update(ก้อน)
    return h.hexdigest()


def main():
    ก = argparse.ArgumentParser(description="ทานลายนิ้วมือไฟล์ต้นทางของรุ่น 2")
    ก.add_argument("--ราก", default=รากปริยาย, help="ที่อยู่โฟลเดอร์ของเว็บรุ่น 2")
    args = ก.parse_args()

    รายการ = อ่านบัญชี()
    print(f"ทานของที่คัดมา · บัญชี {len(รายการ)} ไฟล์ · ต้นทาง {args.ราก}")

    if not os.path.isdir(args.ราก):
        # ⛔ ไม่มีต้นทาง = ตรวจไม่ได้ ⛔ ไม่ใช่ผ่าน ⇒ พูดออกมาให้ชัด แล้วออกด้วยรหัสที่แปลว่า "ข้าม"
        print(f"⏭ ⛔ ไม่มีโฟลเดอร์ {args.ราก} ⇒ **ข้ามการทาน** ⛔ ไม่ได้แปลว่าผ่าน")
        sys.exit(0)

    ไม่ตรง = []
    for แถว in รายการ:
        ทาง = os.path.join(args.ราก, แถว["ไฟล์ต้นทาง"].replace("/", os.sep))
        if not os.path.isfile(ทาง):
            ไม่ตรง.append(f"{แถว['ไฟล์ต้นทาง']} ⇒ ⛔ หาไฟล์ไม่เจอแล้ว")
            continue
        ไบต์ = os.path.getsize(ทาง)
        เลข = ลายนิ้วมือ(ทาง)
        if str(ไบต์) != แถว["ไบต์"] or เลข != แถว["sha256"]:
            ไม่ตรง.append(
                f"{แถว['ไฟล์ต้นทาง']} ⇒ บัญชีจดไว้ {แถว['ไบต์']} ไบต์ · {แถว['sha256'][:16]}…"
                f" ⇒ ของจริงวันนี้ {ไบต์} ไบต์ · {เลข[:16]}…"
            )
        else:
            print(f"  ✅ {แถว['ไฟล์ต้นทาง']}")

    if ไม่ตรง:
        print(f"\n⛔ ต้นทางเปลี่ยนไป {len(ไม่ตรง)} ไฟล์ ⇒ เปิดดูเองว่าเขาแก้อะไร แล้วตัดสินว่าของเราต้องตามไหม")
        for x in ไม่ตรง:
            print("  - " + x)
        sys.exit(1)
    print("\n✅ ต้นทางทุกไฟล์ยังเป็นไฟล์เดิมที่เราคัดมา")


if __name__ == "__main__":
    main()
