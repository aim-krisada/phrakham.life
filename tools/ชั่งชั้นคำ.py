def บีบ(ไบต์):
    """บีบด้วย gzip ท่าเดียวกับ `tools/สร้างเนื้อบท.py` ⇒ เลขที่ได้จึงเทียบกันได้ตรง ๆ"""
    ถัง = io.BytesIO()
    with gzip.GzipFile(fileobj=ถัง, mode="wb", compresslevel=9, mtime=0) as ซ:
        ซ.write(ไบต์)
    return ถัง.getvalue()


def เป็นไบต์(ของ):
    """ทำ JSON ท่าเดียวกับตัวห่อซอง ⇒ เรียงกุญแจตายตัว ไม่มีช่องว่างส่วนเกิน"""
    return json.dumps(ของ, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":")).encode("utf-8")


def เก็บชั้นคำ():
    """อ่าน `_ข้อมูลเว็บ/` ⇒ คืนชั้นคำภาษาเดิมของทุกบท เรียงตามชื่อบท

    คืน [(ชื่อบท, ก้อนของบทนั้น), ...] ⇒ ก้อนมีหน้าตาเดียวกับที่จะเขียนลงไฟล์รายบทจริง
    """
    if not (ต้นทาง / "บัญชี.json").exists():
        raise SystemExit(
            f"⛔ ไม่มี {ต้นทาง}\n"
            "   ⇒ สั่ง 3 คำสั่งนี้ก่อน (ดู docs/ข้อมูลที่เว็บอ่าน.md)\n"
            '     git -c lfs.fetchexclude= lfs pull -I "source/"\n'
            "     py -3.14 tools/แตกกอง.py\n"
            "     py -3.14 tools/สร้างข้อมูลเว็บ.py")

    บัญชี = json.loads((ต้นทาง / "บัญชี.json").read_text(encoding="utf-8"))
    ผล = []
    for เล่ม in บัญชี["เล่ม"]:
        รหัส = เล่ม["รหัส"]
        for ทาง in sorted((ต้นทาง / รหัส).glob("*.json"), key=lambda p: int(p.stem)):
            d = json.loads(ทาง.read_text(encoding="utf-8"))
            ชั้น = {k: v for k, v in d["ชั้น"].items() if k in ชั้นภาษาเดิม}
            if not ชั้น:
                continue
            ผล.append((f"{รหัส}/{ทาง.stem}", {
                "เล่ม": รหัส, "บท": int(ทาง.stem),
                "แหล่งของชั้น": {ช: d["แหล่งของชั้น"][ช] for ช in ชั้น},
                "ชั้น": ชั้น,
            }))
    return ผล


