def จับเวลาโหลดจริง(รายบทบีบแล้ว):
    """เสิร์ฟไฟล์รายบทจริงบนเครื่องนี้ แล้วโหลดครบทุกไฟล์ ⇒ คืนวินาทีที่ใช้

    ⛔ **นี่ ⛔ ไม่ใช่เวลาที่ผู้อ่านจะเจอ** — บนเครื่องเดียวกันไม่มีเวลารอเน็ตเลย
    ⇒ มันตอบคำถามเดียว ⇒ **ตัวเสิร์ฟกับการเปิดไฟล์ทีละไฟล์ กินเวลาเท่าไร**
    """
    import tempfile

    with tempfile.TemporaryDirectory() as ชั่วคราว:
        ราก = Path(ชั่วคราว)
        for ชื่อ, ไบต์ in รายบทบีบแล้ว:
            ทาง = ราก / f"{ชื่อ}.json.gz"
            ทาง.parent.mkdir(parents=True, exist_ok=True)
            ทาง.write_bytes(ไบต์)

        class เงียบ(SimpleHTTPRequestHandler):
            # ⛔ ไม่พิมพ์บรรทัดละคำขอ ⇒ 1,189 บรรทัดกลบผลสรุปจนอ่านไม่เจอ
            def log_message(self, *_):
                pass

        ตัวจัดการ = partial(เงียบ, directory=str(ราก))
        เสิร์ฟ = HTTPServer(("127.0.0.1", 0), ตัวจัดการ)
        เสิร์ฟ.timeout = 5
        พอร์ต = เสิร์ฟ.server_address[1]
        สาย = threading.Thread(target=เสิร์ฟ.serve_forever, daemon=True)
        สาย.start()
        try:
            คิว = [f"http://127.0.0.1:{พอร์ต}/{ชื่อ}.json.gz" for ชื่อ, _ in รายบทบีบแล้ว]
            ดัชนี = [0]
            ล็อก = threading.Lock()
            ได้ = [0]

            def ดึง():
                while True:
                    with ล็อก:
                        if ดัชนี[0] >= len(คิว):
                            return
                        i = ดัชนี[0]
                        ดัชนี[0] += 1
                    with urllib.request.urlopen(คิว[i]) as r:
                        n = len(r.read())
                    with ล็อก:
                        ได้[0] += n

            เริ่ม = time.perf_counter()
            สายทั้งหมด = [threading.Thread(target=ดึง) for _ in range(สายปริยาย)]
            for s in สายทั้งหมด:
                s.start()
            for s in สายทั้งหมด:
                s.join()
            ใช้เวลา = time.perf_counter() - เริ่ม
        finally:
            เสิร์ฟ.shutdown()
            เสิร์ฟ.server_close()
    return ใช้เวลา, ได้[0]


def เวลาบนเน็ตช้า(ไบต์, จำนวนคำขอ, เร็ว, หน่วง, สาย):
    """ประมาณเวลารอของผู้อ่านบนเน็ตช้า ⇒ **เวลารอสาย** บวก **เวลาส่งไบต์**

    ⭐ สูตรมีสองก้อนเท่านั้น ⇒ อ่านแล้วตรวจเองได้ ⛔ ไม่มีตัวคูณลึกลับ
      รอสาย = (จำนวนคำขอ ÷ สายที่เปิดพร้อมกัน) × เวลาหน่วงต่อคำขอ
      ส่งไบต์ = ไบต์ทั้งหมด ÷ ความเร็ว
    """
    รอสาย = (จำนวนคำขอ / สาย) * (หน่วง / 1000)
    ส่งไบต์ = ไบต์ * 8 / (เร็ว * 1000)
    return รอสาย, ส่งไบต์


