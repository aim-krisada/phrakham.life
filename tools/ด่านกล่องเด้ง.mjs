        await เปิดกล่อง(แท็บ, ก)
        const ว = await วัดกล่อง(แท็บ, ก.กล่อง, 0, ชื่อปุ่มปิดกล่อง)
        if (!ว) {
          ตก.push(`① ${ป้าย} ⇒ กดปุ่มแล้ว ⛔ มีกล่อง ${ก.กล่อง}`)
          continue
        }
        const เต็มจอ = w < เส้นจอกว้าง
        // ① รูปแบบ
        if (เต็มจอ) {
          if (Math.abs(ว.ก.l) > 0.5 || Math.abs(ว.ก.r - ว.จอ) > 0.5 || Math.abs(ว.ก.b - ว.สูงจอ) > 0.5 || Math.abs(ว.ก.t - ว.ล่างแถบ) > 0.5)
            ตก.push(`① ${ป้าย} ⇒ ⛔ เป็นหน้าเต็มจอใต้แถบบน ⇒ กล่อง ${ว.ก.l.toFixed(0)},${ว.ก.t.toFixed(0)} ถึง ${ว.ก.r.toFixed(0)},${ว.ก.b.toFixed(0)} · จอ ${ว.จอ}×${ว.สูงจอ} · แถบบนจบที่ ${ว.ล่างแถบ.toFixed(1)}`)
        } else {
          const ป = await ก.ปุ่ม(แท็บ).boundingBox()
          if (!ป) ตก.push(`① ${ป้าย} ⇒ หาปุ่มที่เปิดไม่เจอ`)
          else {
            const ใต้ = ว.ก.t >= ป.y + ป.height - 16
            const ซ้อนนอน = ว.ก.l < ป.x + ป.width && ว.ก.r > ป.x
            const แคบ = ว.ก.r - ว.ก.l <= ว.จอ - 32
            if (!ใต้ || !ซ้อนนอน || !แคบ)
              ตก.push(`① ${ป้าย} ⇒ ⛔ เป็นแผงลงมาใต้ปุ่ม ⇒ แผง ${ว.ก.l.toFixed(0)}–${ว.ก.r.toFixed(0)} บน ${ว.ก.t.toFixed(0)} · ปุ่ม ${ป.x.toFixed(0)}–${(ป.x + ป.width).toFixed(0)} ล่าง ${(ป.y + ป.height).toFixed(0)}`)
          }
        }
        // ② ×
        const ตรวจกากบาท = (ว, ตอน) => {
          if (ว.ปิดกี่ปุ่ม !== 1) return ตก.push(`② ${ป้าย}${ตอน} ⇒ ปุ่มที่ได้ยิน «${ชื่อปุ่มปิดกล่อง}» ในกล่องมี ${ว.ปิดกี่ปุ่ม} ปุ่ม ⛔ ต้อง 1`)
          const x = ว.x
          if (x.w < เป้า - 0.01 || x.h < เป้า - 0.01) ตก.push(`② ${ป้าย}${ตอน} ⇒ ปุ่ม × ${x.w.toFixed(1)}×${x.h.toFixed(1)} ⛔ เล็กกว่า ${เป้า} จุด`)
          if (ว.ก.r - x.r > ใกล้มุม + 0.5 || x.t - ว.ก.t > ใกล้มุม + 0.5 || x.t < ว.ก.t - 0.5)
            ตก.push(`② ${ป้าย}${ตอน} ⇒ ปุ่ม × ⛔ อยู่มุมขวาบน ⇒ ห่างขอบขวา ${(ว.ก.r - x.r).toFixed(1)} · ห่างขอบบน ${(x.t - ว.ก.t).toFixed(1)} (ไม่เกิน ${ใกล้มุม})`)
          // ⭐ ของบนสุดวัดตอนกล่องยังไม่เลื่อน ⇒ เลื่อนแล้วของที่ผ่านใต้แถวหัวที่ติดขอบบนยังมีกรอบสูงกว่า × ทั้งที่ตาไม่เห็น
          if (!ตอน && ว.บนสุดอื่น !== null && ว.บนสุดอื่น < x.t - 0.5) ตก.push(`② ${ป้าย}${ตอน} ⇒ มีของกดได้อยู่สูงกว่า × (${ว.บนสุดอื่น.toFixed(0)} < ${x.t.toFixed(0)}) ⛔ × ต้องอยู่บนสุด`)
        }
        ตรวจกากบาท(ว, '')
        if (ว.กลับไปอ่าน) ตก.push(`② ${ป้าย} ⇒ ยังมีปุ่ม «${ชื่อปุ่มกลับไปอ่านเดิม}» ⛔ ต้องปิดด้วย × (ใบ #153)`)
        // ④ ของในหน้าเต็มจอ ⛔ ทับแถบบน ⇒ ตอนเพิ่งเปิด · เลื่อน 120 · เลื่อนจนสุด
        const ตรวจทับแถบ = (ว, ตอน) => {
          if (!เต็มจอ) return
          if (!ว.โลโก้ในแถบ) ตก.push(`④ ${ป้าย}${ตอน} ⇒ ของในกล่องขึ้นไปทับชื่อเว็บบนแถบบน ⛔ (บั๊กจอพับ)`)
          if (ว.หัวบน !== null && ว.หัวบน < ว.ล่างแถบ - 0.5) ตก.push(`④ ${ป้าย}${ตอน} ⇒ หัวของกล่องเริ่มที่ ${ว.หัวบน.toFixed(1)} ⛔ สูงกว่าขอบล่างแถบบน ${ว.ล่างแถบ.toFixed(1)} ⇒ ถูกตัด`)
          if (ว.x && ว.x.t < ว.ล่างแถบ - 0.5) ตก.push(`④ ${ป้าย}${ตอน} ⇒ ปุ่ม × เริ่มที่ ${ว.x.t.toFixed(1)} ⛔ ซุกใต้แถบบน (${ว.ล่างแถบ.toFixed(1)})`)
        }
        ตรวจทับแถบ(ว, '')
        if (ว.ล้นข้าง > 0) ตก.push(`⑤ ${ป้าย} ⇒ เปิดกล่องแล้วหน้าเลื่อนด้านข้างได้ ${ว.ล้นข้าง} จุด`)
