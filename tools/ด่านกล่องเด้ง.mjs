    const { ctx, แท็บ, พร้อม } = await เปิด({ กว้าง: w, สูง, ตัวใหญ่: ใหญ่, พัง, ...(ฉบับ ? { ฉบับ, เดิม: false } : {}), ...(วาง ? { วาง } : {}) })
