"""ไล่คู่คำที่ติดกันในคำอธิบายไทย แล้วถามคลังว่าเขียนติดกันแล้วเป็นคำในคลังไหม — ใบงาน #46

⭐ ทำไมต้องมีสคริปต์นี้ ⇒ กฎข้อ ③ ให้คนเขียนเคาะวรรคคั่นคำเอง
คนจึงเคาะวรรคกลางคำประกอบได้ เช่นเขียน `กลาย เป็น` แทน `กลายเป็น`
เครื่องตัดคำด้วยช่องว่างล้วน มันจึงเห็นเป็นคนละคำ

⛔ ห้ามนับจุดพวกนี้ด้วยตา ⇒ สคริปต์นี้ไล่ให้ครบทุกคู่แล้วพิมพ์ตัวเลขออกมาเอง

**อันตรายจริงคือคู่ที่ทำให้เกิดคำปลอม** ⇒ ท่อนหน้าหรือท่อนหลังโผล่เข้ารายการคลังขาด
ทั้งที่คำเต็มอยู่ในคลัง ⇒ คนที่เอารายการไปเติมคลังจะเติมของผิด ⇒ **ต้องแก้ให้เขียนติดกัน**

    py -3.14 tools/ทดลอง-ไล่คู่คำติดกัน.py
    py -3.14 tools/ทดลอง-ไล่คู่คำติดกัน.py <ไฟล์คำอธิบาย> --รุ่นคลัง origin/main
"""
import argparse
import collections
import importlib.util
from pathlib import Path

# ดึงวิธีอ่านคลังกับวิธีตัดสินคำมาจากสคริปต์นับหลุดคลัง ⛔ ไม่เขียนซ้ำ
_spec = importlib.util.spec_from_file_location(
    "นับหลุดคลัง", Path(__file__).with_name("ทดลอง-นับหลุดคลัง.py"))
นับหลุดคลัง = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(นับหลุดคลัง)


def หลัก(ไฟล์คำอธิบาย, ref):
    คลัง, sha = นับหลุดคลัง.คลังคำ(ref)
    แถว = นับหลุดคลัง.อ่านtsv(ไฟล์คำอธิบาย)
    print(f"คลังคำ {len(คลัง)} คำ ⇒ ดึงจาก {ref} คอมมิต {sha[:8]}")

    คู่ทั้งหมด = 0
    คู่ไม่ซ้ำ = set()
    ติดกันแล้วอยู่ในคลัง = collections.Counter()   # คู่ ⇒ กี่แถวที่เจอ
    ทำให้เกิดคำปลอม = collections.defaultdict(set)  # คู่ ⇒ ท่อนที่กลายเป็นคำปลอม
    for r in แถว:
        คำ = (r["คำอธิบายไทย"] or "").split()
        for ก, ข in zip(คำ, คำ[1:]):
            คู่ทั้งหมด += 1
            คู่ไม่ซ้ำ.add(f"{ก} {ข}")
            เต็ม = นับหลุดคลัง.จัดรูป(ก) + นับหลุดคลัง.จัดรูป(ข)
            if นับหลุดคลัง.ตัดสินคำ(เต็ม, คลัง)[0] != "ในคลัง":
                continue
            ติดกันแล้วอยู่ในคลัง[f"{ก} {ข}"] += 1
            for ท่อน in (ก, ข):
                ชนิด, รูป = นับหลุดคลัง.ตัดสินคำ(ท่อน, คลัง)
                if ชนิด == "คลังขาด":
                    ทำให้เกิดคำปลอม[f"{ก} {ข}"].add(รูป)

    print()
    print("── ไล่คู่คำที่ติดกันทุกคู่ ──")
    print(f"คู่คำที่ติดกันทั้งหมด          {คู่ทั้งหมด} คู่ ⇒ ไม่ซ้ำกัน {len(คู่ไม่ซ้ำ)} คู่")
    print(f"เขียนติดกันแล้วเป็นคำในคลัง   {len(ติดกันแล้วอยู่ในคลัง)} คู่"
          f" ⇒ โผล่รวม {sum(ติดกันแล้วอยู่ในคลัง.values())} ครั้ง")
    print(f"⭐ ในนั้นทำให้เกิดคำปลอม        {len(ทำให้เกิดคำปลอม)} คู่ ⇒ ต้องแก้ให้เขียนติดกัน")

    print()
    print("── ⭐ คู่ที่ทำให้เกิดคำปลอมในรายการคลังขาด ⇒ ต้องแก้ ──")
    if not ทำให้เกิดคำปลอม:
        print("(ไม่มี)")
    for คู่ in sorted(ทำให้เกิดคำปลอม, key=lambda k: -ติดกันแล้วอยู่ในคลัง[k]):
        print(f"{คู่}\tโผล่ {ติดกันแล้วอยู่ในคลัง[คู่]} แถว"
              f"\tคำปลอมที่เกิด {' '.join(sorted(ทำให้เกิดคำปลอม[คู่]))}")

    print()
    print("── คู่ที่เขียนติดกันแล้วอยู่ในคลัง แต่แยกแล้วสองท่อนก็ยังอยู่ในคลัง ⇒ ไม่เกิดคำปลอม ──")
    print("คู่\tโผล่กี่แถว")
    for คู่, n in ติดกันแล้วอยู่ในคลัง.most_common():
        if คู่ not in ทำให้เกิดคำปลอม:
            print(f"{คู่}\t{n}")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("ไฟล์คำอธิบาย", nargs="?", default="docs/ข้อมูล/ทดลอง-คำอธิบายไทย.tsv")
    p.add_argument("--รุ่นคลัง", default=นับหลุดคลัง.รุ่นคลังตั้งต้น)
    a = p.parse_args()
    # ⛔ ห้ามอ่านช่องด้วย a.<ชื่อไทย> ⇒ ไพทอนจัดรูปชื่อตัวแปรเป็น NFKC แล้ว "คำ" เพี้ยน
    หลัก(getattr(a, "ไฟล์คำอธิบาย"), getattr(a, "รุ่นคลัง"))
