async function เปิด(กว้าง, พัง = {}) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: 820 } })
  if (พัง.ก่อนโหลด) await ctx.addInitScript(พัง.ก่อนโหลด)
  if (พัง.css)
    await ctx.addInitScript((กฎ) => {
      const ใส่ = () => {
        const st = document.createElement('style')
        st.textContent = กฎ
        document.head.appendChild(st)
      }
      if (document.head) ใส่()
      else document.addEventListener('DOMContentLoaded', ใส่)
    }, พัง.css)
  if (พัง.เส้นทาง) await พัง.เส้นทาง(ctx)
  const แท็บ = await ctx.newPage()
  return { ctx, แท็บ }
}

/** อ่านทุกอย่างที่ด่านตัดสินจากหน้าเดียว ⇒ ⛔ เชื่อคลาสของเว็บ ⇒ หาด้วยตัวหนังสือที่ตาเห็นกับ `lang` ที่ใกล้ที่สุด */
const อ่านหน้า = (แท็บ) =>
  แท็บ.evaluate(() => {
    const ข้อความ = (x) => (x.textContent || '').replace(/\s+/g, ' ').trim()
    const ภาษาของ = (x) => x.closest('[lang]')?.getAttribute('lang') || ''
    const เห็น = (x) => !!x.getClientRects().length && getComputedStyle(x).visibility !== 'hidden'
    const เนื้อ = document.querySelector('main') || document.body
    const ลิงก์ = [...เนื้อ.querySelectorAll('a[href]')]
      .filter((a) => !a.closest('header, nav, [role="dialog"], .pk-แถบเครื่องมือ'))
      .filter(เห็น)
      .map((a) => {
        const r = a.getBoundingClientRect()
        return { ข้อความ: ข้อความ(a), ทาง: new URL(a.href, location.href).pathname, ภาษา: ภาษาของ(a), สูง: r.height, กว้าง: r.width, บน: r.top + scrollY }
      })
    const ย่อหน้า = [...เนื้อ.querySelectorAll('p, h1, h2')].filter(เห็น).map((x) => ({ แท็ก: x.tagName, ข้อความ: ข้อความ(x), ภาษา: ภาษาของ(x), บน: x.getBoundingClientRect().top + scrollY }))
    const de = document.documentElement
    return {
      ชื่อแท็บ: document.title.trim(),
      h1: [...document.querySelectorAll('h1')].map(ข้อความ),
      ลิงก์,
      ย่อหน้า,
      ล้น: de.scrollWidth - de.clientWidth,
    }
  })

async function ยิงaxe(แท็บ) {
  await แท็บ.addScriptTag({ path: ที่อยู่axe })
  return แท็บ.evaluate(
    (tags) => window.axe.run(document, { runOnly: { type: 'tag', values: tags } }).then((ผล) => ผล.violations.map((v) => `${v.id} ${v.nodes.length} จุด (${v.nodes[0]?.target?.join(' ')})`)),
    ป้ายaxe,
  )
}

/** ที่อยู่ปลายทางเปิดได้จริงไหม ⇒ ถามที่วางเว็บตรง ๆ ⇒ ⛔ ใช้โค้ดของเว็บ */
const แคชที่มีจริง = new Map()
async function มีจริง(ctx, ทาง) {
  if (!แคชที่มีจริง.has(ทาง)) {
    const ตอบ = await ctx.request.get(new URL(ทาง, ฐาน).href, { maxRedirects: 5 })
    แคชที่มีจริง.set(ทาง, ตอบ.status())
  }
  return แคชที่มีจริง.get(ทาง)
}

async function ตรวจ(พัง = {}, { ทาง: ชุดทาง = ทางที่ไม่มี, จอ: ชุดจอ = จอทั้งหมด } = {}) {
  const ตก = []
  for (const ทาง of ชุดทาง) {
    for (const กว้าง of ชุดจอ) {
      const { ctx, แท็บ } = await เปิด(กว้าง, พัง)
      const ป้าย = `${ทาง} @${กว้าง}`
      try {
        // ① ที่วางเว็บตอบ 404 แล้วหน้าขึ้นจริง
        const ตอบ = await แท็บ.goto(ฐาน + encodeURI(ทาง), { waitUntil: 'domcontentloaded' })
        if (ตอบ?.status() !== 404) ตก.push(`① ${ป้าย} ⇒ ที่วางเว็บตอบ ${ตอบ?.status()} ⛔ ต้อง 404`)
        const ขึ้น = await แท็บ
          // ⛔ รอแค่ `<h1>` ⛔ รอ `lang="en"` ⇒ งั้นก้อนอังกฤษที่หลุด lang กลายเป็น *หน้าไม่ขึ้น* แทนที่จะแดงที่ข้อ ④ (เจอตอนทดสอบตัวเอง)
          .waitForFunction(() => !!document.querySelector('main h1'), null, { timeout: 20000 })
          .then(() => true)
          .catch(() => false)
        if (!ขึ้น) {
          ตก.push(`① ${ป้าย} ⇒ ⛔ เห็นหน้ายังไม่พบหน้านี้ภายใน 20 วินาที (ชื่อแท็บ “${await แท็บ.title()}”) ⇒ หน้าว่าง หน้าค้าง หรือหน้าตั้งต้นของ Nuxt`)
          continue
        }
        await แท็บ.waitForTimeout(300)
        const ห = await อ่านหน้า(แท็บ)

        // ② หัวเรื่องกับชื่อแท็บ
        if (ห.h1.length !== 1) ตก.push(`② ${ป้าย} ⇒ หน้ามี <h1> ${ห.h1.length} ตัว ⛔ ต้องตัวเดียว (${ห.h1.join(' | ')})`)
        if (ห.h1[0] !== คำ.ไทย.หัว) ตก.push(`② ${ป้าย} ⇒ หัวเรื่อง “${ห.h1[0]}” ⛔ ตรงคำที่อนุมัติ “${คำ.ไทย.หัว}”`)
        if (ห.ชื่อแท็บ !== คำ.ไทย.หัว) ตก.push(`② ${ป้าย} ⇒ ชื่อแท็บ “${ห.ชื่อแท็บ}” ⛔ ตรงหัวเรื่อง “${คำ.ไทย.หัว}” (SC 2.4.2)`)

        // ③ ก้อนไทย ⇒ ④ ก้อนอังกฤษ
        const หาย่อหน้า = (ข้อความ) => ห.ย่อหน้า.find((x) => x.ข้อความ === ข้อความ)
        const หาลิงก์ = (ข้อความ) => ห.ลิงก์.filter((x) => x.ข้อความ === ข้อความ)
        for (const [ข้อ, ภาษา, ชุด] of [['③', 'ไทย', คำ.ไทย], ['④', 'อังกฤษ', คำ.อังกฤษ]]) {
          const ควรเป็นอังกฤษ = ภาษา === 'อังกฤษ'
          for (const ชิ้น of ['หัว', 'เนื้อ']) {
            const ย = หาย่อหน้า(ชุด[ชิ้น])
            if (!ย) ตก.push(`${ข้อ} ${ป้าย} ⇒ ⛔ เห็น${ชิ้น}${ภาษา} “${ชุด[ชิ้น].slice(0, 40)}…” ตรงคำที่อนุมัติ`)
            else if ((ย.ภาษา === 'en') !== ควรเป็นอังกฤษ) ตก.push(`${ข้อ} ${ป้าย} ⇒ ${ชิ้น}${ภาษา}อยู่ใต้ lang="${ย.ภาษา}" ⛔ ต้อง${ควรเป็นอังกฤษ ? ' lang="en"' : 'ไม่อยู่ใต้ lang="en"'} (SC 3.1.2)`)
          }
          for (const ชนิด of ['หน้าแรก', 'เล่าประสบการณ์']) {
            const พบ = หาลิงก์(ชุด[ชนิด])
            if (พบ.length !== 1) ตก.push(`${ข้อ} ${ป้าย} ⇒ ลิงก์ “${ชุด[ชนิด]}” มี ${พบ.length} เส้น ⛔ ต้อง 1`)
            else if ((พบ[0].ภาษา === 'en') !== ควรเป็นอังกฤษ) ตก.push(`${ข้อ} ${ป้าย} ⇒ ลิงก์ “${ชุด[ชนิด]}” อยู่ใต้ lang="${พบ[0].ภาษา}" ⛔ ต้อง${ควรเป็นอังกฤษ ? ' lang="en"' : 'ไม่อยู่ใต้ lang="en"'}`)
          }
        }
        const หัวไทย = หาย่อหน้า(คำ.ไทย.หัว)
        const หัวอังกฤษ = หาย่อหน้า(คำ.อังกฤษ.หัว)
        if (หัวไทย && หัวอังกฤษ && !(หัวอังกฤษ.บน > หัวไทย.บน)) ตก.push(`④ ${ป้าย} ⇒ ก้อนอังกฤษอยู่เหนือก้อนไทย ⛔ ต้องอยู่ใต้`)

        // ⑤ ลิงก์ต่อฐานและไปถึงหน้าที่มีจริง
        for (const ชุด of [คำ.ไทย, คำ.อังกฤษ])
          for (const ชนิด of ['หน้าแรก', 'เล่าประสบการณ์'])
            for (const ล of หาลิงก์(ชุด[ชนิด])) {
              const ทางจริง = decodeURIComponent(ล.ทาง)
              if (ทางจริง.replace(/\/+$/, '') !== ปลายทาง[ชนิด].replace(/\/+$/, ''))
                ตก.push(`⑤ ${ป้าย} ⇒ ลิงก์ “${ล.ข้อความ}” ชี้ ${ทางจริง} ⛔ ต้อง ${ปลายทาง[ชนิด]} (ต่อฐาน ${ทางฐาน || '/'})`)
              const สถานะ = await มีจริง(ctx, ล.ทาง)
              if (สถานะ !== 200) ตก.push(`⑤ ${ป้าย} ⇒ ลิงก์ “${ล.ข้อความ}” ไป ${ทางจริง} ⇒ ที่วางเว็บตอบ ${สถานะ} ⛔ ต้อง 200`)
            }

        // ⑥ จอ ⇒ ล้น · ขนาดลิงก์ · axe
        if (ห.ล้น > 1) ตก.push(`⑥ ${ป้าย} ⇒ หน้าล้นซ้ายขวา ${ห.ล้น} จุด (SC 1.4.10)`)
        for (const ล of ห.ลิงก์) if (ล.สูง < เป้า - 0.5) ตก.push(`⑥ ${ป้าย} ⇒ ลิงก์ “${ล.ข้อความ}” สูง ${ล.สูง.toFixed(1)} จุด ⛔ ถึง ${เป้า} (SC 2.5.8)`)
        const axe = await ยิงaxe(แท็บ)
        for (const x of axe) ตก.push(`⑥ ${ป้าย} ⇒ axe ⇒ ${x}`)
      } catch (e) {
        ตก.push(`① ${ป้าย} ⇒ ตรวจไม่จบ ⇒ ${String(e.message || e).split('\n')[0]}`)
      } finally {
        await ctx.close()
      }
    }
  }
  return ตก
}

