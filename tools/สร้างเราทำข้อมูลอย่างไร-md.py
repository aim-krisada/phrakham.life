# ชื่อที่คนอ่านเห็น ⇒ ใบ #88 สั่งให้แต่ละขั้นบอกห้าอย่าง ชื่อช่องจึงใช้คำของใบงาน
ชื่อที่คนอ่านเห็น = {
    "ทำอะไร": "ทำอะไร",
    "ของเข้า": "ของเข้า ⇒ เอาอะไรมา",
    "ทำด้วย": "ทำด้วยเครื่องมือไหน",
    "ของออก": "ของออก ⇒ ได้อะไร",
    "ตัวเลขที่วัดได้": "ตัวเลขที่วัดได้",
    "วิธีดูของจริง": "วิธีตรวจเอง",
    "วิธีตรวจเอง": "วิธีตรวจเอง",
}


def ตาย(ข้อความ):
    print(f"⛔ {ข้อความ}")
    sys.exit(2)


def เลข(ค่า):
    """เลขจำนวนเต็มใส่จุลภาคให้อ่านง่าย ⛔ ไม่แตะค่าอื่น"""
    if isinstance(ค่า, bool):
        return "ใช่" if ค่า else "ไม่ใช่"
    if isinstance(ค่า, int):
        return f"{ค่า:,}"
    return str(ค่า)


def หนี(ข้อความ):
    """กันไม่ให้ขีดตั้งในค่าที่วัดมา ไปทำตารางแตก"""
    return str(ข้อความ).replace("|", "\\|").replace("\n", " ")


def เป็นบรรทัด(ค่า):
    """ค่าหนึ่งค่า เขียนเป็นข้อความบรรทัดเดียว ⇒ ใช้ในตารางกับในข้อ"""
    if isinstance(ค่า, list):
        return " · ".join(เป็นบรรทัด(x) for x in ค่า)
    if isinstance(ค่า, dict):
        return " · ".join(f"{ก} {เป็นบรรทัด(ข)}" for ก, ข in ค่า.items())
    return เลข(ค่า)


def พิมพ์ค่า(ออก, ชื่อ, ค่า, ระดับ=0):
    """พิมพ์ค่าหนึ่งค่าเป็นข้อ ⇒ ค่าที่ซ้อนกันหลายชั้น ย่อหน้าเข้าไปทีละชั้น"""
    เว้น = "  " * ระดับ
    if isinstance(ค่า, (dict, list)) and not ค่า:
        ออก.append(f"{เว้น}- **{ชื่อ}** ไม่มี")
    elif isinstance(ค่า, dict):
        ออก.append(f"{เว้น}- **{ชื่อ}**")
        for ก, ข in ค่า.items():
            พิมพ์ค่า(ออก, ก, ข, ระดับ + 1)
    elif isinstance(ค่า, list) and any(isinstance(x, (dict, list)) for x in ค่า):
        ออก.append(f"{เว้น}- **{ชื่อ}**")
        for x in ค่า:
            พิมพ์ค่า(ออก, "รายการ", x, ระดับ + 1)
    else:
        ออก.append(f"{เว้น}- **{ชื่อ}** {เป็นบรรทัด(ค่า)}")


def ตารางของฉบับ(ออก, รายฉบับ):
    """ตัวบทสามฉบับในแหล่งเดียว ⇒ วางเป็นตารางให้เทียบกันได้ในตาเดียว"""
    หัว = list(รายฉบับ[0].keys())
    ออก.append("| " + " | ".join(หัว) + " |")
    ออก.append("|" + "---|" * len(หัว))
    for ฉ in รายฉบับ:
        ออก.append("| " + " | ".join(หนี(เป็นบรรทัด(ฉ.get(ก, ""))) for ก in หัว) + " |")
    ออก.append("")


def เขียนขั้น(ออก, ขั้น):
    ออก.append(f"#### ขั้นที่ {ขั้น['ลำดับ']}")
    ออก.append("")
    เหลือ = [ก for ก in ขั้น if ก not in ลำดับช่องของขั้น and ก != "ลำดับ"]
    for ก in ลำดับช่องของขั้น + เหลือ:
        if ก not in ขั้น:
            continue
        ชื่อ = ชื่อที่คนอ่านเห็น.get(ก, ก)
        if ก == "ทำอะไร":
            ออก.append(f"**{ชื่อ}** {ขั้น[ก]}")
            ออก.append("")
            continue
        if ก == "ทำด้วย":
            ออก.append(f"- **{ชื่อ}** `{ขั้น[ก]}`")
            continue
        พิมพ์ค่า(ออก, ชื่อ, ขั้น[ก])
    ออก.append("")


def สร้าง(ของ):
    ออก = []
    ออก.append(f"# {ของ['ชื่อหน้า']}")
    ออก.append("")
    ออก.append(f"**หน้านี้ตอบอะไร** {ของ['หน้านี้ตอบอะไร']}")
    ออก.append("")
    ออก.append(f"**หน้านี้ไม่ตอบอะไร** {ของ['หน้านี้ไม่ตอบอะไร']}")
    ออก.append("")
    ออก.append(f"**ตัวเลขในหน้านี้มาจากไหน** {ของ['ตัวเลขในไฟล์นี้มาจากไหน']}")
    ออก.append("")
    ออก.append(
        "**หน้านี้สร้างมาอย่างไร** ตัวสร้างเปิดไฟล์จริงแล้ววัดเอง เขียนผลลง "
        f"`{ทาง(ไฟล์เข้า)}` ด้วย `{ของ['ไฟล์นี้สร้างจาก']}` "
        f"แล้วหน้าที่คุณอ่านอยู่นี้ ปั้นต่อจากไฟล์นั้นด้วย `{ทาง(ตัวเอง())}` "
        "⇒ รันซ้ำได้ผลเดิมทุกไบต์ ⇒ ⛔ ห้ามแก้หน้านี้ด้วยมือ"
    )
    ออก.append("")

    รวม = ของ.get("ของที่ขึ้นเว็บทั้งหมด")
    if รวม:
        ออก.append("## ของที่ขึ้นเว็บทั้งหมด นับได้เท่าไร")
        ออก.append("")
        ออก.append("อ่านหน้านี้ทั้งหน้าแล้ว ควรได้ของครบตามตารางนี้")
        ออก.append("")
        for ก, ข in รวม.items():
            พิมพ์ค่า(ออก, ก, ข)
        ออก.append("")

    ออก.append("## เล่าทีละแหล่ง ทีละขั้น")
    ออก.append("")
    ออก.append(
        "แหล่งหนึ่งแหล่งคือกองข้อมูลหนึ่งกองที่เราเดินด้วยขั้นตอนชุดเดียวกันตั้งแต่ต้นจนจบ "
        "⛔ ไม่ใช่เจ้าของหนึ่งราย ⇒ ส่วนใหญ่หนึ่งแหล่งมีเจ้าของรายเดียว "
        "แต่แหล่งตัวบทฉบับเทียบมีเจ้าของสามราย เพราะสามฉบับนั้นเดินขั้นตอนชุดเดียวกัน "
        "แยกเล่าทีละรายจึงได้ของซ้ำสามรอบ ⇒ ใครอยากรู้ว่าของมาจากใคร ดูที่หน้าแหล่งข้อมูล "
        "แต่ละแหล่งเราทำสี่ขั้น "
        "ทุกขั้นบอกห้าอย่าง คือทำอะไร ของเข้าคือไฟล์ไหน ทำด้วยเครื่องมือไหน ของออกคืออะไร "
        "และวิธีตรวจเองว่าเปิดที่ไหนแล้วจะเห็นอะไร"
    )
    ออก.append("")
    for แหล่ง in ของ["แหล่ง"]:
        ออก.append(f"### แหล่ง `{แหล่ง['รหัส']}` {แหล่ง['ชื่อ']}")
        ออก.append("")
        ออก.append(f"**ได้อะไรจากแหล่งนี้** {แหล่ง['ได้อะไรจากแหล่งนี้']}")
        ออก.append("")
        if แหล่ง.get("รายฉบับ"):
            ตารางของฉบับ(ออก, แหล่ง["รายฉบับ"])
        for ขั้น in แหล่ง["ขั้นตอน"]:
            เขียนขั้น(ออก, ขั้น)

    ยัง = ของ.get("ที่ยังไม่สมบูรณ์")
    if ยัง:
        ออก.append("## ที่ยังไม่สมบูรณ์ ⇒ ตรงไหนยังต้องใช้คนดู")
        ออก.append("")
        ออก.append(
            "หน้านี้ไม่ได้เล่าแต่ส่วนที่ดี ข้างล่างนี้คือของที่เรารู้ตัวว่ายังไม่เรียบร้อย "
            "แต่ละข้อบอกไว้ว่าไม่สมบูรณ์อย่างไร เจ้าของเรื่องอยู่ไฟล์ไหน และตรวจเองได้อย่างไร"
        )
        ออก.append("")
        for n, ข้อ in enumerate(ยัง, 1):
            ออก.append(f"### {n}. {ข้อ['เรื่อง']}")
            ออก.append("")
            ออก.append(ข้อ["ยังไม่สมบูรณ์อย่างไร"])
            ออก.append("")
            for ก, ค in ข้อ.items():
                if ก in ("เรื่อง", "ยังไม่สมบูรณ์อย่างไร"):
                    continue
                พิมพ์ค่า(ออก, ชื่อที่คนอ่านเห็น.get(ก, ก), ค)
            ออก.append("")

    return "\n".join(ออก).rstrip() + "\n"


def ตัวเอง():
    return Path(__file__).resolve()


def ทาง(ไฟล์):
    return str(Path(ไฟล์).relative_to(ที่เก็บ)).replace("\\", "/")


def main():
    ตัวเลือก = argparse.ArgumentParser(description="สร้างไฟล์ .md ของหน้า เราทำข้อมูลอย่างไร")
    ตัวเลือก.add_argument("--ตรวจ", action="store_true",
                          help="สร้างใหม่แล้วเทียบกับไฟล์ที่คอมมิตไว้ ⇒ ไม่ตรงคือแดง")
    คำสั่ง = ตัวเลือก.parse_args()

    if not ไฟล์เข้า.exists():
        ตาย(f"ไม่มีไฟล์ {ทาง(ไฟล์เข้า)} ⇒ สั่ง py -3.14 tools/สร้างเราทำข้อมูลอย่างไร.py ก่อน")
    ข้อความ = สร้าง(json.load(io.open(ไฟล์เข้า, encoding="utf-8")))

    if คำสั่ง.ตรวจ:
        if not ไฟล์ผล.exists():
            ตาย(f"ยังไม่มีไฟล์ {ทาง(ไฟล์ผล)} ⇒ สั่งสร้างก่อน")
        if io.open(ไฟล์ผล, encoding="utf-8", newline="").read() != ข้อความ:
            ตาย(f"{ทาง(ไฟล์ผล)} ไม่ตรงกับของที่สร้างใหม่ ⇒ สั่งสร้างใหม่แล้วคอมมิต")
        print(f"✅ {ทาง(ไฟล์ผล)} ตรงกับของที่สร้างใหม่")
        return

    io.open(ไฟล์ผล, "w", encoding="utf-8", newline="\n").write(ข้อความ)
    print(f"✅ เขียน {ทาง(ไฟล์ผล)} แล้ว ⇒ {len(ข้อความ.splitlines()):,} บรรทัด")


if __name__ == "__main__":
    main()
