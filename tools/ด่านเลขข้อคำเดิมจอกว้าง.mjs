const ป้าย = (ส) =>
  `${ส.เล่ม} ${ส.บท} จอ ${ส.กว้าง} · ${ส.จัดวาง} · ${ส.ฉบับ.length > 1 ? 'สองฉบับ' : 'ฉบับเดียว'} · ตัวอักษร ${Math.round(ส.ตัวอักษร * 100)}% · ${ส.ขนาด}`

async function ตรวจ(ส, พัง = null) {
  const ตก = []
  const ที่ = ป้าย(ส)
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: ส.กว้าง, height: 900 } })
  try {
    await ctx.addInitScript(
      ([ฉ, จ, ข, ต]) => {
        localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
        localStorage.setItem(
          'phrakham.view',
          JSON.stringify({ จัดวาง: จ, แสดงเลข: true, ภาษาเดิม: true, ขนาดคำเดิม: ข, วางจอแคบ: 'ขนานกัน', สัญลักษณ์กาล: true, เครื่องหมาย: ['แดง'] }),
        )
        localStorage.setItem('pk-fs', String(ต))
      },
      [ส.ฉบับ, ส.จัดวาง, ส.ขนาด, ส.ตัวอักษร],
    )
    const แท็บ = await ctx.newPage()
    await แท็บ.goto(`${ฐาน}/read/${ส.เล่ม}?c=${ส.บท}`, { waitUntil: 'domcontentloaded' })
    const พร้อม = await แท็บ
      .waitForFunction(
        (c) => {
          const ก้อน = document.querySelector(`.pk-ชั้นคำ[aria-label$=" ${c}"]`)
          if (!ก้อน?.querySelector('.pk-คำ')) return false
          if (ก้อน.querySelector('.pk-กล่องคำ.pk-แสดงกาล') && !ก้อน.querySelector('.pk-กาล')) return false
          if (ก้อน.querySelector('.pk-คำ[data-ลค]') && !ก้อน.querySelector('[data-คำอ่านเครื่องหมาย]')) return false
          return document.querySelector('.pk-ตัวบท')?.getAttribute('data-จัดแถว') === 'เสร็จ' && document.fonts.status === 'loaded'
        },
        ส.บท,
        { timeout: รอนานสุด },
      )
      .then(() => true)
      .catch(() => false)
    if (!พร้อม) {
      ตก.push(`${ที่} ⇒ ก้อนคำของบท ${ส.บท} ⛔ ขึ้นไม่ครบภายใน ${รอนานสุด / 1000} วินาที`)
      return { ตก, สรุป: '' }
    }
    if (พัง?.css) await แท็บ.addStyleTag({ content: พัง.css })
    await แท็บ.waitForTimeout(100)
    const ผล = await แท็บ.evaluate(
      ([c, คลาด]) => {
        const ตัด = []
        const หลุดบรรทัด = []
        let นับ = 0
        let มีบท = 0
        for (const sup of document.querySelectorAll(`.pk-ชั้นคำ[aria-label$=" ${c}"] .pk-กล่องคำ .pk-ข้อคำ > .pk-เลขข้อ`)) {
          const s = sup.getBoundingClientRect()
          if (!s.height || !s.width) continue
          นับ++
          if (sup.textContent.includes(':')) มีบท++
          const ข้อ = sup.closest('.pk-ข้อคำ')
          const ชื่อ = `${ข้อ.dataset.ข้อเดิม} (${sup.textContent.trim()})`
          const rtl = getComputedStyle(ข้อ).direction === 'rtl'
          // ① ทุกบรรพบุรุษที่ตัดของล้น ⇒ แยกแกน ⇒ ⛔ หยุดที่ตัวแรก ⇒ `.pk-ม้วน` ตัดแค่แกนนอน ⇒ ตัวที่ตัดแกนตั้งอาจอยู่สูงกว่า
          for (let e = sup.parentElement; e && e !== document.documentElement; e = e.parentElement) {
            const cs = getComputedStyle(e)
            const ทั้งคู่ = cs.clipPath !== 'none' || cs.contain.includes('paint')
            const ตั้ง = ทั้งคู่ || cs.overflowY !== 'visible'
            const นอน = ทั้งคู่ || cs.overflowX !== 'visible'
            if (!ตั้ง && !นอน) continue
            const r = e.getBoundingClientRect()
            const พ้น = []
            if (ตั้ง) {
              พ้น.push(r.top + parseFloat(cs.borderTopWidth) - s.top)
              พ้น.push(s.bottom - (r.bottom - parseFloat(cs.borderBottomWidth)))
            }
            if (นอน) พ้น.push(rtl ? s.right - (r.right - parseFloat(cs.borderRightWidth)) : r.left + parseFloat(cs.borderLeftWidth) - s.left)
            const มาก = Math.max(...พ้น)
            if (มาก > คลาด) {
              ตัด.push(`${ชื่อ} ถูก ${e.className.split(' ')[0] || e.tagName} ตัด ${Math.round(มาก * 10) / 10} จุด`)
              break
            }
          }
        }
        // ② แถวแรกของทุกกล่อง ⇒ ขอบบนของปุ่มคำแรก = ขอบบนของแถว ⇒ เลขข้อแรก ⛔ ดันคำลง
        //   ⇒ ⛔ ไม่วัดเลขข้อตัวอื่น ⇒ คำยาวที่ตัวอักษร 200% ห่อลงบรรทัดถัดจากเลขได้เองอยู่แล้ว (มาระโก 11:10 จอ 768) ⇒ เป็นของเดิม ⛔ ไม่ใช่เรื่องของใบนี้
        for (const แถว of document.querySelectorAll(`.pk-ชั้นคำ[aria-label$=" ${c}"] .pk-กล่องคำ > .pk-แถวคำ:first-child`)) {
          const คำแรก = แถว.querySelector(':scope > .pk-ข้อคำ:first-child > .pk-คำ')
          if (!คำแรก) continue
          const ห่าง = คำแรก.getBoundingClientRect().top - แถว.getBoundingClientRect().top
          if (Math.abs(ห่าง) > คลาด)
            หลุดบรรทัด.push(`${คำแรก.closest('.pk-ข้อคำ').dataset.ข้อเดิม} คำแรกอยู่ใต้ขอบบนของแถว ${Math.round(ห่าง * 10) / 10} จุด`)
        }
        return { ตัด, หลุดบรรทัด, นับ, มีบท }
      },
      [ส.บท, คลาดได้],
    )
    if (!ผล.นับ) ตก.push(`${ที่} ⇒ ① ⛔ ไม่เจอเลขข้อในก้อนคำ ⇒ ด่านไม่ได้วัดอะไร`)
    if (!ผล.มีบท) ตก.push(`${ที่} ⇒ ① ⛔ ไม่เจอเลขแบบ บท:ข้อ ⇒ ด่านไม่ได้วัดเลขข้อแรกของก้อน`)
    if (ผล.ตัด.length) ตก.push(`${ที่} ⇒ 🔴 ① เลขข้อถูกตัด ${ผล.ตัด.length} จาก ${ผล.นับ} ตัว ⇒ ${ผล.ตัด.slice(0, 3).join(' · ')}`)
    if (ผล.หลุดบรรทัด.length)
      ตก.push(`${ที่} ⇒ 🔴 ② เลขข้อแรกดันคำแรกของกล่องลง ${ผล.หลุดบรรทัด.length} กล่อง ⇒ ${ผล.หลุดบรรทัด.slice(0, 2).join(' · ')}`)
    return { ตก, สรุป: `วัดเลขข้อ ${ผล.นับ} ตัว · แบบ บท:ข้อ ${ผล.มีบท} ตัว` }
  } catch (e) {
    ตก.push(`${ที่} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message}`)
    return { ตก, สรุป: '' }
  } finally {
    await ctx.close()
  }
}

