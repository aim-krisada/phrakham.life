              ตก.push(`${ปก} ⇒ ⑧ กางเครื่องมือแล้วหัวสูงขึ้น ⇒ แถวหัว ${ว.หัว.toFixed(1)}→${วก.หัว.toFixed(1)} · หัวคำเดิม ${ว.หัวเดิม.toFixed(1)}→${วก.หัวเดิม.toFixed(1)} ⛔ แถบหนึบสูงขึ้น`)
