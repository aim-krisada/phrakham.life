/** ① + ② ⇒ ซ้ายขวา */
async function ตรวจซ้ายขวา({ กว้าง, ฉ, สูง }, พัง = null) {
  const ตก = []
  const ป้าย = `จอ ${กว้าง} ${ฉ.join('+')}+คำเดิม`
  const { ctx, แท็บ } = await เปิด({ กว้าง, สูง, ฉ, พัง })
  try {
    const ว = await วัด(แท็บ)
    if (!ว.คลาส.includes('pk-ซ้ายขวาจอแคบ')) ตก.push(`🔴 ① ${ป้าย} ⇒ หน้า ⛔ วางซ้ายขวา (${ว.คลาส})`)
    if (!ว.ก้อน) ตก.push(`🔴 ① ${ป้าย} ⇒ ⛔ มีคอลัมน์คำเดิมที่ตาเห็น`)
    if (ว.ใต้แถว) ตก.push(`🔴 ① ${ป้าย} ⇒ ยังมีกล่องคำใต้แถว ${ว.ใต้แถว} กล่อง`)
    if (ว.ล้นข้าง > คลาด) ตก.push(`🔴 ① ${ป้าย} ⇒ ทั้งหน้าเลื่อนข้าง ${ว.ล้นข้าง} จุด`)
    if (ว.ก้อน && ว.ช่อง.length === ฉ.length) {
      const [แรก, ...อื่น] = ว.ช่อง
      if (ว.ก้อน.ซ้าย < แรก.ขวา - คลาด) ตก.push(`🔴 ① ${ป้าย} ⇒ คำเดิมไม่อยู่ขวาของคอลัมน์แรก (${ว.ก้อน.ซ้าย} < ${แรก.ขวา})`)
      for (const ช of อื่น)
        if (ช.ซ้าย < ว.ก้อน.ขวา - คลาด) ตก.push(`🔴 ① ${ป้าย} ⇒ ${ช.ฉบับ} ไม่อยู่ขวาของคำเดิม (${ช.ซ้าย} < ${ว.ก้อน.ขวา})`)
      for (const ช of ว.ช่อง)
        if (Math.abs(ช.กว้าง - ว.ก้อน.กว้าง) > 2)
          ตก.push(`🔴 ① ${ป้าย} ⇒ ช่อง ${ช.ฉบับ} กว้าง ${ช.กว้าง.toFixed(1)} ⛔ เท่าคอลัมน์คำเดิม ${ว.ก้อน.กว้าง.toFixed(1)}`)
    } else if (ว.ก้อน) ตก.push(`🔴 ① ${ป้าย} ⇒ เห็นช่องฉบับ ${ว.ช่อง.length} ช่อง ⛔ ใช่ ${ฉ.length}`)
    if (ว.แถว.length < 3) ตก.push(`🔴 ① ${ป้าย} ⇒ จับคู่แถวได้แค่ ${ว.แถว.length} แถว`)
    for (const ถ of ว.แถว)
      if (Math.abs(ถ.ข้อ - ถ.คำ) > คลาด) ตก.push(`🔴 ① ${ป้าย} ⇒ แถว ${ถ.ป้าย} คำเดิมเริ่มที่ ${ถ.คำ.toFixed(1)} ⛔ ระดับเดียวกับตัวบท ${ถ.ข้อ.toFixed(1)}`)

    // ② หัว
    if (!ว.หัวคำ) ตก.push(`🔴 ② ${ป้าย} ⇒ ⛔ มีหัวคำเดิมในแถวหัว`)
    else {
      if (ว.หัวคำ.ค่า !== 'SBLGNT') ตก.push(`🔴 ② ${ป้าย} ⇒ ช่องตัวบทเป็น "${ว.หัวคำ.ค่า}" ⛔ ใช่ SBLGNT`)
      const [ช่อง, ตอน, ปิด] = ว.ปุ่มในหัว
      if (!ช่อง || !ตอน || !ปิด) ตก.push(`🔴 ② ${ป้าย} ⇒ หัวไม่ครบ 3 ปุ่ม`)
      else {
        if (!(ช่อง.ซ้าย < ตอน.ซ้าย && ตอน.ซ้าย < ปิด.ซ้าย)) ตก.push(`🔴 ② ${ป้าย} ⇒ ลำดับในหัว ⛔ ใช่ ตัวบท · ชื่อย่อ · ×`)
        if (Math.abs(ช่อง.บน - ปิด.บน) > คลาด || Math.abs(ตอน.บน - ปิด.บน) > คลาด) ตก.push(`🔴 ② ${ป้าย} ⇒ หัว ⛔ แถวเดียว`)
        for (const [ชื่อ, x] of [['ช่องตัวบท', ช่อง], ['ชื่อย่อ', ตอน], ['×', ปิด]])
          if (x.สูง < 44 - 0.5) ตก.push(`🔴 ② ${ป้าย} ⇒ ${ชื่อ} สูง ${x.สูง.toFixed(1)} ⛔ ถึง 44`)
      }
      const ลำดับหัว = ว.หัวแถว.map((h) => (h.คำเดิม ? 'คำเดิม' : h.ฉบับ)).join(',')
      const ต้อง = [ฉ[0], 'คำเดิม', ...ฉ.slice(1)].join(',')
      if (ลำดับหัว !== ต้อง) ตก.push(`🔴 ② ${ป้าย} ⇒ ลำดับหัว ${ลำดับหัว} ⛔ ใช่ ${ต้อง}`)
      const เรียง = [...ว.หัวแถว].sort((a, b) => a.ซ้าย - b.ซ้าย).map((h) => (h.คำเดิม ? 'คำเดิม' : h.ฉบับ)).join(',')
      if (เรียง !== ต้อง) ตก.push(`🔴 ② ${ป้าย} ⇒ หัวเรียงบนจอ ${เรียง} ⛔ ตรงคอลัมน์ ${ต้อง}`)
      // ⭐ ติดด้านบน ⇒ เลื่อนลง 600 จุด แล้วอีก 600 ⇒ หัวอยู่ใต้แถบบนพอดีทั้งสองครั้ง ⇒ ⛔ เลื่อนหายไปกับตัวบท
      for (const รอบ of [1, 2]) {
        await แท็บ.evaluate(() => window.scrollBy(0, 600))
        await สองเฟรม(แท็บ)
        const { หัว, แถบ } = await แท็บ.evaluate(() => ({
          หัว: document.querySelector('.pk-หัวคอลัมน์ [data-ชื่อคำเดิม]')?.getBoundingClientRect().top ?? -9999,
          แถบ: document.querySelector('.pk-แถบบน')?.getBoundingClientRect().bottom ?? 0,
        }))
        if (Math.abs(หัว - แถบ) > 1.5)
          ตก.push(`🔴 ② ${ป้าย} ⇒ เลื่อนลง ${รอบ * 600} จุดแล้วหัวคำเดิมอยู่ที่ ${หัว.toFixed(1)} ⛔ ใต้แถบบน ${แถบ.toFixed(1)} ⇒ ⛔ ติดด้านบน`)
      }
    }
    if (ว.หัวแยก) ตก.push(`🔴 ② ${ป้าย} ⇒ จอแคบยังมีหัวคำเดิมแยกนอกแถวหัว`)
  } finally {
    await ctx.close()
  }
  return { ตก }
}

