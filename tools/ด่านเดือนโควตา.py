"""ด่าน — **เดือนของโควตาเสียงนับตามเวลาแปซิฟิก และคืนสุดท้ายของเดือนใช้โควตาที่เหลือถึงเพดาน**

ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/188

**นี่คือด่าน ⛔ ไม่ใช่รายงาน** ⇒ ล้มแล้วคืนรหัสไม่เป็นศูนย์ ⇒ ท่อแดง

ตรวจ 5 ข้อ ⇒ ของที่ตัดสินอยู่ `tools/เดือนโควตา.py`
  ① รอบ 03:30 เวลาไทยของวันที่ 1 ธ.ค. ⇒ เดือน 2026-11 (แปซิฟิกยังเป็น 30 พ.ย.)
  ② รอบนั้นคือคืนสุดท้ายของเดือน พ.ย. ⇒ รอบ 30 พ.ย. 03:30 เวลาไทยยังไม่ใช่
  ③ คืนปกติ ⇒ งบ = คืนละ ⇒ ไม่กินส่วนที่กันให้เรื่องเล่า
  ④ คืนสุดท้าย ⇒ งบ = เพดาน − ใช้ไป ⇒ ⛔ เกินเพดาน
  ⑤ ทุกเครื่องมือที่เปิดสมุดส่งเดือนจาก `เดือนของGoogle()` ⇒ ⛔ มี `QuotaLedger()` เปล่า ๆ ที่ใช้เวลาเครื่อง

  python3 tools/ด่านเดือนโควตา.py                  ⇒ ตรวจ
  python3 tools/ด่านเดือนโควตา.py --ทดสอบตัวเอง     ⇒ ยัดของพังลงสำเนาของตัวตัดสินทีละท่า ⇒ ข้อของมันต้องแดง
"""
import importlib.util
import re
import sys
import tempfile
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ราก = Path(__file__).resolve().parent
ไทย = ZoneInfo("Asia/Bangkok")


def โหลด(ทาง: Path):
    spec = importlib.util.spec_from_file_location(f"เดือนโควตา_{abs(hash(ทาง))}", ทาง)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def ตรวจ(m, ไฟล์เครื่องมือ: dict[str, str]) -> list[str]:
    ตก = []
    ธค1 = datetime(2026, 12, 1, 3, 30, tzinfo=ไทย)
    พย30 = datetime(2026, 11, 30, 3, 30, tzinfo=ไทย)
    if m.เดือนของGoogle(ธค1) != "2026-11":
        ตก.append(f"① 1 ธ.ค. 03:30 เวลาไทย ⇒ ได้ {m.เดือนของGoogle(ธค1)} ⇒ ต้อง 2026-11 (แปซิฟิกยังเป็น 30 พ.ย.)")
    if m.เดือนของGoogle(datetime(2026, 12, 1, 16, 0, tzinfo=ไทย)) != "2026-12":
        ตก.append("① 1 ธ.ค. 16:00 เวลาไทย ⇒ ต้องเป็น 2026-12 แล้ว")
    if not m.คืนสุดท้ายของเดือน(ธค1):
        ตก.append("② รอบ 1 ธ.ค. 03:30 เวลาไทย ⇒ ต้องเป็นคืนสุดท้ายของเดือน พ.ย.")
    if m.คืนสุดท้ายของเดือน(พย30):
        ตก.append("② รอบ 30 พ.ย. 03:30 เวลาไทย ⇒ ยังไม่ใช่คืนสุดท้าย (รอบถัดไปยังเป็น พ.ย. ที่แปซิฟิก)")
    งบ, เดือน = m.งบคืนนี้(700_000, 458_000, 150_000, 15_000, False)
    if (งบ, เดือน) != (15_000, 92_000):
        ตก.append(f"③ คืนปกติ ⇒ ได้ {(งบ, เดือน)} ⇒ ต้อง (15000, 92000)")
    งบ, _ = m.งบคืนนี้(700_000, 545_000, 150_000, 15_000, False)
    if งบ != 5_000:
        ตก.append(f"③ คืนปกติใกล้ส่วนที่กันไว้ ⇒ ได้ {งบ} ⇒ ต้อง 5000")
    งบ, _ = m.งบคืนนี้(700_000, 458_000, 150_000, 15_000, True)
    if งบ != 242_000:
        ตก.append(f"④ คืนสุดท้าย ⇒ ได้ {งบ} ⇒ ต้องใช้ที่เหลือถึงเพดาน 242000")
    งบ, _ = m.งบคืนนี้(700_000, 458_000, 150_000, 15_000, True, งบที่สั่ง=900_000)
    if งบ > 242_000:
        ตก.append(f"④ สั่งงบเกิน ⇒ ได้ {งบ} ⇒ ⛔ เกินเพดาน")
    for ชื่อ, เนื้อ in ไฟล์เครื่องมือ.items():
        เปล่า = re.findall(r"QuotaLedger\(\s*\)", เนื้อ)
        if เปล่า:
            ตก.append(f"⑤ {ชื่อ} เปิดสมุดด้วย QuotaLedger() {len(เปล่า)} ที่ ⇒ ต้องส่ง month=เดือนของGoogle()")
    return ตก


ของพัง = {
    "นับเดือนตามเวลาไทย": ("①", "return ตอนนี้.astimezone(เขตเวลาของบัญชีเงิน).strftime(\"%Y-%m\")",
                         "return ตอนนี้.astimezone(ZoneInfo(\"Asia/Bangkok\")).strftime(\"%Y-%m\")"),
    "ไม่มีคืนสุดท้าย": ("②", "    return เดือนของGoogle(ตอนนี้ + timedelta(hours=ห่างกันกี่ชั่วโมง)) != เดือนของGoogle(ตอนนี้)",
                       "    return False"),
    "คืนปกติกินส่วนเรื่องเล่า": ("③", "(0 if คืนสุดท้าย else กันให้เรื่องเล่า)", "0"),
    "คืนสุดท้ายยังใช้แค่คืนละ": ("④", "(งบเดือน if คืนสุดท้าย else คืนละ)", "คืนละ"),
}


def ไฟล์เครื่องมือ() -> dict[str, str]:
    return {p.name: p.read_text(encoding="utf-8") for p in (ราก / "พ่นเสียงพระคำ.py", ราก / "พ่นเสียงเรื่องเล่า.py")}


def main() -> int:
    ตัวตัดสิน = ราก / "เดือนโควตา.py"
    ตก = ตรวจ(โหลด(ตัวตัดสิน), ไฟล์เครื่องมือ())
    if ตก:
        print("⛔ ด่านเดือนโควตาไม่ผ่าน")
        for x in ตก:
            print("  " + x)
        return 1
    print("✅ ด่านเดือนโควตาผ่านครบ ①–⑤")
    if "--ทดสอบตัวเอง" not in sys.argv:
        return 0
    ต้นฉบับ = ตัวตัดสิน.read_text(encoding="utf-8")
    ไม่จับ = []
    for ชื่อ, (ข้อ, จาก, เป็น) in ของพัง.items():
        if จาก not in ต้นฉบับ:
            print(f"⛔ ท่า {ชื่อ} หาคำที่จะแทนไม่เจอ ⇒ ด่านตาย")
            return 1
        with tempfile.TemporaryDirectory() as ที่:
            ทาง = Path(ที่) / "เดือนโควตา.py"
            ทาง.write_text(ต้นฉบับ.replace(จาก, เป็น), encoding="utf-8")
            จับ = any(x.startswith(ข้อ) for x in ตรวจ(โหลด(ทาง), ไฟล์เครื่องมือ()))
        print(f"{'✅' if จับ else '⛔'} {ชื่อ} ⇒ ข้อ {ข้อ} {'แดง' if จับ else 'ไม่แดง'}")
        if not จับ:
            ไม่จับ.append(ชื่อ)
    # ⑤ ⇒ ยัดสมุดเปล่าลงสำเนาของเครื่องมือ
    เครื่องมือ = ไฟล์เครื่องมือ()
    เครื่องมือ["พ่นเสียงเรื่องเล่า.py"] += "\nสมุด = ga.QuotaLedger()\n"
    จับ = any(x.startswith("⑤") for x in ตรวจ(โหลด(ตัวตัดสิน), เครื่องมือ))
    print(f"{'✅' if จับ else '⛔'} เปิดสมุดด้วยเวลาเครื่อง ⇒ ข้อ ⑤ {'แดง' if จับ else 'ไม่แดง'}")
    if not จับ:
        ไม่จับ.append("เปิดสมุดด้วยเวลาเครื่อง")
    if ไม่จับ:
        print(f"⛔ โหมดพิสูจน์: ด่านยังไม่เห็น {len(ไม่จับ)} ท่า ⇒ {' · '.join(ไม่จับ)}")
        return 1
    print(f"✅ โหมดพิสูจน์: ด่านจับของพังได้ครบ {len(ของพัง) + 1} ท่า")
    return 0


if __name__ == "__main__":
    sys.exit(main())
