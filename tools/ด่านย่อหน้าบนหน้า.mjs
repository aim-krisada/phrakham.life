/**
 * ⑦ 🔴 เยื้องบรรทัดแรกตามป้ายของคนแปลอย่างเดียว ⇒ เกณฑ์อยู่หัวไฟล์
 * `กฎพัง` ⇒ CSS ที่ยัดเข้าไปในโหมดพิสูจน์ ⇒ ของจริงส่ง `''`
 */
async function ตรวจเยื้องตามป้าย(กฎพัง) {
  const ตก = []
  let เยื้อง = 0
  let ไม่เยื้อง = 0
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
  const แท็บ = await ctx.newPage()
  try {
    for (const บท of บทของข้อเยื้อง) {
      const [เล่ม, เลขบท] = บท.split('/')
      const ของเล่ม = await (await fetch(`${ฐาน}/api/book/${เล่ม}.json`)).json()
      const ของบท = await (await fetch(`${ฐาน}/api/chapter/${เล่ม}/${เลขบท}.json`)).json()
      const ไม่มีของตัวเอง = ของเล่ม.ฉบับที่ยังไม่มีย่อหน้า || {}

      await เปิด(แท็บ, `/read/${บท}`)
      // ⭐ เปิดครบทุกฉบับ ⇒ ได้ทั้งฉบับที่มีย่อหน้าของตัวเองและฉบับที่ยืม
      await ตั้งจำนวนฉบับ(แท็บ, 99)
      await ตั้งการจัดวาง(แท็บ, 'แยกตามย่อหน้า')
      if (กฎพัง) {
        await แท็บ.addStyleTag({ content: กฎพัง })
        await แท็บ.waitForTimeout(150)
      }
      // ⭐ วัด **กล่องที่วาดจริง** ⇒ ป้ายอ่านจากคลาส `pk-ป้าย-*` · เยื้องอ่านจากค่าที่เบราว์เซอร์คำนวณ
      const ก้อน = await แท็บ.evaluate(() => {
        const หมุดที่สอง = [...document.querySelectorAll('.pk-ตัวบท h2.pk-หมุดบท')][1] || null
        return [...document.querySelectorAll('.pk-ตัวบท [data-ฉบับ] p.pk-ย่อหน้า')]
          .filter(
            (el) =>
              el.getClientRects().length &&
              (!หมุดที่สอง ||
                el.compareDocumentPosition(หมุดที่สอง) & Node.DOCUMENT_POSITION_FOLLOWING),
          )
          .map((el) => ({
            ฉบับ: el.closest('[data-ฉบับ]').getAttribute('data-ฉบับ'),
            ป้าย: ([...el.classList].find((c) => c.startsWith('pk-ป้าย-')) || '').slice('pk-ป้าย-'.length),
            เยื้อง: parseFloat(getComputedStyle(el).textIndent) || 0,
            ข้อแรก: el.querySelector('[data-ข้อ]')?.getAttribute('data-ข้อ') || '',
          }))
      })
      if (!ก้อน.length) {
        ตก.push(`⑦ ${บท} ⇒ 🔴 หาย่อหน้าบนหน้าไม่เจอเลย`)
        continue
      }

      // ── เยื้องตรงกับป้ายไหม
      for (const ก of ก้อน) {
        const ควรเยื้อง = ป้ายเยื้องบรรทัดแรก.has(ก.ป้าย)
        if (ก.เยื้อง > 0) เยื้อง++
        else ไม่เยื้อง++
        if (ควรเยื้อง !== ก.เยื้อง > 0) {
          ตก.push(
            `⑦ ${บท} ${ก.ฉบับ} ย่อหน้าที่ขึ้นด้วยข้อ ${ก.ข้อแรก} ⇒ 🔴 ป้าย «${ก.ป้าย || 'ว่าง'}» ` +
              `${ควรเยื้อง ? 'ต้องเยื้อง' : 'ต้อง ⛔ ไม่เยื้อง'} แต่วัดได้ text-indent ${ก.เยื้อง}px`,
          )
        }
      }

      // ── ป้ายบนหน้าตรงกับซองไหม ⇒ เฉพาะฉบับที่มีย่อหน้าของตัวเอง ⇒ รอยที่ต้นข้อ (`หลังอักษร` 0)
      //   ⇒ ย่อหน้าแรกของฉบับนั้นที่ขึ้นด้วยข้อนั้น = ย่อหน้าที่รอยนี้เปิด
      for (const [ฉ, รอย] of Object.entries(ของบท.ย่อหน้า || {})) {
        if (ฉ in ไม่มีของตัวเอง) continue
        const ของฉ = ก้อน.filter((ก) => ก.ฉบับ === ฉ)
        if (!ของฉ.length) continue
        for (const ร of รอย) {
          if (ร.หลังอักษร !== 0) continue
          if (รอย.find((x) => x.ข้อ === ร.ข้อ && x.หลังอักษร === 0) !== ร) continue
          const ย = ของฉ.find((ก) => ก.ข้อแรก === `${เลขบท}:${ร.ข้อ}`)
          if (!ย) ตก.push(`⑦ ${บท} ${ฉ} ⇒ 🔴 ซองบอกว่าข้อ ${ร.ข้อ} ขึ้นย่อหน้า «${ร.ป้าย}» แต่บนหน้าไม่มีย่อหน้าที่ขึ้นด้วยข้อนี้`)
          else if (ย.ป้าย !== ร.ป้าย)
            ตก.push(`⑦ ${บท} ${ฉ} ข้อ ${ร.ข้อ} ⇒ 🔴 ซองบอกป้าย «${ร.ป้าย}» แต่บนหน้าเป็น «${ย.ป้าย || 'ว่าง'}»`)
        }
      }

      // ⭐ รายงานตัวอย่างที่พี่เอมเห็นเอง ⇒ ข้อ 1 ของ TCV
      const ข้อหนึ่ง = ก้อน.find((ก) => ก.ฉบับ === 'TCV' && ก.ข้อแรก === `${เลขบท}:1`)
      if (ข้อหนึ่ง) console.log(`   ⑦ ${บท} TCV ข้อ 1 ⇒ ป้าย «${ข้อหนึ่ง.ป้าย || 'ว่าง'}» ⇒ text-indent ${ข้อหนึ่ง.เยื้อง}px`)
      const ฉบับที่วัด = [...new Set(ก้อน.map((ก) => ก.ฉบับ))]
      console.log(`   ⑦ ${บท} ⇒ วัด ${ก้อน.length} ย่อหน้า จาก ${ฉบับที่วัด.join(' · ')}`)
    }
  } finally {
    await ctx.close()
  }
  if (!เยื้อง || !ไม่เยื้อง) {
    ตก.push(`⑦ 🔴 วัดได้ย่อหน้าที่เยื้อง ${เยื้อง} ก้อน · ⛔ เยื้อง ${ไม่เยื้อง} ก้อน ⇒ ต้องมีทั้งสองแบบ ⇒ ไม่งั้นข้อนี้ไม่ได้วัดอะไร`)
  }
  return ตก
}

