/**
 * ตรวจ 1 สภาพ ⇒ เปิดหน้าใหม่ทุกครั้ง ⇒ ⛔ ค่าที่เว็บจำไว้จากรอบก่อนไม่ปนเข้ามา
 * `ยัดกฎที่พัง` เป็นจริงเฉพาะโหมดพิสูจน์ว่าด่านยังจับได้
 */
async function ตรวจสภาพ({ กว้างจอ, กี่ฉบับ, ขนาด }, ยัดกฎที่พัง) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้างจอ, height: 900 } })
  const แท็บ = await ctx.newPage()
  const ป้าย = `จอ ${กว้างจอ} · ${กี่ฉบับ} ฉบับ · ตัวอักษร${ขนาด === 'ปกติ' ? 'ปกติ' : `${ขนาด}สุด`}`
  const ตก = []
  try {
    await เปิด(แท็บ, `/read/${บทที่ใช้}`)
    await ตั้งจำนวนฉบับ(แท็บ, กี่ฉบับ)
    if (ขนาด !== 'ปกติ') await ดันขนาดจนสุด(แท็บ, ขนาด)

    // ── ของอ้างอิง ⇒ ตัวหนังสือในโหมด *ไหลต่อเนื่อง*
    await ตั้งการจัดวาง(แท็บ, 'ไหลต่อเนื่อง')
    const เนื้ออ้างอิง = await ตัวหนังสือของฉบับ(แท็บ, 'TCV')

    // ── ของจริง ⇒ โหมด *แยกตามย่อหน้า*
    await ตั้งการจัดวาง(แท็บ, 'แยกตามย่อหน้า')
    if (ยัดกฎที่พัง) {
      await แท็บ.addStyleTag({ content: กฎที่พัง })
      await แท็บ.waitForTimeout(150)
    }
    const เนื้อย่อหน้า = await ตัวหนังสือของฉบับ(แท็บ, 'TCV')
    const วัด = await วัดย่อหน้า(แท็บ, 'TCV')

    if (!เนื้ออ้างอิง.length) {
      ตก.push(`${ป้าย} ⇒ หาตัวบทฉบับ TCV บนหน้าไม่เจอเลย`)
      return ตก
    }

    // ① 🔴 ตัวบทครบทุกตัวอักษร
    if (เนื้อย่อหน้า !== เนื้ออ้างอิง) {
      const ที่ต่าง = [...เนื้ออ้างอิง].findIndex((c, i) => เนื้อย่อหน้า[i] !== c)
      ตก.push(
        `${ป้าย} ⇒ 🔴 ตัวบทเปลี่ยน ⇒ ไหลต่อเนื่อง ${เนื้ออ้างอิง.length} ตัวอักษร · ` +
          `แยกตามย่อหน้า ${เนื้อย่อหน้า.length} ตัวอักษร ⇒ ต่างกันตัวแรกที่ลำดับ ${ที่ต่าง} ` +
          `«${เนื้ออ้างอิง.slice(Math.max(0, ที่ต่าง - 20), ที่ต่าง + 20)}»`,
      )
    }

    // ② 🔴 ขึ้นย่อหน้าจริง
    if (วัด.จำนวนย่อหน้า < 2) {
      ตก.push(`${ป้าย} ⇒ 🔴 มีกล่องย่อหน้าแค่ ${วัด.จำนวนย่อหน้า} กล่อง ⇒ ⛔ ไม่ได้แบ่งย่อหน้าเลย`)
    } else {
      if (วัด.ไม่คาบเกี่ยว < วัด.จำนวนย่อหน้า - 1) {
        ตก.push(
          `${ป้าย} ⇒ 🔴 กล่องย่อหน้าคาบเกี่ยวกันในแนวตั้ง ⇒ ` +
            `${วัด.จำนวนย่อหน้า} กล่อง แต่แยกแถบกันจริงแค่ ${วัด.ไม่คาบเกี่ยว} คู่ ` +
            `⇒ **ย่อหน้าถัดไปเริ่มกลางบรรทัดเดิม ⛔ ไม่ใช่ย่อหน้าจริง**`,
        )
      }
      if (วัด.ทรงที่ไม่ใช่บล็อก.length) {
        ตก.push(
          `${ป้าย} ⇒ 🔴 มีกล่องย่อหน้าที่ ⛔ ไม่ใช่บล็อก ⇒ เจอทรง [${วัด.ทรงที่ไม่ใช่บล็อก.join(' ')}] ` +
            `⇒ **นี่คือถ่างช่องไฟ ⛔ ไม่ใช่ย่อหน้า**`,
        )
      }
      if (วัด.แท็กที่ไม่ใช่p.length) {
        ตก.push(
          `${ป้าย} ⇒ 🔴 ย่อหน้าต้องเป็นแท็ก <p> จริง ⇒ เจอ [${วัด.แท็กที่ไม่ใช่p.join(' ')}] ` +
            `⇒ โปรแกรมอ่านหน้าจอจะ ⛔ ไม่รู้ว่าขึ้นย่อหน้าใหม่`,
        )
      }
    }

    // ⑤ หมุดยังเกาะข้อ ⛔ ไม่ใช่ย่อหน้า
    const หมุด = await นับหมุดข้อ(แท็บ)
    if (หมุด < 1) ตก.push(`${ป้าย} ⇒ ⛔ ไม่มีหมุด id="ข้อ-…" เหลืออยู่เลย ⇒ ลิงก์ไปที่ข้อจะตาย`)

    // ④ เลขข้อเปิดปิดได้อิสระจากการจัดวาง
    const เลขก่อน = await เลขที่ตาเห็น(แท็บ)
    await ตั้งการแสดงเลข(แท็บ, false)
    const เลขหลัง = await เลขที่ตาเห็น(แท็บ)
    const วัดหลังปิดเลข = await วัดย่อหน้า(แท็บ, 'TCV')
    if (!(เลขก่อน > 0 && เลขหลัง === 0)) {
      ตก.push(`${ป้าย} ⇒ ปิดเลขแล้วเลขยังเห็นอยู่ ⇒ ก่อน ${เลขก่อน} · หลัง ${เลขหลัง}`)
    }
    if (วัดหลังปิดเลข.จำนวนย่อหน้า !== วัด.จำนวนย่อหน้า) {
      ตก.push(
        `${ป้าย} ⇒ ปิดเลขแล้วจำนวนย่อหน้าเปลี่ยน ⇒ ${วัด.จำนวนย่อหน้า} ⇒ ` +
          `${วัดหลังปิดเลข.จำนวนย่อหน้า} ⇒ **สองเรื่องนี้ต้องอิสระจากกัน**`,
      )
    }
    await ตั้งการแสดงเลข(แท็บ, true)

    // ⑥ ⛔ ไม่เลื่อนซ้ายขวา
    const ล้น = await แท็บ.evaluate(
      () => document.documentElement.scrollWidth - document.documentElement.clientWidth,
    )
    if (ล้น > 1) ตก.push(`${ป้าย} ⇒ หน้าเลื่อนซ้ายขวาได้ ${ล้น} จุด`)

    if (ที่เก็บภาพ && !ยัดกฎที่พัง) {
      mkdirSync(ที่เก็บภาพ, { recursive: true })
      await แท็บ.screenshot({
        path: `${ที่เก็บภาพ}/ย่อหน้า-จอ${กว้างจอ}-${กี่ฉบับ}ฉบับ-${ขนาด}.png`,
        fullPage: false,
      })
    }
  } finally {
    await ctx.close()
  }
  return ตก
}

/**
 * ③ **ฉบับที่ไม่มีย่อหน้าของตัวเอง ⇒ ยืมจากคอลัมน์ซ้ายสุดที่มี พร้อมป้ายที่หัวคอลัมน์**
 *   (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/106 ⇒ มาแทนข้อ ③ เดิมของใบ #98)
 *
 * ⭐ **ข้อ ③ เดิม** ตรวจว่า *ฉบับที่ยังไม่มีย่อหน้า ต้องมีป้ายบอกผู้อ่าน* ⇒ ใบ #106 เปลี่ยนกติกาแล้ว
 *   ⇒ ฉบับพวกนั้นยืมย่อหน้าได้ ⇒ ป้าย *ยังไม่มี* ⛔ ไม่ขึ้นอีก ⇒ **ป้าย *ย่อหน้าตาม …* มาแทน**
 *   ⇒ ข้อนี้จึงยังเฝ้าเรื่องเดิม คือ **ผู้อ่านต้องรู้ว่าย่อหน้านี้ไม่ใช่ของคนแปลฉบับนั้น** ⛔ ไม่ได้ถอด
 *
 * ตรวจ 3 สภาพบนจอกว้าง ⇒ ทุกสภาพเทียบกับรอยจริงที่หลังบ้านส่งมา ⛔ ไม่พิมพ์ชื่อฉบับไว้ในด่าน
 *   ก. เปิดครบทุกฉบับ ⇒ ฉบับที่ยืมต้องยืมจากฉบับซ้ายสุดที่มีของตัวเอง
 *   ข. ปิดคอลัมน์ซ้ายสุด ⇒ **ป้ายกับจุดขึ้นย่อหน้าต้องเปลี่ยนตาม** (ข้อ 8.1)
 *   ค. ปิดจนเหลือแต่ฉบับที่ไม่มีของตัวเอง ⇒ ต้องยืมจาก TCV (ข้อ 6.1)
 * แต่ละสภาพ ⇒ ป้ายต้องอยู่ในต้นไม้การเข้าถึง (โปรแกรมอ่านหน้าจอได้ยิน · ข้อ 8)
 *   · ฉบับที่มีของตัวเอง ⛔ ไม่มีป้าย (ข้อ 7) · ขึ้นย่อหน้าตรงข้อของต้นแบบ · ตัวบทครบทุกตัวอักษร (ข้อ 9)
 *
 * `ยัดของพัง` ⇒ ซ่อนป้ายทิ้ง ⇒ ใช้เฉพาะโหมดพิสูจน์ว่าด่านยังจับได้
 */
async function ตรวจฉบับที่ยืม(ยัดของพัง) {
  const [เล่ม, เลขบท] = บทที่ใช้.split('/')
  const ของเล่ม = await (await fetch(`${ฐาน}/api/book/${เล่ม}.json`)).json()
  const ของบท = await (await fetch(`${ฐาน}/api/chapter/${เล่ม}/${เลขบท}.json`)).json()
  const ไม่มีของตัวเอง = ของเล่ม.ฉบับที่ยังไม่มีย่อหน้า || {}
  const ตก = []
  if (!Object.keys(ไม่มีของตัวเอง).length) {
    // ⭐ วันที่ทุกฉบับมีย่อหน้าของตัวเองแล้ว ⇒ ไม่มีอะไรให้ยืม ⇒ **บอกตรง ๆ** ⛔ ไม่เขียวเงียบ
    console.log('   ③ ทุกฉบับมีย่อหน้าของตัวเองแล้ว ⇒ ไม่มีฉบับไหนต้องยืม')
    return ตก
  }

  /** จุดขึ้นย่อหน้าที่ควรได้ ⇒ เขียนจากกติกาของใบ #106 ตรง ๆ ⇒ ต้นข้อ · เลื่อนไปข้อถัดไปที่เรามี */
  const ควรขึ้นที่ = (ฉ, ต้นแบบ) => {
    const เรา = Object.keys(ของบท.ชั้น[ฉ] || {})
      .map(Number)
      .sort((a, b) => a - b)
    const ขึ้น = new Set([เรา[0]])
    for (const ร of ของบท.ย่อหน้า?.[ต้นแบบ] || []) {
      const v = เรา.find((n) => n >= ร.ข้อ)
      if (v !== undefined) ขึ้น.add(v)
    }
    return [...ขึ้น].sort((a, b) => a - b)
  }

  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
  const แท็บ = await ctx.newPage()
  try {
    await เปิด(แท็บ, `/read/${บทที่ใช้}`)
    await ตั้งจำนวนฉบับ(แท็บ, 99)
    // ของอ้างอิงตัวบท ⇒ โหมดไหลต่อเนื่อง ⇒ เก็บไว้ก่อนปิดคอลัมน์ใด ๆ
    await ตั้งการจัดวาง(แท็บ, 'ไหลต่อเนื่อง')
    const เนื้ออ้างอิง = {}
    for (const ฉ of Object.keys(ไม่มีของตัวเอง)) เนื้ออ้างอิง[ฉ] = await ตัวหนังสือของฉบับ(แท็บ, ฉ)
    await ตั้งการจัดวาง(แท็บ, 'แยกตามย่อหน้า')
    let ต้นแบบสุดท้าย = ''

    const สภาพ = ['ก. เปิดครบทุกฉบับ', 'ข. ปิดคอลัมน์ซ้ายสุด', 'ค. เหลือแต่ฉบับที่ไม่มีของตัวเอง']
    for (let รอบ = 0; รอบ < สภาพ.length; รอบ++) {
      if (รอบ === 1) {
        await แท็บ.getByRole('button', { name: 'ปิดคอลัมน์ที่ 1', exact: true }).click()
        await แท็บ.waitForTimeout(300)
      }
      if (รอบ === 2) {
        // ปิดทุกคอลัมน์ที่มีย่อหน้าของตัวเอง ⇒ เหลือแต่ฉบับที่ยืม
        //   ⇒ ⭐ ⛔ ไม่ใช่แค่ปิดซ้ายสุดจนซ้ายสุดเป็นผู้ยืม ⇒ ฉบับที่มีของตัวเองทางขวา (KJV ตั้งแต่ 23 พ.ย. 2569) จะค้างเป็นต้นแบบ
        for (let i = 0; i < 8; i++) {
          const คอลัมน์ตอนนี้ = await แท็บ
            .locator('.pk-หัวคอลัมน์ .pk-ช่องหัว')
            .evaluateAll((els) => els.map((el) => el.getAttribute('data-ฉบับ')))
          const ที่ = คอลัมน์ตอนนี้.findIndex((ฉ) => !(ฉ in ไม่มีของตัวเอง))
          if (ที่ < 0 || คอลัมน์ตอนนี้.length < 2) break
          await แท็บ.getByRole('button', { name: `ปิดคอลัมน์ที่ ${ที่ + 1}`, exact: true }).click()
          await แท็บ.waitForTimeout(300)
        }
      }
      const คอลัมน์ = await แท็บ
        .locator('.pk-หัวคอลัมน์ .pk-ช่องหัว')
        .evaluateAll((els) => els.map((el) => el.getAttribute('data-ฉบับ')))
      const ต้นแบบ =
        คอลัมน์.find((ฉ) => !(ฉ in ไม่มีของตัวเอง)) || (ของเล่ม.ชั้น.includes('TCV') ? 'TCV' : '')
      const ผู้ยืม = คอลัมน์.filter((ฉ) => ฉ in ไม่มีของตัวเอง)
      if (!ผู้ยืม.length || !ต้นแบบ) {
        ตก.push(`③ ${สภาพ[รอบ]} ⇒ คอลัมน์ [${คอลัมน์.join(' ')}] ⇒ ⛔ ไม่มีฉบับที่ต้องยืมให้ตรวจ`)
        continue
      }
      const ป้าย = `③ ${สภาพ[รอบ]} [${คอลัมน์.join(' ')}]`
      // ⭐ ใบ #131 ⇒ ป้ายถอดออกจากหัวแล้ว ⇒ หัวทุกหัว ⛔ มีป้าย *ย่อหน้าตาม* (ทั้งที่ตาเห็นและที่ได้ยิน)
      for (const ฉ of คอลัมน์) {
        const หัว = แท็บ.locator(`.pk-หัวคอลัมน์ .pk-ช่องหัว[data-ฉบับ="${ฉ}"]`)
        const ได้ยิน = (await หัว.ariaSnapshot()).replace(/\s+/gu, ' ')
        if (ได้ยิน.includes('ย่อหน้าตาม')) ตก.push(`${ป้าย} ⇒ 🔴 หัวคอลัมน์ ${ฉ} ยังมีป้าย «ย่อหน้าตาม» ⇒ ต้องอยู่ที่หน้าแหล่งข้อมูล (ใบ #131)`)
      }
      ต้นแบบสุดท้าย = ต้นแบบ
      for (const ฉ of ผู้ยืม) {
        // ⭐ จุดขึ้นย่อหน้า ⇒ ข้อของท่อนแรกในแต่ละกล่อง `<p>` ⇒ หนีบไว้ที่บทแรกบทเดียว
        const ขึ้นจริง = await แท็บ.evaluate(
          ([ฉบับ, บท]) =>
            [
              ...document.querySelectorAll(
                `.pk-ตัวบท [data-ฉบับ="${ฉบับ}"] p.pk-ย่อหน้า`,
              ),
            ]
              .map((p) => p.querySelector('.pk-ข้อไหล')?.getAttribute('data-ข้อ') || '')
              .filter((x) => x.startsWith(`${บท}:`))
              .map((x) => Number(x.split(':')[1])),
          [ฉ, Number(เลขบท)],
        )
        const ควร = ควรขึ้นที่(ฉ, ต้นแบบ)
        if (ขึ้นจริง.join(',') !== ควร.join(',')) {
          ตก.push(
            `${ป้าย} ⇒ 🔴 ${ฉ} ขึ้นย่อหน้าที่ข้อ [${ขึ้นจริง.join(' ')}] ⛔ ไม่ตรง ${ต้นแบบ} [${ควร.join(' ')}]`,
          )
        }
        if (ควร.length < 2) ตก.push(`${ป้าย} ⇒ ${ต้นแบบ} มีย่อหน้าเดียวในบทนี้ ⇒ บทนี้ใช้พิสูจน์ไม่ได้`)
        const เนื้อ = await ตัวหนังสือของฉบับ(แท็บ, ฉ)
        if (เนื้อ !== เนื้ออ้างอิง[ฉ]) {
          ตก.push(
            `${ป้าย} ⇒ 🔴 ตัวบท ${ฉ} เปลี่ยน ⇒ ไหลต่อเนื่อง ${เนื้ออ้างอิง[ฉ].length} · ยืมย่อหน้า ${เนื้อ.length} ตัวอักษร (ข้อ 9)`,
          )
        }
      }
      console.log(`   ${ป้าย} ⇒ ${ผู้ยืม.join(' ')} ยืมจาก ${ต้นแบบ}`)
      // ⭐ เก็บภาพของจริงไว้ให้คนตรวจเปิดดู ⇒ **ป้ายย่อหน้าตาม … อยู่ในภาพนี้**
      if (ที่เก็บภาพ && !ยัดของพัง) {
        mkdirSync(ที่เก็บภาพ, { recursive: true })
        await แท็บ.screenshot({ path: `${ที่เก็บภาพ}/ย่อหน้า-ยืม-${รอบ + 1}.png` })
      }
    }
    // ⭐ ใบ #131 ⇒ บรรทัดบนหน้าแหล่งข้อมูล ⇒ ทุกฉบับที่ยืม มีบรรทัดเดียวใต้ฉบับนั้น ⇒ ต้นแบบเท่ากับที่หน้าอ่านยืมจริงในสภาพ ค.
    //   ⇒ ข้อความตรงถ้อยคำใน `app/utils/ถ้อยคำแหล่งข้อมูล.ts` ⇒ ฉบับที่มีย่อหน้าของตัวเอง ⛔ มีบรรทัด
    await แท็บ.goto(`${ฐาน}/sources`, { waitUntil: 'domcontentloaded' })
    await แท็บ.waitForSelector('article.pk-เนื้อ h1')
    if (ยัดของพัง) await แท็บ.addStyleTag({ content: '.pk-ย่อหน้าของฉบับ { display: none !important; }' })
    const บรรทัด = await แท็บ.evaluate(() =>
      [...document.querySelectorAll('.pk-ย่อหน้าของฉบับ')]
        .filter((e) => e.getClientRects().length && getComputedStyle(e).visibility !== 'hidden')
        .map((e) => ({ ฉบับ: e.getAttribute('data-ฉบับ'), ตาม: e.getAttribute('data-ย่อหน้าตาม'), ข้อความ: e.textContent.trim() })),
    )
    for (const ฉ of ของเล่ม.ชั้น.filter((x) => x !== 'คำฮีบรู' && x !== 'คำกรีก')) {
      const ของฉ = บรรทัด.filter((b) => b.ฉบับ === ฉ)
      if (ฉ in ไม่มีของตัวเอง) {
        const ควร = ถ้อยคำแหล่งข้อมูล.ย่อหน้าตาม(ต้นแบบสุดท้าย)
        if (ของฉ.length !== 1) ตก.push(`③ หน้าแหล่งข้อมูล ⇒ 🔴 ${ฉ} ไม่มีย่อหน้าของตัวเอง แต่เห็นบรรทัด «ย่อหน้าตาม» ${ของฉ.length} บรรทัด ⇒ ต้อง 1 บรรทัด`)
        else if (ของฉ[0].ข้อความ !== ควร)
          ตก.push(`③ หน้าแหล่งข้อมูล ⇒ 🔴 ${ฉ} เขียนว่า «${ของฉ[0].ข้อความ}» ⇒ ต้องเป็น «${ควร}» (ต้นแบบที่หน้าอ่านยืมจริง ${ต้นแบบสุดท้าย})`)
      } else if (ของฉ.length) ตก.push(`③ หน้าแหล่งข้อมูล ⇒ 🔴 ${ฉ} มีย่อหน้าของตัวเอง แต่มีบรรทัดว่ายืม`)
    }
    console.log(`   ③ หน้าแหล่งข้อมูล ⇒ ${บรรทัด.map((b) => `${b.ฉบับ} ย่อหน้าตาม ${b.ตาม}`).join(' · ') || 'ไม่มีบรรทัด'}`)
  } finally {
    await ctx.close()
  }
  return ตก
}

