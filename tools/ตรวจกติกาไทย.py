USX = os.path.join(ที่เก็บ, '_แตก', 'tcv', 'usx-rev2-release', 'release', 'USX_1')

# ── เครื่องมือตัวที่สอง ⇒ รายชื่อรหัสตัวมองไม่เห็นที่ยูนิโคดใช้จัดวางตัวอักษร
#    ⛔ **ไม่ใช่ตัวที่ใช้งานจริง** ⇒ ตัวที่ใช้งานคือ `ล้างเพื่อค้นหา` ใน tools/กติกาไทย.py
#    อันนี้เขียนขึ้นเพื่อ **ทาน** ว่าอันนั้นตัดของถูกตัว ⇒ สองวิธีต้องได้ผลเท่ากัน
รหัสมองไม่เห็น = (0x00AD, 0x061C, 0x180E, 0x200B, 0x200C, 0x200D, 0x200E, 0x200F,
                  0x2060, 0x2061, 0x2062, 0x2063, 0x2064, 0x2066, 0x2067, 0x2068,
                  0x2069, 0x202A, 0x202B, 0x202C, 0x202D, 0x202E, 0xFEFF,
                  0xFFF9, 0xFFFA, 0xFFFB)
ตัดด้วยรายชื่อ = re.compile('[%s]' % ''.join('\\u%04X' % o for o in รหัสมองไม่เห็น)).sub


def ล้างวิธีที่สอง(s):
    """ล้างด้วย **รายชื่อรหัสตรง ๆ** ⇒ คนละวิธีคิดกับการดูหมวดยูนิโคด"""
    return ตัดด้วยรายชื่อ('', s)


def นับจากไฟล์ดิบ():
    """เปิดไฟล์ .usx ทั้ง 66 เล่มแบบข้อความดิบ แล้วนับตัวมองไม่เห็นแยกชนิด"""
    นับ = collections.Counter()
    for รหัส in ตัวแปลง.สารบบ:
        with open(os.path.join(USX, รหัส + '.usx'), encoding='utf-8') as f:
            for ช in f.read():
                if unicodedata.category(ช) == กติกาไทย.หมวดที่ล้าง:
                    นับ[ช] += 1
    return นับ


def ชื่อ(ช):
    return 'U+%04X %s' % (ord(ช), unicodedata.name(ช, '(ไม่มีชื่อ)'))


def เทียบชั้นอ่าน(ก่อน, หลัง):
    """เปิดไฟล์ชั้นอ่านของสองรุ่นทีละไฟล์ ⇒ บอกว่าต่างกันที่ช่องไหนบ้าง"""
    ฐานก่อน = os.path.join(ก่อน, 'public', 'data', 'read')
    ฐานหลัง = os.path.join(หลัง, 'public', 'data', 'read')
    รายชื่อ = lambda ฐาน: sorted(
        os.path.relpath(os.path.join(d, f), ฐาน).replace('\\', '/')
        for d, _, fs in os.walk(ฐาน) for f in fs if f.endswith('.json'))
    ก, ห = รายชื่อ(ฐานก่อน), รายชื่อ(ฐานหลัง)
    print('\n⑥ เทียบชั้นอ่านทีละไฟล์ ⇒ ก่อน %s ไฟล์ · หลัง %s ไฟล์'
          % (format(len(ก), ','), format(len(ห), ',')))
    if ก != ห:
        print('   ⛔ รายชื่อไฟล์ไม่ตรงกัน ⇒ ขาด %s · เกิน %s'
              % (sorted(set(ก) - set(ห))[:5], sorted(set(ห) - set(ก))[:5]))
        return 1
    ช่องที่ต่าง = collections.Counter()
    ไฟล์ที่ต่าง = 0
    ตัวอย่าง = []

    def ไล่(ก, ห, ทาง):
        """ไล่ก้อน JSON สองอันเทียบกัน ⇒ คืนรายชื่อที่อยู่ของช่องที่ต่างกัน"""
        if type(ก) is not type(ห):
            return [ทาง + ' (ชนิดต่าง)']
        if isinstance(ก, dict):
            ต่าง = []
            for k in dict.fromkeys(list(ก) + list(ห)):
                if k not in ก:
                    ต่าง.append(ทาง + '.' + k + ' (เพิ่มมา)')
                elif k not in ห:
                    ต่าง.append(ทาง + '.' + k + ' (หายไป)')
                else:
                    ต่าง += ไล่(ก[k], ห[k], ทาง + '.' + k)
            return ต่าง
        if isinstance(ก, list):
            if len(ก) != len(ห):
                return [ทาง + ' (ยาวไม่เท่า)']
            ต่าง = []
            for i, (x, y) in enumerate(zip(ก, ห)):
                ต่าง += ไล่(x, y, ทาง + '[]')
            return ต่าง
        return [] if ก == ห else [ทาง + ' (ค่าต่าง)']

    for ชื่อไฟล์ in ก:
        with open(os.path.join(ฐานก่อน, ชื่อไฟล์), encoding='utf-8') as f:
            ของก่อน = json.load(f)
        with open(os.path.join(ฐานหลัง, ชื่อไฟล์), encoding='utf-8') as f:
            ของหลัง = json.load(f)
        ต่าง = sorted(set(ไล่(ของก่อน, ของหลัง, '')))
        if ต่าง:
            ไฟล์ที่ต่าง += 1
            ช่องที่ต่าง[' · '.join(ต่าง)] += 1
            if len(ตัวอย่าง) < 3:
                ตัวอย่าง.append((ชื่อไฟล์, ต่าง))
    print('   ไฟล์ที่มีอะไรต่าง %s จาก %s' % (format(ไฟล์ที่ต่าง, ','), format(len(ก), ',')))
    for แบบ, n in ช่องที่ต่าง.most_common():
        print('   ต่างที่ %-40s %s ไฟล์' % (แบบ, format(n, ',')))
    for ชื่อไฟล์, ต่าง in ตัวอย่าง:
        print('   ตัวอย่าง %s ⇒ %s' % (ชื่อไฟล์, ต่าง))
    เฉพาะช่องใหม่ = set(ช่องที่ต่าง) <= {'.ตัวบทไทย.ค้นหา (เพิ่มมา)'}
    print('   ⇒ ต่างกันแค่ช่องที่เพิ่มเข้ามาไหม ⇒ %s' % เฉพาะช่องใหม่)
    return 0 if เฉพาะช่องใหม่ else 1


def main(args):
    (ข้อ, _, ว่าง, รอย, เชิงอรรถ,
     พระเยซู) = ตัวแปลง.อ่าน_usx(USX, 'TCV', เอาคำพระเยซู=True)
    ควร = ตัวแปลง.ควรได้['TCV']
    print('① ของเดิม ⇒ ตัวบท %s ข้อ (ควรได้ %s) · ข้อว่าง %s (ควรได้ %s) · '
          'รอยแบ่ง %s อัน · เชิงอรรถ %s อัน · คำพระเยซู %s ช่วง'
          % (format(len(ข้อ), ','), format(ควร['ข้อ'], ','), len(ว่าง), ควร['ว่าง'],
             format(sum(len(v) for v in รอย.values()), ','),
             format(sum(len(v) for v in เชิงอรรถ.values()), ','),
             format(sum(len(v) for v in พระเยซู.values()), ',')))

    # ② นับตัวมองไม่เห็น ⇒ จากไฟล์ดิบ และจากตัวบทที่เก็บได้
    ดิบ = นับจากไฟล์ดิบ()
    ในตัวบท = collections.Counter()
    ข้อที่มี = 0
    for เนื้อ in ข้อ.values():
        มี = [c for c in เนื้อ if unicodedata.category(c) == กติกาไทย.หมวดที่ล้าง]
        if มี:
            ข้อที่มี += 1
            ในตัวบท.update(มี)
    ในเชิงอรรถ = collections.Counter(
        c for v in เชิงอรรถ.values() for ก in v for c in ก['ตัวหนังสือ']
        if unicodedata.category(c) == กติกาไทย.หมวดที่ล้าง)
    print('\n② ตัวมองไม่เห็นในไฟล์ดิบทั้ง 66 เล่ม %s ตัว' % format(sum(ดิบ.values()), ','))
    for ช, n in ดิบ.most_common():
        print('   %-34s %s ตัว' % (ชื่อ(ช), format(n, ',')))
    print('   ⇒ ตกลงมาถึงตัวบท %s ตัว ⇒ อยู่ใน %s ข้อ จาก %s ข้อ'
          % (format(sum(ในตัวบท.values()), ','), format(ข้อที่มี, ','), format(len(ข้อ), ',')))
    print('   ⇒ อยู่ในตัวหนังสือของเชิงอรรถอีก %s ตัว ⛔ ยังไม่ได้ทำช่องค้นหาให้เชิงอรรถ'
          % format(sum(ในเชิงอรรถ.values()), ','))

    # ③ ล้างแล้วไม่มีตัวที่อ่านได้หายไป ⇒ ทานด้วยเครื่องมือตัวที่สอง
    สองวิธีไม่ตรง, กลับไม่ได้, เหลือตัวมองไม่เห็น = 0, 0, 0
    ตัดออกรวม = 0
    for เนื้อ in ข้อ.values():
        ก = กติกาไทย.ล้างเพื่อค้นหา(เนื้อ)
        ข = ล้างวิธีที่สอง(เนื้อ)
        if ก != ข:
            สองวิธีไม่ตรง += 1
        if กติกาไทย.มีตัวมองไม่เห็น(ก):
            เหลือตัวมองไม่เห็น += 1
        ตัดออกรวม += len(เนื้อ) - len(ก)
        # ใส่ตัวที่ตัดออกกลับตามตำแหน่งเดิม ⇒ ต้องได้ตัวบทเดิมทุกตัวอักษร
        กลับ, i = [], 0
        for c in เนื้อ:
            if unicodedata.category(c) == กติกาไทย.หมวดที่ล้าง:
                กลับ.append(c)
            else:
                กลับ.append(ก[i])
                i += 1
        if ''.join(กลับ) != เนื้อ or i != len(ก):
            กลับไม่ได้ += 1
    print('\n③ ข้อที่สองวิธีล้างได้ผลไม่ตรงกัน %s ข้อ' % format(สองวิธีไม่ตรง, ','))
    print('   ข้อที่ล้างแล้วยังมีตัวมองไม่เห็นเหลือ %s ข้อ' % format(เหลือตัวมองไม่เห็น, ','))
    print('   ข้อที่ใส่ตัวที่ตัดออกกลับแล้วไม่ได้ตัวบทเดิม %s ข้อ' % format(กลับไม่ได้, ','))
    print('   ตัวอักษรที่ตัดออกรวม %s ตัว ⇒ ตรงกับที่นับไว้ข้อ ② ไหม ⇒ %s'
          % (format(ตัดออกรวม, ','), ตัดออกรวม == sum(ในตัวบท.values())))

    # ④ ทดลองค้นจริง
    print('\n④ ทดลองค้นคำ ⇒ ตัวเลขคือจำนวนข้อที่เจอ')
    ล้างไว้ = {k: กติกาไทย.ล้างเพื่อค้นหา(v) for k, v in ข้อ.items()}
    print('   %-16s %10s %10s' % ('คำที่ค้น', 'ในช่อง ข้อ', 'ในช่อง ค้นหา'))
    for คำ in ('พระเจ้า', 'ความรัก', 'เยรูซาเล็ม', 'กรุณา', 'ลูกแกะ', 'ความเชื่อ'):
        ก = sum(1 for v in ข้อ.values() if คำ in v)
        ข = sum(1 for v in ล้างไว้.values() if คำ in v)
        print('   %-16s %10s %10s' % (คำ, format(ก, ','), format(ข, ',')))
    ตย = next((k for k, v in ข้อ.items() if 'พระเจ้า' in ล้างไว้[k] and 'พระเจ้า' not in v), None)
    if ตย:
        # หาว่าคำนั้นอยู่ตัวอักษรที่เท่าไรของ **ตัวบทเดิม** ⇒ ไล่นับตัวที่ล้างออกไปด้วย
        i = ล้างไว้[ตย].index('พระเจ้า')
        นับ, เดิมที่ = 0, 0
        for เดิมที่, c in enumerate(ข้อ[ตย]):
            if นับ == i:
                break
            if unicodedata.category(c) != กติกาไทย.หมวดที่ล้าง:
                นับ += 1
        print('   ตัวอย่างข้อที่เดิมค้นไม่เจอ ⇒ %s %s.%s ⇒ ตัดมาให้ดูช่วงเดียวกัน' % ตย)
        print('   เดิม  %s' % repr(ข้อ[ตย][max(0, เดิมที่ - 10):เดิมที่ + 20]))
        print('   ค้นหา %s' % repr(ล้างไว้[ตย][max(0, i - 8):i + 15]))

    # ⑤ ข้อความสัญญาอนุญาต ⇒ ทานด้วย regex อีกทาง
    ก้อน = สัญญาอนุญาต.ดึง()
    ดิบข้อความ = open(สัญญาอนุญาต.METADATA, encoding='utf-8-sig').read()
    def แกะด้วยregex(ป้ายนอก):
        ใน = re.search(r'<%s\b[^>]*>(.*?)</%s>' % (ป้ายนอก, ป้ายนอก), ดิบข้อความ, re.S).group(1)
        return [html.unescape(re.sub(r'<[^>]+>', '', m))
                for m in re.findall(r'<(?:p|h3)\b[^>]*>(.*?)</(?:p|h3)>', ใน, re.S)]
    print('\n⑤ ข้อความสัญญาอนุญาต')
    for ชื่อช่อง, ป้าย in (('ประกาศลิขสิทธิ์ที่ต้องขึ้นหน้าปก', 'statementContent'),
                            ('สัญญาอนุญาตฉบับเต็ม', 'promoVersionInfo')):
        เรา = [ย['ตัวหนังสือ'] for ย in ก้อน[ชื่อช่อง]['ย่อหน้า']]
        อีกทาง = แกะด้วยregex(ป้าย)
        print('   %-32s ย่อหน้า %s ⇒ วิธีที่สองได้ %s ⇒ ตรงกัน %s'
              % (ชื่อช่อง, len(เรา), len(อีกทาง), เรา == อีกทาง))
    ทั้งก้อน = json.dumps(ก้อน, ensure_ascii=False)
    print('   ที่อยู่เว็บที่ดึงมาได้ ⇒ %s' % ' · '.join(ก้อน['ที่อยู่เว็บที่ฝังอยู่ในข้อความ']))
    for ต้องมี in ('www.biblica.com', 'open.bible', 'CC BY-SA', 'Biblica®',
                    'creativecommons.org/licenses/by-sa/4.0'):
        print('   มีข้อความ %-38s ⇒ %s' % (ต้องมี, ต้องมี in ทั้งก้อน))

    if '--เทียบชั้นอ่าน' in args:
        i = args.index('--เทียบชั้นอ่าน')
        return เทียบชั้นอ่าน(args[i + 1], args[i + 2])
    print('\n⑥ ไม่ได้เทียบชั้นอ่าน ⇒ ใส่ --เทียบชั้นอ่าน <ก่อน> <หลัง> จึงตรวจ')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
