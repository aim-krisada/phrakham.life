def ประเภทสัญญา(ข้อความ: str) -> str | None:
    """ชื่อสัญญา ⇒ กลุ่มสี ⇒ ⛔ ไม่รู้จัก = None ⇒ คนต้องมาตัดสินว่าอยู่กลุ่มไหน ⛔ ไม่เดา"""
    s = ข้อความ.strip()
    if s in ("สาธารณสมบัติ", "CC0"):
        return "g1"  # ตัวข้อมูลเป็นของกลาง
    # ⭐ ใบ #111 ⇒ สัญญาของ LGNTDF เป็นข้อตกลงที่ SIL เขียนเอง ⇒ แจกต่อได้ แต่ห้ามขายแยก และต้องขออนุญาตเมื่อขายเกิน 25%
    #   ⇒ ⛔ ไม่ใช่ CC ⇒ เข้ากลุ่ม *เจ้าของเขียนเงื่อนไขพิเศษของตัวเองไว้* (แดง) ⇒ คนทำใบ #111 ตัดสิน ⇒ อ่าน `LICENSE.md` ข้อ 1 ถึง 4 เอง
    if s == "ข้อตกลงของ SIL":
        return "g4"
    # ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/174 ⇒ ฟอนต์ Noto อยู่ใต้ SIL Open Font License 1.1
    #   ⇒ ใช้ แก้ แจกต่อได้ฟรี ⇒ แต่ต้องแจกสัญญาและประกาศลิขสิทธิ์ไปด้วย ⇒ ตัวที่แก้แล้วต้องอยู่ใต้สัญญาเดิม ⇒ ห้ามขายแยกเดี่ยว
    #   ⇒ ตรงกับคำอธิบายสีเหลือง *บอกชื่อแล้วต้องแจกต่อฟรีด้วย* ⇒ ⛔ ไม่ใช่แดง ⇒ เป็นสัญญามาตรฐานที่ใช้กันทั่วไป ⛔ ไม่ใช่เงื่อนไขที่เจ้าของเขียนเอง
    #   ⇒ คนทำใบ #174 ตัดสิน ⇒ อ่านข้อ 1 ถึง 5 ของสัญญาใน `public/fonts/NotoSans-OFL.txt` เอง
    if s == "SIL OFL 1.1":
        return "g3"
    if not s.startswith("CC BY"):
        return None
    if "NC" in s or "ND" in s:
        return "g4"  # เงื่อนไขพิเศษ
    if "BY-SA" in s:
        return "g3"  # บอกชื่อแล้วต้องแจกต่อแบบเดียวกัน
    return "g2"  # ขอแค่บอกชื่อ


