def หัวข้อแหล่ง(md: str) -> dict[str, dict]:
    """หัวข้อ `### ` ทุกอัน ⇒ {ชื่อ: {สัญญา, หมุด}} ⇒ ข้ามของในกล่องโค้ด"""
    ผล: dict[str, dict] = {}
    ในโค้ด = False
    ปัจจุบัน = None
    for บรรทัด in md.split("\n"):
        if บรรทัด.startswith("```"):
            ในโค้ด = not ในโค้ด
            continue
        if ในโค้ด:
            continue
        if บรรทัด.startswith("### "):
            หัว = บรรทัด[4:]
            หมุด = re.search(r'<a id="([^"]+)"></a>', หัว)
            หัว = re.sub(r"<a [^>]*></a>", "", หัว).strip()
            ลิงก์ = re.match(r"\[([^\]]+)\]", หัว)
            ชื่อ = ลิงก์.group(1) if ลิงก์ else หัว
            ปัจจุบัน = ผล.setdefault(ชื่อ, {"สัญญา": None, "หมุด": หมุด.group(1) if หมุด else None})
        elif บรรทัด.startswith("## ") or บรรทัด.startswith("# "):
            ปัจจุบัน = None
        elif ปัจจุบัน is not None and บรรทัด.startswith("- สัญญา "):
            เนื้อ = บรรทัด[len("- สัญญา "):]
            ลิงก์ = re.match(r"\[([^\]]+)\]", เนื้อ)
            ปัจจุบัน["สัญญา"] = ลิงก์.group(1) if ลิงก์ else เนื้อ.split(" ")[0]
    return ผล


def ก้อนแผนภาพ(md: str) -> list[dict]:
    """ทุกก้อน ```mermaid ⇒ ตัวโค้ด + ย่อหน้าตัวหนังสือที่ตามหลังมา"""
    ผล = []
    for m in re.finditer(r"```mermaid\n(.*?)```", md, re.S):
        หลัง = md[m.end():].lstrip("\n")
        ย่อหน้า = หลัง.split("\n\n", 1)[0].strip()
        if ย่อหน้า.startswith(("```", "#", "<")):
            ย่อหน้า = ""
        ผล.append({"โค้ด": m.group(1), "ใต้ภาพ": ย่อหน้า, "จบที่": m.end()})
    return ผล


def แกะภาพ(โค้ด: str) -> tuple[dict, list[str]]:
    """แกะ flowchart ที่เขียนตามกติกาหัวไฟล์ ⇒ คืน (ภาพ, ปัญหาการเขียน)"""
    ปัญหา: list[str] = []
    กล่อง: dict[str, str] = {}
    กลุ่ม: dict[str, list[str]] = {}
    ชื่อกลุ่ม: dict[str, str] = {}
    สีกลุ่ม: set[str] = set()
    เส้น: list[tuple[str, str]] = []
    คลาส: dict[str, str] = {}
    เข้าถึง = {"accTitle": False, "accDescr": False}
    กลุ่มที่เปิด: list[str] = []
    for ดิบ in โค้ด.split("\n"):
        บรรทัด = ดิบ.strip()
        if not บรรทัด or บรรทัด.startswith("%%"):
            continue
        if บรรทัด.startswith(("accTitle:", "accDescr:")):
            เข้าถึง[บรรทัด.split(":")[0]] = bool(บรรทัด.split(":", 1)[1].strip())
            continue
        if บรรทัด.startswith(("flowchart", "direction", "classDef")):
            continue
        m = re.match(r"class ([\w,]+) (\w+)$", บรรทัด)
        if m:
            for ก in m.group(1).split(","):
                คลาส[ก] = m.group(2)
            continue
        m = re.match(r"style (\w+) .*fill:", บรรทัด)
        if m:
            สีกลุ่ม.add(m.group(1))
            continue
        m = re.match(r'subgraph (\w+)\["([^"]*)"\]$', บรรทัด)
        if m:
            กลุ่มที่เปิด.append(m.group(1))
            กลุ่ม[m.group(1)] = []
            ชื่อกลุ่ม[m.group(1)] = m.group(2)
            continue
        if บรรทัด == "end":
            if กลุ่มที่เปิด:
                กลุ่มที่เปิด.pop()
            continue
        for ก, ป้าย in re.findall(r'\b([A-Za-z]\w*)\["([^"]*)"\]', บรรทัด):
            if ก in กล่อง and กล่อง[ก] != ป้าย:
                ปัญหา.append(f"กล่อง {ก} ถูกเขียนสองแบบในภาพเดียว")
            กล่อง[ก] = ป้าย
        เปล่า = re.sub(r'\["[^"]*"\]', "", บรรทัด)
        if "~~~" in เปล่า:
            ชิ้น = [x.strip() for x in เปล่า.split("~~~")]
        elif "-->" in เปล่า:
            ชิ้น = [x.strip() for x in เปล่า.split("-->")]
            for a, b in zip(ชิ้น, ชิ้น[1:]):
                เส้น.append((a, b))
        elif re.search(r"--|==|-\.", เปล่า):
            ปัญหา.append(f"รูปเส้นที่ด่านอ่านไม่ออก ⇒ ใช้ --> เท่านั้น ⇒ {บรรทัด}")
            continue
        else:
            ชิ้น = [เปล่า.strip()]
        for ก in ชิ้น:
            if not re.fullmatch(r"[A-Za-z]\w*", ก):
                ปัญหา.append(f"บรรทัดที่ด่านอ่านไม่ออก ⇒ {บรรทัด}")
                break
            if กลุ่มที่เปิด and ก not in กลุ่ม:
                กลุ่ม[กลุ่มที่เปิด[-1]].append(ก)
    for ก, ป้าย in กล่อง.items():
        if not re.match(r"[SLWDP]_", ก):
            ปัญหา.append(f"กล่อง {ก} ⇒ ชื่อต้องขึ้นต้นด้วย S_ L_ W_ D_ หรือ P_")
    for a, b in เส้น:
        for ก in (a, b):
            if ก not in กล่อง and ก not in กลุ่ม:
                ปัญหา.append(f"เส้นอ้างกล่อง {ก} ที่ไม่มีป้าย")
    return {
        "กล่อง": กล่อง, "กลุ่ม": กลุ่ม, "ชื่อกลุ่ม": ชื่อกลุ่ม, "สีกลุ่ม": สีกลุ่ม,
        "เส้น": เส้น, "คลาส": คลาส, "เข้าถึง": เข้าถึง,
    }, ปัญหา


def เส้นจริง(ภาพ: dict) -> list[tuple[str, str]]:
    """เส้นที่ลากจากกรอบกลุ่ม = เส้นจากทุกกล่องในกลุ่ม"""
    ผล = []
    for a, b in ภาพ["เส้น"]:
        ต้น = ภาพ["กลุ่ม"].get(a, [a])
        ปลาย = ภาพ["กลุ่ม"].get(b, [b])
        ผล += [(x, y) for x in ต้น for y in ปลาย]
    return ผล


def บรรทัดของ(ป้าย: str) -> list[str]:
    return [x.strip() for x in ป้าย.split("<br/>")]


def ชื่อแหล่งในกล่อง(ป้าย: str) -> tuple[str, str]:
    ส่วน = บรรทัดของ(ป้าย)
    return " ".join(ส่วน[:-1]), ส่วน[-1]


