def ชื่องานในท่อ(ci: str) -> set[str]:
    ไม่ใช่งาน = {"variables", "stages", "default", "include", "workflow"}
    ผล = set()
    for บรรทัด in ci.split("\n"):
        m = re.match(r"([^\s#.][^:]*):\s*$", บรรทัด)
        if m and m.group(1) not in ไม่ใช่งาน:
            ผล.add(m.group(1))
    return ผล


def ที่อ่านข้อมูล(nuxt: str) -> list[str]:
    return re.findall(r"new URL\('([^']+)', import\.meta\.url\)", nuxt)


