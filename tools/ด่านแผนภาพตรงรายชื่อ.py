def ตรวจ(md: str, ci: str, nuxt: str, ข้อมูล: dict[str, set[str]], เสียง: dict) -> list[str]:
    """คืนรายการปัญหา ⇒ แต่ละข้อขึ้นต้นด้วยเลขข้อ ⇒ ว่างแปลว่าผ่าน ⇒ ⛔ ไม่พิมพ์เอง ⛔ ไม่ exit เอง"""
    ปัญหา: list[str] = []
    หัวข้อ = หัวข้อแหล่ง(md)
    ก้อน = ก้อนแผนภาพ(md)
    if not ก้อน:
        return ["① ไม่มีแผนภาพในหน้าเลย"]
    งาน = ชื่องานในท่อ(ci)

    แหล่งในภาพ: dict[str, str] = {}  # ชื่อ ⇒ ป้าย
    ป้ายของกล่องแหล่ง: dict[str, str] = {}
    สีที่ใช้: set[str] = set()
    ทุกกล่อง: dict[str, list[tuple[int, dict]]] = {}

    for ลำดับ, ก in enumerate(ก้อน, 1):
        ภาพ, ปัญหาเขียน = แกะภาพ(ก["โค้ด"])
        ปัญหา += [f"⓪ ภาพที่ {ลำดับ} ⇒ {x}" for x in ปัญหาเขียน]
        กล่อง = ภาพ["กล่อง"]
        เส้น = เส้นจริง(ภาพ)
        for ชื่อ in กล่อง:
            ทุกกล่อง.setdefault(ชื่อ, []).append((ลำดับ, ภาพ))

        แหล่งของภาพนี้ = set()
        for ไอดี, ป้าย in กล่อง.items():
            บรรทัด = บรรทัดของ(ป้าย)
            # ⑤ คำว่าด่าน
            if ไอดี.startswith("D_"):
                for ช in บรรทัด:
                    if ช not in งาน:
                        ปัญหา.append(f"⑤ ภาพที่ {ลำดับ} กล่อง {ไอดี} ⇒ \"{ช}\" ไม่ใช่ชื่องานใน .gitlab-ci.yml")
            elif "ด่าน" in ป้าย:
                ปัญหา.append(f"⑤ ภาพที่ {ลำดับ} กล่อง {ไอดี} ⇒ มีคำว่าด่านในกล่องที่ไม่ใช่ด่าน ⇒ ด่านต้องอยู่ในกล่อง D_ และใช้ชื่องานจริง")
            # ① ② กล่องแหล่ง
            if ไอดี.startswith("S_"):
                ชื่อ, สัญญา = ชื่อแหล่งในกล่อง(ป้าย)
                แหล่งของภาพนี้.add(ชื่อ)
                if ไอดี in ป้ายของกล่องแหล่ง and ป้ายของกล่องแหล่ง[ไอดี] != ป้าย:
                    ปัญหา.append(f"① กล่อง {ไอดี} เขียนไม่เหมือนกันในภาพที่ {ลำดับ} กับภาพก่อนหน้า")
                ป้ายของกล่องแหล่ง[ไอดี] = ป้าย
                if ชื่อ in แหล่งในภาพ and แหล่งในภาพ[ชื่อ] != ไอดี:
                    ปัญหา.append(f"① แหล่ง {ชื่อ} มีสองกล่อง ({แหล่งในภาพ[ชื่อ]} กับ {ไอดี})")
                แหล่งในภาพ[ชื่อ] = ไอดี
                if ชื่อ in หัวข้อ and หัวข้อ[ชื่อ]["สัญญา"] != สัญญา:
                    ปัญหา.append(f"② {ชื่อ} ⇒ กล่องเขียนสัญญา \"{สัญญา}\" แต่บนหน้าเขียน \"{หัวข้อ[ชื่อ]['สัญญา']}\"")
                if ประเภทสัญญา(สัญญา) is None:
                    ปัญหา.append(f"③ {ชื่อ} ⇒ บรรทัดท้ายกล่อง \"{สัญญา}\" ไม่ใช่ชื่อสัญญาที่ด่านรู้จัก ⇒ ต้องมีคนตัดสินว่าอยู่สีไหน")
            # ③ สีตามสัญญา ⇒ ทุกกล่องที่บรรทัดท้ายเป็นชื่อสัญญา
            ควรเป็น = ประเภทสัญญา(บรรทัด[-1])
            if ควรเป็น:
                เป็น = ภาพ["คลาส"].get(ไอดี)
                สีที่ใช้.add(เป็น or "")
                if เป็น != ควรเป็น:
                    ปัญหา.append(f"③ ภาพที่ {ลำดับ} กล่อง {ไอดี} สัญญา {บรรทัด[-1]} ⇒ ต้องเป็นสี{สี_คำ[ควรเป็น]} ({ควรเป็น}) แต่ได้ {เป็น}")
            # ⑥ กล่องหน้าอ่าน
            if ไอดี.startswith("P_") and บรรทัด[0] != "หน้าอ่าน":
                ปัญหา.append(f"⑥ ภาพที่ {ลำดับ} กล่อง {ไอดี} ⇒ บรรทัดแรกต้องเป็นคำว่า หน้าอ่าน")
        for กลุ่ม, ชื่อ in ภาพ["ชื่อกลุ่ม"].items():
            if "ด่าน" in ชื่อ:
                ปัญหา.append(f"⑤ ภาพที่ {ลำดับ} กรอบ {กลุ่ม} ⇒ มีคำว่าด่าน")
            if กลุ่ม not in ภาพ["สีกลุ่ม"]:
                ปัญหา.append(f"③ ภาพที่ {ลำดับ} กรอบ {กลุ่ม} ⇒ ไม่ได้ตั้งสีเอง ⇒ เหลืองตั้งต้นของตัววาดชนกับสีเหลืองของสัญญา")

        # ⑥ ทุกแหล่งเดินไปถึงหน้าอ่าน
        ถัดไป: dict[str, set[str]] = {}
        for a, b in เส้น:
            ถัดไป.setdefault(a, set()).add(b)
        for ไอดี in [x for x in กล่อง if x.startswith("S_")]:
            เห็น, คิว = {ไอดี}, [ไอดี]
            while คิว:
                for y in ถัดไป.get(คิว.pop(), ()):
                    if y not in เห็น:
                        เห็น.add(y)
                        คิว.append(y)
            if not any(x.startswith("P_") for x in เห็น):
                ปัญหา.append(f"⑥ ภาพที่ {ลำดับ} กล่อง {ไอดี} ⇒ ไม่มีทางเดินไปถึงกล่องหน้าอ่าน")

        # ⑦ แหล่งที่ลากเข้ากล่องข้อมูล = แหล่งที่ไฟล์ข้อมูลบอก
        for ไอดี, ต้องเป็น in ข้อมูล.items():
            if ไอดี not in กล่อง:
                continue
            เข้า = {ชื่อแหล่งในกล่อง(กล่อง[a])[0] for a, b in เส้น if b == ไอดี and a.startswith("S_") and a in กล่อง}
            if เข้า != ต้องเป็น:
                ขาด = sorted(ต้องเป็น - เข้า)
                เกิน = sorted(เข้า - ต้องเป็น)
                ปัญหา.append(f"⑦ ภาพที่ {ลำดับ} กล่อง {ไอดี} ⇒ ไฟล์ข้อมูลบอกว่ามาจาก {sorted(ต้องเป็น)} ⇒ ขาดเส้นจาก {ขาด} · เกินมาจาก {เกิน}")

        # ⑩ คำอธิบายเป็นตัวหนังสือ
        for ช่อง, มี in ภาพ["เข้าถึง"].items():
            if not มี:
                ปัญหา.append(f"⑩ ภาพที่ {ลำดับ} ⇒ ไม่มี {ช่อง} ⇒ โปรแกรมอ่านหน้าจอไม่รู้ว่าภาพนี้คืออะไร")
        ใต้ = ก["ใต้ภาพ"]
        if not ใต้:
            ปัญหา.append(f"⑩ ภาพที่ {ลำดับ} ⇒ ไม่มีย่อหน้าตัวหนังสือใต้ภาพ")
        else:
            for ชื่อ in sorted(แหล่งของภาพนี้):
                if ชื่อ not in ใต้:
                    ปัญหา.append(f"⑩ ภาพที่ {ลำดับ} ⇒ ย่อหน้าใต้ภาพไม่เอ่ยถึง {ชื่อ} ทั้งที่อยู่ในภาพ")
            for ชื่อ in sorted(set(หัวข้อ) - แหล่งของภาพนี้):
                if ชื่อ in ใต้:
                    ปัญหา.append(f"⑩ ภาพที่ {ลำดับ} ⇒ ย่อหน้าใต้ภาพเอ่ยถึง {ชื่อ} แต่ในภาพไม่มีกล่องของแหล่งนี้")

    # ① ทั้งสองทาง
    for ชื่อ in sorted(set(หัวข้อ) - set(แหล่งในภาพ)):
        ปัญหา.append(f"① หัวข้อ {ชื่อ} อยู่บนหน้า แต่ไม่มีกล่องในแผนภาพ")
    for ชื่อ in sorted(set(แหล่งในภาพ) - set(หัวข้อ)):
        ปัญหา.append(f"① กล่อง {แหล่งในภาพ[ชื่อ]} \"{ชื่อ}\" อยู่ในแผนภาพ แต่ไม่มีหัวข้อแหล่งชื่อนี้บนหน้า")

    # ④ คำอธิบายสี ⇒ ต้องอยู่ใต้ภาพสุดท้าย
    หลังภาพ = md[ก้อน[-1]["จบที่"]:]
    m = re.search(r"^สีในภาพบอก.*$", หลังภาพ, re.M)
    if not m:
        ปัญหา.append("④ ไม่มีย่อหน้าคำอธิบายสี (ขึ้นต้นว่า สีในภาพบอก) ใต้ภาพสุดท้าย")
    else:
        for สี in sorted(x for x in สีที่ใช้ if x):
            if สี_คำ.get(สี, "?") not in m.group(0):
                ปัญหา.append(f"④ ใช้สี{สี_คำ.get(สี, สี)} ({สี}) ในภาพ แต่คำอธิบายสีไม่พูดถึง")

    # ⑧ ทุกที่ที่เว็บอ่านข้อมูลมีกล่อง
    for ที่ in ที่อ่านข้อมูล(nuxt):
        if ที่ in ที่อ่านที่ไม่ใช่ข้อมูล:
            continue
        กล่อง = ที่อ่าน_กล่อง.get(ที่)
        if not กล่อง:
            ปัญหา.append(f"⑧ nuxt.config.ts อ่าน {ที่} แต่ด่านไม่รู้ว่ากล่องไหนในแผนภาพแทนมัน ⇒ วาดกล่องแล้วเติมตาราง ที่อ่าน_กล่อง ในด่านนี้")
        elif กล่อง not in ทุกกล่อง:
            ปัญหา.append(f"⑧ nuxt.config.ts อ่าน {ที่} แต่แผนภาพไม่มีกล่อง {กล่อง}")
    for กล่อง in sorted(ข้อมูล):
        if กล่อง not in ทุกกล่อง:
            ปัญหา.append(f"⑦ ไฟล์ข้อมูลของกล่อง {กล่อง} มีอยู่ แต่แผนภาพไม่มีกล่องนี้")

    # ⑨ กล่องเสียง
    for ไอดี, ร in sorted(เสียง.items()):
        if ไอดี not in ทุกกล่อง:
            continue  # ⇒ ข้อ ⑦ ข้างบนแดงให้แล้ว
        ป้าย = บรรทัดของ(ทุกกล่อง[ไอดี][0][1]["กล่อง"][ไอดี])
        ปี, เดือน, วัน = (int(x) for x in ร["generated"].split("-"))
        วันไทย = f"{วัน} {เดือนไทย[เดือน - 1]} {ปี + 543}"
        # ⭐ เสียงที่ถือเป็นของดัดแปลงใช้สัญญาของของดัดแปลง ⇒ ที่ไม่ใช่ใช้สัญญาของตัวบท
        สัญญาเสียง = ร["source"].get("adaptedLicense") if ร["source"].get("adapted") else ร["source"]["license"]
        if not any(ร["voice"] in ช for ช in ป้าย):
            ปัญหา.append(f"⑨ กล่องเสียง {ไอดี} ไม่บอกเสียง {ร['voice']}")
        if not any(วันไทย in ช for ช in ป้าย):
            ปัญหา.append(f"⑨ กล่องเสียง {ไอดี} ไม่บอกวันที่ทำ {วันไทย}")
        if ป้าย[-1] != สัญญาเสียง:
            ปัญหา.append(f"⑨ กล่องเสียง {ไอดี} ต้องจบด้วยสัญญา {สัญญาเสียง} แต่เขียน {ป้าย[-1]}")
    return ปัญหา


def ของจริง():
    md = หน้า.read_text("utf-8")
    หมุด_ชื่อ = {v["หมุด"]: k for k, v in หัวข้อแหล่ง(md).items() if v["หมุด"]}
    ข้อมูล, เสียง = แหล่งของข้อมูลจริง(หมุด_ชื่อ)
    return md, ท่อ.read_text("utf-8"), ตั้งค่าเว็บ.read_text("utf-8"), ข้อมูล, เสียง


def พิมพ์ผล(ปัญหา: list[str]) -> int:
    if ปัญหา:
        print(f"⛔ แผนภาพกับรายชื่อแหล่งไม่ตรงกัน {len(ปัญหา)} จุด")
        for x in ปัญหา:
            print("   " + x)
        return 1
    return 0


