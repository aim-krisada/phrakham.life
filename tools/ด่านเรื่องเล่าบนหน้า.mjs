/** ⭐ รอจนได้สภาพที่ต้องการ หรือจนหมดเวลา ⛔ ไม่ใช่นอนรอเป็นมิลลิวินาทีตายตัว (`docs/ที่ค้างอยู่.md`) */
async function รอจน(เงื่อนไข, นาน = 15000) {
  const ถึง = Date.now() + นาน
  for (;;) {
    if (await เงื่อนไข()) return true
    if (Date.now() > ถึง) return false
    await new Promise((r) => setTimeout(r, 150))
  }
}

async function เปิด(แท็บ, ทาง) {
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  const คำถาม = new URL(`${ฐาน}${ทาง}`).searchParams
  const c = คำถาม.get('c')
  if (c) await แท็บ.waitForSelector(`#บท-${c}`, { timeout: 15000 })
  // ⭐ **ช่วง `r=` ถูกใช้หลังโค้ดของหน้าทำงาน** ⇒ ไฟล์ดิบมีทั้งบท ⇒ รอจนข้อที่ตาเห็นอยู่ในช่วงทั้งหมด
  //   ⛔ ไม่นอนรอตายตัว ⇒ หน้าไม่เคยตัดตามช่วง ⇒ หมดเวลาแล้วข้อ ② ฟ้องเองว่าข้อบนหน้าไม่ตรงแบบที่ทดสอบ
  const r = /^(\d+)\.(\d+)-(\d+)\.(\d+)$/.exec(คำถาม.get('r') || '')
  if (r) {
    const [จาก, ถึง] = [[+r[1], +r[2]], [+r[3], +r[4]]]
    await รอจน(
      () =>
        แท็บ.evaluate(
          ([จาก, ถึง]) => {
            const ข้อ = [...document.querySelectorAll('.pk-ตัวบท [data-ข้อ]')]
              .filter((e) => e.getClientRects().length)
              .map((e) => e.getAttribute('data-ข้อ').split(':').map(Number))
            const ใน = ([b, v]) => (b > จาก[0] || (b === จาก[0] && v >= จาก[1])) && (b < ถึง[0] || (b === ถึง[0] && v <= ถึง[1]))
            return ข้อ.length > 0 && ข้อ.every(ใน)
          },
          [จาก, ถึง],
        ),
      10000,
    )
  }
  await แท็บ.waitForTimeout(600)
}

/**
 * ⭐ **ข้อบนจอ ⇒ ด่านวัดเอง ⛔ ไม่ถามหน้าเว็บ** ⇒ กล่องข้อที่ตาเห็นจริง และอยู่ในช่องอ่าน
 *   ⇒ ขอบบน = ขอบล่างของแถบบน หรือหัวคอลัมน์ที่หนึบอยู่ ⇒ ขอบล่าง = ขอบบนของแถวนำทางล่าง (⛔ ไม่นับแถบเรื่องเล่าเอง)
 */
async function ข้อบนจอ(แท็บ) {
  return แท็บ.evaluate(() => {
    let บน = document.querySelector('.pk-แถบบน')?.getBoundingClientRect().bottom || 0
    const หัว = document.querySelector('.pk-หัวคอลัมน์')
    if (หัว && getComputedStyle(หัว).position === 'sticky') บน = Math.max(บน, หัว.getBoundingClientRect().bottom)
    const ล่าง = document.querySelector('.pk-นำทางล่าง')?.getBoundingClientRect().top ?? innerHeight
    return [...document.querySelectorAll('.pk-ตัวบท [data-ข้อ]')]
      .filter((e) => e.getClientRects().length)
      .filter((e) => {
        const ก = e.getBoundingClientRect()
        return ก.bottom > บน + 1 && ก.top < ล่าง - 1
      })
      .map((e) => e.getAttribute('data-ข้อ').split(':').map(Number))
  })
}

/** เรื่องที่ควรมีปุ่ม ⇒ คิดจากข้อบนจอที่ด่านวัดเอง กับช่วงในทะเบียน
 *  ⭐ แถบมีปุ่มเดียว ⇒ ทับหลายเรื่อง ⇒ เรื่องที่มีข้อบนสุดของจอ ⇒ ไม่มี ⇒ เรื่องแรกที่ทับ (เคาะ 4 พ.ย. 2569) */
function เรื่องที่ควรมี(ข้อ, เล่ม) {
  if (!ข้อ.length) return []
  const บนสุด = ข้อ.reduce((a, b) => (ก่อนหรือเท่า(a, b) ? a : b))
  const ทับ = เรื่องทั้งหมด
    .filter((ร) => ร.เล่ม === เล่ม)
    .filter((ร) => ข้อ.some((x) => ก่อนหรือเท่า(ร.จาก, x) && ก่อนหรือเท่า(x, ร.ถึง)))
    .sort((a, b) => (ก่อนหรือเท่า(a.จาก, b.จาก) ? -1 : 1))
  const ที่อ่าน = ทับ.find((ร) => ก่อนหรือเท่า(ร.จาก, บนสุด) && ก่อนหรือเท่า(บนสุด, ร.ถึง)) || ทับ[0]
  return ที่อ่าน ? [ที่อ่าน.รหัส] : []
}

/** ข้อนี้อยู่ในเรื่องไหนสักเรื่องของเล่มนี้ไหม ⇒ ใช้คิดว่าแบบทดสอบควรมีปุ่มหรือไม่ ⇒ เรื่องติดกันแล้วท้ายเรื่องแรกไม่ใช่ที่ว่างเสมอ */
const อยู่ในเรื่อง = (เล่ม, x) => เรื่องทั้งหมด.some((ร) => ร.เล่ม === เล่ม && ก่อนหรือเท่า(ร.จาก, x) && ก่อนหรือเท่า(x, ร.ถึง))

/** ปุ่มเรื่องเล่าที่ตาเห็นบนแถบล่าง ⇒ รหัสเรื่องของแถบที่มันอยู่ */
