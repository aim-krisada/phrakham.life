// ⑫ เชิงอรรถ (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/168)
//   ⇒ ⭐ **ตัวเรื่องตัวอย่างอยู่ในด่านนี้เท่านั้น** ⇒ ดักคำตอบของ `/api/story/<เรื่องแรก>.json` แล้วใส่เลขเชิงอรรถ 3 ที่ (อันแรกถูกอ้าง 2 ครั้ง)
//     ⇒ ⛔ ไม่มีเรื่องจริงที่มีเชิงอรรถบนเว็บ (มก. 12:28-44 ถ้อยคำยังไม่อนุมัติ) ⇒ ⛔ ไม่แตะไฟล์ในที่เก็บ
//   ⇒ ใช้แป้นพิมพ์ล้วน ⇒ โฟกัสเลขยกตัวที่ 3 ⇒ Enter ⇒ โฟกัสต้องอยู่ที่เชิงอรรถนั้นและตาเห็น ⇒ Tab ⇒ ลิงก์ ↩ ⇒ Enter ⇒ กลับมาที่เลขเดิม (ตัวที่ 3 ⛔ ตัวแรก)
//   ⇒ เชิงอรรถอยู่ท้ายตัวเรื่อง นอก `data-ตัวเรื่องเล่า` ⇒ ⛔ มี `[^` เหลือบนจอ ⇒ ชื่อที่ได้ยินมีเลขที่ตาเห็น (SC 2.5.3) ⇒ ↩ กว้างและสูง ≥ 24 (SC 2.5.8) ⇒ axe ระดับ AA
// ---------------------------------------------------------------------------
async function ตรวจเชิงอรรถ(พัง) {
  const ปัญหา = []
  const { บริบท, แท็บ } = await เปิดแท็บ({ width: 375, height: 812 }, พัง)
  await บริบท.route(`**/api/story/${เรื่องแรก.รหัส}.json`, async (route) => {
    const ตอบ = await route.fetch()
    const ร = await ตอบ.json()
    const วลี = ร.ย่อหน้า[0].split(' ')
    วลี[0] += '[^1]'
    วลี[Math.floor(วลี.length / 2)] += '[^ข]'
    วลี[วลี.length - 1] += '[^1]'
    ร.ย่อหน้า = [วลี.join(' '), ...ร.ย่อหน้า.slice(1)]
    ร.เชิงอรรถ = [
      { ป้าย: '1', ข้อความ: 'เชิงอรรถตัวอย่างที่หนึ่ง ⇒ ด่านทดสอบเท่านั้น' },
      { ป้าย: 'ข', ข้อความ: 'เชิงอรรถตัวอย่างที่สอง' },
    ]
    await route.fulfill({ response: ตอบ, json: ร })
  })
  await เปิด(แท็บ, หน้าเรื่อง)
  if (!(await เปิดแผ่น(แท็บ))) {
    await บริบท.close()
    return ['กดปุ่มเรื่องเล่าแล้วแผ่น ⛔ ไม่เปิด']
  }
  await แท็บ.waitForTimeout(300)
  const รูป = await แท็บ.evaluate((ตัว) => {
    const d = document.querySelector(ตัว)
    const เลข = [...d.querySelectorAll('sup a[data-เลขเชิงอรรถ]')]
    const ส่วน = d.querySelector('[data-เชิงอรรถเรื่องเล่า]')
    const ย่อหน้า = [...d.querySelectorAll('[data-ตัวเรื่องเล่า]')]
    const กลับ = [...(ส่วน?.querySelectorAll('li a[data-กลับเชิงอรรถ]') || [])]
    return {
      เลข: เลข.map((a) => ({ ตา: a.textContent.trim(), ชื่อ: a.getAttribute('aria-label') || '', ไป: document.querySelector(a.getAttribute('href') || '#ไม่มี')?.closest('[data-เชิงอรรถเรื่องเล่า] li') ? 'เชิงอรรถ' : '' })),
      หัว: ส่วน?.querySelector('h2, h3, h4')?.textContent.trim() || '',
      ชื่อส่วน: ส่วน ? document.getElementById(ส่วน.getAttribute('aria-labelledby') || '')?.textContent.trim() || '' : '',
      อัน: ส่วน ? ส่วน.querySelectorAll('ol > li').length : 0,
      หลังเรื่อง: !!ส่วน && ย่อหน้า.every((p) => p.compareDocumentPosition(ส่วน) & Node.DOCUMENT_POSITION_FOLLOWING) && !ส่วน.closest('[data-ตัวเรื่องเล่า]'),
      ค้าง: ย่อหน้า.some((p) => p.textContent.includes('[^') || p.textContent.includes('เชิงอรรถตัวอย่าง')),
      กลับ: กลับ.map((a) => { const r = a.getBoundingClientRect(); return { ชื่อ: a.getAttribute('aria-label') || '', ก: r.width, ส: r.height } }),
    }
  }, แผ่น)
  const ตาเห็น = รูป.เลข.map((x) => x.ตา).join(',')
  if (ตาเห็น !== '1,2,1') ปัญหา.push(`เลขยกบนจอ ${ตาเห็น || 'ไม่มี'} ⇒ ต้องเป็น 1,2,1 ตามลำดับที่อ้าง`)
  if (รูป.เลข.some((x) => x.ไป !== 'เชิงอรรถ')) ปัญหา.push('เลขยกบางตัวไม่ได้ชี้ไปที่เชิงอรรถท้ายเรื่อง')
  if (รูป.เลข.some((x) => !x.ชื่อ.trim().endsWith(x.ตา))) ปัญหา.push('ชื่อที่ได้ยินของเลขยกไม่มีเลขที่ตาเห็น (SC 2.5.3)')
  if (!รูป.หลังเรื่อง || รูป.อัน !== 2) ปัญหา.push(`เชิงอรรถต้องอยู่ท้ายเรื่อง นอกตัวเรื่อง 2 อัน ⇒ ได้ ${รูป.อัน} อัน · อยู่ท้าย ${รูป.หลังเรื่อง}`)
  if (!รูป.หัว || รูป.ชื่อส่วน !== รูป.หัว) ปัญหา.push('ส่วนเชิงอรรถไม่มีหัวข้อที่เป็นชื่อของส่วน')
  if (รูป.ค้าง) ปัญหา.push('ตัวเรื่องบนจอยังมี [^ หรือเนื้อเชิงอรรถหลุดเข้าตัวเรื่อง')
  if (รูป.กลับ.length !== 2 || รูป.กลับ.some((x) => !x.ชื่อ.trim() || x.ก < 24 || x.ส < 24))
    ปัญหา.push(`ลิงก์ ↩ ต้องมีครบ 2 อัน มีชื่อที่ได้ยิน และกว้างสูง ≥ 24 ⇒ ได้ ${JSON.stringify(รูป.กลับ)}`)

  // ⭐ แป้นพิมพ์ล้วน ⇒ เลขยกตัวที่ 3 (อ้างเชิงอรรถ 1 ครั้งที่ 2) ⇒ Enter ⇒ Tab ⇒ Enter ⇒ ต้องกลับมาที่ตัวที่ 3
  const ที่โฟกัส = () =>
    แท็บ.evaluate((ตัว) => {
      const a = document.activeElement
      const ใน = document.querySelector(`${ตัว} .pk-ในแผ่นเรื่องเล่า`)
      const หัว = document.querySelector(`${ตัว} .pk-หัวแผ่นเรื่องเล่า`)
      const r = a?.getBoundingClientRect()
      const ก = ใน?.getBoundingClientRect()
      const ตาเห็น = !!r && !!ก && r.top >= (หัว?.getBoundingClientRect().bottom ?? ก.top) - 1 && r.bottom <= ก.bottom + 1
      const เลขทั้งหมด = [...document.querySelectorAll(`${ตัว} sup a[data-เลขเชิงอรรถ]`)]
      return {
        อะไร: a?.matches('[data-เชิงอรรถเรื่องเล่า] li') ? `เชิงอรรถ:${a.id}` : a?.matches('[data-กลับเชิงอรรถ]') ? 'กลับ' : เลขทั้งหมด.includes(a) ? `เลข:${เลขทั้งหมด.indexOf(a)}` : a?.tagName || '',
        ตาเห็น,
      }
    }, แผ่น)
  if (รูป.เลข.length === 3) {
    await แท็บ.locator(`${แผ่น} sup a[data-เลขเชิงอรรถ]`).nth(2).focus()
    await แท็บ.keyboard.press('Enter')
    await แท็บ.waitForTimeout(300)
    const ไป = await ที่โฟกัส()
    const ไอดีหนึ่ง = await แท็บ.locator(`${แผ่น} [data-เชิงอรรถเรื่องเล่า] li`).first().getAttribute('id')
    if (ไป.อะไร !== `เชิงอรรถ:${ไอดีหนึ่ง}` || !ไป.ตาเห็น) ปัญหา.push(`กด Enter ที่เลขยก 1 ⇒ โฟกัสไปที่ ${ไป.อะไร} ตาเห็น ${ไป.ตาเห็น} ⇒ ต้องอยู่ที่เชิงอรรถอันแรกและตาเห็น`)
    else {
      await แท็บ.keyboard.press('Tab')
      const ถึงกลับ = await ที่โฟกัส()
      if (ถึงกลับ.อะไร !== 'กลับ') ปัญหา.push(`จากเชิงอรรถกด Tab ⇒ ได้ ${ถึงกลับ.อะไร} ⇒ ต้องถึงลิงก์ ↩ ของเชิงอรรถนั้น`)
      else {
        await แท็บ.keyboard.press('Enter')
        await แท็บ.waitForTimeout(300)
        const กลับ = await ที่โฟกัส()
        if (กลับ.อะไร !== 'เลข:2' || !กลับ.ตาเห็น) ปัญหา.push(`กด ↩ ⇒ โฟกัสไปที่ ${กลับ.อะไร} ตาเห็น ${กลับ.ตาเห็น} ⇒ ต้องกลับมาที่เลขยกตัวที่กดมา (ตัวที่ 3) และตาเห็น`)
      }
    }
  }
  const ที่อยู่ = new URL(แท็บ.url())
  if (ที่อยู่.hash) ปัญหา.push(`กดเชิงอรรถแล้วที่อยู่หน้าเปลี่ยนเป็น ${ที่อยู่.hash} ⇒ ปุ่มย้อนกลับของเบราว์เซอร์จะพาไปผิดที่`)
  if (!(await แท็บ.locator(แผ่น).count())) ปัญหา.push('กดเชิงอรรถแล้วแผ่นเรื่องเล่าปิดไป')

  await แท็บ.addScriptTag({ path: createRequire(import.meta.url).resolve('axe-core/axe.min.js') })
  const ผิด = await แท็บ.evaluate(async (ตัว) => {
    const ร = await window.axe.run(document.querySelector(ตัว), {
      runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22a', 'wcag22aa'] },
      rules: { 'label-content-name-mismatch': { enabled: true } },
    })
    return ร.violations.map((v) => `${v.id} (${v.nodes.length})`)
  }, แผ่น)
  if (ผิด.length) ปัญหา.push(`axe ฟ้องแผ่นที่มีเชิงอรรถ ⇒ ${ผิด.join(' · ')}`)
  await บริบท.close()
  return ปัญหา
}
/** ⭐ โหมดพิสูจน์ ⇒ ยัดทีละชิ้น ⇒ ชิ้นไหนด่านไม่แดง = ตาบอดข้อนั้น */
const ตาบอด = []
for (const พัง of ทดสอบตัวเอง ? [['เลขเชิงอรรถไม่ไปไหน'], ['เชิงอรรถไม่มีทางกลับ']] : [[]]) {
  const ปัญหา = await ตรวจเชิงอรรถ(พัง)
  if (ปัญหา.length) ปัญหา.forEach((x) => ตก('⑫', `${พัง.join('') || 'เชิงอรรถ'} ⇒ ${x}`))
  else if (ทดสอบตัวเอง) ตาบอด.push(`⑫ ${พัง.join('')}`)
  else ผ่าน('⑫', 'เชิงอรรถตัวอย่าง ⇒ เลขยก 1 2 1 ชี้ท้ายเรื่อง ⇒ Enter ไปเชิงอรรถ ⇒ Tab ถึง ↩ ⇒ Enter กลับเลขเดิม ⇒ ที่อยู่หน้าไม่เปลี่ยน ⇒ axe ไม่ฟ้อง')
}

await เบราว์เซอร์.close()

