  //   ⇒ เรื่องที่ป้ายยาวเปิดด้วยช่วง `r=` ของมันเอง ⇒ ข้อบนจออยู่ในช่วงของเรื่องนั้นแน่ ⇒ ปุ่มเป็นของเรื่องนั้น
