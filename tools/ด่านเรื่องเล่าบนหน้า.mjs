    รหัส: ร['รหัส'],
    เล่ม,
    จาก: [Number(c1), Number(v1)],
    ถึง: [Number(c2), Number(v2)],
    ตัวเรื่อง: ส่วน.replace(/\[\^([^\]\s]+)\]/g, (_, ป้าย) => String(ลำดับเชิงอรรถ.indexOf(ป้าย) + 1)).replace(/\s+/g, ' ').trim(),
