async function ตั้งขั้น(แท็บ, ขั้น) {
  await แท็บ.evaluate((v) => document.documentElement.style.setProperty('--pk-fs', String(v)), ขั้น)
  await แท็บ.waitForTimeout(120)
}

/** ค่าที่วัดจากหน้าจริง ⇒ ⭐ อ่านจาก `getComputedStyle` กับกล่องบรรทัดจริง ⛔ ไม่ถามโค้ดของเว็บ */
const วัด = (แท็บ) =>
  แท็บ.evaluate(() => {
    // ⭐⭐ **นิยาม "ตัวอักษรที่กินความกว้าง"** ⇒ ตัวที่เลื่อนปลายปากกาไปทางขวา
    //   ⛔ ไม่นับสระบน สระล่าง วรรณยุกต์ (U+0E31 · U+0E34–U+0E3A · U+0E47–U+0E4E)
    //     ⇒ ไทยวางมันซ้อนบนหรือใต้พยัญชนะ ⇒ ⛔ ไม่กินความกว้างเลย
    //   ⛔ ไม่นับตัวกว้างศูนย์ (U+200B–U+200D · U+FEFF) ⇒ ซองตัวบทของเราแทรก U+200B
    //     ไว้ที่รอยคำเพื่อบอกจุดห่อบรรทัด ⇒ นับด้วยแล้ว **ตัวเลขพุ่งขึ้น 36%** (วัดเอง 8 ก.ย. 2569)
    //   ⇒ ⭐ นี่คือทางที่ทำให้ *"80 characters or glyphs"* ของ WCAG ใช้กับภาษาไทยที่ ⛔ ไม่มีช่องว่างได้
    const ไม่กินความกว้าง = /[ัิ-ฺ็-๎​-‍﻿]/
    const เลข = (v) => Math.round(parseFloat(v) * 100) / 100

    const พื้นจริง = (el) => {
      for (let n = el; n; n = n.parentElement) {
        const c = getComputedStyle(n).backgroundColor
        const m = /rgba?\(([^)]+)\)/.exec(c)
        if (m) {
          const p = m[1].split(',').map((x) => parseFloat(x))
          if (p.length < 4 || p[3] > 0.99) return [p[0], p[1], p[2]]
        }
      }
      return [255, 255, 255]
    }
    const สีหน้า = (el) => {
      const m = /rgba?\(([^)]+)\)/.exec(getComputedStyle(el).color)
      const p = m[1].split(',').map((x) => parseFloat(x))
      return [p[0], p[1], p[2]]
    }
    const ความสว่าง = ([r, g, b]) => {
      const c = [r, g, b]
        .map((v) => v / 255)
        .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
      return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
    }
    const ต่างสี = (el) => {
      const a = ความสว่าง(สีหน้า(el))
      const b = ความสว่าง(พื้นจริง(el))
      return Math.round(((Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05)) * 100) / 100
    }

    const ชิ้น = (sel) => {
      const el = document.querySelector(sel)
      if (!el) return null
      const s = getComputedStyle(el)
      return {
        ที่: sel,
        fs: เลข(s.fontSize),
        เท่าบรรทัด: เลข(parseFloat(s.lineHeight) / parseFloat(s.fontSize)),
        mb: เลข(s.marginBottom),
        mt: เลข(s.marginTop),
        กว้าง: เลข(el.getBoundingClientRect().width),
        สูงกล่อง: เลข(el.getBoundingClientRect().height),
        ต่างสี: ต่างสี(el),
        // ⭐ ความสว่างของ **หมึก** ⇒ ยิ่งน้อยยิ่งเข้ม ⇒ ใช้เทียบว่าใครจางกว่าใครโดย ⛔ ไม่ผ่านพื้น
        สว่างหมึก: Math.round(ความสว่าง(สีหน้า(el)) * 10000) / 10000,
      }
    }

    // ---- ตัวอักษรที่กินความกว้างต่อบรรทัด — นับจาก **กล่องบรรทัดจริง** ⛔ ไม่คำนวณจากความกว้าง
    let ต่อบรรทัด = null
    const ย่อหน้า = [...document.querySelectorAll('.pk-ช่องฉบับ, .pk-ไหล')]
      .filter((p) => (p.textContent || '').length > 150)
      .sort((a, b) => b.textContent.length - a.textContent.length)[0]
    if (ย่อหน้า) {
      const โหนด = [...ย่อหน้า.childNodes].find(
        (n) => n.nodeType === 3 && n.textContent.trim().length > 100,
      )
      if (โหนด) {
        const r = document.createRange()
        const แถว = new Map()
        const s = โหนด.textContent
        for (let i = 0; i < s.length; i++) {
          if (ไม่กินความกว้าง.test(s[i])) continue
          r.setStart(โหนด, i)
          r.setEnd(โหนด, i + 1)
          const b = r.getBoundingClientRect()
          if (!b.width && !b.height) continue
          const คีย์ = Math.round(b.top)
          แถว.set(คีย์, (แถว.get(คีย์) || 0) + 1)
        }
        // ⛔ **ตัดบรรทัดสุดท้ายทิ้ง** ⇒ มันสั้นตามธรรมชาติ ⇒ นับด้วยแล้วค่ากลางเพี้ยนลง
        const นับ = [...แถว.values()].slice(0, -1).sort((a, b) => a - b)
        if (นับ.length)
          ต่อบรรทัด = { กลาง: นับ[Math.floor(นับ.length / 2)], มากสุด: นับ[นับ.length - 1] }
      }
    }

    return {
      ต่อบรรทัด,
      คอลัมน์: ชิ้น('.pk-คอลัมน์'),
      ตัวบท: ชิ้น('.pk-ช่องฉบับ'),
      ข้อ: ชิ้น('.pk-ข้อ'),
      // ⛔ หมุดบทตัวแรกถูกกดระยะเว้นบนทิ้ง (`:first-child`) ⇒ ต้องวัดตัวที่สองขึ้นไป
      หมุดบท: ชิ้น('.pk-หมุดบท:not(:first-child)') || ชิ้น('.pk-หมุดบท'),
      // ⭐⭐ **3 กองข้างล่างเก็บ `null` ไว้ด้วย ⛔ ไม่กรองทิ้ง**
      //   ⇒ กรองทิ้งคือทางที่ทำให้ด่าน **เงียบตอนที่ควรดัง** ⇒ ใครเปลี่ยนชื่อคลาส ด่านจะข้ามไปเฉย ๆ
      //   ⇒ ตัวเรียกเป็นคนแดงเองถ้าเจอ `null` (ดูข้อ *ชิ้นที่ต้องมี*)
      //   ⚠️ `.pk-ชื่อคอลัมน์` (ใบงาน #102) ⇒ ถอดออกจากกองนี้แล้ว ⇒ ใบ #131 note_30489 ⇒ ชื่อเล่มกับบทบนหัวเป็นปุ่มชื่อย่อ ⇒ ปุ่ม ⛔ ต้องจาง
      //     ⇒ ⛔ `.pk-ฉบับที่เปิด` ถูกถอดพร้อมปุ่ม `ฉบับ` บนแถบบน ⇒ ชื่อฉบับอยู่ในหัวคอลัมน์แทน

      // ⭐ กลุ่ม ① ของที่ **โตตาม `--pk-fs`** ⇒ วัดด้วยจำนวนเท่าของตัวบท
      โตตามตัวบท: [
        ชิ้น('.pk-แถบบน .pk-ปุ่มแถบ'),
        ชิ้น('.pk-ลูกศรบท'),
        ชิ้น('.pk-ปุ่มตอนนี้'),
      ],
      // ⭐ กลุ่ม ② ของที่ **ตรึงเป็น `rem` โดยเจตนา** ⇒ วัดด้วยพื้นเป็นจุด
      //   ⇒ ⛔ ไม่ให้โตตาม เพราะจอ 320 จุดที่ 200% จะล้นขอบ (เหตุผลอยู่ในไฟล์ธีม)
      ตรึงเป็นrem: [ชิ้น('.pk-ชื่อเว็บ'), ชิ้น('.pk-ตราประทับ')],
      จางกว่าตัวบท: [ชิ้น('.pk-ตราประทับ')],
      // ⭐ ชื่อตอน ⇒ ใหญ่กว่าตัวบทและหมึกเต็ม (ใบงาน #140) ⇒ เกณฑ์อยู่ที่ `เท่าของชื่อตอน`
      ชื่อตอน: ชิ้น('.pk-หมุดบท'),
      เลขข้อ: ชิ้น('.pk-เลขข้อ:not(.pk-กันที่)'),
      // ⭐ จำนวนฉบับที่วางเทียบกันอยู่ ⇒ หน้าอ่านเป็นคนใส่ค่านี้ลง `--pk-กี่ฉบับ`
      //   ⇒ อ่านจากตัวแปรนั้นตรง ๆ ⛔ ไม่เดาเอง ⇒ คอลัมน์กว้างขึ้นตามจำนวนฉบับโดยตั้งใจ
      กี่ฉบับ: (() => {
        const el = document.querySelector('.pk-คอลัมน์')
        if (!el) return 1
        const n = Number(getComputedStyle(el).getPropertyValue('--pk-กี่ฉบับ'))
        return Number.isFinite(n) && n >= 1 ? n : 1
      })(),
      ล้นขอบ: document.documentElement.scrollWidth - document.documentElement.clientWidth,
      จำนวนข้อ: document.querySelectorAll('.pk-ข้อ, .pk-ข้อไหล').length,
    }
  })

