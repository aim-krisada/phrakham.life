/** `ชื่อของพัง` = กุญแจของ `ของพังหลายคอลัมน์` ⇒ `null` = ตรวจของจริง */
async function ตรวจหลายคอลัมน์(ชื่อของพัง) {
  const ตก = []
  const พูด = []
  const ใส่ของพัง = async (แท็บ) => {
    if (!ชื่อของพัง) return
    await แท็บ.addStyleTag({ content: ของพังหลายคอลัมน์[ชื่อของพัง] })
    await แท็บ.waitForTimeout(250)
  }
  const ถึงพื้น = เกณฑ์.พื้นต่อบรรทัดหลายคอลัมน์
  const ต้องแถวเดียว = new Set(เกณฑ์.จอที่ต้องวางแถวเดียว.map(([ก, n]) => `${ก}×${n}`))

  // ⭐ จอแคบกว่า 768 ⇒ ⛔ ไม่อยู่ในรายการ ⇒ จอแคบอ่านทีละฉบับเป็นค่าตั้งต้น (ใบ #76 · #97) ⛔ ไม่ถูกแตะ
  for (const [กว้าง, ขั้น] of [
    [768, 1],
    [1280, 1],
    [1920, 1],
    // ⭐ ข้อ 8.2 ⇒ ตัวอักษร 200% ⇒ พื้นต้องโตตาม ⇒ คอลัมน์ห่อเองแทนที่จะบีบบรรทัดให้สั้น
    [1920, 2],
    // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/174 ⇒ ขั้นเล็กสุดที่จอ 768 ⇒ ตัวเล็ก = ตัวต่อบรรทัดมากสุด ⇒ เพดาน 80 ตัวต้องยังถูกเฝ้า
    //   ⇒ เปลี่ยนเป็นฟอนต์ Noto แล้วตัวละตินกว้างกว่า Sarabun ⇒ คอลัมน์กว้างสุดของเว็บ (682 จุด) ที่ 100% ใส่ได้แค่ 79 ตัว ⇒ ของพัง *ปลดเพดานในช่อง*
    //     ⛔ เคยเกิน 80 (Sarabun ได้ 84) ⇒ ที่ 100% ⛔ มีจอไหนที่ของพังนี้ทำให้แดงได้แล้ว ⇒ ขั้น 85% ได้ตัวต่อบรรทัดมากขึ้นราว 1.18 เท่า
    //   ⇒ เพิ่มจอให้ของจริงตรวจด้วย ⇒ เข้มขึ้น ⛔ ไม่ใช่ผ่อน
    [768, 0.85],
  ]) {
    for (const n of [1, 2, 3, 4]) {
      if (ชื่อของพัง && !จอของของพัง[ชื่อของพัง].includes(`${กว้าง}×${ขั้น}×${n}`)) continue
      const ป้าย = `หลายคอลัมน์ · จอ ${กว้าง} · ${n} ฉบับ · ขั้น ${ขั้น * 100}%`
      const { ctx, แท็บ } = await เปิดหลายคอลัมน์(เบราว์เซอร์, ฐาน, กว้าง, n, ขั้น)
      try {
        await ใส่ของพัง(แท็บ)
        const คอ = await แท็บ.evaluate(วัดในหน้า)
        if (คอ.length !== n) {
          ตก.push(`${ป้าย} ⇒ เปิด ${n} ฉบับแต่เห็น ${คอ.length} คอลัมน์ ⇒ ⛔ ด่านนี้ตรวจอะไรไม่ได้`)
          continue
        }
        for (const c of คอ) {
          if (c.มากสุด === null) {
            ตก.push(`${ป้าย} ⇒ ${c.ฉบับ} นับตัวอักษรต่อบรรทัดไม่ได้ ⇒ หากล่องตัวบทที่ยาวพอไม่เจอ`)
            continue
          }
          if (c.มากสุด > เกณฑ์.เพดานต่อบรรทัด)
            ตก.push(
              `${ป้าย} ⇒ ${c.ฉบับ} บรรทัดยาวสุด ${c.มากสุด} ตัว (คอลัมน์ ${c.กว้าง} จุด) ⇒ เกินเพดาน ${เกณฑ์.เพดานต่อบรรทัด} ตัวของ WCAG SC 1.4.8`,
            )
          if (เกณฑ์.ฉบับไทย.includes(c.ฉบับ) && c.กลาง < ถึงพื้น)
            ตก.push(
              `${ป้าย} ⇒ ${c.ฉบับ} บรรทัดละ ${c.กลาง} ตัว (คอลัมน์ ${c.กว้าง} จุด) ⇒ ต่ำกว่าพื้น ${ถึงพื้น} ตัวของหลายคอลัมน์ ⇒ ต้องห่อลงแถวใหม่ ⛔ ไม่ใช่บีบ`,
            )
          if (c.ล้นขอบ > 1) ตก.push(`${ป้าย} ⇒ หน้าเลื่อนซ้ายขวาได้ ${c.ล้นขอบ} จุด ⇒ SC 1.4.10`)
        }
        const แถว = Math.max(...คอ.map((c) => c.แถวที่))
        if (ขั้น === 1 && ต้องแถวเดียว.has(`${กว้าง}×${n}`) && แถว > 1)
          ตก.push(
            `${ป้าย} ⇒ ห่อเป็น ${แถว} แถว (คอลัมน์ ${คอ.map((c) => c.กว้าง).join(' · ')} จุด) ⇒ จอนี้กว้างพอวางแถวเดียว ⇒ ด้านข้าง ⛔ ไม่ถูกใช้`,
          )
        พูด.push(
          `  ${ป้าย} ⇒ ${แถว} แถว · ` +
            คอ.map((c) => `${c.ฉบับ} ${c.กว้าง} จุด ${c.กลาง} (${c.มากสุด}) ตัว`).join(' · '),
        )
      } catch (e) {
        ตก.push(`${ป้าย} ⇒ ล้มระหว่างตรวจ ⇒ ${e.message}`)
      } finally {
        await ctx.close()
      }
    }
  }

  // ⭐⭐ **ตอนที่เอามาเทียบ ⛔ ห้ามถูกห่อไปอยู่ใต้ฝั่งหลัก** ⇒ ฝั่งหลักยาวไม่จบ ⇒ ผู้อ่านเลื่อนไปไม่ถึง
  //   ⇒ จอ 1280 · 1 ฉบับ + 3 ตอนเทียบ ⇒ ⛔ ก่อนใบ #102 ก็ห่ออยู่แล้ว ⇒ ข้อนี้คือของที่ใบนี้ซ่อมเพิ่ม
  if (!ชื่อของพัง || จอของของพัง[ชื่อของพัง].includes('เทียบ')) {
    const ป้าย = 'หลายคอลัมน์ · จอ 1280 · 1 ฉบับ + 3 ตอนเทียบ'
    const { ctx, แท็บ } = await เปิดหลายคอลัมน์(เบราว์เซอร์, ฐาน, 1280, 4, 1, 900, 'เทียบ')
    try {
      await ใส่ของพัง(แท็บ)
      const ห่อ = await แท็บ.evaluate(() => {
        const หลัก = document.querySelector('.pk-ฝั่งหลัก')?.getBoundingClientRect()
        return [...document.querySelectorAll('.pk-ตอนเทียบ')].filter(
          (s) => หลัก && s.getBoundingClientRect().top > หลัก.top + หลัก.height / 2,
        ).length
      })
      if (ห่อ)
        ตก.push(
          `${ป้าย} ⇒ ตอนเทียบ ${ห่อ} ตอนถูกห่อไปอยู่ใต้ฝั่งหลัก ⇒ ฝั่งหลักต่อบทไปไม่จบ ⇒ ผู้อ่านเลื่อนไปไม่ถึง`,
        )
      else พูด.push(`  ${ป้าย} ⇒ ทุกตอนอยู่แถวเดียวกับฝั่งหลัก`)
    } catch (e) {
      ตก.push(`${ป้าย} ⇒ ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }
  return [...ตก, ...พูด]
}

