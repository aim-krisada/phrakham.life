const เบราว์เซอร์ = await chromium.launch()

/** เปิดหน้าอ่านให้พร้อมวัด ⇒ ⛔ ไม่วัดก่อนโค้ดของเว็บทำงานเสร็จ */
async function เปิดหน้า(viewport, หลอก) {
  const ctx = await เบราว์เซอร์.newContext({ viewport })
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}${เริ่มที่}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('.pk-ช่องฉบับ')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, {
    timeout: 30000,
  })
  await แท็บ.waitForTimeout(350)
  // ⭐⭐ **ต้องเลื่อนให้บทที่สองถูกต่อเข้ามาก่อน** ⇒ ⛔ ไม่งั้นวัดรอยต่อบทไม่ได้เลย
  //   หน้าที่สร้างไว้ล่วงหน้ามีบทเดียว ⇒ หมุดบทตัวเดียวนั้นเป็น `:first-child`
  //   ⇒ กฎ `.pk-หมุดบท:first-child` กดระยะเว้นบนเป็น 0 ⇒ **วัดตัวนั้นได้ 0 เสมอ แม้กฎถูก**
  //   ⇒ ⛔ **ที่พังจริงถ้าไม่เลื่อน** ⇒ ด่านจะแดงตลอดโดยบอกเหตุผิด
  for (let i = 0; i < 40; i++) {
    if (await แท็บ.evaluate(() => document.querySelectorAll('[data-หมุดบท]').length > 1)) break
    await แท็บ.evaluate(() => window.scrollBy(0, window.innerHeight * 0.8))
    await แท็บ.waitForTimeout(150)
  }
  if (!(await แท็บ.evaluate(() => document.querySelectorAll('[data-หมุดบท]').length > 1))) {
    await ctx.close()
    throw new Error('⛔ เลื่อนจนสุดแล้วยังมีหมุดบทตัวเดียว ⇒ การต่อบทถัดไปพัง ⇒ วัดรอยต่อบทไม่ได้')
  }
  await แท็บ.evaluate(() => window.scrollTo(0, 0))
  await แท็บ.waitForTimeout(200)
  if (หลอก) await ยัดของพัง(แท็บ)
  return { ctx, แท็บ }
}

