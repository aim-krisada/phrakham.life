const อ่านหัว = (แท็บ) =>
  แท็บ.evaluate(() =>
    [...document.querySelectorAll('.pk-หัวช่อง')]
      .filter((h) => h.offsetParent !== null)
      .map((h) => {
        const ชิ้น = []
        // ⭐ ใบ #131 note_30489 ⇒ ป้ายอยู่ในชื่อที่ได้ยินของปุ่มเปลี่ยนตอน ⇒ ⛔ นับเป็นชิ้นแยก ⇒ ใช้อ่านชื่อเล่มกับบทอย่างเดียว
        const ป้าย = h.querySelector('.pk-ที่ของช่อง')
        for (const el of h.querySelectorAll('.pk-ปุ่มตอนเทียบ > *')) {
          const ชนิด = el.getAttribute('data-ปุ่ม') || (el.querySelector('select') ? 'ฉบับ' : '?')
          ชิ้น.push({ ชนิด, el: el.querySelector('select') || el })
        }
        const วัด = ชิ้น
          .filter((x) => x.el.getClientRects().length && getComputedStyle(x.el).display !== 'none')
          .map(({ ชนิด, el }) => {
            const r = el.getBoundingClientRect()
            return {
              ชนิด,
              ซ้าย: Math.round(r.left),
              บน: Math.round(r.top),
              สูง: Math.round(r.height),
              ตัวอักษร: parseFloat(getComputedStyle(el).fontSize),
            }
          })
        // ⭐ ลำดับที่ตาอ่าน ⇒ แถวเดียวกัน (ขอบบนต่างกันไม่เกินครึ่งปุ่ม) เรียงซ้ายไปขวา
        const เรียง = [...วัด].sort((a, b) => (Math.abs(a.บน - b.บน) > 20 ? a.บน - b.บน : a.ซ้าย - b.ซ้าย))
        return {
          ป้าย: (ป้าย?.textContent || '').replace(/\s+/g, ' ').trim(),
          ลำดับ: เรียง.map((x) => x.ชนิด),
          วัด,
          ในตอนเทียบ: !!h.closest('.pk-ตอนเทียบ'),
        }
      }),
  )

async function ตรวจ(พัง) {
  const ตก = []
  const พูด = []

  // ---------------------------------------------------------------- ① ② ③ ④ จอกว้าง 3 คอลัมน์
  {
    const { ctx, แท็บ } = await เปิด(ที่อยู่หลายคอลัมน์, 1280, ['TCV', 'THKJV'], พัง)
    try {
      const หัว = await อ่านหัว(แท็บ)
      if (หัว.length !== 3)
        ตก.push(`① เปิด 2 ฉบับ + 1 ตอนเทียบ แต่เห็นหัว ${หัว.length} หัว ⇒ ต้องมี 3 หัว ⛔ ทุกคอลัมน์ต้องมีหัว`)
      if (!หัว.some((h) => h.ในตอนเทียบ) || !หัว.some((h) => !h.ในตอนเทียบ))
        ตก.push('① ⛔ ไม่เจอหัวของทั้งสองชนิด (คอลัมน์ฉบับ · ตอนเทียบ) ⇒ เทียบหน้าตากันไม่ได้')
      for (const h of หัว) {
        const ที่ = h.ในตอนเทียบ ? 'หัวตอนเทียบ' : 'หัวคอลัมน์ฉบับ'
        if (String(h.ลำดับ) !== String(ลำดับที่ต้องเป็น))
          ตก.push(`① ${ที่} “${h.ป้าย}” เรียงเป็น ${h.ลำดับ.join(' · ')} ⇒ ต้องเป็น ${ลำดับที่ต้องเป็น.join(' · ')}`)
        if (!/[ก-๙]/.test(h.ป้าย) || !/\d/.test(h.ป้าย))
          ตก.push(`① ${ที่} มีป้าย “${h.ป้าย}” ⇒ ต้องบอกชื่อเล่มและบท`)
        for (const x of h.วัด)
          if (x.ชนิด !== 'ป้าย' && x.สูง < 44) ตก.push(`② ${ที่} ปุ่ม ${x.ชนิด} สูง ${x.สูง} จุด ⇒ ต้องไม่ต่ำกว่า 44 จุด`)
      }
      // ① ใบ #131 ⇒ หัว ⛔ มี ‹ ›
      const ลูกศร = await ลูกศรบนหัว(แท็บ)
      if (ลูกศร.length)
        ตก.push(`① จอ 1280 · 3 คอลัมน์ ⇒ หัวยังมี ‹ › ${ลูกศร.join(' · ')} ⇒ ‹ › อยู่ที่แถบล่างที่เดียว (ใบ #131)`)
      // ② ขนาดเดียวกันทุกหัว ⇒ เทียบทีละชนิด
      for (const ชนิด of ลำดับที่ต้องเป็น) {
        const ค่า = หัว.map((h) => h.วัด.find((x) => x.ชนิด === ชนิด)).filter(Boolean)
        const ตัว = new Set(ค่า.map((x) => x.ตัวอักษร))
        const สูง = new Set(ค่า.map((x) => x.สูง))
        if (ตัว.size > 1) ตก.push(`② ${ชนิด} ตัวอักษรไม่เท่ากันทุกหัว ⇒ ${[...ตัว].join(' · ')} จุด`)
        if (ชนิด !== 'ป้าย' && สูง.size > 1) ตก.push(`② ${ชนิด} สูงไม่เท่ากันทุกหัว ⇒ ${[...สูง].join(' · ')} จุด`)
      }
      // ③ 2 คอลัมน์ขึ้นไป ⇒ ทุกหัวมีปุ่มปิดที่ตาเห็น
      for (const h of หัว)
        if (!h.ลำดับ.includes('ปิดคอลัมน์')) ตก.push(`③ หัว “${h.ป้าย}” ⛔ ไม่มีปุ่มปิดที่ตาเห็น ทั้งที่เปิดอยู่ ${หัว.length} คอลัมน์`)
      // ④ แถบบน ⛔ ไม่มีปุ่มที่ซ้ำกับหัวคอลัมน์แรก
      const บนแถบ = await แท็บ.evaluate(() =>
        [...document.querySelectorAll('.pk-แถบบน button')].map((b) => (b.textContent || '').replace(/\s+/g, ' ').trim()),
      )
      const ซ้ำ = บนแถบ.filter((x) => x === 'เลือกบท' || /^ฉบับ/.test(x) || x.startsWith('เปลี่ยนตอน'))
      if (ซ้ำ.length) ตก.push(`④ แถบบนยังมีปุ่ม ${ซ้ำ.join(' · ')} ⇒ ซ้ำกับหัวคอลัมน์ ⛔ ห้ามของอย่างเดียวกันมี 2 ที่ (ข้อ 6.2)`)
      พูด.push(`  จอ 1280 · 3 คอลัมน์ ⇒ ${หัว.map((h) => `“${h.ป้าย}” ${h.ลำดับ.join('·')}`).join(' | ')}`)
      พูด.push(`  แถบบน ⇒ ${บนแถบ.join(' · ')}`)
    } catch (e) {
      ตก.push(`①②③④ ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  // ---------------------------------------------------------------- ③ คอลัมน์เดียว ⇒ ⛔ มีปุ่มปิดที่กดได้ (ใบ #122)
  {
    const { ctx, แท็บ } = await เปิด(ที่อยู่คอลัมน์เดียว, 1280, ['TCV'], พัง)
    try {
      const หัว = await อ่านหัว(แท็บ)
      if (หัว.length !== 1) ตก.push(`③ เปิดฉบับเดียวแต่เห็นหัว ${หัว.length} หัว ⇒ คอลัมน์แรกต้องมีหัวเสมอ`)
      // ⭐ ใบ #122 ⇒ × ยังเห็นแต่กดไม่ได้ (`aria-disabled`) ⇒ นับเฉพาะ × ที่กดได้ ⇒ × ที่กดไม่ได้ตรวจละเอียดที่ `tools/ด่านปุ่มปิดคอลัมน์สุดท้าย.mjs`
      const ปิดได้ = await แท็บ.locator('[data-ปุ่ม="ปิดคอลัมน์"]:not([aria-disabled="true"])').count()
      if (ปิดได้) ตก.push(`③ เหลือคอลัมน์เดียวแต่มีปุ่มปิดที่กดได้ ${ปิดได้} ปุ่ม ⛔ ปิดแล้วหน้าว่าง (ข้อ 6.1 · ใบ #122)`)
      else พูด.push('  คอลัมน์เดียว ⇒ มีหัว ⇒ × กดไม่ได้')
      const ลูกศร = await ลูกศรบนหัว(แท็บ)
      if (ลูกศร.length) ตก.push(`① จอ 1280 · คอลัมน์เดียว ⇒ หัวยังมี ‹ › ${ลูกศร.join(' · ')} ⇒ ‹ › อยู่ที่แถบล่างที่เดียว (ใบ #131)`)
    } catch (e) {
      ตก.push(`③ ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  // ---------------------------------------------------------------- ① จอแคบกับเส้น 768 ⇒ หัว ⛔ มี ‹ › (ใบ #131)
  // ⭐ 2 คอลัมน์ (ฉบับ + ตอนอื่น) ⇒ ไม่เกินเพดานของจอ 320 · 375 (2 คอลัมน์ ⇒ ใบ #131 note_30332 นับจากที่ว่าง) ⇒ ได้หัวทั้งสองชนิดในหน้าเดียว
  for (const กว้าง of จอไม่มีลูกศร) {
    const { ctx, แท็บ } = await เปิด(ที่อยู่หลายคอลัมน์, กว้าง, ['TCV'], พัง)
    try {
      const หัวทั้งหมด = await แท็บ.locator('.pk-หัวช่อง').count()
      if (หัวทั้งหมด < 2) ตก.push(`① จอ ${กว้าง} ⇒ เปิดฉบับ + ตอนอื่นแต่เจอหัว ${หัวทั้งหมด} หัว ⇒ ตรวจลูกศรไม่ได้ครบ`)
      const ลูกศร = await ลูกศรบนหัว(แท็บ)
      if (ลูกศร.length) ตก.push(`① จอ ${กว้าง} ⇒ หัวยังมี ‹ › ${ลูกศร.join(' · ')} ⇒ ‹ › อยู่ที่แถบล่างที่เดียว (ใบ #131)`)
      // ⭐ ทางเปลี่ยนบทยังมีครบ ⇒ ‹ › ของแถบล่าง · *เปลี่ยนตอน* ของทุกหัว
      const ล่าง = await แท็บ.locator('[data-ปุ่ม="บทก่อนล่าง"], [data-ปุ่ม="บทถัดล่าง"]').count()
      const เปลี่ยนตอน = await แท็บ.locator('.pk-หัวช่อง [data-ปุ่ม="เปลี่ยนตอน"]').count()
      if (!ล่าง) ตก.push(`① จอ ${กว้าง} ⇒ แถบล่าง ⛔ ไม่มี ‹ › ⇒ ถอดจากหัวแล้วต้องเหลือที่แถบล่าง`)
      if (เปลี่ยนตอน !== หัวทั้งหมด) ตก.push(`① จอ ${กว้าง} ⇒ หัว ${หัวทั้งหมด} หัวแต่มี *เปลี่ยนตอน* ${เปลี่ยนตอน} ปุ่ม ⇒ ทุกหัวต้องเปลี่ยนตอนของตัวเองได้`)
      พูด.push(`  จอ ${กว้าง} · 2 คอลัมน์ ⇒ หัว ${หัวทั้งหมด} หัว ⛔ ไม่มี ‹ › · แถบล่างมี ‹ › ${ล่าง} ปุ่ม · เปลี่ยนตอน ${เปลี่ยนตอน} ปุ่ม`)
    } catch (e) {
      ตก.push(`① จอ ${กว้าง} ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  // ---------------------------------------------------------------- ⑤ จอแคบ ⇒ แถบหนึบห้ามสูงขึ้น ⇒ แถบบนรวมหัวที่หนึบ (ใบ #131 note_30365 ข้อ 3.1)
  for (const กว้าง of [320, 375])
    for (const [ชุด, ฉบับ, วาง] of [
      ['ฉบับเดียว', ['TCV'], 'ทีละฉบับ'],
      ['ขนานกัน 2 ฉบับ', ['TCV', 'THKJV'], 'ขนานกัน'],
    ]) {
      const { ctx, แท็บ } = await เปิด('/read/JHN?c=1', กว้าง, ฉบับ, พัง, วาง)
      try {
        // ⭐ เลื่อนลงกลางบท ⇒ หัวที่หนึบค้างอยู่ใต้แถบ ⇒ ⛔ ไม่รอเป็นเวลาตายตัว ⇒ รอ 2 เฟรม
        const ผล = await แท็บ.evaluate(async () => {
          const ข้อ = document.getElementById('ข้อ-1-20')
          window.scrollTo(0, window.scrollY + ข้อ.getBoundingClientRect().top - innerHeight / 2)
          await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))
          const แถบ = document.querySelector('.pk-แถบบน').getBoundingClientRect()
          let ล่าง = แถบ.bottom
          for (const หัว of document.querySelectorAll('.pk-หัวคอลัมน์')) {
            const r = หัว.getBoundingClientRect()
            // ⭐ หัวที่ค้างอยู่ใต้แถบ ⇒ ขอบบนอยู่ที่ขอบล่างของแถบพอดี ⇒ นับรวม
            if (['sticky', 'fixed'].includes(getComputedStyle(หัว).position) && r.top <= แถบ.bottom + 1.5 && r.bottom > แถบ.bottom)
              ล่าง = Math.max(ล่าง, r.bottom)
          }
          return { แถบ: Math.round(แถบ.height * 10) / 10, รวม: Math.round(ล่าง * 10) / 10 }
        })
        if (ผล.รวม > เพดานแถบบนจอแคบ + 0.5)
          ตก.push(`⑤ จอ ${กว้าง} · ${ชุด} ⇒ แถบบนรวมหัวที่หนึบสูง ${ผล.รวม} จุด ⇒ สูงกว่าก่อนใบ #102 (${เพดานแถบบนจอแคบ} จุด) ⛔ ห้ามสูงขึ้น`)
        พูด.push(`  จอ ${กว้าง} · ${ชุด} ⇒ แถบบน ${ผล.แถบ} · รวมหัวที่หนึบ ${ผล.รวม} จุด (เพดานก่อนใบ #102 ${เพดานแถบบนจอแคบ})`)
      } catch (e) {
        ตก.push(`⑤ จอ ${กว้าง} · ${ชุด} ล้มระหว่างตรวจ ⇒ ${e.message}`)
      } finally {
        await ctx.close()
      }
    }
  return { ตก, พูด }
}

const ของจริง = await ตรวจ(null)
for (const x of ของจริง.พูด) console.log(x)

let พลาด = ของจริง.ตก.length > 0
if (ของจริง.ตก.length) {
  console.error(`\n⛔ หัวคอลัมน์ไม่ผ่าน — ${ของจริง.ตก.length} รายการ:`)
  for (const x of ของจริง.ตก) console.error('  - ' + x)
}

if (ทดสอบตัวเอง && !พลาด) {
  for (const [ชื่อ, พัง] of Object.entries(ของพัง)) {
    const ผล = await ตรวจ(พัง)
    const จับ = ผล.ตก.filter((x) => x.startsWith(พัง.ข้อ))
    console.log(`${จับ.length ? '✅' : '⛔'} ยัด *${ชื่อ}* ⇒ ข้อ ${พัง.ข้อ} ${จับ.length ? `แดง ${จับ.length} รายการ ⇒ เช่น ${จับ[0]}` : '⛔ ไม่แดง'}`)
    if (!จับ.length) พลาด = true
  }
  if (พลาด) console.error('\n⛔ โหมดพิสูจน์: ยัดของพังแล้วด่านยังไม่เห็นบางชิ้น ⇒ ด่านตายบางส่วน')
  else console.log(`\n✅ โหมดพิสูจน์: ด่านหัวคอลัมน์จับของพังได้ครบ ${Object.keys(ของพัง).length} ชิ้น`)
}

await เบราว์เซอร์.close()
if (พลาด) process.exit(1)
if (!ทดสอบตัวเอง) console.log('\n✅ หัวคอลัมน์หน้าตาเดียวกันทุกคอลัมน์ · ไม่มี ‹ › บนหัวทุกจอ · คอลัมน์เดียว × กดไม่ได้ · แถบบนไม่ซ้ำ ไม่สูงขึ้น')
