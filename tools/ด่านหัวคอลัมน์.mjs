const เบราว์เซอร์ = await chromium.launch()

async function เปิด(ที่อยู่, กว้าง, ฉบับ, พัง, วาง = '') {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: 900 } })
  await ctx.addInitScript(
    ([ฉ, ว]) => {
      try {
        if (!sessionStorage.getItem('pk-ด่านหัว')) {
          localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
          // ⭐ ใบ #131 ⇒ ข้อ ⑤ วัดแบบขนานกันด้วย ⇒ ตั้งการวางจอแคบเฉพาะชุดที่ขอ ⇒ ชุดเดิมไม่แตะ
          //   ⇒ ใบ #131 note_30367 ⇒ การวางย้ายไปช่อง `วางคอลัมน์` ⇒ ตั้งทั้ง 2 ช่อง ⇒ เปลี่ยนแค่ทางตั้งค่า ⛔ ไม่แตะเกณฑ์
          if (ว)
            localStorage.setItem(
              'phrakham.view',
              JSON.stringify({ วางจอแคบ: ว, วางคอลัมน์: ว === 'ขนานกัน' ? 'ซ้ายขวา' : ว }),
            )
          sessionStorage.setItem('pk-ด่านหัว', '1')
        }
      } catch {}
    },
    [ฉบับ, วาง],
  )
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}${ที่อยู่}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('.pk-หัวคอลัมน์ .pk-หัวช่อง')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  // ⭐ ใบ #131 note_30367 ⇒ จอแคบวางบนล่าง ⇒ หัวของคอลัมน์คนละบทอยู่แถวหัวที่หนึบ (`.pk-หัวคู่`) ⇒ ⛔ ไม่มีกล่อง `.pk-ตอนเทียบ` ⇒ รอที่ใดที่หนึ่ง ⇒ เปลี่ยนแค่ที่รอ
  if (ที่อยู่.includes('p=')) await แท็บ.waitForSelector('.pk-ตอนเทียบ .pk-หัวช่อง, .pk-หัวคู่', { timeout: 15000 })
  // ⭐ ใบ #131 คำขอรวมที่ 3 ⇒ รอหน้านิ่ง ⛔ ไม่รอเป็นเวลาตายตัว (ของเดิมรอ 500 กับ 200 มิลลิวินาที)
  await รอหน้านิ่ง(แท็บ)
  if (พัง?.ลูกศรเดิม && (พัง.ลูกศรเดิม === 'แคบ') === กว้าง < 768)
    await แท็บ.evaluate(() => {
      for (const กลุ่ม of document.querySelectorAll('.pk-หัวช่อง .pk-ปุ่มตอนเทียบ')) {
        const เลข = (กลุ่ม.getAttribute('aria-label') || '').replace(/\D+/g, '')
        const ทำ = (ชนิด, ตา, เสียง) => {
          const b = document.createElement('button')
          b.type = 'button'
          b.className = 'pk-ปุ่มเทียบ'
          b.setAttribute('data-ปุ่ม', ชนิด)
          b.innerHTML = `<span aria-hidden="true">${ตา}</span><span class="pk-เฉพาะเสียง">${เสียง} คอลัมน์ที่ ${เลข}</span>`
          return b
        }
        const กลาง = กลุ่ม.querySelector('[data-ปุ่ม="เปลี่ยนตอน"]')
        กลาง?.before(ทำ('บทก่อน', '‹', 'บทก่อนหน้า'))
        กลาง?.after(ทำ('บทถัด', '›', 'บทถัดไป'))
      }
    })
  if (พัง?.css) await แท็บ.addStyleTag({ content: พัง.css })
  if (พัง?.ปุ่มบนแถบ)
    await แท็บ.evaluate((ชื่อ) => {
      const ปุ่ม = document.createElement('button')
      ปุ่ม.className = 'pk-ปุ่มแถบ'
      ปุ่ม.textContent = ชื่อ
      document.querySelector('.pk-แถบบน .pk-ปุ่มบนแถบ')?.prepend(ปุ่ม)
    }, พัง.ปุ่มบนแถบ)
  if (พัง) await รอหน้านิ่ง(แท็บ)
  return { ctx, แท็บ }
}

/**
 * ⭐ ‹ › ที่อยู่ในหัวคอลัมน์ ⇒ นับทั้งที่ตาเห็นและที่ซ่อน ⇒ คืนรายการ `ป้ายหัว: สิ่งที่เจอ`
 *   ⇒ จับได้ 3 ทาง ⇒ `data-ปุ่ม` เป็นบทก่อนหรือบทถัด · ตัวหนังสือมี ‹ › · ชื่อที่ได้ยินมี *บทก่อนหน้า* *บทถัดไป*
 *   ⇒ ⛔ ไม่ได้พึ่งชื่อคลาสหรือ `data-ปุ่ม` อย่างเดียว ⇒ ใครใส่ลูกศรกลับด้วยหน้าตาใหม่ก็ยังแดง
 */
const ลูกศรบนหัว = (แท็บ) =>
  แท็บ.evaluate(() =>
    [...document.querySelectorAll('.pk-หัวช่อง')].flatMap((h) => {
      const ป้าย = (h.querySelector('.pk-ที่ของช่อง')?.textContent || '').replace(/\s+/g, ' ').trim()
      return [...h.querySelectorAll('button, a, [role="button"]')]
        .filter((el) => {
          const ชนิด = el.getAttribute('data-ปุ่ม') || ''
          const คำ = el.textContent || ''
          return /^บท(ก่อน|ถัด)$/.test(ชนิด) || /[‹›]/.test(คำ) || /บทก่อนหน้า|บทถัดไป/.test(คำ + (el.getAttribute('aria-label') || ''))
        })
        .map((el) => `“${ป้าย}” ${el.getAttribute('data-ปุ่ม') || (el.textContent || '').replace(/\s+/g, ' ').trim()}`)
    }),
  )

