// **นี่คือด่าน ⛔ ไม่ใช่รายงาน** ⇒ ตกแล้วคืนรหัสไม่เป็นศูนย์
//
// **ทำไมต้องมี** ⇒ `tools/ด่านหัวข้อย่อยบนหน้า.mjs` เปิดเบราว์เซอร์ดูได้แค่มาระโก 1
//   ⇒ หัวข้อกลางข้อ (TCV 17 อันในพันธสัญญาเดิม) กับหัวข้อที่ตามด้วยบรรทัดกวี (TCV 142 อัน) ⛔ ไม่อยู่ในบทนั้น
//   ⇒ ด่านนี้ยิงฟังก์ชันบริสุทธิ์ของ `app/utils/หัวข้อย่อย.ts` ตรง ๆ กับ **ทุกบททั้งเล่ม** ⇒ ท่าเดียวกับ `tools/ตรวจจัดย่อหน้า.mjs`
//
// **ข้อที่ตรวจ** ⇒ ทุกฉบับที่ซองมีหัวข้อ × ทุกบท
//   ① **แยกตามย่อหน้า** ⇒ ผ่ารอยย่อหน้าของฉบับ + รอยหัวข้อ ⇒ หัวข้อทุกอันเปิดย่อหน้าได้ 1 ย่อหน้าพอดี ⇒ ตัวบทครบทุกตัวอักษร
//   ② **ไหลต่อเนื่อง** ⇒ ผ่ารอยหัวข้ออย่างเดียว ⇒ หัวข้อทุกอันเปิดตอนได้ 1 ตอนพอดี ⇒ ตัวบทครบทุกตัวอักษร
//   ③ **แถวหัวข้อตอนเทียบ** ⇒ TCV คู่ THKJV ทุกบท ⇒ หัวข้อทุกอันอยู่บนหน้า 1 ครั้ง (แถวหัวข้อ หรือในช่อง)
//      ⇒ แถวย่อหน้าเดิมอยู่ครบตามลำดับเดิม ⇒ แถวหัวข้อมีเฉพาะเหนือแถวที่ฉบับใดฉบับหนึ่งเปิดด้วยหัวข้อ
//
// **วิธีพิสูจน์ว่าด่านนี้แดงได้จริง**
//   node --experimental-strip-types tools/ตรวจหัวข้อย่อย.mjs --ทดสอบตัวเอง
//   ⇒ ยัดของพัง 2 แบบ ⇒ ก. จับคู่หัวข้อกับย่อหน้าโดยลืมตำแหน่งกลางข้อ ⇒ ① ต้องแดง
//                      ข. แทรกแถวหัวข้อแต่ทิ้งหัวข้อที่อยู่กลางแถว ⇒ ③ ต้องแดง
//
// รัน  node --experimental-strip-types tools/ตรวจหัวข้อย่อย.mjs

import { readFileSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'
import { จัดย่อหน้า, จับคู่ย่อหน้า } from '../app/utils/ย่อหน้า.ts'
import { รอยของหัวข้อ, หัวข้อของย่อหน้า, แทรกแถวหัวข้อ } from '../app/utils/หัวข้อย่อย.ts'

const ราก = fileURLToPath(new URL('..', import.meta.url))
const อ่าน = (p) => JSON.parse(gunzipSync(readFileSync(ราก + p)).toString('utf8'))
const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')

let ซอง
try {
  ซอง = อ่าน('_พ่น/รอยย่อหน้า.json.gz')
} catch {
  console.error('⛔ ยังไม่มี _พ่น/รอยย่อหน้า.json.gz ⇒ สั่ง py -3.14 tools/สร้างรอยย่อหน้า.py ก่อน')
  process.exit(1)
}
if (!Object.keys(ซอง.หัวข้อ || {}).length) {
  console.error('⛔ ซองรอยย่อหน้าไม่มีช่อง หัวข้อ ⇒ ตัวพ่นรุ่นเก่า หรือหัวข้อหายทั้งซอง')
  process.exit(1)
}
const เนื้อบท = อ่าน('_data/เนื้อบท.json.gz')

/** ข้อของฉบับหนึ่งในบทหนึ่ง ⇒ รูปเดียวกับที่หน้าอ่านส่งเข้า `จัดย่อหน้า` */
function ข้อของ(ฉบับ, กุญแจ) {
  const ของบท = เนื้อบท['บท'][กุญแจ]?.[ฉบับ]
  if (!ของบท) return []
  const บท = Number(กุญแจ.split('/')[1])
  return Object.keys(ของบท)
    .sort((a, b) => Number(a) - Number(b))
    .map((n) => ({ บท, เลข: n, ป้าย: n, ชิ้น: [{ ตัวหนังสือ: ของบท[n], พระเยซู: false }] }))
}
const ตัวบทของ = (ย่อ) => ย่อ.map((ย) => ย.ท่อน.map((ท) => ท.ชิ้น.map((ช) => ช.ตัวหนังสือ).join('')).join('')).join('')

/** ①② ⇒ คืนรายการที่พัง ⇒ `จับคู่` คือฟังก์ชันที่ถูกตรวจ ⇒ โหมดพิสูจน์ส่งแบบผิดเข้ามา */
function ตรวจผ่า(จับคู่) {
  const ตก = []
  const นับ = { หัวข้อ: 0, กลางข้อ: 0 }
  for (const [ฉ, ของฉบับ] of Object.entries(ซอง.หัวข้อ)) {
    for (const [กุญแจ, หัว] of Object.entries(ของฉบับ)) {
      const ข้อ = ข้อของ(ฉ, กุญแจ)
      if (!ข้อ.length) continue
      const เดิม = ข้อ.map((x) => x.ชิ้น[0].ตัวหนังสือ).join('')
      const มีเลข = new Set(ข้อ.map((x) => Number(x.เลข)))
      const ควร = หัว.filter((ห) => มีเลข.has(ห.ข้อ))
      นับ.หัวข้อ += ควร.length
      นับ.กลางข้อ += ควร.filter((ห) => ห.หลังอักษร > 0).length
      for (const [ชื่อ, รอย] of [
        ['① แยกตามย่อหน้า', [...(ซอง.ฉบับ[ฉ]?.[กุญแจ] || []), ...รอยของหัวข้อ(หัว)]],
        ['② ไหลต่อเนื่อง', รอยของหัวข้อ(หัว)],
      ]) {
        const ย่อ = จัดย่อหน้า(ข้อ, รอย)
        if (ตัวบทของ(ย่อ) !== เดิม) ตก.push(`${ชื่อ} ${ฉ} ${กุญแจ} ⇒ ตัวบทไม่ครบหรือไม่ตรง`)
        const ได้ = จับคู่(ย่อ, หัว).filter(Boolean)
        const ขาด = ควร.filter((ห) => !ได้.includes(ห))
        if (ขาด.length || ได้.length !== ควร.length)
          ตก.push(`${ชื่อ} ${ฉ} ${กุญแจ} ⇒ หัวข้อบนหน้า ${ได้.length} อัน ⇒ ซองมี ${ควร.length} อัน ⇒ หาย เช่น ${ขาด[0] ? `${ขาด[0].ข้อ}#${ขาด[0].หลังอักษร} "${ขาด[0].ตัวหนังสือ}"` : '-'}`)
      }
    }
  }
  return { ตก, นับ }
}

/** ③ ⇒ TCV คู่ THKJV ⇒ `แทรก` คือฟังก์ชันที่ถูกตรวจ */
function ตรวจแถว(แทรก) {
  const ตก = []
  const นับ = { บท: 0, แถวหัวข้อ: 0, ในช่อง: 0 }
  const คู่ = ['TCV', 'THKJV']
  for (const กุญแจ of Object.keys(เนื้อบท['บท'])) {
    const คอลัมน์ = คู่.map((ฉ) => {
      const หัว = ซอง.หัวข้อ[ฉ]?.[กุญแจ] || []
      const ย่อ = จัดย่อหน้า(ข้อของ(ฉ, กุญแจ), [...(ซอง.ฉบับ[ฉ]?.[กุญแจ] || []), ...รอยของหัวข้อ(หัว)])
      return { ย่อ, หัว: หัวข้อของย่อหน้า(ย่อ, หัว) }
    })
    if (!คอลัมน์.some((ค) => ค.หัว.some(Boolean))) continue
    นับ.บท++
    const กลุ่ม = จับคู่ย่อหน้า(คอลัมน์.map((ค) => ค.ย่อ))
    const { แถว, ในช่อง } = แทรก(กลุ่ม, คอลัมน์.map((ค) => ค.ย่อ), คอลัมน์.map((ค) => ค.หัว))
    const เดิม = แถว.filter((x) => !x.หัวข้อ)
    if (เดิม.length !== กลุ่ม.length || เดิม.some((x, i) => x !== กลุ่ม[i]))
      ตก.push(`③ ${กุญแจ} ⇒ แถวย่อหน้าเดิมไม่ครบหรือสลับที่`)
    คอลัมน์.forEach((ค, i) => {
      const ควร = ค.หัว.filter(Boolean)
      const ได้ = [
        ...แถว.filter((x) => x.หัวข้อ?.[i]).map((x) => x.หัวข้อ[i]),
        ...[...ในช่อง.entries()].filter(([k]) => k.startsWith(`${i}|`)).map(([, v]) => v),
      ]
      นับ.แถวหัวข้อ += แถว.filter((x) => x.หัวข้อ?.[i]).length
      นับ.ในช่อง += [...ในช่อง.keys()].filter((k) => k.startsWith(`${i}|`)).length
      if (ได้.length !== ควร.length || ควร.some((ห) => !ได้.includes(ห)))
        ตก.push(`③ ${คู่[i]} ${กุญแจ} ⇒ หัวข้อบนหน้า ${ได้.length} อัน ⇒ ควรมี ${ควร.length} อัน`)
    })
    แถว.forEach((x, k) => {
      if (!x.หัวข้อ) return
      const ใต้ = แถว[k + 1]
      const ถูก = ใต้ && !ใต้.หัวข้อ && x.หัวข้อ.every((ห, i) => !ห || คอลัมน์[i].หัว[คอลัมน์[i].ย่อ.indexOf(ใต้.ช่อง[i][0])] === ห)
      if (!ถูก) ตก.push(`③ ${กุญแจ} ⇒ แถวหัวข้อที่ ${k} ⛔ อยู่เหนือย่อหน้าที่หัวข้อนั้นเปิด`)
    })
  }
  return { ตก, นับ }
}

if (ทดสอบตัวเอง) {
  let ผ่าน = true
  // ก. ลืมตำแหน่งกลางข้อ ⇒ จับคู่ด้วยเลขข้ออย่างเดียว ⇒ หัวข้อกลางข้อไปเกาะย่อหน้าต้นข้อ หรือหาย
  const ผิดก = (ย่อ, หัว) => {
    const ตาม = new Map((หัว || []).map((ห) => [`${ห.ข้อ}#0`, ห]))
    return ย่อ.map((ย) => (ย.ท่อน[0] ? ตาม.get(`${ย.ท่อน[0].เลข}#0`) || null : null))
  }
  const ก = ตรวจผ่า(ผิดก)
  console.log(ก.ตก.length ? `✅ ก. ลืมตำแหน่งกลางข้อ ⇒ ① แดงตามคาด ${ก.ตก.length} จุด ⇒ ${ก.ตก[0]}` : '⛔ ก. ลืมตำแหน่งกลางข้อ ⇒ ⛔ ไม่แดง')
  ผ่าน &&= ก.ตก.length > 0
  // ข. ทิ้งหัวข้อที่อยู่กลางแถว
  const ผิดข = (...x) => ({ ...แทรกแถวหัวข้อ(...x), ในช่อง: new Map() })
  const ข = ตรวจแถว(ผิดข)
  console.log(ข.ตก.length ? `✅ ข. ทิ้งหัวข้อกลางแถว ⇒ ③ แดงตามคาด ${ข.ตก.length} จุด ⇒ ${ข.ตก[0]}` : '⛔ ข. ทิ้งหัวข้อกลางแถว ⇒ ⛔ ไม่แดง')
  ผ่าน &&= ข.ตก.length > 0
  process.exit(ผ่าน ? 0 : 1)
}

const ผ = ตรวจผ่า(หัวข้อของย่อหน้า)
const แ = ตรวจแถว(แทรกแถวหัวข้อ)
console.log(`①② หัวข้อที่ตรวจ ${ผ.นับ.หัวข้อ.toLocaleString()} อัน · กลางข้อ ${ผ.นับ.กลางข้อ} อัน`)
console.log(`③ บทที่ TCV คู่ THKJV มีหัวข้อ ${แ.นับ.บท.toLocaleString()} บท ⇒ ขึ้นแถวหัวข้อ ${แ.นับ.แถวหัวข้อ.toLocaleString()} · อยู่ในช่อง ${แ.นับ.ในช่อง.toLocaleString()}`)
const ตก = [...ผ.ตก, ...แ.ตก]
if (ตก.length) {
  console.log(`⛔ ตก ${ตก.length} จุด`)
  for (const x of ตก.slice(0, 20)) console.log(`   ${x}`)
  process.exit(1)
}
if (!ผ.นับ.กลางข้อ) {
  console.log('⛔ ไม่มีหัวข้อกลางข้อให้ตรวจเลย ⇒ ① ⛔ ได้ตรวจกรณีที่ยากที่สุด')
  process.exit(1)
}
console.log('✅ หัวข้อทุกอันไปถึงที่ของมันครั้งเดียว และตัวบทครบทุกตัวอักษร')
