def โหลดสคริปต์(ชื่อไฟล์):
    """โหลดสคริปต์ข้าง ๆ มาใช้ ⛔ import ตรง ๆ ไม่ได้ เพราะ Python แปลง ำ ในชื่อโมดูล
    เป็น ํ + า (NFKC) แล้วหาไฟล์ไม่เจอ"""
    ที่อยู่ = Path(__file__).parent / ชื่อไฟล์
    spec = importlib.util.spec_from_file_location(ที่อยู่.stem, ที่อยู่)
    มอดูล = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(มอดูล)
    return มอดูล


