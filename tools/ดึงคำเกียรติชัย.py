def กลุ่มของลำดับ(ลำดับ):
    """คืนชื่อกลุ่มความถี่ของคำลำดับนั้น ⇒ ลำดับในตารางเรียงจากความถี่มากไปน้อยอยู่แล้ว"""
    ถึง = 0
    for ชื่อ, จำนวน in กลุ่มความถี่:
        ถึง += จำนวน
        if ลำดับ <= ถึง:
            return ชื่อ
    return ""

# ช่องคำในตารางขึ้นต้นด้วยเลขลำดับ + จุด + ช่องว่าง
# ⛔ ต้องมีช่องว่างหลังจุด ไม่งั้นเลขร้อยละอย่าง 3.198 จะโดนจับไปด้วย
ช่องคำ = re.compile(r"^(\d{1,4})\.\s+(\S.*)$")
เลขล้วน = re.compile(r"^[\d,]+$")
ร้อยละล้วน = re.compile(r"^\d+\.\d+$")
# เลขเชิงอรรถที่ห้อยท้ายคำ เช่น แล้ว(เสร็จ)1 ⇒ ตัดออกจากตัวคำ แต่จดไว้ว่ามี
# ⛔ ต้องไม่มีช่องว่างคั่น ไม่งั้นคำจริงที่ลงท้ายด้วยเลข เช่น "ช่อง 7" จะโดนตัดไปด้วย
เชิงอรรถท้ายคำ = re.compile(r"(?<=[^\s\d])(\d)$")
วงเล็บท้ายคำ = re.compile(r"^(.*?)\s*\(([^()]*)\)\s*$")


def อ่านช่องทั้งหมด(เอกสาร):
    """คืนรายการข้อความทุกบรรทัดในตาราง 1 เรียงตามลำดับที่ไฟล์วางไว้"""
    นับซ่อม = Counter()
    บรรทัด = []
    for i in range(หน้าตาราง1[0] - 1, หน้าตาราง1[1]):
        for _, ข้อความ in ดึงคำพื้นฐาน.อ่านบรรทัด(เอกสาร[i], นับซ่อม):
            บรรทัด.append(ข้อความ)
    return บรรทัด, นับซ่อม


def ดึงตาราง(เอกสาร):
    """คืน {ลำดับ: (คำเต็ม, จำนวนครั้ง, ร้อยละ)} — จำนวนกับร้อยละคือบรรทัดถัดจากช่องคำ

    ⚠️ หัวข้อในเนื้อความก็ขึ้นต้นด้วย "เลข. " เหมือนช่องคำ (เช่น "1. รายการคำศัพท์พื้นฐาน…")
    ⇒ กันด้วยการบังคับว่าต้องมีบรรทัดจำนวนครั้งตามมา หัวข้อจึงหลุดออกไปเอง
    """
    บรรทัด, นับซ่อม = อ่านช่องทั้งหมด(เอกสาร)
    ออก = {}
    for j, ข้อความ in enumerate(บรรทัด):
        m = ช่องคำ.match(ข้อความ)
        if not m:
            continue
        ลำดับ = int(m.group(1))
        if ลำดับ in ออก or not (1 <= ลำดับ <= คำที่เล่มบอก):
            continue
        # คำที่ยาวเกินช่องจะขึ้นบรรทัดใหม่ (เช่น "526. เปรียบ/" + "เปรียบเทียบ")
        # ⇒ เก็บบรรทัดต่อเนื่องมาต่อท้าย จนกว่าจะเจอบรรทัดตัวเลข ซึ่งคือช่องจำนวนครั้ง
        คำเต็ม, จำนวน, ร้อยละ = m.group(2).strip(), "", ""
        for ถัดไป in บรรทัด[j + 1 : j + 8]:
            if เลขล้วน.match(ถัดไป):
                จำนวน = ถัดไป.replace(",", "")
            elif จำนวน and ร้อยละล้วน.match(ถัดไป):
                ร้อยละ = ถัดไป
                break
            elif จำนวน or ช่องคำ.match(ถัดไป):
                break
            else:
                คำเต็ม += ถัดไป.strip()
        if not จำนวน:
            continue
        ออก[ลำดับ] = (คำเต็ม, จำนวน, ร้อยละ)
    return ออก, นับซ่อม


def แยกวงเล็บ(คำเต็ม):
    """แยก "ที่(อนุพากย์)" ⇒ ("ที่", "อนุพากย์", "") · คืน (คำ, กำกับ, เลขเชิงอรรถ)"""
    เชิงอรรถ = ""
    m = เชิงอรรถท้ายคำ.search(คำเต็ม)
    if m:
        เชิงอรรถ, คำเต็ม = m.group(1), คำเต็ม[: m.start()]
    m = วงเล็บท้ายคำ.match(คำเต็ม.strip())
    if m:
        return m.group(1).strip(), m.group(2).strip(), เชิงอรรถ
    return คำเต็ม.strip(), "", เชิงอรรถ


def เขียนไฟล์(ตาราง, ปลายทาง):
    ปลายทาง.mkdir(parents=True, exist_ok=True)
    หัว = ("ลำดับ\tคำ\tกำกับหน้าที่\tเชิงอรรถ\tจำนวนครั้ง\tร้อยละ\tกลุ่มความถี่"
           "\tคำเต็มตามต้นฉบับ")
    แถว = [หัว]
    for ลำดับ in sorted(ตาราง):
        คำเต็ม, จำนวน, ร้อยละ = ตาราง[ลำดับ]
        คำ, กำกับ, เชิงอรรถ = แยกวงเล็บ(คำเต็ม)
        แถว.append(f"{ลำดับ}\t{คำ}\t{กำกับ}\t{เชิงอรรถ}\t{จำนวน}\t{ร้อยละ}"
                   f"\t{กลุ่มของลำดับ(ลำดับ)}\t{คำเต็ม}")
    ไฟล์ = ปลายทาง / "คำพื้นฐาน-เกียรติชัย-1033.tsv"
    ไฟล์.write_text("\n".join(แถว) + "\n", encoding="utf-8", newline="\n")
    return ไฟล์


def เทส(ตาราง):
    """เทสที่เครื่องตัดสินได้เอง ⇒ ครบทุกลำดับ · มีคำทุกช่อง · ผลรวมร้อยละใกล้ 100"""
    ตก = []
    ขาด = [n for n in range(1, คำที่เล่มบอก + 1) if n not in ตาราง]
    if ขาด:
        ตก.append(f"ลำดับที่ขาดไป {len(ขาด)} ตัว: {ขาด[:20]}")
    เกิน = [n for n in ตาราง if n > คำที่เล่มบอก]
    if เกิน:
        ตก.append(f"มีลำดับเกิน {คำที่เล่มบอก}: {เกิน}")
    ว่าง = [n for n, (ค, _, _) in ตาราง.items() if not ค]
    if ว่าง:
        ตก.append(f"ช่องคำว่าง {len(ว่าง)} แถว: {ว่าง[:20]}")
    ไม่มีจำนวน = [n for n, (_, จ, _) in ตาราง.items() if not จ]
    if ไม่มีจำนวน:
        ตก.append(f"ไม่มีจำนวนครั้ง {len(ไม่มีจำนวน)} แถว: {ไม่มีจำนวน[:20]}")
    รวมร้อยละ = sum(float(r) for _, _, r in ตาราง.values() if r)
    print(f"  ลำดับ 1-{max(ตาราง)} ครบ {len(ตาราง)} แถว")
    print(f"  ผลรวมร้อยละ {รวมร้อยละ:.2f} (เล่มบอกว่าทุกคำรวมกันคือ 100)")
    # ความถี่ต้องเรียงจากมากไปน้อยตามที่เล่มจัด ⇒ ผิดลำดับ = จับคู่เลขกับคำผิดแถว
    ความถี่ = [int(จ) for _, (_, จ, _) in sorted(ตาราง.items()) if จ]
    ผิดลำดับ = [i for i in range(1, len(ความถี่)) if ความถี่[i] > ความถี่[i - 1]]
    if ผิดลำดับ:
        ตก.append(f"ความถี่ไม่เรียงจากมากไปน้อย {len(ผิดลำดับ)} จุด: {ผิดลำดับ[:20]}")
    if abs(รวมร้อยละ - 100) > 1.5:
        ตก.append(f"ผลรวมร้อยละ {รวมร้อยละ:.2f} ห่างจาก 100 เกิน 1.5")
    # ⭐ เทสของการแบ่งกลุ่มความถี่ ⇒ ยืนยันสองทางจากตัวเล่มเอง
    รวมกลุ่ม = sum(n for _, n in กลุ่มความถี่)
    if รวมกลุ่ม != คำที่เล่มบอก:
        ตก.append(f"จำนวนคำของ 5 กลุ่มรวมกันได้ {รวมกลุ่ม} ⛔ ไม่เท่า {คำที่เล่มบอก}")
    # เทียบด้วยรูปที่ตัดเลขเชิงอรรถออกแล้ว เพราะหน้า pdf 39 ไล่ชื่อโดยไม่มีเลขเชิงอรรถ
    กลุ่มแรก = []
    for n in range(1, กลุ่มความถี่[0][1] + 1):
        if n in ตาราง:
            คำ, กำกับ, _ = แยกวงเล็บ(ตาราง[n][0])
            กลุ่มแรก.append(f"{คำ}({กำกับ})" if กำกับ else คำ)
    if กลุ่มแรก != คำกลุ่มที่1ตามเล่ม:
        ตก.append(f"คำในกลุ่มที่ 1 ไม่ตรงกับที่เล่มไล่ชื่อไว้\n     ได้ {กลุ่มแรก}\n"
                  f"     เล่มบอก {คำกลุ่มที่1ตามเล่ม}")
    else:
        print(f"  ผ่าน คำในกลุ่มที่ 1 ทั้ง {len(กลุ่มแรก)} คำ ตรงกับที่หน้า pdf 39 ไล่ชื่อไว้")
    for ข้อความ in ตก:
        print("  ⛔ ตก", ข้อความ)
    print("  ผ่านทุกข้อ" if not ตก else f"  ตก {len(ตก)} ข้อ")
    return 1 if ตก else 0


def main():
    pdf = Path(sys.argv[1])
    เอกสาร = fitz.open(pdf)
    ตาราง, นับซ่อม = ดึงตาราง(เอกสาร)
    if "--ตรวจ" in sys.argv:
        sys.exit(เทส(ตาราง))
    ไฟล์ = เขียนไฟล์(ตาราง, Path(sys.argv[2]))
    มีวงเล็บ = sum(1 for ค, _, _ in ตาราง.values() if แยกวงเล็บ(ค)[1])
    มีขีดทับ = sum(1 for ค, _, _ in ตาราง.values() if "/" in ค)
    print(f"{ไฟล์.name}  {len(ตาราง)} แถว  ลำดับ 1-{max(ตาราง)}")
    print(f"  มีวงเล็บกำกับหน้าที่ {มีวงเล็บ} คำ · เขียนคู่ด้วยขีดทับ {มีขีดทับ} คำ")
    print("  ที่ซ่อม:", dict(นับซ่อม))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
