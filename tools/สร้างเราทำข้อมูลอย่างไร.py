def วัดตารางแมป(ทาง, ค่ากุญแจ):
    """ตารางสองช่องของ MACULA ที่บอกว่าชิ้นคำไหนใช้ความหมายไหน"""
    หัว, f = อ่านตาราง(ทาง)
    แถว = 0
    ตัวอย่าง = None
    for บรรทัด in f:
        ช่อง = บรรทัด.rstrip("\r\n").split("\t")
        แถว += 1
        if ช่อง[0] == ค่ากุญแจ:
            ตัวอย่าง = ช่อง[1]
    f.close()
    if ตัวอย่าง is None:
        ตาย(f"หา {ค่ากุญแจ} ในตารางแมป {ทาง} ไม่เจอ")
    return {"แถว": แถว, "หัวตาราง": หัว, "ตัวอย่าง": ตัวอย่าง}


def วัดพจนานุกรม(ทาง, หารหัสความหมาย=None, หารหัสรายการ=None):
    """นับรายการกับความหมายในพจนานุกรมของ UBS แล้วหยิบตัวอย่างที่ขอ"""
    ของ = json.load(io.open(ทาง, encoding="utf-8"))
    ความหมายทั้งหมด = 0
    พบ = {}
    for รายการ in ของ:
        for รูปตั้งต้น in รายการ["BaseForms"]:
            for ความหมาย in รูปตั้งต้น["LEXMeanings"]:
                ความหมายทั้งหมด += 1
                if หารหัสความหมาย and ความหมาย.get("LEXID") == หารหัสความหมาย:
                    พบ["ที่อยู่ข้อกี่จุด"] = len(ความหมาย.get("LEXReferences") or [])
                if หารหัสรายการ and ความหมาย.get("LEXEntryCode") == หารหัสรายการ:
                    พบ["รหัสความหมายที่ได้"] = ความหมาย.get("LEXID")
    if (หารหัสความหมาย or หารหัสรายการ) and not พบ:
        ตาย(f"หาตัวอย่างในพจนานุกรม {ทาง} ไม่เจอ")
    return {"รายการ": len(ของ), "ความหมาย": ความหมายทั้งหมด, "ตัวอย่าง": พบ}


def วัดยูเอสเอกซ์(โฟลเดอร์, เล่มตัวอย่าง, ข้อตัวอย่าง):
    """นับไฟล์กับจำนวนข้อของตัวบทที่เจ้าของให้มาเป็นรูป USX"""
    ไฟล์ทั้งหลาย = sorted(โฟลเดอร์.glob("*.usx"))
    if not ไฟล์ทั้งหลาย:
        ตาย(f"ไม่มีไฟล์ .usx ใน {โฟลเดอร์}")
    ข้อรวม = 0
    for ทาง in ไฟล์ทั้งหลาย:
        ราก = ET.parse(ทาง).getroot()
        ข้อรวม += sum(1 for e in ราก.iter("verse") if e.get("sid"))
    # ⚠️ บรรทัดเดียวมีป้ายข้อได้หลายอัน ⇒ ป้ายปิดของข้อก่อนหน้าอยู่ก่อนป้ายเปิดของข้อที่เราหา
    #    ⇒ ต้องเดินถอยหลังจากคำว่า sid ไปหาป้ายที่ครอบมันจริง ๆ ⛔ ไม่หยิบป้ายแรกของบรรทัด
    ป้ายตัวอย่าง = None
    for บรรทัด in io.open(โฟลเดอร์ / f"{เล่มตัวอย่าง}.usx", encoding="utf-8"):
        ที่ = บรรทัด.find(f'sid="{ข้อตัวอย่าง}"')
        if ที่ >= 0:
            หัว = บรรทัด.rfind("<verse", 0, ที่)
            ป้ายตัวอย่าง = บรรทัด[หัว:บรรทัด.index(">", ที่) + 1]
            break
    if not ป้ายตัวอย่าง:
        ตาย(f"หาป้ายข้อ {ข้อตัวอย่าง} ในไฟล์ {เล่มตัวอย่าง}.usx ไม่เจอ")
    return {
        "ไฟล์": len(ไฟล์ทั้งหลาย),
        "ไบต์": sum(t.stat().st_size for t in ไฟล์ทั้งหลาย),
        "ข้อ": ข้อรวม,
        "ป้ายตัวอย่าง": ป้ายตัวอย่าง,
    }


