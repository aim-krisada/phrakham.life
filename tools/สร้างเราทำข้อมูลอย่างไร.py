# ⭐ ช่อง `\qs …\qs*` ที่มีป้ายซ้อน (ป้ายที่ขึ้นต้นด้วยเครื่องหมายบวก) คือจุดที่ตัวแปลงอ่านไม่ออก
#   ⇒ รูปนี้ลอกท่าจับของ `tools/แปลงusfmเป็นusx.mjs` ตัวแปร `ช่องqs` มา ⇒ ⛔ ไม่ใช่กฎใหม่
#   ⇒ เจ้าของความจริงเรื่อง "ทำไมตัวแปลงอ่านไม่ออก" อยู่ในหัวไฟล์นั้น ⛔ ไม่เขียนซ้ำที่นี่
รูปช่องqs = None


def นับจุดที่ต้องเติมมือ(โฟลเดอร์usfm):
    """ไล่ไฟล์ USFM ของฉบับนั้นทั้งกอง แล้วนับจุดที่ตัวแปลงมาตรฐานอ่านไม่ออก

    คืนจำนวนรวม กับรายเล่มว่าเล่มไหนกี่จุด ⇒ ตัวเลขมาจากไฟล์ดิบตอนรัน ⛔ ไม่พิมพ์ด้วยมือ
    """
    global รูปช่องqs
    import re
    if รูปช่องqs is None:
        รูปช่องqs = re.compile(r"\\qs(?![A-Za-z0-9*])([\s\S]*?)\\qs\*")
    if not โฟลเดอร์usfm.exists():
        ตาย(f"ไม่มีโฟลเดอร์ {โฟลเดอร์usfm}")
    รายเล่ม = {}
    for ทาง in sorted(โฟลเดอร์usfm.glob("*.usfm")):
        เนื้อ = io.open(ทาง, encoding="utf-8").read()
        จำนวน = sum(1 for ช in รูปช่องqs.finditer(เนื้อ) if "\\+" in ช.group(1))
        if จำนวน:
            รายเล่ม[ทาง.name] = จำนวน
    return {"รวม": sum(รายเล่ม.values()), "รายไฟล์": รายเล่ม}


