#     วันที่เจ้าของจัดบรรทัดใหม่ ข้อความตรงนี้ขยับตามเอง
def วัดรูปร่างไฟล์(ทาง, คำค้น, ช่องที่หา):
    """วัดว่าไฟล์นี้ขึ้นบรรทัดกี่ตัว และช่องที่ขอ อยู่ห่างจากคำค้นไปกี่ตัวอักษร"""
