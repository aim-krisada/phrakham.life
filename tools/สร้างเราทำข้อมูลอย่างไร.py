    ที่ช่องที่หา = เนื้อ.find(ช่องที่หา, ที่ค่า)
    if ที่ชื่อช่องแรก < 0 or ที่ช่องที่หา < 0:
        ตาย(f"หาช่อง {ช่องที่หา} ต่อจาก {คำค้น} ใน {ทาง} ไม่เจอ")
