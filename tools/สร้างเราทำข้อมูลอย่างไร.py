def เขียน(ของ):
    ไฟล์ผล.parent.mkdir(parents=True, exist_ok=True)
    io.open(ไฟล์ผล, "w", encoding="utf-8", newline="\n").write(
        json.dumps(ของ, ensure_ascii=False, indent=1) + "\n"
    )


def main():
    ตัวเลือก = argparse.ArgumentParser(description="สร้างไฟล์ JSON ของหน้า เราทำข้อมูลอย่างไร")
    ตัวเลือก.add_argument("--ตรวจ", action="store_true",
                          help="สร้างใหม่แล้วเทียบกับไฟล์ที่คอมมิตไว้ ⇒ ไม่ตรงคือแดง")
    คำสั่ง = ตัวเลือก.parse_args()

    ของ = สร้าง()
    ข้อความ = json.dumps(ของ, ensure_ascii=False, indent=1) + "\n"

    if คำสั่ง.ตรวจ:
        if not ไฟล์ผล.exists():
            ตาย(f"ยังไม่มีไฟล์ {ทาง(ไฟล์ผล)} ⇒ สั่งสร้างก่อน")
        เดิม = io.open(ไฟล์ผล, encoding="utf-8", newline="").read()
        if เดิม != ข้อความ:
            ตาย(f"ของที่สร้างใหม่ไม่ตรงกับ {ทาง(ไฟล์ผล)} ⇒ สั่งสร้างใหม่แล้วคอมมิต")
        print(f"✅ {ทาง(ไฟล์ผล)} ตรงกับของที่สร้างใหม่")
        return

    เขียน(ของ)
    ขั้นรวม = sum(len(แหล่ง["ขั้นตอน"]) for แหล่ง in ของ["แหล่ง"])
    print(f"✅ เขียน {ทาง(ไฟล์ผล)} แล้ว ⇒ {len(ของ['แหล่ง'])} แหล่ง {ขั้นรวม} ขั้นตอน")


if __name__ == "__main__":
    main()
