def ตอนหนึ่งของคำอธิบาย(ไฟล์, หัวข้อ):
    """หยิบหัวข้อหนึ่งหัวข้อออกมาจากคำอธิบายหัวไฟล์ของสคริปต์อื่น

    ⭐ ใช้เมื่อความจริงเรื่องนั้น **มีเจ้าของอยู่แล้ว** ⇒ หยิบของเขามาโชว์ ⛔ ไม่เขียนใหม่
       ⇒ วันที่เขาแก้คำอธิบาย หน้านี้ขยับตามเอง ⛔ ไม่มีสำเนาค้างรุ่นเก่า
    """
    if not ไฟล์.exists():
        ตาย(f"ไม่มีไฟล์ {ไฟล์}")
    ก้อน = ast.get_docstring(ast.parse(io.open(ไฟล์, encoding="utf-8").read()))
    if not ก้อน:
        ตาย(f"ไฟล์ {ไฟล์} ไม่มีคำอธิบายหัวไฟล์")
    เก็บ = []
    กำลังเก็บ = False
    for บรรทัด in ก้อน.splitlines():
        if บรรทัด.startswith("## "):
            if กำลังเก็บ:
                break
            กำลังเก็บ = หัวข้อ in บรรทัด
            if กำลังเก็บ:
                continue
        if กำลังเก็บ:
            เก็บ.append(บรรทัด)
    if not เก็บ:
        ตาย(f"หาหัวข้อ {หัวข้อ} ในคำอธิบายของ {ไฟล์} ไม่เจอ")
    return "\n".join(เก็บ).strip()


def ชื่อหัวข้อของคำอธิบาย(ไฟล์, หัวข้อ):
    """หยิบ **บรรทัดหัวข้อ** ของหัวไฟล์นั้นมาทั้งบรรทัด ⇒ ใช้เป็นชื่อเรื่องของข้อ

    ⭐ ทำให้เลขที่อยู่ในชื่อหัวข้อ เช่นจำนวนชิ้นที่ค้าง มาจากไฟล์เจ้าของตอนรัน
       ⛔ ไม่ต้องพิมพ์เลขนั้นซ้ำที่นี่ ⇒ วันที่เขาแก้เลข ชื่อเรื่องขยับตามเอง
    """
    if not ไฟล์.exists():
        ตาย(f"ไม่มีไฟล์ {ไฟล์}")
    ก้อน = ast.get_docstring(ast.parse(io.open(ไฟล์, encoding="utf-8").read())) or ""
    for บรรทัด in ก้อน.splitlines():
        if บรรทัด.startswith("## ") and หัวข้อ in บรรทัด:
            return บรรทัด[3:].replace("⚠️", "").strip()
    ตาย(f"หาหัวข้อ {หัวข้อ} ในคำอธิบายของ {ไฟล์} ไม่เจอ")


