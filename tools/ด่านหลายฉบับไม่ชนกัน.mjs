/**
 * ⭐ อ่าน **ของที่วาดออกมาจริง** ⛔ ไม่ได้ดูว่าโค้ดมีคลาสอะไร
 * คืนของดิบทั้งหมดมาให้ฝั่ง node ตัดสิน ⇒ ข้อความบอกเหตุจะได้เขียนที่เดียว
 */
const เก็บของจริง = (แท็บ, เลขบท) =>
  แท็บ.evaluate((บท) => {
    const เห็น = (el) => el.getClientRects().length > 0
    const กรอบ = (el) => {
      const r = el.getBoundingClientRect()
      return { ซ้าย: r.left, ขวา: r.right }
    }

    // ---------------- ① กล่องของแต่ละฉบับ ⇒ รวมช่วงซ้ายขวาของฉบับเดียวกันเข้าด้วยกัน
    // ⭐ ใบ #102 ⇒ วางไม่พอแล้วฉบับห่อลงแถวใหม่ในข้อเดียวกัน ⇒ ฉบับคนละแถวอยู่ช่วงซ้ายขวาเดียวกันได้โดยไม่ชน
    //   ⇒ เก็บกรอบเต็มของทุกกล่องไว้ด้วย ⇒ ฝั่ง node ตัดสินว่า *ทับกันทั้งสองแกน* ⛔ ไม่ใช่แค่แกนนอน
    const ช่วงของฉบับ = {}
    const กล่องทั้งหมด = []
    for (const el of document.querySelectorAll('.pk-ตัวบท .pk-ช่องฉบับ')) {
      if (!เห็น(el)) continue
      const ชื่อ = el.getAttribute('data-ฉบับ') || '(ไม่มีชื่อ)'
      const r = กรอบ(el)
      const ก = el.getBoundingClientRect()
      กล่องทั้งหมด.push({ ชื่อ, ซ้าย: ก.left, ขวา: ก.right, บน: ก.top, ล่าง: ก.bottom })
      const เดิม = ช่วงของฉบับ[ชื่อ]
      ช่วงของฉบับ[ชื่อ] = เดิม
        ? { ซ้าย: Math.min(เดิม.ซ้าย, r.ซ้าย), ขวา: Math.max(เดิม.ขวา, r.ขวา) }
        : r
    }

    // ---------------- ⑦ ภาษาที่กล่องของแต่ละฉบับประกาศไว้เอง
    // ⛔ **อ่านจาก `getAttribute` ⛔ ไม่ใช่ `el.lang`** ⇒ `el.lang` คืนค่าว่างเมื่อไม่มีป้าย
    //   แต่เราอยากรู้ให้ชัดว่า **ป้ายอยู่บนกล่องนี้จริงไหม** ⛔ ไม่ใช่สืบมาจากพ่อ
    const ภาษาของฉบับ = {}
    for (const el of document.querySelectorAll('.pk-ตัวบท .pk-ช่องฉบับ')) {
      if (!เห็น(el)) continue
      const ชื่อ = el.getAttribute('data-ฉบับ') || '(ไม่มีชื่อ)'
      const ภ = el.getAttribute('lang') || ''
      if (!ภาษาของฉบับ[ชื่อ]) ภาษาของฉบับ[ชื่อ] = []
      if (!ภาษาของฉบับ[ชื่อ].includes(ภ)) ภาษาของฉบับ[ชื่อ].push(ภ)
    }

    // ---------------- ② อ่าน **ตัวหนังสือที่ตาเห็นจริง** ในกล่องที่ครอบหลายฉบับ
    //
    // ⛔⛔ **`innerText` ใช้ไม่ได้กับข้อนี้** — ลองมาแล้ว 8 ก.ย. 2569 ⇒ หน้าที่พังจริง
    //   (ตัวบททุกฉบับต่อกันเป็นพืดในบรรทัดเดียวกัน) `innerText` ยังแถมตัวขึ้นบรรทัด
    //   ให้ตรงรอยต่อของ `<p>` อยู่ดี ⇒ **ด่านจะมองไม่เห็นรอยที่ตาคนเห็นว่าติดกัน**
    //   ⇒ ⭐ จึงต้อง **ถามผังหน้าเอง** ⇒ ไล่ตัวหนังสือทีละก้อน แล้วดูว่าก้อนที่อยู่ติดกัน
    //     **อยู่บรรทัดเดียวกันและชิดกันจริงไหม** ⇒ ชิดจริงถึงจะต่อสตริงกันโดยไม่มีอะไรคั่น
    // ⛔ ข้ามชื่อฉบับที่ซ่อนไว้ให้โปรแกรมอ่านหน้าจอ — ตา ⛔ ไม่เห็นมัน
    const ตัวหนังสือที่ตาเห็น = (กล่อง) => {
      const เดิน = document.createTreeWalker(กล่อง, NodeFilter.SHOW_TEXT)
      const ก้อน = []
      for (let n = เดิน.nextNode(); n; n = เดิน.nextNode()) {
        if (!n.nodeValue || !n.nodeValue.trim()) continue
        if (n.parentElement && n.parentElement.closest('.pk-เฉพาะเสียง')) continue
        const ช่วง = document.createRange()
        ช่วง.selectNodeContents(n)
        const rects = [...ช่วง.getClientRects()].filter((r) => r.width > 0 || r.height > 0)
        if (!rects.length) continue
        ก้อน.push({ ตัวอักษร: n.nodeValue, หัว: rects[0], ท้าย: rects[rects.length - 1] })
      }
      let ผล = ''
      for (let i = 0; i < ก้อน.length; i++) {
        if (i > 0) {
          const a = ก้อน[i - 1].ท้าย
          const b = ก้อน[i].หัว
          // บรรทัดเดียวกัน = กลางกล่องทั้งสองอยู่ในกรอบความสูงของกันและกัน
          const บรรทัดเดียวกัน =
            b.top < a.bottom - 1 && a.top < b.bottom - 1
          const ชิดกัน = Math.abs(b.left - a.right) <= 1
          if (!(บรรทัดเดียวกัน && ชิดกัน)) ผล += '\n'
        }
        ผล += ก้อน[i].ตัวอักษร
      }
      return ผล
    }
    const กล่องรวม = [...document.querySelectorAll('.pk-ตัวบท .pk-ไหล, .pk-ตัวบท .pk-ข้อ')]
      .filter(เห็น)
      .slice(0, 60)
      .map((el) => ({ ชั้น: el.className, ตัวหนังสือ: ตัวหนังสือที่ตาเห็น(el) }))

    // ---------------- ④ ⑤ ⑥ เลขข้อ
    const ตัวบทตัวอย่าง = document.querySelector('.pk-ตัวบท .pk-ช่องฉบับ')
    const ขนาดตัวบท = ตัวบทตัวอย่าง ? parseFloat(getComputedStyle(ตัวบทตัวอย่าง).fontSize) : 0

    const เลขข้อ = [...document.querySelectorAll('.pk-ตัวบท .pk-เลขข้อ')]
      .filter(เห็น)
      .map((el) => ({
        แท็ก: el.tagName,
        ป้าย: (el.textContent || '').trim(),
        ขนาด: parseFloat(getComputedStyle(el).fontSize),
      }))

    // สีจริงของเลขข้อ กับพื้นจริงที่มันทาบอยู่ ⇒ ไต่ขึ้นไปหาพื้นตัวแรกที่ ⛔ ไม่โปร่งใส
    const แปลงสี = (s) => {
      const n = (s.match(/\d+(\.\d+)?/g) || []).map(Number)
      return n.length >= 3 ? { r: n[0], g: n[1], b: n[2], a: n.length > 3 ? n[3] : 1 } : null
    }
    let สีเลข = null
    let สีพื้น = null
    const ตัวอย่างเลข = [...document.querySelectorAll('.pk-ตัวบท .pk-เลขข้อ')].filter(เห็น)[0]
    if (ตัวอย่างเลข) {
      สีเลข = แปลงสี(getComputedStyle(ตัวอย่างเลข).color)
      for (let el = ตัวอย่างเลข; el; el = el.parentElement) {
        const c = แปลงสี(getComputedStyle(el).backgroundColor)
        if (c && c.a > 0) {
          สีพื้น = c
          break
        }
      }
    }

    // เลขข้อแรกของบทที่กำลังตรวจ ⇒ อ่านจากหมุดข้อที่หน้าเว็บวางไว้เอง
    const เลขข้อในบท = [...document.querySelectorAll(`[id^="ข้อ-${บท}-"]`)]
      .map((el) => Number(el.id.split('-')[2]))
      .filter((n) => Number.isFinite(n))

    return {
      ช่วงของฉบับ,
      กล่องทั้งหมด,
      ภาษาของฉบับ,
      กล่องรวม,
      ขนาดตัวบท,
      เลขข้อ,
      สีเลข,
      สีพื้น,
      ข้อแรกของบท: เลขข้อในบท.length ? Math.min(...เลขข้อในบท) : null,
    }
  }, เลขบท)

// สูตรของ WCAG 2.x ⇒ https://www.w3.org/TR/WCAG22/#dfn-contrast-ratio
function ความสว่าง({ r, g, b }) {
  const c = [r, g, b]
    .map((v) => v / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
}
function อัตราส่วน(หน้า, หลัง) {
  const a = ความสว่าง(หน้า)
  const b = ความสว่าง(หลัง)
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05)
}

// ตัวอักษรไทยชนตัวอักษรอังกฤษโดยไม่มีอะไรคั่นเลย
const ไทยชนอังกฤษ = /[฀-๿][A-Za-z]|[A-Za-z][฀-๿]/

/** ตรวจ 1 โหมด ⇒ คืน **รายการที่ตก** ⛔ ไม่พิมพ์เอง เพื่อให้โหมดพิสูจน์เอาไปนับได้ */
function ตัดสิน(ของจริง, ป้าย, กี่ฉบับ) {
  const ตก = []
  const ชื่อฉบับ = Object.keys(ของจริง.ช่วงของฉบับ)

  // ---------------- ① คนละฉบับต้องอยู่คนละกล่อง ⇒ ช่วงซ้ายขวาห้ามทับกัน
  if (ชื่อฉบับ.length < 2) {
    ตก.push(`① ${ป้าย} ⇒ หากล่องตัวบทได้แค่ ${ชื่อฉบับ.length} ฉบับ (ติ๊กไว้ ${กี่ฉบับ} ฉบับ)`)
  }
  // ⭐ ใบ #102 ⇒ เทียบ **กล่องต่อกล่อง ทั้งสองแกน** ⇒ ห่อลงแถวใหม่ (คนละแถว ช่วงซ้ายขวาเดียวกัน) ⛔ ไม่ใช่การชน
  //   ⇒ ⭐ ของพังเดิม (`display:inline`) ยังจับได้ ⇒ กล่องที่ละลายเป็นบรรทัดยาวทับกล่องของอีกฉบับทั้งแนวนอนและแนวตั้ง
  const ชนแล้ว = new Set()
  const ก = ของจริง.กล่องทั้งหมด || []
  for (let i = 0; i < ก.length; i++) {
    for (let j = i + 1; j < ก.length; j++) {
      const a = ก[i]
      const b = ก[j]
      if (a.ชื่อ === b.ชื่อ) continue
      const คู่ = [a.ชื่อ, b.ชื่อ].sort().join('|')
      if (ชนแล้ว.has(คู่)) continue
      // ทับกัน = ช่วงที่ซ้อนกันกว้างเกิน 1 จุด ทั้งสองแกน ⇒ เผื่อการปัดเศษของเบราว์เซอร์
      const ซ้อนนอน = Math.min(a.ขวา, b.ขวา) - Math.max(a.ซ้าย, b.ซ้าย)
      const ซ้อนตั้ง = Math.min(a.ล่าง, b.ล่าง) - Math.max(a.บน, b.บน)
      if (ซ้อนนอน > 1 && ซ้อนตั้ง > 1) {
        ชนแล้ว.add(คู่)
        ตก.push(
          `① ${ป้าย} ⇒ กล่องของ "${a.ชื่อ}" กับ "${b.ชื่อ}" ทับกัน ${Math.round(ซ้อนนอน)} × ${Math.round(ซ้อนตั้ง)} จุด ` +
            `(${Math.round(a.ซ้าย)}–${Math.round(a.ขวา)} กับ ${Math.round(b.ซ้าย)}–${Math.round(b.ขวา)})`,
        )
      }
    }
  }

  // ---------------- ② ไทยห้ามติดอังกฤษ
  for (const ก of ของจริง.กล่องรวม) {
    const พบ = ก.ตัวหนังสือ.match(ไทยชนอังกฤษ)
    if (!พบ) continue
    const ที่ = ก.ตัวหนังสือ.indexOf(พบ[0])
    ตก.push(
      `② ${ป้าย} ⇒ ในกล่อง "${ก.ชั้น}" มีตัวไทยติดตัวอังกฤษ ⇒ …` +
        ก.ตัวหนังสือ.slice(Math.max(0, ที่ - 25), ที่ + 25).replace(/\s+/g, ' ') +
        '…',
    )
    break // จุดเดียวก็พอให้คนแก้เห็นภาพ ⛔ ไม่ถล่มรายงานด้วยของซ้ำ
  }

  // ---------------- ④ เลขข้อเล็กพอและเป็นตัวยกจริง
  if (!ของจริง.เลขข้อ.length) {
    ตก.push(`④ ${ป้าย} ⇒ ⛔ ไม่มีเลขข้อบนหน้าเลย`)
  }
  if (!ของจริง.ขนาดตัวบท) {
    ตก.push(`④ ${ป้าย} ⇒ วัดขนาดตัวบทไม่ได้ ⇒ เทียบขนาดเลขข้อไม่ได้`)
  } else {
    const โตสุด = ของจริง.เลขข้อ.reduce((m, x) => Math.max(m, x.ขนาด), 0)
    const เท่า = โตสุด / ของจริง.ขนาดตัวบท
    if (เท่า > 0.7 + 0.005) {
      ตก.push(
        `④ ${ป้าย} ⇒ เลขข้อโต ${เท่า.toFixed(2)} เท่าของตัวบท (${โตสุด} ต่อ ${ของจริง.ขนาดตัวบท} จุด) ` +
          `⇒ เพดานคือ 0.7 เท่า`,
      )
    }
  }
  const ไม่ใช่ตัวยก = ของจริง.เลขข้อ.filter((x) => x.แท็ก !== 'SUP')
  if (ไม่ใช่ตัวยก.length) {
    ตก.push(
      `④ ${ป้าย} ⇒ เลขข้อ ${ไม่ใช่ตัวยก.length} ตัว ⛔ ไม่ใช่ <sup> ` +
        `(เจอ <${ไม่ใช่ตัวยก[0].แท็ก.toLowerCase()}> ป้าย "${ไม่ใช่ตัวยก[0].ป้าย}")`,
    )
  }

  // ---------------- ⑤ ข้อแรกของบทบอกทั้งบทและข้อ · ข้ออื่นบอกแต่ข้อ
  const ป้ายทั้งหมด = ของจริง.เลขข้อ.map((x) => x.ป้าย).filter((t) => t && t !== '88')
  const มีทวิภาค = [...new Set(ป้ายทั้งหมด.filter((t) => t.includes(':')))]
  const ที่ควรเป็น = `${เลขบทที่ใช้}:${ของจริง.ข้อแรกของบท}`
  if (ของจริง.ข้อแรกของบท === null) {
    ตก.push(`⑤ ${ป้าย} ⇒ หาหมุดข้อของบท ${เลขบทที่ใช้} บนหน้าไม่เจอ`)
  } else if (!มีทวิภาค.length) {
    ตก.push(`⑤ ${ป้าย} ⇒ ⛔ ไม่มีข้อไหนแสดงเลขบทเลย ⇒ ข้อแรกของบทควรเป็น "${ที่ควรเป็น}"`)
  } else if (มีทวิภาค.length > 1 || มีทวิภาค[0] !== ที่ควรเป็น) {
    ตก.push(
      `⑤ ${ป้าย} ⇒ ป้ายที่มีเลขบทควรมีแบบเดียวคือ "${ที่ควรเป็น}" ` +
        `แต่เจอ [${มีทวิภาค.slice(0, 5).join(' ')}]`,
    )
  }
  const ข้ออื่นเพี้ยน = ป้ายทั้งหมด.filter((t) => !t.includes(':') && !/^\d+$/.test(t))
  if (ข้ออื่นเพี้ยน.length) {
    ตก.push(`⑤ ${ป้าย} ⇒ ป้ายข้อที่ ⛔ ไม่ใช่ตัวเลขล้วน [${ข้ออื่นเพี้ยน.slice(0, 5).join(' ')}]`)
  }

  // ---------------- ⑥ สีเลขข้อทาบพื้นจริง ≥ 4.5:1
  if (!ของจริง.สีเลข || !ของจริง.สีพื้น) {
    ตก.push(`⑥ ${ป้าย} ⇒ อ่านสีเลขข้อหรือสีพื้นจากหน้าจริงไม่ได้`)
  } else {
    const r = อัตราส่วน(ของจริง.สีเลข, ของจริง.สีพื้น)
    if (r < 4.5) {
      ตก.push(`⑥ ${ป้าย} ⇒ สีเลขข้อทาบพื้นได้แค่ ${r.toFixed(2)}:1 ⇒ เกณฑ์คือ 4.5:1`)
    }
  }

  // ---------------- ⑦ ทุกกล่องต้องบอกภาษาของตัวเอง และต้องมีมากกว่า 1 ภาษา
  const ชื่อที่มีภาษา = Object.keys(ของจริง.ภาษาของฉบับ || {})
  const ไม่มีป้าย = ชื่อที่มีภาษา.filter((ช) => ของจริง.ภาษาของฉบับ[ช].some((x) => !x))
  if (ไม่มีป้าย.length) {
    ตก.push(
      `⑦ ${ป้าย} ⇒ กล่องของ [${ไม่มีป้าย.join(' ')}] ⛔ ไม่มีป้าย lang ของตัวเอง ` +
        `⇒ WCAG SC 3.1.2 Language of Parts (ระดับ AA)`,
    )
  }
  const ปนกัน = ชื่อที่มีภาษา.filter((ช) => ของจริง.ภาษาของฉบับ[ช].length > 1)
  if (ปนกัน.length) {
    ตก.push(
      `⑦ ${ป้าย} ⇒ ฉบับเดียวกันถูกติดภาษาไม่ตรงกันระหว่างข้อ ⇒ ` +
        ปนกัน.map((ช) => `${ช}=[${ของจริง.ภาษาของฉบับ[ช].join(' ')}]`).join(' · '),
    )
  }
  const ภาษาที่เจอ = [...new Set(ชื่อที่มีภาษา.flatMap((ช) => ของจริง.ภาษาของฉบับ[ช]))].filter(Boolean)
  if (ชื่อที่มีภาษา.length > 1 && ภาษาที่เจอ.length < 2) {
    ตก.push(
      `⑦ ${ป้าย} ⇒ ติ๊กไว้ ${ชื่อที่มีภาษา.length} ฉบับ แต่ทุกกล่องบอกภาษาเดียวกันหมด ` +
        `[${ภาษาที่เจอ.join(' ')}] ⇒ มีทั้งฉบับไทยและฉบับอังกฤษอยู่ ⇒ แปลว่าป้ายยังไม่ได้ผูกกับข้อมูลจริง`,
    )
  }

  return ตก
}

/**
 * ตรวจ 1 โหมด ⇒ **เปิดหน้าใหม่ทุกครั้ง** ⇒ ⛔ ค่าที่เว็บจำไว้จากรอบก่อนไม่ปนเข้ามา
 *
 * ⭐⭐ **เลือกโหมดก่อน แล้วค่อยติ๊กฉบับเพิ่ม** ⇒ นี่คือทางที่พี่เอมเดินจริงตอนเจอของพัง
 *   ⇒ ⛔ ไม่ใช่ติ๊กฉบับก่อนแล้วค่อยเลือกโหมด — ทางนั้นเดินไม่ได้ในเว็บรุ่นที่พัง
 *     เพราะมันซ่อนตัวเลือกการจัดวางทิ้งตอนเลือกหลายฉบับ **แต่ค่าที่จำไว้ยังเป็นไหลต่อเนื่อง**
 *   ⇒ เดินทางนี้ ด่านจึงตรวจของรุ่นเก่าได้ด้วย ⛔ ไม่ใช่ตรวจได้แต่รุ่นที่แก้แล้ว
 *
 * `ยัดกฎที่พัง` เป็นจริงเฉพาะโหมดพิสูจน์ว่าด่านยังจับได้
 */
async function ตรวจโหมด(โหมด, ยัดกฎที่พัง) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
  const แท็บ = await ctx.newPage()
  try {
    await เปิด(แท็บ, `/read/${บทที่ใช้}/?c=${เลขบทที่ใช้}`)
    if (ยัดกฎที่พัง) await แท็บ.addStyleTag({ content: กฎที่พัง })
    await เลือกโหมด(แท็บ, โหมด)
    const กี่ฉบับ = await เลือกทุกฉบับ(แท็บ)
    // ⭐ **ของที่พังของข้อ ⑦ คือ *การไม่มีป้าย* ⛔ ไม่ใช่กฎหน้าตา** ⇒ CSS ยัดกลับไม่ได้
    //   ⇒ จึงถอดป้าย `lang` ออกจากหน้าตรง ๆ ⇒ นี่คือสภาพของเว็บก่อน 12 ต.ค. 2569 เป๊ะ ๆ
    if (ยัดกฎที่พัง) {
      await แท็บ.evaluate(() => {
        for (const el of document.querySelectorAll('.pk-ช่องฉบับ[lang]')) el.removeAttribute('lang')
      })
    }
    const ของจริง = await เก็บของจริง(แท็บ, เลขบทที่ใช้)
    return ตัดสิน(ของจริง, `โหมด ${โหมด} · ${กี่ฉบับ} ฉบับ · จอ 1280`, กี่ฉบับ)
  } finally {
    await ctx.close()
  }
}

async function ตรวจทุกโหมด(ยัดกฎที่พัง) {
  const ตก = []
  for (const โหมด of โหมดทั้งหมด) ตก.push(...(await ตรวจโหมด(โหมด, ยัดกฎที่พัง)))
  return ตก
}

