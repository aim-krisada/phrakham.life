async function หลัก() {
  const แดงจริง = await ตรวจ(รากโค้ด)
  if (แดงจริง.length) {
    console.error('⛔ ด่านของใหม่ (ใบ #187) ไม่ผ่าน')
    for (const x of แดงจริง) console.error('  ' + x)
    process.exit(1)
  }
  console.log('✅ ด่านของใหม่ผ่านครบ ①–⑦')
  if (!ทดสอบตัวเอง) return

  const ไม่จับ = []
  for (const [ชื่อ, [เลข, ไฟล์, จาก, เป็น]] of Object.entries(ของพัง)) {
    const ที่ = mkdtempSync(join(tmpdir(), 'ด่านของใหม่-'))
    try {
      for (const f of ไฟล์ที่ใช้) {
        let s = อ่าน(f)
        if (f === ไฟล์) {
          if (!s.includes(จาก)) throw new Error(`⛔ ท่า "${ชื่อ}" หาคำที่จะแทนไม่เจอใน ${f} ⇒ ด่านตาย`)
          s = s.replace(จาก, เป็น)
        }
        mkdirSync(join(ที่, f, '..'), { recursive: true })
        writeFileSync(join(ที่, f), s)
      }
      const แดง = await ตรวจ(pathToFileURL(ที่ + '/'))
      const จับ = แดง.some((x) => x.startsWith(เลข))
      console.log(`${จับ ? '✅' : '⛔'} ${ชื่อ} ⇒ ข้อ ${เลข} ${จับ ? 'แดง' : 'ไม่แดง'}`)
      if (!จับ) ไม่จับ.push(ชื่อ)
    } finally {
      rmSync(ที่, { recursive: true, force: true })
    }
  }
  if (ไม่จับ.length) {
    console.error(`\n⛔ โหมดพิสูจน์: ยัดของพังแล้ว **ด่านยังไม่เห็น ${ไม่จับ.length} ท่า** ⇒ ${ไม่จับ.join(' · ')}`)
    process.exit(1)
  }
  console.log(`\n✅ โหมดพิสูจน์: ด่านจับของพังได้ครบ ${Object.keys(ของพัง).length} ท่า`)
}

