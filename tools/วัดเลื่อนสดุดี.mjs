// ⭐⭐ **นี่คือเครื่องวัด ⛔ ไม่ใช่ด่าน** — มันพิมพ์ตัวเลขออกมาให้คนอ่านแล้วตัดสินเอง
//   ⇒ ⛔ ไม่ตั้งเกณฑ์ผ่าน/ไม่ผ่านไว้เอง ⇒ กฎบ้านเราเขียนไว้ว่า *เครื่องมือรายงาน ⛔ ไม่เสนอ · คนตัดสิน*
//
// **วัดอะไร**
//   ① **งานยาว (longtask)** — ช่วงที่เบราว์เซอร์ทำงานติดกันเกิน 50 มิลลิวินาที
//     ⇒ ช่วงพวกนี้คือตอนที่ **นิ้วเลื่อนแล้วจอไม่ขยับตาม** ⇒ ผู้อ่านเรียกว่า "หน่วง"
//   ② **จำนวนบทกับจำนวนข้อที่กางอยู่บนหน้า** ⇒ พิสูจน์ว่าบทที่เลื่อนพ้นไปไกลถูกทิ้งจริง
//     ⇒ ⛔ ไม่ทิ้ง = ตัวเลขนี้จะโตขึ้นเรื่อย ๆ จนจบเล่ม
//
// ⭐⭐ **ต้องถ่วงซีพียูด้วย** — เครื่องที่เราสร้างเว็บเร็วกว่ามือถือของผู้อ่านหลายเท่า
//   ⇒ วัดบนเครื่องเราเปล่า ๆ แล้วได้ 0 ⇒ **แปลว่าเครื่องเราเร็ว ⛔ ไม่ได้แปลว่าเว็บลื่น**
//   ⇒ ตัวถ่วงเป็นของเบราว์เซอร์เอง (`Emulation.setCPUThrottlingRate`) ⛔ ไม่ใช่ของที่เราเขียนเอง
//
// ⭐⭐ **วัดรอบเดียวแล้วเชื่อ ⛔ ไม่ได้** — ตัวเลขขยับได้ตามงานอื่นที่เครื่องทำอยู่
//   ⇒ คนตรวจรันเครื่องมือตัวเดียวกันด้วยค่าเดียวกันบนเครื่องเดียวกัน **แล้วได้ไม่ตรงกับที่รายงานไว้**
//     (คนตรวจ !64 ทัก ③ · 7 ก.ย. 2569) ⇒ ⛔ **เลขเดียวที่ทำซ้ำไม่ได้ ⛔ ไม่ใช่หลักฐาน**
//   ⇒ ⭐ **เครื่องมือจึงวัดซ้ำหลายรอบให้เอง แล้วรายงานเป็นช่วง** ⇒ คนอ่านเทียบช่วงกับช่วงได้
//   ⇒ ⛔ **ตอนวัด ให้เครื่องว่างจากงานหนักอย่างอื่น** — สร้างเว็บไปด้วยวัดไปด้วย = ตัวเลขเพี้ยน
//
//   node tools/วัดเลื่อนสดุดี.mjs <ที่อยู่เว็บ> [รอบเลื่อน] [เท่าที่ถ่วงซีพียู] [วัดกี่รอบ]
//
// ⭐⭐ **ต้องวัดได้ทั้งเว็บรุ่นใหม่และรุ่นที่เอามาเทียบ** — ไม่งั้นตัวเลขที่ได้ ⛔ ไม่มีอะไรให้เทียบ
//   ⇒ รุ่นนี้ **1 เล่ม = 1 หน้า** ⇒ สดุดีอยู่ที่ `/read/PSA`
//   ⇒ รุ่นก่อน (`main`) **1 บท = 1 หน้า** ⇒ ⛔ ไม่มี `/read/PSA` ⇒ ต้องเปิด `/read/PSA/1`
//   ⇒ ⭐ **เครื่องมือจึงลองทีละที่อยู่เอง** ⛔ ไม่ให้คนวัดต้องรู้ล่วงหน้าว่าเว็บก้อนนี้เป็นรุ่นไหน
//     (คนตรวจ !64 ทัก ข. · 7 ก.ย. 2569 — เปิดที่อยู่ตายตัวแล้วได้ `TimeoutError` เปล่า ๆ
//      จนคนวัดนึกว่าเว็บพัง ทั้งที่แค่เปิดผิดที่อยู่)

import { chromium } from 'playwright'
import { เส้นทางเว็บ } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const รอบเลื่อน = Number(process.argv[3] || 200)
const ถ่วงซีพียู = Number(process.argv[4] || 1)
const วัดกี่รอบ = Number(process.argv[5] || 3)

/** ที่อยู่ของสดุดีที่จะลอง ⇒ เรียงจากรุ่นใหม่ไปรุ่นเก่า */
const ที่อยู่ที่ลอง = ['/read/PSA', '/read/PSA/1']

// ⭐⭐ **เวลารอต้องเผื่อรุ่นเก่าด้วย** — รุ่น 1 บท 1 หน้า แบกซองข้อมูลหนักกว่ามาก
//   ⛔ รอ 15 วินาทีตายตัวแบบเดิม = รุ่นเก่าโหลดไม่ทัน แล้วโดนตัดสินว่าพัง (เจอเอง 7 ก.ย. 2569)
//   ⇒ ⭐ **พื้นคือ 90 วินาที** ⇒ ที่ถ่วง 6 เท่าซึ่งเป็นค่าที่เราใช้ประจำ คูณแล้วได้ 90 พอดี
//     ⇒ ⛔ **การคูณจึงยัง ⛔ ไม่มีผลจนกว่าจะถ่วงเกิน 6 เท่า** ⇒ มีไว้เผื่อคนตั้งถ่วงสูงกว่านั้น
//     (คนตรวจ !64 ทัก ข. · 7 ก.ย. 2569 ว่าคอมเมนต์เดิมพูดเกินที่โค้ดทำ)
const รอโค้ดติด = Math.max(90000, 15000 * Math.max(1, ถ่วงซีพียู))

/**
 * เปิดหน้าสดุดีให้ได้ ⇒ ⭐ **ลองทีละที่อยู่ แล้วคืนที่อยู่ที่ใช้ได้จริง**
 * ⛔ **นับว่าเปิดได้ ต้องมีข้อขึ้นบนหน้าจริง** ⛔ ไม่ใช่แค่โค้ดของเว็บติด
 *   ⇒ ที่อยู่ที่ไม่มีจริงก็ได้หน้าสำรอง (`404.html`) ซึ่งโค้ดติดเหมือนกัน แต่ ⛔ ไม่มีเนื้อให้เลื่อน
 */
async function เปิดหน้าสดุดี(แท็บ) {
  const เสีย = []
  for (const ทาง of ที่อยู่ที่ลอง) {
    try {
      await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
      await แท็บ.waitForFunction(() => document.querySelectorAll('.pk-ข้อ').length > 0, null, {
        timeout: รอโค้ดติด,
      })
      return ทาง
    } catch {
      เสีย.push(ทาง)
    }
  }
  // ⛔ **ล้มแล้วต้องบอกเป็นคำของเรา** ⛔ ไม่ใช่ปล่อย `TimeoutError` ดิบ ๆ ให้คนอ่านเดาเอง
  throw new Error(
    `⛔ เปิดหน้าสดุดีของเว็บก้อนนี้ ⛔ ไม่ได้ ⇒ ลองมาแล้ว ${เสีย.map((t) => ฐาน + t).join(' และ ')}` +
      // ⛔ **ห้ามเขียนว่า "รอครบ N วินาทีแล้ว"** — ต่อไม่ติดตั้งแต่แรก (⛔ ไม่มีใครเสิร์ฟอยู่)
      //   มันล้มใน 3 วินาที ⇒ ประโยคนั้นกลายเป็นคำโกหก (คนตรวจ !64 ทัก ก. · 7 ก.ย. 2569)
      `\n  ⇒ ทุกที่อยู่เปิดแล้วยัง ⛔ ไม่มีข้อขึ้นบนหน้าเลย (รอได้นานสุด ${Math.round(รอโค้ดติด / 1000)} วินาที)` +
      `\n  ⇒ **ตรวจ 3 อย่างนี้ก่อน** ① เสิร์ฟเว็บอยู่จริงไหม (\`tools/เสิร์ฟเว็บที่สร้างเสร็จ.mjs\`)` +
      ` ② ฐานของเว็บในที่อยู่ถูกไหม ③ เว็บก้อนนั้นสร้างเสร็จจริงไหม`,
  )
}

/**
 * วัด 1 รอบ ⇒ ⭐⭐ **เบราว์เซอร์ใหม่ทุกรอบ** ⛔ ไม่ใช้ตัวเดิมซ้ำ
 *   ⛔ ใช้เบราว์เซอร์เดิมแล้วเปิดแค่แท็บใหม่ ⇒ **รอบแรกแบกงานตั้งตัวของทั้งเบราว์เซอร์ไว้คนเดียว**
 *   ⇒ ตัวเลขรอบแรกสูงกว่ารอบหลังอย่างมีระบบ ⇒ ช่วงที่ได้กว้างเกินจริง (ลองเองแล้ว 7 ก.ย. 2569)
 */
async function วัดหนึ่งรอบ() {
  const เบราว์เซอร์ = await chromium.launch()
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 412, height: 915 } })
  const แท็บ = await ctx.newPage()

  if (ถ่วงซีพียู > 1) {
    const สาย = await ctx.newCDPSession(แท็บ)
    await สาย.send('Emulation.setCPUThrottlingRate', { rate: ถ่วงซีพียู })
  }

  const ทางที่ใช้ = await เปิดหน้าสดุดี(แท็บ)

  // ⭐ ต้องเริ่มจับ **ก่อน** เลื่อน ⇒ ของที่เกิดก่อนตั้งตัวจับ ⛔ ไม่ถูกนับ
  await แท็บ.evaluate(() => {
    window.__งานยาว = []
    new PerformanceObserver((รายการ) => {
      for (const x of รายการ.getEntries()) window.__งานยาว.push(Math.round(x.duration))
    }).observe({ entryTypes: ['longtask'] })
  })

  const สูงสุด = { บท: 0, ข้อ: 0, ปม: 0 }
  for (let i = 0; i < รอบเลื่อน; i++) {
    await แท็บ.mouse.wheel(0, 4000)
    await แท็บ.waitForTimeout(120)
    const ตอนนี้ = await แท็บ.evaluate(() => ({
      บท: document.querySelectorAll('[data-หมุดบท]').length,
      ข้อ: document.querySelectorAll('.pk-ข้อ').length,
      ปม: document.getElementsByTagName('*').length,
    }))
    สูงสุด.บท = Math.max(สูงสุด.บท, ตอนนี้.บท)
    สูงสุด.ข้อ = Math.max(สูงสุด.ข้อ, ตอนนี้.ข้อ)
    สูงสุด.ปม = Math.max(สูงสุด.ปม, ตอนนี้.ปม)
  }

  const จบที่ = await แท็บ.evaluate(() => ({
    ที่อยู่: location.pathname + location.search,
    // ⭐ แถบล่างเลิกบอกชื่อบทแล้ว (ใบ #104) ⇒ บทที่อ่านอยู่อยู่ที่ป้ายหัวคอลัมน์แรก
    บทที่อ่านอยู่: document.querySelector('.pk-หัวคอลัมน์ .pk-ที่ของช่อง')?.textContent?.trim() || '',
  }))
  const งานยาว = await แท็บ.evaluate(() => window.__งานยาว)
  await ctx.close()
  await เบราว์เซอร์.close()

  return {
    ทางที่ใช้,
    จบที่,
    สูงสุด,
    เกิน50: งานยาว.length,
    ยาวสุด: งานยาว.length ? Math.max(...งานยาว) : 0,
    รวม: งานยาว.reduce((a, b) => a + b, 0),
  }
}

const ผลทุกรอบ = []
for (let n = 1; n <= วัดกี่รอบ; n++) {
  let ผล
  try {
    ผล = await วัดหนึ่งรอบ()
  } catch (err) {
    // ⛔ **ตายแล้วต้องบอกเป็นคำของเรา** ⇒ กองสแต็กของ playwright ⛔ ไม่ช่วยให้คนวัดรู้ว่าต้องทำอะไร
    console.error(err.message)
    process.exit(1)
  }
  ผลทุกรอบ.push(ผล)
  console.log(
    `รอบ ${n}/${วัดกี่รอบ} · เปิดจาก ${ผล.ทางที่ใช้} · จบที่ ${ผล.จบที่.ที่อยู่} (${ผล.จบที่.บทที่อ่านอยู่})` +
      ` · งานยาวเกิน 50 มิลลิวินาที ${ผล.เกิน50} ครั้ง · ยาวสุด ${ผล.ยาวสุด} มิลลิวินาที` +
      ` · รวม ${ผล.รวม} มิลลิวินาที · บทที่กางมากสุด ${ผล.สูงสุด.บท} · ข้อมากสุด ${ผล.สูงสุด.ข้อ}` +
      ` · ปมมากสุด ${ผล.สูงสุด.ปม}`,
  )
}

/** ช่วงต่ำสุด–สูงสุดของค่าหนึ่ง ⇒ ⭐ **รายงานเป็นช่วง ⛔ ไม่ใช่ค่าเฉลี่ย** ⇒ ค่าเฉลี่ยซ่อนรอบที่แย่ที่สุด */
const ช่วง = (หยิบ) => {
  const ค่า = ผลทุกรอบ.map(หยิบ)
  return `${Math.min(...ค่า)}–${Math.max(...ค่า)}`
}

console.log(
  `
เปิดสดุดีจาก ${ฐาน}${ผลทุกรอบ[0].ทางที่ใช้} · เลื่อน ${รอบเลื่อน} รอบ ที่จอ 412×915` +
    ` · ถ่วงซีพียู ${ถ่วงซีพียู} เท่า · วัด ${วัดกี่รอบ} รอบ`,
)
console.log(
  `งานยาวเกิน 50 มิลลิวินาที: ${ช่วง((x) => x.เกิน50)} ครั้ง` +
    ` · ยาวสุด ${ช่วง((x) => x.ยาวสุด)} มิลลิวินาที` +
    ` · เวลาที่จอค้างรวม ${ช่วง((x) => x.รวม)} มิลลิวินาที`,
)
console.log(
  `บทที่กางอยู่มากสุด ${ช่วง((x) => x.สูงสุด.บท)} บท` +
    ` · ข้อมากสุด ${ช่วง((x) => x.สูงสุด.ข้อ)} ข้อ` +
    ` · ปมในหน้ามากสุด ${ช่วง((x) => x.สูงสุด.ปม)}`,
)
