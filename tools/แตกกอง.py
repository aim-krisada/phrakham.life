ราก = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ต้นฉบับ = os.path.join(ราก, "source")
ปลายทาง = os.path.join(ราก, "_แตก")

# ตัวชี้ของ LFS เป็นไฟล์ข้อความสั้น ๆ ⇒ ใหญ่กว่านี้ถือว่าเป็นไฟล์จริง
