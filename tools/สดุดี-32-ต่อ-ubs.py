def รูปเดียวกัน(s):
    return unicodedata.normalize("NFC", s or "")


def เฉพาะพยัญชนะ(s):
    """ตัดสระและเครื่องหมายเสียงฮีบรูออก ⇒ ใช้เทียบว่า "อ่านออกเสียงพยัญชนะเดียวกันไหม"

    ⚠️ ใช้ตัดสินว่า **เป็นคำเดียวกัน** ไม่ได้ ⇒ `עַל` (บน) กับ `עֹל` (แอก) พยัญชนะเหมือนกันแต่คนละคำ
    ⇒ ที่ไหนต้องตัดสินว่าเล่มมีคำนี้ไหม ต้องเทียบรูปเต็ม ⛔ ไม่ใช่เทียบพยัญชนะ
    """
    ย = unicodedata.normalize("NFD", s or "")
    return "".join(c for c in ย if not (0x0591 <= ord(c) <= 0x05C7))


def อ่านมาคูลา(เฉพาะบท=บท):
    """คืนรายการชิ้นส่วนคำของบทที่ขอ เรียงตามลำดับในไฟล์"""
    ออก = []
    ช่อง = ("xml:id", "ref", "text", "lemma", "class", "pos", "gloss")
    with io.open(ตารางฮีบรู, encoding="utf-8") as f:
        r = csv.reader(f, delimiter="\t")
        หัว = next(r)
        ดัชนี = {k: หัว.index(k) for k in ช่อง}
        for row in r:
            if len(row) <= max(ดัชนี.values()):
                continue
            if เฉพาะบท is None or row[ดัชนี["ref"]].startswith(เฉพาะบท + ":"):
                ออก.append({k: row[i] for k, i in ดัชนี.items()})
    return ออก


def อ่านพจนานุกรม():
    """คืน (รายการความหมายทั้งเล่ม, รูปคำที่เล่มมี)

    รายการความหมายเป็น (รูปคำ, LEXID, คำแปลสั้น, คำนิยาม, รายชื่อที่อยู่)
    """
    d = json.load(io.open(พจนานุกรมฮีบรู, encoding="utf-8"))
    ความหมาย = []
    รูปที่มี = collections.Counter()
    for e in d:
        รูป = รูปเดียวกัน(e["Lemma"])
        รูปที่มี[รูป] += 1
        for bf in e["BaseForms"] or []:
            for lm in bf["LEXMeanings"] or []:
                s = (lm["LEXSenses"] or [{}])[0]
                ความหมาย.append(
                    (
                        รูป,
                        lm["LEXID"],
                        " · ".join(s.get("Glosses") or []),
                        (s.get("DefinitionShort") or "").strip(),
                        lm["LEXReferences"] or [],
                    )
                )
    return ความหมาย, รูปที่มี


def แยกที่อยู่(t):
    """แยกที่อยู่ 14 หลักของ `#10` เป็น (ที่อยู่ข้อ, เลขตำแหน่ง) ⇒ คืน None ถ้าไม่ใช่ของบทนี้

    ⚠️ ที่อยู่บางอันมีหางแบบ `{N:001}` ต่อท้าย ⇒ ตัดหางทิ้งก่อนอ่านเลข
    """
    ที่ = t.split("{")[0]
    if len(ที่) != 14 or not ที่.isdigit() or not ที่.startswith(หัวที่อยู่):
        return None
    return f"{บท}:{int(ที่[6:9])}", int(ที่[9:])


def อ้างถึงบทนี้():
    """คืนรายการการอ้างถึงสดุดี 32 ทั้งหมดของเล่ม เป็น (ที่อยู่ข้อ, เลขตำแหน่ง, ความหมาย)"""
    ความหมาย, _ = อ่านพจนานุกรม()
    ออก = []
    for รูป, lexid, คำแปล, นิยาม, ที่อยู่ทั้งหมด in ความหมาย:
        for t in ที่อยู่ทั้งหมด:
            ผล = แยกที่อยู่(t)
            if ผล:
                ออก.append((ผล[0], ผล[1], (รูป, lexid, คำแปล, นิยาม)))
    return sorted(ออก)


