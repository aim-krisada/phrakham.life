def ผู้สมัครทั้งสาม(ชิ้นในข้อ):
    """คืน 3 วิธีนับตำแหน่ง ⇒ ชื่อวิธี -> รายการชิ้นส่วนตามลำดับที่วิธีนั้นนับ

    ก นับทุกชิ้นส่วนในข้อ (รวมคำนำหน้าและคำต่อท้าย)
    ข นับทุกชิ้นส่วน **ยกเว้นคำต่อท้าย** (`pos` เป็น `suffix`)
    ค นับเป็นคำเต็ม คือนับที่อยู่คำ `ref` ที่ไม่ซ้ำ
    """
    คำเต็ม = []
    เห็นแล้ว = set()
    for x in ชิ้นในข้อ:
        if x["ref"] not in เห็นแล้ว:
            เห็นแล้ว.add(x["ref"])
            คำเต็ม.append(x)
    return {
        "ก นับทุกชิ้นส่วนในข้อ": ชิ้นในข้อ,
        "ข นับทุกชิ้นส่วน ยกเว้นคำต่อท้าย": [x for x in ชิ้นในข้อ if x["pos"] != "suffix"],
        "ค นับเป็นคำเต็ม": คำเต็ม,
    }


def จัดชิ้นตามข้อ(แถว):
    ในข้อ = collections.defaultdict(list)
    for x in แถว:
        ในข้อ[x["ref"].split("!")[0]].append(x)
    return ในข้อ


def ลำดับตามกฎ(แถว):
    """คืน รหัสชิ้นส่วน -> ลำดับในข้อ ตามกฎที่ชนะ คือนับทุกชิ้นยกเว้นคำต่อท้าย"""
    ลำดับ = {}
    นับ = collections.Counter()
    for x in แถว:
        if x["pos"] == "suffix":
            continue
        ข้อ = x["ref"].split("!")[0]
        นับ[ข้อ] += 1
        ลำดับ[x["xml:id"]] = นับ[ข้อ]
    return ลำดับ


