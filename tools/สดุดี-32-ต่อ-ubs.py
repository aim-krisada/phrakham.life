def ย้อนที่อยู่(ชิ้นในข้อ, ลำดับ):
    """แปลงลำดับชิ้นส่วนกลับเป็นที่อยู่คำแบบ MACULA ⇒ คนอ่านเปิดดูของจริงได้"""
    รายการ = [x for x in ชิ้นในข้อ if x["pos"] != "suffix"]
    if 1 <= ลำดับ <= len(รายการ):
        return รายการ[ลำดับ - 1]["ref"]
    return f"(ตำแหน่ง {ลำดับ} ไม่มีชิ้นส่วน)"


