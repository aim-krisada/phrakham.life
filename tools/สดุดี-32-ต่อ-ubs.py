    # ปฐมกาลคือเลข 001 ⇒ พิสูจน์แล้วที่ `tools/วัด-ubs-คลุมแค่ไหน.py ต่อติดไหม` (ใบ #47)
    กลับ = {1 + i: bk for i, bk in enumerate(ลำดับเล่ม)}
    ความหมาย, _ = อ่านพจนานุกรม()
    น = collections.Counter()
    for รูป, _, _, _, ที่อยู่ทั้งหมด in ความหมาย:
        พยัญชนะ = เฉพาะพยัญชนะ(รูป)
        for t in ที่อยู่ทั้งหมด:
            ที่ = t.split("{")[0]
            if len(ที่) != 14 or not ที่.isdigit():
                น["ที่อยู่ผิดรูป"] += 1
                continue
            เล่ม = int(ที่[:3])
            if เล่ม not in กลับ:
                น["เล่มนอกพันธสัญญาเดิม"] += 1
                continue
            pos = int(ที่[9:])
            if pos % 2:
                น["เลขตำแหน่งเป็นเลขคี่"] += 1
                continue
            รายการ = [
                x for x in ในข้อ.get(f"{กลับ[เล่ม]} {int(ที่[3:6])}:{int(ที่[6:9])}", []) if x["pos"] != "suffix"
            ]
            i = pos // 2
            if not (1 <= i <= len(รายการ)):
                น["ตำแหน่งเกินจำนวนชิ้นส่วนในข้อ"] += 1
                continue
            ได้ = รายการ[i - 1]
            if พยัญชนะ in (เฉพาะพยัญชนะ(ได้["lemma"]), เฉพาะพยัญชนะ(ได้["text"])):
                น["ก ชี้ถูกคำ"] += 1
            else:
                น["ข ชี้ไปคำอื่น"] += 1
    รวม = sum(น.values())
    print(f"  การอ้างถึงข้อของเล่มฮีบรูทั้งหมด {รวม} ครั้ง")
    for k, v in sorted(น.items()):
        print(f"  {k:36s}{v:8d}  {100 * v / รวม:6.2f}%")


