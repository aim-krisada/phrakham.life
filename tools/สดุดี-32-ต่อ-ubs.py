        if เจอ:
            รูป, lexid, คำแปล, นิยาม = เจอ[0]
            # ⛔ ห้ามส่งชื่อช่องภาษาไทยเป็น keyword ของ dict() ⇒ Python แปลงชื่อตัวแปรเป็นรูป NFKC
            #    ทำให้ `ลำ` กลายเป็นคนละสายอักษรกับข้อความในวงเล็บคำพูด ⇒ หาไม่เจอตอนอ่านกลับ
