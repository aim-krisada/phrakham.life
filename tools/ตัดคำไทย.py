def รุ่นตัวตัดคำ():
    """คืน (รุ่น, สัญญาอนุญาต) ของ PyThaiNLP ที่ติดตั้งอยู่จริงในเครื่องนี้

    ⛔ ไม่เขียนเลขรุ่นเป็นค่าคงที่ ⇒ วันที่อัปเกรด เอกสารกับของจริงจะไม่ตรงกันเงียบ ๆ
    """
    ของ = importlib.metadata.metadata("pythainlp")
    return ของ["Version"], ของ.get("License-Expression") or ของ.get("License") or "?"


def ตัดคำ(ข้อความ):
    """ตัดข้อความไทยเป็นรายการคำ ⇒ คืนคำที่เป็นตัวอักษรไทยล้วนเท่านั้น

    ⭐ ลบช่องศูนย์ความกว้างออกก่อนตัด ⇒ **ตั้งใจให้ตัวตัดคำทำงานโดยไม่เห็นเส้นแบ่งของผู้แปล**
       เพราะข้อความที่เราจะเขียนเองในใบถัดไป ไม่มีเครื่องหมายนั้นติดมาด้วย
       ⇒ ถ้าปล่อยไว้ ตัวเลขที่วัดได้จะดีเกินจริง แล้วพอเอาไปใช้กับข้อความของเราจะพัง
    ⛔ ทิ้งคำที่ไม่ใช่ตัวอักษรไทยล้วน ⇒ เลขข้อ เครื่องหมายคำพูด และชื่อย่อเล่มในวงเล็บ
       นับเป็น "คำไทย" ไม่ได้ ⇒ จำนวนที่ทิ้ง ดูได้จาก --นับพระคัมภีร์
    """
    ข้อความ = unicodedata.normalize("NFC", ข้อความ).replace(ช่องศูนย์, "").replace(ช่องแคบ, " ")
    ออก = []
    for ชิ้น in word_tokenize(ข้อความ, engine=เครื่องยนต์, keep_whitespace=False):
        # ตัวตัดคำมีคำในพจนานุกรมที่มีช่องว่างข้างใน เช่น "ทั้งๆ ที่" ⇒ แยกที่ช่องว่างอีกชั้น
        # **ทำไม** ⇒ ไม่งั้นทั้งก้อนจะไม่ผ่านกฎ "ไทยล้วน" แล้วคำดี ๆ สองคำหายไปพร้อมกัน
        ออก += [ท for ท in ชิ้น.split() if ไทยล้วน.match(ท)]
    return ออก


def อ่านพระคัมภีร์():
    """คืน {(เล่ม, บท, ข้อ): ตัวบทไทย} ⇒ ใช้ตัวอ่านของ tools/สร้างข้อมูลเว็บ.py ตัวเดียวกัน

    ⛔ ไม่เขียนตัวอ่าน USX ใหม่ ⇒ เจ้าของความจริงเรื่อง "ตัวบทข้อไหนคืออะไร" คือไฟล์นั้น
    """
    if not พระคัมภีร์ไทย.is_dir():
        sys.exit(f"⛔ ไม่เจอ {พระคัมภีร์ไทย}\n   สั่ง py -3.14 tools/แตกกอง.py ก่อน")
    ข้อ, _, _ = อ่าน_usx(พระคัมภีร์ไทย, "TCV")
    return ข้อ


def นับพระคัมภีร์():
    ข้อ = อ่านพระคัมภีร์()
    นับ = collections.Counter()
    ทิ้ง = collections.Counter()
    for ตัวบท in ข้อ.values():
        สะอาด = unicodedata.normalize("NFC", ตัวบท).replace(ช่องศูนย์, "").replace(ช่องแคบ, " ")
        for ชิ้น in word_tokenize(สะอาด, engine=เครื่องยนต์, keep_whitespace=False):
            for ท in ชิ้น.split():
                (นับ if ไทยล้วน.match(ท) else ทิ้ง)[ท] += 1
    รุ่น, สัญญา = รุ่นตัวตัดคำ()
    print(f"ตัวตัดคำ PyThaiNLP {รุ่น} · เครื่องยนต์ {เครื่องยนต์} · สัญญา {สัญญา}")
    print(f"ข้อที่มีตัวบท {len(ข้อ):,} ข้อ")
    print(f"คำไทยทั้งหมด {sum(นับ.values()):,} คำ")
    print(f"คำไทยไม่ซ้ำ  {len(นับ):,} คำ")
    print(f"ชิ้นที่ทิ้งเพราะไม่ใช่ตัวอักษรไทยล้วน {sum(ทิ้ง.values()):,} ครั้ง "
          f"({len(ทิ้ง):,} รูป)")
    มีอักษรไทยปน = {k: v for k, v in ทิ้ง.items() if re.search(r"[ก-๎]", k)}
    print(f"  ในนั้นเป็นชิ้นที่มีอักษรไทยปนอยู่ {sum(มีอักษรไทยปน.values()):,} ครั้ง ⇒ "
          + " ".join(f"{k!r}×{v}" for k, v in sorted(มีอักษรไทยปน.items(), key=lambda x: -x[1])))
    print("\n20 คำที่โผล่บ่อยที่สุด")
    print("  " + " ".join(f"{k}({v:,})" for k, v in นับ.most_common(20)))
    return 0


def สุ่มทาน(จำนวน):
    """พิมพ์คำที่สุ่มมาพร้อมคำข้างซ้ายขวา ⇒ คนอ่านตัดสินด้วยตาได้ว่าตัดถูกหรือผิด"""
    ข้อ = อ่านพระคัมภีร์()
    ทุกจุด = []
    for ที่อยู่, ตัวบท in ข้อ.items():
        คำ = ตัดคำ(ตัวบท)
        ทุกจุด += [(ที่อยู่, คำ, i) for i in range(len(คำ))]
    สุ่ม = random.Random(เมล็ด)
    รุ่น, สัญญา = รุ่นตัวตัดคำ()
    print(f"ตัวตัดคำ PyThaiNLP {รุ่น} · เครื่องยนต์ {เครื่องยนต์} · สัญญา {สัญญา}")
    print(f"จุดคำทั้งหมด {len(ทุกจุด):,} จุด ⇒ สุ่มมา {จำนวน} จุด ด้วยเมล็ด {เมล็ด}\n")
    for ลำดับ, (ที่อยู่, คำ, i) in enumerate(สุ่ม.sample(ทุกจุด, จำนวน), 1):
        ซ้าย = " ".join(คำ[max(0, i - 4):i])
        ขวา = " ".join(คำ[i + 1:i + 5])
        เล่ม, บท, ข = ที่อยู่
        print(f"{ลำดับ:>3}. {เล่ม} {บท}.{ข}  …{ซ้าย} 【{คำ[i]}】 {ขวา}…")
    return 0


def ขอบ(ชิ้นส่วน):
    """คืนตำแหน่งตัวอักษรที่เป็นเส้นแบ่งคำ ⇒ เอาไปเทียบสองฝ่ายได้ตรง ๆ"""
    ที่ตั้ง, ที่ = set(), 0
    for ท in ชิ้นส่วน:
        ที่ += len(ท)
        ที่ตั้ง.add(ที่)
    return ที่ตั้ง


def ช่วงที่ต่าง(ผู้แปล, เครื่อง):
    """คืนคู่ช่วงที่สองฝ่ายแบ่งไม่เหมือนกัน ⇒ [(ของผู้แปล, ของเครื่อง), ...]

    วิธี ⇒ ตัดข้อความที่ **เส้นแบ่งที่ทั้งสองฝ่ายเห็นตรงกัน** แล้วเทียบเนื้อในแต่ละช่วง
    ⇒ ได้คู่ที่เล็กที่สุดที่ต่างกันจริง ⛔ ไม่ใช่เดาจากรายการคำที่ไม่ตรง
    """
    ร่วม = sorted((ขอบ(ผู้แปล) & ขอบ(เครื่อง)) | {0})
    ออก = []
    for เริ่ม, จบ in zip(ร่วม, ร่วม[1:]):
        ก = [ท for ท in หั่นตามช่วง(ผู้แปล, เริ่ม, จบ)]
        ข = [ท for ท in หั่นตามช่วง(เครื่อง, เริ่ม, จบ)]
        if ก != ข:
            ออก.append((" · ".join(ก), " · ".join(ข)))
    return ออก


def หั่นตามช่วง(ชิ้นส่วน, เริ่ม, จบ):
    """คืนชิ้นที่อยู่ในช่วงตัวอักษร [เริ่ม, จบ)"""
    ออก, ที่ = [], 0
    for ท in ชิ้นส่วน:
        if เริ่ม <= ที่ < จบ:
            ออก.append(ท)
        ที่ += len(ท)
    return ออก


def เทียบเส้นแบ่ง():
    """เทียบเส้นแบ่งคำของตัวตัดคำ กับเส้นแบ่งที่ผู้แปลทำเครื่องหมายไว้เอง

    ⭐ ไฟล์ต้นฉบับ TCV ใส่ช่องว่างศูนย์ความกว้างคั่นคำไว้ให้แล้ว ⇒ มีของเทียบฟรี
    ⚠️ **ของผู้แปลไม่ใช่คำตอบที่ถูกต้อง** ⇒ เขาทำเครื่องหมายไว้ให้ตัดบรรทัดสวย
       ⇒ ตัวเลขนี้บอกว่า "สองฝ่ายแบ่งต่างกันแค่ไหน" ⛔ ไม่ใช่ "ตัวตัดคำผิดกี่ครั้ง"
       ⇒ ใครผิด ต้องคนทานด้วยตาตัดสิน ⇒ --สุ่มทาน
    """
    ข้อ = อ่านพระคัมภีร์()
    ตรงกัน = เครื่องละเอียดกว่า = เครื่องติดกัน = 0
    คู่ที่ต่าง = collections.Counter()
    for ตัวบท in ข้อ.values():
        สะอาด = unicodedata.normalize("NFC", ตัวบท).replace(ช่องแคบ, " ")
        for ท่อน in สะอาด.split():          # ช่องว่างจริงเป็นเส้นแบ่งของทั้งสองฝ่ายอยู่แล้ว
            ผู้แปล = [x for x in ท่อน.split(ช่องศูนย์) if x]
            ล้วน = "".join(ผู้แปล)
            if not ล้วน:
                continue
            เครื่อง = [x for x in word_tokenize(ล้วน, engine=เครื่องยนต์,
                                                keep_whitespace=False) if x]
            ก, ข = ขอบ(ผู้แปล), ขอบ(เครื่อง)
            ตรงกัน += len(ก & ข)
            เครื่องติดกัน += len(ก - ข)
            เครื่องละเอียดกว่า += len(ข - ก)
            for คู่ in ช่วงที่ต่าง(ผู้แปล, เครื่อง):
                if ไทยล้วน.match(คู่[0].replace(" · ", "")):
                    คู่ที่ต่าง[คู่] += 1
    ของผู้แปล = ตรงกัน + เครื่องติดกัน
    รุ่น, _ = รุ่นตัวตัดคำ()
    print(f"ตัวตัดคำ PyThaiNLP {รุ่น} · เครื่องยนต์ {เครื่องยนต์}")
    print(f"เส้นแบ่งที่ผู้แปลทำเครื่องหมายไว้ {ของผู้แปล:,} จุด")
    print(f"  ตัวตัดคำแบ่งตรงกัน            {ตรงกัน:,} จุด "
          f"({100 * ตรงกัน / ของผู้แปล:.2f}%)")
    print(f"  ตัวตัดคำรวมเป็นก้อนเดียว       {เครื่องติดกัน:,} จุด "
          f"({100 * เครื่องติดกัน / ของผู้แปล:.2f}%)")
    print(f"ตัวตัดคำแบ่งเพิ่มเองที่ผู้แปลไม่ได้แบ่ง {เครื่องละเอียดกว่า:,} จุด")
    print(f"\n25 ช่วงที่สองฝ่ายแบ่งต่างกันบ่อยที่สุด (รวม {len(คู่ที่ต่าง):,} รูป)")
    print(f"    {'กี่ครั้ง':>8}  {'ผู้แปลแบ่งว่า':<34} ตัวตัดคำแบ่งว่า")
    for (ก, ข), น in คู่ที่ต่าง.most_common(25):
        print(f"    {น:>8,}  {ก:<34} {ข}")
    return 0


