const จอกว้าง = { width: 1280, height: 900 }

/** กฎที่พังของจอกว้าง ⇒ ⑥ คือของเดิมที่คนตรวจทัก · ⑦ คือ `max-width` ตัวที่หักคำแปลกลางคำ
 *  ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/112 ⇒ ก้อนคำ ⛔ ไม่ลอยด้วย float แล้ว ⇒ อยู่ในตารางแถวของ `.pk-ตัวบท`
 *    ⇒ ถอด float อย่างเดียว ⛔ ไม่ทำให้ของพังอีกแล้ว ⇒ โหมดพิสูจน์ ⑥ จะจับไม่ได้ ⇒ **จึงถอดตารางด้วย**
 *    ⇒ ได้หน้าตาเดิมที่คนตรวจทักเป๊ะ ⇒ ก้อนคำทับบนตัวบทแปลทั้งบท ⇒ ⛔ ไม่ได้ผ่อนเกณฑ์ ⇒ ข้อ ⑥ วัดเหมือนเดิมทุกตัวอักษร */
