    if (ยังพอดี) ตก.push(`${ป้าย} ⇒ ⛔ ผู้อ่านที่เคยจำ พอดี ไว้ ยังได้แบบพอดี ${ยังพอดี} ก้อน ⇒ ต้องเป็นขนาดจริง`)

