    //     ⇒ แถวนี้เป็นก้อนโค้ดที่โหลดแยก ⇒ ขึ้นช้ากว่าคำได้ ⇒ ยัดตอนยังไม่มีแถว = ⛔ ไม่ได้ยัดอะไร ⇒ ฝาแฝดแดงเพราะตัวมันเอง ⛔ ไม่ใช่เพราะด่านตาย
