async function ตรวจจอกว้าง(สภาพ, ยัดกฎที่พัง) {
  const { เล่ม, บท, ชั้น } = สภาพ
  const ctx = await บริบทใหม่({ viewport: จอกว้าง })
  const แท็บ = await ctx.newPage()
  const ป้าย = `${เล่ม} ${บท} (${ชั้น}) จอ ${จอกว้าง.width}`
  const ตก = []

  try {
    await เปิด(แท็บ, `/read/${เล่ม}?c=${บท}`)
    if (ยัดกฎที่พัง) await แท็บ.addStyleTag({ content: กฎที่พังจอกว้าง })
    await ตั้งคำภาษาเดิม(แท็บ, true, บท, ตก)

    // ⑥ **คำเดิมกับคำแปลต้องเห็นพร้อมกัน** ⇒ วัดจากกรอบที่วาดจริง ⛔ ไม่ใช่จากกฎที่เขียนไว้
    //   ⇒ *เห็นพร้อมกัน* แปลว่า **ช่วงแนวตั้งทับกัน** และ **ช่วงแนวนอน ⛔ ไม่ทับกัน**
    //   ⇒ เกณฑ์ของใบ #95 หัวข้อ Description ⇒ *เทียบคำเดิมกับคำแปลได้ด้วยตาตัวเอง*
    const เคียง = await แท็บ.evaluate(() => {
      const กรอบ = (s) => {
        const e = document.querySelector(s)
        if (!e) return null
        const b = e.getBoundingClientRect()
        return { บน: b.top, ล่าง: b.bottom, ซ้าย: b.left, ขวา: b.right }
      }
      return { คำ: กรอบ('.pk-ชั้นคำ'), แปล: กรอบ('.pk-ข้อ') || กรอบ('.pk-ไหล') }
    })
    if (!เคียง.คำ || !เคียง.แปล) {
      ตก.push(`${ป้าย} ⇒ ⛔ หากล่องคำหรือกล่องคำแปลบนหน้าไม่เจอ`)
    } else {
      const ทับแนวตั้ง = เคียง.คำ.บน < เคียง.แปล.ล่าง && เคียง.แปล.บน < เคียง.คำ.ล่าง
      const แยกแนวนอน = เคียง.คำ.ซ้าย >= เคียง.แปล.ขวา || เคียง.แปล.ซ้าย >= เคียง.คำ.ขวา
      if (!ทับแนวตั้ง)
        ตก.push(`${ป้าย} ⇒ ⛔ คำเดิมกับคำแปล ⛔ ไม่เห็นพร้อมกัน ⇒ ต้องเลื่อนหาอีกฝั่ง`)
      if (!แยกแนวนอน) ตก.push(`${ป้าย} ⇒ ⛔ คำเดิมกับคำแปลทับกันในแนวนอน`)
    }

    // ⑦ **คำแปลกำกับ ⛔ ห้ามถูกหักเป็นหลายบรรทัดบนจอกว้าง** ⇒ อ่านเป็นคำไม่ออก = ใช้ไม่ได้
    //   ⛔ **ห้ามนับด้วย `getClientRects()` ของตัวกล่อง** ⇒ กล่องคำแปลเป็นลูกของ `inline-flex`
    //     ⇒ มันถูกทำให้เป็นบล็อก ⇒ **คืนกรอบเดียวเสมอ ต่อให้ข้างในหักกี่บรรทัดก็ตาม**
    //     ⇒ **หลงมาแล้ว 18 ต.ค. 2569** ⇒ ต้องกาง `Range` คร่อมตัวหนังสือแล้วนับกรอบของมันแทน
    const หัก = await แท็บ.evaluate(() => {
      const ผล = []
      for (const e of document.querySelectorAll('.pk-ชั้นคำ .pk-คำแปลคำ')) {
        const ช่วง = document.createRange()
        ช่วง.selectNodeContents(e)
        if (ช่วง.getClientRects().length > 1) ผล.push(e.textContent)
      }
      return ผล
    })
    if (หัก.length)
      ตก.push(`${ป้าย} ⇒ คำแปลถูกหักเป็นหลายบรรทัด ${หัก.length} คำ ⇒ เช่น ${หัก.slice(0, 3).join(' · ')}`)
  } catch (e) {
    ตก.push(`${ป้าย} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message}`)
  } finally {
    await ปิดบริบท(ctx, ป้าย, ตก)
  }
  return ตก
}

