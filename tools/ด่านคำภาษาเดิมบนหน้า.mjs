      //   ⇒ กล่องที่ตั้ง `overflow-x: clip` **ยังรายงาน `scrollWidth` ใหญ่กว่า `clientWidth` อยู่**
      //     ⇒ มันแค่ ⛔ ไม่ใช่กล่องที่เลื่อนได้ ⇒ **ตัวเลขบอกว่ามีของ แต่ผู้อ่านไปถึง ⛔ ไม่ได้**
      // ⭐ **จึงต้องลองเลื่อนจริง** ⇒ สั่งเลื่อนสุดทั้งสองทาง แล้วดูว่า `scrollLeft` ขยับไหม
      //   ⇒ **ลองทั้งสองทางเพราะฝั่งฮีบรูล้นไปทางซ้าย** ⇒ `scrollLeft` ของมันติดลบ
      //   ⇒ นี่คือสิ่งที่ผู้อ่านทำจริง ⛔ ไม่ใช่ความเชื่อที่อ่านจากตัวเลขของกล่อง
      const เลื่อนไม่ถึง = []
      for (const ก of กล่อง) {
        const ล้นข้างใน = [...ก.querySelectorAll('.pk-ข้อคำ')].some(
          (p) => p.scrollWidth - p.clientWidth > 1,
        )
        if (!ล้นข้างใน) continue
        const เดิม = ก.scrollLeft
        ก.scrollLeft = 9999
        const สุดขวา = ก.scrollLeft
        ก.scrollLeft = -9999
        const สุดซ้าย = ก.scrollLeft
        ก.scrollLeft = เดิม
        if (Math.abs(สุดขวา - เดิม) < 1 && Math.abs(สุดซ้าย - เดิม) < 1)
          เลื่อนไม่ถึง.push(ก.className)
      }
      // **คำแปล ⛔ ห้ามถูกหักกลางคำ** ⇒ แต่ **หักตรงรอยต่อของคำได้**
      //   ⛔⛔ **ฝั่งกรีกกับฝั่งฮีบรูคั่นคำคนละแบบ** ⇒ เจอตอนท่อ 11302 job 52298 แดง
