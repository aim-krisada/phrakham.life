def เขียนบัญชี():
    print("=== ด่านที่ต้องผ่านก่อนเขียนบัญชี ⇒ ⛔ แดงข้อไหนคือไม่เขียน")
    for คำสั่ง in ด่านก่อนเขียน:
        print(f"--- py -3.14 {' '.join(คำสั่ง)}", flush=True)
        ผล = subprocess.run([sys.executable, str(ที่เก็บ / คำสั่ง[0])] + คำสั่ง[1:],
                            cwd=str(ที่เก็บ))
        if ผล.returncode != 0:
            ตาย(f"`{' '.join(คำสั่ง)}` คืนค่า {ผล.returncode} ⇒ **ไม่เขียนบัญชี**\n"
                "   ⇒ บัญชีที่เขียนโดยไม่ผ่านด่านนี้ ไม่ใช่หลักฐาน")

    # ⭐ ตรึงกองต้นฉบับไว้ด้วย ⇒ โยงได้ว่าของก้อนนี้ออกมาจากกองไหน
    #   ⛔ ไม่ลอกเลข sha มาพิมพ์ ⇒ อ่านจากบัญชีของกองซึ่งเป็นเจ้าของเรื่องนั้น
    บัญชีกอง = ที่เก็บ / "docs" / "ลายนิ้วมือ.tsv"
    sha_กอง = ลายนิ้วมือไฟล์(บัญชีกอง)

    จริง = กวาดของจริง(กองที่ขึ้นเว็บ)
    บัญชี.parent.mkdir(parents=True, exist_ok=True)
    with open(บัญชี, "w", encoding="utf-8", newline="\n") as ฟ:
        ฟ.write("# ลายนิ้วมือของไฟล์ที่จะขึ้นเว็บ — ตรึงด้วย tools/ด่านเทียบต้นทาง.py --เขียน\n")
        ฟ.write("# ⛔ ห้ามแก้ด้วยมือ · แก้แล้วบัญชีจะเลิกเป็นหลักฐาน\n")
        ฟ.write("# ⭐ เขียนได้ก็ต่อเมื่อสร้างของใหม่จากกองต้นฉบับแล้วตรงกับ _data/ ทุกไบต์\n")
        ฟ.write(f"# กองต้นฉบับที่ใช้ ⇒ docs/ลายนิ้วมือ.tsv sha256 {sha_กอง}\n")
        ฟ.write(แท็บ.join(หัว) + chr(10))
        for ชื่อ in sorted(จริง):
            ไบต์, sha = จริง[ชื่อ]
            ฟ.write(แท็บ.join([ชื่อ, str(ไบต์), sha]) + chr(10))
    print(f"\n✅ เขียน {บัญชี} · {len(จริง):,} ไฟล์")
    return 0


