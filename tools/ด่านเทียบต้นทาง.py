def ตาย(ข้อความ, รหัส=2):
    print(f"⛔ {ข้อความ}")
    sys.exit(รหัส)


def ลายนิ้วมือไฟล์(ทาง):
    """sha256 ของไบต์ทั้งไฟล์ ⛔ ไม่แตะเนื้อข้างใน ⇒ แก้ตัวเดียวก็เปลี่ยน"""
    h = hashlib.sha256()
    with open(ทาง, "rb") as ฟ:
        for ก้อน in iter(lambda: ฟ.read(1 << 20), b""):
            h.update(ก้อน)
    return h.hexdigest()


def กวาดของจริง(ราก):
    """คืน {ชื่อไฟล์ญาติ: (ไบต์, sha256)} ของทุกไฟล์ใต้รากนั้น

    ⛔ ไม่กรองนามสกุล ⇒ ของแปลกที่ใครหย่อนเข้ามาก็ต้องโผล่เป็น "เกินมา"
    """
    ราก = Path(ราก)
    if not ราก.is_dir():
        ตาย(f"ไม่มีโฟลเดอร์ {ราก}")
    ออก = {}
    for ทาง in sorted(ราก.rglob("*")):
        if not ทาง.is_file():
            continue
        ไบต์ = ทาง.read_bytes()
        if ไบต์.startswith(b"version https://git-lfs"):
            ตาย(f"{ทาง} เป็นตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง\n"
                '   ⇒ สั่ง git lfs pull -I "_data/" ก่อน')
        ออก[ทาง.relative_to(ราก).as_posix()] = (len(ไบต์), ลายนิ้วมือไฟล์(ทาง))
    return ออก


def อ่านบัญชี(ที่=None):
    ที่ = Path(ที่ or บัญชี)
    if not ที่.exists():
        return None
    ผล = {}
    for เลขบรรทัด, บรรทัด in enumerate(open(ที่, encoding="utf-8"), 1):
        บรรทัด = บรรทัด.rstrip("\n")
        if not บรรทัด or บรรทัด.startswith("#"):
            continue
        ช่อง = บรรทัด.split(แท็บ)
        if ช่อง[0] == หัว[0]:
            continue
        if len(ช่อง) != len(หัว):
            ตาย(f"บัญชีบรรทัดที่ {เลขบรรทัด} มี {len(ช่อง)} ช่อง ⇒ ต้องมี {len(หัว)} ช่อง")
        try:
            ผล[ช่อง[0]] = (int(ช่อง[1]), ช่อง[2])
        except ValueError:
            ตาย(f"บัญชีบรรทัดที่ {เลขบรรทัด} ช่องตัวเลขอ่านไม่ออก ⇒ {บรรทัด}")
    return ผล


def เทียบ(จริง, เก่า, ละเอียด=True):
    """คืนจำนวนที่ต้องดู ⇒ 0 แปลว่าตรงกันทุกไฟล์"""
    ทัก = []
    for ชื่อ in sorted(set(เก่า) | set(จริง)):
        ก, ข = เก่า.get(ชื่อ), จริง.get(ชื่อ)
        if ก is None:
            ทัก.append((ชื่อ, "⚠ เกินมา", "อยู่ในกองแต่ไม่มีในบัญชี ⇒ ของที่ยังไม่ตรึง"))
        elif ข is None:
            ทัก.append((ชื่อ, "⛔ หายไป", "อยู่ในบัญชีแต่ไม่มีในกอง"))
        elif ก[1] != ข[1]:
            ทัก.append((ชื่อ, "⛔ เนื้อต่าง",
                        f"ไบต์ {ก[0]:,} ⇒ {ข[0]:,} · sha {ก[1][:12]}… ⇒ {ข[1][:12]}…"))
    if ละเอียด:
        for ชื่อ, ผล, บอก in ทัก[:20]:
            print(f"   {ชื่อ:34} {ผล:<12} {บอก}")
        if len(ทัก) > 20:
            print(f"   … และอีก {len(ทัก) - 20} ไฟล์")
    return len(ทัก)


