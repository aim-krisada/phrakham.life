def อ่านซอง() -> dict:
    ไบต์ = ซองเนื้อบท.read_bytes()
    if ไบต์[:40].startswith(b"version https://git-lfs"):
        sys.exit(f'⛔ {ซองเนื้อบท} เป็นตัวชี้ของ Git LFS ⇒ สั่ง git lfs pull -I "_data/" ก่อน')
    return json.loads(gzip.decompress(ไบต์).decode("utf-8"))["บท"]


def ขนาดจริง(ทาง: Path) -> int:
    """ขนาดไบต์ของไฟล์เสียง ⇒ ตัวชี้ของ LFS บอกขนาดไว้เอง ⇒ ท่อ ⛔ ต้องดึงไบต์จริง 30 กว่าเมกะไบต์ต่อฉบับ"""
    ต้น = ทาง.read_bytes()[:200]
    if ต้น.startswith(b"version https://git-lfs"):
        m = re.search(rb"\nsize (\d+)", ต้น)
        if not m:
            raise ValueError(f"ตัวชี้ของ LFS ที่ {ทาง} ไม่บอกขนาด")
        return int(m.group(1))
    return ทาง.stat().st_size


def ภาษาของชั้นบนเว็บ() -> dict[str, str]:
    """ตาราง `ภาษาของชั้น` ที่หน้าเว็บใช้ติด `lang` ให้คอลัมน์ ⇒ อ่านจากโค้ดของหน้าเว็บเอง ⛔ ไม่พิมพ์ซ้ำที่นี่"""
    ข้อความ = ไฟล์ภาษา.read_text("utf-8")
    m = re.search(r"const ภาษาของชั้น[^{]*\{([^}]*)\}", ข้อความ)
    if not m:
        sys.exit(f"⛔ หาตาราง ภาษาของชั้น ใน {ไฟล์ภาษา.relative_to(ราก)} ไม่เจอ ⇒ รูปเขียนเปลี่ยน ⇒ แก้ตัวอ่านในด่านนี้")
    return dict(re.findall(r"(\w+):\s*'([\w-]+)'", m.group(1)))


def ของจริง():
    ตัวบท = อ่านซอง()
    รายการ = {}
    for ฉบับ in sorted(เสียงของฉบับ):
        ทาง = ที่มา / f"{ฉบับ}.puck.json"
        if ทาง.exists():
            รายการ[ฉบับ] = json.loads(ทาง.read_text("utf-8"))
    # ⭐ ทุกโฟลเดอร์ย่อยของกองเสียง ⇒ โฟลเดอร์ที่ไม่มีรายการก็ต้องเห็น (ข้อ ②)
    ไฟล์ = {}
    if กองเสียง.is_dir():
        for โฟลเดอร์ in sorted(p for p in กองเสียง.iterdir() if p.is_dir()):
            ไฟล์[โฟลเดอร์.name] = {p.name: ขนาดจริง(p) for p in โฟลเดอร์.glob("*")}
    return ตัวบท, รายการ, ไฟล์, ภาษาของชั้นบนเว็บ()


def ตรวจ(ตัวบท: dict, รายการ: dict, ไฟล์: dict, ภาษา: dict) -> list[str]:
    """คืนรายการปัญหา ⇒ ว่างแปลว่าผ่าน ⇒ ⛔ ไม่พิมพ์เอง ⛔ ไม่ exit เอง ⇒ ทดสอบตัวเองถึงเรียกซ้ำได้"""
    ปัญหา: list[str] = []
    ต่ำสุด, สูงสุด = ช่วงสัดส่วนที่ยอมรับ

    # ② โฟลเดอร์ที่ไม่มีรายการ
    for โฟลเดอร์ in sorted(set(ไฟล์) - set(รายการ)):
        ปัญหา.append(f"② เสียง/ข้อ/{โฟลเดอร์}/ มี {len(ไฟล์[โฟลเดอร์])} ไฟล์ แต่ ⛔ ไม่มีรายการ เสียง/ที่มา/{โฟลเดอร์}.puck.json")

    for ฉบับ in sorted(เสียงของฉบับ):
        ร = รายการ.get(ฉบับ)
        if ร is None:
            ปัญหา.append(f"① {ฉบับ} ⇒ ⛔ ไม่มีรายการ เสียง/ที่มา/{ฉบับ}.puck.json ⇒ ฉบับนี้ไม่มีเสียงสักข้อ")
            continue
        มีไฟล์ = ไฟล์.get(ร.get("dir", "").strip("/"), {})

        # ⑦ ภาษาของเสียง = ภาษาของคอลัมน์บนเว็บ
        ภาษาเว็บ = ภาษา.get(ฉบับ)
        ภาษาเสียง = ร.get("languageCode", "")
        if ร.get("version") != ฉบับ:
            ปัญหา.append(f"⑦ {ฉบับ} ⇒ รายการบอกว่าเป็นฉบับ {ร.get('version')}")
        if not ภาษาเว็บ or ภาษาเสียง.split("-")[0] != ภาษาเว็บ or not ร.get("voice", "").startswith(ภาษาเสียง + "-"):
            ปัญหา.append(f"⑦ {ฉบับ} ⇒ คอลัมน์บนเว็บเป็นภาษา {ภาษาเว็บ} แต่เสียงคือ {ร.get('voice')} ({ภาษาเสียง})")
        อัตรา = อัตราอ่านของภาษา.get(ภาษาเสียง)

        # ⑧ ที่มาและสัญญา
        แหล่ง = ร.get("source") or {}
        for ช่อง in ("name", "url", "license", "licenseUrl", "permission", "notice"):
            if not str(แหล่ง.get(ช่อง, "")).strip():
                ปัญหา.append(f"⑧ {ฉบับ} ⇒ รายการไม่มี source.{ช่อง} ⇒ ผู้อ่านไม่รู้ว่าเสียงนี้มาจากไหนและใช้ได้เพราะอะไร")
        if re.search("[⇒⛔]", str(แหล่ง.get("notice", ""))):
            ปัญหา.append(f"⑧ {ฉบับ} ⇒ ประกาศที่มามีเครื่องหมาย ⇒ หรือ ⛔ ⇒ ฟอนต์ของเว็บไม่มีตัวนี้")

        # ④ ข้อที่ควรมี ⇒ นับจากตัวบทของเราเอง
        ควรมี = set()
        for รหัสเล่ม, osis in เล่มที่มีเสียงของฉบับอื่น.items():
            c = 1
            while f"{รหัสเล่ม}/{c}" in ตัวบท:
                for v in (ตัวบท[f"{รหัสเล่ม}/{c}"].get(ฉบับ) or {}):
                    ควรมี.add(f"{osis}.{c}.{v}")
                c += 1
        ข้อ = ร.get("verses") or {}
        เว้น = {g.get("id"): g for g in ร.get("gaps") or []}
        for g in เว้น.values():
            if not str(g.get("reason", "")).strip():
                ปัญหา.append(f"④ {ฉบับ} {g.get('id')} ⇒ จงใจไม่มีเสียงแต่ ⛔ ไม่บอกเหตุผล")
            if g.get("id") in ข้อ:
                ปัญหา.append(f"④ {ฉบับ} {g.get('id')} ⇒ อยู่ทั้งในข้อที่มีเสียงและข้อที่จงใจไม่มีเสียง")
            if f"{g.get('id')}.puck.mp3" in มีไฟล์:
                ปัญหา.append(f"④ {ฉบับ} {g.get('id')} ⇒ จงใจไม่มีเสียงแต่มีไฟล์อยู่จริง")
        ขาด = sorted(ควรมี - set(ข้อ) - set(เว้น))
        เกิน = sorted((set(ข้อ) | set(เว้น)) - ควรมี)
        if ขาด:
            ปัญหา.append(f"④ {ฉบับ} ⇒ {len(ขาด)} ข้อที่ตาเห็นบนเว็บ ⛔ ไม่มีเสียงและ ⛔ ไม่มีเหตุผล ⇒ {ขาด[:5]}")
        if เกิน:
            ปัญหา.append(f"④ {ฉบับ} ⇒ {len(เกิน)} ข้อในรายการ ⛔ ไม่มีตัวบทบนเว็บ ⇒ {เกิน[:5]}")

        ส่วนเกิน = sorted(มีไฟล์[e["file"]] - ไบต์ต่อวินาที * float(e.get("d") or 0)
                          for e in ข้อ.values() if e.get("file") in มีไฟล์)
        หัวไฟล์ = ส่วนเกิน[len(ส่วนเกิน) // 2] if ส่วนเกิน else 0
        for รหัส, e in sorted(ข้อ.items()):
            # ①
            if e.get("file") not in มีไฟล์:
                ปัญหา.append(f"① {ฉบับ} {รหัส} ⇒ รายการบอกว่ามีเสียง แต่ ⛔ ไม่มีไฟล์ {ร.get('dir')}{e.get('file')}")
                continue
            osis, c, v = รหัส.split(".")
            รหัสเล่ม = {o: k for k, o in เล่มที่มีเสียงของฉบับอื่น.items()}.get(osis)
            ดิบ = ((ตัวบท.get(f"{รหัสเล่ม}/{c}") or {}).get(ฉบับ) or {}).get(v)
            if ดิบ is None:
                continue  # นับเป็นข้อ ④ เกินไปแล้ว
            พูด = ตัวบทที่ส่งไปพ่นของฉบับ(ฉบับ, ดิบ)
