/**
 * ⭐ ดักการกดลูกศรแถบล่าง ⇒ พาไปที่อยู่ที่พฤติกรรมผิดจะได้ ⇒ คิดจากที่อยู่ก่อนกดกับ `href` ตัวจริง
 *   ⇒ ⛔ ไม่ได้แตะโค้ดของเว็บ ⇒ หน้าที่โหลดใหม่ตามที่อยู่นั้นวาดด้วยโค้ดจริง
 */
function ตัวดักกด(ชนิด) {
  document.addEventListener(
    'click',
    (e) => {
      const a = e.target instanceof Element ? e.target.closest('a[data-ปุ่ม="บทถัดล่าง"], a[data-ปุ่ม="บทก่อนล่าง"]') : null
      if (!a || !e.isTrusted) return
      e.preventDefault()
      e.stopImmediatePropagation()
      const ทิศ = a.getAttribute('data-ปุ่ม') === 'บทถัดล่าง' ? 1 : -1
      const เดิม = new URLSearchParams(location.search)
      const ไป = new URL(a.href)
      const q = ไป.searchParams
      const c = Number(เดิม.get('c'))
      const เล่ม = location.pathname.split('/').filter(Boolean).pop()
      const pเดิม = (เดิม.get('p') || '').split(',').filter(Boolean)
      const ฉบับ = (q.get('t') || '').split(',').filter(Boolean)
      const pใหม่ = (q.get('p') || '').split(',').filter(Boolean)
      if (ชนิด === 'แบบเดิม') {
        // ทุกคอลัมน์ไปบทถัดไปในเล่มของตัวเอง ⇒ ตารางเท่าเดิม
        q.set('t', เดิม.get('t') || '')
        q.set('p', pเดิม.map((x) => x.replace(/^([^.]+)\.(\d+)/, (_, ล, บ) => `${ล}.${Number(บ) + ทิศ}`)).join(','))
      } else if (ชนิด === 'ซ้ายไม่ขยับ') {
        q.set('c', String(c))
        q.set('t', เดิม.get('t') || '')
        q.set('p', pเดิม.map((x) => x.replace(/^[^.]+\.\d+/, `${เล่ม}.${c}`)).join(','))
      } else if (ชนิด === 'ฉบับเปลี่ยน') {
        if (pใหม่.length) q.set('p', pใหม่.map((x) => x.replace(/\.[A-Z0-9]+$/, '.WEB')).join(','))
        else q.set('t', [...ฉบับ.slice(0, -1), 'WEB'].join(','))
      } else if (ชนิด === 'ปิดคอลัมน์') {
        if (pใหม่.length) q.delete('p')
        else q.set('t', ฉบับ.slice(0, -1).join(','))
      } else if (ชนิด === 'ไม่ดึงกลับ') {
        // บทเดียวกัน แต่ฉบับที่เพิ่งเข้าตารางถูกส่งกลับไปไหลเองเป็นคอลัมน์คนละกล่อง
        //   ⇒ ข้อ 5 ⇒ ที่เดียวกันทั้งเล่ม บท ข้อ เท่านั้นที่หน้าเอาเข้าตาราง (ใบ #143) ⇒ ข้อ 5 จึงยังไหลเอง ⇒ ป้ายหัวยังเป็นบทเดียวกัน
        const เดิมt = (เดิม.get('t') || '').split(',').filter(Boolean)
        const เพิ่ม = ฉบับ.filter((x) => !เดิมt.includes(x))
        q.set('t', ฉบับ.filter((x) => เดิมt.includes(x)).join(','))
        q.set('p', [...pใหม่, ...เพิ่ม.map((x) => `${เล่ม}.${q.get('c')}.${x}.5`)].join(','))
      }
      if (!q.get('p')) q.delete('p')
      location.assign(ไป.pathname + '?' + q.toString().replace(/%2C/g, ','))
    },
    true,
  )
}

/** ⭐ ของพัง *ลิงก์ไม่ตรง* ⇒ เขียน `href` แบบเดิม (ใบ #125) ทับตอนอ่าน ⇒ การกดยังเป็นของจริง */
async function อ่านลิงก์(แท็บ, ชนิด, พัง) {
  return แท็บ.evaluate(
    ([ช, ผิด]) => {
      const a = document.querySelector(`.pk-แถบล่าง a[data-ปุ่ม="${ช}"]`)
      if (!a) return null
      if (ผิด) {
        const ทิศ = ช === 'บทถัดล่าง' ? 1 : -1
        const เดิม = new URLSearchParams(location.search)
        const ไป = new URL(a.href)
        const p = (เดิม.get('p') || '').split(',').filter(Boolean)
        if (p.length) {
          ไป.searchParams.set('p', p.map((x) => x.replace(/^([^.]+)\.(\d+)/, (_, ล, บ) => `${ล}.${Number(บ) + ทิศ}`)).join(','))
          ไป.searchParams.set('t', เดิม.get('t') || '')
        }
        a.setAttribute('href', ไป.pathname + '?' + ไป.searchParams.toString().replace(/%2C/g, ','))
      }
      return a.getAttribute('href')
    },
    [ชนิด, !!พัง?.ลิงก์ไม่ตรง],
  )
}

async function เปิด(ที่อยู่, จอ, พัง) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: จอ })
  if (พัง?.พาไป) await ctx.addInitScript(ตัวดักกด, พัง.พาไป)
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}${ที่อยู่}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('.pk-หัวช่อง', { timeout: 30000 })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  await รอนิ่ง(แท็บ)
  return { ctx, แท็บ }
}

/** อ่านสภาพหน้า ⇒ คอลัมน์ที่มีหัว เรียงตามลำดับที่วาด (บนลงล่าง ซ้ายไปขวา) ⇒ ท่าเดียวกับ `ด่านคอลัมน์แบบเดียว` */
const สภาพ = (แท็บ) =>
  แท็บ.evaluate(() => {
    const คอลัมน์ = [...document.querySelectorAll('.pk-หัวช่อง')]
      .filter((h) => h.getClientRects().length > 0 && !h.closest('[data-ชื่อคำเดิม]'))
      .map((h) => {
        const r = h.getBoundingClientRect()
        return {
          ป้าย: (h.querySelector('.pk-ที่ของช่อง')?.textContent || '').replace(/\s+/g, ' ').trim(),
          ฉบับ: h.querySelector('select')?.value || '',
          ในตาราง: !h.closest('.pk-ตอนเทียบ'),
          บน: Math.round(r.top + scrollY),
          ซ้าย: Math.round(r.left),
        }
      })
      // ⭐ ตารางมาก่อนกล่องไหลเองเสมอ (ซ้ายสุดคือช่องแรกของตาราง) ⇒ ในกองเดียวกันเรียงตามที่วาด
      .sort((a, b) => Number(b.ในตาราง) - Number(a.ในตาราง) || a.บน - b.บน || a.ซ้าย - b.ซ้าย)
      .map(({ บน, ซ้าย, ...x }) => x)
    return { คอลัมน์, ที่อยู่: location.pathname + location.search }
  })

const เขียน = (ค) => ค.map((x) => `${x.ป้าย} ${x.ฉบับ}${x.ในตาราง ? ' (ตาราง)' : ''}`).join(' | ')

/** ⭐ รอจนหน้านิ่งจริง ⇒ หัวอ่านได้ 2 รอบติดกันเหมือนกัน · ⛔ มีคอลัมน์ *กำลังเปิด* ⇒ ⛔ รอเป็นเวลาตายตัว */
async function รอนิ่ง(แท็บ) {
  let ก่อน = ''
  const เส้นตาย = Date.now() + 20000
  while (Date.now() < เส้นตาย) {
    await แท็บ.waitForTimeout(300)
    const ส = await สภาพ(แท็บ).catch(() => null)
    if (!ส || !ส.คอลัมน์.length) continue
    const กำลังเปิด = await แท็บ.evaluate(() => /กำลังเปิดตอนนี้/.test(document.body.innerText)).catch(() => true)
    const ตอนนี้ = JSON.stringify(ส)
    if (!กำลังเปิด && ตอนนี้ === ก่อน) return
    ก่อน = ตอนนี้
  }
}

/**
 * ⭐ เลื่อนคู่ = ข้อเดียวกันของทุกฉบับในตารางอยู่ในแถวเดียวกัน ⇒ ท่าเดียวกับ `วัดแถว` ของ `tools/ด่านคอลัมน์แบบเดียว.mjs`
 *   ⇒ ข้อ 1 ถึง 3 ⇒ คืนฉบับที่ช่องของมัน ⛔ อยู่ในกรอบแถวของข้อนั้น (ข้อละรายการ)
 */
const ไม่ตรงแถว = (แท็บ, บท, ฉบับ) =>
  แท็บ.evaluate(
    ([c, ชุด]) => {
      const ผิด = []
      for (const n of [1, 2, 3]) {
        const แถว = document.querySelector(`.pk-ตัวบท .pk-ข้อ[data-ข้อ="${c}:${n}"]`)
        const ก = แถว?.getBoundingClientRect()
        for (const ฉ of ชุด) {
          const el = แถว?.querySelector(`.pk-ช่องฉบับ[data-ฉบับ="${ฉ}"]`)
          const r = el?.getClientRects().length ? el.getBoundingClientRect() : null
          if (!ก || !r || r.top < ก.top - 1 || r.bottom > ก.bottom + 1) ผิด.push(`${c}:${n} ${ฉ}`)
        }
      }
      return ผิด
    },
    [บท, ฉบับ],
  )

const เรียงฉบับ = (ค) => ค.map((x) => x.ฉบับ).sort().join(',')

async function ตรวจ(พัง = null) {
  const ตก = []
  const พูด = []
  for (const ช of ชุด) {
    for (const [ชนิด, ทิศ] of [['บทถัดล่าง', 1], ['บทก่อนล่าง', -1]]) {
      const เรื่อง = `${ช.ชื่อ} · กด ${ทิศ > 0 ? '›' : '‹'}`
      let ctx
      try {
        const เปิดได้ = await เปิด(ช.ทาง, ช.จอ, พัง)
        ctx = เปิดได้.ctx
        const แท็บ = เปิดได้.แท็บ
        const ก่อน = await สภาพ(แท็บ)
        if (ก่อน.คอลัมน์.length < 2 || !ก่อน.คอลัมน์.some((x) => !x.ในตาราง)) {
          ตก.push(`${เรื่อง} ⇒ เปิดชุดแล้วเห็น ${เขียน(ก่อน.คอลัมน์)} ⇒ ⛔ มีคอลัมน์คนละตอนให้ตรวจ`)
          continue
        }
        const ลิงก์ = await อ่านลิงก์(แท็บ, ชนิด, พัง)
        if (!ลิงก์) {
          ตก.push(`① ${เรื่อง} ⇒ ⛔ เจอลูกศร ${ชนิด} บนแถบล่าง`)
          continue
        }
        await แท็บ.locator(`.pk-แถบล่าง a[data-ปุ่ม="${ชนิด}"]`).click()
        await แท็บ.waitForFunction((เดิม) => location.pathname + location.search !== เดิม, ก่อน.ที่อยู่, { timeout: 15000 }).catch(() => {})
        await แท็บ.waitForSelector('.pk-หัวช่อง', { timeout: 30000 }).catch(() => {})
        await รอนิ่ง(แท็บ)
        const หลัง = await สภาพ(แท็บ)
        const บทใหม่ = ช.บท + ทิศ
        const ป้ายใหม่ = `${ชื่อเล่ม} ${บทใหม่}`
        const ค = หลัง.คอลัมน์
        const q = new URL(`http://x${หลัง.ที่อยู่}`).searchParams

        // ① คอลัมน์ซ้ายสุดไปบทเดียว
        if (ค[0]?.ป้าย !== ป้ายใหม่ || !ค[0]?.ในตาราง || q.get('c') !== String(บทใหม่))
          ตก.push(`① ${เรื่อง} ⇒ คอลัมน์ซ้ายสุดเป็น “${ค[0]?.ป้าย}” · c=${q.get('c')} ⇒ ต้องไป ${ป้ายใหม่} (บทเดียวจาก ${ช.บท})`)
        // ② ทุกคอลัมน์เล่มและบทเดียวกับซ้ายสุด
        const ไม่ตาม = ค.filter((x) => x.ป้าย !== ค[0]?.ป้าย)
        if (ไม่ตาม.length)
          ตก.push(`② ${เรื่อง} ⇒ ${ไม่ตาม.map((x) => `${x.ฉบับ} อยู่ “${x.ป้าย}”`).join(' · ')} ⇒ ต้องอยู่ “${ค[0]?.ป้าย}” เหมือนคอลัมน์ซ้ายสุด ⇒ เห็น ${เขียน(ค)}`)
        // ③ ฉบับคงเดิม ⇒ ⛔ คอลัมน์หาย
        if (ค.length !== ก่อน.คอลัมน์.length || เรียงฉบับ(ค) !== เรียงฉบับ(ก่อน.คอลัมน์))
          ตก.push(`③ ${เรื่อง} ⇒ ก่อนกด ${เขียน(ก่อน.คอลัมน์)} ⇒ หลังกด ${เขียน(ค)} ⇒ ฉบับต้องครบชุดเดิม ⛔ คอลัมน์หาย`)
        // ④ คอลัมน์คนละตอนกลับเข้าตาราง ⇒ เลื่อนคู่
        if (ช.ดึงกลับ) {
          const ตัว = ค.find((x) => x.ฉบับ === ช.ดึงกลับ)
          if (!ตัว?.ในตาราง || ค.some((x) => !x.ในตาราง))
            ตก.push(`④ ${เรื่อง} ⇒ คอลัมน์ ${ช.ดึงกลับ} ที่เคยอยู่ลูกา 5 ⇒ เห็น ${เขียน(ค)} ⇒ ต้องอยู่ในตารางกับคอลัมน์ซ้ายสุด (เลื่อนคู่กัน)`)
        } else if (ค.filter((x) => !x.ในตาราง).some((x) => x.ป้าย !== ป้ายใหม่))
          ตก.push(`④ ${เรื่อง} ⇒ คอลัมน์ฉบับซ้ำ ⇒ เห็น ${เขียน(ค)} ⇒ ต้องอยู่ ${ป้ายใหม่} ตอนเดียวกับคอลัมน์ซ้ายสุด`)
        {
          const ผิด = await ไม่ตรงแถว(แท็บ, บทใหม่, ค.filter((x) => x.ในตาราง).map((x) => x.ฉบับ))
          if (ผิด.length) ตก.push(`④ ${เรื่อง} ⇒ ${ผิด.join(' · ')} ⛔ อยู่ในแถวของข้อนั้นในตาราง ⇒ ต้องเลื่อนคู่กับคอลัมน์ซ้ายสุด`)
        }
        // ⑤ href = ที่อยู่หลังกด ⇒ แล้วเปิดในเครื่องใหม่ได้ชุดเดียวกัน
        if (decodeURIComponent(ลิงก์) !== decodeURIComponent(หลัง.ที่อยู่))
          ตก.push(`⑤ ${เรื่อง} ⇒ ลิงก์บนลูกศร “${decodeURIComponent(ลิงก์)}” ⇒ หลังกดได้ “${decodeURIComponent(หลัง.ที่อยู่)}” ⇒ ต้องเป็นหน้าเดียวกัน`)
        else {
          const ใหม่ = await เปิด(ลิงก์.replace(new RegExp(`^${เส้นทางเว็บ}`), ''), ช.จอ, null)
          try {
            const ส = await สภาพ(ใหม่.แท็บ)
            if (เขียน(ส.คอลัมน์) !== เขียน(ค))
              ตก.push(`⑤ ${เรื่อง} ⇒ เปิดลิงก์ของลูกศรในเครื่องใหม่ได้ ${เขียน(ส.คอลัมน์)} ⇒ ต้องเหมือนหลังกด ${เขียน(ค)}`)
          } finally {
            await ใหม่.ctx.close()
          }
        }
        พูด.push(`  ${เรื่อง} ⇒ ${เขียน(ค)} · ${decodeURIComponent(หลัง.ที่อยู่)}`)
      } catch (e) {
        ตก.push(`${พัง ? พัง.ข้อ : '①'} ${เรื่อง} ⇒ ล้มระหว่างตรวจ ⇒ ${e.message.split('\n')[0]}`)
      } finally {
        await ctx?.close()
      }
    }
  }
  return { ตก, พูด }
}

