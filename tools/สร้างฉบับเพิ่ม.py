def ห่อ(ของ):
    ข้อความ = json.dumps(ของ, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    ถัง = io.BytesIO()
    # mtime=0 ⇒ ⛔ ไม่ประทับเวลาลงหัวซอง
    with gzip.GzipFile(fileobj=ถัง, mode="wb", compresslevel=9, mtime=0) as ซ:
        ซ.write(ข้อความ.encode("utf-8"))
    return ถัง.getvalue()


