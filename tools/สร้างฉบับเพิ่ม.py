def sha(ไบต์):
    return hashlib.sha256(ไบต์).hexdigest()


def ข้อความตัวบท(ข้อ):
    """ตัวบททั้งฉบับเป็นตัวหนังสือชุดเดียว ⇒ เรียงกุญแจตายตัว ⇒ ข้อมูลเท่าเดิมได้ลายนิ้วมือเดิม"""
