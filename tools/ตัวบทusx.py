# กองที่จะขึ้นเว็บ ⇒ อยู่ใต้ `_data/` เพราะท่อ CI ดึงไบต์จริงของโฟลเดอร์นี้โฟลเดอร์เดียว
#   (เหตุผลเต็มอยู่ที่ `.lfsconfig` กับหัวข้อ `.เอาซองตัวบท` ใน `.gitlab-ci.yml`)
ปลายทาง = ที่เก็บ / "_data" / "ตัวบท"


class ฉบับหนึ่ง:
    """ฉบับแปลหนึ่งฉบับ ⇒ รหัส · รูปของต้นทาง · ที่อยู่ในกอง"""

    def __init__(self, รหัส, รูป, ที่อยู่):
        self.รหัส = รหัส
        # "usx" = เจ้าของให้มาเป็น USX อยู่แล้ว · "usfm" = ต้องแปลงด้วยตัวแปลงมาตรฐานก่อน
        self.รูป = รูป
        self.ที่อยู่ = กอง / ที่อยู่
        self.เจ้าของ = แหล่งของชั้น[รหัส]

    def ไฟล์usx(self, เล่ม):
        """ที่อยู่ของไฟล์ USX ที่จะเอาไปห่อขึ้นเว็บ

        รูป `usx` ⇒ คือไฟล์ของเจ้าของเอง
        รูป `usfm` ⇒ คือผลของตัวแปลงมาตรฐาน ซึ่งวางไว้ที่ `_usxแปลง/`
        """
        if self.รูป == "usx":
            return self.ที่อยู่ / f"{เล่ม}.usx"
        return ที่พักแปลง / self.รหัส / f"{เล่ม}.usx"


