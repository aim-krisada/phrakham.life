def ลายของ(ข้อความ):
    import hashlib

    return hashlib.blake2b(ข้อความ.encode("utf-8"), digest_size=5).hexdigest()


class กองลายนิ้วมือ:
    """ทำตัวเหมือนข้อความกอง way ⇒ ใช้ `in` · `find` · `bool` ได้เหมือนเดิม"""

    def __init__(self, ชุด, คอมมิต, จำนวนไฟล์):
        self.ชุด = ชุด
        self.คอมมิต = คอมมิต
        self.จำนวนไฟล์ = จำนวนไฟล์

    def __bool__(self):
        return bool(self.ชุด)

    def __contains__(self, ข้อความ):
        if len(ข้อความ) < ยาวหน้าต่าง:
            raise ValueError(f"ข้อความสั้นกว่าหน้าต่าง {ยาวหน้าต่าง} ตัว ⇒ ลายนิ้วมือตอบ ⛔ ไม่ได้")
        return all(
            ลายของ(ข้อความ[j : j + ยาวหน้าต่าง]) in self.ชุด
            for j in range(len(ข้อความ) - ยาวหน้าต่าง + 1)
        )

    def find(self, ข้อความ):
        return 0 if ข้อความ in self else -1


def สร้างชุดลายนิ้วมือ(กอง):
    return {ลายของ(กอง[j : j + ยาวหน้าต่าง]) for j in range(len(กอง) - ยาวหน้าต่าง + 1)}


def เขียนลายนิ้วมือ(ที่อยู่way, ไฟล์ออก, คอมมิต):
    import gzip
    import json

    กอง, _, จำนวนไฟล์ = สร้างกองway(ที่อยู่way)
    ชุด = sorted(สร้างชุดลายนิ้วมือ(กอง))
    ข้อมูล = {
        "ที่มา": "v3/way",
        "คอมมิต": คอมมิต,
        "จำนวนไฟล์": จำนวนไฟล์,
        "ยาวหน้าต่าง": ยาวหน้าต่าง,
        "ลาย": "".join(ชุด),
    }
    with gzip.open(ไฟล์ออก, "wt", encoding="utf-8") as f:
        json.dump(ข้อมูล, f, ensure_ascii=False)
    print(f"✅ เขียนลายนิ้วมือ {len(ชุด)} หน้าต่าง จาก {จำนวนไฟล์} ไฟล์ของ way ({คอมมิต}) ⇒ {ไฟล์ออก}")


def อ่านลายนิ้วมือ(ไฟล์):
    import gzip
    import json

    with gzip.open(ไฟล์, "rt", encoding="utf-8") as f:
        ข้อมูล = json.load(f)
    if ข้อมูล.get("ยาวหน้าต่าง") != ยาวหน้าต่าง:
        raise SystemExit(f"⛔ ลายนิ้วมือใช้หน้าต่าง {ข้อมูล.get('ยาวหน้าต่าง')} ⛔ ไม่ใช่ {ยาวหน้าต่าง} ⇒ สร้างใหม่")
    ลาย = ข้อมูล["ลาย"]
    ชุด = {ลาย[k : k + 10] for k in range(0, len(ลาย), 10)}
    return กองลายนิ้วมือ(ชุด, ข้อมูล.get("คอมมิต", "?"), ข้อมูล.get("จำนวนไฟล์", 0))


def หาท่อนซ้ำ(เนื้อเรา, บรรทัดของเรา, กองway, ที่ไหนway, เพดาน):
    if isinstance(กองway, กองลายนิ้วมือ):
        return หาท่อนซ้ำด้วยลายนิ้วมือ(เนื้อเรา, บรรทัดของเรา, กองway, ที่ไหนway, เพดาน)
    เจอ = []
    i = 0
    n = len(เนื้อเรา)
    while i + เพดาน <= n:
        ท่อน = เนื้อเรา[i : i + เพดาน]
        ที่ = กองway.find(ท่อน)
        if ที่ < 0:
            i += 1
            continue
        ยาว = เพดาน
        while i + ยาว < n and กองway.find(เนื้อเรา[i : i + ยาว + 1]) >= 0:
            ยาว += 1
        ที่ = กองway.find(เนื้อเรา[i : i + ยาว])
        เจอ.append((i, เนื้อเรา[i : i + ยาว], บรรทัดของเรา[i], ที่ไหนway(ที่)))
        i += ยาว
    return เจอ


def หาท่อนซ้ำด้วยลายนิ้วมือ(เนื้อเรา, บรรทัดของเรา, กองway, ที่ไหนway, เพดาน):
    """ผลเท่ากับ `หาท่อนซ้ำ` ⇒ แต่คิดลายของทุกหน้าต่างครั้งเดียว ⛔ ไม่คิดซ้ำทุกรอบที่ยืดท่อน

    ⇒ ท่อน [i, i+ยาว) อยู่ในกอง ⇔ หน้าต่างที่เริ่ม i ถึง i+ยาว-20 มีลายอยู่ในชุดทุกตัว
    """
    n = len(เนื้อเรา)
    มี = [
        ลายของ(เนื้อเรา[j : j + ยาวหน้าต่าง]) in กองway.ชุด
        for j in range(max(0, n - ยาวหน้าต่าง + 1))
    ]
    # ติดกันได้ไกลแค่ไหน ⇒ ติด[j] = จำนวนหน้าต่างที่มีลายติดกันนับจาก j
    ติด = [0] * (len(มี) + 1)
    for j in range(len(มี) - 1, -1, -1):
        ติด[j] = ติด[j + 1] + 1 if มี[j] else 0

    เจอ = []
    i = 0
    while i + เพดาน <= n:
        ยาวได้ = ติด[i] + ยาวหน้าต่าง - 1 if ติด[i] else 0
        if ยาวได้ < เพดาน:
            i += 1
            continue
        ยาว = min(ยาวได้, n - i)
        เจอ.append((i, เนื้อเรา[i : i + ยาว], บรรทัดของเรา[i], ที่ไหนway(0)))
        i += ยาว
    return เจอ


