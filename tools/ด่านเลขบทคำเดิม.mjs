/** ข้อเดิมที่ควรอยู่ในก้อนบท c ⇒ ส่งเข้าหน้าเพื่อรอให้ครบ ⇒ `[{ที่, บท, ข้อ, ไป, ภาษา}]` ของบท c−1 ถึง c+1 */
async function ข้อเดิมรอบบท(เล่ม, c) {
  const ไฟล์ = await ไฟล์คำของเล่ม(สารบัญ.เล่ม.find((x) => x.รหัส === เล่ม))
  return [c - 1, c, c + 1].flatMap((b) => (ไฟล์[b] ? ข้อเดิมของไฟล์(ไฟล์[b]) : []))
}

/**
 * ⭐ รอข้อเดิมในก้อนบท c ครบชุด + ตัวจัดแถวจัดเสร็จ + ฟอนต์มาครบ ⇒ ⛔ ไม่รอเป็นเวลาตายตัว
 *   ⇒ ชุดที่ควรมีคิดในหน้า **จากบทที่อยู่บนหน้าตอนนั้น** ⇒ บทข้างเคียงต่อเข้ามาทีหลังได้ ⇒ ชุดเปลี่ยนตาม
 */
function รอครบ(แท็บ, บท, รอบบท, ช่วง) {
  return แท็บ
    .waitForFunction(
      ([c, รอบ, ช]) => {
        // ⭐ จอแคบ ⇒ คำของบท c อยู่ใต้แต่ละแถว ⇒ หลายกล่องที่ชื่อเดียวกัน (ใบ #124) ⇒ รวมทุกกล่องของบท ⛔ ไม่ดูแค่กล่องแรก
        const ก้อน = [...document.querySelectorAll(`.pk-ชั้นคำ[aria-label$=" ${c}"]`)]
        if (!ก้อน.some((g) => g.querySelector('.pk-คำ'))) return false
        const บนหน้า = [...document.querySelectorAll('[data-หมุดบท]')].map((e) => Number(e.dataset.หมุดบท))
        const ใน = (บ, ข) => !ช || (บ * 1000 + ข >= ช[0] && บ * 1000 + ข <= ช[1])
        const ควร = new Set(รอบ.filter((x) => x.ไป.find(([บ, ข]) => บนหน้า.includes(บ) && ใน(บ, ข))?.[0] === c).map((x) => x.ที่))
        const มี = new Set(ก้อน.flatMap((g) => [...g.querySelectorAll('.pk-ข้อคำ[data-ข้อเดิม]')]).map((p) => p.dataset.ข้อเดิม))
        if (มี.size !== ควร.size || [...ควร].some((k) => !มี.has(k))) return false
        return document.querySelector('.pk-ตัวบท')?.getAttribute('data-จัดแถว') === 'เสร็จ' && document.fonts.status === 'loaded'
      },
      [บท, รอบบท, ช่วง],
      { timeout: รอนานสุด },
    )
    .then(() => true)
    .catch(() => false)
}

/**
 * อ่านเลขของทุกข้อเดิมในก้อนบท c ⇒ `{ที่, ภาษา, เห็น, ได้ยิน}` ⇒ และเลขข้อแรกของก้อนฝั่งฉบับแปล
 *   ⇒ `เห็น` ⇒ ตัวหนังสือที่วาดออกมาจริง ⇒ ข้ามของที่ซ่อนด้วย CSS (รวมท่าเฉพาะเสียงแบบ `.pk-เฉพาะเสียง`)
 *   ⇒ `ได้ยิน` ⇒ `aria-label` ถ้ามี ⇒ ไม่มีก็ตัวหนังสือทั้งหมดที่ ⛔ ไม่อยู่ใต้ `aria-hidden`
 */
function อ่านเลข(แท็บ, บท) {
  return แท็บ.evaluate((c) => {
    // ⭐ ทุกกล่องของบท c ⇒ จอกว้างมีกล่องเดียว · จอแคบมีกล่องใต้ทุกแถว (ใบ #124) ⇒ ⛔ ไม่ดูแค่กล่องแรก
    const ก้อน = [...document.querySelectorAll(`.pk-ชั้นคำ[aria-label$=" ${c}"]`)]
    // ⭐ ซ่อนจากตา ⇒ ดูจากท่าซ่อนจริงของ CSS ⛔ ไม่ดูจากขนาดอย่างเดียว
    //   ⇒ แบบพอดีย่อตัวหนังสือได้ไม่มีขั้นต่ำ (ใบ #112 ข้อ 11.1) ⇒ เลขข้อที่ถูกย่อจนเล็กมากยังเป็นของที่ตาเห็น
    //   ⇒ ท่าซ่อนแบบเฉพาะเสียง (`.pk-เฉพาะเสียง`) ⇒ กล่อง 1×1 จุด + ตัดของล้น หรือ `clip-path`
    const เห็นได้ = (e) => {
      for (let x = e; x && !x.classList?.contains('pk-ข้อคำ'); x = x.parentElement) {
        const s = getComputedStyle(x)
        const r = x.getBoundingClientRect()
        if (s.display === 'none' || s.visibility === 'hidden' || Number(s.opacity) === 0) return false
        if (s.clipPath !== 'none' || (s.clip && s.clip !== 'auto')) return false
        if (r.width <= 1 && r.height <= 1 && s.overflow !== 'visible') return false
      }
      return true
    }
    const เดิน = (n, ตา) => {
      let t = ''
      for (const ค of n.childNodes) {
        if (ค.nodeType === 3) {
          if (!ตา || เห็นได้(ค.parentElement)) t += ค.nodeValue
        } else if (ค.nodeType === 1) {
          if (!ตา && ค.getAttribute('aria-hidden') === 'true') continue
          t += เดิน(ค, ตา)
        }
      }
      return t
    }
    const บนหน้า = [...document.querySelectorAll('[data-หมุดบท]')].map((e) => Number(e.dataset.หมุดบท))
    const เลข = ก้อน.flatMap((g) => [...g.querySelectorAll('.pk-ข้อคำ[data-ข้อเดิม]')]).map((p) => {
      const sup = p.querySelector(':scope > .pk-เลขข้อ')
      if (!sup) return { ที่: p.dataset.ข้อเดิม, ภาษา: p.lang, เห็น: '', ได้ยิน: '' }
      const ซ่อนเสียง = !!sup.closest('[aria-hidden="true"]')
      return {
        ที่: p.dataset.ข้อเดิม,
        ภาษา: p.lang,
        เห็น: เดิน(sup, true).trim(),
        ได้ยิน: ซ่อนเสียง ? '' : (sup.getAttribute('aria-label') ?? เดิน(sup, false)).trim(),
      }
    })
    // ⭐ เลขข้อแรกของก้อนบท c ฝั่งฉบับแปล ⇒ ใช้เทียบว่าคอลัมน์คำเดิมยังตามกติกาของฉบับแปล
    const แปลแรก = [...document.querySelectorAll(`.pk-ตัวบท [data-ข้อ^="${c}:"] .pk-เลขข้อ`)].find(
      (e) => !e.closest('.pk-ชั้นคำ') && !e.classList.contains('pk-กันที่'),
    )
    return { บนหน้า, เลข, แปลแรก: แปลแรก?.textContent.trim() ?? null }
  }, บท)
}

