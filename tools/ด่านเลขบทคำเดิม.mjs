async function ขอ(ที่) {
  const r = await fetch(`${ฐาน}/${ที่}`)
  if (r.status === 404) return null
  if (!r.ok) throw new Error(`ขอ ${ที่} ⇒ ${r.status}`)
  return r.json()
}

