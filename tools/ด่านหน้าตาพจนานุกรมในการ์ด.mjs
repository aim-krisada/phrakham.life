/** ของพังของเดิม ⇒ ยัดกลับเข้าไปหลังการ์ดขึ้นครบ */
async function ยัดของพัง(แท็บ, พัง) {
  if (พัง === 'ป้ายกลาง')
    // ⇒ กฎของป้าย *เปลี่ยนตอน* ที่แถบล่าง ซึ่งป้ายในการ์ดเคยได้มาเพราะชื่อชน
    await แท็บ.addStyleTag({
      content: '.pk-ป้ายตอนพจนานุกรม{display:flex!important;justify-content:center!important;white-space:nowrap!important}',
    })
  if (พัง === 'คำอ่านติด')
    // ⇒ หน้าตาของ `<i> {{ x }} </i>` หลังตัวแปลงแม่แบบทิ้งช่องว่าง ⇒ `<i>x</i>`
    await แท็บ.evaluate(() => document.querySelectorAll('[data-การ์ดคำ] [data-เนื้อ] > i').forEach((i) => (i.textContent = i.textContent.trim())))
  if (พัง === 'เลขติด')
    // ⇒ หน้าตาของ `<b>{{ x }}</b> </template>` ⇒ ช่องว่างท้ายแม่แบบหาย
    await แท็บ.evaluate(() =>
      document.querySelectorAll('[data-การ์ดคำ] [data-เนื้อ] > br + b').forEach((b) => {
        for (let n = b.nextSibling; n && !n.textContent.trim(); n = n.nextSibling) n.textContent = ''
      }),
    )
}

async function ตรวจ(ค, จ, พัง = '') {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: จ.กว้าง, height: จ.สูง } })
  const แท็บ = await ctx.newPage()
  const ป้าย = `${ค.ชื่อ} ${จ.ชื่อ}`
  const ตก = []
  try {
    await เปิดการ์ด(แท็บ, ค)
    if (พัง) await ยัดของพัง(แท็บ, พัง)
    for (const แ of ค.แหล่ง) {
      const นับ = await แท็บ.evaluate(นับในหน้า, แ)
      // ⭐ ของที่ต้องมีให้ตรวจ ⇒ Strong มีป้ายตอนกับคำอ่านเสมอ · BDB ของ בָּרָא มีเลขข้อย่อย
      if (แ === 'strong' && (!นับ.ป้าย || !นับ.คำอ่าน)) ตก.push(`${ป้าย} ⇒ ${แ} ⛔ ไม่มีป้ายตอนหรือคำอ่านให้ตรวจ ⇒ ${JSON.stringify(นับ)}`)
      if (แ === 'bdb' && !นับ.เลข) ตก.push(`${ป้าย} ⇒ ${แ} ⛔ ไม่มีเลขข้อย่อยให้ตรวจ`)
      for (const x of await แท็บ.evaluate(วัดในหน้า, [แ, เพดานขอบซ้าย, ช่องว่างน้อยสุด])) ตก.push(`${ป้าย} ⇒ ${x}`)
    }
  } catch (e) {
    ตก.push(`${ป้าย} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message.split('\n')[0]}`)
  } finally {
    await ctx.close()
  }
  return ตก
}

