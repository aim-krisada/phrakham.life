async function เปิดการ์ด(แท็บ, ค) {
  await แท็บ.goto(`${ฐาน}/read/${ค.เล่ม}?c=${ค.บท}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  await เปิดคำเดิม(แท็บ)
  await แท็บ.waitForSelector('.pk-ชั้นคำ .pk-คำ')
  const เจอ = await แท็บ.evaluate(
    ([ข้อ, คำ]) => {
      const แถว = [...document.querySelectorAll('.pk-ข้อคำ')].find((p) => p.getAttribute('data-ข้อเดิม') === ข้อ)
      // ⭐ เทียบแบบตัดเครื่องหมายออก ⇒ ตัวบท ὸ กับ ό · สระและเครื่องหมายร้องของฮีบรู ⛔ ไม่ทำให้หาไม่เจอ
      //   ⇒ ปุ่มมีคำแปลต่อท้าย ⇒ ดูตัวที่ตามหลังคำ ⇒ ⛔ เป็นอักษรกรีกหรือฮีบรู (ברא ⛔ ไปเข้ากับ בראשית)
      const ล้าง = (s) => s.normalize('NFD').replace(/[̀-֑ͯ-ׇ]/g, '')
      const ปุ่ม = [...(แถว?.querySelectorAll('.pk-คำ') ?? [])].find((b) => {
        const ท = ล้าง(b.textContent).trim()
        const ค = ล้าง(คำ)
        return ท.startsWith(ค) && !/[א-תͰ-Ͽἀ-῿]/.test(ท.charAt(ค.length))
      })
      ปุ่ม?.setAttribute('data-เป้าหน้าตา', '1')
      return !!ปุ่ม
    },
    [ค.ข้อ, ค.คำ],
  )
  if (!เจอ) throw new Error(`หาคำ ${ค.คำ} ใน ${ค.ข้อ} ไม่เจอ`)
  await แท็บ.locator('[data-เป้าหน้าตา]').click()
  await แท็บ.waitForSelector('[data-การ์ดคำ] .pk-ข้อมูลคำ', { timeout: 15000 })
  for (const แ of ค.แหล่ง) {
    if (แ === 'bdb') await แท็บ.locator('[data-การ์ดคำ]').getByRole('checkbox', { name: /BDB/ }).check()
    await แท็บ.waitForSelector(`[data-การ์ดคำ] [data-แหล่ง="${แ}"] [data-เนื้อ]`, { timeout: 15000 })
  }
  await แท็บ.waitForTimeout(200)
}

/** วัดของจริงในแหล่งเดียว ⇒ คืนรายการที่ผิด */
function วัดในหน้า([แหล่ง, เพดานขอบซ้าย, ช่องว่างน้อยสุด]) {
  const ผิด = []
  const เนื้อ = [...document.querySelectorAll(`[data-การ์ดคำ] [data-แหล่ง="${แหล่ง}"] [data-เนื้อ]`)]
  if (!เนื้อ.length) return [`${แหล่ง} ⛔ ไม่มีเนื้อพจนานุกรมบนการ์ด`]

  /** กรอบของตัวหนังสือในโหนด ⇒ ตัดช่องว่างหัวท้าย ⇒ `ตัวแรก` คือกรอบของตัวอักษรตัวแรกตัวเดียว */
  const กรอบตัวหนังสือ = (โหนด, ตัวแรก = false) => {
    const ข้อความ = โหนด.nodeType === Node.TEXT_NODE ? โหนด : null
    const ทุกตัว = []
    const เดิน = document.createTreeWalker(โหนด, NodeFilter.SHOW_TEXT)
    if (ข้อความ) ทุกตัว.push(ข้อความ)
    else while (เดิน.nextNode()) ทุกตัว.push(เดิน.currentNode)
    const มีตัว = ทุกตัว.filter((t) => t.data.trim())
    if (!มีตัว.length) return null
    const r = document.createRange()
    const ต้น = มีตัว[0]
    const ท้าย = มีตัว.at(-1)
    const i = ต้น.data.search(/\S/)
    r.setStart(ต้น, i)
    if (ตัวแรก) r.setEnd(ต้น, i + 1)
    else r.setEnd(ท้าย, ท้าย.data.trimEnd().length)
    return r.getBoundingClientRect()
  }
  /** โหนดก่อนหน้า/ถัดไปที่มีตัวหนังสือ ⇒ เก็บตัวหนังสือที่ข้ามไปด้วย (ช่องว่างล้วนที่อยู่คั่น) */
  const ข้างที่มีตัว = (e, ทาง) => {
    let คั่น = ''
    let n = e
    for (;;) {
      while (n && !(ทาง === 'ก่อน' ? n.previousSibling : n.nextSibling)) n = n.parentNode
      if (!n || n.matches?.('[data-เนื้อ]')) return { โหนด: null, คั่น }
      n = ทาง === 'ก่อน' ? n.previousSibling : n.nextSibling
      if (n.nodeType === Node.COMMENT_NODE) continue
      if (n.textContent.trim()) return { โหนด: n, คั่น }
      คั่น += n.textContent
    }
  }
  /** ช่องว่างระหว่าง 2 โหนดที่ติดกัน ⇒ ทั้งในตัวหนังสือและที่ตาเห็น */
  const ตรวจช่อง = (ซ้าย, ขวา, คั่น, ป้าย) => {
    const มีช่องในตัวหนังสือ = /\s$/.test(ซ้าย.textContent + คั่น) || /^\s/.test(ขวา.textContent)
    if (!มีช่องในตัวหนังสือ) ผิด.push(`${ป้าย} ⇒ ตัวหนังสือติดกัน ⛔ ไม่มีช่องว่างคั่น ⇒ "${(ซ้าย.textContent.trim() + ขวา.textContent.trim()).replace(/\s+/g, ' ').slice(0, 40)}"`)
    const ก = กรอบตัวหนังสือ(ซ้าย)
    const ข = กรอบตัวหนังสือ(ขวา)
    if (!ก || !ข) return
    const บรรทัดเดียว = Math.abs(ก.top - ข.top) < Math.min(ก.height, ข.height) / 2
    if (!บรรทัดเดียว) return
    const ห่าง = ข.left - ก.right
    if (ห่าง < ช่องว่างน้อยสุด)
      ผิด.push(`${ป้าย} ⇒ ตาเห็นห่างกัน ${ห่าง.toFixed(1)} จุด ⛔ ต้องไม่น้อยกว่า ${ช่องว่างน้อยสุด} ⇒ "${ซ้าย.textContent.trim().slice(0, 30)}" กับ "${ขวา.textContent.trim().replace(/\s+/g, ' ').slice(0, 30)}"`)
  }

  for (const ก of เนื้อ) {
    if (ก.querySelector('.pk-ป้ายตอน')) ผิด.push(`${แหล่ง} ① ป้ายตอนในการ์ดยังใช้ชื่อ pk-ป้ายตอน ⇒ ชนกับป้ายเปลี่ยนตอนที่แถบล่าง`)
    // ① ป้ายตอน ⇒ ขอบซ้ายตัวหนังสือป้าย = ขอบซ้ายตัวหนังสือตัวแรกที่ตามมา
    for (const ป้าย of ก.querySelectorAll('.pk-ป้ายตอนพจนานุกรม')) {
      const { โหนด: ถัดไป } = ข้างที่มีตัว(ป้าย, 'ถัด')
      const ซ้ายป้าย = กรอบตัวหนังสือ(ป้าย, true)
      const ซ้ายเนื้อ = ถัดไป && กรอบตัวหนังสือ(ถัดไป, true)
      if (!ซ้ายป้าย || !ซ้ายเนื้อ) {
        ผิด.push(`${แหล่ง} ① ป้าย "${ป้าย.textContent}" ⛔ ไม่มีเนื้อตามมาให้เทียบ`)
        continue
      }
      const ต่าง = Math.abs(ซ้ายป้าย.left - ซ้ายเนื้อ.left)
      if (ต่าง > เพดานขอบซ้าย)
        ผิด.push(`${แหล่ง} ① ป้าย "${ป้าย.textContent}" เริ่มที่ ${ซ้ายป้าย.left.toFixed(1)} แต่เนื้อเริ่มที่ ${ซ้ายเนื้อ.left.toFixed(1)} ⇒ ต่าง ${ต่าง.toFixed(1)} จุด ⛔ เกิน ${เพดานขอบซ้าย}`)
    }
    // ② คำหลัก ⇒ คำอ่าน (ตัวเอน) ⇒ เสียงอ่าน
    for (const อ่าน of ก.querySelectorAll(':scope > i')) {
      const ก่อน = ข้างที่มีตัว(อ่าน, 'ก่อน')
      if (ก่อน.โหนด) ตรวจช่อง(ก่อน.โหนด, อ่าน, ก่อน.คั่น, `${แหล่ง} ② คำหลักกับคำอ่าน`)
      const ถัด = ข้างที่มีตัว(อ่าน, 'ถัด')
      if (ถัด.โหนด?.classList?.contains('pk-เสียงอ่าน')) ตรวจช่อง(อ่าน, ถัด.โหนด, ถัด.คั่น, `${แหล่ง} ② คำอ่านกับเสียงอ่าน`)
    }
    // ③ เลขข้อย่อย (ตัวหนาที่ตามหลังการขึ้นบรรทัด) ⇒ เนื้อ
    for (const เลข of ก.querySelectorAll(':scope > br + b')) {
      if (!/^\d+$/.test(เลข.textContent.trim())) continue
      const ถัด = ข้างที่มีตัว(เลข, 'ถัด')
      if (ถัด.โหนด) ตรวจช่อง(เลข, ถัด.โหนด, ถัด.คั่น, `${แหล่ง} ③ เลขข้อย่อยกับเนื้อ`)
    }
  }
  return ผิด
}

