async function ตรวจรูปลิงก์({ พัง, เฉพาะ } = {}) {
  const ตก = []
  const { ctx, นับ } = await บริบท(พัง)
  for (const ร of รูปลิงก์) {
    if (เฉพาะ && !เฉพาะ.includes(ร.ชื่อ)) continue
    const แท็บ = await ctx.newPage()
    const ข้อผิด = []
    แท็บ.on('pageerror', (e) => ข้อผิด.push(e.message))
    const ได้ = await เปิดจนถึงหน้าอ่าน(แท็บ, ร.ลิงก์)
    const ผิด = เทียบที่อยู่(ได้, ร)
    if (ผิด) ตก.push(`② ${ร.ชื่อ} (${ร.ลิงก์}) ⇒ ${ผิด}`)
    else {
      await รอโค้ดของเว็บติด(แท็บ)
      if (ร.คำถาม.r) {
        // ⭐ หน้าอ่านรับช่วงได้ ⇒ ช่วงยังอยู่ในที่อยู่หลังหน้าติด (หน้าทิ้งช่วงที่กางไม่ได้เงียบ ๆ ⇒ ที่อยู่จะไม่มี r)
        try {
          await แท็บ.waitForFunction(() => document.querySelector('.pk-ข้อ, [data-ข้อ]') !== null, null, { timeout: 20000 })
        } catch {}
        const r = new URL(แท็บ.url()).searchParams.get('r')
        if (r !== ร.คำถาม.r) ตก.push(`② ${ร.ชื่อ} ⇒ หน้าอ่านทิ้งช่วง ⇒ ที่อยู่หลังหน้าติดมี r=${r} ⛔ ${ร.คำถาม.r}`)
      }
      if (ร.การ์ด) {
        const การ์ด = แท็บ.locator('[data-การ์ดคำ]')
        try {
          await การ์ด.waitFor({ state: 'visible', timeout: 30000 })
          const แถว = การ์ด.locator('dt', { hasText: 'เลข Strong' }).locator('xpath=following-sibling::dd[1]')
          await แท็บ.waitForFunction(
            ([el, เลข]) => el && el.textContent.replace(/^0+/, '').includes(เลข),
            [await แถว.elementHandle(), ร.การ์ด],
            { timeout: 20000 },
          )
        } catch {
          const ข้อความ = (await การ์ด.count()) ? (await การ์ด.innerText()).replace(/\s+/g, ' ').slice(0, 120) : 'ไม่มีการ์ด'
          ตก.push(`③ ${ร.ชื่อ} ⇒ การ์ดคำของเลข Strong ${ร.การ์ด} ⛔ ขึ้น ⇒ ได้ “${ข้อความ}”`)
        }
      }
    }
    if (ข้อผิด.length) ตก.push(`④ ${ร.ชื่อ} ⇒ หน้ามีข้อผิดพลาด ⇒ ${ข้อผิด[0].slice(0, 120)}`)
    await แท็บ.close()
  }
  await ctx.close()
  return { ตก, นับ }
}

/** ④ ⑥ ⇒ ลิงก์ที่ต้องได้หน้าแรก */
async function ตรวจหน้าแรก({ พัง, เฉพาะ } = {}) {
  const ตก = []
  const { ctx, นับ } = await บริบท(พัง)
  for (const ล of ลิงก์หน้าแรก) {
    if (เฉพาะ && !เฉพาะ.includes(ล.ชื่อ)) continue
    const แท็บ = await ctx.newPage()
    const ข้อผิด = []
    แท็บ.on('pageerror', (e) => ข้อผิด.push(e.message))
    const ไป = new URL(ฐาน + ล.ลิงก์)
    await แท็บ.goto(ไป.href)
    try {
      await รอโค้ดของเว็บติด(แท็บ)
      await แท็บ.locator('article.pk-หน้าแรก h1').waitFor({ state: 'visible', timeout: 10000 })
    } catch {
      ตก.push(`${ล.ข้อ} ${ล.ชื่อ} (${ล.ลิงก์}) ⇒ ⛔ ได้หน้าแรก ⇒ อยู่ที่ ${แท็บ.url()}`)
      await แท็บ.close()
      continue
    }
    const u = new URL(แท็บ.url())
    if (u.pathname !== ทางฐาน) ตก.push(`${ล.ข้อ} ${ล.ชื่อ} ⇒ ที่อยู่ ${u.pathname} ⛔ ${ทางฐาน}`)
    // ⭐ อยู่ที่เดิม ⇒ ชื่อคำถามชุดเดิม ⇒ ⛔ เทียบตัวอักษรของค่า ⇒ ตัวจัดเส้นทางของ Nuxt เข้ารหัสค่าใหม่เอง (ช่องว่างเป็น + · `%` เป็น `%25`)
    //   ⇒ เป็นของเดิมก่อนใบ #166 ⇒ ⛔ ใช่การพาไปของใบนี้
    const ชื่อคำถาม = (s) => [...new URLSearchParams(s).keys()].sort().join(',')
    if (ล.อยู่ที่เดิม && ชื่อคำถาม(u.search) !== ชื่อคำถาม(ไป.search)) ตก.push(`${ล.ข้อ} ${ล.ชื่อ} ⇒ ที่อยู่ถูกเปลี่ยน ${u.search} ⛔ ${ไป.search}`)
    if (!ล.อยู่ที่เดิม && u.search) ตก.push(`${ล.ข้อ} ${ล.ชื่อ} ⇒ หน้าแรกยังพกคำถามเดิม ${u.search}`)
    if (ข้อผิด.length) ตก.push(`${ล.ข้อ} ${ล.ชื่อ} ⇒ หน้ามีข้อผิดพลาด ⇒ ${ข้อผิด[0].slice(0, 120)}`)
    await แท็บ.close()
  }
  await ctx.close()
  return { ตก, นับ }
}

/** ⑤ ⇒ ถอยหลังไม่วน */
async function ตรวจถอยหลัง({ พัง } = {}) {
  const ตก = []
  const { ctx, นับ } = await บริบท(พัง)
  for (const ลิงก์ of ลิงก์ถอยหลัง) {
    const แท็บ = await ctx.newPage()
    await แท็บ.goto(ฐาน + '/sources')
    await รอโค้ดของเว็บติด(แท็บ)
    const ได้ = await เปิดจนถึงหน้าอ่าน(แท็บ, ลิงก์)
    if (!ได้) {
      ตก.push(`⑤ ${ลิงก์} ⇒ ไม่ไปหน้าอ่าน`)
      await แท็บ.close()
      continue
    }
    await รอโค้ดของเว็บติด(แท็บ)
    await แท็บ.goBack({ waitUntil: 'commit' })
    // ⭐ รอให้ที่อยู่นิ่ง ⇒ ถ้าวน ลิงก์เก่าจะพาไปหน้าอ่านอีก ⇒ รอจนโค้ดของหน้าที่ถอยมาติด
    try {
      await รอโค้ดของเว็บติด(แท็บ)
    } catch {}
    const หลังถอย = new URL(แท็บ.url())
    if (หลังถอย.pathname.replace(/\/+$/, '') !== ทางฐาน + 'sources')
      ตก.push(`⑤ ${ลิงก์} ⇒ ถอยหลังจากหน้าอ่านได้ ${หลังถอย.pathname}${หลังถอย.search} ⛔ ${ทางฐาน}sources`)
    else {
      await แท็บ.goForward({ waitUntil: 'commit' })
      try {
        await รอโค้ดของเว็บติด(แท็บ)
      } catch {}
      if (!ที่หน้าอ่าน(แท็บ.url())) ตก.push(`⑤ ${ลิงก์} ⇒ ไปหน้าแล้วได้ ${แท็บ.url()} ⛔ หน้าอ่าน`)
    }
    await แท็บ.close()
  }
  await ctx.close()
  return { ตก, นับ }
}

