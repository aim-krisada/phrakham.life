/** บริบทใหม่ ⇒ ยัดของพัง (ถ้ามี) ⇒ คืนตัวนับว่าของพังยัดเข้าไปจริงกี่ครั้ง */
async function บริบท(พัง) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 800 } })
  const นับ = { ยัด: 0 }
  if (พัง?.ก่อนโหลด) {
    await ctx.addInitScript(พัง.ก่อนโหลด)
    นับ.ยัด++
  }
  if (พัง?.แทนโค้ด) {
    await ctx.route('**/_nuxt/*.js', async (route) => {
      const r = await route.fetch()
      let เนื้อ = await r.text()
      for (const [จาก, เป็น] of พัง.แทนโค้ด) {
        if (เนื้อ.includes(จาก)) {
          เนื้อ = เนื้อ.split(จาก).join(เป็น)
          นับ.ยัด++
        }
      }
      await route.fulfill({ response: r, body: เนื้อ })
    })
  }
  if (พัง?.ทางข้อมูล) {
    await ctx.route(พัง.ทางข้อมูล, async (route) => {
      นับ.ยัด++
      if (!พัง.แก้ข้อมูล) return route.fulfill({ status: 404, body: 'ไม่พบไฟล์' })
      const r = await route.fetch()
      await route.fulfill({ response: r, body: JSON.stringify(พัง.แก้ข้อมูล(await r.json())) })
    })
  }
  return { ctx, นับ }
}

const ที่หน้าอ่าน = (u) => new URL(u).pathname.startsWith(ทางฐาน + 'read/')

/** เปิดลิงก์ ⇒ รอจนเป็นหน้าอ่าน ⇒ คืนที่อยู่แรกของหน้าอ่าน (ก่อนหน้าอ่านเขียนที่อยู่ของตัวเอง) */
async function เปิดจนถึงหน้าอ่าน(แท็บ, ลิงก์) {
  let แรก = null
  const ฟัง = (f) => {
    if (f === แท็บ.mainFrame() && !แรก && ที่หน้าอ่าน(f.url())) แรก = f.url()
  }
  แท็บ.on('framenavigated', ฟัง)
  await แท็บ.goto(ฐาน + ลิงก์, { waitUntil: 'commit' })
  try {
    await แท็บ.waitForURL((u) => ที่หน้าอ่าน(u.href), { waitUntil: 'commit', timeout: 20000 })
  } catch {}
  แท็บ.off('framenavigated', ฟัง)
  return แรก
}

function เทียบที่อยู่(ได้, คาด) {
  if (!ได้) return 'ไม่ไปหน้าอ่านเลย'
  const u = new URL(ได้)
  const ทาง = u.pathname.slice(ทางฐาน.length).replace(/\/+$/, '')
  const ผิด = []
  if (ทาง !== คาด.ทาง) ผิด.push(`ทาง ${ทาง} ⛔ ${คาด.ทาง}`)
  const ได้คำถาม = Object.fromEntries(u.searchParams)
  for (const k of new Set([...Object.keys(ได้คำถาม), ...Object.keys(คาด.คำถาม)]))
    if (ได้คำถาม[k] !== คาด.คำถาม[k]) ผิด.push(`${k}=${ได้คำถาม[k] ?? '(ไม่มี)'} ⛔ ${คาด.คำถาม[k] ?? '(ไม่มี)'}`)
  return ผิด.join(' · ')
}

/** ① ⇒ 66 เล่ม */
async function ตรวจเล่ม({ พัง, เฉพาะ } = {}) {
  const ตก = []
  const { ctx, นับ } = await บริบท(พัง)
  const แท็บ = await ctx.newPage()
  for (const [รหัส, ชื่อ] of เล่มเว็บเดิม) {
    if (เฉพาะ && !เฉพาะ.includes(รหัส)) continue
    const ได้ = await เปิดจนถึงหน้าอ่าน(แท็บ, `/?ref=${encodeURIComponent(ชื่อ + ' 1:1')}`)
    const ผิด = เทียบที่อยู่(ได้, { ทาง: `read/${รหัส}`, คำถาม: { c: '1', v: '1' } })
    if (ผิด) ตก.push(`① ${ชื่อ.replace(/​/g, '')} 1:1 ⇒ ${ผิด}`)
    const r = await แท็บ.request.get(`${ฐาน}/read/${รหัส}/`)
    if (!r.ok()) ตก.push(`① ${ชื่อ} ⇒ หน้า /read/${รหัส} ⛔ มี (HTTP ${r.status()})`)
  }
  await ctx.close()
  return { ตก, นับ }
}

