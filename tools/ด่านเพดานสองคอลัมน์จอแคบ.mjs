/** เปิดหน้าใหม่ในเครื่องใหม่ ⇒ ตั้งฉบับและมุมมองที่จำไว้ก่อนหน้าจะรัน ⇒ ยัดของพังที่ต้องอยู่ตั้งแต่ก่อนโค้ดของเว็บติด */
async function เปิด(ที่อยู่, { จอ, ฉบับ = ['TCV'], มุม = null, พัง = null, ขั้น = null } = {}) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: จอ })
  await ctx.addInitScript(
    ([ฉ, ม, ข]) => {
      try {
        if (!sessionStorage.getItem('pk-ด่านเพดานจอแคบ')) {
          localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
          if (ม) localStorage.setItem('phrakham.view', JSON.stringify(ม))
          // ⭐ ขนาดตัวอักษรที่ผู้อ่านตั้งไว้ ⇒ ที่เก็บตัวเดียวกับ `public/pk-fontsize.js` ⇒ ท่าเดียวกับ `tools/วัดคอลัมน์อ่าน.mjs`
          if (ข) localStorage.setItem('pk-fs', String(ข))
          sessionStorage.setItem('pk-ด่านเพดานจอแคบ', '1')
        }
      } catch {}
    },
    [ฉบับ, มุม, ขั้น],
  )
  // ⭐ จำจำนวนช่องถอยหลังตอนเอกสารเพิ่งเริ่ม ⇒ ก่อนโค้ดของเว็บติด ⇒ ใช้ดูว่าการตัดเพิ่มช่องไหม
  await ctx.addInitScript(() => {
    window.__ช่องตอนเริ่ม = history.length
  })
  if (พัง) await ctx.addInitScript(ยัดของพังตั้งแต่ต้น, พัง)
  const แท็บ = await ctx.newPage()
  if (ที่อยู่) await ไปที่(แท็บ, ที่อยู่, พัง)
  return { ctx, แท็บ }
}

