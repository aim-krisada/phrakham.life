/** ⭐ ลิงก์เก่าที่เกินเพดาน ⇒ ต้องเหลือ `ต้อง` ⇒ ที่อยู่ตรงกับที่เห็น ⇒ เขียนทับช่องเดิม ⇒ ท่าเดียวกับข้อ ③ */
