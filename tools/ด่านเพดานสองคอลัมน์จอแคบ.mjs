/** ⭐ ใบ #161 ⇒ ปุ่ม *เพิ่มคอลัมน์* ในเมนูที่กางอยู่ ⇒ บอกว่าเต็มไหม (`aria-disabled`) · ใช้ `disabled` ไหม · โฟกัสได้ไหม
 *   ⇒ ⚠️ ของเดิม `อ่านช่อง` อ่านช่องติ๊กทุกช่อง ⇒ ช่องติ๊กถอดแล้ว */
