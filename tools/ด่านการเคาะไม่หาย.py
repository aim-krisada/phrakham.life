#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ด่านการเคาะไม่หาย — ทุกการเคาะที่พี่เอมเคยเคาะ ต้องยังหาเจอในกองเอกสาร

ทำไมมีด่านนี้
  8 ก.ย. 2569 ใบงาน v3/phrakham#85 ผ่า `docs/สิ่งที่เคาะแล้ว.md` (848 บรรทัด) ออกเป็น 4 กอง
  แล้วตัดของซ้ำกับของที่ถูกครอบทิ้งไปด้วย ⇒ ⛔ **การย้ายกับการตัดพร้อมกัน คือจังหวะที่ของหายง่ายที่สุด**
  ⇒ พี่เอมสั่งไว้ว่าของที่แก้แล้วต้องกลายเป็นด่านที่ตรวจซ้ำเองทุกครั้ง
  ⇒ ด่านนี้จึงถือ **รายการหัวข้อของไฟล์เดิมทั้ง 76 หัว** ไว้ที่ `tools/รายการการเคาะ.tsv`
    แล้วตรวจทุกท่อว่าถ้อยคำของทุกหัวยังหาเจอในกองใหม่

เกณฑ์ที่ด่านนี้ตัดสิน
  ✅ ถ้อยคำของหัวข้อยังปรากฏใน `docs/สิ่งที่เคาะแล้ว.md` หรือใน `docs/เคาะ/*.md`
     ⇒ จะอยู่ในรูปหัวข้อ หรือกลืนเป็นบรรทัดในเนื้อก็นับ ⇒ ที่ด่านนี้เฝ้าคือ **การเคาะไม่หาย**
     ⛔ ไม่ใช่ **โครงหัวข้อต้องเหมือนเดิม** — โครงเปลี่ยนได้ ของหายไม่ได้

เกณฑ์ที่ด่านนี้ ⛔ ตัดสินไม่ได้
  ⛔ เนื้อใต้หัวข้อถูกตัดจนความหมายเพี้ยน ⇒ อันนั้นต้องใช้คนอ่าน
  ⛔ การเคาะใหม่ที่ยังไม่มีใครเติมลง `.tsv` ⇒ เติมเองไม่ได้ ต้องคนเติม

เติมการเคาะใหม่ยังไง
  จดลงไฟล์ของกองนั้นตามปกติ แล้วเติมหัวข้อลงท้าย `tools/รายการการเคาะ.tsv` หนึ่งบรรทัด
  ⇒ ⭐ วันหลังใครลบการเคาะนั้นทิ้ง ด่านนี้จะแดงให้เห็น

พิสูจน์ว่าด่านนี้แดงได้จริง
  `python3 tools/ด่านการเคาะไม่หาย.py --ทดสอบตัวเอง`
  ⇒ มันหยิบหัวข้อจริงมาหนึ่งหัว ลบออกจากเนื้อที่อ่านมา แล้วต้องจับได้
  ⇒ job `ด่านการเคาะไม่หายยังจับได้` ใน `.gitlab-ci.yml` รันท่านี้ทุกท่อ
  ⇒ วันที่ใครแก้ด่านจนมันเขียวตลอด ท่อนนั้นจะแดงทันที
"""

import sys
import unicodedata
from pathlib import Path

ราก = Path(__file__).resolve().parent.parent
ไฟล์รายการ = ราก / "tools" / "รายการการเคาะ.tsv"
ไฟล์สารบัญ = ราก / "docs" / "สิ่งที่เคาะแล้ว.md"
โฟลเดอร์กอง = ราก / "docs" / "เคาะ"


def ล้างรูป(ข้อความ: str) -> str:
    """ตัดของที่เปลี่ยนได้โดยความหมายไม่เปลี่ยน ⇒ เครื่องหมายมาร์กดาวน์ ช่องว่าง และรูปยูนิโค้ด

    ⛔ ไม่ตัดตัวอักษรกับตัวเลข ⇒ ถ้อยคำของพี่เอมยังต้องอยู่ครบ
    """
    ข้อความ = unicodedata.normalize("NFC", ข้อความ)
    เก็บ = []
    for ตัว in ข้อความ:
        if ตัว in "*`_#>|":  # เครื่องหมายมาร์กดาวน์ที่ห่อคำ
            continue
        if ตัว.isspace():
            continue
        เก็บ.append(ตัว)
    return "".join(เก็บ)


def อ่านรายการ() -> list[tuple[int, str]]:
    บรรทัด = ไฟล์รายการ.read_text(encoding="utf-8").splitlines()
    ผล = []
    for ที่ในไฟล์, เส้น in enumerate(บรรทัด[1:], start=2):  # ข้ามหัวตาราง
        if not เส้น.strip():
            continue
        ช่อง = เส้น.split("\t")
        if len(ช่อง) != 2:
            print(f"⛔ {ไฟล์รายการ.name} บรรทัด {ที่ในไฟล์} ต้องมี 2 ช่องคั่นด้วยแท็บ")
            sys.exit(1)
        ผล.append((int(ช่อง[0]), ช่อง[1]))
    return ผล


def อ่านกองใหม่() -> str:
    ชิ้น = []
    if ไฟล์สารบัญ.exists():
        ชิ้น.append(ไฟล์สารบัญ.read_text(encoding="utf-8"))
    if โฟลเดอร์กอง.is_dir():
        for ไฟล์ in sorted(โฟลเดอร์กอง.glob("*.md")):
            ชิ้น.append(ไฟล์.read_text(encoding="utf-8"))
    if not ชิ้น:
        print("⛔ ไม่เจอเอกสารสิ่งที่เคาะแล้วสักไฟล์")
        sys.exit(1)
    return "\n".join(ชิ้น)


def หาที่หาย(รายการ: list[tuple[int, str]], เนื้อ: str) -> list[str]:
    กอง = ล้างรูป(เนื้อ)
    return [หัว for _, หัว in รายการ if ล้างรูป(หัว) not in กอง]


def main() -> int:
    ทดสอบตัวเอง = "--ทดสอบตัวเอง" in sys.argv
    รายการ = อ่านรายการ()
    เนื้อ = อ่านกองใหม่()

    if ทดสอบตัวเอง:
        # ทำของพังขึ้นมาเอง ⇒ ลบหัวข้อจริงหัวหนึ่งออกจากเนื้อ แล้วด่านต้องจับได้
        เหยื่อ = รายการ[-1][1]
        เนื้อพัง = เนื้อ.replace(เหยื่อ, "")
        หาย = หาที่หาย(รายการ, เนื้อพัง)
        if เหยื่อ not in หาย:
            print(f"⛔ ด่านนี้เขียวทั้งที่ลบการเคาะออกไปแล้ว ⇒ ด่านเสีย · ที่ลบคือ {เหยื่อ}")
            return 1
        print(f"✅ ลบการเคาะออก 1 หัวแล้วด่านจับได้ ⇒ ด่านยังแดงเป็น · ที่ลบคือ {เหยื่อ}")
        return 0

    หาย = หาที่หาย(รายการ, เนื้อ)
    if หาย:
        print(f"⛔ การเคาะหายไป {len(หาย)} หัว จากทั้งหมด {len(รายการ)} หัว")
        for หัว in หาย:
            print(f"   หาไม่เจอ ⇒ {หัว}")
        print("⇒ เอาถ้อยคำนั้นกลับเข้าไฟล์ในกอง docs/เคาะ/ หรือแก้บรรทัดใน tools/รายการการเคาะ.tsv ให้ตรงของจริง")
        return 1

    print(f"✅ การเคาะครบ {len(รายการ)} หัว")
    return 0


if __name__ == "__main__":
    sys.exit(main())
