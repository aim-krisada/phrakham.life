// **เจ้าของป้ายคือ `nuxt.config.ts` ก้อน `app.head.meta`** ⇒ เหตุผลทุกข้อกับวันที่ต้องเอาป้ายออก
//   เขียนไว้ที่นั่น ⛔ ไม่จดซ้ำที่นี่
//
// ⭐ **เปิดไฟล์ `.html` ทุกไฟล์ ⛔ ไม่ใช่สุ่มมา 3 หน้า** — หน้าที่สร้างออกมามีเป็นร้อย
//   ⇒ สุ่มแล้วเขียว ⛔ ไม่ได้แปลว่าหน้าที่เหลือมีป้าย ⇒ ที่นี่อ่านจากดิสก์ตรง ๆ จึงไล่ครบได้ในไม่กี่วินาที
//
// ⭐ **ไม่เจอไฟล์ `.html` สักไฟล์ = แดง** ⛔ ไม่ใช่เขียว
//   ⇒ ชี้ผิดโฟลเดอร์หรือเว็บสร้างไม่ออก แล้วด่านตอบว่า "ผ่าน" คือด่านที่โกหก
//
// **พิสูจน์ว่าด่านนี้แดงได้จริง** ⇒ ท่า `--ทดสอบตัวเอง` **ถอดป้ายออกจากหน้าจริงที่เพิ่งสร้างเสร็จ**
//   แล้วยิงด่านใส่ ⇒ ⛔ ไม่ใช่หน้าปลอมที่เขียนขึ้นเอง ⇒ job `ด่านห้ามเก็บสารบัญยังจับได้` รันท่านี้ทุกท่อ
//   ⇒ วันที่ใครแก้ด่านจนมันเขียวตลอด ท่อนนั้นจะแดงทันที

import { readFileSync, readdirSync, mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { join, relative, dirname, sep } from 'node:path'
import { tmpdir } from 'node:os'

// ⛔ ไม่ค้นด้วยข้อความตรง ๆ อย่าง `content="noindex"` — ลำดับคุณสมบัติในแท็กเปลี่ยนได้
//   และตัวสร้างอาจใส่ค่าอื่นพ่วงมา เช่น `noindex, noarchive`
//   ⇒ ที่นี่จึงแยกแท็ก `<meta …>` ออกมาทีละอัน แล้วอ่านคุณสมบัติของมันเอง
const แท็กเมตา = /<meta\b[^>]*>/gi
const คุณสมบัติ = /([a-zA-Z-]+)\s*=\s*("([^"]*)"|'([^']*)'|([^\s"'>]+))/g

/** หน้าเดียวมีป้ายห้ามเก็บสารบัญไหม */
export function มีป้ายห้ามเก็บ(เนื้อหน้า) {
  for (const แท็ก of เนื้อหน้า.match(แท็กเมตา) || []) {
    const ของ = {}
    for (const [, ชื่อ, , ก, ข, ค] of แท็ก.matchAll(คุณสมบัติ)) {
      ของ[ชื่อ.toLowerCase()] = (ก ?? ข ?? ค ?? '').toLowerCase()
    }
    // `name="robots"` คือป้ายที่เครื่องค้นหาทุกเจ้าอ่าน ⇒ ⛔ ไม่ผูกกับเจ้าใดเจ้าหนึ่ง
    if (ของ.name !== 'robots') continue
    if ((ของ.content || '').split(',').some((ท่อน) => ท่อน.trim() === 'noindex')) return true
  }
  return false
}

function ไล่หาไฟล์html(โฟลเดอร์, ราก = โฟลเดอร์, เก็บ = []) {
  for (const ของ of readdirSync(โฟลเดอร์, { withFileTypes: true })) {
    const ทาง = join(โฟลเดอร์, ของ.name)
    if (ของ.isDirectory()) ไล่หาไฟล์html(ทาง, ราก, เก็บ)
    else if (ของ.name.toLowerCase().endsWith('.html')) เก็บ.push(relative(ราก, ทาง).split(sep).join('/'))
  }
  return เก็บ
}

/** คืนรายชื่อหน้าที่ ⛔ ไม่มีป้าย · โยนทิ้งเมื่อโฟลเดอร์ว่าง */
export function ตรวจทั้งกอง(โฟลเดอร์) {
  const หน้าทั้งหมด = ไล่หาไฟล์html(โฟลเดอร์)
  if (หน้าทั้งหมด.length === 0) {
    throw new Error(`⛔ ไม่มีไฟล์ .html สักไฟล์ใน ${โฟลเดอร์} ⇒ ยังไม่ได้สร้างเว็บ หรือชี้ผิดโฟลเดอร์`)
  }
  const ขาด = หน้าทั้งหมด.filter((หน้า) => !มีป้ายห้ามเก็บ(readFileSync(join(โฟลเดอร์, หน้า), 'utf8')))
  return { หน้าทั้งหมด, ขาด }
}

