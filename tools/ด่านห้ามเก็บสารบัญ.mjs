//   node tools/ด่านห้ามเก็บสารบัญ.mjs .output/public                 ⇒ ตรวจของจริงที่สร้างเสร็จ
//   node tools/ด่านห้ามเก็บสารบัญ.mjs --ทดสอบตัวเอง .output/public   ⇒ พิสูจน์ว่าด่านยังแดงได้จริง
