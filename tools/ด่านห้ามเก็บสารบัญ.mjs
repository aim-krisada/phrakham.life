//   ⇒ วันที่มีคนแก้ `nuxt.config.ts` แล้วป้ายหลุด **เว็บต้นแบบจะโผล่ในกูเกิลโดย ⛔ ไม่มีอะไรฟ้อง**
//   ⇒ และของที่ถูกเก็บลงสารบัญไปแล้ว **เอาออกยาก** ⇒ ด่านนี้จึง ⛔ ไม่ใส่ `allow_failure`
