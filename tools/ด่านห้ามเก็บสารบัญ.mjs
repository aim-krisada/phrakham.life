// ⭐ ท่าพิสูจน์ว่าด่านยังจับของผิดได้อยู่
//   ⇒ หัวใจอยู่ที่ข้อสุดท้าย: **ถอดป้ายออกจากหน้าจริง แล้วด่านต้องแดง**
// ---------------------------------------------------------------------------
function ทดสอบตัวเอง(โฟลเดอร์จริง) {
  const ผล = []
  const ลอง = (ชื่อ, ทำ) => {
    try {
      ทำ()
      ผล.push(`✅ ${ชื่อ}`)
    } catch (เหตุ) {
      ผล.push(`⛔ ${ชื่อ} ⇒ ${เหตุ.message}`)
    }
  }
  const ยืนยัน = (จริงไหม, ข้อความ) => {
    if (!จริงไหม) throw new Error(ข้อความ)
  }

  // --- ① ตัวอ่านป้ายอ่านถูกไหม ⇒ ใช้หน้าสั้น ๆ ที่เขียนเอง เพราะต้องคุมรูปแท็กให้ต่างกันทีละอย่าง
  ลอง('หน้าที่มีป้าย ⇒ ผ่าน', () =>
    ยืนยัน(มีป้ายห้ามเก็บ('<head><meta name="robots" content="noindex"></head>'), 'ควรผ่านแต่ไม่ผ่าน'))
  ลอง('ป้ายสลับที่คุณสมบัติและพ่วงค่าอื่น ⇒ ผ่าน', () =>
    ยืนยัน(มีป้ายห้ามเก็บ('<meta content="noindex, nofollow" name="ROBOTS">'), 'สลับที่แล้วอ่านไม่ออก'))
  ลอง('ไม่มีป้ายเลย ⇒ ต้องจับได้', () =>
    ยืนยัน(!มีป้ายห้ามเก็บ('<head><meta name="commit" content="dev"></head>'), 'ไม่มีป้ายแต่ตอบว่ามี'))
  // ⛔ คำว่า noindex ที่ลอยอยู่ในเนื้อหน้า ⛔ ไม่ใช่ป้าย ⇒ ด่านต้องไม่หลงเชื่อ
  ลอง('คำว่า noindex ในเนื้อหน้า ⇒ ⛔ ไม่นับ', () =>
    ยืนยัน(!มีป้ายห้ามเก็บ('<p>noindex</p><meta name="robots" content="all">'), 'หลงนับคำในเนื้อหน้าเป็นป้าย'))

  // --- ② กองที่ไม่มีหน้าเลย ต้องแดง ⛔ ไม่ใช่เขียว
  const กองว่าง = mkdtempSync(join(tmpdir(), 'ด่านสารบัญว่าง-'))
  ลอง('กองที่ไม่มีหน้าเลย ⇒ ต้องแดง', () => {
    let แดง = false
    try {
      ตรวจทั้งกอง(กองว่าง)
    } catch {
      แดง = true
    }
    ยืนยัน(แดง, 'กองว่างแต่ตอบว่าผ่าน')
  })
  rmSync(กองว่าง, { recursive: true, force: true })

  // --- ③ ⭐⭐ หัวใจของท่านี้ — **ถอดป้ายออกจากหน้าจริงที่เพิ่งสร้างเสร็จ**
  const ที่พัก = mkdtempSync(join(tmpdir(), 'ด่านสารบัญ-'))
  try {
    const { หน้าทั้งหมด } = ตรวจทั้งกอง(โฟลเดอร์จริง)
    // เอาหน้าที่ซ่อนลึกที่สุดมา ⇒ พิสูจน์ด้วยว่าตัวไล่โฟลเดอร์ลงไปถึงชั้นในจริง
    const หน้าที่ลึกที่สุด = [...หน้าทั้งหมด].sort(
      (ก, ข) => ข.split('/').length - ก.split('/').length || ก.localeCompare(ข),
    )[0]
    const เนื้อเดิม = readFileSync(join(โฟลเดอร์จริง, หน้าที่ลึกที่สุด), 'utf8')
    // ถอดเฉพาะแท็ก `<meta …robots…>` ออก ⛔ ไม่แตะบรรทัดอื่นของหน้า
    const เนื้อที่ถอดป้ายแล้ว = เนื้อเดิม.replace(/<meta\b[^>]*\brobots\b[^>]*>/gi, '')

    ลอง('หน้าจริงมีป้ายอยู่ก่อนถอด', () =>
      ยืนยัน(มีป้ายห้ามเก็บ(เนื้อเดิม), `หน้า ${หน้าที่ลึกที่สุด} ⛔ ไม่มีป้ายตั้งแต่แรก`))
    // ⛔ ถอดแล้วเนื้อเท่าเดิม = ท่าถอดใช้ไม่ได้ ⇒ ข้อข้างล่างจะเขียวแบบหลอกตัวเอง
    ลอง('ถอดป้ายแล้วเนื้อหน้าต้องเปลี่ยนจริง', () =>
      ยืนยัน(เนื้อที่ถอดป้ายแล้ว !== เนื้อเดิม, 'ถอดป้ายแล้วเนื้อไม่ขยับ ⇒ ท่าถอดใช้ไม่ได้'))

    mkdirSync(dirname(join(ที่พัก, หน้าที่ลึกที่สุด)), { recursive: true })
    writeFileSync(join(ที่พัก, หน้าที่ลึกที่สุด), เนื้อที่ถอดป้ายแล้ว)
    writeFileSync(join(ที่พัก, 'index.html'), readFileSync(join(โฟลเดอร์จริง, 'index.html')))

    ลอง('⭐ ถอดป้ายออกจากหน้าจริง ⇒ ด่านต้องแดงและชี้ถูกหน้า', () => {
      const { ขาด } = ตรวจทั้งกอง(ที่พัก)
      ยืนยัน(
        ขาด.length === 1 && ขาด[0] === หน้าที่ลึกที่สุด,
        `ควรฟ้องหน้าเดียวคือ ${หน้าที่ลึกที่สุด} แต่ได้ ${JSON.stringify(ขาด)}`,
      )
    })
  } finally {
    rmSync(ที่พัก, { recursive: true, force: true })
  }

  ผล.forEach((บรรทัด) => console.log(บรรทัด))
  const ล้ม = ผล.filter((บรรทัด) => บรรทัด.startsWith('⛔'))
  if (ล้ม.length) {
    console.error(`⛔ ด่านห้ามเก็บสารบัญเสียเอง ${ล้ม.length} ข้อ`)
    process.exit(1)
  }
  console.log(`✅ ด่านยังจับของผิดได้ครบ ${ผล.length} ข้อ`)
}

// ---------------------------------------------------------------------------
const วิธีใช้ = [
  'ใช้: node tools/ด่านห้ามเก็บสารบัญ.mjs <โฟลเดอร์เว็บที่สร้างเสร็จ>',
  '     node tools/ด่านห้ามเก็บสารบัญ.mjs --ทดสอบตัวเอง <โฟลเดอร์เว็บที่สร้างเสร็จ>',
].join('\n')

const [ที่สั่งมา, ที่สั่งมาสอง] = process.argv.slice(2)

if (ที่สั่งมา === '--ทดสอบตัวเอง') {
  // ⛔ ท่าพิสูจน์ต้องมีโฟลเดอร์ของจริงเสมอ — หน้าที่เขียนเองพิสูจน์ได้แค่ตัวอ่านป้าย
  //   ⛔ ไม่ได้พิสูจน์ว่าด่านแดงกับ **ไบต์ที่ผู้อ่านจะได้จริง**
  if (!ที่สั่งมาสอง) {
    console.error(วิธีใช้)
    process.exit(2)
  }
  ทดสอบตัวเอง(ที่สั่งมาสอง)
} else if (!ที่สั่งมา) {
  console.error(วิธีใช้)
  process.exit(2)
} else {
  const { หน้าทั้งหมด, ขาด } = ตรวจทั้งกอง(ที่สั่งมา)
  if (ขาด.length) {
    console.error(`⛔ ${ขาด.length} จาก ${หน้าทั้งหมด.length} หน้า ⛔ ไม่มีป้ายห้ามเก็บลงสารบัญ`)
    // พิมพ์ไม่เกิน 20 ชื่อ ⇒ ป้ายหลุดทีเดียวเป็นร้อยหน้า จอจะเต็มจนอ่านสาเหตุไม่เจอ
    ขาด.slice(0, 20).forEach((หน้า) => console.error(`   · ${หน้า}`))
    if (ขาด.length > 20) console.error(`   · … และอีก ${ขาด.length - 20} หน้า`)
    console.error('⇒ เจ้าของป้ายคือ nuxt.config.ts ก้อน app.head.meta (ใบงาน v3/phrakham#71)')
    process.exit(1)
  }
  console.log(`✅ ${หน้าทั้งหมด.length} หน้ามีป้ายห้ามเก็บลงสารบัญครบทุกหน้า`)
}
