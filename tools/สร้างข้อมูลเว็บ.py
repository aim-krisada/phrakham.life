def อ่าน_usfx(ไฟล์, ชื่อฉบับ):
    """อ่านตัวบททีละข้อจากไฟล์ USFX ⇒ ท่อเดียวใช้ได้ทั้ง Thai KJV และ WEB

    ⭐ กรองให้เหลือ 66 เล่ม ⇒ WEB มีเล่มนอกสารบบติดมาด้วย
    """
    เก็บ = collections.defaultdict(list)
    ที่อยู่ = [None]

    def เดิน(el):
        t = el.tag
        if t == "v":
            ที่อยู่[0] = el.get("bcv")
            if ที่อยู่[0]:
                เก็บ[ที่อยู่[0]]          # จองช่องไว้ก่อน ⇒ เหตุผลเดียวกับใน อ่าน_usx
            if el.tail and ที่อยู่[0]:
                เก็บ[ที่อยู่[0]].append(el.tail)
            return
        if t == "ve":
            ที่อยู่[0] = None
            return
        if t in ข้ามใน_usfx:
            if el.tail and ที่อยู่[0]:
                เก็บ[ที่อยู่[0]].append(el.tail)
            return
        if el.text and ที่อยู่[0]:
            เก็บ[ที่อยู่[0]].append(el.text)
        for c in el:
            เดิน(c)
        if el.tail and ที่อยู่[0]:
            เก็บ[ที่อยู่[0]].append(el.tail)

    เดิน(ET.parse(ไฟล์).getroot())
    ข้อ, นอกสารบบ, ว่าง = {}, set(), []
    for bcv, ส่วน in เก็บ.items():
        ชิ้น = bcv.split(".")
        if len(ชิ้น) != 3:
            continue
        รหัส, บท, ข = ชิ้น
        if รหัส not in สารบบ:
            นอกสารบบ.add(รหัส)
            continue
        เนื้อ = เล็มหัวท้าย("".join(ส่วน))
        if เนื้อ in ("", "-"):
            ว่าง.append(f"{รหัส} {int(บท)}.{int(ข)}")
            continue
        ข้อ[(รหัส, str(int(บท)), str(int(ข)))] = เนื้อ
    ขาด = [c for c in สารบบ if not any(k[0] == c for k in ข้อ)]
    if ขาด:
        ผิด(f"{ชื่อฉบับ}: ไม่มีเนื้อของเล่ม {', '.join(ขาด)}")
    return ข้อ, sorted(นอกสารบบ), sorted(ว่าง)


# ============================================================== อ่านชั้นคำ
def อ่านชั้นคำ(ไฟล์, ชื่อแหล่ง, ทำคำ):
    """อ่านตารางคำของ MACULA ⇒ คืน {(เล่ม, บท, ข้อ): [คำ, ...]}

    ⭐ ตัดช่องที่เจ้าของไม่ให้เผยแพร่ทิ้งตรงนี้ ⇒ **ไม่มีทางหลุดไปถึงไฟล์ผลลัพธ์**
    """
    ตัดทิ้ง = set(ห้ามเผยแพร่) | set(เลือกไม่เอา)
    out = collections.defaultdict(list)
    with io.open(ไฟล์, encoding="utf-8", newline="") as f:
        ตาราง = csv.DictReader(f, delimiter="\t")
        หลุด = ตัดทิ้ง & set(ตาราง.fieldnames or [])
        for แถว in ตาราง:
            ที่อยู่ = แถว.get("ref") or ""
            try:
                รหัส, ที่เหลือ = ที่อยู่.split(" ", 1)
                บทข้อ, _ = ที่เหลือ.split("!", 1)
                บท, ข = บทข้อ.split(":", 1)
            except ValueError:
                continue
            if รหัส not in สารบบ:
                continue
            คำ = ทำคำ(แถว)
            for ช่อง in ตัดทิ้ง:
                คำ.pop(ช่อง, None)          # กันพลาดชั้นที่สอง ⇒ เผื่อ ทำคำ เผลอหยิบมา
            out[(รหัส, บท, ข)].append(คำ)
    print(f"   ตัดช่องที่ห้ามเผยแพร่ออก {len(หลุด)} ช่อง ⇒ {', '.join(sorted(หลุด)) or 'ไม่มีช่องนั้นในตาราง'}")
    return out


def คำฮีบรู(แถว):
    """หยิบเฉพาะช่องที่หน้าเว็บใช้ ⇒ ช่องที่ไม่ได้หยิบ ไม่มีทางหลุดออกไป"""
    คำ = {"ตัว": แถว["text"], "คำอ่าน": แถว["transliteration"],
          "รูปพจนานุกรม": แถว["lemma"], "รหัส": แถว["strongnumberx"],
          "รูปผัน": แถว["morph"], "คำแปล": แถว["gloss"] or แถว["english"] or "",
          "บทบาท": แถว.get("frame", "")}
    if แถว["after"] == "":
        คำ["ติดคำหลัง"] = True
    if แถว["lang"] == "A":
        คำ["อาราเมค"] = True
    return {k: v for k, v in คำ.items() if v not in ("", None)}


def คำกรีก(แถว):
    คำ = {"ตัว": แถว["text"], "รูปพจนานุกรม": แถว["lemma"], "รหัส": แถว["strong"],
          "รูปผัน": แถว["morph"], "คำแปล": แถว["gloss"] or แถว["english"] or "",
          "บทบาท": แถว.get("frame", ""), "ชี้กลับไปที่": แถว.get("referent", "")}
    if แถว["after"] == "":
        คำ["ติดคำหลัง"] = True
    return {k: v for k, v in คำ.items() if v not in ("", None)}


# ============================================================== เครดิต
หัวข้อแหล่ง = re.compile(r"^### (?:<a id=\"[^\"]*\"></a>)?\[(?P<ชื่อ>[^\]]+)\]\((?P<ที่อยู่>[^)]+)\)")


def อ่านเครดิต():
    """ดึงเครดิตของแต่ละแหล่งจากหน้าเว็บ ⇒ ⭐ **หน้าเว็บเป็นเจ้าของถ้อยคำ**

    ⛔ ไม่คัดประโยคเครดิตมาเขียนไว้ในสคริปต์ — คัดแล้วหน้าเว็บแก้ สำเนาจะค้างทันที
    ⇒ กฎ *ความจริงมีเจ้าของแล้ว* ใน วิธีทำงาน.md
    """
    เครดิต, ชื่อ = {}, None
    for บรรทัด in io.open(หน้าแหล่ง, encoding="utf-8"):
        m = หัวข้อแหล่ง.match(บรรทัด)
        if m:
            ชื่อ = m.group("ชื่อ")
            เครดิต[ชื่อ] = {"ชื่อ": ชื่อ, "ที่อยู่": m.group("ที่อยู่"), "สัญญา": "", "เครดิต": ""}
            continue
        if not ชื่อ:
            continue
        ท = บรรทัด.strip()
        if ท.startswith("- สัญญา "):
            เครดิต[ชื่อ]["สัญญา"] = ท[len("- สัญญา "):].strip()
        elif ท.startswith("- เครดิต "):
            เครดิต[ชื่อ]["เครดิต"] = ท[len("- เครดิต "):].strip()
        elif "เครดิตฉบับเต็ม" in ท:
            เนื้อ = re.sub(r"^.*?</summary>", "", ท)
            เครดิต[ชื่อ]["เครดิต"] = re.sub(r"</details>\s*$", "", เนื้อ).strip()
        elif ท.startswith("## ") and ชื่อ:
            ชื่อ = None
    return เครดิต


# ============================================================== เขียนไฟล์
def เขียน(ทาง, ของ):
    """เขียน JSON แบบเดิมทุกครั้ง ⇒ เรียงกุญแจตายตัว ⛔ ไม่มีเวลาหรือของสุ่มปนอยู่"""
    ทาง.parent.mkdir(parents=True, exist_ok=True)
    ทาง.write_text(json.dumps(ของ, ensure_ascii=False, sort_keys=True,
                              separators=(",", ":")) + "\n", encoding="utf-8")


def เรียงเลข(กุญแจ):
    return sorted(กุญแจ, key=lambda x: int(x))


