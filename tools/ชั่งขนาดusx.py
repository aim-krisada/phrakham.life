def บีบgzip(ไบต์):
    """บีบท่าเดียวกับ `tools/สร้างเนื้อบท.py` ⇒ ไม่ประทับชื่อไฟล์และเวลา ⇒ บีบซ้ำได้ผลเดิม"""
    ถัง = io.BytesIO()
    with gzip.GzipFile(fileobj=ถัง, mode="wb", compresslevel=9, mtime=0) as ซ:
        ซ.write(ไบต์)
    return ถัง.getvalue()


def ชั่งฉบับ(ฉ):
    """ชั่ง **ไฟล์ USX ที่จะขึ้นเว็บจริง** ⛔ ไม่ใช่ไฟล์ต้นทางก่อนแปลง

    ⇒ ฉบับที่ต้องแปลงก่อน ต้องสั่ง `tools/แปลงusfmเป็นusx.mjs` ให้เสร็จก่อนชั่ง
    คืน [(เล่ม, ดิบ, gzip, brotli), ...] ⇒ เรียงตามสารบบ ⛔ ไม่เรียงตามตัวอักษร
    """
    แถว = []
    for เล่ม in สารบบ:
        ทาง = ฉ.ไฟล์usx(เล่ม)
        if not ทาง.exists():
            continue
        ไบต์ = ทาง.read_bytes()
        แถว.append((เล่ม, len(ไบต์), len(บีบgzip(ไบต์)), len(brotli.compress(ไบต์, quality=11))))
    return แถว


def กิโล(n):
    return f"{n / KiB:,.1f} กิโลไบต์"


def เมกะ(n):
    return f"{n / MiB:,.2f} เมกะไบต์"


def main():
    ก = argparse.ArgumentParser(description="ชั่งไฟล์ตัวบทของเจ้าของ — ใบงาน #74 ก้อนที่ 1")
    ก.add_argument("--เขียน", dest="write", action="store_true",
                   help="เขียนผลลง docs/ข้อมูล/ผลชั่งusx.json และ .md")
    ก.add_argument("--ความเร็วเน็ต", type=float, default=เร็วปริยาย)
    ก.add_argument("--เวลาหน่วง", type=float, default=หน่วงปริยาย)
    ก.add_argument("--สายพร้อมกัน", type=int, default=สายปริยาย)
    ต = ก.parse_args()

    ของ = {"สมมติ": {"ความเร็วกิโลบิตต่อวินาที": ต.ความเร็วเน็ต,
                     "หน่วงมิลลิวินาทีต่อคำขอ": ต.เวลาหน่วง,
                     "สายพร้อมกัน": ต.สายพร้อมกัน},
           "ฉบับ": {}, "ยังชั่งไม่ได้": ยังไม่ได้}

    print("=" * 78)
    print("① ชั่งไฟล์ของเจ้าของ — ไบต์จริง ⇒ เครื่องไหนรันก็ได้เลขเดียวกัน")
    print("=" * 78)
    for ฉ in ฉบับ:
        แถว = ชั่งฉบับ(ฉ)
        if not แถว:
            print(f"⛔ {ฉ.รหัส} ไม่เจอไฟล์สักเล่มที่ {ฉ.ที่อยู่}")
            continue
        ดิบ = [ร[1] for ร in แถว]
        ก_z = [ร[2] for ร in แถว]
        ใหญ่ = max(แถว, key=lambda ร: ร[1])
        เล็ก = min(แถว, key=lambda ร: ร[1])
        ของ["ฉบับ"][ฉ.รหัส] = {
            "เจ้าของ": ฉ.เจ้าของ, "รูปต้นทาง": ฉ.รูป, "เล่ม": len(แถว),
            "รวมดิบ": sum(ดิบ), "รวมgzip": sum(ก_z), "รวมbrotli": sum(ร[3] for ร in แถว),
            "รายเล่ม": [{"เล่ม": ร[0], "ดิบ": ร[1], "gzip": ร[2], "brotli": ร[3]} for ร in แถว],
        }
        print(f"\n{ฉ.รหัส} · {ฉ.เจ้าของ} · {len(แถว)} เล่ม")
        print(f"   รวมทั้งชุด  ดิบ {เมกะ(sum(ดิบ))} · gzip {เมกะ(sum(ก_z))}"
              f" · brotli {เมกะ(sum(ร[3] for ร in แถว))}")
        print(f"   เล่มใหญ่สุด {ใหญ่[0]} ⇒ ดิบ {กิโล(ใหญ่[1])} · gzip {กิโล(ใหญ่[2])} · brotli {กิโล(ใหญ่[3])}")
        print(f"   เล่มเล็กสุด {เล็ก[0]} ⇒ ดิบ {กิโล(เล็ก[1])} · gzip {กิโล(เล็ก[2])} · brotli {กิโล(เล็ก[3])}")
        print(f"   ค่ากลาง     ดิบ {กิโล(statistics.median(ดิบ))} · gzip {กิโล(statistics.median(ก_z))}")

    print()
    print("=" * 78)
    print("② ผู้อ่านต้องรอกี่วินาที — ⛔ **เลขสมมติ** ⇒ เน็ตของผู้อ่านอยู่นอกเครื่องเรา")
    print("=" * 78)
    print(f"   ความเร็ว {ต.ความเร็วเน็ต:,.0f} กิโลบิต/วินาที · หน่วงคำขอละ {ต.เวลาหน่วง:,.0f} มิลลิวินาที"
          f" · เปิดพร้อมกัน {ต.สายพร้อมกัน} สาย")
    print("   สูตรอยู่ที่ `tools/ชั่งชั้นคำ.py` ⇒ รอสาย + ส่งไบต์ ⛔ ไม่มีตัวคูณลึกลับ\n")
    for รหัส, ก้อน in ของ["ฉบับ"].items():
        ก_z = [ร["gzip"] for ร in ก้อน["รายเล่ม"]]
        ช่อง = []
        for ไบต์ in (max(ก_z), int(statistics.median(ก_z))):
            รอ, ส่ง = เวลาบนเน็ตช้า(ไบต์, 1, ต.ความเร็วเน็ต, ต.เวลาหน่วง, ต.สายพร้อมกัน)
            ช่อง.append(f"{รอ + ส่ง:,.1f} วินาที ({กิโล(ไบต์)})")
        ก้อน["วินาทีเล่มใหญ่สุด"] = round(sum(เวลาบนเน็ตช้า(
            max(ก_z), 1, ต.ความเร็วเน็ต, ต.เวลาหน่วง, ต.สายพร้อมกัน)), 3)
        print(f"   {รหัส}")
        print(f"      เปิดเล่มใหญ่สุด  {ช่อง[0]}")
        print(f"      เปิดเล่มค่ากลาง  {ช่อง[1]}")

    if ยังไม่ได้:
        print("\n⏸ ฉบับที่ยังชั่งไม่ได้")
        for รหัส, เหตุ in ยังไม่ได้.items():
            print(f"   {รหัส} ⇒ {เหตุ}")

    if ต.write:
        ผลjson.parent.mkdir(parents=True, exist_ok=True)
        ผลjson.write_text(json.dumps(ของ, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
                          encoding="utf-8", newline="\n")
        เขียนmd(ของ)
        print(f"\n✅ เขียน {ผลjson.relative_to(ที่เก็บ)} และ {ผลmd.relative_to(ที่เก็บ)}")
    return 0


def เขียนmd(ของ):
    """เขียนตารางให้คนอ่าน ⇒ ⭐ **ทุกตัวเลขมาจากของที่เพิ่งชั่ง** ⛔ ไม่มีที่พิมพ์ด้วยมือ"""
    บ = []
    บ.append("# ไฟล์ตัวบทของเจ้าของ หนักเท่าไร")
    บ.append("")
    บ.append("⛔ **ห้ามแก้ไฟล์นี้ด้วยมือ** ⇒ สร้างด้วย `py -3.14 tools/ชั่งขนาดusx.py --เขียน`")
    บ.append("")
    บ.append("## ① ขนาดไฟล์ — วัดจากไฟล์จริง")
    บ.append("")
    บ.append("| ฉบับ | เจ้าของ | เล่ม | รวมดิบ | รวม gzip | รวม brotli |")
    บ.append("|---|---|---:|---:|---:|---:|")
    for รหัส, ก in ของ["ฉบับ"].items():
        บ.append(f"| {รหัส} | {ก['เจ้าของ']} | {ก['เล่ม']} | {เมกะ(ก['รวมดิบ'])} "
                 f"| {เมกะ(ก['รวมgzip'])} | {เมกะ(ก['รวมbrotli'])} |")
    บ.append("")
    บ.append("## ② เล่มใหญ่ที่สุด 5 เล่มของแต่ละฉบับ")
    บ.append("")
    บ.append("| ฉบับ | เล่ม | ดิบ | gzip | brotli |")
    บ.append("|---|---|---:|---:|---:|")
    for รหัส, ก in ของ["ฉบับ"].items():
        for ร in sorted(ก["รายเล่ม"], key=lambda ร: -ร["ดิบ"])[:5]:
            บ.append(f"| {รหัส} | {ร['เล่ม']} | {กิโล(ร['ดิบ'])} | {กิโล(ร['gzip'])} "
                     f"| {กิโล(ร['brotli'])} |")
    บ.append("")
    บ.append("## ③ เวลารอของผู้อ่าน — ⛔ เลขสมมติ")
    บ.append("")
    ส = ของ["สมมติ"]
    บ.append(f"สมมติเน็ต {ส['ความเร็วกิโลบิตต่อวินาที']:,.0f} กิโลบิต/วินาที "
             f"หน่วงคำขอละ {ส['หน่วงมิลลิวินาทีต่อคำขอ']:,.0f} มิลลิวินาที "
             f"เปิดพร้อมกัน {ส['สายพร้อมกัน']} สาย")
    บ.append("")
    บ.append("| ฉบับ | เปิดเล่มใหญ่สุด (gzip) |")
    บ.append("|---|---:|")
    for รหัส, ก in ของ["ฉบับ"].items():
        บ.append(f"| {รหัส} | {ก['วินาทีเล่มใหญ่สุด']:,.1f} วินาที |")
    if ของ["ยังชั่งไม่ได้"]:
        บ.append("")
        บ.append("## ⏸ ฉบับที่ยังชั่งไม่ได้")
        บ.append("")
        for รหัส, เหตุ in ของ["ยังชั่งไม่ได้"].items():
            บ.append(f"- **{รหัส}** ⇒ {เหตุ}")
    ผลmd.write_text("\n".join(บ) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    sys.exit(main())
