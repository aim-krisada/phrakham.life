// ---------------------------------------------------------------- ① บท กับ บทที่มี ไม่ขัดกัน
async function ตรวจสารบัญ(บัญชี) {
  const ตก = []
  for (const เล่ม of บัญชี.เล่ม) {
    const เรียง = เล่ม.บทที่มี.every((c, i) => c === i + 1)
    if (เล่ม.บท !== เล่ม.บทที่มี.length || !เรียง)
      ตก.push(`${เล่ม.รหัส} ⇒ 🔴 ① บท ${เล่ม.บท} ⛔ ตรงกับ บทที่มี [${เล่ม.บทที่มี.join(' ')}]`)
    if (!Number.isInteger(เล่ม.บทเดิม) || เล่ม.บทเดิม < 1) {
      ตก.push(`${เล่ม.รหัส} ⇒ 🔴 ① ⛔ มีช่อง บทเดิม ที่เป็นจำนวนบท ⇒ ได้ ${เล่ม.บทเดิม}`)
      continue
    }
    const [มี, เกิน] = await Promise.all([
      ขอ(`api/words/${เล่ม.รหัส}/${เล่ม.บทเดิม}.json`),
      ขอ(`api/words/${เล่ม.รหัส}/${เล่ม.บทเดิม + 1}.json`),
    ])
    if (!มี || เกิน) ตก.push(`${เล่ม.รหัส} ⇒ 🔴 ① บทเดิม ${เล่ม.บทเดิม} ⛔ ตรงกับไฟล์คำเดิมที่เว็บส่ง`)
  }
  const รวม = บัญชี.เล่ม.reduce((ร, x) => ร + x.บท, 0)
  if (บัญชี.จำนวนบท !== รวม) ตก.push(`🔴 ① จำนวนบท ${บัญชี.จำนวนบท} ⛔ เท่ากับผลรวม บท ของทุกเล่ม ${รวม}`)
  return ตก
}
{
  const ตก = await ตรวจสารบัญ(สารบัญ)
  ที่ตก.push(...ตก)
  console.log(`${ตก.length ? '⛔' : '✅'} ① api/books.json ${สารบัญ.เล่ม.length} เล่ม ⇒ บท = จำนวนบทที่มี · บทเดิม ตรงกับไฟล์คำเดิม`)
  for (const x of ตก.slice(0, 10)) console.log(`   ${x}`)
}

// ---------------------------------------------------------------- ข้อเดิมต่างบท ⇒ คิดจากไฟล์ `api/words`
/** ไฟล์คำเดิมทุกบทของเล่ม ⇒ `{<บทเดิม>: ไฟล์}` */
const คลังไฟล์ = new Map()
async function ไฟล์คำของเล่ม(เล่ม) {
  if (คลังไฟล์.has(เล่ม.รหัส)) return คลังไฟล์.get(เล่ม.รหัส)
  const บท = Array.from({ length: Math.max(เล่ม.บท, เล่ม.บทเดิม ?? 0) }, (_, i) => i + 1)
  const ได้ = await Promise.all(บท.map((c) => ขอ(`api/words/${เล่ม.รหัส}/${c}.json`)))
  const ออก = {}
  ได้.forEach((x, i) => {
    if (x) ออก[บท[i]] = x
  })
  คลังไฟล์.set(เล่ม.รหัส, ออก)
  return ออก
}
/** ข้อแปลของข้อเดิม ⇒ ตาราง `ข้อแปล` ⇒ ไม่มีกุญแจ = เลขเดียวกับตัวเอง */
const ข้อแปลของ = (ไฟล์, ข้อ) => ไฟล์.ข้อแปล?.[ข้อ]?.[0] ?? [ไฟล์.บท, Number(ข้อ)]
const เลขข้อของไฟล์ = (ไฟล์) =>
  [...new Set(Object.values(ไฟล์.ชั้น).flatMap((x) => Object.keys(x)))].map(Number).sort((a, b) => a - b)

/**
 * ข้อแรกของทุกช่วงข้อเดิมที่อยู่คนละบทกับข้อแปล ⇒ `[{เล่ม, ตัวบท, เดิม:[บ,ข], แปล:[บ,ข], แถวเดิม, ท้ายบท}]`
 *   ⇒ `แถวเดิม` = ข้อเดิมข้อแรกที่อยู่แถวเดียวกัน · `ท้ายบท` = ข้อแปลเป็นข้อสุดท้ายของบท (`ข้อสุดท้าย` ของ `api/books.json`)
 */
const กรณีต่างบท = []
/** `<เล่ม> <บทแปล:ข้อแปล>` ⇒ ข้อเดิมข้อแรกของแถวนั้น */
const แถวแรก = new Map()
let นับต่างบท = 0
for (const เล่ม of สารบัญ.เล่ม) {
  const ไฟล์ = await ไฟล์คำของเล่ม(เล่ม)
  const ตัวบท = เล่ม.พันธสัญญา === 'เดิม' ? 'WLC' : 'SBLGNT'
  for (const f of Object.values(ไฟล์).sort((a, b) => a.บท - b.บท))
    for (const O of เลขข้อของไฟล์(f)) {
      const k = `${เล่ม.รหัส} ${ข้อแปลของ(f, String(O)).join(':')}`
      if (!แถวแรก.has(k)) แถวแรก.set(k, `${f.บท}:${O}`)
    }
  for (const f of Object.values(ไฟล์)) {
    let ก่อน = false
    for (const O of เลขข้อของไฟล์(f)) {
      const แปล = ข้อแปลของ(f, String(O))
      const ต่าง = แปล[0] !== f.บท
      if (ต่าง) นับต่างบท++
      if (ต่าง && !ก่อน)
        กรณีต่างบท.push({
          เล่ม: เล่ม.รหัส,
          ตัวบท,
          เดิม: [f.บท, O],
          แปล,
          แถวเดิม: แถวแรก.get(`${เล่ม.รหัส} ${แปล.join(':')}`),
          ท้ายบท: เล่ม.ข้อสุดท้าย?.[เล่ม.บทที่มี.indexOf(แปล[0])] === แปล[1],
        })
      ก่อน = ต่าง
    }
  }
}
