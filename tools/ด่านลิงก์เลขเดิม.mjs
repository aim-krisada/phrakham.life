/** ตัวรับแทนเมนูแชร์ ⇒ ท่าเดียวกับ `tools/ด่านแชร์การ์ดคำ.mjs` ⇒ เก็บข้อความที่ส่งไว้ที่ `window.__ส่งออก` */
function ตัวรับแทน() {
  window.__ส่งออก = []
  Object.defineProperty(navigator, 'share', {
    configurable: true,
    get: () => async (ของ) => window.__ส่งออก.push(ของ.text),
  })
  Object.defineProperty(navigator, 'canShare', { configurable: true, get: () => undefined })
}

/**
 * `พัง` (โหมดพิสูจน์เท่านั้น) ⇒ `ไม่มีตาราง` ตัดช่อง `ข้อแปล` ออกจากไฟล์คำ · `เขียนเลขแปล` ตัวเขียนที่อยู่แบบก่อนใบนี้
 *   · `อ่านเลขเดิมเสมอ` ⇒ ลิงก์ฉบับแปลถูกอ่านเป็นเลขเดิม
 */
async function บริบท(พัง = {}, จอ = { width: 1280, height: 900 }) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: จอ })
  await ctx.addInitScript(ตัวรับแทน)
  await เฝ้าข้อผิดพลาด(ctx)
  if (พัง.แทนโค้ด) {
    // ⭐ แก้โค้ดของเว็บที่เสิร์ฟจริงตอนส่งถึงเบราว์เซอร์ ⇒ ท่าเดียวกับ `tools/ด่านลิงก์เว็บเดิม.mjs` ⇒ นับว่าแทนเข้าจริงกี่ครั้ง
    await ctx.route('**/_nuxt/*.js', async (route) => {
      const r = await route.fetch()
      let เนื้อ = await r.text()
      for (const [จาก, เป็น] of พัง.แทนโค้ด) {
        const ก่อน = เนื้อ
        เนื้อ = เนื้อ.replace(จาก, เป็น)
        if (เนื้อ !== ก่อน) พัง.นับแทน = (พัง.นับแทน ?? 0) + 1
      }
      await route.fulfill({ response: r, body: เนื้อ })
    })
  }
  if (พัง.ที่อยู่ค้างบทแรก)
    // ⭐ ที่อยู่ ⛔ ตามบทที่อ่านอยู่ ⇒ ตัวเขียนที่อยู่ทิ้งทุกครั้งที่ `c` ไม่ใช่บทที่ลิงก์เปิด ⇒ อาการของการแก้ใบ #183 ที่แก้เกิน
    await ctx.addInitScript(() => {
      const แรก = new URL(location.href).searchParams.get('c')
      const เดิม = history.replaceState.bind(history)
      history.replaceState = (s, t, url) => {
        const c = typeof url === 'string' ? new URL(url, location.href).searchParams.get('c') : null
        if (แรก && c && c !== แรก) return
        return เดิม(s, t, url)
      }
    })
  await ctx.addInitScript(() => {
    localStorage.setItem('phrakham.view', JSON.stringify({ จัดวาง: 'แยกตามข้อ', แสดงเลข: true, ขนาดคำเดิม: 'พอดี' }))
  })
  if (พัง.ไม่มีตาราง)
    await ctx.route('**/api/words/**', async (r) => {
      const ตอบ = await r.fetch()
      if (!ตอบ.ok()) return r.fulfill({ response: ตอบ })
      const ไฟล์ = await ตอบ.json()
      delete ไฟล์.ข้อแปล
      await r.fulfill({ response: ตอบ, json: ไฟล์ })
    })
  if (พัง.เขียนเลขแปล)
    // ⭐ ตัวเขียนที่อยู่แบบก่อนใบนี้ ⇒ `c` `v` เป็นเลขของข้อแปลที่หน้าพาไป ⇒ ด่านส่งคู่เลขมาให้ (`[[เดิม, แปล]]`)
    await ctx.addInitScript((คู่) => {
      const เดิม = history.replaceState.bind(history)
      history.replaceState = (s, t, url) => {
        if (typeof url === 'string') {
          const u = new URL(url, location.href)
          for (const [[ab, av], [tb, tv]] of คู่)
            if (u.searchParams.get('c') === String(ab) && u.searchParams.get('v') === String(av)) {
              u.searchParams.set('c', String(tb))
              u.searchParams.set('v', String(tv))
            }
          url = u.pathname + u.search
        }
        return เดิม(s, t, url)
      }
    }, พัง.เขียนเลขแปล)
  if (พัง.อ่านเลขเดิมเสมอ)
    // ⭐ ลิงก์ฉบับแปลถูกอ่านเป็นเลขเดิม ⇒ ย้ายตัวบทภาษาเดิมขึ้นหน้า `t` ก่อนหน้าโหลด ⇒ ⛔ ไม่ใช่ลิงก์ที่ผู้อ่านส่งมา
    await ctx.addInitScript(() => {
      const u = new URL(location.href)
      const t = u.searchParams.get('t')?.split(',') ?? []
      const เดิม = t.find((x) => x === 'WLC' || x === 'SBLGNT')
      if (เดิม && t[0] !== เดิม) {
        u.searchParams.set('t', [เดิม, ...t.filter((x) => x !== เดิม)].join(','))
        history.replaceState(null, '', u.pathname + u.search)
      }
    })
  return ctx
}

/**
 * รอจนข้อเป้ามาอยู่หัวจอใต้แถบหนึบ ⇒ แล้ววัดซ้ำ ⇒ คืนผลวัดครั้งหลัง
 *   ⇒ `เดิม` = `บท:ข้อ` ของข้อเดิมที่ลิงก์ขอ (`data-ข้อเดิม`) ⇒ ต้องอยู่ในจอใต้แถบหนึบ
 *   ⇒ `แถวเดิม` = ข้อเดิมข้อแรกของแถวเดียวกัน ⇒ ต้องอยู่หัวจอ ⇒ หน้าพาไปที่ *แถว* (ข้อแปลข้อเดียวมีข้อเดิมหลายข้อได้ ⇒ 1 ซามูเอล 20:42 = ฮีบรู 20:42 + 21:1)
 *   ⇒ `แปล` = `บท:ข้อ` ของข้อแปล (`#ข้อ-บท-ข้อ`) ⇒ ต้องอยู่หัวจอ ⇒ ไม่ส่ง = ไม่ตรวจ
 */
async function วัดหัวจอ(แท็บ, { เดิม, แถวเดิม, แปล }) {
  const วัด = ([เดิม, แถวเดิม, แปล, ช่วง]) => {
    const ขอบ = parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--pk-ขอบล่างหนึบ')) || 0
    const บนของ = (e) => (e ? e.getBoundingClientRect().top - ขอบ : null)
    const ข้อเดิมของ = (k) => (k ? [...document.querySelectorAll(`.pk-ข้อคำ[data-ข้อเดิม="${k}"]`)].find((e) => e.offsetParent) : null)
    const ข้อแปล = แปล ? document.getElementById(`ข้อ-${แปล.replace(':', '-')}`) : null
    const ผล = {
      เดิม: บนของ(ข้อเดิมของ(เดิม)),
      แถวเดิม: บนของ(ข้อเดิมของ(แถวเดิม ?? เดิม)),
      แปล: บนของ(ข้อแปล),
      เตือน: document.querySelector('.pk-เตือน')?.textContent.trim() ?? '',
      ที่อยู่: location.search,
    }
    const ใน = (x) => x !== null && x >= ช่วง.บน && x <= ช่วง.ล่าง
    const ในจอ = (x) => x !== null && x >= ช่วง.บน && x + ขอบ <= innerHeight - 30
    ผล.ถึง = (!เดิม || (ในจอ(ผล.เดิม) && ใน(ผล.แถวเดิม))) && (!แปล || ใน(ผล.แปล))
    return ผล
  }
  await แท็บ.waitForFunction((x) => {
    const จ = document.querySelector('.pk-ตัวบท')?.getAttribute('data-จัดแถว')
    return (จ === 'เสร็จ' || !จ) && document.fonts.status === 'loaded'
  }, null, { timeout: รอนานสุด }).catch(() => {})
  await แท็บ.waitForFunction((ส) => (new Function(`return (${ส.f})`)())(ส.a).ถึง, { f: วัด.toString(), a: [เดิม, แถวเดิม, แปล, หัวจอ] }, { timeout: รอนานสุด }).catch(() => {})
  await แท็บ.waitForTimeout(600)
  return แท็บ.evaluate(วัด, [เดิม, แถวเดิม, แปล, หัวจอ])
}

/**
 * เปิดลิงก์แล้วตรวจที่ที่มันพาไป ⇒ คืนรายการที่ตก
 *   ⇒ `ส` ⇒ `{ที่อยู่, ป้าย, ข้อตรวจ, เดิม?, แปล?, cv?, เตือน?}` ⇒ `cv` = `c` `v` ที่ต้องอยู่ในที่อยู่หลังเปิดเสร็จ
 */
async function ตรวจลิงก์(ctx, ส) {
  const ตก = []
  const แท็บ = await ctx.newPage()
  try {
    await แท็บ.goto(`${ฐาน}${ส.ที่อยู่}`, { waitUntil: 'domcontentloaded' })
    await รอโค้ดของเว็บติด(แท็บ)
    if (ส.เตือน) {
      const ได้ = await แท็บ
        .waitForFunction((ค) => document.querySelector('.pk-เตือน')?.textContent.includes(ค), ส.เตือน, { timeout: รอนานสุด })
        .then(() => true)
        .catch(() => false)
      if (!ได้) ตก.push(`${ส.ป้าย} ⇒ 🔴 ${ส.ข้อตรวจ} ⛔ ขึ้นข้อความ «${ส.เตือน}»`)
      return ตก
    }
    const ผล = await วัดหัวจอ(แท็บ, ส)
    if (/ไม่มีบท/.test(ผล.เตือน)) ตก.push(`${ส.ป้าย} ⇒ 🔴 ${ส.ข้อตรวจ} ขึ้น «${ผล.เตือน}»`)
    const บอก = (ชื่อ, x) =>
      x === null ? `${ชื่อ} ⛔ อยู่บนหน้า` : `${ชื่อ} อยู่ห่างขอบล่างแถบหนึบ ${Math.round(x)} จุด ⛔ อยู่หัวจอ`
    if (!ผล.ถึง) {
      if (ส.เดิม) ตก.push(`${ส.ป้าย} ⇒ 🔴 ${ส.ข้อตรวจ} ${บอก(`ข้อเดิม ${ส.เดิม}`, ผล.เดิม)}`)
      if (ส.แถวเดิม && ส.แถวเดิม !== ส.เดิม)
        ตก.push(`${ส.ป้าย} ⇒ 🔴 ${ส.ข้อตรวจ} ${บอก(`ข้อเดิมข้อแรกของแถว ${ส.แถวเดิม}`, ผล.แถวเดิม)}`)
      if (ส.แปล) ตก.push(`${ส.ป้าย} ⇒ 🔴 ${ส.ข้อตรวจ} ${บอก(`ข้อแปล ${ส.แปล}`, ผล.แปล)}`)
    }
    if (ส.cv && ส.ท้ายบท) {
      // ⭐ ใบ #183 ⇒ ข้อสุดท้ายของบท ⇒ อาการโผล่ **หลัง** บทถัดไปต่อเข้ามาใต้ข้อนั้นแล้วหน้าพาไปข้อเดิมซ้ำ
      //   ⇒ อ่านที่อยู่ก่อนบทถัดไปมา = ยังไม่ได้ตรวจอะไร ⇒ รอให้มีหมุดบทมากกว่า 1 ตัวและตัวจัดแถวเสร็จ ⇒ แล้วรอหน้านิ่งอีกครู่ค่อยอ่าน
      //   ⇒ บทถัดไป ⛔ มา = แดงพร้อมบอก ⛔ ไม่เขียวเงียบ
      const มา = await แท็บ
        .waitForFunction(() => {
          const จ = document.querySelector('.pk-ตัวบท')?.getAttribute('data-จัดแถว')
          return document.querySelectorAll('[data-หมุดบท]').length > 1 && (จ === 'เสร็จ' || !จ)
        }, null, { timeout: รอนานสุด })
        .then(() => true)
        .catch(() => false)
      if (!มา) ตก.push(`${ส.ป้าย} ⇒ 🔴 ${ส.ข้อตรวจ} บทถัดไป ⛔ ต่อเข้ามาใต้ข้อสุดท้ายของบท ⇒ ตรวจที่อยู่ข้อนี้ไม่ได้`)
      await แท็บ.waitForTimeout(1200)
      ผล.ที่อยู่ = await แท็บ.evaluate(() => location.search)
    }
    if (ส.cv) {
      const q = new URLSearchParams(ผล.ที่อยู่)
      const ได้ = `c=${q.get('c')}&v=${q.get('v')}`
      if (ได้ !== ส.cv) ตก.push(`${ส.ป้าย} ⇒ 🔴 ${ส.ข้อตรวจ} ที่อยู่หลังเปิดเสร็จเป็น ${ได้} ⛔ ต้องเป็น ${ส.cv}`)
    }
  } catch (e) {
    ตก.push(`${ส.ป้าย} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message}`)
  } finally {
    await แท็บ.close()
  }
  return ตก
}

