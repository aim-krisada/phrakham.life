/**
 * ตรวจการยืมทุกบท ⇒ คืนรายการที่พัง กับตัวเลขที่ตรวจ
 * `ยืม(ข้อของเรา, รอยต้นแบบ, ข้อของต้นแบบ)` ⇒ ฟังก์ชันที่ถูกตรวจ ⇒ โหมดพิสูจน์ส่งแบบผิดเข้ามาแทน
 */
function ตรวจยืม(ยืม) {
  const ตก = []
  const นับ = { บท: 0, ย่อหน้า: 0, ตัวอักษร: 0, บทเลขข้อไม่ตรง: 0, บทที่รอยกลางข้อ: 0 }
  const ผู้ยืม = Object.keys(ซองย่อ.ไม่มี || {}).filter((ฉ) => เนื้อบท['ชั้น'].includes(ฉ))
  const ต้นแบบทั้งหมด = Object.keys(ซองย่อ.ฉบับ)
  for (const ข of ผู้ยืม) {
    for (const ต of ต้นแบบทั้งหมด) {
      for (const กุญแจ of Object.keys(เนื้อบท['บท'])) {
        const ของเรา = ข้อของ(ข, กุญแจ)
        if (!ของเรา?.length) continue
        const รอย = ซองย่อ.ฉบับ[ต][กุญแจ] || []
        const ของต้นแบบ = ข้อของ(ต, กุญแจ) || []
        const ย่อ = ยืม(ของเรา, รอย, ของต้นแบบ)
        const ที่ = `${ข} ยืม ${ต} ${กุญแจ}`
        นับ.บท++
        นับ.ย่อหน้า += ย่อ.length
        const เลขเรา = ของเรา.map((x) => Number(x.เลข))
        const เลขต้นแบบ = new Set(ของต้นแบบ.map((x) => Number(x.เลข)))
        if (เลขเรา.length !== เลขต้นแบบ.size || เลขเรา.some((n) => !เลขต้นแบบ.has(n))) {
          นับ.บทเลขข้อไม่ตรง++
        }
        if (รอย.some((ร) => ร.หลังอักษร > 0)) นับ.บทที่รอยกลางข้อ++

        // ⑤ก ตัวบทครบทุกตัวอักษร ตรงตัวเป๊ะ
        const เดิม = ของเรา.map((x) => x.ชิ้น[0].ตัวหนังสือ).join('')
        const ได้ = ย่อ.map((ย) => ย.ท่อน.map((ท) => ท.ชิ้น.map((ช) => ช.ตัวหนังสือ).join('')).join('')).join('')
        นับ.ตัวอักษร += เดิม.length
        if (เดิม !== ได้) ตก.push(`${ที่} ⇒ 🔴 ⑤ก ตัวบท ${ได้.length} ตัวอักษร ⛔ ไม่ตรงของเดิม ${เดิม.length}`)

        // ⑤ข ทุกข้อขึ้นครั้งเดียว ตามลำดับ ⛔ ไม่มีข้อไหนถูกผ่า
        const ท่อนทั้งหมด = ย่อ.flatMap((ย) => ย.ท่อน)
        if (ท่อนทั้งหมด.some((ท) => !ท.ท่อนแรก)) {
          ตก.push(`${ที่} ⇒ 🔴 ⑤ข มีข้อถูกผ่ากลางข้อ ⇒ ต้องขึ้นย่อหน้าที่ต้นข้อเท่านั้น (ข้อ 6.2)`)
        }
        const ลำดับได้ = ท่อนทั้งหมด.filter((ท) => ท.ท่อนแรก).map((ท) => Number(ท.เลข))
        if (ลำดับได้.join(',') !== เลขเรา.join(',')) {
          ตก.push(
            `${ที่} ⇒ 🔴 ⑤ข ข้อหาย ซ้ำ หรือสลับ ⇒ ได้ ${ลำดับได้.length} ข้อ จาก ${เลขเรา.length} ข้อ`,
          )
        }

        // ⑤ค ขึ้นย่อหน้าตรงกับต้นแบบ ⇒ เขียนจากกติกาตรง ๆ
        const ขึ้นจริง = new Set(ย่อ.map((ย) => Number(ย.ท่อน[0]?.เลข)))
        const รอยต้นแบบ = [...new Set(รอย.map((ร) => ร.ข้อ))]
        for (let i = 0; i < เลขเรา.length; i++) {
          const v = เลขเรา[i]
          const ก่อน = i ? เลขเรา[i - 1] : -Infinity
          const ควรขึ้น = i === 0 || รอยต้นแบบ.some((m) => m > ก่อน && m <= v)
          if (ควรขึ้น !== ขึ้นจริง.has(v)) {
            ตก.push(
              `${ที่} ข้อ ${v} ⇒ 🔴 ⑤ค ${ควรขึ้น ? 'ต้นแบบขึ้นย่อหน้า แต่เรา ⛔ ไม่ขึ้น' : 'เราขึ้นย่อหน้าเอง ทั้งที่ต้นแบบ ⛔ ไม่ขึ้น'}`,
            )
            break
          }
        }
      }
    }
  }
  return { ตก, นับ, ผู้ยืม, ต้นแบบทั้งหมด }
}

