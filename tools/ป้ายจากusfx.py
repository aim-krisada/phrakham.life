import collections
import xml.etree.ElementTree as ET

import สร้างข้อมูลเว็บ as ตัวแปลง

# ป้าย `style` ของ <p> <q> ⇒ ชนิดรอยตามตารางของตัวแปลง (`พวกรอยแบ่ง`) ⇒ ⛔ ไม่มีรายชื่อสำเนาที่นี่
ชนิดของป้าย = ตัวแปลง.ชนิดของป้าย
ช่วงที่เก็บ = {"wj": "คำพระเยซู", "add": "คำเติม", "nd": "พระนาม"}


def _ตัวที่ไม่ใช่ช่องว่าง(t):
    return [i for i, c in enumerate(t) if not c.isspace()]


def อ่านป้าย(ไฟล์, ตัวบทของซอง):
    """คืน (รอยแบ่ง, ช่วง, ปัญหา)
    ⇒ `ตัวบทของซอง` = {(ล, บ, ข): ตัวบทที่เว็บแสดง} ⇒ ตำแหน่งทุกตัววัดบนตัวบทนี้
    ⇒ รอยแบ่ง = {(ล, int บ): [{ข้อ, หลังอักษร, ป้าย, ชนิด, ตัวหนังสือ?}]} ⇒ รูปเดียวกับของ `อ่าน_usx`
    ⇒ ช่วง = {"คำพระเยซู": {(ล, int บ): [{ข้อ, หลังอักษร, ถึงอักษร, ต่อจากข้อก่อน?}]}, "คำเติม": ..., "พระนาม": ...}
    """
    เก็บ = collections.defaultdict(list)        # bcv ⇒ ชิ้นตัวบทดิบ
    ยาว = collections.Counter()                 # bcv ⇒ ความยาวดิบตอนนี้
    รอยดิบ = []                                 # (bcv, ที่ดิบ, ป้าย, ตัวหนังสือ)
    ช่วงดิบ = []                                # (ชนิด, bcv, หลัง, ถึง, ต่อ)
    ที่อยู่ = [None]
    ค้าง = []                                   # รอยที่รอข้อถัดไป ⇒ (ป้าย, ตัวหนังสือ)
    เปิด = {}                                   # ชนิดช่วงที่เปิดอยู่ ⇒ [bcv, หลัง, ต่อ]

    def ใส่(t):
        if t and ที่อยู่[0]:
            เก็บ[ที่อยู่[0]].append(t)
            ยาว[ที่อยู่[0]] += len(t)

    def ปิดช่วงที่ข้อ():
        for ชนิด, (bcv, หลัง, ต่อ) in เปิด.items():
            if bcv:
                ช่วงดิบ.append((ชนิด, bcv, หลัง, ยาว[bcv], ต่อ))
        for ชนิด in list(เปิด):
            เปิด[ชนิด] = [None, 0, True]

    def ตัวหนังสือใน(el):
        ชิ้น = [el.text or ""]
        for c in el:
            if c.tag not in ตัวแปลง.ข้ามใน_usfx and c.tag not in ("v", "ve"):
                ชิ้น.append(ตัวหนังสือใน(c))
            ชิ้น.append(c.tail or "")
        return "".join(ชิ้น)

    def เดิน(el):
        t = el.tag
        if t == "v":
            if ที่อยู่[0] and เปิด:
                ปิดช่วงที่ข้อ()
            ที่อยู่[0] = el.get("bcv")
            if ที่อยู่[0]:
                เก็บ[ที่อยู่[0]]
                for ป้าย, ตัว in ค้าง:
                    รอยดิบ.append((ที่อยู่[0], 0, ป้าย, ตัว))
                ค้าง.clear()
                for ชนิด, ค in เปิด.items():
                    if ค[0] is None:
                        # ⭐ ช่วงที่ค้างจากข้อก่อน ⇒ ต่อ = True · ช่วงที่เปิดก่อนเลขข้อแรก ⇒ คงค่าเดิม (False)
                        เปิด[ชนิด] = [ที่อยู่[0], 0, ค[2]]
            ใส่(el.tail)
            return
        if t == "ve":
            if เปิด:
                ปิดช่วงที่ข้อ()
            ที่อยู่[0] = None
            return
        if t in ตัวแปลง.ข้ามใน_usfx:
            ใส่(el.tail)
            return
        if t in ("d", "s"):
            ป้าย = el.get("style") or t
            ตัว = " ".join(ตัวหนังสือใน(el).split())
            if any(True for _ in el.iter("ve")):
                ที่อยู่[0] = None
            if ตัว:
                if ที่อยู่[0]:
                    รอยดิบ.append((ที่อยู่[0], ยาว[ที่อยู่[0]], ป้าย, ตัว))
                else:
                    ค้าง.append((ป้าย, ตัว))
            ใส่(el.tail)
            return
        if t in ("p", "q"):
            ป้าย = el.get("style") or el.get("sfm") or t
            if ป้าย in ชนิดของป้าย:
                if ที่อยู่[0]:
                    รอยดิบ.append((ที่อยู่[0], ยาว[ที่อยู่[0]], ป้าย, None))
                else:
                    ค้าง.append((ป้าย, None))
        ชนิดช่วง = ช่วงที่เก็บ.get(t)
        if ชนิดช่วง:
            เปิด[ชนิดช่วง] = [ที่อยู่[0], ยาว[ที่อยู่[0]] if ที่อยู่[0] else 0, False]
        ใส่(el.text)
        for c in el:
            เดิน(c)
        if ชนิดช่วง:
            bcv, หลัง, ต่อ = เปิด.pop(ชนิดช่วง)
            if bcv and ที่อยู่[0] == bcv:
                ช่วงดิบ.append((ชนิดช่วง, bcv, หลัง, ยาว[bcv], ต่อ))
        ใส่(el.tail)

    เดิน(ET.parse(ไฟล์).getroot())

    # ── ย้ายตำแหน่งจากตัวบทดิบไปตัวบทของซอง
    ปัญหา = []
    แผนที่ = {}

    def ตัวบท(bcv):
        if bcv in แผนที่:
            return แผนที่[bcv]
        ชิ้น = bcv.split(".")
        กุญแจ = (ชิ้น[0], str(int(ชิ้น[1])), str(int(ชิ้น[2]))) if len(ชิ้น) == 3 else None
        ซอง = ตัวบทของซอง.get(กุญแจ) if กุญแจ else None
        if ซอง is None:
            แผนที่[bcv] = None
            return None
        ดิบ = "".join(เก็บ[bcv])
        ก, ข = _ตัวที่ไม่ใช่ช่องว่าง(ดิบ), _ตัวที่ไม่ใช่ช่องว่าง(ซอง)
        if [ดิบ[i] for i in ก] != [ซอง[i] for i in ข]:
            ปัญหา.append("%s ⇒ ตัวบทที่เดินได้ ⛔ ไม่ตรงซอง (นอกจากช่องว่าง)" % bcv)
            แผนที่[bcv] = None
            return None
        # นับตัวที่ไม่ใช่ช่องว่างก่อนตำแหน่งดิบแต่ละตำแหน่ง ⇒ ตารางสะสม
        สะสม = [0] * (len(ดิบ) + 1)
        for i, c in enumerate(ดิบ):
            สะสม[i + 1] = สะสม[i] + (not c.isspace())
        แผนที่[bcv] = (กุญแจ, สะสม, ข, len(ซอง))
        return แผนที่[bcv]

    def หัว(m, ที่):
        _, สะสม, ข, ยาวซอง = m
        k = สะสม[ที่]
        return ข[k] if k < len(ข) else ยาวซอง

    def ท้าย(m, ที่):
        _, สะสม, ข, _ = m
        k = สะสม[ที่]
        return ข[k - 1] + 1 if k else 0

    รอยแบ่ง = collections.defaultdict(list)
    for bcv, ที่, ป้าย, ตัว in รอยดิบ:
        m = ตัวบท(bcv)
        if not m:
            continue
        (ล, บ, ข) = m[0]
        ร = {"ข้อ": int(ข), "หลังอักษร": หัว(m, ที่), "ป้าย": ป้าย, "ชนิด": ชนิดของป้าย.get(ป้าย, ป้าย)}
        if ตัว:
            ร["ตัวหนังสือ"] = ตัว
        รอยแบ่ง[(ล, int(บ))].append(ร)

    ช่วง = {ช: collections.defaultdict(list) for ช in ช่วงที่เก็บ.values()}
    for ชนิด, bcv, หลัง, ถึง, ต่อ in ช่วงดิบ:
        m = ตัวบท(bcv)
        if not m or ถึง <= หลัง:
            continue
        (ล, บ, ข) = m[0]
        ก = {"ข้อ": int(ข), "หลังอักษร": หัว(m, หลัง), "ถึงอักษร": ท้าย(m, ถึง)}
        if ก["ถึงอักษร"] <= ก["หลังอักษร"]:
            continue
        if ต่อ:
            ก["ต่อจากข้อก่อน"] = True
        ช่วง[ชนิด][(ล, int(บ))].append(ก)
    return dict(รอยแบ่ง), {ช: dict(v) for ช, v in ช่วง.items()}, ปัญหา


def อ่านป้ายฉบับเพิ่ม(รหัส):
    """ฉบับเพิ่มหนึ่งฉบับ ⇒ คืน (ข้อเว็บ, รอยแบ่ง, ช่วง)
    ⇒ ตัวบทได้จาก `อ่านฉบับ` ของ `tools/สร้างฉบับเพิ่ม.py` ⇒ มันตรวจลายนิ้วมือ zip กับตัวบทเองแล้ว (ตายเองถ้าไม่ตรง)
    ⇒ ⛔ เดินแล้วตัวบทไม่ตรงซองแม้ข้อเดียว ⇒ ตาย ⇒ ⛔ ไม่เขียนซองที่ตำแหน่งเพี้ยน"""
    import importlib
    import tempfile
    import zipfile
    from pathlib import Path

    เพิ่ม = importlib.import_module("สร้างฉบับเพิ่ม")
    ตั้ง = เพิ่ม.ต้นทาง[รหัส]
    ข้อเว็บ, _ = เพิ่ม.อ่านฉบับ(รหัส, ตั้ง)
    with tempfile.TemporaryDirectory(prefix="pk-usfx-") as ที่พัก:
        with zipfile.ZipFile(ตั้ง["zip"]) as ซิป:
            ซิป.extract(ตั้ง["ไฟล์ใน"], ที่พัก)
        รอยแบ่ง, ช่วง, ปัญหา = อ่านป้าย(Path(ที่พัก) / ตั้ง["ไฟล์ใน"], ข้อเว็บ)
    if ปัญหา:
        print("⛔ %s ⇒ เดินไฟล์ USFX แล้วตัวบทไม่ตรงซองฉบับเพิ่ม %d ข้อ ⇒ %s" % (รหัส, len(ปัญหา), " · ".join(ปัญหา[:3])))
        raise SystemExit(1)
    return ข้อเว็บ, รอยแบ่ง, ช่วง
