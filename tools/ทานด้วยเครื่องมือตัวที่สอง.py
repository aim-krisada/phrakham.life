"""ทานไฟล์ .tsv ที่ดึงมาแล้ว ด้วยโปรแกรมอ่าน PDF คนละตัว (pdfplumber)

    py -3.14 tools/ทานด้วยเครื่องมือตัวที่สอง.py <ที่อยู่ไฟล์ pdf> <โฟลเดอร์ tsv>

⭐ **ทำไมต้องมี** — `ดึงคำพื้นฐาน.py` ใช้ PyMuPDF ตัวเดียว
ถ้ามันอ่านผิดแบบเดิมทุกครั้ง เราจะไม่มีทางรู้เลย ⇒ ต้องมีตัวที่สองที่ไม่เกี่ยวข้องกันมาทาน

⛔ **ตัวที่สองไม่ได้เก่งกว่า** — pdfplumber แทรกช่องว่างและเรียงวรรณยุกต์ต่างจากตัวแรก
⇒ **จึงห้ามเทียบแบบตัดคำแล้วนับ** เพราะจะได้ราว 70% ซึ่งวัดวิธีตัดคำ ⛔ ไม่ได้วัดว่าอ่านตรงกันไหม
⇒ ⭐ **วิธีที่ถูกคือถามว่า "คำที่เราจดไว้ โผล่ในสายอักษรที่ตัวที่สองอ่านได้ไหม"**
   สายอักษรของแต่ละหน้าต่อกันตามลำดับที่วาดจริง ⛔ ไม่ตัดคำ ⛔ ไม่จัดแถว
   ⇒ ถ้าเราอ่านสระหรือวรรณยุกต์ผิดไปแม้ตัวเดียว คำนั้นจะหาไม่เจอทันที

ตัวที่สองก็เจอสระ ำ หลุดแบบเดียวกัน ⇒ ต้องซ่อมด้วยกฎเดียวกันก่อนเทียบ
(กฎนั้นคืออะไร และพิสูจน์อย่างไร อ่านที่หัวไฟล์ ดึงคำพื้นฐาน.py)
"""

import sys
from pathlib import Path

import pdfplumber

sys.path.insert(0, str(Path(__file__).parent))
ดึง = __import__("ดึงคำพื้นฐาน")


def สายอักษรของหน้า(หน้า):
    """ต่ออักษรทุกตัวในหน้าตามลำดับที่วาด พร้อมซ่อม ำ ด้วยกฎเดียวกับตัวแรก"""
    ตัว = หน้า.chars
    out, i = [], 0
    while i < len(ตัว):
        c = ตัว[i]
        if c["text"] == " " and (c["x1"] - c["x0"]) < 0.01:
            j, แทรก = i + 1, []
            while j < len(ตัว) and ตัว[j]["text"] in ดึง.วรรณยุกต์:
                แทรก.append(ตัว[j]["text"])
                j += 1
            if j < len(ตัว) and ตัว[j]["text"] in (ดึง.สระอา, ดึง.สระอำ):
                out.extend(แทรก + [ดึง.สระอำ])
                i = j + 1
                continue
            i += 1
            continue
        out.append(c["text"])
        i += 1
    return "".join(out)


def main():
    pdf, ที่เก็บ = sys.argv[1], Path(sys.argv[2])
    with pdfplumber.open(pdf) as เอกสาร:
        # คั่นหน้าด้วยตัวที่เป็นคำไม่ได้ ⇒ กันคำปลอมที่เกิดจากท้ายหน้าต่อกับต้นหน้าถัดไป
        สาย = "\x00".join(สายอักษรของหน้า(p) for p in เอกสาร.pages)

    ช่องทั้งหมด, ไม่ซ้ำ = 0, set()
    for ชื่อ, _, _, _ in ดึง.ตารางในไฟล์:
        for บรรทัด in (ที่เก็บ / f"{ชื่อ}.tsv").read_text(encoding="utf-8").splitlines()[1:]:
            for ช่อง in บรรทัด.split("\t")[1:]:
                if ช่อง.strip():
                    ช่องทั้งหมด += 1
                    ไม่ซ้ำ.add(ช่อง.strip())

    ขาด = sorted(w for w in ไม่ซ้ำ if w not in สาย)
    print(f"ช่องคำในไฟล์ .tsv ทั้งหมด {ช่องทั้งหมด} ช่อง ⇒ ข้อความไม่ซ้ำ {len(ไม่ซ้ำ)} แบบ")
    print(f"ตัวที่สองอ่านได้ตรงกัน {len(ไม่ซ้ำ) - len(ขาด)} แบบ "
          f"({(len(ไม่ซ้ำ) - len(ขาด)) / len(ไม่ซ้ำ):.1%})")
    if ขาด:
        print(f"⛔ ตัวที่สองหาไม่เจอ {len(ขาด)} แบบ:")
        for w in ขาด:
            print("   ", repr(w))
        return 1
    print("✅ ไม่มีคำไหนที่ตัวที่สองอ่านแล้วไม่ตรง")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
