def ทดสอบด่านนับ():
    """ทำของให้หายแล้วต้องแดง · ซ่อมแล้วต้องเขียว ⛔ ไม่ต้องมีกอง `_แตก`

    ⭐ **รันได้บนตัวรันของอัมกิต** ⇒ ปั้นของตัวอย่างเล็ก ๆ กับเลขตรึงของตัวเองขึ้นมา
    ⇒ ⛔ ไม่แตะเลขจริงใน `tools/สร้างข้อมูลเว็บ.py` เลย

    ⭐⭐ **ข้อที่สำคัญที่สุดคือ "คำหายไปคำเดียว"**
    ⇒ ข้อยังครบ เล่มยังครบ ⇒ **ด่านที่นับแต่ข้อจะเขียว ทั้งที่ของหายไปแล้ว**
    """
    import copy

    ตรึง = {
        "TCV":     {"เล่ม": 1, "ข้อ": 2},
        "THKJV":   {"เล่ม": 1, "ข้อ": 2},
        "WEB":     {"เล่ม": 1, "ข้อ": 2},
        "LSV":     {"เล่ม": 1, "ข้อ": 2},
        "คำฮีบรู": {"เล่ม": 1, "ข้อ": 2, "คำ": 3},
        "คำกรีก":  {"เล่ม": 1, "ข้อ": 1, "คำ": 2},
    }
    ตัวบท = {ช: {"1": "ข้อหนึ่ง", "2": "ข้อสอง"} for ช in ชั้นที่เอา}
    ของดี = {"บท": {"PSA/32": copy.deepcopy(ตัวบท)}}
    คำดี = [
        ("PSA", 32, {"ชั้น": {"คำฮีบรู": {"1": [{"ตัว": "א"}, {"ตัว": "ב"}],
                                        "2": [{"ตัว": "ג"}]}}}),
        ("ROM", 8, {"ชั้น": {"คำกรีก": {"1": [{"ตัว": "λ"}, {"ตัว": "μ"}]}}}),
    ]

    def ทำคำหาย():
        ค = copy.deepcopy(คำดี)
        ค[0][2]["ชั้น"]["คำฮีบรู"]["1"].pop()      # ⭐ หายไป **คำเดียว** ⇒ ข้อยังครบ
        return ของดี, ค

    def ทำข้อหาย():
        ค = copy.deepcopy(คำดี)
        del ค[0][2]["ชั้น"]["คำฮีบรู"]["2"]
        return ของดี, ค

    def ทำเล่มหาย():
        ค = copy.deepcopy(คำดี)
        return ของดี, [ค[0]]                        # เล่มกรีกหายไปทั้งเล่ม

    def ทำตัวบทหาย():
        ง = copy.deepcopy(ของดี)
        del ง["บท"]["PSA/32"]["TCV"]["2"]
        return ง, คำดี

    เทส = [
        ("ของครบ", lambda: (ของดี, คำดี), 0),
        ("⭐ คำฮีบรูหายไป 1 คำ ⇒ ข้อยังครบ", ทำคำหาย, 1),
        ("ข้อฮีบรูหายไป 1 ข้อ", ทำข้อหาย, 1),
        ("เล่มกรีกหายไปทั้งเล่ม", ทำเล่มหาย, 1),
        ("ตัวบทแปลหายไป 1 ข้อ", ทำตัวบทหาย, 1),
        ("ซ่อมแล้ว ⇒ กลับมาเขียว", lambda: (ของดี, คำดี), 0),
    ]
    print("ด่านนับ · พิสูจน์แดง-เขียว ⇒ ปั้นของตัวอย่างกับเลขตรึงของตัวเอง\n")
    ตก = 0
    for ชื่อ, ทำของ, ควรแดง in เทส:
        ง, ค = ทำของ()
        ผิด = นับแล้วเทียบ(ง, ค, ตรึง=ตรึง, พิมพ์=False)
        ได้ = 1 if ผิด else 0
        ผ่าน = ได้ == ควรแดง
        ตก += 0 if ผ่าน else 1
        เหตุ = f" ⇒ {ผิด[0]}" if ผิด else ""
        print(f"{'✅' if ผ่าน else '⛔'} {ชื่อ} ⇒ ควรแดง {ควรแดง} · แดงจริง {ได้}{เหตุ}")
    print(f"\n{'✅ เทสผ่านครบ' if not ตก else f'⛔ เทสตก {ตก} ข้อ'}")
    return 1 if ตก else 0


