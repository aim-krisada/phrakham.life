def ห่อชั้นคำ(ชั้นคำรายบท):
    """คืน {ชื่อไฟล์ญาติ: ไบต์} ของทั้งกองชั้นคำ ⇒ ไฟล์รายบท บวกบัญชีอีกหนึ่งใบ

    ⭐ **ชื่อไฟล์คงที่** ⇒ `<รหัสเล่ม>/<เลขบท>.json.gz` ⛔ ไม่มีวันที่ ไม่มีลายนิ้วมือ
    """
    ไฟล์ = {}
    เล่มในบัญชี = {}
    รวมข้อ, รวมคำ = 0, 0
    for รหัส, บท, ก้อน in ชั้นคำรายบท:
        ไบต์, _ = ห่อซอง(ก้อน, f"ไฟล์ชั้นคำ {รหัส}/{บท}")
        ไฟล์[f"{รหัส}/{บท}.json.gz"] = ไบต์
        รายการ = เล่มในบัญชี.setdefault(รหัส, {"รหัส": รหัส, "ชั้น": [], "บทที่มี": []})
        รายการ["บทที่มี"].append(บท)
        for ช in ก้อน["ชั้น"]:
            if ช not in รายการ["ชั้น"]:
                รายการ["ชั้น"].append(ช)
            รวมข้อ += len(ก้อน["ชั้น"][ช])
            รวมคำ += sum(len(x) for x in ก้อน["ชั้น"][ช].values())

    แหล่ง = {}
    for _, _, ก้อน in ชั้นคำรายบท:
        แหล่ง.update(ก้อน["แหล่งของชั้น"])

    # ⭐ บัญชีนี้มีไว้ให้ใบ #70 รู้ว่า **มีไฟล์อะไรให้โหลดบ้าง** โดยไม่ต้องเดาชื่อไฟล์เอง
    #   ⛔ ไม่บีบอัด ⇒ เล็กมาก และคนเปิดอ่านเองได้ตอนตรวจ
    บัญชี = {
        "ชั้น": ชั้นภาษาเดิม,
        "แหล่งของชั้น": แหล่ง,
        # เรียงตามสารบบ ⇒ `ชั้นคำรายบท` เรียงมาแล้ว ⇒ ลำดับที่ใส่เข้า dict คือลำดับสารบบ
        "เล่ม": list(เล่มในบัญชี.values()),
        "รวม": {"เล่ม": len(เล่มในบัญชี), "บท": len(ชั้นคำรายบท),
                "ข้อ": รวมข้อ, "คำ": รวมคำ},
    }
    ข้อความ = json.dumps(บัญชี, ensure_ascii=False, sort_keys=True,
                        separators=(",", ":")) + "\n"
    กันของต้องห้ามหลุด(ข้อความ, "บัญชีของชั้นคำ")
    ไฟล์["บัญชี.json"] = ข้อความ.encode("utf-8")
    return ไฟล์


def ที่มีอยู่จริง():
    """ไฟล์ที่คอมมิตไว้ในกองชั้นคำวันนี้ ⇒ {ชื่อไฟล์ญาติ: ไบต์}"""
    if not ปลายทางภาษาเดิม.exists():
        return {}
    return {p.relative_to(ปลายทางภาษาเดิม).as_posix(): p.read_bytes()
            for p in ปลายทางภาษาเดิม.rglob("*") if p.is_file()}


def เทียบกอง(ใหม่, เดิม):
    """คืนข้อความบอกที่ต่าง ⇒ ว่างเปล่าแปลว่าตรงกันทุกไบต์"""
    ขาด = sorted(set(ใหม่) - set(เดิม))
    เกิน = sorted(set(เดิม) - set(ใหม่))
    ต่าง = sorted(k for k in set(ใหม่) & set(เดิม) if ใหม่[k] != เดิม[k])
    บอก = []
    if ขาด:
        บอก.append(f"ไฟล์ที่ยังไม่ได้เขียน {len(ขาด)} ไฟล์ ⇒ {' · '.join(ขาด[:5])}")
    if เกิน:
        บอก.append(f"ไฟล์ที่ค้างอยู่แต่ไม่ควรมี {len(เกิน)} ไฟล์ ⇒ {' · '.join(เกิน[:5])}")
    if ต่าง:
        บอก.append(f"ไฟล์ที่เนื้อไม่ตรง {len(ต่าง)} ไฟล์ ⇒ {' · '.join(ต่าง[:5])}")
    return บอก


