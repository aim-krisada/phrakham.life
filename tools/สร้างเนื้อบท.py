    """ทำก้อนไบต์ของซอง ⇒ **ข้อมูลเท่าเดิมต้องได้ไบต์เท่าเดิม**"""
    # sort_keys ⇒ ลำดับกุญแจไม่ขึ้นกับลำดับที่ไพทอนเผอิญใส่เข้ามา
    ข้อความ = json.dumps(ของ, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    กันของต้องห้ามหลุด(ข้อความ, ชื่อของ)
    เนื้อ = ข้อความ.encode("utf-8")
    ถัง = io.BytesIO()
    # mtime=0 ⇒ ⛔ ไม่ประทับเวลาลงหัวซอง (ดูหัวไฟล์)
    with gzip.GzipFile(fileobj=ถัง, mode="wb", compresslevel=9, mtime=0) as ซ:
        ซ.write(เนื้อ)
    return ถัง.getvalue(), len(เนื้อ)


