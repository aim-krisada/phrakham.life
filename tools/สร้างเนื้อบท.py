def นับแล้วเทียบ(ของ, ชั้นคำรายบท, ตรึง=None, พิมพ์=True):
    """นับ เล่ม · ข้อ · คำ ของทุกชั้นที่จะขึ้นเว็บ แล้วเทียบกับเลขที่ตรึงไว้

    ⭐ **นับจากของที่กำลังจะเขียนจริง** ⛔ ไม่ใช่นับจาก `_ข้อมูลเว็บ/` อีกรอบ
    ⇒ ตัวแปลงนับตอนอ่านต้นฉบับแล้ว ⇒ ด่านนี้นับ **ปลายทาง** ⇒ ของหายระหว่างห่อซองก็ยังจับได้

    คืน **รายการที่ผิด** ⇒ ว่างเปล่าแปลว่าครบ ⇒ ⭐ คืนค่า ⛔ ไม่ตายเอง
    ⇒ ท่า `--ทดสอบตัวเอง` จึงเรียกซ้ำได้หลายรอบเพื่อพิสูจน์แดง-เขียว
    """
    ตรึง = ตรึง or ควรได้
    นับ = {}
    for ชื่อชั้น in ชั้นที่เอา:
        เล่ม, ข้อ = set(), 0
        for ชื่อบท, ชั้น in ของ["บท"].items():
            if ชื่อชั้น in ชั้น:
                เล่ม.add(ชื่อบท.split("/")[0])
                ข้อ += len(ชั้น[ชื่อชั้น])
        นับ[ชื่อชั้น] = {"เล่ม": len(เล่ม), "ข้อ": ข้อ}
    for ชื่อชั้น in ชั้นภาษาเดิม:
        เล่ม, ข้อ, คำ = set(), 0, 0
        for รหัส, _, ก้อน in ชั้นคำรายบท:
            if ชื่อชั้น not in ก้อน["ชั้น"]:
                continue
            เล่ม.add(รหัส)
            ข้อ += len(ก้อน["ชั้น"][ชื่อชั้น])
            คำ += sum(len(x) for x in ก้อน["ชั้น"][ชื่อชั้น].values())
        นับ[ชื่อชั้น] = {"เล่ม": len(เล่ม), "ข้อ": ข้อ, "คำ": คำ}

    ผิด = []
    for ชื่อชั้น, ได้ in นับ.items():
        ค = ตรึง[ชื่อชั้น]
        ผิดของชั้นนี้ = [f"{ชื่อชั้น}: ได้ {จำนวน:,} {เรื่อง} ⇒ ควรได้ {ค[เรื่อง]:,} {เรื่อง}"
                       for เรื่อง, จำนวน in ได้.items() if จำนวน != ค[เรื่อง]]
        ผิด += ผิดของชั้นนี้
        if พิมพ์:
            พ่วง = f" · {ได้['คำ']:,} คำ" if "คำ" in ได้ else ""
            print(f"   {'⛔' if ผิดของชั้นนี้ else '✅'} "
                  f"{ชื่อชั้น:9} {ได้['เล่ม']:>2} เล่ม · {ได้['ข้อ']:>6,} ข้อ{พ่วง}")
    return ผิด


