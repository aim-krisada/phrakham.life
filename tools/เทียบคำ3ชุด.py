เขตทั้งเจ็ด = ["ก เท่านั้น", "ข เท่านั้น", "ค เท่านั้น", "ก∩ข ไม่มี ค",
               "ก∩ค ไม่มี ข", "ข∩ค ไม่มี ก", "ก∩ข∩ค"]
วงเล็บ = re.compile(r"\s*\([^()]*\)\s*")
# ต้นฉบับบางช่องพิมพ์วงเล็บตกจนไม่ปิด เช่น `แกงจืด (พบบ่อย` ⇒ กฎวงเล็บปิดครบจับไม่ได้
# ⇒ ต้องตัดด้วย ไม่งั้นคำนั้นจะไม่ตรงกับคำเดียวกันของชุดอื่น (คนตรวจจับได้ 31 ส.ค. 2569)
วงเล็บไม่ปิด = re.compile(r"\s*\([^()]*$")


def จัดรูป(คำ, เก็บวงเล็บ):
    """คืนรูปคำที่เอาไปเทียบได้ · คืนค่าว่างแปลว่าไม่ใช่คำ"""
    # บางไฟล์เขียนสระ ำ เป็นนิคหิต + สระอา ⇒ รวบให้เป็นตัวเดียว ไม่งั้น "คํา" ≠ "คำ"
    คำ = unicodedata.normalize("NFC", คำ).replace("ํา", "ำ").strip()
    if not เก็บวงเล็บ:
        คำ = วงเล็บไม่ปิด.sub("", วงเล็บ.sub("", คำ)).replace(")", "")
    return re.sub(r"\s+", "", คำ)


def แยกขีดทับ(คำ):
    """"เรา/พวกเรา" ⇒ ["เรา", "พวกเรา"] · จุดไข่ปลาที่ผู้วิจัยใช้แทนที่ว่าง ทิ้งไป"""
    return [t.replace("…", "").strip() for t in คำ.split("/") if t.replace("…", "").strip()]


def แยกวงเล็บเป็นอีกคำ(คำ):
    """ใช้กับชุด ก เท่านั้น ⇒ วงเล็บของชุด ก คือ **คำอีกรูปหนึ่ง** ⛔ ไม่ใช่ป้ายบอกหน้าที่

    เช่น "ไหม (มั้ย)" ⇒ ทั้ง ไหม และ มั้ย เป็นคำจริงทั้งคู่ · ในวงเล็บมีหลายรูปก็คั่นด้วยจุลภาค
    ⇒ ทำแบบเดียวกับใบ #42 ที่นับคำไม่ซ้ำของชุด ก ได้ 1,567 คำ
    ⚠️ ในชุด ก มีวงเล็บอีกไม่กี่คำที่เป็นป้ายบอกความหมาย ไม่ใช่คำอีกรูป
       เช่น "ซอล (โน้ตดนตรี)" "เขา (บุรุษสรรพนาม)" "ตา (ญาติ)" ⇒ วิธีนี้จะได้คำเกินมาไม่กี่คำ
    """
    ออก = [วงเล็บ.sub("", คำ)]
    for ใน in re.findall(r"\(([^()]*)\)", คำ):
        ออก += [t.strip() for t in ใน.split(",")]
    return ออก


def อ่านtsv(ที่อยู่):
    บรรทัด = ที่อยู่.read_text(encoding="utf-8").splitlines()
    หัว = บรรทัด[0].split("\t")
    return หัว, [dict(zip(หัว, b.split("\t"))) for b in บรรทัด[1:] if b.strip()]


def เก็บคำ(ข้อมูล, เก็บวงเล็บ, วงเล็บคือคำอีกรูป=False):
    """คืน set ของรูปคำที่เทียบได้ จากรายการข้อความดิบ"""
    ออก = set()
    for ดิบ in ข้อมูล:
        for ท่อน in แยกขีดทับ(ดิบ):
            ชิ้น = แยกวงเล็บเป็นอีกคำ(ท่อน) if วงเล็บคือคำอีกรูป else [ท่อน]
            for ช in ชิ้น:
                if รูป := จัดรูป(ช, เก็บวงเล็บ and not วงเล็บคือคำอีกรูป):
                    ออก.add(รูป)
    return ออก


