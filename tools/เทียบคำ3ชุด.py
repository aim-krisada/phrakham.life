def หมวดของชุดข(โฟลเดอร์):
    """คืน {รูปคำ: set(ชื่อหมวดในเล่ม)} ⇒ เอาไว้ตอบว่าคำที่มีแต่ในชุด ข มาจากหมวดไหนมากสุด

    ⭐ ต้องจัดรูปคำด้วยกฎเดียวกับตอนเทียบ ⛔ ไม่งั้นจับคู่กับเขตไม่ติด
    ⚠️ หมวดเดียวกันมีได้หลายชั้น ⇒ รวมชื่อเดียวกันเป็นหมวดเดียว
    """
    _, แถว = อ่านtsv(โฟลเดอร์ / "คำพื้นฐาน-สระบุรี-2568.tsv")
    ออก = defaultdict(set)
    for r in แถว:
        for ท่อน in แยกขีดทับ(r["คำ"]):
            if รูป := จัดรูป(ท่อน, เก็บวงเล็บ=False):
                ออก[รูป].add(r["หมวด"])
    return ออก


def พิมพ์หมวดของขเท่านั้น(โฟลเดอร์, เขต, จำนวน=12):
    """ตาราง `[ข เท่านั้น] N หมวดที่พบมากสุด` ⇒ ของจริงที่เอกสารข้อ ③ อ้างถึง

    ⚠️ **1 คำอยู่ได้หลายหมวด** (เล่มเก็บคำเดียวกันไว้ทั้งหมวดสะกดและหมวดคลังคำศัพท์)
    ⇒ ผลรวมของทุกหมวดจึงมากกว่าจำนวนคำในเขต ⛔ ห้ามเอาไปบวกกันตรง ๆ
    """
    หมวด = หมวดของชุดข(โฟลเดอร์)
    นับ = Counter()
    for คำ in เขต["ข เท่านั้น"]:
        for ชื่อ in หมวด.get(คำ, ()):
            นับ[ชื่อ] += 1
    print(f"  [ข เท่านั้น] {จำนวน} หมวดที่พบมากสุด (จากทั้งหมด {len(นับ)} หมวด)")
    for ชื่อ, n in นับ.most_common(จำนวน):
        print(f"    {n:5,}  {ชื่อ}")
    return นับ


