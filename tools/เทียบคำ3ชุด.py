# ⭐ หัวข้อคำตอบนับเฉพาะที่อยู่ใต้หัวเรื่อง "คำตอบ 5 ข้อ" เท่านั้น
# ⛔ ห้ามจับ `**①` ทั้งเอกสาร เพราะหัวข้อย่อยที่อื่นก็ขึ้นต้นแบบเดียวกัน แล้วเทสจะตั้งเขตผิด
# (คนตรวจทักไว้ 31 ส.ค. 2569 ว่ากฎเดิมไปจับหัวข้อย่อยของหัวข้อ ⑤ ด้วย)
หัวเรื่องคำตอบ = "### คำตอบ 5 ข้อ"
หัวเรื่องอื่น = re.compile(r"^#{2,3} ")
หัวข้อคำตอบ = re.compile(r"^\*\*([①②③④⑤]) .*\*\*")
คำในเครื่องหมาย = re.compile(r"`([^`]+)`")
# ⭐ ข้อตกลงของเอกสาร ⇒ บรรทัดที่ยกตัวอย่างคำ **ต้องขึ้นต้นด้วยคำว่า "ตัวอย่าง"**
# และ **1 คู่เครื่องหมาย ` = 1 คำ** ⇒ เทสจึงรู้แน่ว่าอันไหนเป็นตัวอย่างของเขตนั้น
# ⛔ ถ้าไม่มีข้อตกลง เทสจะไปจับคำที่เอกสารยกมาอธิบายเรื่องอื่น แล้วตกมั่ว
บรรทัดตัวอย่าง = re.compile(r"^(?:-\s*)?ตัวอย่าง")


def ตรวจตัวอย่างในเอกสาร(ที่อยู่md, เขต):
    """อ่านคำตัวอย่างในหัวข้อคำตอบ 5 ข้อ แล้วตรวจว่าอยู่เขตที่อ้างจริง"""
    ตก, นับ = [], 0
    เขตปัจจุบัน, อยู่ในหัวเรื่องคำตอบ = None, False
    for บรรทัด in ที่อยู่md.read_text(encoding="utf-8").splitlines():
        if หัวเรื่องอื่น.match(บรรทัด):
            อยู่ในหัวเรื่องคำตอบ = บรรทัด.strip() == หัวเรื่องคำตอบ
            เขตปัจจุบัน = None
            continue
        if อยู่ในหัวเรื่องคำตอบ and (m := หัวข้อคำตอบ.match(บรรทัด.strip())):
            เขตปัจจุบัน = เขตของคำตอบ.get(m.group(1))
        if not เขตปัจจุบัน or not บรรทัดตัวอย่าง.match(บรรทัด.strip()):
            continue
        for คำ in คำในเครื่องหมาย.findall(บรรทัด):
            รูป = จัดรูป(คำ, เก็บวงเล็บ=False)
            if not รูป:
                continue
            นับ += 1
            if รูป not in เขต[เขตปัจจุบัน]:
                อยู่จริง = [k for k, v in เขต.items() if รูป in v]
                ตก.append(f"{คำ!r} อ้างว่าอยู่ [{เขตปัจจุบัน}] แต่อยู่ {อยู่จริง or 'ไม่อยู่ในชุดใดเลย'}")
    print(f"  ตรวจคำตัวอย่างในเอกสาร {นับ} คำ")
    for ข้อความ in ตก:
        print("  ⛔ ตก", ข้อความ)
    print("  ผ่านทุกคำ" if not ตก else f"  ตก {len(ตก)} คำ")
    return 1 if ตก else 0


