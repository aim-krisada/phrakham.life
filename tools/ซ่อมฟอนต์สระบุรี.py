"""ซ่อมตารางแปลงตัวอักษรของไฟล์ PDF บัญชีคำพื้นฐาน สพป.สระบุรี เขต 1 ปี 2568

    py -3.14 tools/ซ่อมฟอนต์สระบุรี.py <ที่อยู่ไฟล์ pdf>   ⇒ พิมพ์หลักฐานว่าซ่อมถูก

⚠️ ไฟล์ชุดนี้ทำด้วย Canva แล้ว Canva เขียน "ตารางแปลงตัวอักษร" (ToUnicode) ผิด
⇒ ดึงข้อความออกมาได้เป็นตัวประหลาด เช่น ฽นวทาง (แนวทาง) · ฼ขียน (เขียน) · ฿น (ใน)

**สาเหตุที่วัดได้จากตัวไฟล์** — ตารางที่ Canva เขียนบอกว่า รหัสรูปอักษร + 0x0D2B = ตัวอักษร
ซึ่งเป็นสูตรบวกคงที่ แต่ลำดับรูปอักษรจริงในฟอนต์ไม่ได้เรียงแบบนั้น
ช่วง U+0E3B ถึง U+0E3E เป็นรหัสที่ภาษาไทยไม่ได้ใช้ ฟอนต์จึงไม่มีรูปอักษร 4 ตัวนั้น
⇒ ตั้งแต่ U+0E3F ขึ้นไป ทุกตัวจึงเลื่อนผิดไป 4 ช่อง

**วิธีซ่อม ⛔ ไม่เดา** — ฟอนต์ที่ฝังในไฟล์เป็นฟอนต์ THSarabunNew ที่ถูกตัดเอาเฉพาะรูปที่ใช้
แต่ **เลขประจำรูปอักษรยังเป็นเลขเดิมของฟอนต์เต็ม** ⇒ พิสูจน์ได้ด้วยการเทียบเส้นรอบรูปทีละตัว
⇒ จึงเปิดฟอนต์เต็มในเครื่อง อ่านว่ารูปเลขนี้คือตัวอักษรอะไร แล้วเขียนตารางแปลงใหม่ทับของเดิม

⛔ ไม่แก้ไฟล์ต้นทาง — เปิดสำเนาในหน่วยความจำ แก้ตรงนั้น แล้วอ่านข้อความออกมา
"""

import io
import re
import sys
from pathlib import Path

import fitz
from fontTools.ttLib import TTFont

# ฟอนต์เต็มที่ใช้เทียบ อยู่ในเครื่องอยู่แล้ว (Windows) ⇒ ชื่อใน PDF → ชื่อไฟล์ฟอนต์
ฟอนต์เต็ม = {
    "THSarabunNew": r"C:\Windows\Fonts\THSarabunNew.ttf",
    "THSarabunNew-Bold": r"C:\Windows\Fonts\THSarabunNew Bold.ttf",
    "THSarabunNew-Italic": r"C:\Windows\Fonts\THSarabunNew Italic.ttf",
    "THSarabunNew-BoldItalic": r"C:\Windows\Fonts\THSarabunNew BoldItalic.ttf",
}

ชื่อรูปแบบuni = re.compile(r"^uni([0-9A-Fa-f]{4})")


def ตัวอักษรของรูป(ฟอนต์):
    """คืน {เลขประจำรูปอักษร: ตัวอักษรจริง} จากฟอนต์เต็ม

    **อ่านจากชื่อรูปอักษรก่อน** เพราะฟอนต์ไทยเก็บรูปสำรองของวรรณยุกต์ไว้ในช่วงรหัสส่วนตัว
    (U+F700-F71D) เช่น รูป `uni0E48.alt2` ที่ใช้กับพยัญชนะหางสูง ⇒ ถ้าอ่านจาก cmap
    จะได้ตัว U+F70A ซึ่งไม่ใช่ตัวอักษรไทย ⇒ ชื่อรูปบอกตัวจริงว่าคือ U+0E48 (ไม้เอก)
    รูปที่ชื่อไม่ได้ขึ้นต้นด้วย uni จึงค่อยอ่านจาก cmap
    """
    ออก = {}
    for เลข, ชื่อ in enumerate(ฟอนต์.getGlyphOrder()):
        if m := ชื่อรูปแบบuni.match(ชื่อ):
            ออก[เลข] = int(m.group(1), 16)
    for u, ชื่อ in sorted(ฟอนต์.getBestCmap().items()):
        ออก.setdefault(ฟอนต์.getGlyphID(ชื่อ), u)
    return ออก


def เส้นรอบรูป(ฟอนต์, เลข):
    """คืนลายเซ็นของเส้นรอบรูปอักษร ⇒ เอาไว้เทียบว่าเป็นรูปเดียวกันไหม"""
    ลำดับ = ฟอนต์.getGlyphOrder()
    if เลข >= len(ลำดับ):
        return None
    g = ฟอนต์["glyf"][ลำดับ[เลข]]
    if g.numberOfContours == 0:
        return None
    g.expand(ฟอนต์["glyf"])
    if g.isComposite():
        return ("ประกอบ", tuple((c.glyphName, c.x, c.y) for c in g.components))
    return (g.numberOfContours, tuple(g.coordinates.array))


def สมุดลายเซ็น(ฟอนต์):
    """คืน {ลายเซ็นเส้นรอบรูป: ตัวอักษร} ของฟอนต์เต็ม ⇒ ใช้ค้นว่ารูปนี้คือตัวอักษรอะไร

    ⭐ ค้นด้วย **รูปร่างของตัวอักษร** ⛔ ไม่ใช่ด้วยหมายเลขประจำรูป
    ⇒ ต่อให้ Canva สลับหมายเลขรูป หรือฝังฟอนต์คนละรุ่น ก็ยังหาตัวจริงเจอ
    ⛔ ลายเซ็นที่ซ้ำกันหลายรูป ตัดทิ้ง เพราะชี้ขาดไม่ได้ว่าเป็นตัวไหน
    """
    ของรูป = ตัวอักษรของรูป(ฟอนต์)
    นับ, สมุด = {}, {}
    for เลข in range(len(ฟอนต์.getGlyphOrder())):
        ลายเซ็น = เส้นรอบรูป(ฟอนต์, เลข)
        if ลายเซ็น is None or เลข not in ของรูป:
            continue
        นับ[ลายเซ็น] = นับ.get(ลายเซ็น, 0) + 1
        สมุด[ลายเซ็น] = ของรูป[เลข]
    return {k: v for k, v in สมุด.items() if นับ[k] == 1}


def อ่านตารางแปลงเดิม(เนื้อ):
    """อ่าน ToUnicode CMap ที่มีอยู่เดิมออกมาเป็น {เลขรูป: ตัวอักษร} ⇒ เก็บไว้ใช้กับรูปที่ค้นไม่เจอ"""
    ออก = {}
    for a, b in re.findall(r"<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>(?=\s*[^<])", เนื้อ):
        ออก[int(a, 16)] = int(b, 16)
    for a, b, c in re.findall(r"<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>", เนื้อ):
        แรก, ท้าย, ปลาย = int(a, 16), int(b, 16), int(c, 16)
        for i in range(แรก, min(ท้าย, แรก + 4096) + 1):
            ออก[i] = ปลาย + (i - แรก)
    return ออก


def จับคู่ด้วยรูปร่าง(ย่อ, สมุด, ตามหมายเลข, เดิม):
    """คืน ({เลขรูป: ตัวอักษร}, ค้นเจอกี่รูป, ค้นไม่เจอกี่รูป)

    ซ้อนกัน 3 ชั้น จากเชื่อได้น้อยไปมาก
      ① ของเดิมที่ Canva เขียนไว้ ⇒ ใช้เมื่อไม่มีอะไรดีกว่า
      ② เทียบตามหมายเลขประจำรูปกับฟอนต์เต็ม ⇒ ใช้กับรูปที่ไม่มีเส้น เช่น ช่องว่าง
      ③ เทียบด้วยรูปร่างของตัวอักษร ⇒ เชื่อได้ที่สุด เพราะไม่ต้องพึ่งหมายเลข
    ⛔ ไม่เดาแทนรูปที่ค้นไม่เจอ · ถ้าตัวไหนยังเพี้ยน `--ตรวจ` ของ ดึงคำสระบุรี.py จะจับได้
    """
    ตาราง = dict(เดิม)
    ตาราง.update(ตามหมายเลข)
    เจอ = ไม่เจอ = 0
    for เลข in range(1, len(ย่อ.getGlyphOrder())):
        ลายเซ็น = เส้นรอบรูป(ย่อ, เลข)
        if ลายเซ็น is None:
            continue
        if ลายเซ็น in สมุด:
            ตาราง[เลข] = สมุด[ลายเซ็น]
            เจอ += 1
        else:
            ไม่เจอ += 1
    return ตาราง, เจอ, ไม่เจอ


def สร้างตารางแปลง(ตาราง):
    """เขียน ToUnicode CMap ใหม่จาก {เลขรูป: ตัวอักษร}"""
    บรรทัด = [f"<{เลข:04x}><{เลข:04x}><{u:04x}>" for เลข, u in sorted(ตาราง.items())]
    ก้อน = []
    for i in range(0, len(บรรทัด), 100):
        ชิ้น = บรรทัด[i : i + 100]
        ก้อน.append(f"{len(ชิ้น)} beginbfrange\n" + "\n".join(ชิ้น) + "\nendbfrange")
    return (
        "/CIDInit /ProcSet findresource begin\n12 dict begin\nbegincmap\n"
        "/CMapType 2 def\n1 begincodespacerange\n<0000><ffff>\nendcodespacerange\n"
        + "\n".join(ก้อน)
        + "\nendcmap\nCMapName currentdict /CMap defineresource pop\nend\nend"
    ).encode("latin-1")


def เปิดแบบซ่อมแล้ว(ที่อยู่pdf, พิมพ์หลักฐาน=False):
    """เปิดไฟล์ PDF แล้วเขียนตารางแปลงตัวอักษรใหม่ให้ทุกฟอนต์ที่ซ่อมได้

    ⛔ ไม่บันทึกทับไฟล์ต้นทาง — แก้ในหน่วยความจำเท่านั้น
    คืน (เอกสาร, รายงาน) · รายงานคือรายชื่อฟอนต์ที่ซ่อม พร้อมผลเทียบเส้นรอบรูป
    """
    เอกสาร = fitz.open(ที่อยู่pdf)
    รายงาน, เปิดแล้ว = [], {}
    # ไล่ทุกวัตถุรอบเดียว ⇒ ได้ทั้งรายชื่อฟอนต์ลูก และแผนที่ ฟอนต์ลูก → ToUnicode ของฟอนต์แม่
    ฟอนต์ลูก, ตารางแปลงของลูก = [], {}
    for xref in range(1, เอกสาร.xref_length()):
        ชนิด = เอกสาร.xref_get_key(xref, "Subtype")[1]
        if ชนิด == "/CIDFontType2":
            ฟอนต์ลูก.append(xref)
        elif ชนิด == "/Type0":
            tu = เอกสาร.xref_get_key(xref, "ToUnicode")
            if tu[0] != "xref":
                continue
            for เลข in re.findall(r"(\d+) 0 R", เอกสาร.xref_get_key(xref, "DescendantFonts")[1]):
                ตารางแปลงของลูก.setdefault(int(เลข), []).append(int(tu[1].split()[0]))
    for xref in ฟอนต์ลูก:
        ชื่อ = เอกสาร.xref_get_key(xref, "BaseFont")[1].lstrip("/").split("+")[-1]
        ที่อยู่เต็ม = ฟอนต์เต็ม.get(ชื่อ)
        if not ที่อยู่เต็ม or not Path(ที่อยู่เต็ม).exists():
            รายงาน.append((ชื่อ, "ไม่มีฟอนต์เต็มในเครื่อง ⇒ ไม่ซ่อม", 0, 0))
            continue
        ตัวบรรยาย = เอกสาร.xref_get_key(xref, "FontDescriptor")
        if ตัวบรรยาย[0] != "xref":
            continue
        ไฟล์ฟอนต์ = เอกสาร.xref_get_key(int(ตัวบรรยาย[1].split()[0]), "FontFile2")
        if ไฟล์ฟอนต์[0] != "xref":
            continue
        ย่อ = TTFont(io.BytesIO(เอกสาร.xref_stream(int(ไฟล์ฟอนต์[1].split()[0]))), lazy=False)
        if ที่อยู่เต็ม not in เปิดแล้ว:
            ฟ = TTFont(ที่อยู่เต็ม, lazy=False)
            เปิดแล้ว[ที่อยู่เต็ม] = (สมุดลายเซ็น(ฟ), ตัวอักษรของรูป(ฟ))
        สมุด, ตามหมายเลข = เปิดแล้ว[ที่อยู่เต็ม]
        for tu in ตารางแปลงของลูก.get(xref, []):
            เดิม = อ่านตารางแปลงเดิม(เอกสาร.xref_stream(tu).decode("latin-1"))
            ตาราง, เจอ, ไม่เจอ = จับคู่ด้วยรูปร่าง(ย่อ, สมุด, ตามหมายเลข, เดิม)
            เอกสาร.update_stream(tu, สร้างตารางแปลง(ตาราง))
            รายงาน.append((ชื่อ, "ซ่อมแล้ว" if not ไม่เจอ else "ซ่อมได้บางรูป", เจอ, ไม่เจอ))
    if พิมพ์หลักฐาน:
        รวม = {}
        for ชื่อ, ผล, ตรง, ไม่ตรง in รายงาน:
            ก = รวม.setdefault((ชื่อ, ผล), [0, 0, 0])
            ก[0] += 1
            ก[1] += ตรง
            ก[2] += ไม่ตรง
        for (ชื่อ, ผล), (n, ตรง, ไม่ตรง) in sorted(รวม.items()):
            print(f"  {ชื่อ:26} {ผล:28} {n:3} ชุด · รูปที่ค้นเจอ {ตรง} ค้นไม่เจอ {ไม่ตรง}")
    return เอกสาร, รายงาน


def main():
    ที่อยู่ = Path(sys.argv[1])
    print(ที่อยู่.name)
    เอกสาร, _ = เปิดแบบซ่อมแล้ว(ที่อยู่, พิมพ์หลักฐาน=True)
    print("\nตัวอย่างข้อความหลังซ่อม (หน้า pdf 2-3)")
    for i in (1, 2):
        print(f"  --- หน้า {i + 1} ---")
        for บรรทัด in เอกสาร[i].get_text().split("\n")[:12]:
            if บรรทัด.strip():
                print("   ", บรรทัด.strip())


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
