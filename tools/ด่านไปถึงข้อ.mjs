/**
 * กั้นไฟล์บทหนึ่งไว้จนกว่าด่านจะสั่งปล่อย ⇒ เวลาที่ไฟล์มาถึง **ด่านเป็นคนกำหนด** ⛔ ไม่ใช่ดวงของความเร็วเครื่อง
 */
async function กั้นไฟล์บท(ctx, ไฟล์) {
  let ปล่อย
  const ปล่อยแล้ว = new Promise((r) => (ปล่อย = r))
  let บอกว่าถูกขอ
  const ถูกขอ = new Promise((r) => (บอกว่าถูกขอ = r))
  await ctx.route(`**/api/chapter/${ไฟล์}`, async (route) => {
    บอกว่าถูกขอ(true)
    await ปล่อยแล้ว
    await route.continue()
  })
  return { ถูกขอ, ปล่อย }
}

