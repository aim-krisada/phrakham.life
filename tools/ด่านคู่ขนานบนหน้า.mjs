// **พิสูจน์ว่าด่านแดงได้จริง** ⇒ `node tools/ด่านคู่ขนานบนหน้า.mjs <ที่อยู่เว็บ> --ทดสอบตัวเอง`
//   ⇒ ยัดกฎซ่อนบรรทัดคู่ขนาน ⇒ **ข้อ ① ต้องแดง**
import { chromium } from 'playwright'
import { เส้นทางเว็บ, รอโค้ดของเว็บติด } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')
const ที่ตก = []
const กฎที่พัง = `.pk-คู่ขนาน { display: none !important; }`

const เบราว์เซอร์ = await chromium.launch()

async function เปิด(แบบ, สวิตช์ = {}) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
  await ctx.addInitScript((v) => localStorage.setItem('phrakham.view', JSON.stringify(v)), { จัดวาง: แบบ, ...สวิตช์ })
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}/read/MRK/?c=1&t=TCV`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await รอโค้ดของเว็บติด(แท็บ)
  await แท็บ.waitForTimeout(300)
  if (ทดสอบตัวเอง) await แท็บ.addStyleTag({ content: กฎที่พัง })
  return { ctx, แท็บ }
}

const ส่งมา = await (await fetch(`${ฐาน}/api/chapter/MRK/1.json`)).json()
const คาด = (ส่งมา.หัวข้อ?.TCV || []).filter((ห) => ห.คู่ขนาน)
if (!คาด.length) ที่ตก.push('① หลังบ้านไม่ส่งบรรทัดคู่ขนานของมาระโก 1 มาเลย ⇒ ตัวพ่นอ่านบรรทัด r ไม่ออก')

const นับทุกแบบ = {}
for (const แบบ of ['แยกตามข้อ', 'ไหลต่อเนื่อง', 'แยกตามย่อหน้า']) {
  const { ctx, แท็บ } = await เปิด(แบบ)
  const บนหน้า = await แท็บ.evaluate(() =>
    [...document.querySelectorAll('.pk-ช่องฉบับ[data-ฉบับ="TCV"] .pk-คู่ขนาน, [data-ฉบับ="TCV"] .pk-คู่ขนาน, .pk-คู่ขนาน')]
      .filter((x, i, a) => a.indexOf(x) === i && x.getClientRects().length && getComputedStyle(x).visibility !== 'hidden')
      .map((x) => ({ ตัว: x.textContent, กดได้: x.querySelectorAll('.pk-ที่อยู่คู่ขนาน').length })),
  )
  นับทุกแบบ[แบบ] = บนหน้า.length
  if (แบบ === 'แยกตามข้อ') {
    if (บนหน้า.length !== คาด.length) ที่ตก.push(`① มาระโก 1 ส่งคู่ขนานมา ${คาด.length} บรรทัด ⇒ ตาเห็น ${บนหน้า.length} บรรทัด`)
    คาด.forEach((ห, i) => {
      const ได้ = บนหน้า[i]
      if (!ได้) return
      if (ได้.ตัว !== ห.คู่ขนาน.ตัวหนังสือ) ที่ตก.push(`① บรรทัดที่ ${i + 1} ⇒ ส่งมา "${ห.คู่ขนาน.ตัวหนังสือ}" ⇒ ตาเห็น "${ได้.ตัว}"`)
      if (ได้.กดได้ !== ห.คู่ขนาน.โยงไป.length)
        ที่ตก.push(`② บรรทัด "${ห.คู่ขนาน.ตัวหนังสือ}" ⇒ ที่อยู่ส่งมา ${ห.คู่ขนาน.โยงไป.length} ที่ ⇒ แตะได้ ${ได้.กดได้} ที่`)
    })
    if (!ทดสอบตัวเอง && บนหน้า.length) {
      const เล่ม = คาด[0].คู่ขนาน.โยงไป[0].ที่อยู่.slice(0, 3)
      await แท็บ.locator('.pk-ที่อยู่คู่ขนาน').filter({ visible: true }).first().click()
      await แท็บ.waitForTimeout(1500)
      const หลัง = decodeURIComponent(await แท็บ.evaluate(() => location.search))
      if (!หลัง.includes(เล่ม)) ที่ตก.push(`③ แตะ ${คาด[0].คู่ขนาน.โยงไป[0].ตัวหนังสือ} แล้วไม่มีคอลัมน์ของ ${เล่ม} ⇒ ที่อยู่หน้า ${หลัง}`)
    }
  }
  await ctx.close()
}
if (!ทดสอบตัวเอง)
  for (const [แบบ, n] of Object.entries(นับทุกแบบ))
    if (n !== คาด.length) ที่ตก.push(`④ แบบ${แบบ} ตาเห็นบรรทัดคู่ขนาน ${n} บรรทัด ⛔ ต้องเป็น ${คาด.length}`)

// ── ⑤ สวิตช์สองตัวแยกกัน
if (!ทดสอบตัวเอง) {
  const หัวทั้งหมด = (ส่งมา.หัวข้อ?.TCV || []).length
  for (const [หัว, กรอบ] of [[false, true], [true, false], [false, false]]) {
    const { ctx, แท็บ } = await เปิด('แยกตามข้อ', { หัวข้อย่อย: หัว, คู่ขนาน: กรอบ })
    const นับ = await แท็บ.evaluate(() => {
      const เห็น = (s) => [...document.querySelectorAll(s)].filter((x) => x.getClientRects().length).length
      return { หัว: เห็น('.pk-หัวข้อย่อย'), กรอบ: เห็น('.pk-คู่ขนาน') }
    })
    const ต้อง = { หัว: หัว ? หัวทั้งหมด : 0, กรอบ: กรอบ ? คาด.length : 0 }
    if (นับ.หัว !== ต้อง.หัว || นับ.กรอบ !== ต้อง.กรอบ)
      ที่ตก.push(`⑤ สวิตช์หัวข้อ ${หัว ? 'เปิด' : 'ปิด'} กรอบ ${กรอบ ? 'เปิด' : 'ปิด'} ⇒ เห็นหัวข้อ ${นับ.หัว} กรอบ ${นับ.กรอบ} ⛔ ต้องเป็น ${ต้อง.หัว} กับ ${ต้อง.กรอบ}`)
    await ctx.close()
  }
}

await เบราว์เซอร์.close()

if (ทดสอบตัวเอง) {
  const จับได้ = ที่ตก.filter((x) => x.startsWith('①'))
  if (!จับได้.length) {
    console.error('⛔ โหมดพิสูจน์: ซ่อนบรรทัดคู่ขนานแล้ว **ด่านยังเขียว** ⇒ ด่านตาบอด')
    process.exit(1)
  }
  console.log(`✅ โหมดพิสูจน์: ด่านยังจับของพังได้ ⇒ ${จับได้[0]}`)
  process.exit(0)
}
if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
console.log(`✅ บรรทัดคู่ขนานขึ้นครบ ${คาด.length} บรรทัดทุกแบบจัดวาง ตัวหนังสือตรง แตะแล้วเปิดคอลัมน์ได้ และสวิตช์แยกจากหัวข้อ ⇒ มาระโก 1`)
