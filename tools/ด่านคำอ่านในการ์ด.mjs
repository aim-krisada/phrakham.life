      for (const ข of ต้องได้ยิน)
        if (!ต้นไม้.includes(ไม่มีช่องว่าง(`คำอ่าน ${ข}`)))
          ตก.push(`${ที่} ⇒ ⑥ โปรแกรมอ่านหน้าจอ ⛔ ไม่ได้ยิน «คำอ่าน» นำหน้าคำอ่าน «${ข.slice(0, 40)}»`)
