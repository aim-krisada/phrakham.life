        if (!ต้นไม้กาง.includes(ไม่มีช่องว่าง(ที่มาคำอ่าน))) ตก.push(`${ที่} ⇒ ③ กด ⓘ แล้วโปรแกรมอ่านหน้าจอ ⛔ ไม่ได้ยินที่มา`)
