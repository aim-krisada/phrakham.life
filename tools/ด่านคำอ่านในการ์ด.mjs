      // ---------------------------------------------------------------- ⑤ ในวงเล็บต่อท้ายคำ ⇒ ⛔ แถวแยก
      if (บน.หัวแถว.includes('คำอ่าน')) ตก.push(`${ที่} ⇒ ⑤ ยังมีแถว *คำอ่าน* แยก ⇒ หัวแถว ${JSON.stringify(บน.หัวแถว)}`)
