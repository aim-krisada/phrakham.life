        //   ⇒ หักเฉพาะส่วนของแถบหัวที่อยู่ใต้หัวแถวแรก ⇒ ช่วง 0–80 นับเท่าหัวแถวเดียวเหมือนเดิม ⛔ ผ่อน
        let แถวเพิ่ม = 0
