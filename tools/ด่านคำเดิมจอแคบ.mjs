const เบราว์เซอร์ = await chromium.launch()

/** ไฟล์คำเดิมของบทที่เว็บส่งจริง ⇒ ขอจาก Node ⇒ ดักแก้ในแท็บแล้วด่านยังเห็นของจริง */
const คลังไฟล์ = new Map()
async function ไฟล์คำ(เล่ม, c) {
  const k = `${เล่ม}/${c}`
  if (!คลังไฟล์.has(k)) {
    const r = await fetch(`${ฐาน}/api/words/${k}.json`)
    คลังไฟล์.set(k, r.ok ? await r.json() : null)
  }
  return คลังไฟล์.get(k)
}

/** ข้อเดิมทุกข้อของบท c กับบทข้างเคียง ⇒ `[{ที่, ไป, คำ}]` ⇒ หน้าเป็นคนเลือกว่าข้อไหนอยู่ก้อนบท c ตามบทที่อยู่บนหน้าตอนนั้น */
async function ข้อเดิมรอบบท(เล่ม, c) {
  const ออก = []
  for (const b of [c - 1, c, c + 1]) {
    const ไฟล์ = b >= 1 ? await ไฟล์คำ(เล่ม, b) : null
    if (!ไฟล์) continue
    for (const ข้อทั้งหมด of Object.values(ไฟล์.ชั้น))
      for (const [ข้อ, คำ] of Object.entries(ข้อทั้งหมด))
        ออก.push({ ที่: `${b}:${ข้อ}`, ไป: ไฟล์.ข้อแปล?.[ข้อ] ?? [[b, Number(ข้อ)]], คำ: คำ.length })
  }
  return ออก
}

