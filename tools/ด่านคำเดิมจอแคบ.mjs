/**
 * ⭐ รอคำของบท c ขึ้นครบตามไฟล์ + สัญลักษณ์กาล + คำเน้น + ตัวจัดแถวจัดเสร็จ + ฟอนต์ ⇒ ⛔ ไม่รอเป็นเวลาตายตัว
 *   ⇒ ชุดที่ควรมีคิดในหน้า **จากบทที่อยู่บนหน้าตอนนั้น** ⇒ บทข้างเคียงต่อเข้ามาทีหลังได้ ⇒ ชุดเปลี่ยนตาม
 */
function รอครบ(แท็บ, บท, รอบบท, ตัวเลือก = '.pk-คำใต้แถว') {
  return แท็บ
    .waitForFunction(
      ([c, รอบ, sel]) => {
        const บนหน้า = [...document.querySelectorAll('[data-หมุดบท]')].map((e) => Number(e.dataset.หมุดบท))
        const ควร = รอบ.filter((x) => x.ไป.find(([บ]) => บนหน้า.includes(บ))?.[0] === c)
        if (!ควร.length) return false
        const ก้อน = [...document.querySelectorAll(`${sel}[aria-label$=" ${c}"]`)]
        const มี = new Set(ก้อน.flatMap((g) => [...g.querySelectorAll('.pk-ข้อคำ[data-ข้อเดิม]')].map((p) => p.dataset.ข้อเดิม)))
        if (ควร.some((x) => !มี.has(x.ที่))) return false
        if (ก้อน.some((g) => g.querySelector('.pk-กล่องคำ.pk-แสดงกาล') && !g.querySelector('.pk-กาล'))) return false
        if (ก้อน.some((g) => g.querySelector('.pk-คำ[data-ลค]') && !g.querySelector('[data-คำอ่านเครื่องหมาย]'))) return false
        return document.querySelector('.pk-ตัวบท')?.getAttribute('data-จัดแถว') === 'เสร็จ' && document.fonts.status === 'loaded'
      },
      [บท, รอบบท, ตัวเลือก],
      { timeout: รอนานสุด },
    )
    .then(() => true)
    .catch(() => false)
}

async function เปิด(ส, ตก) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: ส.กว้าง, height: 900 } })
  await ctx.addInitScript(
    ([ฉ, จ, ข, ต]) => {
      localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
      localStorage.setItem(
        'phrakham.view',
        JSON.stringify({ จัดวาง: จ, แสดงเลข: true, ภาษาเดิม: true, ขนาดคำเดิม: ข, วางคอลัมน์: 'บนล่าง', สัญลักษณ์กาล: true, เครื่องหมาย: ['แดง'] }),
      )
      localStorage.setItem('pk-fs', String(ต))
    },
    [ส.ฉบับ, ส.จัดวาง, ส.ขนาด, ส.ตัวอักษร],
  )
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}/read/${ส.เล่ม}?c=${ส.บท}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: รอนานสุด })
  const รอบ = await ข้อเดิมรอบบท(ส.เล่ม, ส.บท)
  const ตัวเลือก = ส.จัดวาง === 'ไหลต่อเนื่อง' ? 'section.pk-คำใต้แถว' : '.pk-คำใต้แถว'
  const พร้อม = ส.กว้าง >= 768 ? true : await รอครบ(แท็บ, ส.บท, รอบ, ตัวเลือก)
  if (!พร้อม) ตก.push(`${ป้าย(ส)} ⇒ คำของบท ${ส.บท} ⛔ ขึ้นไม่ครบใต้แถวภายใน ${รอนานสุด / 1000} วินาที`)
  return { ctx, แท็บ, รอบ, พร้อม }
}

async function ยัด(แท็บ, พัง, บท) {
  if (!พัง) return
  if (พัง.css) await แท็บ.addStyleTag({ content: พัง.css })
  if (พัง.js) await แท็บ.evaluate(พัง.js, บท)
  await แท็บ.waitForTimeout(100)
}

/**
 * อ่านผังของบท c บนจอแคบ ⇒ แถวฉบับแปล กล่องคำใต้แถว และลำดับในเอกสาร
 *   ⇒ `ข้อแปล` ⇒ ข้อแปล v อยู่แถวไหน ⇒ แยกตามข้อ = แถวของ `.pk-ข้อ` · แยกตามย่อหน้า = แถวที่ท่อนแรกของ v อยู่ (ใบ #112 ข้อ 2.6)
 */
function อ่านผัง(แท็บ, c) {
  return แท็บ.evaluate((c) => {
    const กรอบ = (e) => {
      const b = e.getBoundingClientRect()
      return { บน: b.top + scrollY, ล่าง: b.bottom + scrollY }
    }
    const แถว = [...document.querySelectorAll(`.pk-ตัวบท [data-แถว^="${c}:"]:not(.pk-แถวคำ)`)]
    const แถวแปล = แถว.map((e) => {
      // ⭐ ล่างสุดของตัวบท **ทุกฉบับที่ตาเห็น** ในแถว ⇒ ขนานกันมีสองช่อง ⇒ ฉบับที่ยาวกว่าเป็นตัวตัดสิน
      const ช่อง = [...e.querySelectorAll('.pk-ช่องฉบับ')].filter((x) => x.getBoundingClientRect().height > 0)
      return {
        แถว: e.dataset.แถว,
        ...กรอบ(e),
        ล่างฉบับ: Math.max(กรอบ(e).ล่าง, ...ช่อง.map((x) => กรอบ(x).ล่าง)),
        ฉบับที่เห็น: ช่อง.length,
      }
    })
    const ข้อแปล = {}
    for (const e of document.querySelectorAll(`.pk-ตัวบท [data-ข้อ^="${c}:"]`)) {
      if (e.closest('.pk-ชั้นคำ')) continue
      const r = e.closest('[data-แถว]:not(.pk-แถวคำ)')?.dataset.แถว
      if (!r) continue
      if (e.classList.contains('pk-ข้อไหล') && !e.querySelector(':scope > .pk-เลขข้อ')) continue
      if (!(e.dataset.ข้อ in ข้อแปล)) ข้อแปล[e.dataset.ข้อ] = r
    }
    const กล่อง = [...document.querySelectorAll(`.pk-คำใต้แถว[aria-label$=" ${c}"]`)].map((g) => ({
      แถว: g.querySelector('.pk-แถวคำ')?.dataset.แถว ?? null,
      ...กรอบ(g),
      ข้อเดิม: [...g.querySelectorAll('.pk-ข้อคำ[data-ข้อเดิม]')].map((p) => [p.dataset.ข้อเดิม, p.querySelectorAll('.pk-คำ').length]),
      ซ่อน: g.closest('[aria-hidden="true"]') !== null || getComputedStyle(g).display === 'none',
      ทั้งบท: g.tagName === 'SECTION',
    }))
    // ⑧ ลำดับในเอกสาร ⇒ แถวกับกล่องของบท c ⇒ `querySelectorAll` คืนตามลำดับเอกสารเสมอ ⇒ ⛔ ไม่สนว่า CSS วางไว้ไหน
    const ลำดับ = [
      ...document.querySelectorAll(`#บท-${c}, .pk-ตัวบท [data-แถว^="${c}:"]:not(.pk-แถวคำ), .pk-ชั้นคำ[aria-label$=" ${c}"]`),
    ].map((e) =>
      e.id === `บท-${c}` ? 'หมุด' : e.classList.contains('pk-ชั้นคำ') ? `คำ ${e.querySelector('.pk-แถวคำ')?.dataset.แถว ?? '?'}` : `แถว ${e.dataset.แถว}`,
    )
    const บนหน้า = [...document.querySelectorAll('[data-หมุดบท]')].map((e) => Number(e.dataset.หมุดบท))
    return { แถวแปล, ข้อแปล, กล่อง, ลำดับ, บนหน้า }
  }, c)
}

/** ⑤ ⑥ ⑧ ⇒ แต่ละแถวได้คำของมัน · กล่องอยู่ระหว่างแถวของมันกับแถวถัดไป ทั้งบนจอและในเอกสาร */
async function ตรวจใต้แถว(แท็บ, ส, รอบ, ตก) {
  const ที่ = ป้าย(ส)
  const ข้อตรวจ = ส.จัดวาง === 'แยกตามย่อหน้า' ? '⑥' : '⑤'
  const ผ = await อ่านผัง(แท็บ, ส.บท)
  const ควร = รอบ.filter((x) => x.ไป.find(([บ]) => ผ.บนหน้า.includes(บ))?.[0] === ส.บท)
  // แถวที่ควรได้ของแต่ละข้อเดิม ⇒ ข้อแปลข้อแรกที่มีแถวบนหน้า ⇒ ไม่มีเลย ⇒ แถวเดียวกับข้อเดิมก่อนหน้า (ใบ #112 ข้อ 2.3 · 2.4)
  const แถวควร = new Map()
  let ก่อน = null
  for (const x of ควร) {
    const r = x.ไป.map(([b, v]) => ผ.ข้อแปล[`${b}:${v}`]).find(Boolean) ?? ก่อน
    แถวควร.set(x.ที่, r)
    ก่อน = r
  }
  // ⑤ คำครบ และอยู่แถวที่ควร
  const ได้ = new Map()
  for (const g of ผ.กล่อง) for (const [k, n] of g.ข้อเดิม) ได้.set(k, { แถว: g.แถว, คำ: n })
  let ตรวจได้ = 0
  for (const x of ควร) {
    const y = ได้.get(x.ที่)
    if (!y) {
      ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} ข้อเดิม ${x.ที่} ⛔ ไม่อยู่ในกล่องคำใต้แถวไหนเลย`)
      continue
    }
    if (y.คำ !== x.คำ) ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} ข้อเดิม ${x.ที่} มีคำ ${y.คำ} ⛔ ไม่เท่าไฟล์ ${x.คำ}`)
    if (y.แถว !== แถวควร.get(x.ที่))
      ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} ข้อเดิม ${x.ที่} อยู่ใต้แถว ${y.แถว} ⛔ ไม่ใช่แถว ${แถวควร.get(x.ที่)} ของข้อแปล ${x.ไป.map((p) => p.join(':')).join(' ')}`)
    else ตรวจได้++
  }
  if (ตรวจได้ < 3) ตก.push(`${ที่} ⇒ ${ข้อตรวจ} ตรวจข้อเดิมได้แค่ ${ตรวจได้} ข้อ ⛔ น้อยกว่า 3 ⇒ ด่านไม่ได้วัดอะไร`)
  // ⑤ แถวที่ไม่มีคำเดิม ⛔ ไม่มีกล่อง · แถวหนึ่งมีกล่องเดียว
  const แถวที่ควรมีคำ = new Set(แถวควร.values())
  const นับกล่อง = new Map()
  for (const g of ผ.กล่อง) นับกล่อง.set(g.แถว, (นับกล่อง.get(g.แถว) ?? 0) + 1)
  for (const [r, n] of นับกล่อง) {
    if (!แถวที่ควรมีคำ.has(r)) ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} แถว ${r} ⛔ ไม่มีข้อเดิมของมัน แต่มีกล่องคำ`)
    if (n > 1) ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} แถว ${r} มีกล่องคำ ${n} กล่อง ⛔ ควรมีกล่องเดียว`)
  }
  for (const g of ผ.กล่อง) if (g.ซ่อน) ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} กล่องคำแถว ${g.แถว} ถูกซ่อน`)
  // ⑤ บนจอ ⇒ กล่องเริ่มหลังตัวบททุกฉบับของแถวจบ ⇒ จบก่อนแถวถัดไปเริ่ม
  const ลำดับแถว = ผ.แถวแปล.map((t) => t.แถว)
  let วัดได้ = 0
  for (const g of ผ.กล่อง) {
    const i = ลำดับแถว.indexOf(g.แถว)
    const t = ผ.แถวแปล[i]
    if (!t) {
      ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} กล่องคำแถว ${g.แถว} ⛔ ไม่มีแถวฉบับแปลคู่กัน`)
      continue
    }
    const ถัด = ผ.แถวแปล[i + 1]
    if (g.บน < t.ล่างฉบับ - คลาดได้)
      ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} กล่องคำแถว ${g.แถว} เริ่มก่อนตัวบทของแถวจบ ${Math.round(t.ล่างฉบับ - g.บน)} จุด`)
    if (ถัด && g.ล่าง > ถัด.บน + คลาดได้)
      ตก.push(`${ที่} ⇒ 🔴 ${ข้อตรวจ} กล่องคำแถว ${g.แถว} จบหลังแถวถัดไป (${ถัด.แถว}) เริ่ม ${Math.round(g.ล่าง - ถัด.บน)} จุด`)
    วัดได้++
  }
  if (ส.ฉบับ.length > 1 && ผ.แถวแปล.length && ผ.แถวแปล.every((t) => t.ฉบับที่เห็น < 2))
    ตก.push(`${ที่} ⇒ ${ข้อตรวจ} ขนานกันแต่ตาเห็นฉบับเดียว ⇒ ด่านไม่ได้วัดสองฉบับ`)
  // ⑧ ลำดับในเอกสาร ⇒ หมุด → แถว → (กล่องของแถวนั้น) → แถวถัดไป ⇒ ⛔ ไม่มีกล่องก่อนแถวแรก
  let แถวล่าสุด = null
  let ลำดับตก = 0
  for (const x of ผ.ลำดับ) {
    if (x === 'หมุด') continue
    const [ชนิด, r] = x.split(' ')
    if (ชนิด === 'แถว') {
      แถวล่าสุด = r
      continue
    }
    if (r !== แถวล่าสุด) {
      if (ลำดับตก++ < 5)
        ตก.push(`${ที่} ⇒ 🔴 ⑧ ในลำดับที่โปรแกรมอ่านหน้าจอเดิน กล่องคำแถว ${r} ตามหลังแถว ${แถวล่าสุด ?? '(ยังไม่มีแถว ⇒ อยู่ก่อนตัวบท)'} ⛔ ไม่ใช่แถวของมัน`)
    }
    แถวล่าสุด = `ใช้แล้ว ${r}`
  }
  if (ลำดับตก > 5) ตก.push(`${ที่} ⇒ 🔴 ⑧ ลำดับผิดอีก ${ลำดับตก - 5} กล่อง`)
  return { ตรวจได้, วัดได้, ผ }
}

/** ⑨ จอ 320 ⇒ ทุกกล่องคำ ป้าย ลิงก์ ปุ่ม อยู่ในจอ ⇒ แบบพอดี ⇒ ทุกปุ่มคำอยู่ในจอ ⇒ ทั้งหน้า ⛔ เลื่อนข้าง */
async function ตรวจล้น(แท็บ, ส, ตก) {
  const ผล = await แท็บ.evaluate((พอดี) => {
    const กว้าง = document.documentElement.clientWidth
    const ล้น = []
    const ทั้งหน้า = document.documentElement.scrollWidth - กว้าง
    if (ทั้งหน้า > 1) ล้น.push(`ทั้งหน้าเลื่อนข้างได้ ${ทั้งหน้า} จุด`)
    const ที่วัด = ['.pk-คำใต้แถว', '.pk-คำใต้แถว .pk-กล่องคำ', '[data-ป้ายคำเดิมท้ายบท]', '[data-ป้ายคำเดิมท้ายบท] a', '[data-ป้ายคำเดิมท้ายบท] button']
    if (พอดี) ที่วัด.push('.pk-คำใต้แถว .pk-คำ')
    for (const sel of ที่วัด)
      for (const e of document.querySelectorAll(sel)) {
        const b = e.getBoundingClientRect()
        if (!b.width) continue
        if (b.right > กว้าง + 1 || b.left < -1) {
          ล้น.push(`${sel} ยื่นพ้นจอ ${Math.round(Math.max(b.right - กว้าง, -b.left))} จุด`)
          break
        }
      }
    if (พอดี)
      for (const e of document.querySelectorAll('.pk-คำใต้แถว .pk-กล่องคำ'))
        if (e.scrollWidth - e.clientWidth > 1) {
          ล้น.push(`กล่องคำแบบพอดีล้นข้างใน ${e.scrollWidth - e.clientWidth} จุด`)
          break
        }
    return ล้น
  }, ส.ขนาด === 'พอดี')
  for (const x of ผล) ตก.push(`${ป้าย(ส)} ⇒ 🔴 ⑨ ${x}`)
}

/**
 * ⑪ เลขข้อในกล่องคำใต้แถว ⇒ ⛔ ถูกตัด ⇒ ทั้งตัวต้องอยู่ในกล่องบรรพบุรุษตัวแรกที่ตัดของล้น
 *   ⇒ คนตรวจ !149 เจอ ⇒ เลขข้อเป็นตัวยก ⇒ โผล่พ้นขอบบนของกล่องคำที่เลื่อนข้างได้ ⇒ ถูกตัด 6 จุดทุกกล่อง
 *   ⇒ ไล่ทุกเลขข้อของบท ⇒ ⛔ ไม่ใช่แค่กล่องแรก
 */
async function ตรวจเลขข้อ(แท็บ, ส, ตก) {
  const ผล = await แท็บ.evaluate((c) => {
    const ตัด = []
    let นับ = 0
    for (const sup of document.querySelectorAll(`.pk-คำใต้แถว[aria-label$=" ${c}"] .pk-ข้อคำ > .pk-เลขข้อ`)) {
      const s = sup.getBoundingClientRect()
      if (!s.height || !s.width) continue
      นับ++
      for (let e = sup.parentElement; e; e = e.parentElement) {
        const cs = getComputedStyle(e)
        if (cs.overflowX === 'visible' && cs.overflowY === 'visible' && cs.clipPath === 'none' && !cs.contain.includes('paint')) {
          if (e.classList.contains('pk-คำใต้แถว')) break
          continue
        }
        const r = e.getBoundingClientRect()
        const บน = r.top + parseFloat(cs.borderTopWidth)
        const ล่าง = r.bottom - parseFloat(cs.borderBottomWidth)
        const ซ้าย = r.left + parseFloat(cs.borderLeftWidth)
        if (s.top < บน - 0.5 || s.bottom > ล่าง + 0.5 || s.left < ซ้าย - 0.5)
          ตัด.push(`${sup.closest('.pk-ข้อคำ')?.dataset.ข้อเดิม} ถูก ${e.className.split(' ')[0]} ตัด ${Math.round(Math.max(บน - s.top, s.bottom - ล่าง, ซ้าย - s.left))} จุด`)
        break
      }
    }
    return { ตัด, นับ }
  }, ส.บท)
  if (!ผล.นับ) ตก.push(`${ป้าย(ส)} ⇒ ⑪ ⛔ ไม่เจอเลขข้อในกล่องคำใต้แถว ⇒ ด่านไม่ได้วัดอะไร`)
  if (ผล.ตัด.length) ตก.push(`${ป้าย(ส)} ⇒ 🔴 ⑪ เลขข้อถูกตัด ${ผล.ตัด.length} จาก ${ผล.นับ} ตัว ⇒ ${ผล.ตัด.slice(0, 3).join(' · ')}`)
  return ผล.นับ
}

async function ตรวจแถว(ส, พัง = null) {
  const ตก = []
  const { ctx, แท็บ, รอบ, พร้อม } = await เปิด(ส, ตก)
  let สรุป = ''
  try {
    if (พร้อม) {
      await ยัด(แท็บ, พัง, ส.บท)
      const { ตรวจได้, วัดได้, ผ } = await ตรวจใต้แถว(แท็บ, ส, รอบ, ตก)
      if (ส.กว้าง === 320 && ส.ตัวอักษร >= 2) await ตรวจล้น(แท็บ, ส, ตก)
      const เลข = await ตรวจเลขข้อ(แท็บ, ส, ตก)
      สรุป = `ข้อเดิมตรงแถว ${ตรวจได้} ข้อ · กล่องคำ ${วัดได้} กล่อง · วัดเลขข้อ ${เลข} ตัว`
      // ⭐ ตัวเลขของอาการที่พี่เอมเจอ ⇒ ข้อ 12 ของมาระโก 11 ⇒ ตัวบทจบที่ไหน คำกรีกเริ่มที่ไหน
      const t12 = ผ.แถวแปล.find((t) => t.แถว === ผ.ข้อแปล['11:12'])
      const g12 = ผ.กล่อง.find((g) => g.ข้อเดิม.some(([k]) => k === '11:12'))
      if (ส.เล่ม === 'MRK' && t12 && g12) สรุป += ` · ข้อ 12 ตัวบทจบ ${Math.round(t12.ล่างฉบับ)} ⇒ คำกรีกเริ่ม ${Math.round(g12.บน)} จุด`
    }
  } catch (e) {
    ตก.push(`${ป้าย(ส)} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message}`)
  } finally {
    await ctx.close()
  }
  return { ตก, สรุป }
}

