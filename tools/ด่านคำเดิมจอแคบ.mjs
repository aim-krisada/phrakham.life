  const ไฟล์ = readFileSync(new URL('../app/utils/คำเดิมจอแคบ.ts', import.meta.url), 'utf8')
  const ก้อน = ไฟล์.slice(ไฟล์.indexOf('export const ถ้อยคำคำเดิมท้ายบท'))
  const ค่า = (ชื่อ) => ก้อน.match(new RegExp(`${ชื่อ}: '([^']*)'`))?.[1]
  const ผล = { ประโยค: ค่า('ประโยค'), ลิงก์: ค่า('ลิงก์'), ปุ่ม: ค่า('ปุ่ม') }
