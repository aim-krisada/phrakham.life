        const หัวแรก = แถบหัว && [...แถบหัว.querySelectorAll('.pk-หัวช่อง')].find((h) => h.getClientRects().length)
        if (หัวแรก) แถวเพิ่ม = Math.max(0, แถบหัว.getBoundingClientRect().bottom - หัวแรก.getBoundingClientRect().bottom)
