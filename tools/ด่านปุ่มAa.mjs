async function ตรวจแป้น(พัง) {
  const ตก = []
  const { ctx, แท็บ } = await เปิด(375, พัง)
  const ป้าย = 'จอ 375'
  const โฟกัส = () =>
    แท็บ.evaluate(() => {
      const el = document.activeElement
      return {
        Aa: el?.getAttribute('data-ปุ่ม') === 'Aa',
        ในแผง: !!el?.closest('#pk-แผงAa'),
        คำ: (el?.textContent || '').replace(/\s+/g, ' ').trim(),
      }
    })
  const กางอยู่ = () => ปุ่มAa(แท็บ).getAttribute('aria-expanded')
  const รอแผง = (มี) =>
    แท็บ
      .waitForSelector('#pk-แผงAa', { state: มี ? 'visible' : 'detached', timeout: 5000 })
      .then(() => true)
      .catch(() => false)
  try {
    // Tab จากเทียบ ⇒ ค้นหา ⇒ แชร์ ⇒ ถึง Aa (ใบ #173 ⇒ ลำดับเดียวกับที่ตาเห็นบนแถบ ⇒ SC 2.4.3)
    await แท็บ.getByRole('button', { name: ชื่อปุ่มเทียบ, exact: true }).focus()
    for (const ชื่อ of ['ค้นหา', 'แชร์']) {
      await แท็บ.keyboard.press('Tab')
      const ที่ = await แท็บ.evaluate(() => document.activeElement?.getAttribute('data-ปุ่ม'))
      if (ที่ !== ชื่อ) ตก.push(`③ ${ป้าย} ⇒ Tab ไปทางขวาของ “${ชื่อปุ่มเทียบ}” แล้วโฟกัสไปที่ “${ที่}” ⛔ ต้องเป็น “${ชื่อ}”`)
    }
    await แท็บ.keyboard.press('Tab')
    if (!(await โฟกัส()).Aa) ตก.push(`③ ${ป้าย} ⇒ Tab จาก “${ชื่อปุ่มเทียบ}” แล้วโฟกัสไปที่ “${(await โฟกัส()).คำ}” ⛔ ไม่ใช่ Aa`)
    await ปุ่มAa(แท็บ).focus()
    // Enter ⇒ กาง
    await แท็บ.keyboard.press('Enter')
    if (!(await รอแผง(true)) || (await กางอยู่()) !== 'true') {
      ตก.push(`③ ${ป้าย} ⇒ กด Enter ที่ Aa แล้วแผง ⛔ ไม่กาง`)
      return ตก
    }
    // Tab ⇒ เข้าแผง ⇒ ไล่ถึง ก+
    await แท็บ.keyboard.press('Tab')
    if (!(await โฟกัส()).ในแผง) ตก.push(`③ ${ป้าย} ⇒ กาง Aa แล้วกด Tab ⇒ โฟกัสไปที่ “${(await โฟกัส()).คำ}” ⛔ ไม่ได้เข้าแผง`)
    for (let i = 0; i < 4 && !/ตัวใหญ่ขึ้น/.test((await โฟกัส()).คำ); i++) await แท็บ.keyboard.press('Tab')
    if (!/ตัวใหญ่ขึ้น/.test((await โฟกัส()).คำ)) ตก.push(`③ ${ป้าย} ⇒ ไล่ Tab ในแผงแล้ว ⛔ ไม่ถึงปุ่ม ก+`)
    else {
      const ขั้นเดิม = await ขั้นตอนนี้(แท็บ)
      await แท็บ.keyboard.press('Enter')
      if (!(await รอขนาดเปลี่ยน(แท็บ, ขั้นเดิม))) ตก.push(`③ ${ป้าย} ⇒ Enter ที่ ก+ แล้วตัวอักษร ⛔ ไม่ใหญ่ขึ้น`)
      await แท็บ.keyboard.press('Shift+Tab')
      if (!/ตัวเล็กลง/.test((await โฟกัส()).คำ)) ตก.push(`③ ${ป้าย} ⇒ Shift+Tab จาก ก+ ⛔ ไม่ถึง ก−`)
      else {
        const ขั้นใหญ่ = await ขั้นตอนนี้(แท็บ)
        await แท็บ.keyboard.press('Space')
        if (!(await รอขนาดเปลี่ยน(แท็บ, ขั้นใหญ่))) ตก.push(`③ ${ป้าย} ⇒ แป้นเว้นวรรคที่ ก− แล้วตัวอักษร ⛔ ไม่เล็กลง`)
      }
    }
    // Escape ⇒ พับ ⇒ โฟกัสกลับ Aa
    await แท็บ.keyboard.press('Escape')
    if (!(await รอแผง(false))) ตก.push(`③ ${ป้าย} ⇒ กด Escape แล้วแผง ⛔ ไม่พับ`)
    else if (!(await โฟกัส()).Aa) ตก.push(`③ ${ป้าย} ⇒ กด Escape แล้วโฟกัสไปที่ “${(await โฟกัส()).คำ}” ⛔ ไม่กลับ Aa`)
    // แป้นเว้นวรรคที่ Aa ⇒ กาง ⇒ อีกครั้ง ⇒ พับ
    await ปุ่มAa(แท็บ).focus()
    await แท็บ.keyboard.press('Space')
    if (!(await รอแผง(true))) ตก.push(`③ ${ป้าย} ⇒ แป้นเว้นวรรคที่ Aa แล้วแผง ⛔ ไม่กาง`)
    await แท็บ.keyboard.press('Space')
    if (!(await รอแผง(false))) ตก.push(`③ ${ป้าย} ⇒ แป้นเว้นวรรคที่ Aa อีกครั้งแล้วแผง ⛔ ไม่พับ`)
  } catch (e) {
    ตก.push(`③ ${ป้าย} ⇒ ล้มระหว่างตรวจ ⇒ ${e.message}`)
  } finally {
    await ctx.close()
  }
  return ตก
}

async function ตรวจทั้งหมด(พัง) {
  const ข้อ = พัง?.ข้อ
  const ตก = []
  if (!ข้อ || ข้อ === '①' || ข้อ === '⑥') ตก.push(...(await ตรวจแถบ(พัง)))
  if (!ข้อ || ['②', '④', '⑤', '⑦'].includes(ข้อ)) ตก.push(...(await ตรวจแผง(พัง)))
  if (!ข้อ || ข้อ === '③') ตก.push(...(await ตรวจแป้น(พัง)))
  return ตก
}

