def ตรวจ(ของ: dict) -> list[str]:
    """คืนรายการปัญหา ⇒ แต่ละข้อขึ้นต้นด้วยเลขข้อ ⇒ ว่าง = ผ่าน"""
    ปัญหา: list[str] = []
    แถว = อ่านตาราง(ของ["ทะเบียน"])
    ตามไฟล์ = {x["ไฟล์"]: x for x in แถว}
    for ไฟล์ in sorted(set(ของ["เรื่อง"]) - set(ตามไฟล์)):
        ปัญหา.append(f"① {ไฟล์} อยู่ใน เรื่องเล่า/ แต่ไม่มีแถวในทะเบียน ⇒ เรื่องที่ยังไม่อนุมัติ ⛔ ห้ามขึ้นเว็บ")
    for ไฟล์ in sorted(set(ตามไฟล์) - set(ของ["เรื่อง"])):
        ปัญหา.append(f"① ทะเบียนมีแถว {ไฟล์} แต่ไม่มีไฟล์")
    สะกด = อ่านตาราง(ของ["สะกด"])
    รหัสที่มี = set()
    for ไฟล์, ไบต์ in sorted(ของ["เรื่อง"].items()):
        ร = ตามไฟล์.get(ไฟล์)
        if not ร:
            continue
        รหัส = ร["รหัส"]
        รหัสที่มี.add(รหัส)
        if blob(ไบต์) != ร["blob"]:
            ปัญหา.append(f"② {ไฟล์} ⇒ blob {blob(ไบต์)[:12]} ไม่ตรงทะเบียน {ร['blob'][:12]} ⇒ ไม่ใช่ไบต์ที่อนุมัติ")
        เนื้อ = ไบต์.decode("utf-8", "replace")
        if f"อนุมัติโดย: พี่เอม (krisada) เมื่อ {ร['อนุมัติเมื่อ']}" not in เนื้อ:
            ปัญหา.append(f"③ {ไฟล์} ⇒ ไม่มีบรรทัด อนุมัติโดย: พี่เอม (krisada) เมื่อ {ร['อนุมัติเมื่อ']}")
        ช่วง = ช่วงของรหัส(รหัส)
        if not ช่วง or f"อ้างอิง: {ร['ชื่อเล่ม']} {ช่วง}\n" not in เนื้อ:
            ปัญหา.append(f"③ {ไฟล์} ⇒ บรรทัด อ้างอิง: ไม่ตรงกับรหัส {รหัส} ในทะเบียน")
        เรื่อง = ตัวเรื่อง(เนื้อ)
        if not เรื่อง:
            ปัญหา.append(f"④ {ไฟล์} ⇒ ไม่มีเนื้อใต้หัวข้อ {หัวเรื่องนำ}")
            continue
        for รอย in รอยรายการตรวจ:
            if รอย in เรื่อง:
                ปัญหา.append(f"④ {ไฟล์} ⇒ ตัวเรื่องมี \"{รอย}\" ⇒ รายการตรวจหลุดเข้ามาในข้อความที่ขึ้นจอและอ่านออกเสียง")
                break
        ปัญหา += ตรวจเชิงอรรถ(ไฟล์, เนื้อ, เรื่อง)
        # ⑤ เสียง
        คู่ = ของ["คู่เสียง"].get(f"{รหัส}.puck.json")
        if not คู่:
            ปัญหา.append(f"⑤ {รหัส} ⇒ ไม่มีไฟล์คู่เสียง เสียง/เรื่องเล่า/{รหัส}.puck.json ⇒ ฟังเรื่องเล่าไม่ได้")
            continue
        if คู่.get("blobเรื่อง") != ร["blob"] or คู่.get("ลายนิ้วมือตัวเรื่อง") != ลายนิ้วมือ(เรื่อง):
            ปัญหา.append(f"⑤ {รหัส} ⇒ เสียงพ่นจากตัวเรื่องคนละฉบับกับที่อนุมัติ ⇒ ต้องพ่นใหม่")
        if คู่.get("ลายนิ้วมือรายการสะกด") != ลายนิ้วมือ(ของ["สะกด"]):
            ปัญหา.append(f"⑤ {รหัส} ⇒ รายการสะกดเปลี่ยนหลังพ่นเสียง ⇒ เสียงค้างรุ่น ⇒ ต้องพ่นใหม่")
        ก้อน = คู่.get("ก้อน") or []
        ต่อกัน = " ".join(x.get("ข้อความที่ส่ง", "") for x in ก้อน)
        for x in สะกด:
            ต่อกัน = ต่อกัน.replace(x["คำที่ส่งพ่น"], x["คำบนจอ"])
        # ⭐ ใบ #168 ⇒ เทียบกับตัวเรื่องที่ตัดเลขเชิงอรรถแล้ว ⇒ เลขเชิงอรรถ ⛔ ไม่อ่านออกเสียง ⇒ ที่เหลือต้องเท่ากันทุกตัวอักษรเหมือนเดิม
        if ต่อกัน != re.sub(r"\s+", " ", รอยเลขเชิงอรรถ.sub("", เรื่อง)).strip():
            ปัญหา.append(f"⑤ {รหัส} ⇒ ข้อความที่ส่งพ่นทุกก้อนต่อกันแล้ว ไม่เท่าตัวเรื่องที่อนุมัติ")
        for x in ก้อน:
            if "[^" in x.get("ข้อความที่ส่ง", ""):
                ปัญหา.append(f"⑨ {รหัส} ก้อน {x.get('ลำดับ')} ⇒ ข้อความที่ส่งไปทำเสียงมี [^ ⇒ เครื่องอ่านเลขเชิงอรรถออกเสียง")
        for x in ก้อน:
            ข้อความ = x.get("ข้อความที่ส่ง", "")
            ควรได้ = len(ข้อความ) / ตัวอักษรต่อวินาที if ข้อความ else 0
