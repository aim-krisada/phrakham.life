def blob(ไบต์: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(ไบต์) + ไบต์).hexdigest()


def ลายนิ้วมือ(ข้อความ: str) -> str:
    return "sha256:" + hashlib.sha256(ข้อความ.encode("utf-8")).hexdigest()[:16]


def อ่านตาราง(ข้อความ: str) -> list[dict]:
    บรรทัด = [x for x in ข้อความ.replace("\r\n", "\n").split("\n") if x and not x.startswith("#")]
    หัว = บรรทัด[0].split("\t")
    return [dict(zip(หัว, x.split("\t"))) for x in บรรทัด[1:]]


def ตัวเรื่อง(เนื้อ: str) -> str | None:
    if หัวเรื่องนำ not in เนื้อ:
        return None
    ส่วน = เนื้อ.split(หัวเรื่องนำ, 1)[1]
    return re.split(r"^## ", ส่วน, maxsplit=1, flags=re.M)[0].strip()


def ตรวจเชิงอรรถ(ไฟล์: str, เนื้อ: str, เรื่อง: str) -> list[str]:
    """ข้อ ⑧ ⇒ เลขในตัวเรื่องกับเชิงอรรถใต้หัวข้อ `## เชิงอรรถ` ต้องคู่กันพอดี"""
    ปัญหา = []
    if รอยนิยามเชิงอรรถ.search(เรื่อง):
        ปัญหา.append(f"⑧ {ไฟล์} ⇒ มีนิยามเชิงอรรถ [^…]: อยู่ในตัวเรื่อง ⇒ จะขึ้นจอเป็นตัวเรื่องและถูกอ่านออกเสียง")
    ที่อ้าง = set(รอยเลขเชิงอรรถ.findall(รอยนิยามเชิงอรรถ.sub("", เรื่อง)))
    หลังเรื่อง = re.split(r"^## ", เนื้อ.split(หัวเรื่องนำ, 1)[1], flags=re.M)[1:]
    ส่วน = [x for x in หลังเรื่อง if x.startswith("เชิงอรรถ")]
    if len(ส่วน) > 1:
        ปัญหา.append(f"⑧ {ไฟล์} ⇒ มีหัวข้อเชิงอรรถ {len(ส่วน)} หัวข้อ ⇒ ต้องมีหัวข้อเดียว")
    นิยาม: dict[str, str] = {}
    if ส่วน:
        ใน = ส่วน[0].partition("\n")[2]
        ชิ้น = re.split(r"(?=^\[\^[^\]\s]+\]:)", ใน, flags=re.M)
        if ชิ้น and ชิ้น[0].strip() and not รอยนิยามเชิงอรรถ.match(ชิ้น[0]):
            ปัญหา.append(f"⑧ {ไฟล์} ⇒ หัวข้อเชิงอรรถมีข้อความที่ไม่ใช่เชิงอรรถ ⇒ \"{ชิ้น[0].strip()[:30]}\"")
        for ช in ชิ้น:
            m = รอยนิยามเชิงอรรถ.match(ช)
            if not m:
                continue
            if m.group(1) in นิยาม:
                ปัญหา.append(f"⑧ {ไฟล์} ⇒ เชิงอรรถ [^{m.group(1)}] ถูกนิยามซ้ำ")
            นิยาม[m.group(1)] = ช[m.end():].strip()
            if not นิยาม[m.group(1)]:
                ปัญหา.append(f"⑧ {ไฟล์} ⇒ เชิงอรรถ [^{m.group(1)}] ว่าง")
    for ป้าย in sorted(ที่อ้าง - set(นิยาม)):
        ปัญหา.append(f"⑧ {ไฟล์} ⇒ เลข [^{ป้าย}] ในตัวเรื่องไม่มีเชิงอรรถคู่ ⇒ กดแล้วไม่ไปไหน")
    for ป้าย in sorted(set(นิยาม) - ที่อ้าง):
        ปัญหา.append(f"⑧ {ไฟล์} ⇒ เชิงอรรถ [^{ป้าย}] ไม่ถูกอ้างในตัวเรื่อง ⇒ ผู้อ่านไม่มีทางไปถึง")
    return ปัญหา


def ช่วงของรหัส(รหัส: str) -> str:
    """`MRK.10.1-10.12` ⇒ `10.1-12` · `MRK.4.35-5.20` ⇒ `4.35-5.20` ⇒ รูปเดียวกับบรรทัด อ้างอิง: ของต้นทาง"""
    m = re.fullmatch(r"[0-9A-Z]{3}\.(\d+)\.(\d+)-(\d+)\.(\d+)", รหัส)
    if not m:
        return ""
    c1, v1, c2, v2 = m.groups()
    return f"{c1}.{v1}-{v2}" if c1 == c2 else f"{c1}.{v1}-{c2}.{v2}"


def ขนาดไฟล์เสียง(ทาง: Path) -> int | None:
    """ไบต์จริง ⇒ ขนาดไฟล์ · ตัวชี้ของ LFS (ในท่อ) ⇒ ขนาดที่ตัวชี้บอก ⇒ ⛔ ไม่ต้องดึงไบต์จริงก็ตรวจขนาดได้"""
    if not ทาง.exists():
        return None
    หัว = ทาง.read_bytes()[:200]
    if หัว.startswith(b"version https://git-lfs"):
        m = re.search(rb"size (\d+)", หัว)
        return int(m.group(1)) if m else None
    return ทาง.stat().st_size


