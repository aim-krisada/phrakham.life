const เป้า = 44

/** อ่านการ์ดทีเดียว ⇒ ของที่ตาเห็น + การล้นขอบ */
const อ่านการ์ด = (แท็บ) =>
  แท็บ.evaluate(() => {
    const ก = document.querySelector('[data-การ์ดคำ]')
    const de = document.documentElement
    const ขวา = Math.min(de.clientWidth, ก.getBoundingClientRect().right)
    /** ตาเห็นไหม ⇒ วาดจริงและมีความสูง */
    const เห็น = (x) => !!x && x.checkVisibility() && x.getBoundingClientRect().height > 0
    /** ปุ่ม ⓘ กับที่มาของแถวหนึ่ง (ใบ #157) ⇒ แถว = `div` ของ `dl` ที่มีที่มานั้น */
    const แถวของ = (sel) => ก.querySelector(`.pk-ข้อมูลคำ > div:has(${sel})`)
    const ปุ่มไอ = (ปุ่ม, ที่มา) => {
      const ทั้งหมด = [...ก.querySelectorAll(ปุ่ม)]
      const b = ทั้งหมด[0]
      const r = b?.getBoundingClientRect()
      const t = ก.querySelector(ที่มา)
      const แถว = แถวของ(ที่มา)
      return {
        ปุ่ม: b
          ? {
              จำนวน: ทั้งหมด.length,
              แท็ก: b.tagName.toLowerCase(),
              ชื่อ: b.getAttribute('aria-label'),
              กาง: b.getAttribute('aria-expanded'),
              คุม: b.getAttribute('aria-controls'),
              กว้าง: r.width,
              สูง: r.height,
              อยู่แถว: !!แถว?.contains(b),
            }
          : null,
        มีที่มา: !!t,
        ที่มาid: t?.id ?? null,
        ที่มาเห็น: เห็น(t),
      }
    }
    /** ⑤ บรรทัดสัญญา ⇒ ตาเห็นทุกบรรทัด */
    const สัญญา = (sel) => [...ก.querySelectorAll(sel)].map((x) => ({ เห็น: เห็น(x), ข้อความ: x.textContent.replace(/\s+/g, ' ').trim().slice(0, 40) }))
    return {
      ที่มากาล: ก.querySelector('[data-กาลในการ์ด] [data-ที่มากาล]')?.textContent.trim() ?? null,
      ศัพท์: [...ก.querySelectorAll('[data-ศัพท์ในการ์ด] .pk-ศัพท์ในการ์ด')].map((x) => {
        // ⭐ ใบ #157 ⇒ ตัดปุ่ม ⓘ ออกก่อนอ่านตัวหนังสือ ⇒ ปุ่มตรวจแยกที่ข้อ ② ⇒ ตัวหนังสือเทียบตารางเท่าเดิม
        const c = x.cloneNode(true)
        for (const b of c.querySelectorAll('[data-ปุ่มที่มาศัพท์]')) b.remove()
        return {
          ชุด: x.getAttribute('data-ชุด'),
          รหัส: x.getAttribute('data-รหัส'),
          ที่มา: x.hasAttribute('data-ที่มาศัพท์'),
          ชื่อ: x.querySelector('.pk-ชื่อศัพท์ในการ์ด')?.textContent.trim() ?? null,
          ข้อความ: c.textContent.replace(/\s+/g, ' ').trim(),
        }
      }),
      ไอ: {
        กาล: ปุ่มไอ('[data-ปุ่มที่มากาล]', '[data-ที่มากาล]'),
        ศัพท์: ปุ่มไอ('[data-ปุ่มที่มาศัพท์]', '[data-ก้อนที่มาศัพท์]'),
      },
      สัญญา: {
        MACULA: สัญญา('.pk-ข้อมูลคำ + .pk-ที่มาในการ์ด'),
        พจนานุกรม: สัญญา('.pk-แหล่งในการ์ด > .pk-ที่มาในการ์ด'),
        LGNTDF: สัญญา('[data-เน้นในการ์ด] .pk-ที่มาในการ์ด'),
      },
      ข้อความทั้งการ์ด: ก.textContent,
      ช่องศัพท์em: (() => {
        const dd = ก.querySelector('[data-ศัพท์ในการ์ด] dd')
        return dd ? dd.getBoundingClientRect().width / parseFloat(getComputedStyle(dd).fontSize) : null
      })(),
      ล้นหน้า: Math.round(de.scrollWidth - de.clientWidth),
      ล้นการ์ด: Math.round(ก.scrollWidth - ก.clientWidth),
      ตัวที่ล้น: [...ก.querySelectorAll('*')]
        .map((el) => ({ el, r: el.getBoundingClientRect() }))
        .filter((x) => x.r.width > 0 && x.r.right > ขวา + 0.5)
        .slice(0, 3)
        .map((x) => `${x.el.tagName.toLowerCase()}.${String(x.el.className).slice(0, 30)} ขวาสุด=${Math.round(x.r.right)}`),
    }
  })

async function ตรวจจอ({ ชื่อ, กว้าง, สูง, ใหญ่สุด }, พัง = null) {
  const ตก = []
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: สูง } })
  if (ใหญ่สุด)
    // ⭐ ผู้อ่านตั้งเบราว์เซอร์ 200% และกดปุ่มของเว็บจนสุด (2.0 = ขั้นสุดท้ายของ `public/pk-fontsize.js`) ไว้ก่อนแล้ว
    await ctx.addInitScript(() => {
      try {
        localStorage.setItem('pk-fs', '2')
      } catch {}
      document.documentElement.style.fontSize = '32px'
    })
  try {
    const แท็บ = await ctx.newPage()
    await เปิดหน้า(แท็บ)
    await เปิดคอลัมน์(แท็บ)
    const ไฟล์การ์ด = await แท็บ.evaluate(async (u) => (await fetch(u)).json(), `${ฐาน}/api/card/${บท.เล่ม}/${บท.บท}.json`)
    const เจอสัญญา = new Set()
    for (const [ข้อ, i] of คำที่กด) {
      const ป้าย = `${ชื่อ} ⇒ มาระโก ${บท.บท}:${ข้อ} คำที่ ${i + 1}`
      const แถว = ไฟล์การ์ด.ชั้น?.คำกรีก?.[ข้อ]?.[i]
      if (!แถว) {
        ตก.push(`${ป้าย} ⇒ ไฟล์การ์ด ⛔ ไม่มีคำนี้ ⇒ ไม่มีอะไรให้ตรวจ ⛔ ไม่นับว่าผ่าน`)
        continue
      }
      const รูปผัน = แถว.split('~')[2] ?? ''
      const ควร = ที่ควรเห็น(รูปผัน)
      if (!ควร.ศัพท์.length && !ควร.กาล) ตก.push(`${ป้าย} (${รูปผัน}) ⇒ คำนี้ไม่มีศัพท์ให้ตรวจ ⇒ เลือกคำผิด`)

      const ปุ่มคำ = แท็บ.locator(`${ก้อนของบท} .pk-ข้อคำ[data-ข้อเดิม="${บท.บท}:${ข้อ}"] .pk-คำ`).nth(i)
      const ตัว = (await ปุ่มคำ.locator('.pk-ตัวเดิม').textContent())?.trim() ?? ''
      await ปุ่มคำ.scrollIntoViewIfNeeded()
      await ปุ่มคำ.click()
      // ⭐ รอการ์ดของ *คำนี้* โหลดเสร็จจริง ⇒ หัวการ์ดเป็นคำนี้ และแถวรูปผันขึ้นรหัสของคำนี้แล้ว
      const ขึ้น = await แท็บ
        .waitForFunction(
          ([ตัว, รูปผัน]) => {
            const ก = document.querySelector('[data-การ์ดคำ]')
            return (
              ก?.querySelector('.pk-คำในการ์ด')?.textContent.trim() === ตัว &&
              ก.querySelector('.pk-รหัสรูปผัน')?.textContent.includes(รูปผัน)
            )
          },
          [ตัว, รูปผัน],
          { timeout: รอนานสุด },
        )
        .then(() => true)
        .catch(() => false)
      if (!ขึ้น) {
        ตก.push(`${ป้าย} ${ตัว} ⇒ กดแล้วการ์ดของคำนี้ ⛔ ไม่ขึ้นภายใน ${รอนานสุด / 1000} วินาที`)
        continue
      }
      await แท็บ.evaluate(() => document.fonts.ready)
      if (พัง && ท่าพัง[พัง]) await แท็บ.evaluate(ท่าพัง[พัง], ความหมายคำสั่ง)
      const บน = await อ่านการ์ด(แท็บ)
      const ที่ = `${ป้าย} ${ตัว} (${รูปผัน})`

      // ---------------------------------------------------------------- ① ที่มาของความหมายกาล
      if (ควร.กาล && บน.ที่มากาล !== ที่มาถ้อยคำ)
        ตก.push(`${ที่} ⇒ ① บรรทัดที่มาของความหมายกาล ${บน.ที่มากาล === null ? '⛔ ไม่มี' : `เป็น «${บน.ที่มากาล}»`} ⇒ ควรเป็น «${ที่มาถ้อยคำ}»`)

      // ---------------------------------------------------------------- ② คำอธิบายศัพท์ครบ ตรงตาราง
      const รายศัพท์ = บน.ศัพท์.filter((x) => !x.ที่มา)
      for (const ศ of ควร.ศัพท์) {
        const x = รายศัพท์.find((y) => y.ชุด === ศ.ชุด && y.รหัส === ศ.รหัส)
        const ข้อความที่ควร = `${ศ.ชื่อ} ${ศ.อธิบาย?.ความหมาย ?? ''}`
        if (!x) ตก.push(`${ที่} ⇒ ② ${ศ.ชื่อ} ⇒ ⛔ ไม่มีคำอธิบายบนการ์ด`)
        else if (x.ชื่อ !== ศ.ชื่อ) ตก.push(`${ที่} ⇒ ② ชื่อศัพท์บนการ์ดเป็น «${x.ชื่อ}» ⛔ ควรเป็นชื่อเดิม «${ศ.ชื่อ}»`)
        else if (x.ข้อความ !== ข้อความที่ควร) ตก.push(`${ที่} ⇒ ② คำอธิบาย ${ศ.ชื่อ} บนการ์ดเป็น «${x.ข้อความ}» ⛔ ไม่ตรงตาราง`)
      }
      if (รายศัพท์.length !== ควร.ศัพท์.length)
        ตก.push(`${ที่} ⇒ ② แถวศัพท์มี ${รายศัพท์.length} บรรทัด ⛔ ควรมี ${ควร.ศัพท์.length} ⇒ มีศัพท์เกินหรือขึ้นซ้ำ`)
      const ที่มาบน = บน.ศัพท์.filter((x) => x.ที่มา).map((x) => x.ข้อความ)
      if (JSON.stringify(ที่มาบน) !== JSON.stringify(ควร.ที่มา))
        ตก.push(`${ที่} ⇒ ② ที่มาของคำอธิบายศัพท์บนการ์ดเป็น ${JSON.stringify(ที่มาบน)} ⛔ ควรเป็น ${JSON.stringify(ควร.ที่มา)}`)
      const คำสั่งกี่ที่ = บน.ข้อความทั้งการ์ด.split(ความหมายคำสั่ง).length - 1
      if (คำสั่งกี่ที่ > 1) ตก.push(`${ที่} ⇒ ② ประโยคคำสั่งขึ้น ${คำสั่งกี่ที่} ที่บนการ์ดเดียว ⇒ ⛔ ขึ้นซ้ำ`)

      // ---------------------------------------------------------------- ① ② ปุ่ม ⓘ ⇒ ตอนการ์ดเพิ่งขึ้น ⇒ ที่มาซ่อน (ใบ #157)
      const มีแถว = { กาล: !!ควร.กาล, ศัพท์: ควร.ที่มา.length > 0 }
      for (const ช of ชนิดที่มา) {
        const ข = บน.ไอ[ช.ชนิด]
        if (!มีแถว[ช.ชนิด]) {
          if (ข.ปุ่ม) ตก.push(`${ที่} ⇒ ${ช.ข้อ} มีปุ่ม ⓘ ของที่มา${ช.ชนิด} ⛔ ทั้งที่ไม่มีที่มาให้กาง`)
          continue
        }
        if (ข.ที่มาเห็น) ตก.push(`${ที่} ⇒ ${ช.ข้อ} ที่มาของความหมาย${ช.ชนิด}กางอยู่ตั้งแต่การ์ดขึ้น ⛔ ต้องซ่อนจนกด ⓘ`)
        const ป = ข.ปุ่ม
        if (!ป) {
          ตก.push(`${ที่} ⇒ ${ช.ข้อ} ⛔ ไม่มีปุ่ม ⓘ ของที่มา${ช.ชนิด}`)
          continue
        }
        if (ป.จำนวน !== 1) ตก.push(`${ที่} ⇒ ${ช.ข้อ} ปุ่ม ⓘ ของที่มา${ช.ชนิด}มี ${ป.จำนวน} ตัว ⛔ ควรมีตัวเดียวต่อการ์ด`)
        if (ป.แท็ก !== 'button') ตก.push(`${ที่} ⇒ ${ช.ข้อ} ปุ่ม ⓘ ของที่มา${ช.ชนิด}เป็น <${ป.แท็ก}> ⛔ ไม่ใช่ปุ่มจริง`)
        if (!ป.อยู่แถว) ตก.push(`${ที่} ⇒ ${ช.ข้อ} ปุ่ม ⓘ ของที่มา${ช.ชนิด} ⛔ ไม่ได้อยู่แถว *${ช.ชื่อ}*`)
        if (ป.ชื่อ !== ช.ชื่อ) ตก.push(`${ที่} ⇒ ${ช.ข้อ} ชื่อที่หูได้ยินของปุ่ม ⓘ เป็น «${ป.ชื่อ}» ⛔ ควรเป็นชื่อแถวเดิม «${ช.ชื่อ}»`)
        if (ป.กาง !== 'false') ตก.push(`${ที่} ⇒ ${ช.ข้อ} ปุ่ม ⓘ ของที่มา${ช.ชนิด}ตอนการ์ดเพิ่งขึ้นมี aria-expanded «${ป.กาง}» ⛔ ควรเป็น false`)
        if (!ป.คุม || ป.คุม !== ข.ที่มาid) ตก.push(`${ที่} ⇒ ${ช.ข้อ} ปุ่ม ⓘ aria-controls «${ป.คุม}» ⛔ ไม่ได้ชี้ที่มา «${ข.ที่มาid}»`)
        if (ป.กว้าง < เป้า - 0.5 || ป.สูง < เป้า - 0.5)
          ตก.push(`${ที่} ⇒ ${ช.ข้อ} ปุ่ม ⓘ ของที่มา${ช.ชนิด}กล่องกด ${Math.round(ป.กว้าง)}×${Math.round(ป.สูง)} จุด ⛔ เล็กกว่า ${เป้า}`)
      }

      // ---------------------------------------------------------------- ⑤ บรรทัดสัญญา ⛔ ซ่อน (ใบ #157 ข้อ 7.3)
      for (const [ชนิด, รายการ] of Object.entries(บน.สัญญา)) {
        if (รายการ.length) เจอสัญญา.add(ชนิด)
        for (const x of รายการ) if (!x.เห็น) ตก.push(`${ที่} ⇒ ⑤ บรรทัดสัญญา ${ชนิด} «${x.ข้อความ}» ⛔ ตาเห็นตอนการ์ดขึ้น ⇒ บรรทัดสัญญาต้องขึ้นเหมือนเดิม`)
      }
      if (!บน.สัญญา.MACULA.length) ตก.push(`${ที่} ⇒ ⑤ ⛔ มีบรรทัดสัญญา MACULA ใต้ตารางข้อมูลคำ`)

      // ---------------------------------------------------------------- ③ โปรแกรมอ่านหน้าจอได้ยิน (ตอนพับ)
      const ต้นไม้ = (await แท็บ.locator('[data-การ์ดคำ]').ariaSnapshot()).replace(/\s+/g, ' ')
      const ต้องได้ยิน = ควร.ศัพท์.map((ศ) => ศ.อธิบาย?.ความหมาย ?? '')
      for (const ข of ต้องได้ยิน)
        if (ข && !ต้นไม้.includes(ข)) ตก.push(`${ที่} ⇒ ③ โปรแกรมอ่านหน้าจอ ⛔ ไม่ได้ยิน «${ข.slice(0, 40)}…»`)
      const ที่มาที่ซ่อน = [...ควร.ที่มา, ...(ควร.กาล ? [ที่มาถ้อยคำ] : [])]
      for (const ข of ที่มาที่ซ่อน)
        if (ต้นไม้.includes(ข)) ตก.push(`${ที่} ⇒ ③ โปรแกรมอ่านหน้าจอได้ยินที่มา «${ข.slice(0, 40)}…» ตั้งแต่การ์ดขึ้น ⛔ ต้องซ่อนจนกด ⓘ`)

      // ---------------------------------------------------------------- ④ ไม่ล้นด้านข้าง (ตอนพับ)
      const ล้น = (x, ตอน) => {
        if (x.ล้นหน้า > 1 || x.ล้นการ์ด > 1 || x.ตัวที่ล้น.length)
          ตก.push(`${ที่} ⇒ ④ ล้นด้านข้าง${ตอน} ⇒ หน้า ${x.ล้นหน้า} จุด · การ์ด ${x.ล้นการ์ด} จุด · ${x.ตัวที่ล้น.join(' | ') || '-'}`)
      }
      ล้น(บน, '')
      if (บน.ช่องศัพท์em !== null && บน.ช่องศัพท์em < 8)
        ตก.push(`${ที่} ⇒ ④ ช่องคำอธิบายศัพท์กว้างแค่ ${บน.ช่องศัพท์em.toFixed(1)} ตัวอักษร ⇒ ⛔ แคบจนคำแตกทีละพยางค์`)

      // ---------------------------------------------------------------- ① ② ③ ④ กด ⓘ ด้วยแป้น ⇒ กาง ⇒ เห็น ⇒ ได้ยิน ⇒ ตัวหนังสือเท่าเดิม
      const กดแล้ว = []
      for (const ช of ชนิดที่มา) {
        if (!มีแถว[ช.ชนิด] || !บน.ไอ[ช.ชนิด].ปุ่ม) continue
        const ปุ่ม = แท็บ.locator(`[data-การ์ดคำ] ${ช.ปุ่ม}`)
        await ปุ่ม.focus()
        await แท็บ.keyboard.press('Enter')
        const ได้ = await แท็บ
          .waitForFunction((s) => document.querySelector(`[data-การ์ดคำ] ${s}`)?.getAttribute('aria-expanded') === 'true', ช.ปุ่ม, { timeout: 5000 })
          .then(() => true)
          .catch(() => false)
        if (!ได้) ตก.push(`${ที่} ⇒ ${ช.ข้อ} กด Enter ที่ปุ่ม ⓘ ของที่มา${ช.ชนิด}แล้ว aria-expanded ⛔ ไม่เป็น true`)
        กดแล้ว.push(ช)
      }
      if (กดแล้ว.length) {
        const กาง = await อ่านการ์ด(แท็บ)
        for (const ช of กดแล้ว)
          if (!กาง.ไอ[ช.ชนิด].ที่มาเห็น) ตก.push(`${ที่} ⇒ ${ช.ข้อ} กด ⓘ แล้วที่มาของความหมาย${ช.ชนิด} ⛔ ไม่ขึ้นให้ตาเห็น`)
        if (ควร.กาล && กาง.ที่มากาล !== ที่มาถ้อยคำ) ตก.push(`${ที่} ⇒ ① กด ⓘ แล้วที่มาของความหมายกาลเป็น «${กาง.ที่มากาล}» ⛔ ควรเป็น «${ที่มาถ้อยคำ}»`)
        const ที่มาบนกาง = กาง.ศัพท์.filter((x) => x.ที่มา).map((x) => x.ข้อความ)
        if (JSON.stringify(ที่มาบนกาง) !== JSON.stringify(ควร.ที่มา))
          ตก.push(`${ที่} ⇒ ② กด ⓘ แล้วที่มาของคำอธิบายศัพท์เป็น ${JSON.stringify(ที่มาบนกาง)} ⛔ ควรเป็น ${JSON.stringify(ควร.ที่มา)}`)
        const ต้นไม้กาง = (await แท็บ.locator('[data-การ์ดคำ]').ariaSnapshot()).replace(/\s+/g, ' ')
        for (const ข of ที่มาที่ซ่อน)
          if (!ต้นไม้กาง.includes(ข)) ตก.push(`${ที่} ⇒ ③ กด ⓘ แล้วโปรแกรมอ่านหน้าจอ ⛔ ไม่ได้ยินที่มา «${ข.slice(0, 40)}…»`)
        ล้น(กาง, 'ตอนกางที่มา')
        // ⭐ กดอีกครั้ง ⇒ พับกลับ
        for (const ช of กดแล้ว) {
          await แท็บ.locator(`[data-การ์ดคำ] ${ช.ปุ่ม}`).press('Enter')
          const พับ = await แท็บ
            .waitForFunction(
              ([ป, ท]) => {
                const ก = document.querySelector('[data-การ์ดคำ]')
                return ก?.querySelector(ป)?.getAttribute('aria-expanded') === 'false' && !ก.querySelector(ท)?.checkVisibility()
              },
              [ช.ปุ่ม, ช.ที่มา],
              { timeout: 5000 },
            )
            .then(() => true)
            .catch(() => false)
          if (!พับ) ตก.push(`${ที่} ⇒ ${ช.ข้อ} กด ⓘ ของที่มา${ช.ชนิด}ครั้งที่ 2 แล้วที่มา ⛔ ไม่พับกลับ`)
        }
      }
    }
    // ⭐ ⑤ ต้องได้ตรวจจริงทั้ง 3 ชนิด ⇒ คำที่กดชุดนี้มีเครื่องหมาย LGNTDF อย่างน้อยหนึ่งคำ ⇒ ⛔ เจอ = ตรวจไม่ได้
    if (!พัง) for (const ชนิด of ['MACULA', 'พจนานุกรม', 'LGNTDF']) if (!เจอสัญญา.has(ชนิด)) ตก.push(`${ชื่อ} ⇒ ⑤ ⛔ เจอบรรทัดสัญญา ${ชนิด} เลยสักคำ ⇒ ตรวจไม่ได้`)
    if (!พัง) console.log(`   ${ชื่อ} ⇒ กด ${คำที่กด.length} คำ`)
  } catch (e) {
    ตก.push(`${ชื่อ} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message.split('\n')[0]}`)
  } finally {
    await ctx.close()
  }
  return ตก
}

