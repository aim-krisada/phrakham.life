/** ของที่ควรเห็นบนการ์ด ⇒ จากไฟล์ที่เว็บส่งจริง ⇒ ตัวแปลกับตารางตัวเดียวกับการ์ด */
function ที่ควรเห็น(รูปผัน) {
  const กาล = กาลจากรูปผัน(รูปผัน)
  const ศัพท์ = แปลรูปผัน(รูปผัน, 'grc')
    .ศัพท์.map((ศ) => ({ ...ศ, อธิบาย: อธิบายศัพท์(ศ.ชุด, ศ.รหัส) }))
    // ⭐ ประโยคคำสั่งขึ้นในแถวกาลแล้ว ⇒ แถวศัพท์ ⛔ ไม่ขึ้นซ้ำ (หัวไฟล์ `ศัพท์ไวยากรณ์.ts`)
    .filter((ศ) => !(กาล?.คำสั่ง && ศ.อธิบาย?.ความหมาย === ความหมายคำสั่ง))
  return { กาล, ศัพท์, ที่มา: [...new Set(ศัพท์.map((ศ) => ศ.อธิบาย?.ที่มา).filter(Boolean))] }
}

