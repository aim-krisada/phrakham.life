def เลือกที่ตรงที่สุด(ตัวเลือก, ยิงกฎทุกข้อ, ลำดับ):
    """คืน (รหัสความหมาย, ชื่อกฎ) ของตัวเลือกที่เข้ากฎแข็งที่สุด ⇒ ไม่มีเลยคืนค่าว่าง

    เสมอกันให้ตัวที่มาก่อนชนะ ⇒ ผลจึงคงที่ ใครรันซ้ำก็ได้เท่าเดิม
    """
    อันดับดีสุด, รหัสดีสุด, กฎดีสุด = len(ลำดับ), '', ''
    for รหัส in ตัวเลือก:
        ผล = next(ยิงกฎทุกข้อ(รหัส), None)   # คายมาเรียงแข็งไปอ่อนแล้ว ⇒ ข้อแรกคือข้อแข็งสุด
        if not ผล: continue
        อันดับ = ลำดับ.index(ผล)
        if อันดับ < อันดับดีสุด:
            อันดับดีสุด, รหัสดีสุด, กฎดีสุด = อันดับ, รหัส, ผล
            if อันดับ == 0: break          # แข็งสุดแล้ว ⇒ ไม่มีอะไรดีกว่านี้
    return รหัสดีสุด, กฎดีสุด

