def ทีละบท(path):
    """ไล่ไฟล์ทีเดียวจบ คายออกมาเป็นบท ๆ ⇒ ⛔ ไม่อมทั้งไฟล์ไว้ในเครื่องพร้อมกัน

    ปลอดภัยเพราะไฟล์ต้นฉบับเรียงตามที่อยู่มาแล้ว และกฎเทียบดูได้ไกลสุดแค่ในคำเดียวกัน
    """
    กอง = []; คีย์ = None
    with open(path, encoding='utf-8') as f:
        for r in csv.DictReader(f, delimiter='\t'):
            ref = (r['ref'] or '').strip()
            if not ref or ' ' not in ref or ':' not in ref: continue
            k = เล่มบทของ(ref)
            if คีย์ is not None and k != คีย์:
                yield คีย์, กอง; กอง = []
            คีย์ = k; กอง.append(r)
    if กอง: yield คีย์, กอง

