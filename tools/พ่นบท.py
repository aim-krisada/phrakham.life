def โหลดหน่วยจับคู่(path):
    """อ่านตารางของ MACULA เป็น **หน่วยจับคู่** ⇒ คืน (xml:id → หน่วย)

    หน่วยหนึ่งคือ (รายชื่อชิ้นมาคูลา, รายชื่อรหัสมาร์เบิล) ⇒ ชิ้นทุกชิ้นในหน่วยชี้ไปที่หน่วยเดียวกัน
    """
    หน่วยของชิ้น = {}
    with open(path, encoding='utf-8') as f:
        next(f)
        for line in f:
            a, b = line.rstrip().split('\t')
            หน่วย = (tuple(a.split()), tuple(b.split()))
            for x in หน่วย[0]: หน่วยของชิ้น[x] = หน่วย
    return หน่วยของชิ้น

