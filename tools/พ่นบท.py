# ───────────────────────── กฎที่ใช้ตัดสินว่าชี้ถูกคำ ─────────────────────────
# ⭐ **คายชื่อกฎ *ทุกข้อ* ที่ตัวเลือกนั้นเข้า** เรียงจากแข็งไปอ่อน ⛔ ไม่ใช่ข้อแรกแล้วหยุด
#
# **ของที่พังจริง** (คนตรวจใบ #81 ทัก · 7 ก.ย. 2569) — เดิมสองฟังก์ชันนี้คืนชื่อกฎข้อแรกที่เข้าแล้วหยุด
