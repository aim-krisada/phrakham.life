def ขอรายการสถานะ(ฐานapi: str, โปรเจกต์: str, sha: str, กุญแจงาน: str) -> list:
    """ถามรายการ commit statuses ⇒ คืนลิสต์ ⇒ อ่านไม่ได้ให้โยนออกไปพร้อมคำของเซิร์ฟเวอร์"""
    ที่อยู่ = f"{ฐานapi}/projects/{urllib.parse.quote(str(โปรเจกต์), safe='')}/repository/commits/{sha}/statuses?per_page=100"
    คำขอ = urllib.request.Request(ที่อยู่, headers={"JOB-TOKEN": กุญแจงาน} if กุญแจงาน else {})
    try:
        with urllib.request.urlopen(คำขอ, timeout=30) as ผล:
            return json.loads(ผล.read().decode())
    except urllib.error.HTTPError as เหตุ:
        เนื้อ = เหตุ.read().decode(errors="replace")[:300]
        raise SystemExit(
            f"⛔ อ่านรายการสถานะของคอมมิตไม่ได้ ⇒ กิตแล็บตอบ {เหตุ.code}\n"
            f"   ⇒ ที่อยู่ที่ยิง: {ที่อยู่}\n"
            f"   ⇒ คำของเซิร์ฟเวอร์: {เนื้อ}\n"
            "   ⇒ ⛔ อย่าตั้งตัวแปรกุญแจขึ้นมาเอง ⇒ เอาเรื่องนี้ไปให้เจ้าของงานตัดสิน"
        )


def ตัดสิน(รายการ: list, เลขท่อ: int) -> tuple[str, str]:
    """คืน (คำตัดสิน, ข้อความ) ⇒ คำตัดสินเป็น 'ขึ้นแล้ว' · 'ยังไม่รู้' · 'ไม่ได้วาง' · 'ไม่ขึ้น'

    ⭐ ฟังก์ชันนี้ **⛔ ไม่แตะเน็ตเลย** ⇒ `--ทดสอบตัวเอง` จึงพิสูจน์มันได้โดย ⛔ ไม่ต้องมีเซิร์ฟเวอร์
    """
    ของท่อนี้ = [ส for ส in รายการ if ส.get("pipeline_id") == เลขท่อ]
    วาง = sorted(
        [ส for ส in ของท่อนี้ if ส.get("name") == "pages:deploy"], key=lambda ส: ส.get("id", 0)
    )
    if วาง:
        ล่าสุด = วาง[-1]
        สถานะ = str(ล่าสุด.get("status"))
        เหตุ = ล่าสุด.get("description") or "(กิตแล็บ ⛔ ไม่ได้เขียนเหตุผลมาด้วย)"
        if สถานะ in ยังไม่จบ:
            return "ยังไม่รู้", f"`pages:deploy` ยังเป็น `{สถานะ}`"
        if สถานะ == "success":
            return "ขึ้นแล้ว", f"`pages:deploy` = `success` เมื่อ {ล่าสุด.get('finished_at')}"
        # ⛔ ⛔ ไม่แปลสาเหตุ ⇒ วางคำของกิตแล็บลงไปทั้งบรรทัด
        return "ไม่ขึ้น", f"`pages:deploy` = `{สถานะ}` ⇒ กิตแล็บบอกว่า: {เหตุ}"

    งานpages = [ส for ส in ของท่อนี้ if ส.get("name") == "pages"]
    if งานpages and str(งานpages[-1].get("status")) in ไม่ได้วาง:
        return "ไม่ได้วาง", f"งาน `pages` เป็น `{งานpages[-1].get('status')}` ⇒ รอบนี้ ⛔ ไม่ได้ตั้งใจวางเว็บ"
    return "ยังไม่รู้", "ยัง ⛔ ไม่เห็นรายการ `pages:deploy` ของท่อนี้"


def ตรวจ(ฐานapi, โปรเจกต์, sha, เลขท่อ, กุญแจงาน, นานสุด=300, ทุกกี่วิ=5) -> int:
    print(f"ถามถึงคอมมิต {sha} ของท่อ {เลขท่อ}")
    เริ่ม = time.monotonic()
    while True:
        รายการ = ขอรายการสถานะ(ฐานapi, โปรเจกต์, sha, กุญแจงาน)
        คำตัดสิน, ข้อความ = ตัดสิน(รายการ, เลขท่อ)
        if คำตัดสิน == "ขึ้นแล้ว":
            print(f"✅ เว็บขึ้นจริง ⇒ {ข้อความ}")
            return 0
        if คำตัดสิน == "ไม่ได้วาง":
            print(f"⏭ ข้ามไปเงียบ ๆ ⇒ {ข้อความ}")
            return 0
        if คำตัดสิน == "ไม่ขึ้น":
            print(f"\n⛔ ของรอบนี้ ⛔ ไม่ได้ขึ้นเว็บ ⇒ {ข้อความ}")
            return 1
        ผ่านไป = time.monotonic() - เริ่ม
        if ผ่านไป >= นานสุด:
            # ⭐ เงียบ ⛔ ไม่ใช่ผ่าน
            print(f"\n⛔ รอจนครบ {นานสุด} วินาทีแล้วยังตอบไม่ได้ ⇒ {ข้อความ}")
            return 1
        print(f"   …{ข้อความ} ⇒ ถามใหม่อีกใน {ทุกกี่วิ} วินาที (ผ่านไป {ผ่านไป:.0f}/{นานสุด})")
        time.sleep(ทุกกี่วิ)


