def หลัก() -> int:
    ต = argparse.ArgumentParser(add_help=True)
    ต.add_argument("--ทดสอบตัวเอง", action="store_true")
    ต.add_argument("--คอมมิต", default=os.environ.get("CI_COMMIT_SHA", ""))
    ต.add_argument("--ท่อ", default=os.environ.get("CI_PIPELINE_ID", ""))
    ต.add_argument("--นานสุด", type=int, default=300)
    ต.add_argument("--ต้องแดง", action="store_true", help="สลับผล ⇒ ใช้ตอนยิงไปที่ของที่รู้อยู่แล้วว่าพัง")
    ค = ต.parse_args()

    if ค.ทดสอบตัวเอง:
        return ทดสอบตัวเอง()

    ฐานapi = os.environ.get("CI_API_V4_URL", "")
    โปรเจกต์ = os.environ.get("CI_PROJECT_ID", "")
    กุญแจงาน = os.environ.get("CI_JOB_TOKEN", "")
    if not (ฐานapi and โปรเจกต์ and ค.คอมมิต and ค.ท่อ):
        print("⛔ ขาดของที่ต้องใช้ ⇒ ต้องมี CI_API_V4_URL · CI_PROJECT_ID · คอมมิต · ท่อ")
        return 1
    if len(ค.คอมมิต) != 40:
        print(f"⛔ ต้องเป็น sha เต็ม 40 ตัว ⇒ เลขย่อคืนรายการเปล่า ⇒ ที่ได้มาคือ '{ค.คอมมิต}'")
        return 1

