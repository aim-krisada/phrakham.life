    ตามบท = collections.defaultdict(list)
    for r in แถวทั้งหมด: ตามบท[(r['ฝั่ง'], r['เล่ม'], r['บท'])].append(r)
    for ฝั่ง, n in จำนวนต่อฝั่ง.items():
        คีย์ = [k for k in ตามบท if k[0] == ฝั่ง and len(ตามบท[k]) >= 30]
        สุ่ม.shuffle(คีย์)
        for k in คีย์:
            แถวในบท = ตามบท[k]; r = สุ่ม.choice(แถวในบท)
            ของเรา = คลัง[ฝั่ง][r['รหัสความหมาย']]
            ห = หมวดของ(ของเรา)
            if not ห: continue
            อื่น = []
            for x in แถวในบท:
                if x['คำในพจนานุกรม'] == r['คำในพจนานุกรม']: continue
                for s in ชั้นของคำ[ฝั่ง][x['คำในพจนานุกรม']]:
                    if s in อื่น or (หมวดของ(คลัง[ฝั่ง][s]) & ห) or not หมวดของ(คลัง[ฝั่ง][s]):
                        continue
                    if ใกล้กันเกินไป(ของเรา, คลัง[ฝั่ง][s]): continue
                    อื่น.append(s)
            if len(อื่น) < ตัวเลือกสูงสุด: continue
            ออก.append(ทำข้อ(สุ่ม, r, 'ง ยกชั้นของคำอื่นมาปน',
                            สุ่ม.sample(อื่น, ตัวเลือกสูงสุด), None, คลัง[ฝั่ง]))
            if sum(1 for x in ออก if x['ฝั่ง'] == ฝั่ง) >= n: break
    return ออก


