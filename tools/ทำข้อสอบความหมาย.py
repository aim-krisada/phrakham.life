def นิยามอ่านออก(t):
    """ตัดเครื่องหมายของ UBS ออก ⇒ `{L:Jesse<SDBH:יִשַׁי>}` เหลือ `Jesse`

    **ทำไมต้องล้าง** ⇒ เครื่องหมายพวกนี้เป็นภาษาเครื่องของ UBS ⇒ ตัวตรวจอ่านไม่รู้เรื่อง
    และมันบอกใบ้ว่าตัวเลือกมาจากเล่มไหน ⇒ เป็นช่องให้เดาใจเรา
    """
    t = re.sub(r'\{[A-Z]:([^<>{}]*?)(?:<[^<>]*>)?\}', r'\1', t or '')
    t = re.sub(r'<[^<>]*>', '', t)
    for ก in '►◄≈':
        t = t.replace(ก, '·')
    return re.sub(r'\s+', ' ', t.replace('=', '')).strip(' ·').strip()


