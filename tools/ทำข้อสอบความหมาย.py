def ใกล้กันเกินไป(ก1, ก2, เพดานคำแปล=0.7, เพดานนิยาม=0.6):
    """ความหมายสองชั้นนี้ใกล้กันเกินจะเอามาเป็นตัวลวงไหม

    ⚠️ **ทำไมต้องมี** ⇒ เทียบคำแปลแบบตรงตัวไม่พอ ⇒ `women` กับ `woman, wife` ไม่ตรงกัน
    เป็นตัวอักษร แต่ความหมายอันเดียวกัน ⇒ เอามาเป็นตัวลวงแล้วคำตอบ *ไม่มีอันไหนเข้า*
    จะกลายเป็นคำตอบที่ผิด ⇒ เราจะไปนับว่าตัวตรวจตอบผิดทั้งที่มันตอบถูก
    ⇒ จึงวัดความคล้ายของตัวอักษรแทน (เจอจริงตอนตรวจข้อสอบรอบแรกด้วยตา 4 ก.ย. 2569)
    ⛔ ตัวกรองนี้จับคำพ้องที่เขียนไม่เหมือนกันไม่ได้ เช่น `to know` กับ `to understand`
       ⇒ ต้องอ่านข้อสอบด้วยตาอีกชั้น
    """
    for a in แปลสั้นของ(ก1):
        for b in แปลสั้นของ(ก2):
            if a in b or b in a or เหมือนกันแค่ไหน(a, b) >= เพดานคำแปล: return True
    น1, น2 = นิยามอ่านออก(ก1.get('นิยาม')).lower(), นิยามอ่านออก(ก2.get('นิยาม')).lower()
    return bool(น1 and น2 and เหมือนกันแค่ไหน(น1, น2) >= เพดานนิยาม)


