def ก้าว2(สุ่ม, แถวทั้งหมด, คลัง, ชั้นของคำ, เป้า, พื้น=12):
    """แบ่งชั้นตาม (ฝั่ง × กฎที่ใช้ชี้ว่าถูกคำ) ⇒ ทุกชั้นได้อย่างน้อย `พื้น` ตัว

    **ทำไมต้องมีพื้น** ⇒ ใบ #49 อยากรู้ว่ากฎที่ช่วยได้น้อย ผิดเยอะไหม
    ⇒ แต่กฎเล็กสุดกินแค่ 0.025% ของกอง ⇒ **สุ่มตามสัดส่วนล้วน ๆ จะได้ 0 ตัว** ⇒ ตอบคำถามนั้นไม่ได้
    ⇒ จึงยกพื้นให้ทุกชั้น แล้วที่เหลือแบ่งตามสัดส่วน
    ⚠️ **พอไม่ได้สุ่มตามสัดส่วนแล้ว ห้ามเอาผลมาเฉลี่ยรวมดื้อ ๆ**
       ⇒ ต้องถ่วงน้ำหนักด้วยขนาดจริงของแต่ละชั้น (ดู `นับผลความหมาย.py`)
       ⛔ เฉลี่ยดิบจะให้น้ำหนักกฎเล็กเกินจริงหลายพันเท่า

    ⏸ ใบเขียนไว้ว่ากฎที่ช่วยน้อยกว่า 100 ครั้งให้ตรวจทุกตัว
       ⇒ **ของจริงไม่มีชั้นไหนต่ำกว่า 100** เล็กสุดคือ 105 ⇒ ข้อนั้นจึงไม่ได้ใช้
    """
    ชั้น = collections.defaultdict(list)
    for r in แถวทั้งหมด: ชั้น[(r['ฝั่ง'], r['ชี้ถูกคำเพราะ'])].append(r)
    ทั้งหมด = sum(len(v) for v in ชั้น.values())
    เลือก = []
    แผน = {}
    for k, v in sorted(ชั้น.items(), key=lambda kv: -len(kv[1])):
        ตามสัดส่วน = round(เป้า * len(v) / ทั้งหมด)
        n = min(len(v), max(พื้น, ตามสัดส่วน))
        เลือก += สุ่ม.sample(v, n)
        แผน['%s · %s' % k] = {
            'ทั้งกอง': len(v), 'สุ่มมา': n,
            'น้ำหนักของชั้น': len(v) / ทั้งหมด,
            'เหตุ': 'สุ่มตามสัดส่วน' if ตามสัดส่วน >= พื้น else 'ยกให้ถึงพื้น %d ตัว' % พื้น}
    ออก = []
    for r in เลือก:
        ฝั่ง = r['ฝั่ง']
        พี่น้อง = [x for x in ชั้นของคำ[ฝั่ง][r['คำในพจนานุกรม']] if x != r['รหัสความหมาย']]
        ล = [r['รหัสความหมาย']] + สุ่ม.sample(พี่น้อง, min(ตัวเลือกสูงสุด - 1, len(พี่น้อง)))
        ออก.append(ทำข้อ(สุ่ม, r, 'จริง', ล, r['รหัสความหมาย'], คลัง[ฝั่ง]))
    return ออก, แผน


