#!/usr/bin/env python3
"""อ่านรายชื่อ "ช่องที่เจ้าของไม่ให้เผยแพร่" จากที่เดียวที่เป็นเจ้าของ

⭐ **เจ้าของความจริงคือ `docs/บันทึก-แหล่งข้อมูล.md` หัวข้อ ③** ⛔ ไม่มีสำเนาที่อื่น
⇒ ⛔ **ห้ามพิมพ์ชื่อช่องซ้ำในสคริปต์ไหนทั้งสิ้น** — พิมพ์ซ้ำแล้วเจ้าของแก้ สำเนาจะค้าง
   แล้วกลายเป็นด่านที่บอกว่าผ่าน ทั้งที่ปล่อยของต้องห้ามหลุดไปแล้ว

**ใครใช้** ⇒ `tools/สร้างข้อมูลเว็บ.py` ใช้ตัดทิ้งตอนอ่าน · `tools/ด่านข้อมูลต้องห้าม.py` ใช้ตรวจซ้ำ
⇒ ⭐ **สองตัวอ่านจากที่เดียวกัน** ⇒ ตัวแปลงพลาด ด่านจับได้ ⛔ ไม่ใช่พลาดเหมือนกันทั้งคู่

**กันตัวอ่านเพี้ยนอย่างไร** ⇒ หัวข้อนั้นเขียนจำนวนช่องไว้เองว่ามีกี่ช่อง
⇒ อ่านได้ไม่เท่ากับที่เขาเขียน = **โยนข้อผิดพลาดทันที** ⛔ ไม่เดาต่อ
"""

import re
from pathlib import Path

บันทึก = Path(__file__).resolve().parent.parent / "docs" / "บันทึก-แหล่งข้อมูล.md"

หัวข้อสาม = re.compile(r"^## ③")
หัวข้อถัดไป = re.compile(r"^#{2,3} ")
ในเครื่องหมาย = re.compile(r"`([^`]+)`")
# ก้อนที่มีนามสกุลไฟล์ ⛔ ไม่ใช่ชื่อช่อง ⇒ หัวข้อนั้นมีชื่อไฟล์ PDF อยู่แถวหนึ่ง
เป็นชื่อไฟล์ = re.compile(r"[/\\]|\.[A-Za-z0-9]{1,6}$")
บอกจำนวน = re.compile(r"ห้ามจริง\s*(\d+)\s*ช่อง")


class อ่านไม่ออก(Exception):
    """หัวข้อ ③ เปลี่ยนรูปจนอ่านไม่ได้ ⇒ ⛔ หยุด ห้ามเดา"""


def เนื้อหัวข้อสาม(ไฟล์=None):
    """คืนบรรทัดของหัวข้อ ③ ตั้งแต่หัวข้อ จนถึงหัวข้อถัดไป

    ⛔ หยุดที่หัวข้อย่อยตัวแรก — ใต้นั้นเป็นตารางของเรื่อง *เราเลือกไม่เอา*
       ซึ่ง **คนละเรื่องกับสัญญาห้าม** ⇒ ลากมาด้วยเมื่อไร ด่านจะแดงใส่ของที่ไม่ได้ห้าม
    """
    p = Path(ไฟล์) if ไฟล์ else บันทึก
    บรรทัด, เก็บ, เริ่ม = p.read_text(encoding="utf-8").splitlines(), [], False
    for บ in บรรทัด:
        if หัวข้อสาม.match(บ):
            เริ่ม = True
            continue
        if เริ่ม:
            if หัวข้อถัดไป.match(บ):
                break
            เก็บ.append(บ)
    if not เริ่ม:
        raise อ่านไม่ออก(f"หาหัวข้อ ③ ใน {p} ไม่เจอ")
    return เก็บ


def อ่านรายชื่อ(ไฟล์=None):
    """คืนชื่อช่องที่ห้ามเผยแพร่ เรียงตามตัวอักษร"""
    เก็บ = เนื้อหัวข้อสาม(ไฟล์)
    ช่อง, จำนวนที่เขาเขียน = [], None
    for บ in เก็บ:
        ที่ = บ.strip()
        m = บอกจำนวน.search(ที่)
        if m:
            จำนวนที่เขาเขียน = int(m.group(1))
        if not ที่.startswith("|") or set(ที่) <= set("|- "):
            continue
        ช่องในแถว = [c.strip() for c in ที่.strip("|").split("|")]
        if len(ช่องในแถว) < 2 or ช่องในแถว[1] == "ช่อง":
            continue                       # แถวหัวตาราง
        for ก้อน in ในเครื่องหมาย.findall(ช่องในแถว[1]):
            ก้อน = ก้อน.strip()
            if ก้อน and not เป็นชื่อไฟล์.search(ก้อน) and ก้อน not in ช่อง:
                ช่อง.append(ก้อน)
    if จำนวนที่เขาเขียน is None:
        raise อ่านไม่ออก("หัวข้อ ③ ไม่ได้เขียนไว้ว่าห้ามจริงกี่ช่อง ⇒ ตรวจตัวอ่านไม่ได้")
    if len(ช่อง) != จำนวนที่เขาเขียน:
        raise อ่านไม่ออก(
            f"อ่านได้ {len(ช่อง)} ช่อง ⇒ {ช่อง} "
            f"แต่หัวข้อ ③ เขียนเองว่าห้ามจริง {จำนวนที่เขาเขียน} ช่อง ⇒ ⛔ ตัวอ่านกับเอกสารไม่ตรงกัน")
    return sorted(ช่อง)


if __name__ == "__main__":
    for c in อ่านรายชื่อ():
        print(c)
