def ไม่มีเครื่องหมายเสียง(s):
    """ตัดเครื่องหมายเสียงออก ⇒ ใช้ตอนเทียบว่าต่างกันแค่เครื่องหมายหรือเปล่า"""
    ย = unicodedata.normalize("NFD", s or "")
    return "".join(c for c in ย if not unicodedata.combining(c)).lower()


def รูปเดียวกัน(s):
    return unicodedata.normalize("NFC", s or "")


def พิมพ์ตาราง(หัวข้อ, นับ, หน่วย, ทศนิยม=1):
    รวม = sum(นับ.values())
    print(f"\n=== {หัวข้อ} ===")
    for k, n in นับ.most_common():
        print(f"  {k:52s}{n:8d}  {100 * n / รวม:5.{ทศนิยม}f}%")
    print(f"  {'รวม ' + หน่วย:52s}{รวม:8d}")


def อ่านช่อง(ไฟล์, ชื่อช่อง):
    """คืนค่าทีละแถวเฉพาะช่องที่ขอ ⇒ ไม่โหลดทั้งตารางเข้าหน่วยความจำ"""
    with io.open(ไฟล์, encoding="utf-8") as f:
        r = csv.reader(f, delimiter="\t")
        หัว = next(r)
        ดัชนี = [หัว.index(c) for c in ชื่อช่อง]
        for row in r:
            if len(row) > max(ดัชนี):
                yield [row[i] for i in ดัชนี]


def ทะเบียนความหมาย(ไฟล์):
    """คืน lemma -> รายการความหมายเรียงตามลำดับที่อยู่ในไฟล์"""
    d = json.load(io.open(ไฟล์, encoding="utf-8"))
    ท = collections.defaultdict(list)
    for e in d:
        for bf in e["BaseForms"] or []:
            for lm in bf["LEXMeanings"] or []:
                หมวด = [x["Domain"] for x in (lm["LEXDomains"] or [])]
                ย่อย = [x.get("Domain") for x in (lm["LEXSubDomains"] or [])]
                แกน = [x.get("Domain") for x in (lm["LEXCoreDomains"] or [])]
                ท[e["Lemma"]].append((lm["LEXID"], หมวด, ย่อย, แกน))
    return d, ท


def รหัสฮีบรู():
    """#02 เอารหัสศัพท์ไปเปิดพจนานุกรม #09 ⇒ ต่อติดกี่แถว"""
    s = io.open(ตารางแปลงรหัส, encoding="utf-8").read()
    แปลง = dict(re.findall(r'<w aug="([^"]+)">([^<]+)</w>', s))
    ฐาน = collections.defaultdict(list)
    for k in แปลง:
        m = re.fullmatch(r"(\d+)([a-z]?)", k)
        if m:
            ฐาน[m.group(1)].append(m.group(2))
    มีในStrong = set(
        re.findall(r'<entry id="H(\d+)">', io.open(พจนานุกรมStrongฮีบรู, encoding="utf-8").read())
    )
    print(f"ตารางแปลงรหัส AugIndex.xml มี {len(แปลง)} รายการ")

    นับ = collections.Counter()
    ตัวอย่าง = collections.defaultdict(set)
    for (รหัส,) in อ่านช่อง(ตารางฮีบรู, ["strongnumberx"]):
        if not รหัส:
            นับ["ช่องว่าง"] += 1
            continue
        m = re.fullmatch(r"0*(\d+)([a-z]?)", รหัส)
        if not m:
            นับ["รูปแบบแปลก มีสองรหัสในช่องเดียว"] += 1
            ตัวอย่าง["แปลก"].add(รหัส)
            continue
        เลข, อักษร = m.group(1), m.group(2)
        if เลข + อักษร in แปลง:
            นับ["ก ต่อได้ตรง"] += 1
        elif อักษร and เลข in แปลง:
            นับ["ข มีอักษรเกิน ถอยออกแล้วต่อได้"] += 1
        elif not อักษร and เลข in ฐาน:
            นับ["ค ไม่มีอักษร แต่ตารางมีหลายตัว ⇒ กำกวม"] += 1
            ตัวอย่าง["กำกวม"].add(รหัส)
        elif เลข in มีในStrong:
            นับ["ง ไม่มีใน BDB แต่มีในพจนานุกรม Strong"] += 1
        else:
            นับ["จ ไม่มีที่ไหนเลย"] += 1
            ตัวอย่าง["ไม่มี"].add(รหัส)
    พิมพ์ตาราง("จุดบรรจบ 1 — รหัสศัพท์ฮีบรู #02 ต่อพจนานุกรม #09", นับ, "แถว")
    for k in ("กำกวม", "ไม่มี", "แปลก"):
        if ตัวอย่าง[k]:
            print(f"  ตัวอย่าง {k}:", sorted(ตัวอย่าง[k])[:8])


def ความหมายฮีบรู():
    """#02 เดินผ่านตารางดัชนีของ #10 ไปหาความหมาย ⇒ ลำดับที่ดัชนีบอก ตรงกับพจนานุกรมไหม"""
    _, ท = ทะเบียนความหมาย(พจนานุกรมฮีบรู)
    นับ = collections.Counter()
    for e in json.load(io.open(ดัชนีสดุดี, encoding="utf-8")):
        for l in e["LexicalLinks"] or []:
            if not l.startswith("SDBH:"):
                นับ["ไม่ใช่ลิงก์พจนานุกรม"] += 1
                continue
            _, lemma, ลำดับ, หมวด = l.split(":", 3)
            รายการ = ท.get(lemma)
            if not รายการ:
                นับ["ไม่มีคำนี้ในพจนานุกรม"] += 1
                continue
            i = int(ลำดับ)
            if i >= len(รายการ):
                นับ["ลำดับเกินจำนวนความหมายที่มี"] += 1
                continue
            _, หลัก, ย่อย, แกน = รายการ[i]
            if หมวด in หลัก:
                นับ["ก ชื่อหมวดตรงกัน"] += 1
            elif หมวด in ย่อย:
                นับ["ข ตรงที่หมวดย่อย"] += 1
            elif หมวด in แกน:
                นับ["ค ตรงที่หมวดแกน"] += 1
            elif not any(หลัก + ย่อย + แกน):
                นับ["ง พจนานุกรมไม่มีชื่อหมวด ⇒ ตรวจไม่ได้"] += 1
            else:
                นับ["จ ชื่อหมวดไม่ตรงเลย"] += 1
    พิมพ์ตาราง("จุดบรรจบ 2 ฝั่งฮีบรู — ตารางดัชนี #10 (เฉพาะไฟล์สดุดี)", นับ, "ลิงก์")
    print("  ⚠ วัดจากไฟล์สดุดีไฟล์เดียว ⛔ ยังไม่ได้กวาดทั้ง 39 เล่ม")
    print("  ⚠ ชื่อหมวดตรง ⛔ ไม่ได้แปลว่าเป็นความหมายเดียวกันเสมอ")


