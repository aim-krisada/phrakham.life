def อ่านคำกรีก():
    """คืน ที่อยู่คำ -> [(รูปพจนานุกรม, รหัสศัพท์)] และลำดับเล่มตามที่ปรากฏในไฟล์"""
    คำ = {}
    ลำดับเล่ม = []
    for ที่อยู่, lemma, รหัส in อ่านช่อง(ตารางกรีก, ["ref", "lemma", "strong"]):
        เล่ม = ที่อยู่.split()[0]
        if เล่ม not in ลำดับเล่ม:
            ลำดับเล่ม.append(เล่ม)
        คำ.setdefault(ที่อยู่, []).append((รูปเดียวกัน(lemma), รหัส.lstrip("0")))
    return คำ, ลำดับเล่ม


