  // ⭐ ทุกคำ ⇒ เลขบนคำ = เลขที่คิดจากไฟล์ ⇒ คำที่ไม่มีเลข Strong ⇒ ⛔ มีเลข (ทางเศร้า เกณฑ์ข้อ 2.4)
  let เทียบได้ = 0
  const ต่าง = []
  for (const x of ทั้งหมด) {
    const รายการ = ควร?.get(x.ข้อ)
    if (!รายการ || x.ลำดับ < 0 || x.ลำดับ >= รายการ.length) continue
    เทียบได้++
    if ((x.เลข ?? '') !== รายการ[x.ลำดับ]) ต่าง.push(`${x.ข้อ} คำที่ ${x.ลำดับ + 1} "${x.คำแปล}" ⇒ บนคำ "${x.เลข ?? ''}" ⇒ ควร "${รายการ[x.ลำดับ]}"`)
  }
  if (ควร && เทียบได้ < ทั้งหมด.length * 0.9) ผิด.push(`② ${ชื่อ} ⇒ จับคู่คำบนหน้ากับไฟล์การ์ดได้แค่ ${เทียบได้} จาก ${ทั้งหมด.length} ปุ่ม ⇒ ด่านไม่ได้ตรวจ`)
  if (ต่าง.length) ผิด.push(`② ${ชื่อ} ⇒ เลขบนคำไม่ตรงกับเลขในไฟล์การ์ด ${ต่าง.length} คำ เช่น ${ต่าง[0]}`)
  const รูป = รูปเลข(ห.อักษร)
  const เพี้ยน = มี.filter((x) => !รูป.test(x.เลข))
  if (เพี้ยน.length) ผิด.push(`② ${ชื่อ} ⇒ เลข ${เพี้ยน.length} ตัวไม่ใช่รูป ${ห.อักษร}<เลข> เช่น ${เพี้ยน[0].ข้อ} "${เพี้ยน[0].คำแปล}" ⇒ "${เพี้ยน[0].เลข}"`)
