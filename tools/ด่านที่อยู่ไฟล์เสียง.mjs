// ④ **รายการที่มี `ฐานของฉบับ` แต่ขาดฉบับกับเล่มนี้ ⇒ ล้ม** ⛔ ไม่หล่นกลับไปใช้ `audio/` เงียบ ๆ
//   ⇒ เว็บที่ย้ายแล้วแต่บางเล่มยังชี้ `audio/` = กดฟังแล้วเงียบ เพราะตัวสร้างเว็บ ⛔ ไม่ได้คัดลอก mp3 แล้ว
//
// ⛔ `allow_failure` ⛔ ไม่ใส่ — แดงแปลว่า **วันที่ย้ายเสียง ผู้อ่านจะกดฟังแล้วเงียบ**
import { ดัชนีเสียงจากรายการ } from '../server/utils/เสียงของเล่ม.ts'
import { สร้างคิว } from '../app/utils/คิวเสียง.ts'

const ฐานเว็บ = '/phrakham/'
const ต่อฐานเว็บ = (ทาง) => ฐานเว็บ + ทาง.replace(/^\/+/, '')
const ที่ = (ฉบับ, กลุ่ม) => `https://aim-krisada.github.io/phrakham-audio-${ฉบับ}-${กลุ่ม}/`

/** รายการเสียงสมมติ ⇒ รูปเดียวกับที่ `tools/สร้างรายการเสียง.py` พ่น ⇒ มีแค่ช่องที่ตัวประกอบที่อยู่ใช้ */
function รายการ(ฐานของฉบับ) {
  const เล่ม = (osis) => ({ osis, บท: { 1: { 1: 5.1, 2: 4.2 } } })
  return {
    รุ่น: 2,
    ฐานที่อยู่: 'audio/',
    ...(ฐานของฉบับ ? { ฐานของฉบับ } : {}),
    ฉบับ: {
      TCV: { ทางย่อย: '', เล่ม: { MRK: เล่ม('Mark'), GEN: เล่ม('Gen'), PSA: เล่ม('Ps') } },
      LSV: { ทางย่อย: 'LSV/', เล่ม: { MRK: เล่ม('Mark') } },
    },
  }
}

const ย้ายแล้ว = {
  TCV: { MRK: ที่('tcv', 'nt'), GEN: ที่('tcv', 'ot1'), PSA: ที่('tcv', 'ot2') },
  LSV: { MRK: ที่('lsv', 'nt'), GEN: ที่('lsv', 'ot1'), PSA: ที่('lsv', 'ot2') },
}

/** ตัวประกอบที่อยู่ของจริง ⇒ ดัชนีของฉบับ ⇒ คิว ⇒ ที่อยู่ไฟล์ของข้อแรก */
const ของจริง = {
  ดัชนี: ดัชนีเสียงจากรายการ,
  คิว: สร้างคิว,
}

function ที่อยู่ข้อแรก(ตัว, ร, เล่ม, ฉบับ) {
  const ด = ตัว.ดัชนี(ร, เล่ม)?.[ฉบับ]
  if (!ด) return `(ไม่มีดัชนีของ ${ฉบับ})`
  const ผล = ตัว.คิว({
    รหัสเล่ม: เล่ม,
    ชื่อเล่ม: เล่ม,
    ดัชนี: ด,
    บทที่มี: [1],
    จาก: { บท: 1, ข้อ: 1 },
    ช่วง: null,
    ต่อที่อยู่: ต่อฐานเว็บ,
  })
  return ผล.คิว[0]?.ที่อยู่ไฟล์ ?? '(คิวว่าง)'
}

function ตรวจ(ตัว) {
  const ปัญหา = []
  const เทียบ = (ข้อ, ชื่อ, ได้, ควร) => {
    if (ได้ !== ควร) ปัญหา.push(`${ข้อ} ${ชื่อ} ⇒ ได้ ${ได้} ⇒ ต้องเป็น ${ควร}`)
  }
  const ลอง = (ข้อ, ชื่อ, งาน) => {
    try {
      งาน()
    } catch (e) {
      ปัญหา.push(`${ข้อ} ${ชื่อ} ⇒ ล้ม ⇒ ${e.message}`)
    }
  }
  ลอง('①', 'ยังไม่ย้าย', () => {
    เทียบ('①', 'TCV มาระโก 1:1', ที่อยู่ข้อแรก(ตัว, รายการ(), 'MRK', 'TCV'), '/phrakham/audio/Mark.1.1.puck.mp3')
    เทียบ('①', 'LSV มาระโก 1:1', ที่อยู่ข้อแรก(ตัว, รายการ(), 'MRK', 'LSV'), '/phrakham/audio/LSV/Mark.1.1.puck.mp3')
  })
  ลอง('②', 'ย้ายแล้ว', () => {
    เทียบ('②', 'TCV มาระโก 1:1', ที่อยู่ข้อแรก(ตัว, รายการ(ย้ายแล้ว), 'MRK', 'TCV'), `${ที่('tcv', 'nt')}Mark.1.1.puck.mp3`)
    เทียบ('②', 'LSV มาระโก 1:1', ที่อยู่ข้อแรก(ตัว, รายการ(ย้ายแล้ว), 'MRK', 'LSV'), `${ที่('lsv', 'nt')}Mark.1.1.puck.mp3`)
  })
  ลอง('③', 'เล่มคนละกลุ่ม', () => {
    เทียบ('③', 'ปฐมกาล 1:1', ที่อยู่ข้อแรก(ตัว, รายการ(ย้ายแล้ว), 'GEN', 'TCV'), `${ที่('tcv', 'ot1')}Gen.1.1.puck.mp3`)
    เทียบ('③', 'สดุดี 1:1', ที่อยู่ข้อแรก(ตัว, รายการ(ย้ายแล้ว), 'PSA', 'TCV'), `${ที่('tcv', 'ot2')}Ps.1.1.puck.mp3`)
  })
  let ล้ม = false
  try {
    ตัว.ดัชนี(รายการ({ TCV: { MRK: ที่('tcv', 'nt') }, LSV: ย้ายแล้ว.LSV }), 'GEN')
  } catch {
    ล้ม = true
  }
  if (!ล้ม) ปัญหา.push('④ รายการมี ฐานของฉบับ แต่ขาด TCV ปฐมกาล ⇒ ตัวประกอบ ⛔ ไม่ล้ม ⇒ ปฐมกาลจะชี้ audio/ ที่ไม่มีไฟล์แล้ว')
  return ปัญหา
}

function ทดสอบตัวเอง() {
  /** ⭐ ของพังแต่ละแบบ ⇒ ห่อตัวจริงแล้วเปลี่ยนแค่จุดเดียว ⇒ แบบที่โค้ดจริงพังได้ */
  const พัง = [
    ['ลืมอ่าน ฐานของฉบับ ⇒ ใช้ audio/ ตลอด', '②', {
      ดัชนี: (ร, เล่ม) => ดัชนีเสียงจากรายการ({ ...ร, ฐานของฉบับ: undefined }, เล่ม),
      คิว: สร้างคิว,
    }],
    // ⇒ คือของที่ได้ถ้ามีคนลบ `ต่อที่อยู่ไฟล์เสียง` ออกจาก `สร้างคิว` แล้วเรียก `o.ต่อที่อยู่` ตรง ๆ แบบเดิม
    ['ต่อฐานของเว็บหน้าที่อยู่เต็ม', '②', {
      ดัชนี: ดัชนีเสียงจากรายการ,
      คิว: (o) => {
        const ผล = สร้างคิว(o)
        return { ...ผล, คิว: ผล.คิว.map((x) => ({ ...x, ที่อยู่ไฟล์: /^https:/.test(x.ที่อยู่ไฟล์) ? o.ต่อที่อยู่(x.ที่อยู่ไฟล์) : x.ที่อยู่ไฟล์ })) }
      },
    }],
    ['ลืมต่อฐานของเว็บให้ทางในตัวเว็บ', '①', {
      ดัชนี: ดัชนีเสียงจากรายการ,
      คิว: (o) => สร้างคิว({ ...o, ต่อที่อยู่: (t) => t }),
    }],
    // ⇒ ของที่ได้ถ้าโค้ดยังต่อ `ทางย่อย` หลังฐานของ GitHub แบบตอนที่ทุกฉบับอยู่ที่เก็บเดียว
    ['ต่อโฟลเดอร์ฉบับซ้อนในที่เก็บของฉบับ', '②', {
      ดัชนี: (ร, เล่ม) => {
        const ด = ดัชนีเสียงจากรายการ(ร, เล่ม)
        if (ด?.LSV && ร.ฐานของฉบับ) ด.LSV = { ...ด.LSV, ไฟล์: ด.LSV.ไฟล์.replace('-lsv-nt/', '-lsv-nt/LSV/') }
        return ด
      },
      คิว: สร้างคิว,
    }],
    ['ทุกฉบับได้ที่เก็บของ TCV', '②', {
      ดัชนี: (ร, เล่ม) => ดัชนีเสียงจากรายการ(
        ร.ฐานของฉบับ ? { ...ร, ฐานของฉบับ: Object.fromEntries(Object.keys(ร.ฐานของฉบับ).map((k) => [k, ร.ฐานของฉบับ.TCV])) } : ร, เล่ม),
      คิว: สร้างคิว,
    }],
    ['ทุกเล่มได้ที่เก็บของมาระโก', '③', {
      ดัชนี: (ร, เล่ม) => ดัชนีเสียงจากรายการ(
        ร.ฐานของฉบับ ? { ...ร, ฐานของฉบับ: Object.fromEntries(Object.entries(ร.ฐานของฉบับ).map(([ฉ, ม]) =>
          [ฉ, Object.fromEntries(Object.keys(ม).map((k) => [k, ม.MRK]))])) } : ร, เล่ม),
      คิว: สร้างคิว,
    }],
    ['เล่มที่ขาดหล่นกลับไปใช้ audio/ เงียบ ๆ', '④', {
      ดัชนี: (ร, เล่ม) => ดัชนีเสียงจากรายการ(
        ร.ฐานของฉบับ && Object.values(ร.ฐานของฉบับ).some((ม) => !ม[เล่ม]) ? { ...ร, ฐานของฉบับ: undefined } : ร, เล่ม),
      คิว: สร้างคิว,
    }],
  ]
  let ตก = 0
  for (const [ชื่อ, ข้อ, ตัว] of พัง) {
    const ปัญหา = ตรวจ(ตัว)
    const จับ = ปัญหา.some((x) => x.startsWith(ข้อ))
    console.log(`${จับ ? '✅' : '⛔'} ${ชื่อ} ⇒ ${จับ ? `จับได้ที่ข้อ ${ข้อ}` : `ด่านไม่แดงที่ข้อ ${ข้อ}`} ${ปัญหา[0] ?? ''}`)
    if (!จับ) ตก++
  }
  if (ตก) {
    console.log(`⛔ ด่านตาบอด ${ตก} แบบ`)
    return 1
  }
  console.log('✅ ด่านจับของพังได้ครบทุกแบบ')
  return 0
}

if (process.argv.includes('--ทดสอบตัวเอง')) {
  const พื้น = ตรวจ(ของจริง)
  if (พื้น.length) {
    console.log('⛔ ของจริงยังไม่ผ่าน ⇒ ทดสอบตัวเองไม่ได้')
    for (const x of พื้น) console.log(`   ${x}`)
    process.exit(1)
  }
  process.exit(ทดสอบตัวเอง())
}
const ปัญหา = ตรวจ(ของจริง)
for (const x of ปัญหา) console.log(`⛔ ${x}`)
if (ปัญหา.length) process.exit(1)
console.log('✅ ที่อยู่ไฟล์เสียงถูกทั้งก่อนและหลังย้ายไป GitHub Pages ⇒ 4 ข้อผ่าน')
