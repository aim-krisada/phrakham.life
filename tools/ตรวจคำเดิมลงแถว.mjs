const เนื้อบท = อ่านgz('_data/เนื้อบท.json.gz')

/** ไฟล์คำเดิมของเล่ม ⇒ `{<บทเดิม>: ไฟล์}` ⇒ ⭐ อ่านจากเว็บที่สร้างเสร็จ ⇒ มีช่อง `ข้อแปล` ที่หลังบ้านคิดให้แล้ว */
function ไฟล์คำของเล่ม(เล่ม) {
  const ออก = {}
  const ที่ = join(กองคำ, เล่ม)
  if (!existsSync(ที่)) return ออก
  for (const f of readdirSync(ที่)) if (f.endsWith('.json')) ออก[Number(f.slice(0, -5))] = JSON.parse(readFileSync(join(ที่, f), 'utf8'))
  return ออก
}

/** ข้อเดิมทุกข้อของไฟล์ ⇒ เรียงตามลำดับฝั่งเดิม ⇒ รูปเดียวกับที่หน้าอ่านส่งเข้า `จัดข้อเดิมลงแถว` */
function ข้อเดิมของไฟล์(ไฟล์) {
  const ออก = []
  for (const [ชั้น, ข้อทั้งหมด] of Object.entries(ไฟล์.ชั้น))
    for (const [ข้อ, คำ] of Object.entries(ข้อทั้งหมด))
      ออก.push({ ชั้น, บท: ไฟล์.บท, ข้อ, คำ: คำ.length, ไป: ไฟล์.ข้อแปล?.[ข้อ] ?? [[ไฟล์.บท, Number(ข้อ)]] })
  return ออก
}

/** ข้อของฉบับหนึ่งในบทหนึ่ง ⇒ รูปเดียวกับที่หน้าอ่านส่งเข้า `จัดย่อหน้า` */
function ข้อของ(ฉบับ, กุญแจ) {
  const ของบท = เนื้อบท['บท'][กุญแจ]?.[ฉบับ]
  if (!ของบท) return []
  const บท = Number(กุญแจ.split('/')[1])
  return Object.keys(ของบท)
    .sort((a, b) => Number(a) - Number(b))
    .map((n) => ({ บท, เลข: n, ป้าย: n, ชิ้น: [{ ตัวหนังสือ: ของบท[n], พระเยซู: false }] }))
    .filter((x) => x.ชิ้น[0].ตัวหนังสือ)
}

/** ย่อหน้าของฉบับ ⇒ ท่าเดียวกับ `จัดย่อหน้าของฉบับ` ในหน้าอ่าน ⇒ ของตัวเอง หรือยืม TCV */
function ย่อหน้าของ(ฉบับ, กุญแจ) {
  const ข้อ = ข้อของ(ฉบับ, กุญแจ)
  if (!ข้อ.length) return []
  if (ซองย่อ.ฉบับ[ฉบับ]) return จัดย่อหน้า(ข้อ, ซองย่อ.ฉบับ[ฉบับ][กุญแจ] || [])
  return จัดย่อหน้า(ข้อ, ยืมรอยย่อหน้า(ซองย่อ.ฉบับ.TCV?.[กุญแจ] || [], ข้อ.map((x) => x.เลข)))
}

/** แถวของฉบับแปลในบทหนึ่ง ⇒ คืน `{ข้อแปล, จำนวน}` ⇒ ท่าเดียวกับ `ผังแถว` ของหน้าอ่าน */
function แถวของบท(แบบ, กุญแจ) {
  if (แบบ.จัดวาง === 'แยกตามข้อ') {
    // ⭐ ข้อที่มีกุญแจในฉบับใดฉบับหนึ่งที่เปิด ⇒ ท่าเดียวกับ `บทที่แสดง` ของหน้าอ่าน
    const เลข = new Set()
    for (const ฉ of แบบ.ฉบับ) for (const n of Object.keys(เนื้อบท['บท'][กุญแจ]?.[ฉ] || {})) เลข.add(n)
    const บท = Number(กุญแจ.split('/')[1])
    const เรียง = [...เลข].sort((a, b) => Number(a) - Number(b))
    const ข้อแปล = เรียง.map((n, แถว) => ({ บท, ข้อ: Number(n), แถว }))
    return { ข้อแปล, จำนวน: Math.max(1, เรียง.length), ควร: new Map(ข้อแปล.map((x) => [`${x.บท}:${x.ข้อ}`, x.แถว])) }
  }
  const กลุ่ม = จับคู่ย่อหน้า(แบบ.ฉบับ.map((ฉ) => ย่อหน้าของ(ฉ, กุญแจ)))
  // ⭐ คำตอบที่ถูกของข้อ ③ เขียนใหม่ในด่าน ⛔ ไม่เรียก `ข้อแปลของกลุ่ม`
  //   ⇒ ข้อแปล v เริ่มที่แถวที่ท่อนแรกของ v อยู่ ⇒ สองคอลัมน์ไม่ตรงกัน ⇒ แถวหลัง (แถวที่ตัดที่จุด *ข้อ v*)
  const ควร = new Map()
  for (let r = 0; r < กลุ่ม.length; r++)
    for (const ช่อง of กลุ่ม[r].ช่อง)
      for (const ย of ช่อง)
        for (const ท of ย.ท่อน) if (ท.ท่อนแรก) ควร.set(`${ท.บท}:${ท.เลข}`, Math.max(r, ควร.get(`${ท.บท}:${ท.เลข}`) ?? -1))
  return { ข้อแปล: ข้อแปลของกลุ่ม(กลุ่ม), จำนวน: Math.max(1, กลุ่ม.length), ควร }
}

const แบบที่ตรวจ = [
  { ชื่อ: 'แยกตามข้อ TCV', จัดวาง: 'แยกตามข้อ', ฉบับ: ['TCV'] },
  { ชื่อ: 'แยกตามข้อ 4 ฉบับ', จัดวาง: 'แยกตามข้อ', ฉบับ: เนื้อบท['ชั้น'] },
  { ชื่อ: 'แยกตามย่อหน้า TCV', จัดวาง: 'แยกตามย่อหน้า', ฉบับ: ['TCV'] },
  { ชื่อ: 'แยกตามย่อหน้า TCV+THKJV', จัดวาง: 'แยกตามย่อหน้า', ฉบับ: ['TCV', 'THKJV'] },
]

/**
 * ตรวจทั้งคลัง ⇒ `จัด(ข้อเดิม, ข้อแปล)` คือตัวจัดแถวที่ถูกตรวจ · `วางก้อน` คือกติกาว่าข้อเดิมไปก้อนบทไหน
 *   ⇒ โหมดพิสูจน์ส่งแบบผิดเข้ามาแทน
 */
function ตรวจ(จัด, วางก้อน = วางก้อนจริง) {
  const ตก = []
  const นับ = { บท: 0, ข้อเดิม: 0, คำ: 0, ไปแถวก่อนหน้า: 0, ข้ามบท: 0, ที่ไปแถวก่อนหน้า: [] }
  const เล่มทั้งหมด = [...new Set(Object.keys(เนื้อบท['บท']).map((k) => k.split('/')[0]))]
  for (const แบบ of แบบที่ตรวจ) {
    for (const เล่ม of เล่มทั้งหมด) {
      const ไฟล์ = ไฟล์คำของเล่ม(เล่ม)
      if (!Object.keys(ไฟล์).length) continue
      const บทแปล = [...new Set(Object.keys(เนื้อบท['บท']).filter((k) => k.startsWith(`${เล่ม}/`)).map((k) => Number(k.split('/')[1])))].sort((a, b) => a - b)
      // ① ทุกข้อเดิมของเล่มต้องขึ้นครั้งเดียวพอดี ⇒ นับว่าแต่ละข้อขึ้นกี่ครั้ง
      const ขึ้น = new Map()
      for (const x of Object.values(ไฟล์).flatMap(ข้อเดิมของไฟล์)) ขึ้น.set(`${x.ชั้น} ${x.บท}:${x.ข้อ}`, { ครั้ง: 0, คำ: x.คำ, ได้คำ: 0 })
      for (const c of บทแปล) {
        const กุญแจ = `${เล่ม}/${c}`
        const ทั้งไฟล์ = [c - 1, c, c + 1].filter((b) => ไฟล์[b]).flatMap((b) => ข้อเดิมของไฟล์(ไฟล์[b]))
        const ของก้อน = วางก้อน(ทั้งไฟล์, c, บทแปล).sort((a, b) => a.บท - b.บท || Number(a.ข้อ) - Number(b.ข้อ))
        const { ข้อแปล, จำนวน, ควร: มีแถว } = แถวของบท(แบบ, กุญแจ)
        นับ.บท++
        for (const ชั้น of new Set(ของก้อน.map((x) => x.ชั้น))) {
          const ข้อ = ของก้อน.filter((x) => x.ชั้น === ชั้น)
          const แถว = จัด(ข้อ, ข้อแปล)
          let ก่อน = 0
          ข้อ.forEach((x, i) => {
            const ที่ = `${แบบ.ชื่อ} ${เล่ม} ${c} ⇒ ${ชั้น} ${x.บท}:${x.ข้อ}`
            const r = แถว[i]
            // ⭐ ตัวจัดแถวคืน `undefined` = ข้อนี้ ⛔ ไม่ถูกวาด ⇒ ไม่นับว่าขึ้น ⇒ ① จะจับเอง
            if (r === undefined) return
            const ก = ขึ้น.get(`${x.ชั้น} ${x.บท}:${x.ข้อ}`)
            ก.ครั้ง++
            ก.ได้คำ += x.คำ
            // ④ แถวอยู่ในช่วงของบท
            if (!(Number.isInteger(r) && r >= 0 && r < จำนวน)) ตก.push(`${ที่} ⇒ ④ แถว ${r} ⛔ อยู่นอกช่วง 0–${จำนวน - 1}`)
            // ② ⛔ ถอยหลัง
            if (r < ก่อน) ตก.push(`${ที่} ⇒ 🔴 ② แถว ${r} ถอยหลังกว่าข้อเดิมข้อก่อน (แถว ${ก่อน}) ⇒ คำสลับลำดับ`)
            ก่อน = Math.max(ก่อน, r)
            // ③ ตรงแถว ⇒ ข้อแปลข้อแรกที่มีแถวบนหน้า ⇒ เขียนกติกาใหม่ในด่าน
            const ควร = x.ไป.map(([บ, ข]) => มีแถว.get(`${บ}:${ข}`)).find((v) => v !== undefined)
            if (ควร !== undefined && r !== ควร) ตก.push(`${ที่} ⇒ 🔴 ③ อยู่แถว ${r} ⛔ ไม่ใช่แถว ${ควร} ของข้อแปล ${x.ไป.map((p) => p.join(':')).join(' ')}`)
            if (ควร === undefined) {
              นับ.ไปแถวก่อนหน้า++
              นับ.ที่ไปแถวก่อนหน้า.push(ที่)
            }
            if (x.บท !== c) นับ.ข้ามบท++
          })
          นับ.ข้อเดิม += ข้อ.length
          นับ.คำ += ข้อ.reduce((n, x) => n + x.คำ, 0)
        }
      }
      for (const [ข้อ, ก] of ขึ้น) {
        if (ก.ครั้ง !== 1) ตก.push(`${แบบ.ชื่อ} ${เล่ม} ⇒ ${ข้อ} ⇒ 🔴 ① ขึ้น ${ก.ครั้ง} ครั้ง ⛔ ต้อง 1 ครั้งพอดี (${ก.คำ} คำ ⇒ ได้ ${ก.ได้คำ})`)
      }
    }
  }
  return { ตก, นับ }
}

/**
 * ⭐ ของจริง ⇒ ท่าเดียวกับ `คำของก้อน` ของหน้าอ่าน ⇒ ข้อเดิมไปก้อนบทของ **ข้อแปลข้อแรกที่อยู่บนหน้า**
 *   ⇒ ด่านจำลองว่า **ทุกบทของเล่มอยู่บนหน้า** (อ่านต่อเนื่องทั้งเล่ม) ⇒ บนหน้า = บทที่ฉบับแปลมี
 */
function วางก้อนจริง(ข้อทั้งหมด, c, บทแปล) {
  return ข้อทั้งหมด.filter((x) => x.ไป.find(([บ]) => บทแปล.includes(บ))?.[0] === c)
}

