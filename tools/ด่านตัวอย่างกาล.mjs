/** ข้อ ② ถึง ⑤ ของข้อความหนึ่งก้อนที่อ้างคำจริง ⇒ ใช้ทั้งตัวอย่างของกาล และย่อหน้านำกับความหมายของ `!` */
function ตรวจข้อความ(ป, ต, หยิบบท, ตก) {
  const ข้อความ = ปกติ(String(ต.ข้อความ ?? ''))
  const คำ = ต.คำ ?? []
  if (!ข้อความ.trim()) ตก.push(`① ${ป} ⇒ ข้อความว่าง`)
  if (!คำ.length) ตก.push(`② ${ป} ⇒ ⛔ ไม่ได้จดคำในข้อมูลจริงไว้สักคำ ⇒ ตรวจกับข้อมูลไม่ได้`)

  // ---------------------------------------------------------------- ② คำในข้อความ ⇔ คำที่จด
  const กรีกที่จด = new Set(คำ.filter((ค) => !ค.ไทย).map((ค) => ปกติ(ค.คำ)))
  for (const m of ข้อความ.matchAll(อักษรกรีก))
    if (!กรีกที่จด.has(m[0])) ตก.push(`② ${ป} ⇒ คำกรีก ${m[0]} อยู่ในข้อความแต่ ⛔ ไม่ได้จดไว้ ⇒ ไม่มีใครตรวจกับข้อมูล`)
  for (const ค of คำ) {
    if (ค.ไทย) {
      if (!ข้อความ.includes(ค.ไทย)) ตก.push(`② ${ป} ⇒ จด ${ค.คำ} เป็นคำไทย «${ค.ไทย}» แต่ ⛔ ไม่มีคำนี้ในข้อความ`)
    } else if (!ข้อความ.includes(ปกติ(ค.คำ))) ตก.push(`② ${ป} ⇒ จด ${ค.คำ} ไว้แต่ ⛔ ไม่มีในข้อความ`)
  }

  // ---------------------------------------------------------------- ③ เลขข้อในข้อความ ⇔ คำ
  const ช่วง = [...ข้อความ.matchAll(ช่วงอ้าง)].map((m) => ({
    ข้อความ: m[0],
    ชื่อ: m[1],
    บท: Number(m[2]),
    ต้น: Number(m[3]),
    ปลาย: Number(m[4] ?? m[3]),
  }))
  if (!ช่วง.length) ตก.push(`③ ${ป} ⇒ ⛔ ไม่ได้บอกว่าอยู่ข้อไหน (ต้องมี *มาระโก บท:ข้อ* หรือ *ลูกา บท:ข้อ*)`)
  const ใน = (ค, ช) => ชื่อเล่ม[ค.เล่ม] === ช.ชื่อ && ค.บท === ช.บท && ค.ข้อ >= ช.ต้น && ค.ข้อ <= ช.ปลาย
  for (const ค of คำ) {
    if (!ชื่อเล่ม[ค.เล่ม]) ตก.push(`③ ${ป} ⇒ ${ค.คำ} อยู่เล่ม ${ค.เล่ม} ที่ด่านไม่รู้จักชื่อไทย`)
    else if (!ช่วง.some((ช) => ใน(ค, ช)))
      ตก.push(`③ ${ป} ⇒ ${ค.คำ} จดไว้ที่ ${ชื่อเล่ม[ค.เล่ม]} ${ค.บท}:${ค.ข้อ} แต่ข้อความอ้าง ${ช่วง.map((ช) => ช.ข้อความ).join(' · ') || '-'}`)
  }
  for (const ช of ช่วง)
    if (!คำ.some((ค) => ใน(ค, ช))) ตก.push(`③ ${ป} ⇒ ข้อความอ้าง ${ช.ข้อความ} แต่ ⛔ ไม่มีคำที่จดไว้ในช่วงนี้ ⇒ เลขข้อลอย`)

  // ---------------------------------------------------------------- ④ คำ กาล (และมาลา) ตรงข้อมูลจริง
  for (const ค of คำ) {
    const ที่คำ = `${ค.คำ} ${ชื่อเล่ม[ค.เล่ม] ?? ค.เล่ม} ${ค.บท}:${ค.ข้อ}`
    const บท = หยิบบท(ค.เล่ม, ค.บท)
    if (!บท) {
      ตก.push(`④ ${ป} ⇒ ${ที่คำ} ⇒ เว็บ ⛔ ไม่มีไฟล์ของบทนี้`)
      continue
    }
    const ในข้อ = บท.ชั้น?.คำกรีก?.[ค.ข้อ] ?? []
    const เจอ = ในข้อ.filter((w) => ปกติ(String(w[0])) === ปกติ(ค.คำ))
    const รหัส = เจอ.map((w) => w[2] ?? 'ไม่มี').join('/')
    if (!เจอ.length) ตก.push(`④ ${ป} ⇒ ${ที่คำ} ⇒ ⛔ ไม่มีคำนี้ในข้อนี้ของข้อมูลจริง`)
    else if (!เจอ.some((w) => String(w[2] ?? '')[0] === ค.กาล))
      ตก.push(`④ ${ป} ⇒ ${ที่คำ} ⇒ ข้อมูลจริงเป็นกาล ${รหัส} ⛔ ไม่ใช่ ${ค.กาล} ที่ถ้อยคำบอก`)
    else if (ค.มาลา && !เจอ.some((w) => String(w[2] ?? '') === ค.กาล + ค.มาลา))
      ตก.push(`④ ${ป} ⇒ ${ที่คำ} ⇒ ข้อมูลจริงเป็น ${รหัส} ⛔ ไม่ใช่มาลา ${ค.มาลา} ที่ถ้อยคำบอก`)
  }

  // ---------------------------------------------------------------- ⑤ เลขหน้า เลขหัวข้อ
  ตรวจเลขตำรา(ป, ข้อความ.replace(ช่วงอ้าง, ''), ตก)
}

/** ข้อ ⑤ ⇒ ⛔ เลขหน้าหรือเลขหัวข้อของตำราขึ้นเว็บ */
function ตรวจเลขตำรา(ป, ข้อความ, ตก) {
  for (const ร of [เลขหน้า, เลขหัวข้อ])
    if (ร.test(ข้อความ ?? '')) ตก.push(`⑤ ${ป} ⇒ มีเลขหน้าหรือเลขหัวข้อของตำรา «${ข้อความ.match(ร)[0]}» ⇒ ⛔ ไม่ขึ้นเว็บ`)
}

/**
 * ตัวตัดสิน ⇒ รับของทุกชิ้นเป็นพารามิเตอร์ ⇒ ฝาแฝดยัดของพังเข้ามาได้โดย ⛔ ไม่ต้องแก้ไฟล์จริง
 * @param หยิบบท `(เล่ม, บท) => ไฟล์ api/words ของบทนั้น | null`
 * @param ร่วม `{ ข้อความ: { ย่อหน้านำ, ความหมายคำสั่ง }, คำ: คำในถ้อยคำร่วม, ที่มา: ที่มาถ้อยคำ }`
 */
function ตรวจ({ ตาราง, หัว, หยิบบท, ร่วม }) {
  const ตก = []
  // ---------------------------------------------------------------- ① ครบ 3 ท่อน
  for (const [ชื่อ, ค่า] of Object.entries(หัว)) if (!String(ค่า ?? '').trim()) ตก.push(`① หัวท่อน ${ชื่อ} ว่าง`)
  for (const รหัส of ['P', 'I', 'A', 'R', 'L', 'F'])
    if (!ตาราง.some((ก) => ก.รหัส === รหัส)) ตก.push(`① ตาราง ⛔ ไม่มีกาล ${รหัส}`)
  for (const ก of ตาราง) {
    const ป้าย = `${ก.ชื่อ} (${ก.รหัส})`
    if (!String(ก.ความหมาย ?? '').trim()) ตก.push(`① ${ป้าย} ⇒ ⛔ ไม่มีท่อนความหมาย`)
    if (!String(ก.อ่านไทย ?? '').trim()) ตก.push(`① ${ป้าย} ⇒ ⛔ ไม่มีท่อนอ่านเป็นไทยว่า`)
    if (!ก.ตัวอย่าง?.length) ตก.push(`① ${ป้าย} ⇒ ⛔ ไม่มีตัวอย่างจริงจากพระคัมภีร์`)
    for (const [ที่, ต] of ตัวอย่างของ(ก)) ตรวจข้อความ(`${ป้าย} ${ที่}`, ต, หยิบบท, ตก)
    ตรวจเลขตำรา(`${ป้าย} ความหมาย`, ก.ความหมาย, ตก)
    ตรวจเลขตำรา(`${ป้าย} อ่านเป็นไทยว่า`, ก.อ่านไทย, ตก)
  }
  // ⭐ ย่อหน้านำกับความหมายของ `!` อ้างคำจริงด้วย (ใบ #120 ข้อ 12.1 · 12.2) ⇒ ข้อ ② ถึง ⑤ แบบเดียวกับตัวอย่าง
  for (const [ชื่อ, ข้อความ] of Object.entries(ร่วม.ข้อความ)) {
    if (!String(ข้อความ ?? '').trim()) ตก.push(`① ${ชื่อ} ว่าง`)
    ตรวจข้อความ(ชื่อ, { ข้อความ, คำ: ร่วม.คำ[ชื่อ] ?? [] }, หยิบบท, ตก)
  }
  // ⭐ บรรทัดที่มา ⇒ ⛔ เลขหน้าหรือเลขหัวข้อของตำรา (ใบ #120 ข้อ 12.4)
  if (!String(ร่วม.ที่มา ?? '').trim()) ตก.push('① บรรทัดที่มาว่าง')
  ตรวจเลขตำรา('บรรทัดที่มา', ร่วม.ที่มา, ตก)
  return ตก
}

