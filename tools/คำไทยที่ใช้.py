import collections
import os
import re
import sys

ราก = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ที่เก็บ = os.path.join(ราก, "_data", "คำแปล")

# ตัวคั่นที่ใช้ในช่องความหมาย ⇒ ` · ` แยกความหมายคนละกิ่ง · ` ⇒ ` แยกความหมายต่อยอด
ตัวคั่น = re.compile(r"\s*·\s*|\s*⇒\s*")


def แยกคำ(ข้อความ):
    for ชิ้น in ตัวคั่น.split(ข้อความ):
        ชิ้น = ชิ้น.strip()
        if ชิ้น and ชิ้น != "=":
            yield ชิ้น


def อ่านไฟล์(ทาง, ช่องที่เอา):
    with open(ทาง, encoding="utf-8") as ฟ:
        บรรทัด = [บ.rstrip("\n").split("\t") for บ in ฟ if บ.strip()]
    หัว = บรรทัด[0]
    if ช่องที่เอา not in หัว:
        return
    ที่ = หัว.index(ช่องที่เอา)
    for ของ in บรรทัด[1:]:
        if len(ของ) > ที่:
            yield from แยกคำ(ของ[ที่])


def หลัก():
    if not os.path.isdir(ที่เก็บ):
        print(f"⛔ ไม่เจอ {ที่เก็บ}")
        return 2
    ทั้งหมด = "--ทั้งหมด" in sys.argv
    ชั้นหนึ่ง = collections.Counter()
    ชั้นสอง = collections.Counter()
    บทที่อ่าน = []

    for ชื่อ in sorted(os.listdir(ที่เก็บ)):
        if not ชื่อ.endswith(".tsv"):
            continue
        ทาง = os.path.join(ที่เก็บ, ชื่อ)
        if ชื่อ == "ศัพท์.tsv":
            ชั้นหนึ่ง.update(อ่านไฟล์(ทาง, "ความหมายตามศัพท์"))
        else:
            ชั้นสอง.update(อ่านไฟล์(ทาง, "ความหมายในข้อนี้"))
            บทที่อ่าน.append(ชื่อ[:-4])

    รวม = set(ชั้นหนึ่ง) | set(ชั้นสอง)
    print(f"อ่านจาก {ที่เก็บ}")
    print(f"บทที่มี ⇒ {', '.join(บทที่อ่าน) if บทที่อ่าน else 'ยังไม่มี'}")
    print(f"ชั้น ① ใช้คำไทย {len(ชั้นหนึ่ง)} คำ · ชั้น ② ใช้ {len(ชั้นสอง)} คำ · รวมไม่ซ้ำ {len(รวม)} คำ")
    print("-" * 60)

    เฉพาะชั้นสอง = sorted(set(ชั้นสอง) - set(ชั้นหนึ่ง))
    print(f"คำที่โผล่เฉพาะตอนแปลตามบริบท {len(เฉพาะชั้นสอง)} คำ")
    print("⇒ กลุ่มนี้คือคำที่พจนานุกรมไม่ได้ให้ เราเลือกเองเพราะบริบทบังคับ")
    for คำ in (เฉพาะชั้นสอง if ทั้งหมด else เฉพาะชั้นสอง[:25]):
        print(f"   {คำ}")
    if not ทั้งหมด and len(เฉพาะชั้นสอง) > 25:
        print(f"   … อีก {len(เฉพาะชั้นสอง) - 25} คำ ⇒ เติม --ทั้งหมด")

    print("-" * 60)
    print("คำที่ใช้บ่อยที่สุด ⇒ กลุ่มนี้มีสิทธิ์เข้ารายการคำพื้นฐานก่อนเพื่อน")
    ทุกคำ = ชั้นหนึ่ง + ชั้นสอง
    for คำ, ครั้ง in ทุกคำ.most_common(None if ทั้งหมด else 20):
        print(f"   {ครั้ง:>3}  {คำ}")
    return 0


if __name__ == "__main__":
    sys.exit(หลัก())
