import os
import sys
import xml.etree.ElementTree as ET

ราก = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ที่เก็บ = os.path.join(ราก, "_data", "คำแปล")
มาคูลา = os.path.join(ราก, "_แตก", "macula-hebrew-main", "WLC", "lowfat")

ช่องศัพท์ = ["รหัสคำ", "คำเดิม", "อ่านว่า", "ชนิดคำ", "ความหมายตามศัพท์", "ที่ทาน"]
ช่องบท = ["ข้อ", "ลำดับ", "รหัสคำ", "รูปในข้อ", "ลักษณะคำ",
          "ความหมายในข้อนี้", "หมายเหตุ", "รหัสมาคูลา"]

# บทไหนมาจากไฟล์ MACULA ไฟล์ไหน ⇒ เพิ่มบทใหม่ให้เติมที่นี่
ไฟล์ต้นทาง = {"สดุดี-32": "19-Psa-032-lowfat.xml"}

พัง = []


def ทัก(ข้อความ):
    พัง.append(ข้อความ)


def อ่าน(ทาง, ช่อง):
    with open(ทาง, encoding="utf-8") as ฟ:
        บรรทัด = [บ.rstrip("\n") for บ in ฟ if บ.strip()]
    หัว = บรรทัด[0].split("\t")
    if หัว != ช่อง:
        ทัก(f"{os.path.basename(ทาง)} หัวตารางไม่ตรงแบบ ⇒ เจอ {หัว}")
        return []
    แถว = []
    for เลข, บ in enumerate(บรรทัด[1:], 2):
        ของ = บ.split("\t")
        if len(ของ) != len(ช่อง):
            ทัก(f"{os.path.basename(ทาง)} บรรทัด {เลข} มี {len(ของ)} ช่อง ⇒ ต้องมี {len(ช่อง)}")
            continue
        แถว.append(dict(zip(ช่อง, ของ)))
    return แถว


def หลัก():
    ทางศัพท์ = os.path.join(ที่เก็บ, "ศัพท์.tsv")
    if not os.path.isfile(ทางศัพท์):
        print(f"⛔ ไม่เจอ {ทางศัพท์}")
        return 2
    ศัพท์ = อ่าน(ทางศัพท์, ช่องศัพท์)

    # ① รหัสคำในชั้น ① ต้องไม่ซ้ำ
    เห็น = set()
    for แถว in ศัพท์:
        if แถว["รหัสคำ"] in เห็น:
            ทัก(f"ศัพท์.tsv มีรหัสคำซ้ำ {แถว['รหัสคำ']}")
        เห็น.add(แถว["รหัสคำ"])

    # ② ทุกคำในชั้น ① ต้องบอกว่าเปิดที่ไหนถึงเจอ
    for แถว in ศัพท์:
        if not แถว["ที่ทาน"].strip():
            ทัก(f"ศัพท์.tsv รหัส {แถว['รหัสคำ']} ไม่ได้บอกว่าทานจากที่ไหน")
        if not แถว["ความหมายตามศัพท์"].strip():
            ทัก(f"ศัพท์.tsv รหัส {แถว['รหัสคำ']} ไม่มีความหมาย")

    ใช้จริง = set()
    for ชื่อบท, ชื่อไฟล์ต้นทาง in sorted(ไฟล์ต้นทาง.items()):
        ทางบท = os.path.join(ที่เก็บ, ชื่อบท + ".tsv")
        if not os.path.isfile(ทางบท):
            ทัก(f"ไม่เจอไฟล์บท {ชื่อบท}.tsv")
            continue
        บท = อ่าน(ทางบท, ช่องบท)

        กุญแจ = set()
        ต่อข้อ = {}
        for แถว in บท:
            ก = (แถว["ข้อ"], แถว["ลำดับ"])
            # ③ กุญแจ (ข้อ, ลำดับ) ต้องไม่ซ้ำ
            if ก in กุญแจ:
                ทัก(f"{ชื่อบท} กุญแจซ้ำที่ ข้อ {ก[0]} ลำดับ {ก[1]}")
            กุญแจ.add(ก)
            ต่อข้อ.setdefault(int(แถว["ข้อ"]), []).append(int(แถว["ลำดับ"]))

            # ④ รหัสคำในชั้น ② ต้องมีอยู่ในชั้น ①
            if แถว["รหัสคำ"] not in เห็น:
                ทัก(f"{ชื่อบท} ข้อ {ก[0]} ลำดับ {ก[1]} ใช้รหัส {แถว['รหัสคำ']} ที่ไม่มีในศัพท์.tsv")
            ใช้จริง.add(แถว["รหัสคำ"])

            # ⑤ ช่องความหมายห้ามว่าง ⇒ ตรงกับชั้น ① ให้เขียน = ลงไป
            if not แถว["ความหมายในข้อนี้"].strip():
                ทัก(f"{ชื่อบท} ข้อ {ก[0]} ลำดับ {ก[1]} ไม่มีคำแปล ⇒ ตรงกับชั้น ① ให้ใส่ =")

        # ⑥ ลำดับในแต่ละข้อต้องเริ่มที่ 1 แล้วไล่ติดกัน ⛔ ห้ามกระโดด
        for ข้อ, ลำดับ in sorted(ต่อข้อ.items()):
            if sorted(ลำดับ) != list(range(1, len(ลำดับ) + 1)):
                ทัก(f"{ชื่อบท} ข้อ {ข้อ} ลำดับคำกระโดด ⇒ {sorted(ลำดับ)}")

        เทียบมาคูลา(ชื่อบท, ชื่อไฟล์ต้นทาง, บท)

    # ⑦ ชั้น ① ห้ามมีคำที่ไม่มีบทไหนใช้ ⇒ กันคำค้างจากบทที่ถูกลบไปแล้ว
    for รหัส in sorted(เห็น - ใช้จริง):
        ทัก(f"ศัพท์.tsv มีรหัส {รหัส} ที่ไม่มีบทไหนใช้")

    for ข in พัง:
        print("⛔", ข)
    print("-" * 60)
    if พัง:
        print(f"ไม่ผ่าน {len(พัง)} เรื่อง")
        return 1
    print(f"ผ่าน ⇒ ศัพท์ {len(ศัพท์)} คำ · บท {len(ไฟล์ต้นทาง)} บท")
    return 0


def เทียบมาคูลา(ชื่อบท, ชื่อไฟล์, บท):
    """⑧ รหัสมาคูลาต้องตรงของจริงทุกตัว ⛔ ไม่ขาดไม่เกินไม่สลับ
    ⑨ ตัวอักษรฮีบรูในช่อง `รูปในข้อ` ต้องตรงของจริงด้วย

    ⭐ ทำไมต้องมีข้อ ⑨ ⇒ ข้อ ⑧ ดูแต่รหัส ⇒ ถ้าใครแก้ตัวอักษรฮีบรูผิดไปหนึ่งสระ
       รหัสยังตรงอยู่ ⇒ ด่านจะเขียวทั้งที่ของเสียแล้ว
       (ที่ปรึกษาภายนอกทักไว้รอบ 4 · ใบงาน v3/phrakham#16)
    """
    ทาง = os.path.join(มาคูลา, ชื่อไฟล์)
    if not os.path.isfile(ทาง):
        print(f"⏭ ข้ามด่านเทียบ MACULA ของ {ชื่อบท} ⇒ ยังไม่มี {ทาง}")
        print('   ดึงก่อน: git -c lfs.fetchexclude= lfs pull -I "source/" แล้ว py -3.14 tools/แตกกอง.py')
        return
    NS = "{http://www.w3.org/XML/1998/namespace}"
    คำจริง = list(ET.parse(ทาง).getroot().iter("w"))
    ของจริง = [ค.get(NS + "id") for ค in คำจริง]
    ของเรา = [แถว["รหัสมาคูลา"] for แถว in บท]
    if ของเรา != ของจริง:
        ขาด = [ก for ก in ของจริง if ก not in set(ของเรา)]
        เกิน = [ก for ก in ของเรา if ก not in set(ของจริง)]
        ทัก(f"{ชื่อบท} รหัสมาคูลาไม่ตรงของจริง ⇒ ของเรา {len(ของเรา)} คำ · ของจริง {len(ของจริง)} คำ")
        if ขาด:
            ทัก(f"   คำที่ยังไม่ได้แปล {len(ขาด)} คำ ⇒ ตัวอย่าง {ขาด[:5]}")
        if เกิน:
            ทัก(f"   คำที่ไม่มีในของจริง {len(เกิน)} คำ ⇒ ตัวอย่าง {เกิน[:5]}")
        return

    for แถว, ค in zip(บท, คำจริง):
        จริง = (ค.text or "").strip()
        if แถว["รูปในข้อ"] != จริง:
            ทัก(f"{ชื่อบท} ข้อ {แถว['ข้อ']} ลำดับ {แถว['ลำดับ']} "
                f"ตัวอักษรฮีบรูไม่ตรงของจริง ⇒ ของเรา {แถว['รูปในข้อ']!r} · ของจริง {จริง!r}")


if __name__ == "__main__":
    sys.exit(หลัก())
