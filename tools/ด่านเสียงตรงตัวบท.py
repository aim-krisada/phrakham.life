def ทดสอบตัวเอง() -> int:
    """⛔ **ยัดของพังเข้าไปจริง** ⇒ ด่านต้องแดงทุกแบบ ⛔ ไม่ใช่เชื่อว่ามันเฝ้าอยู่"""
