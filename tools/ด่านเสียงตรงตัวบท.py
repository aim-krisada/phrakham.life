    ตรงเป๊ะ = ต่างอัญประกาศ = 0
    ใช้บัญชีไป: set[str] = set()
    for รหัส, e in sorted(ในขอบเขต.items()):
        เล่ม = osisเป็นเล่ม[e["osis"]]
