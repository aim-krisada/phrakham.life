def ทดสอบตัวเอง():
    import copy

    if not ซองย่อหน้า.exists():
        print("⛔ ยังไม่มี %s ⇒ รัน `py -3.14 tools/สร้างรอยย่อหน้า.py` ก่อน" % ซองย่อหน้า)
        return 1
    ซองจริง = อ่านซอง(ซองย่อหน้า)
    เนื้อบท = อ่านซอง(ซองเนื้อบท)
    ฉบับที่ใช้ = sorted(ซองจริง["ฉบับ"])[0]
    บทแรก = sorted(ซองจริง["ฉบับ"][ฉบับที่ใช้])[0]

    def ลอง(ชื่อ, ทำพัง, ฐานใหม่=None):
        """ยัดของพังลงสำเนา แล้วยืนยันว่าด่านร้อง ⇒ ⛔ ไม่ร้อง = ฝาแฝดแดง"""
        global พัง, ฐานต่างเฉพาะช่องว่าง
        ซอง = copy.deepcopy(ซองจริง)
        ทำพัง(ซอง)
        ฐานเดิม = ฐานต่างเฉพาะช่องว่าง
        if ฐานใหม่ is not None:
            ฐานต่างเฉพาะช่องว่าง = ฐานใหม่
        พัง = []
        เงียบ = io.StringIO()
        จริง, sys.stdout = sys.stdout, เงียบ
        try:
            for ฉ in ซอง["ฉบับ"]:
                ตรวจฉบับ(ฉ, ซอง["ฉบับ"][ฉ], เนื้อบท)
        finally:
            sys.stdout = จริง
            ฐานต่างเฉพาะช่องว่าง = ฐานเดิม
        จับได้ = bool(พัง)
        print("   %s %-52s ⇒ %s" % ("✅" if จับได้ else "⛔", ชื่อ,
                                    ("ด่านร้อง %d เรื่อง" % len(พัง)) if จับได้
                                    else "⛔ **ด่านเงียบ ⇒ ตาบอดแล้ว**"))
        if จับได้:
            print("        เสียงที่ร้อง ⇒ %s" % พัง[0][:110])
        return จับได้

    print("ฝาแฝด ⇒ ยัดของพัง 5 แบบ แล้วด่านต้องแดงทุกแบบ (ใช้ %s %s เป็นเป้า)"
          % (ฉบับที่ใช้, บทแรก))

    def ขยับรอย(ซอง):
        ซอง["ฉบับ"][ฉบับที่ใช้][บทแรก][0]["หลังอักษร"] += 1

    def ตัดรอยทิ้ง(ซอง):
        ซอง["ฉบับ"][ฉบับที่ใช้][บทแรก].pop(0)

    def เพิ่มรอยปลอม(ซอง):
        อัน = dict(ซอง["ฉบับ"][ฉบับที่ใช้][บทแรก][0])
        อัน["ข้อ"] += 1
        ซอง["ฉบับ"][ฉบับที่ใช้][บทแรก].append(อัน)

    def เปลี่ยนป้าย(ซอง):
        ซอง["ฉบับ"][ฉบับที่ใช้][บทแรก][0]["ป้าย"] = "ป้ายที่ไม่มีจริง"

