def หลัก():
    if not ซองย่อหน้า.exists():
        print("⛔ ยังไม่มี %s ⇒ รัน `py -3.14 tools/สร้างรอยย่อหน้า.py` ก่อน" % ซองย่อหน้า)
        return 1
    ซอง = อ่านซอง(ซองย่อหน้า)
    เนื้อบท = อ่านซอง(ซองเนื้อบท)
    มี, ไม่มี = ซอง["ฉบับ"], ซอง["ไม่มี"]
    # ⭐ ใบงาน #169 ⇒ ฉบับเพิ่ม (KJV) ขึ้นหน้าอ่านด้วย ⇒ ซองรอยย่อหน้าต้องพูดถึงมันเหมือนฉบับในซองเนื้อบท
    from สร้างฉบับเพิ่ม import ต้นทาง as ฉบับเพิ่ม
    ทุกฉบับ = list(เนื้อบท["ชั้น"]) + list(ฉบับเพิ่ม)

    print("ซองรอยย่อหน้า %s ⇒ %.0f กิโลไบต์"
          % (ซองย่อหน้า.name, ซองย่อหน้า.stat().st_size / 1024))
    print("ฉบับในซองเนื้อบท %s ⇒ มีย่อหน้า %s · ยังไม่มี %s"
          % (" ".join(ทุกฉบับ), " ".join(มี) or "—", " ".join(ไม่มี) or "—"))
    if set(มี) & set(ไม่มี):
        ร้อง("ฉบับเดียวกันอยู่ทั้งสองฝั่ง ⇒ %s" % sorted(set(มี) & set(ไม่มี)))
    if set(มี) | set(ไม่มี) != set(ทุกฉบับ):
        ร้อง("ซองไม่ได้พูดถึงทุกฉบับในซองเนื้อบทกับฉบับเพิ่ม ⇒ ขาด %s · เกิน %s"
             % (sorted(set(ทุกฉบับ) - set(มี) - set(ไม่มี)), sorted(set(มี) | set(ไม่มี) - set(ทุกฉบับ))))

    หัวบทของฉบับ = {}
    for ฉบับ in มี:
        หัวบทของฉบับ[ฉบับ] = ตรวจฉบับ(ฉบับ, มี[ฉบับ], เนื้อบท)

    # ⑥ ฉบับที่บอกว่ายังไม่มี ⇒ พิสูจน์ด้วยการนับ
    print("\n⑥ ฉบับที่ซองบอกว่ายังไม่มีย่อหน้าให้ใช้ " + "─" * 28)
    for ฉบับ, เหตุผล in ไม่มี.items():
        ไฟล์ทั้งหมด = sorted((กองตัวบท / ฉบับ).glob("*.usx.gz"))
        if not ไฟล์ทั้งหมด:
            print("   %-6s ⇒ ไม่มีกอง USX เลย ⇒ %s" % (ฉบับ, เหตุผล))
            continue
        ข้อทั้งหมด, รอยทั้งหมด, _, _ = แกะทั้งฉบับ(ฉบับ)
        ต่อบท = collections.Counter()
        for sid, _, _ in รอยทั้งหมด:
            ล, บ, _ = แยกsid(sid)
            ต่อบท["%s/%s" % (ล, บ)] += 1
        บทที่แบ่งจริง = sum(1 for n in ต่อบท.values() if n > 1)
        ยาวไม่เท่า = ต่างตัวหนังสือ = 0
        for sid, เนื้อ in ข้อทั้งหมด.items():
            ล, บ, ข = แยกsid(sid)
            ในซอง = เนื้อบท["บท"].get("%s/%s" % (ล, บ), {}).get(ฉบับ, {}).get(ข)
            if ในซอง is None:
                continue
            if len(ในซอง) != len(เนื้อ):
                ยาวไม่เท่า += 1
            if ในซอง != เนื้อ and "".join(ในซอง.split()) != "".join(เนื้อ.split()):
                ต่างตัวหนังสือ += 1
        print("   %-6s ⇒ รอยย่อหน้าในไฟล์ %s อัน · บทที่ถูกแบ่งจริง (มากกว่า 1 รอย) %s บท "
              "· ข้อที่ยาวไม่เท่าซอง %s · ข้อที่ต่างที่ตัวหนังสือ %s"
              % (ฉบับ, format(len(รอยทั้งหมด), ","), format(บทที่แบ่งจริง, ","),
                 format(ยาวไม่เท่า, ","), format(ต่างตัวหนังสือ, ",")))
        print("          เหตุผลในซอง ⇒ %s" % เหตุผล)
        # ⭐ จดไว้ให้เห็น ⇒ ฉบับที่ถูกตัดออก **ยังไม่ได้ถูกตรวจชั้นตัวหนังสือ**
        #   ⇒ วันไหนมีคนแก้ให้ความยาวตรงแล้วดันเข้าซอง ชั้นที่ 1 ของข้อ ① จะจับเลขนี้ทันที
        if ต่างตัวหนังสือ:
            print("          ⚠️ ฉบับนี้มีข้อที่ **ต่างที่ตัวหนังสือ** %s ข้อ "
                  "⇒ ดันเข้าซองเมื่อไร ข้อ ① ชั้นที่ 1 จะแดง" % format(ต่างตัวหนังสือ, ","))
        if บทที่แบ่งจริง and not ยาวไม่เท่า:
            ร้อง("%s ⇒ ซองบอกว่าไม่มี แต่นับได้ว่าแบ่งจริง %s บท และตัวบทก็ยาวเท่าซอง"
                 % (ฉบับ, format(บทที่แบ่งจริง, ",")))

    # ⑦ รอยของแต่ละฉบับตรงกันแค่ไหน ⇒ วัดไว้ให้รู้ตัว ⛔ ไม่ใช่บั๊ก
    print("\n⑦ รอยของแต่ละฉบับตรงกันแค่ไหน " + "─" * 35)
    ชื่อ = sorted(หัวบทของฉบับ)
    for i, ก in enumerate(ชื่อ):
        for ข in ชื่อ[i + 1:]:
            ชุดก = {(บท, ข้อ) for บท, s in หัวบทของฉบับ[ก].items() for ข้อ in s}
            ชุดข = {(บท, ข้อ) for บท, s in หัวบทของฉบับ[ข].items() for ข้อ in s}
            ร่วม = ชุดก & ชุดข
            print("   %s %s อัน · %s %s อัน ⇒ ขึ้นย่อหน้าที่ข้อเดียวกัน %s อัน "
                  "= %.0f%% ของ %s · %.0f%% ของ %s"
                  % (ก, format(len(ชุดก), ","), ข, format(len(ชุดข), ","),
                     format(len(ร่วม), ","),
                     len(ร่วม) * 100 / len(ชุดก) if ชุดก else 0, ก,
                     len(ร่วม) * 100 / len(ชุดข) if ชุดข else 0, ข))
    print("   ⚠️ ตรงกันไม่ครบเป็นเรื่องปกติ ⇒ **คนแปลคนละคนแบ่งย่อหน้าคนละที่**")
