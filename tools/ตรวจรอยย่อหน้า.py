def ย้ายตำแหน่ง(ต้น, เว็บ, ที่):
    """ตัวบทยาวไม่เท่าเพราะช่องว่าง ⇒ หาตำแหน่งเดียวกันบนตัวบทเว็บ ⇒ **เขียนเองอีกทาง** ⛔ ไม่ยืมของตัวพ่น
    ⇒ k = ตัวที่ไม่ใช่ช่องว่างก่อนรอย ⇒ ตำแหน่งใหม่ = ดัชนีของตัวที่ไม่ใช่ช่องว่างตัวที่ k (นับจาก 0) บนตัวบทเว็บ"""
    if ที่ == 0 or ต้น == เว็บ:
        return ที่
    k = sum(1 for ต in ต้น[:ที่] if not ต.isspace())
    ตัว = [i for i, ต in enumerate(เว็บ) if not ต.isspace()]
    return ตัว[k] if k < len(ตัว) else len(เว็บ)


def ตรวจฉบับ(ฉบับ, จากซอง, เนื้อบท):
    print("\n── %s " % ฉบับ + "─" * 56)
    if not sorted((กองตัวบท / ฉบับ).glob("*.usx.gz")):
        ร้อง("%s ⇒ ไม่มีกอง USX ให้แกะ" % ฉบับ)
        return {}

    ข้อทั้งหมด, รอยทั้งหมด, ตกหล่น, ป้ายดิบ = แกะทั้งฉบับ(ฉบับ)

    # ① ตัวบทที่แกะเอง เทียบกับซองที่เว็บใช้ ⇒ **ตัดสินทั้ง 3 ชั้น** ⛔ ไม่ใช่พิมพ์เลขทิ้งไว้
    เทียบ, ยาวไม่เท่า, ตรงเป๊ะ, ต่างช่องว่าง, ต่างตัวหนังสือ = 0, 0, 0, 0, 0
    ตัวอย่างตัวหนังสือ = []
    for sid, เนื้อ in ข้อทั้งหมด.items():
        ล, บ, ข = แยกsid(sid)
        ก้อน = เนื้อบท["บท"].get("%s/%s" % (ล, บ))
        if not ก้อน or ฉบับ not in ก้อน:
            continue
        ในซอง = ก้อน[ฉบับ].get(ข)
        if ในซอง is None:
            continue
        เทียบ += 1
        if len(ในซอง) != len(เนื้อ):
            ยาวไม่เท่า += 1
        if ในซอง == เนื้อ:
            ตรงเป๊ะ += 1
        # ⭐ ต่างกันแล้ว **ต่างที่ตรงไหน** ⇒ ทิ้งช่องว่างทุกชนิดออกแล้วยังต่าง = ตัวหนังสือเปลี่ยน
        elif "".join(ในซอง.split()) == "".join(เนื้อ.split()):
            ต่างช่องว่าง += 1
        else:
            ต่างตัวหนังสือ += 1
            if len(ตัวอย่างตัวหนังสือ) < 3:
                ตัวอย่างตัวหนังสือ.append("%s %s:%s" % (ล, บ, ข))
    print("① แกะเองได้ %s ข้อ ⇒ เทียบกับซองเนื้อบทได้ %s ข้อ ⇒ ยาวไม่เท่ากัน %s ข้อ"
          % (format(len(ข้อทั้งหมด), ","), format(เทียบ, ","), format(ยาวไม่เท่า, ",")))
    ฐาน = ฐานต่างเฉพาะช่องว่าง.get(ฉบับ)
    print("   เหมือนกันทุกตัวอักษร %s ข้อ · ต่างเฉพาะช่องว่าง %s ข้อ (ฐาน %s) "
          "· **ต่างที่ตัวหนังสือ %s ข้อ**"
          % (format(ตรงเป๊ะ, ","), format(ต่างช่องว่าง, ","),
             format(ฐาน, ",") if ฐาน is not None else "⛔ ยังไม่ตรึง",
             format(ต่างตัวหนังสือ, ",")))
    # ⭐ ยาวไม่เท่าเพราะช่องว่าง ⇒ ⛔ ไม่ร้องแล้ว (23 พ.ย. 2569) ⇒ ตำแหน่งย้ายได้ด้วยการนับตัวที่ไม่ใช่ช่องว่าง
    #   ⇒ ด่านที่ยังเฝ้าคือ ชั้นที่ 1 (ตัวหนังสือต้องตรง) · ชั้นที่ 2 (จำนวนข้อนิ่งเท่าฐาน) · ② (ย้ายเองแล้วต้องชนกับซอง)
    # ชั้นที่ 1 ⇒ กฎตาย ⛔ ไม่มีฐานให้ยืดหยุ่น ⇒ ตัวหนังสือต่างแม้ข้อเดียวคือตัวบทเปลี่ยน
    if ต่างตัวหนังสือ:
        ร้อง("%s ⇒ ตัวบทต่างที่ **ตัวหนังสือ** %s ข้อ ⛔ ไม่ใช่แค่ช่องว่าง ⇒ ตัวอย่าง %s"
             % (ฉบับ, format(ต่างตัวหนังสือ, ","), ตัวอย่างตัวหนังสือ))
    # ชั้นที่ 2 ⇒ จำนวนข้อที่ต่างเฉพาะช่องว่าง ต้องนิ่งเท่าฐานที่ตรึงไว้ 18 ต.ค. 2569
    if ฐาน is None:
        ร้อง("%s ⇒ ⛔ ยังไม่ได้ตรึงฐาน `ฐานต่างเฉพาะช่องว่าง` ⇒ นับได้ %s ข้อ "
             "⇒ เปิดดูของจริงแล้วตรึงฐานก่อน" % (ฉบับ, format(ต่างช่องว่าง, ",")))
    elif ต่างช่องว่าง != ฐาน:
        ร้อง("%s ⇒ ข้อที่ต่างเฉพาะช่องว่างขยับจากฐาน ⇒ ฐาน %s · นับได้ %s "
             "⇒ ของต้นทางหรือตัวอ่านเปลี่ยนไปแล้ว ⛔ อย่าแก้ฐานให้เตือนหายก่อนเปิดดูของจริง"
             % (ฉบับ, format(ฐาน, ","), format(ต่างช่องว่าง, ",")))

    # ② ชนกับซองที่พ่นไว้
    แกะได้ = collections.Counter()
    for sid, ที่, style in รอยทั้งหมด:
        ล, บ, ข = แยกsid(sid)
        ต้น = ข้อทั้งหมด.get(sid)
        เว็บ = เนื้อบท["บท"].get("%s/%s" % (ล, บ), {}).get(ฉบับ, {}).get(ข)
        if ต้น is not None and เว็บ is not None:
            ที่ = ย้ายตำแหน่ง(ต้น, เว็บ, ที่)
        แกะได้[("%s/%d" % (ล, int(บ)), int(ข), ที่, style)] += 1
    ในซองพ่น = collections.Counter()
    for กุญแจ, ก้อน in จากซอง.items():
        for ก in ก้อน:
            ในซองพ่น[(กุญแจ, ก["ข้อ"], ก["หลังอักษร"], ก["ป้าย"])] += 1
    ขาด = แกะได้ - ในซองพ่น
    เกิน = ในซองพ่น - แกะได้
    print("② แกะเองได้ %s รอย · ในซองที่พ่นไว้ %s รอย ⇒ ขาด %s · เกิน %s"
          % (format(sum(แกะได้.values()), ","), format(sum(ในซองพ่น.values()), ","),
             format(sum(ขาด.values()), ","), format(sum(เกิน.values()), ",")))
    if ขาด or เกิน:
        ร้อง("%s ⇒ ซองที่พ่นไว้ไม่ตรงกับที่แกะเอง ⇒ ตัวอย่าง %s"
             % (ฉบับ, (list(ขาด) + list(เกิน))[:3]))

    # ③ ป้ายดิบที่หายระหว่างทาง ต้องอธิบายได้ทุกอัน
    อธิบายได้ = sum(ตกหล่น.values())
    print("③ ป้ายย่อหน้าในไฟล์ดิบ %s อัน ⇒ เก็บได้ %s · ตกหล่นที่อธิบายได้ %s %s"
          % (format(ป้ายดิบ, ","), format(sum(แกะได้.values()), ","),
             format(อธิบายได้, ","), dict(ตกหล่น) or "{}"))
    if ป้ายดิบ != sum(แกะได้.values()) + อธิบายได้:
        ร้อง("%s ⇒ ป้ายหายโดยอธิบายไม่ได้ %s อัน"
             % (ฉบับ, format(ป้ายดิบ - sum(แกะได้.values()) - อธิบายได้, ",")))

    # ④ 🔴 ตัดตามรอยแล้วต่อกลับ ต้องได้ตัวบทเดิมเป๊ะ ⇒ นี่คือเกณฑ์ "ตัวบทครบทุกตัวอักษร"
    ตัวอักษร = ชิ้น = เพี้ยน = 0
    for กุญแจ, ก้อน in จากซอง.items():
        ล, บ = กุญแจ.split("/")
        ของบท = เนื้อบท["บท"].get(กุญแจ, {}).get(ฉบับ, {})
        ที่ของข้อ = collections.defaultdict(list)
        for ก in ก้อน:
            ที่ของข้อ[ก["ข้อ"]].append(ก["หลังอักษร"])
        for ข, ที่หลาย in ที่ของข้อ.items():
            เนื้อ = ของบท.get(str(ข))
            if เนื้อ is None:
                ร้อง("%s %s:%s ⇒ มีรอยย่อหน้าแต่ไม่มีข้อนี้ในซองเนื้อบท" % (ฉบับ, กุญแจ, ข))
                continue
            จุด = [0] + sorted(t for t in ที่หลาย if 0 < t < len(เนื้อ)) + [len(เนื้อ)]
            ท่อน = [เนื้อ[a:b] for a, b in zip(จุด, จุด[1:])]
            ชิ้น += len(ท่อน)
            ตัวอักษร += len(เนื้อ)
            if "".join(ท่อน) != เนื้อ:
                เพี้ยน += 1
    print("④ ตัดตามรอยแล้วต่อกลับ ⇒ %s ข้อ · %s ท่อน · %s ตัวอักษร ⇒ ไม่ตรงของเดิม %s ข้อ"
          % (format(sum(len(set(ก["ข้อ"] for ก in v)) for v in จากซอง.values()), ","),
             format(ชิ้น, ","), format(ตัวอักษร, ","), format(เพี้ยน, ",")))
    if เพี้ยน:
        ร้อง("%s ⇒ ตัดตามรอยแล้วตัวบทเปลี่ยน %s ข้อ" % (ฉบับ, format(เพี้ยน, ",")))

    # ⑤ ทุกรอยต้องตกตรงรอยต่อจริง
    กลางข้อ = ไม่ตรงรอยต่อ = เกินขอบ = 0
    ตัวอย่าง = []
    for กุญแจ, ก้อน in จากซอง.items():
        ของบท = เนื้อบท["บท"].get(กุญแจ, {}).get(ฉบับ, {})
        for ก in ก้อน:
            เนื้อ = ของบท.get(str(ก["ข้อ"]))
            if เนื้อ is None:
                continue
            ที่ = ก["หลังอักษร"]
            if ที่ > len(เนื้อ):
                เกินขอบ += 1
                continue
            if ที่ == 0:
                continue
            กลางข้อ += 1
            if not เนื้อ[ที่ - 1].isspace():
                ไม่ตรงรอยต่อ += 1
                if len(ตัวอย่าง) < 3:
                    ตัวอย่าง.append("%s ข้อ %s ที่ %s" % (กุญแจ, ก["ข้อ"], ที่))
    print("⑤ รอยกลางข้อ %s อัน ⇒ ตัวก่อนหน้าไม่ใช่ช่องว่าง %s · เลยขอบข้อ %s %s"
          % (format(กลางข้อ, ","), format(ไม่ตรงรอยต่อ, ","), format(เกินขอบ, ","),
             ตัวอย่าง or ""))
    if ไม่ตรงรอยต่อ or เกินขอบ:
        ร้อง("%s ⇒ มีรอยที่ไม่ตกตรงรอยต่อจริง" % ฉบับ)

    return {กุญแจ: {ก["ข้อ"] for ก in ก้อน if ก["หลังอักษร"] == 0}
            for กุญแจ, ก้อน in จากซอง.items()}


