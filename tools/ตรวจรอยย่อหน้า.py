#   ⇒ ⭐ บั๊กของการนับระหว่างเดิน จะ ⛔ ไม่โผล่มาเหมือนกันทั้งสองทาง
def สาย(ไฟล์):
    """เดินไฟล์ USX ให้จบ ⇒ คืนสายเหตุการณ์ตามลำดับในเอกสาร

    ('ข้อเริ่ม', sid) · ('ข้อจบ',) · ('ย่อหน้า', style) · ('ตัว', ข้อความ)
    ⛔ เนื้อในป้าย `note` ⇒ ไม่ใช่ตัวบท ⇒ ข้ามทั้งก้อน เอาแต่หางของมัน (ท่าเดียวกับตัวแปลง)
    """
    with gzip.open(ไฟล์) as ฟ:
        ราก = ET.parse(ฟ).getroot()
    ออก = []

    def สั้น(t):
        return t.split("}")[-1]

    def เดิน(el):
        t = สั้น(el.tag)
        if t == "verse":
            if el.get("sid"):
                ออก.append(("ข้อเริ่ม", el.get("sid")))
            elif el.get("eid"):
                ออก.append(("ข้อจบ",))
            if el.tail:
                ออก.append(("ตัว", el.tail))
            return
        if t == "note":
            if el.tail:
                ออก.append(("ตัว", el.tail))
            return
        if t == "para" and el.get("style") in ป้ายไม่ใช่ตัวบท:
            # ⭐ ทั้งก้อนรวมหางของมัน ⇒ ไม่ใช่ตัวบท ⇒ บอกตัวนับว่าข้ามได้ ⇒ ตัวนับตัดสินเองว่าข้อเปิดอยู่ไหม
            ออก.append(("ข้าม", "".join(el.itertext()) + (el.tail or "")))
            return
        if t == "para" and el.get("style") in ป้ายย่อหน้า:
            ออก.append(("ย่อหน้า", el.get("style")))
        if el.text:
            ออก.append(("ตัว", el.text))
        for ลูก in el:
            เดิน(ลูก)
        if el.tail:
            ออก.append(("ตัว", el.tail))

    เดิน(ราก)
    return ออก


def แกะเอง(ไฟล์):
    """อ่านสายเหตุการณ์แล้วสร้าง {sid: ตัวบท} กับ [(sid, หลังอักษร, ป้าย)] ขึ้นมาเอง

    **กติกาที่ต้องเหมือนตัวแปลงเป๊ะ ⇒ จดไว้ตรงนี้ให้เทียบได้ด้วยตา**
      ① ตัวบทของข้อ ถูก **เล็มช่องว่างหัวท้าย** ⇒ ตำแหน่งรอยจึงต้องลบความยาวที่เล็มหัวออก
      ② ข้อที่เล็มแล้วเหลือ `""` หรือ `"-"` คือ **ข้อไม่มีเนื้อ** ⇒ ไม่เข้าตัวบท
      ③ ป้ายที่โผล่ **นอกช่วงข้อ** เกาะกับ **ข้อถัดไปที่เริ่ม** ⇒ ค้างท้ายเล่มแล้วไม่มีข้อถัดไป = ทิ้ง
      ④ ป้ายที่ไปเกาะข้อซึ่งไม่มีเนื้อ = ทิ้ง (ไม่มีอะไรให้แบ่ง)
    """
    เหตุทั้งหมด = สาย(ไฟล์)

    ดิบ = collections.defaultdict(list)     # sid → ชิ้นตัวบทดิบ
    ยาว = collections.Counter()             # sid → ยาวแล้วกี่ตัวอักษร
    ป้าย = []                                # [sid หรือ None, ยาว ณ ตอนนั้น, style]
    อยู่ที่ = None
    for เหตุ in เหตุทั้งหมด:
        if เหตุ[0] == "ข้อเริ่ม":
            อยู่ที่ = เหตุ[1]
            ดิบ[อยู่ที่]                      # จองช่องไว้ ⇒ ข้อที่ไม่มีเนื้อจะได้ ⛔ ไม่หายเงียบ
        elif เหตุ[0] == "ข้อจบ":
            อยู่ที่ = None
        elif เหตุ[0] == "ย่อหน้า":
            ป้าย.append([อยู่ที่, ยาว[อยู่ที่] if อยู่ที่ else 0, เหตุ[1]])
        elif เหตุ[0] == "ข้าม":
            continue
        elif อยู่ที่:
            ดิบ[อยู่ที่].append(เหตุ[1])
            ยาว[อยู่ที่] += len(เหตุ[1])

    # ③ ป้ายนอกช่วงข้อ ⇒ เกาะ **ข้อถัดไปที่เริ่ม** ⇒ เดินย้อนจากท้ายไปหน้าแล้วจำข้อล่าสุดที่เจอ
    ถัดไป, ลำดับ = None, len(ป้าย) - 1
    for เหตุ in reversed(เหตุทั้งหมด):
        if เหตุ[0] == "ข้อเริ่ม":
            ถัดไป = เหตุ[1]
        elif เหตุ[0] == "ย่อหน้า":
            if ป้าย[ลำดับ][0] is None:
                ป้าย[ลำดับ][0], ป้าย[ลำดับ][1] = ถัดไป, 0
            ลำดับ -= 1

    ข้อ, ตกหล่น = {}, collections.Counter()
    for sid, ชิ้น in ดิบ.items():
        เนื้อ = "".join(ชิ้น).strip()
        if เนื้อ in ("", "-"):
            continue
        ข้อ[sid] = เนื้อ

    รอย = []
    for sid, ที่, style in ป้าย:
        if sid is None:
            ตกหล่น["ค้างท้ายเล่ม"] += 1
            continue
        if sid not in ข้อ:
            ตกหล่น["เกาะข้อที่ไม่มีเนื้อ"] += 1
            continue
        เต็ม = "".join(ดิบ[sid])
        ตัดหัว = len(เต็ม) - len(เต็ม.lstrip())
        รอย.append((sid, min(max(ที่ - ตัดหัว, 0), len(ข้อ[sid])), style))
    return ข้อ, รอย, ตกหล่น, len(ป้าย)


def แยกsid(sid):
    เล่ม, บทข้อ = sid.split(" ")
    บท, ข = บทข้อ.split(":")
    return เล่ม, บท, ข


_ที่แกะไว้ = {}


def แกะทั้งฉบับ(ฉบับ):
    """แกะกอง USX ของฉบับหนึ่งให้ครบทุกเล่ม ⇒ จำไว้ เพราะโหมด `--ทดสอบตัวเอง` เรียกซ้ำหลายรอบ"""
    if ฉบับ in _ที่แกะไว้:
        return _ที่แกะไว้[ฉบับ]
    ข้อทั้งหมด, รอยทั้งหมด = {}, []
    ตกหล่น, ป้ายดิบ = collections.Counter(), 0
    for ไฟล์ in sorted((กองตัวบท / ฉบับ).glob("*.usx.gz")):
        ข้อ, รอย, ตก, ดิบ = แกะเอง(ไฟล์)
        ข้อทั้งหมด.update(ข้อ)
        รอยทั้งหมด += รอย
        ตกหล่น.update(ตก)
        ป้ายดิบ += ดิบ
    _ที่แกะไว้[ฉบับ] = (ข้อทั้งหมด, รอยทั้งหมด, ตกหล่น, ป้ายดิบ)
    return _ที่แกะไว้[ฉบับ]


