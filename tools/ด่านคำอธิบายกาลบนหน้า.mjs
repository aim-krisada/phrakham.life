/**
 * อ่านท่อนของกาลจากรากหนึ่ง (แถวในกล่อง หรือ `dd` ของการ์ด) ⇒ รันในหน้า
 * ⇒ คืนของที่ตาเห็น + ตัวหนังสือกรีกที่ภาษาไม่ใช่ `grc` + ตัวหนังสือไทยที่ติด `grc`
 */
function อ่านท่อนในหน้า([sel, กรีก]) {
  const ราก = document.querySelector(sel)
  if (!ราก) return null
  const ท่อน = (k) => ราก.querySelector(`[data-ท่อน="${k}"]`)
  const หัว = (k) => ท่อน(k)?.querySelector('.pk-หัวท่อนกาล')?.textContent.trim() ?? null
  const ภาษาผิด = []
  const เดิน = document.createTreeWalker(ราก, NodeFilter.SHOW_TEXT)
  const มีกรีก = new RegExp(กรีก)
  for (let n = เดิน.nextNode(); n; n = เดิน.nextNode()) {
    if (!n.parentElement.closest('[data-ท่อน]')) continue
    const t = n.textContent.trim()
    if (!t) continue
    const ภาษา = n.parentElement.closest('[lang]')?.getAttribute('lang') ?? null
    if (มีกรีก.test(t) && ภาษา !== 'grc') ภาษาผิด.push(`${t.slice(0, 20)} ⇒ lang=${ภาษา}`)
    if (!มีกรีก.test(t) && /[฀-๿]/.test(t) && ภาษา === 'grc') ภาษาผิด.push(`${t.slice(0, 20)} ⇒ ไทยแต่ lang=grc`)
  }
  return {
    หัว: { ความหมาย: หัว('ความหมาย'), อ่านไทย: หัว('อ่านไทย'), ตัวอย่าง: หัว('ตัวอย่าง'), ระวัง: หัว('ระวัง') },
    ความหมาย: ท่อน('ความหมาย')?.querySelector('[data-ความหมาย]')?.textContent.trim() ?? null,
    อ่านไทย: ท่อน('อ่านไทย')?.querySelector('[data-อ่านไทย]')?.textContent.trim() ?? null,
    ตัวอย่าง: [...(ท่อน('ตัวอย่าง')?.querySelectorAll('[data-ตัวอย่าง]') ?? [])].map((x) => x.textContent.trim()),
    ระวัง: ท่อน('ระวัง')?.querySelector('[data-ตัวอย่าง]')?.textContent.trim() ?? null,
    ภาษาผิด,
  }
}

/** เทียบท่อนบนหน้ากับตาราง ⇒ คืนรายการที่ไม่ตรง ⇒ ใช้ทั้งกล่อง (①) และการ์ด (②) */
function เทียบท่อน(บน, ควร, ป้าย, ข้อ) {
  const ตก = []
  if (!บน) return [`${ป้าย} ⇒ ${ข้อ} ⛔ หาแถวของกาลนี้ไม่เจอ`]
  for (const [k, v] of Object.entries(ควร.หัว))
    if ((บน.หัว[k] ?? null) !== v) ตก.push(`${ป้าย} ⇒ ${ข้อ} หัวท่อน ${k} เป็น «${บน.หัว[k]}» ⛔ ควรเป็น «${v}»`)
  for (const k of ['ความหมาย', 'อ่านไทย', 'ระวัง'])
    if ((บน[k] ?? null) !== ควร[k]) ตก.push(`${ป้าย} ⇒ ${ข้อ} ท่อน ${k} เป็น «${บน[k]}» ⛔ ไม่ตรงตาราง «${ควร[k]}»`)
  if (JSON.stringify(บน.ตัวอย่าง) !== JSON.stringify(ควร.ตัวอย่าง))
    ตก.push(`${ป้าย} ⇒ ${ข้อ} ท่อนตัวอย่างเป็น ${JSON.stringify(บน.ตัวอย่าง)} ⛔ ไม่ตรงตาราง ${JSON.stringify(ควร.ตัวอย่าง)}`)
  for (const x of บน.ภาษาผิด) ตก.push(`${ป้าย} ⇒ ③ ภาษาของตัวหนังสือผิด ⇒ ${x}`)
  return ตก
}

