"""⭐⭐ **เดือนของโควตาเสียง ⇒ นับตามเวลาแปซิฟิก ⛔ เวลาไทย** ⇒ ที่เดียวทั้งที่เก็บ

ใบงาน ⇒ ดูหัว `tools/ด่านเดือนโควตา.py` (ลิงก์ใบอยู่ที่นั่น)

**ทำไมไม่ใช้เวลาไทย**
  ⇒ ส่วนฟรี 1,000,000 ตัวอักษรของ Cloud TTS รีเซ็ตทุกเดือนปฏิทินของบัญชีเงิน
  ⇒ รายงานบัญชีเงินของ Google Cloud ลงวันที่เป็นเวลาแปซิฟิก (US & Canada) ⇒ ช้ากว่าไทย 14–15 ชั่วโมง
  ⇒ งานเสียงรายคืนวิ่ง 03:30 เวลาไทย = 12:30/11:30 ของ *วันก่อน* ที่แปซิฟิก
  ⇒ ถ้านับเดือนตามเวลาไทย ⇒ คืนวันที่ 1 สมุดของเราเริ่มเดือนใหม่จาก 0 ⇒ แต่ Google ยังบวกเข้าเดือนเก่า
  ⇒ คืนสุดท้ายที่ใช้จนชนเพดาน + คืนวันที่ 1 = เดือนเก่าเกินเพดานที่เราตั้ง

**คืนสุดท้ายของเดือน** ⇒ รอบถัดไป (อีก `ห่างกันกี่ชั่วโมง`) ตกเดือนใหม่ของแปซิฟิกแล้ว
  ⇒ รอบนี้คือโอกาสสุดท้ายที่จะใช้โควตาที่เหลือของเดือนนี้ ⇒ `tools/พ่นเสียงพระคำ.py --คืนนี้` ใช้ที่เหลือถึงเพดาน
  ⇒ ตัวอย่าง ⇒ รอบ 03:30 เวลาไทยของวันที่ 1 ธ.ค. = 30 พ.ย. ที่แปซิฟิก ⇒ เป็นรอบสุดท้ายของเดือน พ.ย.

⛔ **สมุดเล่มเดียวใช้ร่วมกันหลายเครื่องมือ** ⇒ `ga.QuotaLedger(month=...)` ⇒ ทุกตัวต้องส่งเดือนจากไฟล์นี้
  ⇒ ตัวหนึ่งใช้เวลาไทย อีกตัวใช้แปซิฟิก ⇒ ช่วงคาบเกี่ยว 2 ตัวจะสลับเดือนกันไปมา ⇒ สมุดล้างยอดผิด
"""
from datetime import datetime, timedelta, timezone
from zoneinfo import ZoneInfo

เขตเวลาของบัญชีเงิน = ZoneInfo("America/Los_Angeles")
#: งานเสียงรายคืนวิ่งวันละครั้ง (`phrakham-tts-nightly.timer`)
ห่างกันกี่ชั่วโมง = 24


def เดือนของGoogle(ตอนนี้: datetime | None = None) -> str:
    """`YYYY-MM` ของเดือนบัญชีเงิน ⇒ ส่งให้ `QuotaLedger(month=...)`"""
    ตอนนี้ = ตอนนี้ or datetime.now(timezone.utc)
    return ตอนนี้.astimezone(เขตเวลาของบัญชีเงิน).strftime("%Y-%m")


def คืนสุดท้ายของเดือน(ตอนนี้: datetime | None = None) -> bool:
    """รอบถัดไปตกเดือนใหม่แล้ว ⇒ รอบนี้ใช้โควตาที่เหลือได้หมด"""
    ตอนนี้ = ตอนนี้ or datetime.now(timezone.utc)
    return เดือนของGoogle(ตอนนี้ + timedelta(hours=ห่างกันกี่ชั่วโมง)) != เดือนของGoogle(ตอนนี้)


def งบคืนนี้(เพดาน: int, ใช้ไป: int, กันให้เรื่องเล่า: int, คืนละ: int, คืนสุดท้าย: bool, งบที่สั่ง: int | None = None) -> tuple[int, int]:
    """คืน `(งบคืนนี้, งบที่เหลือของเดือน)`

    ⇒ คืนปกติ ⇒ ไม่เกินคืนละ และไม่กินส่วนที่กันให้เรื่องเล่า
    ⇒ คืนสุดท้าย ⇒ ใช้ที่เหลือถึงเพดานทั้งหมด ⇒ ส่วนที่กันไว้ให้เรื่องเล่าไม่ได้ใช้แล้ว ⇒ เดือนหมดอยู่ดี
    ⇒ ⛔ เกินเพดานไม่ได้ทุกกรณี ⇒ เพดานต่ำกว่าส่วนฟรีอยู่แล้ว
    """
    งบเดือน = เพดาน - ใช้ไป - (0 if คืนสุดท้าย else กันให้เรื่องเล่า)
    ปกติ = งบที่สั่ง if งบที่สั่ง is not None else (งบเดือน if คืนสุดท้าย else คืนละ)
    return min(ปกติ, งบเดือน), งบเดือน
