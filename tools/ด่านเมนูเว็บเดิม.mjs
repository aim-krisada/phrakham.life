const ที่โฟกัส = (แท็บ) =>
  แท็บ.evaluate(() => {
    const a = document.activeElement
    const ปุ่ม = [...document.querySelectorAll('[data-ปุ่ม="เมนูเว็บเดิม"]')].find((x) => x.getClientRects().length)
    const ไอดี = ปุ่ม?.getAttribute('aria-controls')
    const s = a ? getComputedStyle(a) : null
    return {
      ที่ปุ่ม: a === ปุ่ม,
      ในกล่อง: !!(ไอดี && a && document.getElementById(ไอดี)?.contains(a)),
      ขยาย: ปุ่ม?.getAttribute('aria-expanded'),
      มีกล่อง: !!(ไอดี && document.getElementById(ไอดี)),
      วงโฟกัส: !!s && ((s.outlineStyle !== 'none' && parseFloat(s.outlineWidth) > 0) || (s.boxShadow && s.boxShadow !== 'none')),
      โฟกัสแป้น: !!a && a.matches(':focus-visible'),
    }
  })

