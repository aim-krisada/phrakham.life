// รอให้ที่อยู่หนึ่งตอบก่อน แล้วค่อยไปต่อ — ใช้ใน CI หลังสั่งเสิร์ฟเว็บไว้เบื้องหลัง
//
// ⛔ ไม่ใช้ `sleep` เอาไว้เดา: ตัวรันที่ช้ากว่าปกติจะทำให้ด่านล้มโดยไม่มีอะไรผิด
//   และตัวรันที่เร็วจะเสียเวลารอเปล่า ⇒ ถามจนกว่ามันจะตอบ แล้วยอมแพ้พร้อมบอกเหตุผลถ้าเกินเวลา
//
// ⇒ ยกมาจาก `v3/pleng` → `tools/wait-for.mjs` (ตรรกะเดียวกัน แปลชื่อกับข้อความเป็นไทย)
//
//   node tools/รอให้ที่อยู่ตอบ.mjs <ที่อยู่> [เพดานเวลามิลลิวินาที]

const ที่อยู่ = process.argv[2]
const เพดาน = Number(process.argv[3] || 60000)
if (!ที่อยู่) {
  console.error('ใช้: node tools/รอให้ที่อยู่ตอบ.mjs <ที่อยู่> [เพดานเวลามิลลิวินาที]')
  process.exit(2)
}

const เริ่ม = Date.now()
let ครั้งสุดท้าย = 'ยังไม่ได้ลอง'

while (Date.now() - เริ่ม < เพดาน) {
  try {
    const r = await fetch(ที่อยู่, { signal: AbortSignal.timeout(4000) })
    if (r.ok) {
      console.log(`พร้อมแล้ว: ${ที่อยู่} → ${r.status} (รอ ${Date.now() - เริ่ม} มิลลิวินาที)`)
      process.exit(0)
    }
    ครั้งสุดท้าย = `HTTP ${r.status}`
  } catch (e) {
    ครั้งสุดท้าย = String(e.message || e)
  }
  await new Promise((r) => setTimeout(r, 300))
}

console.error(`⛔ รอ ${ที่อยู่} ไม่ขึ้นภายใน ${เพดาน} มิลลิวินาที · ครั้งสุดท้าย: ${ครั้งสุดท้าย}`)
process.exit(1)
