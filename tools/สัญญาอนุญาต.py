#!/usr/bin/env python3
"""ดึงข้อความสัญญาอนุญาตฉบับเต็มของ TCV ออกจาก metadata.xml มาให้หน้าเว็บแสดง

⭐ **ทำไมต้องมี** ⇒ สัญญา CC BY-SA 4.0 บังคับให้เราบอกที่มา
   ⇒ เจ้าของเขียนถ้อยคำที่ต้องแสดงไว้ให้แล้ว ทั้งภาษาไทยและภาษาอังกฤษ

⛔ **ห้ามพิมพ์ข้อความสัญญาอนุญาตเอง** ⇒ หยิบจากไฟล์ต้นทางตรง ๆ ทุกตัวอักษร
   **ทำไม** ⇒ พิมพ์เองแล้วพลาด 1 คำ = เราแสดงสัญญาผิดจากที่เจ้าของเขียน
   ⇒ และวันที่เจ้าของออกซิปรุ่นใหม่ ถ้อยคำในเว็บจะตามไปเองเมื่อพ่นใหม่

**ข้อความอยู่ 2 ที่ในไฟล์เดียวกัน**
  `copyright/fullStatement`  ⇒ ประกาศลิขสิทธิ์สั้น ๆ ที่ต้องขึ้นหน้าปก
  `promotion/promoVersionInfo` ⇒ เนื้อสัญญาเต็ม มีทั้งไทยและอังกฤษ

⛔ สคริปต์นี้ **ไม่สรุป ไม่ตีความ ไม่ให้คำแนะนำทางกฎหมาย**
   ⇒ มันแค่ยกข้อความกับที่อยู่เว็บที่ฝังอยู่ในข้อความออกมาให้ครบ

รัน  py -3.14 tools/สัญญาอนุญาต.py            ⇒ พิมพ์สรุปสั้น ๆ ให้ดูด้วยตา
     py -3.14 tools/สัญญาอนุญาต.py --ออกที่ C:/gh/phrakham3
                                              ⇒ เขียน public/data/license/tcv.json

ที่มา  ใบงาน https://github.com/aim-krisada/phrakham3/issues/6
"""
import io
import json
import os
import sys
import xml.etree.ElementTree as ET

ที่เก็บ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
METADATA = os.path.join(ที่เก็บ, '_แตก', 'tcv', 'usx-rev2-release', 'metadata.xml')


def ย่อหน้าใน(el):
    """ยกเนื้อในป้าย xhtml ออกมาเป็นย่อหน้าทีละอัน ⛔ ไม่ตัดตัวอักษรไหนทิ้ง

    แต่ละย่อหน้าคืนเป็น {ป้าย, ตัวหนังสือ, ลิงก์}
      `ป้าย`      p หรือ h3 ⇒ หน้าเว็บจะได้รู้ว่าอันไหนเป็นหัวข้อ
      `ตัวหนังสือ` ตัวหนังสือทั้งย่อหน้า ต่อกันตามลำดับเดิม
      `ลิงก์`      ที่อยู่เว็บที่ฝังอยู่ในย่อหน้านั้น ⇒ มีเฉพาะย่อหน้าที่มีลิงก์
    """
    ออก = []
    for ย in el:
        ตัวหนังสือ = ''.join(ย.itertext())
        ก้อน = {'ป้าย': ย.tag, 'ตัวหนังสือ': ตัวหนังสือ}
        ลิงก์ = [a.get('href') for a in ย.iter('a') if a.get('href')]
        if ลิงก์:
            ก้อน['ลิงก์'] = ลิงก์
        ออก.append(ก้อน)
    return ออก


def ดึง(ทาง=METADATA):
    """เปิด metadata.xml แล้วคืนก้อนสัญญาอนุญาตที่หน้าเว็บอ่านไปแสดงได้เลย"""
    ราก = ET.parse(ทาง).getroot()
    ประกาศ = ราก.find('./copyright/fullStatement/statementContent')
    เต็ม = ราก.find('./promotion/promoVersionInfo')
    if ประกาศ is None or เต็ม is None:
        raise SystemExit('⛔ หาช่อง copyright หรือ promotion ใน %s ไม่เจอ' % ทาง)
    ประกาศย่อหน้า = ย่อหน้าใน(ประกาศ)
    เต็มย่อหน้า = ย่อหน้าใน(เต็ม)
    ลิงก์ทั้งหมด = []
    for ก in ประกาศย่อหน้า + เต็มย่อหน้า:
        for l in ก.get('ลิงก์', []):
            if l not in ลิงก์ทั้งหมด:
                ลิงก์ทั้งหมด.append(l)
    ระบุ = ราก.find('./identification')
    เจ้าของ = ราก.find('./agencies/rightsHolder')
    หา = lambda el, ป: (el.findtext(ป) or '').strip() if el is not None else ''
    return {
        'คำอธิบาย': 'ข้อความสัญญาอนุญาตของตัวบทไทย TCV ⇒ หน้าเว็บอ่านไฟล์นี้ไปแสดงได้เลย',
        'ที่มาของข้อความ': 'metadata.xml ในซิปที่เจ้าของแจก ⇒ ช่อง copyright '
                            'และช่อง promotion',
        '⛔ ไม่ได้พิมพ์เอง': 'ทุกตัวอักษรยกมาจากไฟล์ต้นทางด้วย tools/สัญญาอนุญาต.py '
                              '⇒ เจ้าของออกซิปรุ่นใหม่เมื่อไร พ่นใหม่แล้วถ้อยคำตามไปเอง',
        '⛔ ไม่ใช่คำแนะนำทางกฎหมาย': 'ไฟล์นี้คือถ้อยคำของเจ้าของ ⛔ ไม่ใช่ความเห็นของเรา',
        'ฉบับ': 'TCV',
        'ชื่อผลงาน': หา(ระบุ, 'name'),
        'ชื่อผลงานภาษาไทย': หา(ระบุ, 'nameLocal'),
        'ชื่อย่อ': หา(ระบุ, 'abbreviation'),
        'แปลเสร็จเมื่อ': หา(ระบุ, 'dateCompleted'),
        'เจ้าของสิทธิ์': {'ชื่อ': หา(เจ้าของ, 'name'), 'ชื่อย่อ': หา(เจ้าของ, 'abbr'),
                          'ที่อยู่เว็บ': หา(เจ้าของ, 'url')},
        'ประกาศลิขสิทธิ์ที่ต้องขึ้นหน้าปก': {
            'อยู่ที่ในไฟล์ต้นทาง': 'copyright/fullStatement/statementContent',
            'ชนิดเนื้อหา': ประกาศ.get('type'),
            'ย่อหน้า': ประกาศย่อหน้า},
        'สัญญาอนุญาตฉบับเต็ม': {
            'อยู่ที่ในไฟล์ต้นทาง': 'promotion/promoVersionInfo',
            'ชนิดเนื้อหา': เต็ม.get('contentType'),
            'มีทั้งไทยและอังกฤษ': True,
            'ย่อหน้า': เต็มย่อหน้า},
        'ที่อยู่เว็บที่ฝังอยู่ในข้อความ': ลิงก์ทั้งหมด,
    }


def main(args):
    if not os.path.exists(METADATA):
        print('⛔ ยังไม่มี %s\n   สั่ง  py -3.14 tools/แตกกอง.py tcv  ก่อน' % METADATA)
        return 1
    ก้อน = ดึง()
    print('ชื่อผลงาน  %s' % ก้อน['ชื่อผลงาน'])
    print('เจ้าของ    %s' % ก้อน['เจ้าของสิทธิ์']['ชื่อ'])
    print('ประกาศลิขสิทธิ์ %d ย่อหน้า · สัญญาฉบับเต็ม %d ย่อหน้า'
          % (len(ก้อน['ประกาศลิขสิทธิ์ที่ต้องขึ้นหน้าปก']['ย่อหน้า']),
             len(ก้อน['สัญญาอนุญาตฉบับเต็ม']['ย่อหน้า'])))
    print('ที่อยู่เว็บที่ฝังอยู่ในข้อความ %d อัน ⇒ %s'
          % (len(ก้อน['ที่อยู่เว็บที่ฝังอยู่ในข้อความ']),
             ' · '.join(ก้อน['ที่อยู่เว็บที่ฝังอยู่ในข้อความ'])))
    if '--ออกที่' in args:
        ราก = args[args.index('--ออกที่') + 1].rstrip('/')
        ทาง = ราก + '/public/data/license/tcv.json'
        os.makedirs(os.path.dirname(ทาง), exist_ok=True)
        with open(ทาง, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(ก้อน, f, ensure_ascii=False, separators=(',', ':'))
        print('เขียน %s (%s ไบต์)' % (ทาง, format(os.path.getsize(ทาง), ',')))
    return 0


if __name__ == '__main__':
    # ⚠️ ห่อ stdout ตรงนี้เท่านั้น ⛔ ไม่ห่อตอน import
    #    ⇒ สคริปต์ที่ import ไฟล์นี้ ห่อ stdout ของมันไปแล้ว ⇒ ห่อซ้ำ = ระเบิด
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    sys.exit(main(sys.argv[1:]))
