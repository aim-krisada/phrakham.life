import argparse, gzip, io, json, sys, zipfile, re
from pathlib import Path

import brotli

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

เว็บปริยาย = 'C:/gh/phrakham3'
ซิปไทยปริยาย = 'C:/gl/v3/phrakham/source/tcv/usx-rev2-release.zip'
เล่มปริยาย = ['PSA', 'ISA', 'GEN']
ชื่อไทย = {'PSA': 'สดุดี', 'ISA': 'อิสยาห์', 'GEN': 'ปฐมกาล'}


def กิโล(n):
    """ไบต์เป็นกิโลไบต์ ⇒ 1 กิโลไบต์ = 1024 ไบต์"""
    return round(n / 1024, 1)


def บีบ(ก้อน):
    """คืนขนาดหลังบีบด้วย gzip กับ brotli ⇒ ระดับแรงสุดแบบที่เซิร์ฟเวอร์ตั้งไว้ล่วงหน้าได้"""
    return {
        'gzip': len(gzip.compress(ก้อน, 9, mtime=0)),
        'brotli': len(brotli.compress(ก้อน, quality=11)),
    }


def วัดชุดไฟล์(ชิ้น):
    """ชิ้น = รายการไบต์ของแต่ละบท ⇒ คืนตัวเลขทั้ง 3 ท่า"""
    ดิบ = sum(len(b) for b in ชิ้น)
    ทั้งเล่ม = บีบ(b''.join(ชิ้น))
    ทีละบท = {'gzip': 0, 'brotli': 0}
    for b in ชิ้น:
        ผล = บีบ(b)
        ทีละบท['gzip'] += ผล['gzip']
        ทีละบท['brotli'] += ผล['brotli']
    return {
        'จำนวนบท': len(ชิ้น),
        'ดิบ': ดิบ,
        'บีบทั้งเล่ม': ทั้งเล่ม,
        'บีบทีละบทแล้วรวม': ทีละบท,
    }


def อ่านชั้นอ่าน(เว็บ, เล่ม):
    """ไฟล์รายบทของชั้นอ่านที่เว็บใช้จริงวันนี้"""
    ที่ = Path(เว็บ) / 'public' / 'data' / 'read' / เล่ม
    ไฟล์ = sorted(ที่.glob('*.json'))
    if not ไฟล์:
        raise SystemExit(f'⛔ ไม่เจอไฟล์ชั้นอ่านของเล่ม {เล่ม} ที่ {ที่}')
    return [f.read_bytes() for f in ไฟล์]


# ตัวคั่นย่อหน้า/หัวข้อใน USX ⇒ เราตัดออกหมด เหลือแต่ตัวอักษรของข้อ
ตัดแท็ก = re.compile(r'<[^>]+>')


def อ่านตัวบทไทย(ซิป, เล่ม):
    """ถอดตัวบทไทยจาก USX เป็นก้อนต่อบท ⇒ รูปเดียวกับชั้นอ่าน (ข้อ → ข้อความ)

    ⚠️ นี่คือ **การประมาณ** ⇒ พ่นจริงจะมีช่องอื่นเพิ่ม (ชื่อเล่ม เลขบท ที่มา)
       และอาจแตกคำเป็นชิ้นเหมือนฝั่งภาษาเดิม ⇒ ของจริงจะใหญ่กว่านี้เล็กน้อย
    """
    z = zipfile.ZipFile(ซิป)
    ข้อความ = z.read(f'release/USX_1/{เล่ม}.usx').decode('utf-8')

    บท = {}   # เลขบท → {เลขข้อ: ข้อความ}
    บทนี้ = None
    ข้อนี้ = None
    for ชิ้นส่วน in re.split(r'(<[^>]+>)', ข้อความ):
        if ชิ้นส่วน.startswith('<'):
            m = re.match(r'<chapter number="(\d+)"[^>]*sid=', ชิ้นส่วน)
            if m:
                บทนี้, ข้อนี้ = int(m.group(1)), None
                บท.setdefault(บทนี้, {})
                continue
            m = re.match(r'<verse number="([^"]+)"[^>]*sid=', ชิ้นส่วน)
            if m:
                ข้อนี้ = m.group(1)
                บท[บทนี้].setdefault(ข้อนี้, '')
                continue
            if ชิ้นส่วน.startswith('<verse eid='):
                ข้อนี้ = None
            continue
        if บทนี้ is not None and ข้อนี้ is not None:
            บท[บทนี้][ข้อนี้] += ชิ้นส่วน

    ชิ้น = []
    for เลขบท in sorted(บท):
        ก้อน = {
            'เล่ม': เล่ม,
            'บท': เลขบท,
            'ฉบับ': 'TCV',
            'ข้อ': {k: v.strip() for k, v in บท[เลขบท].items()},
        }
        ชิ้น.append(json.dumps(ก้อน, ensure_ascii=False).encode('utf-8'))
    return ชิ้น


def พิมพ์ตาราง(หัว, ผล):
    print(f'\n### {หัว}\n')
    print('| เล่ม | บท | ดิบ | บีบทั้งเล่ม gzip | บีบทั้งเล่ม brotli | บีบทีละบทรวม gzip | บีบทีละบทรวม brotli |')
    print('|---|---:|---:|---:|---:|---:|---:|')
    for เล่ม, ค in ผล.items():
        print(f"| {ชื่อไทย.get(เล่ม, เล่ม)} ({เล่ม}) | {ค['จำนวนบท']} "
              f"| {กิโล(ค['ดิบ'])} กิโลไบต์ "
              f"| {กิโล(ค['บีบทั้งเล่ม']['gzip'])} กิโลไบต์ "
              f"| {กิโล(ค['บีบทั้งเล่ม']['brotli'])} กิโลไบต์ "
              f"| {กิโล(ค['บีบทีละบทแล้วรวม']['gzip'])} กิโลไบต์ "
              f"| {กิโล(ค['บีบทีละบทแล้วรวม']['brotli'])} กิโลไบต์ |")


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--เว็บ', default=เว็บปริยาย)
    p.add_argument('--ซิปไทย', default=ซิปไทยปริยาย)
    p.add_argument('--เล่ม', nargs='*', default=เล่มปริยาย)
    p.add_argument('--ออกเป็นเจสัน', default='')
    a = p.parse_args()

    ผลภาษาเดิม = {ล: วัดชุดไฟล์(อ่านชั้นอ่าน(a.เว็บ, ล)) for ล in a.เล่ม}
    ผลไทย = {ล: วัดชุดไฟล์(อ่านตัวบทไทย(a.ซิปไทย, ล)) for ล in a.เล่ม}

    print('# หนึ่งเล่มหนักกี่ไบต์')
    print(f'\nชั้นอ่านที่วัด: `{a.เว็บ}/public/data/read/`')
    print(f'ตัวบทไทยที่วัด: `{a.ซิปไทย}` (อ่านในซิป ⛔ ไม่แตกไฟล์ ⛔ ไม่เข้าที่เก็บ)')
    พิมพ์ตาราง('① ชั้นอ่านวันนี้ — ⚠️ เป็นตัวบทภาษาเดิม ฮีบรู/กรีก ⛔ ไม่ใช่ไทย', ผลภาษาเดิม)
    พิมพ์ตาราง('② ตัวบทไทย TCV ถอดจากต้นฉบับ — ประมาณการ ⛔ ยังไม่ได้พ่นจริง', ผลไทย)

    if a.ออกเป็นเจสัน:
        Path(a.ออกเป็นเจสัน).write_text(json.dumps(
            {'ชั้นอ่านภาษาเดิม': ผลภาษาเดิม, 'ตัวบทไทยประมาณการ': ผลไทย},
            ensure_ascii=False, indent=1), encoding='utf-8')
        print(f'\nเขียนผลดิบลง `{a.ออกเป็นเจสัน}`')


if __name__ == '__main__':
    main()
