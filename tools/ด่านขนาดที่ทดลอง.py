        # ⑦🔴 **เส้นจริงที่ main() ใช้ (`เพดานชิ้นงานเมกะไบต์`) ยังแดงเมื่อเกิน** (ใบงาน v3/phrakham#103)
        #   ⇒ ⑤ ⑥ พิสูจน์แค่ว่า *ตัวเทียบ* ทำงาน ⇒ ⛔ ไม่ได้พิสูจน์ว่า *เลขที่ตั้งไว้* ยังกัดได้
