// ด่านตรวจ ④ — axe-core บนหน้าจริง (WCAG 2.2 ระดับ AA)
//
// **นี่คือด่าน ⛔ ไม่ใช่รายงาน** — ล้มแล้วคืนรหัสไม่เป็นศูนย์ ⇒ ท่อ CI แดง
//
// ⛔ **ยิงใส่หน้าจริงในเบราว์เซอร์จริง ⛔ ไม่ใช่ DOM ที่ปั้นขึ้นในไฟล์เทส**
//   DOM ปลอมพิสูจน์ได้แค่ว่า DOM ปลอมนั้นเข้าถึงได้ ⇒ ⛔ ไม่ได้พูดถึงหน้าที่คนเปิดเลย
//   ⇒ ใน CI ยิงใส่ **เว็บที่สร้างเสร็จ** ⇒ ของที่ถูกตรวจคือชิ้นเดียวกับที่จะถูกวาง
//
// ⚠️ **เขียวแล้วยัง ⛔ ไม่ได้แปลว่าผ่าน WCAG ครบ** — axe จับได้ราวหนึ่งในสามของข้อทั้งหมด
//   มันบอกไม่ได้ว่าป้ายกำกับสื่อความหรือเปล่า ลำดับการอ่านตรงกับลำดับที่ตาเห็นไหม
//   ⇒ "0 ข้อผิด" = "ไม่มีข้อผิดที่เครื่องหาเจอ" ⛔ ไม่ใช่ "ผ่าน WCAG 2.2 AA"
//
// ⇒ ยกมาจาก `v3/pleng` → `tools/gate-axe.mjs` ⛔ ไม่ลอกทั้งไฟล์
//   ตัดทิ้ง: การสวมทับคลังเพลง (`stubSongStore`) และรายชื่อหน้าของเพลง
//   เพิ่มเอง: **ตรวจตอนกล่องเปิดด้วย** เพราะเนื้อในกล่อง `<details>` ไม่ถูกตรวจตอนปิด
//
// ⭐⭐ **ตรวจ 2 ชั้น: ไฟล์ดิบ กับ หลังโค้ดทำงาน** (คนตรวจ !12 ทัก ③ · 29 ส.ค. 2569)
//   **ของจริงที่พังมาแล้ว** — ถอด `lang="th"` ออกจากไฟล์ `.html` ที่สร้างเสร็จ
//   ⇒ **ด่านรุ่นก่อนยังเขียว** เพราะโค้ดของเว็บเติม `lang` กลับให้ตอนมันเริ่มทำงาน
//   ⇒ แต่ผู้อ่านที่ปิด JavaScript หรือเน็ตช้า ได้หน้าที่ ⛔ ไม่บอกภาษา ⇒ ผิด WCAG SC 3.1.1
//   ⇒ **เหตุผลเต็มกับวิธีตัดโค้ดออก อยู่ที่ `tools/หน้าที่ตรวจ.mjs`** ⛔ ไม่จดซ้ำที่นี่
//
// **วิธีพิสูจน์ว่าด่านนี้แดงได้จริง** ⇒ ถอด `lang="th"` ออกจากไฟล์ `.html` ที่สร้างเสร็จ แล้วยิงใส่
//
//   node tools/ด่านการเข้าถึง.mjs <ที่อยู่เว็บ>

import { chromium } from 'playwright'
import { createRequire } from 'node:module'
import { หน้าทั้งหมด, เส้นทางเว็บ, ปิดโค้ดของเว็บ, ชั้นของหน้า, รอบทในที่อยู่, รอแผนภาพครบ } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const require = createRequire(import.meta.url)
const ที่อยู่axe = require.resolve('axe-core/axe.min.js')

const ความกว้าง = [412, 1280]

// ชุดระดับ AA ที่เรายืนอยู่ ⛔ ไม่ใส่ป้าย AAA — เรา ⛔ ไม่ได้อ้างว่าทั้งเว็บผ่าน AAA
const ป้าย = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22a', 'wcag22aa']

// ⚠️ รายการป้ายอย่างเดียว ⛔ ไม่พอ — axe มีกฎบางข้อที่ถูก **ปิดไว้** ตั้งแต่ต้น
//   กฎที่ปิดอยู่จะไม่ถูกรันเลยแม้ป้ายของมันอยู่ในรายการข้างบน ⇒ ด่านเขียวทั้งที่หน้าพัง
//   ⇒ กฎที่เราอยากได้ ต้องเรียกชื่อมันทีละข้อ
// `label-content-name-mismatch` = WCAG 2.5.3 Label in Name (ระดับ A)
//   axe ปิดไว้เพราะมันติดป้าย `experimental`
const กฎเพิ่ม = { 'label-content-name-mismatch': { enabled: true } }

const เบราว์เซอร์ = await chromium.launch()
const ที่ตก = []
let ตรวจไป = 0
let ตัดสินไม่ได้ = 0

for (const หน้า of หน้าทั้งหมด) {
 // ⭐ หน้าที่บทมาจากคำถามท้ายที่อยู่ มีเฉพาะชั้นที่โค้ดทำงาน ⇒ เหตุผลอยู่ที่ `ชั้นของหน้า`
 for (const ชั้น of ชั้นของหน้า(หน้า)) {
  for (const เปิดกล่อง of [false, true]) {
    for (const w of ความกว้าง) {
      const ctx = await เบราว์เซอร์.newContext({ viewport: { width: w, height: 900 } })
      const แท็บ = await ctx.newPage()
      if (ชั้น.ปิดโค้ด) await ปิดโค้ดของเว็บ(แท็บ)
      await แท็บ.goto(ฐาน + encodeURI(หน้า.ที่อยู่), { waitUntil: 'domcontentloaded' })
      await แท็บ.waitForSelector('article.pk-เนื้อ h1')
      // ⭐ ที่อยู่ที่ขอบทมาด้วย (`?c=`) ⇒ รอหมุดของบทนั้นก่อน ⛔ ไม่งั้นตรวจบทแรกแทนบทยาว
      await รอบทในที่อยู่(แท็บ, หน้า.ที่อยู่)
      if (เปิดกล่อง) {
        await แท็บ.evaluate(() => {
          for (const d of document.querySelectorAll('details')) d.open = true
        })
        // ⛔ ชั้นไฟล์ดิบ ⛔ ไม่มีแผนภาพ — ตัววาดเป็นโค้ดของเว็บที่ถูกตัดทิ้ง
        // ⛔ หน้าที่ ⛔ ไม่มีแผนภาพ ก็ ⛔ ไม่ต้องรอ — รอไปก็ตายเพราะหมดเวลาเปล่า ๆ
        if (!ชั้น.ปิดโค้ด && หน้า.มีแผนภาพ) {
          await รอแผนภาพครบ(แท็บ)
        }
      }
      await แท็บ.addScriptTag({ path: ที่อยู่axe })
      const ผล = await แท็บ.evaluate(
        ({ tags, rules }) =>
          window.axe
            .run(document, { runOnly: { type: 'tag', values: tags }, rules })
            .then((r) => ({
              ผิด: r.violations.map((v) => ({
                id: v.id,
                impact: v.impact,
                help: v.help,
                n: v.nodes.length,
                ที่ไหน: v.nodes.slice(0, 3).map((n) => n.target.join(' ')),
              })),
              สงสัย: r.incomplete.map((v) => ({ id: v.id, n: v.nodes.length })),
              // กฎทุกข้อที่ axe ตัดสินได้ — ใช้พิสูจน์ข้างล่างว่า `กฎเพิ่ม` ได้รันจริง
              รันแล้ว: [...r.violations, ...r.passes, ...r.incomplete, ...r.inapplicable].map((v) => v.id),
            })),
        { tags: ป้าย, rules: กฎเพิ่ม },
      )
      ตรวจไป++
      // ⛔ นับ **จุดที่ axe ชี้** ⛔ ไม่ใช่จำนวนกฎ — ของเดิมนับกฎแล้วพิมพ์ว่า "จุด"
      //   ⇒ กฎเดียวชี้ 19 จุด ก็ถูกรายงานว่า 1 ⇒ **อ่านแล้วเข้าใจว่าเหลือน้อยกว่าจริงเกือบ 20 เท่า**
      //   (คนตรวจ !12 นิด 1 · 29 ส.ค. 2569)
      ตัดสินไม่ได้ += ผล.สงสัย.reduce((รวม, i) => รวม + i.n, 0)
      const ช่อง = `${หน้า.ชื่อ} · ${ชั้น.ชื่อ} @ ${w} จุด · กล่อง${เปิดกล่อง ? 'เปิด' : 'ปิด'}`
      // ⛔ ด่านที่แอบข้ามกฎแล้วบอกว่าเขียว แย่กว่าไม่มีด่าน เพราะไม่มีใครกลับมาดูอีก
      for (const id of Object.keys(กฎเพิ่ม)) {
        if (!ผล.รันแล้ว.includes(id)) ที่ตก.push(`${ช่อง}: กฎ ${id} ไม่ได้ถูกรัน ⇒ ด่านนี้ยังไม่ได้ตรวจข้อนั้นเลย`)
      }
      for (const v of ผล.ผิด) {
        ที่ตก.push(`${ช่อง}: ${v.id} [${v.impact}] ×${v.n} — ${v.help} · ${v.ที่ไหน.join(' | ')}`)
      }
      // รายงานไว้เฉย ๆ ⛔ ไม่ทำให้แดง — axe บอกว่า "ตัดสินไม่ได้" ซึ่งคนละเรื่องกับ "ผิด"
      if (ผล.สงสัย.length) {
        console.log(`  ? ${ช่อง} ตัดสินไม่ได้: ${ผล.สงสัย.map((i) => i.id + '×' + i.n).join(', ')}`)
      }
      await ctx.close()
    }
  }
 }
}

await เบราว์เซอร์.close()

console.log(`axe ตรวจ ${ตรวจไป} ครั้ง (${หน้าทั้งหมด.length} หน้า × ชั้นที่หน้านั้นมี × 2 สถานะกล่อง × ${ความกว้าง.length} ความกว้าง) · ตัดสินไม่ได้ ${ตัดสินไม่ได้} จุด`)
if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — พบข้อผิด ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
console.log('✅ axe: 0 ข้อผิดที่ระดับ AA ⛔ ซึ่งไม่เท่ากับ "ผ่าน WCAG ครบ" — ดูหัวไฟล์')
