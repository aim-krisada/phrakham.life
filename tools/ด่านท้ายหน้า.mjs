const เบราว์เซอร์ = await chromium.launch()

async function เปิด(ที่อยู่, [กว้าง, สูง], { ยัด = '', ทำ = '', ขนาด = 1, มีแผนภาพ = false } = {}) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: สูง } })
  await ctx.addInitScript((fs) => {
    try {
      localStorage.setItem('pk-fs', String(fs))
    } catch {}
  }, ขนาด)
  try {
    const แท็บ = await ctx.newPage()
    await แท็บ.goto(`${ฐาน}${ที่อยู่}`, { waitUntil: 'domcontentloaded' })
    await แท็บ.waitForSelector('.pk-ตราประทับ', { timeout: 30000 })
    await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
    await รอหน้านิ่ง(แท็บ)
    if (มีแผนภาพ) await รอแผนภาพครบ(แท็บ)
    if (ยัด) {
      await แท็บ.addStyleTag({ content: ยัด })
      await รอหน้านิ่ง(แท็บ)
    }
    if (ทำ) await แท็บ.evaluate(ทำ)
    return { ctx, แท็บ }
  } catch (e) {
    // ⭐ เปิดหน้าไม่ขึ้น ⇒ ปิดบริบทก่อนส่งต่อ ⇒ คนเรียกจดเป็นข้อที่ตก ⛔ ด่านล้มทั้งตัว
    await ctx.close()
    throw e
  }
}

