    if (Math.abs(ผล.ขนาด - ผล.ขนาดคอลัมน์) > 0.01)
      ตก.push(`① ${ป้าย} ⇒ คำโปรย ${ผล.ขนาด} จุด ⇒ ไม่เท่าคอลัมน์ ${ผล.ขนาดคอลัมน์} จุด ⇒ ⛔ ห้ามย่อตัวอักษรเพื่อยัดให้พอ (SC 1.4.4)`)
    if (ผล.ขวา > ผล.กว้างจอ + 0.5) ตก.push(`① ${ป้าย} ⇒ คำโปรยล้นขวาของจอ ${Math.round(ผล.ขวา - ผล.กว้างจอ)} จุด`)
    if (ผล.กว้างหน้า > ผล.กว้างจอ) ตก.push(`① ${ป้าย} ⇒ หน้าเลื่อนแนวนอนได้ ${ผล.กว้างหน้า - ผล.กว้างจอ} จุด (SC 1.4.10)`)
    if (กว้าง >= เกณฑ์.บรรทัดเดียวตั้งแต่ && ขนาด === 1 && ผล.บรรทัด !== 1)
      ตก.push(`① ${ป้าย} ⇒ คำโปรย ${ผล.บรรทัด} บรรทัด ⇒ ต้องเป็นบรรทัดเดียวเมื่อแผ่นกว้างพอ`)
