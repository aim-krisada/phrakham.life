    if (ตรา.ทั้งก้อน !== ต้อง) ตก.push(`⑥ ${ป้าย} ⇒ ตราประทับ “${ตรา.ทั้งก้อน}” ⛔ ต้องเป็น “${ต้อง}” ตรงตัว (⛔ สาขา ⛔ เวลาคอมมิต:)`)
