def ลายนิ้วมือ(ไบต์: bytes) -> str:
    """ย่อไฟล์เป็นสายอักขระ 16 ตัว ⇒ คนนอกโหลดไฟล์เดียวกันมาคำนวณเทียบได้

    ⛔ ไม่ปรับการขึ้นบรรทัด เพราะไฟล์ในซิปไม่ถูกกิตแตะ ⇒ ไบต์ตรงกันเสมอ
    """
    return hashlib.blake2b(ไบต์, digest_size=8).hexdigest()


def นับกองไฟล์(z: zipfile.ZipFile) -> dict:
    """แยกว่าในซิปมีไฟล์ชนิดไหน กี่ไฟล์ รวมกี่ไบต์"""
    ชนิด = collections.defaultdict(lambda: {"จำนวนไฟล์": 0, "รวมไบต์": 0})
    for i in z.infolist():
        if i.is_dir():
            continue
        นามสกุล = i.filename.rsplit(".", 1)[-1].lower() if "." in i.filename.rsplit("/", 1)[-1] else "ไม่มีนามสกุล"
        ชนิด[นามสกุล]["จำนวนไฟล์"] += 1
        ชนิด[นามสกุล]["รวมไบต์"] += i.file_size
    return dict(sorted(ชนิด.items()))


def สำรวจตัวบท(z: zipfile.ZipFile) -> dict:
    """เปิดไฟล์ตัวบท 66 เล่ม แล้วนับป้ายทุกชนิดที่ติดมา"""
    ชื่อไฟล์ = sorted(n for n in z.namelist() if n.endswith(".usx"))

    ป้ายทั้งหมด = collections.Counter()
    เชิงอรรถแยกตามของข้างใน = collections.Counter()
    เชิงอรรถที่มี = collections.Counter()
    ที่อ้างอิงเครื่องอ่านได้ = collections.Counter()
    เลขข้อที่เป็นช่วง = 0
    ข้อทั้งหมด = 0
    บททั้งหมด = 0
    ตัวมองไม่เห็นที่เจอ = collections.Counter()
    ตัวอักษรแยกหมวด = collections.Counter()

    for n in ชื่อไฟล์:
        ราก = ET.fromstring(z.read(n))

        for el in ราก.iter():
            สไตล์ = el.get("style")
            if สไตล์:
                ป้ายทั้งหมด[f"{el.tag}/{สไตล์}"] += 1

        # ข้อกับบท นับเฉพาะป้ายเปิด ⇒ ป้ายปิดไม่มีช่อง style
        for v in ราก.iter("verse"):
            if v.get("style") == "v":
                ข้อทั้งหมด += 1
                if "-" in (v.get("number") or ""):
                    เลขข้อที่เป็นช่วง += 1
        for c in ราก.iter("chapter"):
            if c.get("style") == "c":
                บททั้งหมด += 1

        # เชิงอรรถ ⇒ ดูว่าข้างในมีชิ้นส่วนอะไรบ้าง
        for nt in ราก.iter("note"):
            ชิ้น = sorted({c.get("style") for c in nt if c.tag == "char"})
            เชิงอรรถแยกตามของข้างใน["+".join(ชิ้น)] += 1
            for ช in ชิ้น:
                เชิงอรรถที่มี[ช] += 1
            if any(c.tag == "char" and c.get("style") == "xt" for c in nt.iter()):
                เชิงอรรถที่มี["xt ⇒ โยงไปข้ออื่น"] += 1

        # ที่อ้างอิงที่เครื่องอ่านได้ ⇒ ป้าย <ref loc="..."> อยู่ใต้ป้ายอะไร
        for พ่อ in ราก.iter():
            for ลูก in พ่อ:
                if ลูก.tag == "ref":
                    ที่อ้างอิงเครื่องอ่านได้[f"{พ่อ.tag}/{พ่อ.get('style')}"] += 1

        # ตัวอักษร ⇒ ดูว่าตัวบทมีอะไรที่มองไม่เห็นซ่อนอยู่ไหม
        for el in ราก.iter():
            for ข้อความ in (el.text, el.tail):
                if not ข้อความ:
                    continue
                for ตัว in ข้อความ:
                    if ตัว in ตัวมองไม่เห็น:
                        ตัวมองไม่เห็นที่เจอ[ตัวมองไม่เห็น[ตัว]] += 1
                    ตัวอักษรแยกหมวด[unicodedata.category(ตัว)] += 1

    return {
        "ไฟล์ตัวบท": len(ชื่อไฟล์),
        "เล่ม": len(ชื่อไฟล์),
        "บท": บททั้งหมด,
        "ข้อ": ข้อทั้งหมด,
        "เลขข้อที่เป็นช่วง": เลขข้อที่เป็นช่วง,
        "ป้ายทุกชนิด": dict(ป้ายทั้งหมด.most_common()),
        "เชิงอรรถ": {
            "ทั้งหมด": sum(เชิงอรรถแยกตามของข้างใน.values()),
            "แยกตามชุดชิ้นส่วนข้างใน": dict(เชิงอรรถแยกตามของข้างใน.most_common()),
            "มีชิ้นส่วนชนิดนี้กี่เชิงอรรถ": dict(เชิงอรรถที่มี.most_common()),
        },
        "ที่อ้างอิงเครื่องอ่านได้แยกตามที่อยู่": dict(ที่อ้างอิงเครื่องอ่านได้.most_common()),
        "ตัวอักษรที่มองไม่เห็น": dict(ตัวมองไม่เห็นที่เจอ.most_common()),
        "ตัวอักษรแยกหมวดยูนิโคด": dict(ตัวอักษรแยกหมวด.most_common()),
    }


def สำรวจชื่อเล่ม(z: zipfile.ZipFile) -> dict:
    """metadata.xml แจกชื่อเล่มภาษาไทยมาให้ 3 แบบ ⇒ นับว่าครบกี่เล่ม"""
    ราก = ET.fromstring(z.read("metadata.xml"))
    ชื่อ = ราก.find("names")
    ครบทั้งสามแบบ = 0
    ทั้งหมด = 0
    ตัวย่อไม่ซ้ำ = set()
    for n in ชื่อ.findall("name") if ชื่อ is not None else []:
        if not (n.get("id") or "").startswith("book-"):
            continue
        ทั้งหมด += 1
        ย่อ = n.findtext("abbr")
        สั้น = n.findtext("short")
        ยาว = n.findtext("long")
        if ย่อ and สั้น and ยาว:
            ครบทั้งสามแบบ += 1
        if ย่อ:
            ตัวย่อไม่ซ้ำ.add(ย่อ)
    return {
        "เล่มที่มีชื่อไทย": ทั้งหมด,
        "เล่มที่มีครบทั้งชื่อย่อ ชื่อสั้น ชื่อยาว": ครบทั้งสามแบบ,
        "ชื่อย่อที่ไม่ซ้ำกัน": len(ตัวย่อไม่ซ้ำ),
    }


def สำรวจตารางข้อ(z: zipfile.ZipFile) -> dict:
    """versification.vrs มีของ 2 อย่างในไฟล์เดียว

    ① บรรทัดที่บอกว่าแต่ละบทมีข้อสูงสุดเท่าไร ⇒ ใช้ตรวจว่าเราพ่นครบไหม
    ② บรรทัดที่มีเครื่องหมาย = ⇒ ตารางเทียบเลขข้อของฉบับไทย กับเลขข้อของต้นฉบับเดิม
       เช่น GEN 31:55 = GEN 32:1 แปลว่าข้อที่ไทยเรียก 31:55 ต้นฉบับเรียก 32:1
    """
    ข้อความ = z.read("release/versification.vrs").decode("utf-8")
    เล่ม = 0
    บท = 0
    รวมข้อ = 0
    บรรทัดเทียบเลขข้อ = 0
    ข้อที่เลขไม่ตรงต้นฉบับ = 0
    เล่มที่เลขไม่ตรง = set()

    for บรรทัด in ข้อความ.splitlines():
        บรรทัด = บรรทัด.strip()
        if not บรรทัด or บรรทัด.startswith("#"):
            continue

        if "=" in บรรทัด:
            บรรทัดเทียบเลขข้อ += 1
            ซ้าย = บรรทัด.split("=")[0].strip()
            เล่มที่เลขไม่ตรง.add(ซ้าย.split()[0])
            # นับว่าบรรทัดนี้ครอบข้อกี่ข้อ ⇒ ช่วง 32:1-32 คือ 32 ข้อ
            ช่วง = ซ้าย.split(":")[-1]
            if "-" in ช่วง:
                ต้น, ปลาย = ช่วง.split("-")
                ข้อที่เลขไม่ตรงต้นฉบับ += int(ปลาย) - int(ต้น) + 1
            else:
                ข้อที่เลขไม่ตรงต้นฉบับ += 1
            continue

        ชิ้น = บรรทัด.split()
        if len(ชิ้น) < 2 or ":" not in ชิ้น[1]:
            continue
        เล่ม += 1
        for ช in ชิ้น[1:]:
            if ":" in ช:
                บท += 1
                รวมข้อ += int(ช.split(":")[1])

    เล่มที่มีตัวบทจริง = {n.rsplit("/", 1)[-1][:-4] for n in z.namelist() if n.endswith(".usx")}
    return {
        "เล่มในตาราง": เล่ม,
        "เล่มในตารางที่ซิปนี้มีตัวบทจริง": sum(
            1 for บ in ข้อความ.splitlines()
            if บ.strip() and not บ.startswith("#") and "=" not in บ
            and บ.split()[0] in เล่มที่มีตัวบทจริง
        ),
        "บท": บท,
        "ผลรวมข้อสูงสุดของทุกบท": รวมข้อ,
        "ตารางเทียบเลขข้อกับต้นฉบับเดิม": {
            "บรรทัด": บรรทัดเทียบเลขข้อ,
            "ข้อที่เลขไม่ตรงต้นฉบับ": ข้อที่เลขไม่ตรงต้นฉบับ,
            "เล่มที่มีเลขไม่ตรง": len(เล่มที่เลขไม่ตรง),
            "รายชื่อเล่มที่มีเลขไม่ตรง": sorted(เล่มที่เลขไม่ตรง),
        },
    }


def สำรวจแบบตัวอักษร(z: zipfile.ZipFile) -> dict:
    """styles.xml บอกว่าป้ายแต่ละตัวเจ้าของตั้งใจให้แสดงผลอย่างไร"""
    ราก = ET.fromstring(z.read("release/styles.xml"))
    นับ = collections.Counter()
    เลิกใช้แล้ว = 0
    for el in ราก.iter("style"):
        นับ["พิมพ์ออกมาให้ผู้อ่านเห็น" if el.get("publishable") == "true" else "ไม่พิมพ์"] += 1
        if (el.findtext("name") or "").startswith("DEPRECATED"):
            เลิกใช้แล้ว += 1
    return {
        "นิยามป้ายทั้งหมด": sum(นับ.values()),
        "แยกตามว่าพิมพ์ไหม": dict(นับ.most_common()),
        "ป้ายที่เจ้าของบอกว่าเลิกใช้แล้ว": เลิกใช้แล้ว,
    }


def สำรวจซิปซ้อน(z: zipfile.ZipFile) -> dict:
    """ในซิปมีซิปซ้อนอีกชั้น ⇒ เป็นแฟ้มงานดิบของโปรแกรมแปล Paratext"""
    ข้างใน = zipfile.ZipFile(io.BytesIO(z.read("source/paratext-resource.zip")))
    return {
        "ชื่อไฟล์": "source/paratext-resource.zip",
        "ลายนิ้วมือไฟล์": ลายนิ้วมือ(z.read("source/paratext-resource.zip")),
        "กองไฟล์": นับกองไฟล์(ข้างใน),
        "ไฟล์ที่ไม่ใช่ตัวบท": sorted(
            i.filename for i in ข้างใน.infolist()
            if not i.is_dir() and not i.filename.lower().endswith(".sfm")
        ),
    }


def main() -> int:
    ไบต์ซิป = ซิป.read_bytes()
    z = zipfile.ZipFile(io.BytesIO(ไบต์ซิป))

    ผล = {
        "ไฟล์ต้นทาง": {
            "ที่อยู่": str(ซิป),
            "ลายนิ้วมือไฟล์": ลายนิ้วมือ(ไบต์ซิป),
            "ขนาดไบต์": len(ไบต์ซิป),
        },
        "กองไฟล์ในซิปชั้นนอก": นับกองไฟล์(z),
        "ตัวบท": สำรวจตัวบท(z),
        "ชื่อเล่มภาษาไทย": สำรวจชื่อเล่ม(z),
        "ตารางข้อ": สำรวจตารางข้อ(z),
        "แบบตัวอักษร": สำรวจแบบตัวอักษร(z),
        "ซิปซ้อนข้างใน": สำรวจซิปซ้อน(z),
        "ของที่หาแล้วไม่มี": {},
    }

    # หาป้ายที่ฉบับอื่นมักมี แต่ TCV ไม่มี ⇒ ต้องรู้ว่าไม่มี จะได้ไม่ไปรอ
    ป้าย = ผล["ตัวบท"]["ป้ายทุกชนิด"]
    for ป, ความหมาย in [
        ("char/add", "คำที่ผู้แปลเติมเข้ามาเอง"),
        ("note/x", "เชิงอรรถชนิดโยงข้ออื่นโดยเฉพาะ"),
        ("para/ip", "คำนำของแต่ละเล่ม"),
        ("para/imt", "หัวเรื่องของคำนำ"),
        ("char/w", "คำที่ผูกกับพจนานุกรม"),
        ("char/qt", "คำที่ยกมาจากพันธสัญญาเดิม"),
        ("para/ms2", "หัวเรื่องชั้นที่สอง"),
    ]:
        ผล["ของที่หาแล้วไม่มี"][ความหมาย] = {"ป้าย": ป, "พบ": ป in ป้าย}

    ที่ออก.parent.mkdir(parents=True, exist_ok=True)
    ที่ออก.write_text(json.dumps(ผล, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"เขียนแล้ว {ที่ออก}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
