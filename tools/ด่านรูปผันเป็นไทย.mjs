// ด่าน — รหัสรูปผัน **ทุกตัวในข้อมูลจริง** ต้องแปลเป็นคำไทยได้ครบ (ใบงาน v3/phrakham#103 เกณฑ์ข้อ 7)
//
// **นี่คือด่าน ⛔ ไม่ใช่รายงาน** ⇒ แปลไม่ออกแม้ส่วนเดียว ⇒ คืนรหัสไม่เป็นศูนย์ ⇒ ท่อ CI แดง
//
//   node tools/ด่านรูปผันเป็นไทย.mjs                ⇒ ไล่ทุกคำใน `_data/ภาษาเดิม/` (613,652 คำ)
//   node tools/ด่านรูปผันเป็นไทย.mjs --ทดสอบตัวเอง  ⇒ พิสูจน์แดง-เขียว ⛔ ไม่ต้องมีข้อมูล
//
// ⭐ **ไล่จากข้อมูลจริง ⛔ ไม่ใช่รายชื่อรหัสที่พิมพ์ไว้** ⇒ วันที่ MACULA ออกรุ่นใหม่แล้วมีรหัสแปลก
//   ⇒ ด่านนี้แดงเองทันที ⇒ ⛔ การ์ดไม่โชว์รหัสดิบให้ผู้อ่านงง
// ⭐ **ตัวแปลตัวเดียวกับที่การ์ดใช้** ⇒ `app/utils/รูปผัน.ts` ⇒ Node 24 อ่าน TypeScript ได้เอง

import { readFileSync, readdirSync, statSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'
import { join } from 'node:path'
import { แปลรูปผัน } from '../app/utils/รูปผัน.ts'

const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')
const ที่ตก = []

if (ทดสอบตัวเอง) {
  // ⭐ ของที่ต้องได้ตรงตัว ⇒ ตัวอย่างแรกคือตัวอย่างในใบงานเอง
  const ต้องได้ = [
    ['N-GSN', 'grc', false, 'คำนาม · การกที่ 6 (genitive) · เอกพจน์ · เพศกลาง'],
    ['V-2AAP-NSM', 'grc', false, 'คำกริยา · เอออริสต์ แบบที่ 2 (2nd aorist) · กรรตุวาจก (active) · กริยาคุณศัพท์ (participle) · การกที่ 1 (nominative) · เอกพจน์ · เพศชาย'],
    ['Vqp3ms', 'hbo', false, 'คำกริยา · แบบ Qal · รูปสมบูรณ์ (perfect) · บุรุษที่ 3 · เพศชาย · เอกพจน์'],
    ['Vhp3ms', 'hbo', true, 'คำกริยา · แบบ Haphel · รูปสมบูรณ์ (perfect) · บุรุษที่ 3 · เพศชาย · เอกพจน์ · ภาษาอาราเมค'],
    ['Ncfsa', 'hbo', false, 'คำนามสามานยนาม (common noun) · เพศหญิง · เอกพจน์ · รูปอิสระ (absolute)'],
  ]
  for (const [รหัส, ภาษา, อา, ควร] of ต้องได้) {
    const ผล = แปลรูปผัน(รหัส, ภาษา, อา)
    const ได้ = ผล.ส่วน.join(' · ')
    const ok = ได้ === ควร && !ผล.ไม่รู้จัก.length
    console.log(`${ok ? '✅' : '⛔'} ${รหัส} ⇒ ${ได้}`)
    if (!ok) ที่ตก.push(`${รหัส} ได้ "${ได้}" ⛔ ควรได้ "${ควร}"`)
  }
  // ⛔ รหัสที่แปลไม่ออก ⇒ ต้องโผล่เป็น `ไม่รู้จัก` ⛔ ไม่ใช่กลืนเงียบ
  const ต้องจับได้ = [
    ['N-ZSN', 'grc', false],
    ['V-PZI-3S', 'grc', false],
    ['XYZ', 'grc', false],
    ['Vyp3ms', 'hbo', true], // ⇒ y มีในตารางฮีบรู แต่ ⛔ ไม่มีในตารางอาราเมค ⇒ ต้องแดง
    ['Ncfza', 'hbo', false],
    ['Qx', 'hbo', false],
  ]
  for (const [รหัส, ภาษา, อา] of ต้องจับได้) {
    const จับได้ = แปลรูปผัน(รหัส, ภาษา, อา).ไม่รู้จัก.length > 0
    console.log(`${จับได้ ? '✅' : '⛔'} รหัสปลอม ${รหัส} ⇒ ด่าน${จับได้ ? 'จับได้' : '⛔ จับไม่ได้'}`)
    if (!จับได้) ที่ตก.push(`รหัสปลอม ${รหัส} ⛔ ไม่ถูกจับ ⇒ การ์ดจะโชว์คำแปลครึ่ง ๆ กลาง ๆ`)
  }
} else {
  const กอง = '_data/ภาษาเดิม'
  const เห็น = new Map()
  let นับ = 0
  for (const เล่ม of readdirSync(กอง)) {
    if (!statSync(join(กอง, เล่ม)).isDirectory()) continue
    for (const ไฟล์ of readdirSync(join(กอง, เล่ม))) {
      const ของ = JSON.parse(gunzipSync(readFileSync(join(กอง, เล่ม, ไฟล์))).toString('utf8'))
      for (const [ชั้น, ข้อทั้งหมด] of Object.entries(ของ.ชั้น)) {
        const ภาษา = ชั้น === 'คำกรีก' ? 'grc' : 'hbo'
        for (const คำ of Object.values(ข้อทั้งหมด)) {
          for (const ค of คำ) {
            นับ++
            const กุญแจ = `${ภาษา}|${ค['รูปผัน'] ?? ''}|${ค['อาราเมค'] ? 1 : 0}`
            if (!เห็น.has(กุญแจ)) เห็น.set(กุญแจ, `${เล่ม} ${ไฟล์.replace('.json.gz', '')}`)
          }
        }
      }
    }
  }
  let ว่าง = 0
  for (const [กุญแจ, ที่] of เห็น) {
    const [ภาษา, รหัส, อา] = กุญแจ.split('|')
    if (!รหัส) {
      ว่าง++
      continue
    }
    const ผล = แปลรูปผัน(รหัส, ภาษา, อา === '1')
    if (ผล.ไม่รู้จัก.length || !ผล.ส่วน.length)
      ที่ตก.push(`${ภาษา} ${รหัส}${อา === '1' ? ' (อาราเมค)' : ''} ⇒ แปลไม่ออก [${ผล.ไม่รู้จัก.join(' ')}] ⇒ เจอที่ ${ที่}`)
  }
  console.log(`ไล่ ${นับ.toLocaleString()} คำ ⇒ รหัสไม่ซ้ำ ${เห็น.size.toLocaleString()} แบบ (ไม่มีรหัส ${ว่าง} แบบ)`)
}

if (ที่ตก.length) {
  console.log(`\n⛔ ด่านรูปผันเป็นไทยแดง — ${ที่ตก.length} เรื่อง`)
  for (const x of ที่ตก.slice(0, 40)) console.log(`  · ${x}`)
  process.exit(1)
}
console.log(ทดสอบตัวเอง ? '\n✅ ด่านยังจับรหัสที่แปลไม่ออกได้' : '\n✅ รหัสรูปผันทุกตัวในข้อมูลแปลเป็นไทยได้ครบ')
