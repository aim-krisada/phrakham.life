const เบราว์เซอร์ = await chromium.launch()

async function เปิด(ที่อยู่, พัง, กว้าง = 1280, ชั้นคำ = false) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: 900 } })
  if (พัง?.สคริปต์) await ctx.addInitScript(พัง.สคริปต์)
  if (พัง?.เส้นทาง) await พัง.เส้นทาง(ctx)
  // ⑧ เปิดชั้นคำผ่านที่เก็บมุมมองตัวเดียวกับที่ปุ่มในแผ่นปรับหน้าจอเขียน ⇒ ⛔ ไม่ต้องกดเมนูทุกช่วง
  if (ชั้นคำ) await ctx.addInitScript(() => localStorage.setItem('phrakham.view', JSON.stringify({ ภาษาเดิม: true })))
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}${ที่อยู่}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('.pk-ตัวบท [data-ข้อ]')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  await แท็บ.waitForTimeout(900)
  if (พัง?.css) await แท็บ.addStyleTag({ content: พัง.css })
  if (พัง?.หลังเปิด) await พัง.หลังเปิด(แท็บ)
  return { ctx, แท็บ }
}

