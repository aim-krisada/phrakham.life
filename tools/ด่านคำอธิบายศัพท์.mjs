//   ⑤ **มาลาคำสั่งใช้ `ความหมายคำสั่ง` ตัวที่อนุมัติแล้ว** ⇒ ⛔ ไม่มีประโยคเรื่องเดียวกันสองที่ให้ค้างรุ่นเก่า
//
// ⭐ **ตัวแปลกับตารางตัวเดียวกับที่การ์ดใช้** ⇒ Node 24 อ่าน TypeScript ได้เอง ⇒ ⛔ ไม่ต้อง `npm ci`

import { readFileSync, readdirSync, statSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'
import { join } from 'node:path'
import { แปลรูปผัน, ตารางศัพท์กรีก } from '../app/utils/รูปผัน.ts'
import { ตารางคำอธิบายศัพท์ } from '../app/utils/ศัพท์ไวยากรณ์.ts'
import { ที่มาถ้อยคำ, ความหมายคำสั่ง } from '../app/utils/กาลกริยา.ts'

const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')
const ที่ตก = []

/** หน้าตาของเลขหน้า ⇒ *หน้า 461* · *p. 461* · *pp. 461–463* · *461–463* (ปี ค.ศ. ในวงเล็บไม่นับ) */
const เลขหน้า = /หน้า\s*\d|\bpp?\.\s*\d|\d+\s*[–-]\s*\d+/

/**
 * ตัวตัดสิน ⇒ รับของทุกชิ้นเป็นพารามิเตอร์ ⇒ ฝาแฝดยัดของพังเข้ามาได้โดย ⛔ ไม่ต้องแก้ไฟล์จริง
 * @param เห็น Map `ชุด|รหัส` ⇒ `{ ที่, นับ }` จากข้อมูลจริง
 */
function ตรวจ({ เห็น, ตารางชื่อ, ตารางอธิบาย, ที่มากาล, คำสั่ง }) {
  const ตก = []
  const มีครบ = (ชุด, รหัส) => {
    const ค = ตารางอธิบาย[ชุด]?.[รหัส]
    return Boolean(ค?.ความหมาย?.trim() && ค?.ที่มา?.trim())
  }
  // ① ทุกรหัสในข้อมูลจริง
  for (const [กุญแจ, { ที่, นับ }] of เห็น) {
    const [ชุด, รหัส] = กุญแจ.split('|')
    if (!มีครบ(ชุด, รหัส)) ตก.push(`① ${ชุด} ${รหัส} ⇒ ข้อมูลจริงใช้ ${นับ.toLocaleString()} คำ แต่ ⛔ ไม่มีคำอธิบาย ⇒ เจอที่ ${ที่}`)
  }
  for (const [ชุด, ชื่อทั้งหมด] of Object.entries(ตารางชื่อ)) {
    // ② ทุกค่าที่การ์ดแสดงได้
    for (const [รหัส, ชื่อ] of Object.entries(ชื่อทั้งหมด))
      if (!มีครบ(ชุด, รหัส)) ตก.push(`② ${ชื่อ} (${ชุด} ${รหัส}) ⇒ การ์ดแสดงได้แต่ ⛔ ไม่มีคำอธิบาย`)
    // ③ คำอธิบายค้าง
    for (const รหัส of Object.keys(ตารางอธิบาย[ชุด] ?? {}))
      if (!(รหัส in ชื่อทั้งหมด)) ตก.push(`③ คำอธิบาย ${ชุด} ${รหัส} ⇒ ⛔ ไม่มีชื่อในตารางชื่อแล้ว ⇒ ของค้างรุ่นเก่า`)
  }
  for (const ชุด of Object.keys(ตารางอธิบาย))
    if (!(ชุด in ตารางชื่อ)) ตก.push(`③ ชุดคำอธิบาย ${ชุด} ⇒ ⛔ ไม่มีในตารางชื่อ`)
  // ④ เลขหน้า
  const ข้อความขึ้นเว็บ = [['ที่มาของความหมายกาล', ที่มากาล]]
  for (const [ชุด, ทั้งหมด] of Object.entries(ตารางอธิบาย))
    for (const [รหัส, ค] of Object.entries(ทั้งหมด)) {
      ข้อความขึ้นเว็บ.push([`ความหมาย ${ชุด} ${รหัส}`, ค?.ความหมาย ?? ''])
      ข้อความขึ้นเว็บ.push([`ที่มา ${ชุด} ${รหัส}`, ค?.ที่มา ?? ''])
    }
  for (const [ป้าย, ข้อความ] of ข้อความขึ้นเว็บ)
    if (เลขหน้า.test(ข้อความ)) ตก.push(`④ ${ป้าย} ⇒ มีเลขหน้าของตำรา «${ข้อความ.match(เลขหน้า)[0]}» ⇒ ⛔ ไม่ขึ้นเว็บ`)
  // ⑤ มาลาคำสั่ง
  if (ตารางอธิบาย.มาลา?.M?.ความหมาย !== คำสั่ง)
    ตก.push('⑤ คำอธิบายมาลาคำสั่ง ⛔ ไม่ใช่ `ความหมายคำสั่ง` ที่อนุมัติแล้ว ⇒ ประโยคเรื่องเดียวกันมีสองที่')
  return ตก
}

/** จดรหัสของคำหนึ่งคำ ⇒ ใช้ตัวแปลของการ์ดเอง ⛔ ไม่แกะรหัสเองอีกทาง */
function จด(เห็น, รูปผัน, ที่) {
  for (const ศ of แปลรูปผัน(รูปผัน, 'grc').ศัพท์) {
    const กุญแจ = `${ศ.ชุด}|${ศ.รหัส}`
    const เดิม = เห็น.get(กุญแจ)
    if (เดิม) เดิม.นับ++
    else เห็น.set(กุญแจ, { ที่, นับ: 1 })
  }
}

const ของจริง = { ตารางชื่อ: ตารางศัพท์กรีก, ตารางอธิบาย: ตารางคำอธิบายศัพท์, ที่มากาล: ที่มาถ้อยคำ, คำสั่ง: ความหมายคำสั่ง }

if (ทดสอบตัวเอง) {
  // ⭐ ข้อมูลจำลอง ⇒ รหัสจริงที่ครอบทั้ง 3 ชุด ⇒ ไม่ต้องมี `_data/`
  const เห็นจำลอง = () => {
    const เห็น = new Map()
    for (const ร of ['V-AMS-3S', 'V-PNM-3S', 'V-2AAO-3S', 'V-RPP-DPM', 'N-GSN', 'N-VPM', 'P-DSM', 'S-1SNSM'])
      จด(เห็น, ร, 'จำลอง')
    return เห็น
  }
  const ที่ = 'จำลอง'
  const สำเนา = () => JSON.parse(JSON.stringify(ตารางคำอธิบายศัพท์))

  // ⭐ ของดีต้องเขียว ⇒ ไม่งั้นท่าพังข้างล่างพิสูจน์อะไรไม่ได้
  const ตกปกติ = ตรวจ({ ...ของจริง, เห็น: เห็นจำลอง() })
  console.log(`${ตกปกติ.length ? '⛔' : '✅'} ของจริงในหน่วยความจำ ⇒ ${ตกปกติ.length ? 'แดง' : 'เขียว'}`)
  for (const x of ตกปกติ) ที่ตก.push(`ของดีแต่แดง ⇒ ${x}`)

  const ท่าพัง = [
    ['ลบคำอธิบายมาลาสมมุติ', '① มาลา S', (ก) => { delete ก.ตารางอธิบาย.มาลา.S }],
    ['ความหมายการกที่ 6 ว่าง', '① การก G', (ก) => { ก.ตารางอธิบาย.การก.G.ความหมาย = ' ' }],
    ['ที่มาของวาจกว่าง', '① วาจก M', (ก) => { ก.ตารางอธิบาย.วาจก.M.ที่มา = '' }],
    ['ข้อมูลรุ่นใหม่มีรหัสแปลก', '① มาลา Z', (ก) => { ก.เห็น.set('มาลา|Z', { ที่, นับ: 1 }) }],
    ['ชื่อใหม่ไม่มีคำอธิบาย', '② ชื่อใหม่ (วาจก Z)', (ก) => { ก.ตารางชื่อ = { ...ก.ตารางชื่อ, วาจก: { ...ก.ตารางชื่อ.วาจก, Z: 'ชื่อใหม่' } } }],
    ['ค่าที่ไม่อยู่ในข้อมูลไม่มีคำอธิบาย', '② ไม่ระบุวาจก', (ก) => { delete ก.ตารางอธิบาย.วาจก.X }],
    ['คำอธิบายค้าง', '③ คำอธิบาย การก B', (ก) => { ก.ตารางอธิบาย.การก.B = { ความหมาย: 'ค้าง', ที่มา: 'ค้าง' } }],
    ['เลขหน้าหลุดในที่มา', '④ ที่มา มาลา I', (ก) => { ก.ตารางอธิบาย.มาลา.I.ที่มา += ' หน้า 448' }],
    ['ช่วงหน้าหลุดในความหมาย', '④ ความหมาย การก D', (ก) => { ก.ตารางอธิบาย.การก.D.ความหมาย += ' (137–140)' }],
    ['เลขหน้าหลุดในที่มาของกาล', '④ ที่มาของความหมายกาล', (ก) => { ก.ที่มากาล += ', pp. 554–555' }],
    ['มาลาคำสั่งเขียนใหม่', '⑤ คำอธิบายมาลาคำสั่ง', (ก) => { ก.ตารางอธิบาย.มาลา.M.ความหมาย = 'สั่งให้ทำ' }],
  ]
  for (const [ชื่อ, คำ, พัง] of ท่าพัง) {
    const ก = { ...ของจริง, ตารางอธิบาย: สำเนา(), เห็น: เห็นจำลอง() }
    พัง(ก)
    const ตก = ตรวจ(ก)
    const จับได้ = ตก.some((x) => x.startsWith(คำ))
    console.log(`${จับได้ ? '✅' : '⛔'} ${ชื่อ} ⇒ ด่าน${จับได้ ? 'จับได้' : '⛔ จับไม่ได้'}`)
    if (!จับได้) ที่ตก.push(`ท่าพัง ${ชื่อ} ⛔ ไม่ถูกจับด้วยข้อ «${คำ}» ⇒ ได้ ${JSON.stringify(ตก.slice(0, 3))}`)
  }
} else {
  const กอง = '_data/ภาษาเดิม'
  const เห็น = new Map()
  let นับ = 0
  for (const เล่ม of readdirSync(กอง)) {
    if (!statSync(join(กอง, เล่ม)).isDirectory()) continue
    for (const ไฟล์ of readdirSync(join(กอง, เล่ม))) {
      const ของ = JSON.parse(gunzipSync(readFileSync(join(กอง, เล่ม, ไฟล์))).toString('utf8'))
      for (const [ข้อ, คำ] of Object.entries(ของ.ชั้น['คำกรีก'] ?? {}))
        for (const ค of คำ) {
          นับ++
          if (ค['รูปผัน']) จด(เห็น, ค['รูปผัน'], `${เล่ม} ${ไฟล์.replace('.json.gz', '')}:${ข้อ} ${ค['รูปผัน']}`)
        }
    }
  }
  // ⛔ ไม่เจอคำกรีกเลย = ไม่มีอะไรให้ตรวจ ⇒ ⛔ ไม่นับว่าผ่าน (เช่นลืมดึงไบต์จริงของ `_data/`)
  if (!นับ) ที่ตก.push('ไม่เจอคำกรีกสักคำใน `_data/ภาษาเดิม/` ⇒ ไม่มีอะไรให้ตรวจ ⛔ ไม่นับว่าผ่าน')
  ที่ตก.push(...ตรวจ({ ...ของจริง, เห็น }))
  const ต่อชุด = {}
  for (const [กุญแจ, { นับ: น }] of เห็น) {
    const [ชุด, รหัส] = กุญแจ.split('|')
    ;(ต่อชุด[ชุด] ??= []).push(`${รหัส} ${น.toLocaleString()}`)
  }
  console.log(`ไล่คำกรีก ${นับ.toLocaleString()} คำ ⇒ รหัสไม่ซ้ำ ${เห็น.size} ตัว`)
  for (const [ชุด, x] of Object.entries(ต่อชุด)) console.log(`   ${ชุด} ⇒ ${x.join(' · ')}`)
}

if (ที่ตก.length) {
  console.log(`\n⛔ ด่านคำอธิบายศัพท์แดง — ${ที่ตก.length} เรื่อง`)
  for (const x of ที่ตก.slice(0, 40)) console.log(`  · ${x}`)
  process.exit(1)
}
console.log(ทดสอบตัวเอง ? '\n✅ ด่านคำอธิบายศัพท์ยังจับของพังได้ครบทุกท่า' : '\n✅ รหัสมาลา วาจก การก ทุกตัวมีคำอธิบาย และไม่มีเลขหน้าขึ้นเว็บ')
