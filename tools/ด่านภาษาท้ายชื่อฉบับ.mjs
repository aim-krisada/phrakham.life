/** ⭐ ตัวตรวจข้อ ① ⇒ รับตารางเป็นพารามิเตอร์ ⇒ โหมดพิสูจน์ยัดสำเนาที่พังเข้ามาได้ */
function ตรวจตาราง({ ภาษาของชั้น, ชั้นคำ, ชื่อภาษา, ภาษาตัวบท, ป้าย, ตัวบททั้งหมด }) {
  const ตก = []
  const พูด = []
  const ภาษาของ = {}
  if (!Object.keys(ภาษาของชั้น).length) ตก.push('① อ่านตาราง ภาษาของชั้น ได้ 0 แถว ⇒ ด่านอ่านผิดที่')
  for (const [ฉ, รหัส] of Object.entries(ภาษาของชั้น)) {
    if (ฉ in ชั้นคำ) continue // ชั้นคำภาษาเดิม ⇒ ตัวเลือกในช่องคือชื่อตัวบท ⇒ ตรวจข้างล่าง
    ภาษาของ[ฉ] = รหัส
  }
  for (const ตัวบท of ตัวบททั้งหมด) {
    const รหัส = ภาษาตัวบท(ตัวบท)
    const ชั้น = Object.keys(ชั้นคำ).find((ช) => ชื่อตัวบท(ช) === ตัวบท)
    if (!รหัส) ตก.push(`① ตัวบท ${ตัวบท} ⛔ ไม่มีภาษา ⇒ เติมใน ภาษาของตัวบทเดิม ที่ app/utils/ถ้อยคำคำเดิม.ts`)
    else if (ชั้น && ชั้นคำ[ชั้น] !== รหัส)
      ตก.push(`① ตัวบท ${ตัวบท} ภาษา “${รหัส}” ⛔ ตรงกับชั้น ${ชั้น} “${ชั้นคำ[ชั้น]}” ที่ server/utils/ชั้นคำ.ts`)
    ภาษาของ[ตัวบท] = รหัส
  }
  for (const [ฉ, รหัส] of Object.entries(ภาษาของ)) {
    if (!รหัส) continue
    if (!ชื่อภาษา[รหัส]) {
      ตก.push(`① ฉบับ ${ฉ} ภาษา “${รหัส}” ⛔ ไม่มีชื่อไทย ⇒ ตัวเลือกจะขึ้น “${ฉ}” เปล่า ๆ ⇒ เติมใน ชื่อภาษาไทย ที่ app/utils/ถ้อยคำภาษาฉบับ.ts`)
      continue
    }
    const ได้ = ป้าย(ฉ, รหัส)
    if (ที่เคาะ[ฉ] && ได้ !== ที่เคาะ[ฉ]) ตก.push(`① ฉบับ ${ฉ} ⇒ ได้ “${ได้}” ⇒ ที่พี่เอมเคาะคือ “${ที่เคาะ[ฉ]}”`)
    else if (!ที่เคาะ[ฉ] && ได้ !== `${ฉ}${คั่นภาษา}${ชื่อภาษา[รหัส]}`) ตก.push(`① ฉบับ ${ฉ} ⇒ ได้ “${ได้}” ⇒ ต้องเป็นทรง ชื่อฉบับ · ภาษา`)
    พูด.push(`  ${ฉ} (${รหัส}) ⇒ “${ได้}”`)
  }
  for (const ฉ of Object.keys(ที่เคาะ)) if (!(ฉ in ภาษาของ)) ตก.push(`① ฉบับ ${ฉ} ที่เคาะไว้ ⛔ ไม่อยู่ในตารางภาษา`)
  return { ตก, พูด, ภาษาของ }
}

