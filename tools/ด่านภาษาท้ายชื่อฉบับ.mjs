/** ก้อน `{ … }` ของตัวแปรหนึ่งในไฟล์ TS ⇒ ⛔ เจอ ⇒ โยน ⇒ ด่านแดงดีกว่าเงียบ */
function ก้อนของ(ไฟล์, ชื่อตัวแปร) {
  const ข้อความ = readFileSync(new URL(`../${ไฟล์}`, import.meta.url), 'utf8')
  // ⚠️ `\b` ของ JS นับแค่อักษรอังกฤษ ⇒ ชื่อไทยใช้ไม่ได้ ⇒ ดูอักษรถัดไปแทน
  const เจอ = ข้อความ.match(new RegExp(`const ${ชื่อตัวแปร}(?=[\\s:=])[^=]*=\\s*\\{([\\s\\S]*?)\\n\\}`))
  if (!เจอ) throw new Error(`⛔ ไม่เจอตาราง ${ชื่อตัวแปร} ใน ${ไฟล์} ⇒ ด่านต้องรู้ว่าตารางย้ายไปไหน`)
  return เจอ[1]
}
