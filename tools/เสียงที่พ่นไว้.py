# ⛔ `\s` ของทั้งไพทอนและจาวาสคริปต์ **⛔ ไม่จับตัวนี้** ⇒ ต้องถอดด้วยมือ
ช่องว่างศูนย์ = "​"

# ⭐ จุลภาคที่คั่นหลักพัน **เท่านั้น** ⇒ ต้องมีเลข 3 ตัวพอดีหลังจุลภาคทุกตัว
#   ⛔ **ห้ามแตะจุดทศนิยม** ⇒ `2.3 เมตร` กลายเป็น `23 เมตร` คือพระคัมภีร์ที่ผิดข้อเท็จจริง
#   ⛔ **ห้ามแตะจุลภาคของประโยคไทยธรรมดา** ⇒ กฎนี้แตะได้เฉพาะจุลภาคที่ขนาบด้วยตัวเลข
#   ⇒ เหตุผลเต็มอยู่ที่ `etl/audio_text.py` ของรุ่น 2 ⛔ ไม่จดซ้ำที่นี่
_เลขมีจุลภาค = re.compile(r"(?<![\d.])(\d{1,3}(?:,\d{3})+)(?![\d.])")


def ตัวบทบนจอ(ดิบ: str) -> str:
    """ตัวบท **อย่างที่ตาเห็น** ⇒ ยุบช่องว่างซ้ำให้เหลือตัวเดียว ⛔ ไม่ถอดช่องว่างศูนย์

    ⇒ นี่คือชั้นที่ช่อง `domHash` ของไฟล์รายการรุ่น 2 คิดจาก
    """
    return re.sub(r"\s+", " ", ดิบ).strip()


def ตัวบทที่ส่งไปพ่น(ดิบ: str) -> str:
    """ตัวบท **อย่างที่ส่งเข้าเครื่องพ่นเสียง** ⇒ นี่คือชั้นที่ช่อง `h` คิดจาก

    3 ชั้นตามลำดับ ⇒ ① ถอดช่องว่างศูนย์ ② ยุบช่องว่างซ้ำแล้วตัดหัวตัดท้าย ③ กฎจุลภาคหลักพัน
    ⛔ **ลำดับสลับไม่ได้** ⇒ กฎจุลภาคต้องเห็นตัวเลขที่ ⛔ ไม่มีช่องว่างศูนย์คั่นกลางแล้ว
    """
    out = re.sub(r"\s+", " ", ดิบ.replace(ช่องว่างศูนย์, "")).strip()
    return _เลขมีจุลภาค.sub(lambda m: m.group(1).replace(",", ""), out)


def ลายนิ้วมือ(ข้อความ: str) -> str:
    """ท่าเดียวกับ `seg_hash()` ของรุ่น 2 เป๊ะ ⇒ sha256 แล้วตัดเหลือ 16 ตัวแรก

    ⛔ **ตัดสั้นกว่าหรือยาวกว่านี้ไม่ได้** ⇒ ของที่เทียบด้วยคือไฟล์ที่พ่นไว้ตั้งแต่ ก.ค. 2569
    """
    return "sha256:" + hashlib.sha256(ข้อความ.encode("utf-8")).hexdigest()[:16]


