def บทTCVตามลำดับ(บท: dict) -> list[tuple[str, str, int]]:
    """ทุกบทที่มีตัวบท TCV ของเล่มใน `ลำดับเล่มTCV` เรียงตามลำดับที่ทำเสียง ⇒ `[(รหัสเล่ม, osis, บท), ...]`

    ⭐ จำนวนบทมาจากตัวบทใน `_data/` เอง ⛔ ไม่พิมพ์ตาราง ⇒ บทของฉบับนี้จบตรงไหน มีแต่ข้อมูลที่รู้
    """
    ได้ = []
    for รหัสเล่ม, osis in ลำดับเล่มTCV:
        เลขบท = sorted(int(k.split("/")[1]) for k, ชั้น in บท.items()
                       if k.split("/")[0] == รหัสเล่ม and (ชั้น.get("TCV") or {}))
        ได้ += [(รหัสเล่ม, osis, c) for c in เลขบท]
    return ได้


def ข้อTCVของบท(บท: dict, รหัสเล่ม: str, c: int) -> dict[int, str]:
    """`{เลขข้อ: ข้อความที่ส่งไปพ่น}` ของบทเดียว ⇒ ข้อที่ตัวบทว่างหลังผ่านกฎ ⛔ ไม่นับว่ามีตัวบท"""
    ชั้น = (บท.get(f"{รหัสเล่ม}/{c}") or {}).get("TCV") or {}
    ได้ = {}
    for v, ดิบ in ชั้น.items():
        พูด = ตัวบทที่ส่งไปพ่น(ดิบ)
        if พูด:
            ได้[int(v)] = พูด
    return dict(sorted(ได้.items()))


def ข้อที่ขาดในบท(ข้อ) -> list[int]:
    """เลขข้อระหว่าง 1 กับข้อสุดท้ายที่ ⛔ ไม่มีตัวบท ⇒ เช่น มัทธิว 17:21 ⇒ หน้าเว็บข้ามข้อพวกนี้เอง"""
    มี = set(ข้อ)
    return [v for v in range(1, max(มี)) if v not in มี] if มี else []
