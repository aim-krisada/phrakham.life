    """ตัวบทอย่างที่ส่งเข้าเครื่องพ่นเสียง ⇒ **⛔ ไม่เปลี่ยนคำ ⛔ ไม่เปลี่ยนตัวสะกด** มีแค่ 3 ชั้น

    ① ถอดช่องว่างความกว้างศูนย์ ⇒ ตัวบทไทยของเราฝังไว้ช่วยตัดบรรทัด ⇒ ⛔ ไม่ใช่ตัวอักษรที่อ่านออกเสียง
    ② LSV ⇒ ถอด `|` ⇒ ต้นฉบับใช้ `||` บอกขึ้นบรรทัดของบทกวี (เช่น มก. 1:2) ⇒ เป็นเครื่องหมาย ⛔ ไม่ใช่คำ
       ⇒ ⛔ ไม่ถอด = เครื่องอ่านอาจอ่านชื่อเครื่องหมายออกมา
    ③ ยุบช่องว่างและขึ้นบรรทัดให้เหลือช่องว่างเดียว ⇒ WEB กับ THKJV มีขึ้นบรรทัดของบทกวีอยู่ในข้อ

    ⛔ **ไม่มีกฎจุลภาคหลักพันแบบ TCV** ⇒ กฎนั้นแก้ตัวเลขที่เสียงไทยอ่านผิด ⇒ ฉบับอังกฤษอ่าน `5,000` ถูกอยู่แล้ว
       และ THKJV ⇒ ⛔ แตะตัวบทไม่ได้เลย เพราะเจ้าของฉบับเขียนไว้ว่า *ห้ามเปลี่ยนคำหรือเครื่องหมายวรรคตอน*
    """
    out = ดิบ.replace(ช่องว่างศูนย์, "")
    if ฉบับ == "LSV":
        out = out.replace("|", " ")
    return re.sub(r"\s+", " ", out).strip()


