    ctx = เปิด.ctx
    const แท็บ = เปิด.แท็บ
    // ⭐ รอสัญญาณจริงว่าหน้าถึงจังหวะ *กำลังหยิบบทที่ขอ* แล้ว ⇒ ⛔ ไม่ได้นอนรอ ⇒ เส้นตายเป็นแค่เพดาน ⛔ ไม่ค้างเงียบ
