/**
 * ข้อ ② ⇒ จอ 1280 · ข้อ ③ ⇒ จอ 320 · 375 · 1280 ⇒ `พัง` = ชื่อของพังใน `ยัด` หรือ null
 * ⭐ ข้อ ② เดิมตรวจจอ 375 ด้วย ⇒ ใบ #113 ให้จอแคบบอกบท ⇒ จอแคบย้ายไปเป็นข้อ ④ ⑤ ⑥ ⑦ ที่ตรวจว่า *ต้องบอกถูก*
 */
async function ตรวจแถบล่าง(พัง) {
  const ตก = []
  for (const กว้าง of [320, 375, 1280]) {
    let ctx
    try {
      const เปิด = await เปิดหน้า(เริ่มที่, กว้าง)
      ctx = เปิด.ctx
      const แท็บ = เปิด.แท็บ
      if (พัง) await ยัด[พัง](แท็บ)
      const คำ = await คำบนแถบล่าง(แท็บ)
      if (กว้าง >= 768) {
        if (คำ === null) ตก.push(`② จอ ${กว้าง} ⇒ ⛔ ไม่เจอทางเดินบทบนแถบล่าง`)
        else if (/ยอห์น|\d/.test(คำ))
          ตก.push(`② จอ ${กว้าง} ⇒ แถบล่างเขียนว่า “${คำ}” ⇒ ⛔ จอกว้างห้ามบอกชื่อเล่มหรือบทซ้ำกับหัวคอลัมน์ที่หนึบอยู่ (ใบ #104 ข้อ 7)`)
      }
      const ขนาด = await ขนาดปุ่มกลาง(แท็บ)
      if (!ขนาด) ตก.push(`③ จอ ${กว้าง} ⇒ ⛔ ไม่มีปุ่มกลางบนแถบล่าง ⇒ ห้ามทำให้ปุ่มหาย (ใบ #104 ข้อ 7)`)
      else if (ขนาด.กว้าง < 44 || ขนาด.สูง < 44)
        ตก.push(`③ จอ ${กว้าง} ⇒ ปุ่มกลางกว้าง ${ขนาด.กว้าง} สูง ${ขนาด.สูง} จุด ⇒ ต้องไม่เล็กกว่า 44 × 44 (ใบ #104 ข้อ 7 · ใบ #113 ข้อ 8)`)
      else if (!พัง) console.log(`  ②③ จอ ${กว้าง} ⇒ แถบล่าง “${คำ}” · ปุ่มกลาง ${ขนาด.กว้าง} × ${ขนาด.สูง} จุด`)
    } catch (e) {
      ตก.push(`②③ จอ ${กว้าง} ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx?.close()
    }
  }
  return ตก
}

