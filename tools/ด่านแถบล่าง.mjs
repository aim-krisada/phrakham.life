/**
 * อ่าน **ทั้งสองค่าในจังหวะเดียวกัน** ⇒ ⛔ ไม่ใช่ยิงเข้าไปถาม 2 รอบ
 *
 * ⛔⛔ **ของเดิมแยกเป็น 2 ฟังก์ชัน แล้วยิงทีละรอบ** ⇒ ระหว่างรอบแรกกับรอบสอง
 *   หน้ายังเลื่อนและวาดต่อได้ ⇒ **ค่าที่ได้มาจากคนละวินาที** ⇒ เทียบกันแล้วไม่มีความหมาย
 * ⇒ รวมมาไว้ใน `evaluate` เดียว ⇒ ทั้งคู่เป็นภาพนิ่งของจังหวะเดียวกันเสมอ
 *
 * `หลอก` เป็นจริงเฉพาะโหมดพิสูจน์ ⇒ เขียนเลขบทผิดทับลงบนป้ายหัวคอลัมน์ **ในจังหวะเดียวกัน** ก่อนอ่าน
 */
const อ่านทั้งคู่ = (แท็บ, หลอก) =>
  แท็บ.evaluate((หลอกไหม) => {
    const หมุด = [...document.querySelectorAll('[data-หมุดบท]')]
    if (!หมุด.length) return { ควร: null, ขึ้น: null }
    const ขอบบน = document.querySelector('.pk-แถบบน')?.getBoundingClientRect().height || 0
    const สูงล่าง = document.querySelector('.pk-แถบล่าง')?.getBoundingClientRect().height || 0
    const ขอบล่าง = window.innerHeight - สูงล่าง
    const ปลาย =
      document.querySelector('.pk-ตัวบท')?.getBoundingClientRect().bottom ?? window.innerHeight
    let ควร = null
    let มากสุด = -Infinity
    for (let i = 0; i < หมุด.length; i++) {
      const บน = หมุด[i].getBoundingClientRect().top
      const ล่าง = i + 1 < หมุด.length ? หมุด[i + 1].getBoundingClientRect().top : ปลาย
      const กิน = Math.min(ล่าง, ขอบล่าง) - Math.max(บน, ขอบบน)
      if (กิน > มากสุด) {
        มากสุด = กิน
        ควร = Number(หมุด[i].getAttribute('data-หมุดบท'))
      }
    }

    // ⭐ ป้ายของคอลัมน์แรก ⇒ ป้ายที่ตาเห็นอยู่ ⇒ จอ 1280 หัวคอลัมน์หนึบอยู่ใต้แถบบน
    const ป้าย = [...document.querySelectorAll('.pk-หัวคอลัมน์ .pk-ที่ของช่อง')].find((x) => x.getClientRects().length)
    if (!ป้าย) return { ควร, ขึ้น: null }
    // ⭐ โหมดพิสูจน์ ⇒ เขียนเลขบทผิดทับลงไป **ในจังหวะเดียวกับที่อ่าน** ⇒ ด่านต้องจับได้
    if (หลอกไหม) ป้าย.textContent = 'ยอห์น 99'
    const m = (ป้าย.textContent || '').trim().match(/(\d+)\s*$/)
    return { ควร, ขึ้น: m ? Number(m[1]) : null }
  }, หลอก)

/** ข้อความที่ **ตาเห็น** บนแถบล่างส่วนทางเดินบท ⇒ ⛔ ไม่นับคำที่มีไว้ให้โปรแกรมอ่านหน้าจอ */
const คำบนแถบล่าง = (แท็บ) =>
  แท็บ.evaluate(() => {
    const nav = document.querySelector('.pk-นำทางล่าง')
    if (!nav) return null
    const เดิน = (n) =>
      n.nodeType === 3
        ? n.textContent
        : n.classList?.contains('pk-เฉพาะเสียง') ||
            n.getAttribute?.('aria-hidden') === 'true' ||
            // ⭐ ของที่ ⛔ ไม่ได้ถูกวาด (`display: none`) ⇒ ตาไม่เห็น ⇒ ป้ายจอแคบที่ซ่อนอยู่บนจอกว้าง (ใบ #113)
            (n.nodeType === 1 && !n.getClientRects().length) ||
            // ⭐ ซ่อนเฉพาะทางสายตา (ท่าเดียวกับ `.pk-เฉพาะเสียง`) ⇒ คำ *เปลี่ยนตอน* ของจอแคบที่มีไว้ให้โปรแกรมอ่านหน้าจอ
            (n.nodeType === 1 && getComputedStyle(n).clipPath === 'inset(50%)')
          ? ''
          : [...n.childNodes].map(เดิน).join('')
    return เดิน(nav).replace(/\s+/g, ' ').trim()
  })

/** ขนาดกล่องกดของปุ่มกลาง ⇒ ⛔ ไม่มีปุ่ม = null */
