const รอบทนานสุด = 30000

/** อ่านว่าที่อยู่ขออะไร ⇒ `{ บท }` · `{ ช่วง }` · ⛔ ไม่ได้ขอ = null ⇒ ⭐ ที่อยู่เดิม `/read/JHN/4` = ขอบท 4 */
function ที่ขอ(ที่อยู่) {
  const u = new URL(ที่อยู่, 'http://x')
  const r = /^(\d+)\.(\d+)-(\d+)\.(\d+)$/.exec(u.searchParams.get('r') || '')
  if (r) return { ช่วง: { จากบท: +r[1], จากข้อ: +r[2], ถึงบท: +r[3], ถึงข้อ: +r[4] } }
  const c = u.searchParams.get('c') || /^\/read\/[^/]+\/(\d+)/.exec(u.pathname)?.[1]
  return c ? { บท: Number(c) } : null
}

const คำของที่ขอ = (ขอ) =>
  ขอ.ช่วง ? `ช่วง ${ขอ.ช่วง.จากบท}:${ขอ.ช่วง.จากข้อ}–${ขอ.ช่วง.ถึงบท}:${ขอ.ช่วง.ถึงข้อ}` : `บท ${ขอ.บท}`

/**
 * รันในหน้า ⇒ **หน้าแสดงของที่ขอแล้วหรือยัง** ⇒ ดูจากตัวบทอย่างเดียว ⛔ ไม่แตะป้าย
 * ⭐ แยกเป็นฟังก์ชันเดียว ⇒ ตัวรอ (`รอที่ขอขึ้นจอ`) กับฝาแฝด (`พิสูจน์การรอ`) ใช้ตัวเดียวกัน ⛔ ไม่เขียนซ้ำแล้วเลื่อนออกจากกัน
 */
function ที่ขอขึ้นจอแล้ว(ขอ) {
  const หมุด = [...document.querySelectorAll('[data-หมุดบท]')]
  if (!หมุด.length) return false
  if (ขอ.ช่วง) {
    const { จากบท, จากข้อ, ถึงบท, ถึงข้อ } = ขอ.ช่วง
    const เลข = หมุด.map((x) => Number(x.getAttribute('data-หมุดบท')))
    return (
      เลข.includes(จากบท) &&
      เลข.every((b) => b >= จากบท && b <= ถึงบท) &&
      !!document.querySelector(`.pk-ตัวบท [data-ข้อ="${จากบท}:${จากข้อ}"]`) &&
      !!document.querySelector(`.pk-ตัวบท [data-ข้อ="${ถึงบท}:${ถึงข้อ}"]`)
    )
  }
  // ⭐ บทที่กินช่องอ่านมากที่สุด ⇒ สูตรเดียวกับ `อ่านบทกับป้ายล่าง` (ช่องอ่าน = ระหว่างแถบบนกับแถบล่าง)
  const ขอบบน = document.querySelector('.pk-แถบบน')?.getBoundingClientRect().height || 0
  const ขอบล่าง = window.innerHeight - (document.querySelector('.pk-แถบล่าง')?.getBoundingClientRect().height || 0)
  const ปลาย = document.querySelector('.pk-ตัวบท')?.getBoundingClientRect().bottom ?? window.innerHeight
  let ควร = null
  let มากสุด = -Infinity
  for (let i = 0; i < หมุด.length; i++) {
    const บน = หมุด[i].getBoundingClientRect().top
    const ล่าง = i + 1 < หมุด.length ? หมุด[i + 1].getBoundingClientRect().top : ปลาย
    const กิน = Math.min(ล่าง, ขอบล่าง) - Math.max(บน, ขอบบน)
    if (กิน > มากสุด) {
      มากสุด = กิน
      ควร = Number(หมุด[i].getAttribute('data-หมุดบท'))
    }
  }
  return ควร === ขอ.บท
}

/**
 * รอจนหน้าแสดงบทหรือช่วงที่ `ที่อยู่` ขอ ⇒ ⛔ ขึ้นไม่ทันเส้นตาย = โยนข้อผิดพลาดภาษาไทย ⇒ ข้อที่เรียกเขียนเป็นข้อที่ตก
 * ⭐ `waitForFunction` ถามซ้ำข้ามการเปลี่ยนหน้าได้ ⇒ ที่อยู่เดิม `/read/JHN/4` ที่พาไปหน้าใหม่ก็รอได้
 */
async function รอที่ขอขึ้นจอ(แท็บ, ที่อยู่) {
  const ขอ = ที่ขอ(ที่อยู่)
  if (!ขอ) return
  const ขึ้น = await แท็บ
    .waitForFunction(ที่ขอขึ้นจอแล้ว, ขอ, { timeout: รอบทนานสุด })
    .then((h) => h.dispose().then(() => true))
    .catch(() => false)
  if (ขึ้น) return
  const บนหน้า = await แท็บ
    .evaluate(() => [...document.querySelectorAll('[data-หมุดบท]')].map((x) => x.getAttribute('data-หมุดบท')).join(', '))
    .catch(() => '')
  throw new Error(
    `เปิด ${ที่อยู่} แล้วหน้า ⛔ ไม่แสดง${คำของที่ขอ(ขอ)} ภายใน ${รอบทนานสุด / 1000} วินาที` +
      ` ⇒ บนหน้ายังเป็นบท ${บนหน้า || '(ไม่มีหมุดบท)'} ⇒ ⛔ อ่านป้ายตอนนี้ = อ่านป้ายของบทที่ไม่ได้ขอ`,
  )
}

/**
 * เปิดหน้า แล้ว **รอของจริง** ⛔ ไม่รอเป็นเวลาตายตัว (ใบ #113 ข้อ 7.5)
 *   ⇒ โค้ดของเว็บติด (`__vue_app__`) · **หน้าแสดงบทหรือช่วงที่ขอแล้วจริง** (`รอที่ขอขึ้นจอ`)
 *     · ปุ่มกลางมีบนหน้า · **ฟอนต์โหลดครบ** (`document.fonts.ready`)
 *   ⇒ ⭐ ฟอนต์ขาดไม่ได้ ⇒ ฟอนต์สำรองกว้างไม่เท่าฟอนต์จริง ⇒ วัดก่อนฟอนต์มา = วัดความกว้างของป้ายผิด
 * `ขนาด` = ค่าของปุ่ม ก+ ก− ที่เก็บไว้ในเครื่องผู้อ่าน (`pk-fs`) ⇒ `'2'` = 200% = ใหญ่สุดของเว็บ
 * `ก่อนเปิด` = ของที่ฝาแฝดยัดลงทางรับส่งก่อนเปิดหน้า (ถ่วงหรือตัดไฟล์บท)
 * `รอที่ขอ` = เท็จ เฉพาะฝาแฝด `พิสูจน์การรอ` ⇒ ได้การรอแบบเดิมเป๊ะ เพื่อพิสูจน์ว่าแบบเดิมอ่านผิด
 */
async function เปิดหน้า(ที่อยู่, กว้าง, { ขนาด = null, สูง = 800, ก่อนเปิด = null, รอที่ขอ = true } = {}) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: สูง } })
  if (ขนาด) await ctx.addInitScript((x) => localStorage.setItem('pk-fs', x), ขนาด)
  if (ก่อนเปิด) await ก่อนเปิด(ctx)
  const แท็บ = await ctx.newPage()
  try {
    await แท็บ.goto(`${ฐาน}${ที่อยู่}`, { waitUntil: 'domcontentloaded' })
    await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
    if (รอที่ขอ) await รอที่ขอขึ้นจอ(แท็บ, ที่อยู่)
    await แท็บ.waitForSelector(ปุ่มกลาง)
    await แท็บ.evaluate(() => document.fonts.ready.then(() => true))
  } catch (e) {
    // ⭐ ข้อที่เรียกยังไม่ได้ถือ `ctx` ⇒ ปิดเองที่นี่ ⛔ ไม่ทิ้งหน้าค้างไว้ในเบราว์เซอร์
    await ctx.close()
    throw e
  }
  return { ctx, แท็บ }
}

