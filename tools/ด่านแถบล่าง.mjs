//   ⇒ เว็บวางตัวบทกับป้ายในจังหวะเดียวกัน (`ไปที่จุด` ใน `app/components/หน้าอ่าน.vue`) ⇒ ตัวบทขึ้นแล้ว = ป้ายควรตามแล้ว
//     ⇒ ป้ายยังไม่ตาม = **เว็บพัง** ⇒ ด่านแดง ⛔ ไม่ใช่รอต่อ
// ⇒ บทที่ขอ ⛔ ไม่ขึ้นเลย ⇒ แดงที่เส้นตาย พร้อมบอกว่าหน้ายังค้างที่บทไหน ⇒ ⛔ ไม่ค้างเงียบ
//   ⇒ เส้นตายคือเพดาน ⛔ ไม่ใช่เวลาที่นอนรอ ⇒ หน้าขึ้นเมื่อไรออกทันที
