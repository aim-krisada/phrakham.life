def อ่านต้นฉบับ(ไฟล์):
    """อ่านตาราง MACULA ตรง ๆ ⇒ คืน {(เล่ม, บท, ข้อ): [ตัวอักษรของคำ, ...]}

    ⛔ ไม่เรียกโค้ดของตัวแปลงเลย ⇒ ตัวแปลงพลาด ตัวทานนี้จะไม่พลาดตาม
    """
    out = {}
    with io.open(ไฟล์, encoding="utf-8", newline="") as f:
        for แถว in csv.DictReader(f, delimiter="\t"):
            ที่อยู่ = แถว.get("ref") or ""
            try:
                รหัส, ที่เหลือ = ที่อยู่.split(" ", 1)
                บทข้อ, _ = ที่เหลือ.split("!", 1)
                บท, ข = บทข้อ.split(":", 1)
            except ValueError:
                continue
            if รหัส not in สารบบ:
                continue
            out.setdefault((รหัส, บท, ข), []).append(แถว["text"])
    return out


def อ่านที่ส่งขึ้น():
    """อ่านไฟล์รายบทที่จะขึ้นเว็บ ⇒ คืน ({(ชั้น, เล่ม, บท, ข้อ): [คำ...]}, ชุดบทที่มีไฟล์)"""
    if not กองคำ.exists():
        raise SystemExit(f"⛔ ไม่มี {กองคำ} ⇒ สั่ง py -3.14 tools/สร้างเนื้อบท.py ก่อน")
    คำ, บทที่มีไฟล์ = {}, set()
    for ไฟล์ in sorted(กองคำ.rglob("*.json.gz")):
        ไบต์ = ไฟล์.read_bytes()
        if ไบต์.startswith(b"version https://git-lfs"):
            raise SystemExit(f"⛔ {ไฟล์} เป็นตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง\n"
                             '   ⇒ สั่ง git lfs pull -I "_data/" ก่อน')
        d = json.loads(gzip.decompress(ไบต์).decode("utf-8"))
        บทที่มีไฟล์.add((d["เล่ม"], str(d["บท"])))
        for ชื่อชั้น, ข้อทั้งหมด in d["ชั้น"].items():
            for ข, รายการคำ in ข้อทั้งหมด.items():
                # ⭐ ช่องที่ต้นฉบับปล่อยว่าง ตัวแปลงจะไม่เขียนลงไฟล์เลย ⇒ ที่นี่จึงต้องเผื่อว่าง
                #   ⇒ เทียบกับ `text` ที่เป็นค่าว่างของต้นฉบับ ⇒ ยังตรงกันพอดี
                คำ[(ชื่อชั้น, d["เล่ม"], str(d["บท"]), ข)] = [w.get("ตัว", "") for w in รายการคำ]
    return คำ, บทที่มีไฟล์


