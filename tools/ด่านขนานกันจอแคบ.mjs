const เบราว์เซอร์ = await chromium.launch()

/** ตั้งค่าที่เครื่องผู้อ่านก่อนหน้าจะรัน ⇒ ⛔ ไม่ต้องไล่กดเมนูให้ช้าและเปราะ */
async function เปิดหน้า({ viewport, มุมมอง = {}, ขนาดอักษร = '0' }) {
  const ctx = await เบราว์เซอร์.newContext({ viewport })
  await ctx.addInitScript(
    ([ฉบับ, มุม, fs]) => {
      localStorage.setItem('phrakham.versions', JSON.stringify(ฉบับ))
      localStorage.setItem('pk-fs', fs)
      if (Object.keys(มุม).length) localStorage.setItem('phrakham.view', JSON.stringify(มุม))
    },
    [ฉบับที่ติ๊ก, มุมมอง, ขนาดอักษร],
  )
  const แท็บ = await ctx.newPage()
  return { ctx, แท็บ }
}

async function ไปที่บท(แท็บ) {
  await แท็บ.goto(`${ฐาน}/read/${ตอนที่ตรวจ.เล่ม}?c=${ตอนที่ตรวจ.บท}`, {
    waitUntil: 'domcontentloaded',
  })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, {
    timeout: 30000,
  })
  await แท็บ.waitForTimeout(400)
}

/** นับช่องฉบับที่ **ตาเห็นจริง** ⇒ ⛔ ไม่ใช่ที่มีอยู่ใน DOM ⇒ ของเดิมซ่อนด้วย `display: none` */
const สภาพหน้า = (แท็บ) =>
  แท็บ.evaluate(() => {
    const ข้อ = document.querySelector('.pk-ข้อ')
    const ช่อง = [...(ข้อ?.querySelectorAll('.pk-ช่องฉบับ') ?? [])]
    const เห็น = ช่อง.filter((c) => c.offsetParent !== null)
    // ⭐ ใบ #102 ⇒ หัวคอลัมน์บอกฉบับด้วย *ตัวเลือกฉบับ* ⇒ ป้ายบนหัวเป็นชื่อเล่มกับบท
    //   ⇒ นับเฉพาะหัวที่ **ตาเห็น** ⇒ ทีละฉบับซ่อนหัวของฉบับอื่นไว้ใน DOM
    const หัว = [...document.querySelectorAll('.pk-หัวคอลัมน์ .pk-ช่องหัว')].filter(
      (h) => h.offsetParent !== null,
    )
    return {
      ช่องทั้งหมด: ช่อง.length,
      ช่องที่เห็น: เห็น.length,
      ฉบับที่เห็น: เห็น.map((c) => c.getAttribute('data-ฉบับ')),
      ชื่อบนหัวคอลัมน์: หัว.map((h) => h.querySelector('select')?.value || ''),
      // ตัวอักษรของทุกช่องที่เห็น ⇒ ใช้ทานว่า **สลับการวางแล้วเนื้อ ⛔ ไม่หาย**
      เนื้อที่เห็น: เห็น.map((c) => (c.textContent || '').replace(/\s+/g, ' ').trim()),
      สูงแถบบน: Math.round(
        document.querySelector('.pk-แถบบน, header')?.getBoundingClientRect().height ?? 0,
      ),
    }
  })

/** ⭐ **ลองเลื่อนจริง** ⛔ ไม่ตัดสินด้วย `scrollWidth` ⇒ บทเรียนจากใบ #96 */
const เลื่อนทั้งหน้าได้ไหม = (แท็บ) =>
  แท็บ.evaluate(() => {
    const ราก = document.scrollingElement || document.documentElement
    const เดิม = ราก.scrollLeft
    ราก.scrollLeft = 9999
    const ขวา = ราก.scrollLeft
    ราก.scrollLeft = -9999
    const ซ้าย = ราก.scrollLeft
    ราก.scrollLeft = เดิม
    return {
      เลื่อนได้: Math.abs(ขวา - เดิม) > 1 || Math.abs(ซ้าย - เดิม) > 1,
      ตัวเลข: ราก.scrollWidth - ราก.clientWidth,
    }
  })

async function ดันตัวอักษรใหญ่สุด(แท็บ) {
  // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131#note_30332 ข้อ 2 ⇒ ก+ ย้ายเข้าแผง Aa ⇒ เปลี่ยนแค่ทางกด
  //   ⇒ กาง Aa ก่อน ⇒ กดเสร็จพับคืน ⇒ หน้าอยู่สภาพเดียวกับของเดิมที่ ก+ วางบนแถบ ⇒ เกณฑ์คงเดิม
  const ปุ่ม = await ปุ่มขนาดตัวอักษร(แท็บ, '+')
  for (let i = 0; i < 12 && !(await ปุ่ม.isDisabled()); i++) {
    await ปุ่ม.click()
    await แท็บ.waitForTimeout(100)
  }
  await พับแผงAa(แท็บ)
  await แท็บ.waitForTimeout(300)
}

/** กดตัวเลือกการวางในเมนู `เทียบ` (ชื่อเดิม `ฉบับ` ⇒ ใบ #102 · `คอลัมน์` ⇒ ใบ #113) ⇒ **หาด้วยชื่อที่ตาเห็น** ⇒ ชื่อเปลี่ยนเมื่อไรด่านแดงเอง */
async function ตั้งการวาง(แท็บ, แบบ) {
  await ปุ่มเทียบของหน้า(แท็บ).click()
  await แท็บ.waitForSelector('.pk-เมนู')
  await แท็บ.getByRole('radio', { name: ชื่อการวาง[แบบ], exact: true }).check()
  await แท็บ.waitForTimeout(400)
  await ปุ่มเทียบของหน้า(แท็บ).click()
  await แท็บ.waitForTimeout(300)
}

async function ตรวจ(ยัดกฎที่พัง) {
  const ตก = []

  // ---------------------------------------------------------------- ① ค่าตั้งต้น
  {
    const { ctx, แท็บ } = await เปิดหน้า({ viewport: จอแคบ })
    try {
      await ไปที่บท(แท็บ)
      const ส = await สภาพหน้า(แท็บ)
      if (ส.ช่องที่เห็น !== ฉบับที่ติ๊ก.length)
        ตก.push(
          `① ค่าตั้งต้นจอแคบ ⇒ เห็น ${ส.ช่องที่เห็น} ฉบับ ⛔ ต้องเห็นครบ ${ฉบับที่ติ๊ก.length} (ค่าตั้งต้นซ้ายขวา ⇒ ไม่พอเป็นบนล่าง)`,
        )
      if (ส.ช่องทั้งหมด !== ฉบับที่ติ๊ก.length)
        ตก.push(`① ติ๊กไว้ ${ฉบับที่ติ๊ก.length} ฉบับ แต่ใน DOM มี ${ส.ช่องทั้งหมด} ⇒ เนื้อหาย`)
    } catch (e) {
      ตก.push(`① ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  // ---------------------------------------------------------------- ② จอกว้างห้ามมีตัวเลือกนี้
  {
    const { ctx, แท็บ } = await เปิดหน้า({ viewport: จอกว้าง })
    try {
      await ไปที่บท(แท็บ)
      await ปุ่มเทียบของหน้า(แท็บ).click()
      await แท็บ.waitForSelector('.pk-เมนู')
      for (const ชื่อ of Object.values(ชื่อการวาง)) {
        const เจอ = await แท็บ.getByRole('radio', { name: ชื่อ, exact: true }).count()
        if (เจอ) ตก.push(`② จอกว้างยังเจอตัวเลือก ${ชื่อ} อยู่ ${เจอ} ตัว ⛔ มันไม่มีผลบนจอกว้าง`)
      }
    } catch (e) {
      ตก.push(`② ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  // ---------------------------------------------------------------- ③ ④ ⑥ ⑦ สลับไปขนานกัน
  {
    const { ctx, แท็บ } = await เปิดหน้า({ viewport: จอแคบ })
    try {
      await ไปที่บท(แท็บ)
      if (ยัดกฎที่พัง) await แท็บ.addStyleTag({ content: กฎที่พัง })
      // ⭐ ใบ #131 note_30367 ⇒ ค่าตั้งต้นไม่ใช่ทีละฉบับแล้ว ⇒ เลือกทีละฉบับเองก่อน ⇒ สภาพ *ก่อน* เท่าของเดิม ⇒ เกณฑ์ ③ ④ ⑦ เดิม
      await ตั้งการวาง(แท็บ, 'ทีละฉบับ')
      const ก่อน = await สภาพหน้า(แท็บ)

      await ตั้งการวาง(แท็บ, 'ซ้ายขวา')
      const หลัง = await สภาพหน้า(แท็บ)

      // ③ เห็นครบทุกฉบับ และเนื้อครบเท่าเดิม
      if (หลัง.ช่องที่เห็น !== ฉบับที่ติ๊ก.length)
        ตก.push(`③ ขนานกันแล้วเห็น ${หลัง.ช่องที่เห็น} ฉบับ ⛔ ต้องเห็นครบ ${ฉบับที่ติ๊ก.length}`)
      const เนื้อเดิม = ก่อน.เนื้อที่เห็น[0]
      if (เนื้อเดิม && !หลัง.เนื้อที่เห็น.includes(เนื้อเดิม))
        ตก.push('③ ⛔ สลับเป็นขนานกันแล้วตัวบทของฉบับที่เคยอ่านอยู่ เปลี่ยนไปหรือหายไป')

      // ④ รู้ว่าคอลัมน์ไหนเป็นฉบับไหน
      if (หลัง.ชื่อบนหัวคอลัมน์.length !== ฉบับที่ติ๊ก.length)
        ตก.push(
          `④ หัวคอลัมน์มีชื่อ ${หลัง.ชื่อบนหัวคอลัมน์.length} ชื่อ ⛔ ต้องมีครบ ${ฉบับที่ติ๊ก.length} ⇒ ผู้อ่านต้องรู้ว่าคอลัมน์ไหนเป็นฉบับไหน`,
        )

      // ⑦ แถบหนึบห้ามสูงขึ้น
      if (หลัง.สูงแถบบน > ก่อน.สูงแถบบน)
        ตก.push(`⑦ แถบหนึบสูงขึ้นจาก ${ก่อน.สูงแถบบน} เป็น ${หลัง.สูงแถบบน} จุด ⛔ ห้ามสูงขึ้น`)

      // ⑥ จำค่าข้ามรอบ
      await ไปที่บท(แท็บ)
      const หลังโหลดใหม่ = await สภาพหน้า(แท็บ)
      if (หลังโหลดใหม่.ช่องที่เห็น !== ฉบับที่ติ๊ก.length)
        ตก.push('⑥ ⛔ เปิดหน้าใหม่แล้วลืมว่าเลือก ซ้ายขวา ไว้')
    } catch (e) {
      ตก.push(`③④⑥⑦ ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  // ---------------------------------------------------------------- ⑤ ⑧ จอ 320 อักษรใหญ่สุด
  for (const ภาษาเดิม of [false, true]) {
    const ป้าย = ภาษาเดิม ? '⑧ ขนานกัน + ชั้นคำเปิด' : '⑤ ขนานกัน'
    const { ctx, แท็บ } = await เปิดหน้า({
      viewport: จอแคบ,
      ขนาดอักษร: '2',
      มุมมอง: {
        จัดวาง: 'แยกตามข้อ',
        แสดงเลข: true,
        ภาษาเดิม,
        ขนาดคำเดิม: 'ตามขนาดจริง',
        วางจอแคบ: 'ขนานกัน',
        ฉบับที่ดู: '',
      },
    })
    try {
      await ไปที่บท(แท็บ)
      if (ยัดกฎที่พัง) await แท็บ.addStyleTag({ content: กฎที่พัง })
      await ดันตัวอักษรใหญ่สุด(แท็บ)

      const ล้น = await เลื่อนทั้งหน้าได้ไหม(แท็บ)
      if (ล้น.เลื่อนได้)
        ตก.push(
          `${ป้าย} ⇒ จอ 320 ตัวอักษรใหญ่สุด ⇒ **ลากทั้งหน้าเลื่อนซ้ายขวาได้** (${ล้น.ตัวเลข} จุด) ⛔ ห้ามเลื่อนสองแกน`,
        )

      // ⛔⛔ **วัดแค่ว่าทั้งหน้าเลื่อนได้ไหม ⇒ ด่านนี้จะโกหก** (เจอตอนท่อ 11315 job 52875)
      //   ⇒ กล่องอ่าน `.pk-เนื้อ.pk-ม้วน` ตั้ง `overflow-x: clip` ไว้
      //     ⇒ คอลัมน์ที่กว้างเกินกล่อง **ถูกตัดทิ้งเงียบ ๆ** ⇒ ทั้งหน้าจึง ⛔ ไม่เลื่อนเลยสักจุด
      //     ⇒ วัดเอง ⇒ ยัดขั้นต่ำ 400 จุด ⇒ คอลัมน์ออกมา 400 ในกล่อง 234 ⇒ **ยื่นพ้น 56 ตัว**
      //       **แต่ `เลื่อนทั้งหน้าได้` ยังเป็นเท็จ** ⇒ ถ้าเชื่อตัวเดียวก็ปล่อยของพังผ่านไป
      //   ⇒ 🔴 **และการถูกตัดแย่กว่าการล้น** ⇒ ล้นยังเลื่อนไปอ่านได้ ⇒ ถูกตัดคือ **ตัวบทหายไปเฉย ๆ**
      //   ⇒ ⭐ **จึงต้องดูที่ตัวคอลัมน์เองว่ามันยื่นพ้นกล่องที่มันอยู่ไหม**
      //     ⇒ บทเรียนเดียวกับใบ #95 และ #96 ⇒ **อย่าวัดที่ทั้งหน้าอย่างเดียว**
      const ยื่นพ้นกล่อง = await แท็บ.evaluate(() => {
        const พ้น = []
        for (const กล่อง of document.querySelectorAll('.pk-ข้อ .pk-ช่องทั้งหมด')) {
          const ก = กล่อง.getBoundingClientRect()
          for (const c of กล่อง.children) {
            if (c.offsetParent === null) continue
            const b = c.getBoundingClientRect()
            if (b.right > ก.right + 1 || b.left < ก.left - 1)
              พ้น.push(`${Math.round(b.width)} จุด ในกล่อง ${Math.round(ก.width)} จุด`)
          }
        }
        return พ้น
      })
      if (ยื่นพ้นกล่อง.length)
        ตก.push(
          `${ป้าย} ⇒ **คอลัมน์ยื่นพ้นกล่องแล้วถูกตัดทิ้ง** ${ยื่นพ้นกล่อง.length} ช่อง ⇒ เช่น ${ยื่นพ้นกล่อง[0]} ⛔ ตัวบทหายไปจากสายตา`,
        )

      // ⭐ ที่ 320 คอลัมน์ต้อง **ตกเหลือคอลัมน์เดียว** ⇒ นั่นคือข้อ *เรียงต่อกันเป็นม้วน*
      const กี่คอลัมน์ = await แท็บ.evaluate(() => {
        const กล่อง = document.querySelector('.pk-ข้อ .pk-ช่องทั้งหมด')
        if (!กล่อง) return 0
        const บน = new Map()
        for (const c of กล่อง.children) {
          if (c.offsetParent === null) continue
          const t = Math.round(c.getBoundingClientRect().top)
          บน.set(t, (บน.get(t) || 0) + 1)
        }
        return บน.size ? Math.max(...บน.values()) : 0
      })
      if (กี่คอลัมน์ > 1)
        ตก.push(`${ป้าย} ⇒ จอ 320 ยังดัน ${กี่คอลัมน์} คอลัมน์ ⛔ ต้องตกเหลือม้วนเดียว`)
    } catch (e) {
      ตก.push(`${ป้าย} ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  // ---------------------------------------------------------------- ⑨ มือถือจริงต้องได้ 2 คอลัมน์
  // 🔴 **ข้อนี้คือตัวที่เฝ้าเกณฑ์ความกว้างขั้นต่ำเอง** (คนตรวจ !107 ทัก · 19 ต.ค. 2569)
  //   ⇒ เกณฑ์เดิม 160 จุด **ทำให้มือถือที่คนใช้จริง ⛔ ไม่ได้คอลัมน์เลยสักรุ่น**
  //     ⇒ จอ 360 ได้คอลัมน์ 133 จุด · จอ 412 ได้ 159 ⇒ ต่ำกว่าเกณฑ์ทั้งคู่ ⇒ ตกเป็นม้วนทั้งคู่
  //   ⇒ **ของทำงานถูกทุกข้อ แต่ยังไม่ตอบคำขอของพี่เอม** ⇒ *"อยู่ใน mobile mode ก็เห็นเป็น 2 คอลัมน์"*
  //   ⇒ ⭐ **ด่านจึงต้องล้มเมื่อเกณฑ์ถูกดันขึ้นไปจนมือถือหมดสิทธิ์** ⛔ ไม่ใช่ปล่อยให้เงียบ
  {
    const { ctx, แท็บ } = await เปิดหน้า({
      viewport: จอมือถือ,
      มุมมอง: {
        จัดวาง: 'แยกตามข้อ',
        แสดงเลข: true,
        ภาษาเดิม: false,
        ขนาดคำเดิม: 'ตามขนาดจริง',
        วางจอแคบ: 'ขนานกัน',
        ฉบับที่ดู: '',
      },
    })
    try {
      await ไปที่บท(แท็บ)
      if (ยัดกฎที่พัง) await แท็บ.addStyleTag({ content: กฎที่พัง })
      const กี่คอลัมน์ = await แท็บ.evaluate(() => {
        const กล่อง = document.querySelector('.pk-ข้อ .pk-ช่องทั้งหมด')
        if (!กล่อง) return 0
        const บน = new Map()
        for (const c of กล่อง.children) {
          if (c.offsetParent === null) continue
          const t = Math.round(c.getBoundingClientRect().top)
          บน.set(t, (บน.get(t) || 0) + 1)
        }
        return บน.size ? Math.max(...บน.values()) : 0
      })
      if (กี่คอลัมน์ < 2)
        ตก.push(
          `⑨ จอ ${จอมือถือ.width} ขนาดอักษรปกติ ⇒ ขนานกันได้ ${กี่คอลัมน์} คอลัมน์ ⛔ ต้องได้ 2 ⇒ **เกณฑ์ความกว้างขั้นต่ำกว้างเกินจนมือถือหมดสิทธิ์**`,
        )
    } catch (e) {
      ตก.push(`⑨ ล้มระหว่างตรวจ ⇒ ${e.message}`)
    } finally {
      await ctx.close()
    }
  }

  return ตก
}

const ตก = await ตรวจ(false)
