/** เปิดหน้าแล้ว **รอจนฟอนต์โหลดเสร็จจริง** ⛔ ไม่รอแบบเดา */
async function เปิด(แท็บ, ที่อยู่) {
  await แท็บ.goto(`${ฐาน}${ที่อยู่}`, { waitUntil: 'domcontentloaded' })
  await รอโหลดเสร็จ(แท็บ)
}
async function รอโหลดเสร็จ(แท็บ) {
  await แท็บ.waitForSelector('h1')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, {
    timeout: 30000,
  })
  // `document.fonts.ready` คือคำตอบของเบราว์เซอร์เองว่า "โหลดฟอนต์ที่หน้านี้ต้องใช้ครบแล้ว"
  await แท็บ.evaluate(() => document.fonts.ready)
  await แท็บ.waitForTimeout(200)
}

