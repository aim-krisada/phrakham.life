/**
 * ⭐ **ติดป้ายให้ทุกก้อนที่ตาผู้อ่านเห็นตัวหนังสือจริง** แล้วคืนน้ำหนักที่แต่ละก้อนขอใช้
 *   ⛔ **ต้องเป็นก้อนที่มีตัวหนังสือของตัวเอง** — `CSS.getPlatformFontsForNode` ตอบเฉพาะ
 *   ตัวหนังสือที่เป็นลูกตรงของก้อนนั้น ⇒ ถาม `<body>` เฉย ๆ จะได้ศูนย์ตัวอักษรเสมอ
 */
const ติดป้ายก้อนตัวหนังสือ = (แท็บ, ชื่อฟอนต์) =>
  แท็บ.evaluate((ชื่อฟอนต์) => {
    for (const el of document.querySelectorAll('[data-ก้อนฟอนต์]')) el.removeAttribute('data-ก้อนฟอนต์')
    const ก้อน = []
    for (const el of document.querySelectorAll('body *')) {
      if (!el.getClientRects().length) continue
      const ตัวหนังสือของตัวเอง = [...el.childNodes]
        .filter((n) => n.nodeType === 3)
        .map((n) => n.textContent)
        .join('')
      // ⛔ **1 ตัวอักษรก็นับ** — ตราประทับท้ายหน้ามี `<code>—</code>` ที่มีตัวเดียว
      //   ⇒ เคยตั้งขั้นต่ำไว้ 2 ตัว ⇒ ก้อนนั้นไม่ถูกติดป้าย ⇒ ตัวอักษรของมันไปโผล่ที่ก้อนพ่อ
      //     ⇒ ก้อนพ่อถูกตัดสินด้วยกติกาของก้อนพ่อ ⇒ **แดงผิดคน**
      if (ตัวหนังสือของตัวเอง.trim().length < 1) continue
      const cs = getComputedStyle(el)
      if (cs.visibility === 'hidden') continue
      el.setAttribute('data-ก้อนฟอนต์', String(ก้อน.length))
      // พ่อคือก้อนที่ติดป้ายไว้แล้วซึ่งอยู่ใกล้ตัวขึ้นไปที่สุด ⇒ ใช้หักตัวอักษรของลูกออกทีหลัง
      const พ่อ = el.parentElement?.closest('[data-ก้อนฟอนต์]')
      ก้อน.push({
        ที่: ก้อน.length,
        พ่อ: พ่อ ? Number(พ่อ.getAttribute('data-ก้อนฟอนต์')) : -1,
        ป้ายชื่อ: el.tagName.toLowerCase(),
        น้ำหนัก: cs.fontWeight,
        // ⭐ **ก้อนตัวพิมพ์ดีดคือก้อนที่ ⛔ ไม่ได้ขอฟอนต์ของเราเป็นตัวแรก** เช่น `<code>`
        //   ⇒ ตัวอังกฤษกับตัวเลขในนั้น **ตั้งใจ** ให้เป็นตัวพิมพ์ดีดของเครื่อง ⛔ ไม่ใช่ของตกหล่น
        ตัวพิมพ์ดีด: !cs.fontFamily.replace(/["']/g, '').startsWith(ชื่อฟอนต์),
        มีตัวไทย: /[฀-๿]/.test(ตัวหนังสือของตัวเอง),
        ตัวอย่าง: ตัวหนังสือของตัวเอง.trim().replace(/\s+/g, ' ').slice(0, 40),
        // ⭐ **ตัวอักษรที่ ⛔ ไม่ใช่ทั้งอังกฤษและไทย** ⇒ พวกนี้คือตัวที่ฟอนต์มักจะไม่มี
        //   ⇒ ใส่ไว้ในข้อความตอนแดง ⇒ คนอ่านรู้ทันทีว่าต้องไปแก้ตัวไหน
        ตัวแปลก: [
          ...new Set(
            [...ตัวหนังสือของตัวเอง].filter((c) => {
              const o = c.codePointAt(0)
              return o > 0x7f && !(o >= 0x0e00 && o <= 0x0e7f)
            }),
          ),
        ].join(''),
      })
    }
    return ก้อน
  }, ชื่อฟอนต์)

