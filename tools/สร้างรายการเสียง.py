def เติมTCVเล่มใหม่(ของTCV: dict, บทของซอง: dict) -> None:
    """เล่ม TCV ที่ทำทีละคืน (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/171) ⇒ รายการอยู่ที่ `เสียง/ที่มา/TCV.puck.json`

    ⭐ ไฟล์อยู่กองเดียวกับชุดของรุ่น 2 ชื่อแบบเดียวกัน ⇒ **ต่อเข้าก้อน TCV เดิม** ⇒ หน้าเว็บ ⛔ ไม่ต้องรู้ว่ามาจากสองรายการ
    ⛔ **กติกาเดียวกับข้างบนทุกข้อ** ⇒ ไม่มีไฟล์ = หยุด · ไม่มีตัวบท = หยุด · เล่มซ้ำกับชุดของรุ่น 2 = หยุด
    ⇒ บทที่ยังไม่ได้ทำ ⇒ ⛔ ไม่มีกุญแจ ⇒ หน้าอ่านบอกผู้อ่านเองว่าบทนั้นยังไม่มีเสียง
    ⇒ ตรวจว่าเสียงตรงตัวบทไหม เป็นงานของ `tools/ด่านเสียงTCVเล่มใหม่.py` ⛔ ไม่ใช่ของตัวนี้
    """
    ทาง = ที่มาเสียง / "TCV.puck.json"
    if not ทาง.exists():
        return
    ร = json.loads(ทาง.read_text(encoding="utf-8"))
    osisเป็นเล่ม = {osis: k for k, osis in ลำดับเล่มTCV}
    เพิ่ม = 0
    for รหัส, e in ร["verses"].items():
        รหัสเล่ม = osisเป็นเล่ม.get(e["osis"])
        if รหัสเล่ม is None:  # ⇒ มาระโกกับกิจการ ⛔ ไม่อยู่ในลำดับ ⇒ ซ้ำกับชุดของรุ่น 2 ก็ตกที่นี่
            sys.exit(f"⛔ TCV.puck.json มีข้อ {รหัส} ของเล่มที่ไม่อยู่ในลำดับทำเสียง หรือซ้ำกับชุดของรุ่น 2")
        if not (กองเสียง / e["file"]).exists():
            sys.exit(f"⛔ TCV.puck.json บอกว่ามีเสียง {รหัส} แต่ ⛔ ไม่มีไฟล์ใน {กองเสียง}"
                     '\n   ⇒ ไฟล์เสียงอยู่ใน Git LFS ⇒ สั่ง git lfs pull -I "เสียง/" ก่อน')
        if str(e["v"]) not in ((บทของซอง.get(f"{รหัสเล่ม}/{e['c']}") or {}).get("TCV") or {}):
            sys.exit(f"⛔ TCV {รหัส} มีเสียงแต่ ⛔ ไม่มีตัวบทใน v3")
        ข = ของTCV["เล่ม"].setdefault(รหัสเล่ม, {"osis": e["osis"], "บท": {}})
        ข["บท"].setdefault(str(e["c"]), {})[str(e["v"])] = round(float(e["d"]), 2)
        ของTCV["รวมวินาที"] = round(ของTCV["รวมวินาที"] + float(e["d"]), 1)
        เพิ่ม += 1
    ของTCV["จำนวนข้อ"] += เพิ่ม
    for g in ร.get("gaps", []):
        osis, บท, ข้อ = g["id"].split(".")
        ของTCV["ไม่มีเสียง"].append({
            "เล่ม": osisเป็นเล่ม[osis], "บท": int(บท), "ข้อ": int(ข้อ),
            "เหตุผล": "ฉบับ TCV ไม่มีตัวบทของข้อนี้ จึงไม่มีเสียงให้ฟัง", "เหตุผลต้นทาง": g.get("reason", ""),
        })
    ของTCV["ไม่มีเสียง"].sort(key=lambda x: (x["เล่ม"], x["บท"], x["ข้อ"]))


def พ่นฉบับอื่น(ฉบับ: str, บทของซอง: dict) -> dict:
    """ฉบับที่พ่นด้วย `tools/พ่นเสียงพระคำ.py` ⇒ รายการอยู่ที่ `เสียง/ที่มา/<ฉบับ>.puck.json`

    ⛔ **กติกาเดียวกับ TCV ข้างบนทุกข้อ** ⇒ ไม่มีรายการ = หยุด · ไม่มีไฟล์ = หยุด · ไม่มีตัวบท = หยุด
    ⇒ ตรวจว่าเสียงตรงตัวบทไหม เป็นงานของ `tools/ด่านเสียงทุกฉบับ.py` ⛔ ไม่ใช่ของตัวนี้
    """
    ทาง = ที่มาเสียง / f"{ฉบับ}.puck.json"
    if not ทาง.exists():
        sys.exit(f"⛔ ไม่มีรายการเสียงของ {ฉบับ} ที่ {ทาง} ⇒ สั่ง tools/พ่นเสียงพระคำ.py {ฉบับ} --ยิง ก่อน")
    ร = json.loads(ทาง.read_text(encoding="utf-8"))
    osisเป็นเล่ม = {v: k for k, v in เล่มที่มีเสียงของฉบับอื่น.items()}
    เล่ม: dict[str, dict] = {}
    ขาด: list[str] = []
    รวมวินาที = 0.0
    for รหัส, e in sorted(ร["verses"].items(), key=lambda kv: (kv[1]["osis"], kv[1]["c"], kv[1]["v"])):
        รหัสเล่ม = osisเป็นเล่ม[e["osis"]]
        if not (กองเสียง / ร["dir"] / e["file"]).exists():
            ขาด.append(รหัส)
            continue
        if str(e["v"]) not in ((บทของซอง.get(f"{รหัสเล่ม}/{e['c']}") or {}).get(ฉบับ) or {}):
            sys.exit(f"⛔ {ฉบับ} {รหัส} มีเสียงแต่ ⛔ ไม่มีตัวบทใน v3")
        ข = เล่ม.setdefault(รหัสเล่ม, {"osis": e["osis"], "บท": {}})
        ข["บท"].setdefault(str(e["c"]), {})[str(e["v"])] = round(float(e["d"]), 2)
        รวมวินาที += float(e["d"])
    if ขาด:
        sys.exit(f"⛔ {ฉบับ} {len(ขาด)} ข้อ ⛔ ไม่มีไฟล์ใน {กองเสียง / ร['dir']} ⇒ ตัวอย่าง {ขาด[:5]}")
    return {
        "เสียง": ร["voice"],
        "พ่นเมื่อ": ร["generated"],
        "ทางย่อย": ร["dir"],
        "จำนวนข้อ": len(ร["verses"]),
        "รวมวินาที": round(รวมวินาที, 1),
        "แหล่ง": ร["source"],
        "เล่ม": เล่ม,
        "ไม่มีเสียง": [
            {"เล่ม": osisเป็นเล่ม[g["id"].split(".")[0]], "บท": int(g["id"].split(".")[1]),
             "ข้อ": int(g["id"].split(".")[2]), "เหตุผล": g["reason"]}
            for g in ร.get("gaps", [])
        ],
    }


def เขียน(ของ: dict) -> bytes:
    # ⭐ เรียงกุญแจคงที่ + ขึ้นบรรทัดท้ายไฟล์ ⇒ **ไบต์เท่าเดิมทุกครั้งที่พ่น** ⇒ `--ตรวจ` ถึงเชื่อได้
    return (json.dumps(ของ, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")


def main() -> int:
    ป = argparse.ArgumentParser(description=__doc__)
    ป.add_argument("--ตรวจ", action="store_true", help="พ่นใหม่แล้วเทียบกับไฟล์เดิมทุกไบต์")
    ต = ป.parse_args()

    ของ = พ่น()
    ไบต์ = เขียน(ของ)

    if ต.ตรวจ:
        if not ไฟล์ผล.exists():
            print(f"⛔ ยังไม่มี {ไฟล์ผล} ⇒ พ่นก่อน")
            return 1
        if ไฟล์ผล.read_bytes() != ไบต์:
            print(f"⛔ {ไฟล์ผล} ⛔ ไม่ตรงกับของที่พ่นใหม่ ⇒ พ่นใหม่แล้วคอมมิต")
            return 1
        print(f"✅ {ไฟล์ผล} ตรงกับของที่พ่นใหม่ทุกไบต์")
        return 0

    ไฟล์ผล.parent.mkdir(parents=True, exist_ok=True)
    ไฟล์ผล.write_bytes(ไบต์)
    for ชื่อ, ฉ in ของ["ฉบับ"].items():
        print(
            f"✅ {ชื่อ} ⇒ {ฉ['จำนวนข้อ']:,} ข้อ"
            f" · {ฉ['รวมวินาที']/3600:.1f} ชั่วโมง"
            f" · ข้อที่ ⛔ ไม่มีเสียง {len(ฉ['ไม่มีเสียง'])} ข้อ"
        )
    print(f"✅ พ่น {ไฟล์ผล.relative_to(ราก)} ⇒ {len(ไบต์):,} ไบต์")
    return 0


if __name__ == "__main__":
    sys.exit(main())
