import json, sys, os, io, re

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

ราก = 'docs/ข้อมูล/ผลตรวจความหมาย'
ยาวสูงสุด = 4600          # ตัวอักษรต่อการถาม 1 ครั้ง ⇒ ต่ำกว่าชุดสั้นสุดที่ไม่ตอบ (5,335) พอสมควร


def แยกก้อน(เนื้อ):
    """คืน (หัวคำถาม, [ก้อนข้อสอบ...]) ⇒ ก้อนหนึ่งเริ่มที่บรรทัด `--- ข้อสอบ N`"""
    i = เนื้อ.index('--- ข้อสอบ')
    return เนื้อ[:i], [b for b in re.split(r'(?=--- ข้อสอบ )', เนื้อ[i:]) if b.strip()]


def เลขของก้อน(ก้อน):
    return int(re.match(r'--- ข้อสอบ (\d+)', ก้อน).group(1))


def main(args):
    if '--งาน' not in args or '--ชุด' not in args:
        print(__doc__); return 1
    งาน = args[args.index('--งาน') + 1]
    ขอ = {int(a) for a in args[args.index('--ชุด') + 1:] if a.isdigit()}
    ที่ไฟล์ = os.path.join(ราก, งาน + '-ข้อสอบ.json')
    ข้อสอบ = json.load(open(ที่ไฟล์, encoding='utf-8'))
    ชุดถัดไป = max(s['ชุด'] for s in ข้อสอบ['ชุดคำถาม']) + 1
    เพิ่ม = []

    for s in ข้อสอบ['ชุดคำถาม']:
        if s['ชุด'] not in ขอ or s.get('ยกเลิก'):
            continue
        เนื้อ = open(os.path.join(ราก, งาน + '-คำถาม', s['ไฟล์']), encoding='utf-8').read()
        หัว, ก้อน = แยกก้อน(เนื้อ)

        # หั่นให้แต่ละชุดย่อยยาวไม่เกินเกณฑ์ ⇒ ⛔ ไม่หั่นกลางข้อ
        กอง, กำลังทำ = [], []
        for b in ก้อน:
            if กำลังทำ and len(หัว) + sum(map(len, กำลังทำ)) + len(b) > ยาวสูงสุด:
                กอง.append(กำลังทำ); กำลังทำ = []
            กำลังทำ.append(b)
        if กำลังทำ:
            กอง.append(กำลังทำ)

        s['ยกเลิก'] = 'ยาวเกินจนตัวตรวจคืนของเปล่า ⇒ แบ่งเป็นชุด %s' % (
            [ชุดถัดไป + i for i in range(len(กอง))],)
        for i, ก in enumerate(กอง):
            ใหม่ = ชุดถัดไป + i
            ชื่อไฟล์ = 'ชุด%02d.txt' % ใหม่
            ข้อความ = หัว + ''.join(ก)
            # หัวคำถามบอกจำนวนข้อไว้ ⇒ ต้องแก้ให้ตรง ⛔ ปล่อยไว้จะขัดกับของที่ยกมาให้จริง
            ข้อความ = re.sub(r'ข้างล่างมี \d+ ข้อ', 'ข้างล่างมี %d ข้อ' % len(ก), ข้อความ, count=1)
            with open(os.path.join(ราก, งาน + '-คำถาม', ชื่อไฟล์), 'w',
                      encoding='utf-8', newline='\n') as f:
                f.write(ข้อความ)
            เพิ่ม.append({'ชุด': ใหม่, 'ฝั่ง': s['ฝั่ง'], 'ไฟล์': ชื่อไฟล์,
                          'เลขข้อสอบ': [เลขของก้อน(b) for b in ก],
                          'แบ่งมาจากชุด': s['ชุด']})
            print('ชุด %02d ⇒ %d ข้อ · %d ตัวอักษร' % (ใหม่, len(ก), len(ข้อความ)))
        ชุดถัดไป += len(กอง)

    ข้อสอบ['ชุดคำถาม'] += เพิ่ม
    with open(ที่ไฟล์, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(ข้อสอบ, f, ensure_ascii=False, indent=1)
    print('ขึ้นทะเบียนชุดใหม่ %d ชุด ลง %s' % (len(เพิ่ม), ที่ไฟล์))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
