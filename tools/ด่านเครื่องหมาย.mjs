// ---------------------------------------------------------------- แกะ zip เอง (ท่าเดียวกับ `ด่านคำเน้น.mjs`)
function แกะzip(ไบต์) {
  let ท้าย = ไบต์.length - 22
  while (ท้าย >= 0 && ไบต์.readUInt32LE(ท้าย) !== 0x06054b50) ท้าย--
  if (ท้าย < 0) throw new Error('⛔ zip ไม่มีสารบัญท้ายไฟล์ ⇒ ไม่ใช่ zip หรือเป็นตัวชี้ของ LFS')
  const จำนวน = ไบต์.readUInt16LE(ท้าย + 10)
  let p = ไบต์.readUInt32LE(ท้าย + 16)
  const ไฟล์ = new Map()
  for (let i = 0; i < จำนวน; i++) {
    const วิธี = ไบต์.readUInt16LE(p + 10)
    const ขนาดบีบ = ไบต์.readUInt32LE(p + 20)
    const ยาวชื่อ = ไบต์.readUInt16LE(p + 28)
    const ยาวเสริม = ไบต์.readUInt16LE(p + 30)
    const ยาวหมายเหตุ = ไบต์.readUInt16LE(p + 32)
    const หัวไฟล์ = ไบต์.readUInt32LE(p + 42)
    const ชื่อ = ไบต์.subarray(p + 46, p + 46 + ยาวชื่อ).toString('utf8')
    const เริ่ม = หัวไฟล์ + 30 + ไบต์.readUInt16LE(หัวไฟล์ + 26) + ไบต์.readUInt16LE(หัวไฟล์ + 28)
    const ก้อน = ไบต์.subarray(เริ่ม, เริ่ม + ขนาดบีบ)
    ไฟล์.set(ชื่อ, () => (วิธี === 0 ? ก้อน : inflateRawSync(ก้อน)).toString('utf8'))
    p += 46 + ยาวชื่อ + ยาวเสริม + ยาวหมายเหตุ
  }
  return ไฟล์
}

