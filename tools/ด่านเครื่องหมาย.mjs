function ตรงกัน(a, b) {
  if (a === b || a + 'ν' === b || b + 'ν' === a) return true
  const คู่ = new Set([a, b])
  if ([...คู่].every((x) => ['ου', 'ουκ', 'ουχ'].includes(x))) return true
  if (คู่.has('εκ') && คู่.has('εξ')) return true
  const [สั้น, ยาว] = a.length < b.length ? [a, b] : [b, a]
  if (ยาว.length === สั้น.length + 1 && 'αεηιουω'.includes(ยาว.at(-1)) && สั้น.length >= 2) {
    const หัว = สั้น.slice(0, -1) + ({ θ: 'τ', φ: 'π', χ: 'κ' }[สั้น.at(-1)] ?? สั้น.at(-1))
    if (ยาว.slice(0, -1) === หัว) return true
  }
  return false
}

