        await กางเครื่องมือภาษาเดิม(แท็บ)
        if (await แท็บ.locator(`${หัวคำเดิม} [data-ปุ่มเครื่องหมาย]`).count()) await แท็บ.locator(`${หัวคำเดิม} [data-ปุ่มเครื่องหมาย]`).click().catch(() => {})
