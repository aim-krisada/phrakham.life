/**
 * คำที่มีเครื่องหมาย ⇒ จากไฟล์ที่หลังบ้านส่งจริง ⇒ กางช่วงเองในด่าน ⛔ ไม่ใช้โค้ดของหน้าเว็บ
 * ⇒ `{แดง: [[ข้อ, ลำดับ, รหัสแดง, ต้นของรหัสใด]], ทุกรหัส: Map("<ข้อ>|<ลำดับ>" ⇒ [รหัสตามลำดับในไฟล์])}`
 */
async function คำที่ควรหนา(แท็บ, { เล่ม, บท }) {
  const ของ = await แท็บ.evaluate(async (u) => (await fetch(u)).json(), `${ฐาน}/api/words/${เล่ม}/${บท}.json`)
  const ทุกรหัส = new Map()
  const ต้น = new Set()
  const นับคำ = (v) => ของ.ชั้น?.คำกรีก?.[String(v)]?.length ?? 0
  for (const [รหัส, รายการ] of Object.entries(ของ.เครื่องหมาย ?? {}))
    for (const เครื่อง of รายการ) {
      const เลข = เครื่อง.filter((x) => typeof x === 'number')
      const ท่อน = รหัส === 'n' || เลข.length === 2 ? [[เลข[0], เลข[1], เลข[0], เลข[1]]] : []
      for (let i = 0; i + 3 < เลข.length && !ท่อน.length; i += 4) ท่อน.push(เลข.slice(i, i + 4))
      for (let i = 4; i + 3 < เลข.length && ท่อน.length && เลข.length > 4; i += 4) ท่อน.push(เลข.slice(i, i + 4))
      let แรก = !เครื่อง.includes('<')
      for (const [v1, w1, v2, w2] of ท่อน)
        for (let v = v1; v <= v2; v++)
          for (let w = v === v1 ? w1 : 0; w <= (v === v2 ? w2 : นับคำ(v) - 1); w++) {
            const k = `${v}|${w}`
            if (!ทุกรหัส.has(k)) ทุกรหัส.set(k, [])
            ทุกรหัส.get(k).push(รหัส)
            if (แรก && รหัส in รหัสแดง) ต้น.add(`${k}|${รหัส}`)
            แรก = false
          }
    }
  const แดง = []
  for (const [k, รหัสทั้งหมด] of ทุกรหัส) {
    const [ข้อ, i] = k.split('|')
    const ร = [...new Set(รหัสทั้งหมด.filter((x) => x in รหัสแดง))]
    if (ร.length) แดง.push([ข้อ, +i, ร.join(''), ร.filter((x) => ต้น.has(`${k}|${x}`))])
  }
  แดง.sort((a, b) => +a[0] - +b[0] || a[1] - b[1])
  return Object.assign(แดง, { ทุกรหัส })
}

