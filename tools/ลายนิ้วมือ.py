# ตัวชี้ของ LFS เป็นไฟล์ข้อความสั้น ๆ ⇒ ใหญ่กว่านี้ถือว่าเป็นไฟล์จริง
ขนาดตัวชี้สูงสุด = 1024


def เป็นตัวชี้(ทาง):
    """ไฟล์นี้เป็นตัวชี้ของ LFS หรือไฟล์จริง"""
    if os.path.getsize(ทาง) > ขนาดตัวชี้สูงสุด:
        return False
    with open(ทาง, "rb") as ฟ:
        return ฟ.read(60).startswith(b"version https://git-lfs")


def ซอง(ทาง):
    """ลายนิ้วมือของตัวไฟล์ zip ทั้งก้อน ⇒ จับไฟล์เสีย ไฟล์ถูกทับ โหลดไม่ครบ"""
    h = hashlib.sha256()
    with open(ทาง, "rb") as ฟ:
        for ก้อน in iter(lambda: ฟ.read(1 << 20), b""):
            h.update(ก้อน)
    return h.hexdigest()


def เนื้อใน(ทาง):
    """ลายนิ้วมือของข้อมูลข้างใน ⇒ ไม่ขึ้นกับวิธีบีบอัด
    ⇒ ต้นทางบีบอัดใหม่แล้วเลขซองเปลี่ยน แต่เลขนี้ไม่เปลี่ยน ถ้าข้อมูลเท่าเดิม"""
    h = hashlib.sha256()
    นับ = 0
    with zipfile.ZipFile(ทาง) as ซิป:
        for ชื่อ in sorted(ของ.filename for ของ in ซิป.infolist() if not ของ.is_dir()):
            h.update(ชื่อ.encode("utf-8"))
            h.update(ซิป.read(ชื่อ))
            นับ += 1
    return h.hexdigest(), นับ


def ที่โหลดมา():
    """หา zip ที่ "เราโหลดมา" ⛔ ไม่ใช่ zip ที่อยู่ข้างในของที่แตกแล้ว

    ⇒ เอาชั้นบนสุด กับชั้นถัดไป 1 ชั้น (เช่น tcv/) ⛔ ไม่ไล่ลึกกว่านั้น
    ⇒ แล้วตัดโฟลเดอร์ที่เป็น "ของที่แตกออกมา" ทิ้ง — ดูจากว่ามี <ชื่อ>.zip คู่กันอยู่ไหม
    **ทำไม** ⇒ ที่เก็บอย่าง OpenGNT มี zip ซ้อนอยู่ข้างในอีก 60 กว่าไฟล์
              ⇒ ไล่ทั้งหมดจะตรึงลายนิ้วมือของของที่ zip แม่ครอบไว้อยู่แล้ว
    """
    แตกแล้ว = {os.path.basename(ท)[:-4] for ท in glob.glob(os.path.join(กอง, "*.zip"))}
    ทางทั้งหมด = glob.glob(os.path.join(กอง, "*.zip")) + glob.glob(os.path.join(กอง, "*", "*.zip"))
    ผล = {}
    for ทาง in sorted(ทางทั้งหมด):
        ชื่อ = os.path.relpath(ทาง, กอง).replace(os.sep, "/")
        if "/" in ชื่อ and ชื่อ.split("/")[0] in แตกแล้ว:
            continue
        try:
            ก, น = เนื้อใน(ทาง)
        except zipfile.BadZipFile:
            ก, น = "⛔ ซิปเสีย", 0
        ผล[ชื่อ] = (os.path.getsize(ทาง), น, ซอง(ทาง), ก)
    return ผล


def อ่านบัญชี():
    if not os.path.exists(บัญชี):
        return None
    ผล = {}
    for เลขบรรทัด, บรรทัด in enumerate(open(บัญชี, encoding="utf-8"), 1):
        บรรทัด = บรรทัด.rstrip("\n")
        if not บรรทัด or บรรทัด.startswith("#"):
            continue
        ช่อง = บรรทัด.split(แท็บ)
        # ⛔ เทียบชื่อในช่องแรกแบบตรงตัว ⛔ ไม่ใช่ "บรรทัดขึ้นต้นด้วย"
        # **ทำไม** ⇒ ที่เก็บนี้ตั้งชื่อไฟล์เป็นภาษาไทยเป็นเรื่องปกติ
        #            startswith ทำให้ไฟล์ชื่อ "ไฟล์xxx.zip" ถูกข้ามไปเงียบ ๆ
        #            ⇒ บัญชีขาดของ แต่เครื่องมือขึ้นเขียว (คนตรวจจับได้ 21 ส.ค. 2569)
        if ช่อง[0] == หัว[0]:
            continue
        if len(ช่อง) != len(หัว):
            ตาย(f"บัญชีบรรทัดที่ {เลขบรรทัด} มี {len(ช่อง)} ช่อง ⇒ ต้องมี {len(หัว)} ช่อง")
        ชื่อ, ไบต์, ใน, ซ, น = ช่อง
        # ⛔ ช่องครบแต่ตัวเลขไม่ใช่ตัวเลข ก็ต้องหยุดพร้อมบอกบรรทัด
        # **ทำไม** ⇒ docs/บันทึก-แหล่งข้อมูล.md สัญญาว่า "บัญชีอ่านไม่ออกคืน 2 พร้อมบอกเลขบรรทัด"
        #            เดิม int() โยน ValueError ดิบ ⇒ คืน 1 และไม่บอกบรรทัด
        #            ⇒ การตรวจอัตโนมัติแยกไม่ออกว่า "บัญชีเสีย" หรือ "กองเปลี่ยน"
        #            (คนตรวจจับได้ใน v3/phrakham#2 ทัก 13 ⇒ คนทำพลาดไม่ได้อ่านก่อนรวม)
        try:
            ผล[ชื่อ] = (int(ไบต์), int(ใน), ซ, น)
        except ValueError:
            ตาย(f"บัญชีบรรทัดที่ {เลขบรรทัด} ช่องตัวเลขอ่านไม่ออก ⇒ {บรรทัด}")
    return ผล


จริง = ที่โหลดมา()

# ⛔⛔ ห้ามทำงานต่อถ้าไฟล์ยังเป็นตัวชี้ของ LFS
# **ทำไม** ⇒ ตัวชี้เป็นไฟล์ข้อความ 134 ไบต์ ⇒ คำนวณ sha ได้เหมือนกันหมด
#            ⇒ `--เขียน` จะ **ตรึงลายนิ้วมือของตัวชี้ทับบัญชีจริงเงียบ ๆ** ⇒ หลักฐานหายทั้งแฟ้ม
#            ⇒ โหมดเทียบก็จะขึ้น "เนื้อต่าง" ทั้ง 13 แถว โดยที่ของจริงไม่ได้เปลี่ยนอะไรเลย
# ⭐ tools/แตกกอง.py กันเรื่องนี้ไว้แล้ว ⇒ ที่นี่ต้องกันเหมือนกัน
#    (พบตอนทดลองบนโต๊ะที่เช็กเอาต์ใหม่ 21 ส.ค. 2569 · ใบงาน v3/phrakham#4)
ตัวชี้ = [ชื่อ for ชื่อ in จริง if เป็นตัวชี้(os.path.join(กอง, *ชื่อ.split("/")))]
if ตัวชี้:
    ตาย("ยังเป็นตัวชี้ของ LFS %d ไฟล์ ⇒ ทำงานต่อไม่ได้%s   %s%s   สั่งดึงไบต์จริงก่อน:  git -c lfs.fetchexclude= lfs pull -I \"source/\"" % (len(ตัวชี้), chr(10), " · ".join(ตัวชี้[:3]), chr(10)))

if "--เขียน" in sys.argv:
    with open(บัญชี, "w", encoding="utf-8", newline="\n") as ฟ:
        ฟ.write("# ลายนิ้วมือของกองต้นฉบับ — ตรึงไว้ด้วย tools/ลายนิ้วมือ.py\n")
        ฟ.write("# ⛔ ห้ามแก้ด้วยมือ · แก้แล้วบัญชีจะเลิกเป็นหลักฐาน\n")
        ฟ.write("# sha-ซอง = ทั้งไฟล์ zip · sha-เนื้อใน = ชื่อไฟล์เรียงลำดับ + เนื้อทุกไฟล์ (ไม่ขึ้นกับวิธีบีบอัด)\n")
        ฟ.write(แท็บ.join(หัว) + chr(10))
        for ชื่อ in sorted(จริง):
            ไบต์, ใน, ซ, น = จริง[ชื่อ]
            ฟ.write(แท็บ.join([ชื่อ, str(ไบต์), str(ใน), ซ, น]) + chr(10))
    print(f"✅ เขียน {บัญชี} · {len(จริง)} ไฟล์")
    sys.exit(0)

เก่า = อ่านบัญชี()
if เก่า is None:
    print(f"⛔ ยังไม่มีบัญชี {บัญชี} ⇒ สร้างด้วย --เขียน")
    sys.exit(1)

ตรง = ทัก = 0
print(f"{'ไฟล์':<34} {'ผล':<10} สิ่งที่เห็น")
print("-" * 96)
for ชื่อ in sorted(set(เก่า) | set(จริง)):
    ก, ข = เก่า.get(ชื่อ), จริง.get(ชื่อ)
    if ก is None:
        ผล, บอก = "⚠ เกินมา", "อยู่ในกองแต่ไม่มีในบัญชี ⇒ ของใหม่ที่ยังไม่ตรึง"
    elif ข is None:
        ผล, บอก = "⛔ หายไป", "อยู่ในบัญชีแต่ไม่มีในกอง"
    elif ก[3] != ข[3]:
        ผล, บอก = "⛔ เนื้อต่าง", f"ข้อมูลข้างในเปลี่ยน ⇒ ตัวเลขที่วัดไว้เชื่อไม่ได้แล้ว · ไฟล์ใน {ก[1]} ⇒ {ข[1]}"
    elif ก[2] != ข[2]:
        ผล, บอก = "⚠ ซองต่าง", "บีบอัดใหม่ แต่ข้อมูลข้างในเท่าเดิม ⇒ ตัวเลขที่วัดไว้ยังใช้ได้"
    else:
        ผล, บอก = "✅ ตรง", f"{ข[0]:,} ไบต์ · {ข[1]} ไฟล์"
    if ผล.startswith("✅"):
        ตรง += 1
    else:
        ทัก += 1
    print(f"{ชื่อ:<34} {ผล:<10} {บอก}")

print("-" * 96)
print(f"ตรงกับบัญชี {ตรง} จาก {len(เก่า)} · ที่ต้องดู {ทัก}")
print("⛔ ไม่ตรง = มีอะไรเปลี่ยน ⛔ ไม่ได้แปลว่าของใหม่ผิด ⇒ ไปดูของจริงก่อนตัดสิน")
sys.exit(1 if ทัก else 0)
