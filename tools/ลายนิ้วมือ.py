บัญชี = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "ลายนิ้วมือ.tsv")
หัว = ["ไฟล์", "ไบต์", "ไฟล์ใน", "sha-ซอง", "sha-เนื้อใน"]
# ตัวคั่นช่อง — ⭐ เรียกจากที่นี่ทั้งฝั่งอ่านและฝั่งเขียน
# **ทำไม** ⇒ เดิมฝั่งอ่านใช้ chr(9) ฝั่งเขียนใช้อักขระหนี ⇒ ผลเหมือนกันแต่คนอ่านต้องหยุดคิด
