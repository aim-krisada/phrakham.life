แท็บ = chr(9)


def ตาย(ข้อความ):
    """บัญชีอ่านไม่ออก = ห้ามเงียบ ⇒ หยุดแล้วบอกว่าบรรทัดไหน"""
    print(f"⛔ {ข้อความ}")
