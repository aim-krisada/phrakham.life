from ช่องต้องห้าม import อ่านรายชื่อ, อ่านไม่ออก   # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ที่เก็บ = Path(__file__).resolve().parent.parent
ปริยาย = [ที่เก็บ / "_ข้อมูลเว็บ", ที่เก็บ / "_data", ที่เก็บ / "docs"]


def เดินหากุญแจ(ของ, ห้าม, ทาง=""):
    """ไล่ทุกชั้นของ JSON ⇒ คืนรายการ (ทางที่เจอ, ชื่อช่อง) ที่ผิด"""
    เจอ = []
    if isinstance(ของ, dict):
        for k, v in ของ.items():
            ทางนี้ = f"{ทาง}.{k}" if ทาง else str(k)
            if k in ห้าม:
                เจอ.append((ทางนี้, k))
            เจอ += เดินหากุญแจ(v, ห้าม, ทางนี้)
    elif isinstance(ของ, list):
        for i, v in enumerate(ของ):
            เจอ += เดินหากุญแจ(v, ห้าม, f"{ทาง}[{i}]")
    return เจอ


def อ่านตัวหนังสือ(ไฟล์):
    """คืนตัวหนังสือของไฟล์ ⇒ ลงท้าย `.gz` ให้คลายซองก่อน

    ⛔ ตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง ⇒ ต้องบอกให้ชัด ไม่งั้นได้แต่ข้อความล้มของ gzip
    """
    ไบต์ = ไฟล์.read_bytes()
    if ไบต์.startswith(b"version https://git-lfs"):
        raise SystemExit(f"⛔ {ไฟล์} เป็นตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง\n"
                         '   ⇒ สั่ง git lfs pull -I "_data/" ก่อน')
    if ไฟล์.name.endswith(".gz"):
        ไบต์ = gzip.decompress(ไบต์)
    return ไบต์.decode("utf-8")


def ตรวจโฟลเดอร์(ที่, ห้าม, ละเอียด=True):
    """คืนจำนวนไฟล์ที่ตรวจ กับรายการที่ผิด"""
    ที่ = Path(ที่)
    if not ที่.exists():
        raise SystemExit(f"⛔ ไม่มีโฟลเดอร์ {ที่} ⇒ สร้างก่อนด้วย tools/สร้างข้อมูลเว็บ.py")
    # ⭐ กุญแจใน JSON เขียนเป็น "ชื่อ": เสมอ ⇒ ค้นรูปนี้จึงไม่ไปโดน **ค่า** ที่บังเอิญสะกดเหมือนกัน
    รูปกุญแจ = {c: re.compile(r'"' + re.escape(c) + r'"\s*:') for c in ห้าม}
    ผิด, นับไฟล์ = [], 0
    ทั้งหมด = sorted(set(ที่.rglob("*.json")) | set(ที่.rglob("*.json.gz")),
                    key=lambda x: x.as_posix())
    for ไฟล์ in ทั้งหมด:
        นับไฟล์ += 1
        ตัวหนังสือ = อ่านตัวหนังสือ(ไฟล์)
        ชื่อสั้น = ไฟล์.relative_to(ที่).as_posix()
        for ช่อง, รูป in รูปกุญแจ.items():
            if รูป.search(ตัวหนังสือ):
                ผิด.append((ชื่อสั้น, "กวาดตัวหนังสือดิบ", ช่อง))
        try:
            ของ = json.loads(ตัวหนังสือ)
        except json.JSONDecodeError as e:
            ผิด.append((ชื่อสั้น, "แกะ JSON ไม่ออก", str(e)))
            continue
        for ทาง, ช่อง in เดินหากุญแจ(ของ, ห้าม):
            ผิด.append((ชื่อสั้น, ทาง, ช่อง))
    return นับไฟล์, ผิด


def รายงาน(ที่, ห้าม, ละเอียด=True):
    นับไฟล์, ผิด = ตรวจโฟลเดอร์(ที่, ห้าม, ละเอียด)
    if ละเอียด:
        print(f"ด่าน ⑥ · ตรวจ {นับไฟล์:,} ไฟล์ที่ {ที่}")
        print(f"        ช่องต้องห้าม {len(ห้าม)} ช่อง ⇒ {' · '.join(ห้าม)}")
    if ผิด:
        print(f"\n⛔ **ข้อมูลที่เจ้าของไม่ให้เผยแพร่ หลุดออกมา {len(ผิด)} จุด**")
        for ไฟล์, ทาง, ช่อง in ผิด[:20]:
            print(f"   {ไฟล์} ⇒ {ทาง} ⇒ ช่อง `{ช่อง}`")
        if len(ผิด) > 20:
            print(f"   … และอีก {len(ผิด) - 20} จุด")
        print("⇒ ⛔ **หยุดตรงนี้** ⇒ หลุดออกไปแล้วเอากลับไม่ได้")
        return 1
    if ละเอียด:
        print("\n✅ ด่าน ⑥ เขียว ⇒ ไม่มีช่องต้องห้ามหลุดออกมาสักจุด")
    return 0


# =========================================================== พิสูจน์แดง-เขียว
def ทดสอบตัวเอง():
    """ทำของให้พังแล้วต้องแดง · ซ่อมแล้วต้องเขียว ⛔ ไม่ต้องมีกอง _แตก

    ⭐ **รันได้บนตัวรันของอัมกิต** ⇒ สร้างไฟล์ตัวอย่างเองในที่พักชั่วคราว
    """
    import tempfile

    try:
        ห้าม = อ่านรายชื่อ()
    except อ่านไม่ออก as e:
        print(f"⛔ เทสตก — อ่านรายชื่อช่องต้องห้ามไม่ได้: {e}")
        return 1
    if not ห้าม:
        print("⛔ เทสตก — อ่านรายชื่อได้ว่าง ⇒ ด่านจะเขียวตลอดโดยไม่ตรวจอะไรเลย")
        return 1
    ตัวอย่าง = ห้าม[0]

    สะอาด = {"เล่ม": "PSA", "บท": 32,
             "ชั้น": {"คำฮีบรู": {"2": [{"ตัว": "עָוֺן", "รหัส": "5771"}]},
                     "TCV": {"2": "คนที่พระยาห์เวห์ไม่ถือโทษบาปของเขา"}}}

    def ใส่ช่องต้องห้าม():
        ของ = json.loads(json.dumps(สะอาด))
        ของ["ชั้น"]["คำฮีบรู"]["2"][0][ตัวอย่าง] = "005389001001000"
        return ของ

    def ซ่อนลึก():
        ของ = json.loads(json.dumps(สะอาด))
        ของ["ชั้น"]["คำกรีก"] = {"8": [{"ตัว": "λόγος", "ของแถม": {ตัวอย่าง: "025011"}}]}
        return ของ

    def คำนั้นเป็นเนื้อความ():
        # ⭐ ชื่อช่องต้องห้ามที่โผล่มาเป็น **ค่า** ⛔ ไม่ใช่กุญแจ ⇒ **ต้องเขียว**
        ของ = json.loads(json.dumps(สะอาด))
        ของ["ชั้น"]["WEB"] = {"2": f"the king ruled his {ตัวอย่าง} well"}
        ของ["ชั้น"]["คำฮีบรู"]["2"][0]["คำแปล"] = ตัวอย่าง
        return ของ

    เทส = [
        ("ไฟล์สะอาด", lambda: สะอาด, 0, ".json"),
        (f"⭐ แอบใส่ช่อง `{ตัวอย่าง}` ลงในคำ", ใส่ช่องต้องห้าม, 1, ".json"),
        (f"⭐ ซ่อนช่อง `{ตัวอย่าง}` ไว้ลึกอีกชั้น", ซ่อนลึก, 1, ".json"),
        (f"คำว่า `{ตัวอย่าง}` เป็นเนื้อความ ⛔ ไม่ใช่ชื่อช่อง", คำนั้นเป็นเนื้อความ, 0, ".json"),
        # ⭐⭐ ของที่ขึ้นเว็บจริงอยู่ในซองที่บีบแล้ว ⇒ ด่านต้องคลายซองก่อนตรวจ
        #   ⇒ ⛔ เทสสองข้อนี้จะตก ทันทีที่ใครถอดการคลายซองออก
        ("ไฟล์บีบอัดที่สะอาด", lambda: สะอาด, 0, ".json.gz"),
        (f"⭐⭐ แอบใส่ช่อง `{ตัวอย่าง}` ลงในคำ **ในไฟล์บีบอัด**", ใส่ช่องต้องห้าม, 1, ".json.gz"),
        ("ซ่อมแล้ว ⇒ กลับมาเขียว", lambda: สะอาด, 0, ".json"),
    ]
    ตก = 0
    print(f"ด่าน ⑥ · พิสูจน์แดง-เขียว ⇒ ช่องต้องห้ามที่อ่านได้ {len(ห้าม)} ช่อง ⇒ {' · '.join(ห้าม)}\n")
    for ชื่อ, ทำของ, ควรได้, นามสกุล in เทส:
        with tempfile.TemporaryDirectory() as ชั่วคราว:
            p = Path(ชั่วคราว) / "PSA"
            p.mkdir()
            เนื้อ = json.dumps(ทำของ(), ensure_ascii=False).encode("utf-8")
            if นามสกุล.endswith(".gz"):
                เนื้อ = gzip.compress(เนื้อ, mtime=0)
            (p / f"32{นามสกุล}").write_bytes(เนื้อ)
            ได้ = รายงาน(Path(ชั่วคราว), ห้าม, ละเอียด=False)
        ผ่าน = ได้ == ควรได้
        ตก += 0 if ผ่าน else 1
        print(f"{'✅' if ผ่าน else '⛔'} {ชื่อ} ⇒ ควรคืน {ควรได้} · คืนจริง {ได้}")

    # ⭐ ตัวอ่านรายชื่อต้องหยุดเองเมื่อเอกสารกับจำนวนที่เขาเขียนไว้ไม่ตรงกัน
    with tempfile.TemporaryDirectory() as ชั่วคราว:
        ปลอม = Path(ชั่วคราว) / "บันทึก.md"
        ปลอม.write_text(
            "## ③ ⛔ ช่องที่ห้ามเผยแพร่\n\n"
            "| # | ช่อง | ห้ามเพราะ |\n|---|---|---|\n"
            "| 01 | `domain` · `ln` | เหตุผล |\n\n"
            "⇒ ⭐ **ห้ามจริง 6 ช่อง** — เลขนี้ไม่ตรงกับตารางข้างบน\n\n## ④ ถัดไป\n",
            encoding="utf-8")
        try:
            อ่านรายชื่อ(ปลอม)
            print("⛔ เอกสารบอก 6 ช่อง แต่ตารางมี 2 ⇒ ตัวอ่านไม่ทัก ⇒ เทสตก")
            ตก += 1
        except อ่านไม่ออก:
            print("✅ เอกสารบอกจำนวนไม่ตรงกับตาราง ⇒ ตัวอ่านหยุดเอง ⛔ ไม่เดาต่อ")

    print(f"\n{'✅ เทสผ่านครบ' if not ตก else f'⛔ เทสตก {ตก} ข้อ'}")
    return 1 if ตก else 0


def main():
    ป = argparse.ArgumentParser()
    ป.add_argument("--ที่", nargs="*", default=[str(x) for x in ปริยาย],
                   help="โฟลเดอร์ผลลัพธ์ที่จะตรวจ (ใส่ได้หลายโฟลเดอร์)")
    ป.add_argument("--ทดสอบตัวเอง", action="store_true", help="พิสูจน์แดง-เขียว ⛔ ไม่ต้องมีกอง")
    ต = ป.parse_args()
    if ต.ทดสอบตัวเอง:
        return ทดสอบตัวเอง()
    try:
        ห้าม = อ่านรายชื่อ()
    except อ่านไม่ออก as e:
        print(f"⛔ {e}")
        return 2
    # ⛔ ตรวจให้ครบทุกโฟลเดอร์ก่อนค่อยสรุป ⇒ เจอที่แรกแล้วหยุด = อีกที่ไม่เคยถูกตรวจ
    return max(รายงาน(ที่, ห้าม) for ที่ in ต.ที่)


if __name__ == "__main__":
    sys.exit(main())
