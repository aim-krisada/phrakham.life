    ผิด, นับไฟล์ = [], 0
    ทั้งหมด = sorted(set(ที่.rglob("*.json")) | set(ที่.rglob("*.json.gz")),
                    key=lambda x: x.as_posix())
    for ไฟล์ in ทั้งหมด:
        นับไฟล์ += 1
        ตัวหนังสือ = อ่านตัวหนังสือ(ไฟล์)
