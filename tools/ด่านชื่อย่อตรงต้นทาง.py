def ทดสอบตัวเอง() -> int:
    """ยัดของพังใส่สำเนาของไฟล์จริง ⇒ ทุกชิ้นต้องแดง ⇒ ⛔ ไม่ต้องมี zip"""
    จริง = json.loads(ไฟล์ชื่อย่อ.read_text(encoding="utf-8"))
    ต้องเป็น = จริง["ชื่อย่อ"]  # ⭐ ด่านจริงพิสูจน์แล้วว่าไฟล์ = ต้นทาง ⇒ ใช้แทนต้นทางได้
    if เทียบ(ต้องเป็น, จริง):
        print("⛔ ไฟล์จริงเทียบกับตัวเองยังแดง ⇒ ด่านพัง")
        return 1

    def พัง(แก้):
        x = copy.deepcopy(จริง)
        แก้(x)
        return x

    ของพัง = {
        "คิดชื่อย่อเอง": (lambda x: x["ชื่อย่อ"]["TCV"].__setitem__("MRK", "มร."), "①"),
        "ย่อชื่ออังกฤษแบบ SBL": (lambda x: x["ชื่อย่อ"]["WEB"].__setitem__("MRK", "Mark"), "①"),
        "ตัดจุดท้ายทิ้ง": (lambda x: x["ชื่อย่อ"]["TCV"].__setitem__("ACT", "กจ"), "①"),
        "เติมช่องว่าง": (lambda x: x["ชื่อย่อ"]["LSV"].__setitem__("1CH", "1 Ch"), "①"),
        "เล่มหาย": (lambda x: x["ชื่อย่อ"]["LSV"].pop("REV"), "①"),
        "ใช้ชื่อเต็มของ THKJV": (lambda x: x["ชื่อย่อ"]["THKJV"].__setitem__("GEN", "หนังสือปฐมกาล"), "②"),
        "เลิกบอกว่ายืม": (lambda x: x.__setitem__("ยืม", {}), "②"),
        "ย่อ KJV เอง": (lambda x: x["ชื่อย่อ"]["KJV"].__setitem__("MRK", "Mk"), "①"),
        # ⭐ ใบ #169 ⇒ KJV กลายเป็นฉบับที่รู้ที่มาแล้ว ⇒ ฉบับปลอมเปลี่ยนเป็นชื่อที่ไม่มีในเว็บ ⇒ ท่าเดิม ข้อเดิม
        "ฉบับที่ไม่รู้ที่มา": (lambda x: x["ชื่อย่อ"].__setitem__("NKJV", {"MRK": "Mk"}), "③"),
    }
    พลาด = 0
    for ชื่อ, (แก้, ข้อ) in ของพัง.items():
        ผล = [x for x in เทียบ(ต้องเป็น, พัง(แก้)) if x.startswith(ข้อ)]
        print(f"{'✅' if ผล else '⛔'} ยัด *{ชื่อ}* ⇒ ข้อ {ข้อ} {'แดง ⇒ ' + ผล[0] if ผล else '⛔ ไม่แดง'}")
        พลาด += not ผล
    if พลาด:
        print("\n⛔ โหมดพิสูจน์: ยัดของพังแล้วด่านไม่เห็นบางชิ้น ⇒ ด่านตายบางส่วน")
        return 1
    print(f"\n✅ โหมดพิสูจน์: ด่านชื่อย่อตรงต้นทางจับของพังได้ครบ {len(ของพัง)} ชิ้น")
    return 0


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--เขียน", action="store_true")
    p.add_argument("--ทดสอบตัวเอง", action="store_true")
    a = p.parse_args()
    if a.ทดสอบตัวเอง:
        return ทดสอบตัวเอง()
    for ฉ, (z, _, _) in ต้นทาง.items():
        if (กองต้นทาง / z).stat().st_size < 1000:
            print(f"⛔ source/{z} เป็นตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง ⇒ สั่ง git -c lfs.fetchexclude= lfs pull -I \"source/{z}\" ก่อน")
            return 1
    ตาราง, ตก = ตารางจากต้นทาง(เล่มทั้งหมด())
    if a.เขียน:
        if ตก:
            print("⛔ ต้นทางไม่ตรงกับสมมติฐาน ⇒ ไม่เขียน\n  - " + "\n  - ".join(ตก))
            return 1
        ไฟล์ชื่อย่อ.write_text(json.dumps(ไฟล์ใหม่(ตาราง), ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"✅ เขียน {ไฟล์ชื่อย่อ.relative_to(ที่เก็บ)} ⇒ {len(ตาราง)} ฉบับ × {len(ตาราง['TCV'])} เล่ม")
        return 0
    ไฟล์ = json.loads(ไฟล์ชื่อย่อ.read_text(encoding="utf-8"))
    ตก += เทียบ(ตาราง, ไฟล์)
    if ตก:
        print(f"⛔ ชื่อย่อเล่มไม่ตรงต้นทาง — {len(ตก)} รายการ:")
        for x in ตก[:50]:
            print("  - " + x)
        return 1
    print(f"✅ ชื่อย่อเล่ม {len(ตาราง)} ฉบับ × {len(ตาราง['TCV'])} เล่ม ตรงกับ toc3 ของต้นทางทุกตัวอักษร · THKJV ยืมของ TCV เพราะ toc3 ของตัวเอง ⛔ ไม่มีชื่อย่อสักเล่ม")
    for ฉ in ตาราง:
        print(f"  {ฉ} ⇒ MRK “{ตาราง[ฉ]['MRK']}” · ACT “{ตาราง[ฉ]['ACT']}” · 1CH “{ตาราง[ฉ]['1CH']}”")
    return 0


if __name__ == "__main__":
    sys.exit(main())
