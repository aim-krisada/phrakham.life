import { chromium } from 'playwright'
import { เส้นทางเว็บ, เพิ่มฉบับจนครบ, ปุ่มAaของหน้า, ปุ่มขนาดตัวอักษร, พับแผงAa } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')
const ที่ตก = []

// ยอห์น 5 คือบทที่พี่เอมเปิดอยู่ตอนเจอของพัง ⇒ ใช้บทเดียวกัน
const บทที่ใช้ = 'JHN/5'

/** กฎหน้าตาแบบเดิมที่พัง ⇒ ใช้เฉพาะโหมดพิสูจน์ว่าด่านยังจับได้ ⛔ ไม่ใช่ของที่อยู่ในเว็บจริง */
const กฎที่พัง = `
.pk-ข้อ > .pk-ช่องทั้งหมด, .pk-หัวคอลัมน์ > .pk-ช่องทั้งหมด { grid-column: auto; }
.pk-ซ่อนเลข .pk-ข้อ, .pk-หัวคอลัมน์.pk-ซ่อนเลข {
  grid-template-columns: 2.4em minmax(0, 1fr); gap: 0 0.5rem;
}`

const เบราว์เซอร์ = await chromium.launch()

/** เปิดหน้าแล้ว **รอจนโค้ดของเว็บติดจริง** ⇒ ท่าเดียวกับ `ด่านไปถึงข้อ.mjs` ⛔ ไม่รอแบบเดา */
async function เปิด(แท็บ, ทาง) {
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, {
    timeout: 30000,
  })
  await แท็บ.waitForTimeout(300)
}

/** ติ๊กเลือกฉบับให้ครบตามจำนวนที่ขอ ⇒ เลือกทั้งหมดก่อน แล้วค่อยเอาออกทีละตัว */
async function ตั้งจำนวนฉบับ(แท็บ, กี่ฉบับ) {
  // ⭐ ทางเดียวกับผู้อ่าน ⇒ เมนู *เทียบ* (ใบงาน #102 · ชื่อจากใบ #113) ⇒ เจ้าของท่าคือ `tools/หน้าที่ตรวจ.mjs`
  return เพิ่มฉบับจนครบ(แท็บ, กี่ฉบับ)
}

async function ตั้งการแสดงเลข(แท็บ, ติ๊กไว้) {
  // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131#note_30332 ข้อ 2 ⇒ เมนู *ปรับหน้าจอ* รวมเข้าแผง Aa ⇒ เปลี่ยนแค่ทางกด ⇒ เกณฑ์คงเดิม
  await ปุ่มAaของหน้า(แท็บ).click()
  await แท็บ.waitForSelector('.pk-เมนู')
  const ช่อง = แท็บ.getByRole('checkbox', { name: 'แสดงเลขบท/ข้อ' })
  if (ติ๊กไว้) await ช่อง.check()
  else await ช่อง.uncheck()
  await ปุ่มAaของหน้า(แท็บ).click()
  await แท็บ.waitForTimeout(250)
}

/** ⭐ วัด **ของที่วาดออกมาจริง** ⛔ ไม่ได้ดูว่าโค้ดมีคลาสอะไร */
const วัด = (แท็บ) =>
  แท็บ.evaluate(() => {
    const ช่อง = [...document.querySelectorAll('.pk-ตัวบท .pk-ข้อ .pk-ช่องฉบับ')].filter(
      (el) => el.getClientRects().length,
    )
    const ตัวบท = document.querySelector('.pk-ตัวบท')
    return {
      จำนวนช่อง: ช่อง.length,
      กว้างน้อยสุด: ช่อง.length ? Math.min(...ช่อง.map((el) => el.getBoundingClientRect().width)) : 0,
      สูงตัวบท: ตัวบท ? ตัวบท.getBoundingClientRect().height : 0,
      ตัวอักษร: ตัวบท ? parseFloat(getComputedStyle(ตัวบท).fontSize) : 0,
    }
  })

/** กดปุ่มขนาดตัวอักษรจนสุดข้างหนึ่ง ⇒ **กดจนปุ่มถูกปิด** ⛔ ไม่นับจำนวนครั้งเอาเอง */
async function ดันขนาดจนสุด(แท็บ, ทาง) {
  // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131#note_30332 ข้อ 2 ⇒ ก− ก+ ย้ายเข้าแผง Aa ⇒ เปลี่ยนแค่ทางกด
  //   ⇒ กาง Aa ก่อน ⇒ กดเสร็จพับคืน ⇒ หน้าอยู่สภาพเดียวกับของเดิมที่ ก− ก+ วางบนแถบ ⇒ เกณฑ์คงเดิม
  const ปุ่ม = await ปุ่มขนาดตัวอักษร(แท็บ, ทาง === 'ใหญ่' ? '+' : '-')
  for (let i = 0; i < 12; i++) {
    if (await ปุ่ม.isDisabled()) break
    await ปุ่ม.click()
    await แท็บ.waitForTimeout(120)
  }
  await พับแผงAa(แท็บ)
  await แท็บ.waitForTimeout(200)
}

/**
 * ตรวจ 1 สภาพ ⇒ เปิดหน้าใหม่ทุกครั้ง ⇒ ⛔ ค่าที่เว็บจำไว้จากรอบก่อนไม่ปนเข้ามา
 * `ยัดกฎที่พัง` เป็นจริงเฉพาะโหมดพิสูจน์ว่าด่านยังจับได้
 */
async function ตรวจสภาพ({ กว้างจอ, กี่ฉบับ, ขนาด }, ยัดกฎที่พัง) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้างจอ, height: 900 } })
  const แท็บ = await ctx.newPage()
  const ป้าย = `จอ ${กว้างจอ} · ${กี่ฉบับ} ฉบับ · ตัวอักษร${ขนาด === 'ปกติ' ? 'ปกติ' : `${ขนาด}สุด`}`
  const ตก = []
  try {
    await เปิด(แท็บ, `/read/${บทที่ใช้}`)
    if (ยัดกฎที่พัง) await แท็บ.addStyleTag({ content: กฎที่พัง })
    const จริง = await ตั้งจำนวนฉบับ(แท็บ, กี่ฉบับ)
    if (ขนาด !== 'ปกติ') await ดันขนาดจนสุด(แท็บ, ขนาด)

    await ตั้งการแสดงเลข(แท็บ, true)
    const ก่อน = await วัด(แท็บ)
    await ตั้งการแสดงเลข(แท็บ, false)
    const หลัง = await วัด(แท็บ)

    if (!ก่อน.จำนวนช่อง || !หลัง.จำนวนช่อง) {
      ตก.push(`${ป้าย} ⇒ หาช่องตัวบทบนหน้าไม่เจอ (${ก่อน.จำนวนช่อง} ⇒ ${หลัง.จำนวนช่อง})`)
      return ตก
    }
    // ① เลขหายไปแล้ว ช่องเนื้อ **ห้ามแคบลง** ⇒ เผื่อ 4 จุดให้การปัดเศษของเบราว์เซอร์
    if (หลัง.กว้างน้อยสุด < ก่อน.กว้างน้อยสุด - 4) {
      ตก.push(
        `${ป้าย} ⇒ ปิดเลขแล้วช่องเนื้อแคบลงจาก ${Math.round(ก่อน.กว้างน้อยสุด)} เหลือ ` +
          `${Math.round(หลัง.กว้างน้อยสุด)} จุด (เห็น ${จริง} ฉบับ)`,
      )
    }
    // ② ก้อนตัวบท **ห้ามสูงขึ้นเกิน 1.2 เท่า** ⇒ บรรทัดละตัวอักษรทำให้สูงขึ้นหลายเท่าเสมอ
    if (หลัง.สูงตัวบท > ก่อน.สูงตัวบท * 1.2) {
      ตก.push(
        `${ป้าย} ⇒ ปิดเลขแล้วตัวบทสูงขึ้นจาก ${Math.round(ก่อน.สูงตัวบท)} เป็น ` +
          `${Math.round(หลัง.สูงตัวบท)} จุด ⇒ ตัวหนังสือถูกบีบจนขึ้นบรรทัดใหม่ทุกตัว`,
      )
    }
  } finally {
    await ctx.close()
  }
  return ตก
}

// ⭐ ครบทุกมุมที่เกณฑ์ผ่านข้อ 1 ของใบงานสั่งไว้ ⇒ ⛔ ไม่ได้เลือกมาเอง
// ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131 คำขอรวมที่ 2 ⇒ จอแคบกว่า 768 มีเพดานคอลัมน์ ⇒ note_30332 นับเพดานจากที่ว่าง ⇒ จอ 320 · 375 · 412 ยังได้ 2
//   ⇒ ของเดิม จอ 412 · 4 ฉบับ ⇒ เมนูล็อกที่ฉบับที่ 2 ⇒ ด่านได้ 2 ฉบับเงียบ ๆ ทั้งที่ป้ายบอก 4
//   ⇒ สภาพ 4 ฉบับย้ายไปวัดที่จอ 768 ⇒ จอ 412 วัดด้วย 2 ฉบับ ⇒ เกณฑ์ ① ② คงเดิม (แผน #note_30303 ข้อ 10.2.4)
const สภาพทั้งหมด = []
for (const [กว้างจอ, จำนวน] of [
  [412, [1, 2]],
  [768, [4]],
  [1280, [1, 4]],
]) {
  for (const กี่ฉบับ of จำนวน) {
    for (const ขนาด of ['เล็ก', 'ปกติ', 'ใหญ่']) สภาพทั้งหมด.push({ กว้างจอ, กี่ฉบับ, ขนาด })
  }
}

for (const ส of สภาพทั้งหมด) ที่ตก.push(...(await ตรวจสภาพ(ส, false)))

// ---------------------------------------------------------------- พิสูจน์ว่าด่านยังจับได้
if (ทดสอบตัวเอง) {
  const จับได้ = await ตรวจสภาพ({ กว้างจอ: 1280, กี่ฉบับ: 4, ขนาด: 'ปกติ' }, true)
  await เบราว์เซอร์.close()
  if (!จับได้.length) {
    console.error('⛔ โหมดพิสูจน์: ยัดกฎเดิมที่พังกลับเข้าไปแล้ว **ด่านยังเขียว** ⇒ ด่านตายแล้ว')
    process.exit(1)
  }
  if (ที่ตก.length) {
    console.error('⛔ โหมดพิสูจน์: ของจริงบนเว็บก็ไม่ผ่านด้วย ⇒ ไปแก้เว็บก่อน')
    for (const x of ที่ตก) console.error('  - ' + x)
    process.exit(1)
  }
  console.log(`✅ โหมดพิสูจน์: ด่านยังจับของพังได้ ⇒ ${จับได้[0]}`)
  process.exit(0)
}

await เบราว์เซอร์.close()

if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
console.log(`✅ ปิดเลขบท/ข้อแล้วหน้ายังอ่านได้ ⇒ ตรวจครบ ${สภาพทั้งหมด.length} สภาพ`)
