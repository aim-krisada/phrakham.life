def เทสแถวที่อ่านจากภาพ(เอกสาร):
    """ตรวจว่าที่คนจดจากภาพ ตรงกับสายอักษรดิบที่ PDF คืนมาไหม

    ก้อนดิบของแถวที่ช่องชนกัน คือคำทุกช่องต่อกันอยู่แล้ว (เช่นแถว 274 ได้
    "อินเทอร์เน็ต (เน็ต)" สามครั้งติดกัน) ⇒ เอาที่จดไว้มาต่อกันแล้วเทียบได้เลย
    ⇒ ถ้าใครแก้ตาราง อ่านจากภาพ ให้ผิดจากหน้ากระดาษ เทสนี้จะจับได้ทันที
    """
    เจอ, ตก = {}, []
    for i in range(ตารางในไฟล์[1][1] - 1, ตารางในไฟล์[1][2]):
        for _, ช่อง in จัดแถว(อ่านบรรทัด(เอกสาร[i], Counter())):
            if not (ช่อง and เป็นเลขล้วน.match(ช่อง[0][1]) and len(ช่อง) > 1):
                continue
            ลำดับ = แปลงเลขไทย(ช่อง[0][1])
            if ลำดับ in อ่านจากภาพ:
                เจอ[ลำดับ] = "".join(t for _, t in ช่อง[1:]).replace(" ", "")

    for ลำดับ, ช่อง in sorted(อ่านจากภาพ.items()):
        ดิบ = เจอ.get(ลำดับ)
        จด = "".join(ช่อง).replace(" ", "")
        ยอมหาย = อักษรที่ไฟล์ทำหาย.get(ลำดับ, 0)
        if ดิบ is None:
            ตก.append(f"ลำดับ {ลำดับ} หาแถวในไฟล์ PDF ไม่เจอ")
        elif ดิบ == จด:
            print(f"  ผ่าน ลำดับ {ลำดับ:5} ตรงเป๊ะ {len(จด)} ตัวอักษร")
        elif len(จด) - len(ดิบ) == ยอมหาย and เป็นลำดับย่อยของ(ดิบ, จด):
            print(f"  ผ่าน ลำดับ {ลำดับ:5} ตรง ยกเว้นตัวที่ไฟล์วาดทับหาย {ยอมหาย} ตัว")
        else:
            ตก.append(f"ลำดับ {ลำดับ} ไม่ตรง\n     ดิบ {ดิบ!r}\n     จด {จด!r}")

    for ข้อความ in ตก:
        print("  ⛔ ตก", ข้อความ)
    print(f"\n{len(อ่านจากภาพ) - len(ตก)}/{len(อ่านจากภาพ)} แถวผ่าน")
    return 1 if ตก else 0


def เป็นลำดับย่อยของ(สั้น, ยาว):
    it = iter(ยาว)
    return all(c in it for c in สั้น)


def สำรวจ(เอกสาร):
    หลัง = Counter()
    for หน้า in เอกสาร:
        for b in หน้า.get_text("rawdict")["blocks"]:
            for l in b.get("lines", []):
                ตัว = [c for s in l["spans"] for c in s["chars"]]
                for i, c in enumerate(ตัว):
                    if c["c"] == " " and c["bbox"][2] - c["bbox"][0] < 0.01:
                        หลัง["".join(x["c"] for x in ตัว[i + 1 : i + 3])] += 1
    for k, v in หลัง.most_common():
        ชื่อ = " ".join(unicodedata.name(c, "?") for c in k)
        print(f"  ช่องว่างกว้างศูนย์ + {k!r} ({ชื่อ}) × {v}")


