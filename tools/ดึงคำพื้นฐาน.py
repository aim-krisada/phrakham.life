def แปลงเลขไทย(s):
    s = re.sub(r"[^๐-๙]", "", s)
    return int("".join(str(เลขไทย.index(c)) for c in s))


def อ่านบรรทัด(หน้า, นับ):
    """คืน (bbox, ข้อความ) ของทุกบรรทัดในหน้า พร้อมซ่อม ำ ที่หลุด"""
    ผล = []
    for b in หน้า.get_text("rawdict")["blocks"]:
        for l in b.get("lines", []):
            ตัว = [c for s in l["spans"] for c in s["chars"]]
            อักษร, i = [], 0
            while i < len(ตัว):
                c = ตัว[i]
                if c["c"] == " " and c["bbox"][2] - c["bbox"][0] < 0.01:
                    j, แทรก = i + 1, []
                    while j < len(ตัว) and ตัว[j]["c"] in วรรณยุกต์:
                        แทรก.append(ตัว[j]["c"])
                        j += 1
                    if j < len(ตัว) and ตัว[j]["c"] in (สระอา, สระอำ):
                        อักษร.extend(แทรก + [สระอำ])
                        นับ["ซ่อม-ำ" if ตัว[j]["c"] == สระอา else "ตัดช่องว่างหน้า-ำ"] += 1
                        i = j + 1
                        continue
                    นับ["ช่องว่างกว้างศูนย์ที่ซ่อมไม่ได้"] += 1
                    i += 1
                    continue
                อักษร.append(c["c"])
                i += 1
            ข้อความ = "".join(อักษร).strip()
            if ข้อความ:
                ผล.append((l["bbox"], ข้อความ))
    return ผล


def จัดแถว(บรรทัด, เผื่อ=6.0):
    """รวมบรรทัดที่อยู่ระดับเดียวกันเป็นแถวเดียว เรียงซ้ายไปขวา"""
    แถว = defaultdict(list)
    for bbox, ข้อความ in sorted(บรรทัด, key=lambda t: t[0][1]):
        กลาง = (bbox[1] + bbox[3]) / 2
        คีย์ = next((k for k in แถว if abs(k - กลาง) < เผื่อ), กลาง)
        แถว[คีย์].append((bbox, ข้อความ))
    return [(k, sorted(แถว[k], key=lambda t: t[0][0])) for k in sorted(แถว)]


def หัวตาราง(แถวทั้งหมด, จำนวนช่อง):
    """คืนจุดกึ่งกลางแนวนอนของแต่ละช่อง อ่านจากแถวหัวตารางของหน้านั้นเอง"""
    for _, ช่อง in แถวทั้งหมด:
        if len(ช่อง) == จำนวนช่อง and ช่อง[0][1].startswith("ลำดับ"):
            return [(b[0] + b[2]) / 2 for b, _ in ช่อง]
    return None


def ดึงสองช่อง(เอกสาร, หน้าแรก, หน้าท้าย, นับ):
    """ตาราง ลำดับ | คำ ที่วางเรียงกันหลายชุดต่อหน้า

    ถ้าคำยาวเกินช่อง โปรแกรมอ่าน PDF จะรวมช่องข้าง ๆ มาเป็นก้อนเดียว
    ⇒ ตัดก้อนนั้นตรงหน้าเลขลำดับที่มีจุดปิดท้าย แล้วจับคู่ เลข → คำ ใหม่
    """
    ออก = {}
    for i in range(หน้าแรก, หน้าท้าย + 1):
        for _, ช่อง in จัดแถว(อ่านบรรทัด(เอกสาร[i], นับ)):
            ชิ้น = []
            for _, ข้อความ in ช่อง:
                ท่อน = [t.strip() for t in แยกเลขในช่อง.split(ข้อความ) if t.strip()]
                if len(ท่อน) > 1:
                    นับ["ช่องที่ถูกรวมแล้วตัดคืน"] += 1
                ชิ้น.extend(ท่อน)
            j = 0
            while j < len(ชิ้น) - 1:
                if เป็นเลขล้วน.match(ชิ้น[j]) and not เป็นเลขล้วน.match(ชิ้น[j + 1]):
                    ออก[แปลงเลขไทย(ชิ้น[j])] = ชิ้น[j + 1]
                    j += 2
                else:
                    j += 1
    return ออก


def ดึงสี่ช่อง(เอกสาร, หน้าแรก, หน้าท้าย, นับ):
    """ตาราง ลำดับ | ป.1 | ป.2 | ป.3 — แบ่งช่องด้วยตำแหน่งหัวตาราง

    ตั้งแต่ลำดับราว 1,026 ช่อง ป.1 ว่าง (คำของ ป.1 หมดก่อน)
    ⇒ นับช่องเอาไม่ได้ ต้องดูว่าก้อนข้อความอยู่ตรงกับหัวช่องไหน
    คืนค่า (ตาราง, รายการแถวที่ก้อนข้อความคร่อมหลายช่อง ⇒ ตัดเองไม่ได้)
    """
    ออก, คร่อม = {}, []
    for i in range(หน้าแรก, หน้าท้าย + 1):
        แถวทั้งหมด = จัดแถว(อ่านบรรทัด(เอกสาร[i], นับ))
        กลางช่อง = หัวตาราง(แถวทั้งหมด, 4)
        if not กลางช่อง:
            นับ[f"หาหัวตารางไม่เจอ-หน้า{i + 1}"] += 1
            continue
        ระยะช่อง = min(b - a for a, b in zip(กลางช่อง, กลางช่อง[1:]))
        for y, ช่อง in แถวทั้งหมด:
            if not (ช่อง and เป็นเลขล้วน.match(ช่อง[0][1]) and len(ช่อง) > 1):
                continue
            แถว = ["", "", "", ""]
            มีปัญหา = False
            for b, ข้อความ in ช่อง:
                กลาง = (b[0] + b[2]) / 2
                ช่องที่ = min(range(4), key=lambda k: abs(กลางช่อง[k] - กลาง))
                if b[2] - b[0] > ระยะช่อง * 1.15:
                    มีปัญหา = True
                แถว[ช่องที่] = (แถว[ช่องที่] + " " + ข้อความ).strip()
            ลำดับ = แปลงเลขไทย(แถว[0])
            if มีปัญหา:
                คร่อม.append((ลำดับ, i, y, ช่อง[0][0], ช่อง[-1][0]))
                นับ["แถวที่ตัดช่องเองไม่ได้"] += 1
                ออก[ลำดับ] = อ่านจากภาพ[ลำดับ]
                continue
            ออก[ลำดับ] = แถว[1:]
    return ออก, คร่อม


