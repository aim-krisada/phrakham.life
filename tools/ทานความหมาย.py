def แกะ(ทาง):
    return json.loads(gzip.decompress(ทาง.read_bytes()).decode("utf-8"))


def โหลดคลังจริง():
    """ประกอบก้อนความหมายขึ้นใหม่จากไฟล์พจนานุกรมในกอง ⇒ ของจริงที่เอาไว้เทียบ

    คืน (คลังของแต่ละชั้น, รหัสประจำคำศัพท์ของแต่ละคำ)
    ⭐ **ต้องคืนรหัสประจำคำศัพท์ออกมาด้วย** ⇒ กฎเทียบข้อหนึ่งใช้รหัสนี้ยืนยัน
    ⇒ ⛔ ไม่ส่งไป กฎข้อนั้นยิงไม่ออก ⇒ คำที่ต่อถูกจะถูกรายงานว่าตก **แดงมั่ว**
    """
    คลังทุกชั้น, strongทุกชั้น = {}, {}
    for ฝั่ง, พจน in (("ฮีบรู", ตัวห่อ.ฮ_พจน), ("กรีก", ตัวห่อ.ก_พจน)):
        if not พจน.exists():
            print(f"⛔ ไม่มีไฟล์พจนานุกรมที่ {พจน}\n   ⇒ สั่ง py -3.14 tools/แตกกอง.py ก่อน")
            sys.exit(2)
        _, คลัง, sคำ = ตัวต่อ.โหลดพจน(str(พจน), ฝั่ง == "กรีก")
        ชื่อชั้น = ตัวห่อ.ชั้นของฝั่ง[ฝั่ง]
        คลังทุกชั้น[ชื่อชั้น] = คลัง
        strongทุกชั้น[ชื่อชั้น] = sคำ
    return คลังทุกชั้น, strongทุกชั้น


def โหลดต้นฉบับ():
    """คืน {(เล่ม, บท): {ข้อ: [แถวต้นฉบับ, ...]}} ของทั้งสองฝั่ง ⇒ ใช้ดูตัวอักษรจริงในข้อ"""
    ออก = {}
    for ต้นฉบับ in (ตัวห่อ.ฮ_ต้นฉบับ, ตัวห่อ.ก_ต้นฉบับ):
        for (เล่ม, บท), แถว in ตัวต่อ.ทีละบท(str(ต้นฉบับ)):
            ในข้อ = collections.defaultdict(list)
            for r in แถว:
                ในข้อ[str(ตัวต่อ.ข้อของ(r["ref"]))].append(r)
            ออก[(เล่ม, บท)] = ในข้อ
    return ออก


def ชี้ถูกคำไหม(ชื่อชั้น, lem, แถวคำ, เพื่อนแถว, sคำ):
    """คืนชื่อกฎที่ทำให้ตัดสินว่าชี้ถูกคำ ⇒ คืน None แปลว่าไม่เข้ากฎข้อไหนเลย

    ⛔ ไม่เขียนกฎเทียบใหม่ ⇒ เรียกกฎชุดเดียวกับที่ตัวต่อใช้ตอนสร้างของ
    """
    if ชื่อชั้น == "ความหมายฮีบรู":
        ตามชิ้น = {x["xml:id"]: x for x in เพื่อนแถว}
        หัวคำ, ตัวหนังสือ, สตรอง, _ = ตัวต่อ.หน่วยของ(แถวคำ, ตามชิ้น, ตัวต่อ.หน่วยจับคู่ฮีบรู())
        return ตัวต่อ.กฎฮีบรู(lem, หัวคำ, ตัวหนังสือ, สตรอง, sคำ)
    return ตัวต่อ.กฎกรีก(lem, ตัวต่อ.N(แถวคำ["lemma"]), ตัวต่อ.N(แถวคำ["text"]),
                        ตัวต่อ.เลข(แถวคำ["strong"]), sคำ)


def เก็บคำที่ต่อติด():
    """ไล่ `_data/` ทั้งกอง ⇒ คืนรายการ (เล่ม, บท, ข้อ, ลำดับคำ, ชื่อชั้น, รหัสความหมาย)"""
    ออก = []
    บัญชี = json.loads((ความหมาย / "บัญชี.json").read_text(encoding="utf-8"))
    for เล่ม in บัญชี["เล่ม"]:
        for บท in เล่ม["บทที่มี"]:
            d = แกะ(ความหมาย / เล่ม["รหัส"] / f"{บท}.json.gz")
            for ชื่อชั้น, ในข้อ in d["ชั้น"].items():
                for ข้อ, รายการ in ในข้อ.items():
                    for i, รหัส in enumerate(รายการ):
                        if รหัส:
                            ออก.append((เล่ม["รหัส"], บท, ข้อ, i, ชื่อชั้น, รหัส))
    return ออก


def หาคำบังคับ(ทั้งหมด, คลังจริง):
    """หาแถวของคำบังคับในกองจริง ⇒ ⛔ ไม่มีสักแถว = ตก ⛔ ไม่ใช่ข้ามเงียบ ๆ"""
    ได้, ขาด = [], []
    for เล่ม, บท, ข้อ, ตัวอักษร, ต้องแปลว่า in คำบังคับ:
        เจอ = None
        for แถว in ทั้งหมด:
            if (แถว[0], แถว[1], แถว[2]) != (เล่ม, บท, str(ข้อ)):
                continue
            ก = คลังจริง[แถว[4]].get(แถว[5])
            if ก and ต้องแปลว่า in (ก.get("คำแปลสั้น") or []):
                เจอ = แถว
                break
        if เจอ:
            ได้.append((เจอ, f"คำบังคับ ⇒ {ตัวอักษร} ต้องแปลว่า {ต้องแปลว่า}"))
        else:
            ขาด.append(f"{เล่ม} {บท}.{ข้อ} {ตัวอักษร} ⇒ หาความหมายที่แปลว่า {ต้องแปลว่า} ไม่เจอ")
    return ได้, ขาด


def main():
    ก = argparse.ArgumentParser()
    # ⛔ ชื่อช่องเป็น ASCII ⇒ ไพทอนแปลงชื่อตัวแปรภาษาไทยเป็นรูป NFKC ⇒ `args.กี่คำ` กลายเป็นคนละสาย
    #    (กับดักตัวเดียวกับที่ `tools/สดุดี-32-ต่อ-ubs.py` จดไว้เรื่องชื่อช่องใน dict)
    ก.add_argument("--กี่คำ", dest="how_many", type=int, default=20,
                   help="สุ่มกี่คำ (ไม่นับคำบังคับ)")
    args = ก.parse_args()

    if not (ความหมาย / "บัญชี.json").exists():
        print(f"⛔ ยังไม่มี {ความหมาย} ⇒ สั่ง py -3.14 tools/สร้างชั้นความหมาย.py ก่อน")
        return 2

    print("=== อ่านพจนานุกรมจริงในกอง กับต้นฉบับ")
    คลังจริง, strongของคำ = โหลดคลังจริง()
    ต้นฉบับ = โหลดต้นฉบับ()
    คลังในซอง = {ช: แกะ(ความหมาย / f"คลัง-{ฝ}.json.gz")["ความหมาย"]
                for ฝ, ช in ตัวห่อ.ชั้นของฝั่ง.items()}

    ทั้งหมด = เก็บคำที่ต่อติด()
    print(f"   คำที่ต่อความหมายติดในกองที่จะขึ้นเว็บ {len(ทั้งหมด):,} คำ")

    บังคับ, ขาด = หาคำบังคับ(ทั้งหมด, คลังจริง)
    # ⭐ สุ่มให้กระจายหลายเล่ม ⇒ สุ่มเล่มก่อน แล้วค่อยสุ่มคำในเล่มนั้น
    สุ่ม = random.Random(เมล็ด)
    ตามเล่ม = collections.defaultdict(list)
    for แถว in ทั้งหมด:
        ตามเล่ม[แถว[0]].append(แถว)
    เล่มที่สุ่ม = สุ่ม.sample(sorted(ตามเล่ม), min(args.how_many, len(ตามเล่ม)))
    ชุด = บังคับ + [(สุ่ม.choice(ตามเล่ม[b]), "สุ่ม") for b in เล่มที่สุ่ม]

    print(f"\n=== ทานทีละคำ {len(ชุด)} คำ ⇒ คำบังคับ {len(บังคับ)} · สุ่ม {len(ชุด) - len(บังคับ)}")
    print(f"{'ที่อยู่':16} {'ตัวอักษรในข้อ':14} {'คำในพจนานุกรม':14} {'คำแปล':22} ผล")
    print("-" * 118)
    ตก = list(ขาด)
    for (เล่ม, บท, ข้อ, ลำดับ, ชื่อชั้น, รหัส), ป้าย in ชุด:
        ในซอง = คลังในซอง[ชื่อชั้น].get(รหัส)
        ของจริง = คลังจริง[ชื่อชั้น].get(รหัส)
        ที่อยู่ = f"{เล่ม} {บท}.{ข้อ}#{ลำดับ + 1}"
        แถวคำ = ต้นฉบับ[(เล่ม, บท)][ข้อ][ลำดับ]
        เหตุ = []
        if ของจริง is None:
            เหตุ.append(f"รหัส {รหัส} ไม่มีในพจนานุกรมจริง")
        elif ในซอง != ของจริง:
            เหตุ.append("คำนิยามในซองไม่ตรงกับพจนานุกรมจริง")
        กฎ = None
        if ของจริง:
            กฎ = ชี้ถูกคำไหม(ชื่อชั้น, ของจริง["คำในพจนานุกรม"], แถวคำ,
                            ต้นฉบับ[(เล่ม, บท)][ข้อ], strongของคำ[ชื่อชั้น])
            if not กฎ:
                เหตุ.append("ตัวอักษรในข้อกับคำในพจนานุกรมไม่เข้ากฎข้อไหนเลย")
        ผล = "✅ " + (กฎ or "") if not เหตุ else "⛔ " + " · ".join(เหตุ)
        if เหตุ:
            ตก.append(f"{ที่อยู่} ⇒ {' · '.join(เหตุ)}")
        แปล = " · ".join((ของจริง or {}).get("คำแปลสั้น") or [])
        print(f"{ที่อยู่:16} {ตัวต่อ.N(แถวคำ['text']):14} "
              f"{(ของจริง or {}).get('คำในพจนานุกรม', ''):14} {แปล[:22]:22} {ผล}")
        print(f"{'':16} {ป้าย} ⇒ {(ของจริง or {}).get('นิยาม', '')[:90]}")

    print("-" * 118)
    if ตก:
        print(f"⛔ ทานไม่ผ่าน {len(ตก)} คำ ⇒ ⛔ ผิดคำเดียวถือว่าไม่ผ่าน")
        for x in ตก:
            print(f"   {x}")
        return 1
    print(f"✅ ทานครบ {len(ชุด)} คำ ⇒ คำนิยามตรงกับพจนานุกรมจริง และชี้ถูกคำทุกคำ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
