/** วัดแถบล่างของหน้าที่เปิดอยู่ ⇒ คืนรายการที่ผิด แยกตามข้อ */
async function วัด(แท็บ) {
  return แท็บ.evaluate(() => {
    const ผิด = []
    const แถบ = document.querySelector('.pk-แถบล่าง')
    if (!แถบ) return [['①', 'ไม่มีแถบล่าง']]
    const ก = แถบ.getBoundingClientRect()
    const cs = getComputedStyle(แถบ, '::before')
    const แคป = {
      l: ก.left + parseFloat(cs.left),
      r: ก.right - parseFloat(cs.right),
      t: ก.top + parseFloat(cs.top),
      b: ก.bottom - parseFloat(cs.bottom),
    }
    const มุม = Math.min(parseFloat(cs.borderTopLeftRadius) || 0, (แคป.r - แคป.l) / 2, (แคป.b - แคป.t) / 2)
    /** จุดนี้อยู่ในสี่เหลี่ยมมุมมนของแคปซูลไหม ⇒ ยอมคลาด 0.5 จุด */
    const ใน = (x, y) => {
      const e = 0.5
      if (x < แคป.l - e || x > แคป.r + e || y < แคป.t - e || y > แคป.b + e) return false
      const cx = Math.min(Math.max(x, แคป.l + มุม), แคป.r - มุม)
      const cy = Math.min(Math.max(y, แคป.t + มุม), แคป.b - มุม)
      return Math.hypot(x - cx, y - cy) <= มุม + e
    }
    const ปุ่ม = [...แถบ.querySelectorAll('button, a')].filter(
      (e) => e.getClientRects().length && !e.closest('.pk-ลอยเหนือแถบ') && getComputedStyle(e).visibility !== 'hidden',
    )
    if (!ปุ่ม.length) return [['①', 'แถบล่างไม่มีปุ่มให้ตรวจ']]
    const ชื่อ = (e) => e.getAttribute('data-ปุ่ม') || (e.textContent || '').trim().slice(0, 12)
    let ซ้ายสุด = Infinity
    let ขวาสุด = Infinity
    for (const e of ปุ่ม) {
      const q = e.getBoundingClientRect()
      const s = getComputedStyle(e)
      ซ้ายสุด = Math.min(ซ้ายสุด, q.left - แคป.l)
      ขวาสุด = Math.min(ขวาสุด, แคป.r - q.right)
      // ① ไล่จุดรอบขอบปุ่มตามมุมมนของปุ่มเอง ⇒ มุมละ 9 จุด
      const rr = Math.min(parseFloat(s.borderTopLeftRadius) || 0, q.width / 2, q.height / 2)
      const ศูนย์ = [
        [q.left + rr, q.top + rr, Math.PI, 1.5 * Math.PI],
        [q.right - rr, q.top + rr, 1.5 * Math.PI, 2 * Math.PI],
        [q.right - rr, q.bottom - rr, 0, 0.5 * Math.PI],
        [q.left + rr, q.bottom - rr, 0.5 * Math.PI, Math.PI],
      ]
      const นอก = []
      for (const [cx, cy, a0, a1] of ศูนย์)
        for (let i = 0; i <= 8; i++) {
          const a = a0 + ((a1 - a0) * i) / 8
          const x = cx + rr * Math.cos(a)
          const y = cy + rr * Math.sin(a)
          if (!ใน(x, y)) นอก.push(`(${(x - แคป.l).toFixed(1)},${(y - แคป.t).toFixed(1)})`)
        }
      if (นอก.length) ผิด.push(['①', `ปุ่ม ${ชื่อ(e)} โผล่พ้นแคปซูล ${นอก.length} จุด เช่น ${นอก[0]} จากมุมซ้ายบนของแคปซูล`])
      // ④ กล่องกด
      if (q.width < 44 - 0.5 || q.height < 44 - 0.5) ผิด.push(['④', `ปุ่ม ${ชื่อ(e)} ${q.width.toFixed(0)}×${q.height.toFixed(0)} ⇒ ต่ำกว่า 44 (SC 2.5.8)`])
    }
    // ② ห่างขอบสองข้างเท่ากัน
    if (Math.abs(ซ้ายสุด - ขวาสุด) > 1) ผิด.push(['②', `ห่างขอบซ้าย ${ซ้ายสุด.toFixed(1)} · ขวา ${ขวาสุด.toFixed(1)} จุด ⇒ ไม่เท่ากัน`])
    // ⭐ ชิด 0 จุดทั้งสองข้าง = เท่ากันแต่ไม่มีช่องเลย ⇒ ปุ่ม ▶ ฟัง ทรงแคปซูลเข้ามุมมนพอดีเป๊ะแต่ขอบกับเงาทับขอบแคปซูล (ของพังจริง 8 พ.ย. 2569)
    const ช่องน้อยสุด = 4
    if (Math.min(ซ้ายสุด, ขวาสุด) < ช่องน้อยสุด - 0.5)
      ผิด.push(['②', `ห่างขอบซ้าย ${ซ้ายสุด.toFixed(1)} · ขวา ${ขวาสุด.toFixed(1)} จุด ⇒ ต้องเว้นอย่างน้อย ${ช่องน้อยสุด} จุดทั้งสองข้าง`])
    // ③ แคปซูลไม่ถูกตัด ⇒ หากล่องบรรพบุรุษที่ตัดของล้นแนวนอน
    for (let p = แถบ.parentElement; p; p = p.parentElement) {
      const ox = getComputedStyle(p).overflowX
      if (ox === 'visible') continue
      const pr = p.getBoundingClientRect()
      const l = pr.left + p.clientLeft
      const r = l + p.clientWidth
      if (แคป.l < l - 0.5 || แคป.r > r + 0.5) ผิด.push(['③', `แคปซูล ${แคป.l.toFixed(1)}–${แคป.r.toFixed(1)} ล้นกล่องที่ตัดของล้น (${p.className || p.tagName}) ${l.toFixed(1)}–${r.toFixed(1)} ⇒ ขอบถูกตัด`])
      break
    }
    if (แคป.l < -0.5 || แคป.r > innerWidth + 0.5) ผิด.push(['③', `แคปซูล ${แคป.l.toFixed(1)}–${แคป.r.toFixed(1)} ล้นขอบจอ 0–${innerWidth}`])
    if (document.scrollingElement.scrollWidth > innerWidth) ผิด.push(['③', `หน้ากว้าง ${document.scrollingElement.scrollWidth} ⇒ ต้องเลื่อนซ้ายขวา (SC 1.4.10)`])
    // ⑤ ชื่อเล่มถูกหดทั้งที่ยังขึ้นสองแถวได้
    const เรื่อง = แถบ.querySelector('[data-ปุ่ม="เรื่องเล่า"]')
    const หด = [...แถบ.querySelectorAll('.pk-ป้ายเล่ม')].some((e) => e.getClientRects().length && e.scrollWidth > e.clientWidth + 0.5)
    // ⭐ ตัดสินจากที่วางจริง ⛔ ไม่เชื่อชื่อคลาสหรือชื่อแบบ ⇒ ทางเดินบทยังแบ่งแถวกับปุ่มอื่น = ยังมีทางยกให้ทั้งแถว
    const นำทาง = แถบ.querySelector('.pk-นำทางล่าง')
    const n = นำทาง?.getBoundingClientRect()
    const แบ่งแถว =
      n && ปุ่ม.some((e) => {
        if (นำทาง.contains(e)) return false
        const q = e.getBoundingClientRect()
        return q.top < n.bottom - 1 && n.top < q.bottom - 1
      })
    if (เรื่อง && หด && แบ่งแถว)
      ผิด.push(['⑤', `ชื่อเล่มบนปุ่มกลางถูกหด ทั้งที่ทางเดินบทยังแบ่งแถวกับปุ่มอื่น (แบบ ${เรื่อง.getAttribute('data-แบบ')}) ⇒ ยังยกทางเดินบทขึ้นแถวของตัวเองให้ชื่อเต็มได้`])
    return ผิด
  })
}

/** เปิดหน้าแล้ววัดทุกจอที่ขอ ⇒ คืนรายการ [ข้อ, ข้อความ] พร้อมบอกจอ */
async function ตรวจ(ทาง, จอ, กฎพัง) {
  const ผล = []
  const บริบท = await เบราว์เซอร์.newContext({ viewport: { width: จอ[0][0], height: 800 } })
  if (กฎพัง) {
    await บริบท.addInitScript((กฎ) => {
      window.addEventListener('DOMContentLoaded', () => {
        const st = document.createElement('style')
        st.textContent = กฎ
        document.head.appendChild(st)
      })
    }, กฎพัง)
  }
  const แท็บ = await บริบท.newPage()
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  await แท็บ.waitForSelector('#บท-10', { timeout: 15000 })
  await แท็บ.evaluate(() => document.fonts.ready)
  for (const [กว้าง, ขยาย] of จอ) {
    await แท็บ.setViewportSize({ width: กว้าง, height: 800 })
    await แท็บ.evaluate((ข) => (document.documentElement.style.fontSize = `${ข * 100}%`), ขยาย)
    // ⭐ รอให้หน้าเลือกแบบปุ่มเรื่องเล่าใหม่ (ResizeObserver + nextTick) ⇒ รอจนผลนิ่ง 2 รอบติด ⛔ ไม่นอนรอตายตัวอย่างเดียว
    let ก่อน = ''
    let ผิด = []
    for (let i = 0; i < 20; i++) {
      await แท็บ.waitForTimeout(150)
      ผิด = await วัด(แท็บ)
      const ตอนนี้ = JSON.stringify(ผิด) + (await แท็บ.evaluate(() => document.querySelector('[data-ปุ่ม="เรื่องเล่า"]')?.getAttribute('data-แบบ')))
      if (ตอนนี้ === ก่อน) break
      ก่อน = ตอนนี้
    }
    const ป้าย = `${ทาง} จอ ${กว้าง} ตัวอักษร ${ขยาย * 100}%`
    if (!ผิด.length) ผล.push(['✓', ป้าย])
    for (const [ข้อ, เรื่อง] of ผิด) ผล.push([ข้อ, `${ป้าย} ⇒ ${เรื่อง}`])
  }
  await บริบท.close()
  return ผล
}

let ล้ม = false
if (!ทดสอบตัวเอง) {
  const จอทั้งหมด = ทุกจอ.flatMap((ก) => [[ก, 1], [ก, 2]])
  for (const ทาง of หน้า) {
    for (const [ข้อ, เรื่อง] of await ตรวจ(ทาง, จอทั้งหมด)) {
      if (ข้อ === '✓') console.log(`✅ ${เรื่อง} ⇒ ทุกปุ่มอยู่ในแคปซูล ห่างขอบสองข้างเท่ากัน ⇒ กล่องกดไม่ต่ำกว่า 44`)
      else {
        ล้ม = true
        console.log(`⛔ ${ข้อ} ${เรื่อง}`)
      }
    }
  }
} else {
  // ⭐ ก่อนยัดของพัง ⇒ จอที่ใช้ต้องผ่านก่อน ⇒ ⛔ แดงเพราะเว็บพังอยู่แล้วแล้วนับว่าจับได้
  const จอพิสูจน์ = [...new Set(ของพัง.flatMap((x) => x.จอ.map((j) => j.join('|'))))].map((s) => s.split('|').map(Number))
  const ฐานผล = await ตรวจ(หน้า[0], จอพิสูจน์)
  const ฐานผิด = ฐานผล.filter(([ข้อ]) => ข้อ !== '✓')
  if (ฐานผิด.length) {
    ล้ม = true
    for (const [ข้อ, เรื่อง] of ฐานผิด) console.log(`⛔ ก่อนยัดของพัง เว็บก็แดงอยู่แล้ว ⇒ ${ข้อ} ${เรื่อง}`)
  }
  for (const พัง of ของพัง) {
    const ผล = await ตรวจ(หน้า[0], พัง.จอ, พัง.กฎ)
    const จับ = ผล.filter(([ข้อ]) => ข้อ === พัง.ข้อ)
    if (จับ.length) console.log(`✅ ยังจับได้ ${พัง.ข้อ} ${พัง.เรื่อง} ⇒ ${จับ[0][1]}`)
    else {
      ล้ม = true
      console.log(`⛔ ตาบอด ${พัง.ข้อ} ยัด "${พัง.เรื่อง}" แล้วข้อ ${พัง.ข้อ} ไม่แดง ⇒ ได้ ${JSON.stringify(ผล.map((x) => x[0]))}`)
    }
  }
}

