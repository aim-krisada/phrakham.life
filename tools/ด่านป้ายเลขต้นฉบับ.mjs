const เบราว์เซอร์ = await chromium.launch()

/** `ต้อง` = ป้ายต้องขึ้นไหม · `ข้าง` = บทเดิมที่หน้าหยิบมา (บทนั้นกับข้างละบท ที่มีอยู่จริง) ⇒ รอครบก่อนตัดสินว่า *ไม่ขึ้น* */
const ป้ายหน้า = (ส) => `${ส.เล่ม} ${ส.บท} จอ ${ส.กว้าง}`

async function ตรวจ(ส, พัง = null) {
  const ตก = []
  const ที่ = ป้ายหน้า(ส)
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: ส.กว้าง, height: ส.กว้าง < 768 ? 812 : 900 } })
  try {
    await ctx.addInitScript(() => {
      localStorage.setItem('phrakham.versions', JSON.stringify(['TCV']))
      localStorage.setItem('phrakham.view', JSON.stringify({ จัดวาง: 'แยกตามข้อ', แสดงเลข: true, ภาษาเดิม: true }))
    })
    if (พัง?.สคริปต์) await ctx.addInitScript({ content: พัง.สคริปต์ })
    const แท็บ = await ctx.newPage()
    await แท็บ.goto(`${ฐาน}/read/${ส.เล่ม}?c=${ส.บท}`, { waitUntil: 'domcontentloaded' })
    if (พัง?.css) await แท็บ.addStyleTag({ content: พัง.css })
    // ⭐ รอไฟล์ชั้นคำของบทนั้นกับข้างเคียงมาครบ ⇒ ป้ายตัดสินจากไฟล์ชุดนี้ ⇒ ⛔ ครบ ⇒ ยังตัดสิน ⛔ ได้ว่า *ไม่ขึ้น*
    const ครบ = await แท็บ
      .waitForFunction(
        ([เล่ม, ข้าง]) => {
          const มา = performance.getEntriesByType('resource').map((x) => decodeURIComponent(x.name))
          return (
            ข้าง.every((n) => มา.some((u) => u.includes(`/api/words/${เล่ม}/${n}.json`))) &&
            !!document.querySelector('[data-ชื่อคำเดิม] header, header[data-ชื่อคำเดิม]') &&
            document.querySelector('.pk-ตัวบท')?.getAttribute('data-จัดแถว') === 'เสร็จ'
          )
        },
        [ส.เล่ม, ส.ข้าง],
        { timeout: รอนานสุด },
      )
      .then(() => true)
      .catch(() => false)
    if (!ครบ) {
      ตก.push(`${ที่} ⇒ ไฟล์ชั้นคำบท ${ส.ข้าง.join(' · ')} หรือหัวคอลัมน์ภาษาเดิม ⛔ มาไม่ครบภายใน ${รอนานสุด / 1000} วินาที`)
      return ตก
    }
    await รอหน้านิ่ง(แท็บ)
    if (ส.ต้อง)
      await แท็บ
        .waitForFunction((x) => [...document.querySelectorAll(x)].some((p) => p.getClientRects().length), ป้าย, { timeout: 10000 })
        .catch(() => {})
    await แท็บ.evaluate(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))))
    const ผล = await แท็บ.evaluate((x) => {
      const เห็น = [...document.querySelectorAll(x)].filter((p) => p.getClientRects().length)
      const ในหัวเดิม = เห็น.filter((p) => p.closest('[data-ชื่อคำเดิม]'))
      const ข้อมูล = ในหัวเดิม.map((p) => {
        const r = p.getBoundingClientRect()
        const cs = getComputedStyle(p)
        const สูงบรรทัด = parseFloat(cs.lineHeight) || parseFloat(cs.fontSize) * 1.2
        const หัว = p.closest('header')
        const แถบ = หัว?.closest('.pk-หัวคอลัมน์, .pk-ชื่อคำเดิม')
        const สูง = () => [หัว?.getBoundingClientRect().height ?? 0, แถบ?.getBoundingClientRect().height ?? 0]
        // ⭐ หัวสูงเท่าไรถ้าไม่มีป้าย ⇒ ซ่อนป้ายชั่วคราวแล้ววัด ⇒ คืนค่าทันทีในงานเดียวกัน ⇒ เบราว์เซอร์ ⛔ ได้วาดขั้นที่ลอง
        const มี = สูง()
        const เดิม = p.style.getPropertyValue('display')
        p.style.setProperty('display', 'none', 'important')
        const ไม่มี = สูง()
        if (เดิม) p.style.setProperty('display', เดิม)
        else p.style.removeProperty('display')
        const ซ้อน = [...(หัว?.querySelectorAll('button, select') || [])]
          .filter((b) => b.getClientRects().length)
          .map((b) => b.getBoundingClientRect())
          .filter((b) => Math.min(r.right, b.right) - Math.max(r.left, b.left) > 0.5 && Math.min(r.bottom, b.bottom) - Math.max(r.top, b.top) > 0.5)
        return {
          คำ: p.textContent.trim(),
          ซ้าย: r.left,
          ขวา: r.right,
          จอ: innerWidth,
          ถูกตัด: p.scrollWidth - p.clientWidth,
          บรรทัด: r.height / สูงบรรทัด,
          สูงขึ้น: Math.max(มี[0] - ไม่มี[0], มี[1] - ไม่มี[1]),
          ทับ: ซ้อน.length,
        }
      })
      return { เห็น: เห็น.length, ในหัวเดิม: ในหัวเดิม.length, ข้อมูล }
    }, ป้าย)
    if (ผล.เห็น > ผล.ในหัวเดิม) ตก.push(`${ที่} ⇒ 🔴 ② ป้ายอยู่นอกหัวคอลัมน์ภาษาเดิม ${ผล.เห็น - ผล.ในหัวเดิม} ป้าย`)
    if (!ส.ต้อง) {
      if (ผล.ในหัวเดิม) ตก.push(`${ที่} ⇒ 🔴 ② บทนี้ข้อเดิมอยู่บทเดียวกับแถวทุกข้อ ⇒ ป้าย ⛔ ต้องขึ้น ⇒ แต่ขึ้น`)
      return ตก
    }
    if (ผล.ในหัวเดิม !== 1) {
      ตก.push(`${ที่} ⇒ 🔴 ① ป้ายในหัวคอลัมน์ภาษาเดิมต้องมี 1 ป้าย ⇒ เห็น ${ผล.ในหัวเดิม}`)
      return ตก
    }
    const ข = ผล.ข้อมูล[0]
    if (ข.คำ !== คำที่อนุมัติ) ตก.push(`${ที่} ⇒ 🔴 ① คำบนป้าย ⛔ ตรงกับที่อนุมัติ ⇒ เห็น "${ข.คำ}"`)
    if (ข.ซ้าย < -0.5 || ข.ขวา > ข.จอ + 0.5) ตก.push(`${ที่} ⇒ 🔴 ③ ป้ายล้นขอบจอ ⇒ ${Math.round(ข.ซ้าย)}–${Math.round(ข.ขวา)} ในจอ ${ข.จอ}`)
    if (ข.ถูกตัด > 1) ตก.push(`${ที่} ⇒ 🔴 ③ ข้อความบนป้ายถูกตัด ${ข.ถูกตัด} จุด`)
    if (ข.บรรทัด > บรรทัดมากสุด + 0.2) ตก.push(`${ที่} ⇒ 🔴 ③ ป้ายห่อ ${ข.บรรทัด.toFixed(1)} บรรทัด ⇒ เกิน ${บรรทัดมากสุด}`)
    if (ข.สูงขึ้น > 0.5) ตก.push(`${ที่} ⇒ 🔴 ③ ป้ายทำให้หัวที่หนึบสูงขึ้น ${Math.round(ข.สูงขึ้น * 10) / 10} จุด ⇒ ดันตัวบทลง`)
    if (ข.ทับ) ตก.push(`${ที่} ⇒ 🔴 ③ ป้ายทับปุ่มในหัว ${ข.ทับ} ปุ่ม`)
    if (!ตก.length) console.log(`   ${ที่} ⇒ ป้าย ${ข.บรรทัด.toFixed(1)} บรรทัด`)
    return ตก
  } catch (e) {
    ตก.push(`${ที่} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message}`)
    return ตก
  } finally {
    await ctx.close()
  }
}

