/** ผลต้องเป็นอักษรไทยล้วน ⇒ พยางค์ห้ามว่าง ⇒ ยอมแค่ ’ ของคำที่ตัดสระจนเหลือพยัญชนะ */
const ไทยล้วน = /^[ก-๎’]+$/u

/**
 * ตัวตัดสิน ⇒ รับของทุกชิ้นเป็นพารามิเตอร์ ⇒ ฝาแฝดยัดของพังเข้ามาได้โดย ⛔ ไม่ต้องแก้ไฟล์จริง
 * @param คำ Map คำ ⇒ ที่เจอครั้งแรก
 */
function ตรวจ({ คำ, ตาราง, ที่มาบนเว็บ }) {
  const ตก = []
  const อ่าน = สร้างตัวถอด(ตาราง)
  const ลอง = (w) => {
    try {
      return { ผล: อ่าน(w) }
    } catch (e) {
      return { พัง: e.message }
    }
  }
  // ① ทุกคำในข้อมูลจริง
  for (const [w, ที่] of คำ) {
    const x = ลอง(w)
    if (x.พัง) ตก.push(`① «${w}» ถอดไม่ได้ ⇒ ${x.พัง} ⇒ เจอที่ ${ที่}`)
    else if (!x.ผล.พยางค์.length || x.ผล.พยางค์.some((พ) => !ไทยล้วน.test(พ)))
      ตก.push(`① «${w}» ถอดได้ «${x.ผล.พยางค์.join('-')}» ⛔ ไม่ใช่อักษรไทยล้วน ⇒ เจอที่ ${ที่}`)
  }
  // ② ตัวอย่างที่อนุมัติ
  for (const [ก1, อ1, ก2, อ2] of ตัวอย่างอนุมัติ)
    for (const [w, ควร] of [
      [ก1, อ1],
      [ก2, อ2],
    ]) {
      const x = ลอง(w)
      const ได้ = x.พัง ? `โยน ${x.พัง}` : คำอ่านแบบตัวอย่าง(x.ผล)
      if (ได้ !== ควร) ตก.push(`② ตัวอย่างที่อนุมัติ «${w}» ⇒ ได้ «${ได้}» ⛔ ควรเป็น «${ควร}»`)
    }
  for (const [w, ควร] of ตัวอย่างในตาราง) {
    const x = ลอง(w)
    const ได้ = x.พัง ? `โยน ${x.พัง}` : x.ผล.พยางค์.join('-')
    if (ได้ !== ควร) ตก.push(`② ตัวอย่างในตาราง «${w}» ⇒ ได้ «${ได้}» ⛔ ควรเป็น «${ควร}»`)
  }
  // ③ ทุกแถวมีที่มา
  for (const [ชุด, แถว] of Object.entries(ตาราง))
    for (const [กุญแจ, ค] of Object.entries(แถว))
      if (!ค?.ที่มา?.trim()) ตก.push(`③ ตาราง${ชุด} แถว «${กุญแจ}» ⛔ ไม่มีที่มา`)
  // ④ เลขหน้า
  if (เลขหน้า.test(ที่มาบนเว็บ)) ตก.push(`④ บรรทัดที่มาคำอ่านบนการ์ด มีเลขหน้าของตำรา «${ที่มาบนเว็บ.match(เลขหน้า)[0]}» ⇒ ⛔ ไม่ขึ้นเว็บ`)
  if (!ที่มาบนเว็บ?.trim()) ตก.push('④ บรรทัดที่มาคำอ่านบนการ์ดว่าง')
  // ⑤ ของแปลกต้องโยน
  for (const [ชื่อ, w] of ของแปลก) {
    const x = ลอง(w)
    if (!x.พัง) ตก.push(`⑤ ${ชื่อ} «${w}» ⇒ ตัวถอด ⛔ ไม่โยน ⇒ ได้ «${x.ผล.พยางค์.join('-')}» ⇒ กลืนของที่ไม่รู้จักเงียบ ๆ`)
  }
  return ตก
}

