//   *(บทสดุดีของดาวิด เมื่อหนีจากอับซาโลมลูกชายของเขา)* ⇒ เดิมหายทั้งหมด ⇒ ตัวพ่นคือ `tools/สร้างรอยย่อหน้า.py`
