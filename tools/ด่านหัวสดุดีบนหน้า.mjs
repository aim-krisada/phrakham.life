//   ① สดุดี 3 ⇒ **หัวสดุดีอันแรกในหน้าตัวหนังสือตรง ขึ้นอันเดียวกับที่หลังบ้านส่งมาทุกตัว และอยู่เหนือตัวบทข้อ 1** ⇒ ทุกแบบจัดวาง
//   ② **ปิดสวิตช์หัวข้อและกรอบเรื่องเดียวกัน ⇒ หัวสดุดียังขึ้น** ⇒ เป็นถ้อยคำของพระคัมภีร์ ⛔ ไม่ใช่หัวข้อของกองบรรณาธิการ
//   ③ สดุดี 3 ไม่มีหัวข้อ `s1` ⇒ **⛔ ต้องไม่มีหัวข้อเปล่า (h3 ว่าง)** ในหน้า
//   ④ ฮาบากุก 3 มีทั้งหัวข้อและหัวสดุดีที่จุดเดียวกัน ⇒ **เห็นทั้งสองอย่าง**
//
// **พิสูจน์ว่าด่านแดงได้จริง** ⇒ `node tools/ด่านหัวสดุดีบนหน้า.mjs <ที่อยู่เว็บ> --ทดสอบตัวเอง`
//   ⇒ ยัดกฎซ่อนหัวสดุดี ⇒ **ข้อ ① ต้องแดง**
import { chromium } from 'playwright'
import { เส้นทางเว็บ, รอโค้ดของเว็บติด } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')
const ที่ตก = []
const กฎที่พัง = `.pk-หัวสดุดี { display: none !important; }`

const เบราว์เซอร์ = await chromium.launch()

async function เปิด(ที่, แบบ, สวิตช์ = {}) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
  await ctx.addInitScript((v) => localStorage.setItem('phrakham.view', JSON.stringify(v)), { จัดวาง: แบบ, ...สวิตช์ })
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}/read/${ที่}&t=TCV`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await รอโค้ดของเว็บติด(แท็บ)
  await แท็บ.waitForTimeout(300)
  if (ทดสอบตัวเอง) await แท็บ.addStyleTag({ content: กฎที่พัง })
  return { ctx, แท็บ }
}

/** หัวสดุดีที่ตาเห็น ⇒ ตัวหนังสือ + ขอบบน · และหัวข้อ h3 ที่ตาเห็น */
const อ่านหน้า = (แท็บ) =>
  แท็บ.evaluate(() => {
    const เห็น = (x) => x.getClientRects().length && getComputedStyle(x).visibility !== 'hidden'
    const ตัด = (s) => (s || '').replace(/​/g, '').trim()
    const สดุดี = [...document.querySelectorAll('.pk-หัวสดุดี')].filter(เห็น)
    const หัว = [...document.querySelectorAll('.pk-หัวข้อย่อย')].filter(เห็น)
    // ตัวบทข้อ 1 ⇒ ขอบบนของ *ตัวอักษร* คำว่า "ศัตรู" ตัวแรกในหน้า ⇒ ⛔ ไม่ใช้กล่องที่ครอบ เพราะกล่องของแบบไหลต่อเนื่องครอบหัวสดุดีไว้ด้วย
    const ข้อ1 = []
    const เดิน = document.createTreeWalker(document.querySelector('article.pk-เนื้อ') || document.body, NodeFilter.SHOW_TEXT)
    for (let n = เดิน.nextNode(); n; n = เดิน.nextNode()) {
      const ที่ = n.data.replace(/​/g, '').indexOf('ศัตรู')
      if (ที่ < 0 || n.parentElement?.closest('.pk-หัวสดุดี')) continue
      const ช่วง = document.createRange()
      ช่วง.selectNodeContents(n)
      const กล่อง = [...ช่วง.getClientRects()]
      if (กล่อง.length) ข้อ1.push(กล่อง[0].top)
      break
    }
    return {
      สดุดี: สดุดี.map((x) => ({ ตัว: ตัด(x.textContent), บน: x.getBoundingClientRect().top })),
      หัว: หัว.map((x) => ตัด(x.textContent)),
      ข้อ1บน: ข้อ1.length ? Math.min(...ข้อ1) : null,
    }
  })

const ตัด = (s) => (s || '').replace(/​/g, '').trim()
const ส่งมา = await (await fetch(`${ฐาน}/api/chapter/PSA/3.json`)).json()
const คาด = (ส่งมา.หัวข้อ?.TCV || []).filter((ห) => ห.หัวสดุดี).map((ห) => ตัด(ห.หัวสดุดี))
if (คาด.length !== 1) ที่ตก.push(`① หลังบ้านส่งหัวสดุดีของสดุดี 3 มา ${คาด.length} อัน ⛔ ต้องเป็น 1 ⇒ ตัวพ่นอ่านป้าย d ไม่ออก`)

for (const แบบ of ['แยกตามข้อ', 'ไหลต่อเนื่อง', 'แยกตามย่อหน้า']) {
  const { ctx, แท็บ } = await เปิด('PSA/?c=3', แบบ)
  const ได้ = await อ่านหน้า(แท็บ)
  // ⭐ หน้าอ่านโหลดบทถัดไปมาต่อท้ายไว้ด้วย (สดุดี 4 ก็มีหัวสดุดี) ⇒ ของบท 3 คืออันแรกในหน้า
  //   ⇒ ตรวจว่าอันแรกตรง และตัวหนังสือนี้ขึ้นอันเดียว ⛔ ไม่ซ้ำ
  if (ได้.สดุดี[0]?.ตัว !== คาด[0] || ได้.สดุดี.filter((x) => x.ตัว === คาด[0]).length !== 1)
    ที่ตก.push(`① แบบ${แบบ} สดุดี 3 ⇒ ส่งมา ${JSON.stringify(คาด)} ⇒ ตาเห็น ${JSON.stringify(ได้.สดุดี.map((x) => x.ตัว))}`)
  else if (ได้.ข้อ1บน !== null && ได้.สดุดี[0].บน >= ได้.ข้อ1บน)
    ที่ตก.push(`① แบบ${แบบ} สดุดี 3 ⇒ หัวสดุดีอยู่ใต้ตัวบทข้อ 1 (บน ${ได้.สดุดี[0].บน} ≥ ${ได้.ข้อ1บน})`)
  if (!ทดสอบตัวเอง && ได้.หัว.some((x) => !x)) ที่ตก.push(`③ แบบ${แบบ} สดุดี 3 ⇒ มีหัวข้อเปล่า ${ได้.หัว.filter((x) => !x).length} อัน`)
  await ctx.close()
}

if (!ทดสอบตัวเอง) {
  // ── ② ปิดทั้งสองสวิตช์ ⇒ หัวสดุดียังอยู่
  {
    const { ctx, แท็บ } = await เปิด('PSA/?c=3', 'แยกตามข้อ', { หัวข้อย่อย: false, คู่ขนาน: false })
    const ได้ = await อ่านหน้า(แท็บ)
    if (ได้.สดุดี[0]?.ตัว !== คาด[0]) ที่ตก.push(`② ปิดสวิตช์หัวข้อและกรอบ ⇒ ไม่เห็นหัวสดุดีของสดุดี 3 (เห็น ${JSON.stringify(ได้.สดุดี.map((x) => x.ตัว))})`)
    if (ได้.หัว.length) ที่ตก.push(`② ปิดสวิตช์หัวข้อ ⇒ ยังเห็นหัวข้อ ${ได้.หัว.length} อัน`)
    await ctx.close()
  }
  // ── ④ ฮาบากุก 3 ⇒ หัวข้อกับหัวสดุดีจุดเดียวกัน
  {
    const ฮบก = await (await fetch(`${ฐาน}/api/chapter/HAB/3.json`)).json()
    const ห = (ฮบก.หัวข้อ?.TCV || []).find((x) => x.หัวสดุดี)
    if (!ห?.ตัวหนังสือ) ที่ตก.push('④ หลังบ้านไม่ส่งหัวข้อที่มีหัวสดุดีติดมาของฮาบากุก 3')
    else {
      const { ctx, แท็บ } = await เปิด('HAB/?c=3', 'แยกตามข้อ')
      const ได้ = await อ่านหน้า(แท็บ)
      if (!ได้.หัว.includes(ตัด(ห.ตัวหนังสือ))) ที่ตก.push(`④ ฮาบากุก 3 ⇒ ไม่เห็นหัวข้อ "${ตัด(ห.ตัวหนังสือ)}"`)
      if (!ได้.สดุดี.some((x) => x.ตัว === ตัด(ห.หัวสดุดี))) ที่ตก.push(`④ ฮาบากุก 3 ⇒ ไม่เห็นหัวสดุดี "${ตัด(ห.หัวสดุดี)}"`)
      await ctx.close()
    }
  }
}

await เบราว์เซอร์.close()

if (ทดสอบตัวเอง) {
  const จับได้ = ที่ตก.filter((x) => x.startsWith('①'))
  if (!จับได้.length) {
    console.error('⛔ โหมดพิสูจน์: ซ่อนหัวสดุดีแล้ว **ด่านยังเขียว** ⇒ ด่านตาบอด')
    process.exit(1)
  }
  console.log(`✅ โหมดพิสูจน์: ด่านยังจับของพังได้ ⇒ ${จับได้[0]}`)
  process.exit(0)
}
if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
console.log('✅ หัวสดุดีขึ้นเหนือข้อ 1 ตัวหนังสือตรงทุกแบบจัดวาง ขึ้นแม้ปิดสวิตช์ ไม่มีหัวข้อเปล่า และฮาบากุก 3 เห็นทั้งหัวข้อกับหัวสดุดี')
