import glob
import os
import re
import sys

# ⭐ อ่านของที่แตกจาก source/ ⇒ สร้างด้วย tools/แตกกอง.py ⛔ ไม่ขึ้นกิต (ใบงาน #4)
ราก = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
กอง = os.path.join(ราก, "_แตก")

# (ชื่อ, โฟลเดอร์ที่มีไฟล์ .usx)
ฉบับ = [
    ("TCV 2025 ไทย", r"tcv\usx-rev2-release\release\USX_1"),
    ("LSV อังกฤษ",   r"lsv-rev32-release\release\USX_1"),
]

# ข้อที่มีแต่สัญลักษณ์พวกนี้ = ไม่มีเนื้อ ⇒ เจ้าของข้อมูลใส่ไว้เป็นที่หมายว่า "เลขนี้มี แต่เนื้อไปอยู่ที่อื่น"
ขีด = {"", "-", "—", "–", "*"}


def อ่าน(โฟลเดอร์):
    """คืน (ข้อทั้งหมดต่อเล่ม, รายชื่อข้อที่ไม่มีเนื้อ)"""
    ต่อเล่ม, ว่าง = {}, []
    for ทาง in sorted(glob.glob(os.path.join(โฟลเดอร์, "*.usx"))):
        เนื้อไฟล์ = open(ทาง, encoding="utf-8").read()
        นับ = 0
        for จับ in re.finditer(
            r'<verse number="[^"]*" style="v" sid="([^"]+)" />(.*?)<verse eid="\1" />',
            เนื้อไฟล์, re.S):
            นับ += 1
            ข้อความ = re.sub(r"<[^>]+>", "", จับ.group(2)).strip()
            if ข้อความ in ขีด:
                ว่าง.append(จับ.group(1))
        ต่อเล่ม[os.path.basename(ทาง)] = นับ
    return ต่อเล่ม, ว่าง


ผล = {}
for ชื่อ, ย่อย in ฉบับ:
    โฟลเดอร์ = os.path.join(กอง, ย่อย)
    if not os.path.isdir(โฟลเดอร์):
        print(f"⛔ ไม่เจอโฟลเดอร์ {โฟลเดอร์}")
        sys.exit(1)
    ต่อเล่ม, ว่าง = อ่าน(โฟลเดอร์)
    ผล[ชื่อ] = ต่อเล่ม
    print(f"{ชื่อ:<16} {len(ต่อเล่ม)} เล่ม · {sum(ต่อเล่ม.values()):,} ข้อ")
    if ว่าง:
        print(f"   ⚠ ข้อที่ไม่มีเนื้อ {len(ว่าง)} ข้อ ⇒ {' · '.join(ว่าง)}")
    else:
        print("   ✅ ไม่มีข้อว่าง")

print("-" * 70)
ก, ข = [ผล[ชื่อ] for ชื่อ, _ in ฉบับ]
ต่าง = [เล่ม for เล่ม in sorted(set(ก) | set(ข)) if ก.get(เล่ม) != ข.get(เล่ม)]
if ต่าง:
    for เล่ม in ต่าง:
        print(f"⛔ นับไม่เท่ากัน {เล่ม} ⇒ {ฉบับ[0][0]} {ก.get(เล่ม)} · {ฉบับ[1][0]} {ข.get(เล่ม)}")
else:
    print("✅ ทุกเล่มนับได้เท่ากัน")

print("⚠️ นับเท่ากัน ⛔ ไม่ได้แปลว่าเนื้อตรงเลขกัน ⇒ ต้องเปิดเนื้อดูด้วยตาที่ข้อรอบ ๆ ข้อว่างทุกข้อ")
sys.exit(1 if ต่าง else 0)
