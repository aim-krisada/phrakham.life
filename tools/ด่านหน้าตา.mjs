import { chromium } from 'playwright'
import { หน้าทั้งหมด, เส้นทางเว็บ, รอบทในที่อยู่, รอแผนภาพครบ } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')

// เกณฑ์ที่บ้านเรารับมาเอง — `aimagin/way` → `references/ux-rules.md` ตาราง D
const เกณฑ์ตัวหนังสือ = 7

const ที่ตก = []
const เบราว์เซอร์ = await chromium.launch()

// ---------------------------------------------------------------------------
// โค้ดที่ฉีดเข้าไปวัดในหน้า — ใช้ทั้งกับหน้าเปล่าและหน้าจริง ⇒ **เขียนไว้ที่เดียว**
// ---------------------------------------------------------------------------
const ชิ้นทดสอบ = `
  <h1>ก</h1><h2>ก</h2><h3>ก</h3><h4>ก</h4><h5>ก</h5><h6>ก</h6>
  <p>ก</p><ul><li>ก</li></ul><ol><li>ก</li></ol>`

const ช่องที่วัด = ['font-size', 'font-weight', 'margin-top', 'margin-bottom', 'padding-inline-start', 'list-style-type']

function วัดชิ้นทดสอบ(ชิ้นทดสอบ, ช่องที่วัด) {
  const กล่อง = document.createElement('div')
  กล่อง.innerHTML = ชิ้นทดสอบ
  document.body.appendChild(กล่อง)
  const ผล = {}
  for (const el of กล่อง.children) {
    const cs = getComputedStyle(el)
    ผล[el.tagName] = ช่องที่วัด.map((k) => k + '=' + cs.getPropertyValue(k)).join(' ')
  }
  กล่อง.remove()
  return ผล
}

// ---------------------------------------------------------------------------
// ① ค่าตั้งต้นของเบราว์เซอร์ — วัดจากหน้าเปล่าที่ ⛔ ไม่มี CSS ของเราเลย
// ---------------------------------------------------------------------------
const ctxเปล่า = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
const แท็บเปล่า = await ctxเปล่า.newPage()
await แท็บเปล่า.setContent('<!doctype html><html><body></body></html>')
const ค่าเบราว์เซอร์ = await แท็บเปล่า.evaluate(
  ({ ชิ้นทดสอบ, ช่องที่วัด, ตัววัด }) => new Function('return ' + ตัววัด)()(ชิ้นทดสอบ, ช่องที่วัด),
  { ชิ้นทดสอบ, ช่องที่วัด, ตัววัด: วัดชิ้นทดสอบ.toString() },
)
await ctxเปล่า.close()

console.log('① ค่าตั้งต้นของเบราว์เซอร์ที่จะใช้เทียบ')
for (const [t, v] of Object.entries(ค่าเบราว์เซอร์)) console.log(`   ${t.padEnd(3)} ${v}`)

// ---------------------------------------------------------------------------
// สูตรของ WCAG 2.x — ใช้กับสีที่เบราว์เซอร์คำนวณออกมา (รูปแบบ `rgb(r, g, b)`)
// ---------------------------------------------------------------------------
const โค้ดวัดสี = `
function แยกสี(s) {
  const m = s.match(/rgba?\\(([^)]+)\\)/)
  if (!m) return null
  const p = m[1].split(/[,\\/\\s]+/).filter(Boolean).map(Number)
  return { r: p[0], g: p[1], b: p[2], a: p.length > 3 ? p[3] : 1 }
}
function ความสว่าง(c) {
  const f = [c.r, c.g, c.b].map((v) => v / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * f[0] + 0.7152 * f[1] + 0.0722 * f[2]
}
function อัตราส่วน(a, b) {
  const x = ความสว่าง(a), y = ความสว่าง(b)
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)
}
// พื้นที่ตาเห็นจริง = ไต่ขึ้นไปหาบรรพบุรุษตัวแรกที่พื้นไม่ใส
function พื้นจริง(el) {
  for (let n = el; n; n = n.parentElement) {
    const c = แยกสี(getComputedStyle(n).backgroundColor)
    if (c && c.a > 0.99) return c
  }
  return { r: 255, g: 255, b: 255, a: 1 }
}`

async function วัดสีในหน้า(แท็บ) {
  return แท็บ.evaluate(
    ({ โค้ด }) =>
      new Function(
        โค้ด +
          `
      const ออก = []
      for (const el of document.querySelectorAll('body *')) {
        // เอาเฉพาะชิ้นที่มีตัวหนังสือของตัวเอง ⛔ ไม่นับชิ้นที่แค่ห่อลูกไว้
        const มีคำ = [...el.childNodes].some((n) => n.nodeType === 3 && n.textContent.trim())
        if (!มีคำ) continue
        if (el.closest('[aria-hidden="true"]')) continue
        // ⭐ ของที่กดต่อไม่ได้ **ได้รับการยกเว้นจาก SC 1.4.3** ⇒ ⛔ ไม่เอามานับ
        if (el.closest(':disabled')) continue
        const กล่อง = el.getBoundingClientRect()
        if (กล่อง.width < 1 || กล่อง.height < 1) continue
        const cs = getComputedStyle(el)
        if (cs.visibility === 'hidden' || cs.opacity === '0') continue
        const หน้า = แยกสี(cs.color)
        if (!หน้า || หน้า.a < 0.99) continue
        const หลัง = พื้นจริง(el)
        ออก.push({
          แท็ก: el.tagName,
          คลาส: typeof el.className === 'string' ? el.className : '',
          คำ: el.textContent.trim().slice(0, 24),
          สีหน้า: cs.color,
          สีหลัง: 'rgb(' + หลัง.r + ', ' + หลัง.g + ', ' + หลัง.b + ')',
          ต่อ: อัตราส่วน(หน้า, หลัง),
        })
      }
      return ออก`,
      )(),
    { โค้ด: โค้ดวัดสี },
  )
}

// ---------------------------------------------------------------------------
// ③ สีทุกชิ้นในหน้า ⇒ ใช้เทียบโหมดสว่างกับโหมดมืด
// ---------------------------------------------------------------------------
async function ลายเซ็นสี(แท็บ) {
  return แท็บ.evaluate(() =>
    [...document.querySelectorAll('body *')].map((el) => {
      const cs = getComputedStyle(el)
      return [
        el.tagName,
        typeof el.className === 'string' ? el.className : '',
        cs.color,
        cs.backgroundColor,
        cs.borderTopColor,
        cs.borderTopWidth,
        cs.outlineColor,
      ].join('|')
    }),
  )
}

// ---------------------------------------------------------------------------
let นับสีที่วัด = 0

for (const หน้า of หน้าทั้งหมด) {
  const ที่อยู่ = ฐาน + encodeURI(หน้า.ที่อยู่)

  for (const โหมด of ['light', 'dark']) {
    const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 }, colorScheme: โหมด })
    const แท็บ = await ctx.newPage()
    await แท็บ.goto(ที่อยู่, { waitUntil: 'domcontentloaded' })
    await แท็บ.waitForSelector('article.pk-เนื้อ h1')
    // ⭐ ที่อยู่ที่ขอบทมาด้วย (`?c=`) ⇒ รอหมุดของบทนั้นก่อน ⛔ ไม่งั้นวัดบทแรกแทนบทยาว
    await รอบทในที่อยู่(แท็บ, หน้า.ที่อยู่)
    // ⛔ **หน้าที่มีแผนภาพต้องรอให้วาดเสร็จก่อน** — ตัววาดเติมชิ้นเข้าไปในหน้าเรื่อย ๆ
    //   ⇒ ⛔ ไม่รอ = อ่านคนละจังหวะกันสองรอบ ⇒ ข้อ ③ ฟ้องว่าจำนวนชิ้นต่างกัน ทั้งที่ ⛔ ไม่มีอะไรผิด
    //   ⇒ ช่อง `มีแผนภาพ` อยู่ที่ `tools/หน้าที่ตรวจ.mjs` ⛔ ไม่เดาเอาเอง
    //   ⛔ รอแบบ `attached` ⛔ ไม่ใช่ `visible` — แผนภาพนอนอยู่ในกล่อง `<details>` ที่ยังปิดอยู่
    if (หน้า.มีแผนภาพ) {
      await รอแผนภาพครบ(แท็บ)
    }

    if (โหมด === 'light') {
      // ① หน้าตาตั้งต้นของเบราว์เซอร์ยังอยู่ไหม
      const ค่าในหน้า = await แท็บ.evaluate(
        ({ ชิ้นทดสอบ, ช่องที่วัด, ตัววัด }) => new Function('return ' + ตัววัด)()(ชิ้นทดสอบ, ช่องที่วัด),
        { ชิ้นทดสอบ, ช่องที่วัด, ตัววัด: วัดชิ้นทดสอบ.toString() },
      )
      for (const [t, ควรเป็น] of Object.entries(ค่าเบราว์เซอร์)) {
        if (ค่าในหน้า[t] !== ควรเป็น) {
          ที่ตก.push(
            `① ${หน้า.ชื่อ}: <${t.toLowerCase()}> หน้าตาต่างจากค่าตั้งต้นของเบราว์เซอร์\n` +
              `      เบราว์เซอร์ให้ ${ควรเป็น}\n` +
              `      หน้านี้ได้  ${ค่าในหน้า[t]}`,
          )
        }
      }

      // ② ตัวหนังสือทาบพื้นบนหน้าจริง
      const สีทั้งหน้า = await วัดสีในหน้า(แท็บ)
      นับสีที่วัด += สีทั้งหน้า.length
      const เห็นแล้ว = new Set()
      for (const x of สีทั้งหน้า) {
        if (x.ต่อ >= เกณฑ์ตัวหนังสือ) continue
        const กุญแจ = `${x.สีหน้า}|${x.สีหลัง}`
        if (เห็นแล้ว.has(กุญแจ)) continue
        เห็นแล้ว.add(กุญแจ)
        ที่ตก.push(
          `② ${หน้า.ชื่อ}: <${x.แท็ก.toLowerCase()} class="${x.คลาส}"> "${x.คำ}" ` +
            `${x.สีหน้า} ทาบ ${x.สีหลัง} = ${x.ต่อ.toFixed(2)}:1 ⇒ ต่ำกว่าเกณฑ์ ${เกณฑ์ตัวหนังสือ}`,
        )
      }
    }

    หน้า['_ลายเซ็น' + โหมด] = await ลายเซ็นสี(แท็บ)
    await ctx.close()
  }

  // ③ เครื่องตั้งโหมดมืดแล้วหน้าตาต้องเหมือนเดิมทุกจุด
  const สว่าง = หน้า._ลายเซ็นlight
  const มืด = หน้า._ลายเซ็นdark
  if (สว่าง.length !== มืด.length) {
    ที่ตก.push(`③ ${หน้า.ชื่อ}: จำนวนชิ้นในหน้าต่างกันระหว่างโหมดสว่างกับโหมดมืด (${สว่าง.length} vs ${มืด.length})`)
  } else {
    const ต่าง = new Set()
    for (let i = 0; i < สว่าง.length; i++) {
      if (สว่าง[i] !== มืด[i]) ต่าง.add(`${สว่าง[i]}  ⇒โหมดมืด⇒  ${มืด[i]}`)
    }
    for (const t of ต่าง) {
      ที่ตก.push(`③ ${หน้า.ชื่อ}: เครื่องที่ตั้งโหมดมืดเห็นหน้าตาไม่เหมือนกัน ⇒ ${t}`)
    }
  }
  delete หน้า._ลายเซ็นlight
  delete หน้า._ลายเซ็นdark
}

await เบราว์เซอร์.close()

console.log(`\nตรวจ ${หน้าทั้งหมด.length} หน้า · วัดสีตัวหนังสือ ${นับสีที่วัด} จุด · เทียบโหมดมืดครบทุกหน้า`)
if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
console.log('✅ หน้าตาตั้งต้นของเบราว์เซอร์ยังอยู่ · ตัวหนังสือทาบพื้นถึงเกณฑ์ทุกจุด · โหมดมืดไม่เปลี่ยนหน้าตา')
