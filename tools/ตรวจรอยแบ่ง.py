#!/usr/bin/env python3
"""ตรวจว่ารอยแบ่งที่ `อ่าน_usx` เก็บมา ครบและเกาะข้อถูกที่หรือไม่

ใบงาน  https://github.com/aim-krisada/phrakham3/issues/6

ตรวจ 4 ข้อ
  ① ตัวบทเดิมไม่เปลี่ยน ⇒ ต้องได้ 31,087 ข้อเท่าเดิม
  ② จำนวนรอยแบ่งแต่ละพวก เท่ากับที่ `tools/สำรวจรอยแบ่ง.py` ของใบ #53 นับไว้
  ③ ไม่มีรอยแบ่งอันไหนตกหล่นระหว่างทาง ⇒ เทียบกับจำนวนป้ายที่นับจากไฟล์ USX ตรง ๆ
  ④ `หลังอักษร` ชี้ตรงรอยต่อจริง ⇒ ตัวอักษรตรงนั้นต้องเป็นช่องว่างหรือขึ้นบรรทัดใหม่

แล้วพิมพ์ตัวอย่างหัวข้อย่อยที่ **คร่อมรอยบท** ออกมาให้ดูด้วยตา

⛔ สคริปต์นี้อ่านอย่างเดียว ไม่เขียนไฟล์อะไรเลย

รัน  py -3.14 tools/ตรวจรอยแบ่ง.py
"""
import collections
import io
import os
import sys
import xml.etree.ElementTree as ET

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
ที่เก็บ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ที่เก็บ, 'tools'))
import สร้างข้อมูลเว็บ as ตัวแปลง  # noqa: E402

USX = os.path.join(ที่เก็บ, '_แตก', 'tcv', 'usx-rev2-release', 'release', 'USX_1')

# เลขที่ใบ #53 นับไว้จากไฟล์ดิบ ⇒ ใช้เป็นหมุดว่าตัวอ่านเก็บครบไหม
# ⛔ `เว้นวรรค` ไม่มีหมุด เพราะใบ #53 ไม่ได้นับป้าย `b`
หมุดใบ53 = {'หัวข้อย่อย': 1994, 'ย่อหน้า': 11969, 'บรรทัดบทกวี': 23574,
             'ที่อ้างอิงคู่ขนาน': 475, 'หัวสดุดี': 118}


def นับป้ายจากไฟล์ดิบ():
    """เปิดไฟล์ USX นับป้ายที่เราเลือกเก็บ ตรง ๆ ⇒ เป็นตัวหารว่ามีอะไรตกหล่นไหม"""
    น = collections.Counter()
    for รหัส in ตัวแปลง.สารบบ:
        ราก = ET.parse(os.path.join(USX, รหัส + '.usx')).getroot()
        for el in ราก.iter():
            if ตัวแปลง.ชื่อสั้น(el.tag) == 'para':
                ช = ตัวแปลง.ชนิดของป้าย.get(el.get('style'))
                if ช:
                    น[ช] += 1
    return น


def main():
    ข้อ, _, ว่าง, รอย, _เชิงอรรถ = ตัวแปลง.อ่าน_usx(USX, 'TCV')
    ควร = ตัวแปลง.ควรได้['TCV']
    print('① ตัวบทเดิม ⇒ ได้ %s ข้อ (ควรได้ %s) · ข้อว่าง %s (ควรได้ %s)'
          % (format(len(ข้อ), ','), format(ควร['ข้อ'], ','), len(ว่าง), ควร['ว่าง']))

    ได้ = collections.Counter(ร['ชนิด'] for v in รอย.values() for ร in v)
    ดิบ = นับป้ายจากไฟล์ดิบ()
    print('\n%-18s %9s %9s %9s' % ('พวก', 'เก็บได้', 'ในไฟล์ดิบ', 'หมุดใบ53'))
    for ช in ตัวแปลง.พวกรอยแบ่ง:
        print('%-18s %9s %9s %9s' % (ช, format(ได้[ช], ','), format(ดิบ[ช], ','),
                                     format(หมุดใบ53[ช], ',') if ช in หมุดใบ53 else '—'))
    print('%-18s %9s %9s' % ('รวม', format(sum(ได้.values()), ','), format(sum(ดิบ.values()), ',')))

    # ④ `หลังอักษร` ต้องตกตรงรอยต่อ ⇒ ตัวก่อนหน้าเป็นช่องว่าง หรืออยู่หัวข้อพอดี
    เพี้ยน = []
    for (เล่ม, บท), รายการ in รอย.items():
        for ร in รายการ:
            ที่ = ร['หลังอักษร']
            if ที่ == 0:
                continue
            เนื้อ = ข้อ[(เล่ม, str(บท), str(ร['ข้อ']))]
            if ที่ >= len(เนื้อ) or not เนื้อ[ที่ - 1].isspace():
                เพี้ยน.append((เล่ม, บท, ร['ข้อ'], ร['ป้าย'], ที่))
    print('\n④ รอยแบ่งกลางข้อที่ `หลังอักษร` ไม่ตกตรงช่องว่าง %s อัน' % format(len(เพี้ยน), ','))
    for x in เพี้ยน[:5]:
        print('   %s %s.%s ป้าย %s ที่ %s' % x)

    # ⑤ รอยบทที่ตกกลางหัวข้อ ⇒ **หัวใจของงานนี้**
    # นิยาม ⇒ บทถัดไป **ไม่มี** หัวข้อย่อยเกาะที่ข้อแรกของมัน
    #        แปลว่าหัวข้อของบทก่อนหน้ายังครองเนื้อข้ามรอยบทมา ⇒ คร่อม
    # ⛔ ไม่นับรอยบทข้ามเล่ม (คนละหนังสือ ไม่มีอะไรให้คร่อม)
    บทของเล่ม = collections.defaultdict(list)
    for (เล่ม, บท) in รอย:
        บทของเล่ม[เล่ม].append(บท)
    หัว = [ร for v in รอย.values() for ร in v if ร['ชนิด'] == 'หัวข้อย่อย']
    รอยบท, คร่อม = 0, []
    for เล่ม, บทหลาย in บทของเล่ม.items():
        for บท in sorted(บทหลาย)[1:]:           # ข้ามบทแรกของเล่ม ⇒ ไม่ใช่รอยต่อ
            รอยบท += 1
            รายการ = รอย[(เล่ม, บท)]
            ข้อแรก = min(ร['ข้อ'] for ร in รายการ)
            if not any(ร['ชนิด'] == 'หัวข้อย่อย' and ร['ข้อ'] == ข้อแรก and ร['หลังอักษร'] == 0
                       for ร in รายการ):
                ก่อนหน้า = [(ข, ร) for ข in sorted(บทหลาย) if ข < บท
                            for ร in รอย[(เล่ม, ข)] if ร['ชนิด'] == 'หัวข้อย่อย']
                หัวที่ครอง = ก่อนหน้า[-1] if ก่อนหน้า else None
                คร่อม.append((เล่ม, บท, ข้อแรก, หัวที่ครอง))
    # ⚠️ **สองเลขนี้นับคนละหน่วย ⛔ อย่าสลับกัน**
    #    หัวข้อหนึ่งอันอาจกินยาวข้ามหลายบท ⇒ นับเป็นหัวข้อคร่อม 1 อัน แต่เป็นรอยบทหลายรอย
    #    ⇒ เลข "หัวข้อคร่อม" คือเลขเดียวกับที่ใบ #53 รายงานไว้ (149)
    หัวคร่อม = {(เล่ม, ห[0], ห[1]['ข้อ']) for เล่ม, _, _, ห in คร่อม if ห}
    print('\n⑤ รอยบทในเล่มเดียวกัน %s รอย'
          '\n   รอยบทที่ตกกลางหัวข้อ %s รอย = %.1f%% ของรอยบท'
          '\n   หัวข้อย่อยที่คร่อมรอยบท %s อัน = %.1f%% ของหัวข้อย่อย %s อัน'
          % (format(รอยบท, ','), format(len(คร่อม), ','), len(คร่อม) * 100 / รอยบท,
             format(len(หัวคร่อม), ','), len(หัวคร่อม) * 100 / len(หัว) if หัว else 0,
             format(len(หัว), ',')))
    for เล่ม, บท, ข้อแรก, ห in คร่อม[:8]:
        print('   %s %s ⇒ ข้อแรกคือข้อ %s ไม่มีหัวข้อของตัวเอง · หัวข้อที่ครองอยู่คือ %s %s.%s "%s"'
              % (เล่ม, บท, ข้อแรก, เล่ม, ห[0], ห[1]['ข้อ'], ห[1]['ตัวหนังสือ']))

    return 0


if __name__ == '__main__':
    sys.exit(main())
