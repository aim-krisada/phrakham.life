"""ชั่งว่าชั้นคำภาษาเดิมที่ขึ้นเว็บ กินที่เท่าไร และคำครบไหม — ใบงาน v3/phrakham#95

⭐⭐ **ทำไมต้องมีตัวนี้** ⇒ หลังบ้านที่ `server/utils/ชั้นคำ.ts` **ย่อข้อมูลก่อนส่ง**
  ⇒ เหลือ 2 ช่องคือ `ตัว` กับ `คำแปล` ⛔ ตัด `รหัส` `รูปผัน` `รูปพจนานุกรม` `บทบาท` ออก
  ⇒ ⭐ ยกเว้นกริยากรีกที่ได้ช่องที่ 3 = กาลกับมาลา 2 ตัวอักษรจาก `รูปผัน` (ใบ #110)
  ⇒ **การย่อแบบนี้ต้องพิสูจน์ได้ 2 อย่าง** ⛔ ไม่ใช่เชื่อเพราะคนเขียนบอก
    ① **คำไม่หายสักคำ** ⇒ จำนวนคำหลังย่อ ต้องเท่ากับบัญชีของกองเป๊ะ
    ② **ตัวอักษรเดิมไม่เปลี่ยน** ⇒ ช่อง `ตัว` ต้องตรงกับต้นทางทุกตัวอักษร

⛔ **ตัวนี้ ⛔ ไม่ได้อยู่ในท่อ CI** ⇒ มันอ่านกองทั้ง 1,189 บท ⇒ ช้าเกินกว่าจะรันทุกคอมมิต
  ⇒ **ของที่เฝ้าในท่อคือ `tools/ด่านนับชั้นคำ.py`** ⇒ ตัวนี้เป็นของที่คนรันเองตอนอยากรู้ตัวเลข

**สั่ง** ⇒ ``py -3.14 tools/ชั่งชั้นคำบนเว็บ.py``
"""

from __future__ import annotations

import gzip
import json
import re
import sys
from pathlib import Path

ราก = Path(__file__).resolve().parent.parent
กอง = ราก / "_data" / "ภาษาเดิม"
เมกะ = 1024 * 1024


def กาลมาลาของ(รูปผัน: str) -> str | None:
    """กาลกับมาลาของกริยากรีก ⇒ `V-2AAI-3S` ⇒ `AI` (ใบ #110) ⇒ กติกาเดียวกับ `กาลมาลาของ` ใน `server/utils/ชั้นคำ.ts`"""
    if not รูปผัน.startswith("V-"):
        return None
    m = re.match(r"^V-2?([PIFARL])[AMPEDONQX]([ISOMNPR])(?:-|$)", รูปผัน)
    if not m:
        raise ValueError(f"รูปผันกริยา {รูปผัน} ตัดกาลกับมาลาไม่ออก")
    return m.group(1) + m.group(2)


def ย่อคำ(ชื่อชั้น: str, คำ: dict) -> list:
    คู่ = [คำ.get("ตัว", ""), คำ.get("คำแปล", "")]
    # ⭐ ใบ #110 ⇒ กริยากรีกได้ช่องที่ 3 ⇒ ฮีบรู ⛔ ไม่แตะ
    กาล = กาลมาลาของ(คำ.get("รูปผัน", "")) if ชื่อชั้น == "คำกรีก" else None
    return คู่ + [กาล] if กาล else คู่


def ย่อแบบเดียวกับหลังบ้าน(ชั้น: dict) -> dict:
    """ย่อให้ตรงกับ `server/utils/ชั้นคำ.ts` เป๊ะ ⇒ ⛔ แก้ที่นั่นแล้วต้องแก้ที่นี่ด้วย"""
    return {
        ชื่อ: {ข้อ: [ย่อคำ(ชื่อ, คำ) for คำ in คำทั้งข้อ]
               for ข้อ, คำทั้งข้อ in บท.items()}
        for ชื่อ, บท in ชั้น.items()
    }


def main() -> int:
    บัญชี = json.loads((กอง / "บัญชี.json").read_text(encoding="utf-8"))
    ควรได้ = บัญชี["รวม"]

    ไฟล์ = sorted(p for p in กอง.glob("*/*.json.gz"))
    if not ไฟล์:
        print(f"⛔ ไม่เจอกองชั้นคำที่ {กอง}")
        return 1

    ดิบ = ย่อ = ย่อบีบ = 0
    นับคำ = นับข้อ = 0
    ตัวอักษรเพี้ยน: list[str] = []

    for p in ไฟล์:
        ของ = json.loads(gzip.open(p, "rt", encoding="utf-8").read())
        ชั้น = ของ.get("ชั้น", {})
        ดิบ += len(json.dumps(ของ, ensure_ascii=False).encode())

        เล็ก = ย่อแบบเดียวกับหลังบ้าน(ชั้น)
        ก้อน = json.dumps(เล็ก, ensure_ascii=False).encode()
        ย่อ += len(ก้อน)
        ย่อบีบ += len(gzip.compress(ก้อน, 6))

        for ชื่อ, บท in ชั้น.items():
            for ข้อ, คำทั้งข้อ in บท.items():
                นับข้อ += 1
                นับคำ += len(คำทั้งข้อ)
                # ② ตัวอักษรเดิมต้องไม่เปลี่ยน ⇒ เทียบทีละคำกับต้นทาง
                for i, คำ in enumerate(คำทั้งข้อ):
                    if เล็ก[ชื่อ][ข้อ][i][0] != คำ.get("ตัว", ""):
                        ตัวอักษรเพี้ยน.append(f"{p.parent.name}/{p.stem} {ชื่อ} ข้อ {ข้อ} คำที่ {i + 1}")

    print(f"ไฟล์ที่ชั่ง        {len(ไฟล์):>8,} บท")
    print(f"ดิบทั้งก้อน        {ดิบ / เมกะ:>8.1f} MB")
    print(f"ย่อแบบที่ขึ้นเว็บ  {ย่อ / เมกะ:>8.1f} MB  ⇒ เหลือ {ย่อ / ดิบ * 100:.0f}% ของดิบ")
    print(f"ย่อแล้วบีบ gzip    {ย่อบีบ / เมกะ:>8.1f} MB  ⇒ นี่คือไบต์ที่วิ่งจริงถ้าโฮสต์บีบให้")
    print(f"เฉลี่ยต่อบท        {ย่อ / len(ไฟล์) / 1024:>8.1f} KB  ⇒ นี่คือของที่ผู้อ่าน 1 คนจ่ายตอนกด 1 บท")
    print()

    พัง = False
    for ชื่อ, ได้, ต้องได้ in (("คำ", นับคำ, ควรได้["คำ"]), ("ข้อ", นับข้อ, ควรได้["ข้อ"])):
        ตรง = ได้ == ต้องได้
        พัง = พัง or not ตรง
        print(f"{'✅' if ตรง else '⛔'} นับ{ชื่อ}ได้ {ได้:,} ⇒ บัญชีบอก {ต้องได้:,}")

    if ตัวอักษรเพี้ยน:
        พัง = True
        print(f"⛔ ตัวอักษรเดิมเพี้ยน {len(ตัวอักษรเพี้ยน):,} คำ ⇒ ตัวอย่าง {ตัวอักษรเพี้ยน[:3]}")
    else:
        print(f"✅ ตัวอักษรเดิมตรงกับต้นทางครบทั้ง {นับคำ:,} คำ")

    return 1 if พัง else 0


if __name__ == "__main__":
    sys.exit(main())
