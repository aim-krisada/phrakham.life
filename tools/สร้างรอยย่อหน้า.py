def เป็นข้อความ(ของ):
    """ตัวหนังสือในซอง ⇒ sort_keys ⇒ ลำดับกุญแจไม่ขึ้นกับลำดับที่ไพทอนเผอิญใส่เข้ามา"""
    return json.dumps(ของ, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def เป็นไบต์(ข้อความ):
    ถัง = io.BytesIO()
    # mtime=0 ⇒ ⛔ ไม่ประทับเวลาลงหัวซอง ⇒ พ่นซ้ำบนไพทอนตัวเดียวกันได้ไบต์เดิมเสมอ
    with gzip.GzipFile(fileobj=ถัง, mode="wb", compresslevel=9, mtime=0) as ซ:
        ซ.write(ข้อความ.encode("utf-8"))
    return ถัง.getvalue()


