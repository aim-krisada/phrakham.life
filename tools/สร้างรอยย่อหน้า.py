def อ่านคู่ขนาน(ข้อความ, ชื่อ_รหัส):
    """`(มธ.3:13-17; 4:1-11; ลก.3:21,22)` ⇒ [{ตัวหนังสือ, ที่อยู่}] ⇒ ที่อยู่คือข้อแรกของแต่ละท่อน
    ⇒ ท่อน = ชื่อเล่ม + บท:ข้อ + ข้อต่อท้าย (`,9-14` `-27:2`) ⇒ ท่อนที่ขึ้นด้วยเลขเฉย ๆ (`; 4:1-11`) = เล่มเดิม"""
    ชื่อ = sorted(ชื่อ_รหัส, key=len, reverse=True)
    หาง = r"(?:\s?[,–-]\s?\d+(?::\d+)?)*"
    แบบ = re.compile(r"(" + "|".join(re.escape(n) for n in ชื่อ) + r")\s?(\d+):(\d+)" + หาง)
    ต่อ = re.compile(r"\s*;\s*(\d+):(\d+)" + หาง)
    ออก = []
    for m in แบบ.finditer(ข้อความ):
        รหัส = ชื่อ_รหัส[m.group(1)]
        ออก.append({"ตัวหนังสือ": m.group(0), "ที่อยู่": "%s %s:%s" % (รหัส, m.group(2), m.group(3))})
        ที่ = m.end()
        while (m2 := ต่อ.match(ข้อความ, ที่)):
            ตัว = m2.group(0)
            ตัด = len(ตัว) - len(ตัว.lstrip("; 	"))
            ออก.append({"ตัวหนังสือ": ตัว[ตัด:], "ที่อยู่": "%s %s:%s" % (รหัส, m2.group(1), m2.group(2))})
            ที่ = m2.end()
    return ออก


def อ่านคำนำเล่ม(กอง):
    """คำนำเล่มของผู้แปล ⇒ `<para style="ip">` ก่อนบทที่ 1 ⇒ {(เล่ม, 1): [{ป้าย, ตัวหนังสือ}]}
    ⇒ ตัวหนังสือตามเจ้าของ ⇒ ⛔ ไม่เอาเชิงอรรถ ⇒ ยุบช่องว่างซ้อนเป็นช่องเดียว (ขึ้นบรรทัดในไฟล์ ⛔ ใช่ตัวบท)"""
    import xml.etree.ElementTree as ET
    ออก = {}
    for ไฟล์ in sorted(Path(กอง).glob("*.usx")):
        ราก = ET.parse(ไฟล์).getroot()
        เล่ม = (ราก.find("book").get("code") if ราก.find("book") is not None else "")
        ย่อ = []
        for el in ราก:
            if el.tag == "chapter":
                break
            if el.tag == "para" and el.get("style") in ป้ายคำนำ:
                ชิ้น = [el.text or ""]
                for c in el:
                    if c.tag != "note":
                        ชิ้น.append("".join(c.itertext()))
                    ชิ้น.append(c.tail or "")
                ตัว = " ".join("".join(ชิ้น).split())
                if ตัว:
                    ย่อ.append({"ป้าย": el.get("style"), "ตัวหนังสือ": ตัว})
        if ย่อ and เล่ม:
            ออก[(เล่ม, 1)] = ย่อ
    return ออก


def เก็บหัวข้อ(รอยแบ่ง, ชื่อ_รหัส=None, สถิติ=None):
    """คัดเฉพาะหัวข้อย่อย `s1` ⇒ เรียงตามข้อแล้วตามตำแหน่งในข้อ ⇒ หัวข้อที่ไม่มีตัวหนังสือ ⛔ ไม่เอา
    ⇒ บรรทัด `r` ที่ตามหัวข้อมาติด ๆ ⇒ ช่อง `คู่ขนาน` ของหัวข้อนั้น (ดูหัวไฟล์)"""
    ออก = {}
    for (ล, บ), รายการ in รอยแบ่ง.items():
        ก้อน = []
        สดุดี = []
        รอง = []
        ล่าสุด = None
        for ร in รายการ:
            if ร["ป้าย"] == ป้ายหัวข้อ and ร.get("ตัวหนังสือ"):
                ล่าสุด = {"ข้อ": ร["ข้อ"], "หลังอักษร": ร["หลังอักษร"], "ตัวหนังสือ": ร["ตัวหนังสือ"]}
                ก้อน.append(ล่าสุด)
                continue
            if ร["ป้าย"] == ป้ายหัวสดุดี and ร.get("ตัวหนังสือ"):
                if สถิติ is not None:
                    สถิติ["หัวสดุดี"] += 1
                if ร["หลังอักษร"] > 0:
                    # ⛔ หัวสดุดีกลางข้อ ⇒ TCV มีอันเดียว ฮบก.3:19 ⇒ เป็นท้ายบท ⛔ ไม่ใช่หัว ⇒ ดูหัวไฟล์
                    if สถิติ is not None:
                        สถิติ["หัวสดุดีกลางข้อ"].append("%s %d:%d %s" % (ล, บ, ร["ข้อ"], ร["ตัวหนังสือ"]))
                    continue
                สดุดี.append((ร["ข้อ"], ร["ตัวหนังสือ"]))
                continue
            if ร["ป้าย"] in ป้ายหัวรอง and ร.get("ตัวหนังสือ"):
                if สถิติ is not None:
                    สถิติ["หัวรอง"][ร["ป้าย"]] += 1
                # ⛔ กลางข้อ ⇒ ตัวบทของข้อนั้นมีบรรทัดนี้ติดมาแล้ว (เช่น ชื่อผู้พูดใน พซม.1:4) ⇒ ใส่อีก = ซ้ำ
                if ร["หลังอักษร"] == 0:
                    รอง.append((ร["ข้อ"], ร["ป้าย"], ร["ตัวหนังสือ"]))
                elif สถิติ is not None:
                    สถิติ["หัวรองกลางข้อ"] += 1
                ล่าสุด = None
                continue
            if ร["ป้าย"] == "r" and ร.get("ตัวหนังสือ") and สถิติ is not None:
                สถิติ["บรรทัด"] += 1
                ตรงหัว = ล่าสุด and (ล่าสุด["ข้อ"], ล่าสุด["หลังอักษร"]) == (ร["ข้อ"], ร["หลังอักษร"]) and "คู่ขนาน" not in ล่าสุด
                if not ตรงหัว:
                    สถิติ["ไม่มีหัว"].append("%s %d:%d %s" % (ล, บ, ร["ข้อ"], ร["ตัวหนังสือ"]))
                    continue
                if ล่าสุด["หลังอักษร"] > 0:
                    สถิติ["กลางข้อ"] += 1
                    continue
                โยง = อ่านคู่ขนาน(ร["ตัวหนังสือ"], ชื่อ_รหัส or {})
                if not โยง:
                    สถิติ["อ่านไม่ออก"].append("%s %d:%d %s" % (ล, บ, ร["ข้อ"], ร["ตัวหนังสือ"]))
                สถิติ["โยง"] += len(โยง)
                ล่าสุด["คู่ขนาน"] = {"ตัวหนังสือ": ร["ตัวหนังสือ"], "โยงไป": โยง}
            elif ร["ป้าย"] != "r":
                ล่าสุด = None
        for ข้อ, ตัว in สดุดี:
            # ⭐ หัวข้อ `s1` จุดเดียวกันมีอยู่แล้ว ⇒ เกาะเป็นช่องของหัวข้อนั้น ⛔ ไม่ทำหัวข้อซ้อนสองอันที่จุดเดียว
            เดิม = next((ก for ก in ก้อน if (ก["ข้อ"], ก["หลังอักษร"]) == (ข้อ, 0)), None)
            if เดิม is None:
                เดิม = {"ข้อ": ข้อ, "หลังอักษร": 0, "ตัวหนังสือ": ""}
                ก้อน.append(เดิม)
            เดิม["หัวสดุดี"] = (เดิม.get("หัวสดุดี", "") + " " + ตัว).strip()
        for ข้อ, ป้าย, ตัว in รอง:
            # ⭐ ท่าเดียวกับหัวสดุดี ⇒ เกาะหัวข้อจุดเดียวกัน ⇒ เรียงตามลำดับในไฟล์ของเจ้าของ
            เดิม = next((ก for ก in ก้อน if (ก["ข้อ"], ก["หลังอักษร"]) == (ข้อ, 0)), None)
            if เดิม is None:
                เดิม = {"ข้อ": ข้อ, "หลังอักษร": 0, "ตัวหนังสือ": ""}
                ก้อน.append(เดิม)
            เดิม.setdefault("หัวรอง", []).append({"ป้าย": ป้าย, "ตัวหนังสือ": ตัว})
        if ก้อน:
            ก้อน.sort(key=lambda ก: (ก["ข้อ"], ก["หลังอักษร"]))
            ออก["%s/%d" % (ล, บ)] = ก้อน
    return ออก


def แบ่งจริงไหม(ก้อนของฉบับ):
    """ฉบับนี้ **แบ่งย่อหน้าจริง** หรือแค่คลุมทั้งบทไว้ด้วยย่อหน้าเดียว

    ⭐ **เกณฑ์นับเอาเอง ⛔ ไม่ใช่รายชื่อฉบับที่พิมพ์ค้างไว้**
      ⇒ บทที่มีรอยย่อหน้ามากกว่า 1 อัน คือบทที่ถูกแบ่งจริง
      ⇒ ⛔ **ไม่มีบทไหนถูกแบ่งเลย = ฉบับนี้ไม่มีย่อหน้าให้ใช้**
    **ของจริงที่นับเอง 18 ต.ค. 2569** ⇒ LSV มี `p` 1,189 อัน บนบท 1,189 บท ⇒ บทละ 1 อันเป๊ะ
      ⇒ เอามาขึ้นหน้าจอก็ได้ย่อหน้าเดียวยาวทั้งบท ⇒ **เท่ากับไม่มี**
    """
    บทที่แบ่ง = sum(1 for ก้อน in ก้อนของฉบับ.values() if len(ก้อน) > 1)
    return บทที่แบ่ง, len(ก้อนของฉบับ)


