def อ่านคู่ขนาน(ข้อความ, ชื่อ_รหัส):
    """`(มธ.3:13-17; 4:1-11; ลก.3:21,22)` ⇒ [{ตัวหนังสือ, ที่อยู่}] ⇒ ที่อยู่คือข้อแรกของแต่ละท่อน
    ⇒ ท่อน = ชื่อเล่ม + บท:ข้อ + ข้อต่อท้าย (`,9-14` `-27:2`) ⇒ ท่อนที่ขึ้นด้วยเลขเฉย ๆ (`; 4:1-11`) = เล่มเดิม"""
    ชื่อ = sorted(ชื่อ_รหัส, key=len, reverse=True)
    หาง = r"(?:\s?[,–-]\s?\d+(?::\d+)?)*"
    แบบ = re.compile(r"(" + "|".join(re.escape(n) for n in ชื่อ) + r")\s?(\d+):(\d+)" + หาง)
    ต่อ = re.compile(r"\s*;\s*(\d+):(\d+)" + หาง)
    ออก = []
    for m in แบบ.finditer(ข้อความ):
        รหัส = ชื่อ_รหัส[m.group(1)]
        ออก.append({"ตัวหนังสือ": m.group(0), "ที่อยู่": "%s %s:%s" % (รหัส, m.group(2), m.group(3))})
        ที่ = m.end()
        while (m2 := ต่อ.match(ข้อความ, ที่)):
            ตัว = m2.group(0)
            ตัด = len(ตัว) - len(ตัว.lstrip("; 	"))
            ออก.append({"ตัวหนังสือ": ตัว[ตัด:], "ที่อยู่": "%s %s:%s" % (รหัส, m2.group(1), m2.group(2))})
            ที่ = m2.end()
    return ออก


def เก็บหัวข้อ(รอยแบ่ง, ชื่อ_รหัส=None, สถิติ=None):
    """คัดเฉพาะหัวข้อย่อย `s1` ⇒ เรียงตามข้อแล้วตามตำแหน่งในข้อ ⇒ หัวข้อที่ไม่มีตัวหนังสือ ⛔ ไม่เอา
    ⇒ บรรทัด `r` ที่ตามหัวข้อมาติด ๆ ⇒ ช่อง `คู่ขนาน` ของหัวข้อนั้น (ดูหัวไฟล์)"""
    ออก = {}
    for (ล, บ), รายการ in รอยแบ่ง.items():
        ก้อน = []
        ล่าสุด = None
        for ร in รายการ:
            if ร["ป้าย"] == ป้ายหัวข้อ and ร.get("ตัวหนังสือ"):
                ล่าสุด = {"ข้อ": ร["ข้อ"], "หลังอักษร": ร["หลังอักษร"], "ตัวหนังสือ": ร["ตัวหนังสือ"]}
                ก้อน.append(ล่าสุด)
                continue
            if ร["ป้าย"] == "r" and ร.get("ตัวหนังสือ") and สถิติ is not None:
                สถิติ["บรรทัด"] += 1
                ตรงหัว = ล่าสุด and (ล่าสุด["ข้อ"], ล่าสุด["หลังอักษร"]) == (ร["ข้อ"], ร["หลังอักษร"]) and "คู่ขนาน" not in ล่าสุด
                if not ตรงหัว:
                    สถิติ["ไม่มีหัว"].append("%s %d:%d %s" % (ล, บ, ร["ข้อ"], ร["ตัวหนังสือ"]))
                    continue
                if ล่าสุด["หลังอักษร"] > 0:
                    สถิติ["กลางข้อ"] += 1
                    continue
                โยง = อ่านคู่ขนาน(ร["ตัวหนังสือ"], ชื่อ_รหัส or {})
                if not โยง:
                    สถิติ["อ่านไม่ออก"].append("%s %d:%d %s" % (ล, บ, ร["ข้อ"], ร["ตัวหนังสือ"]))
                สถิติ["โยง"] += len(โยง)
                ล่าสุด["คู่ขนาน"] = {"ตัวหนังสือ": ร["ตัวหนังสือ"], "โยงไป": โยง}
            elif ร["ป้าย"] != "r":
                ล่าสุด = None
        if ก้อน:
            ก้อน.sort(key=lambda ก: (ก["ข้อ"], ก["หลังอักษร"]))
            ออก["%s/%d" % (ล, บ)] = ก้อน
    return ออก


