    for (ล, บ, ข), เนื้อ in ข้อ.items():
        ก้อน = เนื้อบท["บท"].get("%s/%s" % (ล, บ))
        if not ก้อน or ฉบับ not in ก้อน:
            continue
        ในซอง = ก้อน[ฉบับ].get(str(ข))
