def แปลงตำแหน่ง(ต้นทาง, ของเว็บ, ที่):
    """ตัวบทต่างกันแค่ช่องว่าง ⇒ ย้ายตำแหน่งรอยจากตัวบทของ USX ไปตัวบทของเว็บ
    ⇒ นับตัวที่ไม่ใช่ช่องว่างก่อนรอย = k ⇒ ตำแหน่งใหม่ = หน้าตัวที่ไม่ใช่ช่องว่างตัวที่ k+1 ของตัวบทเว็บ
    ⇒ ⭐ รอยจึงตกหน้าคำถัดไปเสมอ ⇒ ช่องว่างค้างท้ายย่อหน้าก่อน ⇒ ตรงเกณฑ์ ⑤ ของ `tools/ตรวจรอยย่อหน้า.py`
    ⇒ ⛔ ต่างจาก `แปลงตำแหน่ง` ใน `tools/สร้างเชิงอรรถ.py` ที่วางเครื่องหมาย *ท้ายคำก่อน* ⇒ คนละความหมาย"""
    if ที่ == 0 or ต้นทาง == ของเว็บ:
        return ที่
    นับ = len(ช่องว่าง.sub("", ต้นทาง[:ที่]))
    เจอ = 0
    for i, ต in enumerate(ของเว็บ):
        if not ต.isspace():
            if เจอ == นับ:
                return i
            เจอ += 1
    return len(ของเว็บ)


