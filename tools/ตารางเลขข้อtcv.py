ลายที่อยู่ = re.compile(r"^(\S+) (\d+):(\d+)(?:-(\d+))?$")


def อ่านไฟล์(ไฟล์):
    """คืน (บรรทัดตารางข้อสูงสุด, บรรทัดตารางเทียบ) ⇒ แยกด้วยเครื่องหมาย `=` ก่อนเสมอ"""
    ข้อสูงสุด, เทียบ = [], []
    for บรรทัด in ไฟล์.read_text(encoding="utf-8-sig").splitlines():
        บรรทัด = บรรทัด.strip()
        if not บรรทัด or บรรทัด.startswith("#"):
            continue
        (เทียบ if "=" in บรรทัด else ข้อสูงสุด).append(บรรทัด)
    return ข้อสูงสุด, เทียบ


def ทำตารางข้อสูงสุด(บรรทัดทั้งหมด):
    """`GEN 1:31 2:25 ...` ⇒ {"GEN": {"1": 31, "2": 25, ...}}"""
    ตาราง = {}
    for บรรทัด in บรรทัดทั้งหมด:
        ส่วน = บรรทัด.split()
        เล่ม = ส่วน[0]
        บท = {}
        for ช่อง in ส่วน[1:]:
            เลขบท, เลขข้อ = ช่อง.split(":")
            บท[เลขบท] = int(เลขข้อ)
        ตาราง[เล่ม] = บท
    return ตาราง


def ทำตารางเทียบ(บรรทัดทั้งหมด):
    """`GEN 32:1-32 = GEN 32:2-33` ⇒ ไล่ทีละข้อ {"GEN 32.1": "GEN 32.2", ...}

    คืน (ไทยไปต้นฉบับ, ข้อศูนย์, บรรทัดที่อ่านไม่ออก)
    ข้อศูนย์ = บทที่ตารางบอกว่ามีข้อ 0 (หัวเรื่องเพลงสดุดี) ⇒ ตารางข้อสูงสุดไม่ได้บอกไว้
    """
    ไทยไปต้นฉบับ = {}
    ข้อศูนย์ = {}
    อ่านไม่ออก = []
    for บรรทัด in บรรทัดทั้งหมด:
        ซ้าย, ขวา = [ส.strip() for ส in บรรทัด.split("=", 1)]
        กซ, กข = ลายที่อยู่.match(ซ้าย), ลายที่อยู่.match(ขวา)
        if not กซ or not กข:
            อ่านไม่ออก.append(บรรทัด)
            continue
        บซ, ชซ, ตซ = กซ.group(1), กซ.group(2), int(กซ.group(3))
        จซ = int(กซ.group(4) or กซ.group(3))
        บข, ชข, ตข = กข.group(1), กข.group(2), int(กข.group(3))
        จข = int(กข.group(4) or กข.group(3))
        if จซ - ตซ != จข - ตข:
            อ่านไม่ออก.append(บรรทัด)
            continue
        if ตซ == 0:
            ข้อศูนย์.setdefault(บซ, []).append(int(ชซ))
        for i in range(จซ - ตซ + 1):
            ไทยไปต้นฉบับ[f"{บซ} {ชซ}.{ตซ + i}"] = f"{บข} {ชข}.{ตข + i}"
    return ไทยไปต้นฉบับ, ข้อศูนย์, อ่านไม่ออก


def เฉพาะเล่มเรา(ตาราง):
    ชุด = set(เล่มเรา)
    return {ค: v for ค, v in ตาราง.items() if ค.split()[0] in ชุด}


def ตรวจกับของที่พ่น(สารบัญ, ข้อสูงสุด, ข้อศูนย์, ไทยไปต้นฉบับ):
    """เอาไม้บรรทัดของ TCV ไปชนกับจำนวนข้อที่เราพ่นออกมาจริง

    ตรวจ 2 ฝั่ง
      ฝั่งไทย    ช่อง `บทไทย` ในสารบัญ ⇒ ชนกับตารางข้อสูงสุดตรง ๆ (เลขชุดเดียวกัน)
      ฝั่งต้นฉบับ ช่อง `บท` ในสารบัญ  ⇒ ต้องแปลงไม้บรรทัดผ่านตารางเทียบก่อน
    """
    หนังสือ = สารบัญ["เล่ม"]

    # ไม้บรรทัดคือข้อ 1 ถึงข้อสูงสุด ⇒ อ่านตารางตามที่มันเขียนไว้ตรง ๆ
    # ⚠️ ข้อ 0 ในตารางเทียบ (หัวเรื่องเพลงสดุดี) ⛔ ไม่นับ
    #    เปิดไฟล์ USX ของ TCV ดูแล้ว PSA 3 เริ่มที่ sid="PSA 3:1" ⇒ ตัวบทจริงไม่มีข้อ 0
    def ข้อที่ควรมี(เล่ม, บท):
        return {f"{เล่ม} {บท}.{ต}" for ต in range(1, ข้อสูงสุด[เล่ม][บท] + 1)}

    # ไม้บรรทัดฝั่งต้นฉบับ ⇒ เอาข้อไทยทุกข้อของทั้งเล่มยิงผ่านตารางเทียบ แล้วค่อยจัดกลุ่มตามบทปลายทาง
    # ⚠️ ต้องทำทั้งเล่ม ⛔ ทำทีละบทไม่ได้ เพราะบางที่ข้อข้ามไปอยู่คนละบท เช่น JOL 3 ไทย = JOL 4 ฮีบรู
    # ⚠️ ตอนยิงผ่านตาราง ต้องนับข้อ 0 ด้วย เพราะฝั่งฮีบรูนับหัวเรื่องเพลงสดุดีเป็นข้อจริง
    ไม้บรรทัดต้นฉบับ = {}
    for เล่ม, บททั้งหมด in ข้อสูงสุด.items():
        for บท, สูงสุด in บททั้งหมด.items():
            เริ่ม = 0 if int(บท) in ข้อศูนย์.get(เล่ม, []) else 1
            for ต in range(เริ่ม, สูงสุด + 1):
                คีย์ = f"{เล่ม} {บท}.{ต}"
                ปลาย = ไทยไปต้นฉบับ.get(คีย์, คีย์)
                ไม้บรรทัดต้นฉบับ.setdefault(ปลาย.rsplit(".", 1)[0], set()).add(ปลาย)

    ผล = {}
    for ชื่อฝั่ง, ช่อง in (("ไทย", "บทไทย"), ("ต้นฉบับ", "บท")):
        ตรง, ไม่ตรง, ไม่มีไม้บรรทัด = 0, [], []
        for เล่ม, ของเล่ม in หนังสือ.items():
            for บท, รายการ in ของเล่ม.get(ช่อง, {}).items():
                ของเรา = {(ต if isinstance(ต, int) else ต[0]) for ต in รายการ}
                เรา = {f"{เล่ม} {บท}.{ต}" for ต in ของเรา}
                if ชื่อฝั่ง == "ไทย":
                    if เล่ม not in ข้อสูงสุด or บท not in ข้อสูงสุด[เล่ม]:
                        ไม่มีไม้บรรทัด.append(f"{เล่ม} {บท}")
                        continue
                    ควรมี = ข้อที่ควรมี(เล่ม, บท)
                else:
                    ควรมี = ไม้บรรทัดต้นฉบับ.get(f"{เล่ม} {บท}")
                    if ควรมี is None:
                        ไม่มีไม้บรรทัด.append(f"{เล่ม} {บท}")
                        continue
                if เรา == ควรมี:
                    ตรง += 1
                else:
                    ไม่ตรง.append(
                        {
                            "บท": f"{เล่ม} {บท}",
                            "เราพ่นได้": len(เรา),
                            "ไม้บรรทัดบอก": len(ควรมี),
                            "เรามีเกิน": sorted(เรา - ควรมี)[:6],
                            "เราขาด": sorted(ควรมี - เรา)[:6],
                        }
                    )
        ผล[ชื่อฝั่ง] = {
            "บททั้งหมดที่เราพ่น": ตรง + len(ไม่ตรง) + len(ไม่มีไม้บรรทัด),
            "ตรงกับไม้บรรทัด": ตรง,
            "ไม่ตรง": len(ไม่ตรง),
            "ไม่มีไม้บรรทัดให้เทียบ": ไม่มีไม้บรรทัด,
            "ที่ไม่ตรงทั้งหมด": ไม่ตรง,
        }
    return ผล


