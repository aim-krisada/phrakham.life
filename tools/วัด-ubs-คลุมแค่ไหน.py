def คำที่หลุดหนัก(ชื่อ, ขาด, ทั้งหมดของคำ, ป้าย):
    """เรียงตาม **ส่วนที่หลุด** ⛔ ไม่ใช่จำนวนแถวที่หลุด

    ⇒ เรียงตามจำนวนแถว จะเห็นแต่คำไวยากรณ์ที่โผล่เยอะ ⇒ คำที่เล่มไม่เก็บให้เลยจะถูกกลบ
    """
    for หัวข้อ, เฉพาะเนื้อหา in (("ทุกชนิดคำ", False), (f"เฉพาะ {' '.join(sorted(ชนิดคำเนื้อหา))}", True)):
        แถว = [
            (รูป, n, ทั้งหมดของคำ[รูป])
            for รูป, n in ขาด.items()
            if ทั้งหมดของคำ[รูป] >= ขั้นต่ำที่นับว่าโผล่บ่อย
            and (not เฉพาะเนื้อหา or (ป้าย[รูป][0] or "") in ชนิดคำเนื้อหา)
        ]
        แถว.sort(key=lambda x: (-x[1] / x[2], -x[1]))
        print(f"\n=== {ชื่อ} — คำที่หลุดหนักที่สุด · {หัวข้อ} (โผล่ตั้งแต่ {ขั้นต่ำที่นับว่าโผล่บ่อย} แถวขึ้นไป) ===")
        for รูป, n, ทั้ง in แถว[:15]:
            ชนิด, คำแปล = ป้าย[รูป]
            print(
                f"  {รูป:22s} ไม่คลุม {n:6d} คลุม {ทั้ง - n:6d}  หลุด {100 * n / ทั้ง:6.2f}%"
                f"  ชนิด {ชนิด:10s} คำแปล {คำแปล}"
            )


