def รูปคำในข้อฮีบรู():
    """คืน ที่อยู่ข้อ -> เซตของรูปคำ (เฉพาะพยัญชนะ) ที่อยู่ในข้อนั้นตาม `#02`"""
    ใน = collections.defaultdict(set)
