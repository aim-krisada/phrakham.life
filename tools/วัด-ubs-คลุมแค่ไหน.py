def คำที่ขาด():
    """พิมพ์คำที่ UBS ไม่คลุม เรียงจากที่โผล่บ่อยที่สุด ⇒ เอาไปดูด้วยตาแล้วค่อยแบ่งพวก

    ⛔ สคริปต์นี้ไม่แบ่งพวกให้ ⇒ การแบ่งพวกอยู่ในเอกสาร และมาจากการดูรายการนี้ด้วยตา
    """
    print("\n########## ข้อ ③ คำที่ UBS ไม่คลุม ##########")
    รูปในเล่ม = {
        "ฮีบรู": {เฉพาะพยัญชนะ(x[0]) for x in อ่านพจนานุกรม(พจนานุกรมฮีบรู)[1]},
        "กรีก": {x[0] for x in อ่านพจนานุกรม(พจนานุกรมกรีก)[1]},
    }
    # ⇒ ชุดรูปคำแบบไม่ตัดสระ ⇒ ใช้แยก "ตรงเป๊ะ" ออกจาก "ตรงแค่พยัญชนะ" ⛔ ไม่ให้ช่องเดียวตอบว่า มี เฉย ๆ
    รูปเป๊ะในเล่ม = {
        "ฮีบรู": {x[0] for x in อ่านพจนานุกรม(พจนานุกรมฮีบรู)[1]},
        "กรีก": {x[0] for x in อ่านพจนานุกรม(พจนานุกรมกรีก)[1]},
    }
    for ชื่อ, ผล in (("ฮีบรู", คลุมฮีบรู()), ("กรีก", คลุมกรีก())):
        ตามชนิด = collections.Counter()
        for _, _, ชนิด, _, สถานะ in ผล:
            if not เป็นการคลุม(สถานะ):
                ตามชนิด[ชนิด or "(ไม่มีชนิด)"] += 1
        พิมพ์ตาราง(f"{ชื่อ} — แถวที่ไม่คลุม แยกตามชนิดคำที่ MACULA ติดป้ายไว้", ตามชนิด, "แถวที่ไม่คลุม")
        ขาด = collections.Counter()
        ป้าย = {}
        เหตุ = collections.defaultdict(collections.Counter)
        ทั้งหมดของคำ = collections.Counter()
        for _, รูป, ชนิด, คำแปล, สถานะ in ผล:
            ทั้งหมดของคำ[รูป] += 1
            if เป็นการคลุม(สถานะ):
                continue
            ขาด[รูป] += 1
            เหตุ[รูป][สถานะ[0]] += 1
            ป้าย.setdefault(รูป, (ชนิด, คำแปล))
        รวมขาด = sum(ขาด.values())
        print(f"\n=== {ชื่อ} — คำที่ไม่คลุม 200 อันดับแรก (ไม่คลุมรวม {รวมขาด} แถว · {len(ขาด)} คำ) ===")
        print("  ช่อง เหตุ ⇒ ตัวอักษรตรงกับตารางข้อ ② · ช่อง คลุมบ้าง ⇒ คำนี้มีที่อื่นที่คลุมได้กี่แถว")
        print("  ช่อง ในเล่ม ⇒ ตรงเป๊ะ = รูปคำเหมือนกันทั้งสระ · ตรงแค่พยัญชนะ = ⛔ อาจเป็นคนละคำ · ไม่มี")
        สะสม = 0
        for i, (รูป, n) in enumerate(ขาด.most_common(200), 1):
            สะสม += n
            ชนิด, คำแปล = ป้าย[รูป]
            เหตุหลัก = "".join(sorted(เหตุ[รูป]))
            เทียบ = เฉพาะพยัญชนะ(รูป) if ชื่อ == "ฮีบรู" else รูป
            if รูป in รูปเป๊ะในเล่ม[ชื่อ]:
                มีในเล่ม = "ตรงเป๊ะ       "
            elif เทียบ in รูปในเล่ม[ชื่อ]:
                มีในเล่ม = "ตรงแค่พยัญชนะ"
            else:
                มีในเล่ม = "ไม่มี         "
            print(
                f"  {i:3d}. {รูป:22s} {n:7d}  เหตุ {เหตุหลัก:4s} คลุมบ้าง {ทั้งหมดของคำ[รูป] - n:6d}"
                f"  ในเล่ม {มีในเล่ม}  ชนิด {ชนิด:10s} คำแปล {คำแปล}"
            )
        print(f"  ⇒ 200 อันดับแรกรวมกัน {สะสม} แถว = {100 * สะสม / รวมขาด:.2f}% ของที่ไม่คลุมทั้งหมด")
        คำที่หลุดหนัก(ชื่อ, ขาด, ทั้งหมดของคำ, ป้าย)
        if ชื่อ == "ฮีบรู":
            เล่มฮีบรูมีคำนี้จริงไหม()
