def คลุมฮีบรู():
    """ผลรายแถวฝั่งฮีบรู เป็น (ที่อยู่คำ, รูปคำ, ชนิดคำ, คำแปล, สถานะ)

    ฝั่งฮีบรูมีสองทางเดินไปหาความหมาย และสองทางให้ผลไม่เท่ากัน ⇒ ลองทั้งสองทาง
    ทางที่ 1 ระดับคำ ⇒ ตารางดัชนี `MARBLELinks` ชี้คำต่อคำ แต่ตารางนี้ไม่ได้ลงทุกคำ
    ทางที่ 2 ระดับข้อ ⇒ พจนานุกรมเก็บรายชื่อข้อของแต่ละความหมายไว้เอง ⇒ ตรงข้อและตรงรูปคำ = ถือว่าคลุม
    ⇒ สถานะบอกด้วยว่าคลุมด้วยทางไหน ⇒ คนอ่านเห็นเองว่าทางไหนให้ของมากกว่า
    """
    ดัชนี, _ = อ่านดัชนีฮีบรู()
    ท = ทะเบียนความหมายฮีบรู()
    รายข้อ = ความหมายรายข้อฮีบรู()
    ผล = []
    for รหัส, ที่อยู่, lemma, ชนิด, คำแปล in อ่านตาราง(
        ตารางฮีบรู, ["xml:id", "ref", "lemma", "class", "gloss"]
    ):
        ทาง1 = False
        ล = ดัชนี.get(รหัส)
        if ล:
            _, lemma_ubs, ลำดับ, _ = ล.split(":", 3)
            รายการ = ท.get(รูปเดียวกัน(lemma_ubs))
            ทาง1 = bool(รายการ) and int(ลำดับ) < len(รายการ)
        ชั้นในข้อ = {
            x[1] for x in รายข้อ.get(ที่อยู่.split("!")[0], ()) if x[0] == เฉพาะพยัญชนะ(lemma)
        }
        if ทาง1:
            สถานะ = "ก คลุม ⇒ ทางที่ 1 ตารางดัชนีชี้ให้ถึงระดับคำ"
        elif len(ชั้นในข้อ) == 1:
            สถานะ = "ข คลุม ⇒ ทางที่ 2 ข้อนี้มีความหมายของคำนี้อยู่ชั้นเดียว"
        elif ชั้นในข้อ:
            สถานะ = "ค ครึ่งทาง ⇒ ข้อนี้มีความหมายของคำนี้หลายชั้น เลือกไม่ได้"
        else:
            สถานะ = "ง ไม่คลุม ⇒ ไม่มีทางไหนให้ความหมายเลย"
        ผล.append((ที่อยู่, รูปเดียวกัน(lemma), ชนิด, คำแปล, สถานะ))
    return ผล


def คลุมกรีก():
    """คืนรายการผลรายแถวฝั่งกรีก รูปแบบเดียวกับ `คลุมฮีบรู()`"""
    ชี้, _ = ความหมายที่ชี้มาถึงคำกรีก()
    ผล = []
    for ที่อยู่, lemma, ชนิด, คำแปล in อ่านตาราง(ตารางกรีก, ["ref", "lemma", "class", "gloss"]):
        รูป = รูปเดียวกัน(lemma)
        ชุด = ชี้.get(ที่อยู่)
        if not ชุด:
            สถานะ = "ง ไม่คลุม ⇒ ไม่มีความหมายไหนชี้มาที่คำนี้"
        elif รูป in {x[0] for x in ชุด}:
            สถานะ = "ก คลุม ⇒ มีความหมายชี้มาที่คำนี้ตรง ๆ"
        else:
            สถานะ = "ค ครึ่งทาง ⇒ มีความหมายชี้มา แต่เป็นคนละคำ ใช้ไม่ได้"
        ผล.append((ที่อยู่, รูป, ชนิด, คำแปล, สถานะ))
    return ผล


def เป็นการคลุม(สถานะ):
    """สถานะที่ขึ้นต้นด้วย `ก` หรือ `ข` เท่านั้นคือคลุม ⇒ `ค` ครึ่งทาง กับ `ง` ไม่คลุม ไม่นับ"""
    return สถานะ.startswith(("ก คลุม", "ข คลุม"))


def สรุปคลุม(ชื่อ, ผล, กรองบท=None):
    """พิมพ์ 2 แบบคู่กัน ⇒ นับทุกครั้งที่โผล่ และนับคำไม่ซ้ำ"""
    if กรองบท:
        ผล = [x for x in ผล if x[0].split("!")[0].rsplit(":", 1)[0] == กรองบท]
    นับโผล่ = collections.Counter(x[4] for x in ผล)
    พิมพ์ตาราง(f"{ชื่อ} — แบบนับทุกครั้งที่โผล่", นับโผล่, "แถวคำ")

    คลุมของคำ = collections.defaultdict(bool)
    for _, รูป, _, _, สถานะ in ผล:
        คลุมของคำ[รูป] = คลุมของคำ[รูป] or เป็นการคลุม(สถานะ)
    นับคำ = collections.Counter(
        "ก คลุม ⇒ มีความหมายให้อย่างน้อยหนึ่งที่" if v else "ข ไม่คลุมเลยสักที่" for v in คลุมของคำ.values()
    )
    พิมพ์ตาราง(f"{ชื่อ} — แบบนับคำไม่ซ้ำ (รูปพจนานุกรม)", นับคำ, "คำ")

    # ผู้อ่านกดที่ **คำ** ไม่ได้กดที่ชิ้นส่วนคำ ⇒ ฝั่งฮีบรูซอยคำนำหน้าเป็นคนละแถว
    # ⇒ จึงนับอีกแบบที่ระดับที่อยู่คำ (`ref`) ⇒ ที่อยู่ไหนมีชิ้นที่คลุมอย่างน้อยหนึ่งชิ้น ถือว่าคลุม
    คลุมของที่อยู่ = collections.defaultdict(bool)
    for ที่อยู่, _, _, _, สถานะ in ผล:
        คลุมของที่อยู่[ที่อยู่] = คลุมของที่อยู่[ที่อยู่] or เป็นการคลุม(สถานะ)
    นับที่อยู่ = collections.Counter(
        "ก คลุม ⇒ กดแล้วเจอความหมาย" if v else "ข กดแล้วไม่เจอ" for v in คลุมของที่อยู่.values()
    )
    พิมพ์ตาราง(f"{ชื่อ} — แบบนับที่ตำแหน่งคำที่ผู้อ่านกด", นับที่อยู่, "ตำแหน่งคำ")


