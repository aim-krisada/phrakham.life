    ท = ทะเบียนความหมายฮีบรู()
    นับ = collections.Counter()
    for รหัส, lemma_มาคูลา in อ่านตาราง(ตารางฮีบรู, ["xml:id", "lemma"]):
        ล = ดัชนี.get(รหัส)
        if not ล:
            continue
        lemma_ubs = รูปเดียวกัน(ล.split(":")[1])
        if lemma_ubs not in ท:
            นับ["ค ดัชนีบอกคำที่ไม่มีในเล่ม"] += 1
        elif เฉพาะพยัญชนะ(lemma_ubs) == เฉพาะพยัญชนะ(lemma_มาคูลา):
            นับ["ก รูปคำตรงกันเป๊ะ"] += 1
        else:
            นับ["ข รูปคำต่างกัน"] += 1
    พิมพ์ตาราง("ฝั่งฮีบรู — คำที่ดัชนีชี้ ตรงกับคำใน #02 ไหม", นับ, "แถวที่ต่อได้")

    print("\n--- ⛔ กับดัก ช่อง `sdbh` ของ #02 หน้าตาเหมือน LEXID แต่คนละระบบ ---")
    ทะเบียนlexid = {}
    for รูป, lexid, _, _ in อ่านพจนานุกรม(พจนานุกรมฮีบรู)[1]:
        ทะเบียนlexid[lexid] = รูป
    นับ = collections.Counter()
    ตัวอย่าง = []
    for lemma_มาคูลา, sdbh in อ่านตาราง(ตารางฮีบรู, ["lemma", "sdbh"]):
        if not sdbh:
            continue
        มี = [x for x in sdbh.split() if x in ทะเบียนlexid]
        if not มี:
            นับ["ค ไม่มีเลขนี้ในเล่ม UBS"] += 1
        elif any(เฉพาะพยัญชนะ(ทะเบียนlexid[x]) == เฉพาะพยัญชนะ(lemma_มาคูลา) for x in มี):
            นับ["ก มีเลขนี้ และรูปคำตรงกัน"] += 1
        else:
            นับ["ข มีเลขนี้ แต่รูปคำคนละคำ"] += 1
            if len(ตัวอย่าง) < 6:
                ตัวอย่าง.append((lemma_มาคูลา, มี[0], ทะเบียนlexid[มี[0]]))
    พิมพ์ตาราง("ช่อง `sdbh` ของ #02 เอาไปเปิดเล่ม UBS ตรง ๆ ได้ไหม", นับ, "แถวที่มีค่า sdbh")
    for ก, เลข, ข in ตัวอย่าง:
        print(f"  ตัวอย่างที่หลุด: #02 ว่า {ก}  ⇒ เลข {เลข} ในเล่ม UBS คือคำ {ข}")
    print("  ⇒ ⛔ ห้ามใช้ช่อง `sdbh` เป็นกุญแจ ⇒ ต้องเดินผ่านตารางดัชนี")

    print("\n--- ฝั่งฮีบรู ทางที่ 2 ⇒ ช่อง `LEXReferences` ของ #10 ต่อกับช่อง `ref` ของ #02 ระดับข้อ ---")
    เทสเลขเล่มฮีบรู()

    print("\n--- ฝั่งกรีก ⇒ ช่อง `LEXReferences` ของ #10 ต่อกับช่อง `ref` ของ #01 ---")
    ชี้, นับที่อยู่ = ความหมายที่ชี้มาถึงคำกรีก()
    คำกรีก = {ref: รูปเดียวกัน(lemma) for ref, lemma in อ่านตาราง(ตารางกรีก, ["ref", "lemma"])}
    print(f"  ที่อยู่ที่พจนานุกรมกรีกให้ไว้ทั้งเล่ม       {sum(นับที่อยู่.values()):9d} จุด")
    print(f"  ⇒ แปลงเป็นที่อยู่คำแบบ #01 ได้            {นับที่อยู่['แปลงได้']:9d}")
    print(f"  ⇒ แปลงไม่ได้ (ยาวไม่ใช่ 14 หลัก · ตำแหน่งคี่) {นับที่อยู่['แปลงไม่ได้']:9d}")
    นับ = collections.Counter()
    for ref, ชุด in ชี้.items():
        if ref not in คำกรีก:
            นับ["ค ไม่มีคำที่ตำแหน่งนั้นใน #01"] += 1
        elif คำกรีก[ref] in {x[0] for x in ชุด}:
            นับ["ก รูปคำตรงกันเป๊ะ"] += 1
        else:
            นับ["ข รูปคำต่างกัน"] += 1
    พิมพ์ตาราง("ฝั่งกรีก — ที่อยู่ที่แปลงแล้ว ชี้ถูกคำไหม", นับ, "ที่อยู่ไม่ซ้ำ")
    เสี่ยงเลื่อนแล้วชนคำเดียวกัน()

    print("\n--- ⚠️ ต่อด้วยรหัส Strong หรือเปล่า ---")
    print("  ⛔ ไม่ได้ต่อด้วยรหัส Strong เลย ทั้งสองฝั่ง")
    print("  ฝั่งฮีบรูทางที่ 1 ต่อด้วยรหัสประจำคำ (`ID` ↔ `xml:id`) ⇒ เป็นรหัสตำแหน่งคำ ไม่ใช่รหัสศัพท์")
    print("  ฝั่งฮีบรูทางที่ 2 ต่อด้วยที่อยู่ของข้อ แล้วยืนยันด้วยรูปคำ ⇒ ก็ไม่ใช่รหัสศัพท์")
