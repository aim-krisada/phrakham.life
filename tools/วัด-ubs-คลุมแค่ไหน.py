def รูปเดียวกัน(s):
    return unicodedata.normalize("NFC", s or "")


def เฉพาะพยัญชนะ(s):
    """ตัดสระและเครื่องหมายเสียงฮีบรูออก ⇒ `#02` เขียนมีสระ ส่วน `#10` เขียนไม่มีสระ

    เทียบตัวอักษรตรง ๆ จึงไม่ตรง ต้องถอดเครื่องหมายก่อน (ช่วง U+0591 ถึง U+05C7)
    """
    ย = unicodedata.normalize("NFD", s or "")
    return "".join(c for c in ย if not (0x0591 <= ord(c) <= 0x05C7))


def พิมพ์ตาราง(หัวข้อ, นับ, หน่วย, ทศนิยม=2):
    รวม = sum(นับ.values()) or 1
    print(f"\n=== {หัวข้อ} ===")
    for k, n in sorted(นับ.items()):
        print(f"  {k:56s}{n:9d}  {100 * n / รวม:6.{ทศนิยม}f}%")
    print(f"  {'รวม ' + หน่วย:56s}{sum(นับ.values()):9d}")


def อ่านตาราง(ไฟล์, ชื่อช่อง):
    """คืนค่าทีละแถวเฉพาะช่องที่ขอ ⇒ ไม่โหลดทั้งตารางเข้าหน่วยความจำ"""
    with io.open(ไฟล์, encoding="utf-8") as f:
        r = csv.reader(f, delimiter="\t")
        หัว = next(r)
        ดัชนี = [หัว.index(c) for c in ชื่อช่อง]
        for row in r:
            if len(row) > max(ดัชนี):
                yield [row[i] for i in ดัชนี]


