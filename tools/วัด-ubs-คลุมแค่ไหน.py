def ล็อกความหมาย(ไฟล์, ชื่อ, จำนวนคำ=10):
    """ที่อยู่หนึ่งอัน ถูกความหมายกี่ชั้นของคำเดียวกันอ้างถึง ⇒ 1 ชั้น = ล็อกให้แล้ว

    ⭐ เทสนี้ไม่ต้องแปลงที่อยู่เลย ⇒ ดูข้างในเล่ม UBS อย่างเดียว
       จึงไม่ปนกับความคลาดของกฎคูณสองฝั่งกรีก
    """
    _, ความหมาย = อ่านพจนานุกรม(ไฟล์)
    ของคำ = collections.defaultdict(list)
    for รูป, lexid, คำแปล, ที่อยู่ทั้งหมด in ความหมาย:
        ของคำ[รูป].append((lexid, คำแปล, ที่อยู่ทั้งหมด))

    รวม = collections.Counter()
    for รูป, ชั้น in ของคำ.items():
        if len(ชั้น) < 2:
            continue
        นับที่อยู่ = collections.Counter()
        for _, _, ที่อยู่ทั้งหมด in ชั้น:
            for t in set(ที่อยู่ทั้งหมด):
                นับที่อยู่[t] += 1
        for n in นับที่อยู่.values():
            รวม["ก ที่อยู่นี้มีความหมายเดียว ⇒ ล็อกให้แล้ว" if n == 1 else "ข ที่อยู่นี้มีมากกว่าหนึ่งความหมาย"] += 1
    พิมพ์ตาราง(f"{ชื่อ} — คำที่มีหลายความหมายทั้งเล่ม", รวม, "ที่อยู่")
    ค่าเฉลี่ยทั้งเล่ม = 100 * รวม["ก ที่อยู่นี้มีความหมายเดียว ⇒ ล็อกให้แล้ว"] / (sum(รวม.values()) or 1)

    เลือก = sorted(
        (x for x in ของคำ.items() if len(x[1]) >= 5),
        key=lambda x: -sum(len(t) for _, _, t in x[1]),
    )[:จำนวนคำ]
    print(f"\n--- {ชื่อ} {จำนวนคำ} คำที่มีหลายความหมายและโผล่บ่อยที่สุด ---")
    for รูป, ชั้น in เลือก:
        นับที่อยู่ = collections.Counter()
        for _, _, ที่อยู่ทั้งหมด in ชั้น:
            for t in set(ที่อยู่ทั้งหมด):
                นับที่อยู่[t] += 1
        เดี่ยว = sum(1 for n in นับที่อยู่.values() if n == 1)
        รวมที่ = len(นับที่อยู่) or 1
        print(f"  {รูป:20s} {len(ชั้น):3d} ความหมาย · {รวมที่:6d} ที่อยู่ · ล็อกเดี่ยว {100 * เดี่ยว / รวมที่:6.2f}%")
        # ยกของจริงให้ดู 2 ชั้นแรกที่มีที่อยู่ ⇒ เห็นว่าชั้นต่างกันอ้างคนละข้อ
        ยก = [(l, g, t) for l, g, t in ชั้น if t][:2]
        for l, g, t in ยก:
            print(f"      ชั้น {l} {g} ⇒ ตัวอย่างข้อ {sorted(t)[:3]}")

    print(f"\n--- {ชื่อ} คำแกนศาสนาที่ผู้อ่านจะกดอ่านจริง · ทุกคำในรายชื่อ ⛔ ไม่ตัดแถวไหนออก ---")
    ต่ำกว่าค่าเฉลี่ย = 0
    ทั้งหมดที่ยกมา = 0
    for คำ in คำแกนศาสนา[ชื่อ]:
        ชั้น = ของคำ.get(รูปเดียวกัน(คำ))
        if not ชั้น:
            print(f"  {คำ:20s} ⛔ ไม่มีคำนี้ในเล่ม")
            continue
        นับที่อยู่ = collections.Counter()
        for _, _, ที่อยู่ทั้งหมด in ชั้น:
            for t in set(ที่อยู่ทั้งหมด):
                นับที่อยู่[t] += 1
        เดี่ยว = sum(1 for n in นับที่อยู่.values() if n == 1)
        รวมที่ = len(นับที่อยู่) or 1
        ล็อกเดี่ยว = 100 * เดี่ยว / รวมที่
        ทั้งหมดที่ยกมา += 1
        ต่ำกว่า = ล็อกเดี่ยว < ค่าเฉลี่ยทั้งเล่ม
        ต่ำกว่าค่าเฉลี่ย += ต่ำกว่า
        ป้าย = "ต่ำกว่าค่าเฉลี่ย" if ต่ำกว่า else "⛔ ไม่ต่ำกว่าค่าเฉลี่ย"
        print(f"  {คำ:20s} {len(ชั้น):3d} ความหมาย · {รวมที่:6d} ที่อยู่ · ล็อกเดี่ยว {ล็อกเดี่ยว:6.2f}%  {ป้าย}")
    print(
        f"  ⇒ ต่ำกว่าค่าเฉลี่ยทั้งเล่ม ({ค่าเฉลี่ยทั้งเล่ม:.2f}%)"
        f" {ต่ำกว่าค่าเฉลี่ย} คำ จาก {ทั้งหมดที่ยกมา} คำ"
    )


