/**
 * ⭐ ช่อง `เครื่องหมาย` (ช่วง) ⇒ รูปเดิมของช่อง `เน้น` (รายคำ) ⇒ `{<ข้อ>: {<ลำดับ>: <รหัส>}}` ⇒ เฉพาะ 6 ชนิด
 *   ⇒ กางเองในด่าน ⛔ ไม่ใช้ `app/utils/เครื่องหมายบนคำ.ts` ⇒ ด่านที่ใช้โค้ดเดียวกับหน้าเว็บคือด่านที่เขียวพร้อมกับของที่พัง
 */
function กางหกชนิด(ไฟล์) {
  if (!ไฟล์.เครื่องหมาย) return undefined
  const ผล = {}
  const นับคำ = (v) => ไฟล์.ชั้น?.คำกรีก?.[String(v)]?.length ?? 0
  for (const r of หกชนิด) {
    for (const เครื่อง of ไฟล์.เครื่องหมาย[r] ?? []) {
      const เลข = เครื่อง.filter((x) => typeof x === 'number')
      const ท่อน = []
      if (เลข.length === 2) ท่อน.push([เลข[0], เลข[1], เลข[0], เลข[1]])
      else for (let i = 0; i + 3 < เลข.length; i += 4) ท่อน.push(เลข.slice(i, i + 4))
      for (const [v1, w1, v2, w2] of ท่อน)
        for (let v = v1; v <= v2; v++)
          for (let w = v === v1 ? w1 : 0; w <= (v === v2 ? w2 : นับคำ(v) - 1); w++) {
            ผล[v] ??= {}
            if (!(ผล[v][w] ?? '').includes(r)) ผล[v][w] = (ผล[v][w] ?? '') + r
          }
    }
  }
  return Object.keys(ผล).length ? ผล : undefined
}

