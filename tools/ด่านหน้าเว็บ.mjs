    // ⛔ ตัวที่กว้างหรือสูงเป็นศูนย์ = ยังไม่ถูกวาด ⇒ ⛔ ไม่ใช่ปุ่มเล็ก ⇒ ข้ามไป
    ตัวควบคุม: [...document.querySelectorAll('a[href], button, input, select, textarea')]
      .map((el) => ({ el, r: el.getBoundingClientRect() }))
      .filter((x) => x.r.width > 0 && x.r.height > 0)
