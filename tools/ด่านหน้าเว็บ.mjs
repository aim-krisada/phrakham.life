// ⛔ ชื่อไฟล์ต้นทาง **ไม่ได้แปลงมาจากที่อยู่** — ที่อยู่เป็นอังกฤษ ชื่อไฟล์เป็นไทย
//   ⇒ เจ้าของคู่นี้คือ `tools/หน้าที่ตรวจ.mjs` ⛔ ไม่เดาเอาจากที่อยู่
function อ่านไฟล์ต้นทาง(ไฟล์) {
  const เนื้อ = readFileSync(ไฟล์, 'utf8')
  // ลิงก์แบบ markdown `[คำ](ที่อยู่)`
  // ⭐ ใบ #172 ⇒ ลิงก์ไปหน้าอื่นในเว็บนี้เขียนในไฟล์ว่า `/sources` ⇒ บนหน้าต้องเป็น ฐาน + `/sources` (`ProseA.vue` ต่อให้)
  //   ⇒ เทียบกับ `/phrakham/sources` ⇒ ⛔ ต่อฐานไม่ได้ = หน้าเว็บมี `/sources` ⇒ ไม่ตรง ⇒ ข้อ ② แดงเอง ⛔ ผ่อน
  const ทางฐาน = new URL(ฐาน + '/').pathname.replace(/\/+$/, '')
  const แบบมาร์กดาวน์ = [...เนื้อ.matchAll(/\]\(([^)\s]+)\)/g)].map((m) => (/^\/(?!\/)/.test(m[1]) ? ทางฐาน + m[1] : m[1]))
  // ที่อยู่ที่โผล่เปล่า ๆ ในถ้อยคำ — GFM แปลงให้เป็นลิงก์เอง
  const แบบเปล่า = [...เนื้อ.matchAll(/(?<![(\]])\bhttps?:\/\/[^\s<)"]+/g)].map((m) => m[0])
  return {
    ไฟล์,
    เนื้อ,
    ลิงก์: new Set([...แบบมาร์กดาวน์, ...แบบเปล่า]),
    กล่อง: (เนื้อ.match(/<details/g) || []).length,
  }
}

