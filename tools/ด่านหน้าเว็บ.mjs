    // ⭐ **ข้อแรกของบทแสดงเป็น `บท:ข้อ`** (ใบงาน v3/phrakham#87) ⇒ ตัดหน้าทวิภาคทิ้งก่อนเทียบ
    //   ⇒ เจ้าของรูปแบบที่ตาเห็นคือ `app/components/หน้าอ่าน.vue` (ตัวแปร `ป้าย`) ⛔ ไม่จดซ้ำที่นี่
