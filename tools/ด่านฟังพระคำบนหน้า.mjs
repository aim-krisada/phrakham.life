/**
 * เปิดแท็บใหม่พร้อม **ตัวดักการจราจร** ⇒ เก็บทุกที่อยู่ที่เบราว์เซอร์ขอจริง
 * `พัง` ⇒ ชื่อของพังที่ยัดเข้าไป **เฉพาะโหมดพิสูจน์** ⇒ โหมดปกติ ⛔ ไม่ยัดอะไรเลย
 */
async function เปิดแท็บ(ขนาด = { width: 1280, height: 900 }, เตรียม, พัง = []) {
  const บริบท = await เบราว์เซอร์.newContext({ viewport: ขนาด })
  const ที่ขอ = []
  บริบท.on('request', (r) => ที่ขอ.push(r.url()))
  if (เตรียม) await บริบท.addInitScript(เตรียม)
  for (const ชื่อ of ทดสอบตัวเอง ? พัง : []) {
    const ชิ้น = ของพัง[ชื่อ]
    if (typeof ชิ้น === 'function') await บริบท.addInitScript(ชิ้น)
    else {
      await บริบท.addInitScript((กฎ) => {
        window.addEventListener('DOMContentLoaded', () => {
          const st = document.createElement('style')
          st.textContent = กฎ
          document.head.appendChild(st)
        })
      }, ชิ้น)
    }
  }
  const แท็บ = await บริบท.newPage()
  return { บริบท, แท็บ, ที่ขอ }
}

async function เปิด(แท็บ, ทาง) {
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, {
    timeout: 30000,
  })
  const c = new URL(`${ฐาน}${ทาง}`).searchParams.get('c')
  if (c) await แท็บ.waitForSelector(`#บท-${c}`, { timeout: 15000 })
  await แท็บ.waitForTimeout(500)
}

/**
 * ⭐ **รอจนได้สภาพที่ต้องการ หรือจนหมดเวลา** ⛔ ไม่ใช่นอนรอเป็นมิลลิวินาทีตายตัว
 *   ⇒ เหตุผลอยู่ที่ `docs/ที่ค้างอยู่.md` หัวข้อ *ด่านที่นอนรอเป็นมิลลิวินาทีคือด่านที่จะโกหกวันหนึ่ง*
 */
async function รอจน(เงื่อนไข, นาน = 15000) {
  const ถึง = Date.now() + นาน
  for (;;) {
    if (await เงื่อนไข()) return true
    if (Date.now() > ถึง) return false
    await new Promise((r) => setTimeout(r, 150))
  }
}

