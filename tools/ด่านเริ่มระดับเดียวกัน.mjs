/**
 * ข้อที่ทุกคอลัมน์ขึ้นย่อหน้า **ที่ต้นข้อเดียวกัน** ⇒ อ่านจากซองรอยของหลังบ้าน ⛔ ไม่อ่านจากหน้า
 *   ⇒ ฉบับที่มีของตัวเอง ⇒ รอยที่ต้นข้อ (`หลังอักษร` = 0)
 *   ⇒ ฉบับที่ยืม ⇒ รอยของต้นแบบ (คอลัมน์ซ้ายสุดที่มีของตัวเอง) เลื่อนไปข้อถัดไปที่ฉบับนั้นมี (ใบ #106)
 *   ⇒ ⛔ ไม่นับข้อแรกของบท ⇒ ทุกคอลัมน์เริ่มตรงกันที่นั่นอยู่แล้ว ⇒ นับแล้วด่านเขียวง่ายเกินจริง
 */
async function ข้อที่ต้องเริ่มตรงกัน(ฉบับ) {
  const ของเล่ม = await (await fetch(`${ฐาน}/api/book/${เล่ม}.json`)).json()
  const ของบท = await (await fetch(`${ฐาน}/api/chapter/${เล่ม}/${บท}.json`)).json()
  const ไม่มี = ของเล่ม.ฉบับที่ยังไม่มีย่อหน้า || {}
  const ต้นแบบ = ฉบับ.find((ฉ) => !(ฉ in ไม่มี)) || 'TCV'
  const ชุด = ฉบับ.map((ฉ) => {
    const เรา = Object.keys(ของบท.ชั้น[ฉ] || {}).map(Number).sort((a, b) => a - b)
    if (ฉ in ไม่มี) {
      return new Set((ของบท.ย่อหน้า?.[ต้นแบบ] || []).map((ร) => เรา.find((n) => n >= ร.ข้อ)).filter((n) => n !== undefined))
    }
    return new Set((ของบท.ย่อหน้า?.[ฉ] || []).filter((ร) => ร.หลังอักษร === 0).map((ร) => ร.ข้อ))
  })
  const แรก = Math.min(...Object.keys(ของบท.ชั้น[ฉบับ[0]] || {}).map(Number))
  return [...ชุด[0]].filter((v) => v !== แรก && ชุด.every((s) => s.has(v))).sort((a, b) => a - b)
}

/** ระดับบนของบรรทัดแรกของข้อ v ในแต่ละคอลัมน์ ⇒ ⛔ หนีบไว้ที่บทที่ขอ */
const ระดับของข้อ = (แท็บ, ฉบับ, ข้อ) =>
  แท็บ.evaluate(
    ([b, ฉบับ, ข้อ]) =>
      ข้อ.map((v) =>
        ฉบับ.map((ฉ) => {
          const el =
            document.querySelector(`.pk-ตัวบท [data-ฉบับ="${ฉ}"] .pk-ข้อไหล[data-ข้อ="${b}:${v}"]`) ||
            document.querySelector(`.pk-ตัวบท .pk-ข้อ[data-ข้อ="${b}:${v}"] [data-ฉบับ="${ฉ}"]`)
          if (!el) return null
          // ⭐ วัดที่ **บรรทัดแรกของตัวหนังสือจริง** ⛔ ไม่ใช่ขอบกล่อง ⇒ กล่องอยู่ที่เดิมแต่ตัวหนังสือถูกดันลงได้
          //   ⇒ ข้ามเลขข้อ (ตัวยก) กับชื่อฉบับที่ซ่อนไว้ให้โปรแกรมอ่านหน้าจอ ⇒ สองอย่างนั้นไม่ใช่ตัวบท
          const เดิน = document.createTreeWalker(el, NodeFilter.SHOW_TEXT)
          for (let n = เดิน.nextNode(); n; n = เดิน.nextNode()) {
            if (!n.nodeValue.trim() || n.parentElement.closest('.pk-เลขข้อ, .pk-เฉพาะเสียง')) continue
            const ช่วง = document.createRange()
            ช่วง.selectNodeContents(n)
            const r = [...ช่วง.getClientRects()].find((x) => x.width > 0)
            if (r) return Math.round((r.top + scrollY) * 10) / 10
          }
          return null
        }),
      ),
    [บท, ฉบับ, ข้อ],
  )

/** ขอบซ้ายของกล่องแรกของแต่ละฉบับในบทที่ขอ ⇒ ใช้ดูว่าวางเคียงกันจริงไหม */
const ขอบซ้ายของฉบับ = (แท็บ, ฉบับ) =>
  แท็บ.evaluate(
    ([b, ฉบับ]) =>
      ฉบับ.map((ฉ) => {
        const el =
          document.querySelector(`.pk-ตัวบท [data-ฉบับ="${ฉ}"]:has(.pk-ข้อไหล[data-ข้อ^="${b}:"])`) ||
          document.querySelector(`.pk-ตัวบท .pk-ข้อ[data-ข้อ^="${b}:"] [data-ฉบับ="${ฉ}"]`)
        return Math.round(el?.getBoundingClientRect().left ?? -1)
      }),
    [บท, ฉบับ],
  )

/** ตัวหนังสือของฉบับหนึ่ง เฉพาะบทที่ขอ ⇒ ทิ้งช่องว่าง เลขข้อ และชื่อฉบับสำหรับเสียง */
const ตัวหนังสือของฉบับ = (แท็บ, ฉ) =>
  แท็บ.evaluate(
    ([b, ฉ]) => {
      const หมุด = document.getElementById(`บท-${b}`)
      const หมุดถัด = [...document.querySelectorAll('.pk-ตัวบท h2.pk-หมุดบท')].find(
        (h) => หมุด.compareDocumentPosition(h) & Node.DOCUMENT_POSITION_FOLLOWING,
      )
      const ในบท = (el) =>
        หมุด.compareDocumentPosition(el) & Node.DOCUMENT_POSITION_FOLLOWING &&
        (!หมุดถัด || el.compareDocumentPosition(หมุดถัด) & Node.DOCUMENT_POSITION_FOLLOWING)
      return [...document.querySelectorAll(`.pk-ตัวบท [data-ฉบับ="${ฉ}"]`)]
        .filter(ในบท)
        .map((el) => {
          const ส = el.cloneNode(true)
          for (const x of ส.querySelectorAll('.pk-เลขข้อ, .pk-เฉพาะเสียง, .pk-ยังไม่มีย่อหน้า')) x.remove()
          return ส.textContent || ''
        })
        .join('')
        .replace(/\s+/gu, '')
    },
    [บท, ฉ],
  )

