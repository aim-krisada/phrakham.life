async function ตรวจย่อหน้า(สภาพ, พัง) {
  const ตก = []
  const ป้าย = ป้ายสภาพ(สภาพ)
  const ข้อ = await ข้อที่ต้องเริ่มตรงกัน(สภาพ.ฉบับ)
  if (ข้อ.length < 3) ตก.push(`① ${ป้าย} ⇒ ซองมีจุดที่ทุกคอลัมน์ขึ้นย่อหน้าพร้อมกันแค่ ${ข้อ.length} จุด ⇒ บทนี้ใช้พิสูจน์ไม่ได้`)

  // ③ ของอ้างอิง ⇒ แบบไหลต่อเนื่อง
  const อ้างอิง = {}
  if (สภาพ.ตรวจตัวบท) {
    const { ctx, แท็บ, พร้อม } = await เปิด({ ...สภาพ, จัดวาง: 'ไหลต่อเนื่อง' }, ตก)
    try {
      if (พร้อม) for (const ฉ of สภาพ.ฉบับ) อ้างอิง[ฉ] = await ตัวหนังสือของฉบับ(แท็บ, ฉ)
    } finally {
      await ctx.close()
    }
  }

  const { ctx, แท็บ, พร้อม } = await เปิด(สภาพ, ตก)
  try {
    if (!พร้อม) return ตก
    await ยัด(แท็บ, พัง)
    // ⭐ คอลัมน์ต้องวางเคียงกันจริง ⇒ ห่อลงแถวใหม่เมื่อไร ⛔ ไม่ใช่การเทียบระดับแล้ว ⇒ **แดง ⛔ ไม่ข้ามเงียบ**
    const ซ้าย = await ขอบซ้ายของฉบับ(แท็บ, สภาพ.ฉบับ)
    if (new Set(ซ้าย).size !== สภาพ.ฉบับ.length) ตก.push(`① ${ป้าย} ⇒ คอลัมน์ไม่ได้วางเคียงกัน (ขอบซ้าย [${ซ้าย.join(' ')}]) ⇒ วัดข้อนี้ไม่ได้`)
    const ระดับ = await ระดับของข้อ(แท็บ, สภาพ.ฉบับ, ข้อ)
    ข้อ.forEach((v, k) => {
      const ได้ = ระดับ[k]
      if (ได้.some((x) => x === null)) {
        ตก.push(`① ${ป้าย} ข้อ ${v} ⇒ หาข้อนี้บนหน้าไม่ครบทุกคอลัมน์ [${ได้.join(' ')}]`)
        return
      }
      const ต่าง = Math.max(...ได้) - Math.min(...ได้)
      if (ต่าง > คลาดได้)
        ตก.push(
          `① ${ป้าย} ข้อ ${v} ⇒ 🔴 ทุกคอลัมน์ขึ้นย่อหน้าที่ข้อนี้ แต่เริ่มคนละระดับ [${ได้.join(' ')}] ⇒ ห่างกัน ${Math.round(ต่าง)} จุด`,
        )
    })
    if (สภาพ.ตรวจตัวบท) {
      for (const ฉ of สภาพ.ฉบับ) {
        const ได้ = await ตัวหนังสือของฉบับ(แท็บ, ฉ)
        if (!อ้างอิง[ฉ]) ตก.push(`③ ${ป้าย} ⇒ หาตัวบท ${ฉ} แบบไหลต่อเนื่องไม่เจอ ⇒ เทียบไม่ได้`)
        else if (ได้ !== อ้างอิง[ฉ])
          ตก.push(`③ ${ป้าย} ⇒ 🔴 ตัวบท ${ฉ} ไหลต่อเนื่อง ${อ้างอิง[ฉ].length} · แยกตามย่อหน้า ${ได้.length} ตัวอักษร`)
      }
    }
    console.log(`   ${ป้าย} ⇒ วัด ${ข้อ.length} จุดที่ต้องเริ่มตรงกัน ⇒ ข้อ [${ข้อ.join(' ')}]`)
  } finally {
    await ctx.close()
  }
  return ตก
}

// ---------------------------------------------------------------- ② แบบแยกตามข้อ
async function ตรวจข้อ(สภาพ, พัง) {
  const ตก = []
  const ป้าย = ป้ายสภาพ(สภาพ)
  const { ctx, แท็บ, พร้อม } = await เปิด(สภาพ, ตก)
  try {
    if (!พร้อม) return ตก
    await ยัด(แท็บ, พัง)
    const ข้อ = await แท็บ.evaluate(
      (b) => [...document.querySelectorAll(`.pk-ตัวบท .pk-ข้อ[data-ข้อ^="${b}:"]`)].map((x) => Number(x.dataset.ข้อ.split(':')[1])),
      บท,
    )
    if (ข้อ.length < 10) ตก.push(`② ${ป้าย} ⇒ เจอแถวข้อแค่ ${ข้อ.length} แถว ⇒ วัดไม่พอ`)
    // ⭐ ต้องวางเคียงกันจริง ⇒ ช่องห่อลงแถวใหม่เมื่อไร ⛔ ไม่ใช่การเทียบบรรทัดแล้ว ⇒ บอกตรง ๆ
    const ซ้าย = await ขอบซ้ายของฉบับ(แท็บ, สภาพ.ฉบับ)
    if (new Set(ซ้าย).size !== สภาพ.ฉบับ.length) ตก.push(`② ${ป้าย} ⇒ คอลัมน์ไม่ได้วางเคียงกัน (ขอบซ้าย [${ซ้าย.join(' ')}]) ⇒ วัดข้อนี้ไม่ได้`)
    const ระดับ = await ระดับของข้อ(แท็บ, สภาพ.ฉบับ, ข้อ)
    let ผิด = 0
    ข้อ.forEach((v, k) => {
      const ได้ = ระดับ[k].filter((x) => x !== null)
      if (ได้.length < 2) return
      const ต่าง = Math.max(...ได้) - Math.min(...ได้)
      if (ต่าง > คลาดได้ && ผิด++ < 3)
        ตก.push(`② ${ป้าย} ข้อ ${v} ⇒ 🔴 ข้อเดียวกันเริ่มคนละระดับ [${ระดับ[k].join(' ')}] ⇒ ห่างกัน ${Math.round(ต่าง)} จุด`)
    })
    console.log(`   ${ป้าย} ⇒ วัด ${ข้อ.length} ข้อ`)
  } finally {
    await ctx.close()
  }
  return ตก
}

// ---------------------------------------------------------------- ④ หัวคอลัมน์
async function ตรวจหัว(สภาพ, พัง) {
  const ตก = []
  const ป้าย = `${ป้ายสภาพ(สภาพ)}${สภาพ.เทียบ ? ` + ตอนเทียบ ${สภาพ.เทียบ}` : ''}`
  const { ctx, แท็บ, พร้อม } = await เปิด(สภาพ, ตก)
  try {
    if (!พร้อม) return ตก
    await ยัด(แท็บ, พัง)
    const หัว = await แท็บ.evaluate(() =>
      [...document.querySelectorAll('.pk-หัวช่อง')]
        .filter((h) => h.offsetParent !== null)
        .map((h) => {
          const บน = (sel) => {
            const el = h.querySelector(sel)
            return el ? Math.round(el.getBoundingClientRect().top) : null
          }
          const r = h.getBoundingClientRect()
          return {
            ฉบับ: h.querySelector('select')?.value || '?',
            บน: Math.round(r.top),
            ซ้าย: Math.round(r.left),
            สูง: Math.round(r.height),
            ชื่อตอน: บน('.pk-ที่ของช่อง'),
            ปุ่ม: บน('[data-ปุ่ม="เปลี่ยนตอน"]'),
            ช่องเลือก: บน('select'),
            มีป้าย: !!h.querySelector('.pk-ย่อหน้าตาม:not([aria-hidden])'),
          }
        }),
    )
    if (หัว.length < 2) {
      ตก.push(`④ ${ป้าย} ⇒ เห็นหัวคอลัมน์แค่ ${หัว.length} หัว ⇒ วัดไม่ได้`)
      return ตก
    }
    // ⭐ หัวต้องวางเคียงกันจริง ⇒ ห่อลงแถวใหม่ ⛔ ไม่ใช่สิ่งที่ข้อ 8 พูดถึง ⇒ **แดง ⛔ ไม่ข้ามเงียบ**
    if (new Set(หัว.map((h) => h.ซ้าย)).size !== หัว.length)
      ตก.push(`④ ${ป้าย} ⇒ หัวไม่ได้วางเคียงกัน (ขอบซ้าย [${หัว.map((h) => h.ซ้าย).join(' ')}]) ⇒ วัดข้อนี้ไม่ได้`)
    // ⭐ ใบ #131 ⇒ ป้ายย้ายไปหน้าแหล่งข้อมูล ⇒ ของเดิม *สภาพที่ยืมต้องมีป้าย* ⇒ ตอนนี้ ⛔ มีหัวไหนมีป้าย (ยกเว้นตอนยัดของพัง)
    if (สภาพ.ยืมย่อหน้า && !พัง && หัว.some((h) => h.มีป้าย)) ตก.push(`④ ${ป้าย} ⇒ 🔴 หัวยังมีป้าย *ย่อหน้าตาม* ⇒ ต้องอยู่ที่หน้าแหล่งข้อมูล (ใบ #131)`)
    for (const ส่วน of ['บน', 'สูง', 'ชื่อตอน', 'ปุ่ม', 'ช่องเลือก']) {
      const ค่า = หัว.map((h) => h[ส่วน])
      if (ค่า.some((x) => x === null) || Math.max(...ค่า) - Math.min(...ค่า) > คลาดได้)
        ตก.push(
          `④ ${ป้าย} ⇒ 🔴 ${ส่วน === 'สูง' ? 'หัวสูงไม่เท่ากัน' : `${ส่วน}อยู่คนละระดับ`} ⇒ ` +
            หัว.map((h) => `${h.ฉบับ}${h.มีป้าย ? '(มีป้าย)' : ''} ${h[ส่วน]}`).join(' · '),
        )
    }
  } finally {
    await ctx.close()
  }
  return ตก
}

