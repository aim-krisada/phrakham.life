/**
 * เปิดหน้าตามสภาพที่ขอ ⇒ ตั้งฉบับ · การจัดวาง · ตอนเทียบ ผ่านที่เก็บของผู้อ่านก่อนหน้าโหลด ⛔ ไม่ไล่กดเมนู
 * แล้ว **รอของที่จะวัดขึ้นจริง** ⇒ รอไม่สำเร็จ = เขียนลง `ตก`
 */
async function เปิด({ กว้าง, ฉบับ, จัดวาง, ขนานกัน = false, เทียบ = '' }, ตก) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: 900 } })
  await ctx.addInitScript(
    ([ฉ, จ, ข]) => {
      localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
      localStorage.setItem('phrakham.view', JSON.stringify({ จัดวาง: จ, ...(ข ? { วางจอแคบ: 'ขนานกัน' } : {}) }))
    },
    [ฉบับ, จัดวาง, ขนานกัน],
  )
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}/read/${เล่ม}?c=${บท}${เทียบ ? `&p=${เทียบ}` : ''}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  const พร้อม = await แท็บ
    .waitForFunction(
      ([b, ฉ, จ, ม]) => {
        if (!document.getElementById(`บท-${b}`)) return false
        // ⭐ กล่องของการจัดวางที่ขอต้องขึ้นแล้ว ⇒ ⛔ ไม่วัดตอนหน้ายังเป็นแบบตั้งต้น
        const กล่อง = { แยกตามย่อหน้า: '.pk-ย่อหน้ากอง', แยกตามข้อ: '.pk-ข้อ', ไหลต่อเนื่อง: '.pk-ไหล' }[จ]
        if (!document.querySelector(`.pk-ตัวบท ${กล่อง}`)) return false
        // ⭐ ตัวบทของบทที่ขอ ⇒ ทุกฉบับต้องมีข้อที่ตาเห็นแล้ว
        if (!ฉ.every((x) => document.querySelector(`.pk-ตัวบท [data-ฉบับ="${x}"] [data-ข้อ^="${b}:"], .pk-ตัวบท [data-ข้อ^="${b}:"] [data-ฉบับ="${x}"]`))) return false
        if (ม && !document.querySelector('.pk-ตอนเทียบ .pk-เนื้อตอนเทียบ .pk-เลขข้อ')) return false
        return document.fonts.status === 'loaded'
      },
      [บท, ฉบับ, จัดวาง, !!เทียบ],
      { timeout: รอนานสุด },
    )
    .then(() => true)
    .catch(() => false)
  if (!พร้อม) ตก.push(`${ป้ายสภาพ({ กว้าง, ฉบับ, จัดวาง })} ⇒ หน้า ⛔ ไม่พร้อมภายใน ${รอนานสุด / 1000} วินาที`)
  return { ctx, แท็บ, พร้อม }
}

