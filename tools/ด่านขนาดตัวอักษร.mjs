// ด่านตรวจ ⑧ — ปุ่มปรับขนาดตัวอักษรต้องทำงาน จำค่าได้ และ ⛔ ไม่ทำให้เนื้อล้นขอบจอ
//
// **นี่คือด่าน ⛔ ไม่ใช่รายงาน** — ล้มแล้วคืนรหัสไม่เป็นศูนย์ ⇒ ท่อ CI แดง
//
// **ทำไมต้องมี** — นี่คือ **เกณฑ์ผ่านข้อ 3 ของใบงาน v3/phrakham#24** ที่เขียนว่า
//   "ปรับขนาดตัวอักษรแล้วเนื้อไม่ล้นขอบจอ ⇒ ใช้ `tools/ด่านล้นขอบจอ.mjs` ตรวจที่ขนาดใหญ่สุดด้วย"
//
// ⭐⭐ **ทำไม `ด่านล้นขอบจอ.mjs` ตัวเดียวยังไม่พอ**
//   ด่านนั้นขยับขนาดตัวอักษรที่ **ราก** ซึ่งคือค่าที่ผู้อ่านตั้งในเบราว์เซอร์
//   ⇒ ส่วนปุ่มของเราเป็น **อีกแกนหนึ่ง** ⇒ ผู้อ่านคนเดียวใช้ทั้งสองแกนพร้อมกันได้
//   ⇒ ⛔ วัดทีละแกน = ⛔ ไม่เคยวัดของที่ผู้อ่านสายตาไม่ดีเจอจริง ⇒ ที่นี่จึงเปิดสุดทั้ง 2 แกนพร้อมกัน
//
// **วิธีพิสูจน์ว่าด่านนี้แดงได้จริง** ⛔ อย่าเชื่อว่ามันเฝ้าอยู่
//   ถอด `persist` ของห้องสมุดออก (หรือถอดบรรทัดที่โหลด `pk-fontsize.js` ใน `nuxt.config.ts`)
//   ⇒ สร้างเว็บใหม่แล้วยิงด่านนี้ใส่ ⇒ **ต้องแดง**
//
//   node tools/ด่านขนาดตัวอักษร.mjs <ที่อยู่เว็บ>

import { chromium } from 'playwright'
import { เส้นทางเว็บ, กางแผงAa } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
// ⭐ บทยาวที่สุด ⇒ ล้นขอบง่ายที่สุด · **บทเป็นคำถามท้ายที่อยู่แล้ว** (ใบงาน v3/phrakham#73)
const ที่อยู่บท = `${ฐาน}/read/PSA?c=119`
const ที่ตก = []

const เบราว์เซอร์ = await chromium.launch()
const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
const แท็บ = await ctx.newPage()

const ปุ่มใหญ่ = () => แท็บ.getByRole('button', { name: 'ใหญ่ขึ้น' })
const ปุ่มเล็ก = () => แท็บ.getByRole('button', { name: 'เล็กลง' })
const ค่าที่ขึ้น = () => แท็บ.locator('.pk-ค่าขนาด').innerText()
const ขนาดจริง = () =>
  แท็บ.evaluate(() =>
    parseFloat(getComputedStyle(document.querySelector('.pk-ช่องฉบับ')).fontSize),
  )

await แท็บ.goto(ที่อยู่บท, { waitUntil: 'domcontentloaded' })
await แท็บ.waitForSelector('article.pk-เนื้อ h1')
// ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131#note_30332 ข้อ 2 ⇒ ก− ขนาด ก+ ย้ายเข้าแผง Aa ⇒ เปลี่ยนแค่ทางกด ⇒ กาง Aa ก่อน
//   ⇒ ⛔ ไม่แตะเกณฑ์ข้อไหน ⇒ ทุกข้อยังวัดขนาดตัวหนังสือจริง · ค่าที่ขึ้น · การจำค่า · เพดาน · พื้น · แป้นพิมพ์ · ไม่ล้นขอบจอ 320
await กางแผงAa(แท็บ)
await แท็บ.waitForFunction(() => !document.querySelector('.pk-ขนาดตัวอักษร button').disabled)

// ① เปิดครั้งแรกต้องเป็น 100%
const ขนาดตั้งต้น = await ขนาดจริง()
{
  const ค่า = (await ค่าที่ขึ้น()).trim()
  if (ค่า !== '100%') ที่ตก.push(`① เปิดครั้งแรกแล้วค่าที่ขึ้นคือ "${ค่า}" ⇒ ต้องเป็น "100%"`)
}

// ② กดใหญ่ขึ้น ⇒ ตัวหนังสือต้องโตขึ้นจริง ⛔ ไม่ใช่แค่ตัวเลขบนหน้าจอเปลี่ยน
{
  await ปุ่มใหญ่().click()
  const ใหม่ = await ขนาดจริง()
  if (!(ใหม่ > ขนาดตั้งต้น)) {
    ที่ตก.push(`② กดใหญ่ขึ้นแล้วตัวหนังสือยังเท่าเดิม ⇒ ${ขนาดตั้งต้น} จุด`)
  }
  if ((await ค่าที่ขึ้น()).trim() === '100%') ที่ตก.push('② กดแล้วตัวเลขบนหน้าจอ ⛔ ไม่ขยับ')
}

// ③ ⭐ เปิดหน้าใหม่ ⇒ ต้องจำขนาดที่ตั้งไว้ได้
{
  const ก่อนโหลด = await ขนาดจริง()
  await แท็บ.reload({ waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('.pk-ช่องฉบับ')
  const หลังโหลด = await ขนาดจริง()
  // ⭐ เปิดหน้าใหม่ ⇒ แผง Aa พับเอง ⇒ กางคืนก่อนข้อ ④ ⇒ เปลี่ยนแค่ทางกด (ใบ #131 note_30332 ข้อ 2)
  await กางแผงAa(แท็บ)
  if (Math.abs(หลังโหลด - ก่อนโหลด) > 0.5) {
    ที่ตก.push(`③ เปิดหน้าใหม่แล้วขนาดเปลี่ยนจาก ${ก่อนโหลด} เป็น ${หลังโหลด} ⇒ ⛔ ลืมค่าที่ตั้งไว้`)
  }
}

// ④ กดใหญ่จนสุด ⇒ ปุ่มต้องหยุดเอง และต้องไปถึง 200% ตามที่ WCAG SC 1.4.4 กำหนดเป็นเพดาน
let ค่าสุด = ''
{
  for (let i = 0; i < 20 && (await ปุ่มใหญ่().isEnabled()); i++) await ปุ่มใหญ่().click()
  ค่าสุด = (await ค่าที่ขึ้น()).trim()
  if (await ปุ่มใหญ่().isEnabled()) ที่ตก.push('④ กดใหญ่ขึ้น 20 ครั้งแล้วปุ่มยังกดต่อได้ ⇒ ⛔ ไม่มีเพดาน')
  if (parseInt(ค่าสุด, 10) < 200) ที่ตก.push(`④ ขยายได้ใหญ่สุดแค่ ${ค่าสุด} ⇒ ต้องถึง 200% เป็นอย่างน้อย`)
}

// ⑤ ⭐⭐ **เปิดสุดทั้ง 2 แกนพร้อมกัน ที่จอ 320 จุด ⇒ หน้าต้องยังไม่เลื่อนซ้ายขวา**
{
  await แท็บ.evaluate(() => {
    document.documentElement.style.fontSize = '32px' // ผู้อ่านตั้งเบราว์เซอร์ไว้ 200%
  })
  await แท็บ.setViewportSize({ width: 320, height: 900 })
  await แท็บ.waitForTimeout(200)
  // ⛔ **บอกแค่ "ล้นกี่จุด" ไม่พอ** — ตัวรันของอัมกิตใช้ฟอนต์คนละชุดกับเครื่องเรา
  //   ⇒ ของที่ล้นบนตัวรันอาจ ⛔ ไม่ล้นบนเครื่องเรา ⇒ **ต้องชี้ตัวที่ล้นมาด้วย** ไม่งั้นตามหาไม่เจอ
  //   (ท่าเดียวกับ `ด่านล้นขอบจอ.mjs` ⇒ ยืมมาใช้ ⛔ ไม่คิดใหม่)
  const ผล = await แท็บ.evaluate(() => {
    const de = document.documentElement
    const ปัด = (v) => Math.round(v * 100) / 100
    return {
      ล้น: Math.round(de.scrollWidth - de.clientWidth),
      ตัวที่ล้น: [...document.querySelectorAll('body *')]
        .map((el) => ({ el, r: el.getBoundingClientRect() }))
        .filter((x) => x.r.right > de.clientWidth + 0.5)
        .slice(0, 5)
        .map((x) => `${x.el.tagName.toLowerCase()}.${String(x.el.className).slice(0, 40)} ขวาสุด=${ปัด(x.r.right)}`),
    }
  })
  if (ผล.ล้น > 0) {
    ที่ตก.push(
      `⑤ ตัวอักษรของเว็บ ${ค่าสุด} + ของเบราว์เซอร์ 200% @ 320 จุด ⇒ เลื่อนซ้ายขวา ${ผล.ล้น} จุด` +
        ` · ${ผล.ตัวที่ล้น.join(' | ') || '(หาตัวที่ล้นไม่เจอ ⇒ น่าจะเป็นเศษจุดทศนิยมของฟอนต์)'}`,
    )
  }
}

// ⑥ กดเล็กลงจนสุด ⇒ ปุ่มต้องหยุดเอง ⛔ ไม่ปล่อยให้ตัวหนังสือเล็กจนอ่านไม่ออก
{
  await แท็บ.evaluate(() => {
    document.documentElement.style.fontSize = ''
  })
  await แท็บ.setViewportSize({ width: 1280, height: 900 })
  for (let i = 0; i < 20 && (await ปุ่มเล็ก().isEnabled()); i++) await ปุ่มเล็ก().click()
  if (await ปุ่มเล็ก().isEnabled()) ที่ตก.push('⑥ กดเล็กลง 20 ครั้งแล้วปุ่มยังกดต่อได้ ⇒ ⛔ ไม่มีพื้น')
}

// ⑦ กดด้วยแป้นพิมพ์ได้ (WCAG SC 2.1.1 ระดับ A ⇒ ฟีเจอร์ข้อ 57 ที่พี่เอมติ๊ก)
{
  const ก่อน = await ขนาดจริง()
  await ปุ่มใหญ่().focus()
  await แท็บ.keyboard.press('Enter')
  if (!((await ขนาดจริง()) > ก่อน)) ที่ตก.push('⑦ โฟกัสที่ปุ่มแล้วกด Enter ⇒ ⛔ ขนาดไม่เปลี่ยน')
}

await ctx.close()
await เบราว์เซอร์.close()

if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
console.log(`✅ ปรับขนาดตัวอักษร: ขยายถึง ${ค่าสุด} · จำค่าได้ · กดด้วยแป้นพิมพ์ได้ · และ ⛔ ไม่ล้นขอบจอ 320 จุด`)
