import argparse
import os
import re
import shutil
import subprocess
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

# ⛔ ไม่ใช้ `git ls-files` — มันคืนชื่อไฟล์ไทยเป็นรหัส \340\270... ทำให้ไล่ไฟล์ได้ไม่ครบ
#    (คนตรวจเจอเองที่ !7 note 23488 ⇒ อ่านได้ 4 จาก 12 ไฟล์)
ข้ามโฟลเดอร์ = {".git", "_แตก", "node_modules", ".nuxt", ".output", "dist"}

ป้ายไม่รัน = re.compile(r"<!--\s*ไม่ต้องรัน\s*:\s*(?P<เหตุผล>.*?)\s*-->")
เปิดบล็อก = re.compile(r"^\s*```(?P<ป้าย>[A-Za-z0-9_+-]*)\s*$")
โค้ดในบรรทัด = re.compile(r"`([^`\n]+)`")
ชื่อไฟล์เปล่า = re.compile(r"^\S+$")
มีนามสกุลหรือทับ = re.compile(r"[/\\]|\.[A-Za-z0-9]{1,6}$")

หมดเวลาต่ออัน = 60  # วินาที


class รายการ:
    def __init__(self, ไฟล์, บรรทัด, ชนิด, สคริปต์):
        self.ไฟล์ = ไฟล์
        self.บรรทัด = บรรทัด
        self.ชนิด = ชนิด
        self.สคริปต์ = สคริปต์

    @property
    def ที่อยู่(self):
        return f"{self.ไฟล์}:{self.บรรทัด}"


def หาไฟล์md(ราก):
    out = []
    for โฟลเดอร์, ลูก, ไฟล์ทั้งหลาย in os.walk(ราก):
        ลูก[:] = [d for d in ลูก if d not in ข้ามโฟลเดอร์]
        for ชื่อ in ไฟล์ทั้งหลาย:
            if ชื่อ.endswith(".md"):
                out.append(os.path.join(โฟลเดอร์, ชื่อ))
    return sorted(out)


def เก็บจากไฟล์(path, ราก, ข้อผิดพลาด):
    ชื่อสั้น = os.path.relpath(path, ราก).replace("\\", "/")
    บรรทัดทั้งหมด = open(path, encoding="utf-8").read().split("\n")
    เจอ = []
    i = 0
    while i < len(บรรทัดทั้งหมด):
        บรรทัด = บรรทัดทั้งหมด[i]

        m = ป้ายไม่รัน.search(บรรทัด)
        if m:
            if len(m.group("เหตุผล")) < 5:
                ข้อผิดพลาด.append(
                    f"{ชื่อสั้น}:{i + 1} ⛔ ป้าย 'ไม่ต้องรัน' ไม่ได้บอกเหตุผล ⇒ ยกเว้นลอย ๆ ไม่ได้"
                )
            # ป้ายคุมของชิ้นถัดไป ⇒ ข้ามบรรทัดว่างแล้วข้ามของชิ้นนั้นทั้งชิ้น
            j = i + 1
            while j < len(บรรทัดทั้งหมด) and not บรรทัดทั้งหมด[j].strip():
                j += 1
            if j < len(บรรทัดทั้งหมด) and เปิดบล็อก.match(บรรทัดทั้งหมด[j]):
                j += 1
                while j < len(บรรทัดทั้งหมด) and not เปิดบล็อก.match(บรรทัดทั้งหมด[j]):
                    j += 1
            i = j + 1
            continue

        m = เปิดบล็อก.match(บรรทัด)
        if m:
            เริ่ม = i + 1
            เนื้อ = []
            i += 1
            while i < len(บรรทัดทั้งหมด) and not เปิดบล็อก.match(บรรทัดทั้งหมด[i]):
                เนื้อ.append(บรรทัดทั้งหมด[i])
                i += 1
            i += 1
            if m.group("ป้าย") == "sh" and any(x.strip() for x in เนื้อ):
                เจอ.append(รายการ(ชื่อสั้น, เริ่ม, "บล็อก sh", "\n".join(เนื้อ)))
            continue

        if "วิธีดูของจริง" in บรรทัด:
            for คำสั่ง in โค้ดในบรรทัด.findall(บรรทัด):
                if ชื่อไฟล์เปล่า.match(คำสั่ง) and มีนามสกุลหรือทับ.search(คำสั่ง):
                    continue  # ชื่อไฟล์เปล่า ๆ = ตัวชี้ ⛔ ไม่ใช่คำสั่ง (ดูหัวไฟล์)
                เจอ.append(รายการ(ชื่อสั้น, i + 1, "วิธีดูของจริง", คำสั่ง))
        i += 1
    return เจอ


def บรรทัดของสคริปต์(it):
    return [x for x in it.สคริปต์.strip().split("\n") if x.strip()]


def หาเชลล์():
    for ชื่อ in ("sh", "bash"):
        ที่อยู่ = shutil.which(ชื่อ)
        if ที่อยู่:
            return ที่อยู่
    return None


def main():
    p = argparse.ArgumentParser(description="ด่าน ① คำสั่งในเอกสารต้องรันออกจริง")
    p.add_argument("--ราก", default=None, help="รากของที่เก็บ (ปริยาย = โฟลเดอร์เหนือ tools/)")
    p.add_argument("--รายการ", action="store_true", help="บอกว่าเจออะไรบ้าง ⛔ ไม่รัน")
    a = p.parse_args()

    ราก = os.path.abspath(a.ราก or os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

    ข้อผิดพลาด = []
    ของทั้งหมด = []
    for f in หาไฟล์md(ราก):
        ของทั้งหมด += เก็บจากไฟล์(f, ราก, ข้อผิดพลาด)

    print(f"ด่าน ① · ราก = {ราก}")
    จำนวนบรรทัด = sum(len(บรรทัดของสคริปต์(it)) for it in ของทั้งหมด)
    print(f"เจอของที่ต้องรัน {len(ของทั้งหมด)} ก้อน · รวม {จำนวนบรรทัด} คำสั่ง")
    for it in ของทั้งหมด:
        บรรทัดทั้งหลาย = บรรทัดของสคริปต์(it)
        print(f"  · {it.ที่อยู่} [{it.ชนิด}] {len(บรรทัดทั้งหลาย)} คำสั่ง")
        for บรรทัด in บรรทัดทั้งหลาย:
            print(f"      {บรรทัด}")

    if a.รายการ:
        for e in ข้อผิดพลาด:
            print(e)
        return 1 if ข้อผิดพลาด else 0

    เชลล์ = หาเชลล์()
    if เชลล์ is None:
        print("⛔ หา sh หรือ bash ในเครื่องไม่เจอ ⇒ รันด่านนี้ไม่ได้")
        return 2

    print("")
    for it in ของทั้งหมด:
        try:
            # `set -e` ⇒ บรรทัดไหนล้มก็หยุดทันที ⛔ ไม่ปล่อยให้บรรทัดสุดท้ายกลบ (ดูหัวไฟล์)
            r = subprocess.run(
                [เชลล์, "-c", "set -e\n" + it.สคริปต์],
                cwd=ราก,
                capture_output=True,
                timeout=หมดเวลาต่ออัน,
            )
            รหัส = r.returncode
            ผล = (r.stdout + r.stderr).decode("utf-8", "replace")
        except subprocess.TimeoutExpired:
            รหัส = -1
            ผล = f"⛔ เกิน {หมดเวลาต่ออัน} วินาที"
        if รหัส == 0:
            print(f"✅ {it.ที่อยู่}")
        else:
            print(f"⛔ {it.ที่อยู่} ⇒ exit={รหัส}")
            print(f"   คำสั่ง: {it.สคริปต์.strip()}")
            for บรรทัด in ผล.strip().split("\n")[-15:]:
                print(f"   | {บรรทัด}")
            ข้อผิดพลาด.append(f"{it.ที่อยู่} รันแล้วล้ม exit={รหัส}")

    print("")
    if ข้อผิดพลาด:
        print(f"⛔ ด่าน ① แดง — {len(ข้อผิดพลาด)} เรื่อง")
        for e in ข้อผิดพลาด:
            print(f"  · {e}")
        return 1
    print("✅ ด่าน ① เขียว")
    return 0


if __name__ == "__main__":
    sys.exit(main())
