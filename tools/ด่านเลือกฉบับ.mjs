// ด่านตรวจ ⑦ — ปุ่มเลือกฉบับต้องเปลี่ยนทันที และจำค่าไว้เมื่อเปิดใหม่
//
// **นี่คือด่าน ⛔ ไม่ใช่รายงาน** — ล้มแล้วคืนรหัสไม่เป็นศูนย์ ⇒ ท่อ CI แดง
//
// **ทำไมต้องมี** — นี่คือ **เกณฑ์ผ่านข้อ 2 ของใบงาน v3/phrakham#24** เขียนเป็นคำว่า
//   "กดเลือกฉบับแล้วเปลี่ยนทันที และจำค่าไว้เมื่อเปิดใหม่"
//   ⇒ ⭐ **เกณฑ์ที่ไม่มีเครื่องตรวจ คือเกณฑ์ที่จะค่อย ๆ เลิกเป็นจริงโดยไม่มีใครรู้**
//
// ⛔ **ด่านนี้ต้องเปิดโค้ดของเว็บให้ทำงาน** — การจำค่าเกิดที่เครื่องผู้อ่าน ⛔ ไม่ได้อยู่ในไฟล์
//   ⇒ ต่างจากด่าน ③ ④ ⑤ ที่ตรวจ **2 ชั้น** ⇒ ที่นี่มีชั้นเดียวเพราะของที่ตรวจเป็นพฤติกรรม
//   ⇒ ส่วน "ปิดโค้ดแล้วยังอ่านได้ไหม" ด่าน ⑤ ตอบอยู่แล้ว ⇒ มันอ่านหน้าที่ตัดโค้ดทิ้งทุกรอบ
//
// **วิธีพิสูจน์ว่าด่านนี้แดงได้จริง** ⛔ อย่าเชื่อว่ามันเฝ้าอยู่
//   ถอดบรรทัดที่เรียก `จำฉบับที่เลือก` ออกจาก `app/components/หน้าอ่าน.vue`
//   ⇒ สร้างเว็บใหม่แล้วยิงด่านนี้ใส่ ⇒ **ต้องแดงที่ข้อ ③ เปิดใหม่แล้วลืมที่เลือกไว้**
//
//   node tools/ด่านเลือกฉบับ.mjs <ที่อยู่เว็บ>

import { chromium } from 'playwright'
import { fileURLToPath } from 'node:url'
import { เส้นทางเว็บ, ชั้นที่หน้าอ่านแสดง, รอโค้ดของเว็บติด, เพิ่มฉบับจนครบ, ปุ่มเทียบของหน้า, เพิ่มคอลัมน์ } from './หน้าที่ตรวจ.mjs'
import { แกะซองรวมฉบับเพิ่ม } from '../server/utils/ซองเนื้อบท.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const ที่ตก = []

// ⭐ ซองตัวบทเป็นเจ้าของความจริงว่าฉบับไหนมีข้อความว่าอย่างไร ⇒ ⛔ ด่านนี้ไม่พิมพ์ตัวบทไว้เอง
//   ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/169 ⇒ ซองเดิม + ซองฉบับเพิ่ม (KJV) ⇒ ตัวเดียวกับที่หลังบ้านของเว็บใช้
const ซอง = แกะซองรวมฉบับเพิ่ม(
  fileURLToPath(new URL('../_data/เนื้อบท.json.gz', import.meta.url)),
  fileURLToPath(new URL('../_พ่น/ฉบับเพิ่ม.json.gz', import.meta.url)),
)

// บทที่ใช้ทดสอบ — 3 ยอห์น 1 คือบทสั้นที่สุด ⇒ เปิดเร็ว และเป็นเล่มที่ตัวแปลงรุ่น 2 เคยทำหาย
const บทที่ใช้ = '3JN/1'
// ⭐ **1 เล่ม = 1 หน้า** (ใบงาน v3/phrakham#73) ⇒ 3 ยอห์นมีบทเดียว ⇒ หน้าของเล่มคือบทนั้นพอดี
const ที่อยู่บทที่ใช้ = '/read/3JN'
const อีกฉบับ = 'LSV'

// ⛔ **ต้องปรับช่องว่างให้เหมือนกันก่อนเทียบ** — ในไฟล์ข้อมูลมีการขึ้นบรรทัดกับเว้นวรรคซ้อน
//   แต่เบราว์เซอร์คืนข้อความที่ยุบช่องว่างซ้อนให้แล้ว ⇒ เทียบดิบ ๆ จะ **แดงมั่วทุกครั้ง**
const ปรับ = (s) => s.replace(/\s+/g, ' ').trim()

// ⭐ หยิบ **ต้นข้อ 1** ของแต่ละฉบับมาเป็นลายเซ็น ⇒ ใช้ตอบว่าหน้ากำลังแสดงฉบับไหน
const ลายเซ็น = (ฉ) => ปรับ(ซอง.บท[บทที่ใช้][ฉ]['1'] || '').slice(0, 40)

const เบราว์เซอร์ = await chromium.launch()
const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
const แท็บ = await ctx.newPage()

const เนื้อทั้งหน้า = async () => ปรับ(await แท็บ.locator('.pk-ตัวบท').innerText())

// ⭐⭐ **ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/102 ⇒ เมนูช่องติ๊ก *ฉบับ* ถูกถอดแล้ว**
//   ⇒ **เพิ่ม** ฉบับ = เมนู *เทียบ* บนแถบบน (ชื่อเดิม *คอลัมน์* ⇒ ใบ #113) · **เปลี่ยน** ฉบับ = ตัวเลือกในหัวคอลัมน์ · **เอาออก** = ปุ่มปิดในหัวคอลัมน์
//   ⇒ เกณฑ์ข้อ 2 ของใบ #24 ยังเหมือนเดิมทุกคำ ⇒ *กดเลือกฉบับแล้วเปลี่ยนทันที และจำค่าไว้เมื่อเปิดใหม่*
//     ⇒ ด่านนี้จึงเปลี่ยนแค่ *ทางกด* ⇒ ของที่ตรวจยังเป็นข้อ ① ถึง ⑥ ชุดเดิม
const หัว = () => แท็บ.locator('.pk-หัวคอลัมน์ .pk-ช่องหัว')
const ฉบับบนหัว = () => หัว().locator('select').evaluateAll((s) => s.map((x) => x.value))

async function เพิ่มฉบับ(ฉ) {
  // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/161 ⇒ ปุ่ม *เพิ่มคอลัมน์* แล้วเลือกฉบับที่หัวคอลัมน์ใหม่ ⇒ ท่าอยู่ที่ `tools/หน้าที่ตรวจ.mjs`
  //   ⇒ ⚠️ ของเดิม (ใบ #131 ข้อ 9) ติ๊กช่องของฉบับนั้นในเมนู ⇒ ของเดิมกว่านั้นกดปุ่ม *+ ชื่อเต็ม*
  await เพิ่มคอลัมน์(แท็บ, ฉ)
  await แท็บ.waitForTimeout(200)
}

await แท็บ.goto(`${ฐาน}${ที่อยู่บทที่ใช้}`, { waitUntil: 'domcontentloaded' })
await แท็บ.waitForSelector('article.pk-เนื้อ h1')
// รอให้โค้ดของเว็บติดก่อน ⇒ ⛔ ไม่งั้นกดแล้วยังไม่มีใครรับเรื่อง
//   ⇒ เหตุผลเต็มอยู่ที่ `tools/หน้าที่ตรวจ.mjs` หัวข้อ "รอให้โค้ดของเว็บติดจริง"
await รอโค้ดของเว็บติด(แท็บ)

// ① เปิดครั้งแรกต้องได้ฉบับตั้งต้นฉบับเดียว ⇒ และ ⛔ ไม่มีปุ่มปิด (ใบ #102 ข้อ 6.1 ⇒ ห้ามปิดจนหน้าว่าง)
{
  const เนื้อ = await เนื้อทั้งหน้า()
  if (!เนื้อ.includes(ลายเซ็น(ชั้นที่หน้าอ่านแสดง))) {
    ที่ตก.push(`① เปิดครั้งแรกแล้ว ⛔ ไม่เห็นฉบับตั้งต้น ${ชั้นที่หน้าอ่านแสดง}`)
  }
  if (เนื้อ.includes(ลายเซ็น(อีกฉบับ))) {
    ที่ตก.push(`① เปิดครั้งแรกแล้วเห็นฉบับ ${อีกฉบับ} ทั้งที่ ⛔ ยังไม่มีใครเลือก`)
  }
  const บนหัว = await ฉบับบนหัว()
  if (String(บนหัว) !== ชั้นที่หน้าอ่านแสดง)
    ที่ตก.push(`① หัวคอลัมน์ตอนเปิดครั้งแรกบอกฉบับ ${บนหัว} ⇒ ต้องเป็น ${ชั้นที่หน้าอ่านแสดง} ฉบับเดียว`)
  // ⭐ ใบ #122 ⇒ คอลัมน์เดียวยังเห็น × แต่กดไม่ได้ (`aria-disabled`) ⇒ นับเฉพาะ × ที่กดได้
  const ปิดได้ = await แท็บ.locator('.pk-หัวคอลัมน์ [data-ปุ่ม="ปิดคอลัมน์"]:not([aria-disabled="true"])').count()
  if (ปิดได้) ที่ตก.push(`① เหลือคอลัมน์เดียวแต่ยังมีปุ่มปิดที่กดได้ ${ปิดได้} ปุ่ม ⛔ ปิดแล้วหน้าว่าง (ใบ #102 ข้อ 6.1 · ใบ #122)`)
}

// ② กดเพิ่มอีกฉบับ ⇒ ต้องขึ้นทันทีโดย ⛔ ไม่ต้องโหลดหน้าใหม่
{
  await เพิ่มฉบับ(อีกฉบับ)
  const เนื้อ = await เนื้อทั้งหน้า()
  if (!เนื้อ.includes(ลายเซ็น(อีกฉบับ))) ที่ตก.push(`② กดเพิ่ม ${อีกฉบับ} แล้ว ⛔ เนื้อไม่ขึ้น`)
  if (!เนื้อ.includes(ลายเซ็น(ชั้นที่หน้าอ่านแสดง))) {
    ที่ตก.push(`② เพิ่มแล้ว ⇒ แต่ฉบับเดิมหายไป ⛔ นี่คือเลือกแทน ไม่ใช่เลือกเพิ่ม`)
  }
}

// ②ข ⭐ **เปลี่ยนฉบับของคอลัมน์จากหัวคอลัมน์** ⇒ ต้องเปลี่ยนทันที (ใบ #102 ข้อ 6)
//   ⇒ ⚠️ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/161 ข้อ 7.3 ⇒ ฉบับที่คอลัมน์อื่นใช้อยู่ **ต้องเลือกได้** (ฉบับซ้ำได้)
//     ⇒ ของเดิม (ใบ #131 ข้อ 9.7 ทาง ก.) ⇒ ต้องเลือกไม่ได้ ⇒ @krisada เปลี่ยนเป็นแบบ Bible Gateway 8 พ.ย. 2569 ⇒ เกณฑ์นี้กลับทาง
// ⛔ ⛔ ไม่ใช้ WEB ⇒ ต้นข้อ 1 ของ 3 ยอห์นใน WEB กับ LSV ขึ้นต้นเหมือนกัน ⇒ ลายเซ็นแยกสองฉบับนี้ไม่ออก
const ฉบับที่สาม = 'THKJV'
{
  const ช่อง = แท็บ.locator(`.pk-หัวคอลัมน์ .pk-ช่องหัว[data-ฉบับ="${อีกฉบับ}"] select`)
  // ⛔ อ่าน `disabled` ของ `<option>` ตรง ๆ ⇒ `isDisabled()` ของ Playwright ⛔ ไม่นับ `<option>`
  const ปิดอยู่ = await ช่อง
    .locator(`option[value="${ชั้นที่หน้าอ่านแสดง}"]`)
    .evaluate((o) => o.disabled)
  if (ปิดอยู่)
    ที่ตก.push(`②ข ตัวเลือกฉบับของคอลัมน์ ${อีกฉบับ} ล็อก ${ชั้นที่หน้าอ่านแสดง} ⇒ ต้องเลือกฉบับที่คอลัมน์อื่นเปิดอยู่ได้ (ใบ #161 ข้อ 7.3)`)
  await ช่อง.selectOption(ฉบับที่สาม)
  await แท็บ.waitForTimeout(200)
  const เนื้อ = await เนื้อทั้งหน้า()
  if (!เนื้อ.includes(ลายเซ็น(ฉบับที่สาม)) || เนื้อ.includes(ลายเซ็น(อีกฉบับ)))
    ที่ตก.push(`②ข เปลี่ยนคอลัมน์ ${อีกฉบับ} เป็น ${ฉบับที่สาม} ที่หัวคอลัมน์แล้ว ⛔ เนื้อไม่เปลี่ยนตาม`)
}

// ②ค ⭐ **ทุกฉบับในซองต้องเลือกได้ที่หัวคอลัมน์ และเลือกแล้วเนื้อของฉบับนั้นขึ้นจริง** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/169)
//   ⇒ ⭐ รายชื่อมาจากซองเอง ⛔ ไม่พิมพ์ไว้ที่นี่ ⇒ ฉบับเพิ่มรอบหน้าถูกตรวจเองโดยไม่ต้องมีใครจำ
//   ⇒ ลายเซ็นซ้ำกับฉบับอื่น (WEB กับ LSV ใน 3 ยอห์น) ⇒ ตรวจแค่ว่าเนื้อของฉบับนั้นขึ้น ⇒ ⛔ ไม่ตรวจว่าของเดิมหาย
//   ⇒ จบแล้วเลือกกลับเป็น ${ฉบับที่สาม} ⇒ ข้อ ③ ข้างล่างยังตรวจชุดเดิม
{
  const ช่อง = แท็บ.locator(`.pk-หัวคอลัมน์ .pk-ช่องหัว[data-ฉบับ="${ฉบับที่สาม}"] select`)
  const มีให้เลือก = await ช่อง.locator('option').evaluateAll((o) => o.map((x) => x.value))
  for (const ฉ of ซอง.ชั้น) {
    if (!มีให้เลือก.includes(ฉ)) {
      ที่ตก.push(`②ค ฉบับ ${ฉ} อยู่ในซองตัวบท แต่ ⛔ ไม่มีในตัวเลือกที่หัวคอลัมน์ ⇒ ผู้อ่านเลือกไม่ได้`)
      continue
    }
    await หัว().nth(1).locator("select").selectOption(ฉ)
    await แท็บ.waitForTimeout(200)
    if (!(await เนื้อทั้งหน้า()).includes(ลายเซ็น(ฉ))) ที่ตก.push(`②ค เลือก ${ฉ} ที่หัวคอลัมน์แล้ว ⛔ เนื้อของ ${ฉ} ไม่ขึ้น`)
  }
  await หัว().nth(1).locator("select").selectOption(ฉบับที่สาม)
  await แท็บ.waitForTimeout(200)
}

// ③ ⭐ เปิดหน้าใหม่ ⇒ ต้องจำที่เลือกไว้ได้
{
  await แท็บ.reload({ waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(
    (คำ) =>
      (document.querySelector('.pk-ตัวบท')?.innerText || '').replace(/\s+/g, ' ').includes(คำ),
    ลายเซ็น(ฉบับที่สาม),
    { timeout: 5000 },
  ).catch(() => ที่ตก.push(`③ เปิดหน้าใหม่แล้ว ⛔ ลืมว่าเคยเลือก ${ฉบับที่สาม} ไว้`))
}

// ④ เปิด **บทอื่น** ⇒ ต้องจำข้ามหน้าด้วย ⛔ ไม่ใช่จำเฉพาะหน้าเดิม
{
  await แท็บ.goto(`${ฐาน}/read/PSA?c=23`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await รอโค้ดของเว็บติด(แท็บ)
  await แท็บ
    .waitForFunction(
      () => document.querySelectorAll('.pk-หัวคอลัมน์ .pk-ช่องหัว').length === 2,
      undefined,
      { timeout: 5000 },
    )
    .catch(async () => {
      ที่ตก.push(`④ เปิดบทอื่นแล้วเหลือ ${await หัว().count()} คอลัมน์ ⇒ ต้องเป็น 2 คอลัมน์`)
    })
}

// ⑤ ปิดคอลัมน์จนเหลืออันเดียว ⇒ **ปุ่มปิดต้องกดไม่ได้** ⛔ ปิดจนหน้าว่างไม่ได้ (ใบ #102 ข้อ 6.1 ⇒ ใบ #122 ⇒ × ยังเห็นแต่ `aria-disabled`)
//   ⇒ ของเดิมของข้อนี้คือ *ไม่เหลือฉบับไหนเลยแล้วต้องเตือน* ⇒ ตอนนี้สภาพนั้นเกิดจากการกดไม่ได้แล้ว
{
  for (let i = 0; i < 6; i++) {
    const ปุ่มปิด = แท็บ.locator('.pk-หัวคอลัมน์ [data-ปุ่ม="ปิดคอลัมน์"]:not([aria-disabled="true"])')
    if (!(await ปุ่มปิด.count())) break
    await ปุ่มปิด.first().click()
    await แท็บ.waitForTimeout(150)
  }
  const เหลือ = await หัว().count()
  if (เหลือ !== 1) ที่ตก.push(`⑤ กดปิดจนสุดแล้วเหลือ ${เหลือ} คอลัมน์ ⇒ ต้องเหลือ 1 ⛔ ห้ามปิดจนหน้าว่าง`)
  const เนื้อ = await เนื้อทั้งหน้า()
  if (เนื้อ.length < 100) ที่ตก.push(`⑤ ปิดคอลัมน์แล้วตัวบทเหลือ ${เนื้อ.length} ตัวอักษร ⇒ หน้าว่าง`)
}
// ⑥ ⭐⭐ **เลือกครบทุกฉบับพร้อมกัน แล้วหน้าต้องยังไม่เลื่อนซ้ายขวา**
//
// **ทำไมต้องตรวจที่นี่ ⛔ ไม่ปล่อยให้เป็นหน้าที่ของด่านล้นขอบจอ**
//   ด่านนั้นเปิดหน้าตามที่อยู่ แล้ววัดหน้าที่ **ยังไม่มีใครกดอะไร** ⇒ มันจึงเห็นแค่ฉบับเดียว
//   ⇒ ⛔ **การวางหลายฉบับเรียงกัน คือของที่ล้นขอบง่ายที่สุดในหน้านี้** ⇒ ต้องวัดตอนเปิดครบ
{
  await แท็บ.goto(`${ฐาน}${ที่อยู่บทที่ใช้}`, { waitUntil: 'domcontentloaded' })
  // ⛔ เปิดหน้าใหม่ = โค้ดของเว็บเริ่มใหม่ ⇒ **ต้องรอใหม่ทุกครั้ง** ⛔ ไม่ใช่รอรอบแรกรอบเดียว
  await รอโค้ดของเว็บติด(แท็บ)
  const กี่ฉบับ = await เพิ่มฉบับจนครบ(แท็บ, 99)

  // 320 จุดคือพื้นที่ที่ WCAG SC 1.4.10 กำหนด · 32 จุดคือตัวอักษรใหญ่ 200% ที่ SC 1.4.4 กำหนด
  for (const px of [16, 32]) {
    await แท็บ.evaluate((v) => {
      document.documentElement.style.fontSize = v + 'px'
    }, px)
    await แท็บ.setViewportSize({ width: 320, height: 900 })
    await แท็บ.waitForTimeout(150)
    const ล้น = await แท็บ.evaluate(() => {
      const de = document.documentElement
      return Math.round(de.scrollWidth - de.clientWidth)
    })
    if (ล้น > 0) {
      ที่ตก.push(`⑥ เปิดครบ ${กี่ฉบับ} ฉบับ @ 320 จุด · ตัวอักษร ${px} จุด ⇒ เลื่อนซ้ายขวา ${ล้น} จุด`)
    }
  }
}

await ctx.close()
await เบราว์เซอร์.close()

if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
