# ป้ายที่คนอ่านเห็นเป็นช่วง แต่ที่อยู่ที่เครื่องอ่านเหลือข้อเดียว
ป้ายเป็นช่วง = [ร for ร in รายการโยง if re.search(r"[-–—]", ร[3] or "")]
print(f"ป้ายที่คนอ่านเห็นมีขีดช่วง: {len(ป้ายเป็นช่วง)} อัน")
for เล่มต้น, บทต้น, ข้อต้น, ตัวหนังสือ, ที่อยู่ in ป้ายเป็นช่วง:
    print(f"    {เล่มต้น} {บทต้น}:{ข้อต้น} ป้าย {ตัวหนังสือ!r} → ที่อยู่ {ที่อยู่!r}")
print()
จำนวนต่อเชิงอรรถ = Counter()
for โฟลเดอร์เล่ม in sorted((ที่อยู่ข้อมูล / "read").iterdir()):
    if not โฟลเดอร์เล่ม.is_dir():
        continue
    for ไฟล์บท in sorted(โฟลเดอร์เล่ม.glob("*.json")):
        ก้อน = อ่านเจสัน(ไฟล์บท)
        for เชิงอรรถ in ก้อน.get("ตัวบทไทย", {}).get("เชิงอรรถ", []):
            if "โยงไป" in เชิงอรรถ:
                จำนวนต่อเชิงอรรถ[len(เชิงอรรถ["โยงไป"])] += 1
print(f"เชิงอรรถที่มีช่อง `โยงไป`: {sum(จำนวนต่อเชิงอรรถ.values())} อัน")
print(f"  กี่ที่อยู่ต่อเชิงอรรถ: {dict(sorted(จำนวนต่อเชิงอรรถ.items()))}")
print(f"  มากสุดในเชิงอรรถเดียว: {max(จำนวนต่อเชิงอรรถ)} ที่อยู่")
เล่มปลายทาง = set()
for _, _, _, _, ที่อยู่ in รายการโยง:
    ก = re.match(r"^([A-Z0-9]{3})\b", (ที่อยู่ or "").strip())
    if ก:
        เล่มปลายทาง.add(ก.group(1))
print(f"  เล่มปลายทางต่างกัน: {len(เล่มปลายทาง)} เล่ม")
print()
เล่มไม่มี = Counter()
for เล่มต้น, บทต้น, ข้อต้น, ตัวหนังสือ, ที่อยู่ in รายการโยง:
    ก = re.match(r"^([A-Z0-9]{3})\b", (ที่อยู่ or "").strip())
    if ก and ก.group(1) not in เล่มที่มี:
        เล่มไม่มี[ก.group(1)] += 1
print("เล่มที่เราไม่มี แยกตามรหัสเล่ม")
