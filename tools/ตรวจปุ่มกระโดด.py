"""ตรวจว่าที่อยู่ในช่อง `โยงไป` ของเชิงอรรถ ชี้ไปข้อที่เว็บเรามีจริงไหม

ทำไมต้องมี — ดีไซเนอร์จะเอาช่อง `โยงไป` ไปทำปุ่มกดกระโดด
ถ้าที่อยู่ชี้ไปข้อที่ไม่มี ผู้อ่านกดแล้วไปไหนไม่ได้

รันแบบนี้
    py -3.14 tools/ตรวจปุ่มกระโดด.py C:/gh/phrakham3/public/data
ไม่ใส่ที่อยู่ = ใช้ public/data ในโฟลเดอร์นี้
"""
import io
import json
import re
import sys
from collections import Counter
from pathlib import Path

ที่อยู่ข้อมูล = Path(sys.argv[1] if len(sys.argv) > 1 else "public/data")

# รูปแบบที่อยู่ที่เครื่องอ่านได้ เช่น "MRK 9:29" หรือ "MRK 9:29-31"
แบบข้อเดียว = re.compile(r"^([A-Z0-9]{3})\s+(\d+):(\d+)$")
แบบช่วง = re.compile(r"^([A-Z0-9]{3})\s+(\d+):(\d+)-(\d+)$")
แบบช่วงข้ามบท = re.compile(r"^([A-Z0-9]{3})\s+(\d+):(\d+)-(\d+):(\d+)$")
แบบทั้งบท = re.compile(r"^([A-Z0-9]{3})\s+(\d+)$")


def อ่านเจสัน(ที่):
    with io.open(ที่, encoding="utf-8") as ฟ:
        return json.load(ฟ)


# ---------- ① สร้างตารางว่าเรามีข้ออะไรบ้าง ----------
สารบัญ = อ่านเจสัน(ที่อยู่ข้อมูล / "index.json")
เล่มที่มี = set(สารบัญ["เล่ม"].keys())

มีเนื้อ = {}      # (เล่ม, บท, ข้อ) -> True ถ้ามีตัวหนังสือ
ข้อว่าง = set()   # (เล่ม, บท, ข้อ) ที่มีเลขแต่ไม่มีเนื้อ
บทที่มี = set()   # (เล่ม, บท)

for โฟลเดอร์เล่ม in sorted((ที่อยู่ข้อมูล / "read").iterdir()):
    if not โฟลเดอร์เล่ม.is_dir():
        continue
    เล่ม = โฟลเดอร์เล่ม.name
    for ไฟล์บท in sorted(โฟลเดอร์เล่ม.glob("*.json")):
        ก้อน = อ่านเจสัน(ไฟล์บท)
        บท = int(ก้อน["บท"])
        บทที่มี.add((เล่ม, บท))
        ข้อทั้งหมด = ก้อน.get("ตัวบทไทย", {}).get("ข้อ", {})
        เลขที่มี = set()
        for เลขข้อ, ตัวหนังสือ in ข้อทั้งหมด.items():
            คีย์ = (เล่ม, บท, int(เลขข้อ))
            เลขที่มี.add(int(เลขข้อ))
            ว่าง = not str(ตัวหนังสือ).strip()
            มีเนื้อ[คีย์] = not ว่าง
            if ว่าง:
                ข้อว่าง.add(คีย์)
        # ข้อว่างของ TCV ไม่มีคีย์ในช่อง `ข้อ` เลย ⇒ เห็นเป็นเลขที่ขาดหายกลางบท
        # เชิงอรรถของข้อนั้นติดป้าย `ข้อไม่มีเนื้อ` ไว้ ใช้ยืนยันซ้ำได้
        if เลขที่มี:
            for ขาด in set(range(1, max(เลขที่มี) + 1)) - เลขที่มี:
                ข้อว่าง.add((เล่ม, บท, ขาด))
        for เชิงอรรถ in ก้อน.get("ตัวบทไทย", {}).get("เชิงอรรถ", []):
            if เชิงอรรถ.get("ข้อไม่มีเนื้อ"):
                ข้อว่าง.add((เล่ม, บท, int(เชิงอรรถ["ข้อ"])))

# ---------- ② เก็บที่อยู่ทุกอันในช่อง `โยงไป` ----------
รายการโยง = []  # (เล่มต้นทาง, บทต้นทาง, ข้อต้นทาง, ตัวหนังสือ, ที่อยู่)
for โฟลเดอร์เล่ม in sorted((ที่อยู่ข้อมูล / "read").iterdir()):
    if not โฟลเดอร์เล่ม.is_dir():
        continue
    เล่ม = โฟลเดอร์เล่ม.name
    for ไฟล์บท in sorted(โฟลเดอร์เล่ม.glob("*.json")):
        ก้อน = อ่านเจสัน(ไฟล์บท)
        บท = int(ก้อน["บท"])
        for เชิงอรรถ in ก้อน.get("ตัวบทไทย", {}).get("เชิงอรรถ", []):
            for โยง in เชิงอรรถ.get("โยงไป", []):
                รายการโยง.append(
                    (เล่ม, บท, เชิงอรรถ.get("ข้อ"),
                     โยง.get("ตัวหนังสือ", ""), โยง.get("ที่อยู่", ""))
                )


# ---------- ③ ตรวจทีละอัน ----------
def ตรวจข้อเดียว(เล่ม, บท, ข้อ):
    """คืนชื่อผลตรวจของข้อเดียว"""
    if เล่ม not in เล่มที่มี:
        return "ไม่มีเล่มนี้"
    if (เล่ม, บท) not in บทที่มี:
        return "ไม่มีบทนี้"
    if (เล่ม, บท, ข้อ) in ข้อว่าง:
        return "ข้อว่างไม่มีเนื้อ"
    if (เล่ม, บท, ข้อ) not in มีเนื้อ:
        return "ข้อเกินจำนวนข้อในบท"
    return "ชี้ถึง"


ผลรวม = Counter()
ตัวอย่าง = {}
รูปแบบที่พบ = Counter()
รายการช่วง = []

for เล่มต้น, บทต้น, ข้อต้น, ตัวหนังสือ, ที่อยู่ in รายการโยง:
    ที่อยู่ = (ที่อยู่ or "").strip()
    แหล่ง = f"{เล่มต้น} {บทต้น}:{ข้อต้น}"

    ก = แบบข้อเดียว.match(ที่อยู่)
    if ก:
        รูปแบบที่พบ["ข้อเดียว"] += 1
        ผล = ตรวจข้อเดียว(ก.group(1), int(ก.group(2)), int(ก.group(3)))
    else:
        ข = แบบช่วง.match(ที่อยู่) or แบบช่วงข้ามบท.match(ที่อยู่)
        ค = แบบทั้งบท.match(ที่อยู่)
        if ข:
            รูปแบบที่พบ["ช่วง"] += 1
            เล่ม, บท, ข้อแรก = ข.group(1), int(ข.group(2)), int(ข.group(3))
            รายการช่วง.append((แหล่ง, ที่อยู่, ตัวหนังสือ))
            ผล = ตรวจข้อเดียว(เล่ม, บท, ข้อแรก)  # กระโดดไปข้อแรกของช่วง
        elif ค:
            รูปแบบที่พบ["ทั้งบท"] += 1
            เล่ม, บท = ค.group(1), int(ค.group(2))
            if เล่ม not in เล่มที่มี:
                ผล = "ไม่มีเล่มนี้"
            elif (เล่ม, บท) not in บทที่มี:
                ผล = "ไม่มีบทนี้"
            else:
                ผล = "ชี้ถึง"
        else:
            รูปแบบที่พบ["อ่านไม่ออก"] += 1
            ผล = "รูปแบบอ่านไม่ออก"

    ผลรวม[ผล] += 1
    ตัวอย่าง.setdefault(ผล, [])
    if len(ตัวอย่าง[ผล]) < 5:
        ตัวอย่าง[ผล].append(f"{แหล่ง} → {ที่อยู่!r} (เขียนไว้ว่า {ตัวหนังสือ!r})")


