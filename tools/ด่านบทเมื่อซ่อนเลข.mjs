    //   ⇒ กล่อง *ลงไปดูคำภาษาเดิมที่ท้ายบท* (`[data-ป้ายคำเดิมท้ายบท]` ⇒ จอแคบ · ไหลต่อเนื่อง · เปิดคำภาษาเดิม) อยู่ใต้ชื่อบทและเหนือข้อแรก
