    //   ⇒ ⛔ ใช้กับการนับช่องอ่าน (`กิน`) เท่านั้น ⇒ ข้อ ① ยังเทียบหมุดกับ **ข้อแรกจริง** (`บท[].บน`) ⇒ ⛔ ไม่หลวมลง ⇒ ช่องเผื่อเท่าเดิม
