const บทที่ควร = (น) => Number(Object.entries(น.กิน).reduce((a, b) => (b[1] > a[1] ? b : a), ['0', -Infinity])[0])

/** ①②③ ใน 1 สภาพ ⇒ `ยัดกฎเดิม` เป็นจริงเฉพาะโหมดพิสูจน์ ⇒ คืน `{หมุด, ป้าย, อื่น}` แยกกัน ⇒ ฝาแฝดดูได้ว่าข้อไหนจับได้ */
async function ตรวจสภาพ(ส, ยัดกฎเดิม = false) {
  const ชื่อ = `จอ ${ส.กว้าง} · ${ส.จัดวาง} · ${ส.ภาษาเดิม ? 'เปิด' : 'ปิด'}คำภาษาเดิม`
  const ผล = { หมุด: [], ป้าย: [], อื่น: [] }
  const { ctx, แท็บ } = await เปิด(ส, ทางเริ่ม)
  try {
    if (ยัดกฎเดิม) await แท็บ.addStyleTag({ content: กฎเดิม })
    let น = await ภาพนิ่ง(แท็บ)
    // ⚠️ ใบ #145 ข้อ 4 (พี่เอมเคาะ 7 พ.ย. 2569) ⇒ TCV · LSV · คำเดิม วางข้างกันไม่พอที่จอ 768 กับ 1280 ⇒ คำเดิมเป็นช่องในตารางฉบับ ⇒ ตัวบท ⛔ เป็นตารางแถว
    //   ⇒ สภาพที่พังจริง (หมุดในตารางแถว) ยังถูกตรวจที่จอ 1920 ⇒ จอนั้นต้องเป็นตารางเสมอ ⇒ จอ 768 กับ 1280 ต้องเป็นตารางหรือช่องในตาราง
    if (ส.ภาษาเดิม && ส.กว้าง >= 768 && !น.ตาราง && (ส.กว้าง >= 1920 || !น.ในช่อง))
      ผล.อื่น.push(`${ชื่อ} ⇒ ตัวบท ⛔ ไม่เป็นตาราง ⇒ สภาพที่พังจริงไม่ได้ถูกตรวจ`)

    // ③ หมุดยังเป็นหัวเรื่องที่โปรแกรมอ่านหน้าจอได้ยิน ⇒ และตายังไม่เห็น
    for (const ห of น.หมุด) {
      if (ห.กว้าง > 1.5 || ห.สูง > 1.5)
        ผล.อื่น.push(`③ ${ชื่อ} ⇒ หมุดบท ${ห.บท} ตาเห็น (${Math.round(ห.กว้าง)} × ${Math.round(ห.สูง)} จุด) ⇒ ซ่อนเลขแล้วต้องซ่อนจากตา`)
    }
    const หัวเรื่อง = await แท็บ.getByRole('heading', { level: 2, name: /2\s*โครินธ์\s*6$/ }).count()
    if (!หัวเรื่อง) ผล.อื่น.push(`③ ${ชื่อ} ⇒ ต้นไม้การเข้าถึง ⛔ ไม่มีหัวเรื่องระดับ 2 "2 โครินธ์ 6" ⇒ โปรแกรมอ่านหน้าจอกระโดดข้ามบทไม่ได้`)
    const เลขข้อ = await แท็บ.evaluate(() => [...document.querySelectorAll('.pk-ตัวบท .pk-เลขข้อ')].filter((x) => (x.textContent || '').trim()).length)
    if (!เลขข้อ) ผล.อื่น.push(`③ ${ชื่อ} ⇒ ⛔ ไม่มีเลขข้อเหลือในหน้าให้โปรแกรมอ่านหน้าจออ่าน`)

    // ② เลื่อนลงจนข้ามเข้าบท 7 ไปอีก 2 จังหวะ ⇒ แล้วเลื่อนขึ้นจนกลับบท 6 ไปอีก 2 จังหวะ
    const ก้าว = Math.round(น.สูงช่องอ่าน * 0.45)
    for (const [ทิศ, ปลายทาง] of [[1, 7], [-1, 6]]) {
      let ถึง = -1
      let ข้าม = false
      for (let i = 0; i < 40 && (ถึง < 0 || i < ถึง + 2); i++) {
        await แท็บ.mouse.wheel(0, ทิศ * ก้าว)
        const { น: ตอนนี้, ผิด } = await รอป้ายตรง(แท็บ)
        for (const x of ตรวจหมุด(ตอนนี้)) if (!ผล.หมุด.includes(`① ${ชื่อ} ⇒ ${x}`)) ผล.หมุด.push(`① ${ชื่อ} ⇒ ${x}`)
        if (ผิด.length) {
          ผล.ป้าย.push(`② ${ชื่อ} ⇒ เลื่อน${ทิศ > 0 ? 'ลง' : 'ขึ้น'} ⇒ ${ผิด.join(' · ')}`)
          break
        }
        if (บทที่ควร(ตอนนี้) === ปลายทาง && ถึง < 0) {
          ถึง = i
          ข้าม = true
        }
      }
      if (!ข้าม && !ผล.ป้าย.length)
        ผล.อื่น.push(`② ${ชื่อ} ⇒ เลื่อน${ทิศ > 0 ? 'ลง' : 'ขึ้น'} 40 จังหวะแล้ว ⛔ ไม่ข้ามเข้าบท ${ปลายทาง} ⇒ ด่านไม่ได้ตรวจการข้ามบท`)
    }
  } finally {
    await ctx.close()
  }
  return ผล
}

