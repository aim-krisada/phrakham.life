/** เลขบทท้ายป้าย ⇒ *2 โครินธ์ 7* ⇒ 7 · *2 โครินธ์ 8:5* ⇒ 8 */
function บทบนป้าย(คำ) {
  const m = คำ.match(/(\d+)(?::\d+)?\s*$/)
  return m ? Number(m[1]) : null
}

/** ① หมุดแต่ละตัวอยู่ระหว่างข้อท้ายของบทก่อน กับข้อแรกของบทตัวเอง ⇒ คืนรายการที่ผิด */
function ตรวจหมุด(น) {
  const ผิด = []
  const ของบท = new Map(น.บท.map((x) => [x.บท, x]))
  for (const ห of น.หมุด) {
    const ตัว = ของบท.get(ห.บท)
    if (!ตัว) continue
    const ก่อน = ของบท.get(ห.บท - 1)
    const ล่างสุด = ตัว.บน + 2
    const บนสุด = (ก่อน ? ก่อน.ล่าง : น.บนตัวบท) - 2
    if (ห.บน > ล่างสุด || ห.บน < บนสุด) {
      ผิด.push(
        `หมุดบท ${ห.บท} อยู่ที่ ${Math.round(ห.บน)} ⇒ ต้องอยู่ระหว่าง ${Math.round(บนสุด)} ` +
          `(${ก่อน ? `ข้อท้ายของบท ${ห.บท - 1}` : 'ต้นตัวบท'}) กับ ${Math.round(ล่างสุด)} (ข้อแรกของบท ${ห.บท})`,
      )
    }
  }
  return ผิด
}

/** ② ป้ายทุกป้ายที่วาดอยู่ต้องบอกบทที่ข้อกินช่องอ่านมากที่สุด ⇒ เผื่อตรงรอยต่อบท ⇒ คืนรายการที่ผิด */
function ตรวจป้าย(น) {
  const คู่ = Object.entries(น.กิน).map(([c, v]) => [Number(c), v])
  if (!คู่.length) return ['หาข้อบนหน้าไม่เจอ']
  const [ดีสุด, มากสุด] = คู่.reduce((a, b) => (b[1] > a[1] ? b : a))
  const ผิด = []
  if (!น.ป้าย.length) return ['ไม่มีป้ายบอกบทที่ตาเห็นเลย']
  for (const ป of น.ป้าย) {
    const c = บทบนป้าย(ป.คำ)
    const ได้ = น.กิน[c] ?? -Infinity
    if (มากสุด - ได้ > น.สูงช่องอ่าน * ช่องเผื่อ) {
      ผิด.push(
        `${ป.ที่}เขียน "${ป.คำ}" ⇒ แต่ข้อของบท ${ดีสุด} กินช่องอ่าน ${Math.round(มากสุด)} จุด ` +
          `· บท ${c} กิน ${ได้ === -Infinity ? 'ไม่มีบนหน้า' : `${Math.round(ได้)} จุด`}`,
      )
    }
  }
  return ผิด
}

/** เปิดหน้าใหม่ในบริบทใหม่ ⇒ ⛔ ค่าที่เว็บจำไว้จากรอบก่อนไม่ปนเข้ามา ⇒ ตั้งฉบับกับมุมมองก่อนโค้ดของเว็บติด */
async function เปิด({ กว้าง, จัดวาง, ภาษาเดิม, แสดงเลข = false }, ทาง) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: 900 } })
  await ctx.addInitScript(
    ([ฉ, ม]) => {
      localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
      localStorage.setItem('phrakham.view', JSON.stringify(ม))
    },
    [ฉบับ, { จัดวาง, แสดงเลข, ภาษาเดิม }],
  )
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForFunction(() => !!document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  await แท็บ.evaluate(() => document.fonts.ready.then(() => true))
  // ⭐ รอของจริง ⇒ บท 6 ขึ้นจอ · สวิตช์ซ่อนเลขติดแล้ว · เปิดคำภาษาเดิมที่จอกว้าง ⇒ รอจนตารางแถวมาถึง
  await แท็บ.waitForFunction(
    ([ซ่อน, ตาราง]) => {
      const ตัวบท = document.querySelector('.pk-ตัวบท')
      if (!ตัวบท || !document.querySelector('.pk-ตัวบท [data-ข้อ^="6:"]')) return false
      if (ตัวบท.classList.contains('pk-ซ่อนเลข') !== ซ่อน) return false
      // ⭐ ใบ #145 ข้อ 4 ⇒ ที่วางทุกคอลัมน์ข้างกันไม่พอ ⇒ คำเดิมเป็นช่องในตารางฉบับ (`pk-คำเดิมในช่อง`) ⇒ ตัวบท ⛔ เป็นตารางแถวแล้ว
      const ในช่อง = !!document.querySelector('.pk-คอลัมน์.pk-คำเดิมในช่อง')
      return (
        !ตาราง || ((getComputedStyle(ตัวบท).display === 'grid' || ในช่อง) && !!document.querySelector('.pk-ชั้นคำ'))
      )
    },
    [!แสดงเลข, ภาษาเดิม && กว้าง >= 768],
    { timeout: 30000 },
  )
  await แท็บ.waitForTimeout(400)
  return { ctx, แท็บ }
}

/** รอจนป้ายตรง หรือจนหมดเส้นตาย ⇒ คืนภาพนิ่งสุดท้ายกับรายการที่ผิด ⇒ ⛔ ไม่รอเป็นเวลาตายตัว */
async function รอป้ายตรง(แท็บ, เส้นตาย = 3000) {
  const จบ = Date.now() + เส้นตาย
  let น, ผิด
  do {
    await แท็บ.waitForTimeout(120)
    น = await ภาพนิ่ง(แท็บ)
    ผิด = ตรวจป้าย(น)
  } while (ผิด.length && Date.now() < จบ)
  return { น, ผิด }
}

