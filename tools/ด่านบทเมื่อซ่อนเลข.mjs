  // ⚠️ ใบ #145 ข้อ 4 ⇒ ของเดิมจอ 1280 ⇒ จอนั้นคำเดิมเป็นช่องในตารางฉบับแล้ว ⇒ ตารางแถวที่พังจริงอยู่จอ 1920
