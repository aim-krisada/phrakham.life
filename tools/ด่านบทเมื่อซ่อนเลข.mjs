// ---------------------------------------------------------------- ⑤ กดไปข้อจากแผงเปลี่ยนตอน ⇒ ไปข้างหน้าแล้วย้อนกลับ
/** ทางเดียวกับผู้อ่าน ⇒ ปุ่มเปลี่ยนตอน ⇒ เล่ม ⇒ บท ⇒ ข้อ ⇒ ท่าเดียวกับ `กดเลือก` ใน `tools/ด่านไปถึงข้อ.mjs` */
async function ไปข้อจากแผง(แท็บ, บท, ข้อ) {
  await ปุ่มเปลี่ยนตอนของหน้า(แท็บ).click()
  const แผง = แท็บ.locator('[role="dialog"]')
  await แผง.waitFor()
  await แผง.getByRole('button', { name: /^2\s*โครินธ์/ }).first().click()
  await แผง.locator('.pk-ตารางเลข button').filter({ hasText: new RegExp(`^${บท}$`) }).first().click()
  // ⭐ ปุ่ม *ทั้งบท* คือสัญญาณว่าถึงก้าวเลือกข้อแล้ว ⇒ ⛔ ไม่รอ = กดเลขข้อไปโดนตารางบทที่ยังค้างอยู่
  await แผง.locator('.pk-ปุ่มกว้าง').filter({ hasText: 'ทั้งบท' }).waitFor()
  await แผง.locator('.pk-ตารางเลข button').filter({ hasText: new RegExp(`^${ข้อ}$`) }).first().click()
  await แท็บ.waitForSelector(`.pk-ตัวบท [data-ข้อ="${บท}:${ข้อ}"]`)
}
