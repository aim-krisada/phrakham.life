// ด่านตรวจ — **เชิงอรรถของผู้แปลต้องขึ้นครบ อยู่กับฉบับของมัน และกดเปิดอ่านได้จริง**
//
// **นี่คือด่าน ⛔ ไม่ใช่รายงาน** — ล้มแล้วคืนรหัสไม่เป็นศูนย์ ⇒ ท่อ CI แดง
//
// **ทำไมต้องมี** — เครื่องหมายเป็นชิ้นที่แทรกเข้าไปกลางตัวบท ⇒ หายเงียบได้โดยหน้ายังดูปกติ
//   ⇒ และ @krisada เคาะ 21 พ.ย. 2569 ว่า **เชิงอรรถเป็นของฉบับไหน อยู่กับฉบับนั้น** ⛔ ไม่รวมข้ามฉบับ
//
// **ตรวจ 5 ข้อ บนหน้าจริงที่เปิดด้วยเบราว์เซอร์** (มาระโก 1 เปิดครบทุกฉบับ)
//   ① ทุกฉบับที่หลังบ้านส่งเชิงอรรถมา ⇒ **เครื่องหมายที่ตาเห็นบนหน้าต้องเท่าจำนวนที่ส่งมา**
//   ② ฉบับที่หลังบ้าน ⛔ ไม่ได้ส่งเชิงอรรถมา ⇒ **ห้ามมีเครื่องหมายสักอัน** ⇒ ⛔ ห้ามยืมของฉบับอื่น
//   ③ เครื่องหมาย ⛔ ไม่มีตัวหนังสือในหน้า ⇒ ตัวอักษรวาดด้วย CSS ⇒ คัดลอกหรือแชร์ข้อแล้ว ⛔ ไม่ติด ก ข ค ไปด้วย
//   ④ กดเครื่องหมายแรกของ TCV ⇒ **แผ่นเปิด และตัวหนังสือในแผ่นตรงกับที่หลังบ้านส่งมาทุกตัว**
//      ⇒ Escape ปิดแผ่น
//      ⚠️ เครื่องหมาย ⛔ ไม่ใช่ปุ่ม (ข้อทั้งข้อเป็นปุ่มอยู่แล้ว) ⇒ ทางของแป้นพิมพ์ยังไม่มี ⇒ ด่านนี้จึงยังไม่ตรวจโฟกัส
//   ⑤ มัทธิว 17 ⇒ ข้อ 21 มีเลขแต่ไม่มีเนื้อ ⇒ เครื่องหมายเกาะท้ายข้อ 20 ⇒ **หัวแผ่นต้องบอกเลขข้อ 21**
//   ⑦ WEB ไม่ได้ฝังที่อยู่ ⇒ ที่อยู่ที่อ่านจากตัวหนังสือต้องกดได้ในแผ่น (@krisada 21 พ.ย. 2569 ⇒ "ทุกเล่ม")
//   ⑥ เชิงอรรถเดียวกันโยงไป มก.9:29 ⇒ **กดแล้วเปิดคอลัมน์ใหม่ของมาระโก** และแผ่นปิด (@krisada 21 พ.ย. 2569)
//
// **พิสูจน์ว่าด่านแดงได้จริง** ⇒ `node tools/ด่านเชิงอรรถบนหน้า.mjs <ที่อยู่เว็บ> --ทดสอบตัวเอง`
//   ⇒ ยัดกฎซ่อนเครื่องหมายทั้งหมด ⇒ **ข้อ ① ต้องแดง**
import { chromium } from 'playwright'
import { เส้นทางเว็บ, เพิ่มฉบับจนครบ, รอโค้ดของเว็บติด } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')
const ที่ตก = []
const กฎที่พัง = `.pk-เครื่องหมายเชิงอรรถ { display: none !important; }`

const เบราว์เซอร์ = await chromium.launch()
const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
const แท็บ = await ctx.newPage()

async function เปิด(ทาง) {
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await รอโค้ดของเว็บติด(แท็บ)
  await แท็บ.waitForTimeout(300)
}
const จากหลังบ้าน = (เล่ม, บท) =>
  แท็บ.evaluate(async (ทาง) => await (await fetch(ทาง)).json(), `${ฐาน}/api/chapter/${เล่ม}/${บท}.json`)
const ตัวหนังสือของ = (ก) => ก.ชิ้น.map((ช) => ช.ตัวหนังสือ).join('').trim()

// ── มาระโก 1 ครบทุกฉบับ
await เปิด('/read/MRK/?c=1')
if (ทดสอบตัวเอง) await แท็บ.addStyleTag({ content: กฎที่พัง })
await เพิ่มฉบับจนครบ(แท็บ, 99)
const บท1 = await จากหลังบ้าน('MRK', 1)
const ส่งมา = บท1.เชิงอรรถ || {}

const บนหน้า = await แท็บ.evaluate(() => {
  const ออก = {}
  for (const ช่อง of document.querySelectorAll('.pk-ช่องฉบับ[data-ฉบับ]')) {
    const ฉ = ช่อง.getAttribute('data-ฉบับ')
    const ก = (ออก[ฉ] ||= { เห็น: 0, ทั้งหมด: 0, มีตัวหนังสือ: 0 })
    for (const ม of ช่อง.querySelectorAll('.pk-เครื่องหมายเชิงอรรถ')) {
      ก.ทั้งหมด++
      const r = ม.getBoundingClientRect()
      if (r.width > 0 && r.height > 0 && getComputedStyle(ม).visibility !== 'hidden') ก.เห็น++
      if (ม.textContent) ก.มีตัวหนังสือ++
    }
  }
  return ออก
})

if (!Object.keys(ส่งมา).length) ที่ตก.push('① หลังบ้านไม่ส่งเชิงอรรถของมาระโก 1 มาเลยสักฉบับ ⇒ ซองเชิงอรรถหาย')
for (const [ฉ, รายการ] of Object.entries(ส่งมา)) {
  const ของ = บนหน้า[ฉ]
  if (!ของ) {
    ที่ตก.push(`① ${ฉ}: หาช่องของฉบับนี้บนหน้าไม่เจอ`)
    continue
  }
  if (ของ.เห็น !== รายการ.length)
    ที่ตก.push(`① ${ฉ}: หลังบ้านส่งเชิงอรรถมา ${รายการ.length} อัน ⇒ ตาเห็นบนหน้า ${ของ.เห็น} อัน`)
}
for (const [ฉ, ของ] of Object.entries(บนหน้า)) {
  if (!ส่งมา[ฉ] && ของ.ทั้งหมด)
    ที่ตก.push(`② ${ฉ}: ไม่มีเชิงอรรถของตัวเอง แต่บนหน้ามีเครื่องหมาย ${ของ.ทั้งหมด} อัน ⇒ ยืมของฉบับอื่นมา`)
  if (ของ.มีตัวหนังสือ) ที่ตก.push(`③ ${ฉ}: เครื่องหมาย ${ของ.มีตัวหนังสือ} อันมีตัวหนังสือในหน้า ⇒ คัดลอกข้อแล้วติดไปด้วย`)
}

// ── ④ กดเครื่องหมายแรกของ TCV
if (ส่งมา.TCV?.length && !ทดสอบตัวเอง) {
  const ปุ่ม = แท็บ.locator('.pk-ช่องฉบับ[data-ฉบับ="TCV"] .pk-เครื่องหมายเชิงอรรถ').filter({ visible: true }).first()
  await ปุ่ม.click()
  const แผ่น = แท็บ.locator('.pk-แผ่นเชิงอรรถ')
  if (!(await แผ่น.isVisible())) ที่ตก.push('④ กดเครื่องหมายแรกของ TCV แล้วแผ่นเชิงอรรถไม่ขึ้น')
  else {
    const ในแผ่น = ((await แผ่น.locator('p').textContent()) || '').trim()
    if (ในแผ่น !== ตัวหนังสือของ(ส่งมา.TCV[0]))
      ที่ตก.push(`④ ตัวหนังสือในแผ่นไม่ตรงกับหลังบ้าน ⇒ แผ่น ${ในแผ่น.length} ตัว · หลังบ้าน ${ตัวหนังสือของ(ส่งมา.TCV[0]).length} ตัว`)
    await แท็บ.keyboard.press('Escape')
    await แท็บ.waitForTimeout(200)
    if (await แผ่น.count()) ที่ตก.push('④ กด Escape แล้วแผ่นเชิงอรรถไม่ปิด')
  }
}

// ── ⑦ WEB ไม่ได้ฝังที่อยู่ไว้ ⇒ เราอ่านจากตัวหนังสือ (เช่น Malachi 3:1) ⇒ ในแผ่นต้องกดได้เหมือน TCV
if (!ทดสอบตัวเอง) {
  const ที่ = (ส่งมา.WEB || []).findIndex((x) => x.โยงไป?.length)
  if (ที่ < 0) ที่ตก.push('⑦ มาระโก 1 ของ WEB ไม่มีเชิงอรรถที่มีที่อยู่ข้ออื่นเลย ⇒ ตัวอ่านที่อยู่จากตัวหนังสือหาย')
  else {
    await แท็บ.locator('.pk-ช่องฉบับ[data-ฉบับ="WEB"] .pk-เครื่องหมายเชิงอรรถ').filter({ visible: true }).nth(ที่).click()
    const n = await แท็บ.locator('.pk-แผ่นเชิงอรรถ .pk-ที่อยู่ในเชิงอรรถ').count()
    if (n !== ส่งมา.WEB[ที่].โยงไป.length)
      ที่ตก.push(`⑦ เชิงอรรถ WEB มีที่อยู่ ${ส่งมา.WEB[ที่].โยงไป.length} ที่ ⇒ ในแผ่นกดได้ ${n} ที่`)
    await แท็บ.keyboard.press('Escape')
  }
}

// ── ⑤ มัทธิว 17:21 ข้อที่มีเลขแต่ไม่มีเนื้อ
if (!ทดสอบตัวเอง) {
  await เปิด('/read/MAT/?c=17')
  const บท17 = await จากหลังบ้าน('MAT', 17)
  const ที่ = (บท17.เชิงอรรถ?.TCV || []).findIndex((x) => x.ข้อเดิม === 21)
  if (ที่ < 0) ที่ตก.push('⑤ หลังบ้านไม่ส่งเชิงอรรถของมัทธิว 17:21 มา ⇒ ข้อที่ไม่มีเนื้อหายเงียบ')
  else {
    await แท็บ.locator('.pk-ช่องฉบับ[data-ฉบับ="TCV"] .pk-เครื่องหมายเชิงอรรถ').filter({ visible: true }).nth(ที่).click()
    const หัว = (await แท็บ.locator('.pk-ป้ายแผ่นเชิงอรรถ').textContent()) || ''
    if (!หัว.includes('21')) ที่ตก.push(`⑤ หัวแผ่นของมัทธิว 17:21 ไม่บอกเลขข้อ 21 ⇒ เห็น "${หัว}"`)
    // ── ⑥ เชิงอรรถนี้โยงไป มก.9:29 ⇒ กดที่อยู่แล้วต้องเปิดคอลัมน์ใหม่ที่มาระโก (จอกว้าง ⇒ ยังไม่เต็มเพดาน)
    const โยง = บท17.เชิงอรรถ.TCV[ที่].โยงไป?.[0]
    const ลิงก์ = แท็บ.locator('.pk-แผ่นเชิงอรรถ .pk-ที่อยู่ในเชิงอรรถ').first()
    if (!โยง || !(await ลิงก์.count())) ที่ตก.push('⑥ เชิงอรรถของมัทธิว 17:21 มีที่อยู่ข้ออื่น แต่ในแผ่นไม่มีอะไรให้กด')
    else {
      const เล่ม = โยง.ที่อยู่.slice(0, 3)
      const ก่อน = await แท็บ.evaluate(() => location.search)
      await ลิงก์.click()
      await แท็บ.waitForTimeout(1500)
      const หลัง = await แท็บ.evaluate(() => location.search)
      if (!decodeURIComponent(หลัง).includes(เล่ม))
        ที่ตก.push(`⑥ กด ${โยง.ตัวหนังสือ} แล้วไม่มีคอลัมน์ของ ${เล่ม} ⇒ ที่อยู่หน้า ${ก่อน} → ${หลัง}`)
      if (await แท็บ.locator('.pk-แผ่นเชิงอรรถ').count()) ที่ตก.push('⑥ กดที่อยู่แล้วแผ่นเชิงอรรถไม่ปิด')
    }
  }
}

await เบราว์เซอร์.close()

if (ทดสอบตัวเอง) {
  const จับได้ = ที่ตก.filter((x) => x.startsWith('①'))
  if (!จับได้.length) {
    console.error('⛔ โหมดพิสูจน์: ซ่อนเครื่องหมายทั้งหมดแล้ว **ด่านยังเขียว** ⇒ ด่านตาบอด')
    process.exit(1)
  }
  console.log(`✅ โหมดพิสูจน์: ด่านยังจับของพังได้ ⇒ ${จับได้[0]}`)
  process.exit(0)
}
if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
const สรุป = Object.entries(ส่งมา).map(([ฉ, ร]) => `${ฉ} ${ร.length} อัน`).join(' · ')
console.log(`✅ เชิงอรรถขึ้นครบ อยู่กับฉบับของมัน และกดเปิดอ่านได้ ⇒ มาระโก 1 ${สรุป} · มัทธิว 17:21 บอกเลขข้อถูก`)
