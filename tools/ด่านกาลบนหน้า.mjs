      const เสียงที่ควร = `กริยา ${ชื่อของ[รหัส[0]]}${คำสั่ง ? ' คำสั่ง' : ''}`
      if (x.เสียง !== เสียงที่ควร) ตก.push(`${ที่} ⇒ ② ชื่อกาลที่โปรแกรมอ่านหน้าจอได้ยินคือ «${x.เสียง}» ⛔ ควรเป็น «${เสียงที่ควร}»`)
