    // ⚠️ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/154 ⇒ ปุ่ม *ความหมาย* ▾ ในหมวดเครื่องมือ ⇒ ย้ายเป็นปุ่มตัว i *คำอธิบายสัญลักษณ์* บนหัวคอลัมน์ภาษาเดิม
    //   ⇒ ปุ่มอยู่บนหัวเลย ⛔ ต้องเปิดอะไรก่อน ⇒ กล่องที่เปิดคือ `กล่องคำอธิบาย` ⇒ เกณฑ์เดิมทุกข้อ (aria-expanded · aria-controls · แถวของทุกกาล · ภาพ · ย่อหน้านำ · ที่มา)
