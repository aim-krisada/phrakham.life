      if (x.กาล && !ควรที่.has(`${x.ข้อ}|${x.i}`)) ตก.push(`${ป้าย}:${x.ข้อ} คำที่ ${x.i + 1} ⇒ ② ⛔ ไม่ใช่กริยา แต่มีสัญลักษณ์`)

