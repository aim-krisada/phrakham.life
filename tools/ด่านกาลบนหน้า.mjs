/** สูตรความต่างของสีตาม WCAG 2.2 ⇒ รับ `rgb(r, g, b)` หรือ `#rrggbb` */
function ค่าสี(c) {
  const m = c.startsWith('#') ? c.slice(1).match(/../g).map((x) => parseInt(x, 16)) : c.match(/\d+(\.\d+)?/g).slice(0, 3).map(Number)
  return m
}
function ความสว่าง(c) {
  const [r, g, b] = ค่าสี(c).map((v) => {
    const s = v / 255
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const ต่างกัน = (a, b) => {
  const [x, y] = [ความสว่าง(a), ความสว่าง(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}

