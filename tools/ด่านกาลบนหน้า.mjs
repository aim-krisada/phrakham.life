          const แถว = อธิบาย.แถว[กาล]
          if (!แถว) ตก.push(`${ป้าย} ⇒ ③ สัญลักษณ์ที่ไม่มีคำอธิบาย ⇒ กาล ${กาล} โผล่บนหน้าแต่ ⛔ ไม่มีในคำอธิบาย`)
