#!/usr/bin/env python3
"""เอาไฟล์ตัวบทของเจ้าของขึ้นเว็บ **ทั้งไฟล์** ⛔ ไม่แกะ ไม่ยุบป้าย

รัน: py -3.14 tools/ส่งตัวบทขึ้นเว็บ.py          ⇒ สร้าง `_data/ตัวบท/` ใหม่ทั้งกอง
     py -3.14 tools/ส่งตัวบทขึ้นเว็บ.py --ตรวจ   ⇒ แกะของที่คอมมิตไว้ เทียบกับไฟล์ต้นทางทีละไบต์

ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/74 ก้อนที่ 2

## ⭐ ทำไมเลิกแกะเอง

ไฟล์ที่เจ้าของตัวบทให้มา เป็นรูปมาตรฐานของวงการแปลพระคัมภีร์ชื่อ USX
⇒ มีคู่มือทางการอยู่ที่ <https://ubsicap.github.io/usx/> บอกว่าป้ายไหนหมายถึงอะไร
⇒ ตัวแปลงเดิมของเรายุบป้ายของเขาให้เหลือไม่กี่กลุ่ม ⇒ **ของหายโดยไม่จำเป็น**
   (จำนวนที่ยุบไป อยู่ในใบงาน ⛔ ไม่พิมพ์ซ้ำที่นี่)
⇒ ใบนี้จึงส่งไฟล์ของเขาขึ้นทั้งไฟล์ ⇒ ⭐ **ของครบกว่า แลกกับไฟล์ที่ใหญ่กว่าเดิม**
   ⇒ ใหญ่กว่าเพราะแบกของที่ตัวแปลงเดิมทิ้งไป ⇒ เชิงอรรถ หัวเรื่องกลางบท คำนำหน้าเล่ม
     และที่อ้างอิงคู่ขนาน ⇒ นั่นคือสิ่งที่ได้มาแลกกับขนาด
   ⇒ ⛔ **เทียบขนาดต้องนับฉบับให้เท่ากันก่อน** ⇒ ของเดิม `_data/เนื้อบท.json.gz` มี 4 ฉบับ
     กองใหม่มี 3 ⇒ เอาสองเลขนั้นมาเทียบตรง ๆ จะได้คำตอบกลับข้าง
   ⇒ ขนาดของกองใหม่ อ่านจาก `docs/ข้อมูล/ผลชั่งusx.md` ⛔ ไม่พิมพ์ซ้ำที่นี่

## ⛔ ที่นี่ ⛔ ไม่แตะตัวอักษรสักตัว — แต่ **บีบ** ไฟล์

**ทำไมต้องบีบ** ⇒ เครื่องพี่เอมตั้ง `core.autocrlf=true` ⇒ เป็นค่าของ **เครื่อง** ⛔ ไม่ใช่ของที่เก็บ
⇒ ไฟล์ของเจ้าของลงท้ายบรรทัดเป็น CRLF และมีเครื่องหมายนำหน้าไฟล์ (BOM)
⇒ ⛔ เก็บเป็นไฟล์ข้อความเมื่อไร โต๊ะที่เช็กเอาต์ใหม่จะได้ไบต์ไม่เท่าเดิม ⇒ **เลิกเป็นของเจ้าของทันที**
⇒ ⛔ `.gitattributes` **ไม่มีบรรทัดคลุมนามสกุล `.usx`** ⇒ กิตจึงปล่อยให้ค่าของเครื่องตัดสิน
   ⇒ ถามกิตเองได้ ⇒ `git check-attr text -- _data/ตัวบท/TCV/GEN.usx` ⇒ ตอบว่า `unspecified`
⇒ ⭐ บีบด้วย gzip แล้วเก็บแบบไฟล์ก้อน ⇒ **ไบต์ข้างในเท่าเดิมเป๊ะ** และท่อ CI ดึงโฟลเดอร์นี้อยู่แล้ว
   ⇒ นามสกุล `.gz` มีบรรทัดคลุมอยู่ใน `.gitattributes` จริง และตั้งว่าไม่ใช่ไฟล์ข้อความ
   ⇒ ถามกิตเองได้ ⇒ `git check-attr text -- _data/ตัวบท/TCV/GEN.usx.gz` ⇒ ตอบว่า `unset`

**บีบแบบไม่ประทับเวลา** ⇒ บีบซ้ำกี่รอบก็ได้ไฟล์เดิมทุกไบต์ ⇒ ด่านเทียบจึงเชื่อถือได้

## ⭐ `--ตรวจ` เทียบอะไรกับอะไร

แกะไฟล์ที่คอมมิตไว้ออกมา แล้วเทียบกับ **ไฟล์ต้นทางในกอง** ทีละไบต์
⇒ ⛔ ไม่ใช่เทียบกับของที่สคริปต์นี้เพิ่งสร้าง ⇒ เทียบกับของที่สร้างเอง คือถามตัวเองว่าตัวเองถูกไหม
"""

import argparse
import gzip
import io
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ตัวบทusx import ปลายทาง, ฉบับ, สารบบ, ยังไม่ได้  # noqa: E402
from สร้างข้อมูลเว็บ import ควรได้  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ที่เก็บ = Path(__file__).resolve().parent.parent
บัญชี = ปลายทาง / "บัญชี.json"

# แท็กเปิดข้อของ USX ⇒ คู่มือ <https://ubsicap.github.io/usx/elements.html#verse>
#   บอกว่าข้อหนึ่งมีสองหมุด ⇒ หมุดเปิดมี `sid` หมุดปิดมี `eid` ⇒ **นับหมุดเปิดอย่างเดียว**
#   ⛔ นับทั้งสองแบบ = ได้เลขสองเท่า
แท็กข้อ = re.compile(r"<verse [^>]*\bsid=")


def ตาย(ข้อความ, รหัส=1):
    print(f"⛔ {ข้อความ}")
    sys.exit(รหัส)


def บีบ(ไบต์):
    """gzip แรงสุด ⛔ ไม่ประทับชื่อไฟล์และเวลา ⇒ บีบซ้ำได้ไฟล์เดิมทุกไบต์"""
    ถัง = io.BytesIO()
    with gzip.GzipFile(fileobj=ถัง, mode="wb", compresslevel=9, mtime=0) as ซ:
        ซ.write(ไบต์)
    return ถัง.getvalue()


def เก็บต้นทาง():
    """คืน {รหัสฉบับ: {เล่ม: ไบต์ของไฟล์ USX}} ⇒ ขาดเล่มไหนก็หยุดพร้อมบอกชื่อ"""
    ของ = {}
    for ฉ in ฉบับ:
        ราย = {}
        ขาด = []
        for เล่ม in สารบบ:
            ทาง = ฉ.ไฟล์usx(เล่ม)
            if not ทาง.exists():
                ขาด.append(เล่ม)
                continue
            ราย[เล่ม] = ทาง.read_bytes()
        if ขาด:
            เพิ่ม = ""
            if ฉ.รูป == "usfm":
                เพิ่ม = "\n   ⇒ ฉบับนี้ต้องแปลงก่อน ⇒ สั่ง node tools/แปลงusfmเป็นusx.mjs"
            ตาย(f"{ฉ.รหัส} ขาด {len(ขาด)} เล่ม ⇒ {' '.join(ขาด[:10])}{เพิ่ม}")
        ของ[ฉ.รหัส] = ราย
    return ของ


def นับข้อ(ราย):
    """นับแท็กเปิดข้อทั้งฉบับ ⇒ เลขนี้เทียบกับที่ `tools/สร้างข้อมูลเว็บ.py` ตรึงไว้ได้"""
    return sum(len(แท็กข้อ.findall(ไบต์.decode("utf-8"))) for ไบต์ in ราย.values())


def ด่านนับข้อ(ของ):
    """⛔ ไม่ตรงแม้ข้อเดียวคือหยุด ⇒ เกณฑ์ผ่านของใบ #74

    ⭐ **ตัวเลขที่ควรได้ ⛔ ไม่พิมพ์ซ้ำที่นี่** ⇒ อ่านจาก `tools/สร้างข้อมูลเว็บ.py`
       ซึ่งเป็นเจ้าของเลขชุดนั้นมาตั้งแต่ใบ #23 ⇒ `ข้อ` + `ว่าง` = จำนวนแท็กข้อในไฟล์ของเขา
    """
    ผิด = []
    for ฉ in ฉบับ:
        ได้ = นับข้อ(ของ[ฉ.รหัส])
        ตรึง = ควรได้[ฉ.รหัส]
        ควร = ตรึง["ข้อ"] + ตรึง["ว่าง"]
        เครื่องหมาย = "✅" if ได้ == ควร else "⛔"
        print(f"   {เครื่องหมาย} {ฉ.รหัส:<6} แท็กข้อ {ได้:,} ⇒ ที่ตรึงไว้ {ควร:,}")
        if ได้ != ควร:
            ผิด.append(f"{ฉ.รหัส} ได้ {ได้:,} ⇒ ควรได้ {ควร:,}")
    if ผิด:
        ตาย("จำนวนข้อไม่ตรงกับที่ตรึงไว้ ⇒ " + " · ".join(ผิด)
            + "\n   ⇒ เปิดของจริงดูก่อน ⛔ ห้ามแก้เลขที่ตรึงไว้ให้เตือนหาย")


def ห่อ(ของ):
    """คืน {ชื่อไฟล์ญาติใต้ `_data/ตัวบท/`: ไบต์ที่จะเขียน}"""
    ออก = {}
    for ฉ in ฉบับ:
        for เล่ม, ไบต์ in ของ[ฉ.รหัส].items():
            ออก[f"{ฉ.รหัส}/{เล่ม}.usx.gz"] = บีบ(ไบต์)
    ดัชนี = {
        "รูปแฟ้ม": "USX ⇒ https://ubsicap.github.io/usx/",
        "ฉบับ": {ฉ.รหัส: {"เจ้าของ": ฉ.เจ้าของ,
                          "เล่ม": sorted(ของ[ฉ.รหัส], key=สารบบ.index)} for ฉ in ฉบับ},
        "ยังไม่ได้": ยังไม่ได้,
    }
    ออก["บัญชี.json"] = (json.dumps(ดัชนี, ensure_ascii=False, sort_keys=True,
                                    separators=(",", ":")) + "\n").encode("utf-8")
    return ออก


def ที่มีอยู่จริง():
    if not ปลายทาง.exists():
        return {}
    return {p.relative_to(ปลายทาง).as_posix(): p.read_bytes()
            for p in sorted(ปลายทาง.rglob("*")) if p.is_file()}


def ตรวจ(ของ, ใหม่):
    """แกะของที่คอมมิตไว้ เทียบกับไฟล์ต้นทาง ⇒ คืนจำนวนที่ผิด"""
    เดิม = ที่มีอยู่จริง()
    if not เดิม:
        ตาย(f"ไม่มีกองที่ {ปลายทาง} ให้เทียบ ⇒ สั่ง py -3.14 tools/ส่งตัวบทขึ้นเว็บ.py ก่อน")
    ผิด = 0
    for ชื่อ in sorted(set(เดิม) | set(ใหม่)):
        if ชื่อ not in เดิม:
            print(f"   ⛔ {ชื่อ} หายไปจากกองที่คอมมิตไว้")
            ผิด += 1
            continue
        if ชื่อ not in ใหม่:
            print(f"   ⛔ {ชื่อ} เกินมาในกอง ⇒ ไม่มีไฟล์ต้นทางรองรับ")
            ผิด += 1
            continue
        if เดิม[ชื่อ].startswith(b"version https://git-lfs"):
            ตาย(f"{ปลายทาง / ชื่อ} เป็นตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง\n"
                '   ⇒ สั่ง git lfs pull -I "_data/" ก่อน', 2)
        if เดิม[ชื่อ] != ใหม่[ชื่อ]:
            print(f"   ⛔ {ชื่อ} ไบต์ไม่ตรงกับที่ห่อใหม่ ⇒ {len(เดิม[ชื่อ]):,} ⇒ {len(ใหม่[ชื่อ]):,}")
            ผิด += 1

    # ⭐ ด่านที่สำคัญที่สุด ⇒ แกะไฟล์ที่คอมมิตไว้ แล้วเทียบกับ **ไฟล์ของเจ้าของ** ทีละไบต์
    for ฉ in ฉบับ:
        for เล่ม, ต้น in ของ[ฉ.รหัส].items():
            ชื่อ = f"{ฉ.รหัส}/{เล่ม}.usx.gz"
            if ชื่อ not in เดิม:
                continue
            # ไฟล์ที่ถูกตัดหัวตัดท้าย จะแกะไม่ออกเลย ⇒ ต้องบอกให้ชัด ⛔ ไม่ปล่อยให้ตายเป็นข้อความช่าง
            try:
                แกะ = gzip.decompress(เดิม[ชื่อ])
            except (OSError, EOFError) as ข้อผิด:
                print(f"   ⛔ {ชื่อ} แกะไม่ออก ⇒ ไฟล์เสีย ⇒ {ข้อผิด}")
                ผิด += 1
                continue
            if แกะ != ต้น:
                print(f"   ⛔ {ชื่อ} แกะออกมาแล้ว ⛔ ไม่เหมือนไฟล์ต้นทาง {ฉ.ไฟล์usx(เล่ม)}")
                ผิด += 1
    return ผิด


def main():
    ก = argparse.ArgumentParser(description="เอาไฟล์ตัวบทของเจ้าของขึ้นเว็บ — ใบงาน #74")
    ก.add_argument("--ตรวจ", dest="check", action="store_true",
                   help="แกะของที่คอมมิตไว้ เทียบกับไฟล์ต้นทางทีละไบต์ ⛔ ไม่เขียนอะไร")
    ต = ก.parse_args()

    print("=== อ่านไฟล์ตัวบทของเจ้าของ")
    ของ = เก็บต้นทาง()
    for ฉ in ฉบับ:
        ที่มา = "ไฟล์ของเจ้าของโดยตรง" if ฉ.รูป == "usx" else "แปลงจาก USFM ด้วยตัวแปลงมาตรฐาน"
        print(f"   {ฉ.รหัส:<6} {len(ของ[ฉ.รหัส])} เล่ม · {ที่มา}")
    if ยังไม่ได้:
        for รหัส, เหตุ in ยังไม่ได้.items():
            print(f"   ⏸ {รหัส} ยังไม่ได้ขึ้น ⇒ {เหตุ}")

    print("=== นับแท็กข้อ เทียบกับที่ตรึงไว้")
    ด่านนับข้อ(ของ)

    ใหม่ = ห่อ(ของ)
    รวม = sum(len(ข) for ข in ใหม่.values())

    if ต.check:
        print("=== เทียบของที่คอมมิตไว้ กับไฟล์ต้นทาง")
        ผิด = ตรวจ(ของ, ใหม่)
        if ผิด:
            ตาย(f"ไม่ตรง {ผิด} ที่ ⇒ ⛔ อย่าเพิ่งเชื่อว่าของบนเว็บคือของเจ้าของ")
        print(f"\n✅ ของที่คอมมิตไว้ตรงกับไฟล์ต้นทางทุกไบต์ ⇒ {len(ใหม่):,} ไฟล์")
        return 0

    ปลายทาง.mkdir(parents=True, exist_ok=True)
    for p in sorted(ปลายทาง.rglob("*"), reverse=True):
        if p.is_file():
            p.unlink()
    for ชื่อ, ไบต์ in ใหม่.items():
        ทาง = ปลายทาง / ชื่อ
        ทาง.parent.mkdir(parents=True, exist_ok=True)
        ทาง.write_bytes(ไบต์)
    print(f"\n✅ เขียน {len(ใหม่):,} ไฟล์ · รวม {รวม / 1048576:,.2f} MiB ⇒ ที่ {ปลายทาง}")
    print(f"   บัญชีเล่มอยู่ที่ {บัญชี.relative_to(ที่เก็บ)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
