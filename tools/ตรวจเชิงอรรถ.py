#!/usr/bin/env python3
"""ตรวจว่าเชิงอรรถที่ `อ่าน_usx` เก็บมา ครบและเกาะข้อถูกที่หรือไม่

ใบงาน  https://github.com/aim-krisada/phrakham3/issues/6

ตรวจ 6 ข้อ
  ① ตัวบทเดิมกับรอยแบ่งไม่เปลี่ยน ⇒ ต้องได้ 31,087 ข้อ · ข้อว่าง 16 · รอยแบ่ง 40,827 อันเท่าเดิม
  ② จำนวนเชิงอรรถที่เก็บได้ เท่ากับจำนวนป้าย <note> ที่นับจากไฟล์ USX ตรง ๆ
  ③ จำนวนชิ้นส่วนแต่ละชนิด (fr ft fqa fq fv xt) เท่ากับที่นับจากไฟล์ดิบ
  ④ `ที่อยู่เดิม` ที่เจ้าของเขียนกำกับไว้ ตรงกับข้อที่เราให้มันเกาะ
  ⑤ ข้อที่มีเลขแต่ไม่มีเนื้อ มีเชิงอรรถกี่ข้อ ⇒ พิมพ์รายชื่อออกมาให้ดูด้วยตา
  ⑥ `หลังอักษร` ของเชิงอรรถกลางข้อ ไม่เกินความยาวของข้อนั้น

⛔ สคริปต์นี้อ่านอย่างเดียว ไม่เขียนไฟล์อะไรเลย

รัน  py -3.14 tools/ตรวจเชิงอรรถ.py
"""
import collections
import io
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
ที่เก็บ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ที่เก็บ, 'tools'))
import สร้างข้อมูลเว็บ as ตัวแปลง  # noqa: E402

USX = os.path.join(ที่เก็บ, '_แตก', 'tcv', 'usx-rev2-release', 'release', 'USX_1')

# หมุดของใบ #60 ⇒ รอยแบ่งต้องได้เท่าเดิมเป๊ะ ⛔ งานนี้ห้ามทำให้ตัวเลขนี้ขยับ
หมุดรอยแบ่งใบ60 = 40827


def ช่วงข้อ(เดิม):
    """แตกส่วนหลัง `:` ของที่อยู่เดิมออกเป็นชุดเลขข้อ ⇒ `24:6-8` ⇒ {6, 7, 8}"""
    หลัง = เดิม.split(':', 1)[1] if ':' in เดิม else ''
    ได้ = set()
    for ก้อน in re.split(r'[,;\s]+', หลัง):
        m = re.match(r'^(\d+)\s*[-–]\s*(\d+)$', ก้อน)
        if m:
            ได้ |= set(range(int(m.group(1)), int(m.group(2)) + 1))
        elif ก้อน.isdigit():
            ได้.add(int(ก้อน))
    return ได้


def นับจากไฟล์ดิบ():
    """เปิดไฟล์ USX นับป้าย <note> กับชิ้นส่วนข้างในตรง ๆ ⇒ เป็นตัวหารว่ามีอะไรตกหล่นไหม"""
    เชิงอรรถ = 0
    ชิ้น = collections.Counter()
    เชิงอรรถที่มี = collections.Counter()
    for รหัส in ตัวแปลง.สารบบ:
        ราก = ET.parse(os.path.join(USX, รหัส + '.usx')).getroot()
        for n in ราก.iter('note'):
            เชิงอรรถ += 1
            มี = set()
            for e in n.iter():
                t = ตัวแปลง.ชื่อสั้น(e.tag)
                ป = e.get('style') if t == 'char' else ('ref' if t == 'ref' else None)
                if ป:
                    ชิ้น[ป] += 1
                    มี.add(ป)
            for ป in มี:
                เชิงอรรถที่มี[ป] += 1
    return เชิงอรรถ, ชิ้น, เชิงอรรถที่มี


def main():
    ข้อ, _, ว่าง, รอย, เชิงอรรถ = ตัวแปลง.อ่าน_usx(USX, 'TCV')
    ควร = ตัวแปลง.ควรได้['TCV']
    รวมรอย = sum(len(v) for v in รอย.values())
    print('① ตัวบทเดิม ⇒ ได้ %s ข้อ (ควรได้ %s) · ข้อว่าง %s (ควรได้ %s) · รอยแบ่ง %s (ควรได้ %s)'
          % (format(len(ข้อ), ','), format(ควร['ข้อ'], ','), len(ว่าง), ควร['ว่าง'],
             format(รวมรอย, ','), format(หมุดรอยแบ่งใบ60, ',')))

    ดิบเชิงอรรถ, ดิบชิ้น, ดิบมี = นับจากไฟล์ดิบ()
    ได้ = sum(len(v) for v in เชิงอรรถ.values())
    print('\n② เชิงอรรถ ⇒ เก็บได้ %s อัน · ในไฟล์ดิบ %s อัน'
          % (format(ได้, ','), format(ดิบเชิงอรรถ, ',')))

    ทั้งหมด = [ร for v in เชิงอรรถ.values() for ร in v]
    นับชนิด = collections.Counter(ร['ชนิด'] for ร in ทั้งหมด)
    print('   แยกชนิด ⇒ %s'
          % ' · '.join('%s %s' % (k, format(v, ',')) for k, v in นับชนิด.most_common()))

    เราชิ้น = collections.Counter()
    เรามี = collections.Counter()
    for ร in ทั้งหมด:
        for ป in ร['มีป้าย']:
            เรามี[ป] += 1
        for ก in ร['ชิ้น']:
            if ก['ป้าย']:
                เราชิ้น[ก['ป้าย']] += 1
        เราชิ้น['fr'] += 1 if ร.get('ที่อยู่เดิม') else 0
        เราชิ้น['ref'] += len(ร.get('โยงไป', []))
    print('\n③ %-6s %12s %12s %12s %12s' % ('ป้าย', 'ชิ้นที่เก็บ', 'ชิ้นในไฟล์ดิบ',
                                             'เชิงอรรถที่มี', 'ในไฟล์ดิบ'))
    for ป in sorted(set(ดิบชิ้น) | set(เราชิ้น)):
        print('   %-6s %12s %12s %12s %12s'
              % (ป, format(เราชิ้น[ป], ','), format(ดิบชิ้น[ป], ','),
                 format(เรามี[ป], ','), format(ดิบมี[ป], ',')))
    print('   ⚠️ ช่อง "ชิ้นที่เก็บ" นับ **ท่อนตัวหนังสือ** ⇒ ป้ายที่ครอบป้ายอื่นไว้ '
          '(ft ครอบ xt) จะถูกหั่นเป็นหลายท่อน ⇒ มากกว่าจำนวนป้ายในไฟล์ดิบได้')
    print('   ⇒ ช่องที่ต้องตรงเป๊ะคือ "เชิงอรรถที่มี" กับ "ในไฟล์ดิบ"')

    # ④ ที่อยู่เดิมที่เจ้าของเขียนกำกับ (`fr`) ต้องชี้ข้อเดียวกับที่เราให้เกาะ
    # ⚠️ **เจ้าของเขียนที่อยู่ไว้ 4 แบบ ⛔ ไม่ใช่แบบเดียว** ⇒ เทียบตรง ๆ แล้วแดงมั่ว 200 อัน
    #    `17:21` ข้อเดียว · `28:20,21` หลายข้อ · `24:6-8` เป็นช่วง
    #    `32` แค่เลขบท ⇒ เชิงอรรถเกาะอยู่นอกข้อ (อยู่ในหัวข้อย่อยหรือก่อนข้อ 1)
    #    `6:0` ข้อ 0 ⇒ หัวสดุดี ซึ่งฝั่งไทยไม่นับเป็นข้อ ⇒ เราให้ไปเกาะข้อ 1
    แยก = collections.Counter()
    เพี้ยน = []
    for (เล่ม, บท), รายการ in เชิงอรรถ.items():
        for ร in รายการ:
            เดิม = ร.get('ที่อยู่เดิม', '')
            m = re.match(r'^\s*(\d+)(?:[:.](\d+))?', เดิม)
            if not m or int(m.group(1)) != บท:
                แยก['⛔ อ่านเลขบทไม่ออก หรือบทไม่ตรง'] += 1
                เพี้ยน.append((เล่ม, บท, ร['ข้อ'], เดิม))
            elif m.group(2) is None:
                แยก['เจ้าของเขียนแค่เลขบท ⇒ เชิงอรรถอยู่นอกข้อ'] += 1
            elif int(m.group(2)) == ร['ข้อ']:
                แยก['ตรงเป๊ะ'] += 1
            elif int(m.group(2)) == 0:
                แยก['เจ้าของเขียนข้อ 0 ⇒ หัวสดุดี ⇒ เกาะข้อ 1'] += 1
            elif ร['ข้อ'] in ช่วงข้อ(เดิม):
                แยก['เจ้าของเขียนเป็นช่วงหรือหลายข้อ ⇒ ข้อที่เกาะอยู่ในนั้น'] += 1
            else:
                แยก['⛔ ไม่ตรง'] += 1
                เพี้ยน.append((เล่ม, บท, ร['ข้อ'], เดิม))
    print('\n④ เทียบที่อยู่เดิมที่เจ้าของเขียนกำกับ กับข้อที่เราให้เกาะ')
    for k, v in แยก.most_common():
        print('   %-52s %s' % (k, format(v, ',')))
    for x in เพี้ยน[:8]:
        print('   ⛔ %s %s ⇒ เกาะข้อ %s · เจ้าของเขียนว่า "%s"' % x)

    # ⑤ ⭐ หัวใจของงานนี้ ⇒ ข้อที่มีเลขแต่ไม่มีเนื้อ มีเชิงอรรถอธิบายไหม
    มีเชิงอรรถ = collections.defaultdict(list)
    for (เล่ม, บท), รายการ in เชิงอรรถ.items():
        for ร in รายการ:
            if ร.get('ข้อไม่มีเนื้อ'):
                มีเชิงอรรถ['%s %s.%s' % (เล่ม, บท, ร['ข้อ'])].append(ร)
    ขาด = [k for k in ว่าง if k not in มีเชิงอรรถ]
    print('\n⑤ ข้อที่มีเลขแต่ไม่มีเนื้อ %s ข้อ ⇒ มีเชิงอรรถ %s ข้อ · ไม่มี %s ข้อ'
          % (len(ว่าง), len(ว่าง) - len(ขาด), len(ขาด)))
    for k in ว่าง:
        ร = มีเชิงอรรถ.get(k)
        print('   %-12s %s' % (k, ร[0]['ตัวหนังสือ'] if ร else '⛔ ไม่มีเชิงอรรถ'))

    # ⑥ `หลังอักษร` ต้องไม่เกินความยาวของข้อ
    ล้น = [(เล่ม, บท, ร['ข้อ'], ร['หลังอักษร'])
           for (เล่ม, บท), รายการ in เชิงอรรถ.items() for ร in รายการ
           if not ร.get('ข้อไม่มีเนื้อ')
           and ร['หลังอักษร'] > len(ข้อ[(เล่ม, str(บท), str(ร['ข้อ']))])]
    print('\n⑥ เชิงอรรถที่ `หลังอักษร` ล้นความยาวของข้อ %s อัน' % format(len(ล้น), ','))
    for x in ล้น[:5]:
        print('   %s %s.%s ที่ %s' % x)

    return 0


if __name__ == '__main__':
    sys.exit(main())
