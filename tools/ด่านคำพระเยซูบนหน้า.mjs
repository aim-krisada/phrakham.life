// ด่านตรวจ — **คำที่พระเยซูพูดต้องขึ้นสีบนหน้าจริง และตัวบทต้องไม่หายไปแม้ตัวเดียว**
//
// **นี่คือด่าน ⛔ ไม่ใช่รายงาน** — ล้มแล้วคืนรหัสไม่เป็นศูนย์ ⇒ ท่อ CI แดง
//
// **ทำไมต้องมี** — การใส่สีคือการ **ตัดตัวบทออกเป็นชิ้น ๆ แล้วเอากล่องไปครอบบางชิ้น**
//   ⇒ ⛔ **ตัดพลาดเมื่อไร ตัวอักษรหายหรือซ้ำ โดยหน้าเว็บยังดูปกติทุกอย่าง**
//   ⇒ และช่วงเป็น *ตำแหน่งตัวอักษร* ⇒ เลื่อนไป 1 ตัว **สีก็ไปอยู่ผิดคำ** โดยไม่มีอะไรเตือน
//
// **ด่านนี้ตรวจ 4 ข้อ บนหน้าจริงที่เปิดด้วยเบราว์เซอร์**
//   ① **ตัวบทที่ต่อกลับจากชิ้นทั้งหมด ต้องเท่ากับตัวบทที่หลังบ้านส่งมา ทุกตัวอักษร**
//      ⇒ นี่คือข้อที่สำคัญที่สุด ⇒ มันจับทั้งตัวอักษรหาย ตัวอักษรซ้ำ และลำดับสลับ
//   ② **ฉบับที่เจ้าของทำเครื่องหมายไว้ ต้องมีชิ้นที่ถูกเน้นจริง** ⇒ ⛔ ไม่ใช่ศูนย์ชิ้น
//   ③ **ฉบับที่เจ้าของ ⛔ ไม่ได้ทำเครื่องหมายไว้ ต้องไม่มีสักชิ้น** ⇒ พี่เอมสั่งเอง
//      *"ถ้าข้อมูลไม่มีไม่ต้องทำ ทำเฉพาะเล่มที่มี"* ⇒ ⛔ ห้ามเดาจากฉบับอื่น
//   ④ **สีที่ตาเห็นต้องต่างจากสีตัวบทจริง** ⇒ วัดจาก `getComputedStyle` ของจริงบนหน้า
//      ⇒ ⛔ ไม่ได้อ่านค่าจากไฟล์ CSS ⇒ ค่าในไฟล์ถูกทับได้
//
// **วิธีพิสูจน์ว่าด่านนี้แดงได้จริง** ⛔ อย่าเชื่อว่ามันเฝ้าอยู่
//   `node tools/ด่านคำพระเยซูบนหน้า.mjs <ที่อยู่เว็บ> --ทดสอบตัวเอง`
//   ⇒ ยัดกฎที่ทำให้สีของชิ้นที่เน้น กลายเป็นสีเดียวกับตัวบท ⇒ **ข้อ ④ ต้องแดง**
import { chromium } from 'playwright'
import { เส้นทางเว็บ, เพิ่มฉบับจนครบ } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')
const ทดสอบตัวเอง = process.argv.includes('--ทดสอบตัวเอง')
const ที่ตก = []

// ยอห์น 3 ⇒ บทที่มีคำพระเยซูหนาแน่น และเป็นบทที่คนเปิดบ่อยที่สุด
const บทที่ใช้ = 'JHN'
const เลขบท = 3

/** ฉบับที่เจ้าของทำเครื่องหมาย `wj` ไว้ ⇒ เจ้าของความจริงคือ `tools/สร้างคำพระเยซู.py` */
const ฉบับที่ต้องมีสี = ['TCV', 'THKJV']
/** ⛔ ฉบับที่เจ้าของไม่ได้ทำเครื่องหมายไว้ ⇒ ต้อง ⛔ ไม่มีสักชิ้น */
const ฉบับที่ต้องไม่มีสี = ['WEB', 'LSV']

/** กฎที่ทำให้สีหาย ⇒ ใช้เฉพาะโหมดพิสูจน์ว่าด่านยังจับได้ ⛔ ไม่ใช่ของที่อยู่ในเว็บจริง */
const กฎที่พัง = `.pk-คำพระเยซู { color: inherit; }`

const เบราว์เซอร์ = await chromium.launch()

async function เปิด(แท็บ, ทาง) {
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, {
    timeout: 30000,
  })
  await แท็บ.waitForTimeout(300)
}

/** เปิดทุกฉบับ ⇒ จะได้เห็นทั้งฉบับที่มีสีและที่ไม่มีพร้อมกัน */
async function เลือกทุกฉบับ(แท็บ) {
  // ⭐ ทางเดียวกับผู้อ่าน ⇒ เมนู *เทียบ* (ใบงาน #102 · ชื่อจากใบ #113) ⇒ 99 = เปิดครบทุกฉบับที่มี
  //   ⇒ ⛔ ไม่พิมพ์ชื่อฉบับไว้ในด่าน ⇒ วันไหนเพิ่มฉบับ ด่านนี้ตรวจให้เองทันที
  await เพิ่มฉบับจนครบ(แท็บ, 99)
}

const ctx = await เบราว์เซอร์.newContext({ viewport: { width: 1280, height: 900 } })
const แท็บ = await ctx.newPage()
await เปิด(แท็บ, `/read/${บทที่ใช้}/?c=${เลขบท}`)
if (ทดสอบตัวเอง) await แท็บ.addStyleTag({ content: กฎที่พัง })
await เลือกทุกฉบับ(แท็บ)

// ── ของจริงจากหลังบ้าน ⇒ เอาไว้เทียบว่าตัวบทบนหน้าไม่หายไปไหน
const จากหลังบ้าน = await แท็บ.evaluate(
  async (ทาง) => await (await fetch(ทาง)).json(),
  `${ฐาน}/api/chapter/${บทที่ใช้}/${เลขบท}.json`,
)

const บนหน้า = await แท็บ.evaluate(() => {
  const ออก = {}
  for (const ช่อง of document.querySelectorAll('.pk-ช่องฉบับ')) {
    const ฉบับ = ช่อง.getAttribute('data-ฉบับ')
    if (!ฉบับ) continue
    const เน้น = ช่อง.querySelectorAll('.pk-คำพระเยซู')
    const ก่อน = ออก[ฉบับ] || { ชิ้นที่เน้น: 0, สี: null, สีตัวบท: null }
    ก่อน.ชิ้นที่เน้น += เน้น.length
    if (!ก่อน.สี && เน้น.length) ก่อน.สี = getComputedStyle(เน้น[0]).color
    if (!ก่อน.สีตัวบท) ก่อน.สีตัวบท = getComputedStyle(ช่อง).color
    ออก[ฉบับ] = ก่อน
  }
  return ออก
})

// ── ① ตัวบทที่ต่อกลับจากชิ้นทั้งหมด ต้องเท่ากับของหลังบ้านทุกตัวอักษร
for (const ฉบับ of Object.keys(จากหลังบ้าน.ชั้น || {})) {
  const ข้อทั้งหมด = จากหลังบ้าน.ชั้น[ฉบับ]
  const บนจอ = await แท็บ.evaluate((ฉ) => {
    const ออก = {}
    for (const ข้อ of document.querySelectorAll('.pk-ข้อ')) {
      const เลข = (ข้อ.id.match(/^ข้อ-\d+-(\d+)$/) || [])[1]
      if (!เลข) continue
      const ช่อง = ข้อ.querySelector(`.pk-ช่องฉบับ[data-ฉบับ="${ฉ}"]`)
      if (!ช่อง) continue
      const เสียงเท่านั้น = ช่อง.querySelector('.pk-เฉพาะเสียง')
      ออก[เลข] = ช่อง.textContent.slice((เสียงเท่านั้น?.textContent || '').length)
    }
    return ออก
  }, ฉบับ)

  let เทียบแล้ว = 0
  for (const [เลข, เนื้อ] of Object.entries(ข้อทั้งหมด)) {
    const ที่เห็น = บนจอ[เลข]
    if (ที่เห็น === undefined) continue
    เทียบแล้ว++
    if (ที่เห็น !== เนื้อ) {
      ที่ตก.push(
        `① ${ฉบับ} ข้อ ${เลข}: ตัวบทบนหน้า ⛔ ไม่ตรงกับที่หลังบ้านส่งมา` +
          ` ⇒ บนหน้า ${ที่เห็น.length} ตัว · หลังบ้าน ${เนื้อ.length} ตัว`,
      )
      break
    }
  }
  if (!เทียบแล้ว) ที่ตก.push(`① ${ฉบับ}: เทียบตัวบทไม่ได้สักข้อ ⇒ หาช่องของฉบับนี้บนหน้าไม่เจอ`)
}

// ── ② ฉบับที่ต้องมีสี ⇒ ต้องมีชิ้นที่เน้นจริง
for (const ฉบับ of ฉบับที่ต้องมีสี) {
  const ของ = บนหน้า[ฉบับ]
  if (!ของ) {
    ที่ตก.push(`② ${ฉบับ}: หาช่องของฉบับนี้บนหน้าไม่เจอ`)
    continue
  }
  if (!ของ.ชิ้นที่เน้น) {
    ที่ตก.push(`② ${ฉบับ}: ⛔ ไม่มีชิ้นที่เน้นเลยสักชิ้น ⇒ สีคำพระเยซูหายไปทั้งฉบับ`)
  }
}

// ── ③ ฉบับที่ต้องไม่มีสี ⇒ ห้ามมีสักชิ้น
for (const ฉบับ of ฉบับที่ต้องไม่มีสี) {
  const ของ = บนหน้า[ฉบับ]
  if (ของ?.ชิ้นที่เน้น) {
    ที่ตก.push(
      `③ ${ฉบับ}: มีชิ้นที่เน้น ${ของ.ชิ้นที่เน้น} ชิ้น ⇒ ⛔ เจ้าของฉบับนี้ไม่ได้ทำเครื่องหมายไว้` +
        ' ⇒ แปลว่ามีคนเดาข้อมูลขึ้นมาเอง',
    )
  }
}

// ── ④ สีที่ตาเห็นต้องต่างจากสีตัวบทจริง
for (const ฉบับ of ฉบับที่ต้องมีสี) {
  const ของ = บนหน้า[ฉบับ]
  if (!ของ?.ชิ้นที่เน้น) continue
  if (ของ.สี === ของ.สีตัวบท) {
    ที่ตก.push(`④ ${ฉบับ}: สีของชิ้นที่เน้นเท่ากับสีตัวบท (${ของ.สี}) ⇒ ตาแยกไม่ออก`)
  }
}

await เบราว์เซอร์.close()

if (ทดสอบตัวเอง) {
  const จับได้ = ที่ตก.filter((x) => x.startsWith('④'))
  const อื่น = ที่ตก.filter((x) => !x.startsWith('④'))
  if (อื่น.length) {
    console.error('⛔ โหมดพิสูจน์: ของจริงบนเว็บก็ไม่ผ่านด้วย ⇒ ไปแก้เว็บก่อน')
    for (const x of อื่น) console.error('  - ' + x)
    process.exit(1)
  }
  if (!จับได้.length) {
    console.error('⛔ โหมดพิสูจน์: ยัดกฎที่ทำให้สีหายแล้ว **ด่านยังเขียว** ⇒ ด่านตาบอด')
    process.exit(1)
  }
  console.log(`✅ โหมดพิสูจน์: ด่านยังจับของพังได้ ⇒ ${จับได้[0]}`)
  process.exit(0)
}

if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} รายการ:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
const สรุป = ฉบับที่ต้องมีสี.map((ฉ) => `${ฉ} ${บนหน้า[ฉ]?.ชิ้นที่เน้น || 0} ชิ้น`).join(' · ')
console.log(`✅ คำพระเยซูขึ้นสีถูกที่ และตัวบทไม่หายสักตัว ⇒ ${สรุป}`)
