/* วัดโครงร่างหน้าหลัก แล้วพิมพ์ตารางตัวเลขออกมา — ใบงาน #33
 *
 *   node tools/วัดโครงร่าง.mjs
 *
 * มีไว้ทำไม
 *   เอกสารแบบหน้าจอเคยจดตัวเลขความสูงหน้าไว้ด้วยมือ แล้วเลขหนึ่งผิดไป 54 จุด
 *   โดยไม่มีอะไรร้อง (คนตรวจจับได้ 30 ส.ค. 2569 · คำขอรวม !21)
 *   ไฟล์นี้คือเจ้าของตัวเลขพวกนั้น ใครสงสัยให้รันเอง ไม่ต้องเชื่อเอกสาร
 *
 * วัดอย่างไร ให้ได้เลขเดียวกันทุกครั้ง
 *   - จอกว้าง 320 สูง 640 จุด คือมือถือเตี้ยที่สุดที่เรารองรับ
 *   - วัดเฉพาะกล่อง #หน้าจอ ซึ่งเป็นตัวหน้าเว็บล้วน
 *     ไม่นับแถบป้ายสีเทากับเส้นขอบของโครงร่าง เพราะสองอย่างนั้นเป็นแผงควบคุม
 *     ไม่ใช่ส่วนหนึ่งของหน้าเว็บ (นับรวมแล้วเลขบวมขึ้นราว 30 จุด)
 *   - ตัวอักษรของเครื่องมีผลกับการขึ้นบรรทัดของภาษาไทย คนละเครื่องเลขอาจต่างกันเล็กน้อย
 *
 * ด่านที่ไฟล์นี้ตรวจให้ด้วย ตกข้อไหนจะจบด้วยรหัส 1
 *   1. ปุ่มกับลิงก์ทุกอันสูงไม่ต่ำกว่า 44 จุด
 *   2. ไม่มีของชิ้นไหนกว้างเกิน 320 จุด คือหน้าไม่เลื่อนซ้ายขวา
 *   3. หน้าแรกต้องมีทางเข้าหน้าแหล่งข้อมูลอย่างน้อย 2 ทาง ยกเว้นแบบ ค ที่ไม่มีหน้าแรกแยก
 *
 * พิสูจน์แล้วว่าแดงได้จริง 30 ส.ค. 2569
 *   ลบบรรทัด min-height ของลิงก์ท้ายหน้าออก แล้วมันฟ้องว่ามีลิงก์สูง 22 ถึง 23 จุด
 *   ทั้ง 3 แบบ และจบด้วยรหัส 1 พอใส่กลับก็เขียวเหมือนเดิม
 */
import { chromium } from 'playwright'
import { pathToFileURL } from 'node:url'
import path from 'node:path'

const ไฟล์ = path.resolve('docs/design/wireframe/หน้าหลัก.html')
const จอกว้าง = 320
const จอสูง = 640
const ปุ่มเตี้ยสุดที่ยอมได้ = 44

const เบราว์เซอร์ = await chromium.launch()
const หน้า = await เบราว์เซอร์.newPage({ viewport: { width: จอกว้าง, height: จอสูง } })
await หน้า.goto(pathToFileURL(ไฟล์).href)

const ผล = []
let ตก = []

for (const แบบ of ['ก', 'ข', 'ค']) {
  await หน้า.click(`[data-แบบ="${แบบ}"]`)
  await หน้า.click('.แผง [data-ขนาด="มือถือ"]')
  const วัด = await หน้า.evaluate((เตี้ยสุด) => {
    const หน้าเว็บ = document.getElementById('หน้าจอ')
    const ของที่กดได้ = [...หน้าเว็บ.querySelectorAll('a, button, input')]
    const เตี้ยเกิน = ของที่กดได้
      .map((e) => ({ ข้อความ: (e.textContent || e.placeholder || '').trim().slice(0, 24), สูง: Math.round(e.getBoundingClientRect().height) }))
      .filter((x) => x.สูง < เตี้ยสุด)
    const ล้นขอบ = [...หน้าเว็บ.querySelectorAll('*')].filter((e) => e.getBoundingClientRect().width > 320).length
    return {
      สูง: +หน้าเว็บ.getBoundingClientRect().height.toFixed(1),
      ทางเข้าแหล่งข้อมูล: [...หน้าเว็บ.querySelectorAll('a')].filter((a) => a.dataset['ไป'] === 'แหล่ง').length,
      หัวเรื่องใหญ่สุด: หน้าเว็บ.querySelectorAll('h1').length,
      ปุ่มหลัก: หน้าเว็บ.querySelectorAll('.ปุ่มหลัก').length,
      เตี้ยเกิน,
      ล้นขอบ,
    }
  }, ปุ่มเตี้ยสุดที่ยอมได้)

  ผล.push({ แบบ, ...วัด })
  if (วัด.เตี้ยเกิน.length) ตก.push(`แบบ ${แบบ} มีของกดได้ที่เตี้ยกว่า ${ปุ่มเตี้ยสุดที่ยอมได้} จุด คือ ${JSON.stringify(วัด.เตี้ยเกิน)}`)
  if (วัด.ล้นขอบ) ตก.push(`แบบ ${แบบ} มีของ ${วัด.ล้นขอบ} ชิ้นกว้างเกิน ${จอกว้าง} จุด`)
  if (แบบ !== 'ค' && วัด.ทางเข้าแหล่งข้อมูล < 2) ตก.push(`แบบ ${แบบ} หน้าแรกมีทางเข้าหน้าแหล่งข้อมูลแค่ ${วัด.ทางเข้าแหล่งข้อมูล} ทาง`)
}

await เบราว์เซอร์.close()

console.log(`วัดที่จอกว้าง ${จอกว้าง} สูง ${จอสูง} จุด · วัดเฉพาะตัวหน้าเว็บ ไม่นับแถบป้ายของโครงร่าง\n`)
console.log('| แบบ | ความสูงของหน้า | อยู่ในจอแรกไหม | ทางเข้าแหล่งข้อมูล | หัวเรื่องใหญ่สุด | ปุ่มหลัก | ของเตี้ยกว่า 44 จุด |')
console.log('|---|---|---|---|---|---|---|')
for (const r of ผล) {
  console.log(`| ${r.แบบ} | ${r.สูง} | ${r.สูง <= จอสูง ? 'อยู่' : 'ไม่อยู่ เกิน ' + (r.สูง - จอสูง).toFixed(1) + ' จุด'} | ${r.ทางเข้าแหล่งข้อมูล} | ${r.หัวเรื่องใหญ่สุด} | ${r.ปุ่มหลัก} | ${r.เตี้ยเกิน.length} |`)
}

if (ตก.length) {
  console.log('\nตก')
  for (const t of ตก) console.log('  - ' + t)
  process.exit(1)
}
console.log('\nผ่านทุกข้อ')
