// ⭐⭐ **ด่านที่ตอบว่า "ป้ายหายระหว่างแปลงไหม"**
//
// USFM เขียนป้ายด้วยเครื่องหมายทับกลับหน้าชื่อ เช่น `\v` `\p` `\wj`
// ป้ายบางชนิดมีตัวปิดลงท้ายด้วยดอกจัน เช่น `\wj*` ⇒ เปิดกับปิดนับเป็น **ป้ายเดียว**
// USX เขียนป้ายเดียวกันเป็นชื่อสไตล์ในแท็ก เช่น `<char style="wj">`
// ⇒ ⭐ **ป้ายชนิดไหนมีกี่ตัวใน USFM ต้องมีเท่ากันใน USX** ⛔ ขาดชนิดเดียวก็หยุด
//
// **ทำไมด่านนี้สำคัญกว่าการนับข้อ** ⇒ นับข้ออย่างเดียวจะเขียวอยู่ดี แม้หัวเรื่องหายทั้งเล่ม
// ⚠️ **ป้ายซ้อนป้าย เขียนด้วยเครื่องหมายบวกนำหน้าชื่อ** เช่น `\+w คำ\+w*`
//    ⇒ ใช้เมื่อป้ายหนึ่งอยู่ข้างในอีกป้าย เช่น คำในถ้อยคำของพระเยซู หรือคำในเชิงอรรถ
//    ⇒ ฝั่ง USX เขียนเหมือนป้ายธรรมดา ⇒ **ที่นี่จึงตัดเครื่องหมายบวกทิ้ง แล้วนับรวมกัน**
//    ⛔ ไม่นับรวม = ฝั่ง USX จะมีมากกว่าเสมอ ⇒ ด่านแดงทั้งที่ของครบ
//    (เจอจริงตอนแปลง WEB ⇒ มัทธิวมีป้ายซ้อนชนิด `w` เกินหมื่นตัว · ใบงาน #80)
// ⚠️ **ชื่อป้ายมีได้แค่ตัวอักษรกับตัวเลข** ⇒ ดอกจันเป็นตัวปิด ⛔ ไม่ใช่ส่วนของชื่อ
//    ⇒ `\f*And` ต้องอ่านเป็นตัวปิดของ `f` แล้วตามด้วยคำว่า And ⛔ ไม่ใช่ป้ายชื่อ `f*And`
function นับป้ายusfm(usfm) {
  const นับ = new Map()
  for (const m of usfm.matchAll(/\\(\+?)([A-Za-z]+[0-9]*)(\*?)/g)) {
    if (m[3] === '*') continue // ตัวปิด ⇒ นับไปแล้วตอนเจอตัวเปิด
    นับ.set(m[2], (นับ.get(m[2]) || 0) + 1)
  }
  return นับ
}

function นับสไตล์usx(usx) {
  const นับ = new Map()
  for (const m of usx.matchAll(/<\w+[^>]*?\sstyle="([^"]+)"/g)) {
    นับ.set(m[1], (นับ.get(m[1]) || 0) + 1)
  }
  return นับ
}

function ป้ายหาย(usfm, usx) {
  const ก = นับป้ายusfm(usfm)
  const ข = นับสไตล์usx(usx)
  const ทัก = []
  for (const [ชื่อ, จำนวน] of ก) {
    const ได้ = ข.get(ชื่อ) || 0
    if (ได้ !== จำนวน) ทัก.push(`${ชื่อ} ${จำนวน} ⇒ ${ได้}`)
  }
  return ทัก
}

// ⭐⭐ **ด่านที่ตอบว่า "ถ้อยคำหายระหว่างแปลงไหม"** ⇒ เกณฑ์ผ่านของใบ #80
//
// ด่านนับป้ายข้างบนดูแต่ **ป้าย** ⇒ คำที่หลุดออกมานอกป้ายจะหายไปเงียบ ๆ ได้
// ⇒ ด่านนี้จึง **ถอดป้ายทิ้งทั้งสองฝั่ง แล้วเทียบถ้อยคำที่เหลือทีละตัวอักษร**
//
// **ฝั่ง USFM ถอดอะไรออก** ⇒ ของที่ USX เก็บเป็น **ช่องข้อมูล** ⛔ ไม่ใช่ถ้อยคำ
//   ช่องหลังขีดตั้ง เช่น `|strong="H1"` ⇒ USX เก็บเป็น `strong="H1"`
//   เลขข้อกับเลขบท เช่น `\v 1` `\c 2` ⇒ USX เก็บเป็น `number="1"`
//   รหัสเล่มหลัง `\id` ⇒ USX เก็บเป็น `code="GEN"`
//   ตัวเรียกเชิงอรรถกับที่อ้างอิง เช่น `\f + ` ⇒ USX เก็บเป็น `caller="+"`
//   แล้วจึงลบชื่อป้ายที่เหลือทั้งหมด
// **ฝั่ง USX ถอดอะไรออก** ⇒ ลบแท็กทั้งอัน ⇒ ชื่อช่องกับค่าในช่องหลุดไปพร้อมแท็ก
//   แล้วคืนตัวอักษรที่ XML เขียนแทนไว้ เช่น `&amp;` กลับเป็น `&`
//
// **ช่องว่างยุบให้เหลือช่องเดียวทั้งสองฝั่ง** ⇒ เพราะการขึ้นบรรทัดใหม่คือตัวคั่นป้ายของ USFM
//   ⇒ พอถอดป้ายออก บางที่จึงเหลือช่องว่างไม่เท่ากัน ⛔ ไม่ใช่ถ้อยคำหาย
//   ⇒ ⚠️ **นี่คือข้อเดียวที่ด่านนี้ยอมให้ต่างได้** ⇒ ตัวอักษรอื่นต่างแม้ตัวเดียวคือแดง
function ถ้อยคำusfm(usfm) {
  return usfm
    .replace(/\|[^\\\n]*/g, ' ')
    .replace(/\\[vc]\s+\S+/g, ' ')
    .replace(/\\id\s+\S+/g, ' ')
    .replace(/\\[fx]\s+\S/g, ' ')
    .replace(/\\\+?[A-Za-z]+[0-9]*\*?/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

// ⚠️ **แท็กกลายเป็นช่องว่าง ⛔ ไม่ใช่หายเฉย ๆ** ⇒ ให้เท่ากับฝั่ง USFM ที่ป้ายกลายเป็นช่องว่าง
//    ⇒ ⛔ ขอถ้อยคำจาก `textContent` ตรง ๆ ไม่ได้ ⇒ มันเชื่อมเนื้อของสองแท็กติดกันเป็นคำเดียว
//      เช่นท้าย `\id` กับ `\ide UTF-8` ⇒ ได้ `(WEB)UTF-8` ⇒ ต่างจากต้นทางทั้งที่ของครบ
function ถ้อยคำusx(usx) {
  return usx
    .replace(/<[^>]*>/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-fA-F]+);/g, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&amp;/g, '&') // ⭐ ตัวสุดท้าย ⇒ ⛔ ไม่งั้น `&amp;lt;` จะกลายเป็น `<`
    .replace(/\s+/g, ' ')
    .trim()
}

// คืนที่แรกที่ต่างกัน ⇒ ตรงกันคืนค่าว่าง
function ถ้อยคำต่าง(usfm, usx) {
  const ก = ถ้อยคำusfm(usfm)
  const ข = ถ้อยคำusx(usx)
  if (ก === ข) return ''
  let i = 0
  while (i < ก.length && i < ข.length && ก[i] === ข[i]) i += 1
  const รอบ = (s) => JSON.stringify(s.slice(Math.max(0, i - 40), i + 40))
  return `ต่างที่ตัวอักษรที่ ${i + 1} จาก ${ก.length} ⇒ ต้นทาง ${รอบ(ก)} ⇒ ที่แปลงแล้ว ${รอบ(ข)}`
}

