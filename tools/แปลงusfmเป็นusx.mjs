// **กฎเดียวที่ใช้** ⇒ USFM แยกป้ายซ้อนด้วยเครื่องหมายบวก (`\+w`) แต่ **USX ไม่มีเครื่องหมายนั้น**
// ⇒ ป้ายซ้อนกับป้ายธรรมดาเขียนเหมือนกันหมดใน USX ⇒ `<char style="w">`
// ⇒ พิสูจน์ได้ด้วยตัวแปลงเอง ⇒ ป้อน `\qs \w Selah|strong="H5542"\w*.\qs*` (ไม่มีบวก) เข้าไป
//   มันคาย `<char style="qs"><char style="w" strong="H5542">Selah</char>.</char>` ออกมา
//   ⇒ **เทสข้างล่างบังคับว่าของที่กฎนี้ปั้น ต้องตรงกับของนั้นทุกตัวอักษร**
const ช่องqs = /\\qs(?![A-Za-z0-9*])([\s\S]*?)\\qs\*/g

function หนีxml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

// อ่านเนื้อข้างในป้ายหนึ่ง แล้วคายเป็น USX ⇒ เรียกตัวเองซ้ำได้ ⇒ ป้ายซ้อนกี่ชั้นก็อ่านออก
function เนื้อเป็นusx(เนื้อ) {
  let ออก = ''
  let i = 0
  const ป้าย = /\\(\+?)([A-Za-z]+[0-9]*)\s/g
  while (i < เนื้อ.length) {
    ป้าย.lastIndex = i
    const เปิด = ป้าย.exec(เนื้อ)
    if (!เปิด) {
      ออก += หนีxml(เนื้อ.slice(i))
      break
    }
    ออก += หนีxml(เนื้อ.slice(i, เปิด.index))
    const ชื่อ = เปิด[2]
    const ปิด = `\\${เปิด[1]}${ชื่อ}*`
    const ที่ปิด = เนื้อ.indexOf(ปิด, ป้าย.lastIndex)
    if (ที่ปิด < 0) throw new Error(`ป้าย \\${ชื่อ} ไม่มีตัวปิด ⇒ ${JSON.stringify(เนื้อ)}`)
    const ข้างใน = เนื้อ.slice(ป้าย.lastIndex, ที่ปิด)
    // ⚠️ ช่องข้อมูลอยู่หลังขีดตั้ง ⇒ `|strong="H5542"` ⇒ USX เก็บเป็นช่องของแท็ก
    const ขีด = ข้างใน.indexOf('|')
    const ถ้อยคำ = ขีด < 0 ? ข้างใน : ข้างใน.slice(0, ขีด)
    let ช่อง = ''
    if (ขีด >= 0) {
      const ดิบ = ข้างใน.slice(ขีด + 1).trim()
      // ⛔ รับเฉพาะรูป `ชื่อ="ค่า"` ⇒ รูปอื่นไม่เดา ⇒ หยุดแล้วให้คนมาดู
      const ทุกช่อง = [...ดิบ.matchAll(/([A-Za-z][A-Za-z0-9-]*)="([^"]*)"/g)]
      const กินไป = ทุกช่อง.reduce((n, m) => n + m[0].length, 0) + Math.max(0, ทุกช่อง.length - 1)
      if (!ทุกช่อง.length || กินไป !== ดิบ.length) {
        throw new Error(`ช่องข้อมูลรูปที่ไม่รู้จัก ⇒ ${JSON.stringify(ดิบ)}`)
      }
      ช่อง = ทุกช่อง.map((m) => ` ${m[1]}="${หนีxml(m[2]).replace(/"/g, '&quot;')}"`).join('')
    }
    ออก += `<char style="${ชื่อ}"${ช่อง}>${เนื้อเป็นusx(ถ้อยคำ)}</char>`
    i = ที่ปิด + ปิด.length
  }
  return ออก
}

// ปั้น USX ของช่อง `\qs …\qs*` หนึ่งช่อง
function qsเป็นusx(ข้างใน) {
  return `<char style="qs">${เนื้อเป็นusx(ข้างใน.replace(/^\s+/, ''))}</char>`
}

// ตัวแปลงทักไว้ ⇒ ทุกจุดที่ทัก ต้องตกอยู่ **ในช่วงตัวอักษรของช่อง `\qs` ที่มีป้ายซ้อน** เท่านั้น
// ⛔ มีจุดอื่นแม้จุดเดียว = ไม่ใช่รูที่เรารู้จัก ⇒ คืนเหตุผล แล้วให้ตัวเรียกหยุด
//
// ⛔ **ดูแค่เลขบรรทัดไม่พอ** ⇒ บรรทัดหนึ่งมีของอย่างอื่นอยู่ข้าง ๆ ช่อง `\qs` ได้
//   ⇒ ของพังคนละเรื่องที่บังเอิญอยู่บรรทัดเดียวกัน จะถูกปล่อยผ่านโดยไม่มีใครรู้
//   (คนตรวจใบ #80 จับได้ 7 ก.ย. 2569 ⇒ จึงเปลี่ยนมาเทียบเป็นช่วงตัวอักษร)
//
// **รูปของจุดทัก** ⇒ `At <บรรทัด>:<ตัวอักษร>, Error: …` ⇒ **นับจากศูนย์ทั้งคู่**
//   ⇒ พิสูจน์เอง: ป้อน `\id PSA⏎\c 3⏎\q1 abc⏎\q2 def \qs \+w Selah|strong="H5542"\+w*.\qs*`
//     ตัวแปลงคายว่า `At 3:12` ⇒ บรรทัดที่ 4 คือเลข 3 · และตัวที่ 13 คือเลข 12 (จุดที่ `\+w` เริ่ม)
// ⚠️ อ่านเลขไม่ออก หรือชี้ไปนอกไฟล์ ⇒ **นับเป็นจุดนอก** ⇒ หยุดไว้ก่อน ⛔ ไม่เดา
function ทักนอกqs(usfm, ทัก) {
  const หัวบรรทัด = [0]
  for (let i = 0; i < usfm.length; i += 1) if (usfm[i] === '\n') หัวบรรทัด.push(i + 1)
  const ช่วงรู = []
  ช่องqs.lastIndex = 0
  for (const m of usfm.matchAll(ช่องqs)) {
    if (!m[1].includes('\\+')) continue
    ช่วงรู.push([m.index, m.index + m[0].length])
  }
  const นอก = ทัก.filter((e) => {
    const m = /^At (\d+):(\d+)/.exec(String(e))
    if (!m) return true
    const บรรทัด = Number(m[1])
    if (บรรทัด >= หัวบรรทัด.length) return true
    const ที่ = หัวบรรทัด[บรรทัด] + Number(m[2])
    return !ช่วงรู.some(([ต้น, ท้าย]) => ที่ >= ต้น && ที่ < ท้าย)
  })
  return นอก.length ? `ทัก ${นอก.length} จุดที่ไม่ใช่ป้ายซ้อนใน \\qs ⇒ ${JSON.stringify(นอก.slice(0, 3))}` : ''
}

// เอา USX ที่ตัวแปลงคายมา แล้วเติมแท็ก `<char style="qs"/>` เปล่าให้เต็มตามต้นทาง
function เติมqsที่หาย(usfm, usx) {
  const ช่อง = [...usfm.matchAll(ช่องqs)].filter((m) => m[1].includes('\\+'))
  const ว่าง = [...usx.matchAll(/<char style="qs"\s*\/>/g)]
  if (ช่อง.length !== ว่าง.length) {
    throw new Error(`ต้นทางมีช่องที่ต้องเติม ${ช่อง.length} ⇒ แต่ที่แปลงแล้วว่างอยู่ ${ว่าง.length}`)
  }
  let ออก = ''
  let ที่ = 0
  ว่าง.forEach((m, n) => {
    ออก += usx.slice(ที่, m.index) + qsเป็นusx(ช่อง[n][1])
    ที่ = m.index + m[0].length
  })
  return { usx: ออก + usx.slice(ที่), จำนวน: ช่อง.length }
}

