import os
import re
import sys
import unicodedata
import xml.etree.ElementTree as ET

ที่เก็บ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LDML = os.path.join(ที่เก็บ, '_แตก', 'tcv', 'usx-rev2-release', 'release', 'tha_th.ldml')
ออกที่ = os.path.join(ที่เก็บ, 'docs', 'ข้อมูล', 'tcv-กติกาไทย.json')
SIL = '{urn://www.sil.org/ldml/0.1}'


def คลายรหัส(ข้อความ):
    r"""เปลี่ยนข้อความ `\uXXXX` ให้เป็นตัวอักษรจริง ⇒ ldml เขียนตัวมองไม่เห็นแบบนี้"""
    return re.sub(r'\\u([0-9A-Fa-f]{4})', lambda m: chr(int(m.group(1), 16)), ข้อความ)


def แกะชุด(ข้อความ):
    """แกะชุดตัวอักษรแบบ ldml `[a b {cd} \\u200C]` ⇒ คืนเป็นรายการชิ้น

    ชิ้นหนึ่งอาจยาวกว่า 1 ตัวอักษร ⇒ ldml ครอบด้วยปีกกาเมื่อชิ้นนั้นเป็นลำดับ
    ช่วงแบบ `\\u0E01-\\u0E30` ⇒ ไล่ออกทีละตัว
    """
    ข้อความ = คลายรหัส((ข้อความ or '').strip())
    if ข้อความ.startswith('[') and ข้อความ.endswith(']'):
        ข้อความ = ข้อความ[1:-1]
    ชิ้น, i = [], 0
    while i < len(ข้อความ):
        ช = ข้อความ[i]
        if ช.isspace():
            i += 1
        elif ช == '{':
            j = ข้อความ.index('}', i)
            ชิ้น.append(ข้อความ[i + 1:j])
            i = j + 1
        elif ช == '\\':                      # แบ็กสแลชหน้าตัวที่ ldml ต้องหนี เช่น \{ \}
            ชิ้น.append(ข้อความ[i + 1])
            i += 2
        elif (i + 2 < len(ข้อความ) and ข้อความ[i + 1] == '-'
              and ข้อความ[i + 2] not in '{}'):
            for o in range(ord(ช), ord(ข้อความ[i + 2]) + 1):
                ชิ้น.append(chr(o))
            i += 3
        else:
            ชิ้น.append(ช)
            i += 1
    return ชิ้น


def ชื่อตัวอักษร(ช):
    """เขียนตัวอักษรให้คนอ่านรู้ว่าคือตัวไหน ⇒ ตัวมองไม่เห็นเห็นแค่ชื่อ"""
    return {'รหัส': 'U+%04X' % ord(ช), 'ชื่อยูนิโคด': unicodedata.name(ช, '(ไม่มีชื่อ)'),
            'หมวด': unicodedata.category(ช)}


# ⭐ **ตัวที่ล้างออกในช่องค้นหา = ตัวอักษรหมวด `Cf` ของยูนิโคด** (format character)
#    หมวดนี้คือตัวที่ **ไม่มีความกว้าง ไม่มีเสียง ไม่มีความหมายให้อ่าน**
#    มันมีหน้าที่บอกโปรแกรมว่าจะจัดวางอย่างไรเท่านั้น ⇒ ตัดออกแล้วคำที่อ่านได้ไม่เปลี่ยน
#    ⛔ **ไม่ไล่กันทีละรหัสด้วยมือ** ⇒ ของใหม่ที่เจ้าของใส่เพิ่มมาทีหลังจะหลุด
#    ⇒ ldml ของเจ้าของยืนยันทางเดียวกัน ⇒ เขาจัด U+200C กับ U+200D
#      ไว้ในชุด **เครื่องหมายวรรคตอน** ⛔ ไม่ใช่ชุดตัวอักษรที่ใช้เขียนคำ
#    ⇒ ล้างแล้วเหลือกี่ตัว ตัวไหนหาย ดูได้จาก `tools/ตรวจกติกาไทย.py`
หมวดที่ล้าง = 'Cf'


def ล้างเพื่อค้นหา(ข้อความ):
    """คืนข้อความที่ล้างตัวมองไม่เห็นออกแล้ว ⇒ ใช้เทียบเวลาค้นหา

    ⛔ **ไม่แตะอะไรอื่นเลย** ⇒ ไม่เล็ม ไม่ยุบช่องว่าง ไม่แปลงรูปสระ
    ⇒ ตัวอักษรที่เหลือเรียงเหมือนเดิมทุกตัว ⇒ พิสูจน์ได้ด้วยข้อ ③ ของตัวตรวจ
    """
    return ''.join(ช for ช in ข้อความ if unicodedata.category(ช) != หมวดที่ล้าง)


def มีตัวมองไม่เห็น(ข้อความ):
    return any(unicodedata.category(ช) == หมวดที่ล้าง for ช in ข้อความ)


def อ่านกติกา(ทาง=LDML):
    """เปิด tha_th.ldml อ่านของที่เจ้าของประกาศไว้ ⇒ คืนเป็นก้อนที่เครื่องอ่านต่อได้"""
    ราก = ET.parse(ทาง).getroot()
    ชุด = {}
    for el in ราก.iter():
        if el.tag == 'exemplarCharacters':
            ชุด[el.get('type') or 'ตัวอักษรที่ใช้เขียน'] = แกะชุด(el.text)
        elif el.tag == SIL + 'exemplarCharacters':
            ชุด[el.get('type')] = แกะชุด(el.text)
    วรรคตอน = ชุด.get('punctuation', [])
    มองไม่เห็น = [ช for ช in วรรคตอน if len(ช) == 1
                  and unicodedata.category(ช) == หมวดที่ล้าง]
    หา = lambda ป: (ราก.findtext('.//' + ป) or '')
    return {
        'ไฟล์ต้นทาง': 'release/tha_th.ldml ในซิปของเจ้าของ',
        'ภาษา': ราก.findtext('.//language') or ราก.find('.//language').get('type'),
        'ตัวอักษรที่ใช้เขียน': ชุด.get('ตัวอักษรที่ใช้เขียน', []),
        'เครื่องหมายวรรคตอน': วรรคตอน,
        'ตัวมองไม่เห็นที่เจ้าของจัดเป็นเครื่องหมายวรรคตอน': [ชื่อตัวอักษร(ช) for ช in มองไม่เห็น],
        'ตัวที่เจ้าของใช้ตัดคำ': [ชื่อตัวอักษร(ช) for ช in ชุด.get('wordBreaks', [])
                                   if len(ช) == 1],
        'ตัวที่เจ้าของใช้ทำเลขเชิงอรรถ': ชุด.get('footnotes', []),
        'ตัวที่เจ้าของใช้ทำเลขที่อ้างอิง': ชุด.get('crossrefs', []),
        'ตัวที่เจ้าของใช้แบ่งท่อนย่อยในข้อ': ชุด.get('verseSegments', []),
        'เครื่องหมายคำพูด': {'เปิด': หา('quotationStart'), 'ปิด': หา('quotationEnd'),
                              'เปิดชั้นใน': หา('alternateQuotationStart'),
                              'ปิดชั้นใน': หา('alternateQuotationEnd')},
        'คู่วงเล็บที่ต้องจับคู่กัน': [{'เปิด': el.get('open'), 'ปิด': el.get('close')}
                                        for el in ราก.iter(SIL + 'matched-pair')],
        'ฟอนต์ที่เจ้าของแนะนำ': [el.get('name') for el in ราก.iter(SIL + 'font')],
        'ลำดับการเรียงตัวอักษร': [x for x in
                                    (ราก.findtext('.//' + SIL + 'simple') or '').split() if x],
    }


def main():
    if not os.path.exists(LDML):
        print('⛔ ยังไม่มี %s\n   สั่ง  py -3.14 tools/แตกกอง.py tcv  ก่อน' % LDML)
        return 1
    กติกา = อ่านกติกา()
    กติกา['ช่องค้นหาล้างอะไรออก'] = {
        'กติกา': 'ตัดตัวอักษรหมวด %s ของยูนิโคดออกทั้งหมด ⇒ ตัวที่ไม่มีความกว้าง'
                 ' ไม่มีเสียง ไม่มีความหมายให้อ่าน' % หมวดที่ล้าง,
        'อยู่ที่ไหนในเว็บ': 'read/<เล่ม>/<บท>.json ⇒ ตัวบทไทย.ค้นหา',
        '⛔ ตัวบทเดิมไม่ถูกแตะ': 'ช่อง ตัวบทไทย.ข้อ ยังเป็นของเจ้าของทุกตัวอักษร',
        'จำนวนที่ล้างออกได้จริง': 'รัน py -3.14 tools/ตรวจกติกาไทย.py '
                                   '⛔ ไม่เขียนตัวเลขซ้ำที่นี่',
    }
    os.makedirs(os.path.dirname(ออกที่), exist_ok=True)
    with open(ออกที่, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(กติกา, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write('\n')
    print('เขียน %s' % ออกที่)
    print('   ตัวมองไม่เห็นที่เจ้าของประกาศเป็นเครื่องหมายวรรคตอน %d ตัว ⇒ %s'
          % (len(กติกา['ตัวมองไม่เห็นที่เจ้าของจัดเป็นเครื่องหมายวรรคตอน']),
             ' · '.join('%s %s' % (x['รหัส'], x['ชื่อยูนิโคด'])
                        for x in กติกา['ตัวมองไม่เห็นที่เจ้าของจัดเป็นเครื่องหมายวรรคตอน'])))
    print('   ตัวที่เจ้าของบอกว่าใช้ตัดคำ %d ตัว ⇒ %s'
          % (len(กติกา['ตัวที่เจ้าของใช้ตัดคำ']),
             ' · '.join('%s %s' % (x['รหัส'], x['ชื่อยูนิโคด'])
                        for x in กติกา['ตัวที่เจ้าของใช้ตัดคำ'])))
    return 0


if __name__ == '__main__':
    # ⚠️ ห่อ stdout ตรงนี้เท่านั้น ⛔ ไม่ห่อตอน import
    #    ⇒ สคริปต์ที่ import ไฟล์นี้ ห่อ stdout ของมันไปแล้ว ⇒ ห่อซ้ำ = ระเบิด
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    sys.exit(main())
