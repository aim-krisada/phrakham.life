/** เปิดหน้าใหม่ในเครื่องใหม่ ⇒ ตั้งฉบับกับมุมมองไว้ก่อนหน้าจะรัน ⇒ ⛔ ไม่ไล่กดเมนูให้ช้าและเปราะ */
async function เปิด(ที่อยู่, { ฉบับ = ['TCV', 'LSV'], มุม = { ภาษาเดิม: true }, พัง = null } = {}) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: จอ })
  await ctx.addInitScript(
    ([ฉ, ม]) => {
      try {
        if (!sessionStorage.getItem('pk-ด่านแบบเดียว')) {
          if (ฉ) localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
          if (ม) localStorage.setItem('phrakham.view', JSON.stringify(ม))
          sessionStorage.setItem('pk-ด่านแบบเดียว', '1')
        }
      } catch {}
    },
    [ฉบับ, มุม],
  )
  if (พัง?.ที่อยู่ไม่มีฉบับ || พัง?.ถอยหลังไม่ได้)
    await ctx.addInitScript((พ) => {
      const ตัด = (u) => (typeof u === 'string' ? u.replace(/[?&]t=[^&#]*/, (x) => (x[0] === '?' ? '?' : '')).replace('?&', '?') : u)
      const แทน = History.prototype.replaceState
      const ดัน = History.prototype.pushState
      History.prototype.replaceState = function (s, t, u) {
        return แทน.call(this, s, t, พ.ที่อยู่ไม่มีฉบับ ? ตัด(u) : u)
      }
      History.prototype.pushState = function (s, t, u) {
        if (พ.ถอยหลังไม่ได้) return แทน.call(this, s, t, u)
        return ดัน.call(this, s, t, พ.ที่อยู่ไม่มีฉบับ ? ตัด(u) : u)
      }
    }, พัง)
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}${ที่อยู่}`, { waitUntil: 'domcontentloaded' })
  await รอหน้าพร้อม(แท็บ, มุม?.ภาษาเดิม)
  if (พัง) await ยัดของพัง(แท็บ, พัง)
  return { ctx, แท็บ }
}

async function รอหน้าพร้อม(แท็บ, ภาษาเดิม) {
  await แท็บ.waitForSelector('.pk-หัวคอลัมน์ .pk-หัวช่อง', { timeout: 30000 })
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, { timeout: 30000 })
  await รอนิ่ง(แท็บ, ภาษาเดิม)
}

/**
 * ⭐ **รอจนหน้านิ่งจริง** ⛔ ไม่รอเป็นเวลาตายตัว ⇒ หัวคอลัมน์อ่านได้ 2 รอบติดกันเหมือนกัน
 *   · ⛔ ไม่มีคอลัมน์ที่ยัง *กำลังเปิด* · คำภาษาเดิมของบทคอลัมน์แรกขึ้นแล้ว (เมื่อเปิดไว้)
 */
async function รอนิ่ง(แท็บ, ภาษาเดิม = true) {
  let ก่อน = ''
  const เส้นตาย = Date.now() + 20000
  while (Date.now() < เส้นตาย) {
    await แท็บ.waitForTimeout(300)
    const ส = await สภาพ(แท็บ).catch(() => null)
    if (!ส) continue
    const กำลังเปิด = await แท็บ.evaluate(() => /กำลังเปิดตอนนี้/.test(document.body.innerText))
    const คำพร้อม =
      !ภาษาเดิม ||
      ส.คำเดิม.some((x) => ส.คอลัมน์[0] && x.endsWith(` ${ส.คอลัมน์[0].ป้าย.split(' ').pop()}`))
    const ตอนนี้ = JSON.stringify(ส.คอลัมน์)
    if (!กำลังเปิด && คำพร้อม && ตอนนี้ === ก่อน) return
    ก่อน = ตอนนี้
  }
}

/**
 * ⭐ **ยัดพฤติกรรมเดิมที่เปลี่ยนการกด** ⇒ ดักการคลิกที่ปุ่มก่อนหน้าได้ยิน แล้วส่งต่อให้ปุ่มที่ทำงานแบบเดิม
 *   ⇒ ⛔ ไม่ได้แตะโค้ดของเว็บ ⇒ หน้าทำงานแบบเดียวกับรุ่นก่อนใบ #125 ในเรื่องนั้นเรื่องเดียว
 */
async function ยัดของพัง(แท็บ, พัง) {
  await แท็บ.evaluate((พ) => {
    document.addEventListener(
      'click',
      (e) => {
        const ปุ่ม = e.target instanceof Element ? e.target.closest('button, a') : null
        if (!ปุ่ม || !e.isTrusted) return
        // ⭐ *เปลี่ยนตอน* บนหัวคอลัมน์แรกในตาราง ⇒ เปิดแผงแบบปุ่มทั้งหน้า (ปุ่มกลางของแถบล่าง)
        //   ⇒ ใบ #131 ⇒ ของเดิมส่ง ‹ › บนหัวไปให้ ‹ › แถบล่าง ⇒ ‹ › บนหัวถูกถอดแล้ว ⇒ ย้ายมายัดที่แผง (แผนข้อ 10.3.2)
        const หัวแรก = document.querySelector('.pk-หัวคอลัมน์ .pk-หัวช่อง')
        if (พ.หัวพาทั้งหน้า && หัวแรก?.contains(ปุ่ม) && ปุ่ม.getAttribute('data-ปุ่ม') === 'เปลี่ยนตอน') {
          const ล่าง = document.querySelector('[data-ปุ่ม="เปลี่ยนตอนล่าง"]')
          if (ล่าง) {
            e.preventDefault()
            e.stopImmediatePropagation()
            ล่าง.click()
          }
        }
        // ⭐ ลูกศรแถบล่าง ⇒ พาแค่ตาราง ⇒ คอลัมน์ตอนอื่นอยู่ที่เดิม (ของเดิม ใบ #102 ข้อ 21)
        //   ⇒ ใบ #131 ⇒ ของเดิมส่งต่อให้ › บนหัวคอลัมน์แรก ⇒ ถูกถอดแล้ว
        //   ⇒ ตอนนี้ไปที่อยู่ของลูกศรแถบล่างเอง แต่คืน `p` (คอลัมน์ตอนอื่น) เป็นค่าก่อนกด ⇒ ⛔ ไม่ได้แตะโค้ดของเว็บ
        const ชนิดล่าง = ปุ่ม.getAttribute('data-ปุ่ม')
        if (พ.ล่างพาแค่ตาราง && (ชนิดล่าง === 'บทถัดล่าง' || ชนิดล่าง === 'บทก่อนล่าง') && ปุ่ม.href) {
          e.preventDefault()
          e.stopImmediatePropagation()
          const ไป = new URL(ปุ่ม.href)
          const เดิม = new URLSearchParams(location.search).get('p')
          if (เดิม) ไป.searchParams.set('p', เดิม)
          else ไป.searchParams.delete('p')
          location.assign(ไป.toString())
        }
      },
      true,
    )
  }, พัง)
}

/** ⭐ ของพัง *ไม่ตรงแถว* ⇒ ถอดช่อง LSV ออกจากตาราง ⇒ ทำตอนอ่านสภาพ เพราะหน้าวาดใหม่ทุกครั้งที่ขยับ */
