/** ⭐ ชื่อที่โปรแกรมอ่านหน้าจออ่าน ⇒ ตัวหนังสือทุกชิ้นใต้ตัวคุม ยกเว้นที่ `display: none` หรือ `aria-hidden` */
const ชื่อที่ได้ยิน = (แท็บ, ตัวเลือก) =>
  แท็บ.evaluate((sel) => {
    const el = document.querySelector(sel)
    if (!el) return null
    if (el.getAttribute('aria-label')) return el.getAttribute('aria-label')
    const ได้ = []
    const เดิน = (n) => {
      if (n.nodeType === 3) return ได้.push(n.textContent)
      if (n.nodeType !== 1) return
      if (n.getAttribute('aria-hidden') === 'true' || getComputedStyle(n).display === 'none') return
      for (const c of n.childNodes) เดิน(c)
    }
    เดิน(el)
    return ได้.join('').replace(/\s+/g, ' ').trim()
  }, ตัวเลือก)

