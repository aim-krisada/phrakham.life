#!/bin/sh
# สร้าง **ชิ้นที่จะปล่อยขึ้น GitHub** แล้วตรวจให้ครบก่อนออกจากบ้าน (ใบงาน v3/phrakham#21)
#
# แยกเป็นไฟล์ ⛔ ไม่เขียนยาว ๆ ใน `.gitlab-ci.yml` เพราะ
#   ① job ซ้อมกับ job จริงต้องสร้าง**แบบเดียวกันเป๊ะ** ⇒ มีที่เดียวก็ต่างกันไม่ได้
#   ② รันในเครื่องได้ ⇒ ตรวจก่อนดันขึ้นได้จริง ⛔ ไม่ต้องรอ CI
#
#   sh tools/สร้างเว็บที่จะปล่อย.sh
#
# ฐานปริยาย `/v3/` มาจากที่อยู่ของจริงที่พี่เอมเคาะ 29 ส.ค. 2569 ⇒ https://phrakham.life/v3/
#   **เจ้าของความจริงเรื่องที่อยู่เว็บคือ `ข้อกำหนดโปรเจกต์.md` หัวข้อ "ที่อยู่เว็บ"**
#   ⇒ ย้ายที่อยู่เมื่อไร เปลี่ยนที่ตัวแปร `PUBLISH_BASE_URL` ได้เลย ⛔ ไม่ต้องแก้ไฟล์นี้
#
# ⛔ **ชื่อตัวแปรของ shell ต้องเป็นอักษรอังกฤษ** — ash/dash รับชื่อไทยไม่ได้ (ต่างจากชื่อไฟล์)
set -eu

# ⭐ **ห้าม Git Bash แปลง `/` นำหน้าให้เป็นที่อยู่แบบวินโดวส์** — เหตุผลเต็มอยู่ที่ `nuxt.config.ts`
#   หัวไฟล์นี้บอกเองว่าต้องรันในเครื่องได้ ⇒ ในเครื่องคือ Git Bash บนวินโดวส์
export MSYS_NO_PATHCONV=1

BASE_URL=${PUBLISH_BASE_URL:-/v3/}
OUT=ที่จะปล่อย

# ⭐ ล้างของเก่าของ**โต๊ะตัวเอง** ⛔ ไม่แตะ `node_modules` ซึ่งทุกโต๊ะใช้ก้อนเดียวกัน
#   (ของจริงที่พังมาแล้วอยู่ที่ v3/pleng ใบงาน #38 ⛔ ไม่ทดลองซ้ำ)
rm -rf .nuxt .output "$OUT"

NUXT_APP_BASE_URL="$BASE_URL" npm run generate
mv .output/public "$OUT"

# ฐานที่เอาไว้เทียบที่อยู่ในไฟล์ที่สร้างเสร็จ — ปิดท้ายด้วย `/` เสมอ
case "$BASE_URL" in */) B=$BASE_URL ;; *) B="$BASE_URL/" ;; esac

# --- ด่านสุดท้ายก่อนของออกจากบ้าน ---
# ⛔ พิสูจน์จาก **ไฟล์ที่สร้างเสร็จ** ⛔ ไม่ใช่เชื่อว่าตั้งค่าถูก

# ⚠️ ที่อยู่หน้ากับชื่อไฟล์เนื้อแยกกันแล้ว — พี่เอมเคาะ 29 ส.ค. 2569 ให้ที่อยู่เป็น /sources
#    ⇒ ไฟล์ยังชื่อ content/แหล่งข้อมูล.md ⛔ แต่ที่อยู่ที่สร้างออกมาคือ sources/
#    ⇒ เจ้าของคู่นี้คือ tools/หน้าที่ตรวจ.mjs ⛔ ที่นี่ยืมมาใช้
PAGE="$OUT/sources/index.html"

test -s "$OUT/index.html" \
  || { echo "⛔ ไม่มีไฟล์ที่รากของเว็บ"; exit 1; }
test -s "$PAGE" \
  || { echo "⛔ ไม่มีหน้าแหล่งข้อมูลที่สร้างเสร็จ ⇒ ปล่อยไปก็ได้เว็บที่ไม่มีเนื้อ"; exit 1; }

# ⭐ หน้าอ่านพระคัมภีร์ (ใบงาน v3/phrakham#24) — ของหลักที่ผู้อ่านมาหา
#   ⛔ ซองตัวบทเป็นตัวชี้ของ LFS = สร้างออกมาแล้ว ⛔ ไม่มีบทสักบท ⇒ ด่านนี้จับได้
test -s "$OUT/read/index.html" \
  || { echo "⛔ ไม่มีหน้าสารบัญพระคัมภีร์ ⇒ ปล่อยไปก็ได้เว็บที่อ่านพระคัมภีร์ไม่ได้"; exit 1; }
# ⭐⭐ **1 เล่ม = 1 หน้า** (ใบงาน v3/phrakham#73) ⇒ **จำนวนเล่มอ่านจากซองตัวบทเอง**
#   ⛔ ไม่พิมพ์เลข 66 ไว้ที่นี่ — พิมพ์ไว้เอง = วันที่ข้อมูลเปลี่ยน ตัวเลขจะค้างรุ่นเก่าแล้วแดงมั่ว
WANT=$(node --input-type=module -e \
  'import {แกะซองเนื้อบท} from "./server/utils/ซองเนื้อบท.mjs"
   const บท = Object.keys(แกะซองเนื้อบท("_data/เนื้อบท.json.gz").บท)
   console.log(new Set(บท.map((k) => k.split("/")[0])).size)')
NBOOK=$(find "$OUT/read" -mindepth 2 -maxdepth 2 -name index.html | wc -l)
[ "$NBOOK" -eq "$WANT" ] \
  || { echo "⛔ หน้าเล่มที่สร้างได้ $NBOOK หน้า ⇒ แต่ในซองตัวบทมี $WANT เล่ม"; exit 1; }
# ⭐ **ต้อง ⛔ ไม่มีหน้าของบทเหลืออยู่** ⇒ มีเมื่อไรแปลว่าหลุดกลับไป 1 บท 1 หน้าอีกแล้ว
NCHAP=$(find "$OUT/read" -mindepth 3 -name index.html | wc -l)
[ "$NCHAP" -eq 0 ] \
  || { echo "⛔ ยังมีหน้าของบทอยู่ $NCHAP หน้า ⇒ ต้องเป็นหน้าของเล่มเท่านั้น"; exit 1; }
# ⭐ **ที่อยู่เดิม `/read/<เล่ม>/<บท>` พึ่ง `404.html` ของที่วางเว็บ** ⇒ ไม่มีไฟล์นี้ = ลิงก์เก่าตาย
test -s "$OUT/404.html" \
  || { echo "⛔ ไม่มี 404.html ⇒ ที่อยู่เดิมที่คนแชร์ไว้จะเปิดไม่ได้"; exit 1; }
# ⭐⭐ **และหน้านั้นต้องมีทางไปต่อ ⛔ ไม่ใช่โครงเปล่า** (คนตรวจ !64 ทัก ② · 7 ก.ย. 2569)
#   ⇒ โค้ดของเว็บโหลดไม่สำเร็จเมื่อไร นี่คือทุกอย่างที่ผู้อ่านได้
#   ⛔ **ลิงก์ต้องมีฐานของก้อนนี้ติดอยู่** — ฐานที่นี่ (`/v3/`) ต่างจากที่ทดลอง (`/phrakham/`)
#   ⇒ ลืมเติมฐานเมื่อไร ด่านในเครื่องยังเขียว แต่ก้อนที่ปล่อยจะพาผู้อ่านไปผิดที่
grep -qF "<a href=\"${B}read\"" "$OUT/404.html" \
  || { echo "⛔ 404.html ⛔ ไม่มีลิงก์ ${B}read ⇒ โค้ดโหลดไม่สำเร็จแล้วผู้อ่านจะไปต่อไม่ได้"; exit 1; }
grep -q '<title>' "$OUT/404.html" \
  || { echo "⛔ 404.html ⛔ ไม่มีชื่อหน้า ⇒ ผิด WCAG SC 2.4.2"; exit 1; }

# หน้าเว็บต้องบอกเองได้ว่ามาจากคอมมิตไหน (WPA.08 ของที่ต้องส่งข้อ 1)
grep -q 'name="commit"' "$PAGE" \
  || { echo "⛔ ไม่มีตัวประทับคอมมิตในหน้าเว็บ"; exit 1; }

# ⭐⭐ **ต้นแบบยังไม่เปิดให้คนทั่วไปค้นเจอ ⇒ ทุกหน้าต้องมีป้ายห้ามเก็บลงสารบัญ** (ใบงาน v3/phrakham#71)
#   ⛔ ที่นี่คือด่านสุดท้ายก่อนของขึ้น `phrakham.life/v3` ⇒ หลุดไปแล้วกูเกิลเก็บไว้ เอาออกยาก
#   ⇒ ด่านเปิดดูไฟล์ `.html` **ทุกไฟล์ในกองที่จะส่ง** ⛔ ไม่ใช่แค่หน้าเดียวอย่างบรรทัดบน
node tools/ด่านห้ามเก็บสารบัญ.mjs "$OUT"

# ⭐ ไฟล์ของเว็บต้องอยู่ใต้ฐานที่สั่ง ⇒ ไม่งั้นเปิดแล้วไปหยิบของที่อยู่อื่นมาแสดง
grep -qF "\"${B}_nuxt/" "$PAGE" \
  || { echo "⛔ ไฟล์ของเว็บไม่ได้อยู่ใต้ $B ⇒ ตัวแปร PUBLISH_BASE_URL ไม่ถึงตัวสร้าง"; exit 1; }

# ⭐ **ที่รากเป็นหน้าแรกจริงแล้ว** (ใบงาน v3/phrakham#66 · พี่เอมสั่ง 6 ก.ย. 2569)
#   เดิมรากเป็นแค่หน้าพาต่อไป `/read` ⇒ ด่านตรงนี้จึงเคยหาคำว่า `url=<ฐาน>` ในไฟล์นั้น
#   ⇒ ตอนนี้ต้องพิสูจน์ 2 อย่างแทน และทั้งคู่**เข้มกว่าเดิม** เพราะหน้าพาต่อไม่มีเนื้อให้ตรวจ
#     ① หน้าแรกมีเนื้อจริง ⛔ ไม่ใช่หน้าเปล่า
#     ② ลิงก์บนหน้าแรกต่อฐานถูก ⇒ ⛔ ไม่ต่อ = คนกดแล้วไปโผล่ที่รากของโฮสต์
#        ซึ่งวันนี้คือเว็บรุ่น 2 ที่ผู้อ่านใช้อยู่
#     ③ ที่รากต้อง ⛔ ไม่ใช่หน้าเด้งอีกแล้ว ⇒ เจ้าของเรื่องนี้คือ `nuxt.config.ts` · ที่นี่เป็นตัวเฝ้า
# ⛔ **หา `<h1>` เป๊ะ ๆ ไม่ได้** — วันที่หัวเรื่องมีคลาสติดมาสักตัว ด่านจะแดงทั้งที่หน้าไม่ได้พัง
#   ⇒ รับทั้ง `<h1>` และ `<h1 ...>` ⇒ ยังจับ "หน้าเปล่า" ได้เหมือนเดิม
grep -qE '<h1[ >]' "$OUT/index.html" \
  || { echo "⛔ หน้าแรกไม่มีหัวเรื่อง ⇒ ปล่อยไปก็ได้หน้าเปล่า"; exit 1; }
! grep -qi 'http-equiv="refresh"' "$OUT/index.html" \
  || { echo "⛔ ที่รากยังเป็นหน้าเด้ง ⇒ หน้าแรกจริงไม่ได้ถูกสร้าง"; exit 1; }
grep -qF "\"${B}read\"" "$OUT/index.html" \
  || { echo "⛔ หน้าแรกไม่มีลิงก์ไปหน้าอ่านที่ต่อฐาน $B ⇒ กดแล้วหลุดออกนอกเว็บ"; exit 1; }

# ⭐ **ที่อยู่ถูกรูป ไม่ได้แปลว่าไฟล์มีอยู่จริง**
#   ลบ `_nuxt/` ทั้งโฟลเดอร์โดยไม่แตะ `index.html` ⇒ ด่านข้างบนผ่านหมด
#   ⇒ เว็บที่ไม่มี JS/CSS เลยจะถูกปล่อยขึ้นโดยไม่มีใครแดง (บทเรียนของ v3/pleng 8 ส.ค. 2569)
#
# ⭐ **ที่อยู่ในหน้าเว็บเป็นรหัส `%E0%B9%81…` แต่ชื่อไฟล์บนดิสก์เป็นตัวไทย** ⇒ ต้องถอดรหัสก่อนเทียบ
#   ⛔ ไม่ถอด = ด่านนี้ฟ้องไฟล์ที่มีอยู่จริงทุกไฟล์ที่ชื่อเป็นภาษาไทย (เจอเอง 29 ส.ค. 2569)
#   ⇒ ใช้ node ถอดให้ทีเดียวทั้งชุด เพราะ `printf %b` ถอด `%XX` ไม่ได้ตามมาตรฐาน POSIX
#   **วิธีดูของจริง** ⇒ `grep -oE '"/[^"]+_payload.json[^"]*"' <หน้าเนื้อ>` แล้วเทียบกับ `find` ในโฟลเดอร์
MISSING=0
REFS=$(grep -oE "\"$B[^\"]+\"" "$PAGE" | tr -d '"' | sort -u \
  | node -e 'let s="";process.stdin.on("data",c=>s+=c).on("end",()=>console.log(s.split("\n").filter(Boolean).map(x=>decodeURIComponent(x)).join("\n")))')
for raw in $REFS; do
  # ตัดหางที่ไม่ใช่ชื่อไฟล์ออกก่อน เช่น `_payload.json?_b=<รหัส>` ที่ Nuxt ต่อท้ายกันแคช
  p=${raw%%\?*}
  p=${p%%#*}
  # เอาเฉพาะที่หน้าตาเป็น**ไฟล์** (ท่อนท้ายมีจุด) ⛔ ไม่ใช่เส้นทางของหน้า
  case "${p##*/}" in *.*) ;; *) continue ;; esac
  f="$OUT/${p#$B}"
  [ -f "$f" ] || { echo "⛔ หน้าเนื้ออ้าง $p แต่ไม่มีไฟล์นั้นในของที่จะส่ง"; MISSING=1; }
done
[ "$MISSING" = 0 ] || { echo "⛔ ของที่จะส่งไม่ครบ ⇒ ไม่ส่ง"; exit 1; }

# และต้องมีโค้ดของเว็บจริง ⛔ ไม่ใช่โฟลเดอร์เปล่า
[ "$(find "$OUT/_nuxt" -name '*.js' 2>/dev/null | wc -l)" -gt 0 ] \
  || { echo "⛔ ไม่มีไฟล์โค้ดใน _nuxt ⇒ เว็บจะขึ้นเป็นหน้าเปล่า"; exit 1; }

# ⭐ **ตัวประทับที่เครื่องปลายทางอ่านได้** — ไฟล์ที่รากเป็นแค่หน้าพาต่อ ⇒ ⛔ ไม่มีตัวประทับอยู่ในนั้น
#   ⇒ ฝั่งรับต้องตอบได้ว่า "ของกองนี้มาจากคอมมิตไหน" โดย ⛔ ไม่ต้องเปิดหน้าเนื้อ
#   ⇒ ท่าเดียวกับ v3/pleng ที่เปิดอ่านได้ที่ https://pleng.phrakham.life/v3/version.json
printf '{"commit":"%s","short":"%s","branch":"%s"}\n' \
  "${CI_COMMIT_SHA:-dev}" "${CI_COMMIT_SHORT_SHA:-dev}" "${CI_COMMIT_REF_NAME:-local}" \
  > "$OUT/version.json"

echo "✅ สร้างเสร็จ $(find "$OUT" -type f | wc -l) ไฟล์ · $(du -sh "$OUT" | cut -f1) · ฐานที่ $B"
