const ค่าส่ง = (มุม, ตรวจเป้า) => ({ ตัวเลือกปุ่ม, กรอบครอบปุ่ม, กรอบไม่ครอบปุ่ม, มุม, คลาด, เป้า, ตรวจเป้า })

/** วัดสภาพที่เปิดอยู่ 2 รอบ ⇒ ค่าจริง (①–⑤) แล้วค่าทดลอง (⑥) ⇒ คืน [[ข้อ, ข้อความ]] */
async function วัดสองรอบ(แท็บ, ป้าย) {
  const ผล = []
  const จริง = await แท็บ.evaluate(วัดในหน้า, ค่าส่ง(มุมปุ่ม, true))
  if (!จริง.ปุ่ม) ผล.push(['③', `${ป้าย} ⇒ ⛔ เจอปุ่มสักปุ่ม ⇒ หน้ายังไม่ขึ้น`])
  for (const [ข้อ, x] of จริง.ผิด) ผล.push([ข้อ, `${ป้าย} ⇒ ${x}`])
  if (รายงาน) for (const r of จริง.รายงาน) console.log(`   · ${ป้าย} ⇒ ${r.กรอบ} ${JSON.stringify(r.มุม)}`)
  // ⑥ เปลี่ยนค่ากลางบนหน้าเดิม ⇒ ทุกอย่างต้องขยับตาม ⇒ แล้วคืนค่า
  await แท็บ.evaluate((ค่า) => {
    const st = document.createElement('style')
    st.id = 'ด่าน156ค่าทดลอง'
    st.textContent = `:root { --pk-มุมปุ่ม: ${ค่า}px !important; }`
    document.head.appendChild(st)
  }, มุมทดลอง)
  await รอสองเฟรม(แท็บ)
  const ทดลอง = await แท็บ.evaluate(วัดในหน้า, ค่าส่ง(มุมทดลอง, false))
  for (const [ข้อ, x] of ทดลอง.ผิด) ผล.push(['⑥', `${ป้าย} ⇒ ค่ากลาง --pk-มุมปุ่ม ${มุมทดลอง} จุด ⇒ [${ข้อ}] ${x} ⇒ ⛔ ขยับตามค่ากลาง`])
  await แท็บ.evaluate(() => document.getElementById('ด่าน156ค่าทดลอง')?.remove())
  await รอสองเฟรม(แท็บ)
  return ผล
}

/** ตรวจหน้าหนึ่งที่จอหนึ่ง ⇒ `เลือก` = ชื่อสภาพที่จะวัด (ว่าง = ทุกสภาพ) */
async function ตรวจหน้า({ กว้าง, ขยาย, ทาง, เลือก, พัง }) {
  const ป้ายจอ = `จอ ${กว้าง} ตัวอักษร ${ขยาย * 100}% ${ทาง}`
  const ผล = []
  const { ctx, แท็บ, พร้อม } = await เปิดหน้า({ กว้าง, ขยาย, ทาง, พัง })
  try {
    if (!พร้อม) return [['③', `${ป้ายจอ} ⇒ หน้า ⛔ พร้อมภายใน ${รอนานสุด / 1000} วินาที`]]
    for (const ส of สภาพ[ทาง]) {
      if (เลือก && !เลือก.includes(ส.ชื่อ)) continue
      const ป้าย = `${ป้ายจอ} · ${ส.ชื่อ}`
      if (ส.เปิด && !(await ส.เปิด(แท็บ))) {
        ผล.push(['③', `${ป้าย} ⇒ เปิดแล้ว ⛔ ขึ้น ⇒ ⛔ ได้วัด`])
        await แท็บ.keyboard.press('Escape').catch(() => {})
        continue
      }
      ผล.push(...(await วัดสองรอบ(แท็บ, ป้าย)))
      if (ส.ปิด) await ส.ปิด(แท็บ)
    }
  } catch (e) {
    ผล.push(['③', `${ป้ายจอ} ⇒ ด่านล้มระหว่างตรวจ ⇒ ${e.message.split('\n')[0]}`])
  } finally {
    await ctx.close()
  }
  return ผล
}

