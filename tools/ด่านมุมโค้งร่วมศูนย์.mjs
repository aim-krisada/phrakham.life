/** รันในเบราว์เซอร์ ⇒ คืน `{ ผิด: [[ข้อ, ข้อความ]], รายงาน: [] }` ⇒ `มุม` = ค่าที่ปุ่มต้องเป็น (12 หรือค่าทดลอง) */
function วัดในหน้า({ ตัวเลือกปุ่ม, กรอบครอบปุ่ม, กรอบไม่ครอบปุ่ม, มุม, คลาด, เป้า, ตรวจเป้า }) {
  const ผิด = []
  const รายงาน = []
  const px = (s) => parseFloat(s) || 0
  const ราก = px(getComputedStyle(document.documentElement).fontSize) || 16
  const ใกล้มุม = 2.5 * ราก
  const จอแคบ = !matchMedia('(min-width: 768px)').matches
  const เห็น = (e) => {
    if (!e.getClientRects().length) return false
    if (!e.checkVisibility({ visibilityProperty: true, opacityProperty: true })) return false
    const r = e.getBoundingClientRect()
    return r.width > 1 && r.height > 1
  }
  const ชื่อของ = (e) =>
    `${e.tagName.toLowerCase()}${e.getAttribute('data-ปุ่ม') ? `[data-ปุ่ม=${e.getAttribute('data-ปุ่ม')}]` : ''}.${String(e.className)
      .split(/\s+/)
      .filter((c) => c.startsWith('pk-') && c !== 'pk-ปุ่มชุด')
      .join('.')} «${(e.textContent || e.getAttribute('aria-label') || '').trim().replace(/\s+/g, ' ').slice(0, 16)}»`
  const มุมทั้งสี่ = (cs) => ({
    tl: px(cs.borderTopLeftRadius),
    tr: px(cs.borderTopRightRadius),
    bl: px(cs.borderBottomLeftRadius),
    br: px(cs.borderBottomRightRadius),
  })
  const ข้อยกเว้น = (e) => e.hasAttribute('data-เลือกข้อ') || (e.tagName === 'BUTTON' && e.classList.contains('pk-คำ'))

  // ① ④ ปุ่มทุกปุ่ม
  const ปุ่ม = [...document.querySelectorAll(ตัวเลือกปุ่ม)].filter((e) => !ข้อยกเว้น(e) && เห็น(e))
  const ปุ่มผิดแล้ว = new Set()
  for (const e of ปุ่ม) {
    const ม = มุมทั้งสี่(getComputedStyle(e))
    const ผิดมุม = Object.entries(ม).filter(([, v]) => Math.abs(v - มุม) > 0.5)
    if (ผิดมุม.length) {
      ปุ่มผิดแล้ว.add(e)
      ผิด.push(['①', `ปุ่ม ${ชื่อของ(e)} โค้ง ${ผิดมุม.map(([k, v]) => `${k} ${v}`).join(' · ')} จุด ⇒ ต้อง ${มุม} ทุกมุม`])
    }
    if (ตรวจเป้า && e.tagName !== 'SELECT') {
      const r = e.getBoundingClientRect()
      if (r.width < เป้า - 0.5 || r.height < เป้า - 0.5)
        ผิด.push(['④', `ปุ่ม ${ชื่อของ(e)} ${r.width.toFixed(1)}×${r.height.toFixed(1)} จุด ⇒ ต่ำกว่า ${เป้า}×${เป้า}`])
    }
  }

  // ② ③ กรอบที่ครอบปุ่ม
  // ⭐ ปุ่มเป็นของกรอบชั้นในสุดที่ครอบมัน ⇒ ปุ่มบนแถบบนเป็นของแถบบน ⛔ ของแผ่นอ่าน · ปุ่มในแผงที่ลอยเป็นของแผง ⛔ ของแผ่นที่อยู่ใต้
  const กรอบทั้งหมด = กรอบครอบปุ่ม.flatMap((ก) => [...document.querySelectorAll(ก.ตัวเลือก)]).filter(เห็น)
  const ชั้นในสุด = (b) => {
    let ใน = null
    for (const c of กรอบทั้งหมด) if (c.contains(b) && (!ใน || ใน.contains(c))) ใน = c
    return ใน
  }
  for (const ก of กรอบครอบปุ่ม) {
    for (const el of document.querySelectorAll(ก.ตัวเลือก)) {
      if (!เห็น(el)) continue
      const r = el.getBoundingClientRect()
      let กล่อง
      let cs
      if (ก.เทียม) {
        cs = getComputedStyle(el, '::before')
        if (cs.content === 'none' || cs.display === 'none') continue
        กล่อง = { l: r.left + px(cs.left), r: r.right - px(cs.right), t: r.top + px(cs.top), b: r.bottom - px(cs.bottom) }
      } else {
        cs = getComputedStyle(el)
        กล่อง = { l: r.left, r: r.right, t: r.top, b: r.bottom }
      }
      // ⭐ กรอบที่พ้นจอไปเกือบทั้งกรอบ (แผ่นอ่านที่ยาวทั้งบท) ⇒ วัดเฉพาะมุมที่อยู่ในจอ
      const ม = มุมทั้งสี่(cs)
      const ตรง = new Set(ก.ตรง === 'ล่าง' || (ก.ตรง === 'ล่างจอแคบ' && จอแคบ) ? ['bl', 'br'] : [])
      const ป้าย = `${ก.ชื่อ} (${ก.ตัวเลือก}${ก.เทียม ? '::before' : ''})`
      const ในกรอบ = ปุ่ม.filter((b) => {
        if (ชั้นในสุด(b) !== el) return false
        const q = b.getBoundingClientRect()
        return q.left >= กล่อง.l - 0.5 && q.right <= กล่อง.r + 0.5 && q.top >= กล่อง.t - 0.5 && q.bottom <= กล่อง.b + 0.5
      })
      // ระยะข้างของปุ่มที่ชิดข้างนั้นที่สุด ⇒ ปุ่มที่ร่นเข้ามามากกว่านี้ ⛔ นับเป็นปุ่มชิดมุม
      const ชิดซ้าย = Math.min(...ในกรอบ.map((b) => b.getBoundingClientRect().left - กล่อง.l), Infinity)
      const ชิดขวา = Math.min(...ในกรอบ.map((b) => กล่อง.r - b.getBoundingClientRect().right), Infinity)
      const ผลมุม = {}
      for (const k of ['tl', 'tr', 'bl', 'br']) {
        const บน = k[0] === 't'
        const ซ้าย = k[1] === 'l'
        const มุมy = บน ? กล่อง.t : กล่อง.b
        if (มุมy < -0.5 || มุมy > innerHeight + 0.5) continue
        if (ตรง.has(k)) {
          if (ม[k] > 0.5) ผิด.push(['③', `${ป้าย} มุม ${k} โค้ง ${ม[k]} จุด ⇒ มุมนี้ต้องตรง (ติดขอบจอหรือแผ่นใต้) ⇒ 0`])
          continue
        }
        let ดี = null
        if (ก.มุมปุ่ม.includes(k))
          for (const b of ในกรอบ) {
            const q = b.getBoundingClientRect()
            const dx = ซ้าย ? q.left - กล่อง.l : กล่อง.r - q.right
            const dy = บน ? q.top - กล่อง.t : กล่อง.b - q.bottom
            if (dy > ใกล้มุม) continue
            if (!ดี || dx + dy < ดี.dx + ดี.dy) ดี = { b, dx, dy }
          }
        if (ดี && ดี.dx > (ซ้าย ? ชิดซ้าย : ชิดขวา) + 1) ดี = null
        if (ดี && ดี.dx > ใกล้มุม) ดี = null
        // ⭐ กรอบแบบแผ่นฝ้า (`::before`) ⇒ ปุ่มที่ล้นกล่องของหัวเองออกมาในส่วนที่แผ่นยื่น ⇒ วัดระยะจากขอบกล่องของหัวแทน
        //   ⇒ จอ 320 ตัวอักษร 200% หัวคำเดิมที่ห่อกว้างกว่าแถบหัว 1–2 จุด (ฟอนต์บนตัวรันกว้างกว่าในเครื่อง) ⇒ × ล้นเข้าไปในส่วนยื่นของแผ่น
        //   ⇒ ส่วนยื่น (`--pk-ขอบข้างหัว`) คือระยะที่มุมแผ่นออกแบบไว้ ⇒ หัวที่ล้นเป็นเรื่องของ `tools/ด่านหัวแถวเดียว.mjs` ⛔ ของมุมโค้ง
        //   ⇒ ⛔ ใช้ทางนี้เมื่อปุ่มอยู่ในกล่องของหัวพอดี ⇒ ขอบในหนาขึ้นแต่มุมไม่ตามยังแดงเหมือนเดิม
        if (ดี && ก.เทียม) {
          const q = ดี.b.getBoundingClientRect()
          const ล้น = ซ้าย ? r.left - q.left : q.right - r.right
          if (ล้น > 0.5) ดี.dx = ซ้าย ? r.left - กล่อง.l : กล่อง.r - r.right
        }
        ผลมุม[k] = { โค้ง: ม[k], ...(ดี ? { dx: ดี.dx, dy: ดี.dy, ปุ่ม: ชื่อของ(ดี.b) } : {}) }
        if (ดี) {
          const ต้อง = มุม + ดี.dx
          if (Math.abs(ม[k] - ต้อง) > คลาด + 0.01)
            ผิด.push([
              '②',
              `${ป้าย} มุม ${k} โค้ง ${ม[k].toFixed(1)} จุด ⇒ ปุ่ม ${ชื่อของ(ดี.b)} ห่างขอบข้าง ${ดี.dx.toFixed(1)} จุด ⇒ ต้อง ${มุม} + ${ดี.dx.toFixed(1)} = ${ต้อง.toFixed(1)} (คลาดได้ ${คลาด}) ⇒ ⛔ ร่วมศูนย์`,
            ])
        }
      }
      const มีปุ่ม = Object.values(ผลมุม).filter((x) => x.ปุ่ม)
      const ไม่มีปุ่ม = Object.entries(ผลมุม).filter(([, x]) => !x.ปุ่ม)
      if (ก.ต้องมี && ก.มุมปุ่ม.some((k) => k in ผลมุม) && !มีปุ่ม.length)
        ผิด.push(['③', `${ป้าย} ⇒ หาปุ่มที่ชิดมุม ${ก.มุมปุ่ม.join('/')} ไม่เจอ (ใกล้ไม่เกิน ${ใกล้มุม} จุด) ⇒ ⛔ ได้วัดว่าร่วมศูนย์ไหม ⇒ ${JSON.stringify(ผลมุม)}`])
      // ⭐ มุมที่ไม่มีปุ่มชิด ⇒ เทียบกับมุมที่มีปุ่ม ⇒ ไม่มีสักมุม ⇒ เทียบกันเอง (กรอบหนึ่งโค้งค่าเดียว)
      const ฐาน = มีปุ่ม.length ? มีปุ่ม[0].โค้ง : ไม่มีปุ่ม[0]?.[1].โค้ง
      for (const [k, x] of ไม่มีปุ่ม)
        if (Math.abs(x.โค้ง - ฐาน) > คลาด + 0.01)
          ผิด.push(['③', `${ป้าย} มุม ${k} โค้ง ${x.โค้ง} จุด ⇒ มุมอื่นของกรอบเดียวกันโค้ง ${ฐาน} ⇒ กรอบหนึ่งต้องโค้งค่าเดียว`])
      รายงาน.push({ กรอบ: ป้าย, มุม: ผลมุม })
    }
  }

  // ⑤ กรอบที่ไม่ครอบปุ่ม
  for (const s of กรอบไม่ครอบปุ่ม)
    for (const el of document.querySelectorAll(s)) {
      if (!เห็น(el)) continue
      const cs = getComputedStyle(el)
      const ม = มุมทั้งสี่(cs)
      const ไม่มีเส้น = ['Top', 'Right', 'Bottom', 'Left'].every((d) => px(cs[`border${d}Width`]) === 0 || cs[`border${d}Style`] === 'none')
      const ผิดมุม = Object.entries(ม).filter(([, v]) => Math.abs(v - มุม) > 0.5 && !(v === 0 && ไม่มีเส้น))
      if (ผิดมุม.length)
        ผิด.push(['⑤', `กรอบไม่ครอบปุ่ม ${s} โค้ง ${ผิดมุม.map(([k, v]) => `${k} ${v}`).join(' · ')} จุด ⇒ ต้องเท่าปุ่ม ${มุม} (หรือ 0 เมื่อไม่มีเส้นกรอบ)`])
      รายงาน.push({ กรอบ: s, มุม: ม })
    }
  return { ผิด, รายงาน, ปุ่ม: ปุ่ม.length }
}

