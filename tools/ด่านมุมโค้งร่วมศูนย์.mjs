const เบราว์เซอร์ = await chromium.launch()
const รอสองเฟรม = (แท็บ) => แท็บ.evaluate(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))))

async function เปิดหน้า({ กว้าง, ขยาย, ทาง, พัง }) {
  const ctx = await เบราว์เซอร์.newContext({ viewport: { width: กว้าง, height: กว้าง < 768 ? 740 : 900 } })
  await ctx.addInitScript(() => {
    try {
      if (!sessionStorage.getItem('ด่าน156')) {
        sessionStorage.setItem('ด่าน156', '1')
        localStorage.setItem('phrakham.view', JSON.stringify({ จัดวาง: 'แยกตามข้อ', แสดงเลข: true, สัญลักษณ์กาล: true }))
      }
    } catch {}
    // ⭐ ไม่มีเมนูแชร์ของเครื่อง · คัดลอกไม่ได้ ⇒ ปุ่มแชร์เปิดกล่องคัดลอกเอง ⇒ ท่าเดียวกับ `tools/ด่านปุ่มปิดกากบาท.mjs`
    Object.defineProperty(navigator, 'share', { configurable: true, value: undefined })
    Object.defineProperty(navigator, 'clipboard', {
      configurable: true,
      value: { writeText: () => Promise.reject(new DOMException('ไม่ยอม', 'NotAllowedError')) },
    })
    document.execCommand = () => false
  })
  // ⭐ ของพังเข้าตั้งแต่หน้ายังไม่วาด ⇒ ท่าเดียวกับ `tools/ด่านปุ่มในแคปซูลล่าง.mjs`
  if (พัง?.css)
    await ctx.addInitScript((กฎ) => {
      window.addEventListener('DOMContentLoaded', () => {
        const st = document.createElement('style')
        st.dataset.ด่าน156พัง = ''
        st.textContent = กฎ
        document.head.appendChild(st)
      })
    }, พัง.css)
  const แท็บ = await ctx.newPage()
  await แท็บ.goto(`${ฐาน}${ทาง}`, { waitUntil: 'domcontentloaded' })
  const อ่าน = ทาง.startsWith('/read/')
  const พร้อม = await แท็บ
    .waitForFunction(
      (อ่าน) => {
        if (!document.getElementById('__nuxt')?.__vue_app__) return false
        if (document.fonts.status !== 'loaded') return false
        if (!อ่าน) return !!document.querySelector('.pk-ปุ่มหลัก')
        if (!document.querySelector('#บท-11')) return false
        if (/SBLGNT/.test(location.search) && !document.querySelector('.pk-ชั้นคำ .pk-คำ')) return false
        return (document.querySelector('.pk-ตัวบท')?.getAttribute('data-จัดแถว') ?? 'เสร็จ') === 'เสร็จ'
      },
      อ่าน,
      { timeout: รอนานสุด },
    )
    .then(() => true)
    .catch(() => false)
  if (พร้อม) {
    await แท็บ.evaluate((ข) => (document.documentElement.style.fontSize = `${ข * 100}%`), ขยาย)
    await แท็บ.waitForTimeout(250)
    await รอสองเฟรม(แท็บ)
  }
  return { ctx, แท็บ, พร้อม }
}

/** รอกล่องนิ่ง ⇒ ขอบ 4 ด้านเท่าเดิม 3 เฟรมติด (แผ่นที่ลอยขึ้นหรือเลื่อนขึ้น) ⇒ ท่าทางลอยขึ้นจบ */
async function รอนิ่ง(แท็บ, s) {
  await แท็บ
    .waitForFunction(
      (s) => {
        const e = document.querySelector(s)
        const r = e?.getBoundingClientRect()
        if (!r) return false
        if (e.getAnimations({ subtree: false }).some((a) => a.playState === 'running')) return false
        const ค่า = [r.left, r.right, r.top, r.bottom].map(Math.round).join(',')
        const เดิม = window.__ด่าน156นิ่ง
        window.__ด่าน156นิ่ง = { ค่า, นับ: เดิม?.ค่า === ค่า ? เดิม.นับ + 1 : 0 }
        return window.__ด่าน156นิ่ง.นับ >= 3
      },
      s,
      { polling: 'raf', timeout: 10000 },
    )
    .catch(() => {})
}

/**
 * สภาพที่ด่านวัด ⇒ `เปิด` คืน `true` เมื่อของที่ต้องวัดขึ้นจริง ⇒ `ปิด` คืนหน้ากลับสภาพเปล่า
 *   ⇒ `ชุด` แบ่งงานของโหมดพิสูจน์ ⇒ ⛔ ใช้กับการตรวจของจริง
 */
const ปุ่มปิดใน = (แท็บ, s) => แท็บ.locator(s).getByRole('button', { name: /^ปิด/ }).first()
async function กดแล้วรอ(แท็บ, ปุ่ม, s, { กลางจอ = false } = {}) {
  await ปุ่ม.waitFor({ state: 'visible', timeout: 10000 }).catch(() => {})
  if (!(await ปุ่ม.count())) return false
  await ปุ่ม.scrollIntoViewIfNeeded().catch(() => {})
  // ⭐ ของในตัวบท (คำภาษาเดิม) ⇒ ส่งเหตุการณ์กดตรงที่ตัวคำ ⇒ จอ 768 ตัวอักษร 200% หัวคอลัมน์ที่หนึบสูงจนคำแรกซุกใต้หัว
  //   ⇒ เลื่อนหน้าเองก็ไม่ได้ ⇒ หน้าอ่านยึดข้อที่อ่านอยู่กลับที่เดิม ⇒ ด่านนี้วัดมุมของการ์ด ⛔ ตรวจว่ากดถึงไหม (ของ `tools/ด่านการ์ดคำบนหน้า.mjs`)
  if (กลางจอ) await ปุ่ม.dispatchEvent('click')
  else await ปุ่ม.click()
  const ได้ = await แท็บ
    .waitForSelector(s, { state: 'visible', timeout: 10000 })
    .then(() => true)
    .catch(() => false)
  if (ได้) await รอนิ่ง(แท็บ, s)
  return ได้
}
async function ปิดกล่อง(แท็บ, s) {
  const x = ปุ่มปิดใน(แท็บ, s)
  if (await x.count()) await x.click().catch(() => {})
  else await แท็บ.keyboard.press('Escape')
  await แท็บ.waitForFunction((s) => !document.querySelector(s)?.checkVisibility(), s, { timeout: 5000 }).catch(() => แท็บ.keyboard.press('Escape'))
  await รอสองเฟรม(แท็บ)
}

