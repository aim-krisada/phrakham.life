/** ตั้งค่าที่เครื่องผู้อ่านก่อนหน้าจะรัน ⇒ ⛔ ไม่ต้องไล่กดเมนูให้ช้าและเปราะ */
async function เปิดหน้า({ viewport, ฉบับ = ฉบับที่ติ๊ก, ขนาดอักษร = '0' }) {
  const ctx = await เบราว์เซอร์.newContext({ viewport })
  await ctx.addInitScript(
    ([ฉ, fs]) => {
      localStorage.setItem('phrakham.versions', JSON.stringify(ฉ))
      localStorage.setItem('pk-fs', fs)
    },
    [ฉบับ, ขนาดอักษร],
  )
  const แท็บ = await ctx.newPage()
  return { ctx, แท็บ }
}

/**
 * ⭐⭐ **รอของที่จะตรวจขึ้นจริง ⛔ ไม่ใช่รอเป็นจำนวนวินาที** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/108)
 *   ⇒ ของเดิมรอโค้ดติดแล้วรออีก 600 มิลลิวินาที ⇒ **บนตัวรัน 2 แกน ของยังโหลดไม่เสร็จ**
 *     ⇒ งาน 56380 · 57276 ⇒ ตอนที่เทียบยังเป็น *กำลังเปิดตอนนี้ขึ้นมา…* 22 ตัวอักษร ⇒ ด่านแดงทั้งที่หน้าไม่ได้พัง
 *   ⇒ ⭐ **ทำให้ล้มในเครื่องได้** ⇒ ถ่วงซีพียู 4 เท่า + หน่วงเน็ต 1 วินาทีต่อคำขอ ⇒ ล้มทุกรอบด้วยอาการเดียวกัน
 *   ⇒ ⛔ **รอไม่สำเร็จ ⛔ ไม่นับว่าผ่าน** ⇒ เขียนเป็นข้อที่ตก แล้วข้อตรวจเดิมก็ยังวัดและแดงตามของจริง
 */
const รอนานสุด = 20000

async function ไปที่(แท็บ, คำถาม, ตก) {
  await แท็บ.goto(`${ฐาน}/read/${คอลัมน์แรก.เล่ม}?${คำถาม}`, { waitUntil: 'domcontentloaded' })
  await แท็บ.waitForSelector('article.pk-เนื้อ h1')
  await แท็บ.waitForFunction(() => document.getElementById('__nuxt')?.__vue_app__, null, {
    timeout: 30000,
  })
  // ⭐ หน้าที่สร้างไว้ล่วงหน้ามีแต่บทแรกของเล่ม ⇒ บทที่ `?c=` ขอถูกหยิบหลังโค้ดติด ⇒ **รอหมุดของบทนั้น**
  //   ⇒ ⛔ ไม่รอ = หัวคอลัมน์ยังเขียนว่า *มาระโก 1* ⇒ ข้อ ④ แดงมั่ว (ทำให้เกิดในเครื่องได้ด้วยการถ่วงเดียวกัน)
  const c = new URLSearchParams(คำถาม).get('c')
  const ถึง = await แท็บ
    .waitForFunction((บท) => !!document.getElementById(`บท-${บท}`), c, { timeout: รอนานสุด })
    .then(() => true)
    .catch(() => false)
  if (!ถึง) ตก.push(`เปิด ?${คำถาม} แล้วบท ${c} ของคอลัมน์แรก ⛔ ไม่ขึ้นภายใน ${รอนานสุด / 1000} วินาที`)
}

/**
 * ⭐ **รอตัวบทของตอนที่เทียบขึ้นจริง** ⇒ มีเลขข้ออย่างน้อยหนึ่งตัวในกล่องตัวบทของมัน
 *   ⇒ ตัวบททั้งบทถูกวาดในรอบเดียวกัน (มาจากไฟล์บทไฟล์เดียว) ⇒ เลขข้อตัวแรกโผล่ = ทั้งบทโผล่
 *   ⇒ และไฟล์ของเล่ม (ชื่อไทย) ถูกหยิบ **ก่อน** ไฟล์บทเสมอ ⇒ ตัวบทขึ้น = หัวมีชื่อเล่มแล้ว
 * ⛔ รอไม่สำเร็จ ⇒ **เขียนเป็นข้อที่ตก** ⛔ ไม่กลืนทิ้ง
 */
async function รอตอนเทียบขึ้น(แท็บ, ตก) {
  const ขึ้น = await แท็บ
    .waitForFunction(
      () => {
        // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131#note_30367 ⇒ จอแคบวางบนล่าง ⇒ คอลัมน์คนละบทคู่ทีละข้อในตัวบทของคอลัมน์แรก
        //   ⇒ ⛔ ไม่มีกล่อง `.pk-ตอนเทียบ` ⇒ ตัวบทขึ้นแล้ว = ข้อคู่ข้อแรกมีเลขข้อ ⇒ เปลี่ยนแค่ที่รอ ⛔ ไม่แตะเกณฑ์
        if (document.querySelector('.pk-บนล่างจอแคบ .pk-หัวคู่')) return !!document.querySelector('.pk-ข้อคู่ .pk-เลขข้อ')
        const ทั้งหมด = [...document.querySelectorAll('.pk-ตอนเทียบ')]
        return (
          ทั้งหมด.length > 0 &&
          ทั้งหมด.every((s) => s.querySelector('.pk-เนื้อตอนเทียบ .pk-เลขข้อ'))
        )
      },
      null,
      { timeout: รอนานสุด },
    )
    .then(() => true)
    .catch(() => false)
  if (!ขึ้น) ตก.push(`ตัวบทของตอนที่เทียบ ⛔ ไม่ขึ้นภายใน ${รอนานสุด / 1000} วินาที`)
}

