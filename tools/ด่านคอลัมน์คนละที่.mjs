      // ⭐ ใบ #134 ⇒ หัวข้อย่อยเป็นกล่องของตัวเอง ⇒ `textContent` ต่อมันติดกับคำท้ายข้อก่อนหน้าโดยไม่มีช่องว่าง
      //   ⇒ เติมช่องว่างรอบหัวข้อในสำเนา ⇒ หัวข้อเป็นคำของมันเอง ⇒ ⛔ ไม่ได้ถอดอะไรออก ⇒ ตัวอักษรทุกตัวยังถูกเทียบ
