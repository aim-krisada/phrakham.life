/** ⭐ ตัวบทที่ซองข้อมูลมีจริง ⇒ **เจ้าของความจริงคือซอง ⛔ ไม่ใช่หน้าเว็บ** */
async function ตัวบทจากซอง(แท็บ, ฉบับ) {
  const ที่อยู่ = `${ฐาน}/api/chapter/${ตอนที่เทียบ.เล่ม}/${ตอนที่เทียบ.บท}.json`
  return แท็บ.evaluate(
    async ([url, ฉ]) => {
      const ของ = await (await fetch(url)).json()
      const ชั้น = ของ.ชั้น[ฉ] || {}
      // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/134 ⇒ หัวข้อย่อยของฉบับนี้ขึ้นในตัวบทของคอลัมน์ด้วย (สวิตช์ตั้งต้นเปิด)
      //   ⇒ ของที่คาดต้องมีหัวข้อตรงที่ของมันด้วย ⇒ ⛔ ไม่ใช่ถอดหัวข้อออกจากหน้าก่อนเทียบ ⇒ เกณฑ์ยังเป็น *ทุกตัวอักษรที่เห็นตรงกับซอง*
      //   ⇒ หัวข้อต้นข้อ ⇒ ก่อนตัวบทของข้อ · หัวข้อกลางข้อ ⇒ ตรงตัวอักษรที่เจ้าของวาง
      const หัว = ของ.หัวข้อ?.[ฉ] || []
      const ใส่หัว = (n, t) => {
        let ได้ = t
        for (const ห of หัว.filter((x) => x.ข้อ === Number(n)).sort((a, b) => b.หลังอักษร - a.หลังอักษร))
          ได้ = `${ได้.slice(0, ห.หลังอักษร)} ${ห.ตัวหนังสือ} ${ได้.slice(ห.หลังอักษร)}`
        return ได้
      }
      return Object.keys(ชั้น)
        .sort((a, b) => Number(a) - Number(b))
        .map((n) => ใส่หัว(n, ชั้น[n]))
        .join(' ')
        .replace(/\s+/g, ' ')
        .trim()
    },
    [ที่อยู่, ฉบับ],
  )
}

