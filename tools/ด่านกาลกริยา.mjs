/** ตัดรหัส 2 ตัวอักษรจากรูปผันต้นทาง ⇒ `V-2AAI-3S` ⇒ `AI` · ⛔ ไม่ใช่กริยา ⇒ null */
function รหัสที่ควรได้(รูปผัน) {
  if (!รูปผัน.startsWith('V-')) return null
  const m = /^V-2?([A-Z])[A-Z]([A-Z])(?:-|$)/.exec(รูปผัน)
  return m ? m[1] + m[2] : `ตัดไม่ออก:${รูปผัน}`
}

/** ข้อ ⑤ ⑥ ⇒ ตารางสัญลักษณ์ครบ ไม่ซ้ำ และ aorist ไม่หลุดไปเป็น *ครั้งเดียวจบ* */
function ตรวจตาราง(ตาราง, ถ้อยคำร่วม = { ย่อหน้านำ, ความหมายคำสั่ง, ที่มาถ้อยคำ }) {
  const ตก = []
  for (const [ชื่อ, ค่า] of Object.entries(ถ้อยคำร่วม)) if (!String(ค่า ?? '').trim()) ตก.push(`⑤ ${ชื่อ} ว่าง`)
  const ปฏิเสธ = 'ไม่ได้แปลว่าทำครั้งเดียวจบ'
  const เอออริสต์ = ตาราง.find((ก) => ก.รหัส === 'A')?.ความหมาย ?? ''
  if (!เอออริสต์.includes(ปฏิเสธ)) ตก.push(`⑥ ความหมายของ aorist ⛔ ไม่มีประโยค "${ปฏิเสธ}" แล้ว`)
  for (const ก of ตาราง) {
    if ((ก.ความหมาย ?? '').replace(ปฏิเสธ, '').includes('ครั้งเดียว'))
      ตก.push(`⑥ ความหมายของ ${ก.รหัส} มีคำว่า "ครั้งเดียว" นอกประโยคปฏิเสธ ⇒ คำอธิบายที่ตำราค้านแล้ว`)
  }
  const เห็นเส้น = new Map()
  for (const ก of ตาราง) {
    for (const ช่อง of ['ชื่อ', 'อังกฤษ', 'ความหมาย', 'รูป', 'เส้น']) {
      if (!String(ก[ช่อง] ?? '').trim()) ตก.push(`⑤ กาล ${ก.รหัส} ⛔ ไม่มีช่อง ${ช่อง} ⇒ สัญลักษณ์ที่ไม่มีคำอธิบาย`)
    }
    const หน้าตา = `${ก.เส้น}|${(ก.จุด ?? []).join(',')}`
    if (เห็นเส้น.has(หน้าตา)) ตก.push(`⑤ กาล ${ก.รหัส} หน้าตาเหมือน ${เห็นเส้น.get(หน้าตา)} ⇒ แยกด้วยตา ⛔ ไม่ได้`)
    เห็นเส้น.set(หน้าตา, ก.รหัส)
  }
  for (const รหัส of ['P', 'I', 'A', 'R', 'L', 'F']) {
    if (!ตาราง.some((ก) => ก.รหัส === รหัส)) ตก.push(`⑤ ตาราง ⛔ ไม่มีกาล ${รหัส} (เกณฑ์ข้อ 6 สั่งให้แยกได้อย่างน้อย 6 กาล)`)
  }
  return ตก
}

/**
 * ตรวจบทเดียว ⇒ `ต้นทาง` = ไฟล์จาก `_data/ภาษาเดิม/` · `เว็บ` = ไฟล์ `api/words/` ที่สร้างเสร็จ
 * คืน `{ตก, กริยา}` ⇒ ⛔ ตัวตรวจนี้ตัวเดียวใช้ทั้งของจริงและท่าทดสอบตัวเอง
 */
function ตรวจบท(ป้าย, ต้นทาง, เว็บ, อ่าน = อ่านกาล) {
  const ตก = []
  let กริยา = 0
  for (const [ชั้น, ข้อทั้งหมด] of Object.entries(ต้นทาง.ชั้น)) {
    const กรีก = ชั้น === 'คำกรีก'
    for (const [ข้อ, คำต้นทาง] of Object.entries(ข้อทั้งหมด)) {
      const คำเว็บ = เว็บ?.ชั้น?.[ชั้น]?.[ข้อ]
      if (!คำเว็บ || คำเว็บ.length !== คำต้นทาง.length) {
        ตก.push(`${ป้าย}:${ข้อ} ${ชั้น} ⇒ ต้นทาง ${คำต้นทาง.length} คำ แต่เว็บ ${คำเว็บ?.length ?? 0} คำ`)
        continue
      }
      คำต้นทาง.forEach((ค, i) => {
        const ควร = กรีก ? รหัสที่ควรได้(ค['รูปผัน'] ?? '') : null
        const ได้ = คำเว็บ[i][2]
        const ที่ = `${ป้าย}:${ข้อ} คำที่ ${i + 1} ${ค['ตัว'] ?? ''} (${ค['รูปผัน'] ?? ''})`
        if (ควร === null) {
          if (คำเว็บ[i].length !== 2) ตก.push(`④ ${ที่} ⛔ ไม่ใช่กริยากรีก แต่มีช่องที่ 3 = ${JSON.stringify(ได้)}`)
          return
        }
        กริยา++
        if (ได้ === undefined) return void ตก.push(`① ${ที่} ⇒ กริยาที่ไม่มีสัญลักษณ์`)
        if (ได้ !== ควร) ตก.push(`② ${ที่} ⇒ เว็บส่ง ${ได้} ⛔ ต้นทางคือ ${ควร}`)
        if (!อ่าน(ได้)) ตก.push(`③ ${ที่} ⇒ รหัสกาล ${ได้} แปลไม่ออก`)
      })
    }
  }
  return { ตก, กริยา }
}

