def เทสกฎคอลัมน์():
    """คืนจำนวนข้อที่ตก ⇒ 0 แปลว่ากฎคอลัมน์ยังทำงานถูกทั้ง 5 แบบ"""
    ตก = 0
    for ชื่อ, ช่อง, ที่ควรได้ in เทสจับคู่:
        ได้ = [(n, w) for n, w, _, _ in จับคู่ในตาราง(ช่อง)]
        ผ่าน = ได้ == ที่ควรได้
        ตก += not ผ่าน
        print(f"  {'ok ' if ผ่าน else '⛔ ตก'} {ชื่อ}")
        if not ผ่าน:
            print(f"      ควรได้ {ที่ควรได้}\n      ได้จริง {ได้}")
    ตาราง = แยกหัวเรื่องกับข้อมูล(เทสตัดตาราง)
    ผลตาราง = [(ชื่อ, [(n, w) for n, w, _, _ in จับคู่ในตาราง(ช่อง)]) for ชื่อ, ช่อง in ตาราง]
    ที่ควรได้ = [("", [(1, "ตระ")]),
                ("คำที่ไม่มีตัวสะกด ประสมสระเสียงยาว", [(1, "ขรัว")])]
    ผ่าน = ผลตาราง == ที่ควรได้
    ตก += not ผ่าน
    print(f"  {'ok ' if ผ่าน else '⛔ ตก'} หัวเรื่องตารางถัดไปไม่หลุดมาเป็นคำ (ป.6 หน้า pdf 8)")
    if not ผ่าน:
        print(f"      ควรได้ {ที่ควรได้}\n      ได้จริง {ผลตาราง}")
    return ตก


