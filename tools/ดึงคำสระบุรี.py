def เป็นเชิงอรรถที่ตกจุด(ข้อความ, พ้นหมายเหตุ):
    """ใต้กล่องหมายเหตุ ⇒ "เลข + จุดหรือดอกจัน + ประโยคที่มีช่องว่าง" คือเชิงอรรถ

    เชิงอรรถบางข้อพิมพ์ตกจุดไป เช่น `๒***พรรณไม้ หมายถึง พืชชนิดนั้น ๆ…` (ป.5 หน้า pdf 39)
    ⛔ ต้องมีช่องว่างด้วย เพราะช่องคำจริงก็ขึ้นต้นแบบนี้ได้ เช่น `๙๒***พรรณไม้` ในหน้าเดียวกัน
    ⛔ และใช้ได้เฉพาะใต้กล่องหมายเหตุ ⇒ ในตัวตารางมีคำที่ขึ้นต้นด้วยดอกจันจริง เช่น `*ผูกพัน`
    """
    return bool(พ้นหมายเหตุ and " " in ข้อความ
                and เลขข้อเชิงอรรถหลังหมายเหตุ.match(ข้อความ))


def แยกเครื่องหมายออกจากคำ(ข้อความ):
    """คืน (ตัวคำ, เครื่องหมายที่เล่มใส่ไว้) ⇒ ดอกจันสองข้าง และวงเล็บที่ไม่สมดุล"""
    เก็บ = []
    for กฎ in (ดอกจัน, วงเล็บไม่ปิด):
        for m in กฎ.finditer(ข้อความ):
            if m.group(0).strip():
                เก็บ.append(m.group(0).strip())
        ข้อความ = กฎ.sub("", ข้อความ)
    if ข้อความ.count("(") < ข้อความ.count(")"):
        m = วงเล็บไม่เปิด.match(ข้อความ)
        if m:
            เก็บ.append(")")
            ข้อความ = ข้อความ[: m.end() - 1] + ข้อความ[m.end() :]
    return ข้อความ.strip(), " ".join(เก็บ)


