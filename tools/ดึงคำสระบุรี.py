def เป็นแถวหัวตาราง(ช่อง):
    """แถวหัวตารางคือแถวที่ทุกช่องเป็นคำว่า "คำที่" หรือ "คำ" ⇒ ใช้เป็นหมุดแบ่งหัวเรื่องกับข้อมูล

    ⭐ หมุดนี้เชื่อถือได้กว่าการวัดระยะจากขอบบน เพราะความสูงของหัวเรื่องต่างกันทุกหน้าทุกเล่ม
    """
    return len(ช่อง) >= 2 and all(t in ช่องหัวตาราง for _, t in ช่อง)


def ตัดที่พิมพ์ซ้ำ(ช่อง):
    """ชื่อหมวดในไฟล์ถูกพิมพ์ทับกันสองรอบ (เงาตัวอักษรของ Canva) ⇒ ช่องที่ติดกันจะซ้ำกันเป๊ะ"""
    ออก = []
    for _, ข้อความ in ช่อง:
        if not ออก or ออก[-1] != ข้อความ:
            ออก.append(ข้อความ)
    return "".join(ออก).strip()


