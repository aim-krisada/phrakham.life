def จัดแถว(หน้า, เผื่อ=6.0):
    """รวมบรรทัดที่อยู่ระดับเดียวกันเป็นแถวเดียว เรียงซ้ายไปขวา คืน [(y, [(x0, ข้อความ)])]"""
    แถว = defaultdict(list)
    บรรทัด = []
    for b in หน้า.get_text("dict")["blocks"]:
        for l in b.get("lines", []):
            ข้อความ = "".join(s["text"] for s in l["spans"]).strip()
            if ข้อความ and l["bbox"][0] <= ขอบขวาของตาราง:
                บรรทัด.append((l["bbox"], ข้อความ))
    for bbox, ข้อความ in sorted(บรรทัด, key=lambda t: t[0][1]):
        กลาง = (bbox[1] + bbox[3]) / 2
        คีย์ = next((k for k in แถว if abs(k - กลาง) < เผื่อ), กลาง)
        แถว[คีย์].append((bbox[0], ข้อความ))
    return [(k, sorted(แถว[k])) for k in sorted(แถว)]


def แยกเลขที่ติดกับคำ(ข้อความ):
    """ในหน้าคลังคำศัพท์ ช่องเลขกับช่องคำชิดกันจนโปรแกรมอ่าน PDF คืนมาเป็นก้อนเดียว
    เช่น "๒๖เก็บขยะ" หรือ "๑๐๑ตลอด (พบบ่อย) ๑๒๖โทรทัศน์" ⇒ ตัดตรงรอยต่อเลขกับตัวอักษร

    ⛔ ปลอดภัยเพราะ **ไม่มีคำไหนในบัญชีนี้มีเลขอยู่ในตัวคำ** ⇒ `--ตรวจ` ยืนยันให้อีกชั้น
    """
    ท่อน = [t.strip() for t in re.split(f"([{ทุกเลข}]+)", ข้อความ) if t.strip()]
    return ท่อน or []


