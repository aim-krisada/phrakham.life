def วันแก้ไฟล์(p):
    try:
        return datetime.date.fromtimestamp(os.path.getmtime(p)).isoformat()
    except OSError:
        return None


def ลายนิ้วมือ(p):
    """ลายนิ้วมือของไฟล์ที่เราใช้จริง ⇒ ตรึงรุ่นได้แม้เจ้าของไม่ติดเลขรุ่นมาให้

    ⭐ ทำไมต้องมี ⇒ MACULA โหลดมาเป็นไฟล์บีบอัดจากสาขาหลัก ⛔ ไม่มีเลขคอมมิตติดมา
    ⇒ คนที่อยากทำซ้ำ ดาวน์โหลดไฟล์แล้วคำนวณเทียบ ⇒ ตรงกัน = ใช้ไฟล์เดียวกันแน่
    ⇒ 4 ก.ย. 2569 โคลนใหม่แล้ว ⇒ ได้เลขคอมมิตครบ

    ⚠️ **ปรับการขึ้นบรรทัดให้เป็นแบบเดียวกันก่อนคำนวณ** ⛔ ไม่งั้นตรึงข้ามเครื่องไม่ได้
    เครื่องที่ตั้งกิตให้แปลงการขึ้นบรรทัดเป็นแบบวินโดวส์ตอนโคลน จะได้เลขต่างจากไฟล์บีบอัด
    ทั้งที่เนื้อเหมือนกันทุกตัวอักษร (เจอจริง 4 ก.ย. 2569 ⇒ ต้นฉบับกรีกกับตารางแมปฮีบรู)
    """
    CR, LF = bytes([13]), bytes([10])   # ⛔ เขียนแบบนี้เพื่อเลี่ยงปัญหาตัวหนีบรรทัด
    try:
        h = hashlib.sha256()
        with open(p, 'rb') as f:
            ค้าง = b''
            for ก้อน in iter(lambda: f.read(1 << 20), b''):
                ก้อน = ค้าง + ก้อน
                # ก้อนจบด้วย CR พอดี ⇒ ยังไม่รู้ว่าตามด้วย LF ไหม ⇒ พักไว้รอก้อนถัดไป
                ค้าง = CR if ก้อน.endswith(CR) else b''
                if ค้าง:
                    ก้อน = ก้อน[:-1]
                h.update(ก้อน.replace(CR + LF, LF))
            if ค้าง:
                h.update(ค้าง)
        return h.hexdigest()[:16]
    except OSError:
        return None


def ขนาดไฟล์(p):
    try:
        return os.path.getsize(p)
    except OSError:
        return None


def ของไฟล์(ชื่อ, path, รุ่นที่เจ้าของประกาศ=None, หมายเหตุ=None):
    """ช่องมาตรฐานของทุกไฟล์ที่ใช้ ⇒ แหล่งอื่นใช้โครงนี้ซ้ำได้"""
    d = {'ชื่อ': ชื่อ, 'ไฟล์': os.path.basename(path),
         'รุ่นที่เจ้าของประกาศ': รุ่นที่เจ้าของประกาศ,
         'ลายนิ้วมือไฟล์': ลายนิ้วมือ(path),
         'ขนาดไบต์': ขนาดไฟล์(path),
         'วันที่ไฟล์ในเครื่อง': วันแก้ไฟล์(path)}
    if หมายเหตุ:
        d['หมายเหตุ'] = หมายเหตุ
    return d


def เลขรุ่นกิต(path):
    """เลขรุ่นของกองที่แตกไว้ ⇒ เอา sha มาเฉพาะเมื่อโฟลเดอร์นั้น**เป็นที่เก็บกิตของตัวเอง**

    ⚠️ ⛔ ห้ามเรียก git เฉย ๆ ⇒ ถ้าโฟลเดอร์ไม่ใช่ที่เก็บ git จะเดินขึ้นไปหยิบ sha
    ของที่เก็บแม่มาแทน ⇒ ได้เลขรุ่นของงานเรา ⛔ ไม่ใช่ของแหล่ง ⇒ ผิดแบบที่ดูเหมือนถูก
    (เจอจริง 1 ก.ย. 2569 ⇒ ได้ sha ของ v3/phrakham มาแทน sha ของ MACULA)
    """
    if not os.path.isdir(os.path.join(path, '.git')):
        return None
    try:
        sha = subprocess.run(['git', '-C', path, 'rev-parse', '--short=12', 'HEAD'],
                             capture_output=True, text=True, timeout=10).stdout.strip()
        วัน = subprocess.run(['git', '-C', path, 'log', '-1', '--format=%cs'],
                             capture_output=True, text=True, timeout=10).stdout.strip()
        return (sha + ' · ' + วัน) if sha else None
    except Exception:
        return None


