#!/usr/bin/env python3
"""ตรวจว่าช่วง "คำที่พระเยซูพูด" ที่ `อ่าน_usx` เก็บมา ครบและระบายถูกที่หรือไม่

ใบงาน  https://github.com/aim-krisada/phrakham3/issues/6

ตรวจ 4 ข้อ
  ① ของเดิมไม่เปลี่ยน ⇒ ตัวบท · ข้อว่าง · รอยแบ่ง · เชิงอรรถ ต้องได้เท่าที่ `ควรได้` บอก
  ② จำนวนป้าย `wj` ในไฟล์ USX ดิบ เทียบกับจำนวนช่วงที่เก็บได้
     ⚠️ **สองเลขนี้ไม่จำเป็นต้องเท่ากัน** ⇒ ป้ายเดียวที่คร่อมรอยข้อ ถูกตัดเป็นหลายช่วง
  ③ ⭐ **ตัวหนังสือต้องตรงตัวต่อตัว** ⇒ เอาตัวบทมาตัดตาม `หลังอักษร`-`ถึงอักษร`
     ต่อกันทั้งเล่ม แล้วเทียบกับตัวหนังสือในป้าย `wj` ที่อ่านจากไฟล์ดิบตรง ๆ
     (ทิ้งช่องว่างทั้งสองฝั่งก่อนเทียบ ⇒ เพราะตัวบทถูกเล็มหัวท้ายของข้อไปแล้ว)
  ④ ทุกช่วงต้องอยู่ในกรอบของข้อ และไม่ยาวศูนย์

แล้วพิมพ์ตัวอย่างช่วงที่ **ข้ามรอยข้อ** ออกมาให้ดูด้วยตา

⛔ สคริปต์นี้อ่านอย่างเดียว ไม่เขียนไฟล์อะไรเลย

รัน  py -3.14 tools/ตรวจคำพระเยซู.py
"""
import collections
import io
import os
import sys
import xml.etree.ElementTree as ET

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
ที่เก็บ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ที่เก็บ, 'tools'))
import สร้างข้อมูลเว็บ as ตัวแปลง  # noqa: E402

USX = os.path.join(ที่เก็บ, '_แตก', 'tcv', 'usx-rev2-release', 'release', 'USX_1')


def คำพระเยซูจากไฟล์ดิบ(รหัส):
    """เปิดไฟล์ USX เอาตัวหนังสือในป้าย `wj` มาตรง ๆ ⇒ เป็นตัวหารว่าเก็บครบไหม

    ⛔ ไม่เอาตัวหนังสือในเชิงอรรถ (เหมือนตอนอ่านตัวบท) · ⛔ ไม่เอาหางของป้าย
    """
    ราก = ET.parse(os.path.join(USX, รหัส + '.usx')).getroot()
    ก้อน = []

    def เนื้อใน(e):
        ชิ้น = [e.text or '']
        for c in e:
            if ตัวแปลง.ชื่อสั้น(c.tag) == 'note':
                ชิ้น.append(c.tail or '')
                continue
            ชิ้น.append(เนื้อใน(c))
            ชิ้น.append(c.tail or '')
        return ''.join(ชิ้น)

    for el in ราก.iter():
        if ตัวแปลง.ชื่อสั้น(el.tag) == 'char' and el.get('style') == 'wj':
            ก้อน.append(เนื้อใน(el))
    return ก้อน


def ไม่เอาช่องว่าง(s):
    return ''.join(s.split())


def main():
    (ข้อ, _, ว่าง, รอย, เชิงอรรถ,
     พระเยซู) = ตัวแปลง.อ่าน_usx(USX, 'TCV', เอาคำพระเยซู=True)
    ควร = ตัวแปลง.ควรได้['TCV']
    print('① ของเดิม ⇒ ตัวบท %s ข้อ (ควรได้ %s) · ข้อว่าง %s (ควรได้ %s) · '
          'รอยแบ่ง %s อัน · เชิงอรรถ %s อัน'
          % (format(len(ข้อ), ','), format(ควร['ข้อ'], ','), len(ว่าง), ควร['ว่าง'],
             format(sum(len(v) for v in รอย.values()), ','),
             format(sum(len(v) for v in เชิงอรรถ.values()), ',')))

    ป้ายดิบ = {รหัส: คำพระเยซูจากไฟล์ดิบ(รหัส) for รหัส in ตัวแปลง.สารบบ}
    จำนวนป้าย = sum(len(v) for v in ป้ายดิบ.values())
    ช่วง = sum(len(v) for v in พระเยซู.values())
    ต่อจากข้อก่อน = sum(1 for v in พระเยซู.values() for ก in v if ก.get('ต่อจากข้อก่อน'))
    print('\n② ป้าย `wj` ในไฟล์ดิบ %s อัน ⇒ เก็บเป็นช่วงได้ %s ช่วง '
          '⇒ ช่วงที่ต่อมาจากข้อก่อนหน้า %s ช่วง'
          % (format(จำนวนป้าย, ','), format(ช่วง, ','), format(ต่อจากข้อก่อน, ',')))
    print('   แยกตามเล่ม ⇒ %s'
          % ' · '.join('%s %s/%s' % (ก, len(ป้ายดิบ[ก]),
                                     sum(len(v) for (ล, บ), v in พระเยซู.items() if ล == ก))
                       for ก in ตัวแปลง.สารบบ if ป้ายดิบ[ก]))

    # ③ ตัวหนังสือตรงตัวต่อตัวไหม ⇒ เทียบทีละเล่ม
    ไม่ตรง = []
    for รหัส in ตัวแปลง.สารบบ:
        ดิบ = ไม่เอาช่องว่าง(''.join(ป้ายดิบ[รหัส]))
        ก้อน = []
        for (ล, บ) in sorted((k for k in พระเยซู if k[0] == รหัส), key=lambda k: k[1]):
            for ก in พระเยซู[(ล, บ)]:
                ก้อน.append(ข้อ[(ล, str(บ), str(ก['ข้อ']))][ก['หลังอักษร']:ก['ถึงอักษร']])
        ได้ = ไม่เอาช่องว่าง(''.join(ก้อน))
        if ได้ != ดิบ:
            ไม่ตรง.append((รหัส, len(ดิบ), len(ได้)))
    print('\n③ เล่มที่ตัวหนังสือไม่ตรงกับไฟล์ดิบ %s เล่ม' % len(ไม่ตรง))
    for x in ไม่ตรง:
        print('   %s ⇒ ดิบ %s ตัวอักษร · เก็บได้ %s ตัวอักษร' % x)

    # ④ ทุกช่วงต้องอยู่ในกรอบของข้อ และยาวมากกว่าศูนย์
    นอกกรอบ = []
    for (ล, บ), รายการ in พระเยซู.items():
        for ก in รายการ:
            เนื้อ = ข้อ.get((ล, str(บ), str(ก['ข้อ'])))
            if (เนื้อ is None or not 0 <= ก['หลังอักษร'] < ก['ถึงอักษร'] <= len(เนื้อ)):
                นอกกรอบ.append((ล, บ, ก['ข้อ'], ก['หลังอักษร'], ก['ถึงอักษร']))
    print('\n④ ช่วงที่หลุดกรอบของข้อ %s ช่วง' % format(len(นอกกรอบ), ','))
    for x in นอกกรอบ[:5]:
        print('   %s %s.%s ⇒ %s-%s' % x)

    # ── ตัวอย่างช่วงที่ข้ามรอยข้อ ⇒ ดูด้วยตา
    print('\n⑤ ตัวอย่างช่วงที่ข้ามรอยข้อ 3 จุดแรก')
    เห็นแล้ว = 0
    for (ล, บ) in sorted(พระเยซู):
        รายการ = พระเยซู[(ล, บ)]
        for i, ก in enumerate(รายการ):
            if not ก.get('ต่อจากข้อก่อน') or i == 0:
                continue
            ก่อน = รายการ[i - 1]
            print('   %s %s.%s-%s' % (ล, บ, ก่อน['ข้อ'], ก['ข้อ']))
            print('     ข้อ %s ⇒ …%s' % (ก่อน['ข้อ'],
                  ข้อ[(ล, str(บ), str(ก่อน['ข้อ']))][ก่อน['หลังอักษร']:ก่อน['ถึงอักษร']][-40:]))
            print('     ข้อ %s ⇒ %s…' % (ก['ข้อ'],
                  ข้อ[(ล, str(บ), str(ก['ข้อ']))][ก['หลังอักษร']:ก['ถึงอักษร']][:40]))
            เห็นแล้ว += 1
            if เห็นแล้ว >= 3:
                return 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
