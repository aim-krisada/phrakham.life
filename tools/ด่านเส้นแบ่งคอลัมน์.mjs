const แยกสี = (s) => {
  const m = /rgba?\(([^)]+)\)/.exec(s || '')
  if (!m) return null
  const p = m[1].split(/[,\s/]+/).filter(Boolean).map(Number)
  return { r: p[0], g: p[1], b: p[2], a: p.length > 3 ? p[3] : 1 }
}
const ความสว่าง = ({ r, g, b }) => {
  const f = (c) => ((c /= 255) <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
}
const ต่างสี = (a, b) => {
  const [x, y] = [ความสว่าง(a), ความสว่าง(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}

/** ⑥ ส่วนที่อ่านไฟล์ ⇒ เลขสีของเส้นอยู่ที่เดียว */
function ตรวจไฟล์สี(ตก) {
  const ที่ = 'app/assets/css'
  let เจอ = 0
  let ค่า = null
  for (const f of readdirSync(ที่).filter((x) => x.endsWith('.css'))) {
    const s = readFileSync(join(ที่, f), 'utf8')
    const m = /--pk-สีเส้นคอลัมน์\s*:\s*([^;]+);/.exec(s)
    if (m) ค่า = m[1].trim()
  }
  if (!ค่า) {
    ตก.push('⑥ ไม่เจอ `--pk-สีเส้นคอลัมน์` ในไฟล์ CSS ⇒ สีของเส้นต้องเป็นค่าชุดเดียว')
    return
  }
  if (!/^#[0-9a-f]{3,8}$/i.test(ค่า)) return
  for (const f of readdirSync(ที่).filter((x) => x.endsWith('.css'))) {
    const s = readFileSync(join(ที่, f), 'utf8').toLowerCase()
    เจอ += s.split(ค่า.toLowerCase()).length - 1
  }
  if (เจอ !== 1) ตก.push(`⑥ เลขสี ${ค่า} ของเส้นโผล่ ${เจอ} ที่ในไฟล์ CSS ⇒ ต้องอยู่ที่ \`--pk-สีเส้นคอลัมน์\` ที่เดียว`)
}

/** ⭐ ห่างกลางช่องเท่าไร ⇒ เลือกที่ใกล้สุดระหว่างกลางช่องของกล่อง กับครึ่งช่องของตารางจากกล่องขวาหรือกล่องซ้าย (หัวไฟล์ข้อ ①) */
const ห่างกลาง = (x, ซ้าย, ขวา, G) => Math.min(Math.abs(x - (ซ้าย + ขวา) / 2), Math.abs(x - (ขวา - G / 2)), Math.abs(x - (ซ้าย + G / 2)))

