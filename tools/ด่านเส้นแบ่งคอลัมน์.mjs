function วัดในหน้า() {
  const px = (v) => parseFloat(v) || 0
  const เห็น = (e) => {
    if (!e || !e.getClientRects().length) return false
    const r = e.getBoundingClientRect()
    const cs = getComputedStyle(e)
    return r.width > 0.5 && r.height > 0.5 && cs.visibility !== 'hidden'
  }
  const กล่อง = (r) => ({ ซ้าย: r.left, ขวา: r.right, บน: r.top + scrollY, ล่าง: r.bottom + scrollY })
  const ราก = getComputedStyle(document.documentElement)
  const ตัวลอง = document.createElement('div')
  ตัวลอง.style.cssText = 'position:absolute;visibility:hidden;width:var(--pk-ช่องไฟปุ่ม);height:var(--pk-ช่องคอลัมน์);background:var(--pk-สีเส้นคอลัมน์);color:var(--color-pk-paper)'
  document.body.appendChild(ตัวลอง)
  const ช่องไฟปุ่ม = ตัวลอง.getBoundingClientRect().width
  const ช่องคอลัมน์ = ตัวลอง.getBoundingClientRect().height
  ตัวลอง.style.width = 'var(--pk-ช่องไฟปุ่มเบียด)'
  const ช่องไฟปุ่มเบียด = ตัวลอง.getBoundingClientRect().width
  const สีเส้น = getComputedStyle(ตัวลอง).backgroundColor
  const สีกระดาษ = getComputedStyle(ตัวลอง).color
  ตัวลอง.remove()

  // ⭐ เส้น 1 เส้นจาก `::before` หรือ `::after` ที่ลอยอยู่ ⇒ กล่องอ้างอิงคือขอบในของเจ้าของ
  //   ⇒ เจ้าของที่วางเส้นลงช่องของตาราง (`grid-column`) ⇒ กล่องอ้างอิงคือช่องนั้น ⇒ คิดจากช่องของตารางแม่ที่คำนวณแล้ว
  const เส้นของ = (เจ้าของ, ชนิด, ที่) => {
    const out = []
    for (const p of ['::before', '::after']) {
      const cs = getComputedStyle(เจ้าของ, p)
      if (!cs.content || cs.content === 'none' || cs.content === 'normal' || cs.display === 'none') continue
      if (cs.position !== 'absolute') continue
      const กว้าง = px(cs.width)
      if (กว้าง <= 0 || กว้าง > 2) continue
      const r = เจ้าของ.getBoundingClientRect()
      const hs = getComputedStyle(เจ้าของ)
      let ซ้ายอ้าง = r.left + px(hs.borderLeftWidth)
      const บนอ้าง = r.top + px(hs.borderTopWidth) + scrollY
      const ล่างอ้าง = r.bottom - px(hs.borderBottomWidth) + scrollY
      const เริ่มช่อง = parseInt(cs.gridColumnStart, 10)
      let บนช่อง = บนอ้าง
      let ล่างช่อง = ล่างอ้าง
      if (Number.isFinite(เริ่มช่อง) && hs.display === 'grid') {
        // ⭐ ตารางที่ยืมช่องจากแม่ (`subgrid`) ⇒ ช่องของจริงอยู่ที่แม่ ⇒ ตารางของตัวเอง ⇒ ช่องอยู่ที่ตัวเอง
        const ตาราง = /^subgrid/.test(hs.gridTemplateColumns) ? เจ้าของ.parentElement : เจ้าของ
        const ms = getComputedStyle(ตาราง)
        const ช่อง = ms.gridTemplateColumns.split(/\s+/).map(px)
        const gap = px(ms.columnGap)
        const mr = ตาราง.getBoundingClientRect()
        let x = mr.left + px(ms.borderLeftWidth) + px(ms.paddingLeft)
        for (let i = 0; i < เริ่มช่อง - 1 && i < ช่อง.length; i++) x += ช่อง[i] + gap
        if (เริ่มช่อง - 1 > ช่อง.length) continue
        ซ้ายอ้าง = x
        // ⭐ ระบุแถวด้วย ⇒ กล่องอ้างอิงแนวตั้งคือแถวนั้น
        const เริ่มแถว = parseInt(cs.gridRowStart, 10)
        if (Number.isFinite(เริ่มแถว) && ตาราง === เจ้าของ) {
          const แถว = ms.gridTemplateRows.split(/\s+/).map(px)
          const rg = px(ms.rowGap)
          let y = mr.top + px(ms.borderTopWidth) + px(ms.paddingTop) + scrollY
          for (let i = 0; i < เริ่มแถว - 1 && i < แถว.length; i++) y += แถว[i] + rg
          บนช่อง = y
          ล่างช่อง = y + (แถว[เริ่มแถว - 1] || 0)
        }
      }
      const บน = บนช่อง + px(cs.top)
      const ล่าง = ล่างช่อง - px(cs.bottom)
      if (ล่าง - บน < 8) continue
      out.push({
        x: ซ้ายอ้าง + px(cs.left) + กว้าง / 2,
        บน,
        ล่าง,
        สี: cs.backgroundColor,
        ชนิด,
        ที่,
        z: cs.zIndex,
      })
    }
    return out
  }

  const เส้นหัว = []
  const เส้นตัวบท = []
  // หัว
  const หัว = [
    ...document.querySelectorAll('.pk-หัวคอลัมน์ .pk-หัวช่อง, .pk-ฝั่งหลัก > .pk-ชื่อคำเดิม, .pk-ตอนเทียบ .pk-หัวช่อง'),
  ].filter(เห็น)
  const หัวที่ใช้ = [...new Set(หัว)].map((h) => {
    const ปุ่ม = [...h.querySelectorAll('select, button')].filter((b) => เห็น(b) && !b.closest('.pk-เฉพาะเสียง') && !b.closest('.pk-เมนู'))
    const rs = ปุ่ม.map((b) => b.getBoundingClientRect()).sort((a, b) => a.left - b.left)
    const r = h.getBoundingClientRect()
    return {
      ...กล่อง(r),
      ปุ่มซ้าย: rs.length ? rs[0].left : r.left,
      ปุ่มขวา: rs.length ? rs[rs.length - 1].right : r.right,
      ปุ่มบน: rs.length ? Math.min(...rs.map((x) => x.top)) + scrollY : r.top + scrollY,
      ปุ่มล่าง: rs.length ? Math.max(...rs.map((x) => x.bottom)) + scrollY : r.bottom + scrollY,
      ช่องในหัว: rs.length >= 2 ? rs[1].left - rs[0].right : 0,
      ตอนเทียบ: !!h.closest('.pk-ตอนเทียบ'),
      คำเดิม: h.matches('.pk-ชื่อคำเดิม'),
    }
  })
  for (const h of หัว) เส้นหัว.push(...เส้นของ(h, 'หัว', h.closest('.pk-ตอนเทียบ') ? 'คนละบท' : ''))
  // ตัวบท ⇒ ช่องของทุกแถว
  const ช่องตัวบท = [...document.querySelectorAll('.pk-ตัวบท .pk-ช่องทั้งหมด > *')].filter(เห็น)
  for (const c of ช่องตัวบท) เส้นตัวบท.push(...เส้นของ(c, 'ช่อง', ''))
  // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/154 (ข้อเพิ่มที่พี่เอมแจ้ง 8 พ.ย. 2569) ⇒ ช่องในตารางที่ห่อแถวพร้อมคำภาษาเดิม
  //   ⇒ เส้นเป็นของกล่องข้อทั้งกล่อง (`.pk-ช่องทั้งหมด::before` `::after` ที่วางลงช่องของตาราง) ⛔ ใช่ของช่องทีละช่อง ⇒ หาเส้นจากกล่องนี้ด้วย ⇒ เกณฑ์ทุกข้อคงเดิม
  for (const g of document.querySelectorAll('.pk-ตัวบท .pk-ช่องทั้งหมด')) if (เห็น(g)) เส้นตัวบท.push(...เส้นของ(g, 'ช่อง', ''))
  for (const t of document.querySelectorAll('.pk-ฝั่งหลัก > .pk-ตัวบท')) if (เห็น(t)) เส้นตัวบท.push(...เส้นของ(t, 'ตัวบท', ''))
  for (const f of document.querySelectorAll('.pk-ฝั่งหลัก')) if (เห็น(f)) เส้นตัวบท.push(...เส้นของ(f, 'ตัวบท', ''))
  const กล่องเทียบ = [...document.querySelectorAll('.pk-พื้นที่อ่าน > .pk-ตอนเทียบ')].filter(เห็น)
  for (const b of กล่องเทียบ) {
    for (const l of เส้นของ(b, 'กล่อง', 'คนละบท')) {
      เส้นตัวบท.push(l)
      // ⭐ เส้นของกล่องที่ยกขึ้นเหนือหัว (จอแคบ) ⇒ นับเป็นเส้นของแถวหัวด้วย
      if (l.z !== 'auto') เส้นหัว.push({ ...l, ชนิด: 'กล่องเหนือหัว' })
    }
  }
  const แผ่นคำเดิม = [...document.querySelectorAll('.pk-ตัวบท > .pk-ชั้นคำ')].filter(เห็น).map((e) => กล่อง(e.getBoundingClientRect()))

  // แถวของตัวบท ⇒ คู่ช่องที่อยู่ข้างกัน
  const คู่ = []
  for (const แถว of document.querySelectorAll('.pk-ตัวบท .pk-ช่องทั้งหมด')) {
    if (!เห็น(แถว)) continue
    const ลูก = [...แถว.children].filter(เห็น).map((e) => กล่อง(e.getBoundingClientRect()))
    for (let i = 1; i < ลูก.length; i++) {
      const a = ลูก[i - 1]
      const b = ลูก[i]
      if (Math.abs(a.บน - b.บน) > 2 || b.ซ้าย < a.ขวา - 0.5) continue
      const ข้างแผ่น = แผ่นคำเดิม.some((k) => k.ซ้าย < b.ซ้าย && k.ขวา > a.ขวา)
      คู่.push({ ซ้าย: a.ขวา, ขวา: b.ซ้าย, บน: Math.min(a.บน, b.บน), ล่าง: Math.max(a.ล่าง, b.ล่าง), ข้างแผ่น, คนละบท: false })
    }
  }
  // ฝั่งหลักกับกล่องคนละบท ⇒ คู่ระหว่างกล่อง
  const ฝั่ง = document.querySelector('.pk-ฝั่งหลัก')
  let ก่อน = ฝั่ง && เห็น(ฝั่ง) ? กล่อง(ฝั่ง.getBoundingClientRect()) : null
  for (const b of กล่องเทียบ) {
    const r = กล่อง(b.getBoundingClientRect())
    if (ก่อน && Math.abs(r.บน - ก่อน.บน) <= 2 && r.ซ้าย >= ก่อน.ขวา - 0.5)
      คู่.push({ ซ้าย: ก่อน.ขวา, ขวา: r.ซ้าย, บน: r.บน, ล่าง: r.ล่าง, ข้างแผ่น: false, คนละบท: true })
    ก่อน = r
  }
  const หมุด = [...document.querySelectorAll('.pk-หมุดบท')].filter(เห็น).map((e) => กล่อง(e.getBoundingClientRect()))
  const ช่องทั้งหมดของตัวบท = ช่องตัวบท.map((e) => กล่อง(e.getBoundingClientRect()))

  // แบบที่ใช้ + หัวต่อแถว
  const คอล = document.querySelector('.pk-คอลัมน์')
  const แบบ = !คอล
    ? '?'
    : คอล.classList.contains('pk-ซ้ายขวาจอแคบ')
      ? 'ซ้ายขวา'
      : คอล.classList.contains('pk-บนล่างจอแคบ')
        ? 'บนล่าง'
        : คอล.classList.contains('pk-ทีละฉบับจอแคบ')
          ? 'ทีละฉบับ'
          : innerWidth >= 768
            ? 'กว้าง'
            : 'เดี่ยว'
  const แถวหัว = []
  for (const h of [...หัวที่ใช้].sort((a, b) => a.บน - b.บน || a.ซ้าย - b.ซ้าย)) {
    const แถว = แถวหัว.find((x) => Math.abs(x.บน - h.บน) < 4)
    if (แถว) แถว.n++
    else แถวหัว.push({ บน: h.บน, n: 1 })
  }

  // แถบล่าง
  const นำทาง = document.querySelector('.pk-นำทางล่าง')
  const ช่องแถบล่าง = []
  if (นำทาง) {
    const ปุ่ม = [...นำทาง.children].filter(เห็น).map((e) => e.getBoundingClientRect()).sort((a, b) => a.left - b.left)
    for (let i = 1; i < ปุ่ม.length; i++) if (Math.abs(ปุ่ม[i].top - ปุ่ม[i - 1].top) < 4) ช่องแถบล่าง.push(ปุ่ม[i].left - ปุ่ม[i - 1].right)
  }
  const ป้ายเล่ม = นำทาง ? [...นำทาง.querySelectorAll('.pk-ป้ายเล่ม')].filter(เห็น) : []
  const ป้ายถูกหด = ป้ายเล่ม.some((e) => e.scrollWidth > e.clientWidth + 0.5)

  return {
    ช่องไฟปุ่ม,
    ช่องคอลัมน์,
    ช่องไฟปุ่มเบียด,
    สีเส้น,
    สีกระดาษ,
    หัว: หัวที่ใช้,
    เส้นหัว,
    เส้นตัวบท,
    คู่,
    แผ่นคำเดิม,
    หมุด,
    ช่องทั้งหมดของตัวบท,
    แบบ,
    การวาง: `${แบบ} ${แถวหัว.map((x) => x.n).join('+')}`,
    ช่องแถบล่าง,
    ป้ายถูกหด,
    เลื่อนข้าง: document.documentElement.scrollWidth - document.documentElement.clientWidth,
  }
}

