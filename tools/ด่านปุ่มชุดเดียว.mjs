/** ไล่ข้อความของไฟล์ `.vue` หนึ่งไฟล์ ⇒ คืนรายการที่ผิด */
export function ตรวจซอร์สไฟล์(ชื่อ, ข้อความ) {
  const ผิด = []
  // ตัดคอมเมนต์ HTML ทิ้งก่อน ⇒ คำอธิบายที่พูดถึง `<button>` ⛔ ใช่ปุ่มจริง
  const เนื้อ = ข้อความ.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '))
  for (const m of เนื้อ.matchAll(/<button\b([^>]*)>/g)) {
    // ข้อยกเว้นเดียว ⇒ คำภาษาเดิมในตัวบท (`class="pk-คำ"` ตรงตัว)
    if (/(^|\s)class="pk-คำ"/.test(m[1])) continue
    const บรรทัด = เนื้อ.slice(0, m.index).split('\n').length
    ผิด.push(`${ชื่อ}:${บรรทัด} ⇒ แท็ก <button> ดิบ ⇒ ต้องเรียก <Button> ของ app/components/ui/button/`)
  }
  for (const m of เนื้อ.matchAll(/role\s*[:=]\s*["']button["']/g)) {
    const บรรทัด = เนื้อ.slice(0, m.index).split('\n').length
    ผิด.push(`${ชื่อ}:${บรรทัด} ⇒ role="button" เขียนเอง ⇒ ต้องเรียก <Button> ของ app/components/ui/button/`)
  }
  return ผิด
}

function ไล่ไฟล์(ที่, ออก = []) {
  for (const ชื่อ of readdirSync(ที่)) {
    const เต็ม = join(ที่, ชื่อ)
    if (statSync(เต็ม).isDirectory()) ไล่ไฟล์(เต็ม, ออก)
    else if (/\.(vue|ts)$/.test(ชื่อ)) ออก.push(เต็ม)
  }
  return ออก
}

function ตรวจซอร์ส() {
  const ตก = []
  for (const เต็ม of ไล่ไฟล์(join(รากโค้ด, 'app'))) {
    const ชื่อ = relative(รากโค้ด, เต็ม).replace(/\\/g, '/')
    // ⭐ ตัวปุ่มกลางเอง ⇒ ที่เดียวที่วาด <button> ได้
    if (ชื่อ.startsWith('app/components/ui/button/')) continue
    // ⭐ ตัวบทที่แตะเลือกข้อ ⇒ ข้อยกเว้นตัวหนังสือ (หัวไฟล์) ⇒ ไฟล์เดียวที่ติด role="button"
    const ข้อความ = readFileSync(เต็ม, 'utf8')
    if (ชื่อ === 'app/composables/เลือกข้อ.ts') {
      // ⭐ นับเฉพาะโค้ด ⇒ บรรทัดคอมเมนต์ที่อธิบายเรื่องนี้ ⛔ นับ
      const โค้ด = ข้อความ
        .split('\n')
        .filter((x) => !/^\s*(\/\/|\*|\/\*)/.test(x))
        .join('\n')
      const n = (โค้ด.match(/role\s*[:=]\s*["']button["']/g) || []).length
      if (n !== 1) ตก.push(`⓪ ${ชื่อ} ⇒ ติด role="button" ${n} ที่ ⇒ ต้องมีที่เดียว (ตัวบทที่แตะเลือกข้อ)`)
      continue
    }
    if (!ชื่อ.endsWith('.vue')) {
      if (/role\s*[:=]\s*["']button["']/.test(ข้อความ)) ตก.push(`⓪ ${ชื่อ} ⇒ ติด role="button" เขียนเอง`)
      continue
    }
    for (const x of ตรวจซอร์สไฟล์(ชื่อ, ข้อความ)) ตก.push(`⓪ ${x}`)
  }
  return ตก
}

