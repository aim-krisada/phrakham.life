//   ⇒ ผู้อ่านบนเน็ตช้า **เห็นชั้นไฟล์ดิบก่อนเสมอ** ⇒ ชั้นนั้นล้นขอบก็คือผู้อ่านต้องปัดจอจริง
//   ⇒ และวัดแต่ชั้นหลังโค้ดทำงาน = วัดหน้าที่ **โค้ดวาดใหม่ทับของที่พังไปแล้ว**
//   ⇒ **เหตุผลเต็มกับวิธีตัดโค้ดออก อยู่ที่ `tools/หน้าที่ตรวจ.mjs`** ⛔ ไม่จดซ้ำที่นี่
