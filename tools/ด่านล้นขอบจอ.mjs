//   node tools/ด่านล้นขอบจอ.mjs <ที่อยู่เว็บ>

import { chromium } from 'playwright'
import { หน้าทั้งหมด, เส้นทางเว็บ, ปิดโค้ดของเว็บ, ชั้นของหน้า, รอบทในที่อยู่, รอแผนภาพครบ } from './หน้าที่ตรวจ.mjs'

const ฐาน = (process.argv[2] || `http://127.0.0.1:5396${เส้นทางเว็บ}`).replace(/\/+$/, '')

// 320 คือพื้นที่ SC 1.4.10 กำหนด · ที่เหลือคือความกว้างจอมือถือกับจอคอมที่คนใช้จริง
const ความกว้าง = [320, 360, 375, 390, 412, 430, 768, 1280]
// ปกติ · 150% · 200% (200% คือเพดานที่ SC 1.4.4 กำหนด)
const ขนาดตัวอักษร = [16, 24, 32]

const วัด = () => {
  const de = document.documentElement
  const ปัด = (v) => Math.round(v * 100) / 100
  return {
    ล้น: ปัด(de.scrollWidth - de.clientWidth),
    // ⛔ บอกแค่ "มีอะไรล้น" ไม่พอ ⇒ ชี้ตัวที่กว้างที่สุดออกมาให้คนแก้ไปที่ชิ้นนั้นได้เลย
    ตัวที่ล้น: [...document.querySelectorAll('body *')]
      .map((el) => ({ el, r: el.getBoundingClientRect() }))
      .filter((x) => x.r.right > de.clientWidth + 1)
      .slice(0, 5)
      .map((x) => `${x.el.tagName.toLowerCase()}.${String(x.el.className).slice(0, 40)} ขวาสุด=${ปัด(x.r.right)}`),
  }
}

const เบราว์เซอร์ = await chromium.launch()
const ที่ตก = []
let ตรวจไป = 0

for (const หน้า of หน้าทั้งหมด) {
  // ⭐ หน้าที่บทมาจากคำถามท้ายที่อยู่ มีเฉพาะชั้นที่โค้ดทำงาน ⇒ เหตุผลอยู่ที่ `ชั้นของหน้า`
  for (const ชั้น of ชั้นของหน้า(หน้า)) {
    for (const เปิดกล่อง of [false, true]) {
      const ctx = await เบราว์เซอร์.newContext()
      const แท็บ = await ctx.newPage()
      if (ชั้น.ปิดโค้ด) await ปิดโค้ดของเว็บ(แท็บ)
      await แท็บ.goto(ฐาน + encodeURI(หน้า.ที่อยู่), { waitUntil: 'domcontentloaded' })
      // ⛔ อย่าวัดตอนที่หน้ายังไม่ถูกวาดเสร็จ — จะได้ตัวเลขของหน้าเปล่า แล้วรายงานว่าผ่าน
      await แท็บ.waitForSelector('article.pk-เนื้อ h1')
      // ⭐ ที่อยู่ที่ขอบทมาด้วย (`?c=`) ⇒ รอหมุดของบทนั้นก่อน ⛔ ไม่งั้นวัดบทแรกแทนบทยาว
      await รอบทในที่อยู่(แท็บ, หน้า.ที่อยู่)

      if (เปิดกล่อง) {
        await แท็บ.evaluate(() => {
          for (const d of document.querySelectorAll('details')) d.open = true
        })
        // แผนภาพถูกวาดหลังกล่องเปิด ⇒ รอให้มันวาดเสร็จก่อนวัด
        // ⛔ ชั้นไฟล์ดิบ ⛔ ไม่มีแผนภาพ เพราะตัววาดเป็นโค้ดของเว็บที่ถูกตัดทิ้ง
        //   ⇒ ที่เห็นแทนคือกล่องข้อความรอวาด ซึ่งก็ต้อง ⛔ ไม่ล้นขอบเหมือนกัน
        // ⛔ หน้าที่ ⛔ ไม่มีแผนภาพ ก็ ⛔ ไม่ต้องรอ — รอไปก็ตายเพราะหมดเวลาเปล่า ๆ
        if (!ชั้น.ปิดโค้ด && หน้า.มีแผนภาพ) {
          await รอแผนภาพครบ(แท็บ)
        }
      }

      for (const px of ขนาดตัวอักษร) {
        await แท็บ.evaluate((v) => {
          document.documentElement.style.fontSize = v + 'px'
        }, px)
        for (const w of ความกว้าง) {
          await แท็บ.setViewportSize({ width: w, height: 900 })
          await แท็บ.waitForTimeout(120)
          const ผล = await แท็บ.evaluate(วัด)
          ตรวจไป++
          if (ผล.ล้น > 0) {
            const ช่อง = `${หน้า.ชื่อ} · ${ชั้น.ชื่อ} @ ${w} จุด · ตัวอักษร ${px} จุด · กล่อง${เปิดกล่อง ? 'เปิด' : 'ปิด'}`
            ที่ตก.push(`${ช่อง} ⇒ เลื่อนซ้ายขวา ${ผล.ล้น} จุด · ${ผล.ตัวที่ล้น.join(' | ')}`)
          }
        }
      }
      await ctx.close()
    }
  }
}

await เบราว์เซอร์.close()

console.log(
  `ตรวจ ${ตรวจไป} ช่อง (${หน้าทั้งหมด.length} หน้า × ชั้นที่หน้านั้นมี × 2 สถานะกล่อง` +
    ` × ${ขนาดตัวอักษร.length} ขนาดตัวอักษร × ${ความกว้าง.length} ความกว้าง)`,
)
if (ที่ตก.length) {
  console.error(`\n⛔ ไม่ผ่าน — ${ที่ตก.length} ช่องเลื่อนซ้ายขวา:`)
  for (const x of ที่ตก) console.error('  - ' + x)
  process.exit(1)
}
console.log('✅ ไม่มีช่องไหนเลื่อนซ้ายขวาเลย')
