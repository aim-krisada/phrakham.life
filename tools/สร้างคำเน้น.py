def จับเครื่องหมาย(เล่ม, ข้อที่อ้าง, คำแรก, คำช่วง):
    """เครื่องหมายหนึ่งอัน ⇒ คืน (ท่า, [(บท, ข้อ, ลำดับคำนับจาก0, ลำดับในช่วง, ตำแหน่งในแถว)])

    ⭐ ช่วงข้ามข้อ ⇒ ต่อคำของทุกข้อในกองเราเป็นแถวเดียว แล้วจับเหมือนข้อเดียว ⇒ แปลงตำแหน่งกลับเป็นข้อของมันเอง
    ⭐ ตำแหน่งในแถว ⇒ ใช้แบ่งท่อนที่ติดกัน (`ช่วงต่อกัน`)
    """
    ข้อทั้งบท, _ = ข้อของกอง(เล่ม, ข้อที่อ้าง[0][0])
    แถว: list[str] = []
    ที่ของแถว: list[tuple[int, int, int]] = []
    for (บท, ข้อ) in ข้อที่อ้าง:
        for j, ค in enumerate(ข้อของกอง(เล่ม, บท)[0].get(ข้อ, [])):
            แถว.append(ค)
            ที่ของแถว.append((บท, ข้อ, j))
    มีข้อ = ข้อที่อ้าง[0][1] in ข้อทั้งบท
    ควร = คำแรก - 1

    def ผล(เริ่ม):
        return [(*ที่ของแถว[เริ่ม + i], i, เริ่ม + i) for i in range(len(คำช่วง))]

    if มีข้อ:
        # ① ตรงเลขคำ
        if ตรงทั้งช่วง(แถว, ควร, คำช่วง):
            return "ตรงเลขคำ", ผล(ควร)
        # ② เลื่อนในข้อเดียวกัน ⇒ ระยะที่ใกล้ที่สุดต้องมีที่เดียว ⛔ ซ้ายขวาห่างเท่ากัน = เดาไม่ได้ ⇒ ไปท่า ④
        for ระยะ in range(1, เลื่อนได้ + 1):
            ที่ตรง = [ควร + d for d in (-ระยะ, ระยะ) if ตรงทั้งช่วง(แถว, ควร + d, คำช่วง)]
            if len(ที่ตรง) == 1:
                return "เลื่อนในข้อ", ผล(ที่ตรง[0])
            if ที่ตรง:
                break
    # ③ ข้อข้างเคียง ⇒ เฉพาะตอนที่ข้อนี้ไม่มี หรือคำไม่ถึงเลขที่อ้าง
    if not มีข้อ or ควร + len(คำช่วง) > len(แถว):
        บท, ข้อ = ข้อที่อ้าง[0]
        เจอ = []
        for v in (ข้อ - 1, ข้อ + 1):
            ข้างเคียง = ข้อทั้งบท.get(v)
            if not ข้างเคียง:
                continue
            for s in range(len(ข้างเคียง) - len(คำช่วง) + 1):
                if ตรงทั้งช่วง(ข้างเคียง, s, คำช่วง):
                    เจอ.append((v, s))
        if len(เจอ) == 1:
            v, s = เจอ[0]
            return "ข้อข้างเคียง", [(บท, v, s + i, i, s + i) for i in range(len(คำช่วง))]
    if not มีข้อ:
        return "ไม่มีข้อนี้", []
    # ④ ทีละคำ ⇒ จับคู่ให้ได้มากคำที่สุดโดยลำดับไม่สลับ (ลำดับร่วมที่ยาวที่สุด)
    #   ⇒ แต่ละคู่ห่างจากตำแหน่งที่ควรเป็นไม่เกิน `ห่างได้` คำ ⇒ เสมอกัน ⇒ เอาคู่ที่ห่างรวมน้อยกว่า
    #   ⛔ ไม่จับทีละคำแบบเจอก่อนได้ก่อน ⇒ คำนำหน้านามตัวแรกจะไปคว้าคำของวลีถัดไปแล้วบังคำจริงที่ตามมา
    n, m = len(คำช่วง), len(แถว)
    ดี = [[(0, 0)] * (m + 1) for _ in range(n + 1)]  # (จำนวนคู่, -ระยะรวม)
    for i in range(n - 1, -1, -1):
        for j in range(m - 1, -1, -1):
            ค่า = max(ดี[i + 1][j], ดี[i][j + 1])
            if abs(j - (ควร + i)) <= ห่างได้ and ตรงกัน(แถว[j], คำช่วง[i]):
                k, r = ดี[i + 1][j + 1]
                ค่า = max(ค่า, (k + 1, r - abs(j - (ควร + i))))
            ดี[i][j] = ค่า
    ได้ = []
    i = j = 0
    while i < n and j < m:
        if abs(j - (ควร + i)) <= ห่างได้ and ตรงกัน(แถว[j], คำช่วง[i]):
            k, r = ดี[i + 1][j + 1]
            if (k + 1, r - abs(j - (ควร + i))) == ดี[i][j]:
                ได้.append((*ที่ของแถว[j], i, j))
                i += 1
                j += 1
                continue
        if ดี[i + 1][j] == ดี[i][j]:
            i += 1
        else:
            j += 1
    # ⛔ ได้แค่คำสั้น ๆ อย่างคำนำหน้านาม (ὁ τό τῷ) ⇒ ⛔ ไม่นับว่าจับได้ ⇒ เครื่องหมายบนคำนำหน้านามตัวเดียวพาผู้อ่านเข้าใจผิด
    if not any(len(คำช่วง[i]) >= 4 for (_, _, _, i, _) in ได้):
        ได้ = []
    return ("ทีละคำ" if ได้ else "จับไม่ได้"), ได้


def ช่วงต่อกัน(ได้):
    """คำที่จับได้ของเครื่องหมายหนึ่งอัน ⇒ แบ่งเป็นท่อนที่ติดกันในตัวบทของเรา ⇒ [[(บท, ข้อ, คำ) ต้น, (บท, ข้อ, คำ) ท้าย], ...]

    ⭐ ท่าทีละคำอาจได้คำที่มีคำของเราคั่นอยู่ ⇒ ⛔ ไม่ครอบคำที่คั่น ⇒ แยกเป็นหลายท่อน
    """
    ท่อน = []
    for (บท, ข้อ, j, _, k) in sorted(ได้, key=lambda x: x[4]):
        # ⭐ ติดกัน = ตำแหน่งในแถวติดกัน **และ** ข้อติดกัน ⇒ ข้อที่กองของเราไม่มี (เช่น มาระโก 9:44) ⇒ แยกท่อน
        #   ⇒ ⛔ ไม่ให้ช่วงคร่อมข้อที่ไม่มีอยู่จริง ⇒ ด่านเครื่องหมายข้อ ⑦ ถือว่าข้อในช่วงต้องมีจริง
        ต่อได้ = bool(ท่อน) and k == ท่อน[-1][2] + 1 and (
            (บท == ท่อน[-1][1][0] and ข้อ in (ท่อน[-1][1][1], ท่อน[-1][1][1] + 1)) or (บท == ท่อน[-1][1][0] + 1 and ข้อ == 1))
        if ต่อได้:
            ท่อน[-1][1] = (บท, ข้อ, j)
            ท่อน[-1][2] = k
        else:
            ท่อน.append([(บท, ข้อ, j), (บท, ข้อ, j), k])
    return [(ต้น, ท้าย) for ต้น, ท้าย, _ in ท่อน]


def จับทั้งหมด(เครื่องหมาย):
    """คืน (ของบท {เล่ม/บท: {รหัส: [เครื่องหมาย]}}, ไม่ลง [รายการ], นับ Counter)

    ⭐ รูปของเครื่องหมายหนึ่งอันในบทหนึ่ง ⇒ ลิสต์แบน ⇒ ท่อนละ 4 ตัว `ข้อต้น, คำต้น, ข้อท้าย, คำท้าย` (คำนับจาก 0)
       ⇒ คำเดียว ⇒ ย่อเหลือ `[ข้อ, คำ]` ⇒ ข้ามบท ⇒ ท้ายลิสต์มี `">"` (ไปต่อบทหน้า) หรือ `"<"` (มาจากบทก่อน)
       ⇒ หมายเหตุ ⇒ `[ข้อ, คำ, "ข้อความภาษาอังกฤษตรงตัว"]`
    """
    ของบท: dict = {}
    ไม่ลง = []
    นับ = Counter()
    for m in เครื่องหมาย:
        ท่า, ได้ทั้งหมด = จับเครื่องหมาย(m["เล่ม"], m["ข้อ"], m["คำแรก"], m["คำ"])
        ลำดับในช่วงที่ได้ = {i for (_, _, _, i, _) in ได้ทั้งหมด}
        ขาด = [i for i in range(len(m["คำ"])) if i not in ลำดับในช่วงที่ได้]
        นับ["เครื่องหมาย"] += 1
        นับ[f"ชนิด {m['รหัส']}"] += 1
        นับ["คำในเครื่องหมาย"] += len(m["คำ"])
        นับ["คำที่จับได้"] += len(ได้ทั้งหมด)
        นับ[f"ท่า {ท่า}"] += 1
        if not ได้ทั้งหมด:
            นับ["เครื่องหมายที่จับไม่ได้เลย"] += 1
        elif ขาด:
            นับ["เครื่องหมายที่จับได้บางคำ"] += 1
        else:
            นับ["เครื่องหมายที่จับได้ครบทุกคำ"] += 1
        if ขาด:
            คำของเรา = []
            for (บท, ข้อ) in m["ข้อ"][:3]:
                _, ตัวเดิม = ข้อของกอง(m["เล่ม"], บท)
                คำของเรา.append(f"{บท}:{ข้อ} " + (" ".join(ตัวเดิม[ข้อ]) if ข้อ in ตัวเดิม else "(ไม่มีข้อนี้ในกอง)"))
            ตัวคำ = m["ตัว"].split()
            ไม่ลง.append({
                "ref": m["ref"],
                "รหัส": m["รหัส"],
                "คำที่จับไม่ได้": [ตัวคำ[i] for i in ขาด],
                "จับได้": len(ได้ทั้งหมด),
                "ข้อของเรา": คำของเรา,
            })
        if not ได้ทั้งหมด:
            continue
        # ⭐ แบ่งตามบท ⇒ ท่อนที่ข้ามบทตัดที่ท้ายบท
        ตามบท: dict = {}
        for (ต้น, ท้าย) in ช่วงต่อกัน(ได้ทั้งหมด):
            if ต้น[0] == ท้าย[0]:
                ตามบท.setdefault(ต้น[0], []).append((ต้น, ท้าย))
            else:
                _, ตัวเดิมต้น = ข้อของกอง(m["เล่ม"], ต้น[0])
                ข้อท้ายบท = max(ตัวเดิมต้น)
                ตามบท.setdefault(ต้น[0], []).append((ต้น, (ต้น[0], ข้อท้ายบท, len(ตัวเดิมต้น[ข้อท้ายบท]) - 1)))
                ตามบท.setdefault(ท้าย[0], []).append(((ท้าย[0], 1, 0), ท้าย))
        บทเรียง = sorted(ตามบท)
        for บท in บทเรียง:
            แบน: list = []
            for (ต้น, ท้าย) in ตามบท[บท]:
                if ต้น == ท้าย and len(ตามบท[บท]) == 1:
                    แบน += [ต้น[1], ต้น[2]]
                else:
                    แบน += [ต้น[1], ต้น[2], ท้าย[1], ท้าย[2]]
            if m["โน้ต"] is not None:
                แบน = [แบน[0], แบน[1], m["โน้ต"]]
            if len(บทเรียง) > 1:
                แบน.append(">" if บท == บทเรียง[0] else "<")
            ของบท.setdefault(f"{m['เล่ม']}/{บท}", {}).setdefault(m["รหัส"], []).append(แบน)
    # ⭐ เรียงทุกรายการตามตำแหน่ง ⇒ พ่นซ้ำได้ไบต์เดิม
    for บ in ของบท.values():
        for r in บ:
            บ[r].sort(key=lambda x: (x[0], x[1]))
    return ของบท, ไม่ลง, นับ


