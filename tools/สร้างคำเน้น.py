_ตัดทิ้ง = re.compile(r"[’'ʼ᾽᾿`´·.,;:!?()\[\]⸀⸁⸂⸃—–\-·;]")


def ปรับ(คำ: str) -> str:
    """ตัดเครื่องหมายเสียง ตัวพิมพ์ใหญ่ ς และเครื่องหมายวรรคตอน ⇒ เหลือแต่ตัวอักษร"""
    s = unicodedata.normalize("NFD", คำ)
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = s.lower().replace("ς", "σ")
    return _ตัดทิ้ง.sub("", s)


_สระ = set("αεηιουω")
_ตัดสระแบบมีลม = {"θ": "τ", "φ": "π", "χ": "κ"}


def ตรงกัน(a: str, b: str) -> bool:
    """สองคำที่ปรับแล้ว เป็นคำเดียวกันไหม ⇒ ยอมแค่ 3 ความต่างของการสะกด (หัวไฟล์)"""
    if a == b:
        return True
    # ν ท้ายคำที่เติมได้
    if a + "ν" == b or b + "ν" == a:
        return True
    # οὐκ / οὐχ / οὐ · ἐκ / ἐξ
    คู่ = {a, b}
    if คู่ <= {"ου", "ουκ", "ουχ"} or คู่ == {"εκ", "εξ"}:
        return True
    # ตัดสระท้าย ⇒ ตัวสั้นต้องเป็นหัวของตัวยาว ขาดแค่สระตัวเดียว (ตัวท้ายที่มีลมกลับเป็นตัวไม่มีลมก่อน)
    สั้น, ยาว = (a, b) if len(a) < len(b) else (b, a)
    if len(ยาว) == len(สั้น) + 1 and ยาว[-1] in _สระ and len(สั้น) >= 2:
        หัว = สั้น[:-1] + _ตัดสระแบบมีลม.get(สั้น[-1], สั้น[-1])
        if ยาว[:-1] == หัว:
            return True
    return False


def ตรงทั้งช่วง(คำข้อ: list[str], เริ่ม: int, คำช่วง: list[str]) -> bool:
    if เริ่ม < 0 or เริ่ม + len(คำช่วง) > len(คำข้อ):
        return False
    return all(ตรงกัน(คำข้อ[เริ่ม + i], ค) for i, ค in enumerate(คำช่วง))


