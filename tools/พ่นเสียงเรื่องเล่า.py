def แบ่งสมดุล(ยาว: list[int], k: int) -> list[tuple[int, int]]:
    """แบ่งประโยคตามลำดับเป็น k ก้อนติดกัน ให้ก้อนที่ยาวที่สุดสั้นที่สุด ⇒ ยกมาจากสคริปต์ทดลอง 24 ต.ค. 2569"""
    n = len(ยาว)
    สะสม = [0]
    for x in ยาว:
        สะสม.append(สะสม[-1] + x)
    INF = float("inf")
    ดี = [[INF] * (n + 1) for _ in range(k + 1)]
    ตัด = [[0] * (n + 1) for _ in range(k + 1)]
    ดี[0][0] = 0
    for j in range(1, k + 1):
        for i in range(1, n + 1):
            for m in range(j - 1, i):
                v = max(ดี[j - 1][m], สะสม[i] - สะสม[m])
                if v < ดี[j][i]:
                    ดี[j][i], ตัด[j][i] = v, m
    ขอบ, i = [], n
    for j in range(k, 0, -1):
        m = ตัด[j][i]
        ขอบ.append((m, i))
        i = m
    return list(reversed(ขอบ))


