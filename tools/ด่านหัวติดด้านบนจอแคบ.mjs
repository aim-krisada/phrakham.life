    const { ctx, แท็บ } = await เปิด({ กว้าง: 375, fs, วาง: 'บนล่าง', ฉ: ['TCV'], มุม: { ภาษาเดิม: true, จัดวาง: 'แยกตามข้อ' }, พัง })
