def ถ่วงน้ำหนัก(ข้อสอบ, เฉลย, ตอบ):
    """คิดอัตราที่ตัวตรวจ **ไม่เห็นด้วยกับความหมายที่เราแปะ** สำหรับก้าวที่ 2

    ⚠️ **ต้องถ่วงน้ำหนัก ⛔ เฉลี่ยดิบไม่ได้** ⇒ เราสุ่มกฎเล็กมามากเกินสัดส่วนโดยตั้งใจ
    ⇒ เฉลี่ยดิบจะให้น้ำหนักกฎที่กินแค่ 0.025% ของกอง เท่ากับกฎที่กิน 60%

    สูตรของการสุ่มแบบแบ่งชั้น (stratified sampling)
      อัตราที่ไม่เห็นด้วย  p = Σ Wh · ph          ⇒ Wh คือส่วนแบ่งของชั้นนั้นในกองจริง
      ความแปรปรวน       var = Σ Wh² · ph(1-ph)/nh
      ช่วงความมั่นใจ 95%  p ± 1.96 · √var

    ⚠️ **ไม่เห็นด้วย ⛔ ไม่เท่ากับเราผิด** ⇒ ตัวตรวจเองก็ผิดได้
    ⇒ ตัวเลขนี้จึงเป็น **เพดานบนของความผิดของเรา** ⛔ ไม่ใช่ความผิดของเราตรง ๆ
    """
    ชั้นของข้อ = {}
    for x in ข้อสอบ['ข้อสอบ']:
        ชั้นของข้อ[x['เลขข้อสอบ']] = '%s · %s' % (x['ฝั่ง'], x['ชี้ถูกคำเพราะ'])
    รายชั้น = {}
    p, var = 0.0, 0.0
    for ชื่อชั้น, แผน in ข้อสอบ['แผนสุ่มแบ่งชั้น'].items():
        W = แผน['น้ำหนักของชั้น']
        เลข = [n for n in เฉลย if ชั้นของข้อ.get(n) == ชื่อชั้น and n in ตอบ]
        nh = len(เลข)
        if nh == 0:
            รายชั้น[ชื่อชั้น] = {'ตอบแล้ว': 0, 'ยังคิดไม่ได้': True}
            continue
        ไม่ตรง = sum(1 for n in เลข if ตอบ[n] != เฉลย[n]['คำตอบที่ควรได้'])
        ph = ไม่ตรง / nh
        p += W * ph
        var += W * W * ph * (1 - ph) / nh
        รายชั้น[ชื่อชั้น] = {'ทั้งกอง': แผน['ทั้งกอง'], 'ตอบแล้ว': nh, 'ไม่ตรง': ไม่ตรง,
                            'อัตราไม่ตรง': round(ph, 4), 'น้ำหนักของชั้น': round(W, 6)}
    ขอบ = 1.96 * math.sqrt(var)

    # ⛔ **ห้ามอ่านขอบความคลาดเคลื่อนนี้ ถ้าชั้นไหนยังบางอยู่**
    # **ทำไม** ⇒ ชั้นที่มีตัวอย่างเดียว ph จะเป็น 0 หรือ 1 พอดี ⇒ ph(1-ph) = 0
    #   ⇒ มันใส่ความแปรปรวนเข้าสูตร **ศูนย์** ทั้งที่ความจริงไม่แน่นอนที่สุด
    #   ⇒ ขอบที่ได้จะ **แคบกว่าความจริงมาก** ⇒ ดูน่าเชื่อทั้งที่เชื่อไม่ได้
    # ⇒ จึงติดธงบอกไว้ ⛔ ไม่ปล่อยให้คนอ่านรอบหน้าหยิบตัวเลขไปใช้โดยไม่รู้
    ชั้นบาง = sorted(k for k, v in รายชั้น.items() if v.get('ตอบแล้ว', 0) < 5)
    เชื่อได้ = not ชั้นบาง

    print('\nอัตราที่ตัวตรวจไม่เห็นด้วยกับความหมายที่เราแปะ (ถ่วงน้ำหนักแล้ว)')
    print('  = %.2f%%  ± %.2f%%  ที่ความมั่นใจ 95%%' % (100 * p, 100 * ขอบ))
    print('  ⇒ ช่วง %.2f%% ถึง %.2f%%' % (100 * max(0, p - ขอบ), 100 * min(1, p + ขอบ)))
    if ชั้นบาง:
        print('\n⛔ **ตัวเลขข้างบนยังใช้ไม่ได้** ⇒ มี %d ชั้นที่ตอบมาไม่ถึง 5 ตัว' % len(ชั้นบาง))
        print('   ⇒ ชั้นที่มีตัวอย่างเดียวใส่ความแปรปรวนเป็นศูนย์ ⇒ ขอบแคบกว่าความจริงมาก')
        for k in ชั้นบาง:
            print('   - %s ⇒ ตอบแล้ว %d' % (k, รายชั้น[k].get('ตอบแล้ว', 0)))
    return {'อัตราไม่ตรงถ่วงน้ำหนัก': round(p, 5),
            'ขอบความคลาดเคลื่อน 95%': round(ขอบ, 5),
            'ช่วงล่าง': round(max(0, p - ขอบ), 5), 'ช่วงบน': round(min(1, p + ขอบ), 5),
            'ตัวเลขนี้เชื่อได้แล้วหรือยัง': เชื่อได้,
            'ชั้นที่ยังบางเกินจะสรุป': ชั้นบาง,
            'หมายเหตุ': 'ไม่เห็นด้วย ⛔ ไม่เท่ากับเราผิด ⇒ เป็นเพดานบนของความผิดของเรา',
            'รายชั้น': รายชั้น}


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
