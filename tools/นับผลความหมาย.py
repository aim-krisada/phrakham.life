import json, sys, os, io, re, math, collections

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

ราก = 'docs/ข้อมูล/ผลตรวจความหมาย'


def อ่านคำตอบ(เนื้อ, เลขที่ขอ):
    """คืน {เลขข้อสอบ: ตัวอักษรที่ตอบ} ⇒ ข้อที่หาไม่เจอจะไม่มีในผลลัพธ์"""
    ได้ = {}
    for บรรทัด in เนื้อ.splitlines():
        # แถวตาราง markdown  | 12 | B | เหตุผล |   หรือเขียนไม่มีขีดหน้า  12 | B | เหตุผล
        ช่อง = [c.strip() for c in บรรทัด.strip().strip('|').split('|')]
        if len(ช่อง) < 2:
            continue
        # ⚠️ ต้องรับเลข 3 หลัก ⇒ ก้าวที่ 2 มีข้อสอบหลายร้อยข้อ
        m = re.fullmatch(r'\**\s*(?:ข้อ\s*)?(\d{1,3})\s*\**', ช่อง[0])
        if not m:
            continue
        เลข = int(m.group(1))
        if เลข not in เลขที่ขอ or เลข in ได้:
            continue
        a = re.search(r'\b([A-FX])\b', ช่อง[1].upper())
        if a:
            ได้[เลข] = a.group(1)
    return ได้


