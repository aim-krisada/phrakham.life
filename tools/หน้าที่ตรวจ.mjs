/**
 * ⭐⭐ **แถบหัวคอลัมน์ ⇒ วัดตัวแถบเอง ⛔ ไม่ใช่แค่ความกว้างของหน้า** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/150)
 *   ⇒ หน้าไม่เลื่อนข้างก็จริง แต่แถบหัวเลื่อนข้างในตัวเองได้ ⇒ หัวคำภาษาเดิมหลุดนอกจอเกือบทั้งหัว (จอ 320 ตัวอักษร 200% ⇒ 474 จุดในที่ 288)
 *   ⇒ คืนค่าทุกแถบหัวที่ตาเห็น (`.pk-หัวคอลัมน์ > .pk-ช่องทั้งหมด`)
 *     ⇒ `ล้นในแถบ` ⇒ scrollWidth − clientWidth ของแถบเอง
 *     ⇒ `แถว` ⇒ หัวอยู่กี่แถว (ขอบบนต่างกันเกิน 1.5 จุดนับเป็นคนละแถว)
 *     ⇒ `พอแถวเดียว` ⇒ ลองบังคับแถบเป็นแถวเดียว (`nowrap` · หัวกว้างเท่าของจริง · เพดานหัวแบบแถวเดียว แถบลบ 3.5em) แล้วดูว่าล้นไหม
 *       ⇒ ตั้งแบบ `!important` ในตัวของ ⇒ ชนะของพังที่ยัดมา ⇒ คืนค่าเดิมทันทีก่อนเบราว์เซอร์วาด ⇒ ⛔ มีอะไรเปลี่ยนบนจอ
 *       ⇒ เกณฑ์เดียวกับที่เบราว์เซอร์ใช้ตัดสินว่าจะห่อไหม ⇒ แถบแบบตาราง (ซ้ายขวา · จอกว้าง) ⇒ ⛔ ลอง ⇒ `null`
 *     ⇒ `ปุ่มนอกจอ` ⇒ ปุ่มกับช่องเลือกในหัวที่พ้นขอบจอ หรือพ้นกล่องแถบ
 *     ⇒ `ปุ่มถูกทับ` ⇒ จุดกลางของปุ่มเป็นของอื่น (แถบล่าง · ตัวบท ฯลฯ) ⇒ ตาเห็นแต่กดไม่ได้
 */
export const อ่านแถบหัว = (แท็บ) =>
  แท็บ.evaluate(() => {
    const r1 = (x) => Math.round(x * 10) / 10
    const เห็น = (e) => e.getClientRects().length > 0 && getComputedStyle(e).visibility !== 'hidden'
    return [...document.querySelectorAll('.pk-หัวคอลัมน์ > .pk-ช่องทั้งหมด')].filter(เห็น).map((แถบ) => {
      const หัว = [...แถบ.children].filter((h) => เห็น(h) && h.matches('.pk-หัวช่อง'))
      const บน = []
      for (const h of หัว) {
        const t = h.getBoundingClientRect().top
        if (!บน.some((x) => Math.abs(x - t) <= 1.5)) บน.push(t)
      }
      let พอแถวเดียว = null
      if (getComputedStyle(แถบ).display === 'flex') {
        const เดิมแถบ = แถบ.getAttribute('style')
        const เดิมหัว = หัว.map((h) => h.getAttribute('style'))
        แถบ.style.setProperty('flex-wrap', 'nowrap', 'important')
        แถบ.style.setProperty('overflow', 'visible', 'important')
        for (const h of หัว) {
          h.style.setProperty('flex', '0 0 auto', 'important')
          h.style.setProperty('max-width', 'calc(100% - 3.5em)', 'important')
        }
        พอแถวเดียว = แถบ.scrollWidth <= แถบ.clientWidth + 1
        if (เดิมแถบ === null) แถบ.removeAttribute('style')
        else แถบ.setAttribute('style', เดิมแถบ)
        หัว.forEach((h, i) => (เดิมหัว[i] === null ? h.removeAttribute('style') : h.setAttribute('style', เดิมหัว[i])))
      }
      const กล่อง = แถบ.getBoundingClientRect()
      const ปุ่มนอกจอ = []
      const ปุ่มถูกทับ = []
      for (const b of หัว.flatMap((h) => [...h.querySelectorAll('button, select')])) {
        if (!เห็น(b) || b.closest('.pk-เฉพาะเสียง')) continue
        const r = b.getBoundingClientRect()
        const ชนิด = b.tagName === 'SELECT' ? 'ช่องฉบับ' : b.getAttribute('data-ปุ่ม') || (b.textContent || '').trim().slice(0, 12)
        const ชื่อ = `${b.closest('.pk-หัวช่อง')?.querySelector('select')?.value || '?'} ${ชนิด}`
        const นอก =
          r.left < -0.5 || r.right > innerWidth + 0.5 || r.left < กล่อง.left - 0.5 || r.right > กล่อง.right + 0.5 || r.top < 0 || r.bottom > innerHeight
        if (นอก) ปุ่มนอกจอ.push(`${ชื่อ} (${r1(r.left)} ถึง ${r1(r.right)})`)
        else {
          const ที่ = document.elementFromPoint(r.left + r.width / 2, r.top + r.height / 2)
          if (!ที่ || !(ที่ === b || b.contains(ที่) || ที่ === b.closest('label'))) ปุ่มถูกทับ.push(ชื่อ)
        }
      }
      return {
        กว้างแถบ: r1(แถบ.clientWidth),
        กว้างของในแถบ: r1(แถบ.scrollWidth),
        ล้นในแถบ: r1(แถบ.scrollWidth - แถบ.clientWidth),
        หัว: หัว.length,
        แถว: บน.length,
        พอแถวเดียว,
        ปุ่มนอกจอ,
        ปุ่มถูกทับ,
      }
    })
  })

/**
 * ⭐ ใบ #150 ⇒ **เกณฑ์แถวของหัวบนจอแคบ** ⇒ ตัวเดียวที่ด่านหัวติดด้านบนจอแคบ ② กับด่านวางคอลัมน์จอแคบ ⑧ ใช้
 *   ⇒ พอแถวเดียว ⇒ หัวทุกหัวต้องอยู่แถวเดียวกันเหมือนเดิม (ห่อทั้งที่พอ = ของพัง)
 *   ⇒ ไม่พอ ⇒ ขึ้นแถวใหม่ได้ (พี่เอมอนุมัติ 7 พ.ย. 2569 ทางแชตกับ AI) ⇒ แต่ทุกปุ่มต้องอยู่ในจอ กดได้ และแถบ ⛔ เลื่อนข้าง
 *   ⇒ คืนรายการข้อที่ผิด ⇒ ว่าง = ผ่าน
 */
export function ผิดเกณฑ์แถวหัว(แถบ) {
  const ผิด = []
  for (const ก of แถบ) {
    if (ก.หัว > 1 && ก.พอแถวเดียว !== false && ก.แถว > 1) ผิด.push(`หัว ${ก.หัว} หัวพอวางแถวเดียว แต่อยู่ ${ก.แถว} แถว ⇒ ต้องอยู่แถวเดียวกัน`)
    if (ก.ล้นในแถบ > 1) ผิด.push(`แถบหัวกว้าง ${ก.กว้างแถบ} จุด แต่ของในแถบกว้าง ${ก.กว้างของในแถบ} ⇒ ต้องปัดข้างในแถบ`)
    if (ก.ปุ่มนอกจอ.length) ผิด.push(`ปุ่มบนหัวพ้นจอหรือพ้นแถบ ⇒ ${ก.ปุ่มนอกจอ.join(' · ')}`)
    if (ก.ปุ่มถูกทับ.length) ผิด.push(`ปุ่มบนหัวถูกของอื่นทับ ⇒ ${ก.ปุ่มถูกทับ.join(' · ')}`)
  }
  return ผิด
}