/**
 * ⭐⭐ **ปุ่ม *เพิ่มคอลัมน์* ในเมนู *เทียบ* ⇒ ทางเดียวที่เปิดคอลัมน์ใหม่** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/161)
 *   ⇒ กดแล้วได้คอลัมน์ใหม่ ฉบับและตอนเดียวกับคอลัมน์แรก ⇒ เมนูปิด ⇒ โฟกัสไปช่องเลือกฉบับของคอลัมน์ใหม่ ⇒ เลือกฉบับที่นั่น
 *   ⇒ ⚠️ ของเดิม (ใบ #131 ข้อ 9) ⇒ ช่องติ๊กของทุกฉบับกับช่องติ๊กคำภาษาเดิม (`ช่องฉบับในเมนู` · `ช่องคำเดิมในเมนู` · `ปุ่มเปิดคำเดิมในเมนู`) ⇒ ถอดพร้อมหน้าตา
 *     ⇒ ด่านที่เคยติ๊กเพื่อ *เปิด* ฉบับหรือคำเดิม ⇒ เรียก `เพิ่มคอลัมน์` หรือ `เปิดคำเดิม` แทน ⇒ ได้หน้าเดียวกับติ๊กทุกอย่าง (ฉบับใหม่ต่อท้ายตาราง)
 *     ⇒ ด่านที่เคยเอาติ๊กออกเพื่อ *ปิด* ⇒ ใช้ × บนหัวคอลัมน์ ⇒ ทางเดียวที่เหลือ
 *   ⇒ ⭐ ด่านทุกตัวหาปุ่มด้วยชื่อที่ได้ยินผ่านตัวนี้ ⇒ `exact` ขาดไม่ได้ ⇒ ชื่อต้องเป็นคำที่ตาเห็นตรงตัว (SC 2.5.3)
 *   ⇒ ชื่อจดซ้ำจาก `app/utils/ถ้อยคำเมนูเทียบ.ts` โดยเจตนา ⇒ เปลี่ยนที่นั่นแล้วด่านแดงเอง
 *   ⇒ ⚠️ ปุ่มที่เต็มแล้วเป็น `aria-disabled` ⇒ Playwright ถือว่ากดไม่ได้ ⇒ ด่านที่ต้องกดตอนเต็มใส่ `force: true` เอง
 */
export const ชื่อปุ่มเพิ่มคอลัมน์ = 'เพิ่มคอลัมน์'
export const ข้อความเต็มของ = (จำนวน) => `จอนี้เปิดได้มากสุด ${จำนวน} คอลัมน์ ปิดออก 1 คอลัมน์ก่อนเปิดเพิ่ม`
export function ปุ่มเพิ่มคอลัมน์(แท็บ) {
  return แท็บ.locator('#pk-แผงเทียบ').getByRole('button', { name: ชื่อปุ่มเพิ่มคอลัมน์, exact: true })
}
/** กางเมนู *เทียบ* ⇒ **พับอยู่เท่านั้นถึงกด** ⇒ แล้วรอจนปุ่ม *เพิ่มคอลัมน์* โผล่จริง */
export async function กางเมนูเทียบ(แท็บ) {
  const ปุ่ม = ปุ่มเทียบของหน้า(แท็บ)
  if ((await ปุ่ม.getAttribute('aria-expanded')) !== 'true') await ปุ่ม.click()
  await ปุ่มเพิ่มคอลัมน์(แท็บ).waitFor()
}
/** พับเมนู *เทียบ* ⇒ **กางอยู่เท่านั้นถึงกด** ⇒ แล้วรอจนเมนูหายจริง */
export async function พับเมนูเทียบ(แท็บ) {
  const ปุ่ม = ปุ่มเทียบของหน้า(แท็บ)
  if ((await ปุ่ม.getAttribute('aria-expanded')) === 'true') await ปุ่ม.click()
  await แท็บ.waitForSelector('#pk-แผงเทียบ', { state: 'detached' })
}
/** ⭐ ค่าพิเศษของ `เพิ่มคอลัมน์` ⇒ เลือกตัวบทภาษาเดิมของเล่ม (SBLGNT หรือ WLC) ⇒ ตัวเลือกท้ายสุดของช่องเลือกฉบับ */
export const ตัวบทเดิม = 'คำเดิม'
/**
 * กด *เพิ่มคอลัมน์* 1 ครั้ง ⇒ แล้วเลือก `ฉบับ` ที่ช่องเลือกฉบับของคอลัมน์ใหม่ (ว่าง = ฉบับเดียวกับคอลัมน์แรก ⛔ เลือก)
 *   ⇒ คืน `true` เมื่อได้คอลัมน์ใหม่ ⇒ `false` เมื่อปุ่มบอกว่าเต็ม (`aria-disabled`) ⇒ ⛔ กด ⇒ เมนูยังกางอยู่ ⇒ ผู้เรียกพับเอง
 *   ⇒ ⭐ ฉบับที่ตารางยังไม่มี ⇒ คอลัมน์ใหม่เข้าตารางต่อท้าย ⇒ หน้าเดียวกับติ๊กฉบับแบบเดิม
 */
export async function เพิ่มคอลัมน์(แท็บ, ฉบับ = '') {
  await กางเมนูเทียบ(แท็บ)
  const ปุ่ม = ปุ่มเพิ่มคอลัมน์(แท็บ)
  if ((await ปุ่ม.getAttribute('aria-disabled')) === 'true') return false
  await ปุ่ม.click()
  await แท็บ.waitForSelector('#pk-แผงเทียบ', { state: 'detached' })
  const ช่อง = แท็บ.locator('select.pk-ช่องเลือกฉบับ:focus')
  await ช่อง.waitFor({ timeout: 15000 })
  if (!ฉบับ) return true
  const ค่า =
    ฉบับ === ตัวบทเดิม
      ? await ช่อง.evaluate((x) => [...x.options].map((o) => o.value).find((v) => v === 'SBLGNT' || v === 'WLC') || '')
      : ฉบับ
  if ((await ช่อง.inputValue()) !== ค่า) await ช่อง.selectOption(ค่า)
  return true
}
/** ⭐ เปิดคอลัมน์คำภาษาเดิม ⇒ เพิ่มคอลัมน์แล้วเลือกตัวบท ⇒ เปิดอยู่แล้ว ⛔ เปิดซ้ำ ⇒ ท่าเดียวกับช่องติ๊กเดิมที่ติ๊กอยู่แล้ว */
export async function เปิดคำเดิม(แท็บ) {
  const เปิดอยู่ = await แท็บ.evaluate(
    () => !!document.querySelector('[data-ชื่อคำเดิม]') || /(^|,)(SBLGNT|WLC)(,|$)/.test(new URL(location.href).searchParams.get('t') || ''),
  )
  if (เปิดอยู่) return true
  return เพิ่มคอลัมน์(แท็บ, ตัวบทเดิม)
}
export function ปุ่มปิดคำเดิม(แท็บ) {
  return แท็บ.locator('[data-ปุ่ม="ปิดคำเดิม"]:visible').first()
}

/** เพิ่มคอลัมน์ฉบับจนตารางมี `กี่ฉบับ` คอลัมน์ ⇒ คืนจำนวนที่เปิดได้จริง
 *  ⇒ ขอเกินจำนวนฉบับที่มี (เช่น 99) = เปิดครบทุกฉบับ
 *  ⇒ ⭐ ใบ #161 ⇒ กด *เพิ่มคอลัมน์* แล้วเลือกฉบับที่ตารางยังไม่มีตัวแรกตามรายชื่อฉบับของเว็บ ⇒ ลำดับที่เปิดเหมือนติ๊กแบบเดิม
 *  ⇒ ปุ่มบอกว่าเต็ม (จอแคบกว่า 768 ⇒ เพดานคอลัมน์) ⇒ **หยุด** ⇒ คืนจำนวนที่เปิดได้จริง ⇒ ⛔ แตะเกณฑ์ของด่านที่เรียก */
export async function เพิ่มฉบับจนครบ(แท็บ, กี่ฉบับ) {
  const นับ = () => แท็บ.locator('.pk-หัวคอลัมน์ .pk-ช่องหัว').count()
  for (let i = 0; i < 12 && (await นับ()) < กี่ฉบับ; i++) {
    const ถัดไป = await แท็บ.evaluate(() => {
      const เปิด = new Set([...document.querySelectorAll('.pk-หัวคอลัมน์ .pk-ช่องหัว[data-ฉบับ]')].map((x) => x.dataset.ฉบับ))
      const ช่อง = document.querySelector('.pk-หัวคอลัมน์ .pk-ช่องเลือกฉบับ')
      return [...(ช่อง?.options || [])].map((o) => o.value).find((v) => !เปิด.has(v) && v !== 'SBLGNT' && v !== 'WLC') || ''
    })
    if (!ถัดไป || !(await เพิ่มคอลัมน์(แท็บ, ถัดไป))) break
    await แท็บ.waitForTimeout(150)
  }
  await พับเมนูเทียบ(แท็บ)
  await แท็บ.waitForTimeout(250)
  return นับ()
}

