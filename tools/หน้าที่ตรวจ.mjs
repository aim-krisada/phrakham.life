  //   ⇒ ⛔ ไม่มีรายการที่พับแล้ว ⇒ ของเดิม (note_30302 ข้อ 4) กดปุ่มชื่อฉบับให้กางก่อน ⇒ ถอดท่อนนั้น ⇒ ด่านที่เรียกได้ปุ่มเดิมเหมือนก่อน
