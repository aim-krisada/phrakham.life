เติมหน้าได้ = ("การ", "ความ", "ผู้")     # กฎข้อ ④ ⇒ เหตุผลอยู่ใน docs/ทดลองเขียนด้วยคลังคำ.md
เลี่ยงไม่ได้ = re.compile(r"^«(.+)»$")   # กฎข้อ ⑥ ⇒ ชื่อคน ชื่อของที่ไทยไม่มี
เพดานคำ = 25                             # ใบงานกำหนด ⇒ ยาวไม่เกิน 25 คำต่อคำอธิบาย


def จัดรูป(คำ):
    """กฎข้อ ② ⇒ ทำให้เทียบได้จริงก่อนเทียบ · ทำแบบเดียวกับใบ #44"""
    return re.sub(r"\s+", "", unicodedata.normalize("NFC", คำ).replace("ํา", "ำ").strip())


def ดึงจากกิต(ref, ปลายทาง):
    """คัดไฟล์ที่ต้องใช้ออกจากสาขาของใบ #44 มาไว้ที่พักชั่วคราว ⛔ ไม่แตะโฟลเดอร์ของเขา"""
    sha = subprocess.run(["git", "rev-parse", ref], capture_output=True, text=True).stdout.strip()
    if not sha:
        sys.exit(f"⛔ หารุ่นคลัง {ref} ไม่เจอ ⇒ ลอง git fetch origin <ชื่อสาขา> ก่อน")
    (ปลายทาง / "ข้อมูล").mkdir(parents=True, exist_ok=True)
    for ชื่อ in ไฟล์คลัง:
        ที่อยู่ = f"docs/ข้อมูล/{ชื่อ}.tsv"
        ผล = subprocess.run(["git", "show", f"{sha}:{ที่อยู่}"], capture_output=True)
        if ผล.returncode:
            sys.exit(f"⛔ รุ่น {ref} ไม่มีไฟล์ {ที่อยู่}")
        (ปลายทาง / "ข้อมูล" / f"{ชื่อ}.tsv").write_bytes(ผล.stdout)
    ผล = subprocess.run(["git", "show", f"{sha}:tools/เทียบคำ3ชุด.py"], capture_output=True)
    if ผล.returncode:
        sys.exit(f"⛔ รุ่น {ref} ไม่มี tools/เทียบคำ3ชุด.py")
    (ปลายทาง / "เทียบคำ3ชุด.py").write_bytes(ผล.stdout)
    return sha


def คลังคำ(ref):
    """คืน (เซ็ตคำในคลัง, เลขคอมมิตที่ดึงมา) ⇒ คลัง = ชุด ก ∪ ชุด ค ตามที่ใบ #44 สรุปไว้"""
    with tempfile.TemporaryDirectory() as พัก:
        พัก = Path(พัก)
        sha = ดึงจากกิต(ref, พัก)
        spec = importlib.util.spec_from_file_location("เทียบคำ3ชุด", พัก / "เทียบคำ3ชุด.py")
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        ชุด = m.สามชุด(พัก / "ข้อมูล", เก็บวงเล็บ=False)
    return {จัดรูป(w) for w in (ชุด["ก"] | ชุด["ค"])}, sha


def ตัดสินคำ(คำ, คลัง):
    """คืน ('ในคลัง'|'เลี่ยงไม่ได้'|'คลังขาด', คำที่จัดรูปแล้ว)"""
    if m := เลี่ยงไม่ได้.match(คำ):
        return "เลี่ยงไม่ได้", จัดรูป(m.group(1))
    รูป = จัดรูป(คำ)
    if รูป in คลัง:
        return "ในคลัง", รูป
    for หน้า in เติมหน้าได้:
        if รูป.startswith(หน้า) and หน้า in คลัง and รูป[len(หน้า):] in คลัง:
            return "ในคลัง", รูป
    return "คลังขาด", รูป


def อ่านtsv(ที่อยู่):
    with open(ที่อยู่, encoding="utf-8") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def เขียนหลักฐาน(ที่อยู่, ต้นเรื่อง, คำอธิบาย, คลัง):
    """ไฟล์เดียวที่คนตรวจเปิดแล้วเห็นครบ ⇒ คำต้นทาง · ข้อความ UBS · คำอธิบายไทย · คำที่หลุด"""
    ดัชนี = {(r["บท"], r["คำต้นทาง"], r["รหัสความหมาย"]): r for r in ต้นเรื่อง}
    ช่อง = ["บท", "ข้อที่พบ", "คำต้นทาง", "รูปในข้อ", "ยูบีเอสล็อก", "คำอังกฤษ", "นิยามubs",
            "คำอธิบายไทย", "จำนวนคำ", "คำที่หลุดคลัง", "คำที่เลี่ยงไม่ได้"]
    with open(ที่อยู่, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, ช่อง, delimiter="\t")
        w.writeheader()
        for r in คำอธิบาย:
            ต้น = ดัชนี.get((r["บท"], r["คำต้นทาง"], r["รหัสความหมาย"]), {})
            คำ = (r["คำอธิบายไทย"] or "").split()
            หลุด, เลี่ยง = [], []
            for x in คำ:
                ชนิด, รูป = ตัดสินคำ(x, คลัง)
                (หลุด if ชนิด == "คลังขาด" else เลี่ยง if ชนิด == "เลี่ยงไม่ได้" else []).append(รูป)
            w.writerow({"บท": r["บท"], "ข้อที่พบ": ต้น.get("ข้อที่พบ", ""),
                        "คำต้นทาง": r["คำต้นทาง"], "รูปในข้อ": ต้น.get("รูปในข้อ", ""),
                        "ยูบีเอสล็อก": ต้น.get("ยูบีเอสล็อก", ""), "คำอังกฤษ": r["คำอังกฤษ"],
                        "นิยามubs": ต้น.get("นิยามubs", ""), "คำอธิบายไทย": r["คำอธิบายไทย"],
                        "จำนวนคำ": len(คำ), "คำที่หลุดคลัง": " ".join(หลุด),
                        "คำที่เลี่ยงไม่ได้": " ".join(เลี่ยง)})
    print("เขียนหลักฐานรายคำแล้ว", ที่อยู่)


def หลัก(ไฟล์คำอธิบาย, ไฟล์ต้นเรื่อง, ref):
    คลัง, sha = คลังคำ(ref)
    ต้นเรื่อง = อ่านtsv(ไฟล์ต้นเรื่อง)
    คำอธิบาย = อ่านtsv(ไฟล์คำอธิบาย)
    print(f"คลังคำ {len(คลัง)} คำ ⇒ ดึงจาก {ref} คอมมิต {sha[:8]}")
    เขียนหลักฐาน(Path(ไฟล์คำอธิบาย).with_name("ทดลอง-ผลตรวจรายคำ.tsv"), ต้นเรื่อง, คำอธิบาย, คลัง)

    มี = {(r["บท"], r["คำต้นทาง"], r["รหัสความหมาย"]) for r in คำอธิบาย}
    ขาดแถว = [r for r in ต้นเรื่อง if (r["บท"], r["คำต้นทาง"], r["รหัสความหมาย"]) not in มี]
    print(f"ความหมายที่ UBS ล็อกไว้ {len(ต้นเรื่อง)} รายการ ⇒ เขียนถึงแล้ว {len(ต้นเรื่อง) - len(ขาดแถว)}"
          f" · ยังไม่ได้แตะ {len(ขาดแถว)}")
    for r in ขาดแถว[:10]:
        print("   ยังไม่ได้แตะ", r["บท"], r["คำต้นทาง"], r["คำอังกฤษ"])

    ไม่หลุดเลย = หลุดบ้าง = เขียนไม่ได้ = 0
    หลุดรวม = 0
    ยาวเกิน = []
    นับคลังขาด = collections.Counter()
    นับเลี่ยงไม่ได้ = collections.Counter()
    ตัวอย่างหลุด = collections.defaultdict(list)
    for r in คำอธิบาย:
        ข้อความ = (r["คำอธิบายไทย"] or "").strip()
        if not ข้อความ:
            เขียนไม่ได้ += 1
            continue
        คำ = ข้อความ.split()
        if len(คำ) > เพดานคำ:
            ยาวเกิน.append((r["คำต้นทาง"], len(คำ)))
        หลุดของแถว = []
        for w in คำ:
            ชนิด, รูป = ตัดสินคำ(w, คลัง)
            if ชนิด == "คลังขาด":
                หลุดของแถว.append(รูป)
            elif ชนิด == "เลี่ยงไม่ได้":
                นับเลี่ยงไม่ได้[รูป] += 1
        if หลุดของแถว:
            หลุดบ้าง += 1
            หลุดรวม += len(หลุดของแถว)
            for รูป in set(หลุดของแถว):
                นับคลังขาด[รูป] += 1
                if len(ตัวอย่างหลุด[รูป]) < 3:
                    ตัวอย่างหลุด[รูป].append(r["คำต้นทาง"])
        else:
            ไม่หลุดเลย += 1

    เขียนแล้ว = ไม่หลุดเลย + หลุดบ้าง
    print()
    print("── ③ นับว่าหลุดคลังกี่ครั้ง ──")
    print(f"เขียนได้โดยไม่หลุดคลังเลย   {ไม่หลุดเลย} รายการ"
          f" = {ไม่หลุดเลย * 100 / len(คำอธิบาย):.1f}% ของทั้งหมด")
    print(f"เขียนได้แต่ต้องหลุดคลัง     {หลุดบ้าง} รายการ"
          f" = {หลุดบ้าง * 100 / len(คำอธิบาย):.1f}% ของทั้งหมด")
    print(f"เขียนไม่ได้เลย              {เขียนไม่ได้} รายการ")
    if เขียนแล้ว:
        print(f"หลุดคลังรวม {หลุดรวม} ครั้ง ⇒ เฉลี่ย {หลุดรวม / เขียนแล้ว:.2f} คำต่อคำอธิบายที่เขียนได้")
    print(f"⭐ คลังขาด {len(นับคลังขาด)} คำ ⇒ เติมคลังอีก N = {len(นับคลังขาด)} คำ"
          f" จะเขียนครบโดยไม่หลุดคลัง")
    print(f"เลี่ยงไม่ได้ {len(นับเลี่ยงไม่ได้)} คำ ⛔ ไม่นับเป็นคลังขาด ⇒ "
          + " ".join(f"{w}({n})" for w, n in นับเลี่ยงไม่ได้.most_common()))
    if ยาวเกิน:
        print(f"⛔ ยาวเกิน {เพดานคำ} คำ {len(ยาวเกิน)} รายการ ⇒ {ยาวเกิน}")

    print()
    print("── แยกรายบท ──")
    for ชื่อบท in sorted({r["บท"] for r in คำอธิบาย}):
        ของบท = [r for r in คำอธิบาย if r["บท"] == ชื่อบท]
        สะอาด = ขาดของบท = 0
        คำขาดบท = set()
        for r in ของบท:
            หลุด = [รูป for x in (r["คำอธิบายไทย"] or "").split()
                    for ชนิด, รูป in [ตัดสินคำ(x, คลัง)] if ชนิด == "คลังขาด"]
            if หลุด:
                ขาดของบท += 1
                คำขาดบท |= set(หลุด)
            else:
                สะอาด += 1
        print(f"{ชื่อบท}: {len(ของบท)} รายการ ⇒ ไม่หลุดเลย {สะอาด}"
              f" ({สะอาด * 100 / len(ของบท):.1f}%) · หลุด {ขาดของบท} · คลังขาด {len(คำขาดบท)} คำ")

    print()
    print("── ⭐ รายการคลังขาด เรียงจากที่ต้องใช้บ่อยที่สุด ──")
    print("คำ\tใช้ในคำอธิบายกี่รายการ\tตัวอย่างคำต้นทางที่ต้องใช้")
    for w, n in นับคลังขาด.most_common():
        print(f"{w}\t{n}\t{' '.join(ตัวอย่างหลุด[w])}")


