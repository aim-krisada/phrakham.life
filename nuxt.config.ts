//   ⇒ `CI_COMMIT_TIMESTAMP` คือเวลาของคอมมิตตามที่กิตแล็บบอก ⇒ ⛔ ห้ามเปลี่ยนไปใช้ `Date.now()`
//   ⇒ ⭐ และมันยังเป็นของที่ **พิสูจน์ได้** ⇒ เทียบกับ `git log -1 --format=%cI <sha>` ได้ตรง ๆ
//     ⇒ เวลาสร้างเปลี่ยนทุกครั้งจึงพิสูจน์อะไรไม่ได้ ⇒ เหตุผลเดียวกับที่ job `pages` เขียนไว้เรื่อง sha
// ⭐ **แปลงเป็นเวลาไทยตอนสร้าง** ⇒ บวก 7 ชั่วโมงจากเวลากลาง ⛔ ไม่พึ่งเขตเวลาของเครื่องที่สร้าง
//   ⇒ ตัวรันของอัมกิตตั้งเขตเวลาเป็น UTC ⇒ พึ่งเขตเวลาของเครื่องเมื่อไรได้เวลาช้าไป 7 ชั่วโมง
// ⛔ **ไม่มีค่า (สร้างในเครื่อง) ⇒ ได้ข้อความว่าง** ⇒ ท้ายหน้าเขียนว่า *ในเครื่อง* แทน ⇒ ท่าเดียวกับ sha
