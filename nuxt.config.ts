const เดือนไทย = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.']
function เวลาไทยของคอมมิต(ค่า: string | undefined): string {
  if (!ค่า) return ''
  const t = Date.parse(ค่า)
  if (Number.isNaN(t)) return ''
  const ไทย = new Date(t + 7 * 3600 * 1000)
  const สอง = (n: number) => String(n).padStart(2, '0')
  return (
    `${ไทย.getUTCDate()} ${เดือนไทย[ไทย.getUTCMonth()]} ${ไทย.getUTCFullYear() + 543}` +
    ` ${สอง(ไทย.getUTCHours())}:${สอง(ไทย.getUTCMinutes())} น.`
  )
}

