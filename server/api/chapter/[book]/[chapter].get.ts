// เนื้อของบทเดียว — หน้าอ่านเรียกใช้ตอนตัวสร้างเว็บกำลังสร้างหน้านั้น
//
// ⛔ **ต้องสั่ง import เอง** — เหตุผลอยู่ที่ `server/api/books.get.ts` ⛔ ไม่จดซ้ำที่นี่
import { อ่านบท } from '../../../utils/เนื้อบท'

// ⛔ **ไม่มีบทนั้น = 404 จริง** ⛔ ไม่ใช่คืนของว่างที่ดูเหมือนใช้ได้
//   ⇒ ของว่างจะกลายเป็นหน้าที่มีหัวเรื่องแต่ไม่มีข้อ แล้ว ⛔ ไม่มีใครรู้ว่าพัง
export default defineEventHandler((event) => {
  const เล่ม = getRouterParam(event, 'book') || ''
  // ⭐ ที่อยู่ลงท้ายด้วย `.json` ⇒ เพราะของที่สร้างออกมาต้องเป็น **ไฟล์ที่มีนามสกุล**
  //   ⛔ ไฟล์ไม่มีนามสกุล ⇒ ตัวเสิร์ฟไฟล์นิ่งหลายตัวหาไม่เจอ แล้วตอบ 404 (เจอเอง 30 ส.ค. 2569)
  const บท = (getRouterParam(event, 'chapter') || '').replace(/\.json$/, '')
  const ผล = อ่านบท(เล่ม, บท)
  if (!ผล) throw createError({ statusCode: 404, statusMessage: `ไม่มีบท ${เล่ม} ${บท}` })
  return ผล
})
