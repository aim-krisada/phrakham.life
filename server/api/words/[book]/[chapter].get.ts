// ชั้นคำภาษาเดิมของบทเดียว — **หน้าอ่านขอตอนผู้อ่านกดเปิดเท่านั้น** (ใบงาน v3/phrakham#95)
//
// ⭐⭐ **ที่อยู่เป็นภาษาอังกฤษ** ⇒ `/api/words/<เล่ม>/<บท>.json` ⇒ การเคาะสั่งว่า
//   *ที่อยู่หน้าเว็บภาษาอังกฤษเท่านั้น* ⇒ `docs/เคาะ/หน้าจอกับการอ่าน.md` หัวข้อ *หน้าอ่าน*
//
// ⛔ **ต้องสั่ง import เอง** — เหตุผลอยู่ที่ `server/api/books.get.ts` ⛔ ไม่จดซ้ำที่นี่
import { ชั้นคำของบท } from '../../../utils/ชั้นคำ'

export default defineEventHandler((event) => {
  const เล่ม = getRouterParam(event, 'book') || ''
  // ⭐ ที่อยู่ลงท้ายด้วย `.json` ⇒ ของที่สร้างออกมาต้องเป็น **ไฟล์ที่มีนามสกุล**
  //   ⛔ ไฟล์ไม่มีนามสกุล ⇒ ตัวเสิร์ฟไฟล์นิ่งหลายตัวหาไม่เจอ แล้วตอบ 404 ⇒ เหตุผลเดียวกับ `/api/chapter`
  const บท = (getRouterParam(event, 'chapter') || '').replace(/\.json$/, '')
  const ผล = ชั้นคำของบท(เล่ม, บท)
  // ⛔ **ไม่มีชั้นคำของบทนี้ = 404 จริง** ⇒ ⭐ **แต่ ⛔ ไม่ใช่ความพัง**
  //   ⇒ ฝั่งภาษาเดิมกับฝั่งคำแปลแบ่งบทไม่เท่ากัน ⇒ มีบทที่มีคำแปลแต่ ⛔ ไม่มีคำเดิมจริง ๆ
  //   ⇒ **หน้าอ่านต้องบอกผู้อ่านตรง ๆ ว่าบทนี้ยังไม่มี** ⛔ ไม่ใช่ปล่อยช่องว่างเงียบ ๆ
  if (!ผล) throw createError({ statusCode: 404, statusMessage: `ไม่มีชั้นคำของ ${เล่ม} ${บท}` })
  return ผล
})
