// ของประจำเล่ม — หน้าของเล่มเรียกใช้ตอนตัวสร้างเว็บกำลังสร้างหน้านั้น (ใบงาน v3/phrakham#73)
//
// ⭐ **1 เล่ม = 1 หน้า** ⇒ ชื่อเล่ม · รายชื่อบทที่มี · ข้อสุดท้ายของแต่ละบท · รายชื่อฉบับ
//   ⇒ ของพวกนี้ **โหลดครั้งเดียวต่อเล่ม** ⛔ ไม่ใช่ติดไปกับเนื้อบททุกบท
//   ⇒ เหตุผลเต็มอยู่ที่ `server/utils/เนื้อบท.ts` ฟังก์ชัน `ข้อมูลเล่ม` ⛔ ไม่จดซ้ำที่นี่
//
// ⛔ **ต้องสั่ง import เอง** — เหตุผลอยู่ที่ `server/api/books.json.get.ts` ⛔ ไม่จดซ้ำที่นี่
import { ข้อมูลเล่ม } from '../../utils/เนื้อบท'

export default defineEventHandler((event) => {
  // ⭐ ที่อยู่ลงท้ายด้วย `.json` ⇒ เพราะของที่สร้างออกมาต้องเป็น **ไฟล์ที่มีนามสกุล**
  //   ⛔ ไฟล์ไม่มีนามสกุล ⇒ ตัวเสิร์ฟไฟล์นิ่งหลายตัวหาไม่เจอ แล้วตอบ 404 (เจอเอง 30 ส.ค. 2569)
  const รหัส = (getRouterParam(event, 'book') || '').replace(/\.json$/, '')
  const ผล = ข้อมูลเล่ม(รหัส)
  // ⛔ **ไม่มีเล่มนั้น = 404 จริง** ⛔ ไม่ใช่คืนของว่างที่ดูเหมือนใช้ได้
  if (!ผล) throw createError({ statusCode: 404, statusMessage: `ไม่มีเล่ม ${รหัส}` })
  return ผล
})
