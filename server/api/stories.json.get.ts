// ⭐⭐ **อ่านจาก `เรื่องเล่า/ทะเบียน.tsv` อย่างเดียว** (เกณฑ์ข้อ 2) ⇒ ผ่านตัวอ่านเดิม `server/utils/เรื่องเล่า.ts`
//   ⇒ เรื่องที่ไม่อยู่ในทะเบียน ⛔ ไม่มีทางโผล่ ⇒ เพิ่มแถวในทะเบียน ⇒ สร้างเว็บใหม่ ⇒ ขึ้นเอง ⛔ ไม่ต้องแก้หน้า
// ⭐ จัดกลุ่มตามเล่ม ⇒ **เรียงเล่มตามบัญชี 66 เล่มของซองตัวบท** ⇒ จำนวนบทของเล่มก็มาจากบัญชีนั้น
//   ⇒ ⛔ ไม่พิมพ์ตารางเล่มกับจำนวนบทไว้เองแบบ `BOOKMAP` ของรุ่น 2 ⇒ แผนที่จึงได้ช่องครบทุกบทของทุกเล่ม
// ⛔ ไม่มีตัวหนังสือของเรื่อง ⛔ ไม่มีเสียง ⇒ หน้าบทความขอตัวเรื่องผ่าน `/api/story/<รหัส>.json` ทางเดิม
// ⭐ ที่อยู่ลงท้ายด้วย `.json` ⇒ เหตุผลอยู่ที่ `server/api/books.json.get.ts` ⛔ ไม่จดซ้ำที่นี่
//
// ⛔ **ต้องสั่ง import เอง** — ตัวเติม import อัตโนมัติ ⛔ ไม่รู้จักชื่อภาษาไทย
import { บัญชีเล่ม } from '../utils/เนื้อบท'
import { รายการเรื่องเล่า } from '../utils/เรื่องเล่า'

export default defineEventHandler(() => {
  const เรื่องทั้งหมด = รายการเรื่องเล่า()
  const เล่มทั้งหมด = บัญชีเล่ม().เล่ม
  // ⛔ เรื่องของเล่มที่ไม่อยู่ในบัญชี ⇒ ตายตอนสร้างพร้อมบอกรหัส ⇒ ⛔ ไม่ทิ้งเงียบ ๆ ให้บทความหายจากหน้า
  for (const ร of เรื่องทั้งหมด) {
    if (!เล่มทั้งหมด.some((x) => ร.รหัส.startsWith(`${x.รหัส}.`))) {
      throw new Error(`⛔ เรื่องเล่า ${ร.รหัส} ⇒ ไม่มีเล่มนี้ในบัญชีของซองตัวบท (ใบ #177)`)
    }
  }
  return {
    เล่ม: เล่มทั้งหมด
      .map((x) => ({
        รหัส: x.รหัส,
        ชื่อไทย: x.ชื่อไทย,
        บท: x.บท,
        เรื่อง: เรื่องทั้งหมด
          .filter((ร) => ร.รหัส.startsWith(`${x.รหัส}.`))
          .sort((ก, ข) => ก.จาก.บท - ข.จาก.บท || ก.จาก.ข้อ - ข.จาก.ข้อ)
          .map(({ รหัส, จาก, ถึง, ชื่อ, อนุมัติเมื่อ }) => ({ รหัส, จาก, ถึง, ชื่อ, อนุมัติเมื่อ })),
      }))
      .filter((x) => x.เรื่อง.length),
  }
})
