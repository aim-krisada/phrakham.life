//
// ⭐ ที่อยู่เป็นภาษาอังกฤษ และลงท้ายด้วย `.json` ⇒ เหตุผลทั้งสองข้ออยู่ที่ `server/api/books.json.get.ts`
//   ⛔ ไม่จดซ้ำที่นี่
//
// ⛔⛔ **ซองนี้ ⛔ ไม่คอมมิต ⇒ พ่นตอนสร้าง** (`tools/สร้างรายการเสียง.py`)
//   ⇒ ⭐ **ไม่มีไฟล์ ⇒ ตายพร้อมบอกคำสั่งที่ต้องรัน** ⛔ ไม่ใช่คืนของว่างที่ดูเหมือนใช้ได้
//     **ทำไมต่างจากซองคำพระเยซูที่ขาดได้** ⇒ ซองนั้นหายไปแล้วตัวบทยังครบทุกตัวอักษร ขาดแค่สีเน้น
//     ⇒ แต่หน้าฟัง **⛔ ไม่มีอะไรเหลือเลย** ถ้าไม่มีรายการ ⇒ มันจะกลายเป็นหน้าที่กดแล้วเงียบ
//     ⇒ ⛔ หน้าที่กดแล้วเงียบ คือของที่ใบนี้สั่งห้ามไว้ตรง ๆ
//
// ⛔⛔ **ต้องสั่ง import เอง — ตัวเติม import อัตโนมัติ ⛔ ไม่รู้จักชื่อภาษาไทย**
import { readFileSync } from 'node:fs'

let คลัง: unknown = null

export default defineEventHandler(() => {
  if (!คลัง) {
    const ทาง = useRuntimeConfig().ทางรายการเสียง as string
    try {
      คลัง = JSON.parse(readFileSync(ทาง, 'utf8'))
    } catch {
      throw new Error(
        `⛔ ไม่มีรายการเสียงที่ ${ทาง}\n` +
          '   ⇒ สั่ง py -3.14 tools/สร้างรายการเสียง.py ก่อน (ดูหัวไฟล์นั้นว่าต้องมีอะไรบ้าง)',
      )
    }
  }
  return คลัง
})
