/** `GEN 32.1` ⇒ [บท, ข้อ] */
function แยกที่(ที่: string): [number, number] {
  const [บท, ข้อ] = ที่.split(' ')[1]!.split('.').map(Number)
  return [บท!, ข้อ!]
}
const ลำดับ = ([บท, ข้อ]: [number, number]) => บท * 1000 + ข้อ

let ตารางเลขข้อ: Record<string, string> | null = null
const คลังข้อแปล = new Map<string, Map<number, Record<string, [number, number][]>>>()

/** `{<บทเดิม>: {<ข้อเดิม>: [[บทแปล, ข้อแปล], ...]}}` ของทั้งเล่ม ⇒ เฉพาะข้อที่ไม่ตรงกับเลขของตัวเอง */
export function ข้อแปลของเล่ม(รหัสเล่ม: string): Map<number, Record<string, [number, number][]>> {
  const มีแล้ว = คลังข้อแปล.get(รหัสเล่ม)
  if (มีแล้ว) return มีแล้ว
  const ค่า = useRuntimeConfig()
  ตารางเลขข้อ ??= (
    JSON.parse(readFileSync(ค่า.ทางตารางเลขข้อ as string, 'utf8')) as { ไทยไปต้นฉบับ: Record<string, string> }
  ).ไทยไปต้นฉบับ

  // ① ข้อแปลทุกข้อของเล่ม (ทุกฉบับรวมกัน) ⇒ แปลงเป็นเลขข้อเดิม ⇒ เรียงตามลำดับของฝั่งเดิม
  const ข้อแปลทั้งเล่ม: { เดิม: number; แปล: [number, number] }[] = []
  for (const c of ข้อมูลเล่ม(รหัสเล่ม)?.เล่ม.บทที่มี ?? []) {
    const เลข = new Set<string>()
    for (const ข้อทั้งหมด of Object.values(อ่านบท(รหัสเล่ม, String(c))?.ชั้น ?? {})) {
      for (const n of Object.keys(ข้อทั้งหมด)) เลข.add(n)
    }
    for (const n of เลข) {
      const ไป = ตารางเลขข้อ[`${รหัสเล่ม} ${c}.${n}`]
      if (ไป && !ไป.startsWith(`${รหัสเล่ม} `)) throw new Error(`⛔ ตารางเลขข้อพาข้ามเล่ม ${รหัสเล่ม} ${c}.${n} ⇒ ${ไป}`)
      const แปล: [number, number] = [c, Number(n)]
      ข้อแปลทั้งเล่ม.push({ เดิม: ลำดับ(ไป ? แยกที่(ไป) : แปล), แปล })
    }
  }
  ข้อแปลทั้งเล่ม.sort((a, b) => a.เดิม - b.เดิม || ลำดับ(a.แปล) - ลำดับ(b.แปล))
  const ชี้มา = new Map<number, [number, number][]>()
  for (const x of ข้อแปลทั้งเล่ม) {
    const ที่ = ชี้มา.get(x.เดิม)
    if (ที่) ที่.push(x.แปล)
    else ชี้มา.set(x.เดิม, [x.แปล])
  }

  // ② ข้อเดิมทุกข้อของเล่ม ⇒ เก็บเฉพาะข้อที่อยู่กับข้อแปลคนละเลขกับตัวเอง
  const ผล = new Map<number, Record<string, [number, number][]>>()
  const บัญชี = JSON.parse(readFileSync(join(ค่า.ทางกองภาษาเดิม as string, 'บัญชี.json'), 'utf8')) as {
    เล่ม: { รหัส: string; บทที่มี: number[] }[]
  }
  for (const F of บัญชี.เล่ม.find((x) => x.รหัส === รหัสเล่ม)?.บทที่มี ?? []) {
    const ไฟล์ = อ่านชั้นคำดิบ(รหัสเล่ม, String(F))
    if (!ไฟล์) continue
    const เลขเดิม = new Set<string>()
    for (const ข้อทั้งหมด of Object.values(ไฟล์.ชั้น)) for (const O of Object.keys(ข้อทั้งหมด)) เลขเดิม.add(O)
    for (const O of เลขเดิม) {
      const ที่ = ลำดับ([F, Number(O)])
      let แปล = ชี้มา.get(ที่)
      // ⭐ กติกา ② ⇒ ไม่มีข้อแปลชี้มา ⇒ ข้อแปลข้อถัดไปตามลำดับของฝั่งเดิม
      //   ⇒ ⛔ ไม่มีข้อถัดไปเลย (ท้ายเล่ม) ⇒ ปล่อยเลขของตัวเอง ⇒ วัดแล้ว ⛔ ไม่เกิดสักจุดใน 66 เล่ม
      if (!แปล) {
        const ถัด = ข้อแปลทั้งเล่ม.find((x) => x.เดิม > ที่)
        if (!ถัด) continue
        แปล = [ถัด.แปล]
      }
      if (แปล.length === 1 && แปล[0]![0] === F && แปล[0]![1] === Number(O)) continue
      const ของบท = ผล.get(F) ?? {}
      ของบท[O] = แปล
      ผล.set(F, ของบท)
    }
  }
  คลังข้อแปล.set(รหัสเล่ม, ผล)
  return ผล
}
