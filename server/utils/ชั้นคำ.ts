/**
 * คำหนึ่งคำบนหน้าจอ ⇒ `[ตัวอักษรเดิม, คำแปลกำกับ]` ⛔ ไม่ส่งชื่อช่องซ้ำทุกคำ
 *   ⇒ คำกริยากรีกมีช่องที่ 3 ⇒ `[ตัว, คำแปล, กาลกับมาลา]` เช่น `AI` (ใบ #110 ⇒ ดูหัวไฟล์)
 */
export type คำ = [string, string] | [string, string, string]

/**
 * กาลกับมาลาของคำกริยากรีก ⇒ `V-2AAI-3S` ⇒ `AI` · คำที่ ⛔ ไม่ใช่กริยา ⇒ `null`
 *   ⇒ รูปแบบรหัสตามระบบ Robinson ⇒ ชุดตัวอักษรเดียวกับ `app/utils/รูปผัน.ts` ⛔ ไม่ตั้งเพิ่มเอง
 */
export function กาลมาลาของ(รูปผัน: string): string | null {
  if (!รูปผัน.startsWith('V-')) return null
  const m = /^V-2?([PIFARL])[AMPEDONQX]([ISOMNPR])(?:-|$)/.exec(รูปผัน)
  if (!m) throw new Error(`⛔ รูปผันกริยา ${รูปผัน} ตัดกาลกับมาลาไม่ออก ⇒ แก้ที่ server/utils/ชั้นคำ.ts (ใบ #110)`)
  return m[1]! + m[2]!
}

export interface ชั้นคำของบท {
  บท: number
  /** `{<ชื่อชั้น>: {<เลขข้อ>: [คำ...]}}` ⇒ ⛔ **เลขข้อเป็นของฝั่งภาษาเดิมเอง** */
  ชั้น: Record<string, Record<string, คำ[]>>
  ภาษาของชั้น: Record<string, string>
  ทิศของชั้น: Record<string, 'ltr' | 'rtl'>
  แหล่งของชั้น: Record<string, string>
  /**
   * ⭐ **ข้อเดิมข้อนี้อยู่กับข้อแปลข้อไหน** ⇒ `{<เลขข้อเดิม>: [[บทแปล, ข้อแปล], ...]}` (ใบ #104)
   *   ⇒ **มีเฉพาะข้อที่ไม่ตรงกับเลขของตัวเอง** ⇒ ไม่มีกุญแจ = ข้อเดิม `บท:ข้อ` อยู่กับข้อแปล `บท:ข้อ` เลขเดียวกัน
   *   ⇒ ⛔ **ไม่มีจุดไหนเลยในบทนี้ ⇒ ไม่มีช่องนี้เลย** ⇒ บทส่วนใหญ่ ⛔ ไม่จ่ายเพิ่มสักไบต์
   *   ⇒ หน้าอ่านใช้ **ตัดชั้นคำตามช่วง** (ใบ #104) และ **วางคำเดิมให้ตรงแถวกับข้อแปล** (ใบ #112 ⇒ `app/utils/แถวคำเดิม.ts`)
   */
  ข้อแปล?: Record<string, [number, number][]>
  /** ⭐ เครื่องหมายของ Levinsohn ของชั้นกรีก (ใบ #146) ⇒ `{<รหัสชนิด>: [<เครื่องหมาย>]}` ⇒ ⛔ ไม่มี = ไม่มีช่องนี้ */
  เครื่องหมาย?: Record<string, (number | string)[][]>
}

let ซองเครื่องหมาย: Record<string, Record<string, (number | string)[][]>> | null = null

/** เครื่องหมายของบทเดียว ⇒ ⛔ ไม่มี = `undefined` ⇒ ⛔ ซองหาย = ล้ม (ตัวตั้งค่าเว็บกันไว้แล้วอีกชั้น) */
function เครื่องหมายของบท(รหัสเล่ม: string, บท: string) {
  ซองเครื่องหมาย ??= (
    JSON.parse(gunzipSync(readFileSync(useRuntimeConfig().ทางซองคำเน้น as string)).toString('utf8')) as {
      บท: Record<string, Record<string, (number | string)[][]>>
    }
  ).บท
  return ซองเครื่องหมาย[`${รหัสเล่ม}/${บท}`]
}

interface ไฟล์บท {
  ชั้น: Record<string, Record<string, Record<string, string>[]>>
  แหล่งของชั้น: Record<string, string>
}

/**
 * ภาษากับทิศของชั้นคำ ⇒ **รหัสตาม BCP 47**
 *
 * ⭐⭐ **ทำไมต้องมีทิศแยกจากภาษา** ⇒ `lang` ⛔ **ไม่ได้บอกทิศให้เบราว์เซอร์**
 *   ⇒ ฮีบรูอ่านขวาไปซ้าย ⇒ ⛔ ไม่ใส่ `dir` = คำเรียงกลับด้านทั้งข้อ โดย ⛔ ไม่มีอะไรฟ้อง
 *   ⇒ **WCAG 2.2 SC 1.3.2 Meaningful Sequence (ระดับ A)** ⇒ ลำดับที่สื่อความหมายต้องรู้ได้ด้วยโปรแกรม
 *
 * ⛔⛔ **ชั้นที่ ⛔ ไม่มีชื่อในตารางนี้ ⇒ ล้มทันที** ⛔ ไม่มีค่าสำรอง
 *   ⇒ เหตุผลเดียวกับตาราง `ภาษาของชั้น` ที่ `server/utils/เนื้อบท.ts` ⛔ ไม่จดซ้ำที่นี่
 */
const ชั้นที่รู้จัก: Record<string, { ภาษา: string; ทิศ: 'ltr' | 'rtl' }> = {
  คำฮีบรู: { ภาษา: 'hbo', ทิศ: 'rtl' },
  คำกรีก: { ภาษา: 'grc', ทิศ: 'ltr' },
}

/** แกะไฟล์บทแล้วใช้ซ้ำ — ตัวสร้างเว็บขอทุกบท ⇒ ⛔ แกะซ้ำบทเดิมเปล่า ๆ ไม่ได้ */
const คลัง = new Map<string, ชั้นคำของบท | null>()

/**
 * ชั้นคำของบทเดียว ⇒ ⛔ **ไม่มีบทนั้นคืน `null`** ⛔ ไม่ใช่ของว่างที่ดูเหมือนใช้ได้
 *
 * ⭐ **บทที่ ⛔ ไม่มีชั้นคำเป็นเรื่องปกติ ⛔ ไม่ใช่ความพัง** ⇒ ฝั่งฮีบรูกับฝั่งคำแปลแบ่งบทไม่เท่ากัน
 *   ⇒ ตัวอย่างจริงคือ `MAL/4` ที่ ⛔ ไม่มีชั้นคำเลย ⇒ เจ้าของเรื่องคือ `docs/ข้อมูลที่เว็บอ่าน.md`
 */
export function ชั้นคำของบท(รหัสเล่ม: string, บท: string): ชั้นคำของบท | null {
  const ผล = อ่านชั้นคำดิบ(รหัสเล่ม, บท)
  if (!ผล) return null
  const ข้อแปล = ข้อแปลของเล่ม(รหัสเล่ม).get(Number(บท))
  return ข้อแปล ? { ...ผล, ข้อแปล } : ผล
}

/** อ่านไฟล์บทของกองภาษาเดิมตรง ๆ ⇒ ⛔ ยังไม่มีช่อง `ข้อแปล` */
function อ่านชั้นคำดิบ(รหัสเล่ม: string, บท: string): ชั้นคำของบท | null {
  const กุญแจ = `${รหัสเล่ม}/${บท}`
  if (คลัง.has(กุญแจ)) return คลัง.get(กุญแจ) ?? null

  const ทางกอง = useRuntimeConfig().ทางกองภาษาเดิม as string
  let ของดิบ: ไฟล์บท
  try {
    ของดิบ = JSON.parse(gunzipSync(readFileSync(join(ทางกอง, รหัสเล่ม, `${บท}.json.gz`))).toString('utf8'))
  } catch {
    // ⛔ ไม่มีไฟล์ = บทนี้ไม่มีชั้นคำ ⇒ **เป็นคำตอบที่ถูกต้อง** ⛔ ไม่ใช่ข้อผิดพลาดที่ต้องโยนออกไป
    คลัง.set(กุญแจ, null)
    return null
  }

  const ชื่อชั้น = Object.keys(ของดิบ.ชั้น ?? {})
  const ไม่รู้จัก = ชื่อชั้น.filter((ช) => !ชั้นที่รู้จัก[ช])
  if (ไม่รู้จัก.length) {
    throw new Error(
      `⛔ ชั้นคำ [${ไม่รู้จัก.join(' ')}] ⛔ ไม่มีภาษาและทิศ ⇒ เติมในตาราง ชั้นที่รู้จัก ที่ server/utils/ชั้นคำ.ts`,
    )
  }

  const ชั้น: Record<string, Record<string, คำ[]>> = {}
  for (const ช of ชื่อชั้น) {
    const ข้อทั้งหมด: Record<string, คำ[]> = {}
    for (const [เลขข้อ, คำทั้งข้อ] of Object.entries(ของดิบ.ชั้น[ช] ?? {})) {
      // ⭐ **เรียงตามลำดับของเจ้าของเป๊ะ** ⛔ ไม่เรียงใหม่ ⛔ ไม่กรองคำที่ไม่มีคำแปลทิ้ง
      //   ⇒ กรองทิ้งเมื่อไร ชั้นคำจะสั้นลงแล้ว **เลิกเรียงตรงกับชั้นความหมาย** (ของใบถัดไป)
      ข้อทั้งหมด[เลขข้อ] = คำทั้งข้อ.map((w): คำ => {
        const คู่: [string, string] = [w['ตัว'] ?? '', w['คำแปล'] ?? '']
        // ⭐ ใบ #110 ⇒ กริยากรีกได้ช่องที่ 3 ⇒ ฮีบรู ⛔ ไม่แตะ (ระบบกาลคนละแบบ)
        const กาล = ช === 'คำกรีก' ? กาลมาลาของ(w['รูปผัน'] ?? '') : null
        return กาล ? [...คู่, กาล] : คู่
      })
    }
    ชั้น[ช] = ข้อทั้งหมด
  }

  const ผล: ชั้นคำของบท = {
    บท: Number(บท),
    ชั้น,
    ภาษาของชั้น: Object.fromEntries(ชื่อชั้น.map((ช) => [ช, ชั้นที่รู้จัก[ช]!.ภาษา])),
    ทิศของชั้น: Object.fromEntries(ชื่อชั้น.map((ช) => [ช, ชั้นที่รู้จัก[ช]!.ทิศ])),
    // ⭐ ป้ายบอกที่มาติดทีละชั้น ⛔ ป้ายเดียวคลุมทั้งหน้าไม่ได้ ⇒ `docs/บันทึก-แหล่งข้อมูล.md` หัวข้อ ②
    แหล่งของชั้น: Object.fromEntries(ชื่อชั้น.map((ช) => [ช, ของดิบ.แหล่งของชั้น?.[ช] ?? ''])),
  }
  // ⭐ ใบ #146 ⇒ ข้อมูลของ Levinsohn มีเฉพาะพันธสัญญาใหม่ ⇒ ฮีบรู ⛔ ไม่มีในซองอยู่แล้ว ⇒ เช็กชั้นซ้ำกันไว้อีกชั้น
  const เครื่องหมาย = ชั้น['คำกรีก'] ? เครื่องหมายของบท(รหัสเล่ม, บท) : undefined
  if (เครื่องหมาย) ผล.เครื่องหมาย = เครื่องหมาย
  คลัง.set(กุญแจ, ผล)
  return ผล
}

