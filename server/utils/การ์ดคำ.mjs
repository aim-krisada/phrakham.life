import { readFileSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'
import { join } from 'node:path'

/** แหล่งที่หน้าอ่านเลือกได้ ⇒ ชื่อเป็นอักษรอังกฤษ เพราะเป็นส่วนหนึ่งของที่อยู่เว็บ */
export const แหล่งจากคลังUBS = { 'ubs-grc': 'คลัง-กรีก.json.gz', 'ubs-hbo': 'คลัง-ฮีบรู.json.gz' }
export const แหล่งที่พ่น = ['strong-grc', 'strong-hbo', 'abbott-smith', 'bdb']

/** ชั้นคำ ⇒ ชั้นความหมายที่เรียงคู่กันคำต่อคำ (ชื่อตั้งไว้ที่ `tools/สร้างชั้นความหมาย.py`) */
const ชั้นความหมายของ = { คำกรีก: 'ความหมายกรีก', คำฮีบรู: 'ความหมายฮีบรู' }

function อ่านซอง(ทาง, วิธีแก้) {
  let ไบต์
  try {
    ไบต์ = readFileSync(ทาง)
  } catch {
    throw new Error(`⛔ ไม่มีไฟล์ ${ทาง}\n   ⇒ ${วิธีแก้}`)
  }
  if (ไบต์.subarray(0, 40).toString('utf8').startsWith('version https://git-lfs')) {
    throw new Error(`⛔ ${ทาง} เป็นตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง\n   ⇒ ${วิธีแก้}`)
  }
  return JSON.parse(gunzipSync(ไบต์).toString('utf8'))
}

/**
 * รหัสความหมาย UBS ⇒ แบบย่อ ⇒ `002539001002000` ⇒ `2539001002`
 *
 * ⭐ **ทำไมต้องย่อ** ⇒ ไฟล์การ์ดมีรหัสนี้ทุกคำ 423,020 ครั้ง ⇒ ย่อแล้วประหยัดราว 2.4 เมกะไบต์
 * ⛔ **ย่อได้เพราะรหัสทุกตัวยาว 15 หลักและลงท้าย `000`** ⇒ ⛔ ไม่ใช่ ⇒ ตายทันที ⛔ ไม่ย่อแบบเสียของ
 */
export function ย่อรหัสUBS(รหัส) {
  if (!/^\d{12}000$/.test(รหัส)) throw new Error(`⛔ รหัสความหมาย UBS ${รหัส} ไม่ใช่ 15 หลักที่ลงท้าย 000 ⇒ ย่อไม่ได้`)
  return String(Number(รหัส.slice(0, 12)))
}

/** แบบย่อ ⇒ เลขก้อน ⇒ เลขหัวคำ (6 หลักแรก) หาร 100 ⇒ หน้าเว็บคิดแบบเดียวกันที่ `app/utils/การ์ดคำ.ts` */
function ก้อนของUBS(ย่อ) {
  return String(Math.floor(Number(ย่อ) / 1e6 / 100))
}

const คลังแหล่ง = new Map()

/** ซองทั้งแหล่ง ⇒ `{ก้อน: {<เลขก้อน>: {<กุญแจ>: ...}}}` */
export function ซองของแหล่ง(แหล่ง, { ทางกองความหมาย, ทางกองพจนานุกรม }) {
  if (คลังแหล่ง.has(แหล่ง)) return คลังแหล่ง.get(แหล่ง)
  let ซอง
  if (แหล่งจากคลังUBS[แหล่ง]) {
    const คลัง = อ่านซอง(join(ทางกองความหมาย, แหล่งจากคลังUBS[แหล่ง]), 'สั่ง git lfs pull -I "_data/" ก่อนสร้างเว็บ')
    const ก้อน = {}
    for (const [รหัส, ค] of Object.entries(คลัง.ความหมาย)) {
      const ย่อ = ย่อรหัสUBS(รหัส)
      // ⭐ ยกเฉพาะช่องที่การ์ดแสดง ⇒ ⛔ ไม่แตะตัวหนังสือในช่องไหนเลย
      const ของ = { น: ค['นิยาม'], ก: ค['คำแปลสั้น'] }
      if (ค['หมวด']) ของ.ม = ค['หมวด']
      if (ค['หมวดย่อย']) ของ.ย = ค['หมวดย่อย']
      if (ค['รหัสLouwNida']) ของ.LN = ค['รหัสLouwNida']
      ;(ก้อน[ก้อนของUBS(ย่อ)] ??= {})[ย่อ] = ของ
    }
    ซอง = { แหล่ง, ก้อน }
  } else if (แหล่งที่พ่น.includes(แหล่ง)) {
    ซอง = อ่านซอง(
      join(ทางกองพจนานุกรม, `${แหล่ง}.json.gz`),
      'สั่ง py -3.14 tools/สร้างพจนานุกรม.py ก่อน (ต้องมีไบต์จริงของ zip ต้นทาง ⇒ ดูหัวไฟล์นั้น)',
    )
  } else {
    return null
  }
  คลังแหล่ง.set(แหล่ง, ซอง)
  return ซอง
}

/** ก้อนเดียวของแหล่งเดียว ⇒ ⛔ ไม่มี ⇒ `null` (หลังบ้านตอบ 404) */
export function ก้อนพจนานุกรม(แหล่ง, ก้อน, ทาง) {
  const ซอง = ซองของแหล่ง(แหล่ง, ทาง)
  const คำ = ซอง?.ก้อน?.[ก้อน]
  return คำ ? { แหล่ง, ก้อน: Number(ก้อน), คำ } : null
}

/** รายชื่อที่อยู่ของก้อนทุกก้อน ⇒ ตัวตั้งค่าเว็บสั่งสร้างเป็นไฟล์นิ่ง */
export function ที่อยู่ก้อนทั้งหมด(ทาง) {
  return [...Object.keys(แหล่งจากคลังUBS), ...แหล่งที่พ่น].flatMap((แหล่ง) =>
    Object.keys(ซองของแหล่ง(แหล่ง, ทาง).ก้อน).map((ก) => `/api/lex/${แหล่ง}/${ก}.json`),
  )
}

/**
 * ข้อมูลการ์ดของบทเดียว ⇒ `{บท, ชั้น: {<ชั้นคำ>: {<ข้อ>: ["รูปพจนานุกรม~รหัส~รูปผัน~UBS~a", ...]}}}`
 *
 * ⭐ **คำละ 1 สตริงคั่นด้วย `~`** ⇒ ⛔ ไม่ใช่วัตถุที่มีชื่อช่องซ้ำทุกคำ ⇒ ท่าเดียวกับ `/api/words/`
 *   ⛔ **ไม่ใช้ `|`** ⇒ รหัสฮีบรูใช้ `|` คั่นรหัสคู่อยู่แล้ว เช่น `1886a|0725` (ผู้วินิจฉัย 9:41)
 *   ⇒ ช่องท้ายที่ว่างตัดทิ้ง ⇒ `a` ท้ายสุด = คำนี้เป็นภาษาอาราเมค (รหัสรูปผันอ่านคนละชุด)
 * ⛔⛔ **เรียงตรงกับ `/api/words/` คำต่อคำ** ⇒ หน้าเว็บหยิบด้วยเลขข้อกับลำดับคำ
 *   ⇒ ชั้นความหมายยาวไม่เท่าชั้นคำ ⇒ **ตายทันที** ⛔ ไม่แปะความหมายผิดคำเงียบ ๆ
 */
export function ข้อมูลการ์ดของบท(เล่ม, บท, { ทางกองภาษาเดิม, ทางกองความหมาย }) {
  let คำ
  try {
    คำ = อ่านซอง(join(ทางกองภาษาเดิม, เล่ม, `${บท}.json.gz`), '')
  } catch {
    return null
  }
  let ความหมาย = null
  try {
    ความหมาย = อ่านซอง(join(ทางกองความหมาย, เล่ม, `${บท}.json.gz`), '')
  } catch {
    // ⭐ บทที่ไม่มีชั้นความหมาย ⇒ ทุกคำได้ช่อง UBS ว่าง ⇒ การ์ดบอกว่า UBS ไม่มีคำนี้
  }
  const ชั้น = {}
  for (const [ชื่อ, ข้อทั้งหมด] of Object.entries(คำ.ชั้น)) {
    const คู่ = ความหมาย?.ชั้น?.[ชั้นความหมายของ[ชื่อ]] ?? {}
    const ผล = {}
    for (const [ข้อ, รายการ] of Object.entries(ข้อทั้งหมด)) {
      const รหัสUBS = คู่[ข้อ]
      if (รหัสUBS && รหัสUBS.length !== รายการ.length) {
        throw new Error(`⛔ ${เล่ม} ${บท}:${ข้อ} ชั้นความหมาย ${รหัสUBS.length} คำ แต่ชั้นคำ ${รายการ.length} คำ`)
      }
      ผล[ข้อ] = รายการ.map((ค, i) => {
        const ช่อง = [ค['รูปพจนานุกรม'] ?? '', ค['รหัส'] ?? '', ค['รูปผัน'] ?? '', รหัสUBS?.[i] ? ย่อรหัสUBS(รหัสUBS[i]) : '', ค['อาราเมค'] ? 'a' : '']
        if (ช่อง.some((x) => x.includes('~'))) throw new Error(`⛔ ${เล่ม} ${บท}:${ข้อ} มีตัว ~ ในข้อมูล ⇒ คั่นช่องไม่ได้`)
        return ช่อง.join('~').replace(/~+$/, '')
      })
    }
    ชั้น[ชื่อ] = ผล
  }
  return { บท: Number(บท), ชั้น }
}
