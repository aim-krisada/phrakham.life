// แกะครั้งเดียวแล้วใช้ซ้ำ — ตัวสร้างเว็บเรียกหาบทกว่าพันครั้ง
// ⛔ แกะใหม่ทุกครั้ง = แกะซอง 6.7 เมกะไบต์ 1,189 รอบ
let คลัง: ซอง | null = null

function เปิดซอง(): ซอง {
  // ⭐ ซองเดิม + ซองฉบับเพิ่ม (ใบงาน #169 ⇒ KJV) ⇒ เหตุผลอยู่ที่ `แกะซองรวมฉบับเพิ่ม`
  if (!คลัง) {
    const ค่า = useRuntimeConfig()
    คลัง = แกะซองรวมฉบับเพิ่ม(ค่า.ทางซองเนื้อบท as string, ค่า.ทางซองฉบับเพิ่ม as string) as ซอง
    แยกจำนวนบทสองฝั่ง(คลัง, ค่า.ทางกองภาษาเดิม as string)
  }
  return คลัง
}

/**
 * ⭐⭐ **`บท` = จำนวนบทของฉบับแปล ⇒ เท่ากับ `บทที่มี` ทุกเล่ม · `บทเดิม` = จำนวนบทของฝั่งภาษาเดิม** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/94 ข้อ 3)
 *   ⇒ ⚠️ ของเดิม ⇒ ซองนับบทแบบรวมสองฝั่ง (`tools/สร้างข้อมูลเว็บ.py` ⇒ 1,190 บท) ⇒ โยเอลได้ `บท` 4 แต่ `บทที่มี` 1 2 3 ⇒ สองช่องขัดกัน
 *   ⇒ ⛔ ไม่แก้ซอง ⇒ ซองคือของที่ตรึงลายนิ้วมือไว้ ⇒ แยกตอนเปิดซองที่นี่ที่เดียว ⇒ `api/books.json` กับ `api/book/<เล่ม>.json` ได้ค่าเดียวกัน
 *   ⇒ บทของฝั่งเดิมมาจากบัญชีของกองภาษาเดิมเอง (`_data/ภาษาเดิม/บัญชี.json`) ⇒ ตัวเดียวกับที่ `server/utils/ชั้นคำ.ts` ใช้
 *   ⇒ หน้าอ่านหยิบคำเดิมถึงบทสูงสุดของสองฝั่ง (`บทเดิมที่ต้องหยิบ`) ⇒ โยเอลฮีบรู 4 ยังมา
 */
function แยกจำนวนบทสองฝั่ง(ซ: ซอง, ทางกองภาษาเดิม: string) {
  const บัญชีเดิม = JSON.parse(readFileSync(join(ทางกองภาษาเดิม, 'บัญชี.json'), 'utf8')) as {
    เล่ม: { รหัส: string; บทที่มี: number[] }[]
  }
  for (const เล่ม of ซ.บัญชี.เล่ม) {
    เล่ม.บท = เล่ม.บทที่มี.length
    เล่ม.บทเดิม = บัญชีเดิม.เล่ม.find((x) => x.รหัส === เล่ม.รหัส)?.บทที่มี.length ?? 0
  }
  ซ.บัญชี.จำนวนบท = ซ.บัญชี.เล่ม.reduce((รวม, x) => รวม + x.บท, 0)
}

