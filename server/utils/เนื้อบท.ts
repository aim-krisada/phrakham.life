/**
 * ⭐⭐ **ของประจำเล่ม — หน้าของเล่มหยิบไปใช้ตอนสร้างหน้า** (ใบงาน v3/phrakham#73)
 *
 * **ทำไมต้องแยกออกมาจากเนื้อบท** ⇒ เดิมเนื้อของ *ทุกบท* พก `เล่ม` กับ `แหล่งของชั้น` ติดไปด้วย
 *   ⇒ สดุดี 150 บท = พกรายชื่อบททั้ง 150 บทซ้ำกัน 150 รอบ ⇒ **ไบต์เสียเปล่า**
 *   ⇒ ของพวกนี้เปลี่ยนตามเล่ม ⛔ ไม่เปลี่ยนตามบท ⇒ **ที่ของมันคือระดับเล่ม**
 */
export function ข้อมูลเล่ม(รหัสเล่ม: string) {
  const ซ = เปิดซอง()
  const เล่ม = ซ.บัญชี.เล่ม.find((x) => x.รหัส === รหัสเล่ม)
  if (!เล่ม || !เล่ม.บทที่มี.length) return null
  // ⛔ **ชั้นที่ยังไม่มีภาษา ⇒ ล้มตรงนี้** ⇒ ดูเหตุผลที่ตาราง `ภาษาของชั้น` ข้างบน
  const ขาดภาษา = ซ.ชั้น.filter((ช) => !ภาษาของชั้น[ช])
  if (ขาดภาษา.length) {
    throw new Error(`⛔ ชั้น [${ขาดภาษา.join(' ')}] ⛔ ไม่มีภาษา ⇒ เติมในตาราง ภาษาของชั้น ที่ server/utils/เนื้อบท.ts`)
  }
  // ⛔ **ฉบับที่ยังไม่มีชื่อย่อของเล่มนี้ ⇒ ล้มตอนสร้าง** ⇒ ท่าเดียวกับภาษา ⇒ ⛔ ไม่มีค่าสำรองที่ทำให้ของที่ลืมดูเหมือนถูก
  const ตารางย่อ = ชื่อย่อเล่ม.ชื่อย่อ as Record<string, Record<string, string>>
  const ชื่อย่อของชั้น = Object.fromEntries(
    ซ.ชั้น.filter((ช) => !ชั้นที่ไม่ต้องมีชื่อย่อ.has(ช)).map((ช) => [ช, ตารางย่อ[ช]?.[รหัสเล่ม] || '']),
  )
  const ขาดย่อ = Object.keys(ชื่อย่อของชั้น).filter((ช) => !ชื่อย่อของชั้น[ช])
  if (ขาดย่อ.length) {
    throw new Error(`⛔ ฉบับ [${ขาดย่อ.join(' ')}] ⛔ ไม่มีชื่อย่อของ ${รหัสเล่ม} ⇒ สั่ง py -3.14 tools/ด่านชื่อย่อตรงต้นทาง.py --เขียน`)
  }
  return {
    เล่ม,
    // ⭐ **ลำดับที่ฉบับต่าง ๆ ต้องเรียงบนหน้าเว็บ** ⇒ มาจากซอง ⛔ ไม่ใช่ลำดับกุญแจใน JSON
    //   ⇒ ซองเรียงกุญแจตามตัวอักษรเพื่อให้ไบต์คงที่ ⇒ เอามาใช้ตรง ๆ จะได้ LSV ขึ้นก่อน TCV
    ชั้น: ซ.ชั้น,
    // ⭐ ป้ายบอกที่มาติดทีละชั้น ⛔ ป้ายเดียวคลุมทั้งหน้าไม่ได้
    //   ⇒ เจ้าของเหตุผลคือ docs/บันทึก-แหล่งข้อมูล.md หัวข้อ ②
    แหล่งของชั้น: ซ.แหล่งของชั้น,
    // ⭐ **ภาษาของแต่ละชั้น ⇒ หน้าอ่านเอาไปติด `lang` ให้กล่องของฉบับนั้น**
    //   ⇒ WCAG 2.2 SC 3.1.2 Language of Parts (ระดับ AA) ⇒ *The human language of each passage
    //     or phrase in the content can be programmatically determined*
    //   ⇒ ⛔ ไม่ติด = โปรแกรมอ่านหน้าจออ่านคอลัมน์อังกฤษด้วยเสียงไทย
    ภาษาของชั้น: Object.fromEntries(ซ.ชั้น.map((ช) => [ช, ภาษาของชั้น[ช]!])),
    // ⭐ **ชื่อย่อเล่มนี้ของแต่ละฉบับ** ⇒ หัวคอลัมน์เขียนบนปุ่มเปลี่ยนตอน (ใบ #131 note_30489) ⇒ 4 คำต่อเล่ม
    ชื่อย่อของชั้น,
    // ⭐ **ฉบับไหนยังไม่มีย่อหน้าให้ใช้ และเพราะอะไร** (ใบงาน #98)
    //   ⇒ อยู่ระดับ **เล่ม** ⛔ ไม่ใช่ระดับบท ⇒ มันเปลี่ยนตามฉบับ ⛔ ไม่เปลี่ยนตามบท
    //     ⇒ วางไว้ระดับบท = ส่งประโยคเดิมซ้ำ 1,189 รอบ ⇒ **ไบต์เสียเปล่า**
    //   ⇒ ประโยคมาจากซองที่เครื่องนับเอง ⛔ ไม่ได้พิมพ์ที่นี่
    ฉบับที่ยังไม่มีย่อหน้า: เปิดซองรอยย่อหน้า().ไม่มี,
    // ⭐ **ดัชนีเสียงของเล่มนี้** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/101)
    //   ⇒ เล่มที่ไม่มีเสียงได้ `undefined` ⇒ กุญแจนี้หายไปจากไฟล์ ⇒ จ่าย 0 ไบต์
    //   ⇒ เหตุผลว่าทำไมต้องอยู่ที่นี่ อยู่หัวไฟล์ `server/utils/เสียงของเล่ม.ts` ⛔ ไม่จดซ้ำ
    เสียง: ดัชนีเสียงของเล่ม(รหัสเล่ม),
    // ⭐ **ดัชนีเรื่องเล่าของเล่มนี้** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/105)
    //   ⇒ แค่รหัสกับช่วงข้อ ⇒ ⛔ ไม่มีตัวหนังสือของเรื่อง ⇒ เล่มที่ไม่มีเรื่องเล่าได้ `undefined` ⇒ จ่าย 0 ไบต์
    //   ⇒ เหตุผลอยู่หัวไฟล์ `server/utils/เรื่องเล่า.ts` ⛔ ไม่จดซ้ำ
    เรื่องเล่า: ดัชนีเรื่องเล่าของเล่ม(รหัสเล่ม),
  }
}

/**
 * เนื้อของบทเดียว ⇒ ⛔ ไม่มีบทนั้นคืน null
 *
 * ⭐ **คืนแค่ *เนื้อ* ⛔ ไม่พก `เล่ม` กับ `แหล่งของชั้น` ติดมาด้วย** (ใบงาน v3/phrakham#73)
 *   ⇒ ของพวกนั้นอยู่ที่ `ข้อมูลเล่ม()` ⇒ หน้าโหลดครั้งเดียวต่อเล่ม ⛔ ไม่ใช่ครั้งละบท
 */
export function อ่านบท(รหัสเล่ม: string, บท: string) {
  const ชั้น = เปิดซอง().บท[`${รหัสเล่ม}/${บท}`]
  if (!ชั้น) return null
  // ⭐ ส่งเฉพาะช่วงของ *บทนี้* ⛔ ไม่ส่งทั้งซอง ⇒ ซองทั้งก้อนคือของ 1,189 บทรวมกัน
  const คำพระเยซู: Record<string, ช่วงคำพระเยซู[]> = {}
  const ซองคำ = เปิดซองคำพระเยซู()
  for (const ฉบับ of Object.keys(ซองคำ)) {
    const ของบท = ซองคำ[ฉบับ]?.[`${รหัสเล่ม}/${บท}`]
    if (ของบท?.length) คำพระเยซู[ฉบับ] = ของบท
  }
  // ⭐ รอยขึ้นย่อหน้าของ *บทนี้* เท่านั้น ⛔ ไม่ส่งทั้งซอง ⇒ เหตุผลเดียวกับคำพระเยซู
  const ย่อหน้า: Record<string, รอยย่อหน้า[]> = {}
  const ซองย่อ = เปิดซองรอยย่อหน้า().ฉบับ
  for (const ฉบับ of Object.keys(ซองย่อ)) {
    const ของบท = ซองย่อ[ฉบับ]?.[`${รหัสเล่ม}/${บท}`]
    if (ของบท?.length) ย่อหน้า[ฉบับ] = ของบท
  }
  // ⭐ หัวข้อย่อยของ *บทนี้* เท่านั้น (ใบ #134) ⇒ เหตุผลเดียวกับคำพระเยซู ⇒ ฉบับที่ไม่มีหัวข้อ ⛔ ไม่มีกุญแจ ⇒ จ่าย 0 ไบต์
  const หัวข้อ: Record<string, หัวข้อย่อย[]> = {}
  const ซองหัว = เปิดซองรอยย่อหน้า().หัวข้อ || {}
  for (const ฉบับ of Object.keys(ซองหัว)) {
    const ของบท = ซองหัว[ฉบับ]?.[`${รหัสเล่ม}/${บท}`]
    if (ของบท?.length) หัวข้อ[ฉบับ] = ของบท
  }
  // ⭐ เชิงอรรถของ *บทนี้* เท่านั้น ⇒ เป็นของฉบับไหนอยู่กับฉบับนั้น ⇒ ฉบับที่ไม่มี ⛔ ไม่มีกุญแจ
  const เชิงอรรถ: Record<string, เชิงอรรถ[]> = {}
  const ซองเชิง = เปิดซองเชิงอรรถ()
  for (const ฉบับ of Object.keys(ซองเชิง)) {
    const ของบท = ซองเชิง[ฉบับ]?.[`${รหัสเล่ม}/${บท}`]
    if (ของบท?.length) เชิงอรรถ[ฉบับ] = ของบท
  }
  // ⭐ ช่วงเน้นอื่นของ *บทนี้* ⇒ `{<ชนิด>: {<ฉบับ>: [ช่วง]}}` ⇒ ไม่มี ⇒ ไม่มีกุญแจ
  const ช่วงเน้น: Record<string, Record<string, ช่วงคำพระเยซู[]>> = {}
  for (const [ชนิด, ซอง] of Object.entries(เปิดซองช่วงเน้น())) {
    for (const ฉบับ of Object.keys(ซอง)) {
      const ของบท = ซอง[ฉบับ]?.[`${รหัสเล่ม}/${บท}`]
      if (ของบท?.length) (ช่วงเน้น[ชนิด] ||= {})[ฉบับ] = ของบท
    }
  }
  return { บท: Number(บท), ชั้น, คำพระเยซู, ย่อหน้า, หัวข้อ, เชิงอรรถ, ช่วงเน้น }
}
