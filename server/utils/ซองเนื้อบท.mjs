// ตัวแกะซองตัวบท — **เขียนไว้ที่เดียว** ใช้ทั้งตอนตั้งค่าเว็บและตอนหลังบ้านตอบคำขอ
//
// ⛔ ไม่ให้สองที่นั้นแกะซองเอง — แกะคนละท่าเมื่อไร อีกที่จะเจอข้อผิดพลาดคนละแบบ
//   แล้วคนอ่านต้องไล่ 2 ที่ว่าอันไหนพูดจริง
//
// ⛔⛔ **ต้องอยู่ใน `server/` ⛔ ไม่ใช่ `tools/`** — หลังบ้านตอนพัฒนาหาไฟล์นอก `server/` ไม่เจอ
//   วางไว้ที่ `tools/` แล้วเรียกด้วยที่อยู่ญาติ `../../tools/…` ⇒ มันไปตีความเป็น `C:\tools\…`
//   ⇒ ⛔ ตอนสร้างไม่ฟ้อง แต่พอมีคนเปิดหน้าถึงล้ม (เจอเอง 30 ส.ค. 2569 · ใบงาน v3/phrakham#24)
//
// **ซองมาจากไหน** ⇒ `tools/สร้างเนื้อบท.py` ⇒ เหตุผลทั้งหมดอยู่ที่หัวไฟล์นั้น ⛔ ไม่จดซ้ำที่นี่

import { existsSync, readFileSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'

/** แกะซองที่ `ทาง` ⇒ ⛔ อ่านไม่ได้ให้ตายพร้อมบอกวิธีแก้ */
export function แกะซองเนื้อบท(ทาง) {
  let ไบต์
  try {
    ไบต์ = readFileSync(ทาง)
  } catch {
    throw new Error(
      `⛔ ไม่มีซองตัวบทที่ ${ทาง}\n` +
        '   ⇒ สั่ง py -3.14 tools/สร้างเนื้อบท.py ก่อน (ดูหัวไฟล์นั้นว่าต้องมีอะไรบ้าง)',
    )
  }

  // ⭐⭐ **ตัวชี้ของ Git LFS หน้าตาเหมือนไฟล์ปกติทุกอย่าง — ต่างแค่ข้างในเป็นข้อความสั้น ๆ**
  //   ⇒ ⛔ ไม่ดักไว้ตรงนี้ = ได้ข้อความล้มของ gzip ที่อ่านแล้วเดาต้นเหตุไม่ออกเลย
  //   ⇒ ต้นเหตุจริงคือ **ยังไม่ได้ดึงไบต์จริงของ `_data/`** ⇒ บอกไปตรง ๆ พร้อมคำสั่งที่ต้องรัน
  if (ไบต์.subarray(0, 40).toString('utf8').startsWith('version https://git-lfs')) {
    throw new Error(
      `⛔ ${ทาง} เป็นตัวชี้ของ Git LFS ⛔ ไม่ใช่ไบต์จริง\n` +
        '   ⇒ สั่ง git lfs pull -I "_data/" ก่อนสร้างเว็บ',
    )
  }

  return JSON.parse(gunzipSync(ไบต์).toString('utf8'))
}

/**
 * ⭐⭐ **ซองตัวบทที่เว็บใช้จริง = ซองเดิม + ซองฉบับเพิ่ม** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/169)
 *
 * ซองฉบับเพิ่ม (`_พ่น/ฉบับเพิ่ม.json.gz`) พ่นสดทุกรอบโดย `tools/สร้างฉบับเพิ่ม.py` ⇒ วันนี้มี KJV ฉบับเดียว
 *   ⇒ **ทำไมไม่ใส่ลงซองเดิม** ⇒ เหตุผลอยู่หัวไฟล์ตัวพ่น ⛔ ไม่จดซ้ำที่นี่
 * ⇒ รวมทีละบท ⇒ ฉบับเพิ่มต่อท้ายลำดับฉบับของซองเดิม ⇒ ข้อสุดท้ายของบทคิดใหม่จากทุกฉบับรวมกัน
 *
 * ⛔⛔ **ไม่มีซองฉบับเพิ่ม ⇒ ตายพร้อมบอกคำสั่ง** ⛔ ไม่ใช่ข้ามเงียบ ๆ
 *   ⇒ ข้ามเงียบ = สร้างเว็บที่ฉบับหายไปหนึ่งฉบับโดยไม่มีอะไรเตือน ⇒ ท่าเดียวกับซองคำเน้นใน `nuxt.config.ts`
 * ⛔ **บทที่ซองเดิมไม่มี ⇒ ตาย** ⇒ หน้าเล่มกับสารบัญสร้างจากรายชื่อบทของซองเดิม ⇒ บทนอกรายชื่อจะไม่มีใครเห็น
 *   ⇒ ตัวพ่นตรวจข้อนี้แล้ว (ข้อ ⑤) ⇒ ที่นี่ตรวจซ้ำเพราะเป็นที่ที่ของถูกใช้จริง
 */
export function แกะซองรวมฉบับเพิ่ม(ทางซอง, ทางฉบับเพิ่ม) {
  const ซอง = แกะซองเนื้อบท(ทางซอง)
  if (!existsSync(ทางฉบับเพิ่ม)) {
    throw new Error(
      `⛔ ไม่มีซองฉบับเพิ่มที่ ${ทางฉบับเพิ่ม}\n` +
        '   ⇒ ดึง zip ด้วย git -c lfs.fetchexclude= lfs pull -I "source/eng-kjv2006_usfx.zip"' +
        ' แล้วสั่ง py -3.14 tools/สร้างฉบับเพิ่ม.py',
    )
  }
  const เพิ่ม = แกะซองเนื้อบท(ทางฉบับเพิ่ม)
  const ซ้ำ = เพิ่ม.ชั้น.filter((ช) => ซอง.ชั้น.includes(ช))
  if (ซ้ำ.length) throw new Error(`⛔ ฉบับเพิ่ม [${ซ้ำ.join(' ')}] มีอยู่แล้วในซองเดิม ⇒ ฉบับเดียวมาจากสองที่ไม่ได้`)
  for (const [บท, ชั้น] of Object.entries(เพิ่ม.บท)) {
    if (!ซอง.บท[บท]) throw new Error(`⛔ ฉบับเพิ่มมีบท ${บท} ที่ซองเดิม ⛔ ไม่มี ⇒ สั่ง py -3.14 tools/สร้างฉบับเพิ่ม.py ใหม่`)
    Object.assign(ซอง.บท[บท], ชั้น)
  }
  ซอง.ชั้น = [...ซอง.ชั้น, ...เพิ่ม.ชั้น]
  ซอง.แหล่งของชั้น = { ...ซอง.แหล่งของชั้น, ...เพิ่ม.แหล่งของชั้น }
  // ⭐ ข้อสุดท้ายของแต่ละบท = เลขสูงสุดของทุกฉบับรวมกัน ⇒ กติกาเดียวกับ `tools/สร้างเนื้อบท.py`
  for (const เล่ม of ซอง.บัญชี.เล่ม) {
    เล่ม.ข้อสุดท้าย = เล่ม.บทที่มี.map((บท, i) =>
      Math.max(เล่ม.ข้อสุดท้าย[i], ...Object.values(ซอง.บท[`${เล่ม.รหัส}/${บท}`] || {}).flatMap((ข) => Object.keys(ข).map(Number))),
    )
  }
  return ซอง
}
