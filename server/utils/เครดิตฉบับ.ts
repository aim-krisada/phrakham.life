// เครดิตของแต่ละแหล่ง ⇒ ข้อความที่แชร์ข้อพระคัมภีร์ต้องพกไปด้วย (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/139 ข้อ 6)
//
// ⭐⭐ **เจ้าของถ้อยคำคือหน้าเว็บ `content/แหล่งข้อมูล.md`** ⇒ บรรทัด `สัญญา` บรรทัด `เครดิต` และกล่อง `เครดิตฉบับเต็ม`
//   ⇒ ⛔ ไม่คัดประโยคเครดิตมาเขียนไว้ที่นี่ ⇒ คัดแล้วหน้าเว็บแก้ สำเนาจะค้างทันที
//   ⇒ หลักเดียวกับ `อ่านเครดิต()` ใน `tools/สร้างข้อมูลเว็บ.py` ⇒ ตัวนั้นทวงว่าทุกชั้นที่สร้างมีเครดิตบนหน้า
//   ⇒ ⛔⛔ เจ้าของกฎว่าฉบับไหนบังคับอะไรคือ `docs/บันทึก-แหล่งข้อมูล.md` หัวข้อ ② ⇒ ⛔ ย่อประโยคเครดิตที่นี่
// ⭐ **อ่านผ่านคลังของ Nuxt Content ตัวเดียวกับที่วาดหน้าแหล่งข้อมูล** ⇒ ⛔ ไม่เปิดไฟล์เอง
//   ⇒ ได้ต้นไม้ของหน้าที่แกะแล้ว (minimark) ⇒ ไล่หัวข้อ `h3` กับรายการใต้มัน ⇒ ตัวหนังสือที่ได้คือตัวที่ผู้อ่านเห็นบนหน้านั้น
// ⭐ ผลไปเป็นไฟล์นิ่ง `api/credits.json` ตอนสร้างเว็บ ⇒ หน้าอ่านหยิบเมื่อผู้อ่านเริ่มเลือกข้อเท่านั้น

export interface เครดิตแหล่ง {
  /** ชื่อแหล่งตรงตัวตามหัวข้อบนหน้า ⇒ ตรงกับ `แหล่งของชั้น` ของฉบับ */
  ชื่อ: string
  /** ชื่อสัญญาที่ผู้อ่านเห็น เช่น `CC BY-SA 4.0` หรือ `สาธารณสมบัติ` */
  สัญญา: string
  /** ลิงก์ตัวสัญญา ⇒ ว่าง = สัญญานั้นไม่มีลิงก์บนหน้า */
  ลิงก์สัญญา: string
  /** ถ้อยคำเครดิตที่เจ้าของบังคับ ⇒ ตัวหนังสือล้วน ขึ้นบรรทัดตามกล่องเครดิตฉบับเต็ม ⇒ ว่าง = เจ้าของไม่บังคับ */
  เครดิต: string
}

/** ชิ้นของต้นไม้ minimark ⇒ ตัวหนังสือ หรือ `[ป้าย, คุณสมบัติ, ...ลูก]` */
type ชิ้น = string | [string, Record<string, unknown>, ...ชิ้น[]]

function ลูกของ(ช: ชิ้น): ชิ้น[] {
  return typeof ช === 'string' ? [] : (ช.slice(2) as ชิ้น[])
}

/** ตัวหนังสือของชิ้น ⇒ `<br>` เป็นขึ้นบรรทัด ⇒ ป้ายอื่นเหลือแต่ตัวหนังสือข้างใน */
export function ตัวหนังสือ(ช: ชิ้น): string {
  if (typeof ช === 'string') return ช
  if (ช[0] === 'br') return '\n'
  return ลูกของ(ช).map(ตัวหนังสือ).join('')
}

function เก็บกวาด(s: string) {
  return s
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n[ \t]+/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

/** แกะต้นไม้ของหน้าแหล่งข้อมูล ⇒ 1 หัวข้อ `h3` = 1 แหล่ง ⇒ รายการ `li` ใต้หัวข้อคือบรรทัดของแหล่งนั้น */
export function แกะเครดิต(ต้นไม้: ชิ้น[]): Record<string, เครดิตแหล่ง> {
  const ได้: Record<string, เครดิตแหล่ง> = {}
  let ตัวนี้: เครดิตแหล่ง | null = null
  for (const ช of ต้นไม้) {
    if (typeof ช === 'string') continue
    const ป้าย = ช[0]
    if (ป้าย === 'h3') {
      // ⭐ ชื่อแหล่งคือลิงก์ในหัวข้อ ⇒ หมุด `<a id>` ที่ว่างอยู่หน้าชื่อให้ตัวหนังสือว่าง ⇒ ⛔ ไม่ปน
      const ชื่อ = ตัวหนังสือ(ช).trim()
      ตัวนี้ = { ชื่อ, สัญญา: '', ลิงก์สัญญา: '', เครดิต: '' }
      ได้[ชื่อ] = ตัวนี้
      continue
    }
    if (/^h[1-3]$/.test(ป้าย)) {
      ตัวนี้ = null
      continue
    }
    if (!ตัวนี้ || ป้าย !== 'ul') continue
    for (const li of ลูกของ(ช)) {
      if (typeof li === 'string' || li[0] !== 'li') continue
      const ข้างใน = ลูกของ(li)
      const ข้อความ = ตัวหนังสือ(li)
      const กล่อง = ข้างใน.find((x) => typeof x !== 'string' && x[0] === 'details') as ชิ้น | undefined
      if (ข้อความ.trimStart().startsWith('สัญญา ')) {
        // ⭐ ลิงก์สัญญาต้องติดคำว่า *สัญญา* ⇒ ลิงก์ท่อน *ที่มา* ท้ายบรรทัด ⛔ ไม่ใช่สัญญา (World English Bible ไม่มีลิงก์สัญญา)
        const ลิงก์ = (typeof ข้างใน[0] === 'string' && ข้างใน[0].trim() === 'สัญญา' && typeof ข้างใน[1] !== 'string' && ข้างใน[1]?.[0] === 'a'
          ? ข้างใน[1]
          : undefined) as [string, Record<string, unknown>] | undefined
        if (ลิงก์) {
          ตัวนี้.สัญญา = ตัวหนังสือ(ลิงก์ as ชิ้น).trim()
          ตัวนี้.ลิงก์สัญญา = String(ลิงก์[1].href || '')
        } else {
          // ⭐ สัญญาที่ไม่มีลิงก์ ⇒ คำแรกหลัง *สัญญา* เช่น `สาธารณสมบัติ` ⇒ ท่อนหลังคือเจ้าของกับที่มา ⛔ ไม่ใช่ชื่อสัญญา
          ตัวนี้.สัญญา = ข้อความ.trim().slice('สัญญา '.length).split(/\s/)[0] || ''
        }
      } else if (ข้อความ.trimStart().startsWith('เครดิต ') && !กล่อง) {
        ตัวนี้.เครดิต = เก็บกวาด(ข้อความ.trim().slice('เครดิต '.length))
      } else if (กล่อง) {
        const หัว = ลูกของ(กล่อง).find((x) => typeof x !== 'string' && x[0] === 'summary')
        if (หัว && ตัวหนังสือ(หัว).trim() === 'เครดิตฉบับเต็ม') {
          ตัวนี้.เครดิต = เก็บกวาด(ลูกของ(กล่อง).filter((x) => x !== หัว).map(ตัวหนังสือ).join(''))
        }
      }
    }
  }
  return ได้
}
