import { readFileSync } from 'node:fs'

// ⭐⭐ **รุ่น 2 ของรายการ ⇒ เสียงมีหลายฉบับ** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/132)
//   ⇒ เล่มหนึ่งได้ดัชนีแยกต่อฉบับ ⇒ หน้าอ่านเลือกตามฉบับของคอลัมน์ที่อ่าน ⇒ ⛔ ไม่มีฉบับไหนเป็นค่าสำรองของฉบับอื่น
//   ⇒ ฉบับที่ไม่มีเสียงของเล่มนี้ ⇒ ⛔ ไม่มีกุญแจ ⇒ หน้าบอกผู้อ่านตรง ๆ ว่าฉบับนั้นยังไม่มีเสียง (ข้อ 11.3)
interface เสียงของฉบับ {
  ทางย่อย: string
  เล่ม: Record<string, { osis: string; บท: Record<string, Record<string, number>> }>
}
export interface รายการเสียง {
  รุ่น: number
  ฐานที่อยู่: string
  /** ⭐ เสียงบน GitHub Pages (ใบ #171) ⇒ ฉบับ ⇒ รหัสเล่ม ⇒ ฐานเต็ม `https://…/` ของที่เก็บของฉบับกับเล่มนั้น
   *  ⇒ ที่เก็บแยกตามฉบับ ⇒ ไฟล์อยู่ที่รากของที่เก็บ ⇒ ⛔ ไม่ต่อ `ทางย่อย`
   *  ⇒ ⛔ ไม่มีกุญแจนี้ = ยังไม่ย้าย ⇒ ทุกฉบับใช้ `ฐานที่อยู่` + `ทางย่อย` (`audio/LSV/`) ⇒ ผังอยู่ที่ `เสียง/ที่เก็บบนGitHub.tsv` */
  ฐานของฉบับ?: Record<string, Record<string, string>>
  ฉบับ: Record<string, เสียงของฉบับ>
}

export interface ดัชนีเสียง {
  /** รูปที่อยู่ของไฟล์ ⇒ `{บท}` `{ข้อ}` ถูกแทนด้วยเลขจริง ⇒ ยังไม่ต่อฐานของเว็บ */
  ไฟล์: string
  /** บทที่มีเสียง ⇒ ข้อสุดท้ายที่มีเสียง */
  บท: Record<string, number>
  /** ข้อที่อยู่ระหว่าง 1 กับข้อสุดท้าย แต่ ⛔ ไม่มีเสียง ⇒ ตัวเล่นข้ามไป */
  ข้าม: Record<string, number[]>
}

let คลัง: รายการเสียง | null | undefined

function เปิดรายการ(): รายการเสียง | null {
  if (คลัง !== undefined) return คลัง
  const ทาง = useRuntimeConfig().ทางรายการเสียง as string
  try {
    คลัง = JSON.parse(readFileSync(ทาง, 'utf8')) as รายการเสียง
  } catch {
    // ⭐ **ไม่มีรายการ ⇒ เตือนแล้วไปต่อ ⛔ ไม่ล้ม** ⇒ ท่าเดียวกับซองคำพระเยซูใน `เนื้อบท.ts`
    //   ⇒ คนที่เพิ่งโคลนที่เก็บแล้วสั่ง `npm run dev` ต้องอ่านพระคัมภีร์ได้ ⇒ ขาดแค่ปุ่มเล่น
    //   ⛔ **ในท่อ CI ขาดไม่ได้** ⇒ `สร้างเว็บ` รอ `พ่นรายการเสียง` และ
    //     `tools/ด่านฟังพระคำบนหน้า.mjs` กดเล่นจริงที่มาระโก ⇒ ไม่มีปุ่ม = แดง
    console.warn('⚠️ ไม่มีรายการเสียง ⇒ หน้าอ่านจะไม่มีปุ่มเล่น ⇒ สั่ง py -3.14 tools/สร้างรายการเสียง.py ก่อน')
    คลัง = null
  }
  return คลัง
}

/** ดัชนีเสียงของเล่มนี้ แยกตามฉบับ ⇒ ⛔ ไม่มีฉบับไหนมีเสียงเลย = `undefined` ⇒ กุญแจหายไปจากข้อมูลประจำเล่ม */
export function ดัชนีเสียงของเล่ม(รหัสเล่ม: string): Record<string, ดัชนีเสียง> | undefined {
  const ร = เปิดรายการ()
  if (!ร) return undefined
  return ดัชนีเสียงจากรายการ(ร, รหัสเล่ม)
}

/**
 * ⭐⭐ **ตัวสร้างที่อยู่ไฟล์ฝั่งหน้าเว็บ** ⇒ ของล้วน ⛔ ไม่อ่านไฟล์ ⛔ ไม่แตะค่าตั้งของเว็บ ⇒ `tools/ด่านที่อยู่ไฟล์เสียง.mjs` เรียกตรงได้
 *
 * ⇒ ยังไม่ย้าย ⇒ `ฐานที่อยู่` (`audio/`) + `ทางย่อย` ของฉบับ (`LSV/`) ⇒ ตรงกับโฟลเดอร์ใน `เสียง/ข้อ/`
 * ⇒ ย้ายแล้ว ⇒ `ฐานของฉบับ[ฉบับ][เล่ม]` ⇒ ที่เก็บของฉบับนั้นเอง ⇒ ⛔ ไม่ต่อ `ทางย่อย` เพราะชื่อที่เก็บบอกฉบับแล้ว
 * ⇒ ฐานเต็ม `https://` ⛔ ห้ามถูกต่อฐานของเว็บซ้ำ ⇒ คนกันคือ `ต่อที่อยู่ไฟล์เสียง` ใน `app/utils/คิวเสียง.ts`
 * ⛔ มี `ฐานของฉบับ` แต่ไม่มีฐานของฉบับกับเล่มที่มีเสียง ⇒ ล้ม ⛔ ไม่หล่นกลับไปใช้ `audio/` ⇒ ตัวพ่นรายการกันไว้แล้ว ⇒ มาถึงนี่ได้แปลว่ารายการถูกแก้มือ
 */
export function ดัชนีเสียงจากรายการ(ร: รายการเสียง, รหัสเล่ม: string): Record<string, ดัชนีเสียง> | undefined {
  // ⛔ **รายการรุ่นเก่า ⇒ ล้มตรงนี้** ⇒ อ่านผิดรูปแล้วได้ปุ่มที่เล่นเสียงผิดฉบับ แย่กว่าไม่มีปุ่ม
  if (ร.รุ่น !== 2) throw new Error(`⛔ รายการเสียงรุ่น ${ร.รุ่น} ⇒ ต้องเป็นรุ่น 2 ⇒ สั่ง py -3.14 tools/สร้างรายการเสียง.py ใหม่`)
  const ผล: Record<string, ดัชนีเสียง> = {}
  for (const [ฉบับ, ของฉบับ] of Object.entries(ร.ฉบับ)) {
    const ของเล่ม = ของฉบับ.เล่ม[รหัสเล่ม]
    if (!ของเล่ม) continue
    let ฐาน = ร.ฐานที่อยู่ + ของฉบับ.ทางย่อย
    if (ร.ฐานของฉบับ) {
      const ของนี้ = ร.ฐานของฉบับ[ฉบับ]?.[รหัสเล่ม]
      if (!ของนี้) throw new Error(`⛔ รายการเสียงมี ฐานของฉบับ แต่ไม่มี ${ฉบับ} เล่ม ${รหัสเล่ม} ⇒ สั่ง py -3.14 tools/สร้างรายการเสียง.py ใหม่`)
      ฐาน = ของนี้
    }
    const ด = ดัชนีของฉบับ(ฐาน, ของเล่ม)
    if (ด) ผล[ฉบับ] = ด
  }
  return Object.keys(ผล).length ? ผล : undefined
}

function ดัชนีของฉบับ(
  ฐาน: string,
  ของเล่ม: { osis: string; บท: Record<string, Record<string, number>> } | undefined,
): ดัชนีเสียง | undefined {
  if (!ของเล่ม) return undefined
  const บท: Record<string, number> = {}
  const ข้าม: Record<string, number[]> = {}
  for (const [c, ข้อ] of Object.entries(ของเล่ม.บท)) {
    const มี = new Set(Object.keys(ข้อ).map(Number))
    if (!มี.size) continue
    const ท้าย = Math.max(...มี)
    บท[c] = ท้าย
    // ⭐ **นับจากรายการเอง ⛔ ไม่พิมพ์รายชื่อ** ⇒ ข้อที่ขาดคือข้อที่ TCV ไม่มีตัวบท เช่น มาระโก 7:16
    const ขาด: number[] = []
    for (let v = 1; v < ท้าย; v++) if (!มี.has(v)) ขาด.push(v)
    if (ขาด.length) ข้าม[c] = ขาด
  }
  return { ไฟล์: `${ฐาน}${ของเล่ม.osis}.{บท}.{ข้อ}.puck.mp3`, บท, ข้าม }
}
