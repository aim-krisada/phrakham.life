const หัวเชิงอรรถ = /^เชิงอรรถ/
const รอยเลขเชิงอรรถ = /\[\^([^\]\s]+)\]/g
const รอยนิยามเชิงอรรถ = /^\[\^([^\]\s]+)\]:[ \t]*/gm

/** แกะหัวข้อเชิงอรรถ ⇒ คืนเชิงอรรถเรียงตามที่ถูกอ้างครั้งแรก ⇒ ⛔ ไม่คู่กัน = โยนข้อผิดพลาด */
export function แกะเชิงอรรถ(ไฟล์: string, ส่วนเรื่อง: string, หัวข้อทั้งหมด: string[]): ตัวเรื่องเล่า['เชิงอรรถ'] {
  const พัง = (ข้อ: string) => {
    throw new Error(`⛔ เรื่องเล่า ${ไฟล์} ⇒ ${ข้อ}\n   ⇒ ดู tools/ด่านเรื่องเล่าอนุมัติ.py ข้อ ⑧ (ใบ #168)`)
  }
  if (new RegExp(รอยนิยามเชิงอรรถ.source, 'm').test(ส่วนเรื่อง)) พัง('มีนิยามเชิงอรรถ [^…]: อยู่ในตัวเรื่อง ⇒ จะขึ้นจอและถูกอ่านออกเสียง')
  const ที่อ้าง = [...new Set([...ส่วนเรื่อง.matchAll(รอยเลขเชิงอรรถ)].map((m) => m[1]!))]
  const ส่วน = หัวข้อทั้งหมด.filter((x) => หัวเชิงอรรถ.test(x))
  if (ส่วน.length > 1) พัง('มีหัวข้อเชิงอรรถมากกว่า 1 หัวข้อ')
  const นิยาม = new Map<string, string>()
  if (ส่วน.length) {
    const เนื้อ = ส่วน[0]!.slice(ส่วน[0]!.indexOf('\n') + 1)
    const ชิ้น = เนื้อ.split(new RegExp(`(?=${รอยนิยามเชิงอรรถ.source})`, 'm'))
    if (ชิ้น[0]!.trim() && !new RegExp(`^${รอยนิยามเชิงอรรถ.source}`).test(ชิ้น[0]!)) พัง('หัวข้อเชิงอรรถมีข้อความที่ไม่ใช่เชิงอรรถ')
    for (const ช of ชิ้น) {
      const m = new RegExp(`^${รอยนิยามเชิงอรรถ.source}`).exec(ช)
      if (!m) continue
      if (นิยาม.has(m[1]!)) พัง(`เชิงอรรถ [^${m[1]}] ถูกนิยามซ้ำ`)
      const ข้อความ = ช.slice(m[0].length).replace(/\s+/g, ' ').trim()
      if (!ข้อความ) พัง(`เชิงอรรถ [^${m[1]}] ว่าง`)
      นิยาม.set(m[1]!, ข้อความ)
    }
  }
  for (const ป้าย of ที่อ้าง) if (!นิยาม.has(ป้าย)) พัง(`เลข [^${ป้าย}] ในตัวเรื่องไม่มีเชิงอรรถคู่`)
  for (const ป้าย of นิยาม.keys()) if (!ที่อ้าง.includes(ป้าย)) พัง(`เชิงอรรถ [^${ป้าย}] ไม่ถูกอ้างในตัวเรื่อง`)
  return ที่อ้าง.map((ป้าย) => ({ ป้าย, ข้อความ: นิยาม.get(ป้าย)! }))
}
// ⭐ ที่อยู่ของไฟล์เสียงบนเว็บ ⇒ ตัวเชื่อมกับโฟลเดอร์จริงคือ `nitro.publicAssets` ใน `nuxt.config.ts`
