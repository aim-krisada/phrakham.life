function blob(ไบต์: Buffer): string {
  return createHash('sha1')
    .update(Buffer.concat([Buffer.from(`blob ${ไบต์.length}\0`), ไบต์]))
    .digest('hex')
}

function แกะรหัส(รหัส: string): { เล่ม: string; จาก: ตำแหน่ง; ถึง: ตำแหน่ง } {
  const m = /^([0-9A-Z]{3})\.(\d+)\.(\d+)-(\d+)\.(\d+)$/.exec(รหัส)
  if (!m) throw new Error(`⛔ รหัสเรื่องเล่า "${รหัส}" อ่านไม่ออก ⇒ ต้องเป็น <เล่ม>.<บท>.<ข้อ>-<บท>.<ข้อ>`)
  return {
    เล่ม: m[1]!,
    จาก: { บท: Number(m[2]), ข้อ: Number(m[3]) },
    ถึง: { บท: Number(m[4]), ข้อ: Number(m[5]) },
  }
}

function เปิดคลัง(): ตัวเรื่องเล่า[] {
  if (คลัง) return คลัง
  const ตั้งค่า = useRuntimeConfig()
  const โฟลเดอร์ = ตั้งค่า.ทางกองเรื่องเล่า as string
  const โฟลเดอร์เสียง = ตั้งค่า.ทางกองเสียงเรื่องเล่า as string
  const บรรทัด = readFileSync(join(โฟลเดอร์, 'ทะเบียน.tsv'), 'utf8')
    .replace(/\r\n/g, '\n')
    .split('\n')
    .filter((x) => x && !x.startsWith('#'))
  const หัว = บรรทัด[0]!.split('\t')
  const ผล: ตัวเรื่องเล่า[] = []
  for (const แถวดิบ of บรรทัด.slice(1)) {
    const ร = Object.fromEntries(แถวดิบ.split('\t').map((ค่า, i) => [หัว[i]!, ค่า])) as Record<string, string>
    const ไบต์ = readFileSync(join(โฟลเดอร์, ร['ไฟล์']!))
    if (blob(ไบต์) !== ร['blob']) {
      throw new Error(
        `⛔ เรื่องเล่า ${ร['ไฟล์']} ไม่ใช่ไบต์ที่อนุมัติ (blob ไม่ตรง เรื่องเล่า/ทะเบียน.tsv)\n` +
          '   ⇒ เรื่องเล่าขึ้นเว็บได้เฉพาะฉบับที่พี่เอมอนุมัติ ⇒ ดู tools/ด่านเรื่องเล่าอนุมัติ.py',
      )
    }
    const เนื้อ = ไบต์.toString('utf8')
    const ที่ = เนื้อ.indexOf(หัวเรื่องนำ)
    if (ที่ < 0) throw new Error(`⛔ ${ร['ไฟล์']} ไม่มีหัวข้อ ${หัวเรื่องนำ}`)
    // ⭐ ใบ #177 ⇒ ชื่อเรื่องคือบรรทัด `ชื่อ:` ก่อนหัวข้อเรื่องเล่า ⇒ ⛔ ไม่มี = ตายพร้อมบอกไฟล์ ⛔ ไม่เดาชื่อให้
    const ชื่อ = /^ชื่อ:[ \t]*(.+?)[ \t]*$/m.exec(เนื้อ.slice(0, ที่))?.[1]
    if (!ชื่อ) throw new Error(`⛔ ${ร['ไฟล์']} ไม่มีบรรทัด "ชื่อ:" ที่หัวไฟล์ ⇒ หน้าเล่าประสบการณ์ไม่มีชื่อเรื่องให้แสดง (ใบ #177)`)
    const [ส่วนดิบ, ...หัวข้อถัดไป] = เนื้อ.slice(ที่ + หัวเรื่องนำ.length).split(/^## /m)
    const ส่วน = ส่วนดิบ!.trim()
    const เชิงอรรถ = แกะเชิงอรรถ(ร['ไฟล์']!, ส่วน, หัวข้อถัดไป)
    const ช = แกะรหัส(ร['รหัส']!)
    const ทางคู่ = join(โฟลเดอร์เสียง, `${ร['รหัส']}.puck.json`)
    let เสียง: ตัวเรื่องเล่า['เสียง'] = null
    if (existsSync(ทางคู่)) {
      const คู่ = JSON.parse(readFileSync(ทางคู่, 'utf8'))
      เสียง = { ไฟล์: `${ฐานที่อยู่เสียง}${คู่.ไฟล์เสียง}`, วินาที: คู่.รวมวินาที, รุ่น: คู่.รุ่น, เสียง: คู่.เสียง }
    } else {
      console.warn(`⚠️ เรื่องเล่า ${ร['รหัส']} ยังไม่มีเสียง ⇒ หน้าอ่านจะมีแต่ตัวหนังสือ`)
    }
    ผล.push({
      รหัส: ร['รหัส']!,
      จาก: ช.จาก,
      ถึง: ช.ถึง,
      ชื่อเล่ม: ร['ชื่อเล่ม']!,
      ชื่อ,
      ย่อหน้า: ส่วน.split(/\n\s*\n/).map((x) => x.replace(/\s+/g, ' ').trim()).filter(Boolean),
      เชิงอรรถ,
      อนุมัติเมื่อ: ร['อนุมัติเมื่อ']!,
      เสียง,
    })
  }
  คลัง = ผล
  return ผล
}

/** ดัชนีของเล่ม ⇒ เล่มที่ไม่มีเรื่องเล่าได้ `undefined` ⇒ กุญแจหายจากไฟล์ ⇒ จ่าย 0 ไบต์ */
export function ดัชนีเรื่องเล่าของเล่ม(รหัสเล่ม: string): ดัชนีเรื่องเล่า[] | undefined {
  const ของเล่ม = เปิดคลัง()
    .filter((x) => x.รหัส.startsWith(`${รหัสเล่ม}.`))
    .map(({ รหัส, จาก, ถึง }) => ({ รหัส, จาก, ถึง }))
  return ของเล่ม.length ? ของเล่ม : undefined
}

/** ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/177 ⇒ รายชื่อเรื่องทั้งทะเบียนสำหรับหน้าเล่าประสบการณ์
 *  ⇒ รหัส ช่วง ชื่อ วันอนุมัติ ⇒ ⛔ ไม่มีตัวหนังสือของเรื่อง ⛔ ไม่มีเสียง ⇒ ตัวเรื่องยังขอผ่าน `/api/story/<รหัส>.json` ทางเดียว
 *  ⇒ เรียงตามลำดับในทะเบียน ⇒ หน้ารวมจัดกลุ่มและเรียงเอง */
export function รายการเรื่องเล่า() {
  return เปิดคลัง().map(({ รหัส, จาก, ถึง, ชื่อเล่ม, ชื่อ, อนุมัติเมื่อ }) => ({ รหัส, จาก, ถึง, ชื่อเล่ม, ชื่อ, อนุมัติเมื่อ }))
}

export function อ่านเรื่องเล่า(รหัส: string): ตัวเรื่องเล่า | null {
  return เปิดคลัง().find((x) => x.รหัส === รหัส) || null
}
