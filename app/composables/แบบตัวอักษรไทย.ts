//   ⇒ ป้ายบน `<html>` ถูกใส่ก่อนหน้าจอวาดแล้ว (`สคริปต์ใส่ป้ายก่อนวาด`) ⇒ ที่นี่แค่อ่านป้ายมาแสดงบนปุ่ม แล้วเปลี่ยนเมื่อผู้อ่านกด
//   ⇒ กติกา ค่าเริ่มต้น กับชื่อกุญแจ ⇒ เจ้าของคือ `app/utils/แบบตัวอักษรไทย.ts` ⛔ ไม่จดซ้ำที่นี่
import { กุญแจแบบตัวอักษร, แบบตั้งต้น, type แบบตัวอักษร } from '~/utils/แบบตัวอักษรไทย'

// ⛔ ตอนสร้างหน้าล่วงหน้าเป็นค่าเริ่มต้นเสมอ ⇒ เปลี่ยนเฉพาะในเบราว์เซอร์ (`onMounted`) ⇒ ⛔ หน้ากะพริบหรือวาดไม่ตรงกัน
const แบบ = ref<แบบตัวอักษร>(แบบตั้งต้น)

export function ใช้แบบตัวอักษรไทย() {
  onMounted(() => {
    แบบ.value = document.documentElement.getAttribute('data-font') === 'loopless' ? 'loopless' : 'looped'
  })

  function เลือก(ค่า: แบบตัวอักษร) {
    แบบ.value = ค่า
    // ⭐ เปลี่ยนป้ายทันที ⇒ ตัวอักษรทั้งหน้าเปลี่ยนตามโดยไม่ต้องโหลดหน้าใหม่ (เกณฑ์ข้อ 4)
    if (ค่า === 'loopless') document.documentElement.setAttribute('data-font', 'loopless')
    else document.documentElement.removeAttribute('data-font')
    // ⛔ เครื่องที่จำค่าไม่ได้ ⇒ หน้านี้ยังเปลี่ยนให้ แค่ไม่ติดไปหน้าถัดไป ⇒ ⛔ ไม่ล้ม (เกณฑ์ข้อ 8)
    try {
      if (ค่า === แบบตั้งต้น) localStorage.removeItem(กุญแจแบบตัวอักษร)
      else localStorage.setItem(กุญแจแบบตัวอักษร, ค่า)
    } catch {
      /* หน้าต่างส่วนตัว ⇒ ปล่อยผ่าน */
    }
  }

  return { แบบ, เลือก }
}
