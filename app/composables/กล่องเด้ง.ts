/** เส้นเดียวกับ `@media (min-width: 768px)` ของทั้งเว็บ ⇒ แคบกว่านี้ = หน้าเต็มจอ */
export const เส้นจอกว้าง = 768

/** ⭐ ตัววัดตัวเดียวของทั้งหน้า ⇒ หลายกล่องขอพร้อมกันได้ ⇒ นับคนขอ ⇒ ไม่มีใครขอแล้วถอดตัวดักทิ้ง */
let คนขอ = 0
let ถอด: (() => void) | null = null

function วัดขอบ() {
  const แถบ = document.querySelector<HTMLElement>('.pk-แถบบน')
  if (!แถบ) return
  const ล่าง = Math.max(0, แถบ.getBoundingClientRect().bottom)
  document.documentElement.style.setProperty('--pk-ใต้แถบบน', `${ล่าง}px`)
}

function เริ่มวัด() {
  คนขอ++
  if (ถอด) return void วัดขอบ()
  let รอเฟรม = 0
  const วัดในเฟรมหน้า = () => {
    if (รอเฟรม) return
    รอเฟรม = requestAnimationFrame(() => {
      รอเฟรม = 0
      วัดขอบ()
    })
  }
  วัดขอบ()
  const แถบ = document.querySelector<HTMLElement>('.pk-แถบบน')
  const ตัวเฝ้า = typeof ResizeObserver !== 'undefined' && แถบ ? new ResizeObserver(วัดในเฟรมหน้า) : null
  if (ตัวเฝ้า && แถบ) ตัวเฝ้า.observe(แถบ)
  window.addEventListener('resize', วัดในเฟรมหน้า)
  window.addEventListener('scroll', วัดในเฟรมหน้า, { passive: true })
  ถอด = () => {
    ตัวเฝ้า?.disconnect()
    window.removeEventListener('resize', วัดในเฟรมหน้า)
    window.removeEventListener('scroll', วัดในเฟรมหน้า)
    cancelAnimationFrame(รอเฟรม)
  }
}

function เลิกวัด() {
  คนขอ = Math.max(0, คนขอ - 1)
  if (คนขอ || !ถอด) return
  ถอด()
  ถอด = null
}

/**
 * ⭐ ใช้ในชิ้นที่มีกล่องเด้ง ⇒ ส่งตัวบอกว่ากล่องเปิดอยู่ไหม
 *   ⇒ คืน `จอแคบ` (แคบกว่า 768 ⇒ กล่องเป็นหน้าเต็มจอ) ⇒ เปลี่ยนตามจอจริงตอนหมุนจอหรือกางจอพับ
 *   ⇒ ระหว่างเปิด ⇒ วัดขอบล่างของแถบบนให้ CSS ตลอด
 */
export function ใช้กล่องเด้ง(เปิด: () => boolean) {
  const จอแคบ = ref(false)
  let ตัววัดจอ: MediaQueryList | null = null
  const ตามจอ = () => (จอแคบ.value = !!ตัววัดจอ && !ตัววัดจอ.matches)
  let ขออยู่ = false
  const ตาม = (ค่า: boolean) => {
    if (ค่า && !ขออยู่) {
      ขออยู่ = true
      เริ่มวัด()
    } else if (!ค่า && ขออยู่) {
      ขออยู่ = false
      เลิกวัด()
    }
  }
  onMounted(() => {
    ตัววัดจอ = matchMedia(`(min-width: ${เส้นจอกว้าง}px)`)
    ตามจอ()
    ตัววัดจอ.addEventListener('change', ตามจอ)
    watch(เปิด, ตาม, { immediate: true, flush: 'post' })
  })
  onBeforeUnmount(() => {
    ตัววัดจอ?.removeEventListener('change', ตามจอ)
    ตาม(false)
  })
  return { จอแคบ }
}
