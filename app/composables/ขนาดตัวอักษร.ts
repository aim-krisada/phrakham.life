import { ขั้นขนาดตัวอักษร } from '~/utils/ขั้นขนาดตัวอักษร'

interface ตัวคุมขนาด {
  pct(): number
  canInc(): boolean
  canDec(): boolean
  inc(): number
  dec(): number
  onChange(fn: (scale: number, pct: number) => void): () => void
}

// ⭐⭐ **ค่าเดียวทั้งเว็บ ⇒ ตัวคุมตัวเดียวทั้งหน้า** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/173 เกณฑ์ข้อ 4)
//   ⇒ ปุ่ม Aa อยู่บนแถบบนทุกหน้าแล้ว ⇒ หน้าอ่านยังอ่านเปอร์เซ็นต์ไปจัดแถวคำของมันเอง ⇒ **2 ที่บนหน้าเดียวกันต้องเห็นเลขเดียวกัน**
//   ⇒ ⛔ ของเดิมสร้างตัวคุมใหม่ทุกครั้งที่เรียก ⇒ ตัวคุม 2 ตัวนับขั้นแยกกัน ⇒ กด ก+ ที่ตัวหนึ่ง อีกตัวยังคิดว่า 100%
//   ⇒ ⭐ ข้ามหน้า ⇒ `pk-fontsize.js` จำไว้ในเครื่อง (`pk-fs`) แล้วใส่ให้ก่อนหน้าจอวาด (`nuxt.config.ts`) ⇒ ⛔ ต้องส่งค่าเอง
//   ⇒ ⛔ ค่าใน 3 ตัวนี้เปลี่ยนเฉพาะในเบราว์เซอร์ (`onMounted`) ⇒ ตอนสร้างหน้าล่วงหน้าเป็น 100 เสมอ ⇒ ⛔ ปนกันข้ามหน้า
const เปอร์เซ็นต์ = ref(100)
const เพิ่มได้ = ref(true)
const ลดได้ = ref(true)
let ตัวคุม: ตัวคุมขนาด | null = null

function ทาน() {
  if (!ตัวคุม) return
  เปอร์เซ็นต์.value = ตัวคุม.pct()
  เพิ่มได้.value = ตัวคุม.canInc()
  ลดได้.value = ตัวคุม.canDec()
}

export function ใช้ขนาดตัวอักษร() {
  // 100 คือค่าที่หน้าเว็บถูกสร้างไว้ล่วงหน้าด้วย ⇒ ⛔ ห้ามเดาค่าอื่นตอนวาดครั้งแรก
  //   ⇒ เดาไม่ตรงกับในไฟล์ = หน้ากะพริบ และตัวสร้างจะฟ้องว่าวาดไม่ตรงกัน
  onMounted(() => {
    if (ตัวคุม) return ทาน()
    // ⛔ ห้องสมุดโหลดไม่สำเร็จ = ปุ่มไม่ทำงาน ⛔ แต่หน้าต้องยังอ่านได้ตามปกติ
    const ก = (window as unknown as { PKFontSize?: { create(o: object): ตัวคุมขนาด } }).PKFontSize
    if (!ก) return
    // ⭐ 20 พ.ย. 2569 ⇒ บันไดของเว็บนี้ (เพิ่มขั้น 75%) ⇒ ส่งผ่าน `steps` ⇒ ⛔ แก้ไฟล์ห้องสมุดที่ตรึงลายนิ้วมือไว้
    ตัวคุม = ก.create({ target: document.documentElement, steps: [...ขั้นขนาดตัวอักษร] })
    ทาน()
  })

  return {
    เปอร์เซ็นต์,
    เพิ่มได้,
    ลดได้,
    ใหญ่ขึ้น: () => {
      ตัวคุม?.inc()
      ทาน()
    },
    เล็กลง: () => {
      ตัวคุม?.dec()
      ทาน()
    },
  }
}
