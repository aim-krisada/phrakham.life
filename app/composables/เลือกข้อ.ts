//   ⇒ ตัวบทของข้อในแต่ละคอลัมน์เป็น `role="button"` + `aria-pressed` (ป้าย `data-เลือกข้อ`) ⇒ โปรแกรมอ่านหน้าจอบอกได้ว่าข้อไหนถูกเลือก ⇒ WCAG 2.2 SC 4.1.2 (ระดับ A)
//     ⇒ ⛔ ไม่ครอบหัวข้อย่อย ⇒ เหตุผลอยู่ที่ `เส้นใต้ของข้อ`
//   ⇒ **จุดหยุด Tab มีจุดเดียวทั้งตัวบท** (roving tabindex ⇒ WAI-ARIA APG) ⇒ ⛔ ไม่ใช่ 1 จุดต่อ 1 ข้อ ⇒ คนใช้แป้นพิมพ์ไม่ต้องกด Tab ผ่านทีละข้อ
//     ⇒ ลูกศรขึ้นลง (หรือซ้ายขวา) ⇒ ไปข้อก่อนหรือข้อถัดไปในคอลัมน์เดิม ⇒ Enter หรือ Space ⇒ เลือกหรือเลิกเลือก
//   ⇒ ⛔ ไม่ซ้อนปุ่มในปุ่ม ⇒ ในข้อมีแค่เลขข้อกับตัวหนังสือ ⇒ คำเดิมใต้แถวอยู่นอกกล่องของข้อ
// ⭐⭐ **ข้อที่เลือกเป็นของคอลัมน์ที่แตะ** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/148)
//   ⇒ พี่เอมเคาะ 7 พ.ย. 2569 *"a selection belongs to the column you tapped"* ⇒ แทนใบ #139 ข้อ 10 ที่เลือกเลขข้อเดียวกันทุกคอลัมน์
//   ⇒ **1 ชิ้น = ฉบับ + บท + ข้อ** ⇒ กุญแจ `ฉบับ|บท:เลข` ⇒ ข้อเลขเดียวกันในอีกคอลัมน์ = อีกชิ้นหนึ่ง ⇒ แตะซ้ำเลิกเฉพาะชิ้นนั้น
//   ⇒ `data-เลือกข้อ` ยังเป็น `บท:เลข` (ด่านและการเดินด้วยลูกศรใช้) ⇒ ฉบับอยู่ที่ `data-เลือกฉบับ` ของกล่องเดียวกัน
//   ⇒ ⭐ แบบแยกตามข้อ ⇒ แถวของข้อ ⛔ ไม่ได้เส้นใต้ทั้งแถวแล้ว ⇒ เส้นใต้อยู่ที่ช่องของฉบับที่เลือกเท่านั้น
//     ⇒ แตะในแถวแต่นอกช่องของฉบับ (เช่นเลขข้อ) ⇒ เลือกช่องแรกที่ตาเห็นในแถวนั้น ⇒ ⛔ ไม่เลือกทุกคอลัมน์
// ⭐⭐ **คอลัมน์คนละตอนเลือกได้เหมือนคอลัมน์อื่น** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/159)
//   ⇒ ⚠️ ของเดิม ⇒ กล่องของคอลัมน์คนละตอน ⛔ มีตัวดักการแตะ ⛔ มี `data-เลือกข้อ` ⇒ แตะแล้วเงียบ ⇒ คัดลอกและแชร์ข้อจากคอลัมน์นั้นไม่ได้
//   ⇒ **1 ชิ้น = ฉบับ + เล่ม + บท + ข้อ** ⇒ กุญแจ `ฉบับ|เล่ม|บท:เลข` ⇒ ⭐ เล่มเดียวกับหน้า ⇒ ⛔ เขียนเล่ม ⇒ ได้กุญแจ `ฉบับ|บท:เลข` แบบใบ #148
//     ⇒ ข้อเดียวกันของฉบับเดียวกันได้กุญแจเดียวกันไม่ว่าจะอยู่ในตารางหรือในกล่องคนละตอน ⇒ คอลัมน์ย้ายเข้าออกตารางแล้วการเลือกยังติดอยู่
//   ⇒ กล่องของข้อในคอลัมน์คนละตอนมี `data-เลือกเล่ม` (รหัสเล่มของคอลัมน์นั้นเสมอ) ⇒ ตัวนี้แปลงเป็นกุญแจเอง
//   ⇒ จุดหยุด Tab ⇒ กล่องที่เลื่อนเองของคอลัมน์คนละตอนอยู่นอกตัวบท ⇒ มีจุดหยุดของตัวเอง 1 จุด (ข้อแรกของคอลัมน์ หรือข้อที่ลูกศรพาไปล่าสุด)
//     ⇒ ⭐ บนล่างจอแคบ ข้อของมันแทรกในตัวบท ⇒ ⛔ ถือจุดหยุด ⇒ ท่าเดียวกับคอลัมน์ในตารางที่ไม่ใช่คอลัมน์ที่อ่านอยู่
// ⭐⭐ **ฉบับเดียวกันหลายคอลัมน์ ⇒ แต่ละคอลัมน์เลือกแยกกัน** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/161)
//   ⇒ ปุ่ม *เพิ่มคอลัมน์* เปิดฉบับเดียวกันได้หลายคอลัมน์ ⇒ กุญแจแบบใบ #159 ของ 2 คอลัมน์ TCV ในเล่มเดียวกันซ้ำกัน ⇒ แตะคอลัมน์หนึ่งแล้วอีกคอลัมน์ขีดเส้นใต้ด้วย
//   ⇒ ⭐ คอลัมน์ที่ 2 ขึ้นไปของฉบับเดียวกันในเล่มเดียวกันได้ *ลำดับซ้ำ* ⇒ ฉบับในกุญแจเป็น `TCV~2` (`ฉบับในกุญแจ`) ⇒ ตัวแรกได้กุญแจเดิมทุกตัวอักษร
//   ⇒ กล่องของข้อมี `data-เลือกซ้ำ` (เฉพาะ 2 ขึ้นไป) ⇒ หน้าอ่านนับให้ (`นับซ้ำ`) ⇒ ลิงก์เขียนท่อนแบบ `12.5.TCV~2` (`app/utils/ที่อยู่.ts`)
// ⛔ **ของที่เลือกอยู่ในหน่วยความจำของหน้านี้เท่านั้น** ⇒ ⛔ ไม่เก็บลงเครื่อง ⛔ ไม่ส่งไปไหน (Security measures ข้อ 1)

/** ของที่กดได้ในตัวบท ⇒ แตะแล้วของชิ้นนั้นทำงาน ⛔ ไม่เลือกข้อ */
const กดได้อยู่แล้ว = 'a, button, input, select, textarea, summary, label, [role="dialog"], .pk-ชั้นคำ, .pk-หัวข้อย่อย'

/** กุญแจของ 1 ชิ้นที่เลือก ⇒ `ฉบับ|บท:เลข` ⇒ ใบ #159 ⇒ คนละเล่มกับหน้า ⇒ `ฉบับ|เล่ม|บท:เลข` ⇒ `เล่ม` ว่าง = เล่มของหน้า */
export function กุญแจชิ้น(ฉบับ: string, ข้อ: string, เล่ม = '') {
  return เล่ม ? `${ฉบับ}|${เล่ม}|${ข้อ}` : `${ฉบับ}|${ข้อ}`
}
/** ⭐ ใบ #161 ⇒ ฉบับในกุญแจ ⇒ คอลัมน์ที่ 2 ขึ้นไปของฉบับเดียวกันในเล่มเดียวกัน ⇒ `TCV~2` ⇒ ตัวแรก (หรือไม่ระบุ) ⇒ `TCV` ตรงตัว */
export function ฉบับในกุญแจ(ฉบับ: string, ซ้ำ?: number) {
  return ซ้ำ && ซ้ำ > 1 ? `${ฉบับ}~${ซ้ำ}` : ฉบับ
}
/** ⭐ ใบ #161 ⇒ แยกฉบับในกุญแจกลับเป็นรหัสฉบับจริงกับลำดับซ้ำ ⇒ ไม่มี `~` ⇒ ลำดับ 1 */
export function แยกฉบับซ้ำ(ค่า: string) {
  const m = /^(.*)~(\d+)$/.exec(ค่า)
  return m ? { ฉบับ: m[1]!, ซ้ำ: Number(m[2]) } : { ฉบับ: ค่า, ซ้ำ: 1 }
}
/** แยกกุญแจชิ้นกลับเป็นฉบับ เล่ม (ว่าง = เล่มของหน้า) กับ `บท:เลข` ⇒ ⭐ ใบ #161 ⇒ ฉบับอาจมี `~n` ⇒ ผ่าต่อด้วย `แยกฉบับซ้ำ` */
export function แยกชิ้น(กุญแจ: string) {
  const ท่อน = กุญแจ.split('|')
  return ท่อน.length >= 3
    ? { ฉบับ: ท่อน[0]!, เล่ม: ท่อน[1]!, ข้อ: ท่อน.slice(2).join('|') }
    : { ฉบับ: ท่อน[0]!, เล่ม: '', ข้อ: ท่อน[1] ?? '' }
}

/** ⭐ ใบ #159 ⇒ คอลัมน์คนละตอนของกล่องข้อ ⇒ `ฉบับ` · `เล่ม` ของคอลัมน์ · `ข้อแรก` ของคอลัมน์ (`บท:เลข`) ⇒ ถือจุดหยุด Tab ตอนยังไม่มีใครเดินด้วยลูกศร */
export interface ที่ของเทียบ {
  เล่ม: string
  ข้อแรก: string
  /** ⭐ ใบ #161 ⇒ ลำดับของคอลัมน์นี้ในบรรดาคอลัมน์ฉบับเดียวกันเล่มเดียวกัน ⇒ ไม่มีหรือ 1 = ตัวแรก */
  ซ้ำ?: number
}

export function ใช้การเลือกข้อ(ข้อแรกบนหน้า: () => string, เล่มของหน้า = '') {
  /** กุญแจชิ้น `ฉบับ|บท:เลข` ⇒ เรียงตามลำดับที่ผู้อ่านแตะ ⇒ ตอนแชร์ค่อยเรียงตามบทและข้อ */
  const ที่เลือก = ref<string[]>([])
  /** ข้อที่ถือจุดหยุด Tab ⇒ ว่าง = ข้อแรกบนหน้า */
  const ข้อรับTab = ref('')
  /** ⭐ ใบ #159 ⇒ ข้อที่ถือจุดหยุด Tab ของแต่ละคอลัมน์คนละตอน ⇒ กุญแจ `ฉบับ|เล่ม` ⇒ ⛔ ปนกับของตัวบท */
  const รับTabเทียบ = ref<Record<string, string>>({})
  let แตะล่าสุด = ''
  /** เล่มเดียวกับหน้า ⇒ ⛔ เขียนในกุญแจ ⇒ ชิ้นเดียวกับข้อในตาราง */
  const เล่มในกุญแจ = (เล่ม: string) => (เล่ม && เล่ม !== เล่มของหน้า ? เล่ม : '')

  const ชุด = computed(() => new Set(ที่เลือก.value))

  function สลับ(กุญแจ: string) {
    ที่เลือก.value = ชุด.value.has(กุญแจ)
      ? ที่เลือก.value.filter((x) => x !== กุญแจ)
      : [...ที่เลือก.value, กุญแจ]
  }
  function เลิกทั้งหมด() {
    ที่เลือก.value = []
  }
  function ตั้ง(กุญแจ: string[]) {
    ที่เลือก.value = [...new Set(กุญแจ)]
  }

  /**
   * ของที่ติดบนกล่องของข้อ ⇒ `v-bind` ใส่ทีเดียว
   * `ถือTabได้` ⇒ กล่องนี้เป็นตัวแทนของข้อในคอลัมน์ที่ผู้อ่านอ่านอยู่ ⇒ คอลัมน์อื่น ⇒ −1 เสมอ
   *   ⇒ ⛔ ไม่ให้ข้อเดียวกันมีจุดหยุด Tab ทุกคอลัมน์
   * `ฉบับ` ⇒ คอลัมน์ของกล่องนี้ ⇒ `aria-pressed` กับเส้นใต้บอกเฉพาะชิ้นของคอลัมน์นี้ (ใบ #148 ข้อ 1 · 8)
   *   ⇒ ชื่อที่โปรแกรมอ่านหน้าจอได้ยินมีชื่อฉบับติดอยู่แล้ว (`pk-เฉพาะเสียง` ในกล่อง) ⇒ ได้ยินว่าข้อไหนของฉบับไหนถูกเลือก
   *
   * ⭐⭐ **กล่องของข้อที่มีหัวข้อย่อยอยู่ข้างใน ⛔ ไม่เป็นปุ่ม** (แบบแยกตามข้อ)
   *   ⇒ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/134 วางหัวข้อย่อย `<h3>` ไว้ในกล่องของข้อ
   *   ⇒ ปุ่มกลืนความหมายของลูกทุกตัว ⇒ หัวข้อในปุ่มไม่เป็นหัวข้อแล้ว ⇒ คนที่กระโดดอ่านด้วยหัวข้อหาไม่เจอ (SC 1.3.1)
   *   ⇒ ปุ่มจึงอยู่ที่ช่องตัวบทของแต่ละฉบับข้างใน ⇒ ท่าเดียวกับแบบไหลต่อเนื่องที่มี 1 ปุ่มต่อ 1 คอลัมน์
   */
  function ของข้อ(กุญแจ: string, ฉบับ: string, ถือTabได้ = true, เทียบ?: ที่ของเทียบ) {
    // ⭐ ใบ #159 ⇒ คอลัมน์คนละตอน ⇒ จุดหยุด Tab ของคอลัมน์ตัวเอง ⇒ ⛔ ใช้ข้อของตัวบท
    const ฉ = ฉบับในกุญแจ(ฉบับ, เทียบ?.ซ้ำ)
    const ถือ = เทียบ ? รับTabเทียบ.value[`${ฉ}|${เทียบ.เล่ม}`] || เทียบ.ข้อแรก : ข้อรับTab.value || ข้อแรกบนหน้า()
    const เลือกอยู่ = ชุด.value.has(กุญแจชิ้น(ฉ, กุญแจ, เทียบ ? เล่มในกุญแจ(เทียบ.เล่ม) : ''))
    return {
      role: 'button',
      tabindex: ถือTabได้ && กุญแจ === ถือ ? 0 : -1,
      'aria-pressed': เลือกอยู่ ? 'true' : 'false',
      'data-เลือกข้อ': กุญแจ,
      'data-เลือกฉบับ': ฉบับ,
      'data-เลือกเล่ม': เทียบ?.เล่ม,
      'data-เลือกซ้ำ': เทียบ?.ซ้ำ && เทียบ.ซ้ำ > 1 ? String(เทียบ.ซ้ำ) : undefined,
      class: เลือกอยู่ ? 'pk-ข้อที่เลือก' : undefined,
    }
  }

  function กุญแจของ(el: Element | null) {
    return el?.getAttribute('data-เลือกข้อ') || el?.getAttribute('data-ข้อ') || ''
  }
  /** ⭐ ใบ #161 ⇒ ฉบับของกล่องตามที่กุญแจใช้ ⇒ `TCV` หรือ `TCV~2` */
  function ฉบับของ(el: Element | null) {
    return ฉบับในกุญแจ(el?.getAttribute('data-เลือกฉบับ') || '', Number(el?.getAttribute('data-เลือกซ้ำ') || 1))
  }
  /** ชิ้นของกล่องที่เป็นปุ่มเลือกข้อ ⇒ ฉบับกับข้อของกล่องนั้น ⇒ ⛔ มีฉบับ = ⛔ ไม่ใช่ชิ้น */
  function ชิ้นของ(el: Element | null) {
    const ฉบับ = el?.getAttribute('data-เลือกฉบับ') || ''
    const ข้อ = el?.getAttribute('data-เลือกข้อ') || ''
    return ฉบับ && ข้อ ? กุญแจชิ้น(ฉบับของ(el), ข้อ, เล่มในกุญแจ(el?.getAttribute('data-เลือกเล่ม') || '')) : ''
  }
  /** ⭐ ใบ #159 ⇒ คอลัมน์คนละตอน ⇒ กุญแจจุดหยุด Tab ของมัน ⇒ ว่าง = ข้อของตัวบท ⇒ ใบ #161 ⇒ ฉบับซ้ำแยกกันด้วย `~n` */
  function ที่Tabของ(el: Element | null) {
    const เล่ม = el?.getAttribute('data-เลือกเล่ม')
    return เล่ม ? `${ฉบับของ(el)}|${เล่ม}` : ''
  }
  function ตั้งรับTab(el: Element | null, ข้อ: string) {
    const ที่ = ที่Tabของ(el)
    if (ที่) รับTabเทียบ.value = { ...รับTabเทียบ.value, [ที่]: ข้อ }
    else ข้อรับTab.value = ข้อ
  }
  /** คอลัมน์ของกล่องข้อ ⇒ ลูกศรเดินในคอลัมน์เดิม ⇒ คอลัมน์คนละตอน (ใบ #159) แยกกันตามฉบับและเล่ม */
  function คอลัมน์ของ(el: Element) {
    const ที่ = ที่Tabของ(el)
    return ที่ ? `เทียบ|${ที่}` : (el.closest('.pk-ช่องฉบับ')?.getAttribute('data-ฉบับ') ?? '')
  }

  function แตะในตัวบท(e: MouseEvent) {
    if (e.defaultPrevented || e.button !== 0) return
    const เป้า = e.target as Element | null
    if (!เป้า || เป้า.closest(กดได้อยู่แล้ว)) return
    // ⭐ ใบ #148 ⇒ หากล่องของคอลัมน์ที่แตะก่อน ⇒ แตะในแถวแต่นอกช่องของฉบับ ⇒ ช่องแรกที่ตาเห็นในแถวนั้น
    let ปุ่ม = เป้า.closest('[data-เลือกข้อ]')
    if (!ปุ่ม) {
      const แถว = เป้า.closest('[data-ข้อ]')
      ปุ่ม = แถว ? [...แถว.querySelectorAll('[data-เลือกข้อ]')].find((x) => x.getClientRects().length > 0) || null : null
    }
    const กุญแจ = ชิ้นของ(ปุ่ม)
    if (!กุญแจ) return
    // ⭐ ดับเบิลคลิกเลือกคำ ⇒ คืนสิ่งที่คลิกแรกทำ ⇒ ข้อกลับเป็นแบบเดิม ⇒ คำยังถูกเลือกให้คัดลอกได้
    if (e.detail >= 2) {
      if (e.detail === 2 && แตะล่าสุด === กุญแจ) สลับ(กุญแจ)
      แตะล่าสุด = ''
      return
    }
    // ⭐ ลากเลือกข้อความค้างอยู่ ⇒ ผู้อ่านกำลังเลือกตัวหนังสือ ⛔ ไม่ใช่แตะเลือกข้อ
    const ลาก = window.getSelection()
    if (ลาก && !ลาก.isCollapsed && ลาก.toString().trim()) return
    สลับ(กุญแจ)
    ตั้งรับTab(ปุ่ม, แยกชิ้น(กุญแจ).ข้อ)
    แตะล่าสุด = กุญแจ
  }

  function แป้นในตัวบท(e: KeyboardEvent) {
    const เป้า = e.target as HTMLElement | null
    if (!เป้า?.matches?.('[data-เลือกข้อ]')) return
    const กุญแจ = กุญแจของ(เป้า)
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault()
      const ชิ้น = ชิ้นของ(เป้า)
      if (ชิ้น) สลับ(ชิ้น)
      return
    }
    const ทิศ = ({ ArrowDown: 1, ArrowRight: 1, ArrowUp: -1, ArrowLeft: -1 } as Record<string, number>)[e.key]
    if (!ทิศ) return
    const ราก = e.currentTarget as HTMLElement
    const คอลัมน์ = คอลัมน์ของ(เป้า)
    const ทั้งหมด = [...ราก.querySelectorAll<HTMLElement>('[data-เลือกข้อ]')].filter(
      (x) => x.getClientRects().length > 0 && คอลัมน์ของ(x) === คอลัมน์,
    )
    let i = ทั้งหมด.indexOf(เป้า)
    if (i < 0) return
    // ⭐ ข้อที่ถูกรอยย่อหน้าผ่ากลางมีหลายท่อน ⇒ ข้ามท่อนของข้อเดิม
    while (ทั้งหมด[i] && กุญแจของ(ทั้งหมด[i]!) === กุญแจ) i += ทิศ
    const ไป = ทั้งหมด[i]
    if (!ไป) return
    e.preventDefault()
    const ข้อใหม่ = กุญแจของ(ไป)
    ตั้งรับTab(ไป, ข้อใหม่)
    void nextTick(() => {
      // ⭐ หาใหม่หลัง Vue วาด ⇒ ท่อนแรกของข้อในคอลัมน์เดิม
      const ใหม่ = ทั้งหมด.find((x) => กุญแจของ(x) === ข้อใหม่ && x.isConnected) || ไป
      ใหม่.focus()
    })
  }

  return { ที่เลือก, ชุด, สลับ, เลิกทั้งหมด, ตั้ง, ของข้อ, แตะในตัวบท, แป้นในตัวบท }
}
