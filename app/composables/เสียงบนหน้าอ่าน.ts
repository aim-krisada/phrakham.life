// ปุ่มเล่นเสียงอ่านบนหน้าอ่าน — **อ่านกับฟังในหน้าเดียว**
//
// ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/101
// > *"ผมไม่ต้องการแยก 2 หน้า ต้องการ 1 หน้าได้ทั้งอ่านทั้งฟัง เหมือน app พระคัมภีร์ทั่วไป
// >   ก็แค่กด play มันก็เล่นให้ ไฮไลท์เป็นข้อได้ไม่มีปัญหา"* (พี่เอม 23 ต.ค. 2569)
//
// **ชิ้นนี้ทำ 4 อย่าง** ⇒ ของที่เป็นหน้าจอ (หาข้อบนจอ · เลื่อนจอ) หน้าอ่านส่งมาให้ ⛔ ที่นี่ไม่แตะผังของหน้า
//   ① **ปุ่มเดียว** ⇒ ยังไม่เริ่ม = เล่น · กำลังเล่น = หยุดพัก · หยุดพัก = เล่นต่อ ⇒ อยู่ที่เดิม (ข้อ 11)
//   ② **เล่นจากไหน** ⇒ มีช่วงที่เลือก = ต้นช่วง · ไม่มี = ข้อแรกที่ผู้อ่านเห็นบนจอ (ข้อ 8 · 15)
//   ③ **จอเลื่อนตาม** ⇒ ผู้อ่านเลื่อนเองเมื่อไร **หยุดตาม** แล้วให้ปุ่ม *กลับไปที่กำลังอ่าน* (ข้อ 10)
//   ④ **คิวจบเอง ⇒ บอกว่าหยุดเพราะอะไร** ⇒ ⛔ ไม่เงียบเฉย ๆ (ข้อ 8 · 13)
//
// ⭐⭐ **เสียงของฉบับไหน** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/132 ข้อ 11)
//   ⇒ หน้าอ่านเป็นคนตัดสินว่าฉบับไหน (`ฉบับ`) ⇒ กติกาเขียนไว้ที่ `ฉบับที่ฟัง` ใน `app/components/หน้าอ่าน.vue`
//   ⇒ ที่นี่หยิบดัชนีของฉบับนั้นตัวเดียว ⇒ ⛔ **ฉบับนั้นไม่มีเสียง = ไม่มีปุ่ม** ⛔ ไม่หยิบเสียงของฉบับอื่นมาเล่นแทน (ข้อ 11.3)
//   ⇒ ชื่อฉบับอยู่บนปุ่มให้ตาเห็นก่อนกด และอยู่ในชื่อปุ่มที่โปรแกรมอ่านหน้าจอได้ยิน (ข้อ 11 · 12)
//
// ⛔⛔ **คนที่ไม่กดเล่น ห้ามจ่ายไบต์ของเสียง** (ข้อ 14)
//   ⇒ ตัวเล่นเกิด **ตอนกดครั้งแรก** ⇒ `<audio>` ถูกสร้างตอนนั้น และ `preload = 'none'`
//   ⇒ รายการเต็ม `/api/audio.json` ถูกขอ **หลังกด** เพื่อเอาประกาศที่มาไปแสดงเท่านั้น
//   ⇒ ตัวเฝ้าคือ `tools/ด่านฟังพระคำบนหน้า.mjs` ข้อ ① ⇒ วัดการจราจรจริงของเบราว์เซอร์
//
// ⛔⛔ **การกดต้องสั่งเล่นในจังหวะเดียวกัน ⛔ ห้ามรออะไรก่อน**
//   ⇒ มือถือยอมให้เริ่มเสียงเฉพาะในจังหวะที่นิ้วกดจริง ⇒ จึงคิดคิวจากดัชนีที่อยู่ในหน้าแล้ว
//     แล้วสั่ง `play()` ทันที ⇒ ⛔ ไม่ `await` อะไรคั่นกลาง

import { สร้างตัวเล่นเสียง, type ข้อในคิว, type สภาพตัวเล่น } from '~/utils/ตัวเล่นเสียง'
import { สร้างคิว, มีเสียงบท, type ดัชนีเสียง } from '~/utils/คิวเสียง'
import { ที่อยู่หลังบ้าน, แสดงช่วงฟัง, type ช่วงฟัง } from '~/utils/ที่อยู่'
import type { ComputedRef, Ref } from 'vue'

interface ตำแหน่ง {
  บท: number
  ข้อ: number
}

export function ใช้เสียงบนหน้าอ่าน(o: {
  รหัสเล่ม: string
  ชื่อเล่ม: ComputedRef<string>
  /** ดัชนีเสียงของเล่มนี้ แยกตามฉบับ ⇒ ⛔ ไม่มี = เล่มนี้ไม่มีเสียงสักฉบับ */
  ดัชนีทุกฉบับ: ComputedRef<Record<string, ดัชนีเสียง> | undefined>
  /** ฉบับที่ปุ่มจะอ่าน ⇒ หน้าอ่านตัดสิน ⇒ ว่าง = ไม่มีคอลัมน์คำแปลบนจอ */
  ฉบับ: ComputedRef<string>
  บทที่มี: ComputedRef<number[]>
  ช่วง: Ref<ช่วงฟัง | null>
  บทที่อ่านอยู่: Ref<number>
  /** ข้อแรกที่ผู้อ่านเห็นบนจอ ⇒ หน้าอ่านเป็นคนหา เพราะมันรู้ว่าแถบบนสูงเท่าไร */
  หาข้อบนจอ: () => ตำแหน่ง | null
  /** พาข้อนั้นมาให้เห็น ⇒ `บังคับ` = เลื่อนแม้ข้อนั้นเห็นอยู่แล้ว (ปุ่ม *กลับไปที่กำลังอ่าน*) */
  พาไปข้อ: (ต: ตำแหน่ง, บังคับ: boolean) => Promise<void>
}) {
  const สภาพ = ref<สภาพตัวเล่น>({ สถานะ: 'ยังไม่เริ่ม', ที่ข้อ: -1 })
  const คิว = shallowRef<ข้อในคิว[]>([])
  /** ⭐ จอเลื่อนตามข้อที่กำลังอ่านไหม ⇒ ผู้อ่านเลื่อนเองเมื่อไร ⇒ เป็นเท็จ */
  const ตามอ่าน = ref(true)
  /** ประโยคที่บอกว่าคิวหยุดเพราะอะไร ⇒ ว่าง = ไม่มีอะไรต้องบอก */
  const ข้อความจบ = ref('')
  /** ประกาศที่มาของเสียง ⇒ สัญญาอนุญาต CC BY-SA 4.0 บังคับ ⇒ ยกมาจากรายการเสียงทั้งดุ้น */
  const ประกาศที่มา = ref('')
  let เหตุจบของคิวนี้ = ''
  /** ฉบับของคิวที่กำลังเล่น ⇒ ประกาศที่มาต้องเป็นของฉบับที่ได้ยินอยู่ ⛔ ไม่ใช่ฉบับที่เพิ่งเลือก */
  const ฉบับที่เล่น = ref('')
  let รายการเต็ม: { ฉบับ?: Record<string, { แหล่ง?: { notice?: string } }> } | null = null
  const ดัชนี = computed(() => (o.ฉบับ.value ? o.ดัชนีทุกฉบับ.value?.[o.ฉบับ.value] : undefined))
  type ตัวเล่น = ReturnType<typeof สร้างตัวเล่นเสียง>
  let ตัว: ตัวเล่น | null = null

  const ทำงานอยู่ = computed(() => สภาพ.value.สถานะ !== 'ยังไม่เริ่ม')

  /** ข้อที่กำลังอ่าน ⇒ หน้าเอาไปไฮไลต์ ⇒ `null` = ไม่ได้เล่นอยู่ */
  const ข้อที่เล่นอยู่ = computed<ตำแหน่ง | null>(() => {
    if (!ทำงานอยู่.value) return null
    const ข = คิว.value[สภาพ.value.ที่ข้อ]
    return ข ? { บท: ข.บท, ข้อ: ข.ข้อ } : null
  })

  /** ⭐ **บทที่ปุ่มจะเล่น มีเสียงไหม** ⇒ ⛔ ไม่มี = ⛔ ไม่มีปุ่ม ⇒ บอกว่า *ยังไม่มีเสียง* แทน (ข้อ 13) */
  const มีเสียงให้เล่น = computed(() => {
    if (ทำงานอยู่.value) return true
    const บท = o.ช่วง.value ? o.ช่วง.value.จาก.บท : o.บทที่อ่านอยู่.value
    return มีเสียงบท(ดัชนี.value, บท)
  })

  // ⭐⭐ **บนปุ่มเขียนแค่ *ฟัง* *หยุดพัก* *ฟังต่อ* ⛔ ไม่บอกช่วงบนปุ่มแล้ว**
  //   (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/102 ข้อ 20 · พี่เอม 24 ต.ค. 2569)
  //   > *"ไม่ต้องแสดงสถานะซ้ำซ้อน ... มันก็แค่มีปุ่มให้เลือกว่าจะแสดงหรือเลือกช่วงไหน กับปุ่ม play"*
  //   ⇒ ช่วงบอกไว้ที่เดียว คือหัวคอลัมน์ ⇒ ของเดิม (#101) เขียน `ฟัง 4:40–5:1` บนปุ่ม
  const คำบนปุ่ม = computed(() => {
    if (สภาพ.value.สถานะ === 'กำลังเล่น') return 'หยุดพัก'
    if (สภาพ.value.สถานะ === 'หยุดพัก') return 'ฟังต่อ'
    return 'ฟัง'
  })

  /** ⭐ ชื่อเต็มของปุ่มสำหรับโปรแกรมอ่านหน้าจอ ⇒ **ขึ้นต้นด้วยคำที่ตาเห็น** ⇒ SC 2.5.3 Label in Name (A)
   *  ⭐ **ตาไม่เห็นช่วงซ้ำ แต่คนที่มองไม่เห็นยังรู้ว่าจะได้ฟังอะไร** ⇒ `ฟัง มาระโก 10:13–16` (ใบ #102 ข้อ 20.3) */
  //   ⭐ ใบ #132 ข้อ 12 ⇒ **ชื่อย่อฉบับตามหลังคำบนปุ่มทันที** ⇒ ตาเห็น *ฟัง* กับ *LSV* ⇒ หูได้ยิน *ฟัง LSV ...*
  //     ⇒ ⛔ ไม่ต่อชื่อเต็มภาษาอังกฤษ ⇒ N ตรวจ 4 พ.ย. 2569 ⇒ เสียงไทยอ่านชื่ออังกฤษยาวสะดุด ชื่อปุ่มยาวเกินจำเป็น (Nielsen ข้อ 8)
  const ชื่อเต็มของปุ่ม = computed(() => {
    const ฉ = o.ฉบับ.value
    // ⭐ ระหว่างเล่น ฉบับ ⛔ เปลี่ยนไม่ได้ ⇒ หน้าอ่านหยุดเสียงทันทีที่ฉบับของคอลัมน์เปลี่ยน ⇒ `o.ฉบับ` = ฉบับที่ได้ยินอยู่
    if (ทำงานอยู่.value) return `${คำบนปุ่ม.value} ${ฉ}`
    return o.ช่วง.value
      ? `${คำบนปุ่ม.value} ${ฉ} ${o.ชื่อเล่ม.value} ${แสดงช่วงฟัง(o.ช่วง.value)}`
      : `${คำบนปุ่ม.value} ${ฉ} ตั้งแต่ข้อแรกบนจอ`
  })

  function เอาตัวเล่น(): ตัวเล่น {
    if (!ตัว) {
      ตัว = สร้างตัวเล่นเสียง(
        (ส) => (สภาพ.value = ส),
        () => (ข้อความจบ.value = เหตุจบของคิวนี้),
      )
    }
    return ตัว
  }

  function เริ่มใหม่() {
    const ดัชนีนี้ = ดัชนี.value
    if (!ดัชนีนี้) return
    // ⭐ จุดเริ่ม ⇒ ช่วงที่เลือกไว้ชนะ ⇒ ไม่มีช่วง = ข้อแรกบนจอ ⇒ ข้อแรกบนจออยู่บทที่ไม่มีเสียง = ต้นบทที่อ่านอยู่
    let จาก: ตำแหน่ง | null = o.ช่วง.value ? { ...o.ช่วง.value.จาก } : o.หาข้อบนจอ()
    if (!จาก || !มีเสียงบท(ดัชนีนี้, จาก.บท)) จาก = { บท: o.บทที่อ่านอยู่.value, ข้อ: 1 }
    const ผล = สร้างคิว({
      รหัสเล่ม: o.รหัสเล่ม,
      ชื่อเล่ม: o.ชื่อเล่ม.value,
      ดัชนี: ดัชนีนี้,
      บทที่มี: o.บทที่มี.value,
      จาก,
      ช่วง: o.ช่วง.value,
      ต่อที่อยู่: ที่อยู่หลังบ้าน,
    })
    ข้อความจบ.value = ''
    เหตุจบของคิวนี้ = ผล.เหตุจบ
    if (!ผล.คิว.length) {
      ข้อความจบ.value = ผล.เหตุจบ
      return
    }
    คิว.value = ผล.คิว
    ฉบับที่เล่น.value = o.ฉบับ.value
    ตามอ่าน.value = true
    const ต = เอาตัวเล่น()
    ต.ตั้งคิว(ผล.คิว)
    // ⛔ **ต้องอยู่ในจังหวะเดียวกับการกด** ⇒ เหตุผลอยู่หัวไฟล์นี้
    ต.กดปุ่มเดียว()
    void หยิบประกาศที่มา()
  }

  function กดปุ่มฟัง() {
    if (ทำงานอยู่.value && ตัว) {
      ตัว.กดปุ่มเดียว()
      return
    }
    เริ่มใหม่()
  }

  /** หยุดทั้งคิว ⇒ ใช้ตอนผู้อ่านเปลี่ยนช่วง ⇒ คิวเดิมไม่ตรงกับที่เขาเลือกแล้ว */
  function หยุด() {
    ตัว?.หยุด()
    คิว.value = []
  }

  async function กลับไปที่กำลังอ่าน() {
    ตามอ่าน.value = true
    const ต = ข้อที่เล่นอยู่.value
    if (ต) await o.พาไปข้อ(ต, true)
  }

  async function หยิบประกาศที่มา() {
    const ฉ = ฉบับที่เล่น.value
    try {
      รายการเต็ม ??= await $fetch<typeof รายการเต็ม>(ที่อยู่หลังบ้าน('api/audio.json'))
      // ⭐ ประกาศของฉบับที่ได้ยินอยู่ ⇒ ระหว่างรอ ผู้อ่านอาจเปลี่ยนฉบับไปแล้ว ⇒ ⛔ ไม่เขียนทับด้วยของฉบับเก่า
      if (ฉ === ฉบับที่เล่น.value) ประกาศที่มา.value = รายการเต็ม?.ฉบับ?.[ฉ]?.แหล่ง?.notice || ''
    } catch {
      // ⛔ หยิบไม่ได้ ⇒ เสียงยังเล่นต่อได้ ⇒ ⛔ ไม่ทำให้ปุ่มพัง
    }
  }

  // ⭐ ข้อที่กำลังอ่านเปลี่ยน ⇒ จอเลื่อนตาม **เฉพาะตอนยังตามอยู่**
  watch(ข้อที่เล่นอยู่, (ต) => {
    if (ต && ตามอ่าน.value) void o.พาไปข้อ(ต, false)
  })

  // ⭐⭐ **ผู้อ่านเลื่อนจอเอง ⇒ หยุดตาม** (ข้อ 10)
  //   ⇒ ⛔ **ดักจากนิ้วกับแป้นพิมพ์ ⛔ ไม่ใช่จากเหตุการณ์ `scroll`**
  //     ⇒ การเลื่อนที่ตัวเล่นสั่งเองก็ทำให้เกิด `scroll` ⇒ แยกไม่ออกว่าใครเลื่อน
  //     ⇒ ท่าเดียวกับรุ่น 2 (`onUserScroll` ใน `assets/pk-audio.js`) ⇒ ฟัง `wheel` กับ `touchmove`
  const ปุ่มเลื่อน = new Set(['PageUp', 'PageDown', 'ArrowUp', 'ArrowDown', 'Home', 'End', ' '])
  function ผู้อ่านเลื่อนเอง() {
    if (ทำงานอยู่.value) ตามอ่าน.value = false
  }
  function ดักแป้น(e: KeyboardEvent) {
    if (!ปุ่มเลื่อน.has(e.key)) return
    const ที่ = e.target as HTMLElement | null
    // ⛔ ปุ่มลูกศรในช่องเลือกหรือในแผง ⛔ ไม่ใช่การเลื่อนหน้า
    if (ที่?.closest?.('input, select, textarea, button, [role="dialog"], [tabindex]')) return
    ผู้อ่านเลื่อนเอง()
  }

  onMounted(() => {
    window.addEventListener('wheel', ผู้อ่านเลื่อนเอง, { passive: true })
    window.addEventListener('touchmove', ผู้อ่านเลื่อนเอง, { passive: true })
    window.addEventListener('keydown', ดักแป้น)
  })
  onBeforeUnmount(() => {
    window.removeEventListener('wheel', ผู้อ่านเลื่อนเอง)
    window.removeEventListener('touchmove', ผู้อ่านเลื่อนเอง)
    window.removeEventListener('keydown', ดักแป้น)
    ตัว?.ปิด()
  })

  return {
    สภาพ,
    ทำงานอยู่,
    ข้อที่เล่นอยู่,
    ตามอ่าน,
    ข้อความจบ,
    ประกาศที่มา,
    มีเสียงให้เล่น,
    คำบนปุ่ม,
    ชื่อเต็มของปุ่ม,
    ฉบับที่เล่น,
    กดปุ่มฟัง,
    กลับไปที่กำลังอ่าน,
    หยุด,
  }
}
