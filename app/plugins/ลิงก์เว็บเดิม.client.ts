type ชั้นการ์ด = Record<string, Record<string, string[]>>

async function หยิบ<T>(ทาง: string): Promise<T | null> {
  try {
    return await $fetch<T>(ที่อยู่หลังบ้าน(ทาง))
  } catch {
    return null
  }
}

/** ⭐ หาคำของ `w` ในช่วง ⇒ เลข Strong ตรงตัว · เลขล้วน · รูปพจนานุกรม ⇒ ไม่เจอในช่วง ⇒ ลองทั้งบทในช่วง (เลขข้อสองฝั่งต่างกันได้) */
async function หาคำ(อ: อ้างอิงเว็บเดิม, คำ: string, ขนาด: ขนาดเล่ม | null) {
  const ข้อ = ข้อในอ้างอิง(อ, ขนาด)
  const บท = [...new Set(ข้อ.map(([c]) => c))]
  const การ์ด = await Promise.all(บท.map((c) => หยิบ<{ ชั้น: ชั้นการ์ด }>(`api/card/${อ.รหัส}/${c}.json`)))
  for (const ทั้งบท of [false, true])
    for (const แบบ of ['รหัส', 'เลขล้วน', 'รูป'] as const)
      for (let i = 0; i < บท.length; i++) {
        const c = บท[i]!
        const ข้อที่หา = ทั้งบท
          ? Object.keys(Object.values(การ์ด[i]?.ชั้น ?? {})[0] ?? {}).map(Number).sort((a, b) => a - b)
          : ข้อ.filter(([x]) => x === c).map(([, v]) => v)
        const เจอ = หาคำในบท(การ์ด[i]?.ชั้น, ข้อที่หา, คำ, แบบ)
        if (เจอ) return { บท: c, ข้อ: เจอ[0], คำที่: เจอ[1] }
      }
  return null
}

export default defineNuxtPlugin({
  name: 'ลิงก์เว็บเดิม',
  parallel: false,
  async setup() {
    const ฐาน = ที่อยู่หน้าแรก()
    const ทาง = location.pathname
    const ท้าย = (ทาง + '/').startsWith(ฐาน) ? ทาง.slice(ฐาน.length) : null
    if (ท้าย !== '' && ท้าย !== 'index.html') return
    const คำถาม = new URLSearchParams(location.search)
    const ref = คำถาม.get('ref')
    const ไปหน้าแรก = ท้าย === 'index.html'
    let ที่ไป: string | null = null
    if (ref !== null) {
      const เล่ม = await หยิบ<{ เล่ม: { รหัส: string; ข้อสุดท้าย?: number[] }[] }>('api/books.json')
      const ขนาด: ขนาดเล่ม | null = เล่ม
        ? Object.fromEntries(เล่ม.เล่ม.filter((x) => x.ข้อสุดท้าย?.length).map((x) => [x.รหัส, x.ข้อสุดท้าย!]))
        : null
      const อ = อ่านอ้างอิงเว็บเดิม(ref, ขนาด)
      if (อ) {
        const คำ = อ่านคำเว็บเดิม(คำถาม.get('w'))
        // ⭐ `orig=1` หรือมีคำ ⇒ เปิดคอลัมน์คำภาษาเดิมด้วย ⇒ การ์ดคำเปิดได้ต้องมีคอลัมน์นี้ (หัว `ที่อยู่คำที่แชร์`)
        const ตัวบท = อ.ลำดับ < 39 ? 'WLC' : 'SBLGNT'
        const ฉบับ = คำถาม.get('orig') === '1' || คำ ? [ฉบับตั้งต้น, ตัวบท] : null
        const ช่วง = ช่วงจากอ้างอิง(อ, ขนาด)
        ที่ไป = ที่อยู่หน้าอ่าน(อ.รหัส, อ.บทต้น, อ.ข้อต้น, null, ช่วง, ฉบับ)
        const เจอ = คำ ? await หาคำ(อ, คำ, ขนาด) : null
        if (เจอ) ที่ไป += `${ที่ไป.includes('?') ? '&' : '?'}w=${เขียนคำที่แชร์(เจอ)}`
      }
    }
    if (!ที่ไป && ไปหน้าแรก) ที่ไป = ฐาน
    if (!ที่ไป) return
    location.replace(ที่ไป)
    await new Promise((r) => setTimeout(r, 10000))
  },
})
