<script setup lang="ts">
// ตัวบทของคอลัมน์ที่เปิดคนละเล่มคนละบท — **ชิ้นส่วนเดียวทุกที่ที่วาด** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131#note_30367)
//
// ⭐⭐ **ทำไมแยกออกมาจาก `หน้าอ่าน.vue`** ⇒ ตัวบทของคอลัมน์นี้ถูกวาดได้ 3 ที่แล้ว
//   ① กล่องของตัวเอง (`section.pk-ตอนเทียบ`) ⇒ จอกว้าง · จอแคบที่วางซ้ายขวา · จอแคบที่อ่านทีละฉบับ
//   ② **ทีละข้อ คู่กับข้อของคอลัมน์แรก** ⇒ จอแคบวางบนล่าง ⇒ มัทธิว 17:1 ⇒ มาระโก 9:1 ⇒ 17:2 ⇒ 9:2 (note_30310 ข้อ 3)
//   ③ **ทั้งบทต่อท้ายบทคู่ของคอลัมน์แรก** ⇒ จอแคบวางบนล่าง แบบไหลต่อเนื่อง หรือแยกตามย่อหน้า ⇒ ไม่มีแถวรายข้อให้คู่
//   ⇒ ⛔ เขียน 3 ที่ = วันหนึ่งที่หนึ่งถูกแก้แล้วอีกที่ค้าง ⇒ เหตุผลเดียวกับ `หัวคอลัมน์.vue` (SC 3.2.4)
// ⭐ **หน้าตาและชื่อคลาสเดิมทุกตัว** ⇒ `pk-ข้อตอนเทียบ` · `pk-ไหลตอนเทียบ` · `pk-ย่อหน้า` ⇒ ด่านเดิมหาเจอที่เดิม
// ⭐ `data-ข้อเทียบ` บนทุกข้อ ⇒ หน้าอ่านหาข้อที่ผู้อ่านเลือกให้คอลัมน์นี้ แล้วเลื่อนกล่องของมันไปที่ข้อนั้น (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/143)
// ⭐⭐ **แตะข้อเลือกได้แบบคอลัมน์อื่น** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/159)
//   ⇒ หน้าอ่านส่ง `เลือก` มา ⇒ ของที่ติดบนกล่องของข้อ (ปุ่มแบบตัวหนังสือ · `aria-pressed` · `data-เลือกข้อ` · เส้นใต้) ⇒ ตัวเดียวกับคอลัมน์ในตาราง
//   ⇒ ⛔ ชิ้นนี้ ⛔ ถือการเลือกเอง ⇒ ตัวดักการแตะกับแป้นพิมพ์อยู่ที่กล่องที่ครอบ ⇒ กติกาอยู่ที่ `app/composables/เลือกข้อ.ts`
//   ⇒ คอลัมน์คำภาษาเดิม ⇒ ⛔ ได้ `เลือก` ⇒ คำยังเป็นปุ่มเปิดการ์ด
// ⭐ `ป้าย` ⇒ ป้ายเล็กหน้าข้อตอนวางบนล่าง (`data-ป้ายบนล่าง`) ⇒ ตาเห็นจาก CSS ⛔ ไม่อยู่ในตัวหนังสือของข้อ
//   ⇒ โปรแกรมอ่านหน้าจอได้ยินชื่อเต็มจากกล่องที่ครอบอยู่แล้ว ⇒ ⛔ ไม่ได้ยินซ้ำ (กฎอยู่ที่ `main.css` หัวข้อ *วางบนล่างบนจอแคบ*)
import type { ComputedRef } from 'vue'
import type { ชิ้นเนื้อ } from '~/utils/คำพระเยซู'
import { เยื้องบรรทัดแรก, type ย่อหน้า } from '~/utils/ย่อหน้า'
import { หัวข้อตามข้อ, type หัวข้อย่อย } from '~/utils/หัวข้อย่อย'
import { เลขบนคำ } from '~/utils/เลขStrong'
import คู่ขนานใต้หัวข้อ from '~/components/คู่ขนานใต้หัวข้อ.vue'

/** ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/145 ก้อน ง. ⇒ คำของคอลัมน์คำภาษาเดิมคนละที่ ⇒ ตัวเดิม · คำแปลกำกับ · กาล */
type คำเดิม = [ตัว: string, คำแปล: string, กาล?: string]
interface แถวเทียบ {
  บท: number
  เลข: string
  ป้าย: string
  ชิ้น: ชิ้นเนื้อ[]
  /** ⭐ มีเฉพาะคอลัมน์คำภาษาเดิม ⇒ แต่ละคำเป็นปุ่ม ⇒ ⛔ มี = ฉบับแปล */
  คำ?: คำเดิม[]
}

const props = defineProps<{
  ต: {
    กุญแจ: string
    เล่ม: string
    ชื่อฉบับ: string
    ภาษา: string
    แถว: แถวเทียบ[]
    ย่อหน้า: ย่อหน้า[]
    ยังไม่มีย่อหน้า: string
    /** ⭐ หัวข้อย่อย (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/134) ⇒ ว่าง = ปิดสวิตช์ หรือฉบับนี้ไม่มีหัวข้อ
     *  ⇒ คอลัมน์นี้ ⛔ ไม่อยู่ในผังเทียบบรรทัด ⇒ หัวข้อไหลไปกับคอลัมน์ของตัวเอง ⇒ กติกาอยู่หัวไฟล์ `app/utils/หัวข้อย่อย.ts` */
    หัวข้อ: หัวข้อย่อย[]
    หัวของย่อหน้า: (หัวข้อย่อย | null)[]
    ตอนไหล: { ย่อหน้า: ย่อหน้า[]; หัว: (หัวข้อย่อย | null)[] } | null
    /** ⭐ ใบ #145 ก้อน ง. ⇒ คอลัมน์คำภาษาเดิมคนละที่ ⇒ ชื่อชั้นกับทิศของตัวหนังสือ */
    คำเดิม?: { ชั้น: string; ทิศ: 'ltr' | 'rtl' }
  }
  จัดวาง: string
  /** เล่มของหน้า ⇒ ใช้เน้นข้อที่เสียงกำลังอ่าน ⇒ เสียงอ่านแค่เล่มของคอลัมน์แรก */
  เล่มของหน้า: string
  กุญแจที่เล่น: string
  /** ⭐ วาดข้อเดียว ⇒ ลำดับในแถวของคอลัมน์นี้ ⇒ ใช้ตอนคู่ทีละข้อ ⇒ ว่าง = วาดทั้งบทตามแบบการจัดวาง */
  แถวที่?: number
  /** ⭐ ป้ายเล็กของตอนวางบนล่าง ⇒ ว่าง = ไม่มีป้าย */
  ป้าย?: string
  /** ⭐ ใบ #159 ⇒ ของที่ติดบนกล่องของข้อให้แตะเลือกได้ ⇒ `ท่อนแรก` = ท่อนแรกของข้อ (ข้อที่ถูกย่อหน้าผ่ามีหลายท่อน) ⇒ ว่าง = เลือกไม่ได้ */
  เลือก?: (บท: number, เลข: string, ท่อนแรก: boolean) => Record<string, unknown>
}>()

/** ของที่ติดบนกล่องของข้อ ⇒ ⛔ มี `เลือก` ⇒ ว่าง */
const ของเลือก = (บท: number, เลข: string, ท่อนแรก = true) => props.เลือก?.(บท, เลข, ท่อนแรก) ?? {}

/** หัวข้อของแต่ละข้อ ⇒ ใช้กับแบบที่วาดทีละข้อ ⇒ หัวข้อกลางข้อขึ้นเหนือข้อนั้น */
const หัวตามข้อ = computed(() => หัวข้อตามข้อ(props.ต.หัวข้อ))

/**
 * ⭐ กดคำ ⇒ บอกหน้าอ่าน ⇒ การ์ดความหมายตัวเดียวกับคำในตาราง (ใบ #103) ⇒ ⛔ ชิ้นนี้ไม่ถือการ์ดเอง
 *   ⇒ ส่งก้อนทั้งก้อนกลับไป ⇒ หน้ารู้เล่ม บท และชั้นของคอลัมน์นี้ ⇒ คนละเล่มก็ได้การ์ดของเล่มนั้น
 */
/** ⭐ สองสวิตช์ของหน้าอ่าน (หัวข้อ · กรอบเรื่องเดียวกัน) ⇒ ส่งลงมาด้วย provide ⇒ ไม่มี (ใช้นอกหน้าอ่าน) ⇒ เปิดทั้งคู่ */
const แสดงหัวจากหน้า = inject<ComputedRef<{ หัว: boolean; คู่ขนาน: boolean }> | null>('pk-แสดงหัว', null)
const แสดง = computed(() => แสดงหัวจากหน้า?.value ?? { หัว: true, คู่ขนาน: true })
const emit = defineEmits<{
  คำ: [{ e: Event; ต: object; บท: number; ข้อ: string; i: number; คำ: คำเดิม }]
  /** ⭐ แตะที่อยู่ในบรรทัดคู่ขนานใต้หัวข้อ ⇒ หน้าอ่านเปิดคอลัมน์ใหม่ (`app/components/คู่ขนานใต้หัวข้อ.vue`) */
  ไปที่: [{ ที่อยู่: string; ต: object }]
}>()
/** ⭐ แถวที่วาด ⇒ ข้อเดียวตอนคู่ทีละข้อ · ทุกข้อตอนวาดทั้งบท */
const แถวคำ = computed(() =>
  props.แถวที่ !== undefined ? (props.ต.แถว[props.แถวที่] ? [props.ต.แถว[props.แถวที่]!] : []) : props.ต.แถว,
)

/** ⭐ ใบ #178 ⇒ เลข Strong ของคำ ⇒ ภาษาเดียวกับที่การ์ดของคอลัมน์นี้ใช้ (`hbo` · อื่น ๆ เป็นกรีก) */
const เลข = (บท: number, ข้อ: string, i: number) =>
  เลขบนคำ(props.ต.เล่ม, บท, props.ต.คำเดิม?.ชั้น || '', ข้อ, i, props.ต.ภาษา === 'hbo' ? 'hbo' : 'grc')

const กำลังอ่าน = (บท: number, เลข: string) =>
  props.ต.เล่ม === props.เล่มของหน้า && props.กุญแจที่เล่น === `${บท}:${เลข}`
</script>

<template>
  <!-- ⭐⭐ **คอลัมน์คำภาษาเดิมคนละที่** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/145 ข้อ 4 ⇒ ก้อน ง.)
         ⇒ 1 ข้อ 1 ย่อหน้าทุกแบบจัดวาง ⇒ ท่าเดียวกับก้อนคำในตาราง (`pk-ข้อคำ` · `pk-คำ`) ⇒ เลขข้อของฝั่งภาษาเดิมเอง (ใบ #117)
         ⇒ ทุกคำเป็น `<button>` จริง ⇒ ชื่อที่ได้ยิน = คำที่ตาเห็น (SC 2.5.3) ⇒ กดแล้วการ์ดเดียวกับในตาราง
         ⇒ `data-ข้อเทียบ` ⇒ หน้าเลื่อนกล่องไปข้อที่เลือกได้เหมือนฉบับแปล (ใบ #143) -->
  <div v-if="ต.คำเดิม" class="pk-กล่องคำ pk-คำเดิมเทียบ" :lang="ต.ภาษา || undefined" :dir="ต.คำเดิม.ทิศ">
    <p
      v-for="x in แถวคำ"
      :key="`${ต.กุญแจ}-${x.เลข}`"
      class="pk-ข้อคำ"
      :class="{ 'pk-ข้อคู่': แถวที่ !== undefined }"
      :data-ป้ายบนล่าง="ป้าย || undefined"
      :data-ข้อเทียบ="`${x.บท}:${x.เลข}`"
    >
      <sup class="pk-เลขข้อ">{{ x.ป้าย }}</sup
      ><button
        v-for="(ค, i) in x.คำ || []"
        :key="i"
        type="button"
        class="pk-คำ"
        aria-haspopup="dialog"
        @click="emit('คำ', { e: $event, ต, บท: x.บท, ข้อ: x.เลข, i, คำ: ค })"
      >
        <span class="pk-ตัวเดิม">{{ ค[0] }}</span><span class="pk-คำแปลคำ" lang="en" dir="ltr"
          >{{ ค[1] }}<!-- ⭐ ใบ #178 ⇒ เลข Strong ⇒ ไฟล์การ์ดของเล่มบทของคอลัมน์นี้ ⇒ ตัวเดียวกับที่การ์ดของคอลัมน์นี้หยิบ --><span
            v-if="เลข(x.บท, x.เลข, i)"
            class="pk-เลขStrong"
            >{{ เลข(x.บท, x.เลข, i) }}</span
          ></span
        >
      </button>
    </p>
  </div>
  <!-- ② ข้อเดียว ⇒ คู่กับข้อของคอลัมน์แรก ⇒ หัวข้อของคอลัมน์นี้ขึ้นเหนือข้อของมันเอง (ใบ #134) -->
  <template v-else-if="แถวที่ !== undefined && ต.แถว[แถวที่]">
  <h3
    v-if="แสดง.หัว && หัวตามข้อ.get(Number(ต.แถว[แถวที่]!.เลข))?.ตัวหนังสือ"
    class="pk-หัวข้อย่อย pk-ข้อคู่"
    :lang="ต.ภาษา"
    :data-ป้ายบนล่าง="ป้าย || undefined"
  >
    {{ หัวตามข้อ.get(Number(ต.แถว[แถวที่]!.เลข))!.ตัวหนังสือ }}
  </h3>
  <component :is="คู่ขนานใต้หัวข้อ" :หัว="หัวตามข้อ.get(Number(ต.แถว[แถวที่]!.เลข))" @ไปที่="(t: string) => emit('ไปที่', { ที่อยู่: t, ต })" />
  <p
    class="pk-ข้อตอนเทียบ pk-ข้อคู่"
    :class="{ 'pk-กำลังอ่าน': กำลังอ่าน(ต.แถว[แถวที่]!.บท, ต.แถว[แถวที่]!.เลข) }"
    :lang="ต.ภาษา"
    :data-ป้ายบนล่าง="ป้าย || undefined"
    :data-ข้อเทียบ="`${ต.แถว[แถวที่]!.บท}:${ต.แถว[แถวที่]!.เลข}`"
    v-bind="ของเลือก(ต.แถว[แถวที่]!.บท, ต.แถว[แถวที่]!.เลข)"
  >
    <span class="pk-เฉพาะเสียง">{{ ป้าย || ต.ชื่อฉบับ }}: </span
    ><sup class="pk-เลขข้อ">{{ ต.แถว[แถวที่]!.ป้าย }}</sup
    ><template v-for="(ชิ้น, j) in ต.แถว[แถวที่]!.ชิ้น" :key="j"
      ><span v-if="ชิ้น.พระเยซู" class="pk-คำพระเยซู">{{ ชิ้น.ตัวหนังสือ }}</span
      ><template v-else>{{ ชิ้น.ตัวหนังสือ }}</template></template
    >
  </p>
  </template>

  <!-- ⭐ **ตอนที่เทียบเดินตามโหมดการจัดวางที่ผู้อ่านเลือกไว้เหมือนกัน**
         ⇒ ⛔ ไม่ทำโหมดของตัวเองขึ้นมาใหม่ ⇒ ของที่เห็นสองฝั่งจะได้เป็นทรงเดียวกัน
       ⛔ **ย่อหน้าของสองฝั่ง ⛔ ไม่ตรงบรรทัดกัน และ ⛔ ไม่ต้องตรง** ⇒ คนแปลคนละคนแบ่งคนละที่ -->
  <template v-else-if="แถวที่ === undefined && จัดวาง === 'แยกตามย่อหน้า'">
    <p v-if="ต.ยังไม่มีย่อหน้า" class="pk-ยังไม่มีย่อหน้า" role="note">
      ฉบับ {{ ต.ชื่อฉบับ }} ⛔ ยังไม่มีย่อหน้าให้ใช้ ⇒ {{ ต.ยังไม่มีย่อหน้า }}
    </p>
    <template v-for="(ย, k) in ต.ย่อหน้า" :key="`${ต.กุญแจ}-${ย.กุญแจ}`">
    <h3 v-if="แสดง.หัว && ต.หัวของย่อหน้า[k]?.ตัวหนังสือ" class="pk-หัวข้อย่อย" :lang="ต.ภาษา">{{ ต.หัวของย่อหน้า[k]!.ตัวหนังสือ }}</h3>
    <component :is="คู่ขนานใต้หัวข้อ" :หัว="ต.หัวของย่อหน้า[k]" @ไปที่="(t: string) => emit('ไปที่', { ที่อยู่: t, ต })" />
    <p
      class="pk-ย่อหน้า"
      :class="[ย.ป้าย ? `pk-ป้าย-${ย.ป้าย}` : undefined, { 'pk-เยื้อง': เยื้องบรรทัดแรก(ย.ป้าย) }]"
      :lang="ต.ภาษา"
      :data-ป้ายบนล่าง="ป้าย || undefined"
    >
      <template v-for="(ท, t) in ย.ท่อน" :key="ท.กุญแจ"
        ><span
          :class="{ 'pk-กำลังอ่าน': กำลังอ่าน(ท.บท, ท.เลข) }"
          :data-ข้อเทียบ="`${ท.บท}:${ท.เลข}`"
          v-bind="ของเลือก(ท.บท, ท.เลข, ท.ท่อนแรก)"
          ><sup v-if="ท.ป้าย" class="pk-เลขข้อ">{{ ท.ป้าย }}</sup
          ><template v-for="(ชิ้น, j) in ท.ชิ้น" :key="j"
            ><span v-if="ชิ้น.พระเยซู" class="pk-คำพระเยซู">{{ ชิ้น.ตัวหนังสือ }}</span
            ><template v-else>{{ ชิ้น.ตัวหนังสือ }}</template></template
          ></span
        ><template v-if="t < ย.ท่อน.length - 1">{{ ' ' }}</template></template
      >
    </p>
    </template>
  </template>

  <!-- ⭐ ไหลต่อเนื่องที่มีหัวข้อ ⇒ ผ่าเป็นตอน ⇒ `h3` คั่นระหว่างตอน ⇒ ⛔ อยู่ใน `<p>` ไม่ได้ (ใบ #134) -->
  <div
    v-else-if="แถวที่ === undefined && จัดวาง === 'ไหลต่อเนื่อง' && ต.ตอนไหล"
    class="pk-ไหลตอนเทียบ pk-ไหลมีหัวข้อ"
    :lang="ต.ภาษา"
    :data-ป้ายบนล่าง="ป้าย || undefined"
  >
