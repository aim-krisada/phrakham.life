<script setup lang="ts">
// คำอ่านอักษรไทยของคำกรีก 1 คำ บนการ์ดคำ (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/116)
//
// ⭐ ตารางกับตัวถอดอยู่ `app/utils/คำอ่านกรีก.ts` ที่เดียว ⇒ ที่นี่แค่วางผลลงหน้า
//   ⇒ พยางค์คั่นด้วย `-` ⇒ พยางค์เสียงหนักเป็นตัวหนา (พี่เอมเลือก 27 ต.ค. 2569 ⇒ ใบ #116 note 29711)
//   ⇒ ตัวหนาเป็น `<b>` ⇒ โปรแกรมอ่านหน้าจอ ⛔ ไม่อ่านขีดหรือเครื่องหมายแทรกกลางคำ (ร่างข้อ 7.9.2)
//
// ⭐ `lang="th"` ⇒ โปรแกรมอ่านหน้าจออ่านเป็นภาษาไทย ⇒ WCAG 2.2 SC 3.1.2 (เกณฑ์ข้อ 5.2)
//   ⇒ ใส่ที่ตัวคำอ่านเอง ⛔ ไม่พึ่งภาษาของหน้า ⇒ คำอ่านอยู่ติดคำกรีกที่เป็น `lang="grc"`
//
// ⛔⛔ **ถอดไม่ได้ ⇒ บอกตรง ๆ ⛔ ไม่เงียบ ⛔ ไม่ขึ้นคำอ่านครึ่ง ๆ กลาง ๆ** (เกณฑ์ข้อ 7)
//   ⇒ ด่าน `tools/ด่านคำอ่านกรีก.mjs` ไล่ทุกคำในข้อมูลจริงแล้ว ⇒ บรรทัดนี้ควรไม่มีวันขึ้น ⇒ มีไว้กันข้อมูลรุ่นใหม่
import { computed } from 'vue'
import { อ่านกรีก } from '~/utils/คำอ่านกรีก'

const props = defineProps<{ คำ: string }>()

const ผล = computed(() => {
  try {
    return อ่านกรีก(props.คำ)
  } catch {
    return null
  }
})
</script>

<template>
  <span v-if="ผล" class="pk-คำอ่าน" lang="th" data-คำอ่านไทย
    ><template v-for="(พ, i) of ผล.พยางค์" :key="i"
      >{{ i ? '-' : '' }}<b v-if="i === ผล.หนัก">{{ พ }}</b><template v-else>{{ พ }}</template></template
    ></span
  >
  <span v-else class="pk-หมายเหตุการ์ด" data-ถอดไม่ได้>⛔ ยังถอดคำอ่านของคำนี้ไม่ได้</span>
</template>
