<script setup lang="ts">
// สัญลักษณ์กาลบนคำกริยากรีกหนึ่งคำ (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/110)
//
// ⭐⭐ **ชิ้นนี้ถูกโหลดตอนคอลัมน์คำภาษาเดิมเปิดและมีกริยากรีกบนหน้าเท่านั้น**
//   ⇒ หน้าอ่านเรียกด้วย `defineAsyncComponent` ⇒ โค้ด ตารางสัญลักษณ์ และหน้าตา (CSS) อยู่ในก้อนของตัวเอง
//   ⇒ เกณฑ์ข้อ 8 ⇒ *คนที่ไม่เปิดคอลัมน์คำภาษาเดิม ต้องไม่จ่ายไบต์เพิ่มเลย*
//   ⇒ ตัวเฝ้าคือ `tools/ด่านกาลบนหน้า.mjs` ข้อ ① ⇒ วัดจากการจราจรจริงของเบราว์เซอร์
//
// ⭐ **ชิ้นนี้อยู่ท้ายปุ่มคำใน DOM แต่ขึ้นหน้าคำด้วย CSS** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/133 ⇒ เดิมขึ้นบนหัวคำ)
//   ⇒ ชื่อที่โปรแกรมอ่านหน้าจอได้ยินขึ้นต้นด้วยคำที่ตาเห็น ⇒ WCAG 2.2 SC 2.5.3 Label in Name (ระดับ A)
//   ⇒ ภาพ `aria-hidden` ⇒ ความหมายอยู่ในตัวหนังสือเฉพาะเสียง ⇒ WCAG 2.2 SC 1.3.1 (ระดับ A)
//   ⇒ หน้าตาและเหตุผลของที่วางอยู่ `app/assets/css/สัญลักษณ์กาล.css` หัวข้อ *จาก กาลบนคำ.vue*
//
// ⭐⭐ **`ซ่อน` ⇒ ผู้อ่านปิดสัญลักษณ์ที่หัวคอลัมน์** (ใบ #133 ข้อ 15 ⇒ ปิดแล้วคำไม่ขยับ)
//   ⇒ ภาพยังอยู่แต่ล่องหน ⇒ ที่ของมันคงเดิม ⇒ คำไม่ถูกดึงเข้าไปแทนที่
//   ⇒ ชื่อกาลที่เป็นเสียงถูกถอด ⇒ ปิดแล้วโปรแกรมอ่านหน้าจอ ⛔ ได้ยินชื่อกาล ⇒ ตรงกับที่ตาเห็น
import { computed } from 'vue'
import รูปกาล from '~/components/รูปกาล.vue'
import { อ่านกาล, คำอ่าน } from '~/utils/กาลกริยา'

const props = defineProps<{ รหัส: string; ซ่อน?: boolean }>()
const กาล = computed(() => อ่านกาล(props.รหัส) ?? null)
</script>

<template>
  <component :is="รูปกาล" :กาล="กาล" :data-ซ่อน="ซ่อน ? '' : undefined" /><span
    v-if="!ซ่อน"
    class="pk-เฉพาะเสียง"
    lang="th"
    data-คำอ่านกาล
    >{{ ` ${คำอ่าน(กาล)}` }}</span
  >
</template>

