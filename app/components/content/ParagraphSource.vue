<script setup lang="ts">
// ⭐⭐ **บรรทัด *ย่อหน้าตาม …* ใต้ฉบับบนหน้าแหล่งข้อมูล** (พี่เอมสั่ง 3 พ.ย. 2569 ในใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131)
//   ⇒ ของเดิม (ใบ #106 ข้อ 8) ⇒ ป้ายอยู่ที่หัวคอลัมน์ ⇒ เปลืองที่แนวตั้ง ⇒ ถอดออกจากหัวแล้วมาบอกที่นี่
//   ⇒ ใช้ในไฟล์ `.md` ว่า `:paragraph-source{version="WEB"}` ⇒ ชื่อชิ้นส่วนเป็นอักษรอังกฤษเพราะ MDC ต้องการ
//
// ⭐ **ฉบับไหนไม่มีย่อหน้าของตัวเอง** ⇒ ซองรอยย่อหน้าชุดเดียวกับหน้าอ่าน (`api/paragraphs.json`) ⇒ ⛔ พิมพ์ชื่อฉบับไว้ใน `.md`
//   ⇒ ฉบับที่มีย่อหน้าของตัวเอง ⇒ ⛔ แสดงอะไรเลย ⇒ วันที่ต้นทางเปลี่ยน บรรทัดขึ้นหรือหายเอง
// ⭐ **ต้นแบบ** ⇒ `เลือกฉบับต้นแบบ` ตัวเดียวกับที่ `จัดย่อหน้าของฉบับ` ในหน้าอ่านใช้ ⇒ ⛔ แยกกันเดินได้
//   ⇒ หน้านี้ ⛔ มีคอลัมน์ ⇒ ส่งรายการคอลัมน์ว่าง ⇒ ได้ฉบับสำรองของหน้าอ่าน (TCV) ⇒ กติกาคอลัมน์ซ้ายสุดบอกเป็นตัวหนังสือในถ้อยคำ
import { เลือกฉบับต้นแบบ } from '~/utils/ย่อหน้า'
import { ถ้อยคำแหล่งข้อมูล } from '~/utils/ถ้อยคำแหล่งข้อมูล'
import { ที่อยู่หลังบ้าน } from '~/utils/ที่อยู่'

const props = defineProps<{ version: string }>()

const { data } = await useAsyncData('ย่อหน้าของฉบับ', () =>
  $fetch<{ ชั้น: string[]; ไม่มี: Record<string, string> }>(ที่อยู่หลังบ้าน('api/paragraphs.json')),
)

const ต้นแบบ = computed(() => {
  const ข = data.value
  if (!ข || !(props.version in ข.ไม่มี)) return ''
  return เลือกฉบับต้นแบบ([], ข.ไม่มี, ข.ชั้น)
})
</script>

<template>
  <p v-if="ต้นแบบ" class="pk-ย่อหน้าของฉบับ" :data-ย่อหน้าตาม="ต้นแบบ" :data-ฉบับ="version">
    {{ ถ้อยคำแหล่งข้อมูล.ย่อหน้าตาม(ต้นแบบ) }}
  </p>
</template>
