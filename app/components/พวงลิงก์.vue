<script setup lang="ts">
// พวงลิงก์ท้ายหน้า — **ของสำรองที่มาแทนหัวเมนูตอนหัวเมนูถูกซ่อน** ⛔ ไม่ใช่เมนูชุดที่สอง
//
// ⭐⭐ **อยู่ที่หน้าอ่านหน้าเดียว และโผล่เฉพาะจอแคบ** (พี่เอมทักเอง 12 ต.ค. 2569)
//   > *"อยากแก้แบบหน้าแรก มันซ้ำซ้อน สารบัญพระคัมภีร์ และ แหล่งข้อมูล เมนูก็มี"*
//   ⇒ **เขาถูก** ⇒ ของเดิมวางชุดนี้ไว้ทุกหน้า **ทั้งที่หัวเมนูข้างบนก็มีทางเดียวกันครบอยู่แล้ว**
//   ⇒ หน้าแรกจึงมีทางไป `/read` **3 ที่** และทางไป `/sources` **2 ที่** บนหน้าที่ยาวไม่ถึงจอเดียว
//
// **มาตรฐานที่ตัดสิน ⛔ ไม่ใช่รสนิยม**
//   1. **NN/g ข้อ 8 Aesthetic and minimalist design** ⇒ *Every extra unit of information in an
//      interface competes with the relevant units and diminishes their relative visibility*
//   2. **Krug — Don't Make Me Think** หัวข้อ *Clutter* ⇒ ให้ตั้งต้นว่า **ทุกชิ้นคือเสียงรบกวนไว้ก่อน**
//      แล้วเก็บเฉพาะชิ้นที่พิสูจน์ได้ว่าทำงานจริง
//   3. **WCAG 2.2 SC 2.4.5 Multiple Ways (ระดับ AA)** ⇒ *More than one way is available to locate
//      a web page within a set of web pages*
//      ⇒ ⛔ **ลิงก์ชุดเดิมวางซ้ำสองที่ ⛔ ไม่ใช่ "สองทาง"** ⇒ มันคือทางเดียวที่พิมพ์สองรอบ
//      ⇒ ทางที่หนึ่งจริง ๆ คือ **แถบนำทาง** · ทางที่สองคือ **หน้าสารบัญ 66 เล่ม** (`/read`)
//   4. **WCAG 2.2 SC 3.2.4 Consistent Identification (ระดับ AA)** ⇒ *Components that have the same
//      functionality within a set of web pages are identified consistently*
//      ⇒ ⛔ ของเดิมเรียกปลายทางเดียวกันว่า *สารบัญพระคัมภีร์* ที่นี่ แต่เรียกว่า *อ่านพระคัมภีร์*
//        บนแถบนำทาง ⇒ **ชื่อเดียวกันทั้งเว็บแล้ว**
//
// ⭐ **ที่ยังต้องมีชุดนี้** ⇒ จอแคบของหน้าอ่าน **ซ่อนหัวเมนู** ไว้ไม่ให้แถบหนึบสูงขึ้น (ใบงาน #76)
//   ⇒ ตัดชุดนี้ทิ้งด้วยเมื่อไร **จอแคบจะเหลือทางออกทางเดียวคือชื่อเว็บ** ⇒ `/sources` กลายเป็นหน้ากำพร้า
//   ⇒ ⛔ **จอกว้างจึงซ่อนชุดนี้** ⇒ ที่นั่นหัวเมนูเห็นครบอยู่แล้ว ⇒ เจ้าของกติกาคือ `main.css`
//
// ⭐⭐ **ลิงก์ *อ่านพระคัมภีร์* ที่นี่ เปิดแผงเดียวกับหัวเมนู** ⛔ ไม่ได้พาไปหน้าอื่น
//   ⇒ **ทั้งเว็บมีแผงเลือกพระธรรมแผงเดียว** ⇒ เหตุผลเต็มอยู่ที่ `app/components/แถบนำทาง.vue`
//   ⇒ ⛔ ปล่อยให้ที่นี่พาไปหน้าสารบัญ ก็กลับไปมี 2 หน้าตาเหมือนเดิม **เฉพาะบนจอแคบ**
//     ⇒ ซึ่งคือจอที่พี่เอมใช้จริงตอนทัก
import {
  ที่อยู่สารบัญ,
  ที่อยู่หน้าแรก,
  ที่อยู่หน้าแหล่งข้อมูล,
} from '~/utils/ที่อยู่'
import { ตั้งใจเปิดแท็บใหม่ } from '~/utils/กดลิงก์'

const emit = defineEmits<{ เปิดแผง: [] }>()

function กดอ่านพระคัมภีร์(e: MouseEvent) {
  if (ตั้งใจเปิดแท็บใหม่(e)) return
  e.preventDefault()
  emit('เปิดแผง')
}
</script>

<template>
  <!-- ⛔ **ลำดับต้องเหมือนแถบนำทาง** ⇒ WCAG 2.2 SC 3.2.3 Consistent Navigation (ระดับ AA) -->
  <nav class="pk-พวงลิงก์" aria-label="ลิงก์ของทั้งเว็บ">
    <a :href="ที่อยู่หน้าแรก()">หน้าแรก</a>
    <span class="pk-คั่น" aria-hidden="true">·</span>
    <a :href="ที่อยู่สารบัญ()" @click="กดอ่านพระคัมภีร์">อ่านพระคัมภีร์</a>
    <span class="pk-คั่น" aria-hidden="true">·</span>
    <!-- ⛔ **ลิงก์ *ฟังพระคำ* ถูกถอดแล้ว** (พี่เอมเคาะ 24 ต.ค. 2569 · ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/101)
         ⇒ ปุ่มเล่นอยู่ที่แถบล่างของหน้าอ่านเอง ⇒ ⛔ ไม่มีหน้าฟังแยกให้ลิงก์ไปอีกแล้ว -->
    <a data-ไป="แหล่ง" :href="ที่อยู่หน้าแหล่งข้อมูล()">แหล่งข้อมูล</a>
  </nav>
</template>
