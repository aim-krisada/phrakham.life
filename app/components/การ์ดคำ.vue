  กางที่มาศัพท์.value = false
  ข้อมูลคำ.value = null
  ผลของแหล่ง.value = {}
  สถานะคำ.value = 'กำลังโหลด'
  const กุญแจตอนขอ = `${props.เล่ม}/${props.บท}/${props.ชั้น}/${props.ข้อ}/${props.ลำดับ}`
  try {
