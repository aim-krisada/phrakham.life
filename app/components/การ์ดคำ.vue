 *   ⇒ ถ้อยคำมาจาก `app/utils/ศัพท์ไวยากรณ์.ts` ที่เดียว ⇒ ⛔ ไม่พิมพ์ซ้ำที่นี่
 *   ⇒ `ความหมาย: null` = ยังไม่มีคำอธิบาย ⇒ บอกตรง ๆ ⛔ ไม่เงียบ
 *   ⇒ ⛔ ประโยคที่แถวความหมายของกาลขึ้นแล้ว (คำสั่ง) ⇒ ไม่ขึ้นซ้ำ ⇒ หัวไฟล์ `ศัพท์ไวยากรณ์.ts`
 */
const ศัพท์ในการ์ด = computed(() => {
  if (props.ภาษา !== 'grc' || !รูปผันไทย.value) return []
  const ขึ้นแล้ว = กาลในการ์ด.value?.คำสั่ง ? ความหมายคำสั่ง : null
  return รูปผันไทย.value.ศัพท์
    .map((ศ) => ({ ...ศ, อธิบาย: อธิบายศัพท์(ศ.ชุด, ศ.รหัส) ?? null }))
    .filter((ศ) => ศ.อธิบาย?.ความหมาย !== ขึ้นแล้ว)
})
/** ⭐ ที่มาของคำอธิบายที่ขึ้นจริง ⇒ ไม่ซ้ำ ⇒ เรียงตามที่เจอ (เกณฑ์ข้อ 7.2) */
const ที่มาศัพท์ = computed(() => [...new Set(ศัพท์ในการ์ด.value.flatMap((ศ) => (ศ.อธิบาย ? [ศ.อธิบาย.ที่มา] : [])))])
/**
 * ⭐ เครื่องหมายของ Levinsohn บนคำนี้ (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/146 เกณฑ์ข้อ 12)
 *   ⇒ ทุกชนิดขึ้นชื่อต้นทางเสมอ ตามด้วยชื่อไทย ความหมาย และหน้าตา ⇒ ถ้อยคำมาจาก `app/utils/คำเน้น.ts` ที่เดียว
 *   ⇒ ⛔ รหัสที่ไม่รู้จัก ⇒ บอกตรง ๆ ⛔ ไม่เงียบ ⇒ ไม่มีเครื่องหมาย ⇒ ไม่มีแถวนี้
 *   ⇒ ชนิดเดียวกันซ้ำบนคำเดียว (หมายเหตุ 2 อัน) ⇒ ขึ้นทุกอัน
 */
const เครื่องหมายในการ์ด = computed(() =>
  props.ภาษา === 'grc' && props.จุด?.length
    ? props.จุด.map((จ) => ({ จ, ช: อ่านรหัส(จ.รหัส), เรา: ป้ายที่เราเติม(จ.รหัส) }))
    : undefined,
)
/** ⭐ คำเดียวมีได้หลายรหัส ⇒ กรีกคั่นด้วย `+` (เช่น `5228+1537+4053`) · ฮีบรูคั่นด้วย `|` (เช่น `1886a|0725`) */
const แยกรหัส = (รหัส: string) => (รหัส ? รหัส.split(/[+|]/).filter(Boolean) : [])
// ⛔ รหัสฮีบรูที่มีตัวอักษรท้าย ⛔ ไม่ใช่เลข Strong ⇒ เหตุผลอยู่หัว `tools/สร้างพจนานุกรม.py`
const มีตัวอักษร = (ร: string) => /[a-z]$/.test(ร)
const รหัสมีตัวอักษร = computed(() => แยกรหัส(ข้อมูลคำ.value?.รหัส ?? '').some(มีตัวอักษร))
// ⭐ ใบ #178 ⇒ ตัวคิดเลขย้ายไป `app/utils/เลขStrong.ts` ⇒ เลขท้ายคำบนหน้า (สวิตช์ *แสดงเลข Strong*) ใช้ตัวเดียวกัน ⇒ ตรงกับการ์ดเสมอ
const เลขStrong = computed(() => เลขStrongจากรหัส(ข้อมูลคำ.value?.รหัส ?? '', props.ภาษา))
const ชื่อMACULA = computed(() => (props.ภาษา === 'grc' ? 'MACULA Greek' : 'MACULA Hebrew'))

async function โหลดแหล่ง(id: string) {
  const แ = ตารางแหล่ง[id]?.[props.ภาษา]
  const คำ = ข้อมูลคำ.value
  if (!แ || !คำ) return
  const ตั้ง = (ผล: ผลแหล่ง) => (ผลของแหล่ง.value = { ...ผลของแหล่ง.value, [id]: ผล })
  ตั้ง({ สถานะ: 'กำลังโหลด' })
  try {
    if (id === 'ubs') {
      if (!คำ.UBS) return ตั้ง({ สถานะ: 'ไม่มี', เหตุ: 'UBS ไม่มีความหมายที่ผูกไว้กับคำนี้ในข้อนี้' })
      const ก้อน = await หยิบก้อน(แ.ไฟล์, Math.floor(Number(คำ.UBS) / 1e6 / 100))
      const ของ = ก้อน?.[คำ.UBS] as ความหมายUBS | undefined
      return ตั้ง(ของ ? { สถานะ: 'UBS', ของ } : { สถานะ: 'ไม่มี', เหตุ: 'UBS ไม่มีคำนี้' })
    }
    const ส่วน = แยกรหัส(คำ.รหัส)
    const พบ: { รหัส: string; รายการ: รายการพจนานุกรม[] }[] = []
    for (const ร of ส่วน) {
      const กุญแจ = กุญแจของรหัส(ร)
      const ก = ก้อนของกุญแจ(กุญแจ)
      if (ก === null) continue
      const ก้อน = await หยิบก้อน(แ.ไฟล์, ก)
      const รายการ = ก้อน?.[กุญแจ] as รายการพจนานุกรม[] | undefined
      if (รายการ?.length) พบ.push({ รหัส: ร, รายการ })
    }
    if (พบ.length) return ตั้ง({ สถานะ: 'รายการ', ของ: พบ })
    const เหตุ =
      id === 'strong' && รหัสมีตัวอักษร.value
        ? `${แ.ชื่อ} ไม่มีคำนี้ ⇒ รหัส ${คำ.รหัส} เป็นรหัสที่ฐานข้อมูลคำเติมเอง ⛔ ไม่ใช่เลข Strong`
        : `${แ.ชื่อ} ไม่มีคำนี้`
    ตั้ง({ สถานะ: 'ไม่มี', เหตุ })
  } catch {
    ตั้ง({ สถานะ: 'พัง' })
  }
}

