// ⭐ **ข้อความ = ของที่การ์ดแสดง ⇒ ชื่อแถวเดิม** (ข้อ 8) ⇒ ทรงของข้อความอยู่ `app/utils/แชร์คำ.ts`
// ⭐ **เครดิตหยิบตอนการ์ดขึ้น** ⇒ Safari เปิดเมนูแชร์ได้เฉพาะตอนที่ยังนับว่าคนเพิ่งกด ⇒ ตอนกดต้องมีของพร้อมแล้ว
//   ⇒ ไฟล์เล็ก ⇒ หยิบครั้งเดียวต่อการเปิดหน้า ⇒ คนที่ไม่กดคำ ⛔ ไม่ต้องโหลด (การ์ดทั้งก้อนโหลดตอนกดคำเท่านั้น)
const ชื่อปุ่มแชร์ = `${ถ้อยคำแชร์.ปุ่ม} การ์ดความหมายคำ`
let เครดิตที่หยิบ: Promise<Record<string, แหล่งที่ต้องให้เครดิต> | null> | null = null
function หยิบเครดิต() {
  if (!เครดิตที่หยิบ) {
    เครดิตที่หยิบ = $fetch<Record<string, แหล่งที่ต้องให้เครดิต>>(ที่อยู่หลังบ้าน('api/credits.json')).catch(() => {
      เครดิตที่หยิบ = null
      return null
    })
  }
  return เครดิตที่หยิบ
}
onMounted(() => void หยิบเครดิต())

/** คำอ่านไทยแบบตัวหนังสือล้วน ⇒ ตรงกับที่การ์ดแสดงในวงเล็บ ⇒ ฮีบรู · ถอดไม่ได้ ⇒ ว่าง ⇒ ⛔ ไม่มีวงเล็บ */
function อ่านเป็นข้อความ(คำ: string) {
  if (props.ภาษา !== 'grc' || !คำ) return ''
  try {
    return อ่านกรีก(คำ).พยางค์.join('-')
  } catch {
    return ''
  }
}

async function ข้อความแชร์(): Promise<string> {
  const ค = ข้อมูลคำ.value
  const ต้น = location.origin
  const เครดิตทั้งหมด = await หยิบเครดิต()
  const แถว: [string, string][] = [['คำแปลกำกับ', props.คำแปล || '—']]
  if (ค) {
    แถว.push(['รูปพจนานุกรม', ค.รูปพจนานุกรม ? คำกับคำอ่าน(ค.รูปพจนานุกรม, อ่านเป็นข้อความ(ค.รูปพจนานุกรม)) : '—'])
    แถว.push([
      'เลข Strong',
      `${เลขStrong.value || '—'}${รหัสมีตัวอักษร.value ? ' (รหัสที่มีตัวอักษรท้าย ⛔ ไม่ใช่เลข Strong ⇒ ฐานข้อมูลคำเติมเอง)' : ''}`,
    ])
    const ส่วน = รูปผันไทย.value?.ส่วน.length ? รูปผันไทย.value.ส่วน.join(' · ') : '—'
    แถว.push(['รูปผัน', ค.รูปผัน ? `${ส่วน} · รหัส ${ค.รูปผัน}` : ส่วน])
  }
  if (เครื่องหมายในการ์ด.value)
    แถว.push([
      หัวแถวการ์ด,
      เครื่องหมายในการ์ด.value
        .map(({ จ, ช }) =>
          ช ? `${ช.ต้นทาง} · ${ช.ชื่อ} ${ช.ความหมาย}${จ.โน้ต ? ` ${จ.โน้ต}` : ''}` : `⛔ อ่านรหัสเครื่องหมาย ${จ.รหัส} ไม่ออก`,
        )
        .join('\n'),
    ])
  // ⭐ เครดิตที่เจ้าของบังคับ (ข้อ 9) ⇒ ข้อมูลคำของ MACULA ทุกคำ ⇒ LGNTDF เฉพาะคำที่มีเครื่องหมาย
  //   ⇒ หยิบไม่สำเร็จ ⇒ ชี้ไปหน้าแหล่งข้อมูลที่มีเครดิตเต็ม ⇒ ท่าเดียวกับแชร์ข้อ ⇒ ⛔ ไม่ส่งข้อมูลเปล่า ๆ
  const เครดิต = [ชื่อMACULA.value, ...(เครื่องหมายในการ์ด.value ? ['LGNTDF'] : [])].map(
    (ชื่อ) => เครดิตทั้งหมด?.[ชื่อ] ?? { ชื่อ, สัญญา: '', ลิงก์สัญญา: '', เครดิต: ต้น + ที่อยู่หน้าแหล่งข้อมูล() },
  )
  return ประกอบข้อความคำ({
    ตัว: props.ตัว,
    อ่าน: อ่านเป็นข้อความ(props.ตัว),
    ชื่อเล่ม: props.ชื่อเล่ม,
    บท: props.บท,
    ข้อ: props.ข้อ,
    แถว,
    เครดิต,
    ลิงก์: ต้น + ที่อยู่คำที่แชร์(
      props.เล่ม,
      { บท: props.บท, ข้อ: Number(props.ข้อ), คำที่: props.ลำดับ + 1 },
      props.ฉบับ ?? [],
      props.ที่ในลิงก์,
    ),
  })
}

