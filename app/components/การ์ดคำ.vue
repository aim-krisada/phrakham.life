//     ⇒ ตั้ง `scroll-padding-top` ของแผ่นเท่าความสูงหัวจริง ⇒ หัวห่อหลายบรรทัดตอนจอแคบหรือตัวอักษรใหญ่ ⇒ วัดใหม่ทุกครั้ง
