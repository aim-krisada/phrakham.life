// ---------------------------------------------------------------- กดที่อื่นแล้วปิด (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/129)
// ⭐⭐ **แตะที่ใดก็ได้นอกการ์ดและนอกคำภาษาเดิม ⇒ การ์ดปิด** ⇒ ไม่ต้องเลื่อนกลับขึ้นไปหาปุ่ม *ปิด*
//   ⇒ ท่า *light dismiss* ของ HTML popover ⇒ **ต้องเริ่มกดนอกการ์ด และปล่อยนอกการ์ด** ⇒ กดในการ์ดแล้วลากออก ⛔ ไม่ปิด
//   ⇒ ⭐ ตัดสินที่ `click` ⛔ ไม่ใช่ `pointerdown` (ต่างจากเมนูในหน้าอ่าน) ⇒ ลากนิ้วเลื่อนหน้า เบราว์เซอร์ยกเลิกการกด
//     ⇒ ⛔ ไม่เกิด `click` ⇒ **เลื่อนหน้าหรือเลื่อนในการ์ด ⛔ ไม่ปิด** (เกณฑ์ข้อ 4.3)
//   ⇒ ⛔⛔ **การกดที่ปิดการ์ด ⛔ ไม่ไปกดของข้างใต้** (เกณฑ์ข้อ 4.2) ⇒ ดักที่ `document` ช่วงจับ (capture)
//     ⇒ กลืน `click` ทั้งก้อน ⇒ ปุ่ม ลิงก์ ช่องติ๊ก ข้างใต้ ⛔ ไม่ได้ยินการกดนี้เลย
//   ⇒ **คำภาษาเดิม ⛔ ไม่ดัก** ⇒ การ์ดเปลี่ยนคำตามเดิม ⛔ ไม่ถูกถอดแล้วขึ้นใหม่ ⇒ ⛔ ไม่กระพริบ (เกณฑ์ข้อ 4.1)
//   ⇒ ปิดผ่าน `emit('ปิด')` ทางเดียวกับปุ่ม *ปิด* และ Esc ⇒ หน้าอ่านคืนโฟกัสให้คำเดิม (เกณฑ์ข้อ 4.4)
//   ⇒ ⛔ **คลิกที่เกิดจากแป้นพิมพ์ ⛔ ไม่นับ** ⇒ Enter กับ Space บนปุ่มก็ส่ง `click` ⇒ แต่ ⛔ ไม่มี `pointerdown` นำ
//     ⇒ Tab ออกจากการ์ดแล้วกดปุ่มอื่นได้ตามปกติ ⇒ การ์ดไม่ปิดกั้นหน้า (`aria-modal="false"`) ⇒ เกณฑ์ข้อ 6
//   ⇒ ตัวเฝ้าคือ `tools/ด่านการ์ดคำปิดนอกการ์ด.mjs` ⇒ จอ 375 แบบจอสัมผัส · จอ 1280 แบบเมาส์
/** ที่กดอยู่ใน *ที่ของการ์ด* ไหม ⇒ ตัวการ์ด · คำภาษาเดิม (กดแล้วเปลี่ยนคำ) · หน้าต่างอื่นที่ลอยอยู่ เช่นแผ่นเรื่องเล่า */
function ในที่ของการ์ด(เป้า: EventTarget | null) {
  if (!(เป้า instanceof Element)) return true
  if (แผ่น.value?.contains(เป้า)) return true
  return !!เป้า.closest('button.pk-คำ, dialog, [role="dialog"]')
}

/** จุดเริ่มกดนอกการ์ด ⇒ `null` = การกดล่าสุด ⛔ ไม่ได้เริ่มนอกการ์ด */
let เริ่มกดนอก: { x: number; y: number } | null = null
/** ⭐ ขยับเกินนี้ = ลาก ⛔ ไม่ใช่แตะ ⇒ เช่นลากคลุมตัวหนังสือ ⇒ ⛔ ไม่ปิด และ ⛔ ไม่กลืน */
const ระยะลาก = 10

function เริ่มกด(e: PointerEvent) {
  เริ่มกดนอก = null
  if (!e.isPrimary || e.button !== 0 || ในที่ของการ์ด(e.target)) return
  // ⛔ กดบนแถบเลื่อนของหน้าหรือของกล่อง ⇒ คือการเลื่อน ⛔ ไม่ใช่กดที่อื่น
  //   ⇒ จุดกดเลยขอบในของกล่อง = อยู่บนแถบเลื่อน ⇒ ของแบบอินไลน์มี `clientWidth` เป็น 0 ⇒ ⛔ ไม่เอามาเทียบ
  const ก = e.target as Element
  if ((ก.clientWidth && e.offsetX > ก.clientWidth) || (ก.clientHeight && e.offsetY > ก.clientHeight)) return
  if (e.target === document.documentElement && e.clientX >= document.documentElement.clientWidth) return
  เริ่มกดนอก = { x: e.clientX, y: e.clientY }
}

function เลิกกด() {
  เริ่มกดนอก = null
}

function กดที่อื่น(e: MouseEvent) {
  const เริ่ม = เริ่มกดนอก
  เริ่มกดนอก = null
  // ⛔ `detail === 0` = คลิกจากแป้นพิมพ์หรือจากโค้ด ⇒ ⛔ ไม่ใช่นิ้วหรือเมาส์
  if (!เริ่ม || e.detail === 0 || ในที่ของการ์ด(e.target)) return
  if (Math.hypot(e.clientX - เริ่ม.x, e.clientY - เริ่ม.y) > ระยะลาก) return
  e.preventDefault()
  e.stopImmediatePropagation()
  emit('ปิด')
}

onMounted(() => {
  document.addEventListener('pointerdown', เริ่มกด, true)
  document.addEventListener('pointercancel', เลิกกด, true)
  document.addEventListener('click', กดที่อื่น, true)
})
onBeforeUnmount(() => {
  document.removeEventListener('pointerdown', เริ่มกด, true)
  document.removeEventListener('pointercancel', เลิกกด, true)
  document.removeEventListener('click', กดที่อื่น, true)
})

