async function หยิบ<T>(ทาง: string): Promise<T | null> {
  try {
    return await $fetch<T>(ที่อยู่หลังบ้าน(ทาง))
  } catch (e: unknown) {
    // ⭐ 404 = **ไม่มีไฟล์นี้จริง** ⇒ เป็นคำตอบ ⛔ ไม่ใช่ความพัง ⇒ เช่นก้อนที่ไม่มีคำเลข Strong ช่วงนั้น
    if ((e as { statusCode?: number })?.statusCode === 404) return null
    throw e
  }
}

function หยิบการ์ด(เล่ม: string, บท: number) {
  const k = `${เล่ม}/${บท}`
  if (!ที่เก็บการ์ด.has(k)) {
    const p = หยิบ<ข้อมูลการ์ด>(`api/card/${เล่ม}/${บท}.json`)
    p.catch(() => ที่เก็บการ์ด.delete(k))
    ที่เก็บการ์ด.set(k, p)
  }
  return ที่เก็บการ์ด.get(k)!
}

function หยิบก้อน(ไฟล์: string, ก้อน: number) {
  const k = `${ไฟล์}/${ก้อน}`
  if (!ที่เก็บก้อน.has(k)) {
    const p = หยิบ<{ คำ: Record<string, unknown> }>(`api/lex/${ไฟล์}/${ก้อน}.json`).then((x) => x?.คำ ?? null)
    p.catch(() => ที่เก็บก้อน.delete(k))
    ที่เก็บก้อน.set(k, p)
  }
  return ที่เก็บก้อน.get(k)!
}

