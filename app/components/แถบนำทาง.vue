function จัดค้นหา() {
  const ก = แถบ.value
  if (!ก || !props.มีเครื่องมือ) return
  const ชื่อ = ก.querySelector<HTMLElement>(':scope > .pk-ชื่อเว็บ')
  const กลุ่ม = ก.querySelector<HTMLElement>(':scope > .pk-ปุ่มบนแถบ')
  if (!ชื่อ || !กลุ่ม) return
  // ⭐ ลองวางครบก่อน ⇒ วัด ⇒ ตัดสิน ⇒ ทั้งหมดในจังหวะเดียว ⇒ เบราว์เซอร์ยังไม่ได้วาด ⇒ ⛔ กะพริบ
  ก.classList.remove(คลาสหลบ)
  const ล่างชื่อ = ชื่อ.getBoundingClientRect().bottom
  const แตก = [...กลุ่ม.children].some((x) => x.getClientRects().length > 0 && x.getBoundingClientRect().top >= ล่างชื่อ - 2)
  ก.classList.toggle(คลาสหลบ, แตก)
}
