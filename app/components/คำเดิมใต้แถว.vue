//   ⇒ ⭐ **ย้ายในโครงหน้าจริง ⛔ ไม่ใช่ย้ายด้วยหน้าตา** ⇒ โปรแกรมอ่านหน้าจออ่านคำเดิมของข้อ n หลังตัวบทข้อ n
