//   ⇒ ⭐ **จัดการเลื่อนกับโฟกัสเอง ⛔ ปล่อยให้เบราว์เซอร์ไปตาม `#`** ⇒ แผ่นเป็น `<dialog>` ที่เลื่อนในกล่องเอง ⇒ และ `#` ในที่อยู่
