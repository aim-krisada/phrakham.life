      <template v-else>
        <!-- ⭐ ปุ่มเดียว ⇒ ฟังเรื่องเล่า · หยุดพัก · ฟังต่อ ⇒ ท่าเดียวกับปุ่มฟังพระคำบนแถบล่าง
             ⛔ **เรื่องที่ยังไม่มีเสียง ⛔ ไม่มีปุ่ม** ⇒ ⛔ ไม่มีปุ่มที่กดแล้วเงียบ
             ⛔ **ต้องสั่งเล่นในจังหวะเดียวกับการกด** ⇒ ตัวเรื่องโหลดเสร็จก่อนปุ่มนี้โผล่ ⇒ หน้าอ่านสั่งเล่นทันที ⛔ ไม่รออะไร -->
        <div v-if="เรื่อง.เสียง" class="pk-ฟังเรื่องเล่า">
          <Button
            type="button"
            variant="เข้ม"
            class="pk-ปุ่มฟัง"
            data-ปุ่ม="ฟังเรื่องเล่า"
            :data-สถานะ="สถานะเสียง"
            @click="emit('ฟัง', เรื่อง)"
          >
            <span aria-hidden="true">{{ สถานะเสียง === 'กำลังเล่น' ? '❚❚' : '▶' }}</span>
            {{ คำบนปุ่ม }}
          </Button>
          <!-- ⭐ **บอกตรง ๆ ว่าเป็นเสียงที่เครื่องอ่าน** ⇒ ⛔ ไม่ใช่เสียงคนอ่าน -->
          <p class="pk-หมายเหตุเสียงเรื่องเล่า">ยาว {{ ความยาว }} · เสียงอ่านจากเครื่องอ่านอัตโนมัติ</p>
        </div>
        <!-- ⭐ ใบ #168 ⇒ เลขเชิงอรรถเป็นเลขยกที่กดได้ ⇒ ⛔ ไม่ใช้ v-html ⇒ ตัวเรื่องเป็นข้อความล้วน ⇒ ⛔ ไม่มีทางฝังโค้ดผ่านไฟล์เรื่อง -->
        <p v-for="(ชุด, i) in ย่อหน้าเป็นชิ้น" :key="i" class="pk-ย่อหน้าเรื่องเล่า" data-ตัวเรื่องเล่า>
          <template v-for="(ช, j) in ชุด" :key="j">
            <sup v-if="'ป้าย' in ช" class="pk-เลขเชิงอรรถ"><a
              :id="ช.ไอดี"
              :href="`#${ไอดีเชิงอรรถ(ช.ป้าย)}`"
              :aria-label="ถ้อยคำเชิงอรรถ.เลข(ช.ลำดับ)"
              data-เลขเชิงอรรถ
              @click.prevent="ไปเชิงอรรถ(ช.ป้าย, ช.ไอดี)"
            >{{ ช.ลำดับ }}</a></sup>
            <template v-else>{{ ช.ข้อความ }}</template>
          </template>
        </p>
        <!-- ⭐ เชิงอรรถท้ายเรื่อง ⇒ ⛔ อยู่นอก `data-ตัวเรื่องเล่า` ⇒ ⛔ ไม่ใช่ตัวเรื่อง ⇒ ⛔ ไม่อ่านออกเสียง
             ⇒ `<ol>` ⇒ เลขหน้ารายการตรงกับเลขยก ⇒ โปรแกรมอ่านหน้าจอบอกได้ว่ามีกี่อัน
             ⇒ `tabindex="-1"` ⇒ รับโฟกัสได้ตอนกดเลขยก ⛔ ไม่เพิ่มจุดหยุดของปุ่มแท็บ -->
        <section
          v-if="เรื่อง.เชิงอรรถ?.length"
          class="pk-เชิงอรรถเรื่องเล่า"
          aria-labelledby="pk-หัวเชิงอรรถเรื่องเล่า"
          data-เชิงอรรถเรื่องเล่า
        >
          <h3 id="pk-หัวเชิงอรรถเรื่องเล่า">{{ ถ้อยคำเชิงอรรถ.หัว }}</h3>
          <ol>
            <li
              v-for="(ช, i) in เรื่อง.เชิงอรรถ"
              :id="ไอดีเชิงอรรถ(ช.ป้าย)"
              :key="ช.ป้าย"
              tabindex="-1"
              data-เชิงอรรถ
            >
              {{ ช.ข้อความ }}
              <a
                :href="`#${กดมาจาก[ช.ป้าย] || `pk-อ้างเชิงอรรถ-${ช.ป้าย}-1`}`"
                class="pk-กลับจากเชิงอรรถ"
                :aria-label="ถ้อยคำเชิงอรรถ.กลับ(i + 1)"
                data-กลับเชิงอรรถ
                @click.prevent="กลับจากเชิงอรรถ(ช.ป้าย)"
              ><span aria-hidden="true">↩</span></a>
            </li>
          </ol>
        </section>
      </template>
    </div>
  </dialog>
</template>
