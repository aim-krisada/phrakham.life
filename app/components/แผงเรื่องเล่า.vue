//   ⇒ ⭐ ถ้อยคำ 3 ชิ้นข้างล่าง ⇒ G เขียน N ตรวจ (บันทึกแนบในคำขอรวมของใบ #168) ⇒ เลี่ยงคำว่า *ข้อ* เพราะชนกับเลขข้อพระคัมภีร์
const ถ้อยคำเชิงอรรถ = {
  หัว: 'คำอธิบายเพิ่มเติม',
  เลข: (ลำดับ: number) => `อ่านคำอธิบายเพิ่มเติม ลำดับที่ ${ลำดับ}`,
  กลับ: (ลำดับ: number) => `กลับไปที่เนื้อเรื่อง ลำดับที่ ${ลำดับ}`,
