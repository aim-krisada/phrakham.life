// ⭐⭐ **เชิงอรรถ** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/168) ⇒ ท่าเดียวกับเชิงอรรถของ GitHub/pandoc
//   ⇒ `[^ป้าย]` ในตัวเรื่อง ⇒ เลขยกที่เป็นลิงก์ ⇒ กดแล้วเลื่อนลงไปที่เชิงอรรถท้ายเรื่อง **และโฟกัสย้ายไปที่นั่น**
