type ชิ้นย่อหน้า = { ข้อความ: string } | { ป้าย: string; ลำดับ: number; ไอดี: string }
const รอยเลขเชิงอรรถ = /(\[\^[^\]\s]+\])/

const ไอดีเชิงอรรถ = (ป้าย: string) => `pk-เชิงอรรถ-${ป้าย}`
/** ย่อหน้าแตกเป็นชิ้น ⇒ ข้อความ กับเลขเชิงอรรถ ⇒ ⛔ ไม่แก้ตัวหนังสือสักตัว แค่แยกเลขออกมาวาดเป็นลิงก์ */
const ย่อหน้าเป็นชิ้น = computed<ชิ้นย่อหน้า[][]>(() => {
  const ร = เรื่อง.value
  if (!ร) return []
  const ลำดับ = new Map((ร.เชิงอรรถ || []).map((x, i) => [x.ป้าย, i + 1]))
  const นับ = new Map<string, number>()
  return ร.ย่อหน้า.map((ย) =>
    ย.split(รอยเลขเชิงอรรถ).filter(Boolean).map((ส่วน): ชิ้นย่อหน้า => {
      const ป้าย = /^\[\^([^\]\s]+)\]$/.exec(ส่วน)?.[1]
      if (!ป้าย || !ลำดับ.has(ป้าย)) return { ข้อความ: ส่วน }
      const ครั้ง = (นับ.get(ป้าย) || 0) + 1
      นับ.set(ป้าย, ครั้ง)
      return { ป้าย, ลำดับ: ลำดับ.get(ป้าย)!, ไอดี: `pk-อ้างเชิงอรรถ-${ป้าย}-${ครั้ง}` }
    }),
  )
})
/** เลขที่ผู้อ่านกดมาล่าสุดของแต่ละเชิงอรรถ ⇒ ลิงก์ ↩ พากลับไปที่นั่น */
const กดมาจาก = reactive<Record<string, string>>({})

function ไปที่(ไอดี: string) {
  const ที่ = document.getElementById(ไอดี)
  if (!ที่) return
  ที่.scrollIntoView({ block: 'center', behavior: 'auto' })
  ที่.focus({ preventScroll: true })
}
function ไปเชิงอรรถ(ป้าย: string, จาก: string) {
  กดมาจาก[ป้าย] = จาก
  ไปที่(ไอดีเชิงอรรถ(ป้าย))
}
function กลับจากเชิงอรรถ(ป้าย: string) {
  ไปที่(กดมาจาก[ป้าย] || `pk-อ้างเชิงอรรถ-${ป้าย}-1`)
}

/** ⭐ ปิดทุกทางไหลมาที่นี่ ⇒ ปุ่มปิด · Esc (เบราว์เซอร์ปิดเอง) · แตะนอกแผ่น */
function ปิด() {
  if (กล่อง.value?.open) กล่อง.value.close()
}

/** แตะนอกแผ่น ⇒ ฉากหลัง (`::backdrop`) ส่งคลิกมาที่ตัว `<dialog>` เอง
 *  ⇒ ข้างในแผ่นมีกล่องเนื้อคลุมเต็มพื้นที่ ⇒ คลิกในแผ่นจึง ⛔ ไม่เคยมีเป้าเป็นตัว `<dialog>` */
function กดที่กล่อง(e: MouseEvent) {
  if (e.target === กล่อง.value) ปิด()
}

onMounted(async () => {
  const ก = กล่อง.value
  if (ก) {
    // ⭐ ล็อกหน้าข้างหลัง ⇒ เลื่อนนิ้วบนฉากหลังแล้วตัวบท ⛔ ไม่ไหลไป (รอบ 2 ข้อ 2.1)
    // ⛔⛔ **ต้องเติมช่องแทนแถบเลื่อนที่หายไป** ⇒ จอที่แถบเลื่อนกินที่ (คอมพิวเตอร์ส่วนใหญ่) ซ่อนแล้วหน้ากว้างขึ้นราว 15 จุด
    //   ⇒ ตัวบทจัดบรรทัดใหม่ ⇒ ที่เลื่อนขยับ ⇒ ลองท่า `scrollbar-gutter` แล้ว (25 ต.ค. 2569) จอที่ไม่มีแถบเลื่อนกลับหดลง 15 จุด
    //     ⇒ แถบบนสูงขึ้น 108 เป็น 159 และปิดแผ่นแล้วหน้ากระโดดไปไกล 6,000 จุด ⇒ จึงวัดของจริงแล้วเติมเท่าที่หายไปเท่านั้น
    const แถบเลื่อน = window.innerWidth - document.documentElement.clientWidth
    if (แถบเลื่อน > 0) document.documentElement.style.paddingRight = `${แถบเลื่อน}px`
    document.documentElement.classList.add('pk-ล็อกการเลื่อน')
    ก.showModal()
    หัว.value?.focus({ preventScroll: true })
  }
  try {
    เรื่อง.value = await $fetch<ตัวเรื่อง>(props.ที่อยู่เรื่อง)
  } catch {
    // ⛔ โหลดไม่ได้ ⇒ **บอกตรง ๆ** และตัวบทพระคัมภีร์ยังอ่านต่อได้ ⛔ ห้ามหน้าพัง
    พัง.value = 'เปิดเรื่องเล่าไม่ได้ตอนนี้ ปิดแผ่นแล้วลองกดใหม่อีกครั้ง ตัวบทพระคัมภีร์ยังอ่านต่อได้ตามปกติ'
  }
})

onBeforeUnmount(() => {
  document.documentElement.classList.remove('pk-ล็อกการเลื่อน')
  document.documentElement.style.paddingRight = ''
  if (กล่อง.value?.open) กล่อง.value.close()
})
</script>

