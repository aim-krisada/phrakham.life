/** คำที่ตัวนี้ย่อไว้ ⇒ จัดรอบใหม่คืนขนาดจริงก่อนแล้ววัดใหม่ ⇒ ⛔ ไม่ค้างขนาดเก่าตอนจอกว้างขึ้น */
