      e.getBoundingClientRect().width -
      parseFloat(ส.paddingLeft) -
      parseFloat(ส.paddingRight) -
      parseFloat(ส.borderLeftWidth) -
      parseFloat(ส.borderRightWidth)
    จำ.set(e, ได้)
  }
  return ได้
}

/** ความกว้างที่คำกินในบรรทัด ⇒ รวมระยะข้างของปุ่มคำ */
