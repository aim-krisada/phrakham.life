/** ⭐ ข้อ 11.13 ⇒ ย่อเฉพาะคำที่กว้างเกินที่ ⇒ ตั้งทุกคำก่อน อ่านทุกคำทีเดียว ⇒ หน้าคำนวณผังรอบละครั้ง */
