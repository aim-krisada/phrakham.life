  }
  // ⭐⭐ **หาขนาดใหญ่สุดที่พอที่ ⇒ เดาตามสัดส่วนแล้วบีบช่วงจากสองข้าง** ⇒ ⛔ ย่อลงทางเดียว
  //   ⇒ ⚠️ ของเดิม (ถึง 20 พ.ย. 2569) ⇒ ล้นเมื่อไรก็ย่อต่อตามสัดส่วน × 0.99 ⇒ ⛔ เคยขยายกลับ
  //     ⇒ บนลินุกซ์ความกว้างตัวหนังสือ *ไม่* ตามขนาดเป็นเส้นตรง (ระยะตัวอักษรปัดเป็นจุดเต็มทีละตัว ⇒ ความกว้างขึ้นเป็นขั้น)
  //     ⇒ ท่อ GitHub รอบ 44680588981 ⇒ הִנָּקֵ֖ם (avenge.themselves) ⇒ คำแปลที่ 13.13 จุดกว้าง 121 ⇒ ที่ 10.08 จุดกว้าง 87
  //       ⇒ ต่อจุดแคบลง 6% ⇒ รอบแรกยังล้น ⇒ รอบสองย่อข้ามลงไปขั้นล่าง ⇒ เหลือ 101 ในที่ 112 (ย่อเกินจำเป็น)
