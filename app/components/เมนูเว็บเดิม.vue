<script setup lang="ts">
// ⭐⭐ **เมนูของเว็บเดิมบนเว็บใหม่** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/163 ⇒ m1.wpa.24.us15)
//   ⇒ @krisada ขอ 9 พ.ย. 2569 *"อยากให้เอาเมนูของพระคำเดิมกลับมา"* ⇒ เว็บเดิมยังมีความรู้ประกอบ รูปภาพ แผนที่
//   ⇒ รายการ ถ้อยคำ และทาง ⇒ `app/utils/ถ้อยคำเมนูเว็บเดิม.ts` · ที่อยู่ของเว็บเดิมกับเว็บเพลง ⇒ `app/utils/ที่อยู่.ts`
//
// ⭐ **รูปของมัน ⇒ ปุ่ม ≡ *เมนู* ปุ่มเดียว ท้ายสุดของกลุ่มปุ่มบนแถบบน ทุกหน้า ทุกจอ** ⇒ กดแล้วกางแผง
//   ⇒ @krisada เลือกทางแชตกับ AI 9 พ.ย. 2569 (ดูภาพจอ Gmail บนมือถือเป็นต้นแบบ)
//     ⇒ *"เห็นด้วย"* (ย้าย อ่านพระคัมภีร์ · แหล่งข้อมูล เข้า ≡ บนจอแคบ)
//     ⇒ *"ใส่ชื่อตรงหัวเมนูได้ และจะได้รู้ด้วยว่าโปรแกรมอะไร"* (ชื่อเว็บเป็นหัวของแผง)
//     ⇒ *"ผมว่า hamburger อยู่ขวาไม่ดีกว่าหรอ"* (≡ ขวาสุด)
//   ⇒ **ในแผงเรียงจากบน** ⇒ ชื่อเว็บ (ลิงก์กลับหน้าแรก ⇒ แถวเดียวกับ ×) · จอแคบของหน้าที่ไม่มีเครื่องมือ ⇒ อ่านพระคัมภีร์ · แหล่งข้อมูล · แล้วเมนูของเว็บเดิม
//   ⇒ **ปุ่มรูป ≡ ตามกติกาคำข้างรูปของใบ #155** ⇒ จอแคบกว่า 1100 รูปอย่างเดียว · ตั้งแต่ 1100 รูปพร้อมคำ *เมนู*
//   ⇒ **ทรง WAI-ARIA APG *Disclosure Navigation Menu*** ⇒ ปุ่มจริง (ชิ้น `Button` กลางของเว็บ) บอกสถานะด้วย `aria-expanded`
//     ⇒ `aria-controls` ชี้แผงตอนกาง ⇒ รายการเป็นลิงก์ธรรมดาใน `<ul>` ⇒ ⛔ ไม่ใช่ `role="menu"` ⇒ ⛔ ไม่มี `aria-haspopup` (SC 4.1.2)
//   ⇒ **กล่องที่กางคือกล่องเด้งชิ้นเดียวกับ Aa · เทียบ** (`กล่องเด้ง.vue` ⇒ การเคาะของใบ #153)
//     ⇒ จอแคบกว่า 768 ⇒ หน้าเต็มจอใต้แถบบน · จอกว้าง ⇒ แผงลงมาใต้ปุ่ม ⛔ ทับปุ่ม ⇒ ปิดด้วย × · Escape · กดนอกกล่อง · กดลิงก์ในแผง
//     ⇒ ปิดด้วย × หรือ Escape ⇒ โฟกัสกลับปุ่ม ⇒ WCAG 2.2 SC 2.1.1 · 2.1.2 · 2.4.3
//   ⇒ **ความรู้ประกอบ ⇒ หัวกลุ่มที่เห็นรายการย่อยทันที** ⇒ หัวกลุ่มเป็นชื่อของรายการย่อย (`aria-labelledby`)
//   ⇒ ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/165 (@krisada 10 พ.ย. 2569) ⇒ *ความรู้ประกอบ* ซ่อนไว้ก่อน (`เปิด: false` ⇒ สวิตช์อยู่ที่ไฟล์ถ้อยคำ)
//     ⇒ *เกี่ยวกับเรา* เป็นหัวกลุ่มแบบเดียวกัน ⇒ เกี่ยวกับเรา · แหล่งข้อมูล (หน้าของเว็บนี้ทั้งคู่ ⇒ บนหน้าของตัวเอง ⇒ ตัวหนังสือติด `aria-current` ⛔ ลิงก์วนกลับ)
//     ⇒ ⭐ ใบ #172 ⇒ *เกี่ยวกับเรา* ไปหน้า `/about` ของเว็บนี้ ⛔ ไปเว็บเดิมแล้ว
//     ⇒ ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/177 ⇒ *เล่าประสบการณ์* ไปหน้า `/reflections` ของเว็บนี้ ⛔ ไปเว็บเดิมแล้ว
//       ⇒ บนหน้ารวมเอง ⇒ ตัวหนังสือติด `aria-current` ⛔ ลิงก์วนกลับ ⇒ หน้าบทความ ⇒ ยังเป็นลิงก์ (คนละหน้ากับหน้ารวม)
//   ⇒ ⭐ **ลิงก์เปิดในแท็บเดิม** ⇒ ท่าเดียวกับเมนูของเว็บเดิม
// ⭐ ตัวเฝ้าคือ `tools/ด่านเมนูเว็บเดิม.mjs` ⇒ การเคาะอยู่ที่ `docs/เคาะ/หน้าจอกับการอ่าน.md` หัวข้อ *เมนูของเว็บเดิม*
import { Button } from '~/components/ui/button'
import กล่องเด้ง from '~/components/กล่องเด้ง.vue'
import { ใช้กล่องเด้ง } from '~/composables/กล่องเด้ง'
import { ถ้อยคำเมนูเว็บเดิม, type รายการเมนูเว็บเดิม } from '~/utils/ถ้อยคำเมนูเว็บเดิม'
import {
  ที่อยู่หน้าแหล่งข้อมูล,
  ที่อยู่หน้าเกี่ยวกับเรา,
  ที่อยู่หน้าเล่าประสบการณ์,
  ที่อยู่เว็บเดิม,
  ที่อยู่เว็บเพลง,
} from '~/utils/ที่อยู่'

/** หน้าที่เปิดอยู่ ⇒ รายการที่ชี้มาหน้านี้เป็นตัวหนังสือติด `aria-current` ⛔ ลิงก์วนกลับ ⇒ ค่าเดียวกับ `หน้านี้` ของ `แถบนำทาง.vue` */
const props = defineProps<{ หน้านี้?: 'หน้าแรก' | 'สารบัญ' | 'แหล่ง' | 'เกี่ยวกับ' | 'เล่าประสบการณ์' }>()

// ⭐ ใบ #163 รอบ 3 ⇒ อยู่ที่เดียว (ท้ายกลุ่มปุ่มของแถบบน) ⇒ ไอดีเดียว
//   ⇒ ช่อง `ชื่อ` ⇒ หัวของแผง (ชื่อเว็บ) · ช่อง `ลิงก์` ⇒ รายการต้นแผงบนจอแคบ (หัวเมนูของเว็บนี้) ⇒ เจ้าของคือ `แถบนำทาง.vue`
const ไอดีแผง = 'pk-แผงเมนูเว็บเดิม'
const ช่อง = useSlots()
/** ระยะห่างขอบจอของแผงจอกว้าง ⇒ ค่าเดียวกับเมนูของหน้าอ่าน (ใบ #109 ข้อ 9) */
const ระยะเผื่อขอบจอ = 16

const กาง = ref(false)
const กล่อง = ref<HTMLElement | null>(null)
const ปุ่ม = ref<{ $el: HTMLElement } | null>(null)
const { จอแคบ } = ใช้กล่องเด้ง(() => กาง.value)

/** ที่อยู่ของรายการ ⇒ เพลงไปเว็บเพลง · แหล่งข้อมูล เกี่ยวกับเรา เล่าประสบการณ์ไปหน้าของเว็บนี้ · ที่เหลือต่อทางกับที่อยู่เว็บเดิม */
const ที่อยู่ของ = (x: รายการเมนูเว็บเดิม) =>
  x.ไปเล่าประสบการณ์
    ? ที่อยู่หน้าเล่าประสบการณ์()
    : x.ไปแหล่ง
    ? ที่อยู่หน้าแหล่งข้อมูล()
    : x.ไปเกี่ยวกับ
      ? ที่อยู่หน้าเกี่ยวกับเรา()
      : x.ไปเพลง
        ? ที่อยู่เว็บเพลง
        : ที่อยู่เว็บเดิม + (x.ทาง || '')
/** รายการนี้คือหน้าที่เปิดอยู่ไหม */
const คือหน้านี้ = (x: รายการเมนูเว็บเดิม) =>
  (!!x.ไปแหล่ง && props.หน้านี้ === 'แหล่ง') ||
  (!!x.ไปเกี่ยวกับ && props.หน้านี้ === 'เกี่ยวกับ') ||
  (!!x.ไปเล่าประสบการณ์ && props.หน้านี้ === 'เล่าประสบการณ์')
/** ⭐ รายการที่แสดง ⇒ ตัดกลุ่มที่ปิดสวิตช์ไว้ (`เปิด: false`) ⇒ ไอดีหัวกลุ่มนับตามลำดับในรายการเต็ม ⇒ เปิดกลับแล้วไอดีไม่ชนกัน */
const รายการที่เห็น = ถ้อยคำเมนูเว็บเดิม.รายการ.map((x, i) => ({ x, i })).filter(({ x }) => x.เปิด !== false)
const ไอดีกลุ่ม = (i: number) => `pk-กลุ่มเมนูเว็บเดิม-${i}`

function คืนโฟกัส() {
  ปุ่ม.value?.$el?.focus()
}

function ปิด(คืน: boolean) {
  if (!กาง.value) return
  กาง.value = false
  if (คืน) คืนโฟกัส()
}

// ⛔ ดักที่ `pointerdown` ⛔ `click` ⇒ เหตุผลเดียวกับเมนูของหน้าอ่าน (กดค้างแล้วลากออกไปปล่อย ⛔ เกิด `click`)
function กดที่ไหนบนหน้า(e: PointerEvent) {
  if (กล่อง.value && e.target instanceof Node && กล่อง.value.contains(e.target)) return
  ปิด(false)
}
function กดแป้น(e: KeyboardEvent) {
  if (e.key === 'Escape') ปิด(true)
}
// ⭐ กดลิงก์ในแผง ⇒ พับแผง ⇒ *อ่านพระคัมภีร์* เปิดแผงเลือกพระธรรมคาหน้าเดิม ⇒ ⛔ ให้แผงนี้ค้างอยู่ใต้แผงนั้น
function กดในแผง(e: MouseEvent) {
  if (e.target instanceof Element && e.target.closest('a[href]')) ปิด(false)
}

// ⭐ แผงจอกว้างชิดขวาของปุ่มตามกฎเดิมของ `.pk-เมนู` ⇒ ล้นซ้ายหรือขวาเมื่อไร ⇒ เลื่อนกลับเข้ามา ⇒ ห่างขอบจออย่างน้อย 16 จุด
//   ⇒ ท่าเดียวกับ `จัดที่เมนู()` ของหน้าอ่าน ⇒ สูงเกินจอ ⇒ เลื่อนในแผง (SC 1.4.10 อนุญาตการเลื่อนในกล่องย่อย)
const เลื่อน = ref(0)
const กว้างสุด = ref(0)
const สูงสุด = ref(0)
async function จัดที่() {
  const จอ = document.documentElement
  กว้างสุด.value = จอ.clientWidth - 2 * ระยะเผื่อขอบจอ
  เลื่อน.value = 0
  await nextTick()
  const แผง = กล่อง.value?.querySelector<HTMLElement>(`#${ไอดีแผง}`)
  if (!แผง || แผง.classList.contains('pk-เต็มจอ')) return
  const กรอบ = แผง.getBoundingClientRect()
  if (กรอบ.right > จอ.clientWidth - ระยะเผื่อขอบจอ) เลื่อน.value = -(กรอบ.right - (จอ.clientWidth - ระยะเผื่อขอบจอ))
  if (กรอบ.left + เลื่อน.value < ระยะเผื่อขอบจอ) เลื่อน.value = ระยะเผื่อขอบจอ - กรอบ.left
  สูงสุด.value = Math.max(2 * 44, Math.floor(จอ.clientHeight - กรอบ.top - ระยะเผื่อขอบจอ))
}
const สไตล์แผง = computed(() => ({
  '--pk-เลื่อนเมนู': `${เลื่อน.value}px`,
  ...(กว้างสุด.value > 0 ? { '--pk-กว้างเมนูสุด': `${กว้างสุด.value}px` } : {}),
  ...(สูงสุด.value > 0 ? { '--pk-สูงเมนูสุด': `${สูงสุด.value}px` } : {}),
}))

watch(กาง, (เปิด) => {
  if (เปิด) {
    document.addEventListener('pointerdown', กดที่ไหนบนหน้า)
    document.addEventListener('keydown', กดแป้น)
    window.addEventListener('resize', จัดที่)
    จัดที่()
  } else {
    document.removeEventListener('pointerdown', กดที่ไหนบนหน้า)
    document.removeEventListener('keydown', กดแป้น)
    window.removeEventListener('resize', จัดที่)
  }
})
watch(จอแคบ, () => กาง.value && จัดที่())
onBeforeUnmount(() => (กาง.value = false))
</script>

<template>
  <div ref="กล่อง" class="pk-กล่องเมนู pk-เมนูเว็บเดิม">
    <!-- ⭐ ใบ #163 รอบ 2 ⇒ **ปุ่มรูป ≡ ตามกติกาคำข้างรูปของใบ #155** ⇒ จอแคบกว่า 1100 รูปอย่างเดียว · ตั้งแต่ 1100 รูปพร้อมคำ *เมนู*
           ⇒ กลไกเดียวกับแชร์ · เฟือง · i ⇒ คำอยู่ใน `.pk-คำข้างรูป` (ก้อน *คำข้างรูป* ท้าย `main.css`) ⇒ ทางหนี `pk-คำข้างรูปไม่พอ` ใช้ร่วมกัน
           ⇒ ชื่อที่ได้ยินมาจาก `aria-label` = คำ *เมนู* ⇒ ขึ้นต้นด้วยคำที่ตาเห็นทุกจอ (SC 2.5.3) ⇒ หน้าตาและขนาดของ `.pk-ปุ่มแถบ` (44 จุด) -->
    <Button
      ref="ปุ่ม"
      type="button"
      class="pk-ปุ่มแถบ pk-ปุ่มเมนูเว็บเดิม"
      data-ปุ่ม="เมนูเว็บเดิม"
      :aria-label="ถ้อยคำเมนูเว็บเดิม.ปุ่ม"
      :aria-expanded="กาง"
      :aria-controls="กาง ? ไอดีแผง : undefined"
      @click="กาง = !กาง"
    >
      <!-- ⭐ รูป `menu` ของ Lucide (ขีด 3 ขีด) ⇒ ชุดเดียวกับรูปแชร์ -->
      <svg
        viewBox="0 0 24 24"
        width="20"
        height="20"
        fill="none"
        stroke="currentColor"
        stroke-width="2"
        stroke-linecap="round"
        stroke-linejoin="round"
        aria-hidden="true"
      >
        <line x1="4" x2="20" y1="12" y2="12" />
        <line x1="4" x2="20" y1="6" y2="6" />
        <line x1="4" x2="20" y1="18" y2="18" />
      </svg>
      <span class="pk-คำข้างรูป">{{ ถ้อยคำเมนูเว็บเดิม.ปุ่ม }}</span>
    </Button>
    <!-- ⛔ ชื่อแท็กต้องเป็นตัวอักษรอังกฤษ ⇒ ชื่อชิ้นส่วนภาษาไทยต้องผ่าน `<component :is>` -->
    <component
      :is="กล่องเด้ง"
      v-if="กาง"
      :id="ไอดีแผง"
      class="pk-เมนู pk-แผงเมนูเว็บเดิม"
      :เต็มจอ="จอแคบ"
      :style="สไตล์แผง"
      @ปิด="ปิด(true)"
      @click="กดในแผง"
    >
      <!-- ⭐ หัวของแผง ⇒ ชื่อเว็บ (@krisada *"ใส่ชื่อตรงหัวเมนูได้ และจะได้รู้ด้วยว่าโปรแกรมอะไร"*) ⇒ แถวเดียวกับ × -->
      <template #หัว><slot name="ชื่อ" /></template>
      <!-- ⭐ จอแคบ ⇒ หัวเมนูของเว็บนี้ต้นแผง (หน้าที่ส่งมา) ⇒ จอกว้างอยู่บนแถบอยู่แล้ว ⇒ ⛔ ซ้ำ -->
      <ul v-if="จอแคบ && ช่อง.ลิงก์" class="pk-รายการเมนูเว็บเดิม pk-ลิงก์หลักในเมนู"><slot name="ลิงก์" /></ul>
      <ul class="pk-รายการเมนูเว็บเดิม">
        <li v-for="{ x, i } in รายการที่เห็น" :key="x.คำ">
          <template v-if="x.ย่อย">
            <p :id="ไอดีกลุ่ม(i)" class="pk-หัวกลุ่มเมนูเว็บเดิม">{{ x.คำ }}</p>
            <ul :aria-labelledby="ไอดีกลุ่ม(i)">
              <li v-for="y in x.ย่อย" :key="y.คำ">
                <span v-if="คือหน้านี้(y)" class="pk-ลิงก์เมนูเว็บเดิม pk-หน้านี้" aria-current="page">{{ y.คำ }}</span>
                <a v-else class="pk-ลิงก์เมนูเว็บเดิม" :href="ที่อยู่ของ(y)">{{ y.คำ }}</a>
              </li>
            </ul>
          </template>
          <span v-else-if="คือหน้านี้(x)" class="pk-ลิงก์เมนูเว็บเดิม pk-หน้านี้" aria-current="page">{{ x.คำ }}</span>
          <a v-else class="pk-ลิงก์เมนูเว็บเดิม" :href="ที่อยู่ของ(x)">{{ x.คำ }}</a>
        </li>
      </ul>
    </component>
  </div>
</template>
