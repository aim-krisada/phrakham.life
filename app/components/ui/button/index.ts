// ⛔⛔ **ของเดิมของ shadcn-vue ถูกถอดคลาสของ Tailwind ออกหมด โดยเจตนา**
//   ⇒ คลาสอย่าง `h-9 px-4 bg-primary` กำหนดขนาดและสีใหม่ ⇒ ปุ่มทุกตัวจะขยับและเปลี่ยนสีพร้อมกัน
//   ⇒ ขนาด สี และตำแหน่งของแต่ละปุ่มยังเป็นของคลาส `pk-` เดิม (ด่านหลายตัวจับปุ่มด้วยชื่อเหล่านั้น)
//   ⇒ ที่นี่เป็นเจ้าของแค่ **ชนิดของปุ่ม** ⇒ ⛔ ไม่มีคลาส `dark:` ⇒ ธีมมืดเป็นใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/67
//
// **ชนิด (`variant`)** ⇒ เลือกจากหน้าตาที่ปุ่มมีอยู่แล้ว ⛔ ไม่ใช่หน้าตาใหม่
//   ⇒ `กรอบ` ⇒ พื้นอ่อน กรอบทอง ⇒ ปุ่มเกือบทุกตัว (ตั้งต้น)
//   ⇒ `เข้ม` ⇒ พื้นทึบสีหมึกหรือสีน้ำตาล ⇒ ปุ่มหลักของหน้า ⇒ ปุ่ม *เลือกพระธรรมที่จะอ่าน* · *ฟัง* · *กลับไปที่กำลังอ่าน*
//   ⇒ `ลิงก์` ⇒ หน้าตาเป็นลิงก์ขีดเส้นใต้ ⛔ ไม่นูน ⇒ ลิงก์ย้อนในรอยทางของแผงเลือกพระคัมภีร์ (การเคาะรอบที่ 2 ของใบ #140 ข้อ 7.5)
// **ทรง (`ทรง`)** ⇒ `มน` ทรงเดียว ⇒ โค้ง `--pk-มุมปุ่ม` (12 จุด)
//   ⇒ ⚠️ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/156 ⇒ ทรง `แคปซูล` (มนสุด) ถูกถอด ⇒ ปุ่มทุกปุ่มโค้งเท่ากัน
//   ⇒ ป้าย `data-ทรง="มน"` ยังอยู่ ⇒ `tools/ด่านปุ่มชุดเดียว.mjs` ข้อ ① อ่านป้ายนี้ ⇒ ปุ่มที่ใส่ทรงอื่นมาเองจะแดง
//
// **ตัวเฝ้า** ⇒ `tools/ด่านปุ่มชุดเดียว.mjs` ⇒ ทุกปุ่มบนทุกหน้า และในแผงที่เปิดขึ้นมา ต้องมาจากชิ้นนี้และหน้าตาตรงค่าชุดเดียว
import type { VariantProps } from "class-variance-authority"
import { cva } from "class-variance-authority"

