/** บทที่เป็นบทจบได้ ⇒ **เฉพาะเล่มเดียวกัน และอยู่หลังบทเริ่ม** ⇒ ⛔ ข้ามเล่มไม่ได้ */
const บทหลังบทเริ่ม = computed(() =>
  (เล่มที่เลือก.value?.บทที่มี || []).filter((c) => c > บทที่เลือก.value),
