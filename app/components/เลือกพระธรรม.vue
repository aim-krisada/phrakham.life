//   ⇒ นี่คือของที่ผมทำพลาดเอง แล้ว N จับได้ ⛔ ไม่ใช่ของที่รุ่น 2 ทำไว้ผิด
const แท็บทั้งหมด = ['เดิม', 'ใหม่'] as const
function เดินแท็บ(e: KeyboardEvent) {
  const i = แท็บทั้งหมด.indexOf(แท็บ.value)
  let ใหม่ = i
  if (e.key === 'ArrowRight') ใหม่ = (i + 1) % แท็บทั้งหมด.length
  else if (e.key === 'ArrowLeft') ใหม่ = (i - 1 + แท็บทั้งหมด.length) % แท็บทั้งหมด.length
  else if (e.key === 'Home') ใหม่ = 0
  else if (e.key === 'End') ใหม่ = แท็บทั้งหมด.length - 1
  else return
  e.preventDefault()
  e.stopPropagation()
  แท็บ.value = แท็บทั้งหมด[ใหม่]!
  // ⭐ ย้ายโฟกัสไปที่แท็บใหม่ด้วย ⇒ ไม่งั้นโฟกัสค้างอยู่ที่แท็บเก่าซึ่งกดต่อไม่ได้แล้ว
  nextTick(() => {
    กล่อง.value?.querySelectorAll<HTMLElement>('[role="tab"]')[ใหม่]?.focus()
  })
}

