function กดเล่ม(b: เล่ม) {
  เล่มที่เลือก.value = b
  // เล่มที่มีบทเดียว ข้ามขั้นเลือกบทไปเลย ⇒ ท่าเดียวกับรุ่น 2
  if (b.บทที่มี.length === 1) {
    บทที่เลือก.value = b.บทที่มี[0]!
    ก้าวนี้.value = 'ข้อ'
  } else {
    ก้าวนี้.value = 'บท'
  }
}
function กดบท(c: number) {
  บทที่เลือก.value = c
  ก้าวนี้.value = 'ข้อ'
}

function ส่ง(จุด: จุดอ่าน) {
  emit('เลือก', จุด)
  emit('ปิด')
}
/** ⭐ **กำลังเลือกเป็นช่วงไหม** ⇒ แผงที่เปิดให้คอลัมน์เทียบ ⛔ มีแต่แบบข้อเริ่ม */
const เป็นช่วง = computed(() => props.เลือกช่วงได้ && แบบ.value === 'ช่วง')

/**
 * ⭐ **ปุ่ม *ทั้งบท*** ⇒ แบบข้อเริ่ม = ไปต้นบทแล้วอ่านต่อไปเรื่อย ๆ
 *   ⇒ แบบช่วง = **ช่วงคือทั้งบทนี้** ⇒ หน้าแสดงบทนี้บทเดียว ปุ่มเล่นเล่นบทนี้แล้วหยุด
 */
function ต้นบท() {
  const b = เล่มที่เลือก.value!
  if (เป็นช่วง.value) {
    ส่ง({
      รหัส: b.รหัส,
      บท: บทที่เลือก.value,
      ข้อ: 1,
      ถึง: { บท: บทที่เลือก.value, ข้อ: ข้อสุดท้ายของ(b, บทที่เลือก.value) },
    })
    return
  }
  ส่ง({ รหัส: b.รหัส, บท: บทที่เลือก.value, ข้อ: null })
}
function กดข้อ(v: number) {
  if (!เป็นช่วง.value) {
    ส่ง({ รหัส: เล่มที่เลือก.value!.รหัส, บท: บทที่เลือก.value, ข้อ: v })
    return
  }
  ข้อเริ่ม.value = v
  ก้าวนี้.value = 'ข้อจบ'
}

// ---------- ก้าว ④ ข้อจบ ⇒ ท่าของ `mEnd` `mEndCh` `mEndVerses` ในรุ่น 2 ----------
// ⛔ **ปุ่ม *ไม่กำหนดข้อจบ* กับ *เฉพาะข้อ* ของใบ #101 ถูกถอดแล้ว** (ใบ #102)
//   ⇒ *ไม่กำหนดข้อจบ* = แบบเลือกแค่ข้อเริ่ม ⇒ ตอนนี้เลือกได้ตั้งแต่ก่อนกดข้อ
//   ⇒ *เฉพาะข้อ* = กดเลขข้อแรกในตารางข้อจบ ⇒ มันคือข้อเดียวกับข้อเริ่ม ⇒ ⛔ ไม่ต้องมีปุ่มซ้ำ
function กดข้อจบ(บท: number, ข้อ: number) {
