// ⛔ **โฟกัสต้องวนอยู่ในหน้าต่าง** ⇒ ไม่งั้นคนใช้แป้นพิมพ์จะหลุดไปอยู่หลังฉากที่ตามองไม่เห็น
function ดักปุ่ม(e: KeyboardEvent) {
  if (e.key === 'Escape') {
    emit('ปิด')
    return
  }
  if (e.key !== 'Tab' || !กล่อง.value) return
  // ⛔⛔ **ต้องคัดของที่ `tabindex="-1"` ทิ้ง** — ปุ่มในตารางกับแท็บที่ไม่ได้เลือก ตั้งค่านี้ไว้
  //   ⇒ ⛔ นับมันเป็นจุดหยุดของ Tab เมื่อไร ตัวแรกกับตัวสุดท้ายที่คำนวณได้จะผิด
  //     ⇒ วนโฟกัสไปเกาะปุ่มที่ Tab ไปไม่ถึงจริง ⇒ คนใช้แป้นพิมพ์หลุดออกนอกหน้าต่าง
  const ได้ = [...กล่อง.value.querySelectorAll<HTMLElement>('button, [href], input, select')].filter(
    (el) => !el.hasAttribute('disabled') && el.getClientRects().length && el.tabIndex >= 0,
  )
  if (!ได้.length) return
  const แรก = ได้[0]!
  const สุดท้าย = ได้[ได้.length - 1]!
  if (e.shiftKey && document.activeElement === แรก) {
    สุดท้าย.focus()
    e.preventDefault()
  } else if (!e.shiftKey && document.activeElement === สุดท้าย) {
    แรก.focus()
    e.preventDefault()
  }
}

