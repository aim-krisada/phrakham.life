let ที่พิมพ์ค้าง = ''
let ตัวนับพิมพ์: ReturnType<typeof setTimeout> | undefined

/** กี่ปุ่มต่อแถว ⇒ **นับจากของที่วาดออกมาจริง** ⛔ ไม่ฝังตัวเลข — ตารางห่อแถวตามความกว้างจอ
 *  ⛔ นับแถวแรกอย่างเดียว ⛔ ไม่ได้ — ก้าวเลือกข้อมีปุ่ม *ทั้งบท* กินเต็มแถวอยู่แถวบนสุด
 *  ⇒ จึงเอา **แถวที่มีปุ่มมากที่สุด** เป็นตัวตอบ */
function กี่คอลัมน์(ปุ่ม: HTMLElement[]): number {
  const ต่อแถว = new Map<number, number>()
  for (const el of ปุ่ม) ต่อแถว.set(el.offsetTop, (ต่อแถว.get(el.offsetTop) || 0) + 1)
  return Math.max(1, ...ต่อแถว.values())
}

function ปุ่มของก้าว(): HTMLButtonElement[] {
  return [...(กล่อง.value?.querySelectorAll<HTMLButtonElement>('.pk-ตารางเลือก .pk-ปุ่มเลือก') || [])]
}

/** พิมพ์แล้วกระโดด ⇒ ท่าเดียวกับที่กล่องเลือกของเบราว์เซอร์ทำ ⇒ ตัวที่พิมพ์ค้างไว้หมดอายุใน 1 วินาที */
function กระโดดตามที่พิมพ์(ตัว: string, ปุ่ม: HTMLButtonElement[]) {
  clearTimeout(ตัวนับพิมพ์)
  ที่พิมพ์ค้าง += ตัว
  ตัวนับพิมพ์ = setTimeout(() => (ที่พิมพ์ค้าง = ''), 1000)
  const คำ = ที่พิมพ์ค้าง
  const เจอ = ปุ่ม.find((b) => (b.textContent || '').trim().startsWith(คำ))
  if (เจอ) {
    เจอ.focus()
    return
  }
  // ⭐ ก้าวเลือกเล่มเท่านั้น ⇒ ไม่เจอในแท็บนี้ ให้ข้ามแท็บไปหาให้ ⛔ ไม่ปล่อยให้ผู้อ่านหาเอง
  if (ก้าวนี้.value !== 'เล่ม') return
  const อีกแท็บ = แท็บทั้งหมด.find((t) => t !== แท็บ.value)!
  if (!props.เล่มทั้งหมด.some((b) => b.พันธสัญญา === อีกแท็บ && b.ชื่อไทย.startsWith(คำ))) return
  แท็บ.value = อีกแท็บ
  nextTick(() => {
    ปุ่มของก้าว()
      .find((b) => (b.textContent || '').trim().startsWith(คำ))
      ?.focus()
  })
}

function เดินตาราง(e: KeyboardEvent) {
  const ปุ่ม = ปุ่มของก้าว()
  if (!ปุ่ม.length) return
  const ตอนนี้ = Math.max(0, ปุ่ม.indexOf(document.activeElement as HTMLButtonElement))
  const ท้าย = ปุ่ม.length - 1
  let ไป = -1
  if (e.key === 'ArrowRight') ไป = Math.min(ท้าย, ตอนนี้ + 1)
  else if (e.key === 'ArrowLeft') ไป = Math.max(0, ตอนนี้ - 1)
  else if (e.key === 'ArrowDown') ไป = Math.min(ท้าย, ตอนนี้ + กี่คอลัมน์(ปุ่ม))
  else if (e.key === 'ArrowUp') ไป = Math.max(0, ตอนนี้ - กี่คอลัมน์(ปุ่ม))
  else if (e.key === 'Home') ไป = 0
  else if (e.key === 'End') ไป = ท้าย
  else if (e.key.length === 1 && !e.ctrlKey && !e.metaKey && !e.altKey) {
    e.preventDefault()
    e.stopPropagation()
    กระโดดตามที่พิมพ์(e.key, ปุ่ม)
    return
  } else return
  e.preventDefault()
  e.stopPropagation()
  ปุ่ม[ไป]!.focus()
}

