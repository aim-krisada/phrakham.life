const รอยทาง = computed(() => {
  const b = เล่มที่เลือก.value
  const ทาง: { ป้าย: string; ไป?: () => void }[] = [
    { ป้าย: 'พระคัมภีร์', ไป: ก้าวนี้.value === 'เล่ม' ? undefined : เริ่มใหม่ },
  ]
  if (!b || ก้าวนี้.value === 'เล่ม') return ทาง
  ทาง.push({ ป้าย: b.ชื่อไทย, ไป: ก้าวนี้.value === 'บท' ? undefined : () => (ก้าวนี้.value = 'บท') })
  if (ก้าวนี้.value === 'บท') return ทาง
  ทาง.push({
    ป้าย: `บท ${บทที่เลือก.value}`,
    ไป: ก้าวนี้.value === 'ข้อ' ? undefined : () => (ก้าวนี้.value = 'ข้อ'),
  })
  if (ก้าวนี้.value === 'ข้อ') return ทาง
  const จาก = `จาก ${บทที่เลือก.value}:${ข้อเริ่ม.value}`
  if (ก้าวนี้.value === 'ข้อจบ') ทาง.push({ ป้าย: `${จาก} ถึง…` })
  else if (ก้าวนี้.value === 'บทจบ') ทาง.push({ ป้าย: `${จาก} ถึงบท…` })
  else {
    ทาง.push({ ป้าย: `${จาก} ถึง บท ${บทจบ.value}`, ไป: () => (ก้าวนี้.value = 'บทจบ') })
    ทาง.push({ ป้าย: 'ข้อ' })
  }
  return ทาง
})

const หัวเรื่อง = computed(() => {
  const b = เล่มที่เลือก.value
  if (!b) return 'เลือกพระคัมภีร์'
  if (ก้าวนี้.value === 'บท') return b.ชื่อไทย
  if (ก้าวนี้.value === 'ข้อจบ' || ก้าวนี้.value === 'บทจบ') {
    return `${b.ชื่อไทย} ${บทที่เลือก.value}:${ข้อเริ่ม.value} ถึงข้อไหน`
  }
  if (ก้าวนี้.value === 'ข้อจบบทอื่น') {
    return `${b.ชื่อไทย} ${บทที่เลือก.value}:${ข้อเริ่ม.value} ถึงบท ${บทจบ.value} ข้อไหน`
  }
  return เป็นช่วง.value
    ? `${b.ชื่อไทย} บทที่ ${บทที่เลือก.value} · เลือกข้อเริ่มของช่วง`
    : `${b.ชื่อไทย} บทที่ ${บทที่เลือก.value}`
})

