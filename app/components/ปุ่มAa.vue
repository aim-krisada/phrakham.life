<script setup lang="ts">
// ⭐⭐ **ปุ่ม Aa กับแผงของมัน ⇒ ชิ้นเดียวทั้งเว็บ** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/173 เกณฑ์ข้อ 1 · 4 · 5)
//   ⇒ ยกออกมาจาก `หน้าอ่าน.vue` ทั้งดุ้น ⛔ ไม่ได้ทำปุ่มใหม่ (Notes ข้อ 3 ของใบ) ⇒ ปุ่ม · หัวแผง · ก− ขนาด ก+ ⇒ คำ คลาส ไอดี เดิมทุกตัว
//   ⇒ ⭐ **หน้าอ่าน** ⇒ ส่งของในแผงเพิ่มทางช่องว่าง (การจัดวาง · แสดงผล) ⇒ หน้าตาเดิมทุกอย่าง ⇒ ด่านเดิมทุกตัวหาเจอที่เดิม
//   ⇒ ⭐ **หน้าอื่น** (หน้าแรก · สารบัญ · แหล่งข้อมูล · เกี่ยวกับเรา) ⇒ `แถบนำทาง.vue` วางชิ้นนี้ให้เอง ⇒ แผงมีแค่ขนาดตัวอักษรกับแบบตัวอักษรไทย (ใบ #174)
//     ⇒ ⛔ ตัวเลือกการจัดวางกับแสดงผลมีความหมายเฉพาะตัวบทพระคัมภีร์ ⇒ วางบนหน้าอื่น = ปุ่มที่กดแล้วไม่เกิดอะไร (ใบ #76)
//   ⇒ ⭐ ขนาดเป็นค่าเดียวทั้งเว็บ ⇒ เจ้าของคือ `app/composables/ขนาดตัวอักษร.ts`
//   ⇒ ⭐ แบบตัวอักษรไทยก็ค่าเดียวทั้งเว็บ ⇒ เจ้าของคือ `app/composables/แบบตัวอักษรไทย.ts`
//
// ⭐ **ชิ้นนี้ ⛔ ถือสถานะกางหรือพับเอง** ⇒ ท่าเดียวกับ `กล่องเด้ง.vue`
//   ⇒ หน้าอ่านมีระบบเมนูของมันเอง (Aa กับ เทียบ กางทีละอัน · ปิดแล้วกลับไปข้อที่อ่านค้าง) ⇒ ผู้เรียกส่ง `เปิด` แล้วรับ `สลับ` · `ปิด`
//   ⇒ ตัวดักกดนอกแผงกับ Escape เป็นของผู้เรียก ⇒ ⭐ ผู้เรียกห่อชิ้นนี้ด้วย `.pk-กล่องเมนู` ของตัวเอง ⇒ ใช้กล่องนั้นตอบว่ากดในหรือนอก
//
// ⭐ เหตุผลของหน้าตา (APG Disclosure · ชื่อที่ได้ยิน · หน้าเต็มจอบนมือถือ) อยู่ที่คอมเมนต์ข้างปุ่มใน `หน้าอ่าน.vue` ⛔ ไม่จดซ้ำที่นี่
import { Button } from '~/components/ui/button'
import กล่องเด้ง from '~/components/กล่องเด้ง.vue'
import { ใช้ขนาดตัวอักษร } from '~/composables/ขนาดตัวอักษร'
import { ใช้แบบตัวอักษรไทย } from '~/composables/แบบตัวอักษรไทย'
import { ถ้อยคำแผงAa } from '~/utils/ถ้อยคำแผงAa'
import type { แบบตัวอักษร as แบบตัวอักษรที่เลือก } from '~/utils/แบบตัวอักษรไทย'

defineProps<{
  /** แผงกางอยู่ไหม */
  เปิด: boolean
  /** จอแคบกว่า 768 ⇒ แผงเป็นหน้าเต็มจอใต้แถบบน ⇒ ส่งต่อให้ `กล่องเด้ง.vue` */
  เต็มจอ: boolean
  /** ค่าที่ผู้เรียกวัดให้แผง (เลื่อนเข้าจอ · กว้างสุด · สูงสุด) ⇒ ⛔ ไม่ส่ง = CSS ใช้ค่าสำรองของมันเอง */
  สไตล์แผง?: Record<string, string>
}>()
const emit = defineEmits<{ สลับ: []; ปิด: [] }>()
const ช่อง = useSlots()
const ขนาด = ใช้ขนาดตัวอักษร()
const แบบตัวอักษร = ใช้แบบตัวอักษรไทย()
// ⭐ เรียงตามเว็บเพลง ⇒ ไม่มีหัวซ้าย มีหัวขวา
const ตัวเลือกแบบ: { ค่า: แบบตัวอักษรที่เลือก; ชื่อ: string }[] = [
  { ค่า: 'loopless', ชื่อ: ถ้อยคำแผงAa.ไม่มีหัว },
  { ค่า: 'looped', ชื่อ: ถ้อยคำแผงAa.มีหัว },
]
/** ลูกศรซ้ายขวาบนล่าง ⇒ ย้ายไปอีกปุ่มแล้วเลือกเลย ⇒ ทรง APG Radio Group ⇒ มีแค่ 2 ปุ่ม ⇒ ทางไหนก็ได้อีกปุ่ม */
function กดลูกศร(e: KeyboardEvent) {
  if (!['ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown'].includes(e.key)) return
  e.preventDefault()
  const อีกแบบ = แบบตัวอักษร.แบบ.value === 'looped' ? 'loopless' : 'looped'
  แบบตัวอักษร.เลือก(อีกแบบ)
  ;(e.currentTarget as HTMLElement).querySelector<HTMLElement>(`[data-แบบ="${อีกแบบ}"]`)?.focus()
}
</script>

<template>
  <Button
    type="button"
    class="pk-ปุ่มแถบ pk-ปุ่มAa"
    data-ปุ่ม="Aa"
    :aria-expanded="เปิด"
    :aria-controls="เปิด ? 'pk-แผงAa' : undefined"
    @click="emit('สลับ')"
  >
    <!-- ⛔ ช่องว่างหน้าคำที่ซ่อนต้องอยู่ในวงเล็บปีกกา ⇒ เขียนไว้นอกวงเล็บ Vue ตัดทิ้ง ⇒ ได้ยินติดกันเป็น *Aaปรับ…* -->
    {{ ถ้อยคำแผงAa.ตาเห็น }}<span class="pk-เฉพาะเสียง">{{ ` ${ถ้อยคำแผงAa.ต่อท้ายชื่อ}` }}</span>
  </Button>
  <!-- ⛔ ชื่อแท็กต้องเป็นตัวอักษรอังกฤษ ⇒ ชื่อชิ้นส่วนภาษาไทยต้องผ่าน `<component :is>` -->
  <component
    :is="กล่องเด้ง"
    v-if="เปิด"
    id="pk-แผงAa"
    class="pk-เมนู"
    role="group"
    aria-labelledby="pk-หัวแผงAa"
    :เต็มจอ="เต็มจอ"
    :style="สไตล์แผง"
    @ปิด="emit('ปิด')"
  >
    <template #หัว>
      <p id="pk-หัวแผงAa" class="pk-หัวแผง">{{ ถ้อยคำแผงAa.หัวแผง }}</p>
    </template>

    <!-- ⭐ ตัวอักษรบนปุ่มคือ "ก" ⇒ คำเต็มติดไปกับปุ่มสำหรับโปรแกรมอ่านหน้าจอ
           ⇒ WCAG SC 2.5.3 Label in Name (ระดับ A) ⇒ ชื่อที่โปรแกรมได้ยิน **ต้องมีคำที่ตาเห็นอยู่ด้วย** -->
    <p id="pk-หัวขนาด" class="pk-หัวเมนู">{{ ถ้อยคำแผงAa.หัวขนาด }}</p>
    <div class="pk-ขนาดตัวอักษร" role="group" aria-labelledby="pk-หัวขนาด">
      <Button type="button" class="pk-ปุ่มแถบ" :disabled="!ขนาด.ลดได้.value" @click="ขนาด.เล็กลง()">
        ก<span aria-hidden="true">−</span><span class="pk-เฉพาะเสียง"> ตัวเล็กลง</span>
      </Button>
      <output class="pk-ค่าขนาด" aria-live="polite">{{ ขนาด.เปอร์เซ็นต์.value }}%</output>
      <Button type="button" class="pk-ปุ่มแถบ" :disabled="!ขนาด.เพิ่มได้.value" @click="ขนาด.ใหญ่ขึ้น()">
        ก<span aria-hidden="true">+</span><span class="pk-เฉพาะเสียง"> ตัวใหญ่ขึ้น</span>
      </Button>
    </div>
    <!-- ⭐⭐ **แบบตัวอักษรไทย** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/174 เกณฑ์ข้อ 1)
           ⇒ ลอกมาจากแผง Aa ของเว็บเพลง ⇒ หัว *ตัวอักษรไทย* · 2 ปุ่ม *ไม่มีหัว* · *มีหัว* ⇒ แต่ละปุ่มมี ก ข ค ในฟอนต์ของตัวเอง
