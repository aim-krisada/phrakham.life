<script setup lang="ts">
// เครื่องหมายของ Levinsohn บนคำกรีกหนึ่งคำ (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/111 · #146)
//
// ⭐⭐ **ชิ้นนี้ถูกโหลดตอนคอลัมน์คำภาษาเดิมเปิดและมีเครื่องหมายที่เปิดอยู่บนหน้าเท่านั้น**
//   ⇒ หน้าอ่านเรียกด้วย `ชิ้นโหลดแยก` ⇒ โค้ด ตารางถ้อยคำ และ CSS อยู่ในก้อนของตัวเอง
//   ⇒ ใบ #111 เกณฑ์ข้อ 11 ⇒ *คนที่ไม่เปิดคอลัมน์คำภาษาเดิม ต้องไม่จ่ายไบต์เพิ่ม* ⇒ ตัวเฝ้าคือ `tools/ด่านคำเน้นบนหน้า.mjs` ข้อ ①
//
// ⭐ **หน้าตาเกิดจาก CSS ที่จับ `data-ลค` ของปุ่มคำ** ⇒ ชิ้นนี้มีหน้าที่ 2 อย่าง
//   ① ให้โปรแกรมอ่านหน้าจอได้ยินชื่อชนิดต่อท้ายคำ ⇒ WCAG 2.2 SC 1.3.1 (ระดับ A)
//      ⇒ คำแรกของช่วงได้ยินชื่อชนิด ⇒ คำท้ายของช่วงที่ยาวกว่า 1 คำได้ยิน *จบ* ตามด้วยชื่อ ⇒ คำกลางช่วงเงียบ
//      ⇒ ⛔ ไม่ใส่ชื่อทุกคำ ⇒ คำพูดยาว 509 คำจะได้ยินชื่อซ้ำ 509 ครั้ง
//   ② พาไฟล์ CSS ของเครื่องหมายมาด้วย
// ⭐ ชื่อที่ได้ยินยังขึ้นต้นด้วยคำที่ตาเห็น ⇒ ชิ้นนี้อยู่ท้ายปุ่ม ⇒ WCAG 2.2 SC 2.5.3 Label in Name (ระดับ A)
import { computed } from 'vue'
import { อ่านรหัส, คำว่าจบ } from '~/utils/คำเน้น'
import '~/assets/css/คำเน้น.css'

const props = defineProps<{
  /** รหัสพร้อมต้นท้าย ⇒ เช่น `F<> r<` ⇒ คิดจาก `หน้าตาของคำ` ใน `app/utils/เครื่องหมายบนคำ.ts` */
  เสียง?: string
}>()

const ข้อความ = computed(() =>
  (props.เสียง ?? '')
    .split(' ')
    .filter(Boolean)
    .map((ท) => {
      const ช = อ่านรหัส(ท[0]!)
      if (!ช) return ''
      const ต้น = ท.includes('<')
      return ต้น ? ช.ชื่อ : `${คำว่าจบ}${ช.ชื่อ}`
    })
    .filter(Boolean)
    .join(' · '),
)
</script>

<template>
  <span v-if="ข้อความ" class="pk-เฉพาะเสียง" lang="th" data-คำอ่านเครื่องหมาย>{{ ` ${ข้อความ}` }}</span>
</template>
