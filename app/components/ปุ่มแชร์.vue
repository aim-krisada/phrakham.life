//   ⇒ รูปตามเครื่อง ⇒ iPhone · iPad · Mac เห็นกล่องมีลูกศรชี้ขึ้น · เครื่องอื่นเห็นวงกลม 3 วงต่อกัน (รูปของ Lucide ชุดเดียวกับเว็บเพลง)
//   ⚠️ **⛔ มีคำว่า แชร์ ใต้รูปแล้ว ⇒ เหลือรูปอย่างเดียว** (พี่เอมสั่งเอง 5 พ.ย. 2569 22:51 ⇒ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/141)
//     ⇒ ⛔ แทนของเดิมของใบ #139 ที่ให้คำติดกับรูปตลอดตาม NN/g Icon Usability ⇒ การเคาะอยู่ที่ `docs/เคาะ/หน้าจอกับการอ่าน.md` หัวข้อ *ปุ่มแชร์เหลือแค่รูป*
//     ⇒ ชื่อที่โปรแกรมอ่านหน้าจอได้ยินยังเหมือนเดิมทุกตัวอักษร (`aria-label`) ⇒ ปุ่มยังสูงเท่าปุ่ม เทียบ กับ Aa และไม่เล็กกว่า 44 จุด
//   ⚠️ **ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/155 ⇒ จอตั้งแต่ 1100 ⇒ คำว่า แชร์ ข้างรูป** (⛔ ใต้รูป) ⇒ @krisada ตกลง 8 พ.ย. 2569
//     ⇒ *"ในจอเล็ก icon อย่างเดียว ในจอใหญ่ใส่คำข้าง icon ก็ได้นะ แต่ถ้าจะทำต้องทำทั้งหมดทุกปุ่มเหมือนกัน"* ⇒ เส้นเดียวกับเฟืองกับ i บนหัวคอลัมน์ภาษาเดิม
//   ⇒ แถบบนของจอมือถือ ⛔ ไม่สูงขึ้น (ใบ #76 · #131 ⇒ ตัวเฝ้าคือ `tools/ด่านปุ่มAa.mjs`)
// ⭐ **รูปตัดสินตอนหน้าติดแล้วเท่านั้น** ⇒ ตอนสร้างหน้าไม่รู้ว่าเป็นเครื่องอะไร ⇒ ตั้งต้นเป็นวงกลม 3 วง
// ⭐ **ตัวเลขข้อที่เลือกติดบนปุ่ม** ⇒ ผู้อ่านรู้ก่อนกดว่าจะแชร์กี่ข้อ (ข้อ 7) ⇒ หูได้ยินในชื่อปุ่ม ⇒ ตาเห็นตัวเลข
//   ⇒ ชื่อที่ได้ยินขึ้นต้นด้วยคำว่า *แชร์* ⇒ ตาเห็นแต่รูป ⇒ ⛔ มีคำบนปุ่มให้ SC 2.5.3 Label in Name ต้องเทียบแล้ว
// ⭐ **ผลของการกดบอกด้วย `role="status"`** ⇒ โปรแกรมอ่านหน้าจอได้ยินโดยไม่ต้องย้ายโฟกัส ⇒ SC 4.1.3 (ระดับ AA)
// ⭐ กติกาการส่งกับเหตุผลที่ลิงก์อยู่ในข้อความ ⇒ `app/utils/แชร์ข้อ.ts` ⛔ ไม่จดซ้ำที่นี่
import { ถ้อยคำแชร์ } from '~/utils/ถ้อยคำแชร์'
import { เป็นเครื่องแอปเปิล, ส่งเข้าเมนูแชร์ } from '~/utils/แชร์ข้อ'
// ⭐⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/153 ⇒ กล่องคัดลอกเองเป็นกล่องเด้งแบบเดียวกับ Aa กับ เทียบ
//   ⇒ ปุ่มแชร์บนแถบบน ⇒ จอแคบกว่า 768 หน้าเต็มจอใต้แถบบน · จอกว้างแผงใต้ปุ่ม ⇒ × มุมขวาบน · Escape ⇒ โฟกัสกลับปุ่มแชร์
//   ⇒ ปุ่มแชร์ของการ์ดคำ (`ป้าย`) ⇒ กล่องอยู่ในการ์ดที่เดิม (การ์ดเป็นแผ่นของตัวเอง) ⇒ ได้ × มุมขวาบนกับ Escape แบบเดียวกัน
//   ⇒ ⚠️ ของเดิม (ใบ #139) ⇒ ปุ่ม *ปิด* ท้ายกล่อง ⇒ ถอดแล้ว ⇒ × ได้ยินคำเดียวกัน *ปิด*
import กล่องเด้ง from '~/components/กล่องเด้ง.vue'
import { ใช้กล่องเด้ง } from '~/composables/กล่องเด้ง'

const props = defineProps<{
  /** จำนวนข้อที่เลือกอยู่ ⇒ 0 = แชร์ทั้งหน้า */
  จำนวน: number
  /** ประกอบข้อความที่จะส่ง ⇒ เรียกตอนกดเท่านั้น
   *  ⇒ ⚠️ Safari เปิดเมนูแชร์ได้เฉพาะตอนที่ยังนับว่าคนเพิ่งกด ⇒ หน้าอ่านเตรียมเนื้อกับเครดิตไว้ก่อนแล้ว ⇒ ปกติได้คำตอบทันที */
  ข้อความ: () => string | Promise<string>
  /** ⭐ ใบ #149 ⇒ ปุ่มแชร์ของการ์ดคำ ⇒ ชื่อที่หูได้ยินแทน *แชร์ ทั้งหน้า* ⇒ ว่าง = ปุ่มของแถบบนแบบเดิม */
  ชื่อปุ่ม?: string
  /** ⭐ ใบ #149 ⇒ ป้าย `data-ปุ่ม` ⇒ ปุ่มของการ์ดคำต้องไม่ชนกับปุ่มของแถบบนที่ด่านแชร์ข้อจับด้วย `data-ปุ่ม="แชร์"` */
  ป้าย?: string
  /** ⭐ ใบ #149 ⇒ `id` ของหัวกล่องคัดลอกเอง ⇒ 2 ปุ่มบนหน้าเดียวกันต้อง ⛔ ใช้ `id` ซ้ำ */
  รหัสหัว?: string
}>()

const แอปเปิล = ref(false)
onMounted(() => {
  แอปเปิล.value = เป็นเครื่องแอปเปิล(navigator as never)
})

const ผล = ref<'' | 'คัดลอกแล้ว' | 'คัดลอกเอง'>('')
const ข้อความที่ค้าง = ref('')
const กล่องข้อความ = ref<HTMLTextAreaElement | null>(null)
let ตัวนับ: ReturnType<typeof setTimeout> | undefined

const ชื่อที่ได้ยิน = computed(
  () =>
    props.ชื่อปุ่ม ||
    `${ถ้อยคำแชร์.ปุ่ม} ${props.จำนวน ? ถ้อยคำแชร์.ต่อท้ายข้อ(props.จำนวน) : ถ้อยคำแชร์.ต่อท้ายทั้งหน้า}`,
)
const หัว = computed(() => props.รหัสหัว || 'pk-หัวคัดลอกเอง')

async function กด() {
  clearTimeout(ตัวนับ)
  ผล.value = ''
  const ข้อความ = await props.ข้อความ()
  const ได้ = await ส่งเข้าเมนูแชร์(ข้อความ, navigator as never)
  if (ได้ === 'คัดลอกแล้ว') {
    ผล.value = ได้
    ตัวนับ = setTimeout(() => (ผล.value = ''), 2500)
  } else if (ได้ === 'คัดลอกเอง') {
    ข้อความที่ค้าง.value = ข้อความ
    ผล.value = ได้
    await nextTick()
    กล่องข้อความ.value?.focus()
    กล่องข้อความ.value?.select()
  }
}

const กล่องแชร์ = ref<HTMLElement | null>(null)
/** ⭐ ปุ่มแชร์บนแถบบนเท่านั้นที่เป็นหน้าเต็มจอบนจอแคบ ⇒ การ์ดคำมีที่ของมันเอง */
const { จอแคบ } = ใช้กล่องเด้ง(() => ผล.value === 'คัดลอกเอง' && !props.ป้าย)
const เต็มจอ = computed(() => จอแคบ.value && !props.ป้าย)

/** ปิดกล่องคัดลอกเอง ⇒ โฟกัสกลับปุ่มแชร์ที่เปิดมัน ⇒ ⛔ ปล่อยโฟกัสหล่นไป `<body>` (WCAG 2.2 SC 2.4.3) */
function ปิดกล่อง() {
  ผล.value = ''
  กล่องแชร์.value?.querySelector<HTMLElement>('.pk-ปุ่มแชร์')?.focus()
}

// ⭐ ใบ #153 ⇒ กดนอกกล่อง (เช่นปุ่ม Aa หรือ เทียบ บนแถบ) ⇒ ปิดเหมือนกล่องอื่น ⇒ ⛔ สองกล่องซ้อนกันบนจอแคบ
//   ⇒ ดักที่ `pointerdown` ท่าเดียวกับเมนูบนแถบ (`กดที่ไหนบนหน้า` ใน `หน้าอ่าน.vue`) ⇒ ⛔ ย้ายโฟกัส ⇒ ผู้อ่านกดของอื่นอยู่
//   ⇒ เฉพาะปุ่มแชร์บนแถบบน ⇒ การ์ดคำมีตัวดักกดนอกการ์ดของมันเอง
function กดนอกกล่อง(e: PointerEvent) {
  if (e.target instanceof Node && กล่องแชร์.value?.contains(e.target)) return
  ผล.value = ''
}
// ⭐ Escape ปิดได้แม้โฟกัสหลุดออกจากกล่อง (เช่นแตะที่ว่างในหน้าเต็มจอ) ⇒ ท่าเดียวกับเมนูบนแถบ ⇒ โฟกัสกลับปุ่มแชร์
function กดแป้น(e: KeyboardEvent) {
  if (e.key === 'Escape' && ผล.value === 'คัดลอกเอง') ปิดกล่อง()
}
function ถอดตัวดัก() {
  document.removeEventListener('pointerdown', กดนอกกล่อง, true)
  document.removeEventListener('keydown', กดแป้น)
}
watch(ผล, (ค่า) => {
  if (import.meta.server || props.ป้าย) return
  ถอดตัวดัก()
  if (ค่า === 'คัดลอกเอง') {
    document.addEventListener('pointerdown', กดนอกกล่อง, true)
    document.addEventListener('keydown', กดแป้น)
  }
})

onBeforeUnmount(() => {
  clearTimeout(ตัวนับ)
  if (!import.meta.server) ถอดตัวดัก()
})
</script>

<template>
  <div ref="กล่องแชร์" class="pk-กล่องแชร์">
    <Button
      type="button"
      class="pk-ปุ่มแถบ pk-ปุ่มแชร์"
      :data-ปุ่ม="ป้าย || 'แชร์'"
      :data-รูป="แอปเปิล ? 'แอปเปิล' : 'วงกลม'"
      :aria-label="ชื่อที่ได้ยิน"
      @click="กด"
    >
      <!-- ⭐ รูปของ Lucide ⇒ `share` (กล่องมีลูกศร) กับ `share-2` (วงกลม 3 วง) ⇒ ชุดเดียวกับเว็บเพลง -->
      <svg
        class="pk-รูปแชร์"
        viewBox="0 0 24 24"
        width="20"
        height="20"
        fill="none"
        stroke="currentColor"
        stroke-width="2"
        stroke-linecap="round"
        stroke-linejoin="round"
        aria-hidden="true"
      >
        <template v-if="แอปเปิล">
          <path d="M4 12v8a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2v-8" />
          <polyline points="16 6 12 2 8 6" />
          <line x1="12" x2="12" y1="2" y2="15" />
        </template>
        <template v-else>
          <circle cx="18" cy="5" r="3" />
          <circle cx="6" cy="12" r="3" />
          <circle cx="18" cy="19" r="3" />
          <line x1="8.59" x2="15.42" y1="13.51" y2="17.49" />
          <line x1="15.41" x2="8.59" y1="6.51" y2="10.49" />
        </template>
      </svg>
      <!-- ⭐ ใบ #155 ⇒ คำข้างรูป ⇒ ตาเห็นเฉพาะจอตั้งแต่ 1100 (ก้อน *คำข้างรูป* ท้าย `main.css`) ⇒ ทั้งปุ่มบนแถบบนและปุ่มของการ์ดคำ
           ⇒ หูได้ยินจาก `aria-label` ⇒ *แชร์ ทั้งหน้า* · *แชร์ N ข้อที่เลือก* · *แชร์ การ์ดความหมายคำ* ⇒ ขึ้นต้นด้วยคำที่ตาเห็น (SC 2.5.3) -->
      <span class="pk-คำข้างรูป">{{ ถ้อยคำแชร์.ปุ่ม }}</span>
      <span v-if="จำนวน" class="pk-จำนวนแชร์" aria-hidden="true">{{ จำนวน }}</span>
    </Button>
    <!-- ⭐ ผลของการกด ⇒ กล่องสถานะอยู่ตลอด ⇒ ของข้างในเปลี่ยนแล้วโปรแกรมอ่านหน้าจอได้ยิน (SC 4.1.3) -->
    <div role="status" class="pk-ผลแชร์">
      <p v-if="ผล === 'คัดลอกแล้ว'" class="pk-ป้ายแชร์" data-ผลแชร์="คัดลอกแล้ว">{{ ถ้อยคำแชร์.คัดลอกแล้ว }}</p>
    </div>
    <!-- ⛔ คัดลอกไม่ได้ ⇒ **ข้อความทั้งก้อนให้คัดลอกเอง** ⛔ ห้ามเงียบแล้วเหมือนสำเร็จ (ข้อ 17)
         ⇒ `textarea` อ่านอย่างเดียว ⇒ กดค้างแล้วคัดลอกได้ทุกเครื่อง ⇒ โฟกัสย้ายเข้ามาให้เอง -->
    <component
      :is="กล่องเด้ง"
      v-if="ผล === 'คัดลอกเอง'"
      class="pk-กล่องคัดลอกเอง"
      role="group"
      :aria-labelledby="หัว"
      data-ผลแชร์="คัดลอกเอง"
      :เต็มจอ="เต็มจอ"
      @keydown.esc="ปิดกล่อง"
      @ปิด="ปิดกล่อง"
    >
      <template #หัว>
        <p :id="หัว" class="pk-หัวคัดลอกเอง">{{ ถ้อยคำแชร์.หัวคัดลอกเอง }}</p>
      </template>
      <textarea
        ref="กล่องข้อความ"
        class="pk-ข้อความคัดลอกเอง"
        readonly
        rows="8"
        :aria-labelledby="หัว"
        :value="ข้อความที่ค้าง"
      />
    </component>
  </div>
</template>
