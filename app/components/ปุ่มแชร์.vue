// ⭐ ปุ่มกลางของทั้งเว็บ (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/141) ⇒ ทุกปุ่มบนหน้านี้เรียกชิ้นนี้ ⇒ เหตุผลอยู่ที่ `app/components/ui/button/index.ts`
import { Button } from '~/components/ui/button'
// ปุ่มแชร์บนแถบบนของหน้าอ่าน (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/139 ข้อ 1 · 7 · 8 · 15 · 16 · 17)
