<script setup lang="ts">
// ⭐ แผ่นเชิงอรรถของผู้แปล ⇒ เปิดจากเครื่องหมายเล็ก ๆ ในตัวบท ⇒ ⛔ ไม่ดันตัวบทให้ขยับ
//   ⇒ ลอยติดขอบล่างของจอ ⇒ ปิดด้วย × · Escape · กดนอกแผ่น ⇒ ผู้เรียกคืนโฟกัสให้เครื่องหมายที่เปิด
//   ⇒ ⭐ เชิงอรรถเป็นของฉบับไหน แผ่นบอกชื่อฉบับนั้น ⇒ ผู้อ่านรู้ว่าเป็นคำของผู้แปล ⛔ ไม่ใช่ของที่เว็บเขียนเพิ่ม
//   ⇒ ถ้อยคำทั้งหมดอยู่ที่ `app/utils/ถ้อยคำเชิงอรรถ.ts` ⛔ ไม่พิมพ์ตรงในไฟล์นี้
//   ⇒ ⭐ ที่อยู่ข้ออื่นในเชิงอรรถ (เช่น *ดู ฉธบ.15:11*) กดได้ (@krisada 21 พ.ย. 2569)
//     ⇒ แผ่นแค่บอกที่อยู่ (`ไปที่`) ⇒ หน้าอ่านตัดสินเองว่าเปิดคอลัมน์ใหม่ หรือพาไป (คอลัมน์เต็มแล้ว)
//     ⇒ TCV ใช้ที่อยู่ที่ผู้แปลฝังไว้ (`ref loc`) ⇒ WEB ไม่มีที่อยู่ฝัง ⇒ ตัวพ่นอ่านจากตัวหนังสือด้วยชื่อเล่มของ WEB เอง
//   ⇒ ⭐ **ทางของแป้นพิมพ์และโปรแกรมอ่านหน้าจอ** (22 พ.ย. 2569) ⇒ เครื่องหมายในตัวบท ⛔ เป็นปุ่มไม่ได้ (ข้อทั้งข้อเป็นปุ่มอยู่แล้ว)
//     ⇒ เลือกข้อแล้วกดปุ่ม *เชิงอรรถ* ในแถบข้อที่เลือก ⇒ แผ่นนี้เปิดพร้อม **เชิงอรรถทุกอันของข้อที่เลือก** (`รายการ`)
//     ⇒ เปิดจากปุ่ม ⇒ โฟกัสย้ายเข้าแผ่น (`จับโฟกัส`) ⇒ ปิดแล้วหน้าอ่านคืนโฟกัสให้ปุ่ม ⇒ WCAG 2.1.1 Keyboard · 2.4.3 Focus Order
//     ⇒ หลายอันในแผ่นเดียว ⇒ ทุกอันบอกเลขข้อ ⇒ ผู้อ่านรู้ว่าอันไหนของข้อไหน
import ปุ่มกากบาท from '~/components/ปุ่มกากบาท.vue'
import { Button } from '~/components/ui/button'
import type { เครื่องหมายเชิงอรรถ } from '~/utils/เชิงอรรถ'
import { ถ้อยคำเชิงอรรถ } from '~/utils/ถ้อยคำเชิงอรรถ'

const props = defineProps<{
  รายการ: เครื่องหมายเชิงอรรถ[]
  /** ภาษาของแต่ละฉบับ ⇒ ติด `lang` ให้ตัวหนังสือของเชิงอรรถ */
  ภาษาของ: Record<string, string | undefined>
  /** เปิดจากปุ่มในแถบข้อที่เลือก ⇒ ย้ายโฟกัสเข้าแผ่น */
  จับโฟกัส?: boolean
}>()
const emit = defineEmits<{ ปิด: []; ไปที่: [ที่อยู่: string, ก้อน: เครื่องหมายเชิงอรรถ] }>()

/** ชิ้นที่วาดได้เลย ⇒ ชิ้น `xt` ถูกผ่าตรงที่อยู่ที่ผู้แปลฝังไว้ ⇒ ตัวหนังสือต่อกลับได้ครบเท่าเดิม */
function ท่อนของ(ก้อน: เครื่องหมายเชิงอรรถ) {
  const ที่เหลือ = [...(ก้อน.โยงไป || [])]
  const ออก: { ตัวหนังสือ: string; ป้าย: string; ที่อยู่?: string }[] = []
  for (const ช of ก้อน.ชิ้น) {
    let ข้อความ = ช.ตัวหนังสือ
    while (ที่เหลือ.length) {
      const ร = ที่เหลือ[0]!
      const ที่ = ร.ตัวหนังสือ ? ข้อความ.indexOf(ร.ตัวหนังสือ) : -1
      if (ที่ < 0) break
      if (ที่ > 0) ออก.push({ ตัวหนังสือ: ข้อความ.slice(0, ที่), ป้าย: ช.ป้าย })
      ออก.push({ ตัวหนังสือ: ร.ตัวหนังสือ, ป้าย: ช.ป้าย, ที่อยู่: ร.ที่อยู่ })
      ข้อความ = ข้อความ.slice(ที่ + ร.ตัวหนังสือ.length)
      ที่เหลือ.shift()
    }
    if (ข้อความ) ออก.push({ ตัวหนังสือ: ข้อความ, ป้าย: ช.ป้าย })
  }
  return ออก
}

const แผ่น = ref<HTMLElement | null>(null)
const คำยก = new Set(['fq', 'fqa'])

function กดแป้น(e: KeyboardEvent) {
  if (e.key === 'Escape') emit('ปิด')
}
function กดนอก(e: PointerEvent) {
  const t = e.target as HTMLElement | null
  if (!แผ่น.value || แผ่น.value.contains(t) || t?.closest('[data-เชิงอรรถ]')) return
  emit('ปิด')
}
onMounted(() => {
  if (props.จับโฟกัส) แผ่น.value?.focus()
  document.addEventListener('keydown', กดแป้น)
  document.addEventListener('pointerdown', กดนอก)
})
onBeforeUnmount(() => {
  document.removeEventListener('keydown', กดแป้น)
  document.removeEventListener('pointerdown', กดนอก)
})
/** หัวของแต่ละอัน ⇒ หลายอัน หรือข้อที่ไม่มีเนื้อ ⇒ บอกเลขข้อด้วย */
const หลายอัน = computed(() => props.รายการ.length > 1)
const หัวของ = (ก: เครื่องหมายเชิงอรรถ) =>
  ก.ข้อเดิม || หลายอัน.value ? ถ้อยคำเชิงอรรถ.ข้อเดิม(ก.ป้าย, ก.ข้อเดิม || ก.ข้อ) : ก.ป้าย
const ชื่อแผ่น = computed(() => {
  const ก = props.รายการ[0]!
  return หลายอัน.value ? ถ้อยคำเชิงอรรถ.ปุ่ม : ถ้อยคำเชิงอรรถ.แผ่น(ก.ป้าย, ก.ฉบับ, ก.ข้อเดิม)
})
</script>

<template>
  <aside ref="แผ่น" class="pk-แผ่นเชิงอรรถ" role="dialog" tabindex="-1" :aria-label="ชื่อแผ่น">
    <template v-for="(ก้อน, k) in รายการ" :key="k">
      <div class="pk-หัวแผ่นเชิงอรรถ">
        <span class="pk-ป้ายแผ่นเชิงอรรถ">{{ หัวของ(ก้อน) }}</span>
        <span class="pk-ฉบับแผ่นเชิงอรรถ">{{ ถ้อยคำเชิงอรรถ.ของฉบับ(ก้อน.ฉบับ) }}</span>
        <component :is="ปุ่มกากบาท" v-if="k === 0" :ชื่อ="ถ้อยคำเชิงอรรถ.ปิด" @click="emit('ปิด')" />
      </div>
      <p :lang="ภาษาของ[ก้อน.ฉบับ]"
        ><template v-for="(ช, i) in ท่อนของ(ก้อน)" :key="i"
          ><Button
            v-if="ช.ที่อยู่"
            type="button"
            variant="ลิงก์"
            class="pk-ที่อยู่ในเชิงอรรถ"
            :data-ที่อยู่="ช.ที่อยู่"
            @click="emit('ไปที่', ช.ที่อยู่, ก้อน)"
            >{{ ช.ตัวหนังสือ }}</Button
          ><em v-else-if="คำยก.has(ช.ป้าย)" class="pk-คำยกเชิงอรรถ">{{ ช.ตัวหนังสือ }}</em
          ><template v-else>{{ ช.ตัวหนังสือ }}</template></template
        ></p
      >
    </template>
  </aside>
</template>
