<script setup lang="ts">
// หน้าบทความเล่าประสบการณ์หนึ่งเรื่อง (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/177 เกณฑ์ข้อ 3 · 6)
//
// ⭐⭐ **แสดงเฉพาะส่วนเรื่องเล่า** ⇒ ตัวเรื่องมาจาก `/api/story/<รหัส>.json` ⇒ ตัวอ่านเดิม `server/utils/เรื่องเล่า.ts` ตัดส่วนอื่นทิ้งแล้ว
//   ⇒ ⛔ รายการตรวจ ก ข ค ง ⛔ ขึ้นหน้า ⇒ ⛔ ไม่แก้ ⛔ ไม่ตัด ⛔ ไม่เติมตัวหนังสือของเรื่อง (กติกาเดียวกับแผ่นเรื่องเล่า ใบ #105)
//   ⇒ ชื่อเรื่อง ⇒ บรรทัด `ชื่อ:` ของไฟล์ที่อนุมัติ ⇒ ⛔ แต่งชื่อเอง
// ⭐ **ลำดับบนหน้า** ⇒ กลับหน้ารวม ⇒ ชื่อเรื่อง ⇒ ลิงก์ไปหน้าอ่านที่ช่วงข้อนั้น ⇒ ปุ่มฟังพร้อมความยาว ⇒ ตัวเรื่อง ⇒ เชิงอรรถ
//   ⇒ ปุ่มฟังอยู่ใต้หัวเรื่องก่อนเนื้อที่มันอ่าน ⇒ ท่าเดียวกับแผ่นเรื่องเล่า ⇒ ที่มาจดไว้ที่หัว `app/components/แผงเรื่องเล่า.vue`
// ⭐ **ลิงก์ไปหน้าอ่าน** ⇒ `c` `v` พาไปข้อแรกของเรื่อง · `r` คือช่วงของเรื่อง ⇒ ตัวต่อที่อยู่ `ที่อยู่หน้าอ่าน` ที่เดียว
// ⭐ **เสียง** ⇒ `<audio preload="none">` ⇒ ⛔ ขอไฟล์จนกว่าผู้อ่านกดฟัง ⇒ เรื่องที่ยังไม่มีเสียง ⛔ ไม่มีปุ่ม ⇒ ⛔ ไม่มีปุ่มที่กดแล้วเงียบ
//   ⇒ ⛔ ใช้ตัวเล่นของหน้าอ่าน (`ตัวเล่นเสียง.ts`) ⇒ หน้านี้มีเสียงเดียว ⇒ ปุ่มเดียว ฟัง · หยุดพัก · ฟังต่อ ⇒ คำเดิมของแผ่นเรื่องเล่า
//
// ⛔⛔ **ทางที่ไม่มีในทะเบียน ⇒ 404 จริง** (เกณฑ์ข้อ 6) ⇒ ⛔ หน้าว่าง ⛔ หน้าพัง
//   ⇒ ที่วางเว็บนิ่งส่ง `404.html` (โครงเปล่า) ⇒ โค้ดของหน้านี้ขอตัวเรื่อง ⇒ ไม่มีไฟล์ ⇒ โยน 404 ⇒ ได้หน้าไม่พบหน้านี้ของเว็บ
//   ⇒ ⭐ ทางต้องเป็นทรงที่ `ทางจากรหัสเรื่อง` เขียนเท่านั้น ⇒ ทางทรงอื่นที่แปลงกลับได้รหัสเดียวกัน ⛔ ได้หน้า ⇒ หนึ่งเรื่องหนึ่งที่อยู่
//
// ⛔⛔ **ต้องสั่ง import เอง — ตัวเติม import อัตโนมัติ ⛔ ไม่รู้จักชื่อภาษาไทย**
import { Button } from '~/components/ui/button'
import แถบนำทาง from '~/components/แถบนำทาง.vue'
import { ถ้อยคำเล่าประสบการณ์ as ถ } from '~/utils/ถ้อยคำเล่าประสบการณ์'
import { ทางจากรหัสเรื่อง, รหัสเรื่องจากทาง } from '~/utils/ทางบทความ'
import { ที่อยู่หลังบ้าน, ที่อยู่หน้าอ่าน, ที่อยู่หน้าเล่าประสบการณ์, แสดงช่วงฟัง } from '~/utils/ที่อยู่'

interface ตัวเรื่อง {
  รหัส: string
  จาก: { บท: number; ข้อ: number }
  ถึง: { บท: number; ข้อ: number }
  ชื่อเล่ม: string
  ชื่อ: string
  ย่อหน้า: string[]
  เชิงอรรถ?: { ป้าย: string; ข้อความ: string }[]
  เสียง: { ไฟล์: string; วินาที: number } | null
}

const route = useRoute()
const ทาง = String(route.params.id || '').replace(/\/+$/, '')
const รหัส = รหัสเรื่องจากทาง(ทาง)

const { data: เรื่อง } = await useAsyncData(`บทความ:${ทาง}`, async () => {
  if (!รหัส || ทางจากรหัสเรื่อง(รหัส) !== ทาง) return null
  try {
    return await $fetch<ตัวเรื่อง>(ที่อยู่หลังบ้าน(`api/story/${รหัส}.json`))
  } catch {
    // ⛔ ไม่มีไฟล์ตัวเรื่อง = เรื่องนี้ไม่อยู่ในทะเบียน ⇒ ตกไปเป็น 404 ข้างล่าง
    return null
  }
})
if (!เรื่อง.value) {
  throw createError({ statusCode: 404, statusMessage: 'ไม่มีหน้านี้', fatal: true })
}
const ร = เรื่อง.value

const ช่วง = `${ร.ชื่อเล่ม} ${แสดงช่วงฟัง({ จาก: ร.จาก, ถึง: ร.ถึง })}`
const ที่อยู่อ่าน = ที่อยู่หน้าอ่าน(ร.รหัส.split('.')[0]!, ร.จาก.บท, ร.จาก.ข้อ, null, { จาก: ร.จาก, ถึง: ร.ถึง })

// ---------------------------------------------------------------- เสียง
const เครื่องเล่น = ref<HTMLAudioElement | null>(null)
const สถานะ = ref<'ยังไม่เริ่ม' | 'กำลังเล่น' | 'หยุดพัก'>('ยังไม่เริ่ม')
const คำบนปุ่ม = computed(() =>
  สถานะ.value === 'กำลังเล่น' ? ถ.หยุดพัก : สถานะ.value === 'หยุดพัก' ? ถ.ฟังต่อ : ถ.ฟัง,
)
function กดฟัง() {
  const ก = เครื่องเล่น.value
  if (!ก) return
  if (ก.paused) void ก.play().catch(() => (สถานะ.value = 'ยังไม่เริ่ม'))
  else ก.pause()
}

// ---------------------------------------------------------------- เชิงอรรถ
// ⭐ ท่าเดียวกับแผ่นเรื่องเล่า (ใบ #168) ⇒ `[^ป้าย]` ⇒ เลขยกที่เป็นลิงก์ ⇒ กดแล้วเลื่อนไปท้ายเรื่องและโฟกัสย้ายตาม ⇒ ↩ กลับไปที่เลขที่กดมา
//   ⇒ ⛔ ใช้ v-html ⇒ ตัวเรื่องเป็นข้อความล้วน ⇒ ⛔ ไม่มีทางฝังโค้ดผ่านไฟล์เรื่อง
type ชิ้นย่อหน้า = { ข้อความ: string } | { ป้าย: string; ลำดับ: number; ไอดี: string }
const รอยเลขเชิงอรรถ = /(\[\^[^\]\s]+\])/
const ไอดีเชิงอรรถ = (ป้าย: string) => `pk-เชิงอรรถ-${ป้าย}`
const ลำดับเชิงอรรถ = new Map((ร.เชิงอรรถ || []).map((x, i) => [x.ป้าย, i + 1]))
const นับอ้าง = new Map<string, number>()
const ย่อหน้าเป็นชิ้น: ชิ้นย่อหน้า[][] = ร.ย่อหน้า.map((ย) =>
  ย.split(รอยเลขเชิงอรรถ).filter(Boolean).map((ส่วน): ชิ้นย่อหน้า => {
    const ป้าย = /^\[\^([^\]\s]+)\]$/.exec(ส่วน)?.[1]
    if (!ป้าย || !ลำดับเชิงอรรถ.has(ป้าย)) return { ข้อความ: ส่วน }
    const ครั้ง = (นับอ้าง.get(ป้าย) || 0) + 1
    นับอ้าง.set(ป้าย, ครั้ง)
    return { ป้าย, ลำดับ: ลำดับเชิงอรรถ.get(ป้าย)!, ไอดี: `pk-อ้างเชิงอรรถ-${ป้าย}-${ครั้ง}` }
  }),
)
const กดมาจาก = reactive<Record<string, string>>({})
function ไปที่(ไอดี: string) {
  const ที่ = document.getElementById(ไอดี)
  if (!ที่) return
  ที่.scrollIntoView({ block: 'center' })
  ที่.focus({ preventScroll: true })
}

/** แผงเลือกพระธรรมกางอยู่ไหม ⇒ เจ้าของแผงคือ `แถบนำทาง.vue` */
const เปิดแผง = ref(false)

// WCAG SC 2.4.2 (ระดับ A) — ทุกหน้ามีชื่อที่บอกว่าเป็นหน้าอะไร
useHead({ title: ร.ชื่อ })
</script>

<template>
  <article class="pk-เนื้อ pk-ม้วน pk-แผ่นเนื้อความ pk-หน้าบทความ" data-หน้า="บทความ" :data-รหัส="ร.รหัส">
    <!-- ⛔ ชื่อแท็กต้องเป็นตัวอักษรอังกฤษ ⇒ ชื่อชิ้นส่วนภาษาไทยต้องผ่าน `<component :is>` -->
    <component :is="แถบนำทาง" :เปิดแผง="เปิดแผง" @เปิดแผง="เปิดแผง = true" @ปิดแผง="เปิดแผง = false" />
    <p class="pk-กลับหน้ารวม">
      <a :href="ที่อยู่หน้าเล่าประสบการณ์()" data-ไป="เล่าประสบการณ์"><span aria-hidden="true">← </span>{{ ถ.ชื่อหน้า }}</a>
    </p>
    <h1>{{ ร.ชื่อ }}</h1>
    <p class="pk-ไปหน้าอ่าน">
      <a :href="ที่อยู่อ่าน" data-ไป="หน้าอ่าน">{{ ถ.ไปหน้าอ่าน(ช่วง) }}</a>
    </p>

    <!-- ⛔ เรื่องที่ยังไม่มีเสียง ⛔ ไม่มีปุ่ม -->
    <div v-if="ร.เสียง" class="pk-ฟังเรื่องเล่า">
      <Button type="button" variant="เข้ม" class="pk-ปุ่มฟัง" data-ปุ่ม="ฟังบทความ" :data-สถานะ="สถานะ" @click="กดฟัง">
        <span aria-hidden="true">{{ สถานะ === 'กำลังเล่น' ? '❚❚' : '▶' }}</span>
        {{ คำบนปุ่ม }}
      </Button>
      <p class="pk-หมายเหตุเสียงเรื่องเล่า">{{ ถ.หมายเหตุเสียง(ร.เสียง.วินาที) }}</p>
      <audio
        ref="เครื่องเล่น"
        preload="none"
        :src="ที่อยู่หลังบ้าน(ร.เสียง.ไฟล์)"
        @play="สถานะ = 'กำลังเล่น'"
        @pause="สถานะ = ($event.target as HTMLAudioElement).ended ? 'ยังไม่เริ่ม' : 'หยุดพัก'"
        @ended="สถานะ = 'ยังไม่เริ่ม'"
      />
    </div>

    <div class="pk-ตัวบทความ" data-ตัวเรื่องเล่า>
      <p v-for="(ชุด, i) in ย่อหน้าเป็นชิ้น" :key="i" class="pk-ย่อหน้าเรื่องเล่า">
        <template v-for="(ช, j) in ชุด" :key="j">
          <sup v-if="'ป้าย' in ช" class="pk-เลขเชิงอรรถ"><a
            :id="ช.ไอดี"
            :href="`#${ไอดีเชิงอรรถ(ช.ป้าย)}`"
            :aria-label="ถ.เลขเชิงอรรถ(ช.ลำดับ)"
            data-เลขเชิงอรรถ
            @click.prevent="(กดมาจาก[ช.ป้าย] = ช.ไอดี), ไปที่(ไอดีเชิงอรรถ(ช.ป้าย))"
          >{{ ช.ลำดับ }}</a></sup>
          <template v-else>{{ ช.ข้อความ }}</template>
        </template>
      </p>
    </div>
    <!-- ⭐ เชิงอรรถ ⛔ อยู่นอก `data-ตัวเรื่องเล่า` ⇒ ⛔ ไม่ใช่ตัวเรื่อง ⇒ ⛔ ไม่อ่านออกเสียง -->
    <section v-if="ร.เชิงอรรถ?.length" class="pk-เชิงอรรถเรื่องเล่า" aria-labelledby="pk-หัวเชิงอรรถ" data-เชิงอรรถเรื่องเล่า>
      <h2 id="pk-หัวเชิงอรรถ">{{ ถ.หัวเชิงอรรถ }}</h2>
      <ol>
        <li v-for="(ช, i) in ร.เชิงอรรถ" :id="ไอดีเชิงอรรถ(ช.ป้าย)" :key="ช.ป้าย" tabindex="-1" data-เชิงอรรถ>
          {{ ช.ข้อความ }}
          <a
            :href="`#${กดมาจาก[ช.ป้าย] || `pk-อ้างเชิงอรรถ-${ช.ป้าย}-1`}`"
            class="pk-กลับจากเชิงอรรถ"
            :aria-label="ถ.กลับจากเชิงอรรถ(i + 1)"
            data-กลับเชิงอรรถ
            @click.prevent="ไปที่(กดมาจาก[ช.ป้าย] || `pk-อ้างเชิงอรรถ-${ช.ป้าย}-1`)"
          ><span aria-hidden="true">↩</span></a>
        </li>
      </ol>
    </section>
  </article>
</template>
