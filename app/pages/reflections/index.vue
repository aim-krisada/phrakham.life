            <line x1="3" y1="12" x2="3.01" y2="12" />
            <line x1="3" y1="18" x2="3.01" y2="18" />
          </svg>
          {{ ถ.รายการ }}
        </Button>
      </div>
    </div>

    <!-- ---------------------------------------------------------------- แผนที่ -->
    <div class="pk-แผนที่บทความ" data-มุม="แผนที่" :hidden="มุม !== 'แผนที่'">
      <section
        v-for="x in เล่มทั้งหมด"
        :key="x.รหัส"
        class="pk-แผนที่เล่ม"
        :data-เล่ม="x.รหัส"
        :aria-labelledby="`pk-แผนที่-${x.รหัส}`"
      >
        <h3 :id="`pk-แผนที่-${x.รหัส}`" class="pk-หัวแผนที่เล่ม">
          <span class="pk-ชื่อเล่มบนแผนที่">{{ x.ชื่อไทย }}</span>
          <span class="pk-ป้ายเล่มบนแผนที่">{{ ถ.ป้ายเล่มบนแผนที่(x.เรื่อง.length, บทที่มี(x).ต้น, บทที่มี(x).ท้าย) }}</span>
        </h3>
        <div class="pk-แถวช่องบท">
          <template v-for="บท in จำนวนช่อง(x)" :key="บท">
            <!-- ⭐ เลขจำนวนเรื่องมุมช่อง (รุ่น 2 `.cdot`) ⇒ อยู่ **นอกปุ่ม** ⇒ อยู่ในปุ่มแล้วตาเห็น *104* แต่ชื่อที่ได้ยินขึ้นต้นด้วย *มาระโก บทที่ 10*
                   ⇒ ผิด SC 2.5.3 Label in Name (axe `label-content-name-mismatch` จับได้จริงตอนทำ) ⇒ จำนวนอยู่ในชื่อที่ได้ยินแล้ว ⇒ เลขมุมช่องซ่อนจากโปรแกรมอ่านหน้าจอ -->
            <span v-if="เรื่องของบท(x, บท).length" class="pk-ห่อช่องบท">
              <Button
                type="button"
                variant="เข้ม"
                class="pk-ช่องบท pk-มีบทความ"
                :data-บท="บท"
                :aria-label="ถ.ชื่อช่องบท(x.ชื่อไทย, บท, เรื่องของบท(x, บท).length)"
                :aria-pressed="คือช่องที่เลือก(x, บท)"
                @click="ที่เลือก = { เล่ม: x.รหัส, บท }"
              >
                {{ บท }}
              </Button>
              <span v-if="เรื่องของบท(x, บท).length > 1" class="pk-นับในช่อง" aria-hidden="true">{{ เรื่องของบท(x, บท).length }}</span>
            </span>
            <!-- ⭐ บทที่ยังไม่มี ⇒ ⛔ ปุ่ม ⇒ ซ่อนจากโปรแกรมอ่านหน้าจอแบบรุ่น 2 ⇒ ป้ายข้างชื่อเล่มบอกช่วงบทที่มีแล้ว -->
            <span v-else class="pk-ช่องบท" :data-บท="บท" aria-hidden="true">{{ บท }}</span>
          </template>
        </div>
      </section>
      <p class="pk-คำอธิบายสีแผนที่">
        <span><i class="pk-สีมีบทความ" aria-hidden="true" />{{ ถ.มีบทความ }}</span>
