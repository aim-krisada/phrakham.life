<script setup lang="ts">
// หน้าเล่าประสบการณ์ — หน้ารวมบทความ ดูได้ 2 แบบ *แผนที่* กับ *รายการ* (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/177)
//
// ⭐⭐ **แบบเดียวกับหน้าเดิมของรุ่น 2** ⇒ `krisada/phrakham.life2` ไฟล์ `reflections/index.qmd` (@krisada ชอบหน้านี้ ⇒ ใบข้อ *ทำไม* 2)
//   ⇒ คำบนหน้าทุกคำลอกจากไฟล์นั้น ⇒ อยู่ที่ `app/utils/ถ้อยคำเล่าประสบการณ์.ts` ที่เดียว
//   ⇒ **รายการ** ⇒ แยกกลุ่มตามเล่ม (ลำดับพระธรรม) ⇒ เรียงบทแล้วข้อ ⇒ แถวละช่วงข้อกับชื่อเรื่อง (เกณฑ์ข้อ 1.1)
//   ⇒ **แผนที่** ⇒ เล่มละแถว ช่องละบท ⇒ บทที่มีบทความเป็นปุ่มสีเข้ม ⇒ กดแล้วแผงใต้แผนที่บอกบทความของบทนั้น
//     ⇒ บทที่ยังไม่มีเป็นช่องจาง ⛔ ปุ่ม ⛔ กดไม่ได้ (เกณฑ์ข้อ 1.2) ⇒ เรื่องที่คร่อมบทติดทุกบทที่คร่อม (เกณฑ์ข้อ 1.3)
//   ⇒ **ปุ่มสลับ** ⇒ `aria-pressed` แบบรุ่น 2 ⇒ โปรแกรมอ่านหน้าจอบอกได้ว่าเลือกแบบไหนอยู่ (เกณฑ์ข้อ 5)
//     ⇒ ⭐ ช่องบทบนแผนที่ที่ถูกเลือกก็บอกด้วย `aria-pressed` ⇒ รุ่น 2 บอกแค่ด้วยเส้นขอบ (ตาเห็นอย่างเดียว)
//   ⇒ ⭐ รุ่น 2 จำแบบที่เลือกไว้ในเครื่อง (`pk-ref-view`) ⇒ ที่นี่จำด้วยชื่อเดียวกัน ⇒ ⛔ เก็บไม่ได้ ⇒ ได้ *รายการ* ตามรุ่น 2
//   ⇒ ⭐ เปิดหน้ามา แผงใต้แผนที่เลือกบทของเรื่องที่อนุมัติล่าสุดไว้ให้ ⇒ ท่าเดียวกับรุ่น 2 ที่เลือกบทของบทความใหม่สุด
//
// ⭐⭐ **รายชื่อบทความมาจาก `/api/stories.json` ⇒ อ่านจาก `เรื่องเล่า/ทะเบียน.tsv` อย่างเดียว** (เกณฑ์ข้อ 2)
//   ⇒ หน้านี้ ⛔ พิมพ์ชื่อเรื่องหรือช่วงไว้เองสักตัว ⇒ เพิ่มแถวในทะเบียนแล้วขึ้นเอง
// ⭐ ลิงก์ไปหน้าบทความเป็น `<a>` ธรรมดา ⇒ หน้าบทความถูกสร้างไว้ล่วงหน้าครบ ⇒ เหตุผลเดียวกับหน้าสารบัญ (`app/pages/read/index.vue`)
// ⭐ ตัวเฝ้าคือ `tools/ด่านหน้าเล่าประสบการณ์.mjs`
//
// ⛔⛔ **ต้องสั่ง import เอง — ตัวเติม import อัตโนมัติ ⛔ ไม่รู้จักชื่อภาษาไทย**
// ⭐ ปุ่มกลางของทั้งเว็บ (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/141) ⇒ เหตุผลอยู่ที่ `app/components/ui/button/index.ts`
import { Button } from '~/components/ui/button'
import แถบนำทาง from '~/components/แถบนำทาง.vue'
import { ถ้อยคำเล่าประสบการณ์ as ถ } from '~/utils/ถ้อยคำเล่าประสบการณ์'
import { ที่อยู่หลังบ้าน, ที่อยู่หน้าบทความ, แสดงช่วงฟัง } from '~/utils/ที่อยู่'

interface ตำแหน่ง {
  บท: number
  ข้อ: number
}
interface เรื่อง {
  รหัส: string
  จาก: ตำแหน่ง
  ถึง: ตำแหน่ง
  ชื่อ: string
  อนุมัติเมื่อ: string
}
interface เล่ม {
  รหัส: string
  ชื่อไทย: string
  บท: number
  เรื่อง: เรื่อง[]
}

const { data: ข้อมูล } = await useAsyncData('รายชื่อบทความ', () =>
  $fetch<{ เล่ม: เล่ม[] }>(ที่อยู่หลังบ้าน('api/stories.json')),
)
// ⛔ อ่านรายชื่อไม่ได้ = พังจริง ⛔ ไม่ใช่หน้าเปล่าที่ดูเหมือนยังไม่มีบทความ
if (!ข้อมูล.value) {
  throw createError({ statusCode: 500, statusMessage: 'อ่านรายชื่อบทความไม่ได้', fatal: true })
}

const เล่มทั้งหมด = computed(() => ข้อมูล.value!.เล่ม)
const จำนวนทั้งหมด = computed(() => เล่มทั้งหมด.value.reduce((n, x) => n + x.เรื่อง.length, 0))

/** เรื่องของบทหนึ่ง ⇒ เรื่องที่คร่อมบทอยู่ในทุกบทที่มันคร่อม ⇒ เรียงบทแล้วข้อ (ของมาเรียงแล้ว) */
const เรื่องของบท = (x: เล่ม, บท: number) => x.เรื่อง.filter((ร) => ร.จาก.บท <= บท && ร.ถึง.บท >= บท)
/** บทที่มีบทความ ⇒ ต้นถึงท้ายของทั้งเล่ม ⇒ ป้ายข้างชื่อเล่มบนแผนที่ */
const บทที่มี = (x: เล่ม) => {
  const ทุกบท = x.เรื่อง.flatMap((ร) => Array.from({ length: ร.ถึง.บท - ร.จาก.บท + 1 }, (_, i) => ร.จาก.บท + i))
  return { ต้น: Math.min(...ทุกบท), ท้าย: Math.max(...ทุกบท) }
}
/** จำนวนช่องของเล่ม ⇒ จำนวนบทจากบัญชี 66 เล่ม ⇒ ⛔ น้อยกว่าบทที่มีเรื่อง */
const จำนวนช่อง = (x: เล่ม) => Math.max(x.บท, บทที่มี(x).ท้าย)
const ช่วงของ = (ร: เรื่อง) => แสดงช่วงฟัง({ จาก: ร.จาก, ถึง: ร.ถึง })

// ---------------------------------------------------------------- มุมมอง
type มุมมอง = 'แผนที่' | 'รายการ'
const กุญแจจำ = 'pk-ref-view'
const มุม = ref<มุมมอง>('รายการ')
function เลือกมุม(ม: มุมมอง) {
  มุม.value = ม
  try {
    localStorage.setItem(กุญแจจำ, ม === 'แผนที่' ? 'map' : 'list')
  } catch {}
}
onMounted(() => {
  try {
    if (localStorage.getItem(กุญแจจำ) === 'map') มุม.value = 'แผนที่'
  } catch {}
})

// ---------------------------------------------------------------- บทที่เลือกบนแผนที่
/** ⭐ ตั้งต้น ⇒ บทแรกของเรื่องที่อนุมัติล่าสุด ⇒ ท่ารุ่น 2 (`selectChapter(ARTICLES[0]...)` ⇒ บทความใหม่สุด) */
const ล่าสุด = computed(() => {
  let ผล: { เล่ม: string; บท: number; วัน: string } | null = null
  for (const x of เล่มทั้งหมด.value)
    for (const ร of x.เรื่อง) if (!ผล || ร.อนุมัติเมื่อ > ผล.วัน) ผล = { เล่ม: x.รหัส, บท: ร.จาก.บท, วัน: ร.อนุมัติเมื่อ }
  return ผล
})
const ที่เลือก = ref<{ เล่ม: string; บท: number } | null>(ล่าสุด.value ? { เล่ม: ล่าสุด.value.เล่ม, บท: ล่าสุด.value.บท } : null)
const เล่มที่เลือก = computed(() => เล่มทั้งหมด.value.find((x) => x.รหัส === ที่เลือก.value?.เล่ม) || null)
const เรื่องที่เลือก = computed(() =>
  เล่มที่เลือก.value && ที่เลือก.value ? เรื่องของบท(เล่มที่เลือก.value, ที่เลือก.value.บท) : [],
)
const คือช่องที่เลือก = (x: เล่ม, บท: number) => ที่เลือก.value?.เล่ม === x.รหัส && ที่เลือก.value?.บท === บท

/** แผงเลือกพระธรรมกางอยู่ไหม ⇒ เจ้าของแผงคือ `แถบนำทาง.vue` ⇒ ท่าเดียวกับหน้าอื่น */
const เปิดแผง = ref(false)

// WCAG SC 2.4.2 (ระดับ A) — ทุกหน้ามีชื่อที่บอกว่าเป็นหน้าอะไร
useHead({ title: ถ.ชื่อหน้า, meta: [{ name: 'description', content: ถ.คำโปรย }] })
</script>

<template>
  <!-- ⭐ `pk-แผ่นเนื้อความ` ⇒ พื้นโต๊ะกับแผ่นแบบเดียวกับหน้าแหล่งข้อมูลและหน้าเกี่ยวกับเรา ⇒ เหตุผลอยู่ที่ `app/pages/[...slug].vue` -->
  <article class="pk-เนื้อ pk-ม้วน pk-แผ่นเนื้อความ pk-หน้าเล่าประสบการณ์" data-หน้า="เล่าประสบการณ์">
    <!-- ⛔ ชื่อแท็กต้องเป็นตัวอักษรอังกฤษ ⇒ ชื่อชิ้นส่วนภาษาไทยต้องผ่าน `<component :is>` -->
    <component
      :is="แถบนำทาง"
      หน้านี้="เล่าประสบการณ์"
      :เปิดแผง="เปิดแผง"
      @เปิดแผง="เปิดแผง = true"
      @ปิดแผง="เปิดแผง = false"
    />
    <h1>{{ ถ.ชื่อหน้า }}</h1>
    <p class="pk-โปรยเล่าประสบการณ์">{{ ถ.คำโปรย }}</p>

    <div class="pk-หัวบทความทั้งหมด">
      <h2 id="pk-หัวบทความทั้งหมด">{{ ถ.หัวทั้งหมด(จำนวนทั้งหมด) }}</h2>
      <!-- ⭐ รุ่น 2 ⇒ กลุ่มปุ่มสลับ ⇒ แผนที่ก่อน รายการตาม ⇒ บอกสถานะด้วย `aria-pressed`
           ⇒ ปุ่มกลางของเว็บ (ใบ #141 ⇒ `tools/ด่านปุ่มชุดเดียว.mjs`) ⇒ ที่เลือกอยู่เป็นชนิด `เข้ม` (พื้นทึบ) · อีกปุ่มชนิด `กรอบ`
           ⇒ ⚠️ รุ่น 2 เป็นกล่องเดียวแบ่งสองช่อง ⇒ ที่นี่เป็นสองปุ่มวางชิดกัน ⇒ มุม เงา กรอบ มาจากค่าชุดเดียวของทั้งเว็บ -->
      <div class="pk-สลับมุมมอง" role="group" :aria-label="ถ.กลุ่มมุมมอง">
        <Button
          type="button"
          class="pk-ปุ่มมุมมอง"
          :variant="มุม === 'แผนที่' ? 'เข้ม' : 'กรอบ'"
          data-มุมมอง="แผนที่"
          :aria-pressed="มุม === 'แผนที่'"
          @click="เลือกมุม('แผนที่')"
        >
          <!-- รูปของรุ่น 2 ⇒ ตาราง 4 ช่อง -->
          <svg viewBox="0 0 24 24" aria-hidden="true">
            <rect x="3" y="3" width="7" height="7" />
            <rect x="14" y="3" width="7" height="7" />
            <rect x="3" y="14" width="7" height="7" />
            <rect x="14" y="14" width="7" height="7" />
          </svg>
          {{ ถ.แผนที่ }}
        </Button>
        <Button
          type="button"
          class="pk-ปุ่มมุมมอง"
          :variant="มุม === 'รายการ' ? 'เข้ม' : 'กรอบ'"
          data-มุมมอง="รายการ"
          :aria-pressed="มุม === 'รายการ'"
          @click="เลือกมุม('รายการ')"
        >
          <!-- รูปของรุ่น 2 ⇒ รายการ 3 แถว -->
          <svg viewBox="0 0 24 24" aria-hidden="true">
            <line x1="8" y1="6" x2="21" y2="6" />
            <line x1="8" y1="12" x2="21" y2="12" />
