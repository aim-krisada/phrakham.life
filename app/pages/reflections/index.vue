        v-if="เล่มที่เลือก && ที่เลือก && เรื่องที่เลือก.length"
        class="pk-แผงบทที่เลือก"
        data-แผงบท
        aria-labelledby="pk-หัวแผงบท"
      >
        <h3 id="pk-หัวแผงบท">
          {{ ถ.หัวแผงบท(เล่มที่เลือก.ชื่อไทย, ที่เลือก.บท) }}
          <span class="pk-นับเรื่อง">{{ ถ.จำนวนเรื่อง(เรื่องที่เลือก.length) }}</span>
        </h3>
        <ul class="pk-รายการบทความ">
          <li v-for="ร in เรื่องที่เลือก" :key="ร.รหัส">
            <a :href="ที่อยู่หน้าบทความ(ร.รหัส)" :data-รหัส="ร.รหัส">
              <span class="pk-ช่วงบทความ">{{ ช่วงของ(ร) }}</span>
              <span class="pk-ชื่อบทความ">{{ ร.ชื่อ }}</span>
            </a>
          </li>
        </ul>
      </section>
    </div>

    <!-- ---------------------------------------------------------------- รายการ -->
    <div class="pk-รายการบทความทั้งหมด" data-มุม="รายการ" :hidden="มุม !== 'รายการ'">
      <section v-for="x in เล่มทั้งหมด" :key="x.รหัส" :data-เล่ม="x.รหัส" :aria-labelledby="`pk-รายการ-${x.รหัส}`">
        <h3 :id="`pk-รายการ-${x.รหัส}`" class="pk-หัวเล่มในรายการ">
          {{ x.ชื่อไทย }} <span class="pk-นับเรื่อง">{{ ถ.จำนวนบทความ(x.เรื่อง.length) }}</span>
        </h3>
        <ul class="pk-รายการบทความ">
          <li v-for="ร in x.เรื่อง" :key="ร.รหัส">
            <a :href="ที่อยู่หน้าบทความ(ร.รหัส)" :data-รหัส="ร.รหัส">
              <span class="pk-ช่วงบทความ">{{ ช่วงของ(ร) }}</span>
              <span class="pk-ชื่อบทความ">{{ ร.ชื่อ }}</span>
            </a>
          </li>
        </ul>
      </section>
    </div>
  </article>
