<script setup lang="ts">
// หน้าเดียวรับทุกที่อยู่ แล้วไปหยิบไฟล์ `.md` ที่ตรงกับที่อยู่นั้นมาแสดง
// ⇒ เพิ่มไฟล์ใน `content/` แล้วได้หน้าใหม่ทันที ⛔ ไม่ต้องมาเขียนหน้า `.vue` เพิ่มทุกครั้ง
const route = useRoute()
// ⭐ **ที่อยู่ที่ผู้อ่านพิมพ์มา ต้องล้างให้เป็นรูปเดียวกับที่คลังเก็บก่อนค้น** (เจ้าของที่อยู่ = บรรทัด `path:` ของไฟล์ `.md`)
//   ⛔ `route.path` เก็บของที่ **เข้ารหัสเป็น %E0%B9%81…** เมื่อที่อยู่มีตัวไทย ส่วนในคลังเก็บเป็นตัวไทย
//   ⇒ ไม่ถอดรหัสก่อน = หาไม่เจอ แล้วได้ 404 (เจอเองตอนเปิดครั้งแรก 29 ส.ค. 2569)
//   ⭐ **และต้องตัดทับปิดท้ายทิ้งด้วย** — คลังเก็บที่อยู่ตามบรรทัด `path:` ของไฟล์ `.md` ⇒ ⛔ ไม่มีทับปิดท้าย
//   ⇒ ผู้อ่านที่เปิดที่อยู่แบบมีทับ (โฮสต์พาไปเองเวลาที่อยู่นั้นเป็นโฟลเดอร์) จะหาไม่เจอ
//   ⇒ โค้ดโยน 404 ทับหน้าที่สร้างไว้ล่วงหน้า ⇒ **เนื้อขึ้นแล้วหายไปต่อหน้าผู้อ่าน**
//   (พี่เอมเจอเอง 29 ส.ค. 2569 · ใบงาน v3/phrakham#22)
const ที่อยู่ = computed(() => decodeURIComponent(route.path).replace(/\/+$/, '') || '/')
const { data: หน้า } = await useAsyncData(`หน้า:${ที่อยู่.value}`, () =>
  queryCollection('content').path(ที่อยู่.value).first(),
)

// ⛔ ไม่มีไฟล์ตรงกับที่อยู่นี้ = 404 จริง ⛔ ไม่ใช่หน้าเปล่าที่ดูเหมือนใช้ได้
if (!หน้า.value) {
  throw createError({ statusCode: 404, statusMessage: 'ไม่มีหน้านี้', fatal: true })
}

// WCAG SC 2.4.2 (ระดับ A) — ทุกหน้ามีชื่อที่บอกว่าเป็นหน้าอะไร
useHead({ title: หน้า.value.title })

// ⭐⭐ **หน้าพวกนี้เคยเป็นทางตัน** ⇒ วัดเองจากหน้าจริง 11 ต.ค. 2569 ⇒ `/sources` ที่ขึ้นเว็บอยู่
//   **⛔ ไม่มีชื่อเว็บ ⛔ ไม่มีเมนู ⛔ ไม่มีลิงก์กลับหน้าแรกเลยสักเส้น** ⇒ เข้าไปแล้วออกไม่ได้
//   ⇒ ผิด **WCAG 2.2 SC 3.2.3 Consistent Navigation (ระดับ AA)** เพราะหน้าอื่นมีของนำทาง แต่หน้านี้ไม่มี
//   ⇒ และตก *trunk test* ของ Krug ⇒ เขาว่าโยนคนลงหน้าไหนก็ได้ เขาต้องตอบได้ทันทีว่า
//     **เว็บอะไร · อยู่ตรงไหน · ไปไหนต่อได้บ้าง** ⇒ หน้านี้ตอบไม่ได้สักข้อ
// ⛔⛔ **ต้องสั่ง import เอง — ตัวเติม import อัตโนมัติ ⛔ ไม่รู้จักชื่อภาษาไทย**
import แถบนำทาง from '~/components/แถบนำทาง.vue'

// ⭐ หน้าไหนเป็นหน้าแหล่งข้อมูล ⇒ ดูจาก **ที่อยู่ที่ไฟล์ `.md` ประกาศไว้เอง** ⛔ ไม่พิมพ์ที่อยู่ซ้ำที่นี่
//   ⇒ ⭐ ใบ #172 ⇒ หน้าเกี่ยวกับเรา (`content/เกี่ยวกับเรา.md`) ⇒ รายการ *เกี่ยวกับเรา* ในเมนูเป็นตัวหนังสือติด `aria-current` ⛔ ลิงก์วนกลับ
const หน้านี้ = computed(() =>
  ที่อยู่.value.endsWith('/sources') ? 'แหล่ง' : ที่อยู่.value.endsWith('/about') ? 'เกี่ยวกับ' : undefined,
)

// ⭐⭐ **แผงเลือกพระธรรมของทั้งเว็บเป็นของ `แถบนำทาง.vue`** ⇒ หน้านี้ถือแค่สถานะว่ากางอยู่ไหม
//   ⇒ ⛔ ไม่ถือสถานะ = หัวเมนู *อ่านพระคัมภีร์* บนหน้านี้กดแล้วไม่เกิดอะไร
//     ⇒ กลับไปเป็น **2 หน้าตาสำหรับงานเดียวกัน** ซึ่งคือข้อที่พี่เอมทักไว้ 12 ต.ค. 2569
const เปิดแผง = ref(false)
</script>

<template>
  <!-- ⛔ **ห้ามใส่คลาส `pk-หน้าอ่าน` ที่นี่** — กฎทั้งบล็อกของคลาสนั้นเขียนไว้เองว่า ⛔ ไม่แตะหน้าแหล่งข้อมูล
       ⇒ ใส่แล้วความกว้างย่อหน้ากับขนาดตัวอักษรของหน้านี้จะเปลี่ยนตาม โดย ⛔ ไม่มีใครสั่ง
       ⭐ **`pk-แผ่นเนื้อความ`** ⇒ พื้นโต๊ะกับแผ่นแบบเดียวกับหน้าอื่น ⛔ ไม่แตะขนาดหรือความกว้างของตัวหนังสือ
         (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/141 ข้อ 3) ⇒ กฎอยู่ท้าย `app/assets/css/main.css` -->
  <article class="pk-เนื้อ pk-ม้วน pk-แผ่นเนื้อความ">
    <!-- ⛔ ชื่อแท็กต้องเป็นตัวอักษรอังกฤษ ⇒ ชื่อชิ้นส่วนภาษาไทยต้องผ่าน `<component :is>` -->
    <component
      :is="แถบนำทาง"
      :หน้านี้="หน้านี้"
      :เปิดแผง="เปิดแผง"
      @เปิดแผง="เปิดแผง = true"
      @ปิดแผง="เปิดแผง = false"
    />
    <ContentRenderer v-if="หน้า" :value="หน้า" />
  </article>
</template>
