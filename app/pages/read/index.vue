  รหัส: string
  ชื่อไทย: string
  พันธสัญญา: string
  บท: number
  บทที่มี: number[]
}

const { data: บัญชี } = await useAsyncData('บัญชีเล่ม', () =>
  $fetch<{ จำนวนเล่ม: number; จำนวนบท: number; เล่ม: เล่ม[] }>(ที่อยู่หลังบ้าน('api/books.json')),
)

// ⛔ อ่านบัญชีไม่ได้ = พังจริง ⛔ ไม่ใช่หน้าเปล่าที่ดูเหมือนใช้ได้
if (!บัญชี.value) {
  throw createError({ statusCode: 500, statusMessage: 'อ่านบัญชีเล่มไม่ได้', fatal: true })
}

const กลุ่ม = computed(() => [
  { ชื่อ: 'พันธสัญญาเดิม', เล่ม: บัญชี.value!.เล่ม.filter((b) => b.พันธสัญญา === 'เดิม') },
  { ชื่อ: 'พันธสัญญาใหม่', เล่ม: บัญชี.value!.เล่ม.filter((b) => b.พันธสัญญา === 'ใหม่') },
])

/** แผงเลือกพระธรรมกางอยู่ไหม ⇒ เปิดจากปุ่มค้นหาบนแถบ (ใบ #173) */
