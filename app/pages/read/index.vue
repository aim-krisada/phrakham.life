            ⇒ ให้เบราว์เซอร์เปิดหน้าใหม่ตรง ๆ ⇒ ผู้อ่านที่เน็ตช้าหรือโค้ดโหลดไม่สำเร็จ ก็ยังเดินได้ครบทุกหน้า
          -->
