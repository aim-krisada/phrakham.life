  <article class="pk-เนื้อ pk-หน้าอ่าน pk-ม้วน">
    <!-- ⛔ ชื่อแท็กต้องเป็นตัวอักษรอังกฤษ ⇒ ชื่อชิ้นส่วนภาษาไทยต้องผ่าน `<component :is>` -->
    <!-- ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/173 ⇒ ปุ่มค้นหาบนแถบเปิดแผงเลือกพระธรรมได้จากหน้านี้ด้วย ⇒ หน้านี้ถือสถานะว่าแผงกางอยู่ไหม
           ⇒ ท่าเดียวกับหน้าแรกและหน้าแหล่งข้อมูล ⇒ เจ้าของแผงคือ `แถบนำทาง.vue` -->
