<script setup lang="ts">
// ⭐⭐ **ที่อยู่เดิม `/read/<เล่ม>/<บท>` — มีไว้พาไปที่อยู่ใหม่เท่านั้น** (ใบงาน v3/phrakham#73)
//
// **ทำไมต้องเหลือไว้** ⇒ ลิงก์แบบนี้ถูกแชร์ออกไปแล้ว และคนคั่นหน้าไว้
//   ⇒ **ทำให้ลิงก์เก่าตาย = ทำร้ายคนที่เคยใช้เว็บเรา** ⇒ ใบงานห้ามไว้ตรง ๆ
//
// ⭐ **หน้านี้ ⛔ ไม่ถูกสร้างไว้ล่วงหน้า** ⇒ ถ้าสร้าง ก็กลับไปมี 1,189 หน้าเหมือนเดิม
//   ⇒ ที่วางเว็บนิ่ง (GitLab Pages · GitHub Pages) เจอที่อยู่ที่ไม่มีไฟล์ **จะส่ง `404.html` มาให้**
//     ⇒ `404.html` ที่ตัวสร้างทำให้ **คือโครงของเว็บทั้งก้อน** ⇒ โค้ดของเว็บติดแล้วเดินเส้นทางนี้เอง
//   ⇒ **วิธีดูของจริง** ⇒ เปิด `.output/public/404.html` แล้วดูว่ามี `<div id="__nuxt">` เปล่า ๆ อยู่
//   ⇒ ตัวเสิร์ฟตอนตรวจ (`tools/เสิร์ฟเว็บที่สร้างเสร็จ.mjs`) ทำแบบเดียวกัน ⇒ ด่านจึงเห็นของจริง
//
// ⛔⛔ **ต้องสั่ง import เอง — ตัวเติม import อัตโนมัติ ⛔ ไม่รู้จักชื่อภาษาไทย**
import { ที่อยู่หน้าอ่าน } from '~/utils/ที่อยู่'
import { ออกไปที่ } from '~/utils/ออกจากหน้า'

const route = useRoute()
const รหัสเล่ม = String(route.params.book)
const เลขบท = String(route.params.chapter)
const ข้อ = Number(route.query['v'])

// ⛔ **ต้องเป็น `replace` ⛔ ไม่ใช่การเปิดหน้าใหม่ทับ** — ไม่งั้นกดปุ่มถอยกลับแล้ววนกลับมาที่นี่ไม่รู้จบ
const ที่ไป = ที่อยู่หน้าอ่าน(รหัสเล่ม, เลขบท, Number.isFinite(ข้อ) && ข้อ > 0 ? ข้อ : null)

// WCAG SC 2.4.2 (ระดับ A) — ทุกหน้ามีชื่อที่บอกว่าเป็นหน้าอะไร
useHead({ title: 'กำลังพาไปหน้าของเล่มนี้ — อ่านพระคัมภีร์' })

// ⭐ `ออกไปที่` = `location.replace` + บอกตัวนับคนเข้าเว็บว่าหน้านี้ไม่นับ (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/170)
onMounted(() => ออกไปที่(ที่ไป))
</script>

<template>
  <article class="pk-เนื้อ pk-หน้าอ่าน">
    <h1>กำลังพาไปหน้าของเล่มนี้…</h1>
    <!-- ⭐ ลิงก์จริงติดไว้ด้วย ⇒ โค้ดของเว็บโหลดไม่สำเร็จ ผู้อ่านก็ยังกดไปเองได้ -->
    <p><a :href="ที่ไป">กดที่นี่ถ้าหน้าไม่เปลี่ยนเอง</a></p>
  </article>
</template>
