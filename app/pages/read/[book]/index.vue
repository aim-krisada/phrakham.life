<script setup lang="ts">
// หน้าอ่านของ **หนึ่งเล่ม** — ⭐⭐ **1 เล่ม = 1 หน้า** (ใบงาน v3/phrakham#73 · พี่เอมสั่ง 6 ก.ย. 2569)
//
// > *"ผมว่าควรนับได้แค่ 66 หน้า คือแต่ละเล่ม ตัวบทและข้อคือการเลือกภายใน ไม่ใช่หน้า"*
//
// ⇒ **บทกับข้อเป็นคำถามท้ายที่อยู่** `?c=119&v=1` ⛔ ไม่ใช่เส้นทางของหน้า
// ⇒ เจ้าของรูปที่อยู่คือ `app/utils/ที่อยู่.ts` ⛔ ไม่จดซ้ำที่นี่
//
// ⭐ **บทที่ถูกวาดไว้ล่วงหน้าในหน้านี้คือบทแรกของเล่ม** ⇒ บทอื่นถูกหยิบมาตอนคนเลื่อนถึงหรือกดเลือก
//   ⇒ ⛔ ไม่ยัดทั้งเล่มลงหน้าเดียว — เล่มที่ยาวที่สุดจะหนักจนเลื่อนไม่ลื่น
//   ⇒ **หน้าต่างบทที่กางอยู่กว้างแค่ไหน เจ้าของคือ `app/components/หน้าอ่าน.vue`** ⛔ ไม่จดซ้ำที่นี่
//
// ⭐ **เนื้อทั้งหมดอยู่ที่ `app/components/หน้าอ่าน.vue`** ⇒ ที่นี่กับราก `/` ใช้ชิ้นเดียวกัน
//   ⇒ ⛔ ไม่ให้แยกเป็น 2 ชุด — แยกเมื่อไรอีกหน้าจะค้างรุ่นเก่าโดยไม่มีอะไรฟ้อง
//
// ⛔⛔ **ต้องสั่ง import เอง — ตัวเติม import อัตโนมัติ ⛔ ไม่รู้จักชื่อภาษาไทย**
import หน้าอ่าน from '~/components/หน้าอ่าน.vue'
import { ที่อยู่หลังบ้าน } from '~/utils/ที่อยู่'

interface ผลเล่ม {
  เล่ม: { รหัส: string; บทที่มี: number[] }
}

const route = useRoute()
const รหัสเล่ม = String(route.params.book)

// ⭐ **บทแรกของเล่มอ่านจากข้อมูล ⛔ ไม่เดาว่าเป็นบท 1** — เล่มที่ข้อมูลยังแปลไม่ครบ บทแรกอาจไม่ใช่ 1
//   ⇒ กุญแจ `เล่ม:<รหัส>` ตรงกับที่ชิ้นส่วนหน้าอ่านใช้ ⇒ ทั้งสองที่แชร์ผลก้อนเดียวกัน ⛔ ไม่โหลดซ้ำ
const { data: ของเล่ม } = await useAsyncData(`เล่ม:${รหัสเล่ม}`, () =>
  $fetch<ผลเล่ม>(ที่อยู่หลังบ้าน(`api/book/${รหัสเล่ม}.json`)),
)

// ⛔ ไม่มีเล่มนี้ = 404 จริง ⛔ ไม่ใช่หน้าเปล่าที่ดูเหมือนใช้ได้
if (!ของเล่ม.value?.เล่ม.บทที่มี.length) {
  throw createError({ statusCode: 404, statusMessage: `ไม่มีเล่ม ${รหัสเล่ม}`, fatal: true })
}
const บทเริ่ม = ของเล่ม.value.เล่ม.บทที่มี[0]!
</script>

<template>
  <!-- ⛔ ชื่อแท็กต้องเป็นตัวอักษรอังกฤษ ⇒ ชื่อชิ้นส่วนภาษาไทยต้องผ่าน `<component :is>` -->
  <component :is="หน้าอ่าน" :รหัสเล่ม="รหัสเล่ม" :เลขบท="บทเริ่ม" />
</template>
