// ⭐⭐ **บท c มีป้าย เมื่อข้อเดิมสักข้ออยู่คนละบทกับแถวของมัน และบทใดบทหนึ่งในสองฝั่งนั้นคือ c**
//   ① ฉบับแปลบท c มีข้อเดิมของบทอื่นมาอยู่ด้วย ⇒ โยเอล 2 (ฮีบรู 3:1–5 อยู่แถว 2:28–32) · โยเอล 3 (ฮีบรู 4) · มาลาคี 4 (ฮีบรู 3:19–24)
//   ② ข้อเดิมของบท c ไปอยู่แถวของบทอื่น ⇒ มาลาคี 3 ⇒ ฮีบรู 3 มี 24 ข้อ แต่ในบท 3 เห็นแค่ 18 ข้อ
//     ⇒ ปฐมกาล 32 ⇒ ฮีบรู 32:1 ไปอยู่แถว 31:55 ⇒ ทั้งบทเลขฮีบรูนำฉบับแปลอยู่ 1 ข้อ
//     ⇒ ⛔ นับแค่ข้อ ① ⇒ มาลาคี 3 กับปฐมกาล 32 ไม่มีป้าย ทั้งที่เลขสองฝั่งไม่ตรงกันจริง
//   ⇒ ⛔ **เลขข้อต่างแต่อยู่บทเดียวกัน ⇒ ไม่มีป้าย** ⇒ เช่น สดุดีที่มีหัวเพลง (ฮีบรู 51:3 = ฉบับแปล 51:1)
//     ⇒ ตามเกณฑ์ข้อ 1 ของใบ *ข้อเดิมอยู่คนละบทกับแถว* ⇒ รายชื่อ 27 เล่มในคำขอรวม !257 ⛔ มีสดุดี (ข้อ 3.3)
//
// ⭐ **ข้อเดิมอยู่ห่างจากบทของแถวไม่เกิน 1 บท** (วัดไว้ที่ `บทเดิมที่ต้องหยิบ` ของหน้าอ่าน)
//   ⇒ ดูไฟล์ชั้นคำแค่ 3 ไฟล์ ⇒ c−1 · c · c+1 ⇒ เป็นไฟล์ที่หน้าอ่านหยิบมาอยู่แล้ว ⇒ ⛔ โหลดอะไรเพิ่ม

/** ไฟล์ชั้นคำของบทเดิม ⇒ เฉพาะช่องที่ใช้ที่นี่ ⇒ รูปเดียวกับ `api/words` */
export interface ไฟล์ข้อแปล {
  บท: number
  ข้อแปล?: Record<string, [number, number][]>
}

/**
 * บท c ต้องมีป้ายไหม
 * ⇒ `ไฟล์ของบท(n)` ⇒ ไฟล์ชั้นคำของบทเดิม n ⇒ `undefined` = ยังไม่มา · `null` = บทนี้ไม่มีชั้นคำ
 * ⇒ ⛔ ไฟล์ยังมาไม่ครบ ⇒ ตอบเท่าที่รู้ ⇒ ป้ายขึ้นทีหลังได้เมื่อไฟล์บทข้างเคียงมาถึง
 */
export function บทมีเลขต้นฉบับต่างบท(c: number, ไฟล์ของบท: (n: number) => ไฟล์ข้อแปล | null | undefined): boolean {
  for (const n of [c - 1, c, c + 1]) {
    const ไฟล์ = ไฟล์ของบท(n)
    if (!ไฟล์?.ข้อแปล) continue
    for (const ไป of Object.values(ไฟล์.ข้อแปล))
      for (const [บทแปล] of ไป) if (บทแปล !== ไฟล์.บท && (บทแปล === c || ไฟล์.บท === c)) return true
  }
  return false
}
