//   ⇒ เจ้าของตารางคือ `server/utils/ชั้นคำ.ts` ⇒ ข้อเดิมข้อนี้อยู่แถวเดียวกับข้อแปลข้อไหน
//   ⇒ ไม่มีกุญแจในตาราง = ข้อเดิม `บท:ข้อ` อยู่กับข้อแปลเลขเดียวกัน ⇒ ⛔ ต่างบทแน่นอน
//   ⇒ ⛔ ไม่จดรายชื่อเล่มหรือบทไว้ที่นี่ ⇒ ตารางเปลี่ยนเมื่อไร ป้ายตามเอง
