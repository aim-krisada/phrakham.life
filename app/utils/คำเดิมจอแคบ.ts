// คำภาษาเดิมบนจอแคบ (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/124)
//
// ⭐⭐ **ถ้อยคำของป้ายแบบไหลต่อเนื่องอยู่ที่นี่ที่เดียว** ⇒ เปลี่ยนถ้อยคำ = แก้ค่าคงที่ข้างล่างค่าเดียว
//   ⇒ ⛔ ห้ามพิมพ์ถ้อยคำนี้ซ้ำในหน้าอ่านหรือในด่าน ⇒ ด่านอ่านค่าจากไฟล์นี้ (`tools/ด่านคำเดิมจอแคบ.mjs`)
//   ⇒ ถ้อยคำบนจอเป็นงานถ้อยคำ ⇒ G ร่าง ⇒ N ตรวจ ⇒ พี่เอมอนุมัติในใบ #124 ก่อนขึ้นจริง (ข้อ 7.1)
//
// ⭐⭐ **ทำไมแบบไหลต่อเนื่องต้องมีป้าย** ⇒ แบบนี้ตัวบททั้งบทของแต่ละฉบับเป็นก้อนเดียว (ใบ #87)
//   ⇒ ⛔ แทรกคำเดิมทีละข้อไม่ได้ ⇒ คำเดิมของทั้งบทจึงเป็นก้อนเดียว **ไว้ท้ายบท** บนจอแคบ
//   ⇒ ท้ายบท ⛔ ไม่ใช่ต้นบท ⇒ โปรแกรมอ่านหน้าจออ่านคำเดิมของข้อ n หลังตัวบทข้อ n (WCAG 2.2 SC 1.3.2)
//   ⇒ ป้ายใต้ชื่อบทบอก **ว่าคำอยู่ไหน** (ลิงก์พาลงไป) และ **ดูทีละข้อได้ยังไง** (ปุ่มเปลี่ยนเป็นแยกตามข้อ)
//
// ⭐ `ประโยค` ⇒ ว่างได้ ⇒ ว่าง = ป้ายมีแค่ลิงก์กับปุ่ม ⇒ มี = ขึ้นหน้าลิงก์
// ⭐ `ปุ่ม` ต้องมีชื่อ *แยกตามข้อ* ตรงตัว ⇒ ชื่อเดียวกับในเมนู ⇒ ผู้อ่านไปเจอชื่อเดียวกันในเมนู
// ⭐ `ลิงก์` อ่านเดี่ยว ๆ แล้วต้องรู้ว่าไปไหน ⇒ WCAG 2.2 SC 2.4.4 Link Purpose (ระดับ A)
export const ถ้อยคำคำเดิมท้ายบท = {
  ประโยค: '',
  ลิงก์: 'ลงไปดูคำภาษาเดิมที่ท้ายบท',
  ปุ่ม: 'แสดงแบบแยกตามข้อ',
} as const

import type { จุดบนคำ, หน้าตาคำ } from '~/utils/เครื่องหมายบนคำ'

type คำเดิม = [ตัว: string, คำแปล: string, กาล?: string]

/** ข้อเดิมหนึ่งข้อที่อยู่ในแถว ⇒ ตัวเดียวกับ `แถวคำเดิม` ของหน้าอ่าน */
export interface ข้อในแถว {
  บท: number
  ข้อ: string
  คำ: คำเดิม[]
  /** เครื่องหมายของ Levinsohn ทุกชนิดของแต่ละคำ (ใบ #146) ⇒ การ์ดคำอ่านช่องนี้ */
  จุด?: (จุดบนคำ[] | undefined)[]
  /** หน้าตาของแต่ละคำตามตระกูลที่เปิด (ใบ #146) ⇒ ⛔ ว่าง = ไม่มีเครื่องหมายที่เปิดอยู่ */
  ตา?: หน้าตาคำ[]
}

/** ชั้นคำหนึ่งชั้นของแถวเดียว ⇒ หน้าอ่านคิดจาก `กลุ่มคำของก้อน` ตัวเดียวกับจอกว้าง */
export interface ชั้นของแถว {
  ชื่อ: string
  ภาษา: string
  ทิศ: 'ltr' | 'rtl'
  แหล่ง: string
  /** ข้อเดิมข้อแรกของชั้นนี้ในก้อนบท ⇒ ได้เลขแบบ *บท:ข้อ* (ใบ #117) */
  ข้อแรก: ข้อในแถว | undefined
  /** แถวนี้คือแถวแรกที่ชั้นนี้มีคำ ⇒ ป้ายที่มาขึ้นที่นี่ครั้งเดียวต่อบท */
  แรก: boolean
  ข้อ: ข้อในแถว[]
  /** คำที่ได้ `tabindex=0` ของทั้งบทชั้นนี้ ⇒ หน้าอ่านคิดให้ (`คำที่รับTab`) */
  รับTab: string
}

/** ของที่ชิ้นคำใต้แถวต้องยืมจากหน้าอ่าน ⇒ การ์ด โฟกัส แป้นพิมพ์ ⇒ ⛔ ไม่มีสถานะของตัวเอง */
export interface ตัวช่วยคำเดิม {
  กุญแจคำ: (บท: number, ชั้น: string, ข้อ: string | number, i: number) => string
  เปิดอยู่: (บท: number, ชั้น: string, ข้อ: string, i: number) => boolean
  กดคำ: (e: Event, บท: number, ชั้น: string, ข้อ: string, i: number, คำ: คำเดิม, จุด?: จุดบนคำ[]) => void
  โฟกัสคำ: (e: FocusEvent, บทก้อน: number, ชั้น: string, บท: number, ข้อ: string, i: number) => void
  แป้น: (e: KeyboardEvent) => void
  /** ⭐ ใบ #178 ⇒ เลข Strong ของคำ ⇒ สวิตช์ปิดหรือคำไม่มีเลข ⇒ ว่าง ⇒ ตัวเดียวกับจอกว้าง (`app/utils/เลขStrong.ts`) */
  เลข: (บท: number, ชั้น: string, ข้อ: string, i: number, ภาษา: string) => string
}
