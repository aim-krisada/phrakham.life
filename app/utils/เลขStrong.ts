// ⭐⭐ **หยิบไฟล์การ์ดเฉพาะตอนผู้อ่านเปิดสวิตช์ *แสดงเลข Strong*** (ค่าตั้งต้นปิด ⇒ @krisada เคาะ 18 พ.ย. 2569)
//   ⇒ คนที่ไม่เปิด ⛔ จ่ายไบต์เพิ่ม ⇒ ท่าเดียวกับการ์ดที่หยิบตอนกดคำ (ใบ #103 เกณฑ์ข้อ 11)
//   ⇒ ไฟล์ยังไม่มา หรือหยิบไม่สำเร็จ ⇒ คืนค่าว่าง ⇒ คำนั้น ⛔ แสดงอะไร (เกณฑ์ข้อ 2.4) ⛔ ไม่ใช่ G0 · G undefined
// ⭐ **สวิตช์เป็นค่าเดียวทั้งหน้า** (`แสดงเลขStrong` ⇒ หน้าอ่านตั้งจาก `มุม`) ⇒ ชิ้นที่วาดคำทั้ง 3 ชิ้นอ่านจากที่นี่
//   ⇒ ⛔ ส่งค่าผ่านพร็อปทีละชั้น ⇒ คอลัมน์คนละเล่มคนละบท (`เนื้อตอนเทียบ.vue`) ถูกวาดจากหลายที่
import { reactive, ref } from 'vue'
import { ที่อยู่หลังบ้าน } from '~/utils/ที่อยู่'

/** แยกรหัส ⇒ กรีก `5228+1537` · ฮีบรู `1886a|0725` */
export const แยกรหัส = (รหัส: string) => (รหัส ? รหัส.split(/[+|]/).filter(Boolean) : [])
/** รหัสฮีบรูที่มีตัวอักษรท้าย ⇒ ⛔ ไม่ใช่เลข Strong ⇒ เหตุผลอยู่หัว `tools/สร้างพจนานุกรม.py` */
export const มีตัวอักษร = (ร: string) => /[a-z]$/.test(ร)
/** เลขในพจนานุกรม ⇒ ตัด 0 นำหน้า */
export const กุญแจของรหัส = (รหัส: string) => รหัส.replace(/^0+/, '') || '0'

/** ⭐ รหัสของคำ ⇒ เลข Strong ที่ตาเห็น ⇒ ว่าง = ไม่มีเลข */
export function เลขStrongจากรหัส(รหัส: string, ภาษา: string): string {
  const อักษร = ภาษา === 'hbo' ? 'H' : 'G'
  return แยกรหัส(รหัส)
    .map((x) => (มีตัวอักษร(x) ? x : อักษร + กุญแจของรหัส(x)))
    .join(' + ')
}

/** สวิตช์ *แสดงเลข Strong* ⇒ หน้าอ่านตั้งจาก `มุม.แสดงเลขStrong` */
export const แสดงเลขStrong = ref(false)

/** `<เล่ม>/<บท>` ⇒ ชั้น ⇒ ข้อ ⇒ รหัสของแต่ละคำ ⇒ ใส่ตอนหยิบเสร็จเท่านั้น */
const รหัสของบท = reactive(new Map<string, Record<string, Record<string, string[]>>>())
/** ⭐ ⛔ reactive ⇒ จดว่าหยิบแล้วระหว่างวาดได้ โดย ⛔ ปลุกให้วาดซ้ำ ⇒ หยิบไม่สำเร็จก็ค้างไว้ ⇒ ⛔ ยิงซ้ำทุกรอบที่วาด */
const หยิบแล้ว = new Set<string>()

function หยิบบท(เล่ม: string, บท: number) {
  const กุญแจ = `${เล่ม}/${บท}`
  if (หยิบแล้ว.has(กุญแจ)) return
  หยิบแล้ว.add(กุญแจ)
  $fetch<{ ชั้น?: Record<string, Record<string, string[]>> }>(ที่อยู่หลังบ้าน(`api/card/${เล่ม}/${บท}.json`))
    .then((x) => {
      const ชั้น: Record<string, Record<string, string[]>> = {}
      for (const [ช, ข้อทั้งหมด] of Object.entries(x?.ชั้น ?? {}))
        for (const [ข, คำ] of Object.entries(ข้อทั้งหมด)) (ชั้น[ช] ??= {})[ข] = คำ.map((แถว) => แถว.split('~')[1] ?? '')
      รหัสของบท.set(กุญแจ, ชั้น)
    })
    // ⭐ หยิบไม่สำเร็จ ⇒ ค้างค่าว่าง ⇒ คำ ⛔ แสดงเลข ⇒ หน้ายังอ่านได้ปกติ ⇒ เปิดหน้าใหม่ลองหยิบอีกรอบ
    .catch(() => {})
}

/** ⭐ เลข Strong ของคำที่ `i` ของข้อนั้น ⇒ สวิตช์ปิด · ไฟล์ยังไม่มา · คำไม่มีรหัส ⇒ ว่าง */
export function เลขบนคำ(เล่ม: string, บท: number, ชั้น: string, ข้อ: string | number, i: number, ภาษา: string): string {
  if (!แสดงเลขStrong.value || !เล่ม || !ชั้น) return ''
  const ของบท = รหัสของบท.get(`${เล่ม}/${บท}`)
  if (!ของบท) {
    หยิบบท(เล่ม, บท)
    return ''
  }
  return เลขStrongจากรหัส(แยกรหัส(ของบท[ชั้น]?.[String(ข้อ)]?.[i] ?? '').filter((x) => !มีตัวอักษร(x)).join('+'), ภาษา)
}
