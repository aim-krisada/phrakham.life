// รูปของ **จุดที่ผู้อ่านถูกพาไป** และวิธีเขียนมันให้คนอ่าน
//
// ⛔⛔ **`อ่านอ้างอิง` ถูกถอดออกแล้ว** (ใบงาน v3/phrakham#79 · พี่เอมสั่ง 7 ก.ย. 2569)
//   มันเป็นตัวอ่านข้อความที่ผู้อ่านพิมพ์ ⇒ คัดมาจาก `parseRef` ของเว็บรุ่น 2
//   ⇒ **ช่องพิมพ์ถูกเอาออกจากแผงเลือกพระคัมภีร์แล้ว** ⇒ ⛔ ไม่มีใครเรียกมันอีก
//   ⇒ **เอากลับมาเมื่อไร** ⇒ วันที่มีช่องพิมพ์อีกครั้ง ⇒ ของเดิมอยู่ในประวัติกิตครบ
//     ⇒ ⛔ **ห้ามเก็บโค้ดตายไว้เฉย ๆ** — วันหน้าคนอ่านจะเดาว่ามันยังทำงานอยู่
//   ⇒ เหตุผลว่าทำไมถอดช่องพิมพ์ อยู่หัวไฟล์ `app/components/เลือกพระธรรม.vue` ⛔ ไม่จดซ้ำที่นี่

/** จุดเดียวที่ผู้อ่านถูกพาไป ⇒ `ข้อ` เป็น `null` ได้ แปลว่า **ต้นบท** */
export interface จุดอ่าน {
  รหัส: string
  บท: number
  ข้อ: number | null
  /** ⭐ **ข้อจบของช่วงที่จะฟัง** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/101 ข้อ 29)
   *  ⇒ ไม่มี = ผู้อ่านเลือกจุดเดียว ⇒ **อยู่เล่มเดียวกับ `รหัส` เสมอ** เพราะช่วงห้ามข้ามเล่ม
   *  ⇒ ⛔ ช่วงนี้ ⛔ ไม่ใช่กำแพงของการอ่าน ⇒ เหตุผลอยู่ที่ `app/utils/ที่อยู่.ts` หัวข้อ `ช่วงฟัง` */
  ถึง?: { บท: number; ข้อ: number }
}

/**
 * ⭐ **แสดงผลด้วยทวิภาค** ⇒ รูปที่ผู้อ่านเห็น (กฎบ้านเรา **เก็บด้วยจุด แสดงผลด้วยทวิภาค**)
 * ⛔ ไม่มีขีดกลางอีกแล้ว — ชื่อของจุดเดียวไม่มีปลาย
 */
export function แสดงเป็นข้อความ(จุด: จุดอ่าน, ชื่อไทย: string): string {
  return จุด.ข้อ === null ? `${ชื่อไทย} ${จุด.บท}` : `${ชื่อไทย} ${จุด.บท}:${จุด.ข้อ}`
}
