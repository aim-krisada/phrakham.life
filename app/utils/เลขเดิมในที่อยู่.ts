// ⭐⭐ **ลิงก์ที่ฉบับแรกใน `t` เป็นตัวบทภาษาเดิม ⇒ `c` กับ `v` เป็นเลขของฝั่งภาษาเดิม** (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/94)
//
// ## ทำไมต้องมี
//   ⇒ ต้นฉบับแบ่งบทต่างจากฉบับแปลได้ ⇒ เช่น ฮีบรูแบ่งโยเอลเป็น 4 บท ฉบับแปลแบ่ง 3 บท ⇒ ฮีบรู 3:1 = ไทย 2:28 · ฮีบรู 4:1 = ไทย 3:1
//   ⇒ ลิงก์ `/read/JOL?c=4&v=1&t=WLC` บอกครบแล้วว่าใช้เลขของใคร ⇒ ของเดิมอ่าน `c` เป็นเลขฉบับแปล ⇒ ขึ้น *ไม่มีบท 4* แล้วพาไปบท 1
//   ⇒ พี่เอมเคาะ 18 พ.ย. 2569 ⇒ ⛔ ไม่แก้ข้อมูลต้นทาง ⛔ ไม่เปลี่ยนเลขบทของฉบับไหน ⇒ เว็บต้องเปิดถูกที่เอง
//
// ## กติกา
//   ⇒ ฉบับแรกใน `t` เป็นชื่อตัวบทภาษาเดิม (`WLC` · `SBLGNT`) ⇒ `c` `v` เป็นเลขฝั่งเดิม ⇒ ทั้งตอนอ่านและตอนเขียนที่อยู่
//   ⇒ ฉบับแรกเป็นฉบับแปล หรือไม่มี `t` ⇒ เลขของฉบับแปลเหมือนเดิมทุกตัวอักษร
//   ⇒ ⭐ **ข้อเดิมข้อไหนอยู่แถวเดียวกับข้อแปลข้อไหน ⇒ ใช้ตาราง `ข้อแปล` ตัวเดียว** (เจ้าของคือ `server/utils/ชั้นคำ.ts`)
//     ⇒ ⛔ ไม่ตั้งกติกาที่สอง ⇒ ตารางมาในไฟล์ `api/words/<เล่ม>/<บท>.json` ที่หน้าอ่านหยิบอยู่แล้ว
//     ⇒ ไม่มีกุญแจในตาราง = ข้อเดิม `บท:ข้อ` อยู่กับข้อแปลเลขเดียวกัน
//   ⇒ ข้อเดิมอยู่ห่างจากบทของข้อแปลไม่เกิน 1 บท (วัดไว้ที่ `บทเดิมที่ต้องหยิบ` ของหน้าอ่าน) ⇒ หาย้อนกลับจากบทข้างเคียงข้างละบท

/** ไฟล์ชั้นคำของบทเดิม ⇒ เฉพาะช่องที่ใช้ที่นี่ ⇒ รูปเดียวกับ `api/words` */
export interface ไฟล์เลขเดิม {
  บท: number
  ชั้น: Record<string, Record<string, unknown>>
  ข้อแปล?: Record<string, [number, number][]>
}

/** ⭐ ฉบับแรกของ `t` เป็นตัวบทภาษาเดิมไหม ⇒ ใช่ ⇒ `c` `v` เป็นเลขฝั่งเดิม */
export function ที่อยู่ใช้เลขเดิม(ฉบับ: readonly string[], ชื่อตัวบทเดิม: readonly string[]): boolean {
  return ฉบับ.length > 0 && ชื่อตัวบทเดิม.includes(ฉบับ[0]!)
}

/** เลขข้อเดิมทุกข้อในไฟล์ ⇒ เรียงน้อยไปมาก */
function เลขข้อของไฟล์(ไฟล์: ไฟล์เลขเดิม): number[] {
  const เลข = new Set<number>()
  for (const ข้อทั้งหมด of Object.values(ไฟล์.ชั้น)) for (const k of Object.keys(ข้อทั้งหมด)) เลข.add(Number(k))
  return [...เลข].sort((a, b) => a - b)
}

/** ข้อเดิม `ไฟล์.บท:ข้อ` ⇒ ข้อแปลที่อยู่แถวเดียวกัน ⇒ ⛔ ไม่มีข้อนี้ในไฟล์ ⇒ `null` */
export function เดิมไปแปล(ไฟล์: ไฟล์เลขเดิม | null | undefined, ข้อ: number): [number, number] | null {
  if (!ไฟล์ || !Object.values(ไฟล์.ชั้น).some((x) => String(ข้อ) in x)) return null
  const ไป = ไฟล์.ข้อแปล?.[String(ข้อ)]?.[0]
  return ไป ? [ไป[0], ไป[1]] : [ไฟล์.บท, ข้อ]
}

/**
 * ข้อแปล `บท:ข้อ` ⇒ ข้อเดิมข้อแรกที่อยู่แถวเดียวกัน ⇒ หาในไฟล์บทเดิม `บท-1` ถึง `บท+1`
 *   ⇒ ข้อแปลที่มีข้อเดิมหลายข้อ (หัวเพลงสดุดี) ⇒ เอาข้อเดิมข้อแรก ⇒ เปิดกลับมาแล้วได้แถวเดียวกัน
 *   ⇒ ⛔ หาไม่เจอ (ไฟล์ยังไม่มา · ข้อแปลที่ไม่มีข้อเดิม) ⇒ `null` ⇒ ผู้เรียกใช้เลขเดิมของตัวเอง
 */
export function แปลไปเดิม(
  ไฟล์ของบท: (บท: number) => ไฟล์เลขเดิม | null | undefined,
  บท: number,
  ข้อ: number,
): [number, number] | null {
  for (const F of [บท - 1, บท, บท + 1]) {
    const ไฟล์ = ไฟล์ของบท(F)
    if (!ไฟล์) continue
    for (const O of เลขข้อของไฟล์(ไฟล์)) {
      const ไป = ไฟล์.ข้อแปล?.[String(O)] ?? [[ไฟล์.บท, O]]
      if (ไป.some(([b, v]) => b === บท && v === ข้อ)) return [ไฟล์.บท, O]
    }
  }
  return null
}

/**
 * ⭐ จุดของหน้า (เลขฉบับแปล) ⇒ เลขที่เขียนลง `c` `v` เมื่อที่อยู่ใช้เลขเดิม
 *   ⇒ ไม่มีข้อ (ทั้งบท) ⇒ ดูข้อ 1 ⇒ ได้ข้อเดิมข้อ 1 ⇒ เขียนแค่บท ⇒ ⛔ ไม่ใช่ข้อ 1 ⇒ เขียนข้อด้วย (โยเอล 2:28 ⇒ `c=3&v=1`)
 */
export function จุดเป็นเลขเดิม(
  ไฟล์ของบท: (บท: number) => ไฟล์เลขเดิม | null | undefined,
  บท: number,
  ข้อ: number | null,
): { บท: number; ข้อ: number | null } {
  const ได้ = แปลไปเดิม(ไฟล์ของบท, บท, ข้อ ?? 1)
  if (!ได้) return { บท, ข้อ }
  return { บท: ได้[0], ข้อ: ข้อ === null && ได้[1] === 1 ? null : ได้[1] }
}

/**
 * ⭐ `c` `v` ที่เป็นเลขเดิม ⇒ จุดของหน้า (เลขฉบับแปล) ⇒ ตัวกลับของ `จุดเป็นเลขเดิม`
 *   ⇒ ⛔ ไม่มีข้อนั้น ⇒ ไปต้นบทเดิม ⇒ ⛔ บทเดิมนั้นไม่มีเลย ⇒ `null` ⇒ ผู้เรียกบอก *ไม่มีบท* ด้วยเลขเดิม
 */
export function จุดจากเลขเดิม(
  ไฟล์: ไฟล์เลขเดิม | null | undefined,
  ข้อ: number | null,
): { บท: number; ข้อ: number | null } | null {
  const ได้ = (ข้อ !== null ? เดิมไปแปล(ไฟล์, ข้อ) : null) ?? (ไฟล์ ? เดิมไปแปล(ไฟล์, เลขข้อของไฟล์(ไฟล์)[0] ?? 1) : null)
  if (!ได้) return null
  const ทั้งบท = ข้อ === null || !เดิมไปแปล(ไฟล์, ข้อ)
  return { บท: ได้[0], ข้อ: ทั้งบท && ได้[1] === 1 ? null : ได้[1] }
}
