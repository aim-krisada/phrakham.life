//     กับ `macula-hebrew-main/WLC/tsv/macula-hebrew.tsv` (`tools/สร้างข้อมูลเว็บ.py`) ⇒ ⛔ ไม่ได้ตั้งชื่อใหม่เอง
// ⭐ **ชื่อภาษามาจากข้อมูลชั้นคำตรงตัว** ⇒ *คำกรีก* · *คำฮีบรู* (ใบ #125 ข้อ 21)
// ⭐ **เรียกของชิ้นนี้ว่า *คำภาษาเดิม* คำเดียวทุกที่** ⇒ ปุ่มเปิด ปุ่มปิด ⇒ WCAG 2.2 SC 3.2.4 Consistent Identification
//
// ⭐ **พี่เอมอนุมัติแล้ว 31 ต.ค. 2569** ⇒ ปุ่มเปิดปิด ⇒ https://aimgit.aimagin.com/v3/phrakham/-/issues/125#note_30149
//   ⇒ ชื่อตัวบทบนหัวและป้ายจอแคบ ⇒ https://aimgit.aimagin.com/v3/phrakham/-/issues/125#note_30154
//   ⇒ ⛔ เปลี่ยนถ้อยคำ ⇒ ต้องผ่าน G · N · พี่เอม อีกรอบ ⇒ แล้วแก้ที่นี่ที่เดียว

export const ถ้อยคำคำเดิม = {
  /** ช่องติ๊กในเมนู *เทียบ* ⇒ ติ๊กคือเปิด เอาติ๊กออกคือปิด (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/131 ข้อ 9)
   *  ⇒ ของเดิม (ใบ #125 ข้อ 11.6) ⇒ ปุ่ม *+ คำภาษาเดิม* ⇒ ตัด *+* ออก เพราะช่องติ๊กทั้งเปิดและปิด
   *  ⇒ พี่เอมอนุมัติ 1 พ.ย. 2569 ⇒ https://aimgit.aimagin.com/v3/phrakham/-/issues/131#note_30219 */
  เปิด: 'คำภาษาเดิม',
  /** ชื่อที่โปรแกรมอ่านหน้าจออ่านของปุ่ม × บนหัวคอลัมน์ (ข้อ 11.5) ⇒ ตาเห็นแค่ × เหมือนหัวคอลัมน์อื่น */
  ปิด: 'ปิดคอลัมน์คำภาษาเดิม',
} as const

/** ⭐ ชื่อตัวบทของชั้นคำแต่ละชั้น ⇒ คีย์คือชื่อชั้นในข้อมูล (`server/utils/ชั้นคำ.ts`) */
const ตัวบทของชั้น: Record<string, string> = {
  คำกรีก: 'SBLGNT',
  // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/130 ตรวจแล้ว ⇒ ตัวบทฮีบรูของ MACULA ตรงกับ WLC ⛔ ไม่ใช่ UXLC (#note_30170)
  คำฮีบรู: 'WLC',
}

/** ⭐ ชื่อตัวบทภาษาเดิมทุกชื่อ ⇒ ที่อยู่ `t=SBLGNT` แปลว่าตารางเหลือแต่คำภาษาเดิม (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/145 ข้อ 5)
 *  ⇒ ⛔ ไม่ชนรหัสฉบับแปล ⇒ ฉบับแปลของเว็บไม่มีชื่อนี้ ⇒ ตัวอ่านที่อยู่จึงแยกได้จากชื่ออย่างเดียว */
export const ชื่อตัวบทเดิมทั้งหมด: readonly string[] = Object.values(ตัวบทของชั้น)

/** ⭐ ภาษาของตัวบทภาษาเดิม ⇒ รหัส BCP 47 ⇒ ช่องเลือกฉบับเขียน *SBLGNT · กรีก* (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/175)
 *  ⇒ รหัสเดียวกับ `ชั้นที่รู้จัก` ที่ `server/utils/ชั้นคำ.ts` (คำกรีก `grc` · คำฮีบรู `hbo`) ⇒ `tools/ด่านภาษาท้ายชื่อฉบับ.mjs` ข้อ ① เทียบสองที่ให้ตรงกัน */
const ภาษาของตัวบทเดิม: Record<string, string> = {
  SBLGNT: 'grc',
  WLC: 'hbo',
}

export function ภาษาของตัวบท(ตัวบท: string): string {
  return ภาษาของตัวบทเดิม[ตัวบท] ?? ''
}

export function ชื่อตัวบท(ชื่อชั้น: string): string {
  return ตัวบทของชั้น[ชื่อชั้น] ?? ''
}

/** ⭐ ป้ายภาษากับตัวบทของชั้นหนึ่ง ⇒ `คำกรีก · SBLGNT` ⇒ ป้ายเหนือคำใต้แถวจอแคบ (ข้อ 11.4) และต้นก้อนบทจอกว้าง */
export function ป้ายชั้นคำ(ชื่อชั้น: string): string {
  return [ชื่อชั้น, ชื่อตัวบท(ชื่อชั้น)].filter(Boolean).join(' · ')
}
