// ⭐⭐ **ข้อแรกของก้อนบท ⇒ `บท:ข้อ` · ข้ออื่นเป็นเลขข้อเปล่า** ⇒ ท่าของรุ่น 2 ที่ฉบับแปลใช้มาตลอด
//   ⇒ ผู้อ่านรู้ว่าขึ้นบทใหม่จากตัวเลขในเนื้อ ⛔ ไม่ต้องรอหัวข้อคั่น
// ⭐⭐ **ข้อที่อยู่คนละบทกับก้อน ⇒ `บท:ข้อ` เสมอ** ⇒ เกิดได้แค่คอลัมน์คำภาษาเดิม (ข้อเดิม 140 ข้อของทั้งคลัง)
//   ⇒ เช่น วิวรณ์ 13:1–4 ได้ *12:18* ⇒ เขียนแค่ *18* ผู้อ่านจะนึกว่าเป็น 13:18 ซึ่งไม่มีอยู่จริง
//   ⇒ ฉบับแปลส่ง `บทของข้อ` = `บทของก้อน` เสมอ ⇒ เงื่อนไขนี้ไม่มีผลกับฉบับแปล
// ⭐⭐ **บทของแถว (ใบ #117 ข้อ 6.1) = บทของก้อนที่ข้อเดิมไปอยู่** ⇒ ⛔ ไม่ตั้งกติกาที่สอง
//   ⇒ ก้อนตัดสินด้วยตาราง `ข้อแปล` ของใบ #104 อยู่แล้ว ⇒ ข้อแปลข้อแรกของข้อเดิมที่อยู่บนหน้า อยู่บทไหน ไปก้อนนั้น
//   ⇒ ทุกแถวในก้อนบท c เป็นข้อแปลของบท c ⇒ **บทของก้อน คือบทของแถวทุกแถวในก้อน**
// ⭐ **ข้อแรกของก้อน** ⇒ ฉบับแปล = แถวแรกของก้อน · คอลัมน์คำภาษาเดิม = ข้อเดิมข้อแรกของชั้นนั้นในก้อน
//   ⇒ ⛔ ของเดิม (ใบ #95) คอลัมน์คำภาษาเดิมพิมพ์ *บท:ข้อ* ทุกข้อ ⇒ ตอนนั้นคำเดิมยังไม่ตรงแถว (ใบ #112 แก้แล้ว)
//
// ⭐ **ทำไมต้องเป็นฟังก์ชันกลาง** ⇒ ใบ #117 ข้อ 6 ⇒ เลขของคอลัมน์คำภาษาเดิมต้องหน้าตาแบบเดียวกับฉบับแปล
//   ⇒ ผู้จ่ายงานเคาะ 27 ต.ค. 2569 ⇒ ข้อแรกของก้อนต้องมีบทเหมือนฉบับแปล ⇒ **ใช้เงื่อนไขเดียวกัน ⛔ ไม่เขียนคู่ขนาน**
//   ⇒ วันหน้าใครเปลี่ยนวิธีบอกบทของฉบับแปล ⇒ คอลัมน์คำภาษาเดิมเปลี่ยนตามเอง ⇒ สองฝั่ง ⛔ ไม่มีทางหน้าตาต่างกัน
// ⭐ **เก็บด้วยจุด แสดงผลด้วยทวิภาค** ⇒ กฎการอ้างอิงพระคัมภีร์ ⇒ ที่นี่คือฝั่ง *แสดงผล*
// ⭐ ตัวหนังสือที่คืน = ตัวหนังสือที่ตาเห็น = ที่โปรแกรมอ่านหน้าจอได้ยิน ⇒ ⛔ ห้ามเติมเลขบทแบบเฉพาะเสียง (ใบ #117 ข้อ 6.3)
//
// ⭐ **ฟังก์ชันบริสุทธิ์** ⇒ ด่านเรียกตรงได้ ⇒ ตัวเฝ้าคือ `tools/ด่านเลขบทคำเดิม.mjs`

/**
 * `บทของข้อ` บทของข้อนั้นเอง · `บทของก้อน` บทของก้อนบทที่มันอยู่บนหน้า
 * `ข้อแรกของก้อน` เป็นข้อแรกที่ก้อนนั้นแสดง (แบบเลือกเป็นช่วง ⇒ ข้อแรกของช่วงในบทนั้น)
 */
export function ป้ายเลขข้อ(บทของข้อ: number, ข้อ: string | number, บทของก้อน: number, ข้อแรกของก้อน: boolean): string {
  return ข้อแรกของก้อน || บทของข้อ !== บทของก้อน ? `${บทของข้อ}:${ข้อ}` : String(ข้อ)
}
