import type { ข้อในคิว } from './ตัวเล่นเสียง'
import type { ช่วงฟัง } from './ที่อยู่'

/** รูปเดียวกับที่ `server/utils/เสียงของเล่ม.ts` ส่งมา ⇒ เจ้าของรูปคือไฟล์นั้น */
export interface ดัชนีเสียง {
  ไฟล์: string
  บท: Record<string, number>
  ข้าม: Record<string, number[]>
}

export interface ผลคิว {
  คิว: ข้อในคิว[]
  /** ⭐ **ประโยคที่บอกผู้อ่านตอนคิวจบ** ⇒ หยุดเพราะอะไร ⇒ ⛔ ไม่ปล่อยให้เงียบแล้วให้เขาเดาเอง */
  เหตุจบ: string
}

/**
 * ⭐⭐ **ที่อยู่ไฟล์เสียงที่เบราว์เซอร์จะขอ** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/171)
 *
 * ⇒ ทางในตัวเว็บ (`audio/Mark.1.1.puck.mp3`) ⇒ ต่อฐานของเว็บ (`/phrakham/`) ⇒ ท่าเดิม
 * ⇒ ⛔ **ฐานเต็มของ GitHub Pages (`https://…`) ⇒ ใช้ตามนั้น ⛔ ห้ามต่อฐานของเว็บ**
 *   ⇒ ต่อซ้ำ = `/phrakham/https://…` ⇒ ผู้อ่านกดฟังแล้วเงียบทุกข้อ ⇒ ตัวเฝ้าคือ `tools/ด่านที่อยู่ไฟล์เสียง.mjs`
 * ⇒ ⭐ ไฟล์อยู่คนละโฮสต์กับเว็บได้ ⇒ ตัวเล่นใช้ `<audio>` ตัวเดียวแล้วเปลี่ยนแค่ `src` ⇒ ⛔ ไม่ต้องตั้ง CORS
 */
export function ต่อที่อยู่ไฟล์เสียง(ทาง: string, ต่อที่อยู่: (ทาง: string) => string): string {
  return /^https:\/\//.test(ทาง) ? ทาง : ต่อที่อยู่(ทาง)
}

export function มีเสียงบท(ดัชนี: ดัชนีเสียง | undefined, บท: number): boolean {
  return !!ดัชนี && ดัชนี.บท[String(บท)] !== undefined
}

export function สร้างคิว(o: {
  รหัสเล่ม: string
  ชื่อเล่ม: string
  ดัชนี: ดัชนีเสียง
  /** บทที่มีตัวบทของเล่มนี้ เรียงตามลำดับ ⇒ ใช้หาบทถัดไป ⛔ ไม่บวกเลขบทเอง */
  บทที่มี: number[]
  จาก: { บท: number; ข้อ: number }
  ช่วง: ช่วงฟัง | null
  /** ต่อฐานของเว็บให้ที่อยู่ไฟล์ ⇒ เจ้าของคือ `app/utils/ที่อยู่.ts` */
  ต่อที่อยู่: (ทาง: string) => string
}): ผลคิว {
  const { ดัชนี, ชื่อเล่ม, ช่วง } = o
  const คิว: ข้อในคิว[] = []
  // ⛔ **จบช่วงแล้ว ⛔ ไม่มีประโยคบอก** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/102 ข้อ 20.1)
  //   ⇒ หน้าแสดงแค่ข้อในช่วงอยู่แล้ว ⇒ เล่นจนจบแล้วผู้อ่านเห็นเองว่าจบ ⇒ บอกซ้ำ = สถานะซ้ำซ้อนที่พี่เอมห้าม
  //   ⇒ ⭐ **แต่หยุดเพราะบทในช่วงยังไม่มีเสียง ยังบอกเหมือนเดิม** ⇒ อันนั้นผู้อ่านเห็นเองไม่ได้
  const จบช่วง = ''
  let เหตุจบ = ''
  let i = o.บทที่มี.indexOf(o.จาก.บท)
  if (i < 0 || !มีเสียงบท(ดัชนี, o.จาก.บท)) {
    return { คิว, เหตุจบ: `${ชื่อเล่ม} บท ${o.จาก.บท} ยังไม่มีเสียง` }
  }
  for (; ; i++) {
    const c = o.บทที่มี[i]
    if (c === undefined) {
      เหตุจบ = ช่วง ? จบช่วง : `จบเล่ม${ชื่อเล่ม}แล้ว`
      break
    }
    if (ช่วง && c > ช่วง.ถึง.บท) {
      เหตุจบ = จบช่วง
      break
    }
    const ท้าย = ดัชนี.บท[String(c)]
    if (ท้าย === undefined) {
      เหตุจบ = `หยุดเล่นที่ท้าย${ชื่อเล่ม} ${o.บทที่มี[i - 1]} ⇒ บท ${c} ยังไม่มีเสียง`
      break
    }
    const ข้าม = new Set(ดัชนี.ข้าม[String(c)] || [])
    const เริ่ม = c === o.จาก.บท ? o.จาก.ข้อ : 1
    const สุด = ช่วง && c === ช่วง.ถึง.บท ? Math.min(ช่วง.ถึง.ข้อ, ท้าย) : ท้าย
    for (let v = เริ่ม; v <= สุด; v++) {
      if (ข้าม.has(v)) continue
      คิว.push({
        รหัส: `${o.รหัสเล่ม}.${c}.${v}`,
        เล่ม: o.รหัสเล่ม,
        ชื่อเล่ม,
        บท: c,
        ข้อ: v,
        ที่อยู่ไฟล์: ต่อที่อยู่ไฟล์เสียง(ดัชนี.ไฟล์.replace('{บท}', String(c)).replace('{ข้อ}', String(v)), o.ต่อที่อยู่),
        วินาที: 0,
      })
    }
    if (ช่วง && c === ช่วง.ถึง.บท) {
      เหตุจบ = จบช่วง
      break
    }
  }
  return { คิว, เหตุจบ }
}
