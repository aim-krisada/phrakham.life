/** อ้างอิงที่อ่านออก ⇒ `ข้อต้น` ว่าง = ทั้งบท · `ข้อปลาย` ว่าง = ถึงท้ายบท `บทปลาย` (กติกาเดียวกับเว็บเดิม) */
export interface อ้างอิงเว็บเดิม {
  รหัส: string
  /** ลำดับเล่มในตาราง (0–65) ⇒ น้อยกว่า 39 = พันธสัญญาเดิม */
  ลำดับ: number
  บทต้น: number
  ข้อต้น: number | null
  บทปลาย: number
  ข้อปลาย: number | null
}

/** ⭐ จำนวนบทกับข้อสุดท้ายของแต่ละบทของเล่ม ⇒ มาจาก `api/books.json` ของเว็บนี้ ⇒ ใช้บีบเลขที่เกินให้อยู่ในเล่ม (เว็บเดิมก็บีบ) */
export type ขนาดเล่ม = Record<string, number[]>

const ตัดว่าง = (s: string) => s.replace(/[\s​]+/g, '')

/**
 * ⭐⭐ **อ่านอ้างอิงแบบเว็บเดิม** ⇒ `มาระโก 1:1-15` · `อิสยาห์ 52:13-53:12` · `เลวีนิติ 16` · `mrk 1:1` · `Mark 1:1`
 *   ⇒ กติกาตาม `PK.parseRef` ⇒ ตัดวงเล็บ (ตัวช่วยพิมพ์ของเว็บเดิมต่อ *(English)* ท้ายชื่อ) ⇒ ตัดช่องว่างทั้งหมด
 *   ⇒ เล่มแรกที่ตรง ⇒ รหัส USFM ตรงตัว (ตัวเล็กใหญ่ไม่สน) · ชื่ออังกฤษขึ้นต้นด้วย · ชื่อไทยตรงตัวหรือขึ้นต้นด้วย
 *   ⇒ ⛔ อ่านไม่ออก (ไม่มีเลขบท · ไม่รู้จักเล่ม) ⇒ `null` ⇒ ผู้เรียกปล่อยให้อยู่หน้าแรก ⛔ ไม่ใช่หน้าพัง
 */
export function อ่านอ้างอิงเว็บเดิม(ข้อความ: unknown, ขนาด?: ขนาดเล่ม | null): อ้างอิงเว็บเดิม | null {
  if (typeof ข้อความ !== 'string') return null
  const s = ตัดว่าง(ข้อความ.replace(/\([^)]*\)/g, ''))
  if (s.length > 80) return null
  const m = /^(.+?)(\d+)(?::(\d*))?(?:[-–](\d*)(?::(\d*))?)?$/.exec(s)
  if (!m) return null
  const ชื่อ = m[1]!
  const ตัวเล็ก = ชื่อ.toLowerCase()
  const ลำดับ = เล่มเว็บเดิม.findIndex(([รหัส, ไทย, อังกฤษ]) => {
    const ท = ตัดว่าง(ไทย)
    return (
      รหัส.toLowerCase() === ตัวเล็ก ||
      ตัดว่าง(อังกฤษ).toLowerCase().startsWith(ตัวเล็ก) ||
      ท === ตัดว่าง(ชื่อ) ||
      ท.startsWith(ตัดว่าง(ชื่อ))
    )
  })
  if (ลำดับ < 0) return null
  const รหัส = เล่มเว็บเดิม[ลำดับ]![0]
  const เลข = (g: string | undefined) => (g !== undefined && g !== '' ? Number(g) : null)
  const มีทวิภาค = m[3] !== undefined
  const มีขีด = m[4] !== undefined
  let บทต้น = Number(m[2])
  const v1 = เลข(m[3])
  const e1 = เลข(m[4])
  const e2 = เลข(m[5])
  let ข้อต้น: number | null
  let บทปลาย: number
  let ข้อปลาย: number | null
  if (!มีทวิภาค) {
    ข้อต้น = null
    บทปลาย = e1 || บทต้น
    ข้อปลาย = null
  } else {
    ข้อต้น = v1 !== null ? v1 : 1
    if (e2 !== null) {
      บทปลาย = e1 ?? บทต้น
      ข้อปลาย = e2
    } else if (e1 !== null) {
      บทปลาย = บทต้น
      ข้อปลาย = e1
    } else if (มีขีด) {
      บทปลาย = บทต้น
      ข้อปลาย = null
    } else {
      บทปลาย = บทต้น
      ข้อปลาย = v1
    }
  }
  // ⭐ บีบเลขที่เกินให้อยู่ในเล่ม ⇒ ท่าเดียวกับเว็บเดิม ⇒ `มาระโก 99:1` ได้บทสุดท้าย ⛔ ไม่ใช่หน้าว่าง
  const ข้อสุดท้าย = ขนาด?.[รหัส]
  if (ข้อสุดท้าย?.length) {
    const n = ข้อสุดท้าย.length
    บทต้น = Math.min(Math.max(บทต้น, 1), n)
    บทปลาย = Math.min(Math.max(บทปลาย, บทต้น), n)
    if (ข้อต้น !== null) ข้อต้น = Math.min(Math.max(ข้อต้น, 1), ข้อสุดท้าย[บทต้น - 1] || 1)
    if (ข้อปลาย !== null) ข้อปลาย = Math.min(Math.max(ข้อปลาย, 1), ข้อสุดท้าย[บทปลาย - 1] || 1)
  }
  if (!บทต้น || บทปลาย < บทต้น) return null
  if (ข้อต้น !== null && ข้อปลาย !== null && บทปลาย === บทต้น && ข้อปลาย < ข้อต้น) ข้อปลาย = ข้อต้น
  return { รหัส, ลำดับ, บทต้น, ข้อต้น, บทปลาย, ข้อปลาย }
}

/**
 * ⭐ **ช่วงของหน้าอ่าน (`r`) จากอ้างอิง** ⇒ มีช่วงมากกว่า 1 ข้อเท่านั้น ⇒ ข้อเดียวหรือทั้งบท ⇒ `null`
 *   ⇒ ปลายเปิด (`มาระโก 1:5-` · ข้ามบทแบบไม่บอกข้อ) ⇒ ต้องรู้ข้อสุดท้ายของบท ⇒ ไม่รู้ ⇒ `null` ⇒ ยังพาไปต้นช่วงได้
 */
export function ช่วงจากอ้างอิง(
  อ: อ้างอิงเว็บเดิม,
  ขนาด?: ขนาดเล่ม | null,
): { จาก: { บท: number; ข้อ: number }; ถึง: { บท: number; ข้อ: number } } | null {
  const ท้ายบท = (c: number) => ขนาด?.[อ.รหัส]?.[c - 1] ?? null
  const ต้น = อ.ข้อต้น ?? 1
  if (อ.ข้อต้น === null && อ.บทปลาย === อ.บทต้น) return null
  const ปลาย = อ.ข้อปลาย ?? ท้ายบท(อ.บทปลาย)
  if (!ปลาย) return null
  if (อ.บทปลาย === อ.บทต้น && ปลาย <= ต้น) return null
  return { จาก: { บท: อ.บทต้น, ข้อ: ต้น }, ถึง: { บท: อ.บทปลาย, ข้อ: ปลาย } }
}

/**
 * ⭐ **ทุกข้อในช่วงของอ้างอิง เรียงตามลำดับ** ⇒ ใช้หาคำของ `w` ⇒ ⛔ เกิน 10 บท ⇒ ตัดที่ 10 บทแรก (ลิงก์จริงยาวสุด 2 บท)
 *   ⇒ ไม่รู้ข้อสุดท้ายของบท ⇒ ถึงข้อ 200 (ไฟล์การ์ดไม่มีข้อนั้นก็แค่ไม่เจอ)
 */
export function ข้อในอ้างอิง(อ: อ้างอิงเว็บเดิม, ขนาด?: ขนาดเล่ม | null): [number, number][] {
  const ได้: [number, number][] = []
  const บทสุด = Math.min(อ.บทปลาย, อ.บทต้น + 9)
  for (let c = อ.บทต้น; c <= บทสุด; c++) {
    const ท้าย = ขนาด?.[อ.รหัส]?.[c - 1] ?? 200
    const vs = c === อ.บทต้น ? (อ.ข้อต้น ?? 1) : 1
    const ve = c === อ.บทปลาย ? (อ.ข้อปลาย ?? ท้าย) : ท้าย
    for (let v = vs; v <= ve; v++) ได้.push([c, v])
  }
  return ได้
}

/**
 * ⭐ **คำของ `w` ตรงกับคำในไฟล์การ์ดไหม** ⇒ กติกาเดียวกับ `PK.findWordInRange` ของเว็บเดิม ⇒ เลข Strong ก่อน แล้วรูปพจนานุกรม
 *   ⇒ ลิงก์เดิมเขียน `G2098` · `H7225` ⇒ ไฟล์การ์ดของเว็บนี้เก็บ `2098` · `7225` · `0871a` (ฮีบรูมีศูนย์นำและตัวอักษรท้ายได้)
 *   ⇒ ตัด G/H นำ · ตัดศูนย์นำ · ตัวเล็กใหญ่ไม่สน ⇒ เทียบตรงตัว
 */
export function ล้างรหัสคำ(x: string): string {
  return x.trim().toLowerCase().replace(/^[gh](?=\d)/, '').replace(/^0+(?=\d)/, '')
}

/** ⭐ ไม่มีลิงก์เก่าจริงที่ใช้คำแบบอื่นนอกจากเลข Strong ⇒ รูปพจนานุกรมรับไว้ตามตัวอ่านเดิม ⇒ ค่าแปลก ๆ ทิ้งเงียบ ๆ */
export function อ่านคำเว็บเดิม(ค่า: unknown): string | null {
  if (typeof ค่า !== 'string') return null
  const x = ค่า.trim()
  if (!x || x.length > 40) return null
  return x
}

/**
 * ⭐ **หาคำที่ตรงในข้อมูลการ์ดของบท** ⇒ `ชั้น` = `{ชื่อชั้น: {ข้อ: ["รูปพจนานุกรม~รหัส~..."]}}` ของ `api/card/<เล่ม>/<บท>.json`
 *   ⇒ คืน `[ข้อ, คำที่ (นับจาก 1)]` ⇒ ⛔ ไม่เจอ ⇒ `null`
 *   ⇒ ⭐ ชั้นแรกของไฟล์ ⇒ บทหนึ่งมีชั้นคำชั้นเดียว (คำกรีก หรือ คำฮีบรู)
 */
export function หาคำในบท(
  ชั้น: Record<string, Record<string, string[]>> | null | undefined,
  ข้อที่หา: number[],
  คำ: string,
  แบบ: 'รหัส' | 'เลขล้วน' | 'รูป',
): [number, number] | null {
  const ข้อทั้งหมด = ชั้น ? Object.values(ชั้น)[0] : undefined
  if (!ข้อทั้งหมด) return null
  // ⭐ `เลขล้วน` ⇒ ลิงก์เขียน `H871` แต่ไฟล์เก็บ `0871a` ⇒ เทียบเฉพาะเลข ⇒ ผู้เรียกลองหลังเทียบตรงตัวไม่เจอเท่านั้น
  const แปลง = (x: string) =>
    แบบ === 'รหัส' ? ล้างรหัสคำ(x) : แบบ === 'เลขล้วน' ? ล้างรหัสคำ(x).replace(/\D+$/, '') : x.normalize('NFC')
  const หา = แปลง(คำ)
  if (!หา) return null
  for (const v of ข้อที่หา) {
    const รายการ = ข้อทั้งหมด[String(v)]
    if (!รายการ) continue
    for (let i = 0; i < รายการ.length; i++) {
      const [รูป = '', รหัส = ''] = รายการ[i]!.split('~')
      const ค่า = แบบ === 'รูป' ? รูป : รหัส
      if (ค่า && แปลง(ค่า) === หา) return [v, i + 1]
    }
  }
  return null
}
