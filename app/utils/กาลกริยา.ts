const ตามรหัส = new Map(ตารางกาล.map((x) => [x.รหัส, x]))

/** มาลาคำสั่ง ⇒ `M` = imperative · `R` = กริยาคุณศัพท์ใช้เป็นคำสั่ง (ตาราง `มาลากรีก` ใน `รูปผัน.ts`) */
const มาลาคำสั่ง = new Set(['M', 'R'])

export interface กาลของคำ {
  กาล: กาล
  คำสั่ง: boolean
}

/**
 * อ่านช่องที่ 3 ของคำ ⇒ `undefined` = ⛔ ไม่ใช่คำกริยา (ไม่มีช่องนี้)
 * ⛔⛔ **รหัสที่ไม่รู้จักโยนทิ้ง ⛔ ไม่ได้** ⇒ คืน `null` ⇒ หน้าอ่านวาดเครื่องหมาย `?` ให้เห็นว่าพัง
 *   ⇒ ด่าน `tools/ด่านกาลกริยา.mjs` ไล่ทุกรหัสในของที่สร้างเสร็จ ⇒ เจอ `null` แม้ตัวเดียว = แดง
 */
export function อ่านกาล(รหัส: string | undefined): กาลของคำ | null | undefined {
  if (รหัส === undefined) return undefined
  const กาล = ตามรหัส.get(รหัส[0] as รหัสกาล)
  if (!กาล || รหัส.length !== 2 || !/^[ISOMNPR]$/.test(รหัส[1]!)) return null
  return { กาล, คำสั่ง: มาลาคำสั่ง.has(รหัส[1]!) }
}

/** ตัดกาลกับมาลาจากรูปผันเต็ม ⇒ ให้การ์ดคำใช้ ⇒ กติกาเดียวกับ `กาลมาลาของ` ที่ `server/utils/ชั้นคำ.ts` */
export function กาลจากรูปผัน(รูปผัน: string): กาลของคำ | null | undefined {
  if (!รูปผัน.startsWith('V-')) return undefined
  const m = /^V-2?([PIFARL])[AMPEDONQX]([ISOMNPR])(?:-|$)/.exec(รูปผัน)
  return m ? อ่านกาล(m[1]! + m[2]!) : null
}

/** ⭐ ของที่โปรแกรมอ่านหน้าจอได้ยินต่อท้ายคำ ⇒ WCAG 2.2 SC 1.3.1 (ระดับ A) */
export function คำอ่าน(ก: กาลของคำ | null): string {
  if (!ก) return 'กริยา ⛔ อ่านกาลไม่ออก'
  return `กริยา ${ก.กาล.ชื่อ}${ก.คำสั่ง ? ' คำสั่ง' : ''}`
}
