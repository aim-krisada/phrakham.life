/** ช่วงอักษรกรีก (รวมเครื่องหมายเสียงที่ติดมาเป็นตัวประกอบ) ⇒ ใช้ทั้งหน้าเว็บและด่าน ⇒ ⛔ ไม่มีสองกติกา */
export const อักษรกรีก = /[\u0370-\u03FF\u1F00-\u1FFF][\u0300-\u036F\u0370-\u03FF\u1F00-\u1FFF]*/g

/** ตัดข้อความเป็นท่อน ⇒ ท่อนที่เป็นคำกรีกได้ `กรีก: true` ⇒ หน้าเว็บห่อด้วย `lang="grc"` (WCAG 2.2 SC 3.1.2) */
export function แยกกรีก(ข้อความ: string): { ข้อความ: string; กรีก: boolean }[] {
  const ผล: { ข้อความ: string; กรีก: boolean }[] = []
  let ที่ = 0
  for (const m of ข้อความ.matchAll(อักษรกรีก)) {
    if (m.index! > ที่) ผล.push({ ข้อความ: ข้อความ.slice(ที่, m.index), กรีก: false })
    ผล.push({ ข้อความ: m[0], กรีก: true })
    ที่ = m.index! + m[0].length
  }
  if (ที่ < ข้อความ.length) ผล.push({ ข้อความ: ข้อความ.slice(ที่), กรีก: false })
  return ผล
}

