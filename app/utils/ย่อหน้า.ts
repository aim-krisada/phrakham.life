/** ข้อที่ส่งเข้ามา ⇒ รูปเดียวกับ `แถว` ของหน้าอ่าน แต่เอาเฉพาะฉบับเดียว */
export interface ข้อสำหรับจัด {
  บท: number
  เลข: string
  ป้าย: string
  ชิ้น: ชิ้นเนื้อ[]
}

/**
 * ผ่ากองชิ้นออกเป็นสองกอง ตรงตัวอักษรลำดับที่ `ที่`
 *
 * ⛔ **ชิ้นที่ถูกผ่ากลาง ต้องคงสถานะ `พระเยซู` ไว้ทั้งสองซีก**
 *   ⇒ ไม่งั้นสีคำพระเยซูจะหายไปครึ่งหนึ่งตรงรอยย่อหน้า
 */
export function ผ่าชิ้น(ชิ้น: ชิ้นเนื้อ[], ที่: number): [ชิ้นเนื้อ[], ชิ้นเนื้อ[]] {
  const ก่อน: ชิ้นเนื้อ[] = []
  const หลัง: ชิ้นเนื้อ[] = []
  let นับ = 0
  for (const ช of ชิ้น) {
    const เริ่ม = นับ
    const จบ = นับ + ช.ตัวหนังสือ.length
    นับ = จบ
    if (จบ <= ที่) {
      ก่อน.push(ช)
    } else if (เริ่ม >= ที่) {
      หลัง.push(ช)
    } else {
      const ตรงกลาง = ที่ - เริ่ม
      ก่อน.push({ ตัวหนังสือ: ช.ตัวหนังสือ.slice(0, ตรงกลาง), พระเยซู: ช.พระเยซู })
      หลัง.push({ ตัวหนังสือ: ช.ตัวหนังสือ.slice(ตรงกลาง), พระเยซู: ช.พระเยซู })
    }
  }
  return [ก่อน, หลัง]
}

/**
 * จัดข้อทั้งบทของ **ฉบับเดียว** ให้เป็นย่อหน้า
 *
 * ⛔ **ไม่มีรอยเลย ⇒ คืนย่อหน้าเดียวที่มีทุกข้อ** ⇒ ⛔ ไม่โยนข้อผิดพลาด
 *   **ทำไม** ⇒ ของนี้ไปโผล่กลางหน้าอ่านของผู้อ่าน ⇒ **ตัวบทต้องขึ้นเสมอ**
 *   ⇒ ตัวดักของจริงคือด่านฝั่งข้อมูล ซึ่งตัดฉบับที่ใช้ไม่ได้ทิ้งตั้งแต่ตอนพ่นซอง
 *
 * ⛔ **รอยที่ล้นขอบข้อ หรือเกาะข้อที่ไม่มีในบทนี้ ⇒ ทิ้งเงียบ ๆ** ⇒ เหตุผลเดียวกับบรรทัดบน
 */
export function จัดย่อหน้า(ข้อทั้งบท: ข้อสำหรับจัด[], รอยของบท: รอยย่อหน้า[] | undefined): ย่อหน้า[] {
  if (!ข้อทั้งบท.length) return []

  // รอยของข้อไหนบ้าง ⇒ เรียงตามตำแหน่งในข้อ ⛔ ซ้ำตำแหน่งเดียวกันเอาอันเดียว
  const รอยของข้อ = new Map<number, รอยย่อหน้า[]>()
  for (const ร of รอยของบท || []) {
    const กอง = รอยของข้อ.get(ร.ข้อ) || []
    if (!กอง.some((x) => x.หลังอักษร === ร.หลังอักษร)) กอง.push(ร)
    รอยของข้อ.set(ร.ข้อ, กอง)
  }
  for (const กอง of รอยของข้อ.values()) กอง.sort((a, b) => a.หลังอักษร - b.หลังอักษร)

  const ออก: ย่อหน้า[] = []
  let กำลังทำ: ย่อหน้า | null = null

  const เปิดย่อหน้า = (ป้าย: string, อ้างอิง: string) => {
    กำลังทำ = { กุญแจ: `ย่อหน้า-${อ้างอิง}-${ออก.length}`, ป้าย, ท่อน: [] }
    ออก.push(กำลังทำ)
  }

  for (const ข of ข้อทั้งบท) {
    const ยาว = ข.ชิ้น.reduce((n, ช) => n + ช.ตัวหนังสือ.length, 0)
    const กอง = (รอยของข้อ.get(Number(ข.เลข)) || []).filter(
      (ร) => ร.หลังอักษร >= 0 && ร.หลังอักษร <= ยาว,
    )

    // รอยที่หัวข้อพอดี ⇒ ข้อนี้เริ่มย่อหน้าใหม่ **ก่อน** ตัวอักษรตัวแรก
    const รอยหัวข้อ = กอง.find((ร) => ร.หลังอักษร === 0)
    if (รอยหัวข้อ || !กำลังทำ) {
      เปิดย่อหน้า(รอยหัวข้อ?.ป้าย || '', `${ข.บท}-${ข.เลข}`)
    }

    // รอยกลางข้อ ⇒ ผ่าตัวบทของข้อนี้เป็นท่อน ๆ ⇒ ท่อนแรกอยู่ย่อหน้าเดิม ที่เหลือขึ้นย่อหน้าใหม่
    const กลางข้อ = กอง.filter((ร) => ร.หลังอักษร > 0 && ร.หลังอักษร < ยาว)
    let เหลือ = ข.ชิ้น
    let ตัดไปแล้ว = 0
    let ท่อนแรก = true

    for (const ร of กลางข้อ) {
      const [ก่อน, หลัง] = ผ่าชิ้น(เหลือ, ร.หลังอักษร - ตัดไปแล้ว)
      กำลังทำ!.ท่อน.push({
        กุญแจ: `${ข.บท}:${ข.เลข}#${ตัดไปแล้ว}`,
        บท: ข.บท,
        เลข: ข.เลข,
        ป้าย: ท่อนแรก ? ข.ป้าย : '',
        ท่อนแรก,
        ชิ้น: ก่อน,
      })
      เปิดย่อหน้า(ร.ป้าย, `${ข.บท}-${ข.เลข}-${ร.หลังอักษร}`)
      เหลือ = หลัง
      ตัดไปแล้ว = ร.หลังอักษร
      ท่อนแรก = false
    }

    กำลังทำ!.ท่อน.push({
      กุญแจ: `${ข.บท}:${ข.เลข}#${ตัดไปแล้ว}`,
      บท: ข.บท,
      เลข: ข.เลข,
      ป้าย: ท่อนแรก ? ข.ป้าย : '',
      ท่อนแรก,
      ชิ้น: เหลือ,
    })
  }

  // ⛔ ย่อหน้าที่ไม่มีท่อนเลย ⇒ ทิ้ง ⇒ เกิดได้เมื่อรอยเกาะข้อที่ไม่มีเนื้อในบทนี้
  return ออก.filter((ย) => ย.ท่อน.some((ท) => ท.ชิ้น.some((ช) => ช.ตัวหนังสือ.length)))
}

