/** แถวหนึ่งของแบบแยกตามย่อหน้า ⇒ ทุกคอลัมน์เริ่มแถวนี้ที่ระดับเดียวกัน */
export interface กลุ่มย่อหน้า {
  กุญแจ: string
  /** ย่อหน้าของแต่ละคอลัมน์ในแถวนี้ ⇒ ลำดับเดียวกับคอลัมน์ที่ส่งเข้ามา ⇒ ไม่มีอะไรในแถวนี้ = `[]` */
  ช่อง: ย่อหน้า[][]
}

/**
 * จัดย่อหน้าของทุกคอลัมน์เป็นแถว ⇒ **ตัดแถวเฉพาะจุดที่ทุกคอลัมน์ขึ้นย่อหน้าพร้อมกัน**
 *
 * `คอลัมน์` ⇒ ย่อหน้าของแต่ละคอลัมน์ ⇒ ผลของ `จัดย่อหน้า` ของบทเดียวกัน เรียงซ้ายไปขวา
 * ⭐ คอลัมน์ที่ไม่มีย่อหน้าเลย (ฉบับนั้นไม่มีบทนี้) ⇒ ⛔ ไม่ร่วมตัดสิน ⇒ ได้ `[]` ทุกแถว
 * ⭐ **ย่อหน้าทุกก้อนอยู่ครบ ลำดับเดิม ⛔ ไม่ซ้ำ** ⇒ ต่อทุกแถวของคอลัมน์หนึ่งกลับมา = ของที่ส่งเข้ามาเป๊ะ
 *   ⇒ ด่าน `tools/ตรวจจัดย่อหน้า.mjs` ข้อ ⑥ พิสูจน์ซ้ำทุกบท
 */
export function จับคู่ย่อหน้า(คอลัมน์: readonly (readonly ย่อหน้า[])[]): กลุ่มย่อหน้า[] {
  const ร่วม = คอลัมน์.map((ย่อ, c) => (ย่อ.length ? c : -1)).filter((c) => c >= 0)
  if (!ร่วม.length) return []

  // ช่วงที่การขึ้นย่อหน้าแต่ละก้อนนับว่า *ตรงกัน* ได้ ⇒ [ต่ำสุด, สูงสุด] เป็นเลขข้อ
  const ช่วงของ = คอลัมน์.map((ย่อ) => {
    const มี = [...new Set(ย่อ.flatMap((ย) => ย.ท่อน.map((ท) => Number(ท.เลข))))].sort((a, b) => a - b)
    return ย่อ.map((ย, j): [number, number] | null => {
      const ท = ย.ท่อน[0]
      if (j === 0 || !ท) return null
      const v = Number(ท.เลข)
      if (!ท.ท่อนแรก) return [v, v]
      const ก่อน = มี.filter((n) => n < v).pop()
      return [ก่อน === undefined ? v : ก่อน + 1, v]
    })
  })

  // ⭐ จุดที่ลองตัด ⇒ เลขสูงสุดของทุกช่วง ⇒ ช่วงของทุกคอลัมน์ทับกันเมื่อไร จุดต่ำสุดของปลายช่วงอยู่ในส่วนที่ทับเสมอ
  const จุดที่ลอง = [
    ...new Set(ร่วม.flatMap((c) => ช่วงของ[c]!.filter((x) => x).map((x) => x![1]))),
  ].sort((a, b) => a - b)

  const ล่าสุด = คอลัมน์.map(() => 0)
  const รอยตัด: number[][] = []
  for (const p of จุดที่ลอง) {
    const ได้ = คอลัมน์.map(() => -1)
    let ครบ = true
    for (const c of ร่วม) {
      const j = ช่วงของ[c]!.findIndex((x, k) => k > ล่าสุด[c]! && !!x && x[0] <= p && p <= x[1])
      if (j < 0) {
        ครบ = false
        break
      }
      ได้[c] = j
    }
    if (!ครบ) continue
    for (const c of ร่วม) ล่าสุด[c] = ได้[c]!
    รอยตัด.push(ได้)
  }

  const เริ่ม = คอลัมน์.map(() => 0)
  const ออก: กลุ่มย่อหน้า[] = []
  const ปิดแถว = (จบ: (c: number) => number) => {
    const ช่อง = คอลัมน์.map((ย่อ, c) => (ร่วม.includes(c) ? ย่อ.slice(เริ่ม[c], จบ(c)) : []))
    const หัว = ช่อง[ร่วม[0]!]![0]?.ท่อน[0]
    ออก.push({ กุญแจ: `กลุ่ม-${หัว ? `${หัว.บท}-${หัว.เลข}-${ออก.length}` : ออก.length}`, ช่อง })
  }
  for (const ตัด of รอยตัด) {
    ปิดแถว((c) => ตัด[c]!)
    for (const c of ร่วม) เริ่ม[c] = ตัด[c]!
  }
  ปิดแถว((c) => คอลัมน์[c]!.length)
  return ออก
}
