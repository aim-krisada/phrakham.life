/**
 * กางเครื่องหมายของทั้งบทเป็นรายคำ ⇒ กุญแจ `"<ข้อ>:<ลำดับคำ>"`
 * ⭐ ช่วงที่ข้ามข้อ ⇒ ต้องรู้ว่าแต่ละข้อมีกี่คำ ⇒ `จำนวนคำ(ข้อ)`
 * ⛔ ข้อที่ไม่มีในบท ⇒ ข้ามไปเงียบ ๆ ⛔ ไม่ล้ม ⇒ ด่านฝั่งข้อมูลเฝ้าความครบแล้ว
 */
export function กางเครื่องหมาย(
  ข้อมูล: Record<string, (number | string)[][]> | undefined,
  จำนวนคำ: (ข้อ: number) => number,
): Map<string, จุดบนคำ[]> {
  const ผล = new Map<string, จุดบนคำ[]>()
  if (!ข้อมูล) return ผล
  const ใส่ = (ข้อ: number, คำ: number, จ: จุดบนคำ) => {
    const k = `${ข้อ}:${คำ}`
    const เดิม = ผล.get(k)
    if (เดิม) เดิม.push(จ)
    else ผล.set(k, [จ])
  }
  for (const [รหัส, รายการ] of Object.entries(ข้อมูล)) {
    for (const เครื่อง of รายการ) {
      if (รหัส === 'n') {
        ใส่(Number(เครื่อง[0]), Number(เครื่อง[1]), { รหัส, ต้น: true, ท้าย: true, โน้ต: String(เครื่อง[2] ?? '') })
        continue
      }
      const มาจากก่อน = เครื่อง.includes('<')
      const ไปต่อ = เครื่อง.includes('>')
      const เลข = เครื่อง.filter((x): x is number => typeof x === 'number')
      const ท่อน: [number, number, number, number][] = []
      if (เลข.length === 2) ท่อน.push([เลข[0]!, เลข[1]!, เลข[0]!, เลข[1]!])
      else for (let i = 0; i + 3 < เลข.length; i += 4) ท่อน.push([เลข[i]!, เลข[i + 1]!, เลข[i + 2]!, เลข[i + 3]!])
      const คำทั้งหมด: [number, number][] = []
      for (const [v1, w1, v2, w2] of ท่อน) {
        for (let v = v1; v <= v2; v++) {
          const สุด = v === v2 ? w2 : จำนวนคำ(v) - 1
          for (let w = v === v1 ? w1 : 0; w <= สุด; w++) คำทั้งหมด.push([v, w])
        }
      }
      คำทั้งหมด.forEach(([v, w], i) =>
        ใส่(v, w, { รหัส, ต้น: i === 0 && !มาจากก่อน, ท้าย: i === คำทั้งหมด.length - 1 && !ไปต่อ }),
      )
    }
  }
  return ผล
}

/** สิ่งที่หน้าอ่านติดให้ปุ่มคำ ⇒ ว่างหมด = คำนี้ไม่มีเครื่องหมายของตระกูลที่เปิด */
export interface หน้าตาคำ {
  /** โทเค็นให้ CSS ⇒ `rs` · `rs<` (ต้นช่วง) · `rs>` (ท้ายช่วง) */
  ลค?: string
  /** ป้ายตัวอักษรบนคำแรกของเครื่องหมาย */
  ป้าย?: string
  /** อัญประกาศหรือดอกจันหน้าคำ / หลังคำ */
  หน้า?: string
  หลัง?: string
  /** รหัสพร้อมต้นท้าย ⇒ ให้ชิ้นเสียงแปลงเป็นชื่อไทย ⇒ เช่น `F<> r<` */
  เสียง?: string
}

/** หน้าตาของคำหนึ่งคำ ตามตระกูลที่เปิด ⇒ ลำดับตามตาราง `แบบของรหัส` */
export function หน้าตาของคำ(จุด: จุดบนคำ[] | undefined, เปิด: readonly string[]): หน้าตาคำ {
  if (!จุด?.length || !เปิด.length) return {}
  const ลค: string[] = []
  const ป้าย: string[] = []
  const เสียง: string[] = []
  let หน้า = ''
  let หลัง = ''
  const ลำดับ = Object.keys(แบบของรหัส)
  for (const จ of [...จุด].sort((a, b) => ลำดับ.indexOf(a.รหัส) - ลำดับ.indexOf(b.รหัส))) {
    const แบบ = แบบของรหัส[จ.รหัส]
    if (!แบบ || !เปิด.includes(แบบ[0])) continue
    const [, ร, ป, ปเรา] = แบบ
    ลค.push(ร)
    if (จ.ต้น) ลค.push(`${ร}<`)
    if (จ.ท้าย) ลค.push(`${ร}>`)
    if (จ.ต้น) {
      if (ร === 'bl') หน้า += '“'
      else if (ร === 'mg') หน้า += '‘'
      else if (ร === 'st') หน้า += '*'
      else if (ป || ปเรา) ป้าย.push(ป || ปเรา)
    }
    if (จ.ท้าย) {
      if (ร === 'bl') หลัง = '”' + หลัง
      else if (ร === 'mg') หลัง = '’' + หลัง
      else if (ร === 'st') หลัง = '*' + หลัง
    }
    if (จ.ต้น || จ.ท้าย) เสียง.push(`${จ.รหัส}${จ.ต้น ? '<' : ''}${จ.ท้าย ? '>' : ''}`)
  }
  if (!ลค.length) return {}
  return {
    ลค: [...new Set(ลค)].join(' '),
    ป้าย: ป้าย.length ? [...new Set(ป้าย)].join(' ') : undefined,
    หน้า: หน้า || undefined,
    หลัง: หลัง || undefined,
    เสียง: เสียง.join(' ') || undefined,
  }
}
