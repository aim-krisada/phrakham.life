/** รายการเสียงตามรูปของ `api/audio.json` ⇒ เอาเฉพาะช่องที่ใช้ */
export interface รายการเสียง {
  ฉบับ?: Record<string, { เล่ม?: Record<string, { บท?: Record<string, unknown> }> }>
}

/** ภาพของที่ผู้อ่านเห็น ⇒ `ฉบับ:เล่ม:บท` ⇒ เก็บในเครื่องเป็นอาร์เรย์ ⇒ เทียบรุ่นต่อรุ่น */
export function ภาพเสียง(รายการ: รายการเสียง | null | undefined): string[] {
  const ได้: string[] = []
  for (const [ฉบับ, ก้อน] of Object.entries(รายการ?.ฉบับ || {}))
    for (const [เล่ม, ข] of Object.entries(ก้อน?.เล่ม || {}))
      for (const บท of Object.keys(ข?.บท || {})) ได้.push(`${ฉบับ}:${เล่ม}:${บท}`)
  return ได้.sort()
}

export interface เสียงใหม่ของเล่ม {
  ฉบับ: string
  เล่ม: string
  บท: number[]
}

/** ของที่มีในรุ่นนี้ แต่ไม่มีในภาพที่เครื่องจำไว้ ⇒ จัดกลุ่มตามฉบับกับเล่ม ⇒ เรียงตามที่เจอในรายการ */
export function หาเสียงใหม่(เก่า: string[], ใหม่: string[]): เสียงใหม่ของเล่ม[] {
  const มีแล้ว = new Set(เก่า)
  const กลุ่ม = new Map<string, เสียงใหม่ของเล่ม>()
  for (const k of ใหม่) {
    if (มีแล้ว.has(k)) continue
    const [ฉบับ, เล่ม, บท] = k.split(':')
    if (!ฉบับ || !เล่ม || !บท) continue
    const g = กลุ่ม.get(`${ฉบับ}:${เล่ม}`) || { ฉบับ, เล่ม, บท: [] }
    g.บท.push(Number(บท))
    กลุ่ม.set(`${ฉบับ}:${เล่ม}`, g)
  }
  for (const g of กลุ่ม.values()) g.บท.sort((a, b) => a - b)
  return [...กลุ่ม.values()]
}

/** `[2,3,4,7]` ⇒ `2–4, 7` */
export function ช่วงบท(บท: number[]): string {
  const ท่อน: string[] = []
  for (let i = 0; i < บท.length; ) {
    let j = i
    while (j + 1 < บท.length && บท[j + 1] === บท[j]! + 1) j++
    ท่อน.push(i === j ? `${บท[i]}` : `${บท[i]}–${บท[j]}`)
    i = j + 1
  }
  return ท่อน.join(', ')
}

/** ⭐ ข้อความต้องสั้น (เกณฑ์ Notes ข้อ 2 ⇒ ขึ้นทุกคืน) ⇒ แสดงไม่เกิน `แสดงสูงสุด` เล่ม ⇒ ที่เหลือบอกเป็นจำนวน */
export const แสดงสูงสุด = 2

/**
 * ⭐ ท่อนของใหม่บนบรรทัดเขียว ⇒ ⛔ มีของใหม่ ⇒ `[]` (เกณฑ์ข้อ 3 ⇒ ⛔ แสดงรายการว่าง)
 *   ⇒ เล่มของฉบับเดียวกันรวบเป็นท่อนเดียว ⇒ *เพิ่มเสียง TCV ลูกา 5–7, กิจการ 1–3* ⇒ ⛔ เขียน *เสียง TCV* ซ้ำทุกเล่ม (N ตรวจ 24 พ.ย. 2569)
 *   ⇒ เกิน `แสดงสูงสุด` เล่ม ⇒ ต่อท้ายท่อนสุดท้ายว่า *และอีก N เล่ม*
 *   ⇒ `ชื่อเล่ม` แปลงรหัสเล่มเป็นชื่อไทย (`api/books.json` ช่อง `ชื่อไทย`) ⇒ ไม่รู้ ⇒ ใช้รหัส
 */
export function ท่อนของใหม่(
  ใหม่: เสียงใหม่ของเล่ม[],
  ชื่อเล่ม: (รหัส: string) => string | undefined,
  คำ: { เพิ่มเสียง: (ฉบับ: string, เล่มกับบท: string) => string; อีก: (จำนวน: number) => string },
): string[] {
  const ตามฉบับ = new Map<string, string[]>()
  for (const g of ใหม่.slice(0, แสดงสูงสุด)) {
    const รายการ = ตามฉบับ.get(g.ฉบับ) || []
    รายการ.push(`${ชื่อเล่ม(g.เล่ม) || g.เล่ม} ${ช่วงบท(g.บท)}`)
    ตามฉบับ.set(g.ฉบับ, รายการ)
  }
  const ท่อน = [...ตามฉบับ].map(([ฉบับ, เล่ม]) => คำ.เพิ่มเสียง(ฉบับ, เล่ม.join(', ')))
  if (ใหม่.length > แสดงสูงสุด) ท่อน[ท่อน.length - 1] += ' ' + คำ.อีก(ใหม่.length - แสดงสูงสุด)
  return ท่อน
}

/**
 * ⭐ คำตัดสินว่าจะบอกว่าอัปเดตแล้วไหม ⇒ เรียกเมื่อสถานะออฟไลน์เป็น `พร้อม` เท่านั้น (เก็บรุ่นนี้ครบแล้ว ⇒ เกณฑ์ข้อ 4)
 *   ⇒ `รุ่นเดิม` ว่าง (⛔ เคยจด) ⇒ เปิดครั้งแรกหลังติดตั้ง ⇒ ต้องจดไว้ ⇒ ⛔ บอกว่าอัปเดต (เกณฑ์ข้อ 5)
 *   ⇒ รุ่นเดิมตรงรุ่นนี้ ⇒ ⛔ มีอะไรบอก
 *   ⇒ รุ่นต่าง ⇒ ท่อนของใหม่ ⇒ ว่างได้ ⇒ บรรทัดขึ้นแค่ *อัปเดตแล้ว* (เกณฑ์ข้อ 3)
 */
export function ตัดสินของใหม่(
  รุ่นเดิม: string | null,
  เสียงเดิม: string[],
  รุ่นนี้: { รุ่น: string; เสียง: string[] },
  ชื่อเล่ม: (รหัส: string) => string | undefined,
  คำ: Parameters<typeof ท่อนของใหม่>[2],
): { อัปเดต?: string[]; ต้องจด: boolean } {
  if (!รุ่นเดิม) return { ต้องจด: true }
  if (รุ่นเดิม === รุ่นนี้.รุ่น) return { ต้องจด: false }
  return { อัปเดต: ท่อนของใหม่(หาเสียงใหม่(เสียงเดิม, รุ่นนี้.เสียง), ชื่อเล่ม, คำ), ต้องจด: false }
}
