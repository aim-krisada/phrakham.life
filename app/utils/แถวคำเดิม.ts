/** ข้อแปลหนึ่งข้อกับแถวที่มันเริ่ม ⇒ ส่งเข้ามาเรียงหรือไม่เรียงก็ได้ */
export interface ข้อแปลในแถว {
  บท: number
  ข้อ: number
  แถว: number
}

/** ข้อเดิมหนึ่งข้อ ⇒ `ไป` = ข้อแปลที่มันอยู่ด้วย เรียงตามลำดับ ⇒ ไม่มีในตาราง = `[[บทเดิม, ข้อเดิม]]` */
export interface ข้อเดิมเข้าแถว {
  ไป: readonly (readonly [number, number])[]
}

const ลำดับ = (บท: number, ข้อ: number) => บท * 1000 + ข้อ

/**
 * แถวของข้อเดิมแต่ละข้อ ⇒ คืนเป็นเลขแถว (นับจาก 0) **ลำดับเดียวกับที่ส่งเข้ามา**
 *
 * `ข้อเดิม` ⇒ ⛔ **ต้องเรียงตามลำดับของฝั่งเดิมแล้ว** ⇒ ลำดับนี้คือลำดับคำที่ห้ามสลับ
 * `ข้อแปล` ⇒ ข้อแปลทุกข้อที่มีแถวบนหน้าของก้อนนี้ ⇒ ว่าง = ทุกข้อเดิมได้แถว 0
 */
export function จัดข้อเดิมลงแถว(
  ข้อเดิม: readonly ข้อเดิมเข้าแถว[],
  ข้อแปล: readonly ข้อแปลในแถว[],
): number[] {
  const ตรง = new Map<number, number>()
  for (const x of ข้อแปล) {
    const k = ลำดับ(x.บท, x.ข้อ)
    // ⭐ ข้อแปลข้อเดียวมาหลายแถว ⇒ เอาแถวหลังสุด ⇒ เหตุผลอยู่ที่ `ข้อแปลของกลุ่ม` ข้างล่าง
    if (!ตรง.has(k) || ตรง.get(k)! < x.แถว) ตรง.set(k, x.แถว)
  }
  const เรียง = [...ตรง.entries()].sort((a, b) => a[0] - b[0])

  /** ② แถวของข้อแปลที่อยู่ก่อนเป้าหมายที่ใกล้ที่สุด ⇒ ไม่มีเลย = แถว 0 */
  const แถวก่อน = (k: number) => {
    let ได้ = 0
    for (const [ที่, แถว] of เรียง) {
      if (ที่ > k) break
      ได้ = แถว
    }
    return ได้
  }

  const ออก: number[] = []
  let ล่าสุด = 0
  for (const x of ข้อเดิม) {
    // ① ข้อแปลข้อแรกที่มีแถวบนหน้า
    const เจอ = x.ไป.map(([บ, ข]) => ตรง.get(ลำดับ(บ, ข))).find((r) => r !== undefined)
    const แรก = x.ไป[0]
    let แถว = เจอ ?? (แรก ? แถวก่อน(ลำดับ(แรก[0], แรก[1])) : ล่าสุด)
    // ③ ⛔ ห้ามถอยหลัง ⇒ ลำดับคำของฝั่งเดิมต้องเดินหน้าเสมอ
    if (แถว < ล่าสุด) แถว = ล่าสุด
    ออก.push(แถว)
    ล่าสุด = แถว
  }
  return ออก
}

// ⭐⭐ **เลขกำกับของข้อเดิม (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/117)** ⇒ ⛔ ไม่ได้อยู่ที่นี่
//   ⇒ ใช้ `ป้ายเลขข้อ` ใน `app/utils/ป้ายเลขข้อ.ts` ⇒ **ตัวเดียวกับฉบับแปล** ⇒ เหตุผลกับนิยาม *บทของแถว* อยู่ที่นั่น
//   ⇒ ใจความ ⇒ ข้อแรกของก้อนบทกับข้อเดิมที่อยู่คนละบทกับก้อน ⇒ *บท:ข้อ* · ข้ออื่นเลขข้อเปล่า
//   ⇒ ⛔ ของเดิม (ใบ #95) พิมพ์ *บท:ข้อ* ทุกข้อ ⇒ ตอนนั้นคำเดิมยังไม่ตรงแถว (ใบ #112 แก้แล้ว)

/**
 * ข้อแปลของแต่ละแถว ⇒ **แบบแยกตามย่อหน้า** (แถวของใบ #109)
 *
 * ⭐ ข้อแปลเริ่มที่แถวที่ **ท่อนแรก** ของมันอยู่ ⇒ ข้อที่ถูกรอยย่อหน้าผ่ากลางข้อ ⇒ คำเดิมอยู่แถวที่ข้อนั้นเริ่ม
 *   ⇒ **ทำไม** ⇒ เรา ⛔ ไม่รู้ว่ารอยผ่าตรงกับคำเดิมคำไหน ⇒ ผ่าคำเดิมตามไปคือการเดา
 * ⭐⭐ **สองคอลัมน์เริ่มข้อเดียวกันคนละแถว ⇒ เอาแถวหลัง** ⇒ เจอจริง 15 จุด (เช่น 1 พงศาวดาร 1:51 · ลูกา 15:20)
 *   ⇒ TCV ขึ้นย่อหน้ากลางข้อ 51 ⇒ THKJV ขึ้นย่อหน้าที่ต้นข้อ 51 ⇒ แถวถูกตัดที่จุด *ข้อ 51* (กติกาใบ #109)
 *   ⇒ แถวหลังคือแถวที่ **เริ่มที่ข้อนั้น** ⇒ ข้อเดิมที่ตามข้อนั้นไปจึงอยู่ต้นแถว ⇒ ข้อ 9 *คำแรกของแต่ละแถวอยู่ต้นแถว*
 *   ⇒ แถวแรกคือแถวที่ข้อนั้นแค่ *เริ่มกลางย่อหน้า* ของคอลัมน์หนึ่ง ⇒ วางที่นั่นคำเดิมจะเริ่มเร็วกว่าจุดตัดของแถว
 */
export function ข้อแปลของกลุ่ม(กลุ่ม: readonly กลุ่มย่อหน้า[]): ข้อแปลในแถว[] {
  const ได้ = new Map<string, ข้อแปลในแถว>()
  กลุ่ม.forEach((ก, แถว) => {
    for (const ช่อง of ก.ช่อง)
      for (const ย of ช่อง)
        for (const ท of ย.ท่อน) if (ท.ท่อนแรก) ได้.set(`${ท.บท}:${ท.เลข}`, { บท: ท.บท, ข้อ: Number(ท.เลข), แถว })
  })
  return [...ได้.values()]
}
