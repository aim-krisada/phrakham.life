// ⭐ **หัวข้อกลางข้อ** (TCV 17 อัน เช่น ปฐมกาล 29:14) ⇒ *แยกตามข้อ* วางเหนือข้อนั้น (1 ข้อ 1 แถว ผ่ากลางข้อไม่ได้)
//   ⇒ *แยกตามย่อหน้า* กับ *ไหลต่อเนื่อง* ผ่าตรงตัวอักษรที่เจ้าของวางพอดี
//
// ⭐ **ฟังก์ชันบริสุทธิ์** ⇒ ⛔ ไม่แตะหน้าจอ ⛔ ไม่อ่านไฟล์ ⇒ เทสยิงตรงได้ (`tools/ตรวจหัวข้อย่อย.mjs`)

import type { กลุ่มย่อหน้า, รอยย่อหน้า, ย่อหน้า } from './ย่อหน้า'

/** หัวข้อย่อยหนึ่งอันในซอง ⇒ ตำแหน่งนับแบบเดียวกับรอยย่อหน้าเป๊ะ */
export interface หัวข้อย่อย {
  ข้อ: number
  /** 0 = ก่อนข้อนี้เริ่ม · มากกว่า 0 = กลางข้อ */
  หลังอักษร: number
  ตัวหนังสือ: string
  /** บรรทัดคู่ขนานใต้หัวข้อ (`<para style="r">`) ⇒ ผู้วาดคือ `app/components/คู่ขนานใต้หัวข้อ.vue` */
  คู่ขนาน?: { ตัวหนังสือ: string; โยงไป: { ตัวหนังสือ: string; ที่อยู่: string }[] }
}

/** หัวข้อของแต่ละข้อ ⇒ `เลขข้อ → หัวข้อ` ⇒ ใช้กับ *แยกตามข้อ* ⇒ หัวข้อกลางข้อขึ้นเหนือข้อนั้น */
export function หัวข้อตามข้อ(รายการ: readonly หัวข้อย่อย[] | undefined): Map<number, หัวข้อย่อย> {
  const ได้ = new Map<number, หัวข้อย่อย>()
  for (const ห of รายการ || []) if (!ได้.has(ห.ข้อ)) ได้.set(ห.ข้อ, ห)
  return ได้
}

/**
 * หัวข้อ ⇒ รอยผ่าตัวบท ⇒ ส่งเข้า `จัดย่อหน้า` ได้ตรง ๆ
 * ⭐ ป้าย `s1` ⇒ ย่อหน้าที่เปิดด้วยรอยนี้ได้คลาส `pk-ป้าย-s1` ⇒ ⛔ ไม่มีกฎหน้าตา ⇒ หน้าตาเท่าย่อหน้าธรรมดา
 */
export function รอยของหัวข้อ(รายการ: readonly หัวข้อย่อย[] | undefined): รอยย่อหน้า[] {
  return (รายการ || []).map((ห) => ({ ข้อ: ห.ข้อ, หลังอักษร: ห.หลังอักษร, ป้าย: 's1' }))
}

/**
 * ย่อหน้าไหนเปิดด้วยหัวข้อไหน ⇒ คืนรายการยาวเท่า `ย่อ` ⇒ ไม่มีหัวข้อ = `null`
 * ⭐ จุดเริ่มของย่อหน้า = กุญแจของท่อนแรก `<บท>:<ข้อ>#<ตัดไปแล้ว>` ⇒ เลขเดียวกับ `หลังอักษร` ของหัวข้อ
 */
export function หัวข้อของย่อหน้า(
  ย่อ: readonly ย่อหน้า[],
  รายการ: readonly หัวข้อย่อย[] | undefined,
): (หัวข้อย่อย | null)[] {
  if (!รายการ?.length) return ย่อ.map(() => null)
  const ตาม = new Map<string, หัวข้อย่อย>()
  for (const ห of รายการ) ตาม.set(`${ห.ข้อ}#${ห.หลังอักษร}`, ห)
  return ย่อ.map((ย) => {
    const ท = ย.ท่อน[0]
    if (!ท) return null
    return ตาม.get(`${ท.เลข}#${ท.กุญแจ.split('#')[1] ?? '0'}`) || null
  })
}

/** แถวของแบบแยกตามย่อหน้าที่มีแถวหัวข้อแทรกแล้ว ⇒ `หัวข้อ` มีเฉพาะแถวหัวข้อ ⇒ ลำดับเดียวกับคอลัมน์ */
export interface แถวย่อหน้า extends กลุ่มย่อหน้า {
  หัวข้อ?: (หัวข้อย่อย | null)[]
}

/**
 * แทรกแถวหัวข้อเหนือแถวย่อหน้าที่ฉบับใดฉบับหนึ่งเปิดด้วยหัวข้อ (กติกา ② หัวไฟล์)
 *
 * `หัวของคอลัมน์[i]` ⇒ ผลของ `หัวข้อของย่อหน้า` ของคอลัมน์ i ⇒ ลำดับเดียวกับย่อหน้าที่ส่งเข้า `จับคู่ย่อหน้า`
 * คืน ⇒ `แถว` ⇒ แถวย่อหน้าเดิมครบทุกแถว ลำดับเดิม + แถวหัวข้อ
 *      `ในช่อง` ⇒ หัวข้อที่ ⛔ ได้แถวของตัวเอง ⇒ `<คอลัมน์>|<กุญแจย่อหน้า>` → หัวข้อ ⇒ วาดในช่องเหนือย่อหน้านั้น (กติกา ③)
 * ⭐ ฟังก์ชันนี้เคยคืน `ใต้แถว` ไว้ให้ย่อหน้าใต้หัวข้อ ⛔ ไม่เยื้อง ⇒ **ถอดแล้ว 17 พ.ย. 2569** ⇒ เยื้องหรือไม่ตัดสินจากป้ายของคนแปลอย่างเดียว ⇒ ดู `เยื้องบรรทัดแรก` ใน `app/utils/ย่อหน้า.ts`
 * ⛔ ไม่แตะย่อหน้าของใคร ⇒ แถวย่อหน้าเดิมเป็นก้อนเดิมทุกก้อน ⇒ แถวหัวข้อมีแต่หัวข้อ (`ช่อง` ว่างทุกคอลัมน์)
 */
export function แทรกแถวหัวข้อ(
  กลุ่ม: readonly กลุ่มย่อหน้า[],
  คอลัมน์: readonly (readonly ย่อหน้า[])[],
  หัวของคอลัมน์: readonly (readonly (หัวข้อย่อย | null)[])[],
): { แถว: แถวย่อหน้า[]; ในช่อง: Map<string, หัวข้อย่อย> } {
  const หัวของย่อ = คอลัมน์.map((ย่อ, i) => {
    const m = new Map<string, หัวข้อย่อย>()
    ย่อ.forEach((ย, j) => {
      const ห = หัวของคอลัมน์[i]?.[j]
      if (ห) m.set(ย.กุญแจ, ห)
    })
    return m
  })
  const แถว: แถวย่อหน้า[] = []
  const ในช่อง = new Map<string, หัวข้อย่อย>()
  for (const ก of กลุ่ม) {
    const หัวแถว = ก.ช่อง.map((ช่อง, i) => (ช่อง[0] ? หัวของย่อ[i]?.get(ช่อง[0].กุญแจ) || null : null))
    if (หัวแถว.some(Boolean)) {
      แถว.push({ กุญแจ: `หัวข้อ-${ก.กุญแจ}`, ช่อง: ก.ช่อง.map(() => []), หัวข้อ: หัวแถว })
    }
    ก.ช่อง.forEach((ช่อง, i) =>
      ช่อง.forEach((ย, j) => {
        if (j === 0 && หัวแถว[i]) return
        const ห = หัวของย่อ[i]?.get(ย.กุญแจ)
        if (ห) ในช่อง.set(`${i}|${ย.กุญแจ}`, ห)
      }),
    )
    แถว.push(ก)
  }
  return { แถว, ในช่อง }
}
