//   ⇒ สองเว็บของพระคำ.ชีวิตใช้ฟอนต์ชุดเดียวกัน ⇒ ไม่มีหัว = Noto Sans Thai · มีหัว = Noto Sans Thai Looped
//
// ⭐ **ค่าเริ่มต้นคือ *มีหัว*** ⇒ พี่เอมเคาะ 15 พ.ย. 2569 (เกณฑ์ข้อ 3) ⇒ เดิมเว็บใช้ Sarabun ซึ่งเป็นตัวมีหัว
//   ⇒ คนที่เคยเข้าเว็บยังเห็นตัวมีหัวเหมือนเดิม ⇒ ⭐ **มีหัวคือหน้าที่ไม่มีป้ายอะไรเลยบน `<html>`**
//     ⇒ เครื่องที่จำค่าไม่ได้ (หน้าต่างส่วนตัว · ปิดที่เก็บ) ⇒ ไม่ได้ป้าย ⇒ ได้มีหัวเอง ⛔ ไม่ล้ม (เกณฑ์ข้อ 8)
//
// ⭐ **ป้ายบน `<html>` คือ `data-font="loopless"`** ⇒ ชื่อเดียวกับเว็บเพลงที่ใช้ `data-font="looped"`
//   ⇒ เว็บเพลงตั้งต้นที่ไม่มีหัวจึงติดป้ายฝั่งมีหัว ⇒ เราตั้งต้นที่มีหัว ⇒ ติดป้ายฝั่งไม่มีหัวแทน
//   ⇒ ฟอนต์ที่ป้ายนี้เลือก ⇒ เจ้าของคือ `app/assets/css/main.css` หัวข้อ *ฟอนต์ที่ฝากมากับเว็บ* ⛔ ไม่จดซ้ำที่นี่
//
// ⭐ **จำไว้ในเครื่องที่กุญแจ `pk-font`** ⇒ ท่าเดียวกับขนาดตัวอักษรที่จำไว้ที่ `pk-fs` (`public/pk-fontsize.js`)
//   ⇒ ค่าเดียวทั้งเว็บ ⇒ ติดไปทุกหน้า และตอนเปิดเว็บครั้งถัดไปในเครื่องเดียวกัน (เกณฑ์ข้อ 4)

/** กุญแจในที่เก็บของเครื่อง */
export const กุญแจแบบตัวอักษร = 'pk-font'

export type แบบตัวอักษร = 'looped' | 'loopless'

/** ค่าเริ่มต้น ⇒ มีหัว (เกณฑ์ข้อ 3) */
export const แบบตั้งต้น: แบบตัวอักษร = 'looped'

// ⭐⭐ **ต้องใส่ป้ายก่อนหน้าจอวาดครั้งแรก** ⇒ ⛔ ใส่ทีหลัง = คนที่เลือกไม่มีหัวเห็นตัวมีหัวแวบหนึ่งแล้วสลับ
//   ⇒ และเบราว์เซอร์จะโหลดฟอนต์มีหัวมาฟรี ๆ ทั้งที่ผู้อ่านไม่ได้ใช้ (เกณฑ์ข้อ 5)
//   ⇒ `nuxt.config.ts` ฝังข้อความนี้ลง `<head>` ตรง ๆ ⇒ ⛔ ห้ามเลื่อนไปท้ายหน้า
// ⛔ **ห่อด้วย try** ⇒ หน้าต่างส่วนตัวบางตัวโยนข้อผิดพลาดตอนแตะที่เก็บ ⇒ ⛔ ห่อไม่ครบ = สคริปต์ล้มทั้งก้อน
export const สคริปต์ใส่ป้ายก่อนวาด =
  `try{if(localStorage.getItem('${กุญแจแบบตัวอักษร}')==='loopless')` +
  `document.documentElement.setAttribute('data-font','loopless')}catch(e){}`
