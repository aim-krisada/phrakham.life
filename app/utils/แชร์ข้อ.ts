// ⭐ มาตรฐานที่ตาม (ลิงก์อยู่ในใบ)
//   ⇒ web.dev *ให้ผู้ใช้แชร์เว็บที่เปิดอยู่* ⇒ ใช้เมนูแชร์ของเครื่อง (`navigator.share`) · ปิดเมนูเฉย ๆ (`AbortError`) ไม่ใช่ความผิดพลาด
