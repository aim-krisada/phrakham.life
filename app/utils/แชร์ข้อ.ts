//   ⇒ NN/g Icon Usability ⇒ รูปแชร์ไม่ใช่รูปที่ทุกคนรู้จัก ⇒ คำว่า แชร์ ติดกับรูปตลอด
//   ⇒ ไม่มีเมนูแชร์ ⇒ คัดลอกข้อความให้ ⇒ ทางเดียวกับเว็บเพลง (ใบ v3/pleng 151 ข้อ 5) เพราะคนของเราใช้ LINE เป็นหลัก
//
// ⭐⭐ **ลิงก์อยู่ท้ายช่อง `text` ⛔ ไม่ส่งช่อง `url` แยก** (ใบ #139 Notes ข้อ 4)
//   ⇒ ส่ง `text` กับ `url` แยกกัน ⇒ แอปปลายทางบางตัวเก็บแค่ลิงก์แล้วทิ้งข้อความ (iPhone ⇒ แอปที่รับลิงก์อย่างเดียว)
//     ⇒ ตัวบทกับเครดิตหายทั้งก้อน ⇒ เครดิตที่เจ้าของบังคับหายไปด้วย ⇒ คือผิดสัญญา
//   ⇒ ลิงก์อยู่ในข้อความ ⇒ ทุกแอปได้ก้อนเดียวกัน ⇒ LINE ทำลิงก์ที่อยู่ในข้อความให้กดได้เอง
//   ⇒ ราคาที่จ่าย ⇒ แอปที่ทำภาพตัวอย่างจากช่อง `url` จะ ⛔ ไม่ได้ภาพตัวอย่าง ⇒ ใบ #139 Notes ข้อ 5 ไม่เอาเรื่องภาพตัวอย่างอยู่แล้ว
// ⭐ **ช่อง `title` ⛔ ไม่ส่ง** ⇒ Android ใส่เป็นหัวเรื่องแยก ⇒ บางแอปต่อหัวเรื่องเข้ากับข้อความ ⇒ ชื่อเล่มซ้ำ 2 ครั้ง
//   ⇒ ชื่อเล่มกับข้ออยู่บรรทัดแรกของข้อความแล้ว

/** iPhone · iPad · Mac ⇒ กล่องมีลูกศรชี้ขึ้น ⇒ เครื่องอื่น ⇒ วงกลม 3 วงต่อกัน (ใบ #139 ข้อ 1 ⇒ ทรงเดียวกับเว็บเพลง)
 *  ⇒ iPadOS บอกตัวเองว่าเป็น `Macintosh` ⇒ ข้อ Mac คลุมให้เอง */
export function เป็นเครื่องแอปเปิล(nav: { userAgent?: string; platform?: string; userAgentData?: { platform?: string } }) {
  const p = nav.userAgentData?.platform || nav.platform || ''
  return /mac|iphone|ipad|ipod|ios/i.test(p) || /Macintosh|iPhone|iPad|iPod/.test(nav.userAgent || '')
}

export interface ข้อที่จะแชร์ {
  บท: number
  /** เลขข้อตามกุญแจของข้อมูล */
  เลข: string
  /** ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/159 ⇒ รหัสเล่มของข้อที่อยู่คนละเล่มกับหน้า (คอลัมน์คนละตอน)
   *  ⇒ ว่าง = เล่มของหน้า ⇒ 1 ชิ้น = ฉบับ + เล่ม + บท + ข้อ */
  เล่ม?: string
}

/** ⭐ ใบ #159 ⇒ แบ่งรายการตามเล่ม ⇒ เล่มของหน้า (ว่าง) ก่อน ⇒ เล่มอื่นตามลำดับที่เจอในรายการ */
function ตามเล่ม(รายการ: ข้อที่จะแชร์[]): [string, ข้อที่จะแชร์[]][] {
  const กลุ่ม = new Map<string, ข้อที่จะแชร์[]>()
  for (const x of รายการ) {
    const k = x.เล่ม || ''
    if (!กลุ่ม.has(k)) กลุ่ม.set(k, [])
    กลุ่ม.get(k)!.push(x)
  }
  return [...กลุ่ม].sort((a, b) => Number(!!a[0]) - Number(!!b[0]))
}

/**
 * อ้างอิงที่ผู้อ่านเห็น ⇒ **แสดงผลด้วยทวิภาค** (หลักเดียวกับ `แสดงช่วงฟัง` ใน `app/utils/ที่อยู่.ts`)
 * ⇒ ข้อติดกันย่อเป็นช่วง `12:1–3` · ข้ามข้อคั่นจุลภาค `12:1, 5` · ข้ามบทคั่นอัฒภาค `12:30; 13:2`
 */
export function เขียนอ้างอิง(ชื่อเล่ม: string, รายการ: ข้อที่จะแชร์[]): string {
  const ตามบท = new Map<number, number[]>()
  for (const x of รายการ) {
    const n = Number(x.เลข)
    if (!ตามบท.has(x.บท)) ตามบท.set(x.บท, [])
    ตามบท.get(x.บท)!.push(n)
  }
  const ท่อนบท: string[] = []
  for (const [บท, เลข] of [...ตามบท].sort((a, b) => a[0] - b[0])) {
    const เรียง = [...new Set(เลข)].sort((a, b) => a - b)
    const ช่วง: string[] = []
    for (let i = 0; i < เรียง.length; ) {
      let j = i
      while (j + 1 < เรียง.length && เรียง[j + 1] === เรียง[j]! + 1) j++
      ช่วง.push(j > i ? `${เรียง[i]}–${เรียง[j]}` : `${เรียง[i]}`)
      i = j + 1
    }
    ท่อนบท.push(`${บท}:${ช่วง.join(', ')}`)
  }
  return `${ชื่อเล่ม} ${ท่อนบท.join('; ')}`
}

export interface ฉบับที่จะแชร์ {
  /** ชื่อเต็มของฉบับ ⇒ ชื่อเดียวกับหัวข้อบนหน้าแหล่งข้อมูล */
  ชื่อ: string
  /** ข้อที่ถูกเลือกในคอลัมน์ของฉบับนี้ (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/148)
   *  ⇒ ⛔ ใส่ ⇒ ใช้ทุกข้อในรายการอ้างอิง (ท่าเดิมของใบ #139) */
  ข้อ?: ข้อที่จะแชร์[]
  /** ตัวบทของแต่ละข้อ ⇒ กุญแจ `บท:เลข` ⇒ **ตัวหนังสือเดียวกับที่วาดบนหน้า** ⇒ `เล่ม` ว่าง = เล่มของหน้า (ใบ #159) */
  เนื้อ: (บท: number, เลข: string, เล่ม: string) => string
  สัญญา: string
  ลิงก์สัญญา: string
  เครดิต: string
}

/**
 * ข้อความที่ส่งออกไป ⇒ อ้างอิง · ตัวบทแยกกลุ่มตามฉบับ · ที่มาของตัวบท · ลิงก์ปิดท้าย (ใบ #139 ข้อ 6)
 * ⭐⭐ **ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/148 ข้อ 3** ⇒ แต่ละฉบับส่งเฉพาะข้อที่เลือกในคอลัมน์ของมัน (`ฉบับ.ข้อ`)
 *   ⇒ หน้าอ่านส่งมาเฉพาะฉบับที่มีข้อถูกเลือก ⇒ เครดิตจึงมีเฉพาะฉบับที่ส่ง และครบทุกฉบับที่ส่ง
 *   ⇒ ⚠️ แทนใบ #139 ข้อ 10 ที่ส่งทุกฉบับคำแปลที่เปิด (พี่เอมเคาะ 7 พ.ย. 2569 *"a selection belongs to the column you tapped"*)
 * ⭐ บรรทัดอ้างอิง (`รายการ`) ⇒ ทุกข้อที่มีชิ้นถูกเลือกอย่างน้อย 1 ฉบับ
 * ⭐ **ตัวบทตรงกับที่เห็นบนหน้าทุกตัวอักษร** ⇒ ⛔ ไม่ตัด ⛔ ไม่เติม ⇒ หน้าอ่านส่งตัวหนังสือที่มันวาดมาให้
 * ⭐ ข้อที่ฉบับนั้นไม่มีตัวบท ⇒ ⛔ ไม่มีบรรทัด ⇒ ⛔ ไม่ส่งเลขข้อลอย ๆ
 */
export function ประกอบข้อความข้อ(
  ชื่อเล่ม: string,
  รายการ: ข้อที่จะแชร์[],
  ฉบับ: ฉบับที่จะแชร์[],
  หัวที่มา: string,
  ลิงก์: string,
  /** ⭐ ใบ #159 ⇒ ชื่อไทยของเล่มอื่นที่มีข้อถูกเลือก ⇒ กุญแจรหัสเล่ม */
  ชื่อเล่มอื่น: Record<string, string> = {},
): string {
  // ⭐⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/159 ⇒ ข้อจากคอลัมน์คนละเล่ม ⇒ อ้างอิงแยกตามเล่ม คั่นด้วยอัฒภาค
  //   ⇒ *มาระโก 13:31–32; ยอห์น 18:13–15* ⇒ ตัวคั่นเดียวกับข้ามบท ⇒ ⛔ คำใหม่
  //   ⇒ กลุ่มตัวบทแยกตามฉบับและเล่ม ⇒ บรรทัดของข้อเขียนชื่อเล่มนำหน้า ⇒ *ยอห์น 18:13 …* ⇒ ผู้รับรู้ว่าข้อไหนมาจากเล่มไหน
  //   ⇒ ⭐ ทุกข้ออยู่เล่มเดียวกับหน้า ⇒ ได้ข้อความเหมือนก่อนใบ #159 ทุกตัวอักษร
  const ชื่อของ = (เล่ม: string) => (เล่ม ? ชื่อเล่มอื่น[เล่ม] || เล่ม : ชื่อเล่ม)
  const กลุ่มเล่ม = ตามเล่ม(รายการ)
  const หลายเล่ม = กลุ่มเล่ม.some(([ล]) => !!ล)
  const ท่อน: string[] = [
    หลายเล่ม ? กลุ่มเล่ม.map(([ล, x]) => เขียนอ้างอิง(ชื่อของ(ล), x)).join('; ') : เขียนอ้างอิง(ชื่อเล่ม, รายการ),
  ]
  for (const ฉ of ฉบับ) {
    for (const [ล, ข้อ] of ตามเล่ม(ฉ.ข้อ ?? รายการ)) {
      const บรรทัด = ข้อ
        .map((x) => ({ x, เนื้อ: ฉ.เนื้อ(x.บท, x.เลข, x.เล่ม || '') }))
        .filter((y) => y.เนื้อ)
        .map((y) => `${หลายเล่ม ? `${ชื่อของ(ล)} ` : ''}${y.x.บท}:${y.x.เลข} ${y.เนื้อ}`)
      if (บรรทัด.length) ท่อน.push([ฉ.ชื่อ, ...บรรทัด].join('\n'))
    }
  }
  const ที่มา = ฉบับ.map((ฉ) =>
    [
      [ฉ.ชื่อ, ฉ.สัญญา, ฉ.ลิงก์สัญญา].filter(Boolean).join(' · '),
      ฉ.เครดิต && ฉ.เครดิต !== ฉ.ชื่อ ? ฉ.เครดิต : '',
    ]
      .filter(Boolean)
      .join('\n'),
  )
  ท่อน.push([หัวที่มา, ...ที่มา].join('\n'))
  ท่อน.push(ลิงก์)
  return ท่อน.join('\n\n')
}

/** ข้อความตอนแชร์ทั้งหน้า ⇒ ชื่อตอนที่อ่านอยู่ · ชื่อเว็บ แล้วลิงก์ (ใบ #139 ข้อ 5) */
export function ประกอบข้อความหน้า(ชื่อตอน: string, ชื่อเว็บ: string, ลิงก์: string): string {
  return `${ชื่อตอน} · ${ชื่อเว็บ}\n${ลิงก์}`
}

export type ผลแชร์ = 'แชร์แล้ว' | 'ปิดเมนู' | 'คัดลอกแล้ว' | 'คัดลอกเอง'

interface ตัวเครื่อง {
  share?: (ของ: { text: string }) => Promise<void>
  canShare?: (ของ: { text: string }) => boolean
  clipboard?: { writeText?: (t: string) => Promise<void> }
}

/**
 * ส่งข้อความเข้าเมนูแชร์ของเครื่อง ⇒ บอกผลให้หน้าจอพูดตาม
 *   ⇒ `แชร์แล้ว` เมนูรับไป · `ปิดเมนู` ผู้อ่านปิดเมนูเอง ⇒ ⛔ ไม่เตือนอะไร (ข้อ 16)
 *   ⇒ `คัดลอกแล้ว` ไม่มีเมนูแชร์ ⇒ ข้อความอยู่ในคลิปบอร์ด (ข้อ 15)
 *   ⇒ `คัดลอกเอง` คัดลอกก็ไม่ได้ ⇒ หน้าจอต้องขึ้นข้อความทั้งก้อน ⇒ ⛔ ห้ามเงียบ (ข้อ 17)
 * ⛔ **เขียนคลิปบอร์ดอย่างเดียว ⛔ ไม่อ่าน** (Security measures ข้อ 2)
 */
export async function ส่งเข้าเมนูแชร์(ข้อความ: string, เครื่อง: ตัวเครื่อง): Promise<ผลแชร์> {
  const ของ = { text: ข้อความ }
  if (typeof เครื่อง.share === 'function' && (typeof เครื่อง.canShare !== 'function' || เครื่อง.canShare(ของ))) {
    try {
      await เครื่อง.share(ของ)
      return 'แชร์แล้ว'
    } catch (e) {
      if ((e as { name?: string } | null)?.name === 'AbortError') return 'ปิดเมนู'
      // ⭐ เหตุอื่น (เครื่องไม่ยอม · ไม่ใช่การกดของคน) ⇒ ตกไปคัดลอกแทน
    }
  }
  try {
    if (typeof เครื่อง.clipboard?.writeText !== 'function') throw new Error('ไม่มีคลิปบอร์ด')
    await เครื่อง.clipboard.writeText(ข้อความ)
    return 'คัดลอกแล้ว'
  } catch {
    return 'คัดลอกเอง'
  }
}
