// ผู้อ่านเลือกไว้ว่าจะดูฉบับไหนบ้าง — **เก็บไว้ในเครื่องของเขาเอง**
//
// ⭐ **ทำไมเก็บในเครื่องผู้อ่าน ⛔ ไม่เก็บที่เซิร์ฟเวอร์** ⇒ เว็บนี้เป็นไฟล์นิ่ง ⛔ ไม่มีหลังบ้านตอนผู้อ่านเปิด
//   ⇒ และของชิ้นนี้เป็นความชอบส่วนตัว ⛔ ไม่ใช่ข้อมูลที่ต้องแชร์ข้ามเครื่อง
//
// ⛔ **ที่เก็บของเบราว์เซอร์ล้มได้** — โหมดส่วนตัว · ผู้ใช้ปิดการเก็บ · พื้นที่เต็ม
//   ⇒ ล้มแล้วต้องเงียบและใช้ค่าตั้งต้นแทน ⛔ ไม่ใช่หน้าพังทั้งหน้าเพราะจำค่าไม่ได้

const กุญแจ = 'phrakham.versions'

/** ฉบับที่แสดงตอนยังไม่มีใครเลือกอะไร ⇒ ฉบับไทยที่หน้าเว็บใช้มาตั้งแต่ก้อนที่ 1 */
export const ฉบับตั้งต้น = 'TCV'

/** ⭐ `ว่างได้` (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/145) ⇒ ผู้อ่านเปิดคำภาษาเดิมไว้ และปิดฉบับแปลหมดเอง
 *  ⇒ ที่เก็บเป็น `[]` จริง ๆ ⇒ คืน `[]` ⇒ ตารางเหลือแต่คำเดิมเหมือนที่เขาทิ้งไว้
 *  ⇒ ⛔ ไม่ได้เปิดคำเดิม ⇒ `[]` ยังตกกลับเป็นฉบับตั้งต้นเหมือนเดิม ⇒ ⛔ ไม่มีหน้าว่าง */
export function อ่านฉบับที่เลือก(ฉบับที่มี: string[], ว่างได้ = false): string[] {
  try {
    const เก็บไว้ = localStorage.getItem(กุญแจ)
    if (!เก็บไว้) return [ฉบับตั้งต้น]
    if (ว่างได้ && เก็บไว้.replace(/\s/g, '') === '[]') return []
    // ⛔ กรองด้วยรายชื่อฉบับที่มีจริง — ค่าที่เก็บไว้เมื่อวานอาจอ้างฉบับที่วันนี้ไม่มีแล้ว
    const ได้ = (JSON.parse(เก็บไว้) as unknown[]).filter(
      (x): x is string => typeof x === 'string' && ฉบับที่มี.includes(x),
    )
    return ได้.length ? ได้ : [ฉบับตั้งต้น]
  } catch {
    return [ฉบับตั้งต้น]
  }
}

export function จำฉบับที่เลือก(ฉบับ: string[]): void {
  try {
    localStorage.setItem(กุญแจ, JSON.stringify(ฉบับ))
  } catch {
    // จำไม่ได้ก็อ่านต่อได้ ⇒ ⛔ ไม่ทำให้หน้าพัง
  }
}

/**
 * ⭐ ตำแหน่งของคอลัมน์คำภาษาเดิมในตาราง (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/145 ข้อ 2)
 *   ⇒ จำนวนฉบับแปลที่อยู่ซ้ายของมัน ⇒ จำไว้ในเครื่องคู่กับฉบับที่เลือก ⇒ เปิดเว็บใหม่ได้ลำดับเดิม
 *   ⇒ ⛔ เคยจำ ⇒ 1 = ขวาติดคอลัมน์แรก ⇒ หน้าตาเดียวกับก่อนใบนี้ (ใบ #125 ข้อ 11)
 */
const กุญแจที่คำเดิม = 'phrakham.originalAt'

export function อ่านที่คำเดิม(): number {
  try {
    const n = Number(localStorage.getItem(กุญแจที่คำเดิม))
    return localStorage.getItem(กุญแจที่คำเดิม) !== null && Number.isInteger(n) && n >= 0 ? n : 1
  } catch {
    return 1
  }
}

export function จำที่คำเดิม(ที่: number): void {
  try {
    localStorage.setItem(กุญแจที่คำเดิม, String(ที่))
  } catch {
    // จำไม่ได้ก็อ่านต่อได้
  }
}
