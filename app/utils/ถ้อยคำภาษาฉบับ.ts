// ⭐⭐ **ภาษามาจากรหัส BCP 47 ของฉบับ ⛔ ไม่จดชื่อภาษาซ้ำทีละฉบับ**
//   ⇒ ฉบับแปล ⇒ ตาราง `ภาษาของชั้น` ที่ `server/utils/เนื้อบท.ts` (ตัวเดียวกับที่ติด `lang` ให้กล่องของฉบับ)
//   ⇒ ตัวบทภาษาเดิม ⇒ `ภาษาของตัวบท()` ที่ `app/utils/ถ้อยคำคำเดิม.ts`
//   ⇒ ⛔ **ฉบับที่ไม่รู้ภาษา ⇒ ⛔ ห้ามขึ้นชื่อเปล่าเงียบ ๆ** (เกณฑ์ข้อ 4 · 5)
//     ⇒ ฉบับใหม่ที่ไม่มีในตาราง `ภาษาของชั้น` ⇒ สร้างเว็บล้มอยู่แล้ว (`ข้อมูลเล่ม()`)
//     ⇒ รหัสภาษาที่ไม่มีชื่อไทยในตารางข้างล่าง ⇒ `tools/ด่านภาษาท้ายชื่อฉบับ.mjs` ข้อ ① แดงก่อนขึ้นเว็บ

/** ชื่อภาษาเป็นคำไทย ⇒ คีย์คือรหัส BCP 47 ⇒ เติมรหัสใหม่ที่นี่เมื่อมีฉบับภาษาใหม่ */
export const ชื่อภาษาไทย: Readonly<Record<string, string>> = {
  th: 'ไทย',
  en: 'อังกฤษ',
  grc: 'กรีก',
  hbo: 'ฮีบรู',
}

/** ตัวคั่นระหว่างชื่อฉบับกับภาษา ⇒ ตัวเดียวกับ `ป้ายชั้นคำ()` (*คำกรีก · SBLGNT*) */
export const คั่นภาษา = ' · '

/** ข้อความของตัวเลือก ⇒ *SBLGNT · กรีก* ⇒ ไม่รู้ชื่อภาษา ⇒ คืนชื่อฉบับเปล่า ⇒ ด่านข้อ ② แดงจากหน้าจริง */
export function ป้ายฉบับพร้อมภาษา(ฉบับ: string, รหัสภาษา: string | undefined): string {
  const ชื่อ = รหัสภาษา ? ชื่อภาษาไทย[รหัสภาษา] : undefined
  return ชื่อ ? `${ฉบับ}${คั่นภาษา}${ชื่อ}` : ฉบับ
}
