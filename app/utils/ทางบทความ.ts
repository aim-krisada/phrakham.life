/** รหัสเรื่องในทะเบียน ⇒ ทางของหน้าบทความ (⛔ ไม่มีฐานของเว็บ ⛔ ไม่มี `/reflections/`) */
export function ทางจากรหัสเรื่อง(รหัส: string): string {
  const m = /^([0-9A-Z]{3})\.(\d+)\.(\d+)-(\d+)\.(\d+)$/.exec(รหัส)
  if (!m) throw new Error(`⛔ รหัสเรื่องเล่า "${รหัส}" อ่านไม่ออก ⇒ ต้องเป็น <เล่ม>.<บท>.<ข้อ>-<บท>.<ข้อ>`)
  const [, เล่ม, c1, v1, c2, v2] = m
  const ต้น = `${เล่ม!.toLowerCase()}-${c1}-${v1}`
  return c1 === c2 ? `${ต้น}-${v2}` : `${ต้น}-to-${c2}-${v2}`
}

/** ทางของหน้าบทความ ⇒ รหัสเรื่องในทะเบียน ⇒ อ่านไม่ออก ⇒ `null` (หน้าตอบ 404 เอง ⛔ ไม่ใช่หน้าพัง) */
export function รหัสเรื่องจากทาง(ทาง: string): string | null {
  const m = /^([0-9a-z]{3})-(\d+)-(\d+)-(?:to-(\d+)-)?(\d+)$/.exec(ทาง)
  if (!m) return null
  const [, เล่ม, c1, v1, c2, v2] = m
  return `${เล่ม!.toUpperCase()}.${c1}.${v1}-${c2 || c1}.${v2}`
}
