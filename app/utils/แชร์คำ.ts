// แชร์คำอธิบายของคำภาษาเดิมจากการ์ดคำ — ตัวประกอบข้อความ (ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/149 ก้อน ข.)
//
// ⭐ **ไม่มี Vue ในไฟล์นี้** ⇒ ท่าเดียวกับ `app/utils/แชร์ข้อ.ts` ⇒ ตัวส่งเข้าเมนูแชร์ใช้ตัวเดียวกับแชร์ข้อ (`ส่งเข้าเมนูแชร์`)
//   ⇒ ⭐ ลิงก์อยู่ท้ายช่อง `text` ⛔ ไม่ส่งช่อง `url` แยก ⇒ เหตุผลเดียวกับแชร์ข้อ ⇒ อยู่หัวไฟล์ `แชร์ข้อ.ts` ⛔ ไม่จดซ้ำที่นี่
//
// ⭐⭐ **ข้อความ = ของที่การ์ดแสดง ⇒ ชื่อแถวเดิมของการ์ดทุกแถว ⛔ ไม่มีถ้อยคำใหม่** (ใบ #149 ข้อ 8)
//   ⇒ บรรทัดแรก ⇒ คำ (คำอ่าน) · เล่ม บท:ข้อ ⇒ ตามด้วยแถวของการ์ดทีละบรรทัด *ชื่อแถว: ค่า*
//   ⇒ ค่าว่างขึ้น — แบบเดียวกับการ์ด ⇒ คำที่ไม่มีคำอ่าน ⛔ ไม่มีวงเล็บว่าง
// ⭐ **เครดิตที่เจ้าของบังคับ** (ข้อ 9) ⇒ ทรงเดียวกับท่อนที่มาของแชร์ข้อ ⇒ `ชื่อ · สัญญา · ลิงก์สัญญา` แล้วถ้อยคำเครดิตบรรทัดถัดไป
//   ⇒ ถ้อยคำมาจาก `api/credits.json` ⇒ แกะจากหน้าแหล่งข้อมูล (`server/utils/เครดิตฉบับ.ts`) ⇒ LGNTDF ได้ถ้อยคำของ SIL ตรงตัว
//   ⇒ ⛔ ไม่มีหัวกลุ่ม ⇒ หัว *ที่มาของตัวบท* ของแชร์ข้อพูดถึงตัวบท ⛔ ใช่ข้อมูลคำ ⇒ ไม่เติมถ้อยคำใหม่ตามกติกาข้อ 8
// ⛔ ไม่มีข้อมูลส่วนตัว ⇒ มีแค่ข้อมูลของคำกับลิงก์ (ใบ #149 Security measures)

export interface แหล่งที่ต้องให้เครดิต {
  ชื่อ: string
  สัญญา: string
  ลิงก์สัญญา: string
  /** ถ้อยคำเครดิตที่เจ้าของบังคับ ⇒ ว่าง = ไม่บังคับ */
  เครดิต: string
}

export interface คำที่จะแชร์ {
  ตัว: string
  /** คำอ่านไทย ⇒ ว่าง = ไม่มีคำอ่าน ⇒ ⛔ ไม่มีวงเล็บ */
  อ่าน: string
  ชื่อเล่ม: string
  บท: number
  ข้อ: string
  /** แถวของการ์ดตามลำดับบนการ์ด ⇒ `[ชื่อแถว, ค่า]` ⇒ ค่าหลายบรรทัดได้ */
  แถว: [string, string][]
  เครดิต: แหล่งที่ต้องให้เครดิต[]
  ลิงก์: string
}

/** คำกับคำอ่านในวงเล็บ ⇒ หน้าตาเดียวกับแถวของการ์ด (ใบ #149 ก้อน ก.) */
export function คำกับคำอ่าน(คำ: string, อ่าน: string): string {
  return อ่าน ? `${คำ} (${อ่าน})` : คำ
}

export function ประกอบข้อความคำ(ค: คำที่จะแชร์): string {
  const ท่อน: string[] = []
  ท่อน.push(
    [`${คำกับคำอ่าน(ค.ตัว, ค.อ่าน)} · ${ค.ชื่อเล่ม} ${ค.บท}:${ค.ข้อ}`, ...ค.แถว.map(([ชื่อ, ค่า]) => `${ชื่อ}: ${ค่า}`)].join('\n'),
  )
  const ที่มา = ค.เครดิต.map((แ) =>
    [[แ.ชื่อ, แ.สัญญา, แ.ลิงก์สัญญา].filter(Boolean).join(' · '), แ.เครดิต && แ.เครดิต !== แ.ชื่อ ? แ.เครดิต : '']
      .filter(Boolean)
      .join('\n'),
  )
  if (ที่มา.length) ท่อน.push(ที่มา.join('\n'))
  ท่อน.push(ค.ลิงก์)
  return ท่อน.join('\n\n')
}
