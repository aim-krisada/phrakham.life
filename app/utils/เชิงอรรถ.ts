import type { ชิ้นเนื้อ } from './คำพระเยซู'

export interface เชิงอรรถ {
  ข้อ: number
  หลังอักษร: number
  ชนิด: string
  ชิ้น: { ป้าย: string; ตัวหนังสือ: string }[]
  โยงไป?: { ตัวหนังสือ: string; ที่อยู่: string }[]
  ท้ายข้อ?: boolean
  /** ข้อที่มีเลขแต่ไม่มีเนื้อ ⇒ เชิงอรรถเกาะท้ายข้อก่อนหน้า ⇒ นี่คือเลขข้อเดิมของมัน */
  ข้อเดิม?: number
}

/** เครื่องหมายบนตัวบท ⇒ `ป้าย` คือตัวอักษรเล็กที่ผู้อ่านเห็น */
export interface เครื่องหมายเชิงอรรถ extends เชิงอรรถ {
  ป้าย: string
  ฉบับ: string
}

const ไทย = 'กขคงจฉชซฌญฎฏฐฑฒณดตถทธนบปผฝพฟภมยรลวศษสหฬอฮ'
const ละติน = 'abcdefghijklmnopqrstuvwxyz'

/** ลำดับที่ `i` ในบท ⇒ ตัวอักษร ⇒ หมดชุดแล้ววนใหม่ */
export function ป้ายเชิงอรรถ(i: number, ภาษา: string | undefined): string {
  const ชุด = (ภาษา || '').startsWith('th') ? ไทย : ละติน
  return ชุด[i % ชุด.length]!
}

/**
 * แทรกเครื่องหมายเชิงอรรถของข้อ `เลขข้อ` ลงในชิ้นที่ตัดตามคำพระเยซูแล้ว
 *
 * ⛔ ตำแหน่งที่ล้นขอบ ⇒ ไปท้ายข้อ ⛔ ไม่ทิ้ง ⇒ เชิงอรรถเป็นของผู้แปล ⛔ ห้ามหายเงียบ
 */
export function แทรกเชิงอรรถ(
  ชิ้น: ชิ้นเนื้อ[],
  เลขข้อ: number,
  ของบท: เชิงอรรถ[] | undefined,
  ฉบับ: string,
  ภาษา: string | undefined,
): ชิ้นเนื้อ[] {
  if (!ของบท?.length || !ชิ้น.length) return ชิ้น
  const ของข้อนี้: เครื่องหมายเชิงอรรถ[] = []
  ของบท.forEach((ช, i) => {
    if (ช.ข้อ === เลขข้อ) ของข้อนี้.push({ ...ช, ป้าย: ป้ายเชิงอรรถ(i, ภาษา), ฉบับ })
  })
  if (!ของข้อนี้.length) return ชิ้น

  const ออก: ชิ้นเนื้อ[] = []
  let k = 0
  let นับ = 0
  for (const ช of ชิ้น) {
    const ยาว = ช.ตัวหนังสือ.length
    let ที่ = 0
    // ⭐ ของข้อนี้เรียงตามตำแหน่งมาจากตัวพ่นแล้ว ⇒ ตรงรอยต่อพอดี ⇒ ติดท้ายชิ้นก่อน (คำที่มันกำกับ)
    while (k < ของข้อนี้.length && ของข้อนี้[k]!.หลังอักษร <= นับ + ยาว) {
      const ตัด = Math.max(ของข้อนี้[k]!.หลังอักษร - นับ, ที่)
      if (ตัด > ที่) ออก.push({ ตัวหนังสือ: ช.ตัวหนังสือ.slice(ที่, ตัด), พระเยซู: ช.พระเยซู })
      ออก.push({ ตัวหนังสือ: '', พระเยซู: ช.พระเยซู, เชิงอรรถ: ของข้อนี้[k] })
      ที่ = ตัด
      k++
    }
    if (ที่ < ยาว) ออก.push(ที่ ? { ตัวหนังสือ: ช.ตัวหนังสือ.slice(ที่), พระเยซู: ช.พระเยซู } : ช)
    นับ += ยาว
  }
  // ⭐ ที่เหลือ (ล้นขอบ) ⇒ ท้ายข้อ
  for (; k < ของข้อนี้.length; k++) ออก.push({ ตัวหนังสือ: '', พระเยซู: false, เชิงอรรถ: ของข้อนี้[k] })
  return ออก
}
