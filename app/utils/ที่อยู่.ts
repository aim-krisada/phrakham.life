/**
 * ที่อยู่ของหน้าอ่าน — **1 เล่ม = 1 หน้า** เช่น `/read/PSA?c=23&v=1`
 *
 * ⭐⭐ **บทกับข้อเป็น *การเลือกภายในหน้า* ⛔ ไม่ใช่หน้าใหม่** (พี่เอมเคาะ 6 ก.ย. 2569 · ใบงาน #73)
 *   > *"ผมว่าควรนับได้แค่ 66 หน้า คือแต่ละเล่ม ตัวบทและข้อคือการเลือกภายใน ไม่ใช่หน้า"*
 *   ⇒ เปลี่ยนบทคือ **เลื่อนไปอีกที่หนึ่งของเล่มเดียวกัน** ⛔ ไม่ใช่หยิบหนังสือเล่มใหม่
 *
 * ⛔ **ชื่อคำถามต้องเป็นอักษรอังกฤษ** ⇒ ชื่อไทยกลายเป็นรหัส `%E0%B8%8A…` ยาว 3 เท่าตอนแชร์
 *   (เหตุผลเดียวกับที่อยู่ทั้งเว็บ ⇒ ดูหัวไฟล์นี้) ⇒ `c` ย่อจาก chapter · `v` ย่อจาก verse
 * ⭐ **เลขบทกับเลขข้อเป็นแค่ *จุดที่พาไป* ⛔ ไม่ใช่ขอบเขต** ⇒ เปิดแล้วยังเลื่อนอ่านต่อได้ทั้งเล่ม
 */
export function ที่อยู่หน้าอ่าน(
  รหัสเล่ม: string,
  บท?: number | string | null,
  ข้อ?: number | null,
  เทียบ?: คอลัมน์เทียบ[] | null,
  ช่วง?: ช่วงฟัง | null,
  ฉบับ?: string[] | null,
): string {
  const ทาง = `${ฐาน()}read/${รหัสเล่ม}`
  const คำถาม: string[] = []
  if (บท) คำถาม.push(`c=${บท}`)
  if (ข้อ) คำถาม.push(`v=${ข้อ}`)
  const p = เขียนคอลัมน์เทียบ(เทียบ || [])
  if (p) คำถาม.push(`p=${p}`)
  if (ช่วง) คำถาม.push(`r=${เขียนช่วงฟัง(ช่วง)}`)
  // ⭐ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/143 ⇒ มีคอลัมน์คนละที่ ⇒ เขียน `t` เสมอ แม้เหลือ TCV ฉบับเดียว
  //   ⇒ ⛔ ไม่เขียน = คนที่เปิดลิงก์ได้ฉบับที่ตัวเองจำไว้ในเครื่อง ⇒ ตารางมีฉบับเกินมา ⇒ ไม่ใช่หน้าที่คนส่งเห็น
  const t = เขียนฉบับในที่อยู่(ฉบับ || [], !!p)
  if (t) คำถาม.push(`t=${t}`)
  return คำถาม.length ? `${ทาง}?${คำถาม.join('&')}` : ทาง
}

/**
 * ⭐⭐ **ฉบับของคอลัมน์ที่ข้อตรงแถวกับคอลัมน์แรก** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/125 ข้อ 13)
 *
 * ⭐ **ทำไมต้องอยู่ในที่อยู่แล้ว** ⇒ ใบ #125 ให้คอลัมน์ย้ายเข้าออกตารางที่ตรงแถวได้
 *   ⇒ ของเดิมจำฉบับของตารางไว้ในเครื่องผู้อ่านอย่างเดียว (`app/utils/ฉบับที่เลือก.ts`)
 *   ⇒ คอลัมน์เทียบที่เข้าตาราง จึงหายจากที่อยู่ ⇒ คัดลอกลิงก์ไปเปิดที่อื่นได้คอลัมน์ไม่ครบ · กดถอยหลังแล้วคอลัมน์หาย
 * ⭐ **รูปคือฉบับคั่นด้วยจุลภาค เรียงตามที่เห็นจากซ้ายไปขวา** ⇒ `t=TCV,LSV` ⇒ ชื่อคำถามเป็นอักษรอังกฤษตัวเดียว เหตุผลเดียวกับ `c` `v` `p` `r`
 * ⛔ **TCV ฉบับเดียว ⇒ ⛔ ไม่เขียน** ⇒ ที่อยู่ของคนที่ไม่แตะอะไรหน้าตาเหมือนเดิมทุกตัวอักษร
 *   ⇒ ⭐ ยกเว้นมีคอลัมน์คนละที่ (`เขียนเสมอ`) ⇒ ใบ https://aimgit.aimagin.com/v3/phrakham/-/issues/143 ⇒ เหตุผลอยู่ที่ `ที่อยู่หน้าอ่าน`
 *   ⇒ ⭐ ลิงก์เก่าที่ไม่มี `t` ยังเปิดได้ ⇒ หน้าใช้ฉบับที่ผู้อ่านจำไว้ในเครื่องเหมือนเดิม ⇒ เจ้าของกติกาคือ `onMounted` ของหน้าอ่าน
 */
export function เขียนฉบับในที่อยู่(ฉบับ: string[], เขียนเสมอ = false): string {
  if (!ฉบับ.length || (!เขียนเสมอ && ฉบับ.length === 1 && ฉบับ[0] === ฉบับตั้งต้น)) return ''
  return ฉบับ.join(',')
}

/** ⛔ **ค่าที่อ่านไม่ออกถูกทิ้งเงียบ ๆ** ⇒ ตัวที่ซ้ำถูกทิ้ง ⇒ ฉบับที่เล่มนั้นไม่มี หน้าอ่านกรองเอง */
export function อ่านฉบับในที่อยู่(ค่า: unknown): string[] {
  if (typeof ค่า !== 'string' || !ค่า) return []
  const ได้: string[] = []
  for (const x of ค่า.split(',')) {
    if (/^[A-Z0-9]+$/.test(x) && !ได้.includes(x)) ได้.push(x)
    if (ได้.length >= เพดานคอลัมน์ในที่อยู่) break
  }
  return ได้
}

/**
 * ⭐⭐ **ช่วงที่ผู้อ่านเลือกไว้ฟัง** (ใบงาน https://aimgit.aimagin.com/v3/phrakham/-/issues/101 ข้อ 29)
 *
 * ⭐ **ช่วงคือขอบเขตของ *การฟัง* ⛔ ไม่ใช่กำแพงของการอ่าน** ⇒ เลือกแล้วยังเลื่อนอ่านต่อได้ทั้งเล่ม
 *   ⇒ หลักเดียวกับที่พี่เอมขีดไว้ 12 ต.ค. 2569 เรื่องโหมดเลือกข้อ ⇒ *ช่วงคือขอบเขตของผลลัพธ์*
 *   ⇒ เจ้าของเรื่องคือ `docs/เคาะ/หน้าจอกับการอ่าน.md` ⛔ ไม่จดซ้ำที่นี่
 * ⛔ **ข้ามเล่มไม่ได้** ⇒ พี่เอมสั่งเอง 24 ต.ค. 2569 ⇒ ช่วงจึงมีแค่บทกับข้อ ⇒ เล่มคือหน้าที่เปิดอยู่
 *
 * ⭐ **เป็นคำถามแยกของตัวเอง ⛔ ไม่ใช่ `c` กับ `v`** ⇒ สองตัวนั้นเปลี่ยนตามการเลื่อนอ่าน
 *   ⇒ ถ้าช่วงฝากไว้กับมัน เลื่อนพ้นบทเมื่อไรช่วงจะหายจากที่อยู่ ⇒ ส่งต่อให้คนอื่นไม่ได้
 * ⭐ **รูปคือ `<บท>.<ข้อ>-<บท>.<ข้อ>`** ⇒ `r=4.3-4.9` ⇒ ชื่อคำถามเป็นอักษรอังกฤษตัวเดียว เหตุผลเดียวกับ `c` `v` `p`
 */
export interface ช่วงฟัง {
  จาก: { บท: number; ข้อ: number }
  ถึง: { บท: number; ข้อ: number }
}

/** ⛔ **ค่าที่อ่านไม่ออก หรือปลายอยู่ก่อนต้น ⇒ ทิ้งเงียบ ๆ** ⇒ ตกกลับเป็นหน้าที่ไม่มีช่วง ⛔ ไม่ใช่หน้าพัง */
export function อ่านช่วงฟัง(ค่า: unknown): ช่วงฟัง | null {
  if (typeof ค่า !== 'string') return null
  const m = /^(\d+)\.(\d+)-(\d+)\.(\d+)$/.exec(ค่า.trim())
  if (!m) return null
  const [c1, v1, c2, v2] = m.slice(1).map(Number) as [number, number, number, number]
  if (!c1 || !v1 || !c2 || !v2) return null
  if (c2 < c1 || (c2 === c1 && v2 < v1)) return null
  return { จาก: { บท: c1, ข้อ: v1 }, ถึง: { บท: c2, ข้อ: v2 } }
}

export function เขียนช่วงฟัง(ช: ช่วงฟัง): string {
  return `${ช.จาก.บท}.${ช.จาก.ข้อ}-${ช.ถึง.บท}.${ช.ถึง.ข้อ}`
}

/** ช่วงในรูปที่ผู้อ่านเห็น ⇒ **แสดงผลด้วยทวิภาค** ⇒ บทเดียวกันเขียนสั้น `4:3–9` · ข้ามบท `4:3–5:12` */
export function แสดงช่วงฟัง(ช: ช่วงฟัง): string {
  const ต้น = `${ช.จาก.บท}:${ช.จาก.ข้อ}`
  if (ช.จาก.บท === ช.ถึง.บท) {
    return ช.จาก.ข้อ === ช.ถึง.ข้อ ? ต้น : `${ต้น}–${ช.ถึง.ข้อ}`
  }
  return `${ต้น}–${ช.ถึง.บท}:${ช.ถึง.ข้อ}`
}

