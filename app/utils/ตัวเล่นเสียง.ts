export interface ข้อในคิว {
  /** `ACT.1.1` ⇒ ใช้เป็นกุญแจของแถวในรายการ */
  รหัส: string
  เล่ม: string
  ชื่อเล่ม: string
  บท: number
  ข้อ: number
  /** ว่าง = ข้อนี้ ⛔ ไม่มีเสียง ⇒ ตัวเล่นข้ามไป และหน้าจอต้องบอกผู้อ่านตรง ๆ */
  ที่อยู่ไฟล์: string
  วินาที: number
  /** ⭐ ชื่อบนหน้าจอล็อก ⇒ ว่าง = `<ชื่อเล่ม> <บท>:<ข้อ>` ของพระคำ ⇒ เรื่องเล่าใส่ชื่อของตัวเอง (ใบ #105) */
  หัวเรื่อง?: string
  /** ⭐ บรรทัดที่สองบนหน้าจอล็อก ⇒ ว่าง = ชื่อฉบับ TCV ⇒ เสียงเรื่องเล่า ⛔ ไม่ใช่เสียงอ่านของฉบับ TCV */
  ผู้ทำ?: string
}

export interface สภาพตัวเล่น {
  สถานะ: 'ยังไม่เริ่ม' | 'กำลังเล่น' | 'หยุดพัก'
  ที่ข้อ: number
}

type ฟังผล = (ส: สภาพตัวเล่น) => void

/**
 * สร้างตัวเล่นหนึ่งตัวต่อหนึ่งหน้า ⇒ **`<audio>` ตัวเดียวตลอดอายุหน้า**
 *
 * ⛔ **เรียกได้เฉพาะในเบราว์เซอร์** ⇒ ตอนสร้างเว็บล่วงหน้า ⛔ ไม่มี `Audio`
 */
export function สร้างตัวเล่นเสียง(แจ้ง: ฟังผล, เมื่อจบเอง?: () => void) {
  let กล่อง: HTMLAudioElement | null = null
  let คิว: ข้อในคิว[] = []
  let ที่ข้อ = -1
  let สถานะ: สภาพตัวเล่น['สถานะ'] = 'ยังไม่เริ่ม'

  function บอก() {
    แจ้ง({ สถานะ, ที่ข้อ })
  }

  function เตรียมกล่อง(): HTMLAudioElement {
    if (กล่อง) return กล่อง
    const a = new Audio()
    // ⛔ **ห้ามเป็น 'metadata' หรือ 'auto'** ⇒ สองค่านั้นสั่งเบราว์เซอร์ขอไฟล์ทันทีที่ตั้ง `src`
    //   ⇒ คนที่เปิดหน้าแล้ว ⛔ ไม่กดฟัง จะจ่ายไบต์ไปแล้ว ⇒ **ผิดเกณฑ์ของใบ**
    a.preload = 'none'
    a.addEventListener('ended', ข้อถัดไป)
    // ⛔ **ไฟล์เดียวโหลดไม่ขึ้น ⛔ ห้ามล้มทั้งคิว** ⇒ ข้ามไปข้อถัดไป
    //   ⇒ เงียบค้างกลางทางตอนจอดับ คือของที่ผู้อ่านแก้เองไม่ได้ เพราะเขา ⛔ ไม่ได้มองจอ
    a.addEventListener('error', () => {
      if (สถานะ !== 'ยังไม่เริ่ม') ข้อถัดไป()
    })
    a.addEventListener('play', () => {
      สถานะ = 'กำลังเล่น'
      // ⭐ **ผูกปุ่มหน้าจอล็อกใหม่ทุกครั้งที่เริ่มเล่น** (ใบ #105) ⇒ หน้าอ่านมีตัวเล่น 2 ตัวแล้ว (พระคำ · เรื่องเล่า)
      //   ⇒ แผงหน้าจอล็อกมีชุดเดียวทั้งหน้า ⇒ ⛔ ผูกแค่ตอนสร้าง = ปุ่มบนหูฟังไปคุมตัวที่ถูกสร้างทีหลัง ⛔ ไม่ใช่ตัวที่กำลังเล่น
      ตั้งปุ่มบนหน้าจอล็อก()
      ตั้งแผงหน้าจอล็อก()
      บอก()
    })
    a.addEventListener('pause', () => {
      // ⛔ **ไฟล์จบเองก็ยิง `pause` ก่อน `ended`** ⇒ ⛔ ไม่ใช่ผู้อ่านกดหยุด
      //   ⇒ ไม่กันไว้ ปุ่มจะกะพริบเป็น *ฟังต่อ* ทุกรอยต่อข้อ และถ้ากดตรงจังหวะนั้นพอดี
      //     ปุ่มจะสั่งเล่นไฟล์เดิมซ้ำแทนการหยุด ⇒ ฝาแฝดของด่านจับได้เอง 24 ต.ค. 2569
      if (a.ended) return
      if (สถานะ === 'กำลังเล่น') สถานะ = 'หยุดพัก'
      บอก()
    })
    // ⭐⭐ **วางตัวเล่นลงในหน้าจริง ⛔ ไม่ปล่อยลอยอยู่ในหน่วยความจำ**
    //   ⇒ **ซ่อนไว้** เพราะปุ่มคุมของจริงคือปุ่ม `ฟัง` ⛔ ไม่ใช่แถบคุมของเบราว์เซอร์
    //   ⇒ ⭐ **เหตุผลที่ต้องอยู่ในหน้า** ⇒ `tools/ด่านฟังพระคำบนหน้า.mjs` ข้อ ⑤ ต้องหาตัวนี้ให้เจอ
    //     เพื่อสั่งให้ไฟล์จบก่อนเวลา แล้วดูว่า **มันต่อข้อถัดไปเองไหม**
    //     ⇒ ⛔ ลอยอยู่นอกหน้า = **ด่านมองไม่เห็น** ⇒ ของที่ตรวจไม่ได้ ก็คือของที่พังเงียบได้
    a.hidden = true
    document.body.appendChild(a)
    กล่อง = a
    ตั้งปุ่มบนหน้าจอล็อก()
    return a
  }

  /** ⭐ ข้อที่ ⛔ ไม่มีไฟล์ ⇒ ข้ามไป ⇒ **หน้าจอเป็นคนบอกผู้อ่านว่าข้ามเพราะอะไร** */
  function หาข้อที่เล่นได้(เริ่ม: number): number {
    for (let i = เริ่ม; i < คิว.length; i++) if (คิว[i]!.ที่อยู่ไฟล์) return i
    return -1
  }

  function เล่นที่(i: number) {
    const ดัชนี = หาข้อที่เล่นได้(i)
    if (ดัชนี < 0) {
      จบคิว()
      return
    }
    const a = เตรียมกล่อง()
    ที่ข้อ = ดัชนี
    a.src = คิว[ดัชนี]!.ที่อยู่ไฟล์
    ตั้งแผงหน้าจอล็อก()
    // ⛔ เบราว์เซอร์ปฏิเสธการเล่นนอกการกดของผู้ใช้ ⇒ ⛔ ไม่ทำให้หน้าพัง ⇒ ผู้อ่านกด ▶ ใหม่
    void a.play().catch(() => {
      สถานะ = 'หยุดพัก'
      บอก()
    })
    บอก()
  }

  function ข้อถัดไป() {
    if (ที่ข้อ + 1 < คิว.length && หาข้อที่เล่นได้(ที่ข้อ + 1) >= 0) {
      เล่นที่(ที่ข้อ + 1)
      return
    }
    // ⭐ **คิวหมดเอง** ⇒ บอกหน้าด้วย ⇒ หน้าต้องบอกผู้อ่านว่าหยุดเพราะอะไร (ใบ #101 ข้อ 8)
    จบคิว()
    เมื่อจบเอง?.()
  }

  function จบคิว() {
    สถานะ = 'ยังไม่เริ่ม'
    ที่ข้อ = -1
    if (กล่อง) {
      กล่อง.pause()
      กล่อง.removeAttribute('src')
    }
    ตั้งสถานะแผง('none')
    บอก()
  }

  // ---------------------------------------------------------------- หน้าจอล็อก
  // ⭐⭐ **นี่คือชิ้นที่ทำให้ "มือถืออยู่ในกระเป๋า" ใช้ได้จริง**
  //   ⇒ ชื่อข้อที่กำลังอ่านขึ้นบนหน้าจอล็อก ⇒ ผู้อ่านรู้ว่าอยู่ตรงไหนโดย ⛔ ไม่ต้องปลดล็อก
  //   ⇒ ปุ่มหยุด/เล่น/ถัดไป/ก่อนหน้า บนหูฟังและบนหน้าจอล็อกใช้ได้
  //   ⛔ เบราว์เซอร์ที่ ⛔ ไม่มี `mediaSession` ⇒ ข้ามไปเงียบ ๆ ⇒ เสียงยังเล่นได้เหมือนเดิม
  function แผง(): MediaSession | null {
    return typeof navigator !== 'undefined' && 'mediaSession' in navigator
      ? navigator.mediaSession
      : null
  }

  function ตั้งสถานะแผง(ส: MediaSessionPlaybackState) {
    const ms = แผง()
    if (ms) ms.playbackState = ส
  }

  function ตั้งแผงหน้าจอล็อก() {
    const ms = แผง()
    const ข = คิว[ที่ข้อ]
    if (!ms || !ข || typeof MediaMetadata === 'undefined') return
    ms.metadata = new MediaMetadata({
      title: ข.หัวเรื่อง || `${ข.ชื่อเล่ม} ${ข.บท}:${ข.ข้อ}`,
      artist: ข.ผู้ทำ || 'พระคริสตธรรมคัมภีร์ ฉบับ Thai Common Version 2025',
      album: 'พระคำ.ชีวิต',
    })
  }

  function ตั้งปุ่มบนหน้าจอล็อก() {
    const ms = แผง()
    if (!ms) return
    const ผูก = (ชื่อ: MediaSessionAction, ทำ: () => void) => {
      try {
        ms.setActionHandler(ชื่อ, ทำ)
      } catch {
        /* เบราว์เซอร์นี้ ⛔ ไม่รองรับปุ่มนี้ ⇒ ข้ามไป */
      }
    }
    ผูก('play', () => void กล่อง?.play())
    ผูก('pause', () => กล่อง?.pause())
    ผูก('nexttrack', () => ข้อถัดไป())
    ผูก('previoustrack', () => เล่นที่(Math.max(0, ที่ข้อ - 1)))
  }

  return {
    /** ตั้งคิวใหม่ ⇒ ⛔ ไม่เริ่มเล่นเอง ⇒ **ไบต์แรกเกิดตอนกด ▶ เท่านั้น** */
    ตั้งคิว(ใหม่: ข้อในคิว[]) {
      คิว = ใหม่
      จบคิว()
    },
    /** ปุ่มเดียวของผู้อ่าน ⇒ ยังไม่เริ่ม = เริ่มจากข้อแรก · กำลังเล่น = หยุดพัก · หยุดพัก = ไปต่อ */
    กดปุ่มเดียว() {
      if (สถานะ === 'กำลังเล่น') {
        กล่อง?.pause()
        return
      }
      if (สถานะ === 'หยุดพัก' && กล่อง?.src) {
        void กล่อง.play().catch(() => undefined)
        return
      }
      เล่นที่(0)
    },
    เล่นข้อที่(i: number) {
      เล่นที่(i)
    },
    หยุด() {
      จบคิว()
    },
    ปิด() {
      if (กล่อง) {
        กล่อง.pause()
        กล่อง.removeAttribute('src')
        กล่อง.remove()
        กล่อง = null
      }
    },
  }
}
