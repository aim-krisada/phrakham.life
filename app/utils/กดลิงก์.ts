// ⭐⭐ **ทั้งเว็บมีแผงเลือกพระธรรมแผงเดียว** ⇒ ทุกทางที่เขียนว่า *อ่านพระคัมภีร์* เปิดแผงเดียวกันนั้น
//   ⇒ แต่ของพวกนั้น **ยังต้องเป็น `<a href>` จริง** ⇒ โค้ดของเว็บโหลดไม่สำเร็จ ก็ยังได้หน้าสารบัญ 66 เล่ม
//   ⇒ เหตุผลเต็มอยู่ที่ `app/components/แถบนำทาง.vue` ⛔ ไม่จดซ้ำที่นี่

/**
 * ผู้อ่านตั้งใจ **เปิดแท็บใหม่** หรือเปล่า ⇒ จริง = ⛔ **ห้ามขวาง** ปล่อยให้ลิงก์ทำงานตามปกติ
 *
 * ⛔⛔ **`preventDefault` ดื้อ ๆ ทุกกรณี = ยึดลิงก์ไปจากผู้อ่าน**
 *   ⇒ กดค้าง Ctrl หรือ Cmd เพื่อเปิดแท็บใหม่ · กดด้วยปุ่มกลาง · Shift เพื่อเปิดหน้าต่างใหม่
 *   ⇒ ของพวกนี้เบราว์เซอร์ให้มาฟรี ⇒ **เอาคืนไปโดยไม่มีอะไรทดแทน คือทำให้เว็บแย่ลง**
 */
export function ตั้งใจเปิดแท็บใหม่(e: MouseEvent): boolean {
  return e.ctrlKey || e.metaKey || e.shiftKey || e.altKey || e.button !== 0
}
