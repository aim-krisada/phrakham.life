/** ⭐ แปลงค่าที่เก็บไว้ ⇒ ช่องใหม่ก่อน ⇒ ไม่มี ⇒ *ขนานกัน* ของเดิมคือผู้อ่านเลือกเอง (ค่าตั้งต้นเดิมคือทีละฉบับ) ⇒ เป็นซ้ายขวา
 *  ⇒ *ทีละฉบับ* ของช่องเดิม ⛔ ไม่ตาม ⇒ แยกไม่ออกว่าเลือกเองไหม ⇒ เหตุผลอยู่ที่ช่อง `วางคอลัมน์` ข้างบน */
function อ่านการวาง(ของ: Partial<มุมมอง> & { วางจอแคบ?: unknown }): แบบวางจอแคบ {
  if (การวางจอแคบที่มี.includes(ของ.วางคอลัมน์ as แบบวางจอแคบ)) return ของ.วางคอลัมน์ as แบบวางจอแคบ
  if (ของ.วางจอแคบ === 'ขนานกัน') return 'ซ้ายขวา'
  return มุมมองตั้งต้น.วางคอลัมน์
}

