// ตัดตัวบทของข้อหนึ่ง ออกเป็นชิ้น ๆ ตามช่วง **คำที่พระเยซูพูด**
//
// **ซองมาจากไหน** ⇒ `tools/สร้างคำพระเยซู.py` ⇒ เหตุผลทั้งหมดอยู่ที่หัวไฟล์นั้น ⛔ ไม่จดซ้ำที่นี่
//
// ⛔⛔ **ช่วงเป็น *ตำแหน่งตัวอักษร* ⛔ ไม่ใช่ตัวหนังสือ**
//   ⇒ ตัวบทที่ส่งเข้ามาต้องเป็นก้อนเดียวกับที่ตัวพ่นใช้วัด
//   ⇒ ตัวพ่นมีด่านเทียบความยาวทุกข้อก่อนเขียนซอง ⇒ ยาวไม่เท่าเมื่อไร **มันหยุดเอง**
//
// ⭐ **ฟังก์ชันบริสุทธิ์** ⇒ ⛔ ไม่แตะหน้าจอ ⛔ ไม่อ่านไฟล์ ⇒ เขียนเทสยิงตรงได้

/** ช่วงหนึ่งช่วงในซอง ⇒ ตำแหน่งบนตัวบทของ *ข้อนั้น* */
export interface ช่วงคำพระเยซู {
  ข้อ: number
  หลังอักษร: number
  ถึงอักษร: number
  /** คำพูดเดียวกันที่ถูกรอยข้อตัด ⇒ ชิ้นนี้ต่อจากข้อก่อนหน้า ⛔ ไม่ใช่คำพูดใหม่ */
  ต่อจากข้อก่อน?: boolean
}

/** ชิ้นเนื้อที่พร้อมวาด ⇒ `พระเยซู` จริง = ชิ้นนี้ต้องถูกเน้น */
export interface ชิ้นเนื้อ {
  ตัวหนังสือ: string
  พระเยซู: boolean
  /** ช่วงเน้นอื่นของเจ้าของฉบับ ⇒ `คำเติม` (ตัวเอียงของ KJV) · `พระนาม` (LORD) ⇒ ดู `ผ่าตามช่วงเน้น` */
  เน้น?: string
  /** ชิ้นนี้คือเครื่องหมายเชิงอรรถ ⇒ ตัวหนังสือว่าง ⇒ เจ้าของคือ `app/utils/เชิงอรรถ.ts` */
  เชิงอรรถ?: import('./เชิงอรรถ').เครื่องหมายเชิงอรรถ
}

/**
 * ตัด `เนื้อ` ของข้อเลข `เลขข้อ` ตามช่วงที่ให้มา
 *
 * ⛔ **ช่วงที่ล้นขอบหรือกลับหัวกลับหาง ⇒ ทิ้งเงียบ ๆ** ⇒ ⛔ ไม่โยนข้อผิดพลาด
 *   **ทำไม** ⇒ ของพวกนี้ไปโผล่กลางหน้าอ่านของผู้อ่าน ⇒ **ตัวบทต้องขึ้นเสมอ**
 *   ⇒ ตัวดักของจริงคือด่านฝั่งข้อมูล ซึ่งหยุดตั้งแต่ตอนพ่นซอง ⛔ ไม่ใช่ตอนผู้อ่านเปิดหน้า
 */
export function ตัดเนื้อตามคำพระเยซู(
  เนื้อ: string,
  เลขข้อ: number,
  ช่วงของบท: ช่วงคำพระเยซู[] | undefined,
): ชิ้นเนื้อ[] {
  if (!เนื้อ) return []
  const ของข้อนี้ = (ช่วงของบท || [])
    .filter((ช) => ช.ข้อ === เลขข้อ && ช.ถึงอักษร > ช.หลังอักษร && ช.หลังอักษร < เนื้อ.length)
    .map((ช) => ({
      เริ่ม: Math.max(ช.หลังอักษร, 0),
      จบ: Math.min(ช.ถึงอักษร, เนื้อ.length),
    }))
    .sort((a, b) => a.เริ่ม - b.เริ่ม)

  if (!ของข้อนี้.length) return [{ ตัวหนังสือ: เนื้อ, พระเยซู: false }]

  const ออก: ชิ้นเนื้อ[] = []
  let ที่: number = 0
  for (const ช of ของข้อนี้) {
    // ⛔ ช่วงที่ซ้อนทับช่วงก่อนหน้า ⇒ ข้ามไป ⇒ ⛔ ไม่ให้ตัวหนังสือโผล่ซ้ำ
    if (ช.จบ <= ที่) continue
    const เริ่ม = Math.max(ช.เริ่ม, ที่)
    if (เริ่ม > ที่) ออก.push({ ตัวหนังสือ: เนื้อ.slice(ที่, เริ่ม), พระเยซู: false })
    ออก.push({ ตัวหนังสือ: เนื้อ.slice(เริ่ม, ช.จบ), พระเยซู: true })
    ที่ = ช.จบ
  }
  if (ที่ < เนื้อ.length) ออก.push({ ตัวหนังสือ: เนื้อ.slice(ที่), พระเยซู: false })

  // ⭐ **ตัวหนังสือที่ต่อกลับมาต้องเท่าเดิมเป๊ะ** ⇒ ของที่หายไปแม้ตัวเดียวคือตัวบทที่ผู้อ่านไม่ได้อ่าน
  return ออก
}

/**
 * ผ่าชิ้นที่ตัดตามคำพระเยซูแล้ว ซ้ำอีกชั้นตาม **ช่วงเน้นอื่นของเจ้าของฉบับ** ⇒ ติดชนิดไว้ที่ `เน้น`
 * ⇒ `ช่วงตามชนิด` = `{<ชนิด>: [ช่วงของบท]}` ของฉบับนี้ ⇒ ซองมาจาก `tools/สร้างคำพระเยซู.py` (ไฟล์ `_พ่น/ช่วงเน้น.json.gz`)
 * ⇒ ⭐ ตัวหนังสือที่ต่อกลับต้องเท่าเดิมเป๊ะ ⇒ ผ่าอย่างเดียว ⛔ ไม่ตัด ไม่เติม ⇒ ช่วงซ้อนกัน ⇒ ช่วงแรกชนะ
 */
export function ผ่าตามช่วงเน้น(
  ชิ้น: ชิ้นเนื้อ[],
  เลขข้อ: number,
  ช่วงตามชนิด: Record<string, ช่วงคำพระเยซู[]> | undefined,
): ชิ้นเนื้อ[] {
  if (!ช่วงตามชนิด || !ชิ้น.length) return ชิ้น
  const ช่วง = Object.entries(ช่วงตามชนิด)
    .flatMap(([ชนิด, รายการ]) => (รายการ || []).filter((ช) => ช.ข้อ === เลขข้อ && ช.ถึงอักษร > ช.หลังอักษร).map((ช) => ({ ชนิด, เริ่ม: ช.หลังอักษร, จบ: ช.ถึงอักษร })))
    .sort((a, b) => a.เริ่ม - b.เริ่ม)
  if (!ช่วง.length) return ชิ้น
  const ชนิดที่ = (i: number) => ช่วง.find((ช) => ช.เริ่ม <= i && i < ช.จบ)?.ชนิด
  const ออก: ชิ้นเนื้อ[] = []
  let นับ = 0
  for (const ช of ชิ้น) {
    const t = ช.ตัวหนังสือ
    if (!t) {
      ออก.push(ช)
      continue
    }
    // ⭐ จุดผ่าในชิ้นนี้ ⇒ ขอบของทุกช่วงที่ตกในชิ้น
    const จุด = [...new Set([0, t.length, ...ช่วง.flatMap((x) => [x.เริ่ม - นับ, x.จบ - นับ]).filter((x) => x > 0 && x < t.length)])].sort((a, b) => a - b)
    for (let k = 0; k < จุด.length - 1; k++) {
      const เน้น = ชนิดที่(นับ + จุด[k]!)
      const ชิ้นใหม่: ชิ้นเนื้อ = { ...ช, ตัวหนังสือ: t.slice(จุด[k]!, จุด[k + 1]!) }
      if (เน้น) ชิ้นใหม่.เน้น = เน้น
      ออก.push(ชิ้นใหม่)
    }
    นับ += t.length
  }
  return ออก
}

/** ช่วงเน้นของบท `{<ชนิด>: {<ฉบับ>: [ช่วง]}}` ⇒ เฉพาะของฉบับ `ฉ` ⇒ `{<ชนิด>: [ช่วง]}` */
export function ช่วงเน้นของฉบับ(
  ช่วงเน้น: Record<string, Record<string, ช่วงคำพระเยซู[]>> | undefined,
  ฉ: string,
): Record<string, ช่วงคำพระเยซู[]> | undefined {
  if (!ช่วงเน้น) return undefined
  const ออก: Record<string, ช่วงคำพระเยซู[]> = {}
  for (const [ชนิด, ของ] of Object.entries(ช่วงเน้น)) if (ของ[ฉ]?.length) ออก[ชนิด] = ของ[ฉ]!
  return Object.keys(ออก).length ? ออก : undefined
}

/** คลาสของชิ้นที่ต้องครอบด้วย `<span>` ⇒ คำพระเยซูกับช่วงเน้นซ้อนกันได้ ⇒ CSS อยู่ `app/assets/css/main.css` */
export function คลาสของชิ้น(ชิ้น: ชิ้นเนื้อ): Record<string, boolean> {
  return { 'pk-คำพระเยซู': ชิ้น.พระเยซู, 'pk-คำเติม': ชิ้น.เน้น === 'คำเติม', 'pk-พระนาม': ชิ้น.เน้น === 'พระนาม' }
}
