// ตัดตัวบทของข้อหนึ่ง ออกเป็นชิ้น ๆ ตามช่วง **คำที่พระเยซูพูด**
//
// **ซองมาจากไหน** ⇒ `tools/สร้างคำพระเยซู.py` ⇒ เหตุผลทั้งหมดอยู่ที่หัวไฟล์นั้น ⛔ ไม่จดซ้ำที่นี่
//
// ⛔⛔ **ช่วงเป็น *ตำแหน่งตัวอักษร* ⛔ ไม่ใช่ตัวหนังสือ**
//   ⇒ ตัวบทที่ส่งเข้ามาต้องเป็นก้อนเดียวกับที่ตัวพ่นใช้วัด
//   ⇒ ตัวพ่นมีด่านเทียบความยาวทุกข้อก่อนเขียนซอง ⇒ ยาวไม่เท่าเมื่อไร **มันหยุดเอง**
//
// ⭐ **ฟังก์ชันบริสุทธิ์** ⇒ ⛔ ไม่แตะหน้าจอ ⛔ ไม่อ่านไฟล์ ⇒ เขียนเทสยิงตรงได้

/** ช่วงหนึ่งช่วงในซอง ⇒ ตำแหน่งบนตัวบทของ *ข้อนั้น* */
export interface ช่วงคำพระเยซู {
  ข้อ: number
  หลังอักษร: number
  ถึงอักษร: number
  /** คำพูดเดียวกันที่ถูกรอยข้อตัด ⇒ ชิ้นนี้ต่อจากข้อก่อนหน้า ⛔ ไม่ใช่คำพูดใหม่ */
  ต่อจากข้อก่อน?: boolean
}

/** ชิ้นเนื้อที่พร้อมวาด ⇒ `พระเยซู` จริง = ชิ้นนี้ต้องถูกเน้น */
export interface ชิ้นเนื้อ {
  ตัวหนังสือ: string
  พระเยซู: boolean
  /** ชิ้นนี้คือเครื่องหมายเชิงอรรถ ⇒ ตัวหนังสือว่าง ⇒ เจ้าของคือ `app/utils/เชิงอรรถ.ts` */
  เชิงอรรถ?: import('./เชิงอรรถ').เครื่องหมายเชิงอรรถ
}

/**
 * ตัด `เนื้อ` ของข้อเลข `เลขข้อ` ตามช่วงที่ให้มา
 *
 * ⛔ **ช่วงที่ล้นขอบหรือกลับหัวกลับหาง ⇒ ทิ้งเงียบ ๆ** ⇒ ⛔ ไม่โยนข้อผิดพลาด
 *   **ทำไม** ⇒ ของพวกนี้ไปโผล่กลางหน้าอ่านของผู้อ่าน ⇒ **ตัวบทต้องขึ้นเสมอ**
 *   ⇒ ตัวดักของจริงคือด่านฝั่งข้อมูล ซึ่งหยุดตั้งแต่ตอนพ่นซอง ⛔ ไม่ใช่ตอนผู้อ่านเปิดหน้า
 */
export function ตัดเนื้อตามคำพระเยซู(
  เนื้อ: string,
  เลขข้อ: number,
  ช่วงของบท: ช่วงคำพระเยซู[] | undefined,
): ชิ้นเนื้อ[] {
  if (!เนื้อ) return []
  const ของข้อนี้ = (ช่วงของบท || [])
    .filter((ช) => ช.ข้อ === เลขข้อ && ช.ถึงอักษร > ช.หลังอักษร && ช.หลังอักษร < เนื้อ.length)
    .map((ช) => ({
      เริ่ม: Math.max(ช.หลังอักษร, 0),
      จบ: Math.min(ช.ถึงอักษร, เนื้อ.length),
    }))
    .sort((a, b) => a.เริ่ม - b.เริ่ม)

  if (!ของข้อนี้.length) return [{ ตัวหนังสือ: เนื้อ, พระเยซู: false }]

  const ออก: ชิ้นเนื้อ[] = []
  let ที่: number = 0
  for (const ช of ของข้อนี้) {
    // ⛔ ช่วงที่ซ้อนทับช่วงก่อนหน้า ⇒ ข้ามไป ⇒ ⛔ ไม่ให้ตัวหนังสือโผล่ซ้ำ
    if (ช.จบ <= ที่) continue
    const เริ่ม = Math.max(ช.เริ่ม, ที่)
    if (เริ่ม > ที่) ออก.push({ ตัวหนังสือ: เนื้อ.slice(ที่, เริ่ม), พระเยซู: false })
    ออก.push({ ตัวหนังสือ: เนื้อ.slice(เริ่ม, ช.จบ), พระเยซู: true })
    ที่ = ช.จบ
  }
  if (ที่ < เนื้อ.length) ออก.push({ ตัวหนังสือ: เนื้อ.slice(ที่), พระเยซู: false })

  // ⭐ **ตัวหนังสือที่ต่อกลับมาต้องเท่าเดิมเป๊ะ** ⇒ ของที่หายไปแม้ตัวเดียวคือตัวบทที่ผู้อ่านไม่ได้อ่าน
  return ออก
}
